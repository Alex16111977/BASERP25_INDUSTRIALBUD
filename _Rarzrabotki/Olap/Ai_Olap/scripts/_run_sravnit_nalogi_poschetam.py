# -*- coding: utf-8 -*-
# Запуск логики отчёта А_СравнитьОстаткиНалоговПосчетамЕРПсBASБухгалтерия
# (точные запросы из ObjectModule.bsl) за ноябрь 2025.
import sys
sys.stdout.reconfigure(encoding="utf-8")
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

PER = "ДАТАВРЕМЯ(2025,11,1), ДАТАВРЕМЯ(2025,11,30,23,59,59)"

# --- список ЕДРПОУ А_ВБалансе из ЕРП ---
q = erp.NewObject("Запрос")
q.Текст = ('ВЫБРАТЬ Организации.КодПоЕДРПОУ КАК ЕДРПОУ ИЗ Справочник.Организации КАК Организации '
           'ГДЕ Организации.А_ВБалансе И Организации.КодПоЕДРПОУ <> ""')
edrpou = []
sel = q.Выполнить().Выбрать()
while sel.Следующий():
    edrpou.append(sel.ЕДРПОУ)
print("Орг А_ВБалансе (ЕДРПОУ):", edrpou)

# --- ЕРП Хозрасчетный 64x/65x ---
q = erp.NewObject("Запрос")
q.Текст = f"""
ВЫБРАТЬ Ост.Счет.Код КАК КодСчета,
    СУММА(Ост.СуммаНачальныйОстатокКт - Ост.СуммаНачальныйОстатокДт) КАК НО,
    СУММА(Ост.СуммаОборотКт) КАК Нач,
    СУММА(Ост.СуммаОборотДт) КАК Упл,
    СУММА(Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) КАК КО
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты({PER}, , , , , ) КАК Ост
ГДЕ (Ост.Счет.Код ПОДОБНО "641%" ИЛИ Ост.Счет.Код ПОДОБНО "642%" ИЛИ Ост.Счет.Код ПОДОБНО "651%")
    И Ост.Организация.А_ВБалансе
СГРУППИРОВАТЬ ПО Ост.Счет.Код"""
erp_t = {}
sel = q.Выполнить().Выбрать()
while sel.Следующий():
    erp_t[str(sel.КодСчета).strip()] = (float(sel.НО), float(sel.Нач), float(sel.Упл), float(sel.КО))

# --- BuhBud Хозрасчетный 64x/65x ---
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
qb = buh.NewObject("Запрос")
masEDR = buh.NewObject("Массив")
for e in edrpou:
    masEDR.Добавить(e)
qb.УстановитьПараметр("масЕДРПОУ", masEDR)
qb.Текст = f"""
ВЫБРАТЬ Ост.Счет.Код КАК КодСчета,
    СУММА(Ост.СуммаНачальныйОстатокКт - Ост.СуммаНачальныйОстатокДт) КАК НО,
    СУММА(Ост.СуммаОборотКт) КАК Нач,
    СУММА(Ост.СуммаОборотДт) КАК Упл,
    СУММА(Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) КАК КО
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты({PER}, , , , , ) КАК Ост
ГДЕ (Ост.Счет.Код ПОДОБНО "641%" ИЛИ Ост.Счет.Код ПОДОБНО "642%" ИЛИ Ост.Счет.Код ПОДОБНО "651%")
    И Ост.Организация.КодПоЕДРПОУ В (&масЕДРПОУ)
СГРУППИРОВАТЬ ПО Ост.Счет.Код"""
buh_t = {}
sel = qb.Выполнить().Выбрать()
while sel.Следующий():
    buh_t[str(sel.КодСчета).strip()] = (float(sel.НО), float(sel.Нач), float(sel.Упл), float(sel.КО))

def vid(code):
    c = code.strip()
    if c.startswith("6411"): return "НДФЛ"
    if c.startswith("6412"): return "НДС"
    if c.startswith("6413"): return "НалогНаПрибыль"
    if c.startswith("6414"): return "ЕдиныйНалог"
    if c.startswith("642"):  return "ВоенныйСбор"
    if c.startswith("651"):  return "НачисленныйЕСВ"
    return "ДругиеНалоги"

allc = sorted(set(erp_t) | set(buh_t))
print(f"\n{'Счёт':<8}{'ВидНалога':<16}{'КО ЕРП':>16}{'КО BuhBud':>16}{'Разница':>16}")
tot_e = tot_b = 0.0
for c in allc:
    e = erp_t.get(c, (0,0,0,0)); b = buh_t.get(c, (0,0,0,0))
    tot_e += e[3]; tot_b += b[3]
    mark = "   <<< Налог на прибыль" if c.startswith("6413") else ""
    print(f"{c:<8}{vid(c):<16}{e[3]:>16,.2f}{b[3]:>16,.2f}{e[3]-b[3]:>16,.2f}{mark}")
print(f"{'ИТОГО':<24}{tot_e:>16,.2f}{tot_b:>16,.2f}{tot_e-tot_b:>16,.2f}")
print(f"\nПАП «Налог на прибыль» (свод/OLAP) = 1 641 963,16")
print(f"BuhBud 6413 КО = {buh_t.get('6413',(0,0,0,0))[3]:,.2f}")
