# -*- coding: utf-8 -*-
# Read-only проверка фикса обработки «Перенос остатков налогов из бухгалтерии»:
# повторяет загрузку сальдо из BuhBud + НОВУЮ консолидацию ПАП (Подр×ТипНалога,
# одна управленческая орг). Ничего не пишет.
import sys
sys.stdout.reconfigure(encoding="utf-8")
import win32com.client
from collections import defaultdict

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def tip(code):
    c = code.strip()
    if c == "6411": return "НДФЛ"
    if c == "642":  return "ВоенныйСбор"
    if c == "651":  return "НачисленныйЕСВ"
    if c == "6412": return "НДС"
    if c == "6413": return "НалогНаПрибыль"
    if c == "6414": return "ЕдиныйНалог"
    return "ДругиеНалоги"

# 1) ЕРП: орг А_ВБалансе → ЕДРПОУ + А_ПодразделениеЗарплатаБух
q = erp.NewObject("Запрос")
q.Текст = ('ВЫБРАТЬ О.КодПоЕДРПОУ КАК ЕДРПОУ, ПРЕДСТАВЛЕНИЕ(О.А_ПодразделениеЗарплатаБух) КАК Подр '
           'ИЗ Справочник.Организации КАК О ГДЕ О.А_ВБалансе И О.КодПоЕДРПОУ <> ""')
podr_by_edr = {}
sel = q.Выполнить().Выбрать()
while sel.Следующий():
    podr_by_edr[str(sel.ЕДРПОУ).strip()] = str(sel.Подр)
print("Орг А_ВБалансе → Подразделение:", podr_by_edr)

# 2) BuhBud: сальдо Кт-Дт по (ЕДРПОУ, Счёт.Код) на 30.11.2025 (как ЗагрузитьОстатки)
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
masSch = buh.NewObject("Массив")
for c in "6411,6412,6413,6414,6415,6417,642,651".split(","):
    masSch.Добавить(c)
masE = buh.NewObject("Массив")
for e in podr_by_edr:
    masE.Добавить(e)
qb = buh.NewObject("Запрос")
qb.УстановитьПараметр("Счета", masSch)
qb.УстановитьПараметр("масЕ", masE)
qb.Текст = """
ВЫБРАТЬ Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ, Ост.Счет.Код КАК КодСчета,
    Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт КАК Сальдо
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(ДАТАВРЕМЯ(2025,11,30,23,59,59), ДАТАВРЕМЯ(2025,11,30,23,59,59), , , Счет.Код В (&Счета), , ) КАК Ост
ГДЕ Ост.Организация.КодПоЕДРПОУ В (&масЕ) И (Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) <> 0"""

# === СТАРАЯ логика: по бух.организации ===
old = defaultdict(float)   # (ЕДРПОУ, Подр, Тип) -> сальдо
# === НОВАЯ логика (фикс): консолидация на одну орг, агрегат Подр×Тип ===
new = defaultdict(float)   # (Подр, Тип) -> сальдо
sel = qb.Выполнить().Выбрать()
while sel.Следующий():
    edr = str(sel.ЕДРПОУ).strip(); code = str(sel.КодСчета).strip()
    s = float(sel.Сальдо); t = tip(code); p = podr_by_edr.get(edr, "?")
    old[(edr, p, t)] += s
    new[(p, t)] += s

print("\n=== БЫЛО: ПАП налоги по бух.организациям (КО на 30.11) ===")
tot_by_org = defaultdict(float)
for (edr, p, t), s in sorted(old.items()):
    tot_by_org[edr] += s
for edr, s in tot_by_org.items():
    print(f"  орг {edr} ({podr_by_edr.get(edr)}): {s:,.2f}")
print(f"  ИТОГО по 3 орг: {sum(tot_by_org.values()):,.2f}")
print(f"  → в OLAP попадала только ТОВ 40645273 = {tot_by_org.get('40645273',0):,.2f}")

print("\n=== СТАЛО (фикс): ПАП налоги на ОДНУ орг ТОВ ІНДАСТРІАЛБУД, агрегат Подр×ТипНалога ===")
print(f"{'Подразделение':<22}{'ТипНалога':<16}{'Сумма (signed)':>16}{'ВидДвижения':>14}")
tot = 0.0
for (p, t), s in sorted(new.items(), key=lambda x: -x[1]):
    if abs(s) < 0.005: continue
    tot += s
    vd = "Приход" if s > 0 else "Расход"
    print(f"{p[:22]:<22}{t:<16}{s:>16,.2f}{vd:>14}")
print(f"{'ИТОГО (управ.баланс «Налоги»)':<38}{tot:>16,.2f}")
print(f"\nОжидаемо = 5 210 076,10 (= отчёт УБ = регл.бухучёт = BuhBud).")
