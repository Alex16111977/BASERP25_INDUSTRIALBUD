from collections import Counter, defaultdict
agg = defaultdict(lambda: Counter())
for d in docs:
    k = (d['Комплект'].strip(), d['ОНКомплекта'] or '', d['Счет'], 'РК' if d['РКНомер'] else 'вне РК')
