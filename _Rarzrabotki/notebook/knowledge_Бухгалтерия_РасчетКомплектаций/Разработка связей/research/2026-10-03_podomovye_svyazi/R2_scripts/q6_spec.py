from h import *
import json, re
B = connect('buh')
specs = q(B, """
ВЫБРАТЬ С.Ссылка КАК Ссылка, С.Код КАК Код, С.Наименование КАК Спец, С.Владелец.Наименование КАК Владелец, С.Владелец.Код КАК КодВлад,
	С.Количество КАК КолВыхода, С.ПометкаУдаления КАК Помеч,
	ВЫБОР КОГДА С.Владелец.ОсновнаяСпецификацияНоменклатуры = С.Ссылка ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК Основная
ИЗ Справочник.СпецификацииНоменклатуры КАК С
УПОРЯДОЧИТЬ ПО С.Код""")
rows = q(B, """
ВЫБРАТЬ ИК.Ссылка.Код КАК КодСпец, ИК.Номенклатура.Код КАК КодНом, ИК.Номенклатура.Наименование КАК Ном,
	ИК.Номенклатура.ОбщееНазваниеНоменклатуры.Наименование КАК ОН, СУММА(ИК.Количество) КАК Кол
ИЗ Справочник.СпецификацииНоменклатуры.ИсходныеКомплектующие КАК ИК
СГРУППИРОВАТЬ ПО ИК.Ссылка.Код, ИК.Номенклатура.Код, ИК.Номенклатура.Наименование, ИК.Номенклатура.ОбщееНазваниеНоменклатуры.Наименование""")
json.dump({"specs": specs, "rows": rows}, open('specs.json', 'w', encoding='utf-8'), ensure_ascii=False)
from collections import defaultdict, Counter
byspec = defaultdict(dict)
for r in rows:
    byspec[r['КодСпец']][r['КодНом']] = (r['Ном'], r['ОН'], r['Кол'])
own = Counter(s['Владелец'].strip() for s in specs)
print("=== владельцы спецификаций (кол-во спец.)")
for k, v in own.most_common():
    print(v, "|", k)
print("=== основные спецификации:", sum(1 for s in specs if s['Основная']))
for s in specs:
    if s['Основная']:
        print("  осн:", s['Код'], s['Спец'].strip(), "<-", s['Владелец'].strip(), "строк", len(byspec.get(s['Код'], {})))
# ООН per-house specs
oon = [s for s in specs if 'ООН' in s['Владелец'] and not s['Помеч']]
print("=== ООН-спецификации:", len(oon))
for s in oon:
    print(s['Код'], "|", s['Спец'].strip(), "|", s['Владелец'].strip(), "| строк", len(byspec.get(s['Код'], {})), "| вых", s['КолВыхода'])
