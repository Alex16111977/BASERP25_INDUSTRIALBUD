def arr(items):
    a = b.NewObject("Массив")
    for x in items:
        a.Добавить(x)
    return a

def run(name, text, params=None):
    q = b.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    try:
        r = q.Execute().Выгрузить()
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"[{name}] FAIL: {e.excepinfo[2]}")
        else:
            print(f"[{name}] FAIL: {e}")
        return None
    n = r.Количество()
    nc = r.Колонки.Количество()
    cols = [r.Колонки.Получить(i).Имя for i in range(nc)]
    out = []
    for i in range(n):
        row = r.Получить(i)
        d = {}
        for j, c in enumerate(cols):
            v = row.Получить(j)
            if isinstance(v, (int, float, str, bool)) or v is None:
                d[c] = v
            else:
                d[c] = S(v)
        out.append(d)
    print(f"[{name}] OK, рядків={n}")
    return out

