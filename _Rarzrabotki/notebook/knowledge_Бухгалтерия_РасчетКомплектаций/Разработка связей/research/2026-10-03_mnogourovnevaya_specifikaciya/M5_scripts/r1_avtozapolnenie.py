# r1: что даст «Заповнити з СС» по правилам доработанного M5 (кандидаты ТОЛЬКО из базы, без факта/JSON).
# Только чтение. BuhBud. Правила:
#  A: у ОН позиции заполнена ОсновнаяНоменклатура -> она
#  B: иначе у ОН ровно одна активная карточка -> она
#  C: иначе 2+ карточки -> выбирает бухгалтер
#  D: ОН пуста или карточек 0 -> нет кандидата
#  Нулевые строки (Количество = 0) пропускаются.
# Единица строки: из {ЕдиницаСС (после пересчёта СС), ЕдиницаСС_Оригинал} та, что совпадает с единицей карточки
# по КлючЕдиницы (серверная функция СС) -> k = 1; иначе k нужно задать.
import sys
from h import connect, q, pr
c = connect('buh')
M = c.А_СтруктураСебестоимостиСервер

def run(kod):
    rows = q(c, """
ВЫБРАТЬ
	К.НомерСтроки КАК Н,
	К.НоменклатураСС КАК Поз,
	К.ОбщееНазвание КАК ОНСсылка,
	ПРЕДСТАВЛЕНИЕ(К.ОбщееНазвание) КАК ОН,
	К.ОбщееНазвание.ОсновнаяНоменклатура КАК Осн,
	К.Количество КАК Кол,
	К.ЕдиницаСС КАК ЕдСС,
	К.КоличествоСС_Оригинал КАК КолОриг,
	К.ЕдиницаСС_Оригинал КАК ЕдОриг,
	К.Сумма КАК Сум
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Код = &Код
УПОРЯДОЧИТЬ ПО
	Н
""", Код=kod)
    cards = q(c, """
ВЫБРАТЬ
	Н.ОбщееНазваниеНоменклатуры КАК ОНСсылка,
	Н.Ссылка КАК Карта,
	Н.БазоваяЕдиницаИзмерения.Наименование КАК ЕдКарты
ИЗ
	Справочник.Номенклатура КАК Н
ГДЕ
	НЕ Н.ПометкаУдаления
	И НЕ Н.ЭтоГруппа
	И Н.ОбщееНазваниеНоменклатуры В
		(ВЫБРАТЬ РАЗЛИЧНЫЕ К.ОбщееНазвание ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
		 ГДЕ К.Ссылка.Код = &Код)
""", Код=kod)
    # единицы основной карточки
    osn = q(c, """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	К.ОбщееНазвание.ОсновнаяНоменклатура КАК Карта,
	К.ОбщееНазвание.ОсновнаяНоменклатура.БазоваяЕдиницаИзмерения.Наименование КАК ЕдКарты
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Код = &Код
	И К.ОбщееНазвание.ОсновнаяНоменклатура <> ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
""", Код=kod)
    by_on = {}
    for r in cards:
        by_on.setdefault(r['ОНСсылка'], []).append(r)
    unit_of = {r['Карта']: r['ЕдКарты'] for r in cards}
    for r in osn:
        unit_of[r['Карта']] = r['ЕдКарты']
    ku = {}
    def key(t):
        t = (t or '').strip()
        if t not in ku:
            ku[t] = M.КлючЕдиницы(t) if t else ''
        return ku[t]
    cat = {}
    zero = []
    kneed = []
    korig = 0
    for r in rows:
        if (r['Кол'] or 0) == 0:
            zero.append(r); continue
        on = r['ОНСсылка']; lst = by_on.get(on, []) if r['ОН'] else []
        if r['Осн'] and r['Осн'].strip():
            k, card = 'A ОсновнаяНоменклатура', r['Осн']
        elif len(lst) == 1:
            k, card = 'B одна карточка ОН', lst[0]['Карта']
        elif len(lst) >= 2:
            k, card = 'C 2+ карточки', None
        else:
            k, card = 'D нет кандидата', None
        cat.setdefault(k, [0, 0.0]); cat[k][0] += 1; cat[k][1] += r['Сум'] or 0
        if card:
            uc = key(unit_of.get(card, ''))
            if uc == key(r['ЕдСС']):
                pass
            elif r['ЕдОриг'] and uc == key(r['ЕдОриг']):
                korig += 1
            else:
                kneed.append((r['Н'], r['Поз'], r['ЕдСС'], r['ЕдОриг'], unit_of.get(card, ''), card))
    print(f"=== СС {kod}: строк {len(rows)}, нулевых (пропуск) {len(zero)}, Σ {sum((r['Сум'] or 0) for r in rows):,.2f}")
    for k in sorted(cat):
        print(f"  {k}: позиций {cat[k][0]}, сумма {cat[k][1]:,.2f}")
    print(f"  с кандидатом: единица карточки = ЕдиницаСС -> k=1; = ЕдиницаСС_Оригинал (строка в исходной ед., k=1): {korig}; нужен k: {len(kneed)}")
    for x in kneed:
        print("    k? поз.", x[0], "|", x[1], "| ЕдСС", x[2], "| ЕдОриг", x[3], "| ед.карточки", x[4], "|", x[5])
    gv = [r for r in rows if r['ОН'] and 'Гвинтов' in r['ОН']]
    print(f"  «Гвинтові кріплення»: позиций {len(gv)}, сумма {sum(r['Сум'] for r in gv):,.2f}")

for kod in sys.argv[1:] or ['000000009']:
    run(kod)
