def nums(t):
    t=re.sub(r'(?i)ст\.?\s*\d+','',t).replace(',','.')
    out=[]
    for n in re.findall(r'\d+(?:\.\d+)?', t):
        f=float(n); out.append(('%g'%f))
    return out
def score(a,b):
    na,nb=nums(a),nums(b)
    if not na: return 0
    return len([n for n in na if n in nb])/len(na)
