def run(text, params=None, cols=None):
    q = b.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    try:
        r = q.Execute().Выгрузить()
    except Exception as e:
        print("FAIL:", e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e)
        return []
    out = []
    n = r.Колонки.Количество()
    names = [r.Колонки.Получить(i).Имя for i in range(n)]
    for i in range(r.Количество()):
        row = r.Получить(i)
        out.append({names[j]: row.Получить(j) for j in range(n)})
    return out

