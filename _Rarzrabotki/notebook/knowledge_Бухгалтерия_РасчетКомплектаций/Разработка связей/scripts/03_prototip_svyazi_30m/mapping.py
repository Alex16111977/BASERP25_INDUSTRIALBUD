BY_LINE = build()


def line_method(n):
    if n == SEPTIC_LINE:
        return "комплект"
    if LINE[n]["k"] in GROUP_ON:
        return "групова норма"
    lst = BY_LINE.get(n, [])
    if not lst:
        return "без карточки"
    ms = {MAP[c]["method"] for c, _, _ in lst}
    if "аліас" in ms:
        return "аліас / пересорт"
    if "за розміром" in ms:
        return "за розміром"
    if "за ОН N:1" in ms:
        return "N:1 за ОН"
    return "1:1 за ОН"


def line_conf(n):
    lst = BY_LINE.get(n, [])
    if not lst:
        return "—"
    order = {"high": 0, "medium": 1, "low": 2}
    return max((l["conf"] for _, _, l in lst), key=lambda x: order[x])


