def sv(v):
    if v is None:
        return ""
    if isinstance(v, (int, float, str, bool)):
        return v
    try:
        return B.String(v)
    except Exception:
        return str(v)


def rows(vt, cols):
    out = []
    for i in range(vt.Количество()):
        r = vt.Получить(i)
        out.append({c: sv(getattr(r, c)) for c in cols})
    return out


