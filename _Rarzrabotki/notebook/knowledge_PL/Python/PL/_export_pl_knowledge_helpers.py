def render_dds_mapping(mapping_rows):
    """mapping_rows: result of fetch_mapping() — flat rows with per-PL per-ДДС row."""
    # Aggregate: forward PL→[ДДС] and reverse ДДС→[PL]
    headers = {}       # PL_Наим → {код, группа, тип, ддс_header_код, ддс_header_наим}
    forward = defaultdict(list)
    reverse = defaultdict(list)
    for r in mapping_rows:
        pl_name = r["PLНаим"]
        if pl_name not in headers:
            headers[pl_name] = {
                "код": r["PLКод"], "группа": r["PLГруппа"], "тип": r["PLТип"],
                "ддс_header_код": r["ДДСHeaderКод"], "ддс_header_наим": r["ДДСHeaderНаим"],
            }
        tc_naim = r["ДДСТЧНаим"]
        if tc_naim:
            forward[pl_name].append({"код": r["ДДСТЧКод"], "наим": tc_naim})
