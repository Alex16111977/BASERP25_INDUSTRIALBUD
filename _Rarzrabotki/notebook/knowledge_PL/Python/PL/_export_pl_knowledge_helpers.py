def render_delta(prev_month, curr_month, prev_label, curr_label):
    """Render month-to-month delta. Each month is {grouped, gaps_...} dict from render flow.

    For simplicity, we pass the raw plan+fact+cash data as tuples.
    """
    (plan_p, fr_p, fd_p, c_p, mapping) = prev_month
    (plan_c, fr_c, fd_c, c_c, _) = curr_month

    # Aggregate per article across all subrozd
    def aggregate(plan, fact_rash, fact_doh, cash, mapping_rows):
        grouped, _, _, _ = _group_by_article(plan, fact_rash, fact_doh, cash, mapping_rows)
        per_art = defaultdict(lambda: {
            "plan": 0.0, "fr": 0.0, "fd": 0.0, "cin": 0.0, "cout": 0.0,
            "коммент": "", "контрагенти": set(), "группа": "", "тип": "",
        })
        for subs in grouped.values():
            for art, b in subs.items():
                a = per_art[art]
                a["plan"] += b["plan_суммы"]["pl"]
                a["fr"] += sum(x["сумма"] for x in b["fact_rash"])
                a["fd"] += sum(x["сумма"] for x in b["fact_doh"])
                a["cin"] += sum(x["приход"] for x in b["cash"])
                a["cout"] += sum(x["расход"] for x in b["cash"])
                for d in b["fact_rash"] + b["fact_doh"] + b["cash"]:
                    if d.get("контрагент"):
                        a["контрагенти"].add(d["контрагент"])
                if b["plan_коммент"] and not a["коммент"]:
                    a["коммент"] = b["plan_коммент"]
                a["группа"] = b["группа"] or a["группа"]
                a["тип"] = b["тип"] or a["тип"]
        return per_art

    a_prev = aggregate(plan_p, fr_p, fd_p, c_p, mapping)
    a_curr = aggregate(plan_c, fr_c, fd_c, c_c, mapping)
    all_arts = set(a_prev) | set(a_curr)

    empty = {"plan": 0, "fr": 0, "fd": 0, "cin": 0, "cout": 0, "коммент": "", "контрагенти": set(), "группа": "", "тип": ""}

    rows = []
    for art in all_arts:
        p = a_prev.get(art, empty)
        c = a_curr.get(art, empty)
        rows.append({
            "стаття": art,
            "группа": c["группа"] or p["группа"],
            "тип": c["тип"] or p["тип"],
            "план_prev": p["plan"], "план_curr": c["plan"], "d_план": c["plan"] - p["plan"],
            "факт_prev": p["fr"] + p["fd"], "факт_curr": c["fr"] + c["fd"],
            "d_факт": (c["fr"] + c["fd"]) - (p["fr"] + p["fd"]),
            "новинки": sorted(c["контрагенти"] - p["контрагенти"]),
            "зникли": sorted(p["контрагенти"] - c["контрагенти"]),
            "коммент_prev": p["коммент"], "коммент_curr": c["коммент"],
        })

    lines = [
        f"# PL-дельта ІНДАСТРІАЛБУД: {curr_label} vs {prev_label}",
        "",
        f"Дата генерації: {datetime.date.today().isoformat()}  ",
        "Тип: ЗМІННИЙ",
        "",
        "## Contextual metadata для AI-retrieval",
        "",
        "**Company:** ТОВ \"ІНДАСТРІАЛБУД\" (INDUSTRIALBUD LLC)  ",
        f"**Comparison:** {curr_label} (поточний) vs {prev_label} (попередній)  ",
        "**Currency:** UAH (₴)  ",
        "**Document type:** Місяць-до-місяця дельта PL (топ-10 змін, нові/зниклі контрагенти, коментарі до і після)  ",
        "**Scope:** Тільки ЦО-документи, без СВОД-дублювань  ",
        "",
        "---",
        "",
        "## Top-10 статей за абсолютною зміною плану",
        "",
        "| Стаття | Група | План prev ₴ | План curr ₴ | Δ План ₴ | Факт prev ₴ | Факт curr ₴ | Δ Факт ₴ |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda x: -abs(x["d_план"]))[:10]:
        lines.append(f"| {r['стаття']} | {r['группа']} | "
                     f"{fmt_money(r['план_prev'])} | {fmt_money(r['план_curr'])} | {fmt_money(r['d_план'])} | "
                     f"{fmt_money(r['факт_prev'])} | {fmt_money(r['факт_curr'])} | {fmt_money(r['d_факт'])} |")
    lines.append("")
    lines.append("## Top-10 статей за абсолютною зміною факту")
    lines.append("")
    lines.append("| Стаття | Група | Факт prev ₴ | Факт curr ₴ | Δ Факт ₴ |")
    lines.append("|---|---|---|---|---|")
    for r in sorted(rows, key=lambda x: -abs(x["d_факт"]))[:10]:
        lines.append(f"| {r['стаття']} | {r['группа']} | {fmt_money(r['факт_prev'])} | {fmt_money(r['факт_curr'])} | {fmt_money(r['d_факт'])} |")
    lines.append("")

    all_new = set()
    for r in rows:
        all_new.update(r["новинки"])
    lines.append(f"## Нові контрагенти у {curr_label}")
    lines.append("")
    if all_new:
        for k in sorted(all_new)[:30]:
            arts = [r["стаття"] for r in rows if k in r["новинки"]]
            lines.append(f"- **{k}** → у: {', '.join(arts[:5])}")
    else:
        lines.append("*(жодного нового контрагента)*")
    lines.append("")

    all_gone = set()
    for r in rows:
        all_gone.update(r["зникли"])
    lines.append(f"## Контрагенти що зникли порівняно з {prev_label}")
    lines.append("")
    if all_gone:
        for k in sorted(all_gone)[:30]:
            arts = [r["стаття"] for r in rows if k in r["зникли"]]
            lines.append(f"- **{k}** → раніше у: {', '.join(arts[:5])}")
    else:
        lines.append("*(жодного зниклого контрагента)*")
    lines.append("")

    lines.append("## Коментар тоді й зараз — Top-10 значимих статей")
    lines.append("")
    signif = sorted(rows, key=lambda x: -(abs(x["план_curr"]) + abs(x["факт_curr"])))[:10]
    for r in signif:
        if not (r["коммент_prev"] or r["коммент_curr"]):
            continue
        lines.append(f"### {r['стаття']}")
        lines.append(f"- **{prev_label}**: {r['коммент_prev'] or '*(немає)*'}")
        lines.append(f"- **{curr_label}**: {r['коммент_curr'] or '*(немає)*'}")
        lines.append("")

    return "\n".join(lines)


def load_excel_comments(raw_sheets_path, period_label):
    try:
        data = json.loads(Path(raw_sheets_path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}
    period = next((p for p in data if p["label"] == period_label), None)
    if not period:
        return {}
    out = defaultdict(list)
    for sh in period["sheets"]:
        for row in sh["rows"]:
            art = (row.get("article") or "").strip()
            if art:
                out[(sh["sheet_name"], art)].append({
                    "row": row.get("row"),
                    "comment": (row.get("comment") or "").strip(),
                    "sum_f1": row.get("sum_f1") or 0.0,
                    "sum_f2": row.get("sum_f2") or 0.0,
                    "total": row.get("total") or 0.0,
                })
    return dict(out)
