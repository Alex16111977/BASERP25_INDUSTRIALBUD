def fmt_money(x):
    if x is None or abs(float(x)) < 0.01:
        return "—"
    neg = x < 0
    ax = abs(float(x))
    intp = int(ax)
    frac = ax - intp
    s = f"{intp:,}".replace(",", " ")
    if frac > 0.005:
        s = f"{s}.{int(round(frac * 100)):02d}"
    return f"−{s}" if neg else s


def fmt_date(v):
    if not v:
        return ""
    s = str(v)[:10]
    if s in ("0001-01-01", "0100-01-01"):
        return ""
    if len(s) == 10 and s[4] == "-":
        y, m, d = s.split("-")
        if y in ("0001", "0100"):
            return ""
        return f"{d}.{m}.{y}"
    return s


def clean_type(type_str):
    """Convert type string to clean form.

    Handles both 'Документ.РеализацияТоваровУслуг' and 'Реализация товаров и услуг' (ПРЕДСТАВЛЕНИЕ).
    """
    if not type_str:
        return ""
    if type_str.startswith("Документ."):
        return type_str[len("Документ."):]
    return type_str


