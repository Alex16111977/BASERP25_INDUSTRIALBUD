# -*- coding: utf-8 -*-
"""
05b_drill_os_params.py — drill 3-х ОС из задвоенного документа:
  - параметры амортизации БУ (РС.ПараметрыАмортизацииОСБУ)
  - параметры амортизации УУ (РС.ПараметрыАмортизацииОСУУ)
  - первоначальные сведения (РС.ПервоначальныеСведенияОС)
  - стоимость (РН.СтоимостьОС.Остатки)

Цель: подтвердить — отличаются ли методы амортизации (БУ vs УУ)
и из-за этого создаются 2 строки в РН.ПрочиеРасходы.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import connect_erp, fail, money

OBJECTS = [
    "Гайковерт удар.акумулятор. BOSCH 18B GDS 18V-1050 H 2*5Ah",
    "Вишка Варіант 1,2*2,0 6+1 вис 8,7",
    "Фільтр зворотного осмосу ECOSOFT Robust mini+бак+кран д/набора води",
]


def find_obj(erp, name):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Н", name)
    q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.ОбъектыЭксплуатации ГДЕ Наименование = &Н"
    sel = q.Выполнить().Выбрать()
    if sel.Следующий():
        return sel.Ссылка
    return None


def dump_query(erp, name, q_text, params):
    q = erp.NewObject("Запрос")
    for k, v in params.items():
        q.УстановитьПараметр(k, v)
    q.Текст = q_text
    try:
        rez = q.Выполнить().Выгрузить()
    except Exception as e:
        print(f"  FAIL {name}: {fail(e)}")
        return
    if rez.Количество() == 0:
        print(f"  {name}: (нет записей)")
        return
    print(f"  {name}: {rez.Количество()} строк")
    cols = [c.Имя for c in rez.Колонки]
    for i in range(rez.Количество()):
        r = rez.Получить(i)
        parts = []
        for c in cols:
            try:
                v = getattr(r, c)
            except Exception:
                v = None
            if v is None or str(v) == "" or str(v) == "Пустая ссылка" or str(v) == "0":
                continue
            parts.append(f"{c}={v}")
        print(f"    [{i}] " + " | ".join(parts))


def main():
    erp = connect_erp()

    for obj_name in OBJECTS:
        print(f"\n{'='*100}\n=== {obj_name}\n{'='*100}")
        obj = find_obj(erp, obj_name)
        if obj is None or not erp.ЗначениеЗаполнено(obj):
            print("  НЕ НАЙДЕН")
            continue

        params = {"ОС": obj}

        # 1) Параметры амортизации БУ — НЕТ поля МетодНачисления, только СПИ + Стоимость + График
        dump_query(erp, "РС.ПараметрыАмортизацииОСБУ (срез последних)", """
            ВЫБРАТЬ
                Период,
                СрокПолезногоИспользованияБУ КАК СПИ_БУ_мес,
                СрокПолезногоИспользованияНУ КАК СПИ_НУ_мес,
                СтоимостьДляВычисленияАмортизации КАК СтДляВычисл_БУ,
                СтоимостьДляВычисленияАмортизацииНУ КАК СтДляВычисл_НУ,
                ЛиквидационнаяСтоимость,
                ПРЕДСТАВЛЕНИЕ(ГрафикАмортизации) КАК ГрафикАмортизации,
                ПРЕДСТАВЛЕНИЕ(Регистратор) КАК Регистратор
            ИЗ РегистрСведений.ПараметрыАмортизацииОСБУ.СрезПоследних(ДАТАВРЕМЯ(2026,4,1,0,0,0), ОсновноеСредство = &ОС)
        """, params)

        # 2) Параметры амортизации УУ — С полем МетодНачисления
        dump_query(erp, "РС.ПараметрыАмортизацииОСУУ (срез последних)", """
            ВЫБРАТЬ
                Период,
                ПРЕДСТАВЛЕНИЕ(МетодНачисленияАмортизации) КАК МетодУУ,
                СрокИспользования КАК СПИ_УУ_мес,
                СтоимостьДляВычисленияАмортизации КАК СтДляВычисл_Упр,
                СтоимостьДляВычисленияАмортизацииРегл КАК СтДляВычисл_Регл,
                ЛиквидационнаяСтоимость КАК ЛиквСтоимость_Упр,
                ЛиквидационнаяСтоимостьРегл КАК ЛиквСтоимость_Регл,
                КоэффициентУскорения,
                ПРЕДСТАВЛЕНИЕ(Регистратор) КАК Регистратор
            ИЗ РегистрСведений.ПараметрыАмортизацииОСУУ.СрезПоследних(ДАТАВРЕМЯ(2026,4,1,0,0,0), ОсновноеСредство = &ОС)
        """, params)

        # 3) Стоимость ОС на конец Март 2026
        dump_query(erp, "РН.СтоимостьОС.Остатки на 01.04.2026", """
            ВЫБРАТЬ
                СтоимостьОстаток КАК СтоимостьУУ,
                СтоимостьРеглОстаток КАК СтоимостьБУ,
                СтоимостьНУОстаток КАК СтоимостьНУ,
                АмортизационнаяПремияОстаток КАК АмортПремия
            ИЗ РегистрНакопления.СтоимостьОС.Остатки(ДАТАВРЕМЯ(2026,4,1,0,0,0), ОсновноеСредство = &ОС)
        """, params)

        # 4) Амортизация накопленная
        dump_query(erp, "РН.АмортизацияОС.Остатки на 01.04.2026", """
            ВЫБРАТЬ
                АмортизацияОстаток КАК АмортизацияУУ,
                АмортизацияРеглОстаток КАК АмортизацияБУ,
                АмортизацияНУОстаток КАК АмортизацияНУ
            ИЗ РегистрНакопления.АмортизацияОС.Остатки(ДАТАВРЕМЯ(2026,4,1,0,0,0), ОсновноеСредство = &ОС)
        """, params)

    return 0


if __name__ == "__main__":
    sys.exit(main())
