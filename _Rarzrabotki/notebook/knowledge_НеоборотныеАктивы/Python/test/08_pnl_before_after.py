# -*- coding: utf-8 -*-
"""
08_pnl_before_after.py — диагностика того, что попадает в А_ФинРез_PL.

А_ФинРез_PL.ObjectModule.bsl:183 читает:
  СУММА(Р.СуммаПриход) ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(Период, Регистратор, )

Где СуммаПриход = Σ колонки `Сумма` по ВидДвижения=Приход.

Этот скрипт:
  1. Показывает текущее Σ Сумма_Приход по нашему документу 000Ц-000003 (что попадает в PnL сейчас)
  2. Симулирует Σ Сумма_Приход после Варианта B v2 (правка БОБА строк)
  3. Сравнивает с правильной управ.амортизацией = Σ Поступление в РН.ПАП за период

Выгрузка: _artifacts/08_pnl_diag.csv
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import connect_erp, save_csv, fail, money

DOC_UUID = "2d9182ad-3062-11f1-a2e7-eb06fbf9b98b"


def main():
    erp = connect_erp()
    uid = erp.NewObject("УникальныйИдентификатор", DOC_UUID)
    doc_ref = erp.Документы.АмортизацияОС.ПолучитьСсылку(uid)
    print(f"Документ: {erp.String(doc_ref)}\n")

    # 1) Текущее СОСТОЯНИЕ: Σ Сумма_Приход + Σ СуммаРегл_Приход по РН.ПрочиеРасходы
    print("=== А_ФинРез_PL читает СЕЙЧАС (РН.ПрочиеРасходы.Обороты) ===")
    q1 = erp.NewObject("Запрос")
    q1.УстановитьПараметр("Р", doc_ref)
    q1.Текст = """
    ВЫБРАТЬ
        ПРЕДСТАВЛЕНИЕ(ПР.Подразделение) КАК Подразделение,
        ПРЕДСТАВЛЕНИЕ(ПР.АналитикаРасходов) КАК Аналитика,
        СУММА(ПР.Сумма)     КАК Σ_Сумма_Приход,
        СУММА(ПР.СуммаУпр)  КАК Σ_СуммаУпр_Приход,
        СУММА(ПР.СуммаРегл) КАК Σ_СуммаРегл_Приход
    ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
    ГДЕ ПР.Регистратор = &Р
        И ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        И ПР.СтатьяРасходов.Наименование ПОДОБНО "Амортиз%"
    СГРУППИРОВАТЬ ПО ПР.Подразделение, ПР.АналитикаРасходов
    """
    try:
        rez = q1.Выполнить().Выгрузить()
    except Exception as e:
        print(f"FAIL: {fail(e)}")
        return 1

    print(f"  {'Подразделение':<20} {'Аналитика':<55} {'Σ Сумма':>14} {'Σ СуммаУпр':>14} {'Σ СуммаРегл':>14}")
    rows = []
    σ_сумма = σ_суммаупр = σ_суммарегл = 0
    for i in range(rez.Количество()):
        r = rez.Получить(i)
        s = float(r.Σ_Сумма_Приход or 0)
        su = float(r.Σ_СуммаУпр_Приход or 0)
        sr = float(r.Σ_СуммаРегл_Приход or 0)
        σ_сумма += s; σ_суммаупр += su; σ_суммарегл += sr
        nazv = str(r.Аналитика)
        podr = str(r.Подразделение)
        print(f"  {podr[:20]:<20} {nazv[:55]:<55} {money(s):>14} {money(su):>14} {money(sr):>14}")
        rows.append({
            "Подразделение": podr, "ОС": nazv,
            "Σ_Сумма_СЕЙЧАС": s, "Σ_СуммаУпр_СЕЙЧАС": su, "Σ_СуммаРегл_СЕЙЧАС": sr,
        })

    print(f"  {'ИТОГО':<20} {'':<55} {money(σ_сумма):>14} {money(σ_суммаупр):>14} {money(σ_суммарегл):>14}")
    print(f"\n  ★ В PnL сейчас идёт: {money(σ_сумма)} (Σ Сумма_Приход)")
    print(f"  ★ Должно идти:        {money(σ_суммарегл * 1.20)} (бух × 1.20 = с НДС, упрощённо)\n")

    # 2) Что должно идти в PnL после Вариант B v2:
    # = Σ Поступление в РН.ПАП по статье «Основные средства» (Аналитика=ОС) — это правильная управ.с НДС
    print("=== А_ФинРез_PL ПОСЛЕ Варианта B v2 (взято из остатка РН.ПАП на НачалоМесяца) ===")
    q2 = erp.NewObject("Запрос")
    q2.УстановитьПараметр("Р", doc_ref)
    q2.Текст = """
    ВЫБРАТЬ РАЗЛИЧНЫЕ
        ВЫРАЗИТЬ(ПР.АналитикаРасходов КАК Справочник.ОбъектыЭксплуатации) КАК ОС,
        ПРЕДСТАВЛЕНИЕ(ПР.Подразделение) КАК Подразделение,
        ПРЕДСТАВЛЕНИЕ(ПР.АналитикаРасходов) КАК ОСИмя
    ПОМЕСТИТЬ втОС
    ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
    ГДЕ ПР.Регистратор = &Р
        И ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        И ПР.СтатьяРасходов.Наименование ПОДОБНО "Амортиз%"
    ;
    ВЫБРАТЬ
        втОС.Подразделение, втОС.ОСИмя,
        ЕСТЬNULL(СУММА(ВЫБОР
            КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) И Т.Период <= ДАТАВРЕМЯ(2026,3,31,23,59,59)
                ТОГДА Т.Сумма
            КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) И Т.Период < ДАТАВРЕМЯ(2026,3,1,0,0,0)
                ТОГДА -Т.Сумма
            ИНАЧЕ 0
        КОНЕЦ), 0) КАК Остаток_НаНачМес,
        ЕСТЬNULL(МАКСИМУМ(ПАрБУ.СрокПолезногоИспользованияБУ), 1) КАК СПИ
    ИЗ втОС
        ЛЕВОЕ СОЕДИНЕНИЕ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
            ПО Т.Аналитика = втОС.ОС
                И Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОсновныеСредства)
                И Т.Регистратор <> &Р
        ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.ПараметрыАмортизацииОСБУ.СрезПоследних(ДАТАВРЕМЯ(2026,3,31,23,59,59)) КАК ПАрБУ
            ПО ПАрБУ.ОсновноеСредство = втОС.ОС
    СГРУППИРОВАТЬ ПО втОС.Подразделение, втОС.ОСИмя
    """
    try:
        rez2 = q2.Выполнить().Выгрузить()
    except Exception as e:
        print(f"FAIL: {fail(e)}")
        return 2

    print(f"  {'Подразделение':<20} {'ОС':<55} {'Остаток':>14} {'СПИ':>5} {'ПравильнАморт':>14}")
    σ_правильно = 0
    for i in range(rez2.Количество()):
        r = rez2.Получить(i)
        podr = str(r.Подразделение)
        nazv = str(r.ОСИмя)
        ostatok = float(r.Остаток_НаНачМес or 0)
        spi = max(1, int(r.СПИ or 1))
        aмort = round(ostatok / spi, 2) if spi > 1 else ostatok
        σ_правильно += aмort
        print(f"  {podr[:20]:<20} {nazv[:55]:<55} {money(ostatok):>14} {spi:>5} {money(aмort):>14}")
        # Объединяем с rows
        for row in rows:
            if row["ОС"] == nazv and row["Подразделение"] == podr:
                row["Остаток_НаНачМес"] = ostatok
                row["СПИ_БУ"] = spi
                row["ПравильнАморт_ПОСЛЕ"] = aмort
                row["Δ_PnL"] = aмort - row["Σ_Сумма_СЕЙЧАС"]
                break

    print(f"  {'ИТОГО':<20} {'':<55} {'':<14} {'':<5} {money(σ_правильно):>14}")

    print(f"\n=== СРАВНЕНИЕ ===")
    print(f"  Σ_Сумма_СЕЙЧАС (в PnL сейчас):       {money(σ_сумма)}")
    print(f"  Σ_Сумма_ПОСЛЕ (в PnL после Вар B v2): {money(σ_правильно)}")
    print(f"  Δ:                                    {money(σ_правильно - σ_сумма)}")
    print(f"  Σ_СуммаРегл (бух — не меняется):     {money(σ_суммарегл)}")

    save_csv("08_pnl_diag", rows,
             ["Подразделение","ОС","Σ_Сумма_СЕЙЧАС","Σ_СуммаУпр_СЕЙЧАС","Σ_СуммаРегл_СЕЙЧАС",
              "Остаток_НаНачМес","СПИ_БУ","ПравильнАморт_ПОСЛЕ","Δ_PnL"])
    print(f"\n→ _artifacts/08_pnl_diag.csv ({len(rows)} строк)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
