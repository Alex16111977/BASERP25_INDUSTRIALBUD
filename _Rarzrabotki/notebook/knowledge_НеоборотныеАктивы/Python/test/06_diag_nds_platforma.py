# -*- coding: utf-8 -*-
"""
06_diag_nds_platforma.py — диагностика «вечного остатка НДС» в управ.балансе.

Сценарий: Платформа роликова підкатна 6,0т поворотна Able (ІБ-01 362)
  1. СписаниеТоваровПоТребованию 000Ц-000016 от 12.03.2026
     → РН.ПАП Дт «Основные средства» = 5 458,00 × 4 = 21 832,00 (С НДС)
  2. АмортизацияОС 000Ц-000003 от 31.03.2026
     → РН.ПАП Кт «Основные средства» = 4 548,34 × 4 = 18 193,36 (БЕЗ НДС)
  3. Остаток = 21 832,00 − 18 193,36 = 3 638,64 (НДС, 909,66 × 4)
     → «висит вечно» в управ.балансе как непогашенный остаток ОС

Сравнить с Гайковертом BOSCH (1 ед):
  1. ПринятиеКУчетуОС  → ОС оприходовано без НДС (22 806,29 в РС.ПараметрыАмортизацииОСБУ)
  2. АмортизацияОС     → Кт ОС = 22 806,29 (без НДС, БОБА) + Дт Расходы доп.27 367,55 (с НДС, УПР)
     → задвоение в Контроле баланса

Цель: показать что для разных ОС работают разные механизмы НДС, и оба некорректны.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import connect_erp, save_csv, fail, money, get_org

OBJECTS = [
    ("Платформа роликова підкатна 6,0т поворотна Able", "Списание (с НДС)"),
    ("Гайковерт удар.акумулятор. BOSCH 18B GDS 18V-1050 H 2*5Ah", "ПринятиеКУчету (без НДС)"),
    ("Вишка Варіант 1,2*2,0 6+1 вис 8,7", "ПринятиеКУчету (без НДС)"),
    ("Фільтр зворотного осмосу ECOSOFT Robust mini+бак+кран д/набора води", "ПринятиеКУчету (без НДС)"),
]


def find_obj(erp, name):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Н", name)
    q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.ОбъектыЭксплуатации ГДЕ Наименование = &Н"
    sel = q.Выполнить().Выбрать()
    if sel.Следующий():
        return sel.Ссылка
    return None


def main():
    erp = connect_erp()
    org = get_org(erp)

    out_rows = []
    print(f"{'='*120}")
    print(f"{'ОС':<70} {'Поступление':>15} {'Аморт.К':>15} {'Остаток':>15} {'Источник':<25}")
    print(f"{'='*120}")

    for obj_name, source in OBJECTS:
        obj = find_obj(erp, obj_name)
        if obj is None or not erp.ЗначениеЗаполнено(obj):
            continue

        # Суммы Прихода и Расхода РН.ПАП по статье «Основные средства» И Аналитика=ОС
        # за период до 31.03.2026 включительно
        q = erp.NewObject("Запрос")
        q.УстановитьПараметр("ОС", obj)
        q.УстановитьПараметр("Орг", org)
        q.Текст = """
        ВЫБРАТЬ
            СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                       ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Поступление,
            СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                       ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК АмортизацияКт,
            КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Регистратор) КАК ЧислоРегистраторов
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
        ГДЕ Т.Организация = &Орг
            И Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОсновныеСредства)
            И Т.Аналитика = &ОС
            И Т.Период <= ДАТАВРЕМЯ(2026,3,31,23,59,59)
        """
        try:
            rez = q.Выполнить().Выгрузить()
        except Exception as e:
            print(f"  FAIL {obj_name[:50]}: {fail(e)}")
            continue
        if rez.Количество() == 0:
            continue
        r = rez.Получить(0)
        post = float(r.Поступление or 0)
        amort = float(r.АмортизацияКт or 0)
        ostatok = post - amort
        n_reg = int(r.ЧислоРегистраторов or 0)
        print(f"{obj_name[:70]:<70} {money(post):>15} {money(amort):>15} {money(ostatok):>15} {source:<25}")
        out_rows.append({
            "ОС": obj_name,
            "Поступление_Дт": post,
            "Амортизация_Кт": amort,
            "Остаток": ostatok,
            "ЧислоРегистраторов": n_reg,
            "ИсточникПоступления": source,
        })

    # Drill регистраторов для Платформы
    print(f"\n{'='*120}")
    print("=== DRILL Регистраторов для Платформы (что писало в Аналитика = ОС) ===")
    print(f"{'='*120}")
    platforma = find_obj(erp, "Платформа роликова підкатна 6,0т поворотна Able")
    if platforma:
        q = erp.NewObject("Запрос")
        q.УстановитьПараметр("ОС", platforma)
        q.УстановитьПараметр("Орг", org)
        q.Текст = """
        ВЫБРАТЬ
            ПРЕДСТАВЛЕНИЕ(Т.Регистратор) КАК Регистратор,
            ПРЕДСТАВЛЕНИЕ(Т.ВидДвижения) КАК ВидДвижения,
            ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
            СУММА(Т.Сумма) КАК Сумма,
            КОЛИЧЕСТВО(*) КАК Строк
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
        ГДЕ Т.Организация = &Орг
            И Т.Аналитика = &ОС
            И Т.Период <= ДАТАВРЕМЯ(2026,3,31,23,59,59)
        СГРУППИРОВАТЬ ПО Т.Регистратор, Т.ВидДвижения, Т.Статья
        """
        try:
            rez = q.Выполнить().Выгрузить()
            for i in range(rez.Количество()):
                r = rez.Получить(i)
                print(f"  {str(r.Регистратор)[:70]:<70} {str(r.ВидДвижения):<8} {str(r.Статья):<25} "
                      f"{money(float(r.Сумма)):>15} ({int(r.Строк)} строк)")
        except Exception as e:
            print(f"  FAIL: {fail(e)}")

    save_csv("06_nds_diag", out_rows,
             ["ОС","Поступление_Дт","Амортизация_Кт","Остаток","ЧислоРегистраторов","ИсточникПоступления"])
    print(f"\n→ _artifacts/06_nds_diag.csv ({len(out_rows)} строк)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
