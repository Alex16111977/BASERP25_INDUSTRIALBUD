# -*- coding: utf-8 -*-
"""
02_compare_prochie_rashody_vs_pap.py — главная разоблачающая диагностика.

Гипотеза: документ Амортизация ОС пишет в РН.ПрочиеАктивыПассывы
  - Кт ОС (Расход) ← на СуммаРегл (это А_СформироватьДвиженияАктивовПассивов в ObjectModule.bsl:280)
  - Дт Расходы (Приход) ← делает штатная Обработка.ДвиженияАктивовПассивов на ДРУГУЮ сумму (Сумма? СуммаУпр?)

Этот скрипт сравнивает по регистратору 000Ц-000003:
  СУММА(ПрочиеРасходы.СуммаРегл, СуммаУпр, Сумма) per (Подразделение, АналитикаРасходов)
  vs
  Σ(ПАП.Приход), Σ(ПАП.Расход) per (Подразделение)

Выгрузка: _artifacts/02_pr_vs_pap.csv
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import connect_erp, save_csv, fail, money

DOC_UUID = "2d9182ad-3062-11f1-a2e7-eb06fbf9b98b"


def main():
    erp = connect_erp()
    uid = erp.NewObject("УникальныйИдентификатор", DOC_UUID)
    doc_ref = erp.Документы.АмортизацияОС.ПолучитьСсылку(uid)
    print(f"Документ: {erp.String(doc_ref)}\n")

    # 1) ПрочиеРасходы по регистратору (вход амортизации)
    print("=== РН.ПрочиеРасходы (Приход / Расход / СуммаРегл / СуммаУпр / Сумма) ===")
    q1 = erp.NewObject("Запрос")
    q1.УстановитьПараметр("Р", doc_ref)
    q1.Текст = """
    ВЫБРАТЬ
        ПРЕДСТАВЛЕНИЕ(ПР.Подразделение) КАК Подразделение,
        ПРЕДСТАВЛЕНИЕ(ПР.ВидДвижения)   КАК ВидДвижения,
        ПРЕДСТАВЛЕНИЕ(ПР.СтатьяРасходов) КАК СтатьяРасходов,
        ПРЕДСТАВЛЕНИЕ(ПР.СтатьяРасходов.ТипРасходов) КАК ТипРасходов,
        ПРЕДСТАВЛЕНИЕ(ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл) КАК ВариантРаспределенияРеглБух,
        ПРЕДСТАВЛЕНИЕ(ПР.АналитикаРасходов) КАК Аналитика,
        СУММА(ПР.Сумма)     КАК Сумма,
        СУММА(ПР.СуммаУпр)  КАК СуммаУпр,
        СУММА(ПР.СуммаРегл) КАК СуммаРегл
    ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
    ГДЕ ПР.Регистратор = &Р
    СГРУППИРОВАТЬ ПО
        ПР.Подразделение, ПР.ВидДвижения, ПР.СтатьяРасходов,
        ПР.СтатьяРасходов.ТипРасходов,
        ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл,
        ПР.АналитикаРасходов
    """
    try:
        r1 = q1.Выполнить().Выгрузить()
    except Exception as e:
        print(f"FAIL ПрочиеРасходы: {fail(e)}")
        return 1
    rows_pr = []
    for i in range(r1.Количество()):
        r = r1.Получить(i)
        row = {
            "Подразделение": str(r.Подразделение),
            "ВидДвижения":   str(r.ВидДвижения),
            "СтатьяРасходов": str(r.СтатьяРасходов),
            "ТипРасходов":   str(r.ТипРасходов),
            "ВарРаспРегл":   str(r.ВариантРаспределенияРеглБух),
            "Аналитика":     str(r.Аналитика),
            "Сумма":         float(r.Сумма or 0),
            "СуммаУпр":      float(r.СуммаУпр or 0),
            "СуммаРегл":     float(r.СуммаРегл or 0),
        }
        rows_pr.append(row)
        print(f"  {row['Подразделение']:<25} {row['ВидДвижения']:<8} {row['СтатьяРасходов']:<35} "
              f"С={money(row['Сумма']):>13} Упр={money(row['СуммаУпр']):>13} Регл={money(row['СуммаРегл']):>13}")

    # 2) Свод ПАП по этому регистратору (Подразделение × Статья × signed)
    print("\n=== РН.ПрочиеАктивыПассивы (Σ signed по Подразделение × Статья) ===")
    q2 = erp.NewObject("Запрос")
    q2.УстановитьПараметр("Р", doc_ref)
    q2.Текст = """
    ВЫБРАТЬ
        ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подразделение,
        ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК ΣДт,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК ΣКт
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор = &Р
    СГРУППИРОВАТЬ ПО Т.Подразделение, Т.Статья
    """
    try:
        r2 = q2.Выполнить().Выгрузить()
    except Exception as e:
        print(f"FAIL ПАП: {fail(e)}")
        return 2
    rows_pap = []
    for i in range(r2.Количество()):
        r = r2.Получить(i)
        row = {
            "Подразделение": str(r.Подразделение),
            "Статья":        str(r.Статья),
            "ΣДт":           float(r.ΣДт or 0),
            "ΣКт":           float(r.ΣКт or 0),
        }
        rows_pap.append(row)
        print(f"  {row['Подразделение']:<25} {row['Статья']:<35} Дт={money(row['ΣДт']):>13} Кт={money(row['ΣКт']):>13}")

    # 3) Свод: сумма Приход по ПрочиеРасходы (по подразделению) → должна совпадать с Дт-стороной ПАП
    print("\n=== Свод сравнения: что должно совпадать (по Подразделение) ===")
    print(f"  {'Подразделение':<25} {'ПР_Сумма_Приход':>15} {'ПР_СуммаУпр_П':>15} {'ПР_СуммаРегл_П':>15} {'ПАП_ΣДт':>13} {'ПАП_ΣКт':>13} {'Δ':>10}")
    podr_pr_appr = {}
    for r in rows_pr:
        if "Приход" in r["ВидДвижения"]:
            p = r["Подразделение"]
            d = podr_pr_appr.setdefault(p, {"Сумма": 0, "СуммаУпр": 0, "СуммаРегл": 0})
            d["Сумма"]    += r["Сумма"]
            d["СуммаУпр"] += r["СуммаУпр"]
            d["СуммаРегл"]+= r["СуммаРегл"]
    podr_pap = {}
    for r in rows_pap:
        p = r["Подразделение"]
        d = podr_pap.setdefault(p, {"ΣДт": 0, "ΣКт": 0})
        d["ΣДт"] += r["ΣДт"]
        d["ΣКт"] += r["ΣКт"]
    all_podr = sorted(set(list(podr_pr_appr.keys()) + list(podr_pap.keys())))
    summary = []
    tot_pr_s, tot_pr_u, tot_pr_r, tot_dt, tot_kt = 0,0,0,0,0
    for p in all_podr:
        pr = podr_pr_appr.get(p, {"Сумма":0,"СуммаУпр":0,"СуммаРегл":0})
        pap = podr_pap.get(p, {"ΣДт":0,"ΣКт":0})
        delta = pap["ΣДт"] - pap["ΣКт"]
        summary.append({
            "Подразделение": p,
            "ПР_Сумма_Приход":  money(pr["Сумма"]),
            "ПР_СуммаУпр_П":    money(pr["СуммаУпр"]),
            "ПР_СуммаРегл_П":   money(pr["СуммаРегл"]),
            "ПАП_ΣДт":          money(pap["ΣДт"]),
            "ПАП_ΣКт":          money(pap["ΣКт"]),
            "Δ_Дт_минус_Кт":    money(delta),
        })
        print(f"  {p:<25} {money(pr['Сумма']):>15} {money(pr['СуммаУпр']):>15} {money(pr['СуммаРегл']):>15} "
              f"{money(pap['ΣДт']):>13} {money(pap['ΣКт']):>13} {money(delta):>10}")
        tot_pr_s += pr["Сумма"]; tot_pr_u += pr["СуммаУпр"]; tot_pr_r += pr["СуммаРегл"]
        tot_dt += pap["ΣДт"]; tot_kt += pap["ΣКт"]
    print(f"  {'ИТОГО':<25} {money(tot_pr_s):>15} {money(tot_pr_u):>15} {money(tot_pr_r):>15} "
          f"{money(tot_dt):>13} {money(tot_kt):>13} {money(tot_dt-tot_kt):>10}")

    save_csv("02_prochie_rashody",   rows_pr,
             ["Подразделение","ВидДвижения","СтатьяРасходов","ТипРасходов","ВарРаспРегл",
              "Аналитика","Сумма","СуммаУпр","СуммаРегл"])
    save_csv("02_pap_by_podr_statya", rows_pap, ["Подразделение","Статья","ΣДт","ΣКт"])
    save_csv("02_summary_compare",    summary,
             ["Подразделение","ПР_Сумма_Приход","ПР_СуммаУпр_П","ПР_СуммаРегл_П",
              "ПАП_ΣДт","ПАП_ΣКт","Δ_Дт_минус_Кт"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
