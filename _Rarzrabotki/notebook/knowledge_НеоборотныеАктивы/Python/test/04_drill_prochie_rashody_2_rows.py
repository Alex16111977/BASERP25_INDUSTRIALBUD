# -*- coding: utf-8 -*-
"""
04_drill_prochie_rashody_2_rows.py — детальный drill РН.ПрочиеРасходы
по документу АмортизацияОС 000Ц-000003: смотрим ПОСТРОЧНО каждое движение
со всеми колонками (Сумма / СуммаБезНДС / СуммаУпр / СуммаУпрБезНДС /
СуммаРегл / СуммаРеглБезНДС / НДСРегл) + СтатьяРасходов + НалоговоеНазначение.

Гипотеза (нового цикла расследования):
  По одному и тому же ОС создаются ДВЕ строки Приход:
    - одна с заполненной СуммаРегл (бух/нал учёт)
    - другая со заполненной СуммаУпр (управ учёт)
  Штатная Обработка.ДвиженияАктивовПассывы суммирует обе → задвоение в ПАП Дт Расходы.

Выгрузка: _artifacts/04_prochie_rashody_all_cols.csv
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import connect_erp, save_csv, fail, money

DOC_UUID = "2d9182ad-3062-11f1-a2e7-eb06fbf9b98b"


def main():
    erp = connect_erp()
    uid = erp.NewObject("УникальныйИдентификатор", DOC_UUID)
    doc_ref = erp.Документы.АмортизацияОС.ПолучитьСсылку(uid)
    print(f"Документ: {erp.String(doc_ref)}\n")

    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Р", doc_ref)
    q.Текст = """
    ВЫБРАТЬ
        Т.НомерСтроки                           КАК НомерСтроки,
        ПРЕДСТАВЛЕНИЕ(Т.ВидДвижения)            КАК ВидДвижения,
        ПРЕДСТАВЛЕНИЕ(Т.Подразделение)          КАК Подразделение,
        ПРЕДСТАВЛЕНИЕ(Т.СтатьяРасходов)         КАК СтатьяРасходов,
        ПРЕДСТАВЛЕНИЕ(Т.СтатьяРасходов.ТипРасходов) КАК ТипРасходов,
        ПРЕДСТАВЛЕНИЕ(Т.СтатьяРасходов.ВариантРаспределенияРасходовРегл) КАК ВарРаспРегл,
        ПРЕДСТАВЛЕНИЕ(Т.НалоговоеНазначение)    КАК НалоговоеНазначение,
        ПРЕДСТАВЛЕНИЕ(Т.АналитикаРасходов)      КАК Аналитика,
        Т.Сумма           КАК Сумма,
        Т.СуммаБезНДС     КАК СуммаБезНДС,
        Т.СуммаУпр        КАК СуммаУпр,
        Т.СуммаУпрБезНДС  КАК СуммаУпрБезНДС,
        Т.СуммаРегл       КАК СуммаРегл,
        Т.СуммаРеглБезНДС КАК СуммаРеглБезНДС,
        Т.НДСРегл         КАК НДСРегл
    ИЗ РегистрНакопления.ПрочиеРасходы КАК Т
    ГДЕ Т.Регистратор = &Р
    """
    try:
        rez = q.Выполнить().Выгрузить()
    except Exception as e:
        print(f"FAIL: {fail(e)}")
        return 1

    rows = []
    for i in range(rez.Количество()):
        r = rez.Получить(i)
        rows.append({
            "НомерСтроки":   int(r.НомерСтроки) if r.НомерСтроки else 0,
            "ВидДвижения":   str(r.ВидДвижения),
            "Подразделение": str(r.Подразделение),
            "СтатьяРасходов":str(r.СтатьяРасходов),
            "ТипРасходов":   str(r.ТипРасходов),
            "ВарРаспРегл":   str(r.ВарРаспРегл),
            "НалНазначение": str(r.НалоговоеНазначение),
            "Аналитика":     str(r.Аналитика),
            "Сумма":         float(r.Сумма or 0),
            "СуммаБезНДС":   float(r.СуммаБезНДС or 0),
            "СуммаУпр":      float(r.СуммаУпр or 0),
            "СуммаУпрБезНДС":float(r.СуммаУпрБезНДС or 0),
            "СуммаРегл":     float(r.СуммаРегл or 0),
            "СуммаРеглБезНДС":float(r.СуммаРеглБезНДС or 0),
            "НДСРегл":       float(r.НДСРегл or 0),
        })

    rows.sort(key=lambda r: (r["Подразделение"], r["Аналитика"][:60], r["ВидДвижения"], r["НомерСтроки"]))

    print(f"=== РН.ПрочиеРасходы (всего строк: {len(rows)}) ===\n")
    cur_obj = None
    for r in rows:
        obj_key = (r["Подразделение"], r["Аналитика"][:60])
        if obj_key != cur_obj:
            print(f"\n--- {r['Подразделение']} | {r['Аналитика'][:60]} ---")
            cur_obj = obj_key
        # Определяем источник строки по заполненности
        marker = ""
        if r["СуммаУпр"] > 0 and abs(r["СуммаРегл"]) < 0.01:
            marker = " ← УПР учёт"
        elif r["СуммаРегл"] > 0 and abs(r["СуммаУпр"]) < 0.01:
            marker = " ← РЕГЛ учёт"
        elif r["СуммаУпр"] > 0 and r["СуммаРегл"] > 0:
            marker = " ← БОБА (Регл+Упр)"
        print(f"  #{r['НомерСтроки']:>3} {r['ВидДвижения']:<7} {r['СтатьяРасходов']:<25} "
              f"С={money(r['Сумма']):>13} БезНДС={money(r['СуммаБезНДС']):>13} "
              f"Упр={money(r['СуммаУпр']):>13} УпрБезНДС={money(r['СуммаУпрБезНДС']):>13} "
              f"Регл={money(r['СуммаРегл']):>13} НДС={money(r['НДСРегл']):>9}{marker}")

    # Анализ задвоения
    print("\n\n=== АНАЛИЗ ЗАДВОЕНИЯ по объектам (только Приход + Амортизация) ===")
    print(f"  {'Объект':<55} {'Σ Сумма':>13} {'Σ СуммаУпр':>13} {'Σ СуммаРегл':>13} {'Σ всех ст.':>13} {'РазныеИст?':>10}")
    obj_agg = {}
    for r in rows:
        if "Приход" not in r["ВидДвижения"]:
            continue
        if "мортиз" not in r["СтатьяРасходов"].lower():
            continue
        key = (r["Подразделение"], r["Аналитика"][:60])
        d = obj_agg.setdefault(key, {"С": 0, "СУпр": 0, "СРегл": 0, "Строк": 0, "ИстИзРегл": 0, "ИстИзУпр": 0})
        d["С"]    += r["Сумма"]
        d["СУпр"] += r["СуммаУпр"]
        d["СРегл"]+= r["СуммаРегл"]
        d["Строк"]+= 1
        if r["СуммаРегл"] > 0 and abs(r["СуммаУпр"]) < 0.01:
            d["ИстИзРегл"] += 1
        if r["СуммаУпр"] > 0 and abs(r["СуммаРегл"]) < 0.01:
            d["ИстИзУпр"] += 1

    summary = []
    for (podr, anal), d in sorted(obj_agg.items()):
        zadvoenie = "ДА" if (d["ИстИзРегл"] > 0 and d["ИстИзУпр"] > 0) else ""
        print(f"  {(podr+' / '+anal[:50])[:55]:<55} {money(d['С']):>13} {money(d['СУпр']):>13} {money(d['СРегл']):>13} {d['Строк']:>13} {zadvoenie:>10}")
        summary.append({
            "Подразделение": podr,
            "Объект":         anal,
            "СтрокПрихАмортиз": d["Строк"],
            "СтрокРеглТолько":  d["ИстИзРегл"],
            "СтрокУпрТолько":   d["ИстИзУпр"],
            "Σ_Сумма":   d["С"],
            "Σ_СуммаУпр":d["СУпр"],
            "Σ_СуммаРегл":d["СРегл"],
            "Задвоение": zadvoenie,
        })

    print("\n=== ИТОГИ ===")
    n_dup = sum(1 for s in summary if s["Задвоение"] == "ДА")
    print(f"  Всего объектов: {len(summary)}")
    print(f"  Объектов с задвоением: {n_dup}")
    print(f"  Σ_Сумма (что попадает в Дт Расходы) = {money(sum(s['Σ_Сумма'] for s in summary))}")
    print(f"  Σ_СуммаУпр                          = {money(sum(s['Σ_СуммаУпр'] for s in summary))}")
    print(f"  Σ_СуммаРегл                         = {money(sum(s['Σ_СуммаРегл'] for s in summary))}")
    print(f"  Δ_Σ_СуммаУпр_минус_Σ_СуммаРегл      = {money(sum(s['Σ_СуммаУпр'] for s in summary) - sum(s['Σ_СуммаРегл'] for s in summary))}")

    save_csv("04_prochie_rashody_all_cols", rows,
             ["НомерСтроки","ВидДвижения","Подразделение","СтатьяРасходов","ТипРасходов",
              "ВарРаспРегл","НалНазначение","Аналитика",
              "Сумма","СуммаБезНДС","СуммаУпр","СуммаУпрБезНДС","СуммаРегл","СуммаРеглБезНДС","НДСРегл"])
    save_csv("04_zadvoenie_summary", summary,
             ["Подразделение","Объект","СтрокПрихАмортиз","СтрокРеглТолько","СтрокУпрТолько",
              "Σ_Сумма","Σ_СуммаУпр","Σ_СуммаРегл","Задвоение"])
    print(f"\n→ _artifacts/04_prochie_rashody_all_cols.csv ({len(rows)} строк)")
    print(f"→ _artifacts/04_zadvoenie_summary.csv ({len(summary)} объектов)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
