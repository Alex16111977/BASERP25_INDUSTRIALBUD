# -*- coding: utf-8 -*-
"""
07_full_nds_picture_000C_000003.py — полная картина по всем 12 ОС из АмортизацияОС 000Ц-000003.

Для каждого ОС из РН.ПАП.Кт по этому регистратору:
  - Поступление = Σ Дт «Основные средства» в РН.ПАП с Аналитика=ОС за весь период до 31.03.2026
  - АмортизацияКт = Σ Кт «Основные средства» в РН.ПАП с Аналитика=ОС за этот регистратор (000Ц-000003)
  - АмортизацияКт_За_Период = Σ Кт за весь период до 31.03.2026
  - Остаток_До = Поступление − АмортизацияКт_За_Период_До_Этого_Документа
  - Остаток_После = Поступление − АмортизацияКт_За_Период_включая
  - НДС_доля (20% от Кт-суммы)
  - Есть_УПР_строка (есть ли в РН.ПрочиеРасходы по этому документу строка СуммаРегл=0 для этого ОС)

Цель: показать что для всех 12 ОС есть либо задвоение (Дт > Кт), либо недоамортизация
      (остаток после амортизации > 0).
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import connect_erp, save_csv, fail, money

DOC_UUID = "2d9182ad-3062-11f1-a2e7-eb06fbf9b98b"


def main():
    erp = connect_erp()
    uid = erp.NewObject("УникальныйИдентификатор", DOC_UUID)
    doc_ref = erp.Документы.АмортизацияОС.ПолучитьСсылку(uid)
    print(f"Документ: {erp.String(doc_ref)}\n")

    # 1. Достать все ОС из РН.ПАП.Расход (Кт «Основные средства») по этому документу
    q1 = erp.NewObject("Запрос")
    q1.УстановитьПараметр("Р", doc_ref)
    q1.Текст = """
    ВЫБРАТЬ
        Т.Аналитика КАК ОС,
        ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подразделение,
        ПРЕДСТАВЛЕНИЕ(Т.Аналитика) КАК ОСИмя,
        СУММА(Т.Сумма) КАК АмортКт_Документа
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор = &Р
        И Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
        И Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОсновныеСредства)
    СГРУППИРОВАТЬ ПО Т.Аналитика, Т.Подразделение
    """
    try:
        rez = q1.Выполнить().Выгрузить()
    except Exception as e:
        print(f"FAIL: {fail(e)}")
        return 1

    print(f"{'='*180}")
    print(f"{'Подразделение':<20} {'ОС':<55} "
          f"{'Поступление':>12} {'Аморт.Кт':>12} {'Дт.вэтомДок':>12} {'Δ_Контр.Баланса':>16} "
          f"{'Остаток_После':>13} {'УПР?':>5} {'НДС%':>6}")
    print(f"{'='*180}")

    rows = []
    for i in range(rez.Количество()):
        r = rez.Получить(i)
        os_ref = r.ОС
        os_name = str(r.ОСИмя)
        podr = str(r.Подразделение)
        amort_kt_doc = float(r.АмортКт_Документа or 0)

        # Запрос: поступление и Дт-сумма по этому документу
        q2 = erp.NewObject("Запрос")
        q2.УстановитьПараметр("ОС", os_ref)
        q2.УстановитьПараметр("Р", doc_ref)
        q2.Текст = """
        ВЫБРАТЬ
            СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                       И Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОсновныеСредства)
                       ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Поступление_Дт,
            СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                       И Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОсновныеСредства)
                       ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Аморт_Кт_Всего
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
        ГДЕ Т.Аналитика = &ОС
            И Т.Период <= ДАТАВРЕМЯ(2026,3,31,23,59,59)
        """
        rez2 = q2.Выполнить().Выгрузить()
        if rez2.Количество() == 0:
            continue
        r2 = rez2.Получить(0)
        post = float(r2.Поступление_Дт or 0)
        amort_kt_total = float(r2.Аморт_Кт_Всего or 0)
        ostatok_after = post - amort_kt_total

        # Запрос: есть ли УПР строка для этого ОС в РН.ПрочиеРасходы по этому регистратору
        # И сколько Дт записано штатной обработкой (Расходы текущего периода)
        q3 = erp.NewObject("Запрос")
        q3.УстановитьПараметр("ОС", os_ref)
        q3.УстановитьПараметр("Р", doc_ref)
        q3.Текст = """
        ВЫБРАТЬ
            СУММА(ПР.Сумма) КАК Σ_Сумма,
            СУММА(ПР.СуммаРегл) КАК Σ_СуммаРегл,
            СУММА(ПР.СуммаУпр) КАК Σ_СуммаУпр,
            КОЛИЧЕСТВО(*) КАК ЧислоСтрок,
            СУММА(ВЫБОР КОГДА ПР.СуммаРегл = 0 И ПР.СуммаУпр > 0 ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ЧислоУПРСтрок
        ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
        ГДЕ ПР.Регистратор = &Р
            И ПР.АналитикаРасходов = &ОС
            И ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        """
        rez3 = q3.Выполнить().Выгрузить()
        if rez3.Количество() == 0:
            continue
        r3 = rez3.Получить(0)
        sum_sum = float(r3.Σ_Сумма or 0)  # это и есть Дт «Расходы текущего периода» (штатная обработка)
        n_upr = int(r3.ЧислоУПРСтрок or 0)
        has_upr = "✓" if n_upr > 0 else ""

        dt_kontr = sum_sum - amort_kt_doc  # Δ Контроль баланса в этом документе
        nds_proc = (ostatok_after / amort_kt_total * 100) if amort_kt_total > 0 else 0

        print(f"{podr[:20]:<20} {os_name[:55]:<55} "
              f"{money(post):>12} {money(amort_kt_total):>12} {money(sum_sum):>12} {money(dt_kontr):>16} "
              f"{money(ostatok_after):>13} {has_upr:>5} {nds_proc:>5.1f}%")
        rows.append({
            "Подразделение": podr,
            "ОС": os_name,
            "Поступление_Дт": post,
            "АмортизацияКт_Всего": amort_kt_total,
            "Дт_ВЭтомДок": sum_sum,
            "Δ_КонтрБаланса": dt_kontr,
            "Остаток_После": ostatok_after,
            "ЕстьУПРстрока": "Да" if n_upr > 0 else "Нет",
            "НДС_проц_от_Кт": round(nds_proc, 1),
        })

    print(f"\n=== ИТОГИ ===")
    print(f"  Σ Поступление = {money(sum(r['Поступление_Дт'] for r in rows))}")
    print(f"  Σ Амортизация_Кт = {money(sum(r['АмортизацияКт_Всего'] for r in rows))}")
    print(f"  Σ Дт_документа = {money(sum(r['Дт_ВЭтомДок'] for r in rows))}")
    print(f"  Σ Δ_Контроль_Баланса = {money(sum(r['Δ_КонтрБаланса'] for r in rows))}")
    print(f"  Σ Остаток_После (НДС, недоамортизация) = {money(sum(r['Остаток_После'] for r in rows))}")
    print(f"  Объектов с УПР строкой: {sum(1 for r in rows if r['ЕстьУПРстрока']=='Да')} (создают Δ_Контроль_Баланса)")
    print(f"  Объектов БЕЗ УПР строки: {sum(1 for r in rows if r['ЕстьУПРстрока']=='Нет')} (остаток НДС висит)")

    save_csv("07_full_nds_picture", rows,
             ["Подразделение","ОС","Поступление_Дт","АмортизацияКт_Всего","Дт_ВЭтомДок",
              "Δ_КонтрБаланса","Остаток_После","ЕстьУПРстрока","НДС_проц_от_Кт"])
    print(f"\n→ _artifacts/07_full_nds_picture.csv ({len(rows)} строк)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
