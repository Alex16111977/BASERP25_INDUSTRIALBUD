import win32com.client, pythoncom
pythoncom.CoInitialize()

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ARTIFACTS = os.path.join(os.path.dirname(__file__), "_artifacts")
os.makedirs(ARTIFACTS, exist_ok=True)

print("=" * 130)
print("СКРИПТ apr26_rsps_match — РСППС vs ПАП, апрель 2026, 9 подразделений")
print("=" * 130)

# Организация
q0 = erp.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Орг ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
sel = q0.Выполнить().Выбрать(); sel.Следующий()
ORG = sel.Орг
