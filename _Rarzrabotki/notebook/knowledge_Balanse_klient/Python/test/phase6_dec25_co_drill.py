# -*- coding: utf-8 -*-
"""
Phase 6 — Drill-down декабря 2025: подразделение ЦО (0Ц-000007), пара ±36 408,04.
Найти конкретные первичные документы которые дают расхождение ПАП vs РСКПС.

Сводный нетто = 0 (Задол.клиентов +36408 / Получ.авансы -36408),
поэтому пользователь не видит расхождения в свёртке статей.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, get_type_name

erp = connect_erp()
refs = get_refs(erp)
ORG = refs["Орг"]
S = erp.String

ЦО = erp.Справочники.СтруктураПредприятия.НайтиПоКоду("0Ц-000007")
print(f"ЦО ref: {S(ЦО)}")

print("=" * 110)
print("Phase 6 — Drill-down декабря 2025 ЦО: ПАП vs РСКПС по статьям ЗадКл/ПолучАв")
print("=" * 110)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("Подр", ЦО)
q.УстановитьПараметр("НП", refs["НашеПредприятие"])
q.Текст = """
// === ПАП за декабрь по ЦО / клиентские статьи ===
ВЫБРАТЬ
    Т.Регистратор КАК Док,
    Т.Статья КАК Статья,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК ПАП_Sign
ПОМЕСТИТЬ втПАП
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
    И Т.Организация = &Орг
    И Т.Подразделение = &Подр
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
    И Т.Статья В (
        ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьКлиентов),
        ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ПолученныеАвансы))
СГРУППИРОВАТЬ ПО Т.Регистратор, Т.Статья
;
// === РСКПС за декабрь, ОР.Подразделение = ЦО ===
ВЫБРАТЬ
    Р.ДокументРегистратор КАК Док,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ДолгУпр ИНАЧЕ -Р.ДолгУпр КОНЕЦ) КАК РСК_Долг,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ПредоплатаУпр ИНАЧЕ -Р.ПредоплатаУпр КОНЕЦ) КАК РСК_Аванс
ПОМЕСТИТЬ втРСК
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Р.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
    И АП.Организация = &Орг
    И АП.Партнер <> &НП
    И ВЫБОР КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
            ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
            ИНАЧЕ Р.ОбъектРасчетов.Подразделение
      КОНЕЦ = &Подр
СГРУППИРОВАТЬ ПО Р.ДокументРегистратор
;
// === Объединить документы ===
ВЫБРАТЬ РАЗЛИЧНЫЕ ПАП.Док КАК Док ПОМЕСТИТЬ втКл ИЗ втПАП КАК ПАП
ОБЪЕДИНИТЬ ВЫБРАТЬ РСК.Док ИЗ втРСК КАК РСК
;
// === Итог ===
ВЫБРАТЬ
    К.Док КАК ДокРеф,
    ПРЕДСТАВЛЕНИЕ(К.Док) КАК Документ,
    СУММА(ВЫБОР КОГДА ПАП.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьКлиентов)
                ТОГДА ЕСТЬNULL(ПАП.ПАП_Sign, 0) ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ЗадКл,
    СУММА(ВЫБОР КОГДА ПАП.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ПолученныеАвансы)
                ТОГДА ЕСТЬNULL(ПАП.ПАП_Sign, 0) ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ПолучАв,
    МАКСИМУМ(ЕСТЬNULL(РСК.РСК_Долг, 0)) КАК РСК_Долг,
    МАКСИМУМ(ЕСТЬNULL(РСК.РСК_Аванс, 0)) КАК РСК_Аванс
ИЗ втКл КАК К
    ЛЕВОЕ СОЕДИНЕНИЕ втПАП КАК ПАП ПО К.Док = ПАП.Док
    ЛЕВОЕ СОЕДИНЕНИЕ втРСК КАК РСК ПО К.Док = РСК.Док
СГРУППИРОВАТЬ ПО К.Док, ПРЕДСТАВЛЕНИЕ(К.Док)
"""

r = q.Выполнить().Выгрузить()
print(f"\nДокументов задействовано: {r.Количество()}\n")

# Найти документы где |ПАП_ЗадКл - РСК_Долг| > 0.01 ИЛИ |ПАП_ПолучАв + РСК_Аванс| > 0.01
print(f"{'Документ':<60}{'ПАП_ЗадКл':>14}{'РСК_Долг':>14}{'Δ_Долг':>14}{'ПАП_ПолучАв':>14}{'РСК_Аванс':>14}{'Δ_Аванс':>14}")
print("-" * 144)
кандидаты = []
total_d_dolg = 0.0
total_d_avans = 0.0
for i in range(r.Количество()):
    rec = r.Получить(i)
    p_zk = float(rec.ПАП_ЗадКл or 0)
    p_pa = float(rec.ПАП_ПолучАв or 0)
    rk_d = float(rec.РСК_Долг or 0)
    rk_a = float(rec.РСК_Аванс or 0)
    d_dolg = p_zk - rk_d
    d_avans = p_pa - (-rk_a)  # знак инверсии (РСК_Аванс положительный = +ПолучАв в ПАП с инверсией = -ПолучАв)
    total_d_dolg += d_dolg
    total_d_avans += d_avans
    if abs(d_dolg) > 0.01 or abs(d_avans) > 0.01:
        кандидаты.append({
            "док": str(rec.Документ),
            "тип": get_type_name(erp, rec.ДокРеф),
            "p_zk": p_zk, "rk_d": rk_d, "d_dolg": d_dolg,
            "p_pa": p_pa, "rk_a": rk_a, "d_avans": d_avans,
        })

# Сортировка по |Δ|
кандидаты.sort(key=lambda x: -max(abs(x["d_dolg"]), abs(x["d_avans"])))
for x in кандидаты[:30]:
    print(f"{x['док'][:58]:<60}{money(x['p_zk']):>14}{money(x['rk_d']):>14}{money(x['d_dolg']):>14}"
          f"{money(x['p_pa']):>14}{money(x['rk_a']):>14}{money(x['d_avans']):>14}")

print("-" * 144)
print(f"Всего кандидатов с |Δ|>0.01: {len(кандидаты)}")
print(f"Σ Δ_Долг по кандидатам: {money(total_d_dolg)}")
print(f"Σ Δ_Аванс по кандидатам: {money(total_d_avans)}")

# Группировка по типу документа
типы = {}
for x in кандидаты:
    типы.setdefault(x["тип"], {"cnt": 0, "d_dolg": 0, "d_avans": 0})
    типы[x["тип"]]["cnt"] += 1
    типы[x["тип"]]["d_dolg"] += x["d_dolg"]
    типы[x["тип"]]["d_avans"] += x["d_avans"]
print("\nГруппировка по ТипДок:")
for тип, v in sorted(типы.items(), key=lambda x: -abs(x[1]["d_dolg"] + x[1]["d_avans"])):
    print(f"  {тип:<45} {v['cnt']:>4}  Δ_Долг={money(v['d_dolg']):>14}  Δ_Аванс={money(v['d_avans']):>14}")
