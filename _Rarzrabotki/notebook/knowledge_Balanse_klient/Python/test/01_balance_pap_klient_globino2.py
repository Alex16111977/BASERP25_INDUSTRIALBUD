# -*- coding: utf-8 -*-
"""
СКРИПТ 01 — Остатки ПАП по статье "Задолженность клиентов" / Глобино-2

ЧТО ИЩЕТ:
    Начальные (НМ), приход, расход и конечные (КМ) остатки регистра
    ПрочиеАктивыПассивы для статьи "Задолженность клиентов",
    Источник = РасчетыСКлиентамиПоСрокам, Организация = ТОВ ІНДАСТРІАЛБУД,
    Подразделение В ИЕРАРХИИ (Глобино-2) за 2 периода: ноя+дек 2025.

ПОЧЕМУ ОСНОВНАЯ ТАБЛИЦА (а не .ОстаткиИОбороты):
    Поле `Источник` — реквизит, недоступен в условии виртуальной таблицы.
    Канон Свод_СебестоимостьТоваров использует ОСНОВНУЮ таблицу с signed
    через ВЫБОР Приход +Сумма ИНАЧЕ -Сумма (см. knowledge_Balanse §2).

КАК СЧИТАЕТ:
    signed = ВЫБОР ВидДвижения=Приход +Сумма ИНАЧЕ -Сумма
    НМ = Σ signed по [Период < НачМес]
    КМ = Σ signed по [Период <= КонМес]
    Приход = Σ |Сумма| по [Период МЕЖДУ НачМес И КонМес И ВидДвижения=Приход]
    Расход = Σ |Сумма| по [Период МЕЖДУ НачМес И КонМес И ВидДвижения=Расход]

    Даты — встроенно через ДАТАВРЕМЯ() в текст запроса (memory tz-shift).

ЧТО ДАЁТ:
    print: таблица 2 периода × {НМ, Приход, Расход, КМ}.
    artifact: _artifacts/01_pap_balances.json

SELF-CHECK:
    КМ_ноя = НМ_дек (один и тот же момент).
    КМ_ноя сравнивается с цифрой со скриншота ВРСК = 43 998 627,87.
"""
from _common import (
    connect_erp,
    get_refs,
    money,
    save_json,
)


QUERY_TEMPLATE = """
ВЫБРАТЬ
    ПАП.Подразделение КАК Подразделение,
    ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК ПодрНаим,
    СУММА(ВЫБОР
            КОГДА ПАП.Период < {НАЧ_МЕС}
                 И ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                 ТОГДА ПАП.Сумма
            КОГДА ПАП.Период < {НАЧ_МЕС}
                 И ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                 ТОГДА -ПАП.Сумма
            ИНАЧЕ 0
         КОНЕЦ) КАК НМ,
    СУММА(ВЫБОР
            КОГДА ПАП.Период МЕЖДУ {НАЧ_МЕС} И {КОН_МЕС}
                 И ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                 ТОГДА ПАП.Сумма
            ИНАЧЕ 0
         КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР
            КОГДА ПАП.Период МЕЖДУ {НАЧ_МЕС} И {КОН_МЕС}
                 И ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                 ТОГДА ПАП.Сумма
            ИНАЧЕ 0
         КОНЕЦ) КАК Расход,
    СУММА(ВЫБОР
            КОГДА ПАП.Период <= {КОН_МЕС}
                 И ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                 ТОГДА ПАП.Сумма
            КОГДА ПАП.Период <= {КОН_МЕС}
                 И ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                 ТОГДА -ПАП.Сумма
            ИНАЧЕ 0
         КОНЕЦ) КАК КМ
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Организация = &Орг
    И ПАП.Подразделение В ИЕРАРХИИ (&Подр)
    И ПАП.Источник = &Источник
    И ПАП.Статья = &Статья
    И ПАП.Период <= {КОН_МЕС}
СГРУППИРОВАТЬ ПО
    ПАП.Подразделение,
    ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение)
"""


def run_period(erp, refs, нач_мес, кон_мес, label):
    """Один период (ноя или дек) — возврат сводки по Подразделению."""
    q = erp.NewObject("Запрос")
    q.Текст = QUERY_TEMPLATE.replace("{НАЧ_МЕС}", нач_мес).replace("{КОН_МЕС}", кон_мес)
    q.УстановитьПараметр("Орг", refs["Орг"])
    q.УстановитьПараметр("Подр", refs["Подр"])
    q.УстановитьПараметр("Источник", refs["Источник"])
    q.УстановитьПараметр("Статья", refs["Статья"])

    res = q.Выполнить().Выгрузить()
    rows = []
    sum_нм = sum_км = sum_приход = sum_расход = 0.0
    for i in range(res.Количество()):
        r = res.Получить(i)
        nm = float(r.НМ or 0)
        km = float(r.КМ or 0)
        prh = float(r.Приход or 0)
        rsh = float(r.Расход or 0)
        rows.append(
            {
                "Подразделение": str(r.ПодрНаим),
                "НМ": nm,
                "Приход": prh,
                "Расход": rsh,
                "КМ": km,
            }
        )
        sum_нм += nm
        sum_км += km
        sum_приход += prh
        sum_расход += rsh

    return {
        "Период": label,
        "НМ": sum_нм,
        "Приход": sum_приход,
        "Расход": sum_расход,
        "КМ": sum_км,
        "СтрокПодразделений": len(rows),
        "ПодробноПоПодразделениям": rows,
    }


def main():
    print("=" * 80)
    print("СКРИПТ 01 — Остатки ПАП «Задолженность клиентов» / Глобино-2 / ТОВ ІНДАСТРІАЛБУД")
    print("=" * 80)

    erp = connect_erp()
    refs = get_refs(erp)

    нов = run_period(
        erp, refs,
        "ДАТАВРЕМЯ(2025,11,1,0,0,0)",
        "ДАТАВРЕМЯ(2025,11,30,23,59,59)",
        "ноябрь_2025",
    )

    дек = run_period(
        erp, refs,
        "ДАТАВРЕМЯ(2025,12,1,0,0,0)",
        "ДАТАВРЕМЯ(2025,12,31,23,59,59)",
        "декабрь_2025",
    )

    print(f"\n{'Период':<15} {'НМ':>18} {'Приход':>18} {'Расход':>18} {'КМ':>18}")
    print("-" * 95)
    for s in (нов, дек):
        print(
            f"{s['Период']:<15} "
            f"{money(s['НМ']):>18} "
            f"{money(s['Приход']):>18} "
            f"{money(s['Расход']):>18} "
            f"{money(s['КМ']):>18}"
        )

    print("\n--- Декабрь по подразделениям ---")
    for r in дек["ПодробноПоПодразделениям"]:
        print(
            f"  {r['Подразделение']:<25} НМ={money(r['НМ']):>18} "
            f"Приход={money(r['Приход']):>14} Расход={money(r['Расход']):>14} "
            f"КМ={money(r['КМ']):>18}"
        )

    контр_30_11 = нов["КМ"]
    контр_01_12 = дек["НМ"]
    контр_31_12 = дек["КМ"]

    print()
    print(f"Контрольная точка КМ ноября (на 30.11.2025): {money(контр_30_11)} UAH")
    print(f"Контрольная точка НМ декабря (на 01.12.2025): {money(контр_01_12)} UAH")
    print(f"Контрольная точка КМ декабря (на 31.12.2025): {money(контр_31_12)} UAH")

    if abs(контр_30_11 - контр_01_12) > 0.01:
        print(f"\n⚠️ ALERT: КМ_ноя ({money(контр_30_11)}) ≠ НМ_дек ({money(контр_01_12)})!")
    else:
        print("\n✓ Self-check: КМ_ноя == НМ_дек (|Δ|=0)")

    ETALON_SCREEN = 43998627.87
    diff_etalon = контр_30_11 - ETALON_SCREEN
    print(
        f"Сверка со скрином ВРСК (НМ_дек = {money(ETALON_SCREEN)}): "
        f"Δ = {money(diff_etalon)} UAH"
    )

    artifact = {
        "ноябрь": нов,
        "декабрь": дек,
        "контр_30_11_2025": контр_30_11,
        "контр_01_12_2025": контр_01_12,
        "контр_31_12_2025": контр_31_12,
        "delta_self_check_KM_noya_eq_NM_dek": контр_30_11 - контр_01_12,
        "delta_vs_screen_etalon_43998627_87": diff_etalon,
    }
    path = save_json("01_pap_balances", artifact)
    print(f"\nАртефакт сохранён: {path}")


if __name__ == "__main__":
    main()
