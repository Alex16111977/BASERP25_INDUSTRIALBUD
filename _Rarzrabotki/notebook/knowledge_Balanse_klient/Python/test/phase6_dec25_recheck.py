# -*- coding: utf-8 -*-
"""
Phase 6 — Re-check декабря 2025: есть ли ВООБЩЕ Расхождение=Истина по РСКПС/РСППС
после завершения ручного перепроведения.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money

erp = connect_erp()
refs = get_refs(erp)
ORG = refs["Орг"]
S = erp.String

print("=" * 100)
print("Phase 6 — Перепроверка декабря 2025 на Расхождение=Истина (живой запрос)")
print("=" * 100)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("РСКПС", erp.Перечисления.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
q.УстановитьПараметр("РСППС", erp.Перечисления.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам)
q.Текст = """
ВЫБРАТЬ
    Т.Source КАК SourceRef,
    Т.Подразделение.Код КАК ПодрКод,
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
    Т.Статья.Код КАК СтатьяКод,
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    Т.Расхождение КАК Расх,
    Т.СуммаПриход КАК СуммаПриход,
    Т.СуммаРасход КАК СуммаРасход,
    Т.СуммаКонечныйОстаток КАК СуммаКМ,
    ПРЕДСТАВЛЕНИЕ(Т.Регистратор) КАК Регистратор,
    Т.Регистратор.Месяц КАК Месяц
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
ГДЕ Т.Организация = &Орг
    И Т.Регистратор.Месяц = ДАТАВРЕМЯ(2025,12,1)
    И Т.Source В (&РСКПС, &РСППС)
    И Т.Расхождение = ИСТИНА
УПОРЯДОЧИТЬ ПО Т.Подразделение.Код, Т.Статья.Код, Т.Source
"""

r = q.Выполнить().Выгрузить()
print(f"\nВсего записей Расхождение=Истина за декабрь 2025 РСКПС/РСППС: {r.Количество()}")

if r.Количество() == 0:
    print("\n[OK] Декабрь 2025 чист — Расхождение=Истина по РСКПС/РСППС ОТСУТСТВУЕТ")
    sys.exit(0)

print(f"\n{'Подр':<12}{'Подразделение':<35}{'Статья':<14}{'Статья назв':<35}{'Source':<35}{'ΣКМ':>20}")
print("-" * 150)
total_abs = 0.0
total_sign = 0.0
for i in range(r.Количество()):
    rec = r.Получить(i)
    src = str(S(rec.SourceRef)) if erp.ЗначениеЗаполнено(rec.SourceRef) else "(пусто)"
    s_km = float(rec.СуммаКМ or 0)
    total_abs += abs(s_km)
    total_sign += s_km
    print(f"{str(rec.ПодрКод or ''):<12}{str(rec.Подр or '')[:33]:<35}"
          f"{str(rec.СтатьяКод or ''):<14}{str(rec.Статья or '')[:33]:<35}"
          f"{src[:33]:<35}{money(s_km):>20}")
print("-" * 150)
print(f"{'ИТОГО':<131}{money(total_abs):>20}  ΣABS")
print(f"{'':<131}{money(total_sign):>20}  ΣSign")
