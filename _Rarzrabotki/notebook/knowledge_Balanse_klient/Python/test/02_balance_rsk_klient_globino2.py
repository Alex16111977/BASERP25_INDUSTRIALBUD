# -*- coding: utf-8 -*-
"""
СКРИПТ 02 — Остатки РСКПС (РасчетыСКлиентамиПоСрокам) / Глобино-2

ЧТО ИЩЕТ:
    НМ/КМ остатки регистра РасчетыСКлиентамиПоСрокам (источник отчёта ВРСК)
    для фильтра: Орг=ТОВ ІНДАСТРІАЛБУД, Партнер<>НашеПредприятие,
    Подразделение(fallback) В ИЕРАРХИИ Глобино-2, за периоды ноя+дек 2025.

ПОЧЕМУ С РАЗДЕЛЕНИЕМ ПО ЗНАКУ:
    Свод_РасчетыСПартнерами в ПАП проектирует РСКПС так:
        ДолгУпр > 0 (нетто долг)     → Статья=ЗадолженностьКлиентов
        ДолгУпр < 0 (нетто предоплата) → Статья=ПолученныеАвансы
    Для сравнения с ПАП(Статья=ЗадолженностьКлиентов) нам нужны
    ТОЛЬКО положительные нетто-остатки партнёров.

КАК СЧИТАЕТ:
    signed = ВЫБОР Приход +ДолгУпр ИНАЧЕ -ДолгУпр   (на основной таблице)
    Группируем по (Партнер, КлючАналитики) → нетто-остаток партнёра.
    Затем в Python:
        ДолгКлиентов = Σ нетто по партнёрам где нетто > 0
        Авансы       = Σ |нетто| по партнёрам где нетто < 0
        Нетто        = Σ всех нетто (контроль)

    Даты — серверно через ДАТАВРЕМЯ() в тексте запроса.

ЧТО ДАЁТ:
    print: 2 периода × {Нетто, ДолгКлиентов, Авансы} + кол-во партнёров.
    artifact: _artifacts/02_rsk_balances.json

SELF-CHECK:
    На 30.11.2025 КМ_ноя_ДолгКлиентов должен быть = 43 998 627,87
    (скриншот ВРСК показывает именно эту цифру).
"""
from _common import (
    connect_erp,
    get_refs,
    money,
    save_json,
)


# Один период (ноя или дек): для каждого партнёра — НМ + Приход + Расход + КМ.
# Группируем по Партнеру (через АналитикаУчетаПоПартнерам) и по
# Подразделению (формула fallback ОбъектРасчетов.Подразделение).
QUERY_TEMPLATE = """
ВЫБРАТЬ
    АП.Партнер КАК Партнер,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК ПартнерНаим,
    ВЫБОР
        КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
             ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
        ИНАЧЕ Р.ОбъектРасчетов.Подразделение
    КОНЕЦ КАК Подразделение,
    ПРЕДСТАВЛЕНИЕ(ВЫБОР
        КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
             ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
        ИНАЧЕ Р.ОбъектРасчетов.Подразделение
    КОНЕЦ) КАК ПодрНаим,
    СУММА(ВЫБОР
            КОГДА Р.Период < {НАЧ_МЕС}
                 И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                 ТОГДА Р.ДолгУпр
            КОГДА Р.Период < {НАЧ_МЕС}
                 И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                 ТОГДА -Р.ДолгУпр
            ИНАЧЕ 0
         КОНЕЦ) КАК НМ,
    СУММА(ВЫБОР
            КОГДА Р.Период МЕЖДУ {НАЧ_МЕС} И {КОН_МЕС}
                 И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                 ТОГДА Р.ДолгУпр
            ИНАЧЕ 0
         КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР
            КОГДА Р.Период МЕЖДУ {НАЧ_МЕС} И {КОН_МЕС}
                 И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                 ТОГДА Р.ДолгУпр
            ИНАЧЕ 0
         КОНЕЦ) КАК Расход,
    СУММА(ВЫБОР
            КОГДА Р.Период <= {КОН_МЕС}
                 И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                 ТОГДА Р.ДолгУпр
            КОГДА Р.Период <= {КОН_МЕС}
                 И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                 ТОГДА -Р.ДолгУпр
            ИНАЧЕ 0
         КОНЕЦ) КАК КМ
ИЗ
    РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
        ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ
    Р.Период <= {КОН_МЕС}
    И АП.Организация = &Орг
    И АП.Партнер <> &НашеПредприятие
    И ВЫБОР
        КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
             ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
        ИНАЧЕ Р.ОбъектРасчетов.Подразделение
      КОНЕЦ В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО
    АП.Партнер,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер),
    ВЫБОР
        КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
             ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
        ИНАЧЕ Р.ОбъектРасчетов.Подразделение
    КОНЕЦ,
    ПРЕДСТАВЛЕНИЕ(ВЫБОР
        КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
             ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
        ИНАЧЕ Р.ОбъектРасчетов.Подразделение
    КОНЕЦ)
"""


def run_period(erp, refs, нач_мес, кон_мес, label):
    q = erp.NewObject("Запрос")
    q.Текст = QUERY_TEMPLATE.replace("{НАЧ_МЕС}", нач_мес).replace("{КОН_МЕС}", кон_мес)
    q.УстановитьПараметр("Орг", refs["Орг"])
    q.УстановитьПараметр("Подр", refs["Подр"])
    q.УстановитьПараметр("НашеПредприятие", refs["НашеПредприятие"])

    res = q.Выполнить().Выгрузить()

    rows = []
    долг_клиентов_НМ = долг_клиентов_КМ = 0.0
    авансы_НМ = авансы_КМ = 0.0
    нетто_НМ = нетто_КМ = 0.0
    sum_приход = sum_расход = 0.0
    cnt_pos = cnt_neg = 0

    for i in range(res.Количество()):
        r = res.Получить(i)
        nm = float(r.НМ or 0)
        km = float(r.КМ or 0)
        prh = float(r.Приход or 0)
        rsh = float(r.Расход or 0)

        rows.append({
            "Партнер": str(r.ПартнерНаим),
            "Подразделение": str(r.ПодрНаим),
            "НМ": nm,
            "Приход": prh,
            "Расход": rsh,
            "КМ": km,
        })

        нетто_НМ += nm
        нетто_КМ += km
        sum_приход += prh
        sum_расход += rsh

        if nm > 0.005:
            долг_клиентов_НМ += nm
        elif nm < -0.005:
            авансы_НМ += -nm

        if km > 0.005:
            долг_клиентов_КМ += km
            cnt_pos += 1
        elif km < -0.005:
            авансы_КМ += -km
            cnt_neg += 1

    return {
        "Период": label,
        "ВсегоПартнеров": len(rows),
        "ПартнеровСДолгом": cnt_pos,
        "ПартнеровСАвансом": cnt_neg,
        "Нетто_НМ": нетто_НМ,
        "Нетто_КМ": нетто_КМ,
        "ДолгКлиентов_НМ": долг_клиентов_НМ,
        "ДолгКлиентов_КМ": долг_клиентов_КМ,
        "Авансы_НМ": авансы_НМ,
        "Авансы_КМ": авансы_КМ,
        "Приход_ДолгУпр": sum_приход,
        "Расход_ДолгУпр": sum_расход,
        "ПодробноПоПартнерам": rows,
    }


def main():
    print("=" * 90)
    print("СКРИПТ 02 — Остатки РСКПС (Долг клиентов) / Глобино-2 / ТОВ ІНДАСТРІАЛБУД")
    print("=" * 90)

    erp = connect_erp()
    refs = get_refs(erp)

    нов = run_period(
        erp, refs,
        "ДАТАВРЕМЯ(2025,11,1,0,0,0)",
        "ДАТАВРЕМЯ(2025,11,30,23,59,59)",
        "ноябрь_2025",
    )

    дек = run_period(
        erp, refs,
        "ДАТАВРЕМЯ(2025,12,1,0,0,0)",
        "ДАТАВРЕМЯ(2025,12,31,23,59,59)",
        "декабрь_2025",
    )

    print(
        f"\n{'Период':<14} {'Партн':>6} {'ДолгКл_НМ':>16} {'ДолгКл_КМ':>16} "
        f"{'Аванс_НМ':>14} {'Аванс_КМ':>14} {'Нетто_КМ':>16}"
    )
    print("-" * 110)
    for s in (нов, дек):
        print(
            f"{s['Период']:<14} "
            f"{s['ВсегоПартнеров']:>6} "
            f"{money(s['ДолгКлиентов_НМ']):>16} "
            f"{money(s['ДолгКлиентов_КМ']):>16} "
            f"{money(s['Авансы_НМ']):>14} "
            f"{money(s['Авансы_КМ']):>14} "
            f"{money(s['Нетто_КМ']):>16}"
        )

    контр_30_11_РСКПС = нов["ДолгКлиентов_КМ"]
    контр_31_12_РСКПС = дек["ДолгКлиентов_КМ"]

    print()
    print(
        f"Контрольная точка 30.11.2025 (ДолгКлиентов_КМ_ноя): "
        f"{money(контр_30_11_РСКПС)} UAH"
    )
    print(
        f"Контрольная точка 31.12.2025 (ДолгКлиентов_КМ_дек): "
        f"{money(контр_31_12_РСКПС)} UAH"
    )

    ETALON_SCREEN = 43998627.87
    diff_etalon = контр_30_11_РСКПС - ETALON_SCREEN
    print(
        f"Сверка со скрином ВРСК (Итого Долг клиента на 30.11.2025): "
        f"Δ = {money(diff_etalon)} UAH"
    )

    print("\n--- Декабрь по партнёрам (топ-10 по |КМ|) ---")
    top = sorted(дек["ПодробноПоПартнерам"], key=lambda r: -abs(r["КМ"]))[:10]
    for r in top:
        print(
            f"  {r['Партнер'][:35]:<35} {r['Подразделение'][:12]:<12} "
            f"НМ={money(r['НМ']):>14} Приход={money(r['Приход']):>12} "
            f"Расход={money(r['Расход']):>12} КМ={money(r['КМ']):>14}"
        )

    artifact = {
        "ноябрь": нов,
        "декабрь": дек,
        "контр_30_11_2025_ДолгКлиентов": контр_30_11_РСКПС,
        "контр_31_12_2025_ДолгКлиентов": контр_31_12_РСКПС,
        "delta_vs_screen_etalon_43998627_87": diff_etalon,
    }
    path = save_json("02_rsk_balances", artifact)
    print(f"\nАртефакт сохранён: {path}")


if __name__ == "__main__":
    main()
