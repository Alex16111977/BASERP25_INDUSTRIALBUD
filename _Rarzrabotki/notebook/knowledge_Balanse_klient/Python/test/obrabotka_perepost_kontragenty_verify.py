# -*- coding: utf-8 -*-
"""
G1 verify для обработки «Перепровести Расчеты по контрагентам с выбором за период».

Доказывает корректность АЛГОРИТМА ПОИСКА документов (read-only, безопасно):
  RED : текущий запрос падает — &масКонтрагент не установлен.
  Д2  : «ПоСрокам».Регистратор = служебный РегистраторРасчётов,
        «ПоСрокам».ДокументРегистратор = первичные документы.
  Доп : нужны ли «ПоСрокам»-ветки (ДокументРегистратор ⊄ операционные.Регистратор?).
  Д1+Д3: исправленный 4-union с фильтром по контрагенту и без (пусто=все) + дедуп.

Период теста: декабрь 2025 (хорошо покрыт в knowledge_Balanse_klient).
НЕ перепроводит документы (COM-репост РСКПС/РСППС запрещён).
"""
import sys
from _common import connect_erp, get_type_name

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

PERIOD = ("ДАТАВРЕМЯ(2025,12,1,0,0,0)", "ДАТАВРЕМЯ(2025,12,31,23,59,59)")
results = []  # (gate, ok, msg)


def gate(name, ok, msg=""):
    results.append((name, ok, msg))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" — {msg}" if msg else ""))


def newq(erp, text):
    q = erp.NewObject("Запрос")
    q.Текст = text
    return q


def main():
    erp = connect_erp()
    print("=" * 70)
    print("G1 verify — Перепровести Расчеты по контрагентам")
    print("=" * 70)

    # --- RED: текущий запрос (масКонтрагент не установлен) должен падать ---
    print("\n[RED] масКонтрагент не установлен → ожидаем исключение")
    q = newq(erp, f"""
    ВЫБРАТЬ Рег.Регистратор КАК Регистратор
    ИЗ РегистрНакопления.РасчетыСКлиентами КАК Рег
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Рег.АналитикаУчетаПоПартнерам = АП.КлючАналитики
    ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
        И АП.Партнер В ИЕРАРХИИ(&масКонтрагент)
    """)
    try:
        q.Выполнить()
        gate("RED: незаполненный масКонтрагент падает", False, "запрос НЕ упал (неожиданно)")
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        msg = (info[2] if info else str(e))[:120]
        gate("RED: незаполненный масКонтрагент падает", True, msg)

    # --- Д2: тип Регистратор (служебный) vs ДокументРегистратор (первичник) ---
    print("\n[Д2] ПоСрокам: .Регистратор vs .ДокументРегистратор")
    for reg in ("РасчетыСКлиентамиПоСрокам", "РасчетыСПоставщикамиПоСрокам"):
        # .Регистратор
        q = newq(erp, f"""ВЫБРАТЬ РАЗЛИЧНЫЕ ПЕРВЫЕ 30 Р.Регистратор КАК Док
        ИЗ РегистрНакопления.{reg} КАК Р
        ГДЕ Р.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}""")
        t = q.Выполнить().Выгрузить()
        types_reg = {}
        for i in range(t.Количество()):
            tn = get_type_name(erp, t.Получить(i).Док) or "<пусто>"
            types_reg[tn] = types_reg.get(tn, 0) + 1
        # .ДокументРегистратор
        q = newq(erp, f"""ВЫБРАТЬ РАЗЛИЧНЫЕ ПЕРВЫЕ 30 Р.ДокументРегистратор КАК Док
        ИЗ РегистрНакопления.{reg} КАК Р
        ГДЕ Р.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}""")
        t2 = q.Выполнить().Выгрузить()
        types_dok = {}
        empty_dok = 0
        for i in range(t2.Количество()):
            d = t2.Получить(i).Док
            if not erp.ЗначениеЗаполнено(d):
                empty_dok += 1
                continue
            tn = get_type_name(erp, d) or "<пусто>"
            types_dok[tn] = types_dok.get(tn, 0) + 1
        print(f"   {reg}.Регистратор типы: {types_reg}")
        print(f"   {reg}.ДокументРегистратор типы: {types_dok} (пустых={empty_dok})")
        reg_is_service = set(types_reg.keys()) <= {"РегистраторРасчетов", "<пусто>"}
        dok_is_primary = "РегистраторРасчетов" not in types_dok and len(types_dok) > 0
        gate(f"Д2 {reg}: .Регистратор=служебный", reg_is_service, str(list(types_reg)))
        gate(f"Д2 {reg}: .ДокументРегистратор=первичники", dok_is_primary, str(list(types_dok)))

    # --- Доп: нужны ли ПоСрокам-ветки (есть ли документы только в них?) ---
    print("\n[Доп] ДокументРегистратор(ПоСрокам) ⊄ Регистратор(операционные)?")

    def uuids(text):
        t = newq(erp, text).Выполнить().Выгрузить()
        s = set()
        for i in range(t.Количество()):
            d = t.Получить(i).Док
            if erp.ЗначениеЗаполнено(d):
                s.add(str(erp.String(d.УникальныйИдентификатор())))
        return s

    op = uuids(f"""ВЫБРАТЬ РАЗЛИЧНЫЕ Рег.Регистратор КАК Док
        ИЗ РегистрНакопления.РасчетыСКлиентами КАК Рег
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
        ОБЪЕДИНИТЬ
        ВЫБРАТЬ РАЗЛИЧНЫЕ Рег.Регистратор
        ИЗ РегистрНакопления.РасчетыСПоставщиками КАК Рег
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}""")
    posrokam = uuids(f"""ВЫБРАТЬ РАЗЛИЧНЫЕ Рег.ДокументРегистратор КАК Док
        ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Рег
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
        ОБЪЕДИНИТЬ
        ВЫБРАТЬ РАЗЛИЧНЫЕ Рег.ДокументРегистратор
        ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Рег
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}""")
    only_posrokam = posrokam - op
    print(f"   операционные(уник.)={len(op)}, ПоСрокам.ДокРег(уник.)={len(posrokam)}, "
          f"только в ПоСрокам={len(only_posrokam)}")
    gate("Доп: ПоСрокам-ветки нужны?", True,
         f"только в ПоСрокам={len(only_posrokam)} (>0 ⇒ ветки нужны)")

    # --- Д1+Д3: исправленный 4-union, фильтр + дедуп ---
    print("\n[Д1+Д3] исправленный запрос: фильтр по контрагенту / пусто=все / дедуп")
    FIXED = f"""
    ВЫБРАТЬ ВложЗ.Регистратор КАК Регистратор, МИНИМУМ(ВложЗ.Дата) КАК Дата
    ИЗ (
        ВЫБРАТЬ Рег.Регистратор КАК Регистратор, МИНИМУМ(Рег.Регистратор.Дата) КАК Дата
        ИЗ РегистрНакопления.РасчетыСКлиентами КАК Рег
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Рег.АналитикаУчетаПоПартнерам = АП.КлючАналитики
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
            И (НЕ &Фильтр ИЛИ АП.Партнер В ИЕРАРХИИ(&масКонтрагент))
        СГРУППИРОВАТЬ ПО Рег.Регистратор
        ОБЪЕДИНИТЬ ВСЕ
        ВЫБРАТЬ Рег.Регистратор, МИНИМУМ(Рег.Регистратор.Дата)
        ИЗ РегистрНакопления.РасчетыСПоставщиками КАК Рег
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Рег.АналитикаУчетаПоПартнерам = АП.КлючАналитики
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
            И (НЕ &Фильтр ИЛИ АП.Партнер В ИЕРАРХИИ(&масКонтрагент))
        СГРУППИРОВАТЬ ПО Рег.Регистратор
        ОБЪЕДИНИТЬ ВСЕ
        ВЫБРАТЬ Рег.ДокументРегистратор, МИНИМУМ(Рег.ДокументРегистратор.Дата)
        ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Рег
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Рег.АналитикаУчетаПоПартнерам = АП.КлючАналитики
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
            И (НЕ &Фильтр ИЛИ АП.Партнер В ИЕРАРХИИ(&масКонтрагент))
        СГРУППИРОВАТЬ ПО Рег.ДокументРегистратор
        ОБЪЕДИНИТЬ ВСЕ
        ВЫБРАТЬ Рег.ДокументРегистратор, МИНИМУМ(Рег.ДокументРегистратор.Дата)
        ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Рег
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Рег.АналитикаУчетаПоПартнерам = АП.КлючАналитики
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]}
            И (НЕ &Фильтр ИЛИ АП.Партнер В ИЕРАРХИИ(&масКонтрагент))
        СГРУППИРОВАТЬ ПО Рег.ДокументРегистратор
    ) КАК ВложЗ
    СГРУППИРОВАТЬ ПО ВложЗ.Регистратор
    УПОРЯДОЧИТЬ ПО Дата
    """
    empty_arr = erp.NewObject("Массив")

    # пусто=все
    q = newq(erp, FIXED)
    q.УстановитьПараметр("Фильтр", False)
    q.УстановитьПараметр("масКонтрагент", empty_arr)
    t_all = q.Выполнить().Выгрузить()
    n_all = t_all.Количество()
    gate("Д3 пусто=все: запрос отработал", n_all > 0, f"всего документов={n_all}")

    # дедуп
    seen = set()
    for i in range(n_all):
        seen.add(str(erp.String(t_all.Получить(i).Регистратор.УникальныйИдентификатор())))
    gate("Дедуп: нет повторов Регистратора", len(seen) == n_all, f"уник={len(seen)} строк={n_all}")

    # фильтр по 1 контрагенту (берём контрагента с движениями в периоде)
    q = newq(erp, f"""ВЫБРАТЬ ПЕРВЫЕ 1 АП.Партнер КАК К, КОЛИЧЕСТВО(*) КАК Н
        ИЗ РегистрНакопления.РасчетыСКлиентами КАК Рег
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Рег.АналитикаУчетаПоПартнерам = АП.КлючАналитики
        ГДЕ Рег.Период МЕЖДУ {PERIOD[0]} И {PERIOD[1]} И АП.Партнер <> ЗНАЧЕНИЕ(Справочник.Партнеры.ПустаяСсылка)
        СГРУППИРОВАТЬ ПО АП.Партнер
        УПОРЯДОЧИТЬ ПО Н УБЫВ""")
    sel = q.Выполнить().Выбрать()
    if sel.Следующий():
        contr = sel.К
        arr = erp.NewObject("Массив")
        arr.Добавить(contr)
        q = newq(erp, FIXED)
        q.УстановитьПараметр("Фильтр", True)
        q.УстановитьПараметр("масКонтрагент", arr)
        t_f = q.Выполнить().Выгрузить()
        n_f = t_f.Количество()
        print(f"   партнёр='{erp.String(contr)}' → документов={n_f} (из {n_all})")
        gate("Д1 фильтр: вернул документы и ≤ всего", 0 < n_f <= n_all, f"{n_f}<={n_all}")
    else:
        gate("Д1 фильтр: найден тестовый партнёр", False, "нет партнёров с движениями")

    # --- Итог ---
    print("\n" + "=" * 70)
    npass = sum(1 for _, ok, _ in results if ok)
    print(f"ИТОГ G1: {npass}/{len(results)} PASS")
    for name, ok, _ in results:
        if not ok:
            print(f"   FAIL → {name}")
    print("=" * 70)


if __name__ == "__main__":
    main()
