for target_nm, target_val in TARGET_DELTAS.items():
    # Найти точное совпадение по имени
    pap_v = 0; rsps_v = 0
    for k in pap_bal:
        if target_nm.lower() in k.lower() or k.lower() in target_nm.lower():
            pap_v = pap_bal[k]; break
    for k in rsps_bal:
        if target_nm.lower() in k.lower() or k.lower() in target_nm.lower():
            rsps_v = rsps_bal[k][0]; break  # ДолгОстаток

    # В ПАП расходный знак = МИНУС задолженность (PAP_Net < 0 = есть долг)
    # РСППС ДолгОстаток > 0 = есть долг
    # Расхождение = PAP_Net - (-РСППС_Долг) = PAP_Net + РСППС_Долг
    delta = pap_v + rsps_v
    match = "✓" if abs(delta - target_val) < 1.0 else ""
    print(f"  {target_nm:<45}  {pap_v:>+16,.2f}  {rsps_v:>+16,.2f}  {delta:>+16,.2f}  {target_val:>+16,.2f}  {match:>8}")

print()
