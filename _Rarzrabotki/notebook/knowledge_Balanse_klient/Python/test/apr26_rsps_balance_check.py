IST = erp.Перечисления.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам

print("=" * 120)
print("ШАГ A — РСППС.Остатки на 30.04.2026 по подразделениям (ОР.Подр)")
