# -*- coding: utf-8 -*-
"""
Phase 6 fix — Step 3: Корректировка строки в Авансах ЮЕйДрім.

Старое: Сумма=СуммаУпр=СуммаРегл=36570 (содержит избыточный долг 36408,04 + аванс 161,96)
Новое:  Сумма=СуммаУпр=СуммаРегл=161,96 (только настоящий аванс)

Долг 36 408,04 уже корректно отражён в документе Долгов 0Ц-00000082 (строка #1).

После корректировки:
1) Перепровести Авансы
2) Перепровести А_ФинРез_Баланс декабря
3) Проверить что плуг исчез (РС А_ОтчётБаланс_Свод по ЦО за декабрь 2025)
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money, get_refs

erp = connect_erp()
refs = get_refs(erp)
ORG = refs["Орг"]
S = erp.String

ОЖИДАЕМАЯ_СТАРАЯ = 36570.0
НОВАЯ_СУММА = 161.96

q = erp.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ Ссылка ИЗ Документ.ВводОстатков ГДЕ Номер = "0Ц-00000083" """
sel = q.Выполнить().Выбрать(); sel.Следующий()
refAv = sel.Ссылка

q.Текст = """ВЫБРАТЬ Ссылка ИЗ Документ.ВводОстатков ГДЕ Номер = "0Ц-00000082" """
sel = q.Выполнить().Выбрать(); sel.Следующий()
refDol = sel.Ссылка

objAv = refAv.ПолучитьОбъект()
print(f"Документ Авансов: {S(refAv)}")

# Найти строку ЮЕйДрім
tc = objAv.РасчетыСПартнерами
target_row = None
target_idx = None
for i in range(tc.Количество()):
    row = tc.Получить(i)
    try:
        p = str(S(row.Партнер) or "")
    except: p = ""
    if "ЮЕйДрім" in p:
        target_row = row
        target_idx = i
        break

if target_row is None:
    print("[FAIL] Строка не найдена"); sys.exit(1)

print(f"\nДо изменения (строка #{target_idx+1}):")
print(f"  Сумма:      {target_row.Сумма}")
print(f"  СуммаУпр:   {target_row.СуммаУпр}")
print(f"  СуммаРегл:  {target_row.СуммаРегл}")

if abs(float(target_row.Сумма) - ОЖИДАЕМАЯ_СТАРАЯ) > 0.01:
    print(f"[STOP] Сумма не равна ожидаемой {ОЖИДАЕМАЯ_СТАРАЯ} — возможно фикс уже применён или данные изменились")
    sys.exit(2)

# Изменить
target_row.Сумма = НОВАЯ_СУММА
target_row.СуммаУпр = НОВАЯ_СУММА
target_row.СуммаРегл = НОВАЯ_СУММА

print(f"\nПосле изменения:")
print(f"  Сумма:      {target_row.Сумма}")
print(f"  СуммаУпр:   {target_row.СуммаУпр}")
print(f"  СуммаРегл:  {target_row.СуммаРегл}")

# Запись
print("\n[1] Запись с проведением...")
try:
    objAv.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("    [OK] Авансы перепроведены")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print(f"    [FAIL] {info[2] if info else e}")
    sys.exit(3)

# Verify РСКПС по партнёру
print("\n[2] Verify РСКПС по ЮЕйДрім")
q.УстановитьПараметр("Док1", refAv)
q.УстановитьПараметр("Док2", refDol)
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ДокументРегистратор) КАК Док,
    Р.ВидДвижения КАК ВидДв,
    Р.ДолгУпр КАК Долг,
    Р.ПредоплатаУпр КАК Аванс
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Р.ДокументРегистратор В (&Док1, &Док2)
    И АП.Партнер.Наименование ПОДОБНО "%ЮЕйДрім%"
УПОРЯДОЧИТЬ ПО Р.Период
"""
r = q.Выполнить().Выгрузить()
print(f"  Движений: {r.Количество()}")
for i in range(r.Количество()):
    rec = r.Получить(i)
    print(f"    {str(rec.Док)[:55]:<57}  {S(rec.ВидДв):<8}  Долг={float(rec.Долг or 0):>+12,.2f}  Аванс={float(rec.Аванс or 0):>+12,.2f}")

# Остатки
print("\n[3] Остатки РСКПС за партнёра")
import datetime
for d_str, d_obj in [("31.10.2025", datetime.datetime(2025,10,31,23,59,59)),
                     ("31.12.2025", datetime.datetime(2025,12,31,23,59,59))]:
    q.УстановитьПараметр("Дата", d_obj)
    q.Текст = """
ВЫБРАТЬ
    СУММА(Р.ДолгУпрОстаток) КАК Долг,
    СУММА(Р.ПредоплатаУпрОстаток) КАК Аванс
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(&Дата,) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Партнер.Наименование ПОДОБНО "%ЮЕйДрім%"
"""
    q.УстановитьПараметр("Дата", d_obj)
    rr = q.Выполнить().Выгрузить()
    if rr.Количество() > 0:
        rec = rr.Получить(0)
        print(f"  {d_str}:  Долг={float(rec.Долг or 0):>+12,.2f}  Аванс={float(rec.Аванс or 0):>+12,.2f}")

# Перепровести А_ФинРез_Баланс декабря
print("\n[4] Перепроведение А_ФинРез_Баланс декабря 2025")
q.УстановитьПараметр("Орг", ORG)
q.Текст = """
ВЫБРАТЬ Д.Ссылка ИЗ Документ.А_ФинРез_Баланс КАК Д
ГДЕ Д.Организация = &Орг И Д.Месяц = ДАТАВРЕМЯ(2025,12,1)
    И Д.Проведен И НЕ Д.ПометкаУдаления
"""
r = q.Выполнить().Выгрузить()
if r.Количество() == 0:
    print("  [!] А_ФинРез_Баланс декабря не найден")
else:
    fr = r.Получить(0).Ссылка
    print(f"  Найден: {S(fr)}")
    try:
        fr.ПолучитьОбъект().Записать(erp.РежимЗаписиДокумента.Проведение)
        print("  [OK] перепроведён")
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        print(f"  [FAIL] {info[2] if info else e}")
        sys.exit(4)

# Проверить плуг
print("\n[5] Проверка плуга Расхождение=Истина по ЦО за декабрь 2025")
q.УстановитьПараметр("Орг", ORG)
q.Текст = """
ВЫБРАТЬ
    Т.Подразделение.Код КАК ПодрКод,
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
    Т.Статья.Код КАК СтатьяКод,
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    Т.СуммаКонечныйОстаток КАК СуммаКМ
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
ГДЕ Т.Организация = &Орг
    И Т.Регистратор.Месяц = ДАТАВРЕМЯ(2025,12,1)
    И Т.Source В (ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
                  ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
    И Т.Расхождение = ИСТИНА
УПОРЯДОЧИТЬ ПО Т.Подразделение.Код, Т.Статья.Код
"""
r = q.Выполнить().Выгрузить()
print(f"  Записей Расхождение=Истина по РСКПС/РСППС за декабрь 2025: {r.Количество()}")
for i in range(r.Количество()):
    rec = r.Получить(i)
    print(f"    {str(rec.ПодрКод):<12} {str(rec.Подр)[:25]:<27}  {str(rec.СтатьяКод):<14} {str(rec.Статья)[:30]:<32}  ΣКМ={float(rec.СуммаКМ):>+15,.2f}")

if r.Количество() == 0:
    print("\n[OK] ✅ ПЛУГ УСТРАНЁН")
elif r.Количество() <= 2:
    print("\n[partial] Плуг изменился — посмотреть осталось ли по ЦО")
