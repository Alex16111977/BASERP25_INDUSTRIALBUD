    podrs = {r['Подразделение'] for r in rows}
    if len(podrs) > 1:
        cross_docs.append((dok_name, rows))
    # Также включим если один поддр имеет только ПАП, другой только РСППС
    pap_podrs = {r['Подразделение'] for r in rows if abs(r['ПАП']) > 0.01 and abs(r['РСППС']) < 0.01}
