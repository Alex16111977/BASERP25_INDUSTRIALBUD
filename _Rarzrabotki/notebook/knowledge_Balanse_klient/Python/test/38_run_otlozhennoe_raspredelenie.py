try:
    erp.ОперативныеВзаиморасчетыСервер.ВыполнитьОтложенноеРаспределение()
    print("OK — процедура выполнилась без ошибок")
except Exception as e:
    msg = str(e)[:300]
    if hasattr(e, "excepinfo") and e.excepinfo and e.excepinfo[2]:
        msg = str(e.excepinfo[2])[:300]
    print(f"ОШИБКА: {msg}")

# === 3. Проверка результата ===
count_movements("ПОСЛЕ")

