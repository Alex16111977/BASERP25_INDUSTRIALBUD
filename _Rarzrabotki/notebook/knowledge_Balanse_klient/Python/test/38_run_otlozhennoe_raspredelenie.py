import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
from datetime import datetime, timedelta

pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")

print("=" * 110)
print("СКРИПТ 38 — ВыполнитьОтложенноеРаспределение в BASERP25 + verify ІБ00-007576")
print("=" * 110)

erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# === 0. Найдём документ ІБ00-007576 для verify ===
dt = datetime(2025, 12, 19, 18, 11, 56)
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Ном", "ІБ00-007576")
q.УстановитьПараметр("Н1", dt - timedelta(days=1))
q.УстановитьПараметр("Н2", dt + timedelta(days=1))
q.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.ПриобретениеТоваровУслуг
            ГДЕ Номер = &Ном И Дата МЕЖДУ &Н1 И &Н2"""
ref = q.Выполнить().Выгрузить().Получить(0).Ссылка
print(f"Документ: {S(ref)}")

def count_movements(label):
    q.УстановитьПараметр("Д", ref)
    q.Текст = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.ПрочиеАктивыПассивы ГДЕ Регистратор=&Д"""
    pap = int(q.Выполнить().Выгрузить().Получить(0).К or 0)
    q.Текст = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам ГДЕ ДокументРегистратор=&Д"""
    rsp = int(q.Выполнить().Выгрузить().Получить(0).К or 0)
    q.Текст = """ВЫБРАТЬ РАЗЛИЧНЫЕ Т.Регистратор, ПРЕДСТАВЛЕНИЕ(Т.Регистратор) КАК Имя
                ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Т
                ГДЕ Т.ДокументРегистратор=&Д"""
    regs = q.Выполнить().Выгрузить()
    reg_imya = ""
    if regs.Количество() > 0:
        reg_imya = str(regs.Получить(0).Имя)
    print(f"  [{label}] ПАП={pap}, РСППС={rsp}, Регистратор: {reg_imya or '(нет)'}")

count_movements("ДО")

# === 1. Проверка количества заданий ===
q.Текст = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.ЗаданияКРаспределениюРасчетов"""
zad_count = int(q.Выполнить().Выгрузить().Получить(0).К or 0)
print(f"\nЗаданий в РС.ЗаданияКРаспределениюРасчетов: {zad_count}")

# Если заданий нет — пробуем сгенерировать через перепроведение документа
if zad_count == 0:
    print("Заданий нет. Делаем дополнительное перепроведение для генерации заданий...")
    obj = ref.ПолучитьОбъект()
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)

    q.Текст = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.ЗаданияКРаспределениюРасчетов"""
    zad_count = int(q.Выполнить().Выгрузить().Получить(0).К or 0)
    print(f"После перепроведения заданий: {zad_count}")

# === 2. Запуск отложенного распределения ===
