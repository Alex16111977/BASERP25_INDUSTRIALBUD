# -*- coding: utf-8 -*-
"""
СКРИПТ 14 — Поиск записей Расхождение=Истина в А_ОтчетБаланс_Свод

Период: 01.12.2025 — 31.12.2026 (13 месяцев)
Организация: ТОВ ІНДАСТРІАЛБУД (ЕДРПОУ 40645273)
Регистр: РегистрСведений.А_ОтчетБаланс_Свод (независимый РС)
Регистратор: Документ.А_ФинРез_Баланс (есть реквизит Месяц)

ПАТТЕРН (из _Rarzrabotki/Python/test/test_finansist_rascheti_vs_pap.py):
- Сериализация ссылок/перечислений через erp.String(ref) — НЕ str()
- ПРЕДСТАВЛЕНИЕ в SQL только на ссылочных полях основной таблицы, не подзапроса

Цель: понять масштаб расхождений после правки DvAktPas (FIX-2026-05-23)
и собрать список (Подр × Статья × Source × Месяц).

Артефакты:
  _artifacts/14_raskhozhdenie_summary.csv      — сводка по месяцу × источнику
  _artifacts/14_raskhozhdenie_records.csv      — детально по подразделению/статье/источнику/месяцу
  _artifacts/14_raskhozhdenie_recorders.csv    — уникальные ДокументДвижения с расхождением
"""
import sys, io, os, csv
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, save_csv, ARTIFACTS_DIR

erp = connect_erp()
refs = get_refs(erp)
ORG = refs["Орг"]
S = erp.String  # сериализатор: ссылку/перечисление/число → строка-синоним

print("=" * 110)
print("СКРИПТ 14 — Расхождение=Истина в А_ОтчетБаланс_Свод (период 01.12.2025–31.12.2026)")
print("=" * 110)

# ---------------------------------------------------------------------------
# 1. Сводка по (Месяц × Source)
# ---------------------------------------------------------------------------
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.Текст = """
ВЫБРАТЬ
    Т.Регистратор.Месяц КАК Месяц,
    Т.Source КАК SourceRef,
    КОЛИЧЕСТВО(*) КАК КолвоЗаписей,
    СУММА(ВЫБОР КОГДА Т.СуммаКонечныйОстаток > 0
            ТОГДА Т.СуммаКонечныйОстаток ИНАЧЕ -Т.СуммаКонечныйОстаток КОНЕЦ) КАК СуммаABS,
    СУММА(Т.СуммаКонечныйОстаток) КАК СуммаSign,
    СУММА(Т.СуммаПриход) КАК СуммаПриход,
    СУММА(Т.СуммаРасход) КАК СуммаРасход
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
ГДЕ Т.Расхождение = ИСТИНА
    И Т.Организация = &Орг
    И Т.Регистратор.Месяц МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2026,12,31,23,59,59)
СГРУППИРОВАТЬ ПО Т.Регистратор.Месяц, Т.Source
УПОРЯДОЧИТЬ ПО Месяц, SourceRef
"""
r = q.Выполнить().Выгрузить()
print(f"\n--- Сводка по (Месяц × Source), записей={r.Количество()} ---")
print(f"{'Месяц':<12}{'Источник':<45}{'Кол-во':>8}{'ΣABS':>20}{'ΣSign':>20}")
print("-" * 105)
summary_rows = []
total_abs = 0.0
for i in range(r.Количество()):
    rec = r.Получить(i)
    mes = str(rec.Месяц)[:10] if rec.Месяц else ""
    src = S(rec.SourceRef) if erp.ЗначениеЗаполнено(rec.SourceRef) else "(пусто)"
    src = str(src) if src else "(пусто)"
    kol = int(rec.КолвоЗаписей or 0)
    abs_ = float(rec.СуммаABS or 0)
    sgn = float(rec.СуммаSign or 0)
    total_abs += abs_
    print(f"{mes:<12}{src[:43]:<45}{kol:>8}{money(abs_):>20}{money(sgn):>20}")
    summary_rows.append({
        "Месяц": mes,
        "Источник": src,
        "КолвоЗаписей": kol,
        "СуммаABS": abs_,
        "СуммаSign": sgn,
        "СуммаПриход": float(rec.СуммаПриход or 0),
        "СуммаРасход": float(rec.СуммаРасход or 0),
    })
print(f"\nИТОГО ΣABS по всем месяцам и источникам: {money(total_abs)}")
save_csv("14_raskhozhdenie_summary", summary_rows,
         ["Месяц", "Источник", "КолвоЗаписей", "СуммаABS", "СуммаSign",
          "СуммаПриход", "СуммаРасход"])

# ---------------------------------------------------------------------------
# 2. Детально по (Подр × Статья × Source × Месяц)
# ---------------------------------------------------------------------------
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.Текст = """
ВЫБРАТЬ
    Т.Регистратор.Месяц КАК Месяц,
    Т.Подразделение КАК ПодразделениеRef,
    Т.Подразделение.Код КАК ПодразделениеКод,
    Т.Статья КАК СтатьяRef,
    Т.Статья.Код КАК СтатьяКод,
    Т.Source КАК SourceRef,
    КОЛИЧЕСТВО(*) КАК КолвоЗаписей,
    СУММА(Т.СуммаКонечныйОстаток) КАК СуммаKM,
    СУММА(Т.СуммаПриход) КАК СуммаПриход,
    СУММА(Т.СуммаРасход) КАК СуммаРасход
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
ГДЕ Т.Расхождение = ИСТИНА
    И Т.Организация = &Орг
    И Т.Регистратор.Месяц МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2026,12,31,23,59,59)
СГРУППИРОВАТЬ ПО
    Т.Регистратор.Месяц,
    Т.Подразделение, Т.Подразделение.Код,
    Т.Статья, Т.Статья.Код,
    Т.Source
УПОРЯДОЧИТЬ ПО Месяц, ПодразделениеКод, СтатьяКод, SourceRef
"""
r = q.Выполнить().Выгрузить()
print(f"\n--- Детально (Подр × Статья × Source × Месяц): {r.Количество()} группировок ---")
detail_rows = []
for i in range(r.Количество()):
    rec = r.Получить(i)
    podr_name = S(rec.ПодразделениеRef) if erp.ЗначениеЗаполнено(rec.ПодразделениеRef) else ""
    statya_name = S(rec.СтатьяRef) if erp.ЗначениеЗаполнено(rec.СтатьяRef) else ""
    src_name = S(rec.SourceRef) if erp.ЗначениеЗаполнено(rec.SourceRef) else ""
    detail_rows.append({
        "Месяц": str(rec.Месяц)[:10] if rec.Месяц else "",
        "ПодразделениеКод": str(rec.ПодразделениеКод or ""),
        "Подразделение": str(podr_name or ""),
        "СтатьяКод": str(rec.СтатьяКод or ""),
        "Статья": str(statya_name or ""),
        "Source": str(src_name or ""),
        "КолвоЗаписей": int(rec.КолвоЗаписей or 0),
        "СуммаKM": float(rec.СуммаKM or 0),
        "СуммаПриход": float(rec.СуммаПриход or 0),
        "СуммаРасход": float(rec.СуммаРасход or 0),
    })
save_csv("14_raskhozhdenie_records", detail_rows,
         ["Месяц", "ПодразделениеКод", "Подразделение", "СтатьяКод", "Статья",
          "Source", "КолвоЗаписей", "СуммаKM", "СуммаПриход", "СуммаРасход"])

# Топ-30 по |СуммаKM|
print(f"\n--- ТОП-30 группировок по |СуммаKM| ---")
top30 = sorted(detail_rows, key=lambda x: -abs(x["СуммаKM"]))[:30]
print(f"{'Месяц':<12}{'ПодрКод':<12}{'СтатьяКод':<14}{'Источник':<35}{'СуммаKM':>20}")
print("-" * 95)
for row in top30:
    print(f"{row['Месяц']:<12}{row['ПодразделениеКод']:<12}{row['СтатьяКод']:<14}"
          f"{(row['Source'] or '(пусто)')[:33]:<35}{money(row['СуммаKM']):>20}")

# ---------------------------------------------------------------------------
# 3. Уникальные ДокументДвижения для РСКПС / РСППС
# ---------------------------------------------------------------------------
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("РСКПС", erp.Перечисления.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
q.УстановитьПараметр("РСППС", erp.Перечисления.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам)
q.Текст = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    Т.ДокументДвижения КАК ДокументДвижения,
    ПРЕДСТАВЛЕНИЕ(Т.ДокументДвижения) КАК ДокИмя,
    Т.Source КАК SourceRef,
    Т.Регистратор.Месяц КАК Месяц
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
ГДЕ Т.Расхождение = ИСТИНА
    И Т.Организация = &Орг
    И Т.Регистратор.Месяц МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2026,12,31,23,59,59)
    И Т.Source В (&РСКПС, &РСППС)
"""
r = q.Выполнить().Выгрузить()
print(f"\n--- Уникальные ДокументДвижения (РСКПС/РСППС): {r.Количество()} ---")
recorders_rows = []
type_counts = {}
for i in range(r.Количество()):
    rec = r.Получить(i)
    dok_ref = rec.ДокументДвижения
    dok_type = ""
    try:
        if dok_ref is not None and erp.ЗначениеЗаполнено(dok_ref):
            dok_type = str(dok_ref.Метаданные().Имя)
    except Exception:
        dok_type = ""
    type_counts[dok_type] = type_counts.get(dok_type, 0) + 1
    src_name = S(rec.SourceRef) if erp.ЗначениеЗаполнено(rec.SourceRef) else ""
    recorders_rows.append({
        "Месяц": str(rec.Месяц)[:10] if rec.Месяц else "",
        "Source": str(src_name or ""),
        "ТипДок": dok_type,
        "ДокИмя": str(rec.ДокИмя or ""),
    })
print("\nГруппировка по типу документа:")
for t, c in sorted(type_counts.items(), key=lambda x: -x[1]):
    print(f"  {t or '(пусто)':<55} {c}")
save_csv("14_raskhozhdenie_recorders", recorders_rows,
         ["Месяц", "Source", "ТипДок", "ДокИмя"])

print(f"\nАртефакты в {ARTIFACTS_DIR}")
print("  14_raskhozhdenie_summary.csv")
print("  14_raskhozhdenie_records.csv")
print("  14_raskhozhdenie_recorders.csv")
