# -*- coding: utf-8 -*-
"""
СКРИПТ 15v3 — ПРАВИЛЬНЫЙ фильтр: только документы с ХозОп=ПереносАванса

ПАТТЕРН: расширение скрипта 21 на период 01.12.2025—31.12.2026.

ПРИНЦИП (из FINDINGS.md раздел 7):
  Правка DvAktPas снимает фильтр <>ПереносАванса в 4 проекциях. Значит затронуты
  ТОЛЬКО документы которые писали в РСКПС/РСППС строки с ХозОп=ПереносАванса.
  Для остальных документов правка эффекта не даёт — перепроведение бессмысленно.

ВИНОВНИКИ В ДЕКАБРЕ 2025:
  СписаниеБезналичныхДС 000Ц-000286 (5 194 594,73) + 000Ц-000287 (2 000 000,00)
  ХозОп = ВозвратОплатыКлиенту, партнёр = самопартнёр Глобино-2

Артефакты:
  _artifacts/15v3_perenosavansa_rows.csv      — все строки с ПереносАванса
  _artifacts/15v3_docs_to_repost.csv          — уникальные документы к перепроведению
"""
import sys, io, os, csv
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, save_csv, ARTIFACTS_DIR

erp = connect_erp()
refs = get_refs(erp)
ORG = refs["Орг"]
S = erp.String

print("=" * 110)
print("СКРИПТ 15v3 — Документы с ХозОп=ПереносАванса (период 01.12.2025–31.12.2026)")
print("=" * 110)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.Текст = """
ВЫБРАТЬ
    "РСК" КАК Регистр,
    Т.ДокументРегистратор КАК Док,
    ПРЕДСТАВЛЕНИЕ(Т.ДокументРегистратор) КАК ДокИмя,
    Т.ХозяйственнаяОперация КАК ХозОпРеф,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.ДолгУпр ИНАЧЕ -Т.ДолгУпр КОНЕЦ) КАК Σ_ДолгУпр,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.ПредоплатаУпр ИНАЧЕ -Т.ПредоплатаУпр КОНЕЦ) КАК Σ_Аванс
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Т
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Т.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Т.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2026,12,31,23,59,59)
    И АП.Организация = &Орг
    И Т.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПереносАванса)
СГРУППИРОВАТЬ ПО Т.ДокументРегистратор, ПРЕДСТАВЛЕНИЕ(Т.ДокументРегистратор), Т.ХозяйственнаяОперация

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
    "РСП",
    Т.ДокументРегистратор,
    ПРЕДСТАВЛЕНИЕ(Т.ДокументРегистратор),
    Т.ХозяйственнаяОперация,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.ДолгУпр ИНАЧЕ -Т.ДолгУпр КОНЕЦ),
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.ПредоплатаУпр ИНАЧЕ -Т.ПредоплатаУпр КОНЕЦ)
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Т
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Т.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Т.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2026,12,31,23,59,59)
    И АП.Организация = &Орг
    И Т.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПереносАванса)
СГРУППИРОВАТЬ ПО Т.ДокументРегистратор, ПРЕДСТАВЛЕНИЕ(Т.ДокументРегистратор), Т.ХозяйственнаяОперация
"""
res = q.Выполнить().Выгрузить()
print(f"Строк РСКПС/РСППС с ПереносАванса: {res.Количество()}")

rows = []
unique_docs = set()
type_counts = {}
sum_d = sum_a = 0.0
count_rsk = count_rsp = 0

for i in range(res.Количество()):
    r = res.Получить(i)
    reg = str(r.Регистр)
    d = float(r.Σ_ДолгУпр or 0); a = float(r.Σ_Аванс or 0)
    sum_d += d; sum_a += a
    if reg == "РСК": count_rsk += 1
    else: count_rsp += 1

    dok_ref = r.Док
    dok_type = ""
    try:
        if dok_ref is not None and erp.ЗначениеЗаполнено(dok_ref):
            dok_type = str(dok_ref.Метаданные().Имя)
    except Exception:
        dok_type = ""
    type_counts[dok_type] = type_counts.get(dok_type, 0) + 1
    unique_docs.add((dok_type, str(r.ДокИмя)))

    rows.append({
        "Регистр": reg,
        "ТипДок": dok_type,
        "Документ": str(r.ДокИмя),
        "Σ_ДолгУпр": d,
        "Σ_Аванс": a,
        "Σ_Δ_отрезано": d - a,
    })

print(f"  РСК: {count_rsk}, РСП: {count_rsp}")
print(f"  Σ Долг = {money(sum_d)}, Σ Аванс = {money(sum_a)}")
print(f"  Σ (Долг - Аванс) = что было отрезано фильтром = {money(sum_d - sum_a)}")

print(f"\nУникальных первичных документов: {len(unique_docs)}")
print("По типам документа:")
for t, c in sorted(type_counts.items(), key=lambda x: -x[1]):
    print(f"  {t or '(пусто)':<55} {c}")

# Топ-20 по |Σ_Δ_отрезано|
print(f"\nТоп-20 по |Σ (Долг - Аванс)|:")
print(f"{'Рег':<4} {'ТипДок':<35} {'Документ':<60} {'Σ_Δ':>16}")
print("-" * 120)
for r in sorted(rows, key=lambda x: -abs(x["Σ_Δ_отрезано"]))[:20]:
    print(f"{r['Регистр']:<4} {r['ТипДок'][:33]:<35} {r['Документ'][:60]:<60} {money(r['Σ_Δ_отрезано']):>16}")

save_csv("15v3_perenosavansa_rows", rows,
         ["Регистр", "ТипДок", "Документ", "Σ_ДолгУпр", "Σ_Аванс", "Σ_Δ_отрезано"])

unique_rows = [{"ТипДок": t, "ДокИмя": n} for t, n in sorted(unique_docs)]
save_csv("15v3_docs_to_repost", unique_rows, ["ТипДок", "ДокИмя"])

print(f"\nАртефакты в {ARTIFACTS_DIR}")
print("  15v3_perenosavansa_rows.csv     — все строки с ПереносАванса")
print("  15v3_docs_to_repost.csv         — уникальные документы к перепроведению")
