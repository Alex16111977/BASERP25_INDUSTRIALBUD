"""
Phase 6 fix — Rollback: вернуть строку ЮЕйДрім в Авансах к Сумма=36570
после того как фикс изменил сальдо партнёра.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money

erp = connect_erp()
S = erp.String

q = erp.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ Ссылка ИЗ Документ.ВводОстатков ГДЕ Номер = "0Ц-00000083" """
sel = q.Выполнить().Выбрать(); sel.Следующий()
refAv = sel.Ссылка
objAv = refAv.ПолучитьОбъект()

# Найти строку ЮЕйДрім
for i in range(objAv.РасчетыСПартнерами.Количество()):
    row = objAv.РасчетыСПартнерами.Получить(i)
    try:
        p = str(S(row.Партнер) or "")
    except: p = ""
    if "ЮЕйДрім" in p:
        print(f"До отката: строка #{i+1} Сумма={row.Сумма}, СуммаУпр={row.СуммаУпр}, СуммаРегл={row.СуммаРегл}")
        row.Сумма = 36570
        row.СуммаУпр = 36570
        row.СуммаРегл = 36570
        print(f"После отката: Сумма=36570")
        break

try:
    objAv.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("[OK] Авансы перепроведены с откатом")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print(f"[FAIL] {info[2] if info else e}")
    sys.exit(1)

