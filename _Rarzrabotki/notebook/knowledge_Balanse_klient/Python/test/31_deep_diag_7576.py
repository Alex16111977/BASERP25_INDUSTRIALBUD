import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
from datetime import datetime, timedelta
from _common import connect_erp, money

erp = connect_erp()
S = erp.String

dt = datetime(2025, 12, 19, 18, 11, 56)
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Ном", "ІБ00-007576")
q.УстановитьПараметр("Н1", dt - timedelta(days=1))
q.УстановитьПараметр("Н2", dt + timedelta(days=1))
q.Текст = """ВЫБРАТЬ Ссылка ИЗ Документ.ПриобретениеТоваровУслуг
            ГДЕ Номер = &Ном И Дата МЕЖДУ &Н1 И &Н2"""
ref = q.Выполнить().Выгрузить().Получить(0).Ссылка
print(f"Ссылка: {S(ref)}")
obj = ref.ПолучитьОбъект()

# === 1. Все ТЧ ===
print(f"\n--- Содержимое документа ---")
print(f"  ХозОперация: {S(obj.ХозяйственнаяОперация)}")
print(f"  Партнер: {S(obj.Партнер)}")
print(f"  Подразделение: {S(obj.Подразделение)}")
print(f"  ОбъектРасчетовУпр: {S(obj.ОбъектРасчетовУпр)}")
print(f"  Договор: {S(obj.Договор)}")
print(f"  Соглашение: {S(obj.Соглашение)}")
print(f"  ПорядокРасчетов: {S(obj.ПорядокРасчетов)}")
print(f"  ГруппаФинУчета: {S(obj.ГруппаФинансовогоУчета)}")
print(f"  СуммаДок: {money(obj.СуммаДокумента)}")
print(f"  СуммаВзаиморасчетов: {money(obj.СуммаВзаиморасчетов)}")
print(f"  Курс: {obj.Курс}, Кратность: {obj.Кратность}")
print(f"  А_Обработан: {bool(obj.А_Обработан)}")
print(f"  А_ВведенВЕРП: {bool(obj.А_ВведенВЕРП)}")

print(f"\n  ТЧ Товары: {obj.Товары.Количество()} строк")
for i in range(min(3, obj.Товары.Количество())):
    т = obj.Товары.Получить(i)
    print(f"    [{i+1}] {S(т.Номенклатура)[:35]:<35} Кол={т.Количество} Сум={money(т.Сумма)} ОбъектРасч={S(т.ОбъектРасчетов)} СтРасх={S(т.СтатьяРасходов)}")

print(f"\n  ТЧ РасшифровкаПлатежа: {obj.РасшифровкаПлатежа.Количество()} строк")
for i in range(obj.РасшифровкаПлатежа.Количество()):
    т = obj.РасшифровкаПлатежа.Получить(i)
    print(f"    [{i+1}] Сум={money(т.Сумма)} СВ={money(т.СуммаВзаиморасчетов)} Вал={S(т.ВалютаВзаиморасчетов)} ОбъектРасч={S(т.ОбъектРасчетов)}")

print(f"\n  ТЧ ЭтапыГрафикаОплаты: {obj.ЭтапыГрафикаОплаты.Количество()} строк")
for i in range(obj.ЭтапыГрафикаОплаты.Количество()):
    т = obj.ЭтапыГрафикаОплаты.Получить(i)
    print(f"    [{i+1}] СумПлат={money(т.СуммаПлатежа)} СВ={money(т.СуммаВзаиморасчетов)} ОбъектРасч={S(т.ОбъектРасчетов)}")

# === 2. Список всех движений по типам регистров ===
print(f"\n--- ВСЕ движения документа (по всем регистрам) ---")
def count(reg, field="Регистратор"):
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Д", ref)
    qq.Текст = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ {reg} ГДЕ {field} = &Д"
    try:
        r = qq.Выполнить().Выбрать(); r.Следующий(); return int(r.К or 0)
    except Exception:
        return -1

for reg in [
    "РегистрНакопления.ПрочиеАктивыПассивы",
    "РегистрНакопления.РасчетыСПоставщикамиПоСрокам",
    "РегистрНакопления.РасчетыСПоставщиками",
    "РегистрНакопления.ТоварыНаСкладах",
    "РегистрНакопления.ТоварыОрганизаций",
    "РегистрНакопления.СебестоимостьТоваров",
    "РегистрНакопления.ВыручкаИСебестоимостьПродаж",
    "РегистрНакопления.ДенежныеСредстваБезналичные",
]:
    n = count(reg, "Регистратор")
    print(f"  {reg:<55} Регистратор: {n}")

