# -*- coding: utf-8 -*-
"""
СКРИПТ 11 — Правильная сверка ПАП vs РСКПС по реквизиту ДокументРегистратор

ОТКРЫТИЕ: в РСКПС поле `Регистратор` — это не сам первичный документ, а
служебный `Документ.РегистраторРасчётов`. Связь с первичкой — через
РЕКВИЗИТ записи `ДокументРегистратор`. Поэтому сверка по `Регистратор`
(скрипты 04-06) дала ошибочную картину "Только_ПАП vs Только_РСКПС".

ЭТОТ скрипт делает то, что должно быть:
    КЛЮЧ_ПАП = ПАП.Регистратор
    КЛЮЧ_РСКПС = РСКПС.ДокументРегистратор
    JOIN по этому ключу + фильтры Орг + Подр(прямо ПАП vs ОР.Подр РСКПС).

ЦЕЛЬ:
    Найти первичные документы, где сумма в ПАП (для Глобино-2/ЗадКл)
    НЕ равна сумме в РСКПС (для ДолгУпр/ОР.Подр=Глобино-2). Эти документы
    и есть истинный источник расхождения 7 194 594,73.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom

pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ОРГ = erp.NewObject("Запрос")
ОРГ.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
орг = ОРГ.Выполнить().Выбрать(); орг.Следующий(); ORG = орг.Ссылка

ПОДР = erp.Справочники.СтруктураПредприятия.НайтиПоКоду("00-000298")
СТАТЬЯ = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоКоду("00000000002")
ИСТ = erp.Перечисления.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам
НП = erp.Справочники.Партнеры.НашеПредприятие

print("=" * 110)
print("СКРИПТ 11 — Сверка ПАП vs РСКПС через ДокументРегистратор (декабрь 2025 / Глобино-2)")
print("=" * 110)

# === ОДНИМ ЗАПРОСОМ: ПАП-сумма + РСКПС-сумма по каждому первичному документу ===
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("Подр", ПОДР)
q.УстановитьПараметр("Ист", ИСТ)
q.УстановитьПараметр("Статья", СТАТЬЯ)
q.УстановитьПараметр("НП", НП)
q.Текст = """
// === ПАП за декабрь по Глобино-2 / ЗадолженностьКлиентов ===
ВЫБРАТЬ
    Т.Регистратор КАК Док,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК ПАП_Sign
ПОМЕСТИТЬ втПАП
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
    И Т.Организация = &Орг
    И Т.Подразделение В ИЕРАРХИИ (&Подр)
    И Т.Источник = &Ист
    И Т.Статья = &Статья
СГРУППИРОВАТЬ ПО Т.Регистратор
;
// === РСКПС за декабрь по ОР.Подразделение В Глобино-2, ключ = ДокументРегистратор ===
ВЫБРАТЬ
    Р.ДокументРегистратор КАК Док,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ДолгУпр ИНАЧЕ -Р.ДолгУпр КОНЕЦ) КАК РСК_Sign
ПОМЕСТИТЬ втРСК
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Р.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
    И АП.Организация = &Орг
    И АП.Партнер <> &НП
    И ВЫБОР КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
            ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
            ИНАЧЕ Р.ОбъектРасчетов.Подразделение
      КОНЕЦ В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО Р.ДокументРегистратор
;
// === FULL OUTER через ключи + объединение ===
ВЫБРАТЬ ПАП.Док КАК Док ПОМЕСТИТЬ втКлючи ИЗ втПАП КАК ПАП
ОБЪЕДИНИТЬ
ВЫБРАТЬ РСК.Док ИЗ втРСК КАК РСК
;
ВЫБРАТЬ
    К.Док КАК Док,
    ПРЕДСТАВЛЕНИЕ(К.Док) КАК ДокИмя,
    ЕСТЬNULL(ПАП.ПАП_Sign, 0) КАК ПАП_Sign,
    ЕСТЬNULL(РСК.РСК_Sign, 0) КАК РСК_Sign,
    ЕСТЬNULL(ПАП.ПАП_Sign, 0) - ЕСТЬNULL(РСК.РСК_Sign, 0) КАК Дельта
ИЗ втКлючи КАК К
    ЛЕВОЕ СОЕДИНЕНИЕ втПАП КАК ПАП ПО К.Док = ПАП.Док
    ЛЕВОЕ СОЕДИНЕНИЕ втРСК КАК РСК ПО К.Док = РСК.Док
УПОРЯДОЧИТЬ ПО Дельта
"""
r = q.Выполнить().Выгрузить()

print(f"\nВсего уникальных первичных документов: {r.Количество()}")

# Категоризация
оба_ок, оба_разные, только_ПАП, только_РСК = [], [], [], []
sum_total_pap = sum_total_rsk = sum_total_delta = 0.0
for i in range(r.Количество()):
    rec = r.Получить(i)
    p = float(rec.ПАП_Sign or 0)
    rk = float(rec.РСК_Sign or 0)
    d = float(rec.Дельта or 0)
    sum_total_pap += p
    sum_total_rsk += rk
    sum_total_delta += d
    bucket_row = {
        "док": str(rec.ДокИмя), "p": p, "rk": rk, "d": d,
        "ref": rec.Док,
    }
    if abs(d) < 0.01:
        оба_ок.append(bucket_row)
    elif abs(p) > 0.01 and abs(rk) > 0.01:
        оба_разные.append(bucket_row)
    elif abs(p) > 0.01:
        только_ПАП.append(bucket_row)
    else:
        только_РСК.append(bucket_row)

print(f"\nΣ ПАП  по всем: {sum_total_pap:>+18,.2f}")
print(f"Σ РСКПС по всем: {sum_total_rsk:>+18,.2f}")
print(f"Σ Δ (ПАП-РСК):   {sum_total_delta:>+18,.2f}")
print()
print(f"Категории:")
print(f"  ✓ Оба совпадают (|Δ|<0.01): {len(оба_ок):>4}, ΣΔ = {sum(x['d'] for x in оба_ок):>+14,.2f}")
print(f"  ⚠ Оба, разные суммы:        {len(оба_разные):>4}, ΣΔ = {sum(x['d'] for x in оба_разные):>+14,.2f}")
print(f"  ⚠ ТОЛЬКО ПАП (РСК=0):       {len(только_ПАП):>4}, ΣΔ = {sum(x['d'] for x in только_ПАП):>+14,.2f}")
print(f"  ⚠ ТОЛЬКО РСК (ПАП=0):       {len(только_РСК):>4}, ΣΔ = {sum(x['d'] for x in только_РСК):>+14,.2f}")

def dump(title, lst, lim=20):
    if not lst: return
    print(f"\n--- {title} (топ-{min(len(lst),lim)} по |Δ|) ---")
    lst_sorted = sorted(lst, key=lambda x: -abs(x['d']))[:lim]
    for x in lst_sorted:
        print(f"  {x['док'][:75]:<75}  ПАП={x['p']:>+15,.2f}  РСК={x['rk']:>+15,.2f}  Δ={x['d']:>+15,.2f}")

dump("Оба разные суммы (главные подозреваемые)", оба_разные)
dump("Только ПАП (есть в ПАП, нет в РСК)", только_ПАП)
dump("Только РСК (есть в РСК, нет в ПАП)", только_РСК)

# Сохранить полный CSV
import csv, os
out_path = os.path.join(os.path.dirname(__file__), "_artifacts", "11_match_via_dokreg.csv")
with open(out_path, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["Документ", "ПАП_Sign", "РСКПС_Sign", "Дельта", "Категория"])
    def cat(p, rk):
        if abs(p-rk) < 0.01: return "Оба_ОК"
        if abs(p) > 0.01 and abs(rk) > 0.01: return "Оба_разные"
        if abs(p) > 0.01: return "Только_ПАП"
        return "Только_РСК"
    for i in range(r.Количество()):
        rec = r.Получить(i)
        p = float(rec.ПАП_Sign or 0); rk = float(rec.РСК_Sign or 0)
        w.writerow([str(rec.ДокИмя), p, rk, p-rk, cat(p,rk)])

print(f"\nАртефакт: {out_path}")
