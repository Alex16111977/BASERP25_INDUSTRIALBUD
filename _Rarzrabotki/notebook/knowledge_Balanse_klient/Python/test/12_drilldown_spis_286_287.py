# -*- coding: utf-8 -*-
"""
СКРИПТ 12 — Drill-down двух виновных «Списание безналичных ДС» 000Ц-000286/287

КОНТЕКСТ:
    Скрипт 11 (правильная сверка по ДокументРегистратор) показал что ВЕСЬ
    разрыв 7 194 594,73 даёт эта пара:
        000Ц-000286 от 28.12.2025 19:01:15  → РСКПС +5 194 594,73, ПАП 0
        000Ц-000287 от 28.12.2025 19:27:23  → РСКПС +2 000 000,00, ПАП 0

ЦЕЛЬ:
    1. Реквизиты документов: Орг, Партнёр, Подр, Сумма, ХозОперация, ТЧ
    2. ВСЕ движения в ПАП (где этот документ Регистратор) — какая статья/источник?
    3. ВСЕ движения в РСКПС (где этот документ ДокументРегистратор) — какие ОР?
    4. Понять КУДА они пишут в ПАП (и почему не в "Задолженность клиентов")
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom

pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


for ном in ("000Ц-000286", "000Ц-000287"):
    print("=" * 100)
    print(f"ДОКУМЕНТ Списание безналичных ДС № {ном}")
    print("=" * 100)

    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Н", ном)
    q.Текст = '''ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.СписаниеБезналичныхДенежныхСредств ГДЕ Номер = &Н'''
    рез = q.Выполнить().Выгрузить()
    if рез.Количество() == 0:
        print("Не найден!"); continue
    doc = рез.Получить(0).Ссылка
    obj = doc.ПолучитьОбъект()

    # === 1. Реквизиты шапки ===
    print("\n[ШАПКА]")
    for поле in ("Дата", "Номер", "Проведен", "ПометкаУдаления",
                 "Организация", "Подразделение", "Партнер", "Контрагент", "Договор",
                 "ОбъектРасчетов", "ХозяйственнаяОперация", "ФормаОплаты", "Валюта",
                 "СуммаДокумента", "Комментарий", "ВидОперации"):
        if hasattr(obj, поле):
            try:
                val = getattr(obj, поле)
                if isinstance(val, (int, float)):
                    print(f"  {поле:<25}: {val:,.2f}")
                else:
                    print(f"  {поле:<25}: {S(val) if val is not None else ''}")
            except Exception as e:
                print(f"  {поле:<25}: [ошибка: {e}]")

    # === 2. Табличные части ===
    for тч_имя in ("РасшифровкаПлатежа", "ПлатежПоЗаказам", "ПлатежПартнерам", "Расшифровка"):
        if hasattr(obj, тч_имя):
            тч = getattr(obj, тч_имя)
            try:
                cnt = тч.Количество()
                if cnt == 0: continue
                print(f"\n[ТЧ {тч_имя}] ({cnt} строк)")
                for i in range(min(cnt, 20)):
                    стр = тч.Получить(i)
                    parts = []
                    for поле in ("Партнер", "Контрагент", "Договор", "ОбъектРасчетов",
                                 "Заказ", "Документ", "СтатьяДоходов", "СтатьяРасходов",
                                 "ХозОперация", "СуммаПлатежа", "Сумма", "СтатьяДвиженияДенежныхСредств"):
                        if hasattr(стр, поле):
                            try:
                                v = getattr(стр, поле)
                                if isinstance(v, (int, float)) and v != 0:
                                    parts.append(f"{поле}={v:,.2f}")
                                elif not isinstance(v, (int, float)) and v is not None:
                                    s = S(v)
                                    if s: parts.append(f"{поле}={s[:55]}")
                            except Exception: pass
                    print(f"   [{i+1}] " + " | ".join(parts))
            except Exception as e:
                print(f"   [{тч_имя}] ошибка: {e}")

    # === 3. ВСЕ движения ПАП по этому документу ===
    print("\n[ПАП-движения этого регистратора]")
    qm = erp.NewObject("Запрос")
    qm.УстановитьПараметр("Р", doc)
    qm.Текст = '''
    ВЫБРАТЬ
        Т.Активность, Т.ВидДвижения,
        ПРЕДСТАВЛЕНИЕ(Т.Организация) КАК Орг,
        ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
        ПРЕДСТАВЛЕНИЕ(Т.Источник) КАК Ист,
        ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст,
        Т.Сумма
    ИЗ РегистрНакопления.ПрочиеАктивыПассывы КАК Т
    ГДЕ Т.Регистратор = &Р
    '''
    # ПрочиеАктивыПассывы — пишется "Пассывы", не "Пассивы" в имени класса
    try:
        rm = qm.Выполнить().Выгрузить()
    except Exception:
        qm.Текст = qm.Текст.replace("ПрочиеАктивыПассывы", "ПрочиеАктивыПассивы")
        rm = qm.Выполнить().Выгрузить()
    print(f"   Строк: {rm.Количество()}")
    for i in range(rm.Количество()):
        r = rm.Получить(i)
        print(f"   Активн={r.Активность} {S(r.ВидДвижения):<7} Сум={float(r.Сумма):>+15,.2f}  "
              f"Орг={r.Орг[:22]:<22}  Подр={r.Подр[:14]:<14}  Ист={r.Ист[:30]:<30}  Ст={r.Ст}")

    # === 4. ВСЕ движения РСКПС где ДокументРегистратор = этот ===
    print("\n[РСКПС-движения где ДокументРегистратор = этот документ]")
    qr = erp.NewObject("Запрос")
    qr.УстановитьПараметр("Р", doc)
    qr.Текст = '''
    ВЫБРАТЬ
        Т.Период, Т.Активность, Т.ВидДвижения,
        ПРЕДСТАВЛЕНИЕ(Т.Регистратор) КАК РегИмя,
        ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК Партн,
        ПРЕДСТАВЛЕНИЕ(Т.ОбъектРасчетов) КАК ОР,
        ПРЕДСТАВЛЕНИЕ(Т.ОбъектРасчетов.Подразделение) КАК ПодрОР,
        ПРЕДСТАВЛЕНИЕ(Т.ОбъектРасчетов.Договор) КАК Дог,
        ПРЕДСТАВЛЕНИЕ(Т.ХозяйственнаяОперация) КАК ХО,
        Т.ДолгУпр, Т.ПредоплатаУпр
    ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Т
        ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
            ПО Т.АналитикаУчетаПоПартнерам = АП.КлючАналитики
    ГДЕ Т.ДокументРегистратор = &Р
    УПОРЯДОЧИТЬ ПО Т.Период
    '''
    rr = qr.Выполнить().Выгрузить()
    print(f"   Строк: {rr.Количество()}")
    for i in range(rr.Количество()):
        r = rr.Получить(i)
        print(f"   Активн={r.Активность} {S(r.ВидДвижения):<7} ДолгУпр={float(r.ДолгУпр):>+12,.2f}  "
              f"Аванс={float(r.ПредоплатаУпр):>+12,.2f}  Партн={r.Партн[:25]:<25}  "
              f"ОР={r.ОР[:35]:<35}  ПодрОР={r.ПодрОР[:14]:<14}  ХО={r.ХО[:30]:<30}  "
              f"Рег={r.РегИмя[:25]}")

    # === 5. Регистр Расчеты с поставщиками — может туда пишут? ===
    qrp = erp.NewObject("Запрос")
    qrp.УстановитьПараметр("Р", doc)
    qrp.Текст = '''
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К, СУММА(Т.ДолгУпр) КАК Σдолг
    ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Т
    ГДЕ Т.ДокументРегистратор = &Р
    '''
    try:
        rrp = qrp.Выполнить().Выгрузить().Получить(0)
        print(f"\n[РасчетыСПоставщикамиПоСрокам где ДокументРегистратор=этот]: К={int(rrp.К or 0)}, Σдолг={float(rrp.Σдолг or 0):,.2f}")
    except Exception as e:
        print(f"  [РасчСПоставщ ошибка: {e}]")

    print()
