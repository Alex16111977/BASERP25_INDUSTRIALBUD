# -*- coding: utf-8 -*-
"""
Phase 6 — drill-down по строкам ТЧ документа ВводОстатков 0Ц-00000083 (ЦО).
Найти конкретную строку/ОР которая даёт ±36 408,04 расхождения ПАП vs РСКПС.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money

erp = connect_erp()
S = erp.String

# 1) Получить ссылку
q0 = erp.NewObject("Запрос")
q0.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.ВводОстатков ГДЕ Номер = "0Ц-00000083" """
sel = q0.Выполнить().Выбрать(); sel.Следующий()
ДОК = sel.Ссылка
print(f"Документ: {S(ДОК)}")

# 2) Прочитать строки ТЧ через COM объект (раздел учёта Расчёты с клиентами имеет свою ТЧ)
obj = ДОК.ПолучитьОбъект()
print(f"\n--- Реквизиты документа ---")
md = obj.Метаданные()
for r in md.Реквизиты:
    name = r.Имя
    try:
        v = getattr(obj, name)
        if v is None: continue
        if isinstance(v, (str, int, float, bool)):
            print(f"  {name}: {v}")
        else:
            try:
                print(f"  {name}: {S(v)}")
            except:
                print(f"  {name}: <object>")
    except: pass

# Перебрать все ТЧ
print(f"\n--- Табличные части документа ---")
for tc in md.ТабличныеЧасти:
    тч = getattr(obj, tc.Имя)
    if тч.Количество() > 0:
        print(f"  {tc.Имя}: строк={тч.Количество()}")

# 3) Запрос — ПАП per НомерСтроки/ОбъектРасчетов
print("\n--- ПАП per НомерСтроки / Статья / ОР по этому документу ---")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Док", ДОК)
q.Текст = """
ВЫБРАТЬ
    Т.НомерСтроки КАК НомСтр,
    Т.Статья КАК Статья,
    Т.Подразделение КАК Подр,
    ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ КАК Sign
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор = &Док
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
УПОРЯДОЧИТЬ ПО НомСтр, Статья
"""
r = q.Выполнить().Выгрузить()
print(f"  Строк ПАП: {r.Количество()}")
pap_rows = []
for i in range(r.Количество()):
    rec = r.Получить(i)
    pap_rows.append({"номстр": int(rec.НомСтр), "статья": str(S(rec.Статья)),
                     "подр": str(S(rec.Подр)), "sign": float(rec.Sign)})
    print(f"    стр#{int(rec.НомСтр):>3}  {str(S(rec.Статья)):<30}  Подр={str(S(rec.Подр))[:25]:<25}  {money(rec.Sign):>14}")

# 4) Запрос — РСКПС per НомерСтроки / ОР / Партнёр через ДокументРегистратор
print("\n--- РСКПС per ДокументРегистратор=0Ц-00000083 (агрегация по ОР+Партнёр) ---")
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("Док", ДОК)
q2.Текст = """
ВЫБРАТЬ
    Р.ОбъектРасчетов КАК ОР,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    АП.Партнер КАК Партнер,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК ПартнерИмя,
    АП.Контрагент КАК Контрагент,
    ПРЕДСТАВЛЕНИЕ(АП.Контрагент) КАК КонтрИмя,
    АП.Договор КАК Договор,
    ПРЕДСТАВЛЕНИЕ(АП.Договор) КАК ДоговорИмя,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ДолгУпр ИНАЧЕ -Р.ДолгУпр КОНЕЦ) КАК ДолгSign,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ПредоплатаУпр ИНАЧЕ -Р.ПредоплатаУпр КОНЕЦ) КАК АвансSign
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Р.ДокументРегистратор = &Док
СГРУППИРОВАТЬ ПО
    Р.ОбъектРасчетов,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов),
    АП.Партнер, ПРЕДСТАВЛЕНИЕ(АП.Партнер),
    АП.Контрагент, ПРЕДСТАВЛЕНИЕ(АП.Контрагент),
    АП.Договор, ПРЕДСТАВЛЕНИЕ(АП.Договор)
ИМЕЮЩИЕ
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ДолгУпр ИНАЧЕ -Р.ДолгУпр КОНЕЦ) <> 0
 ИЛИ СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Р.ПредоплатаУпр ИНАЧЕ -Р.ПредоплатаУпр КОНЕЦ) <> 0
УПОРЯДОЧИТЬ ПО ДолгSign
"""
r2 = q2.Выполнить().Выгрузить()
print(f"  Строк РСКПС: {r2.Количество()}\n")

print(f"{'Договор':<45}{'Партнёр':<30}{'ОР':<35}{'ДолгУпр':>14}{'Предоплата':>14}")
print("-" * 138)
total_dolg = total_avans = 0.0
suspect = None
for i in range(r2.Количество()):
    rec = r2.Получить(i)
    d = float(rec.ДолгSign or 0)
    a = float(rec.АвансSign or 0)
    total_dolg += d
    total_avans += a
    or_str = str(rec.ОРИмя or "")
    dog_str = str(rec.ДоговорИмя or "")
    p_str = str(rec.ПартнерИмя or "")
    print(f"{dog_str[:43]:<45}{p_str[:28]:<30}{or_str[:33]:<35}{money(d):>14}{money(a):>14}")
    # ищем строку которая даёт ±36408
    if abs(abs(d) - 36408.04) < 0.5 or abs(abs(a) - 36408.04) < 0.5:
        suspect = {"dog": dog_str, "p": p_str, "or": or_str, "d": d, "a": a, "контр": str(rec.КонтрИмя or "")}

print("-" * 138)
print(f"{'ИТОГО':<110}{money(total_dolg):>14}{money(total_avans):>14}")

if suspect:
    print(f"\n>>> ПОДОЗРИТЕЛЬНАЯ СТРОКА (содержит ±36 408,04):")
    print(f"    Договор:    {suspect['dog']}")
    print(f"    Партнёр:    {suspect['p']}")
    print(f"    Контрагент: {suspect['контр']}")
    print(f"    ОР:         {suspect['or']}")
    print(f"    ДолгУпр:    {money(suspect['d'])}")
    print(f"    Предоплата: {money(suspect['a'])}")

# 5) Найти ту же сумму в ТЧ документа (если есть колонка СуммаУпр или Сумма)
print("\n--- Поиск +/-36 408,04 в табличных частях документа ---")
for tc in md.ТабличныеЧасти:
    тч = getattr(obj, tc.Имя)
    if тч.Количество() == 0: continue
    cols = [c.Имя for c in тч.Колонки]
    for ri in range(тч.Количество()):
        row = тч.Получить(ri)
        for col in cols:
            try:
                v = getattr(row, col)
                if isinstance(v, (int, float)) and abs(abs(float(v)) - 36408.04) < 0.5:
                    # вывести всю строку
                    print(f"\n  ТЧ.{tc.Имя}  строка #{ri+1}  колонка {col} = {v}")
                    for c2 in cols:
                        v2 = getattr(row, c2)
                        if v2 is not None and not (isinstance(v2, (int, float)) and v2 == 0):
                            try:
                                vs = S(v2) if not isinstance(v2, (int, float, str, bool)) else str(v2)
                            except: vs = str(v2)
                            print(f"      {c2}: {vs}")
            except: pass
