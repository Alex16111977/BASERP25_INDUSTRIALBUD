# -*- coding: utf-8 -*-
"""
Phase 6 — диагностика реальных движений РСКПС/ПАП по партнёру ЮЕйДрім
до изменений (чтобы понять что лежит в каком документе).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money

erp = connect_erp()
S = erp.String

# Найти партнёра
q = erp.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Партнеры ГДЕ Наименование ПОДОБНО "%ЮЕйДрім%" """
sel = q.Выполнить().Выбрать(); sel.Следующий()
partner = sel.Ссылка
print(f"Партнёр: {S(partner)}")

# Найти ДокументАвансов и Долгов
def get_doc(num):
    q.Текст = f'ВЫБРАТЬ Ссылка ИЗ Документ.ВводОстатков ГДЕ Номер = "{num}"'
    sel = q.Выполнить().Выбрать(); sel.Следующий()
    return sel.Ссылка
refAv = get_doc("0Ц-00000083")
refDol = get_doc("0Ц-00000082")

# РСКПС движения per документ
print("\n[1] РСКПС движения по ЮЕйДрім (все документы)")
q.УстановитьПараметр("Партнёр", partner)
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ДокументРегистратор) КАК Док,
    Р.Период КАК Период,
    Р.ВидДвижения КАК ВидДв,
    Р.ДолгУпр КАК ДолгУпр,
    Р.ПредоплатаУпр КАК Аванс,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОР
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Партнер = &Партнёр
УПОРЯДОЧИТЬ ПО Период
"""
r = q.Выполнить().Выгрузить()
print(f"  Всего движений: {r.Количество()}")
for i in range(r.Количество()):
    rec = r.Получить(i)
    print(f"  {str(rec.Период)[:10]:<11}  {str(rec.Док)[:55]:<57}  {S(rec.ВидДв):<8}  Долг={float(rec.ДолгУпр or 0):>+12,.2f}  Аванс={float(rec.Аванс or 0):>+12,.2f}")

# Остатки за разные даты
print("\n[2] РСКПС остатки на конец дат")
q.Текст = """
ВЫБРАТЬ
    СУММА(Р.ДолгУпрОстаток) КАК Долг,
    СУММА(Р.ПредоплатаУпрОстаток) КАК Аванс
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(&Дата,) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Партнер = &Партнёр
"""
import datetime
for d_str, d_obj in [("31.10.2025", datetime.datetime(2025,10,31,23,59,59)),
                     ("30.11.2025", datetime.datetime(2025,11,30,23,59,59)),
                     ("31.12.2025", datetime.datetime(2025,12,31,23,59,59))]:
    q.УстановитьПараметр("Дата", d_obj)
    rr = q.Выполнить().Выгрузить()
    if rr.Количество() > 0:
        rec = rr.Получить(0)
        print(f"  {d_str}:  Долг={float(rec.Долг or 0):>+12,.2f}  Аванс={float(rec.Аванс or 0):>+12,.2f}")

# ПАП движения per документ для партнёра ЮЕйДрім
# ПАП не имеет партнёра напрямую — но можно через КлючАналитики
print("\n[3] Движения в ПАП по этим 2 документам (ВводОстатков Авансы+Долги)")
q.УстановитьПараметр("Док1", refAv)
q.УстановитьПараметр("Док2", refDol)
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Т.Регистратор) КАК Док,
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
    Т.Источник КАК Источник,
    Т.ВидДвижения КАК ВидДв,
    Т.Сумма КАК Сумма,
    Т.НомерСтроки КАК НомСтр
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор В (&Док1, &Док2)
    И ПРЕДСТАВЛЕНИЕ(Т.Подразделение) = "ЦО"
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
УПОРЯДОЧИТЬ ПО Док, НомСтр, Статья
"""
try:
    r = q.Выполнить().Выгрузить()
    print(f"  Строк ПАП по ЦО: {r.Количество()}")
    for i in range(r.Количество()):
        rec = r.Получить(i)
        print(f"  {str(rec.Док)[:55]:<57}  стр#{int(rec.НомСтр):>3}  {str(rec.Статья)[:30]:<32}  {S(rec.ВидДв):<8}  Сумма={float(rec.Сумма):>+12,.2f}")
except Exception as e:
    print(f"  FAIL: {e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else e}")

# Сумма реальная в ТЧ обоих документов для ЮЕйДрім
print("\n[4] Что записано в ТЧ обоих документов по ЮЕйДрім:")
for nm, ref in [("Авансы (0Ц-00000083)", refAv), ("Долги (0Ц-00000082)", refDol)]:
    obj = ref.ПолучитьОбъект()
    tc = obj.РасчетыСПартнерами
    for i in range(tc.Количество()):
        row = tc.Получить(i)
        try:
            p = str(S(row.Партнер) or "")
        except: p = ""
        if "ЮЕйДрім" in p:
            print(f"  {nm} стр#{i+1}: Партнёр={p}, Договор={S(row.Договор)}, Сумма={row.Сумма}, СуммаУпр={row.СуммаУпр}, СуммаРегл={row.СуммаРегл}")
