# -*- coding: utf-8 -*-
"""
СКРИПТ 32 (Phase 4) — Σ-инвариант штатного Отчёт.УправленческийБаланс

ПРОВЕРКА:
    Σ signed (КО, OD-3) per орг = 0 (балансовый инвариант)
    Эталоны:
    - дек 2025: ±278 093 267,32
    - янв 2026: ±288 787 750,11
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
from _common import connect_erp, get_refs

erp = connect_erp()
refs = get_refs(erp)

ЭТАЛОНЫ = {
    "31.12.2025": (278_093_267.32, datetime.datetime(2025, 12, 31, 23, 59, 59)),
    "31.01.2026": (288_787_750.11, datetime.datetime(2026, 1, 31, 23, 59, 59)),
}

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", refs["Орг"])

ok = True
print("=" * 80)
print("СКРИПТ 32 — Σ-инвариант управленческого баланса (OD-3)")
print("=" * 80)
for дата, (эталон, дт) in ЭТАЛОНЫ.items():
    q.УстановитьПараметр("Д", дт)
    q.Текст = """
    ВЫБРАТЬ
        СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма
                    ИНАЧЕ -Т.Сумма КОНЕЦ) КАК Σsigned,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма
                    ИНАЧЕ 0 КОНЕЦ) КАК Σактив
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Период <= &Д И Т.Организация = &Орг
        И НЕ Т.Статья В ИЕРАРХИИ (
            ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.СобственныеСредства),
            ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ДоходыТекущегоПериода),
            ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.РасходыТекущегоПериода))
    """
    r = q.Выполнить().Выгрузить().Получить(0)
    σ_s = float(r.Σsigned or 0)
    σ_a = float(r.Σактив or 0)
    print(f"\n  {дата}:")
    print(f"    Σ signed (OD-3): {σ_s:+,.2f}  (эталон 0,00)")
    print(f"    Σ Актив (|пассив|): {σ_a:,.2f}  (эталон {эталон:,.2f})")
    print(f"    Δ Актив vs эталон: {σ_a - эталон:+,.2f}")
    if abs(σ_s) > 1.0:  # допуск 1 руб
        print(f"    ⚠️ Σ signed ≠ 0 — балансовый инвариант нарушен!")
        ok = False

if ok:
    print("\n✓ Σ-инвариант штатного отчёта сохранён")
    sys.exit(0)
else:
    print("\n❌ Σ-инвариант нарушен — rollback!")
    sys.exit(1)
