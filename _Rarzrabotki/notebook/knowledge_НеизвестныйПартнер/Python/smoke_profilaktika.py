# -*- coding: utf-8 -*-
# Smoke профилактики: Часть A (контрагент) + документный гард (логика, без записи)
import sys
sys.path.insert(0, r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test')
import _common_neizv as c

erp = c.connect()
P = c.neizv(erp)

# ===== Smoke A: КонтрагентыПередЗаписью подставляет реального партнёра =====
print("=== A: профилактика на записи контрагента ===")
k = erp.Справочники.Контрагенты.СоздатьЭлемент()
k.Наименование = "ТЕСТ_НеизвФикс_УДАЛИТЬ"
k.Партнер = P
k.ЮридическоеФизическоеЛицо = erp.Перечисления.ЮридическоеФизическоеЛицо.ЮридическоеЛицо
k.Записать()
created_partner = k.Партнер
print("  Партнёр после записи:", created_partner.Наименование)
assert not c.same(erp, created_partner, P), "Часть A НЕ сработала: партнёр остался Неизвестным!"
print("  OK: Часть A подставила реального партнёра")
# уборка теста
k.ПометкаУдаления = True
k.Записать()
if not c.same(erp, created_partner, P):
    pobj = created_partner.ПолучитьОбъект()
    pobj.ПометкаУдаления = True
    pobj.Записать()
print("  тестовые объекты помечены на удаление")

# ===== Smoke B: документный гард правит поле Партнёр (в памяти, без записи) =====
print("\n=== B: документный гард (логика, без записи) ===")
# найдём контрагента с УЖЕ реальным партнёром (чтобы гард не создавал нового)
q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 К.Ссылка КАК Ссылка, К.Партнер КАК Партнер ИЗ Справочник.Контрагенты КАК К "
          "ГДЕ К.Партнер <> &P И НЕ К.Партнер.ПометкаУдаления И НЕ К.ПометкаУдаления")
q.УстановитьПараметр("P", P)
s = q.Execute().Выбрать()
assert s.Следующий(), "нет контрагента с реальным партнёром"
контр = s.Ссылка
реальный = s.Партнер
print("  контрагент:", контр.Наименование, "| реальный партнёр:", реальный.Наименование)

# создаём документ В ПАМЯТИ (не пишем), ставим Контрагент + Партнер=Неизв, зовём гард
doc = erp.Документы.ЗаказПоставщику.СоздатьДокумент()
doc.Контрагент = контр
doc.Партнер = P
print("  до гарда: Партнер =", doc.Партнер.Наименование)
erp.А_СобытияОбъектов.А_ИсправитьНеизвестногоПартнераВДокументе(doc)
print("  после гарда: Партнер =", doc.Партнер.Наименование)
assert not c.same(erp, doc.Партнер, P), "гард НЕ исправил поле Партнёр!"
assert c.same(erp, doc.Партнер, реальный), "гард подставил не того партнёра!"
print("  OK: документный гард подставил партнёра контрагента (без записи документа)")

print("\nВСЁ OK: профилактика работает в рантайме")
