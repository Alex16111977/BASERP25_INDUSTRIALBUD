# -*- coding: utf-8 -*-
# Валидация исправления (БЕЗ перепроведения) на ОДНОМ застрявшем ключе:
# поправить КлючАналитики в кэше на канонический -> ключ освобождается -> удалить.
import sys
sys.path.insert(0, r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test')
import _common_neizv as c

erp = c.connect()
P = c.neizv(erp)


def refs(ref):
    arr = erp.NewObject("Массив"); arr.Добавить(ref)
    return erp.НайтиПоСсылкам(arr).Количество()


# взять ОДИН застрявший ключ, который держит ТОЛЬКО кэш (АналитикаУчетаПоПартнерам)
q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ Ссылка, Организация КАК О, Контрагент КАК К, Договор КАК Д, НаправлениеДеятельности КАК Н "
          "ИЗ Справочник.КлючиАналитикиУчетаПоПартнерам ГДЕ Партнер = &P И ПометкаУдаления")
q.УстановитьПараметр("P", P)
s = q.Execute().Выбрать()
target_key = None
while s.Следующий():
    k = s.Ссылка
    # держит только кэш?
    arr = erp.NewObject("Массив"); arr.Добавить(k)
    res = erp.НайтиПоСсылкам(arr)
    onlycache = res.Количество() > 0
    for i in range(res.Количество()):
        try:
            fn = res.Получить(i).Метаданные.ПолноеИмя()
        except Exception:
            fn = "?"
        if fn != "РегистрСведений.АналитикаУчетаПоПартнерам":
            onlycache = False
    if onlycache:
        target_key = {"k": k, "О": s.О, "К": s.К, "Д": s.Д, "Н": s.Н}
        break

if target_key is None:
    print("Нет ключа, который держит только кэш — пропускаю валидацию")
    sys.exit(0)

K = target_key["k"]
print("Ключ:", c.uid(erp, K), "| держат ДО:", refs(K))

# канонический ключ (real partner, те же измерения, не помечен)
qc = erp.NewObject("Запрос")
qc.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка, Партнер ИЗ Справочник.КлючиАналитикиУчетаПоПартнерам "
           "ГДЕ Партнер <> &P И НЕ ПометкаУдаления И Организация=&О И Контрагент=&К И Договор=&Д И НаправлениеДеятельности=&Н")
qc.УстановитьПараметр("P", P); qc.УстановитьПараметр("О", target_key["О"]); qc.УстановитьПараметр("К", target_key["К"])
qc.УстановитьПараметр("Д", target_key["Д"]); qc.УстановитьПараметр("Н", target_key["Н"])
sc = qc.Execute().Выбрать()
assert sc.Следующий(), "нет канонического ключа"
canon = sc.Ссылка
target_partner = sc.Партнер
print("Канонический ключ:", c.uid(erp, canon), "| партнёр:", target_partner.Наименование)

# поправить кэш: записи АналитикаУчетаПоПартнерам с КлючАналитики=K -> canon (менеджер записи, БЕЗ перепроведения)
qk = erp.NewObject("Запрос")
qk.Text = ("ВЫБРАТЬ Партнер КАК Птн, Организация КАК О, Контрагент КАК К, Договор КАК Д, НаправлениеДеятельности КАК Н "
           "ИЗ РегистрСведений.АналитикаУчетаПоПартнерам ГДЕ КлючАналитики = &K")
qk.УстановитьПараметр("K", K)
sk = qk.Execute().Выбрать()
fixed = 0
while sk.Следующий():
    mz = erp.РегистрыСведений.АналитикаУчетаПоПартнерам.СоздатьМенеджерЗаписи()
    mz.Партнер = sk.Птн; mz.Организация = sk.О; mz.Контрагент = sk.К; mz.Договор = sk.Д; mz.НаправлениеДеятельности = sk.Н
    mz.Прочитать()
    if mz.Выбран():
        mz.КлючАналитики = canon
        mz.Записать()
        fixed += 1
print("кэш-записей перенаправлено на канонический ключ:", fixed)

n = refs(K)
print("держат ПОСЛЕ:", n)
if n == 0:
    K.ПолучитьОбъект().Удалить()
    print("OK: ключ освобождён и УДАЛЁН (без перепроведения)")
else:
    print("ещё держат:", n, "- удаление пропущено")
