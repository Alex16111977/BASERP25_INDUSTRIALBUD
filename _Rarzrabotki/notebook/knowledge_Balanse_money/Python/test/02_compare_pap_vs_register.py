# -*- coding: utf-8 -*-
"""
СКРИПТ 02 — Сверка ПАП vs Регистр.ДенежныеСредства* по эталону штатной ведомости

Зеркалит логику Свод_ДенежныеСредства (BSL 621-845) НО с ВКЛЮЧЁННЫМ
четвёртым источником ДенежныеСредстваВПути (как должно быть!).

ARGV: <YYYY-MM>  (например 2025-12) — месяц для сверки

Артефакт:
  _artifacts/02_pap_vs_reg_<месяц>.csv
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, save_csv

if len(sys.argv) < 2:
    print("Usage: python 02_compare_pap_vs_register.py <YYYY-MM>")
    sys.exit(1)
y, m = map(int, sys.argv[1].split("-"))
end_y = y if m < 12 else y + 1
end_m = m + 1 if m < 12 else 1

erp = connect_erp()
refs = get_refs(erp)

print("=" * 110)
print(f"СКРИПТ 02 — ПАП vs Регистр.ДС* за {sys.argv[1]}")
print("=" * 110)

# === Шаг 1: Агрегат из 4 регистров РНДС (зеркало штатной ведомости) ===
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", refs["Орг"])
q.УстановитьПараметр("ИБ", refs["Ист_Безнал"])
q.УстановитьПараметр("ИН", refs["Ист_Налич"])
q.УстановитьПараметр("ИП", refs["Ист_Подотч"])
q.УстановитьПараметр("ИВ", refs["Ист_ВПути"])
q.Текст = f"""
// Безналичные
ВЫБРАТЬ
    ЕСТЬNULL(Б.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
    &ИБ КАК Source,
    СУММА(Б.СуммаНачальныйОстаток) КАК НО,
    СУММА(Б.СуммаКонечныйОстаток) КАК КМ
ПОМЕСТИТЬ втРНДС
ИЗ РегистрНакопления.ДенежныеСредстваБезналичные.ОстаткиИОбороты(
    ДАТАВРЕМЯ({y},{m},1,0,0,0), КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ), , , Организация = &Орг) КАК Б
СГРУППИРОВАТЬ ПО ЕСТЬNULL(Б.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))

ОБЪЕДИНИТЬ ВСЕ

// Наличные
ВЫБРАТЬ ЕСТЬNULL(Н.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)),
    &ИН, СУММА(Н.СуммаНачальныйОстаток), СУММА(Н.СуммаКонечныйОстаток)
ИЗ РегистрНакопления.ДенежныеСредстваНаличные.ОстаткиИОбороты(
    ДАТАВРЕМЯ({y},{m},1,0,0,0), КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ), , , Организация = &Орг) КАК Н
СГРУППИРОВАТЬ ПО ЕСТЬNULL(Н.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))

ОБЪЕДИНИТЬ ВСЕ

// Подотчётные (нет Подразделения как измерения — берём пустое)
ВЫБРАТЬ ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка),
    &ИП, СУММА(П.СуммаНачальныйОстаток), СУММА(П.СуммаКонечныйОстаток)
ИЗ РегистрНакопления.ДенежныеСредстваУПодотчетныхЛиц.ОстаткиИОбороты(
    ДАТАВРЕМЯ({y},{m},1,0,0,0), КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ), , , Организация = &Орг) КАК П

ОБЪЕДИНИТЬ ВСЕ

// В пути — критический регистр пропущен в Свод_!
ВЫБРАТЬ ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка),
    &ИВ, СУММА(Вп.СуммаНачальныйОстаток), СУММА(Вп.СуммаКонечныйОстаток)
ИЗ РегистрНакопления.ДенежныеСредстваВПути.ОстаткиИОбороты(
    ДАТАВРЕМЯ({y},{m},1,0,0,0), КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ), , , Организация = &Орг) КАК Вп
;
// === ПАП ===
ВЫБРАТЬ
    ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
    Т.Источник КАК Source,
    СУММА(ВЫБОР КОГДА Т.Период < ДАТАВРЕМЯ({y},{m},1,0,0,0)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                    ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК НО,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КМ
ПОМЕСТИТЬ втПАП
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг
    И Т.Период <= КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ)
    И Т.Источник В (&ИБ, &ИН, &ИП, &ИВ)
СГРУППИРОВАТЬ ПО ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)),
    Т.Источник
;
// === FULL OUTER через ключи ===
ВЫБРАТЬ РАЗЛИЧНЫЕ К.Подр КАК Подр, К.Source КАК Source ПОМЕСТИТЬ втКл ИЗ
    (ВЫБРАТЬ Подр, Source ИЗ втРНДС
     ОБЪЕДИНИТЬ ВЫБРАТЬ Подр, Source ИЗ втПАП) КАК К
;
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(К.Подр) КАК Подр,
    К.Source КАК SourceRef,
    ЕСТЬNULL(втПАП.НО, 0) КАК ПАП_НО,
    ЕСТЬNULL(втРНДС.НО, 0) КАК РНДС_НО,
    ЕСТЬNULL(втПАП.НО, 0) - ЕСТЬNULL(втРНДС.НО, 0) КАК Δ_НО,
    ЕСТЬNULL(втПАП.КМ, 0) КАК ПАП_КМ,
    ЕСТЬNULL(втРНДС.КМ, 0) КАК РНДС_КМ,
    ЕСТЬNULL(втПАП.КМ, 0) - ЕСТЬNULL(втРНДС.КМ, 0) КАК Δ_КМ
ИЗ втКл КАК К
    ЛЕВОЕ СОЕДИНЕНИЕ втПАП КАК втПАП ПО К.Подр = втПАП.Подр И К.Source = втПАП.Source
    ЛЕВОЕ СОЕДИНЕНИЕ втРНДС КАК втРНДС ПО К.Подр = втРНДС.Подр И К.Source = втРНДС.Source
ГДЕ ЕСТЬNULL(втПАП.КМ, 0) - ЕСТЬNULL(втРНДС.КМ, 0) > 0.01
    ИЛИ ЕСТЬNULL(втПАП.КМ, 0) - ЕСТЬNULL(втРНДС.КМ, 0) < -0.01
    ИЛИ ЕСТЬNULL(втПАП.НО, 0) - ЕСТЬNULL(втРНДС.НО, 0) > 0.01
    ИЛИ ЕСТЬNULL(втПАП.НО, 0) - ЕСТЬNULL(втРНДС.НО, 0) < -0.01
УПОРЯДОЧИТЬ ПО Δ_КМ
"""

r = q.Выполнить().Выгрузить()
print(f"\nВсего расхождений (Подр × Source): {r.Количество()}")
S = erp.String

rows = []
print(f"\n{'Подр':<30}{'Source':<35}{'ПАП_НО':>15}{'РНДС_НО':>15}{'Δ_НО':>15}{'ПАП_КМ':>15}{'РНДС_КМ':>15}{'Δ_КМ':>15}")
print("-" * 155)
for i in range(r.Количество()):
    rec = r.Получить(i)
    src = str(S(rec.SourceRef))
    print(f"{str(rec.Подр)[:28]:<30}{src[:33]:<35}"
          f"{money(rec.ПАП_НО):>15}{money(rec.РНДС_НО):>15}{money(rec.Δ_НО):>15}"
          f"{money(rec.ПАП_КМ):>15}{money(rec.РНДС_КМ):>15}{money(rec.Δ_КМ):>15}")
    rows.append({
        "Подр": str(rec.Подр), "Source": src,
        "ПАП_НО": float(rec.ПАП_НО), "РНДС_НО": float(rec.РНДС_НО), "Δ_НО": float(rec.Δ_НО),
        "ПАП_КМ": float(rec.ПАП_КМ), "РНДС_КМ": float(rec.РНДС_КМ), "Δ_КМ": float(rec.Δ_КМ),
    })

save_csv(f"02_pap_vs_reg_{sys.argv[1]}", rows,
         ["Подр", "Source", "ПАП_НО", "РНДС_НО", "Δ_НО", "ПАП_КМ", "РНДС_КМ", "Δ_КМ"])
print(f"\nАртефакт: 02_pap_vs_reg_{sys.argv[1]}.csv")
