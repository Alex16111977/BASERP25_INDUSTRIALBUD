# -*- coding: utf-8 -*-
"""
Phase 7 — Массовый фикс 4 ПКО: установить Подразделение из Кассы.Подразделение.
Безопасно для COM т.к. ХозОп "Конвертация валюты" / "Инкассация" — без РСКПС.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money, find_doc_by_number

erp = connect_erp()
S = erp.String

DOCS = [
    "000Ц-000001",
    "000Ц-000002",
    "000Ц-000003",  # уже перепроведён smoke
    "N0000023706",
]

print("=" * 100)
print("Phase 7 — Массовый фикс 4 ПКО (Подразделение в шапке из Кассы)")
print("=" * 100)

for num in DOCS:
    ref = find_doc_by_number(erp, "ПриходныйКассовыйОрдер", num)
    if ref is None:
        print(f"\n[!] ПКО {num} не найден"); continue
    obj = ref.ПолучитьОбъект()
    cur_podr = S(obj.Подразделение) if erp.ЗначениеЗаполнено(obj.Подразделение) else "(пусто)"
    target = obj.Касса.Подразделение if erp.ЗначениеЗаполнено(obj.Касса) else None
    tgt = S(target) if target and erp.ЗначениеЗаполнено(target) else None
    print(f"\nПКО {num}:")
    print(f"  Касса: {S(obj.Касса)}")
    print(f"  Подр сейчас: {cur_podr}  →  Целевое (из Кассы): {tgt}")
    if cur_podr != "(пусто)":
        print(f"  [skip] Уже заполнено")
        continue
    if target is None or not erp.ЗначениеЗаполнено(target):
        print(f"  [skip] У Кассы Подр пусто")
        continue
    obj.Подразделение = target
    try:
        obj.Записать(erp.РежимЗаписиДокумента.Проведение)
        print(f"  [OK] перепроведён")
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        print(f"  [FAIL] {info[2] if info else e}")

print("\n=== Проверка остатка пустых Подр в РНДС.Наличные за декабрь ===")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273"))
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Н.Регистратор) КАК Док,
    ПРЕДСТАВЛЕНИЕ(Н.Касса) КАК Касса,
    Н.ВидДвижения КАК ВидДв,
    СУММА(Н.Сумма) КАК Сумма
ИЗ РегистрНакопления.ДенежныеСредстваНаличные КАК Н
ГДЕ Н.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2025,12,15),МЕСЯЦ)
    И Н.Организация = &Орг
    И Н.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
СГРУППИРОВАТЬ ПО Н.Регистратор, Н.Касса, Н.ВидДвижения
"""
r = q.Выполнить().Выгрузить()
print(f"Осталось строк с (пусто) в РНДС.Налич за декабрь: {r.Количество()}")
for i in range(r.Количество()):
    rec = r.Получить(i)
    print(f"  {str(rec.Док)[:60]:<62}  {str(rec.Касса)[:30]:<32}  {S(rec.ВидДв):<8}  {money(rec.Сумма)}")
