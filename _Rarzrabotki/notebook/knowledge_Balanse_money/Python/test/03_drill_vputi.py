# -*- coding: utf-8 -*-
"""
СКРИПТ 03 — Drill: «Денежные средства в пути» (РН.ДенежныеСредстваВПути)

⚠️ КРИТИЧЕСКАЯ АРХИТЕКТУРНАЯ ДЕТАЛЬ:
   В регистре ДенежныеСредстваВПути НЕТ измерения Подразделение!
   Измерения: Организация, ВидПереводаДенежныхСредств, Получатель, Отправитель, Контрагент, Валюта.

   Поэтому Свод_ДенежныеСредства не может его агрегировать по Подразделению напрямую —
   нужно через Получатель.Подразделение / Отправитель.Подразделение (реквизиты).

   Этот скрипт показывает per (ВидПеревода, Получатель, Отправитель, Контрагент).

ARGV: <YYYY-MM>  (например 2025-12)
Артефакт: _artifacts/03_vputi_drill_<месяц>.csv
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, save_csv

if len(sys.argv) < 2:
    print("Usage: python 03_drill_vputi.py <YYYY-MM>"); sys.exit(1)
y, m = map(int, sys.argv[1].split("-"))
end_y = y if m < 12 else y + 1
end_m = m + 1 if m < 12 else 1

erp = connect_erp()
refs = get_refs(erp)
S = erp.String

print("=" * 110)
print(f"СКРИПТ 03 — Drill ДенежныеСредстваВПути за {sys.argv[1]}")
print("    ⚠ В этом регистре НЕТ Подразделения как измерения!")
print("=" * 110)

# === ОстаткиИОбороты per (ВидПеревода, Получатель, Отправитель, Контрагент, Валюта) ===
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", refs["Орг"])
q.Текст = f"""
ВЫБРАТЬ
    Вп.ВидПереводаДенежныхСредств КАК ВидПеревода,
    Вп.Получатель КАК Получатель,
    Вп.Отправитель КАК Отправитель,
    Вп.Контрагент КАК Контрагент,
    Вп.Валюта КАК Валюта,
    СУММА(Вп.СуммаНачальныйОстаток) КАК НО,
    СУММА(Вп.СуммаПриход) КАК Приход,
    СУММА(Вп.СуммаРасход) КАК Расход,
    СУММА(Вп.СуммаКонечныйОстаток) КАК КМ
ИЗ РегистрНакопления.ДенежныеСредстваВПути.ОстаткиИОбороты(
    ДАТАВРЕМЯ({y},{m},1,0,0,0), КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ), , , Организация = &Орг) КАК Вп
СГРУППИРОВАТЬ ПО Вп.ВидПереводаДенежныхСредств, Вп.Получатель, Вп.Отправитель, Вп.Контрагент, Вп.Валюта
ИМЕЮЩИЕ СУММА(Вп.СуммаКонечныйОстаток) <> 0 ИЛИ СУММА(Вп.СуммаНачальныйОстаток) <> 0
УПОРЯДОЧИТЬ ПО КМ
"""
r = q.Выполнить().Выгрузить()
print(f"\nДвижений в ДС.ВПути: {r.Количество()}")

print(f"\n{'ВидПер':<25}{'Получатель':<30}{'Отправитель':<30}{'Контрагент':<25}{'Вал':<6}{'НО':>14}{'Приход':>14}{'Расход':>14}{'КМ':>14}")
print("-" * 172)
rows = []
total_no = total_pr = total_rs = total_km = 0.0
for i in range(r.Количество()):
    rec = r.Получить(i)
    vid = str(S(rec.ВидПеревода) or "")
    pol = str(S(rec.Получатель) or "")
    otp = str(S(rec.Отправитель) or "")
    kontr = str(S(rec.Контрагент) or "")
    val = str(S(rec.Валюта) or "")
    no = float(rec.НО or 0); pr = float(rec.Приход or 0); rs = float(rec.Расход or 0); km = float(rec.КМ or 0)
    total_no += no; total_pr += pr; total_rs += rs; total_km += km
    print(f"{vid[:23]:<25}{pol[:28]:<30}{otp[:28]:<30}{kontr[:23]:<25}{val[:4]:<6}"
          f"{money(no):>14}{money(pr):>14}{money(rs):>14}{money(km):>14}")
    rows.append({"ВидПеревода": vid, "Получатель": pol, "Отправитель": otp,
                 "Контрагент": kontr, "Валюта": val,
                 "НО": no, "Приход": pr, "Расход": rs, "КМ": km})
print("-" * 172)
print(f"{'ИТОГО':<116}{money(total_no):>14}{money(total_pr):>14}{money(total_rs):>14}{money(total_km):>14}")

save_csv(f"03_vputi_drill_{sys.argv[1]}", rows,
         ["ВидПеревода", "Получатель", "Отправитель", "Контрагент", "Валюта", "НО", "Приход", "Расход", "КМ"])

# === Сверка с ПАП.ВПути за период ===
print("\n\n--- Сверка с ПАП per Подр (источник = Денежные средства в пути) ---")
q.УстановитьПараметр("ИВ", refs["Ист_ВПути"])
q.Текст = f"""
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
    СУММА(ВЫБОР КОГДА Т.Период < ДАТАВРЕМЯ({y},{m},1,0,0,0)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                    ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_НО,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК ПАП_КМ
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг
    И Т.Период <= КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ)
    И Т.Источник = &ИВ
СГРУППИРОВАТЬ ПО Т.Подразделение
УПОРЯДОЧИТЬ ПО ПАП_КМ
"""
r = q.Выполнить().Выгрузить()
print(f"\nПодразделений в ПАП с записями ВПути: {r.Количество()}")
print(f"{'Подразделение':<45}{'ПАП_НО':>16}{'ПАП_КМ':>16}")
print("-" * 77)
pap_total_no = pap_total_km = 0
for i in range(r.Количество()):
    rec = r.Получить(i)
    podr = str(rec.Подр or "(пусто)")
    no = float(rec.ПАП_НО or 0); km = float(rec.ПАП_КМ or 0)
    pap_total_no += no; pap_total_km += km
    print(f"{podr[:43]:<45}{money(no):>16}{money(km):>16}")
print("-" * 77)
print(f"{'ИТОГО ПАП':<45}{money(pap_total_no):>16}{money(pap_total_km):>16}")
print(f"{'ИТОГО Регистр.ВПути (без Подр)':<45}{money(total_no):>16}{money(total_km):>16}")
print(f"{'Δ (ПАП - Регистр)':<45}{money(pap_total_no - total_no):>16}{money(pap_total_km - total_km):>16}")
print(f"\n   ⚠ Если Δ ≠ 0 — это плуги Расхождение=Истина в А_ОтчётБаланс_Свод (по статье 'Денежные средства в пути')")
print(f"\nАртефакт: 03_vputi_drill_{sys.argv[1]}.csv")
