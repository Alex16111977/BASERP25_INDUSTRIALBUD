# -*- coding: utf-8 -*-
"""
СКРИПТ 04 — Drill безналичных per (Подр, БанковскийСчет) — зеркало штатной Ведомости

Объясняет зеркальные суммы ЦО (−19,2 М) vs (пусто) (+19,2 М):
если один и тот же БанковскийСчет числится с разным Подразделением в ПАП vs РНДС.Безнал —
получаем плуги.

ARGV: <YYYY-MM>

Артефакт: _artifacts/04_beznal_<месяц>.csv
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, save_csv

if len(sys.argv) < 2:
    print("Usage: python 04_drill_beznal_per_bs.py <YYYY-MM>"); sys.exit(1)
y, m = map(int, sys.argv[1].split("-"))
end_y = y if m < 12 else y + 1
end_m = m + 1 if m < 12 else 1

erp = connect_erp()
refs = get_refs(erp)
S = erp.String

print("=" * 110)
print(f"СКРИПТ 04 — Безналичные per (Подр, БанкСчет) за {sys.argv[1]}")
print("=" * 110)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", refs["Орг"])
q.Текст = f"""
ВЫБРАТЬ
    ЕСТЬNULL(Б.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
    Б.БанковскийСчет КАК БС,
    СУММА(Б.СуммаНачальныйОстаток) КАК НО,
    СУММА(Б.СуммаПриход) КАК Приход,
    СУММА(Б.СуммаРасход) КАК Расход,
    СУММА(Б.СуммаКонечныйОстаток) КАК КМ
ИЗ РегистрНакопления.ДенежныеСредстваБезналичные.ОстаткиИОбороты(
    ДАТАВРЕМЯ({y},{m},1,0,0,0), КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ), , , Организация = &Орг) КАК Б
СГРУППИРОВАТЬ ПО ЕСТЬNULL(Б.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)), Б.БанковскийСчет
ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток) <> 0 ИЛИ СУММА(Б.СуммаНачальныйОстаток) <> 0
УПОРЯДОЧИТЬ ПО Подр, КМ УБЫВ
"""
r = q.Выполнить().Выгрузить()
print(f"\nСтрок: {r.Количество()}")

print(f"\n{'Подр':<25}{'БанкСчет':<55}{'НО':>15}{'Приход':>15}{'Расход':>15}{'КМ':>15}")
print("-" * 140)
rows = []
for i in range(r.Количество()):
    rec = r.Получить(i)
    podr = str(S(rec.Подр) or "(пусто)")
    bs = str(S(rec.БС) or "")
    no = float(rec.НО or 0); pr = float(rec.Приход or 0); rs = float(rec.Расход or 0); km = float(rec.КМ or 0)
    print(f"{podr[:23]:<25}{bs[:53]:<55}{money(no):>15}{money(pr):>15}{money(rs):>15}{money(km):>15}")
    rows.append({"Подр": podr, "БанкСчет": bs, "НО": no, "Приход": pr, "Расход": rs, "КМ": km})

save_csv(f"04_beznal_{sys.argv[1]}", rows, ["Подр", "БанкСчет", "НО", "Приход", "Расход", "КМ"])

# Pivot: тот же БС в разных Подр?
print("\n--- Поиск задвоения: БанкСчет числится в нескольких Подр ---")
by_bs = {}
for r in rows:
    by_bs.setdefault(r["БанкСчет"], []).append(r)
for bs, lst in by_bs.items():
    if len(lst) > 1:
        print(f"  БС: {bs}")
        for x in lst:
            print(f"     Подр={x['Подр'][:30]:<32}  КМ={money(x['КМ']):>15}")
print(f"\nАртефакт: 04_beznal_{sys.argv[1]}.csv")
