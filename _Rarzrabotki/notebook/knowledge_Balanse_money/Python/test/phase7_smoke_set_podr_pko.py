# -*- coding: utf-8 -*-
"""
Phase 7 SMOKE — Установить Подразделение в шапке ПКО + перепровести (1 документ).

Берём ПКО 000Ц-000003 (Касса Подгорцы, Сумма 573 512) — самый чистый кейс.
Касса.Подразделение = КГ "Подгорцы" — устанавливаем в шапку.

После — проверяем что РНДС.Наличные теперь с КГ "Подгорцы" вместо (пусто).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money, find_doc_by_number

erp = connect_erp()
S = erp.String

ref = find_doc_by_number(erp, "ПриходныйКассовыйОрдер", "000Ц-000003")
if ref is None:
    print("ПКО не найден"); sys.exit(1)

print(f"Документ: {S(ref)}")
obj = ref.ПолучитьОбъект()
print(f"До: Подразделение = {S(obj.Подразделение) if erp.ЗначениеЗаполнено(obj.Подразделение) else '(пусто)'}")

# Получить Подразделение из Кассы
kassa = obj.Касса
print(f"Касса: {S(kassa)}")
podr_target = kassa.Подразделение
print(f"Касса.Подразделение: {S(podr_target) if erp.ЗначениеЗаполнено(podr_target) else '(пусто)'}")

if not erp.ЗначениеЗаполнено(podr_target):
    print("[FAIL] У Кассы нет Подразделения — сценарий неприменим")
    sys.exit(2)

# Backup значения для rollback
old_podr = obj.Подразделение

# Установить и записать
obj.Подразделение = podr_target
try:
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("[OK] ПКО перепроведён с новым Подразделением")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print(f"[FAIL] {info[2] if info else e}")
    sys.exit(3)

# Проверить РНДС.Налич
print("\nПроверка движений РНДС.Наличные после перепроведения:")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Док", ref)
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Н.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Н.Касса) КАК Касса,
    Н.ВидДвижения КАК ВидДв,
    СУММА(Н.Сумма) КАК Сумма
ИЗ РегистрНакопления.ДенежныеСредстваНаличные КАК Н
ГДЕ Н.Регистратор = &Док
СГРУППИРОВАТЬ ПО Н.Подразделение, Н.Касса, Н.ВидДвижения
"""
r = q.Выполнить().Выгрузить()
for i in range(r.Количество()):
    rec = r.Получить(i)
    print(f"  Подр={str(rec.Подр or '(пусто)')[:25]:<27}  Касса={str(rec.Касса)[:35]:<37}  {S(rec.ВидДв):<8}  Σ={money(rec.Сумма)}")

# Проверить ПАП
print("\nПроверка движений ПАП после перепроведения:")
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    Т.ВидДвижения КАК ВидДв,
    СУММА(Т.Сумма) КАК Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор = &Док
СГРУППИРОВАТЬ ПО Т.Подразделение, Т.Статья, Т.ВидДвижения
"""
r = q.Выполнить().Выгрузить()
for i in range(r.Количество()):
    rec = r.Получить(i)
    print(f"  Подр={str(rec.Подр or '(пусто)')[:25]:<27}  Статья={str(rec.Статья)[:30]:<32}  {S(rec.ВидДв):<8}  Σ={money(rec.Сумма)}")
