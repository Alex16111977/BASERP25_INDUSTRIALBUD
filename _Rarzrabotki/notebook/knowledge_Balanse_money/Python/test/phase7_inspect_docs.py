"""
Phase 7 — Inspect 15 виновных документов:
- Какое Подразделение в шапке
- Какие движения создаёт в ПАП (с каким Подр)
- Какие движения создаёт в РНДС (с каким Подр)
- Сравнение
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, money, find_doc_by_number

erp = connect_erp()
S = erp.String

DOCS_SPIS = [
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000284"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000211"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000212"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000213"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000214"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000215"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000216"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000281"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000268"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000186"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000187"),
]
DOCS_PKO = [
    ("ПриходныйКассовыйОрдер", "000Ц-000001"),
    ("ПриходныйКассовыйОрдер", "000Ц-000002"),
    ("ПриходныйКассовыйОрдер", "000Ц-000003"),
    ("ПриходныйКассовыйОрдер", "N0000023706"),
]

def inspect(doc_type, number):
    ref = find_doc_by_number(erp, doc_type, number)
    if ref is None:
        print(f"[!] {doc_type} {number} НЕ найден")
        return
    obj = ref.ПолучитьОбъект()
    print(f"\n=== {S(ref)} ===")
    # Реквизиты-аналитики
    for fld in ("Подразделение", "БанковскийСчет", "Касса", "ХозяйственнаяОперация",
                "Партнер", "Контрагент", "Получатель", "А_Обработан",
                "А_ОбработанКазна", "А_ВведенВЕРП"):
        try:
            v = getattr(obj, fld)
            if v is None:
                continue
            if isinstance(v, (str, int, float, bool)):
                print(f"  {fld}: {v}")
            else:
                try:
                    print(f"  {fld}: {S(v) if erp.ЗначениеЗаполнено(v) else '(пусто)'}")
                except:
                    print(f"  {fld}: <obj>")
        except: pass
    # Проводки в ПАП (per Подр)
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Док", ref)
    q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    ПРЕДСТАВЛЕНИЕ(Т.Источник) КАК Источник,
    Т.ВидДвижения КАК ВидДв,
    СУММА(Т.Сумма) КАК Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор = &Док
СГРУППИРОВАТЬ ПО Т.Подразделение, Т.Статья, Т.Источник, Т.ВидДвижения
"""
    r = q.Выполнить().Выгрузить()
    print(f"  ПАП движений: {r.Количество()}")
    for i in range(r.Количество()):
        rec = r.Получить(i)
        print(f"    Подр={str(rec.Подр or '(пусто)')[:25]:<27}  Статья={str(rec.Статья)[:30]:<32}  Ист={str(rec.Источник)[:30]:<32}  {S(rec.ВидДв):<8}  Σ={money(rec.Сумма)}")

    # Проводки в РНДС.Безнал (per Подр)
    q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Б.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Б.БанковскийСчет) КАК БС,
    Б.ВидДвижения КАК ВидДв,
    СУММА(Б.Сумма) КАК Сумма
ИЗ РегистрНакопления.ДенежныеСредстваБезналичные КАК Б
ГДЕ Б.Регистратор = &Док
СГРУППИРОВАТЬ ПО Б.Подразделение, Б.БанковскийСчет, Б.ВидДвижения
"""
    r = q.Выполнить().Выгрузить()
    print(f"  РНДС.Безнал движений: {r.Количество()}")
    for i in range(r.Количество()):
        rec = r.Получить(i)
        print(f"    Подр={str(rec.Подр or '(пусто)')[:25]:<27}  БС={str(rec.БС)[:35]:<37}  {S(rec.ВидДв):<8}  Σ={money(rec.Сумма)}")

    # Наличные тоже
    q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Н.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Н.Касса) КАК Касса,
    Н.ВидДвижения КАК ВидДв,
    СУММА(Н.Сумма) КАК Сумма
ИЗ РегистрНакопления.ДенежныеСредстваНаличные КАК Н
ГДЕ Н.Регистратор = &Док
СГРУППИРОВАТЬ ПО Н.Подразделение, Н.Касса, Н.ВидДвижения
"""
    r = q.Выполнить().Выгрузить()
    if r.Количество() > 0:
        print(f"  РНДС.Налич движений: {r.Количество()}")
        for i in range(r.Количество()):
            rec = r.Получить(i)
            print(f"    Подр={str(rec.Подр or '(пусто)')[:25]:<27}  Касса={str(rec.Касса)[:35]:<37}  {S(rec.ВидДв):<8}  Σ={money(rec.Сумма)}")

print("=" * 110)
print("Phase 7 — Inspect 15 виновных документов")
print("=" * 110)

print("\n### СПИСАНИЯ БЕЗНАЛИЧНЫХ (главный виновник 000Ц-000284) ###")
for tp, num in DOCS_SPIS:
    inspect(tp, num)

print("\n\n### ПКО (наличные) ###")
for tp, num in DOCS_PKO:
    inspect(tp, num)
