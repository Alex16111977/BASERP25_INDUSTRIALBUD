# -*- coding: utf-8 -*-
"""
Phase 7 — Drill: найти конкретные документы которые пишут в РНДС.Безнал/Налич
с Подразделением=ПустаяСсылка для декабря 2025.

Гипотеза: в РНДС.Подразделение проводка пишется с пустым Подр (хотя в ПАП —
с реальным), что даёт зеркальный плуг.

Артефакт: _artifacts/phase7_empty_podr_docs_<YYYY-MM>.csv
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
from _common import connect_erp, get_refs, money, save_csv, get_type_name

if len(sys.argv) < 2:
    print("Usage: python phase7_drill_empty_podr_docs.py <YYYY-MM>"); sys.exit(1)
y, m = map(int, sys.argv[1].split("-"))

erp = connect_erp()
refs = get_refs(erp)
S = erp.String

print("=" * 110)
print(f"Phase 7 — Drill документов с Подр=пусто в РНДС.Безнал/Налич за {sys.argv[1]}")
print("=" * 110)

# === БЕЗНАЛИЧНЫЕ ===
print("\n[A] БЕЗНАЛИЧНЫЕ: документы с Подразделение=ПустаяСсылка")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", refs["Орг"])
q.Текст = f"""
ВЫБРАТЬ
    Б.Регистратор КАК Док,
    ПРЕДСТАВЛЕНИЕ(Б.Регистратор) КАК ДокИмя,
    Б.БанковскийСчет КАК БС,
    ПРЕДСТАВЛЕНИЕ(Б.БанковскийСчет) КАК БСИмя,
    Б.ВидДвижения КАК ВидДв,
    СУММА(Б.Сумма) КАК Сумма,
    МАКСИМУМ(Б.Период) КАК Период
ИЗ РегистрНакопления.ДенежныеСредстваБезналичные КАК Б
ГДЕ Б.Период МЕЖДУ ДАТАВРЕМЯ({y},{m},1,0,0,0) И КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ)
    И Б.Организация = &Орг
    И Б.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
СГРУППИРОВАТЬ ПО Б.Регистратор, ПРЕДСТАВЛЕНИЕ(Б.Регистратор), Б.БанковскийСчет, ПРЕДСТАВЛЕНИЕ(Б.БанковскийСчет), Б.ВидДвижения
УПОРЯДОЧИТЬ ПО Период
"""
r = q.Выполнить().Выгрузить()
print(f"  Строк: {r.Количество()}")

rows_b = []
total_b = 0.0
print(f"\n  {'Док':<70}{'БС':<30}{'ВидДв':<8}{'Сумма':>16}")
print("  " + "-" * 124)
for i in range(r.Количество()):
    rec = r.Получить(i)
    vd = S(rec.ВидДв)
    s = float(rec.Сумма or 0)
    signed = s if vd == "Приход" else -s
    total_b += signed
    print(f"  {str(rec.ДокИмя)[:68]:<70}{str(rec.БСИмя)[:28]:<30}{vd[:6]:<8}{money(signed):>16}")
    rows_b.append({"Док": str(rec.ДокИмя), "БС": str(rec.БСИмя), "ВидДв": vd,
                   "Сумма": s, "Signed": signed, "Период": str(rec.Период)[:19],
                   "ТипДок": get_type_name(erp, rec.Док)})
print("  " + "-" * 124)
print(f"  ИТОГО (signed) Безнал пустое Подр за декабрь: {money(total_b)}")

# Группировка по типу документа
типы_b = {}
for r in rows_b:
    типы_b.setdefault(r["ТипДок"], {"кол": 0, "Σ": 0.0})
    типы_b[r["ТипДок"]]["кол"] += 1
    типы_b[r["ТипДок"]]["Σ"] += r["Signed"]
print("\n  По ТипДок (Безнал пустое):")
for t, v in sorted(типы_b.items(), key=lambda x: -abs(x[1]["Σ"])):
    print(f"    {t:<50} {v['кол']:>4}  Σ={money(v['Σ']):>16}")

# === НАЛИЧНЫЕ ===
print("\n\n[B] НАЛИЧНЫЕ: документы с Подразделение=ПустаяСсылка")
q.Текст = f"""
ВЫБРАТЬ
    Н.Регистратор КАК Док,
    ПРЕДСТАВЛЕНИЕ(Н.Регистратор) КАК ДокИмя,
    Н.Касса КАК Касса,
    ПРЕДСТАВЛЕНИЕ(Н.Касса) КАК КассаИмя,
    Н.ВидДвижения КАК ВидДв,
    СУММА(Н.Сумма) КАК Сумма,
    МАКСИМУМ(Н.Период) КАК Период
ИЗ РегистрНакопления.ДенежныеСредстваНаличные КАК Н
ГДЕ Н.Период МЕЖДУ ДАТАВРЕМЯ({y},{m},1,0,0,0) И КОНЕЦПЕРИОДА(ДАТАВРЕМЯ({y},{m},15),МЕСЯЦ)
    И Н.Организация = &Орг
    И Н.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
СГРУППИРОВАТЬ ПО Н.Регистратор, ПРЕДСТАВЛЕНИЕ(Н.Регистратор), Н.Касса, ПРЕДСТАВЛЕНИЕ(Н.Касса), Н.ВидДвижения
УПОРЯДОЧИТЬ ПО Период
"""
r = q.Выполнить().Выгрузить()
print(f"  Строк: {r.Количество()}")

rows_n = []
total_n = 0.0
print(f"\n  {'Док':<70}{'Касса':<30}{'ВидДв':<8}{'Сумма':>16}")
print("  " + "-" * 124)
for i in range(r.Количество()):
    rec = r.Получить(i)
    vd = S(rec.ВидДв)
    s = float(rec.Сумма or 0)
    signed = s if vd == "Приход" else -s
    total_n += signed
    print(f"  {str(rec.ДокИмя)[:68]:<70}{str(rec.КассаИмя)[:28]:<30}{vd[:6]:<8}{money(signed):>16}")
    rows_n.append({"Док": str(rec.ДокИмя), "Касса": str(rec.КассаИмя), "ВидДв": vd,
                   "Сумма": s, "Signed": signed, "Период": str(rec.Период)[:19],
                   "ТипДок": get_type_name(erp, rec.Док)})
print("  " + "-" * 124)
print(f"  ИТОГО (signed) Налич пустое Подр за декабрь: {money(total_n)}")

типы_n = {}
for r in rows_n:
    типы_n.setdefault(r["ТипДок"], {"кол": 0, "Σ": 0.0})
    типы_n[r["ТипДок"]]["кол"] += 1
    типы_n[r["ТипДок"]]["Σ"] += r["Signed"]
print("\n  По ТипДок (Налич пустое):")
for t, v in sorted(типы_n.items(), key=lambda x: -abs(x[1]["Σ"])):
    print(f"    {t:<50} {v['кол']:>4}  Σ={money(v['Σ']):>16}")

save_csv(f"phase7_empty_podr_beznal_{sys.argv[1]}", rows_b,
         ["Период", "Док", "ТипДок", "БС", "ВидДв", "Сумма", "Signed"])
save_csv(f"phase7_empty_podr_nalich_{sys.argv[1]}", rows_n,
         ["Период", "Док", "ТипДок", "Касса", "ВидДв", "Сумма", "Signed"])
print(f"\nАртефакты: phase7_empty_podr_{{beznal,nalich}}_{sys.argv[1]}.csv")
