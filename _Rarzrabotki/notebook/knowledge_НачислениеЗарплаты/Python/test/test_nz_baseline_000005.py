    gross = s['bukh'] + s['fss']
    flags = []
    if s['nz_minrow'] < -0.005:
        flags.append("НЕГ-ОКЛАД")
    if s['fss'] > 0.005 and s['upr'] < 0.005:
        # чисто-больничний (за рах. фондів, без упр) — НЗоклад має = bukhGROSS, а не плуг
        if abs(s['nz_oklad'] - gross) > 0.02:
            flags.append("ЧБОЛ≠GROSS")
    if s['upr'] < 0.005 and s['kazna_nach'] < -0.005:
        flags.append("KAZNA<0")
    mark = ("  <-- " + ",".join(flags)) if flags else ""
    print(f"{s['name'][:32]:32s} {s['upr']:9.2f} {s['kazna_nach']:9.2f} {s['bukh']:9.2f} {s['fss']:8.2f} {gross:10.2f} {s['nz_oklad']:9.2f} {s['nz_shtraf']:8.2f} {s['nz_minrow']:8.2f}{mark}")
    if flags:
        ANOM.append((s, flags))

