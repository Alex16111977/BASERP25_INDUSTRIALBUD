# ---------- 2. Агрегати родителя по ФЛ ----------
D = {}  # key -> dict


def slot(k, nm):
    if k not in D:
        D[k] = dict(name=nm, upr=0.0, kazna_sum=0.0, kazna_nach=0.0, bukh=0.0, fss=0.0,
                    ndfl=0.0, nz_oklad=0.0, nz_shtraf=0.0, nz_negrows=0, nz_minrow=0.0,
                    nz_ndfl=0.0, nz_vznos=0.0, kdept={}, bvids={})
    return D[k]


