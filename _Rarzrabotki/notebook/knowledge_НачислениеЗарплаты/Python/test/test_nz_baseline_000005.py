erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
X = erp.XMLСтрока
Z = erp.ЗначениеЗаполнено


def num(x):
    return float(S(x).replace('\xa0', '').replace(' ', '').replace(',', '.') or "0")


def key(ref):
    if not Z(ref):
        return None
    return X(ref)


def run(text, **params):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, vv in params.items():
        q.SetParameter(k, vv)
    return q.Execute().Выгрузить()


# ---------- 1. Знайти родителя, дочку НЗ, ОЗФУ ----------
