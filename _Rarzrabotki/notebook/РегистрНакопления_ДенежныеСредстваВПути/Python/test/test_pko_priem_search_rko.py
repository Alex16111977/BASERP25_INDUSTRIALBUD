"""
Rule #-1 валидация: детерминированный поиск ПАРНОГО РКО для ПКО
ХозОп = ПоступлениеДенежныхСредствИзДругойКассы.

Цель — заполнить реквизиты ПКО:
  - А_ДокРасходныйКассовыйОрдерПередачиДенег = найденный РКО
  - А_ПодразделениеОтправитель = РКО.Подразделение

Критерии РКО (отправитель):
  РКО.Проведен
  И РКО.ХозяйственнаяОперация = ВыдачаДенежныхСредствВДругуюКассу
  И РКО.Организация    = ПКО.Организация
  И РКО.КассаПолучатель = ПКО.Касса
  И РКО.СуммаДокумента = ПКО.СуммаДокумента
  И РКО.Валюта         = ПКО.Валюта
  [если ПКО.КассаОтправитель заполнен -> доп. РКО.Касса = ПКО.КассаОтправитель]
Дизамбигуация: ПЕРВЫЕ 1, ближайший Дата<=ПКО.Дата, УПОРЯДОЧИТЬ ПО Дата УБЫВ.
"""
import win32com.client
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def com_err(e):
    info = getattr(e, 'excepinfo', None)
    return info[2] if info else str(e)


def наим(ссылка):
    """Наименование ссылки (str() от COM-ссылки даёт '<COMObject>')."""
    if not erp.ЗначениеЗаполнено(ссылка):
        return "<пусто>"
    try:
        return str(ссылка.Наименование)
    except Exception:
        return str(erp.XMLСтрока(ссылка))


# Текст запроса поиска парного РКО (1:1 как пойдёт в BSL).
# Параметры шапки ПКО передаём явными &-параметрами (а не подзапросом по Ссылке),
# чтобы запрос был переносим в проведение, где данные шапки уже на руках.
ТЕКСТ_ПОИСКА_РКО = """
ВЫБРАТЬ ПЕРВЫЕ 1
	РКО.Ссылка                КАК Ссылка,
	РКО.Номер                 КАК Номер,
	РКО.Дата                  КАК Дата,
	РКО.Подразделение         КАК Подразделение,
	РКО.Касса                 КАК Касса,
	РКО.КассаПолучатель       КАК КассаПолучатель,
	РКО.СуммаДокумента        КАК СуммаДокумента
ИЗ
	Документ.РасходныйКассовыйОрдер КАК РКО
ГДЕ
	РКО.Проведен
	И РКО.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыдачаДенежныхСредствВДругуюКассу)
	И РКО.Организация = &Организация
	И РКО.КассаПолучатель = &Касса
	И РКО.СуммаДокумента = &СуммаДокумента
	И РКО.Валюта = &Валюта
	И (НЕ &ОтправительЗаполнен ИЛИ РКО.Касса = &КассаОтправитель)
	И РКО.Дата <= &ДатаПКО
УПОРЯДОЧИТЬ ПО
	РКО.Дата УБЫВ
"""

# Версия запроса для подсчёта ВСЕХ кандидатов (без ПЕРВЫЕ 1) — для статистики 0/1/>1.
ТЕКСТ_СЧЕТЧИК_РКО = """
ВЫБРАТЬ
	КОЛИЧЕСТВО(РКО.Ссылка) КАК Кво
ИЗ
	Документ.РасходныйКассовыйОрдер КАК РКО
ГДЕ
	РКО.Проведен
	И РКО.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыдачаДенежныхСредствВДругуюКассу)
	И РКО.Организация = &Организация
	И РКО.КассаПолучатель = &Касса
	И РКО.СуммаДокумента = &СуммаДокумента
	И РКО.Валюта = &Валюта
	И (НЕ &ОтправительЗаполнен ИЛИ РКО.Касса = &КассаОтправитель)
	И РКО.Дата <= &ДатаПКО
"""


def установить_параметры(q, докПКО):
    """Заполняет &-параметры запроса из шапки ПКО."""
    касса_отпр = докПКО.КассаОтправитель
    отпр_заполнен = erp.ЗначениеЗаполнено(касса_отпр)
    q.УстановитьПараметр("Организация", докПКО.Организация)
    q.УстановитьПараметр("Касса", докПКО.Касса)
    q.УстановитьПараметр("СуммаДокумента", докПКО.СуммаДокумента)
    q.УстановитьПараметр("Валюта", докПКО.Валюта)
    q.УстановитьПараметр("ОтправительЗаполнен", отпр_заполнен)
    q.УстановитьПараметр("КассаОтправитель", касса_отпр)
    q.УстановитьПараметр("ДатаПКО", докПКО.Дата)


def найти_рко(докПКО):
    """Возвращает (ссылкаРКО|None, число_кандидатов)."""
    # число кандидатов
    qc = erp.NewObject("Запрос")
    qc.Text = ТЕКСТ_СЧЕТЧИК_РКО
    установить_параметры(qc, докПКО)
    кво = qc.Execute().Выгрузить()
    n = int(кво.Получить(0).Кво) if кво.Количество() > 0 else 0

    # ближайший по времени РКО
    q = erp.NewObject("Запрос")
    q.Text = ТЕКСТ_ПОИСКА_РКО
    установить_параметры(q, докПКО)
    res = q.Execute().Выгрузить()
    if res.Количество() > 0:
        return res.Получить(0), n
    return None, n


