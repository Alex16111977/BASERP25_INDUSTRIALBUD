    print(f"  Уникальных (ровно 1 РКО):   {cnt1}")
    print(f"  Пусто (0 РКО):              {cnt0}")
    print(f"  Множественных (>1 РКО):     {cntM}  <- риск ложных пар")
    if примеры_множ:
        print("\n  Первые 5 множественных (номер ПКО, дата, число кандидатов):")
