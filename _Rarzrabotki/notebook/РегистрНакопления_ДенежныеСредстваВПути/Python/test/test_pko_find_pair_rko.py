# -*- coding: utf-8 -*-
"""
Rule #-1 pre-test: запрос поиска парного РКО для ПКО "Поступление из другой кассы".
Эталон: ПКО N0000023550 -> РКО N0000052985, А_ПодразделениеОтправитель=Строительство.
1:1 как будет в BSL ObjectModule.А_ЗаполнитьПодразделениеОтправителяПоРКО().
"""
from _common import connect_erp

erp = connect_erp()

# --- найдём эталонный ПКО N0000023550 ---
qPKO = erp.NewObject("Запрос")
qPKO.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    ПКО.Ссылка КАК Ссылка,
    ПКО.Дата КАК Дата,
    ПКО.Организация КАК Организация,
    ПКО.Касса КАК Касса,
    ПКО.КассаОтправитель КАК КассаОтправитель,
    ПКО.СуммаДокумента КАК СуммаДокумента,
    ПКО.Валюта КАК Валюта,
    ПКО.ХозяйственнаяОперация КАК ХозОп,
    ПКО.А_ПодразделениеОтправитель КАК А_ПодразделениеОтправитель,
    ПКО.А_ДокРасходныйКассовыйОрдерПередачиДенег КАК А_ДокРКО
ИЗ Документ.ПриходныйКассовыйОрдер КАК ПКО
ГДЕ ПКО.Номер = &Номер
"""
qPKO.SetParameter("Номер", "N0000023550")
try:
    selPKO = qPKO.Execute().Выбрать()
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL PKO lookup:", info[2] if info else e); raise SystemExit

if not selPKO.Следующий():
    print("ПКО N0000023550 не найден"); raise SystemExit

pko_ref = selPKO.Ссылка
print("=== ЭТАЛОН ПКО N0000023550 ===")
print("Дата:", selPKO.Дата)
print("Организация:", erp.String(selPKO.Организация))
print("Касса:", erp.String(selPKO.Касса))
print("КассаОтправитель заполнена:", erp.ЗначениеЗаполнено(selPKO.КассаОтправитель),
      "|", erp.String(selPKO.КассаОтправитель))
print("СуммаДокумента:", selPKO.СуммаДокумента)
print("Валюта:", erp.String(selPKO.Валюта))
print("ХозОп:", erp.XMLСтрока(selPKO.ХозОп))
print("Текущ. А_ПодразделениеОтправитель:", erp.String(selPKO.А_ПодразделениеОтправитель))
print("Текущ. А_ДокРКО:", erp.String(selPKO.А_ДокРКО))

# ============================================================
# ОСНОВНОЙ ЗАПРОС (как в BSL) — поиск парного РКО
# ============================================================
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    РКО.Ссылка        КАК Ссылка,
    РКО.Подразделение КАК Подразделение,
    РКО.Дата          КАК Дата,
    РКО.Номер         КАК Номер
ИЗ
    Документ.РасходныйКассовыйОрдер КАК РКО
ГДЕ
    РКО.Проведен = ИСТИНА
    И РКО.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыдачаДенежныхСредствВДругуюКассу)
    И РКО.Организация = &Организация
    И РКО.КассаПолучатель = &КассаПолучатель
    И РКО.СуммаДокумента = &СуммаДокумента
    И РКО.Валюта = &Валюта
    И РКО.Дата <= &Дата
    {ДОППараметрКассы}
УПОРЯДОЧИТЬ ПО
    РКО.Дата УБЫВ
"""
# доп. условие по кассе-отправителю, если у ПКО заполнена КассаОтправитель
доп_касса = erp.ЗначениеЗаполнено(selPKO.КассаОтправитель)
if доп_касса:
    q.Text = q.Text.replace("{ДОППараметрКассы}", "И РКО.Касса = &КассаОтправитель")
else:
    q.Text = q.Text.replace("{ДОППараметрКассы}", "")

q.SetParameter("Организация", selPKO.Организация)
q.SetParameter("КассаПолучатель", selPKO.Касса)        # касса ПКО = КассаПолучатель РКО
q.SetParameter("СуммаДокумента", selPKO.СуммаДокумента)
q.SetParameter("Валюта", selPKO.Валюта)
q.SetParameter("Дата", selPKO.Дата)
if доп_касса:
    q.SetParameter("КассаОтправитель", selPKO.КассаОтправитель)

print("\n=== ПОИСК ПАРНОГО РКО (доп.касса =", доп_касса, ") ===")
try:
    рез = q.Execute()
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL RKO query:", info[2] if info else e); raise SystemExit

выб = рез.Выбрать()
n = 0
найден_подр = None
найден_ссылка = None
while выб.Следующий():
    n += 1
    найден_подр = выб.Подразделение
    найден_ссылка = выб.Ссылка
    print(f"  РКО Номер={выб.Номер} Дата={выб.Дата} Подразделение={erp.String(выб.Подразделение)}")

print("Найдено строк (ПЕРВЫЕ 1):", n)
if n == 1:
    print("РЕЗУЛЬТАТ: А_ДокРКО =", erp.String(найден_ссылка))
    print("РЕЗУЛЬТАТ: А_ПодразделениеОтправитель =", erp.String(найден_подр))
    ok = (erp.String(найден_подр) == "Строительство")
    print("VERIFY Подразделение == 'Строительство':", "PASS" if ok else "FAIL")
else:
    print("Не заполнять (0 или >1 совпадений) — гард сработал бы.")
