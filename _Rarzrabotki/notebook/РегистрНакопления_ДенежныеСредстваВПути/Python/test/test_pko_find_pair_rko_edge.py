# -*- coding: utf-8 -*-
"""
Edge-case проверка: сколько РКО-кандидатов БЕЗ фильтра по КассаОтправитель
(на случай если у ПКО касса-отправитель не заполнена) — риск >1 совпадения.
"""
from _common import connect_erp
erp = connect_erp()

# параметры эталона N0000023550
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    РКО.Ссылка КАК Ссылка, РКО.Номер КАК Номер, РКО.Дата КАК Дата,
    РКО.Подразделение КАК Подразделение, РКО.Касса КАК Касса
ИЗ Документ.РасходныйКассовыйОрдер КАК РКО
ГДЕ
    РКО.Проведен = ИСТИНА
    И РКО.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыдачаДенежныхСредствВДругуюКассу)
    И РКО.Организация = &Организация
    И РКО.КассаПолучатель = &КассаПолучатель
    И РКО.СуммаДокумента = &СуммаДокумента
    И РКО.Валюта = &Валюта
    И РКО.Дата <= &Дата
УПОРЯДОЧИТЬ ПО РКО.Дата УБЫВ
"""
# вытащим параметры из ПКО
qp = erp.NewObject("Запрос")
qp.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 ПКО.Организация КАК Орг, ПКО.Касса КАК Касса, ПКО.СуммаДокумента КАК Сумма, ПКО.Валюта КАК Вал, ПКО.Дата КАК ДатаД ИЗ Документ.ПриходныйКассовыйОрдер КАК ПКО ГДЕ ПКО.Номер=&Ном"
qp.SetParameter("Ном","N0000023550")
s=qp.Execute().Выбрать(); s.Следующий()
q.SetParameter("Организация",s.Орг); q.SetParameter("КассаПолучатель",s.Касса)
q.SetParameter("СуммаДокумента",s.Сумма); q.SetParameter("Валюта",s.Вал); q.SetParameter("Дата",s.ДатаД)

try:
    выб=q.Execute().Выбрать()
except Exception as e:
    info=getattr(e,"excepinfo",None); print("FAIL:",info[2] if info else e); raise SystemExit

n=0
while выб.Следующий():
    n+=1
    print(f"  кандидат №{n}: {выб.Номер} {выб.Дата} Касса={erp.String(выб.Касса)} Подр={erp.String(выб.Подразделение)}")
print("ИТОГО кандидатов БЕЗ фильтра по КассаОтправитель:", n)
print(">> Вывод:", "уникально, можно без касса-фильтра" if n==1 else "НЕ уникально — касса-фильтр нужен / иначе риск ложной пары")
