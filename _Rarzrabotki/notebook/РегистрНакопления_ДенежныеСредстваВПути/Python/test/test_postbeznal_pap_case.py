# -*- coding: utf-8 -*-
"""
ТЕСТ-CASE: ПоступлениеБезналичныхДенежныхСредств 00DL-006964
Цель:
 1) Подтвердить, что ДокПоступление.А_ПодразделениеОтправитель = Строительство.
 2) Подтвердить, что текущая строка РН.ПрочиеАктивыПассивы со статьёй
    "Денежные средства в пути" имеет Подразделение = получатель (НЕ Строительство).
 3) Прогнать мини-CASE через Python COM на Документ.ПоступлениеБезналичныхДенежныхСредств:
    ВЫБОР КОГДА А_ПодразделениеОтправитель<>ПустаяСсылка И А_ПодразделениеОтправитель ЕСТЬ НЕ NULL
          ТОГДА А_ПодразделениеОтправитель ИНАЧЕ Подразделение КОНЕЦ
    -> для 00DL-006964 должно вернуть Строительство (синтаксис ветки валиден).

ВЕРНУТЬ: текущее ПАП-"в пути".Подразделение, ВПути.Подразделение, результат CASE, PASS/FAIL.
"""
import win32com.client
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')


def excep(e):
    info = getattr(e, 'excepinfo', None)
    if info:
        try:
            return info[2]
        except Exception:
            return str(e)
    return str(e)


NOMER = "00DL-006964"
STATYA_VPUTI = "Денежные средства в пути"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def predstavlenie(ssylka):
    """Безопасное представление ссылки (НЕ str())."""
    if ssylka is None:
        return "<None>"
    try:
        if not erp.ЗначениеЗаполнено(ssylka):
            return "<ПустаяСсылка>"
    except Exception:
        pass
    try:
        n = ssylka.Наименование
        if n:
            return n
    except Exception:
        pass
    try:
        return erp.XMLСтрока(ssylka)
    except Exception:
        return "<?>"


results = {
    "Номер": NOMER,
    "А_ПодразделениеОтправитель": None,
    "ПАП_ВПути_Подразделение": None,
    "ВПути_Подразделение": None,
    "CASE_результат": None,
    "PASS_FAIL": None,
    "детали": [],
}

# -------------------------------------------------------------------------
# 0) Найти документ-Поступление и его реквизиты
# -------------------------------------------------------------------------
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Док.Ссылка КАК Ссылка,
    Док.Номер КАК Номер,
    Док.Дата КАК Дата,
    Док.А_ПодразделениеОтправитель КАК ПодрОтправитель,
    Док.Подразделение КАК ПодрДок,
    Док.А_СписаниеБезналичныхДенежныхСредств КАК ПарноеСписание,
    ВЫБОР
        КОГДА Док.А_ПодразделениеОтправитель <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
             И Док.А_ПодразделениеОтправитель ЕСТЬ НЕ NULL
        ТОГДА Док.А_ПодразделениеОтправитель
        ИНАЧЕ Док.Подразделение
    КОНЕЦ КАК CASE_Подразделение
ИЗ
    Документ.ПоступлениеБезналичныхДенежныхСредств КАК Док
ГДЕ
    Док.Номер = &Номер
"""
q.SetParameter("Номер", NOMER)
try:
    tz = q.Execute().Выгрузить()
    if tz.Количество() == 0:
        results["PASS_FAIL"] = "FAIL"
        results["детали"].append(f"Документ {NOMER} не найден")
        print(results)
        sys.exit(0)
    row = tz.Получить(0)
    dok_ssylka = row.Ссылка
    podr_otpr = row.ПодрОтправитель
    podr_dok = row.ПодрДок
    case_podr = row.CASE_Подразделение
    parnoe_spis = row.ПарноеСписание

    results["А_ПодразделениеОтправитель"] = predstavlenie(podr_otpr)
    results["CASE_результат"] = predstavlenie(case_podr)
    results["детали"].append(f"Дата={erp.XMLСтрока(row.Дата)}")
    results["детали"].append(f"Подразделение(дока)={predstavlenie(podr_dok)}")
    results["детали"].append(f"ПарноеСписание={predstavlenie(parnoe_spis)}")
except Exception as e:
    results["PASS_FAIL"] = "FAIL"
    results["детали"].append(f"Ошибка запроса документа: {excep(e)}")
    print(results)
    sys.exit(0)

# -------------------------------------------------------------------------
# 1) Текущая строка РН.ПрочиеАктивыПассивы со статьёй "Денежные средства в пути"
#    Регистратор = дока-Поступление
# -------------------------------------------------------------------------
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    ПАП.Подразделение КАК Подразделение,
    ПАП.Статья КАК Статья,
    ПАП.Статья.Наименование КАК СтатьяНаим,
    ПАП.ВидДвижения КАК ВидДвижения,
    ПАП.Сумма КАК Сумма
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Регистратор = &Рег
    И ПАП.Статья.Наименование = &Статья
"""
q2.SetParameter("Рег", dok_ssylka)
q2.SetParameter("Статья", STATYA_VPUTI)
try:
    tz2 = q2.Execute().Выгрузить()
    results["детали"].append(f"ПАП-строк '{STATYA_VPUTI}' = {tz2.Количество()}")
    podrs = []
    for i in range(tz2.Количество()):
        r = tz2.Получить(i)
        podrs.append(predstavlenie(r.Подразделение))
        results["детали"].append(
            f"  ПАП[{i}]: Подр={predstavlenie(r.Подразделение)}, "
            f"Вид={erp.XMLСтрока(r.ВидДвижения)}, Сумма={r.Сумма}"
        )
    if podrs:
        results["ПАП_ВПути_Подразделение"] = "; ".join(sorted(set(podrs)))
    else:
        results["ПАП_ВПути_Подразделение"] = "<нет строк>"
except Exception as e:
    results["детали"].append(f"Ошибка запроса ПАП: {excep(e)}")
    results["ПАП_ВПути_Подразделение"] = f"ERROR: {excep(e)}"

# -------------------------------------------------------------------------
# 2) Текущая строка РН.ДенежныеСредстваВПути (ВПути), Регистратор = дока
# -------------------------------------------------------------------------
q3 = erp.NewObject("Запрос")
q3.Text = """
ВЫБРАТЬ
    ВПути.Подразделение КАК Подразделение,
    ВПути.ВидДвижения КАК ВидДвижения,
    ВПути.Сумма КАК Сумма
ИЗ
    РегистрНакопления.ДенежныеСредстваВПути КАК ВПути
ГДЕ
    ВПути.Регистратор = &Рег
"""
q3.SetParameter("Рег", dok_ssylka)
try:
    tz3 = q3.Execute().Выгрузить()
    results["детали"].append(f"ВПути-строк = {tz3.Количество()}")
    podrs3 = []
    for i in range(tz3.Количество()):
        r = tz3.Получить(i)
        podrs3.append(predstavlenie(r.Подразделение))
        results["детали"].append(
            f"  ВПути[{i}]: Подр={predstavlenie(r.Подразделение)}, "
            f"Вид={erp.XMLСтрока(r.ВидДвижения)}, Сумма={r.Сумма}"
        )
    if podrs3:
        results["ВПути_Подразделение"] = "; ".join(sorted(set(podrs3)))
    else:
        results["ВПути_Подразделение"] = "<нет строк>"
except Exception as e:
    results["детали"].append(f"Ошибка запроса ВПути: {excep(e)}")
    results["ВПути_Подразделение"] = f"ERROR: {excep(e)}"

# -------------------------------------------------------------------------
# 3) Сводный вердикт PASS/FAIL
# -------------------------------------------------------------------------
ozhid_otpr = "Строительство"
checks = []

# 3.1 А_ПодразделениеОтправитель = Строительство
c1 = results["А_ПодразделениеОтправитель"] == ozhid_otpr
checks.append((f"А_ПодразделениеОтправитель == {ozhid_otpr}", c1))

# 3.2 CASE возвращает Строительство (синтаксис ветки валиден + ожидаемое значение)
c2 = results["CASE_результат"] == ozhid_otpr
checks.append((f"CASE == {ozhid_otpr}", c2))

# 3.3 Текущая ПАП-"в пути".Подразделение НЕ Строительство (т.е. = получатель)
pap_val = results["ПАП_ВПути_Подразделение"]
c3 = (pap_val is not None
      and pap_val not in ("<нет строк>",)
      and ozhid_otpr not in str(pap_val))
checks.append(("Текущее ПАП-в-пути.Подразделение != Строительство (получатель)", c3))

all_ok = all(c for _, c in checks)
results["PASS_FAIL"] = "PASS" if all_ok else "FAIL"
for name, ok in checks:
    results["детали"].append(f"CHECK [{'OK' if ok else 'X'}] {name}")

# -------------------------------------------------------------------------
# Печать результата
# -------------------------------------------------------------------------
print("=" * 70)
print(f"ТЕСТ-CASE  Поступление {NOMER}")
print("=" * 70)
print(f"А_ПодразделениеОтправитель      : {results['А_ПодразделениеОтправитель']}")
print(f"Текущее ПАП-'в пути'.Подразделение: {results['ПАП_ВПути_Подразделение']}")
print(f"ВПути.Подразделение             : {results['ВПути_Подразделение']}")
print(f"CASE результат                  : {results['CASE_результат']}")
print(f"ВЕРДИКТ                         : {results['PASS_FAIL']}")
print("-" * 70)
for d in results["детали"]:
    print(d)
print("=" * 70)
