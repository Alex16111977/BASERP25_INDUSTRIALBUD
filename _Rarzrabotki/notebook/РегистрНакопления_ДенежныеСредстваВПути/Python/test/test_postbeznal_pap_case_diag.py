# -*- coding: utf-8 -*-
"""Доп.диагностика к 00DL-006964: получатель vs отправитель, парное Списание."""
import win32com.client
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

def excep(e):
    info = getattr(e, 'excepinfo', None)
    return info[2] if info else str(e)

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def P(s):
    if s is None: return "<None>"
    try:
        if not erp.ЗначениеЗаполнено(s): return "<Пусто>"
    except Exception: pass
    try:
        n = s.Наименование
        if n: return n
    except Exception: pass
    try: return erp.XMLСтрока(s)
    except Exception: return "<?>"

# Поступление + банковские счета (подразделение владельца счёта)
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Док.Ссылка КАК Ссылка,
    Док.Номер КАК Номер,
    Док.БанковскийСчет КАК СчетПолучателя,
    Док.БанковскийСчет.Владелец КАК ВладелецСчетаПол,
    Док.БанковскийСчет.Подразделение КАК ПодрСчетаПол,
    Док.БанковскийСчетОтправитель КАК СчетОтправителя,
    Док.БанковскийСчетОтправитель.Подразделение КАК ПодрСчетаОтпр,
    Док.А_ПодразделениеОтправитель КАК ПодрОтпр,
    Док.Подразделение КАК ПодрДок,
    Док.А_СписаниеБезналичныхДенежныхСредств КАК Списание
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Док
ГДЕ Док.Номер = &Н
"""
q.SetParameter("Н", "00DL-006964")
r = q.Execute().Выгрузить().Получить(0)
print("=== Поступление 00DL-006964 ===")
print(f"  Подразделение(дока)      : {P(r.ПодрДок)}")
print(f"  А_ПодразделениеОтправитель: {P(r.ПодрОтпр)}")
print(f"  СчетПолучателя           : {P(r.СчетПолучателя)} | владелец={P(r.ВладелецСчетаПол)}")
try: print(f"  Подр.СчетаПолучателя     : {P(r.ПодрСчетаПол)}")
except Exception as e: print(f"  Подр.СчетаПолучателя     : ERR {excep(e)}")
print(f"  СчетОтправителя          : {P(r.СчетОтправителя)}")
try: print(f"  Подр.СчетаОтправителя    : {P(r.ПодрСчетаОтпр)}")
except Exception as e: print(f"  Подр.СчетаОтправителя    : ERR {excep(e)}")
spis = r.Списание

# Парное Списание: реквизиты + его движения ПАП/ВПути
print("\n=== Парное Списание ===")
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    С.Ссылка КАК Ссылка, С.Номер КАК Номер,
    С.Подразделение КАК ПодрДок,
    С.БанковскийСчет КАК СчетОтпр,
    С.БанковскийСчетПолучатель КАК СчетПол
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК С
ГДЕ С.Ссылка = &Сп
"""
q2.SetParameter("Сп", spis)
tz2 = q2.Execute().Выгрузить()
spis_ssylka = None
if tz2.Количество() > 0:
    rs = tz2.Получить(0)
    spis_ssylka = rs.Ссылка
    print(f"  Номер={rs.Номер}  Подразделение(дока)={P(rs.ПодрДок)}")
    print(f"  СчетОтпр={P(rs.СчетОтпр)}  СчетПол={P(rs.СчетПол)}")
else:
    print("  Списание не найдено")

for nm, reg in (("ПрочиеАктивыПассивы", "ПрочиеАктивыПассивы"),
                ("ДенежныеСредстваВПути", "ДенежныеСредстваВПути")):
    for label, rg in (("Поступление", r.Ссылка), ("Списание", spis_ssylka)):
        if rg is None: continue
        qx = erp.NewObject("Запрос")
        if nm == "ПрочиеАктивыПассивы":
            qx.Text = ("ВЫБРАТЬ ПАП.Подразделение КАК Подр, ПАП.Статья.Наименование КАК Ст, "
                       "ПАП.ВидДвижения КАК Вид, ПАП.Сумма КАК Сумма "
                       "ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП ГДЕ ПАП.Регистратор=&Р")
        else:
            qx.Text = ("ВЫБРАТЬ ВП.Подразделение КАК Подр, ВП.ВидДвижения КАК Вид, ВП.Сумма КАК Сумма "
                       "ИЗ РегистрНакопления.ДенежныеСредстваВПути КАК ВП ГДЕ ВП.Регистратор=&Р")
        qx.SetParameter("Р", rg)
        try:
            tzx = qx.Execute().Выгрузить()
            print(f"\n  [{nm}] Регистратор={label}: строк={tzx.Количество()}")
            for i in range(tzx.Количество()):
                rr = tzx.Получить(i)
                st = getattr(rr, "Ст", "")
                print(f"    Подр={P(rr.Подр)}  {('Статья='+str(st)+' ') if st else ''}"
                      f"Вид={erp.XMLСтрока(rr.Вид)}  Сумма={rr.Сумма}")
        except Exception as e:
            print(f"  [{nm}] {label}: ERR {excep(e)}")
