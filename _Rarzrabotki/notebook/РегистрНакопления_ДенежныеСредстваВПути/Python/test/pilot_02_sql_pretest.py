# -*- coding: utf-8 -*-
"""
ПИЛОТ Шаг 02 — SQL пре-тест ПЕРЕД правкой ManagerModule.bsl.

Согласно Rule #-1 (CLAUDE.md): любой SQL-запрос — сначала через Python COM,
потом перенести в BSL.

Здесь воспроизводим логику ИЗМЕНЁННОГО блока SELECT функции
`ТекстЗапросаДенежныеСредстваВПути` (ManagerModule.bsl стр. 1815-1843,
блок №3 «КонвертацияВалюты» — ХозОп нашего пилотного ПКО 000Ц-000001),
с ДОБАВЛЕННОЙ колонкой `Подразделение = ДанныеДокумента.Касса.Подразделение`.

Цель: убедиться что SQL парсится, выполняется, возвращает корректные данные
ДО переноса в BSL.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# --- Найти ссылку на ПКО ---
q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.ПриходныйКассовыйОрдер ГДЕ Номер = "000Ц-000001"'
sel = q.Выполнить().Выбрать(); sel.Следующий()
ref = sel.Ссылка
print(f"Тестовый ПКО: {S(ref)}")

# --- Воспроизведём SQL блока КонвертацияВалюты (стр. 1815-1843 ManagerModule.bsl) ---
# с добавленной колонкой Подразделение
# ВНИМАНИЕ: параметры в типовом коде передаются через Запрос.УстановитьПараметр
# Для пре-теста подставим разумные значения вручную.

import datetime
period = datetime.datetime(2025, 12, 10, 16, 35, 1)  # Дата ПКО 000Ц-000001

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Ссылка", ref)
q.УстановитьПараметр("Период", period)
q.УстановитьПараметр("ХозяйственнаяОперация",
                     erp.Перечисления.ХозяйственныеОперации.КонвертацияВалюты)
q.УстановитьПараметр("СтатьяДвиженияДенежныхСредств",
                     erp.Справочники.СтатьиДвиженияДенежныхСредств.ПустаяСсылка())
q.УстановитьПараметр("КоэффициентПересчетаВВалютуУпр", 1.0)
q.УстановитьПараметр("КоэффициентПересчетаВВалютуРегл", 1.0)
q.УстановитьПараметр("КоэффициентПересчетаВВалютуКонвертации", 1.0)
q.УстановитьПараметр("ВалютаРегламентированногоУчета",
                     erp.Константы.ВалютаРегламентированногоУчета.Получить())

q.Текст = """
ВЫБРАТЬ
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)                                            КАК ВидДвижения,
    &Период                                                                           КАК Период,

    ДанныеДокумента.Организация                                                       КАК Организация,
    ДанныеДокумента.Касса.Подразделение                                               КАК Подразделение,  // ★ НОВАЯ КОЛОНКА
    ДанныеДокумента.Касса                                                             КАК Получатель,
    НЕОПРЕДЕЛЕНО                                                                      КАК Отправитель,
    ВЫБОР КОГДА ДанныеДокумента.ВалютаКонвертации = &ВалютаРегламентированногоУчета
        ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыПереводовДенежныхСредств.ПриобретениеВалюты)
        ИНАЧЕ ЗНАЧЕНИЕ(Перечисление.ВидыПереводовДенежныхСредств.РеализацияВалюты)
    КОНЕЦ                                                                             КАК ВидПереводаДенежныхСредств,
    ДанныеДокумента.Контрагент                                                        КАК Контрагент,
    ДанныеДокумента.ВалютаКонвертации                                                 КАК Валюта,

    ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуКонвертации          КАК Сумма,
    ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуУпр                  КАК СуммаУпр,
    ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуРегл                 КАК СуммаРегл,

    &ХозяйственнаяОперация                                                            КАК ХозяйственнаяОперация,
    &СтатьяДвиженияДенежныхСредств                                                    КАК СтатьяДвиженияДенежныхСредств

ИЗ
    Документ.ПриходныйКассовыйОрдер КАК ДанныеДокумента

ГДЕ
    ДанныеДокумента.Ссылка = &Ссылка
    И ДанныеДокумента.ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.КонвертацияВалюты)
    )
"""

print("\n=== Тест SQL для блока КонвертацияВалюты (с НОВОЙ колонкой Подразделение) ===")
try:
    rr = q.Выполнить().Выгрузить()
    print(f"[OK] Запрос успешно выполнен, строк: {rr.Количество()}")
    if rr.Количество() > 0:
        for i in range(rr.Количество()):
            rec = rr.Получить(i)
            print(f"\n  ВидДвижения      = {S(rec.ВидДвижения)}")
            print(f"  Период           = {rec.Период}")
            print(f"  Организация      = {S(rec.Организация)}")
            print(f"  ★ Подразделение  = {S(rec.Подразделение) if erp.ЗначениеЗаполнено(rec.Подразделение) else '(пусто)'}")
            print(f"  Получатель       = {S(rec.Получатель)}")
            print(f"  Отправитель      = {rec.Отправитель if rec.Отправитель else '(НЕОПРЕДЕЛЕНО)'}")
            print(f"  ВидПеревода      = {S(rec.ВидПереводаДенежныхСредств)}")
            print(f"  Контрагент       = {S(rec.Контрагент) if erp.ЗначениеЗаполнено(rec.Контрагент) else '(пусто)'}")
            print(f"  Валюта           = {S(rec.Валюта)}")
            print(f"  Сумма / СуммаУпр / СуммаРегл = {rec.Сумма} / {rec.СуммаУпр} / {rec.СуммаРегл}")
    else:
        print("  (нет строк — возможно ХозОп не Конвертация; проверь правильность ПКО)")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    msg = info[2] if info else str(e)
    print(f"[FAIL] {msg}")
    print("\n  → ОСТАНОВИТЬСЯ. SQL некорректен — НЕ переносить в BSL.")
    sys.exit(1)

print("\n[ACCEPTANCE]")
