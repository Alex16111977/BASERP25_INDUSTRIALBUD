# -*- coding: utf-8 -*-
"""
Rule #-1 валидация: ИСПРАВЛЕННЫЙ БЛОК 1 функции ТекстЗапросаДенежныеСредстваВПути
(Documents/ПриходныйКассовыйОрдер/Ext/ManagerModule.bsl).

БЛОК 1: ХозОп = ПоступлениеДенежныхСредствИзДругойКассы, ВидДвижения = Расход.
Правка: Подразделение берётся из А_ПодразделениеОтправитель с fallback на шапку.

Тест на ПКО N0000023550 (08.12.2025 13:53:51).
ОЖИДАНИЕ: 1 строка, Подразделение = Строительство (из А_ПодразделениеОтправитель),
          ВидДвижения = Расход, Сумма = 800000.
"""
import win32com.client
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def предст(ссылка):
    """Презентация ссылки (Наименование) без глобальной Строка()."""
    if not erp.ЗначениеЗаполнено(ссылка):
        return "<НЕОПРЕДЕЛЕНО/Пусто>"
    try:
        return ссылка.Наименование
    except Exception:
        return str(ссылка)


НОМЕР_ПКО = "N0000023550"

# --- 1. Найти ПКО по номеру ---
qref = erp.NewObject("Запрос")
qref.Text = """
ВЫБРАТЬ
    ПКО.Ссылка КАК Ссылка,
    ПКО.Дата КАК Дата,
    ПКО.Номер КАК Номер,
    ПКО.ХозяйственнаяОперация КАК ХозОп,
    ПКО.СуммаДокумента КАК Сумма,
    ПКО.Подразделение КАК Подразделение,
    ПКО.А_ПодразделениеОтправитель КАК А_ПодразделениеОтправитель
ИЗ
    Документ.ПриходныйКассовыйОрдер КАК ПКО
ГДЕ
    ПКО.Номер = &Номер
"""
qref.SetParameter("Номер", НОМЕР_ПКО)
sel = qref.Execute().Выбрать()
if not sel.Следующий():
    print(f"FAIL: ПКО {НОМЕР_ПКО} не найден")
    sys.exit(1)

СсылкаПКО = sel.Ссылка
ДатаПКО = sel.Дата
print(f"ПКО найден: Номер={sel.Номер}  Дата={sel.Дата}")
print(f"  ХозОп                     = {erp.XMLСтрока(sel.ХозОп)}")
print(f"  СуммаДокумента            = {sel.Сумма}")
print(f"  Подразделение (шапка)     = {предст(sel.Подразделение)}")
print(f"  А_ПодразделениеОтправитель= {предст(sel.А_ПодразделениеОтправитель)}")
print("-" * 70)

# --- 2. БЛОК 1 ТОЧНО как в BSL (с исправленным источником Подразделения) ---
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)                                            КАК ВидДвижения,
    &Период                                                                           КАК Период,

    ДанныеДокумента.Организация                                                       КАК Организация,
    ВЫБОР
        КОГДА ТИПЗНАЧЕНИЯ(ДанныеДокумента.КассаОтправитель) = ТИП(Справочник.Кассы) ТОГДА
            ДанныеДокумента.Касса
        ИНАЧЕ
            НЕОПРЕДЕЛЕНО
    КОНЕЦ КАК Получатель,
    ДанныеДокумента.КассаОтправитель                                                  КАК Отправитель,
    ЗНАЧЕНИЕ(Перечисление.ВидыПереводовДенежныхСредств.ПеремещениеВДругуюКассу)       КАК ВидПереводаДенежныхСредств,
    НЕОПРЕДЕЛЕНО                                                                      КАК Контрагент,
    ДанныеДокумента.Валюта                                                            КАК Валюта,

    ДанныеДокумента.СуммаДокумента                                                    КАК Сумма,
    ВЫРАЗИТЬ(ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуУпр КАК ЧИСЛО(31,2))   КАК СуммаУпр,
    ВЫРАЗИТЬ(ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуРегл КАК ЧИСЛО(31,2))  КАК СуммаРегл,

    ВЫБОР
        КОГДА ДанныеДокумента.А_ПодразделениеОтправитель <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
            ТОГДА ДанныеДокумента.А_ПодразделениеОтправитель
        ИНАЧЕ ДанныеДокумента.Подразделение
    КОНЕЦ                                                                             КАК Подразделение,
    &ХозяйственнаяОперация                                                            КАК ХозяйственнаяОперация,
    &СтатьяДвиженияДенежныхСредств                                                    КАК СтатьяДвиженияДенежныхСредств

ИЗ
    Документ.ПриходныйКассовыйОрдер КАК ДанныеДокумента

ГДЕ
    ДанныеДокумента.Ссылка = &Ссылка
    И ДанныеДокумента.ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствИзДругойКассы)
    )
"""

q.SetParameter("Период", ДатаПКО)
q.SetParameter("Ссылка", СсылкаПКО)
q.SetParameter("ХозяйственнаяОперация",
               erp.Перечисления.ХозяйственныеОперации.ПоступлениеДенежныхСредствИзДругойКассы)
q.SetParameter("СтатьяДвиженияДенежныхСредств",
               erp.Справочники.СтатьиДвиженияДенежныхСредств.ПустаяСсылка())
q.SetParameter("КоэффициентПересчетаВВалютуУпр", 1.0)
q.SetParameter("КоэффициентПересчетаВВалютуРегл", 1.0)

try:
    рез = q.Execute().Выгрузить()
except Exception as e:
    info = getattr(e, 'excepinfo', None)
    print("FAIL: ошибка парсинга/выполнения запроса БЛОКА 1:")
    print(info[2] if info else e)
    sys.exit(1)

n = рез.Количество()
print(f"Запрос распарсился и выполнился. Строк: {n}")
print("-" * 70)

ok = True
if n != 1:
    print(f"FAIL: ожидалась 1 строка, получено {n}")
    ok = False

if n >= 1:
    стр = рез.Получить(0)
    видДв = erp.XMLСтрока(стр.ВидДвижения)
    подр = предст(стр.Подразделение)
    сумма = стр.Сумма
    получ = предст(стр.Получатель)
    отпр = предст(стр.Отправитель)
    видПер = erp.XMLСтрока(стр.ВидПереводаДенежныхСредств)

    print(f"  ВидДвижения             = {видДв}")
    print(f"  Период                  = {стр.Период}")
    print(f"  Получатель (Касса)      = {получ}")
    print(f"  Отправитель(КассаОтпр)  = {отпр}")
    print(f"  ВидПереводаДС           = {видПер}")
    print(f"  Сумма                   = {сумма}")
    print(f"  СуммаУпр                = {стр.СуммаУпр}")
    print(f"  СуммаРегл               = {стр.СуммаРегл}")
    print(f"  Подразделение           = {подр}   <-- проверяемое поле")
    print("-" * 70)

    if видДв != "Expense":
        print(f"FAIL: ВидДвижения = {видДв}, ожидался Расход (Expense)")
        ok = False
    if подр != "Строительство":
        print(f"FAIL: Подразделение = '{подр}', ожидалось 'Строительство'")
        ok = False
    if abs(float(сумма) - 800000) > 0.005:
        print(f"FAIL: Сумма = {сумма}, ожидалось 800000")
        ok = False

print("=" * 70)
print("РЕЗУЛЬТАТ: PASS" if ok else "РЕЗУЛЬТАТ: FAIL")
sys.exit(0 if ok else 1)
