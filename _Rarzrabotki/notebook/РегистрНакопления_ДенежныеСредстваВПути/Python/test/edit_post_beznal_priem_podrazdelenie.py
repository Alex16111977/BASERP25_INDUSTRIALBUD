"""
Защитная доработка ПоступлениеБезналичных "Поступление с другого счёта" — Подразделение отправителя.
3 правки (детерминированно, с гардами):
1) ManagerModule.bsl ТекстЗапросаТаблицаДенежныеСредстваВПути, блок ПоступлениеДенежныхСредствСДругогоСчета:
   Подразделение = ВЫБОР(А_ПодразделениеОтправитель, иначе шапка).
2) ObjectModule.bsl: процедура А_ЗаполнитьПодразделениеОтправителяПоСписаниюБезнал() + вызов в хуке обмена.
3) DataProcessors/ДвиженияАктивовПассивов/Ext/ManagerModule.bsl: ветка ДокПоступление.А_ПодразделениеОтправитель
   перед ДокПоступление.Подразделение в каскаде МАКСИМУМ(ВЫБОР).
"""
import sys, io, re
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)

MM = r"C:\Configuration_downloads\BASERP25\Documents\ПоступлениеБезналичныхДенежныхСредств\Ext\ManagerModule.bsl"
OM = r"C:\Configuration_downloads\BASERP25\Documents\ПоступлениеБезналичныхДенежныхСредств\Ext\ObjectModule.bsl"
DAP = r"C:\Configuration_downloads\BASERP25\DataProcessors\ДвиженияАктивовПассивов\Ext\ManagerModule.bsl"

# ===== 1) ManagerModule блок ПоступлениеДенежныхСредствСДругогоСчета =====
with open(MM, "r", encoding="utf-8") as f: mm = f.read()
fs = mm.find("Функция ТекстЗапросаТаблицаДенежныеСредстваВПути")
fe = mm.find("КонецФункции", fs)
func = mm[fs:fe]
if "А_ПодразделениеОтправитель" in func:
    print("[STOP] MM: А_ПодразделениеОтправитель уже есть"); sys.exit(2)
parts = func.split("ОБЪЕДИНИТЬ ВСЕ")
hit = [i for i, p in enumerate(parts) if "ПоступлениеДенежныхСредствСДругогоСчета" in p]
if len(hit) != 1:
    print(f"[FAIL] MM: блок с ПоступлениеДенежныхСредствСДругогоСчета найден {len(hit)} раз"); sys.exit(3)
bi = hit[0]
pat = re.compile(r"^([ \t]*\|[ \t]*)ДанныеДокумента\.Подразделение[ \t]+КАК Подразделение,[ \t]*$", re.M)
if len(pat.findall(parts[bi])) != 1:
    print("[FAIL] MM: в целевом блоке не ровно 1 строка Подразделение"); sys.exit(4)
choose = (
    "\t|\tВЫБОР\n"
    "\t|\t\tКОГДА ДанныеДокумента.А_ПодразделениеОтправитель <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)\n"
    "\t|\t\t\tТОГДА ДанныеДокумента.А_ПодразделениеОтправитель\n"
    "\t|\t\tИНАЧЕ ДанныеДокумента.Подразделение\n"
    "\t|\tКОНЕЦ                                                                               КАК Подразделение,"
)
parts[bi] = pat.sub(lambda m: choose, parts[bi], count=1)
func_new = "ОБЪЕДИНИТЬ ВСЕ".join(parts)
mm_new = mm[:fs] + func_new + mm[fe:]
with open(MM, "w", encoding="utf-8") as f: f.write(mm_new)
print("[OK] 1) ManagerModule блок 'с другого счёта' — Подразделение = ВЫБОР(А_ПодразделениеОтправитель)")

# ===== 2) ObjectModule: процедура + вызов =====
with open(OM, "r", encoding="utf-8") as f: om = f.read()
if "А_ЗаполнитьПодразделениеОтправителяПоСписаниюБезнал" in om:
    print("[STOP] OM: процедура уже есть"); sys.exit(5)
ps = om.find("Процедура ОбновитьПоступлениеБезналичныхДенежныхСредств_КазнаПослеОбмена()")
pe = om.find("КонецПроцедуры", ps)
proc = om[ps:pe]
marker = "А_ОбработанКазна = Истина;"
idx = proc.rfind(marker)
if idx < 0: print("[FAIL] OM: маркер А_ОбработанКазна не найден"); sys.exit(6)
ls = proc.rfind("\n", 0, idx) + 1
call_block = (
    "\t// Заполнить подразделение/документ отправителя для \"Поступление с другого счёта\"\n"
    "\tЕсли ХозяйственнаяОперация = Перечисления.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета Тогда\n"
    "\t\tА_ЗаполнитьПодразделениеОтправителяПоСписаниюБезнал();\n"
    "\tКонецЕсли;\n"
    "\t\n"
)
proc_new = proc[:ls] + call_block + proc[ls:]

pl = [
    "",
    "// Заполняет реквизиты отправителя (А_ПодразделениеОтправитель, А_СписаниеБезналичныхДенежныхСредств)",
    "// для \"Поступление денежных средств с другого счёта\" по парному проведённому Списанию",
    "// \"Перечисление денежных средств на другой счёт\". Идемпотентна: только при незаполненном А_ПодразделениеОтправитель.",
    "Процедура А_ЗаполнитьПодразделениеОтправителяПоСписаниюБезнал() Экспорт",
    "\t",
    "\tЕсли НЕ ХозяйственнаяОперация = Перечисления.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета Тогда",
    "\t\tВозврат;",
    "\tКонецЕсли;",
    "\t",
    "\tЕсли ЗначениеЗаполнено(А_ПодразделениеОтправитель) Тогда",
    "\t\tВозврат;",
    "\tКонецЕсли;",
    "\t",
    "\tЗапрос = Новый Запрос;",
    "\tЗапрос.Текст =",
    "\t\"ВЫБРАТЬ ПЕРВЫЕ 1",
    "\t|\tСпис.Ссылка        КАК Ссылка,",
    "\t|\tСпис.Подразделение КАК Подразделение",
    "\t|ИЗ",
    "\t|\tДокумент.СписаниеБезналичныхДенежныхСредств КАК Спис",
    "\t|ГДЕ",
    "\t|\tСпис.Проведен = ИСТИНА",
    "\t|\tИ Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)",
    "\t|\tИ Спис.Организация = &Организация",
    "\t|\tИ Спис.БанковскийСчетПолучатель = &СчетПолучатель",
    "\t|\tИ Спис.БанковскийСчет = &СчетОтправитель",
    "\t|\tИ Спис.СуммаДокумента = &СуммаДокумента",
    "\t|\tИ Спис.Валюта = &Валюта",
    "\t|\tИ Спис.Дата <= &Дата",
    "\t|УПОРЯДОЧИТЬ ПО",
    "\t|\tСпис.Дата УБЫВ,",
    "\t|\tСпис.Номер УБЫВ\";",
    "\t",
    "\tЗапрос.УстановитьПараметр(\"Организ␃ация\".Replace, 0);" if False else "\tЗапрос.УстановитьПараметр(\"Организация\",    Организация);",
    "\tЗапрос.УстановитьПараметр(\"СчетПолучатель\",  БанковскийСчет);",
    "\tЗапрос.УстановитьПараметр(\"СчетОтправитель\", БанковскийСчетОтправитель);",
    "\tЗапрос.УстановитьПараметр(\"СуммаДокумента\",  СуммаДокумента);",
    "\tЗапрос.УстановитьПараметр(\"Валюта\",          Валюта);",
    "\tЗапрос.УстановитьПараметр(\"Дата\",            Дата);",
    "\t",
    "\tВыборка = Запрос.Выполнить().Выбрать();",
    "\tЕсли Выборка.Следующий() Тогда",
    "\t\tА_СписаниеБезналичныхДенежныхСредств = Выборка.Ссылка;",
    "\t\tА_ПодразделениеОтправитель = Выборка.Подразделение;",
    "\tКонецЕсли;",
    "\t",
    "КонецПроцедуры",
]
new_proc = "\n".join(pl)
before, after = om[:ps], om[pe:]
kp = after.find("\n")
after_new = after[:kp+1] + "\n" + new_proc + after[kp+1:]
om_new = before + proc_new + after_new
with open(OM, "w", encoding="utf-8") as f: f.write(om_new)
print("[OK] 2) ObjectModule — процедура + вызов в хуке")

# ===== 3) ДвиженияАктивовПассивов — ветка ДокПоступление.А_ПодразделениеОтправитель =====
with open(DAP, "r", encoding="utf-8") as f: dap = f.read()
psd = dap.find("Процедура ДобавитьТекстЗапросаДенежныеСредстваВПути")
ped = dap.find("КонецПроцедуры", psd)
pseg = dap[psd:ped]
if "ДокПоступление.А_ПодразделениеОтправитель" in pseg:
    print("[STOP] DAP: ветка ДокПоступление.А_ПодразделениеОтправитель уже есть"); sys.exit(7)
patd = re.compile(
    r"(^[ \t]*\|[ \t]*ТОГДА ДокСписание\.Подразделение[ \t]*\n)"
    r"([ \t]*\|([ \t]*)КОГДА ДокПоступление\.Подразделение <> ЗНАЧЕНИЕ\(Справочник\.СтруктураПредприятия\.ПустаяСсылка\))",
    re.M)
m = patd.search(pseg)
if not m: print("[FAIL] DAP: якорь ДокСписание/ДокПоступление не найден"); sys.exit(8)
kogda = m.group(2); prefix = kogda[:kogda.index("КОГДА")]; inner = prefix + "\t"
branch = (
    f"{prefix}КОГДА ДокПоступление.А_ПодразделениеОтправитель <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)\n"
    f"{inner}И ДокПоступление.А_ПодразделениеОтправитель ЕСТЬ НЕ NULL\n"
    f"{prefix}ТОГДА ДокПоступление.А_ПодразделениеОтправитель\n"
)
pseg_new, n = patd.subn(lambda mm: mm.group(1) + branch + mm.group(2), pseg, count=1)
if n != 1: print(f"[FAIL] DAP: вставок {n}"); sys.exit(9)
dap_new = dap[:psd] + pseg_new + dap[ped:]
with open(DAP, "w", encoding="utf-8") as f: f.write(dap_new)
print("[OK] 3) ДвиженияАктивовПассивов — ветка ДокПоступление.А_ПодразделениеОтправитель")
print("\nГОТОВО: 3 правки применены.")
