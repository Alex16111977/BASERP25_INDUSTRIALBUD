# -*- coding: utf-8 -*-
"""
ПостБезнал — SQL пре-тест БЛОКА 2 функции ТекстЗапросаТаблицаДенежныеСредстваВПути
(ManagerModule.bsl стр. 2063-2090: ХозОп ПоступлениеДенежныхСредствСДругогоСчета,
 ВидПеревода ПеречислениеНаДругойСчет).

Цель: проверить НОВЫЙ источник Подразделения через выражение
  ВЫБОР КОГДА ДанныеДокумента.А_ПодразделениеОтправитель <> ПустаяСсылка
       ТОГДА ДанныеДокумента.А_ПодразделениеОтправитель
       ИНАЧЕ ДанныеДокумента.Подразделение
  КОНЕЦ КАК Подразделение

Тест-док: 00DL-006964 (01.12.2025, 9 641 228,35 UAH),
          А_ПодразделениеОтправитель = Строительство (заполнен вручную).

ОЖИДАНИЕ: 1 строка, Подразделение=Строительство, ВидДвижения=Расход, Сумма=9641228.35.
Rule #-1: запрос 1:1 как будет в BSL, прогон на реальной базе ДО переноса.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

НОМЕР = "00DL-006964"
ОЖИД_ПОДР = "Строительство"
ОЖИД_СУММА = 9641228.35

# --- найти тестовый документ + его реквизиты (Дата, А_ПодразделениеОтправитель, Подразделение) ---
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Номер", НОМЕР)
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Ссылка                       КАК Ссылка,
    Дата                         КАК Дата,
    СуммаДокумента               КАК СуммаДокумента,
    Подразделение                КАК Подразделение,
    А_ПодразделениеОтправитель   КАК А_ПодразделениеОтправитель,
    ХозяйственнаяОперация        КАК ХозяйственнаяОперация
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств
ГДЕ Номер = &Номер
"""
sel = q.Выполнить().Выбрать()
if not sel.Следующий():
    print(f"[FAIL] Документ ПостБезнал Номер={НОМЕР} не найден")
    sys.exit(1)

ref = sel.Ссылка
period = sel.Дата
подр_отпр_заполнен = erp.ЗначениеЗаполнено(sel.А_ПодразделениеОтправитель)
print("=== Реквизиты тест-дока ===")
print(f"  Ссылка                     = {S(ref)}")
print(f"  Дата (Период)              = {period}")
print(f"  СуммаДокумента             = {sel.СуммаДокумента}")
print(f"  Подразделение (шапка)      = {S(sel.Подразделение) if erp.ЗначениеЗаполнено(sel.Подразделение) else '(пусто)'}")
print(f"  А_ПодразделениеОтправитель = {S(sel.А_ПодразделениеОтправитель) if подр_отпр_заполнен else '(пусто)'}")
print(f"  ХозяйственнаяОперация      = {S(sel.ХозяйственнаяОперация)}")

# --- БЛОК 2: воспроизведение 1:1 как будет в BSL, с НОВЫМ источником Подразделения ---
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Период", period)
q.УстановитьПараметр("Ссылка", ref)
q.УстановитьПараметр("ПроведеноБанком", True)
q.УстановитьПараметр("ХозяйственнаяОперация",
                     erp.Перечисления.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
q.УстановитьПараметр("СтатьяДвиженияДенежныхСредств",
                     erp.Справочники.СтатьиДвиженияДенежныхСредств.ПустаяСсылка())
q.УстановитьПараметр("КоэффициентПересчетаВВалютуУпр", 1.0)
q.УстановитьПараметр("КоэффициентПересчетаВВалютуРегл", 1.0)

q.Текст = """
ВЫБРАТЬ
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)                                       КАК ВидДвижения,
    &Период                                                                      КАК Период,

    ДанныеДокумента.Организация                                                  КАК Организация,
    ДанныеДокумента.БанковскийСчет                                               КАК Получатель,
    ДанныеДокумента.БанковскийСчетОтправитель                                    КАК Отправитель,
    ЗНАЧЕНИЕ(Перечисление.ВидыПереводовДенежныхСредств.ПеречислениеНаДругойСчет) КАК ВидПереводаДенежныхСредств,
    НЕОПРЕДЕЛЕНО                                                                 КАК Контрагент,
    ДанныеДокумента.Валюта                                                       КАК Валюта,

    ДанныеДокумента.СуммаДокумента                                               КАК Сумма,
    ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуУпр             КАК СуммаУпр,
    ДанныеДокумента.СуммаДокумента * &КоэффициентПересчетаВВалютуРегл            КАК СуммаРегл,

    ВЫБОР
        КОГДА ДанныеДокумента.А_ПодразделениеОтправитель <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
            ТОГДА ДанныеДокумента.А_ПодразделениеОтправитель
        ИНАЧЕ ДанныеДокумента.Подразделение
    КОНЕЦ                                                                        КАК Подразделение,
    &ХозяйственнаяОперация                                                       КАК ХозяйственнаяОперация,
    &СтатьяДвиженияДенежныхСредств                                               КАК СтатьяДвиженияДенежныхСредств

ИЗ
    Документ.ПоступлениеБезналичныхДенежныхСредств КАК ДанныеДокумента

ГДЕ
    ДанныеДокумента.Ссылка = &Ссылка
    И &ПроведеноБанком
    И ДанныеДокумента.ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
        )
"""

print("\n=== SQL блок 2 (ПоступлениеДенежныхСредствСДругогоСчета) + НОВЫЙ источник Подразделения ===")
try:
    rr = q.Выполнить().Выгрузить()
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print(f"[FAIL] Ошибка выполнения запроса: {info[2] if info else e}")
    sys.exit(1)

n = rr.Количество()
print(f"  Строк: {n}")

errors = []
if n != 1:
    errors.append(f"ожидалась 1 строка, получено {n}")

if n >= 1:
    rec = rr.Получить(0)
    подр = S(rec.Подразделение) if erp.ЗначениеЗаполнено(rec.Подразделение) else "(пусто)"
    виддв = S(rec.ВидДвижения)
    сумма = round(float(rec.Сумма), 2)
    получатель = S(rec.Получатель) if erp.ЗначениеЗаполнено(rec.Получатель) else "(пусто)"
    отправитель = S(rec.Отправитель) if erp.ЗначениеЗаполнено(rec.Отправитель) else "(пусто)"
    видпер = S(rec.ВидПереводаДенежныхСредств)

    print(f"\n  ★ Подразделение            = {подр}")
    print(f"    ВидДвижения              = {виддв}")
    print(f"    Сумма                    = {сумма}")
    print(f"    Получатель (БанкСчет)    = {получатель}")
    print(f"    Отправитель (БС Отпр)    = {отправитель}")
    print(f"    ВидПереводаДенежныхСредств = {видпер}")
    print(f"    СуммаУпр                 = {round(float(rec.СуммаУпр),2)}")
    print(f"    СуммаРегл                = {round(float(rec.СуммаРегл),2)}")

    if подр != ОЖИД_ПОДР:
        errors.append(f"Подразделение={подр}, ожидалось {ОЖИД_ПОДР}")
    if виддв != "Расход":
        errors.append(f"ВидДвижения={виддв}, ожидался Расход")
    if abs(сумма - ОЖИД_СУММА) > 0.005:
        errors.append(f"Сумма={сумма}, ожидалось {ОЖИД_СУММА}")

print("\n" + "=" * 60)
if errors:
    print("[FAIL] " + "; ".join(errors))
    sys.exit(1)
else:
    print(f"[PASS] 1 строка | Подразделение={ОЖИД_ПОДР} | ВидДвижения=Расход | Сумма={ОЖИД_СУММА}")
    print("[PASS] Валидированный SELECT готов к переносу в BSL (ManagerModule.bsl блок 2, стр. 2063-2090)")
