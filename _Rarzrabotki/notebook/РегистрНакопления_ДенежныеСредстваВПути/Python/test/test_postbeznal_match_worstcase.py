# -*- coding: utf-8 -*-
"""
Worst-case: есть ли Поступление, где в ОДНО МГНОВЕНИЕ (Дата = Дата Поступления)
существует >1 кандидат-Списание с РАЗНЫМИ подразделениями?
=> тогда тай-брейкер по Номер УБЫВ мог бы выбрать чужое подразделение.
"""
from _common import connect_erp
erp = connect_erp()

ТЕКСТ = """
ВЫБРАТЬ
    Спис.Номер         КАК Номер,
    Спис.Дата          КАК Дата,
    Спис.Подразделение КАК Подразделение
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Спис
ГДЕ
    Спис.Проведен = ИСТИНА
    И Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)
    И Спис.Организация = &Организация
    И Спис.БанковскийСчетПолучатель = &СчетПолучатель
    И Спис.БанковскийСчет = &СчетОтправитель
    И Спис.СуммаДокумента = &СуммаДокумента
    И Спис.Валюта = &Валюта
    И Спис.Дата = &ДатаТочно
"""

qAll = erp.NewObject("Запрос")
qAll.Text = """
ВЫБРАТЬ
    Пост.Номер                     КАК Номер,
    Пост.Дата                      КАК Дата,
    Пост.Организация               КАК Организация,
    Пост.БанковскийСчет            КАК БанковскийСчет,
    Пост.БанковскийСчетОтправитель КАК БанковскийСчетОтправитель,
    Пост.СуммаДокумента            КАК СуммаДокумента,
    Пост.Валюта                    КАК Валюта
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пост
ГДЕ Пост.Проведен = ИСТИНА
    И Пост.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
"""

selAll = qAll.Execute().Выбрать()
worst = 0
worst_примеры = []
while selAll.Следующий():
    q = erp.NewObject("Запрос")
    q.Text = ТЕКСТ
    q.SetParameter("Организация",     selAll.Организация)
    q.SetParameter("СчетПолучатель",  selAll.БанковскийСчет)
    q.SetParameter("СчетОтправитель", selAll.БанковскийСчетОтправитель)
    q.SetParameter("СуммаДокумента",  selAll.СуммаДокумента)
    q.SetParameter("Валюта",          selAll.Валюта)
    q.SetParameter("ДатаТочно",       selAll.Дата)   # ТОЧНОЕ мгновение Поступления
    в = q.Execute().Выбрать()
    канд = []
    while в.Следующий():
        канд.append((str(в.Номер).strip(), erp.String(в.Подразделение)))
    подр = set(c[1] for c in канд)
    if len(канд) > 1 and len(подр) > 1:
        worst += 1
        if len(worst_примеры) < 10:
            worst_примеры.append((str(selAll.Номер).strip(), str(selAll.Дата), канд))

print("WORST-CASE (в одно мгновение Даты Поступления >1 Списание с РАЗНЫМИ подр):", worst)
if worst_примеры:
    for ном, дата, канд in worst_примеры:
        print(f"  Поступление {ном} ({дата}):")
        for сн, сп in канд:
            print(f"     Списание {сн} Подр={сп}")
else:
    print("[OK] Таких нет => при равной Дате кандидат всегда из ОДНОГО подразделения.")
    print("     Тай-брейкер Дата УБЫВ + Номер УБЫВ выбирает Списание той же секунды,")
    print("     а в ту же секунду подразделение однозначно => результат корректен.")
