# -*- coding: utf-8 -*-
"""
Диагностика: для всех проведённых Поступлений "Поступление с другого счёта" сравнить
Подразделение ШАПКИ (попадает в движения сейчас) vs Подразделение ПАРНОГО Списания (отправитель).
Цель — понять, реален ли баг (header != sender) для безнала, и найти контрольный док (header != sender).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
def S(v):
    try: return erp.XMLСтрока(v)
    except: return str(v)
def nm(v):
    try: return v.Наименование if erp.ЗначениеЗаполнено(v) else "(пусто)"
    except: return "(?)"

# все проведённые Поступления с другого счёта
q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ П.Ссылка КАК Ссылка, П.Номер КАК Номер, П.Дата КАК Дата, П.Организация КАК Организация,
    П.Подразделение КАК ПодрШапки, П.БанковскийСчет КАК СчетПолуч, П.БанковскийСчетОтправитель КАК СчетОтпр,
    П.СуммаДокумента КАК Сумма, П.Валюта КАК Валюта, П.А_ПодразделениеОтправитель КАК АОтпр
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК П
ГДЕ П.Проведен = ИСТИНА
    И П.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
"""
sel = q.Выполнить().Выбрать()

match = erp.NewObject("Запрос")
match.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Спис.Ссылка КАК Ссылка, Спис.Подразделение КАК Подр, Спис.Номер КАК Номер
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Спис
ГДЕ Спис.Проведен = ИСТИНА
    И Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)
    И Спис.Организация = &Организация
    И Спис.БанковскийСчетПолучатель = &СчетПолуч
    И Спис.БанковскийСчет = &СчетОтпр
    И Спис.СуммаДокумента = &Сумма
    И Спис.Валюта = &Валюта
    И Спис.Дата <= &Дата
УПОРЯДОЧИТЬ ПО Спис.Дата УБЫВ, Спис.Номер УБЫВ
"""

total=0; no_pair=0; same=0; diff=0; diff_examples=[]
while sel.Следующий():
    total+=1
    match.УстановитьПараметр("Организация", sel.Организация)
    match.УстановитьПараметр("СчетПолуч", sel.СчетПолуч)
    match.УстановитьПараметр("СчетОтпр", sel.СчетОтпр)
    match.УстановитьПараметр("Сумма", sel.Сумма)
    match.УстановитьПараметр("Валюта", sel.Валюта)
    match.УстановитьПараметр("Дата", sel.Дата)
    m = match.Выполнить().Выбрать()
    if not m.Следующий():
        no_pair+=1; continue
    hdr = S(sel.ПодрШапки); snd = S(m.Подр)
    if hdr == snd:
        same+=1
    else:
        diff+=1
        if len(diff_examples) < 12:
            diff_examples.append((sel.Номер, nm(sel.ПодрШапки), nm(m.Подр), m.Номер, nm(sel.АОтпр)))

print(f"Всего проведённых Поступлений 'с другого счёта': {total}")
print(f"  пара не найдена: {no_pair}")
print(f"  Подр шапки == Подр отправителя (Списания): {same}  (фикс = no-op)")
print(f"  Подр шапки != Подр отправителя: {diff}  <-- БАГ виден здесь, фикс меняет движение")
print(f"\nПримеры (header != sender) — кандидаты в контрольный док:")
print(f"  {'Поступление':<16} {'ПодрШапки(сейчас)':<22} {'ПодрОтправителя(надо)':<22} {'Списание':<14} {'А_ПодрОтпр'}")
for nmr, h, s2, sn, a in diff_examples:
    print(f"  {nmr:<16} {h[:21]:<22} {s2[:21]:<22} {sn:<14} {a}")
