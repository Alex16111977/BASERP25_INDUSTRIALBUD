# -*- coding: utf-8 -*-
"""PILOT Свод_ДенежныеСредства Шаг 01 — Baseline А_ОтчетБаланс_Свод (январь 2026).

Снимаем состояние ДО доработки 4-й ветки в Свод_ДенежныеСредства:
- Σ записей по статье «Денежные средства в пути» (Расхождение=Истина и Ложь)
- Σ записей по 3 остальным денежным статьям (для контроля регрессий)
- Σ Актив=|Пассив| per Орг (целевой баланс 288 787 750,11 на янв26)

Регистр непериодический → фильтр через ДокументДвижения (А_ФинРез_Баланс за пилот-месяц).
"""
import sys, io, os, json, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ART = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_artifacts")
os.makedirs(ART, exist_ok=True)

ORG = erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273")
print(f"Org: {S(ORG)}")

# Найти документ А_ФинРез_Баланс за январь 2026
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("М1", datetime.datetime(2026, 1, 1, 0, 0, 0))
q.УстановитьПараметр("М2", datetime.datetime(2026, 1, 1, 23, 59, 59))
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.А_ФинРез_Баланс
ГДЕ Организация = &Орг И Месяц МЕЖДУ &М1 И &М2 И Проведен = ИСТИНА
"""
sel = q.Выполнить().Выбрать()
if not sel.Следующий():
    print("[FAIL] Документ А_ФинРез_Баланс за январь 2026 не найден"); sys.exit(1)
DOC = sel.Ссылка
print(f"Документ: {S(DOC)}")

# Резолв статей
def _ст(nm):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Н", nm)
    q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = &Н"
    sel = q.Выполнить().Выбрать()
    return sel.Ссылка if sel.Следующий() else None

СтВПути = _ст("Денежные средства в пути")
СтБезнал = _ст("Денежные средства (безналичные)")
СтНал = _ст("Денежные средства (наличные)")
СтПодотч = _ст("Денежные средства (у подотчетных лиц)")
print(f"СтВПути: {S(СтВПути) if СтВПути else 'NOT FOUND'}")

snapshot = {"org": str(S(ORG)), "doc": str(S(DOC)), "month": "2026-01", "statyas": {}}

for nm, st in [("ВПути", СтВПути), ("Безнал", СтБезнал), ("Налич", СтНал), ("Подотч", СтПодотч)]:
    if st is None:
        snapshot["statyas"][nm] = {"error": "статья не найдена"}; continue
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Орг", ORG)
    q.УстановитьПараметр("Ст", st)
    q.УстановитьПараметр("Док", DOC)
    q.Текст = """
    ВЫБРАТЬ
        Р.Расхождение КАК Расхождение,
        КОЛИЧЕСТВО(*) КАК К,
        СУММА(Р.СуммаНачальныйОстаток) КАК НО,
        СУММА(Р.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Р
    ГДЕ Р.Организация = &Орг И Р.Статья = &Ст И Р.ДокументДвижения = &Док
    СГРУППИРОВАТЬ ПО Р.Расхождение
    """
    try:
        r = q.Выполнить().Выгрузить()
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        print(f"  [WARN] {nm}: {info[2] if info else e}"); continue
    info = {"rows": []}
    for i in range(r.Количество()):
        rec = r.Получить(i)
        info["rows"].append({
            "Расхождение": bool(rec.Расхождение),
            "К": int(rec.К),
            "НО": float(rec.НО or 0),
            "КО": float(rec.КО or 0)
        })
    snapshot["statyas"][nm] = info
    print(f"\n=== Статья: {nm} ===")
    for row in info["rows"]:
        print(f"  Расхождение={row['Расхождение']!s:<5}  К={row['К']:>5}  НО={row['НО']:>16,.2f}  КО={row['КО']:>16,.2f}")

# Σ Актив=|Пассив| — тотал
print("\n=== Σ по ВСЕМ строкам регистра за январь 2026 ===")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("Док", DOC)
q.Текст = """
ВЫБРАТЬ
    КОЛИЧЕСТВО(*) КАК ВсегоСтрок,
    СУММА(Р.СуммаНачальныйОстаток) КАК ΣНО,
    СУММА(Р.СуммаКонечныйОстаток) КАК ΣКО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Р
ГДЕ Р.Организация = &Орг И Р.ДокументДвижения = &Док
"""
r = q.Выполнить().Выгрузить()
if r.Количество():
    rec = r.Получить(0)
    snapshot["total"] = {
        "ВсегоСтрок": int(rec.ВсегоСтрок),
        "ΣНО": float(rec.ΣНО or 0),
        "ΣКО": float(rec.ΣКО or 0)
    }
    print(f"  Строк всего: {int(rec.ВсегоСтрок)}")
    print(f"  Σ НО: {float(rec.ΣНО or 0):>16,.2f}")
    print(f"  Σ КО: {float(rec.ΣКО or 0):>16,.2f}  (должен быть ≈ 0 для сбалансированности)")

out = os.path.join(ART, "pilot_svod_vputi_01_baseline.json")
with open(out, "w", encoding="utf-8") as f:
    json.dump(snapshot, f, ensure_ascii=False, indent=2, default=str)
print(f"\n[OK] Snapshot: {out}")
