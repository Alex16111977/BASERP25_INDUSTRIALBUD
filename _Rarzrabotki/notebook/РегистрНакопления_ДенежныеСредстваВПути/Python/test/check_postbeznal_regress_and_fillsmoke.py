"""ПостБезнал защитная правка — 2 контроля:
1) Регрессия общего ПАП-каскада: ПКО N0000023550 ПАП «в пути».Подр всё ещё = Строительство.
2) Smoke процедуры А_ЗаполнитьПодразделениеОтправителяПоСписаниюБезнал на пустом безнал-доке (в памяти, без Записать)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
def nm(v):
    try: return v.Наименование if erp.ЗначениеЗаполнено(v) else "(пусто)"
    except: return "(?)"

print("=== 1) Регрессия ПКО N0000023550 (общий ПАП-каскад) ===")
q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.ПриходныйКассовыйОрдер ГДЕ Номер = "N0000023550"'
s = q.Выполнить().Выбрать()
if s.Следующий():
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("Док", s.Ссылка)
    qq.Текст = ("ВЫБРАТЬ Статья КАК Ст, Подразделение КАК П, Сумма КАК С ИЗ РегистрНакопления.ПрочиеАктивыПассивы "
                "КАК Р ГДЕ Р.Регистратор = &Док")
    r = qq.Выполнить().Выбрать(); ok=False
    while r.Следующий():
        st = nm(r.Ст)
        if "пути" in st.lower():
            ok = (nm(r.П)=="Строительство")
            print(f"  ПКО ПАП «в пути»: Подр={nm(r.П)} Σ={r.С}  -> {'PASS' if ok else 'FAIL'}")
    if not ok: print("  [!] проверить ПКО")
else:
    print("  (N0000023550 не найден)")

print("\n=== 2) Smoke процедуры заполнения на пустом безнал-доке (в памяти) ===")
# найти проведённый ПостБезнал 'с другого счёта' с пустым А_ПодразделениеОтправитель
q2 = erp.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка, П.Номер КАК Номер
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК П
ГДЕ П.Проведен = ИСТИНА
    И П.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
    И П.А_ПодразделениеОтправитель = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
"""
s2 = q2.Выполнить().Выбрать()
if not s2.Следующий():
    print("  (нет пустых документов — пропуск)")
else:
    obj = s2.Ссылка.ПолучитьОбъект()
    print(f"  Док: {s2.Номер}; А_ПодразделениеОтправитель ДО = {nm(obj.А_ПодразделениеОтправитель)}; шапка={nm(obj.Подразделение)}")
    try:
        obj.А_ЗаполнитьПодразделениеОтправителяПоСписаниюБезнал()   # в памяти, без Записать
        a = nm(obj.А_ПодразделениеОтправитель); d = nm(obj.А_СписаниеБезналичныхДенежныхСредств)
        print(f"  ПОСЛЕ вызова: А_ПодразделениеОтправитель={a}; А_Списание={d}")
        print(f"  -> {'PASS (заполнилось из парного Списания)' if a not in ('(пусто)','(?)') else 'WARN (пара не найдена для этого дока)'}")
    except Exception as e:
        info=getattr(e,"excepinfo",None); print(f"  [FAIL] вызов процедуры: {info[2] if info else e}")
