# -*- coding: utf-8 -*-
"""
Детерминированная правка ПКО "Поступление денежных средств из другой кассы":
1) ManagerModule.bsl, функция ТекстЗапросаДенежныеСредстваВПути, ТОЛЬКО блок 1:
   заменить `ДанныеДокумента.Подразделение КАК Подразделение,` на ВЫБОР с А_ПодразделениеОтправитель (fallback на шапку).
2) ObjectModule.bsl: добавить процедуру А_ЗаполнитьПодразделениеОтправителяПоРКО()
   + вызов перед последним `А_ОбработанКазна = Истина;` в ОбновитьПриходныйКассовыйОрдерПослеОбмена().
Гарды: ровно по 1 правке; блоки 2/3 ВПути не трогаются.
"""
import sys, io, re
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)

MM = r"C:\Configuration_downloads\BASERP25\Documents\ПриходныйКассовыйОрдер\Ext\ManagerModule.bsl"
OM = r"C:\Configuration_downloads\BASERP25\Documents\ПриходныйКассовыйОрдер\Ext\ObjectModule.bsl"

# ============ 1) ManagerModule: блок 1 ВПути ============
with open(MM, "r", encoding="utf-8") as f:
    text = f.read()

fs = text.find("Функция ТекстЗапросаДенежныеСредстваВПути(")
if fs < 0: print("[FAIL] функция ВПути не найдена"); sys.exit(1)
fe = text.find("КонецФункции", fs)
func = text[fs:fe]

if "А_ПодразделениеОтправитель" in func:
    print("[STOP] А_ПодразделениеОтправитель уже есть в функции ВПути"); sys.exit(2)

ub = func.find("ОБЪЕДИНИТЬ ВСЕ")
if ub < 0: print("[FAIL] ОБЪЕДИНИТЬ ВСЕ не найдено"); sys.exit(3)
block1, rest = func[:ub], func[ub:]

pat = re.compile(r"^([ \t]*\|[ \t]*)ДанныеДокумента\.Подразделение[ \t]+КАК Подразделение,[ \t]*$", re.M)
found = pat.findall(block1)
if len(found) != 1:
    print(f"[FAIL] в блоке 1 ожидалась 1 строка Подразделение, найдено {len(found)}"); sys.exit(4)

new_choose = (
    "\t|\tВЫБОР\n"
    "\t|\t\tКОГДА ДанныеДокумента.А_ПодразделениеОтправитель <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)\n"
    "\t|\t\t\tТОГДА ДанныеДокумента.А_ПодразделениеОтправитель\n"
    "\t|\t\tИНАЧЕ ДанныеДокумента.Подразделение\n"
    "\t|\tКОНЕЦ                                                                             КАК Подразделение,"
)
block1_new = pat.sub(lambda m: new_choose, block1, count=1)
func_new = block1_new + rest
text_new = text[:fs] + func_new + text[fe:]

# контроль: в блоках 2/3 строка Подразделение осталась нетронутой (>=2 простых вхождения в rest)
rest_plain = pat.findall(rest)
if len(rest_plain) < 2:
    print(f"[FAIL] блоки 2/3: ожидалось >=2 простых Подразделение, найдено {len(rest_plain)} — отмена"); sys.exit(5)

with open(MM, "w", encoding="utf-8") as f:
    f.write(text_new)
print("[OK] ManagerModule блок 1 ВПути исправлен (А_ПодразделениеОтправитель + fallback)")

# ============ 2) ObjectModule: процедура + вызов ============
with open(OM, "r", encoding="utf-8") as f:
    om = f.read()

if "А_ЗаполнитьПодразделениеОтправителяПоРКО" in om:
    print("[STOP] процедура А_ЗаполнитьПодразделениеОтправителяПоРКО уже есть"); sys.exit(6)

ps = om.find("Процедура ОбновитьПриходныйКассовыйОрдерПослеОбмена()")
if ps < 0: print("[FAIL] процедура ОбновитьПриходныйКассовыйОрдерПослеОбмена не найдена"); sys.exit(7)
pe = om.find("КонецПроцедуры", ps)
if pe < 0: print("[FAIL] КонецПроцедуры не найден"); sys.exit(8)

proc = om[ps:pe]                       # тело без КонецПроцедуры
marker = "А_ОбработанКазна = Истина;"
idx = proc.rfind(marker)              # последнее вхождение в этой процедуре (перед КонецПроцедуры)
if idx < 0: print("[FAIL] маркер А_ОбработанКазна = Истина не найден в процедуре"); sys.exit(9)
line_start = proc.rfind("\n", 0, idx) + 1

call_block = (
    "\t// Заполнить подразделение/документ отправителя для \"Поступление из другой кассы\"\n"
    "\tЕсли ХозяйственнаяОперация = Перечисления.ХозяйственныеОперации.ПоступлениеДенежныхСредствИзДругойКассы Тогда\n"
    "\t\tА_ЗаполнитьПодразделениеОтправителяПоРКО();\n"
    "\tКонецЕсли;\n"
    "\t\n"
)
proc_new = proc[:line_start] + call_block + proc[line_start:]

proc_lines = [
    "",
    "// Заполняет реквизиты отправителя (А_ПодразделениеОтправитель, А_ДокРасходныйКассовыйОрдерПередачиДенег)",
    "// для ПКО \"Поступление денежных средств из другой кассы\" по парному проведённому РКО",
    "// \"Выдача денежных средств в другую кассу\". Идемпотентна: заполняет ТОЛЬКО при незаполненном А_ПодразделениеОтправитель.",
    "Процедура А_ЗаполнитьПодразделениеОтправителяПоРКО() Экспорт",
    "\t",
    "\tЕсли НЕ ХозяйственнаяОперация = Перечисления.ХозяйственныеОперации.ПоступлениеДенежныхСредствИзДругойКассы Тогда",
    "\t\tВозврат;",
    "\tКонецЕсли;",
    "\t",
    "\tЕсли ЗначениеЗаполнено(А_ПодразделениеОтправитель) Тогда",
    "\t\tВозврат;",
    "\tКонецЕсли;",
    "\t",
    "\tЗапрос = Новый Запрос;",
    "\tЗапрос.Текст =",
    "\t\"ВЫБРАТЬ ПЕРВЫЕ 1",
    "\t|\tРКО.Ссылка        КАК Ссылка,",
    "\t|\tРКО.Подразделение КАК Подразделение",
    "\t|ИЗ",
    "\t|\tДокумент.РасходныйКассовыйОрдер КАК РКО",
    "\t|ГДЕ",
    "\t|\tРКО.Проведен = ИСТИНА",
    "\t|\tИ РКО.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыдачаДенежныхСредствВДругуюКассу)",
    "\t|\tИ РКО.Организация = &Организация",
    "\t|\tИ РКО.КассаПолучатель = &КассаПолучатель",
    "\t|\tИ РКО.СуммаДокумента = &СуммаДокумента",
    "\t|\tИ РКО.Валюта = &Валюта",
    "\t|\tИ РКО.Дата <= &Дата",
    "\t|\tИ (НЕ &ОтправительЗаполнен ИЛИ РКО.Касса = &КассаОтправитель)",
    "\t|УПОРЯДОЧИТЬ ПО",
    "\t|\tРКО.Дата УБЫВ\";",
    "\t",
    "\tЗапрос.УстановитьПараметр(\"Организация\",        Организация);",
    "\tЗапрос.УстановитьПараметр(\"КассаПолучатель\",     Касса);",
    "\tЗапрос.УстановитьПараметр(\"СуммаДокумента\",      СуммаДокумента);",
    "\tЗапрос.УстановитьПараметр(\"Валюта\",              Валюта);",
    "\tЗапрос.УстановитьПараметр(\"Дата\",                Дата);",
    "\tЗапрос.УстановитьПараметр(\"ОтправительЗаполнен\", ЗначениеЗаполнено(КассаОтправитель));",
    "\tЗапрос.УстановитьПараметр(\"КассаОтправитель\",    КассаОтправитель);",
    "\t",
    "\tВыборка = Запрос.Выполнить().Выбрать();",
    "\tЕсли Выборка.Следующий() Тогда",
    "\t\tА_ДокРасходныйКассовыйОрдерПередачиДенег = Выборка.Ссылка;",
    "\t\tА_ПодразделениеОтправитель = Выборка.Подразделение;",
    "\tКонецЕсли;",
    "\t",
    "КонецПроцедуры",
]
new_proc = "\n".join(proc_lines)

before = om[:ps]
after = om[pe:]                       # начинается с "КонецПроцедуры"
kp_nl = after.find("\n")            # конец строки "КонецПроцедуры"
after_new = after[:kp_nl + 1] + "\n" + new_proc + after[kp_nl + 1:]
om_new = before + proc_new + after_new

with open(OM, "w", encoding="utf-8") as f:
    f.write(om_new)
print("[OK] ObjectModule: процедура добавлена + вызов вставлен")

print("\n=== Контроль ManagerModule (блок 1) ===")
for ln in text_new[fs:fs+1400].split("\n"):
    if "А_ПодразделениеОтправитель" in ln or "ПоступлениеДенежныхСредствИзДругойКассы" in ln or ("КАК Подразделение" in ln):
        print("  " + ln)

print("\n=== Контроль ObjectModule (вызов) ===")
oi = om_new.find("А_ЗаполнитьПодразделениеОтправителяПоРКО();")
print("  " + om_new[oi-160:oi+60].replace("\n", "\n  "))
