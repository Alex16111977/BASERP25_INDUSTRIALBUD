"""PILOT РасчетКурсовых Шаг 02 — Диагностика источников переоценки.

РасчетКурсовых ПЕРЕОЦЕНИВАЕТ существующие остатки в РНДС.ВПути.
Подразделение в новых движениях переоценки = Подразделение остатка-источника.

Если остатки-источники (от РКО/ПКО/Спис/Пост) имеют Подр=пусто (старые проводки)
— переоценка тоже будет с пустым Подр (как сейчас).

Диагностика: смотрим какие остатки переоценивает этот документ
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ORG = erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273")
print("=" * 100)
print("Диагностика: валютные остатки в РНДС.ВПути на 31.01.2026 (момент переоценки)")
print("=" * 100)

# Остатки валютных счетов в пути на конец января 2026
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("ВалУпр", erp.Константы.ВалютаУправленческогоУчета.Получить())
q.УстановитьПараметр("ВалРегл", erp.Константы.ВалютаРегламентированногоУчета.Получить())
q.УстановитьПараметр("Дата", datetime.datetime(2026,1,31,23,59,59))
q.Текст = """
ВЫБРАТЬ
    О.Валюта КАК Валюта,
    О.Подразделение КАК Подразделение,
    О.ВидПереводаДенежныхСредств КАК ВидПеревода,
    О.Получатель КАК Получатель,
    О.Отправитель КАК Отправитель,
    О.Контрагент КАК Контрагент,
    О.СуммаОстаток КАК Сумма,
    О.СуммаУпрОстаток КАК СуммаУпр,
    О.СуммаРеглОстаток КАК СуммаРегл
ИЗ РегистрНакопления.ДенежныеСредстваВПути.Остатки(&Дата,
    Организация = &Орг И (Валюта <> &ВалУпр ИЛИ Валюта <> &ВалРегл)) КАК О
ГДЕ О.СуммаОстаток <> 0
"""
r = q.Выполнить().Выгрузить()
print(f"\nВалютных остатков на 31.01.2026: {r.Количество()}")
for i in range(r.Количество()):
    rec = r.Получить(i)
    podr = S(rec.Подразделение) if erp.ЗначениеЗаполнено(rec.Подразделение) else "(пусто)"
    val = S(rec.Валюта)
    vp = S(rec.ВидПеревода) if erp.ЗначениеЗаполнено(rec.ВидПеревода) else ""
    get_ = S(rec.Получатель) if erp.ЗначениеЗаполнено(rec.Получатель) else "—"
    otp_ = S(rec.Отправитель) if erp.ЗначениеЗаполнено(rec.Отправитель) else "—"
    print(f"  {val} Σ={rec.Сумма}  Упр={rec.СуммаУпр}  Регл={rec.СуммаРегл}  Подр={podr}")
    print(f"     {vp[:30]:<32}  {otp_} → {get_}")

print("\nВЫВОДЫ:")
print("  ⚠ Если все остатки с Подр=(пусто) — РасчетКурсовых тоже даст пустое Подр")
print("  ⚠ Источники остатков (РКО/ПКО/Спис/Пост) уже доработаны 2026-05-24,")
print("    но СТАРЫЕ записи (до перепроведения исходных документов) сохраняют пустое Подр")
print("  → Чтобы РасчетКурсовых получил Подр — нужно сначала перепровести")
print("    исходные документы которые формировали остатки")
