# -*- coding: utf-8 -*-
"""
Доп-проверка безопасности тай-брейкера для коллизий (>1 кандидат).
Вопросы:
  Q1. ПЕРВЫЕ 1 (Дата УБЫВ, Номер УБЫВ) выбирает Списание с ТОЙ ЖЕ Датой, что и Поступление?
  Q2. Среди всех 174 коллизий — отличаются ли Подразделения кандидатов?
      (если все кандидаты одного Подразделения => даже "неверный" выбор не портит результат)
"""
from _common import connect_erp

erp = connect_erp()

ТЕКСТ_МАТЧ = """
ВЫБРАТЬ {ПЕРВЫЕ}
    Спис.Подразделение КАК Подразделение,
    Спис.Дата          КАК Дата,
    Спис.Номер         КАК Номер
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Спис
ГДЕ
    Спис.Проведен = ИСТИНА
    И Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)
    И Спис.Организация = &Организация
    И Спис.БанковскийСчетПолучатель = &СчетПолучатель
    И Спис.БанковскийСчет = &СчетОтправитель
    И Спис.СуммаДокумента = &СуммаДокумента
    И Спис.Валюта = &Валюта
    И Спис.Дата <= &ДатаПоступления
УПОРЯДОЧИТЬ ПО Спис.Дата УБЫВ, Спис.Номер УБЫВ
"""


def q_match(пост, первые_1=True):
    q = erp.NewObject("Запрос")
    q.Text = ТЕКСТ_МАТЧ.replace("{ПЕРВЫЕ}", "ПЕРВЫЕ 1" if первые_1 else "")
    q.SetParameter("Организация",     пост["Организация"])
    q.SetParameter("СчетПолучатель",  пост["БанковскийСчет"])
    q.SetParameter("СчетОтправитель", пост["БанковскийСчетОтправитель"])
    q.SetParameter("СуммаДокумента",  пост["СуммаДокумента"])
    q.SetParameter("Валюта",          пост["Валюта"])
    q.SetParameter("ДатаПоступления", пост["Дата"])
    return q


qAll = erp.NewObject("Запрос")
qAll.Text = """
ВЫБРАТЬ
    Пост.Номер                     КАК Номер,
    Пост.Дата                      КАК Дата,
    Пост.Организация               КАК Организация,
    Пост.БанковскийСчет            КАК БанковскийСчет,
    Пост.БанковскийСчетОтправитель КАК БанковскийСчетОтправитель,
    Пост.СуммаДокумента            КАК СуммаДокумента,
    Пост.Валюта                    КАК Валюта
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пост
ГДЕ Пост.Проведен = ИСТИНА
    И Пост.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
"""
selAll = qAll.Execute().Выбрать()

коллизий = 0
коллизий_разные_подр = 0          # критично: кандидаты в РАЗНЫХ подразделениях
выбор_не_та_дата = 0              # ПЕРВЫЕ 1 выбрал Списание с Датой != Дата Поступления
выбор_не_та_дата_примеры = []
разные_подр_примеры = []

while selAll.Следующий():
    пост = {
        "Дата":                    selAll.Дата,
        "Организация":             selAll.Организация,
        "БанковскийСчет":          selAll.БанковскийСчет,
        "БанковскийСчетОтправитель": selAll.БанковскийСчетОтправитель,
        "СуммаДокумента":          selAll.СуммаДокумента,
        "Валюта":                  selAll.Валюта,
    }
    вм = q_match(пост, первые_1=False).Execute().Выбрать()
    канд = []
    while вм.Следующий():
        канд.append((str(вм.Номер).strip(), str(вм.Дата), erp.String(вм.Подразделение)))
    if len(канд) <= 1:
        continue
    коллизий += 1
    подр_set = set(c[2] for c in канд)
    if len(подр_set) > 1:
        коллизий_разные_подр += 1
        if len(разные_подр_примеры) < 5:
            разные_подр_примеры.append((str(selAll.Номер).strip(), str(selAll.Дата), канд))
    # что выберет ПЕРВЫЕ 1
    вп = q_match(пост, первые_1=True).Execute().Выбрать()
    if вп.Следующий():
        if str(вп.Дата) != str(selAll.Дата):
            выбор_не_та_дата += 1
            if len(выбор_не_та_дата_примеры) < 5:
                выбор_не_та_дата_примеры.append(
                    (str(selAll.Номер).strip(), str(selAll.Дата),
                     str(вп.Номер).strip(), str(вп.Дата), erp.String(вп.Подразделение)))

print("Коллизий (>1 кандидат):", коллизий)
print("  из них кандидаты в РАЗНЫХ подразделениях:", коллизий_разные_подр)
print("  ПЕРВЫЕ 1 выбрал Списание с Датой != Дата Поступления:", выбор_не_та_дата)

if разные_подр_примеры:
    print("\n[!] Коллизии с РАЗНЫМИ подразделениями (реальный риск):")
    for ном, дата, канд in разные_подр_примеры:
        print(f"  Поступление {ном} ({дата}):")
        for сн, сд, сп in канд:
            print(f"     Списание {сн} {сд} Подр={сп}")
else:
    print("\n[OK] Во ВСЕХ коллизиях кандидаты в ОДНОМ подразделении => выбор любого кандидата даёт верное Подразделение.")

if выбор_не_та_дата_примеры:
    print("\n[i] Где ПЕРВЫЕ 1 выбрал Списание другой даты (не мгновение Поступления):")
    for пн, пд, сн, сд, сп in выбор_не_та_дата_примеры:
        print(f"  Пост {пн} {пд} -> Спис {сн} {сд} Подр={сп}")
else:
    print("[OK] ПЕРВЫЕ 1 всегда выбирает Списание той же даты, что и Поступление.")
