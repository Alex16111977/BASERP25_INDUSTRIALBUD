# -*- coding: utf-8 -*-
"""
Rule #-1 pre-test: матчинг парного Списания для Поступления "Поступление с другого счёта".
Эталон: Поступление 00DL-006964 (01.12.2025, 9 641 228,35 UAH)
        -> Списание 000Ц-000090, Спис.Подразделение=Строительство.
1:1 как будет в BSL ObjectModule.А_ЗаполнитьПодразделениеОтправителяПоСписанию().

Критерии матчинга (Спис. = Списание, Пост. = Поступление):
  Спис.Проведен
  И Спис.ХозОп = ПеречислениеДенежныхСредствНаДругойСчет
  И Спис.Организация              = Пост.Организация
  И Спис.БанковскийСчетПолучатель = Пост.БанковскийСчет           (счёт-получатель)
  И Спис.БанковскийСчет           = Пост.БанковскийСчетОтправитель (счёт-отправитель)
  И Спис.СуммаДокумента           = Пост.СуммаДокумента
  И Спис.Валюта                   = Пост.Валюта
  И Спис.Дата                    <= Пост.Дата
ПЕРВЫЕ 1 УПОРЯДОЧИТЬ ПО Спис.Дата УБЫВ, Спис.Номер УБЫВ  (тай-брейкер).
"""
from _common import connect_erp

erp = connect_erp()

ТЕКСТ_МАТЧ = """
ВЫБРАТЬ {ПЕРВЫЕ}
    Спис.Ссылка        КАК Ссылка,
    Спис.Подразделение КАК Подразделение,
    Спис.Дата          КАК Дата,
    Спис.Номер         КАК Номер
ИЗ
    Документ.СписаниеБезналичныхДенежныхСредств КАК Спис
ГДЕ
    Спис.Проведен = ИСТИНА
    И Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)
    И Спис.Организация = &Организация
    И Спис.БанковскийСчетПолучатель = &СчетПолучатель
    И Спис.БанковскийСчет = &СчетОтправитель
    И Спис.СуммаДокумента = &СуммаДокумента
    И Спис.Валюта = &Валюта
    И Спис.Дата <= &ДатаПоступления
УПОРЯДОЧИТЬ ПО
    Спис.Дата УБЫВ,
    Спис.Номер УБЫВ
"""


def построить_запрос(пост, первые_1=True):
    q = erp.NewObject("Запрос")
    q.Text = ТЕКСТ_МАТЧ.replace("{ПЕРВЫЕ}", "ПЕРВЫЕ 1" if первые_1 else "")
    q.SetParameter("Организация",     пост["Организация"])
    q.SetParameter("СчетПолучатель",  пост["БанковскийСчет"])           # счёт Поступления = счёт-получатель Списания
    q.SetParameter("СчетОтправитель", пост["БанковскийСчетОтправитель"])
    q.SetParameter("СуммаДокумента",  пост["СуммаДокумента"])
    q.SetParameter("Валюта",          пост["Валюта"])
    q.SetParameter("ДатаПоступления", пост["Дата"])
    return q


# ============================================================
# ЧАСТЬ 1. ЭТАЛОН 00DL-006964
# ============================================================
print("=" * 64)
print("ЧАСТЬ 1. ЭТАЛОН: Поступление 00DL-006964")
print("=" * 64)

qP = erp.NewObject("Запрос")
qP.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Пост.Ссылка                  КАК Ссылка,
    Пост.Дата                    КАК Дата,
    Пост.Организация             КАК Организация,
    Пост.БанковскийСчет          КАК БанковскийСчет,
    Пост.БанковскийСчетОтправитель КАК БанковскийСчетОтправитель,
    Пост.СуммаДокумента          КАК СуммаДокумента,
    Пост.Валюта                  КАК Валюта,
    Пост.ХозяйственнаяОперация   КАК ХозОп,
    Пост.А_ПодразделениеОтправитель КАК А_ПодразделениеОтправитель,
    Пост.А_СписаниеБезналичныхДенежныхСредств КАК А_Списание
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пост
ГДЕ Пост.Номер = &Номер
"""
qP.SetParameter("Номер", "00DL-006964")
try:
    selP = qP.Execute().Выбрать()
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL Поступление lookup:", info[2] if info else e); raise SystemExit

if not selP.Следующий():
    print("Поступление 00DL-006964 не найдено"); raise SystemExit

пост = {
    "Ссылка":                  selP.Ссылка,
    "Дата":                    selP.Дата,
    "Организация":             selP.Организация,
    "БанковскийСчет":          selP.БанковскийСчет,
    "БанковскийСчетОтправитель": selP.БанковскийСчетОтправитель,
    "СуммаДокумента":          selP.СуммаДокумента,
    "Валюта":                  selP.Валюта,
}
print("Дата:", selP.Дата)
print("Организация:", erp.String(selP.Организация))
print("БанковскийСчет (получатель):", erp.String(selP.БанковскийСчет))
print("БанковскийСчетОтправитель:", erp.String(selP.БанковскийСчетОтправитель))
print("СуммаДокумента:", selP.СуммаДокумента)
print("Валюта:", erp.String(selP.Валюта))
print("ХозОп:", erp.XMLСтрока(selP.ХозОп))
print("Текущ. А_ПодразделениеОтправитель:", erp.String(selP.А_ПодразделениеОтправитель))
print("Текущ. А_Списание:", erp.String(selP.А_Списание))

print("\n--- ПОИСК ПАРНОГО СПИСАНИЯ (ПЕРВЫЕ 1 + тай-брейкер) ---")
try:
    рез = построить_запрос(пост, первые_1=True).Execute()
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL match query:", info[2] if info else e); raise SystemExit

выб = рез.Выбрать()
n = 0
найден_подр = найден_ссылка = найден_номер = None
while выб.Следующий():
    n += 1
    найден_подр   = выб.Подразделение
    найден_ссылка = выб.Ссылка
    найден_номер  = выб.Номер
    print(f"  Списание Номер={выб.Номер} Дата={выб.Дата} Подразделение={erp.String(выб.Подразделение)}")

print("Найдено строк (ПЕРВЫЕ 1):", n)
verdict = "FAIL"
if n == 1:
    ok_num  = (str(найден_номер).strip() == "000Ц-000090")
    ok_podr = (erp.String(найден_подр) == "Строительство")
    print("VERIFY Номер == '000Ц-000090':", "PASS" if ok_num else f"FAIL (={найден_номер})")
    print("VERIFY Подразделение == 'Строительство':", "PASS" if ok_podr else f"FAIL (={erp.String(найден_подр)})")
    verdict = "PASS" if (ok_num and ok_podr) else "FAIL"
else:
    print("Ожидалось ровно 1 совпадение, получено:", n)
print(">>> ЧАСТЬ 1 ВЕРДИКТ:", verdict)

# ============================================================
# ЧАСТЬ 2. СТАТИСТИКА ПО ВСЕЙ БАЗЕ (риск коллизий ДО тай-брейкера)
# ============================================================
print("\n" + "=" * 64)
print("ЧАСТЬ 2. СТАТИСТИКА ПО ВСЕЙ БАЗЕ")
print("=" * 64)

qAll = erp.NewObject("Запрос")
qAll.Text = """
ВЫБРАТЬ
    Пост.Ссылка                    КАК Ссылка,
    Пост.Номер                     КАК Номер,
    Пост.Дата                      КАК Дата,
    Пост.Организация               КАК Организация,
    Пост.БанковскийСчет            КАК БанковскийСчет,
    Пост.БанковскийСчетОтправитель КАК БанковскийСчетОтправитель,
    Пост.СуммаДокумента            КАК СуммаДокумента,
    Пост.Валюта                    КАК Валюта
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пост
ГДЕ
    Пост.Проведен = ИСТИНА
    И Пост.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
УПОРЯДОЧИТЬ ПО
    Пост.Дата
"""
try:
    selAll = qAll.Execute().Выбрать()
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL all-Поступления query:", info[2] if info else e); raise SystemExit

cnt_total = 0
cnt_1 = 0
cnt_0 = 0
cnt_many = 0
примеры_many = []  # (НомерПост, ДатаПост, число_совпадений, [(НомерСпис,ДатаСпис,Подр), ...])

while selAll.Следующий():
    cnt_total += 1
    пост_i = {
        "Дата":                    selAll.Дата,
        "Организация":             selAll.Организация,
        "БанковскийСчет":          selAll.БанковскийСчет,
        "БанковскийСчетОтправитель": selAll.БанковскийСчетОтправитель,
        "СуммаДокумента":          selAll.СуммаДокумента,
        "Валюта":                  selAll.Валюта,
    }
    # БЕЗ ПЕРВЫЕ 1 — считаем все кандидаты ДО тай-брейкера
    qm = построить_запрос(пост_i, первые_1=False)
    try:
        вм = qm.Execute().Выбрать()
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        print("FAIL match for", selAll.Номер, ":", info[2] if info else e); continue
    кандидаты = []
    while вм.Следующий():
        кандидаты.append((str(вм.Номер).strip(), str(вм.Дата), erp.String(вм.Подразделение)))
    k = len(кандидаты)
    if k == 1:
        cnt_1 += 1
    elif k == 0:
        cnt_0 += 1
    else:
        cnt_many += 1
        if len(примеры_many) < 5:
            примеры_many.append((str(selAll.Номер).strip(), str(selAll.Дата), k, кандидаты))

print(f"Всего проведённых Поступлений (ХозОп=ПоступлениеДенежныхСредствСДругогоСчета): {cnt_total}")
print(f"  -> ровно 1 совпадение:  {cnt_1}")
print(f"  -> 0 совпадений:        {cnt_0}")
print(f"  -> >1 совпадение:       {cnt_many}")

if cnt_total:
    pct1 = 100.0 * cnt_1 / cnt_total
    print(f"  доля однозначных матчей: {pct1:.1f}%")

if примеры_many:
    print("\n--- Примеры коллизий (>1 кандидат до тай-брейкера) ---")
    for номер, дата, k, кандидаты in примеры_many:
        print(f"  Поступление {номер} ({дата}) -> {k} кандидатов:")
        for сн, сд, сп in кандидаты:
            print(f"       Списание {сн}  {сд}  Подр={сп}")
else:
    print("\nКоллизий (>1 кандидат) НЕ обнаружено.")

print("\n=== КОНЕЦ ===")
