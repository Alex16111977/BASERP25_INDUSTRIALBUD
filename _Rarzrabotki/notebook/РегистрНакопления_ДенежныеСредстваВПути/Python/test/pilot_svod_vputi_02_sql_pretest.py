# -*- coding: utf-8 -*-
"""PILOT Свод_ДенежныеСредства Шаг 02 — Pre-test SQL (Rule #-1).

Прогоняем ТОЛЬКО 4-ю ветку UNION ALL отдельным запросом до записи в BSL.
Verify:
- запрос синтаксически валиден
- колонка Подразделение присутствует
- Σ КО per Орг == ожидаемый агрегат из baseline.json (плуги ВПути.КО = 133 447,50)
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ORG = erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273")
print(f"Org: {S(ORG)}")

# Резолв СтВПути и ИстВПути
q_st = erp.NewObject("Запрос")
q_st.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Денежные средства в пути"'
sel = q_st.Выполнить().Выбрать(); sel.Следующий()
СтВПути = sel.Ссылка
print(f"СтВПути: {S(СтВПути)}")

# ИстВПути — Перечисление.ИсточникиУправленческогоБаланса.ДенежныеСредстваВПути
ИстВПути = erp.Перечисления.ИсточникиУправленческогоБаланса.ДенежныеСредстваВПути
print(f"ИстВПути: {S(ИстВПути)}")

# Параметры периода (как в Свод_ДенежныеСредства для январь 2026)
НачМес = datetime.datetime(2026, 1, 1, 0, 0, 0)
КонМес = datetime.datetime(2026, 1, 31, 23, 59, 59)

print()
print("=" * 80)
print("PRE-TEST: 4-я ветка UNION ALL (РегистрНакопления.ДенежныеСредстваВПути)")
print("=" * 80)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("НачМес", НачМес)
q.УстановитьПараметр("КонМес", КонМес)
q.УстановитьПараметр("СтВПути", СтВПути)
q.УстановитьПараметр("ИстВПути", ИстВПути)
q.Текст = """
ВЫБРАТЬ
	ВП.Организация КАК Организация,
	ЕСТЬNULL(ВП.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подразделение,
	&СтВПути КАК Статья,
	&ИстВПути КАК Source,
	ВЫБОР КОГДА ВП.Получатель = НЕОПРЕДЕЛЕНО ТОГДА ВП.Отправитель ИНАЧЕ ВП.Получатель КОНЕЦ КАК ДенежныеСредства,
	ЗНАЧЕНИЕ(Справочник.ФизическиеЛица.ПустаяСсылка) КАК ФизическоеЛицо,
	СУММА(ВП.СуммаНачальныйОстаток) КАК СуммаНачальныйОстаток,
	СУММА(ВП.СуммаКонечныйОстаток) КАК СуммаКонечныйОстаток
ИЗ
	РегистрНакопления.ДенежныеСредстваВПути.ОстаткиИОбороты(&НачМес, &КонМес, , , Организация = &Орг) КАК ВП
СГРУППИРОВАТЬ ПО
	ВП.Организация,
	ЕСТЬNULL(ВП.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)),
	ВЫБОР КОГДА ВП.Получатель = НЕОПРЕДЕЛЕНО ТОГДА ВП.Отправитель ИНАЧЕ ВП.Получатель КОНЕЦ
"""

try:
    r = q.Выполнить().Выгрузить()
    print(f"[OK] Строк: {r.Количество()}")
    cols = [c.Имя for c in r.Колонки]
    print(f"Колонки: {cols}")
    assert "Подразделение" in cols, "Подразделение отсутствует!"
    print("  ✓ Колонка Подразделение присутствует")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print(f"[FAIL] {info[2] if info else e}"); sys.exit(1)

# Σ КО + примеры строк
total_no = 0.0
total_ko = 0.0
print()
print(f"{'Подразделение':<35} {'ДС':<35} {'НО':>16}  {'КО':>16}")
print("-" * 110)
for i in range(r.Количество()):
    rec = r.Получить(i)
    podr = S(rec.Подразделение) if erp.ЗначениеЗаполнено(rec.Подразделение) else "(пусто)"
    ds_v = rec.ДенежныеСредства
    ds = S(ds_v) if (ds_v is not None and erp.ЗначениеЗаполнено(ds_v)) else "—"
    но = float(rec.СуммаНачальныйОстаток or 0)
    ко = float(rec.СуммаКонечныйОстаток or 0)
    total_no += но
    total_ko += ко
    print(f"{podr[:35]:<35} {ds[:35]:<35} {но:>16,.2f}  {ко:>16,.2f}")

print("-" * 110)
print(f"{'Σ':<71} {total_no:>16,.2f}  {total_ko:>16,.2f}")
print()

# Сравнение с baseline (плуги ВПути.КО=133 447,50)
import json, os
ART = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_artifacts")
with open(os.path.join(ART, "pilot_svod_vputi_01_baseline.json"), encoding="utf-8") as f:
    baseline = json.load(f)
plug_ko = sum(r["КО"] for r in baseline["statyas"]["ВПути"]["rows"] if r["Расхождение"])
plug_no = sum(r["НО"] for r in baseline["statyas"]["ВПути"]["rows"] if r["Расхождение"])
print(f"Baseline плуг ВПути: НО={plug_no:,.2f}  КО={plug_ko:,.2f}")
print(f"Pre-test Σ:         НО={total_no:,.2f}  КО={total_ko:,.2f}")
print(f"Δ НО: {total_no - plug_no:+,.2f}")
print(f"Δ КО: {total_ko - plug_ko:+,.2f}")
if abs(total_ko - plug_ko) < 0.5:
    print()
    print("[OK] Σ КО pre-test ≈ Σ КО плугов baseline — после доработки плуги станут деталями")
else:
    print()
    print("[WARN] Расхождение Σ КО — нужно понять источник (м.б. в РНДС.ВПути есть данные не покрытые ПАП)")
