import win32com.client as w

erp = w.Dispatch("V83.COMConnector").Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
ref = erp.Документы.А_ОтражениеЗПпоКазне.НайтиПоНомеру("000000001")
ob = ref.ПолучитьОбъект()
ob.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()   # перезагрузка ТЧ из zup_1 (в памяти)

print("УдержанияБухгалтерия Гуняги после правки:")
ok = False
for i in range(ob.УдержанияБухгалтерия.Количество()):
    s = ob.УдержанияБухгалтерия.Получить(i)
    if erp.ЗначениеЗаполнено(s.ФизическоеЛицо) and s.ФизическоеЛицо.Наименование.startswith("Гуняга"):
        ст = s.СтатьяАктивовПассивов.Наименование if erp.ЗначениеЗаполнено(s.СтатьяАктивовПассивов) else "<пусто>"
        сч = s.СчетУчета.Код if erp.ЗначениеЗаполнено(s.СчетУчета) else "<пусто>"
        пол = s.Субконто1.Наименование if erp.ЗначениеЗаполнено(s.Субконто1) else "<нет>"
        print(f"   Σ={s.Сумма} | статья={ст} | счёт={сч} | Субконто1={пол}")
        ok = (abs(s.Сумма - 400) < 0.01 and ст == "Денежные средства (у подотчетных лиц)"
              and сч == "3721" and not erp.ЗначениеЗаполнено(s.Субконто1))
print("ИТОГ Гуняга:", "GREEN ✅" if ok else "RED ❌")

# Регрессия: алименты (счёт 6853) на месте
