# -*- coding: utf-8 -*-
# Verify Stage 4: перенос Ф1-only. ПОЛНЫЙ ПРОГОН С СОХРАНЕНИЕМ (родитель+ОЗФУ+перенос).
# Суммы сохраняются + ФормаPL; перенос берёт только Форма1.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")
q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка, Номер КАК Номер ИЗ Документ.А_ОтражениеЗПпоКазне "
           "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2026,4,1,0,0,0) И ДАТАВРЕМЯ(2026,4,30,23,59,59) УПОРЯДОЧИТЬ ПО Дата")
sel = q.Выполнить().Выбрать(); sel.Следующий()
print(f"Родитель: №{sel.Номер}")
obj = sel.Ссылка.ПолучитьОбъект()

РежимПровед = erp.РежимЗаписиДокумента.Проведение
print("Наполнение + СОХРАНЕНИЕ родителя (с разметкой ФормаPL)...")
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
obj.ЗаполнитьОтражениеЗарплатыВФинансовомУчетеИзБазЗП()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
try:
    obj.Записать(РежимПровед)
    print("  Родитель сохранён+проведён.")
except Exception as e:
    print("  FAIL save родителя:", e.excepinfo[2] if (hasattr(e,'excepinfo') and e.excepinfo) else e); sys.exit(1)

print("Создание ОЗФУ + переноса (Ф1-only)...")
obj.СоздатьДокументОтражениеЗарплатыВФинансовомУчете()
obj.СоздатьПередачуНачисленийМеждуПодразделениями()

# Найти перенос
qp = erp.NewObject("Запрос")
qp.УстановитьПараметр("Осн", sel.Ссылка)
qp.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка, П.Номер КАК Номер, П.Проведен КАК Проведен "
            "ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями КАК П "
            "ГДЕ П.А_ДокументОснование = &Осн И НЕ П.ПометкаУдаления")
sp = qp.Выполнить().Выбрать()
if not sp.Следующий():
    print("FAIL: перенос не найден"); sys.exit(1)
print(f"\nПеренос: №{sp.Номер} проведён={sp.Проведен}")
п = sp.Ссылка.ПолучитьОбъект()
sНач = sum(float(r.Сумма) for r in п.Начисления)
sНал = sum(float(r.Сумма) for r in п.Налоги)
sУд  = sum(float(r.Сумма) for r in п.Удержания)
print(f"  ТЧ Начисления: {п.Начисления.Количество()} строк, Σ={sНач:,.2f}")
print(f"  ТЧ Налоги:     {п.Налоги.Количество()} строк, Σ={sНал:,.2f}")
print(f"  ТЧ Удержания:  {п.Удержания.Количество()} строк, Σ={sУд:,.2f}")

# ПАП net-zero по переносу (Σ по статье должна быть 0: реверс+копия)
qb = erp.NewObject("Запрос")
qb.УстановитьПараметр("Рег", sp.Ссылка)
qb.Текст = ("ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(ПАП.Статья) КАК Статья, "
            "СУММА(ВЫБОР КОГДА ПАП.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Сальдо "
            "ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП ГДЕ ПАП.Регистратор=&Рег СГРУППИРОВАТЬ ПО ПАП.Статья")
print("\nПАП переноса (net-zero ожидается 0 по каждой статье):")
вб = qb.Выполнить().Выбрать(); maxabs = 0.0
while вб.Следующий():
    print(f"  {вб.Статья:25} Сальдо={float(вб.Сальдо):,.2f}")
    maxabs = max(maxabs, abs(float(вб.Сальдо)))
print(f"  net-zero: {'OK' if maxabs < 0.5 else 'FAIL'} (max|Сальдо|={maxabs:,.2f})")

# А_ВзСС net-zero
qv = erp.NewObject("Запрос")
qv.УстановитьПараметр("Рег", sp.Ссылка)
qv.Текст = ("ВЫБРАТЬ СУММА(ВЫБОР КОГДА В.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА В.Сумма ИНАЧЕ -В.Сумма КОНЕЦ) КАК С "
            "ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК В ГДЕ В.Регистратор=&Рег")
вв = qv.Выполнить().Выбрать(); вв.Следующий()
взсс = float(вв.С) if вв.С is not None else 0.0
print(f"А_ВзСС переноса Σ = {взсс:,.2f} ({'OK' if abs(взсс)<0.5 else 'FAIL'})")

erp = None
print("\nDone (ЭТАЛОН СОХРАНЁН: родитель+ОЗФУ+перенос перепроведены с ФормаPL).")
