import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")

def run(text):
    q = erp.NewObject("Запрос"); q.Текст = text
    return q.Выполнить().Выгрузить()

PER = 'ГОД(%(a)s)=2026 И МЕСЯЦ(%(a)s)=2'

# 1) НачисленияБух per (ФЛ, Орг) — бух GROSS истина
tz = run("""ВЫБРАТЬ НБ.ФизЛицо.Наименование КАК ФИО, НБ.Организация.Наименование КАК Орг, СУММА(НБ.Сумма) КАК С
ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленияБух КАК НБ
ГДЕ """ + (PER % {'a':'НБ.Ссылка.Дата'}) + """ И НЕ НБ.Ссылка.ПометкаУдаления
СГРУППИРОВАТЬ ПО НБ.ФизЛицо.Наименование, НБ.Организация.Наименование""")
buh = {}
for i in range(tz.Количество()):
    r = tz.Получить(i); buh.setdefault(r.ФИО, {})[r.Орг] = round(float(r.С), 2)

# 2) НЗ Форма1 per (ФЛ, ОргБух)
tz = run("""ВЫБРАТЬ НЗ.ФизическоеЛицо.Наименование КАК ФИО, НЗ.ОрганизацияБухгалтерия.Наименование КАК Орг, СУММА(НЗ.Сумма) КАК С
ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленнаяЗарплатаИВзносыПоФизлицам КАК НЗ
ГДЕ """ + (PER % {'a':'НЗ.Ссылка.Дата'}) + """ И НЕ НЗ.Ссылка.ПометкаУдаления
  И НЗ.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
СГРУППИРОВАТЬ ПО НЗ.ФизическоеЛицо.Наименование, НЗ.ОрганизацияБухгалтерия.Наименование""")
nz1 = {}
for i in range(tz.Количество()):
    r = tz.Получить(i); nz1.setdefault(r.ФИО, {})[r.Орг or "(пусто)"] = round(float(r.С), 2)

# 3) А_ВзСС Форма1 per (ФЛ, ОргБух): Приход / Расход
tz = run("""ВЫБРАТЬ ВзС.ФизическоеЛицо.Наименование КАК ФИО, ВзС.ОрганизацияБухгалтерия.Наименование КАК Орг,
  СУММА(ВЫБОР КОГДА ВзС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК Приход,
  СУММА(ВЫБОР КОГДА ВзС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК Расход
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзС
ГДЕ """ + (PER % {'a':'ВзС.Период'}) + """ И ВзС.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
СГРУППИРОВАТЬ ПО ВзС.ФизическоеЛицо.Наименование, ВзС.ОрганизацияБухгалтерия.Наименование""")
vz1 = {}
for i in range(tz.Количество()):
    r = tz.Получить(i); vz1.setdefault(r.ФИО, {})[r.Орг or "(пусто)"] = (round(float(r.Приход),2), round(float(r.Расход),2))

multi = [ф for ф in buh if len(buh[ф]) > 1]
print(f"\n=== Multi-org сотрудников: {len(multi)} ===")
print(f"{'ФИО':38} {'Орг':26} {'НачБух':>11} {'НЗ-Ф1':>11} {'ВзСС-Прих':>11} {'ВзСС-Расх':>11} {'Кон.ост':>10}")
total_plug = 0.0
for ф in sorted(multi):
    orgs = set(buh.get(ф,{})) | set(nz1.get(ф,{})) | set(vz1.get(ф,{}))
    for o in sorted(orgs):
        gb = buh.get(ф,{}).get(o, 0.0)
        n1 = nz1.get(ф,{}).get(o, 0.0)
        pr, rs = vz1.get(ф,{}).get(o, (0.0,0.0))
        kon = round(pr - rs, 2)
        flag = "  <-- ПЛУГ" if abs(kon) > 0.01 else ""
        total_plug += abs(kon)
        print(f"{ф[:37]:38} {o[:25]:26} {gb:11,.2f} {n1:11,.2f} {pr:11,.2f} {rs:11,.2f} {kon:10,.2f}{flag}")
    print("-"*120)
print(f"Σ |Кон.остаток| (плуги) по multi-org Форма1: {total_plug:,.2f}")

# === Аулова deep-dive ===
A = "Аулова Маргарита Володимирівна"
print(f"\n=== Аулова: РаспределениеКазна — источник Орг (Форма1) ===")
tz = run("""ВЫБРАТЬ
  ВЫРАЗИТЬ(РК.ДокРаспределениеЗП КАК Документ.А_РаспределениеЗаработнойПлаты).Организация.Наименование КАК ОргРаспред,
  РК.Подразделение.Наименование КАК Подр, СУММА(РК.Сумма) КАК Сумма, СУММА(РК.СуммаНачисления) КАК Нач
ИЗ Документ.А_ОтражениеЗПпоКазне.РаспределениеКазна КАК РК
ГДЕ """ + (PER % {'a':'РК.Ссылка.Дата'}) + """ И РК.Сотрудник.ФизическоеЛицо.Наименование = \"""" + A + """\"
  И РК.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
СГРУППИРОВАТЬ ПО ВЫРАЗИТЬ(РК.ДокРаспределениеЗП КАК Документ.А_РаспределениеЗаработнойПлаты).Организация.Наименование, РК.Подразделение.Наименование""")
for i in range(tz.Количество()):
    r = tz.Получить(i)
    print(f"   ОргРаспред={r.ОргРаспред!r:30} Подр={r.Подр!r:18} Сумма={float(r.Сумма):11,.2f} Нач={float(r.Нач):11,.2f}")

print(f"\n=== Аулова: НалогиБухгалтерия per-org (НДФЛ / ВЗ / ЕСВ) ===")
tz = run("""ВЫБРАТЬ НБ.Организация.Наименование КАК Орг,
  СУММА(ВЫБОР КОГДА НБ.ТипНалога=ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.НДФЛ) ТОГДА НБ.Сумма ИНАЧЕ 0 КОНЕЦ) КАК НДФЛ,
  СУММА(ВЫБОР КОГДА НБ.ТипНалога=ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.ВоенныйСбор) ТОГДА НБ.Сумма ИНАЧЕ 0 КОНЕЦ) КАК ВЗ,
  СУММА(ВЫБОР КОГДА НБ.ТипНалога=ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.НачисленныйЕСВ) ТОГДА НБ.СуммаФОТ ИНАЧЕ 0 КОНЕЦ) КАК ЕСВ
ИЗ Документ.А_ОтражениеЗПпоКазне.НалогиБухгалтерия КАК НБ
ГДЕ """ + (PER % {'a':'НБ.Ссылка.Дата'}) + """ И НБ.Сотрудник.ФизическоеЛицо.Наименование = \"""" + A + """\"
СГРУППИРОВАТЬ ПО НБ.Организация.Наименование""")
for i in range(tz.Количество()):
    r = tz.Получить(i)
    print(f"   Орг={r.Орг[:25]:26} НДФЛ={float(r.НДФЛ):10,.2f} ВЗ={float(r.ВЗ):10,.2f} ЕСВ={float(r.ЕСВ):10,.2f}")

# Формула: Ф1_орг = Ф1_ФЛ * GROSS_орг / GROSS_ФЛ ?
print(f"\n=== Аулова: проверка gross-пропорциональной формулы ===")
gtot = sum(buh.get(A,{}).values())
f1tot = sum(nz1.get(A,{}).values())
print(f"   GROSS_ФЛ={gtot:,.2f}  Форма1_ФЛ(НЗ)={f1tot:,.2f}")
for o, g in sorted(buh.get(A,{}).items()):
    pred = round(f1tot * g / gtot, 2)
    fact_pr = vz1.get(A,{}).get(o,(0,0))[0]
    fact_rs = vz1.get(A,{}).get(o,(0,0))[1]
    print(f"   {o[:25]:26} GROSS={g:11,.2f}  предсказ Ф1={pred:11,.2f}  факт ВзСС-Приход={fact_pr:11,.2f}  факт ВзСС-Расход={fact_rs:11,.2f}")

erp = None
print("\nDone.")
