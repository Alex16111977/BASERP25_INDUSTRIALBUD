def test_month(y, m):
    nm = datetime.datetime(y, m, 1, 0, 0, 0)
    # конец месяца
    if m == 12:
        km = datetime.datetime(y, 12, 31, 23, 59, 59)
    else:
        km = datetime.datetime(y, m + 1, 1, 0, 0, 0) - datetime.timedelta(seconds=1)
    q = zup.NewObject("Запрос")
    q.Текст = QTEXT
    q.УстановитьПараметр("НачалоПериода", nm)
    q.УстановитьПараметр("КонецПериода", km)
    q.УстановитьПараметр("масКодПоЕДРПОУ", arr)
    try:
        r = q.Выполнить().Выгрузить()
        n = r.Количество()
        s = 0.0
        for i in range(n):
            s += float(r.Получить(i).Сумма)
        print(f"\n=== {y}-{m:02d}: OK rows={n}, Σ={s:,.2f}")
        for i in range(min(5, n)):
            row = r.Получить(i)
            print(f"  ИНН={row.СотрудникИНН} | {row.СотрудникНаименование} | вид='{row.ВидРасчета}' код={row.КодВидРасчета} | {float(row.Сумма):,.2f} | ЕДРПОУ={row.КодПоЕДРПОУ}")
        # уникальные виды расчёта
        vids = {}
        for i in range(n):
            row = r.Получить(i)
            vids[row.КодВидРасчета] = row.ВидРасчета
        print(f"  Уникальных видов расчёта: {len(vids)} -> {dict(list(vids.items())[:15])}")
        return n
    except Exception as e:
        msg = e.excepinfo[2] if (hasattr(e, 'excepinfo') and e.excepinfo) else str(e)
        print(f"\n=== {y}-{m:02d}: FAIL: {msg}")
        return -1

for (y, m) in [(2026, 4), (2026, 3), (2026, 1), (2025, 12)]:
    test_month(y, m)

