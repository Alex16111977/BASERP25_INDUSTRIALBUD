import win32com.client

A_FL_PREFIX = ["Воронцов Олександр", "Манжула Максим", "Аулова Маргарита", "Шостак Жанета",
               "Соколенко Тарас", "Шинкаренко Олег", "Шкурат Ігор", "Пономаренко Олександр",
               "Пономаренко Віталій", "Травінський Петро", "Скрипник Сергій"]


def main():
    erp = win32com.client.Dispatch("V83.COMConnector").Connect(
        'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
    )

    # Все декабрьские документы
    q = erp.NewObject("Запрос")
    q.Текст = """
ВЫБРАТЬ
    Док.Номер КАК Номер, Док.Дата КАК Дата, Док.Проведен КАК Проведен,
    Док.Организация.Наименование КАК Орг
ИЗ Документ.А_ОтражениеЗПпоКазне КАК Док
ГДЕ Док.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
УПОРЯДОЧИТЬ ПО Док.Дата, Док.Номер
"""
    t = q.Выполнить().Выгрузить()
    print(f"=== Документы А_ОтражениеЗПпоКазне декабрь 2025: {t.Количество()} ===")
    for i in range(t.Количество()):
        r = t.Получить(i)
        print(f"  №{r.Номер} | {r.Дата} | Проведен={r.Проведен} | {r.Орг}")

    # Какие документы содержат multi-org A-ФЛ (по НалогиБухгалтерия)
    cond = " ИЛИ ".join(
        [f'НБ.Сотрудник.ФизическоеЛицо.Наименование ПОДОБНО "{p}%"' for p in A_FL_PREFIX]
    )
    q2 = erp.NewObject("Запрос")
    q2.Текст = f"""
ВЫБРАТЬ РАЗЛИЧНЫЕ
    НБ.Ссылка.Номер КАК Номер, НБ.Ссылка.Дата КАК Дата
ИЗ Документ.А_ОтражениеЗПпоКазне.НалогиБухгалтерия КАК НБ
ГДЕ НБ.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
    И НБ.СуммаНДФЛ <> 0 И ({cond})
УПОРЯДОЧИТЬ ПО Дата, Номер
"""
    t2 = q2.Выполнить().Выгрузить()
    print(f"\n=== Документы, содержащие 11 multi-org A-ФЛ (перепровести обязательно): {t2.Количество()} ===")
    for i in range(t2.Количество()):
        r = t2.Получить(i)
        print(f"  №{r.Номер} | {r.Дата}")


if __name__ == "__main__":
    main()
