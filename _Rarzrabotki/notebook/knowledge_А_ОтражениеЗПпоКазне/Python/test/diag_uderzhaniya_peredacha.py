# -*- coding: utf-8 -*-
"""Диагностика: почему _ПНМП_ЗаполнитьУдержания даёт 0 строк (передача №000000001 от 31.12.2025).
Реплика логики BSL _ПНМП_ПостроитьОргБухПоФЛ + _ПНМП_ЗаполнитьУдержания + _ПНМП_ДобавитьСтроку
с печатью причины пропуска каждой строки УдержанияБухгалтерия."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне "
          "ГДЕ Номер = &Н И Дата = ДАТАВРЕМЯ(2025,12,31,12,0,0)")
q.УстановитьПараметр("Н", "000000001")
s = q.Выполнить().Выбрать()
if not s.Следующий():
    print("Документ не найден"); sys.exit(1)
doc = s.Ссылка.ПолучитьОбъект()
print("Док:", doc.Номер, "от", doc.Дата)

def зап(x):  # ЗначениеЗаполнено
    return erp.ЗначениеЗаполнено(x)

# --- _ПНМП_ПостроитьОргБухПоФЛ: Ф1 НачисленнаяЗарплата, ОргБух заполнено ---
оргбух = {}
тн = doc.НачисленнаяЗарплатаИВзносыПоФизлицам
for i in range(тн.Количество()):
    r = тн.Получить(i)
    if erp.XMLСтрока(r.ФормаPL) != "Форма1": continue
    if not зап(r.ОрганизацияБухгалтерия): continue
    if зап(r.ФизическоеЛицо):
        k = erp.XMLСтрока(r.ФизическоеЛицо)
        if k not in оргбух:
            оргбух[k] = r.ОрганизацияБухгалтерия
print(f"Карта ОргБухПоФЛ (Ф1): {len(оргбух)} ФЛ")

# --- _ПНМП_ЗаполнитьУдержания + guard'ы _ПНМП_ДобавитьСтроку ---
ту = doc.УдержанияБухгалтерия
print(f"\nУдержанияБухгалтерия: {ту.Количество()} строк")
прошло = 0
for i in range(ту.Количество()):
    r = ту.Получить(i)
    фл = r.ФизическоеЛицо
    summa = float(r.Сумма)
    подр = r.ПодразделениеПредприятия
    flk = erp.XMLСтрока(фл) if зап(фл) else None
    ob = оргбух.get(flk)
    reasons = []
    if summa == 0: reasons.append("Сумма=0")
    if not зап(фл): reasons.append("ФЛ пусто")
    if ob is None or not зап(ob): reasons.append("ОргБух пусто (ФЛ нет в карте Ф1)")
    if not зап(подр): reasons.append("ИсхПодр(ПодразделениеПредприятия) ПУСТО")
    if ob is not None and зап(ob):
        цел = ob.А_ПодразделениеЗарплатаБух
        if not зап(цел): reasons.append("ЦелПодр(ОргБух.А_ПодразделениеЗарплатаБух) пусто")
        elif зап(подр) and erp.XMLСтрока(цел) == erp.XMLСтрока(подр): reasons.append("ЦелПодр=ИсхПодр")
    флн = фл.Наименование if зап(фл) else "(пусто)"
    подрн = подр.Наименование if зап(подр) else "(ПУСТО)"
    obн = ob.Наименование if (ob is not None and зап(ob)) else "(нет)"
    статус = "✓ ПРОЙДЕТ" if not reasons else ("✗ " + "; ".join(reasons))
    if not reasons: прошло += 1
    print(f"  {флн[:28]:28} | Σ {summa:>10.2f} | подр={подрн[:18]:18} | ОргБух={obн[:18]:18} | {статус}")

print(f"\nИтог: прошло бы {прошло} из {ту.Количество()} строк удержаний")
