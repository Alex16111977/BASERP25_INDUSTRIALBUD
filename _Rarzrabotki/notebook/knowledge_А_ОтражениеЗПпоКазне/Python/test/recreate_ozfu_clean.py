print(f"Родитель НачЗП total (saved) = {tot:,.2f}")

print("СоздатьДокументОтражениеЗарплатыВФинансовомУчете (из сохранённого)...")
obj.СоздатьДокументОтражениеЗарплатыВФинансовомУчете()

erp = None
