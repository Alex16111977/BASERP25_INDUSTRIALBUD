# -*- coding: utf-8 -*-
# Создаёт (find-or-create) статью АП «Расчёты с ФСС» (актив) + способ отражения «Больничные за счёт ФСС».
# Способ.СтатьяРасходов = статья АП → ОЗФУ дебетует эту статью в ПАП (Кт «Оплата труда»), баланс сходится.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected BaseERP")

ИМЯ_СТАТЬИ = "Расчеты с ФСС"
ИМЯ_СПОСОБА = "Больничные за счет ФСС"

# 1. Статья АП «Расчеты с ФСС» (актив)
st = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию(ИМЯ_СТАТЬИ)
if not erp.ЗначениеЗаполнено(st):
    obj = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.СоздатьЭлемент()
    obj.Наименование = ИМЯ_СТАТЬИ
    obj.АктивПассив = erp.Перечисления.ВидыСтатейУправленческогоБаланса.Актив
    obj.БезАналитики = True
    obj.ВыводитьОборот = True
    obj.Описание = "Расчеты с Фондом соцстраха (больничные за счет ФСС) — дебиторка от фонда. Дт-сторона больничного за счет ФСС в управбалансе."
    obj.Записать()
    st = obj.Ссылка
    print(f"СОЗДАНА статья АП: {ИМЯ_СТАТЬИ} | актив | {st}")
else:
    print(f"Статья АП уже есть: {ИМЯ_СТАТЬИ} | {st}")
    # убедимся, что актив
    print(f"  АктивПассив = {erp.XMLСтрока(st.АктивПассив)}")

# 2. Способ отражения «Больничные за счет ФСС» (СтатьяРасходов = статья АП)
sp = erp.Справочники.СпособыОтраженияЗарплатыВБухучете.НайтиПоНаименованию(ИМЯ_СПОСОБА)
if not erp.ЗначениеЗаполнено(sp):
    obj = erp.Справочники.СпособыОтраженияЗарплатыВБухучете.СоздатьЭлемент()
    obj.Наименование = ИМЯ_СПОСОБА
    obj.СтатьяРасходов = st              # АП-статья -> ОЗФУ дебетует её в ПАП
    obj.Описание = "Дт статья АП «Расчеты с ФСС», Кт «Оплата труда». Больничные за счет фонда, не на затраты (класс 9)."
    obj.Записать()
    sp = obj.Ссылка
    print(f"СОЗДАН способ: {ИМЯ_СПОСОБА} | {sp}")
else:
    # обновим СтатьяРасходов на нашу статью (на случай если был пустой)
    o = sp.ПолучитьОбъект()
    if erp.XMLСтрока(o.СтатьяРасходов) != erp.XMLСтрока(st):
        o.СтатьяРасходов = st
        o.Записать()
        print(f"Способ обновлён: {ИМЯ_СПОСОБА} -> СтатьяРасходов={ИМЯ_СТАТЬИ}")
    else:
        print(f"Способ уже есть и настроен: {ИМЯ_СПОСОБА} | {sp}")

# Проверка типа СтатьяРасходов способа
o = sp.ПолучитьОбъект()
print(f"\nСпособ.СтатьяРасходов тип = {erp.XMLСтрока(o.СтатьяРасходов)}")
print(f"  это СтатьиАктивовПассивов: {'СтатьиАктивовПассивов' in erp.XMLСтрока(o.СтатьяРасходов) or 'StatiAktivov' in erp.XMLСтрока(o.СтатьяРасходов)}")
erp = None
print("Done.")
