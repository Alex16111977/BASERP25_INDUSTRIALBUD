# Воронцов: текущий код vs регистр — ОргБух Ф1 «Зарплата управл».
# Казна+выплата = ДЖИ 15746.50 / ІНД 123200. Регистр ОЗФУ = 57250 / 81696.50 (перекос).
# Вопрос: текущий код даёт правильный сплит (значит регистр устарел → перепровести)
#         или баг в коде (значит править)?
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
def en(v): return erp.XMLСтрока(v) if erp.ЗначениеЗаполнено(v) else ""
def fl(v): return erp.ЗначениеЗаполнено(v)

# найти Dec-док с Воронцовым
q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ РАЗЛИЧНЫЕ ТЧ.Ссылка КАК С, ТЧ.Ссылка.Номер КАК Н, ТЧ.Ссылка.Проведен КАК Пров"
           " ИЗ Документ.А_ОтражениеЗПпоКазне.РаспределениеКазна КАК ТЧ"
           " ГДЕ ТЧ.Сотрудник.ФизическоеЛицо.Наименование ПОДОБНО \"Воронцов Олександр%\""
           "  И ТЧ.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59)")
s = q.Выполнить().Выбрать()
docs = []
while s.Следующий(): docs.append((s.С, str(s.Н), bool(s.Пров)))
print("Документы с Воронцовым (Dec):", [(н, "пров" if п else "НЕ пров") for _, н, п in docs])

for ссылка, ном, пров in docs:
    obj = ссылка.ПолучитьОбъект()
    # 1) СОХРАНЁННОЕ состояние (что в регистре)
    saved = {}
    for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
        if not fl(r.ФизическоеЛицо): continue
        if not str(r.ФизическоеЛицо.Наименование).startswith("Воронцов Олександр"): continue
        if en(r.ФормаPL) != "Форма1": continue
        if float(r.ВзносыВсего) != 0: continue
        sp = r.СпособОтраженияЗарплатыВБухучете
        if fl(sp) and sp.А_ЭтоУдержание: continue
        о = str(r.ОрганизацияБухгалтерия.Наименование) if fl(r.ОрганизацияБухгалтерия) else "(пусто)"
        saved[о] = saved.get(о, 0.0) + float(r.Сумма)
    # 2) ТЕКУЩИЙ код — заполнить в памяти
    obj.ЗаполнитьНачисленияУпризЗуп2()
    obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
    obj.ЗаполнитьОтражениеЗарплатыВФинансовомУчетеИзБазЗП()
    obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
    fresh = {}
    for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
        if not fl(r.ФизическоеЛицо): continue
        if not str(r.ФизическоеЛицо.Наименование).startswith("Воронцов Олександр"): continue
        if en(r.ФормаPL) != "Форма1": continue
        if float(r.ВзносыВсего) != 0: continue
        sp = r.СпособОтраженияЗарплатыВБухучете
        if fl(sp) and sp.А_ЭтоУдержание: continue
        о = str(r.ОрганизацияБухгалтерия.Наименование) if fl(r.ОрганизацияБухгалтерия) else "(пусто)"
        fresh[о] = fresh.get(о, 0.0) + float(r.Сумма)
    print(f"\n=== Док №{ном} ({'проведён' if пров else 'НЕ проведён'}) ===")
    print(f"  СОХРАНЁННОЕ (в регистре) Ф1 ЗПупр по ОргБух: " + ", ".join(f"{k}={v:.2f}" for k,v in saved.items()))
    print(f"  ТЕКУЩИЙ КОД (в памяти)   Ф1 ЗПупр по ОргБух: " + ", ".join(f"{k}={v:.2f}" for k,v in fresh.items()))
    print(f"  Эталон (Казна+выплата): ДЖИ ТРИ КОНСТРАКШН ТОВ=15746.50, ТОВ \"ІНДАСТРІАЛБУД\"=123200.00")
erp = None
