# -*- coding: utf-8 -*-
# Диагностика: почему ОЗФУ Форма1 = 19 575,72 вместо 27 913,53 для Постернака (дек 2025, №000000001).
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")

# Постернак ФизЛицо
qf = erp.NewObject("Запрос")
qf.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка, Наименование КАК Имя ИЗ Справочник.ФизическиеЛица "
            "ГДЕ Наименование ПОДОБНО \"%Постернак Андр%\"")
fs = qf.Выполнить().Выбрать()
if not fs.Следующий():
    print("ФЛ не найден"); sys.exit(1)
ФЛ = fs.Ссылка
print(f"ФизЛицо: {fs.Имя}")
uid = erp.String(ФЛ.УникальныйИдентификатор())

# Родитель дек 2025
qp = erp.NewObject("Запрос")
qp.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка, Номер КАК Номер ИЗ Документ.А_ОтражениеЗПпоКазне "
            "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59) УПОРЯДОЧИТЬ ПО Дата")
ps = qp.Выполнить().Выбрать()
if not ps.Следующий():
    print("Родитель дек 2025 не найден"); sys.exit(1)
print(f"Родитель: №{ps.Номер}")
obj = ps.Ссылка.ПолучитьОбъект()

def en(v): return erp.XMLСтрока(v) if erp.ЗначениеЗаполнено(v) else "<пусто>"

print("\n=== РаспределениеКазна Форма1 для Постернака ===")
рк_зп = рк_нач = рк_удерж = рк_сумма_всего = 0.0
for r in obj.РаспределениеКазна:
    if not erp.ЗначениеЗаполнено(r.Сотрудник): continue
    if not (erp.ЗначениеЗаполнено(r.Сотрудник.ФизическоеЛицо) and
            erp.String(r.Сотрудник.ФизическоеЛицо.УникальныйИдентификатор())==uid): continue
    if en(r.ФормаPL)!="Форма1": continue
    статья = str(r.СтатьяДвиженияДенежныхСредств)
    print(f"  Статья='{статья}' Сумма={float(r.Сумма):,.2f} СуммаНач={float(r.СуммаНачисления):,.2f} СуммаФОТ={float(r.СуммаФОТ):,.2f} СуммаНал={float(r.СуммаНалогов):,.2f}")
    рк_сумма_всего += float(r.Сумма)

print("\n=== НачисленияБух (gross) для Постернака ===")
нб = 0.0
for r in obj.НачисленияБух:
    if erp.ЗначениеЗаполнено(r.ФизЛицо) and erp.String(r.ФизЛицо.УникальныйИдентификатор())==uid:
        print(f"  ВидРасчета='{r.ВидРасчета}' Сумма={float(r.Сумма):,.2f}")
        нб += float(r.Сумма)
print(f"  Σ НачисленияБух = {нб:,.2f}")

print("\n=== НалогиБухгалтерия для Постернака ===")
нал_ндфл = нал_фот = 0.0
for r in obj.НалогиБухгалтерия:
    if not erp.ЗначениеЗаполнено(r.Сотрудник): continue
    if not (erp.ЗначениеЗаполнено(r.Сотрудник.ФизическоеЛицо) and
            erp.String(r.Сотрудник.ФизическоеЛицо.УникальныйИдентификатор())==uid): continue
    print(f"  ТипНалога={en(r.ТипНалога)} СуммаНДФЛ={float(r.СуммаНДФЛ):,.2f} СуммаФОТ={float(r.СуммаФОТ):,.2f} Сумма={float(r.Сумма):,.2f}")
    нал_ндфл += float(r.СуммаНДФЛ); нал_фот += float(r.СуммаФОТ)
print(f"  Σ СуммаНДФЛ = {нал_ндфл:,.2f} | Σ СуммаФОТ(ЕСВ) = {нал_фот:,.2f}")

print("\n=== УдержанияБухгалтерия для Постернака ===")
уд = 0.0
for r in obj.УдержанияБухгалтерия:
    if erp.ЗначениеЗаполнено(r.ФизическоеЛицо) and erp.String(r.ФизическоеЛицо.УникальныйИдентификатор())==uid:
        получ = str(r.Субконто1) if erp.ЗначениеЗаполнено(r.Субконто1) else "<нет>"
        print(f"  Сумма={float(r.Сумма):,.2f} ВидОперации={en(r.ВидОперации)} Получатель(Субконто1)={получ}")
        уд += float(r.Сумма)
print(f"  Σ УдержанияБухгалтерия = {уд:,.2f}")

bukh = нб - нал_ндфл - уд
print(f"\n=== РАСЧЁТ bukh (как в _ОтрЗП_РазметитьФормаPL) ===")
print(f"  bukh = НачисленияБух({нб:,.2f}) - НалогиБух.СуммаНДФЛ({нал_ндфл:,.2f}) - УдержанияБух({уд:,.2f}) = {bukh:,.2f}")
print(f"  ОЖИДАЕТСЯ (РаспределениеКазна Зарплата line) = 27 913,53")
print(f"  Если bukh=19 575,72 → НДФЛ вычтен дважды (в НалогиБух И в УдержанияБух)")

erp = None
print("\nDone.")
