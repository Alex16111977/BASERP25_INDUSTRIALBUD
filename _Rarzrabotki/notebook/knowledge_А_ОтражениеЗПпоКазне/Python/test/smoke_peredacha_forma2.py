# -*- coding: utf-8 -*-
"""GREEN приёмка: кнопка на №000000005 → перенос Ф2 на корни. Инварианты."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

OK_F2_SUM, OK_F2_ROWS = 2474162.32, 203

def найти_отражение(номер):
    q = erp.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне ГДЕ Номер = &Н"
    q.УстановитьПараметр("Н", номер); s = q.Выполнить().Выбрать()
    return s.Ссылка if s.Следующий() else None

def найти_передачу(осн):
    q = erp.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями "
              "ГДЕ А_ДокументОснование = &О")
    q.УстановитьПараметр("О", осн); s = q.Выполнить().Выбрать()
    return s.Ссылка if s.Следующий() else None

def тч_по_форме(пер):
    q = erp.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ Н.ФормаPL КАК Ф, КОЛИЧЕСТВО(*) КАК К, СУММА(Н.Сумма) КАК С "
              "ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Начисления КАК Н "
              "ГДЕ Н.Ссылка = &Д СГРУППИРОВАТЬ ПО Н.ФормаPL")
    q.УстановитьПараметр("Д", пер); res = {}
    s = q.Выполнить().Выбрать()
    while s.Следующий():
        res[erp.XMLСтрока(s.Ф)] = (int(s.К), round(float(s.С or 0), 2))
    return res

отр = найти_отражение("000000005")
print("Отражение:", отр.Номер if отр else None)

# === Прогон 1 ===
отр.ПолучитьОбъект().СоздатьПередачуНачисленийМеждуПодразделениями()
пер = найти_передачу(отр)
обj = пер.ПолучитьОбъект()
print("Передача:", пер.Номер, "Проведен =", обj.Проведен)

тч = тч_по_форме(пер)
print("ТЧ Начисления по ФормаPL:", тч)
ф2 = тч.get("Форма2", (0, 0.0))
print(f"  Форма2: {ф2[0]} строк, Σ {ф2[1]}  (ожид. {OK_F2_ROWS} / {OK_F2_SUM})")

# ПАП(Оплата труда) net по регистратору
qp = erp.NewObject("Запрос")
qp.Text = ("ВЫБРАТЬ СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) "
           "ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Нетто, СУММА(П.Сумма) КАК Оборот "
           "ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П "
           "ГДЕ П.Регистратор = &Д И П.Статья.Наименование = &Ст")
qp.УстановитьПараметр("Д", пер); qp.УстановитьПараметр("Ст", "Оплата труда")
s = qp.Выполнить().Выбрать(); s.Следующий()
print(f"ПАП(Оплата труда): net={round(float(s.Нетто or 0),2)} (ожид.~0), оборот={round(float(s.Оборот or 0),2)}")

# А_ВзСС net + обороты по ФормаPL
qv = erp.NewObject("Запрос")
qv.Text = ("ВЫБРАТЬ ВзС.ФормаPL КАК Ф, "
           "СУММА(ВЫБОР КОГДА ВзС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) "
           "ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ -ВзС.СуммаВзаиморасчетов КОНЕЦ) КАК Нетто, "
           "СУММА(ВЫБОР КОГДА ВзС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) "
           "ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК Приход "
           "ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзС "
           "ГДЕ ВзС.Регистратор = &Д СГРУППИРОВАТЬ ПО ВзС.ФормаPL")
qv.УстановитьПараметр("Д", пер); s = qv.Выполнить().Выбрать()
print("А_ВзСС по ФормаPL (net ожид.~0; Приход = объём переноса):")
while s.Следующий():
    print(f"  {erp.XMLСтрока(s.Ф)}: net={round(float(s.Нетто or 0),2)}, Приход={round(float(s.Приход or 0),2)}")

# === Прогон 2 — идемпотентность ===
отр.ПолучитьОбъект().СоздатьПередачуНачисленийМеждуПодразделениями()
тч2 = тч_по_форме(найти_передачу(отр))
ф2b = тч2.get("Форма2", (0, 0.0))
print(f"\nИдемпотентность: повтор Форма2 = {ф2b[0]} строк, Σ {ф2b[1]} (Δ строк={ф2b[0]-ф2[0]}, ΔΣ={round(ф2b[1]-ф2[1],2)})")

# === Вердикт ===
ok = (ф2[0] == OK_F2_ROWS and abs(ф2[1]-OK_F2_SUM) < 0.05 and ф2b == ф2)
print("\n=== ВЕРДИКТ:", "PASS" if ok else "CHECK", "===")
