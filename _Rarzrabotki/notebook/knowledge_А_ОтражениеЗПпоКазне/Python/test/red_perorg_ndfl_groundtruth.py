"""
RED ground-truth для фикса «НДФЛ Форма1 по организации» (per-org А_ВзСС).

Доказывает ДО правок:
  (а) НалогиБухгалтерия.Организация заполнена per-org (нет пустой) и даёт точный сплит
      → multi-org ФЛ (>=2 организаций) — это класс A. Если у кого-то Организация пустая,
        Правка 1 для него не сработает (упадёт в fallback на шапку) — это надо знать заранее.
  (б) Текущий регистр А_ВзСС Форма1 Воронцова разъезжается (ожидаем ДЖИ 57250 / ІНД 81696.50).

Запуск: C:\\Python313\\python.exe red_perorg_ndfl_groundtruth.py
"""
import io
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8")

import win32com.client


def main():
    erp = win32com.client.Dispatch("V83.COMConnector").Connect(
        'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
    )

    # (а) НалогиБухгалтерия per (ФЛ, Организация) — декабрь 2025 (даты литералом — без TZ-сдвига)
    q = erp.NewObject("Запрос")
    q.Текст = """
ВЫБРАТЬ
    НБ.Сотрудник.ФизическоеЛицо.Наименование КАК ФЛ,
    НБ.Организация.Наименование КАК Орг,
    НБ.Организация КАК ОргСсылка,
    СУММА(НБ.СуммаНДФЛ) КАК СуммаНДФЛ
ИЗ Документ.А_ОтражениеЗПпоКазне.НалогиБухгалтерия КАК НБ
ГДЕ НБ.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
    И НБ.СуммаНДФЛ <> 0
СГРУППИРОВАТЬ ПО
    НБ.Сотрудник.ФизическоеЛицо.Наименование, НБ.Организация.Наименование, НБ.Организация
"""
    t = q.Выполнить().Выгрузить()

    by_fl = {}      # ФЛ -> {орг: сумма}
    empty_org_rows = 0
    for i in range(t.Количество()):
        r = t.Получить(i)
        fl = r.ФЛ or "<ФЛ пусто>"
        org_filled = erp.ЗначениеЗаполнено(r.ОргСсылка)
        org = r.Орг if org_filled else "<ОРГ ПУСТО>"
        if not org_filled:
            empty_org_rows += 1
        by_fl.setdefault(fl, {})[org] = by_fl.setdefault(fl, {}).get(org, 0) + r.СуммаНДФЛ

    multi = {fl: orgs for fl, orgs in by_fl.items() if len(orgs) >= 2}
    print("=== (а) multi-org ФЛ по НалогиБухгалтерия (>=2 организаций), декабрь 2025 ===")
    print(f"    Всего ФЛ с НДФЛ: {len(by_fl)} | multi-org: {len(multi)}")
    for fl in sorted(multi):
        orgs = multi[fl]
        total = sum(orgs.values())
        print(f"  {fl}")
        for org in sorted(orgs):
            print(f"      {org:34s} | {orgs[org]:>12.2f}")
        print(f"      {'ИТОГО ФЛ':34s} | {total:>12.2f}")
    print(f"    >>> строк НалогиБухгалтерия с ПУСТОЙ Организация: {empty_org_rows} (RED-условие OK если 0)")

    # Воронцов крупным планом
    vor = {fl: o for fl, o in by_fl.items() if fl.startswith("Воронцов")}
    print("\n    Контроль Воронцов (ожидаем ДЖИ ≈ 4703.50 / ІНД ≈ 36800):")
    for fl, orgs in vor.items():
        for org in sorted(orgs):
            print(f"      {fl} | {org:34s} | {orgs[org]:>12.2f}")

    # (б) Текущий регистр А_ВзСС Форма1 Воронцова per ОргБух (ОЗФУ-регистратор, Приход)
    q2 = erp.NewObject("Запрос")
    q2.Текст = """
ВЫБРАТЬ
    ВзС.ОрганизацияБухгалтерия.Наименование КАК ОргБух,
    СУММА(ВЫБОР КОГДА ВзС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР КОГДА ВзС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
        ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК Расход
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзС
ГДЕ ВзС.ФизическоеЛицо.Наименование ПОДОБНО "Воронцов%"
    И ВзС.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
    И ВЫРАЗИТЬ(ВзС.Регистратор КАК Документ.ОтражениеЗарплатыВФинансовомУчете).Ссылка ЕСТЬ НЕ NULL
СГРУППИРОВАТЬ ПО ВзС.ОрганизацияБухгалтерия.Наименование
"""
    print("\n=== (б) Текущий А_ВзСС Форма1 Воронцова per ОргБух (ОЗФУ Приход) — ожидаем разлёт 57250 / 81696.50 ===")
    t2 = q2.Выполнить().Выгрузить()
    for i in range(t2.Количество()):
        r = t2.Получить(i)
        print(f"  {r.ОргБух or '<ПУСТО>':34s} | Приход={r.Приход:>12.2f} | Расход={r.Расход:>12.2f}")


if __name__ == "__main__":
    main()
