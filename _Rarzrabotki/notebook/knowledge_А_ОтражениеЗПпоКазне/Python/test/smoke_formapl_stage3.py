# -*- coding: utf-8 -*-
# Smoke Stage 3: ФормаPL протащен в ОЗФУ (4 ТЧ), Σ сохранена.
# Родитель наполняется в память (с разметкой), затем СоздатьОЗФУ (ОЗФУ сохраняется/перепроводится,
# суммы те же + маркер). READ родителя НЕ сохраняем.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")
q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка, Номер КАК Номер ИЗ Документ.А_ОтражениеЗПпоКазне "
           "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2026,4,1,0,0,0) И ДАТАВРЕМЯ(2026,4,30,23,59,59) УПОРЯДОЧИТЬ ПО Дата")
sel = q.Выполнить().Выбрать(); sel.Следующий()
print(f"Родитель: №{sel.Номер}")
obj = sel.Ссылка.ПолучитьОбъект()

print("Наполнение родителя в память (с разметкой)...")
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
obj.ЗаполнитьОтражениеЗарплатыВФинансовомУчетеИзБазЗП()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
parent_net = sum(float(r.Сумма) for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам)
print(f"Родитель Σ НачисленнаяЗарплата.Сумма = {parent_net:,.2f}")

print("СоздатьДокументОтражениеЗарплатыВФинансовомУчете (читает родителя в памяти, сохраняет ОЗФУ)...")
try:
    obj.СоздатьДокументОтражениеЗарплатыВФинансовомУчете()
except Exception as e:
    msg = e.excepinfo[2] if (hasattr(e, 'excepinfo') and e.excepinfo) else str(e)
    print("FAIL создания ОЗФУ:", msg); sys.exit(1)

# Найти ОЗФУ
qо = erp.NewObject("Запрос")
qо.УстановитьПараметр("Осн", sel.Ссылка)
qо.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 ОЗ.Ссылка КАК Ссылка, ОЗ.Номер КАК Номер, ОЗ.Проведен КАК Проведен "
            "ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете КАК ОЗ "
            "ГДЕ ОЗ.А_ДокОтражениеЗПпоКазне = &Осн И НЕ ОЗ.ПометкаУдаления")
so = qо.Выполнить().Выбрать()
if not so.Следующий():
    print("FAIL: ОЗФУ не найден"); sys.exit(1)
print(f"ОЗФУ: №{so.Номер} проведён={so.Проведен}")
оз = so.Ссылка.ПолучитьОбъект()

def en(v): return erp.XMLСтрока(v) if erp.ЗначениеЗаполнено(v) else "<пусто>"

def summ(тч, поле):
    s = 0.0; n = тч.Количество(); none = 0
    f1 = f2 = 0.0
    for i in range(n):
        r = тч.Получить(i)
        val = float(getattr(r, поле))
        s += val
        фп = en(r.ФормаPL)
        if фп == "Форма1": f1 += val
        elif фп == "Форма2": f2 += val
        else: none += 1
    return s, f1, f2, none, n

print("\n=== ОЗФУ ТЧ (Σ / Форма1 / Форма2 / безФормаPL / строк) ===")
for тчимя, поле in [("НачисленнаяЗарплатаИВзносыПоФизлицам","Сумма"),
                    ("НачисленнаяЗарплатаИВзносы","Сумма"),
                    ("НачисленныйНДФЛ","Сумма"),
                    ("УдержаннаяЗарплата","Сумма")]:
    тч = getattr(оз, тчимя)
    s,f1,f2,none,n = summ(тч, поле)
    print(f"  {тчимя:38} Σ={s:>15,.2f} Ф1={f1:>15,.2f} Ф2={f2:>15,.2f} безФ={none} строк={n}")
# взносы отдельно
sv,_,_,_,_ = summ(оз.НачисленнаяЗарплатаИВзносы, "ВзносыВсего")
print(f"  НачисленнаяЗарплатаИВзносы.ВзносыВсего Σ = {sv:,.2f}")

# сверка: НачПоФЛ.Сумма ОЗФУ == родителя
озп = sum(float(r.Сумма) for r in оз.НачисленнаяЗарплатаИВзносыПоФизлицам)
print(f"\nСверка Σ НачПоФЛ: родитель {parent_net:,.2f} vs ОЗФУ {озп:,.2f}  Δ={parent_net-озп:,.2f}")

erp = None
print("\nDone.")
