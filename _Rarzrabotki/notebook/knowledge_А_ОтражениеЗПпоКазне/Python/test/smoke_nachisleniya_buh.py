# -*- coding: utf-8 -*-
# Smoke: вызвать ЗагрузитьНалогиИУдержанияИзЗарплатыБух() на реальном документе и проверить НачисленияБух.
# В память (без записи) — реальный документ не мутируем.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")

q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка, Номер КАК Номер, Дата КАК Дата "
           "ИЗ Документ.А_ОтражениеЗПпоКазне "
           "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2026,4,1,0,0,0) И ДАТАВРЕМЯ(2026,4,30,23,59,59) "
           "УПОРЯДОЧИТЬ ПО Дата")
sel = q.Выполнить().Выбрать()
if not sel.Следующий():
    print("FAIL: нет документа А_ОтражениеЗПпоКазне за апрель 2026"); sys.exit(1)
print(f"Документ: №{sel.Номер} от {sel.Дата}")

obj = sel.Ссылка.ПолучитьОбъект()
try:
    obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
except Exception as e:
    msg = e.excepinfo[2] if (hasattr(e, 'excepinfo') and e.excepinfo) else str(e)
    print("FAIL вызова метода:", msg); sys.exit(1)

# Регрессия: Налоги/Удержания тоже наполнились
print(f"\n[регрессия] НалогиБухгалтерия rows = {obj.НалогиБухгалтерия.Количество()}")
print(f"[регрессия] УдержанияБухгалтерия rows = {obj.УдержанияБухгалтерия.Количество()}")

nb = obj.НачисленияБух
n = nb.Количество()
s = 0.0
c661 = 0
cSub = 0
cSubEqFL = 0
for i in range(n):
    r = nb.Получить(i)
    s += float(r.Сумма)
    kod = str(r.СчетКт.Код) if erp.ЗначениеЗаполнено(r.СчетКт) else ""
    if kod == "661":
        c661 += 1
    if erp.ЗначениеЗаполнено(r.СубконтоКт1):
        cSub += 1
        if erp.ЗначениеЗаполнено(r.ФизЛицо) and \
           erp.String(r.СубконтоКт1.УникальныйИдентификатор()) == erp.String(r.ФизЛицо.УникальныйИдентификатор()):
            cSubEqFL += 1

print(f"\n=== НачисленияБух ===")
print(f"rows                 = {n}")
print(f"Σ Сумма              = {s:,.2f}")
print(f"строк с СчетКт=661    = {c661}")
print(f"строк с СубконтоКт1   = {cSub}")
print(f"СубконтоКт1 == ФизЛицо= {cSubEqFL}")

print("\n--- 5 примеров ---")
for i in range(min(5, n)):
    r = nb.Получить(i)
    fl = str(r.ФизЛицо) if erp.ЗначениеЗаполнено(r.ФизЛицо) else "<нет>"
    org = str(r.Организация) if erp.ЗначениеЗаполнено(r.Организация) else "<нет>"
    sub = str(r.СубконтоКт1) if erp.ЗначениеЗаполнено(r.СубконтоКт1) else "<нет>"
    sch = str(r.СчетКт.Код) if erp.ЗначениеЗаполнено(r.СчетКт) else "<нет>"
    print(f"  {fl} | ФИО='{r.ФИО}' | вид='{r.ВидРасчета}'/{r.КодВидРасчета} | {float(r.Сумма):,.2f} | Кт={sch} | Суб1={sub} | орг={org}")

erp = None
print("\nDone (документ НЕ записан).")
