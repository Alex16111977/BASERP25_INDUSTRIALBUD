"""Разбор 3 крупных не-алиментных расхождений Fix B vs текущее (Алова/Пономаренко О./Травінський).
Сравнение в разрезе (Подразделение, ОргБух): родительская ТЧ Ф1 vs движения А_ВзСС ОЗФУ."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
зап=lambda x: erp.ЗначениеЗаполнено(x); X=lambda x: erp.XMLСтрока(x)

q=erp.NewObject("Запрос")
q.Text="ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне ГДЕ Номер=&Н И Дата=ДАТАВРЕМЯ(2025,12,31,12,0,0)"
q.УстановитьПараметр("Н","000000001"); s=q.Выполнить().Выбрать(); s.Следующий(); отр=s.Ссылка

def цель_и_гард(ob, подр):
    if not зап(ob): return "(ОргБух пуст)", False
    цел = ob.А_ПодразделениеЗарплатаБух
    if not зап(цел): return "(нет целевого)", False
    if X(цел)==X(подр): return цел.Наименование+"(=исх)", False
    return цел.Наименование, True

for имя in ["Алова%", "Пономаренко Олександр%", "Травінський%"]:
    print(f"\n========== {имя} ==========")
    # Родительская ТЧ Ф1 (что читает текущий _ПНМП_ЗаполнитьНачисления)
    qp=erp.NewObject("Запрос"); qp.УстановитьПараметр("Осн",отр); qp.УстановитьПараметр("ФЛ",имя)
    qp.Text="""ВЫБРАТЬ Т.ПодразделениеПредприятия КАК Подр, Т.ОрганизацияБухгалтерия КАК ОргБух, СУММА(Т.Сумма) КАК С
    ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленнаяЗарплатаИВзносыПоФизлицам КАК Т
    ГДЕ Т.Ссылка=&Осн И Т.ФизическоеЛицо.Наименование ПОДОБНО &ФЛ И Т.ФормаPL=ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
        И Т.ВзносыВсего=0 И ЕСТЬNULL(Т.СпособОтраженияЗарплатыВБухучете.А_ЭтоУдержание,ЛОЖЬ)=ЛОЖЬ
    СГРУППИРОВАТЬ ПО Т.ПодразделениеПредприятия, Т.ОрганизацияБухгалтерия"""
    P=qp.Выполнить().Выгрузить()
    print(" РОДИТЕЛЬ Ф1 (текущий источник):")
    pt=0.0
    for i in range(P.Количество()):
        r=P.Получить(i); цн,гд=цель_и_гард(r.ОргБух,r.Подр); сум=float(r.С)
        if гд: pt+=сум
        об=r.ОргБух.Наименование if зап(r.ОргБух) else "(пусто)"
        пд=r.Подр.Наименование if зап(r.Подр) else "(пусто)"
        print(f"   {пд[:14]:14} ОргБух={об[:22]:22} Σ={сум:>10.2f} цель={цн[:16]:16} {'ПЕРЕНОС' if гд else 'отсев'}")
    print(f"   → переносится (текущее): {round(pt,2)}")
    # ОЗФУ А_ВзСС Ф1 (что читает Fix B)
    qv=erp.NewObject("Запрос"); qv.УстановитьПараметр("Осн",отр); qv.УстановитьПараметр("ФЛ",имя)
    qv.Text="""ВЫБРАТЬ ВзС.Подразделение КАК Подр, ВзС.ОрганизацияБухгалтерия КАК ОргБух,
        СУММА(ВЫБОР КОГДА ВзС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ -ВзС.СуммаВзаиморасчетов КОНЕЦ) КАК С
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзС
    ГДЕ ВЫРАЗИТЬ(ВзС.Регистратор КАК Документ.ОтражениеЗарплатыВФинансовомУчете).А_ДокОтражениеЗПпоКазне=&Осн
        И ВзС.ФизическоеЛицо.Наименование ПОДОБНО &ФЛ И ВзС.ФормаPL=ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
    СГРУППИРОВАТЬ ПО ВзС.Подразделение, ВзС.ОрганизацияБухгалтерия"""
    V=qv.Выполнить().Выгрузить()
    print(" ОЗФУ А_ВзСС Ф1 (источник Fix B):")
    vt=0.0
    for i in range(V.Количество()):
        r=V.Получить(i); цн,гд=цель_и_гард(r.ОргБух,r.Подр); сум=float(r.С)
        if гд: vt+=сум
        об=r.ОргБух.Наименование if зап(r.ОргБух) else "(пусто)"
        пд=r.Подр.Наименование if зап(r.Подр) else "(пусто)"
        print(f"   {пд[:14]:14} ОргБух={об[:22]:22} Σ={сум:>10.2f} цель={цн[:16]:16} {'ПЕРЕНОС' if гд else 'отсев'}")
    print(f"   → переносится (Fix B): {round(vt,2)}")
