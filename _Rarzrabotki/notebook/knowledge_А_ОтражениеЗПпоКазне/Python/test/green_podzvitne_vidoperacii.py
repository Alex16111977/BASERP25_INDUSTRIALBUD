import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client as w
erp = w.Dispatch("V83.COMConnector").Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
ob = erp.Документы.А_ОтражениеЗПпоКазне.НайтиПоНомеру("000000001").ПолучитьОбъект()
ob.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
ok = False
print("УдержанияБухгалтерия:")
for i in range(ob.УдержанияБухгалтерия.Количество()):
    s = ob.УдержанияБухгалтерия.Получить(i)
    флн = s.ФизическоеЛицо.Наименование if erp.ЗначениеЗаполнено(s.ФизическоеЛицо) else ""
    вид = erp.XMLСтрока(s.ВидОперации) if erp.ЗначениеЗаполнено(s.ВидОперации) else "<нет>"
    ст = s.СтатьяАктивовПассивов.Наименование if erp.ЗначениеЗаполнено(s.СтатьяАктивовПассивов) else "<пусто>"
    сч = s.СчетУчета.Код if erp.ЗначениеЗаполнено(s.СчетУчета) else "<нет>"
    суб = s.Субконто1.Наименование if erp.ЗначениеЗаполнено(s.Субконто1) else "<нет>"
    print(f"   {флн[:22]:22s} | вид={вид[:34]:34s} | счёт={сч} | статья={ст[:18]:18s} | Субконто1={суб[:18]}")
    if флн.startswith("Гуняга"):
        ok = (вид == "УдержаниеНеизрасходованныхПодотчетныхСумм" and сч == "3721"
              and ст == "<пусто>" and суб == флн)
print("\nИТОГ Гуняга (ВидОперации УдержаниеНеизрасходованных, статья пуста, 3721, Субконто1=ФЛ):",
      "GREEN ✅" if ok else "RED ❌")
