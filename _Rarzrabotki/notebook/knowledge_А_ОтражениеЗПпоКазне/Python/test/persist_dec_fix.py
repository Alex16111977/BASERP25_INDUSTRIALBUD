# Перепроведение декабрьского документа с фиксом Ф1=GROSS: родитель+ОЗФУ+перенос.
# Проверка: А_ВзСС Ф1 Постернак=27913.53, ПАП Оплата труда не изменилась, перенос Ф1.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")

qf = erp.NewObject("Запрос")
qf.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.ФизическиеЛица ГДЕ Наименование ПОДОБНО \"%Постернак Андр%\"")
fs = qf.Выполнить().Выбрать(); fs.Следующий(); Постернак=fs.С
uid = erp.String(Постернак.УникальныйИдентификатор())

qp = erp.NewObject("Запрос")
qp.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С, Номер КАК Н ИЗ Документ.А_ОтражениеЗПпоКазне "
            "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59) УПОРЯДОЧИТЬ ПО Дата")
ps = qp.Выполнить().Выбрать(); ps.Следующий(); Родитель=ps.С
print(f"Родитель: №{ps.Н}")
obj = Родитель.ПолучитьОбъект()

print("Наполнение + СОХРАНЕНИЕ родителя...")
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
obj.ЗаполнитьОтражениеЗарплатыВФинансовомУчетеИзБазЗП()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
obj.Записать(erp.РежимЗаписиДокумента.Проведение)
print("  сохранён.")
print("Создание ОЗФУ + переноса...")
obj.СоздатьДокументОтражениеЗарплатыВФинансовомУчете()
obj.СоздатьПередачуНачисленийМеждуПодразделениями()

# ОЗФУ
qo = erp.NewObject("Запрос"); qo.УстановитьПараметр("О", Родитель)
qo.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С, Номер КАК Н ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете "
            "КАК ОЗ ГДЕ ОЗ.А_ДокОтражениеЗПпоКазне=&О И НЕ ОЗ.ПометкаУдаления")
oz=qo.Выполнить().Выбрать(); oz.Следующий(); ОЗФУ=oz.С
print(f"ОЗФУ: №{oz.Н}")

# А_ВзСС Постернак по ФормаPL (от ОЗФУ)
qv = erp.NewObject("Запрос"); qv.УстановитьПараметр("Р",ОЗФУ); qv.УстановитьПараметр("ФЛ",Постернак)
qv.Текст = ("ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(В.ФормаPL) КАК Форма, "
            "СУММА(ВЫБОР КОГДА В.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА В.Сумма ИНАЧЕ -В.Сумма КОНЕЦ) КАК Сальдо "
            "ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК В "
            "ГДЕ В.Регистратор=&Р И В.ФизическоеЛицо=&ФЛ СГРУППИРОВАТЬ ПО В.ФормаPL")
print("\n=== А_ВзСС Постернак (от ОЗФУ) по ФормаPL ===")
vb=qv.Выполнить().Выбрать()
while vb.Следующий():
    print(f"  {vb.Форма}: {float(vb.Сальдо):,.2f}   (Ф1 ожид 27 913,53)")

# ПАП Оплата труда total ОЗФУ (не изменилась)
qb = erp.NewObject("Запрос"); qb.УстановитьПараметр("Р",ОЗФУ)
qb.Текст = ("ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(ПАП.Статья) КАК Статья, "
            "СУММА(ВЫБОР КОГДА ПАП.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Сальдо "
            "ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП ГДЕ ПАП.Регистратор=&Р СГРУППИРОВАТЬ ПО ПАП.Статья")
print("\n=== ПАП ОЗФУ (Оплата труда не должна измениться) ===")
bb=qb.Выполнить().Выбрать()
while bb.Следующий():
    print(f"  {bb.Статья:28} {float(bb.Сальдо):,.2f}")

# Перенос Ф1 Постернак
qt = erp.NewObject("Запрос"); qt.УстановитьПараметр("О",Родитель); qt.УстановитьПараметр("ФЛ",Постернак)
qt.Текст = ("ВЫБРАТЬ СУММА(Н.Сумма) КАК С ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Начисления КАК Н "
            "ГДЕ Н.Ссылка.А_ДокументОснование=&О И Н.ФизическоеЛицо=&ФЛ")
tb=qt.Выполнить().Выбрать(); tb.Следующий()
print(f"\n=== Перенос Начисления Постернак = {float(tb.С) if tb.С else 0:,.2f} (ожид 27 913,53) ===")

erp=None
print("\nDone (декабрьский документ перепроведён с фиксом).")
