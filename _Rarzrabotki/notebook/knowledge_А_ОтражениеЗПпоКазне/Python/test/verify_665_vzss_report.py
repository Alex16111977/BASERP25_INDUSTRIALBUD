"""
RED/GREEN COM-зеркало BuhBud-стороны отчёта А_СравнитьОстаткиВзаиморасчетыСотрудники.
Повторяет логику ПолучитьОстаткиBuhBud для двух наборов счетов и показывает дельту 665.
GREEN-условие: 665-строки surface (Алов ІНДЕПТ СТІЛ Кт 21433.49/Дт 21433.49/Кон 0);
ключи без 665-движений не изменились (661/663 без регрессии).

Запуск: C:\\Python313\\python.exe verify_665_vzss_report.py
"""
import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client as w

v8 = w.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# ЕДРПОУ организаций в балансе (фильтр отчёта)
qo = erp.NewObject("Запрос")
qo.Текст = 'ВЫБРАТЬ КодПоЕДРПОУ КАК Е ИЗ Справочник.Организации ГДЕ А_ВБалансе И КодПоЕДРПОУ<>""'
to = qo.Выполнить().Выгрузить()
edrpou = sorted({str(to.Получить(i).Е).strip() for i in range(to.Количество())})


def buh_side(codes):
    inlist = ", ".join(f'"{c}"' for c in codes)
    q = buh.NewObject("Запрос")
    arr = buh.NewObject("Массив")
    for e in edrpou:
        arr.Добавить(e)
    q.УстановитьПараметр("Орг", arr)
    q.Текст = f'''ВЫБРАТЬ
 ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод КАК ИдКод,
 ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).Наименование КАК ФЛ,
 Ост.Организация.КодПоЕДРПОУ КАК Е,
 СУММА(Ост.СуммаОборотКт) КАК Кт, СУММА(Ост.СуммаОборотДт) КАК Дт,
 СУММА(Ост.СуммаКонечныйОстатокКт-Ост.СуммаКонечныйОстатокДт) КАК Кон
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(ДАТАВРЕМЯ(2025,12,1,0,0,0),ДАТАВРЕМЯ(2025,12,31,23,59,59)) КАК Ост
ГДЕ Ост.Счет.Код В ({inlist}) И Ост.Субконто1 ССЫЛКА Справочник.ФизическиеЛица
 И Ост.Организация.КодПоЕДРПОУ В (&Орг)
СГРУППИРОВАТЬ ПО ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод,
 ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).Наименование, Ост.Организация.КодПоЕДРПОУ'''
    t = q.Выполнить().Выгрузить()
    d = {}
    for i in range(t.Количество()):
        r = t.Получить(i)
        d[(str(r.ИдКод).strip(), str(r.Е).strip())] = (r.ФЛ, round(r.Кт, 2), round(r.Дт, 2), round(r.Кон, 2))
    return d


old = buh_side(["661", "663"])
new = buh_side(["661", "663", "665"])
print(f"Орг в балансе: {edrpou}")
print(f"661/663: {len(old)} строк | 661/663/665: {len(new)} строк")

added = sorted(set(new) - set(old))
changed = sorted([k for k in old if old[k] != new.get(k)])
print(f"\n=== Новые ключи из-за 665 ({len(added)}) ===")
for k in added:
    fl, kt, dt, kon = new[k]
    print(f"  ИдКод={k[0]} ЕДРПОУ={k[1]} {fl[:22]:22s} | Кт={kt} Дт={dt} Кон={kon}")
print(f"\n=== Изменённые существующие ключи ({len(changed)}) — ожидаемо те, у кого есть и 661/663, и 665 ===")
for k in changed:
    print(f"  ИдКод={k[0]} ЕДРПОУ={k[1]} {new[k][0][:22]:22s} | СТАР={old[k]} -> НОВ={new[k]}")

print("\nКонтроль Алов (ожид. Кт=21433.49, Дт=21433.49, Кон=0):")
for k, v in new.items():
    if v[0].startswith("Алов"):
        print(f"  {k} -> {v}")
