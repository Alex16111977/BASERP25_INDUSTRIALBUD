# --- 4. Классификация ---
def cls(d):
    erp_kon = sum(d['erp_org'].values()); buh_kon = sum(d['buh_org'].values())
    razn = erp_kon - buh_kon
    # per-org разъезд?
    orgs = set(d['erp_org']) | set(d['buh_org'])
    perorg = any(abs(d['erp_org'].get(o,0.0) - d['buh_org'].get(o,0.0)) > 0.01 for o in orgs)
    if abs(razn) <= 0.01 and perorg: return "A_межорг"
    if abs(razn) < 1.0: return "D_копейки" if abs(razn) > 0.001 else "ok"
    if abs(razn) <= 1000: return "D_копейки"
    if erp_kon > buh_kon + 0.01 and abs(buh_kon) < 1.0: return "B_ЕРП_долг_не_выпл"
    if erp_kon < buh_kon - 0.01: return "C_Бух_долг_ЕРП_нет"
    return "?_прочее"

rows = []
for ид, d in FL.items():
    erp_kon = round(sum(d['erp_org'].values()),2); buh_kon = round(sum(d['buh_org'].values()),2)
    razn = round(erp_kon - buh_kon, 2)
    c = cls(d)
    if c == "ok": continue
    rows.append((c, abs(razn), ид, d, erp_kon, buh_kon, razn))
rows.sort(key=lambda r: (r[0], -r[1]))

