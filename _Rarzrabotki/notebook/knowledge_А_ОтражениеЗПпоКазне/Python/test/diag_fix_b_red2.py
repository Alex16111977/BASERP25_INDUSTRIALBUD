"""RED Fix B (уточнённый): применяем гарды _ПНМП_ДобавитьСтроку к источнику Fix B (ОЗФУ А_ВзСС Ф1)
и сверяем per-ФЛ с ТЕКУЩИМИ Начислениями Ф1 передачи. Разница должна быть ТОЛЬКО у алиментщиков."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
зап=lambda x: erp.ЗначениеЗаполнено(x); X=lambda x: erp.XMLСтрока(x)

q=erp.NewObject("Запрос")
q.Text="ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне ГДЕ Номер=&Н И Дата=ДАТАВРЕМЯ(2025,12,31,12,0,0)"
q.УстановитьПараметр("Н","000000001"); s=q.Выполнить().Выбрать(); s.Следующий(); отр=s.Ссылка

# Источник Fix B (рефы)
qa=erp.NewObject("Запрос"); qa.УстановитьПараметр("Осн",отр)
qa.Text="""ВЫБРАТЬ ВзС.ФизическоеЛицо КАК ФЛ, ВзС.Подразделение КАК Подр, ВзС.ОрганизацияБухгалтерия КАК ОргБух,
	СУММА(ВЫБОР КОГДА ВзС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
		ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ -ВзС.СуммаВзаиморасчетов КОНЕЦ) КАК Сумма
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзС
ГДЕ ВЫРАЗИТЬ(ВзС.Регистратор КАК Документ.ОтражениеЗарплатыВФинансовомУчете).А_ДокОтражениеЗПпоКазне=&Осн
	И ВзС.ФормаPL=ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
СГРУППИРОВАТЬ ПО ВзС.ФизическоеЛицо, ВзС.Подразделение, ВзС.ОрганизацияБухгалтерия"""
A=qa.Выполнить().Выгрузить()

guard_total=0.0; per_fl_b={}; skip_orgbukh=0.0; skip_cel=0.0
for i in range(A.Количество()):
    r=A.Получить(i); ob=r.ОргБух; подр=r.Подр; фл=r.ФЛ; сум=float(r.Сумма)
    if not зап(ob): skip_orgbukh+=сум; continue
    цел=ob.А_ПодразделениеЗарплатаБух
    if not зап(цел) or X(цел)==X(подр): skip_cel+=сум; continue
    guard_total+=сум; нм=фл.Наименование; per_fl_b[нм]=per_fl_b.get(нм,0.0)+сум
print(f"Fix B после гардов: ИТОГО={round(guard_total,2)} | отсеяно ОргБух-пусто={round(skip_orgbukh,2)}, целевое={round(skip_cel,2)}")

# Текущие Начисления Ф1 передачи per ФЛ (рефы)
qb=erp.NewObject("Запрос"); qb.УстановитьПараметр("Осн",отр)
qb.Text="""ВЫБРАТЬ Н.ФизическоеЛицо КАК ФЛ, СУММА(Н.Сумма) КАК С
ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Начисления КАК Н
ГДЕ Н.Ссылка.А_ДокументОснование=&Осн И Н.ФормаPL=ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
СГРУППИРОВАТЬ ПО Н.ФизическоеЛицо"""
B=qb.Выполнить().Выгрузить()
per_fl_cur={}; cur_total=0.0
for i in range(B.Количество()):
    r=B.Получить(i); per_fl_cur[r.ФЛ.Наименование]=float(r.С); cur_total+=float(r.С)
print(f"Текущее (после гардов): ИТОГО={round(cur_total,2)}")
print(f"\nДельта ИТОГО (Fix B − текущее) = {round(guard_total-cur_total,2)} (ожид. −12512.50 = −Σ алиментов)")

# Per-ФЛ расхождения (кроме нулевых)
print("\nРасхождения per-ФЛ (Fix B − текущее), |Δ|>0.01:")
кл=set(per_fl_b)|set(per_fl_cur); n=0
for k in кл:
    d=per_fl_b.get(k,0.0)-per_fl_cur.get(k,0.0)
    if abs(d)>0.01:
        n+=1
        print(f"  {k[:34]:34}: Fix B={round(per_fl_b.get(k,0),2):>10} тек={round(per_fl_cur.get(k,0),2):>10} Δ={round(d,2)}")
print(f"Всего ФЛ с расхождением: {n} (ожид. 2 — Дубінько, Старіков)")
