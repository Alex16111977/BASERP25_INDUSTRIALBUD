import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")

qf = erp.NewObject("Запрос")
qf.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.ФизическиеЛица ГДЕ Наименование ПОДОБНО \"%Постернак Андр%\"")
fs = qf.Выполнить().Выбрать(); fs.Следующий()
ФЛ = fs.С; uid = erp.String(ФЛ.УникальныйИдентификатор())

qp = erp.NewObject("Запрос")
qp.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.А_ОтражениеЗПпоКазне "
            "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59) УПОРЯДОЧИТЬ ПО Дата")
ps = qp.Выполнить().Выбрать(); ps.Следующий()
obj = ps.С.ПолучитьОбъект()
print("Наполнение в память...")
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()
obj.ЗаполнитьОтражениеЗарплатыВФинансовомУчетеИзБазЗП()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()

def en(v): return erp.XMLСтрока(v) if erp.ЗначениеЗаполнено(v) else "<пусто>"
def isfl(r):
    return erp.ЗначениеЗаполнено(r.ФизическоеЛицо) and erp.String(r.ФизическоеЛицо.УникальныйИдентификатор())==uid

ф1=ф2=tot=есв=0.0
for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
    if not isfl(r): continue
    s=float(r.Сумма); vz=float(r.ВзносыВсего); фп=en(r.ФормаPL)
    tot+=s; есв+=vz
    if фп=="Форма1": ф1+=s
    elif фп=="Форма2": ф2+=s
ндфл=sum(float(r.Сумма) for r in obj.НачисленныйНДФЛ if isfl(r))

print(f"\n=== НачисленнаяЗарплата для Постернака (после разметки) ===")
print(f"  Σ Сумма ВСЕГО (management total) = {tot:,.2f}")
print(f"  Σ Форма1 = {ф1:,.2f}")
print(f"  Σ Форма2 = {ф2:,.2f}")
print(f"  Σ ВзносыВсего (ЕСВ) = {есв:,.2f}")
print(f"  Σ НачисленныйНДФЛ = {ндфл:,.2f}")
print(f"\n=== Что даст А_ВзСС (Оплата труда) ===")
print(f"  А_ВзСС Ф1 = НачЗП(Ф1) - НДФЛ = {ф1:,.2f} - {ндфл:,.2f} = {ф1-ндфл:,.2f}  <-- в отчёте 19 575,72")
print(f"  ОЖИДАЕТСЯ А_ВзСС Ф1 = 27 913,53 (= РаспределениеКазна Зарплата)")
print(f"\n=== ДИАГНОЗ ===")
print(f"  bukh(NET take-home) = 27 913,53; GROSS(НачисленияБух) = 36 251,34; НДФЛ = 8 337,81")
print(f"  Если Ф1={ф1:,.2f} ≈ bukh(27913.53) → НачЗП.Ф1 = NET, провед. вычитает НДФЛ снова → {ф1-ндфл:,.2f} (двойное)")
print(f"  ФИКС: Ф1 должен = GROSS(36 251,34) → А_ВзСС = 36251.34 - 8337.81 = 27913.53 ✓")
print(f"  Management total(tot)={tot:,.2f} >= GROSS(36251.34)? {'ДА' if tot>=36251.34 else 'НЕТ — упрётся в потолок'}")

erp=None
