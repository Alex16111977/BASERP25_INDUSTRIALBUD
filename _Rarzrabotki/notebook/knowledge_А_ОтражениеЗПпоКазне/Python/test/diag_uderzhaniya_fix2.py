# -*- coding: utf-8 -*-
"""RED Fix 2: ИсхПодр удержаний из дочернего ОЗФУ УдержаннаяЗарплата (per ФЛ, max-Σ).
Тест запроса + симуляция исправленного _ПНМП_ЗаполнитьУдержания на №000000001 от 31.12.2025."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
зап = lambda x: erp.ЗначениеЗаполнено(x)

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне "
          "ГДЕ Номер = &Н И Дата = ДАТАВРЕМЯ(2025,12,31,12,0,0)")
q.УстановитьПараметр("Н", "000000001")
s = q.Выполнить().Выбрать(); s.Следующий()
отр = s.Ссылка
doc = отр.ПолучитьОбъект()
print("Отражение:", doc.Номер, "от", doc.Дата)

# --- Запрос Fix 2: ФЛ -> подразделение из дочернего ПРОВЕДЁННОГО ОЗФУ УдержаннаяЗарплата ---
qm = erp.NewObject("Запрос")
qm.УстановитьПараметр("Осн", отр)
qm.Text = """ВЫБРАТЬ
	У.ФизическоеЛицо КАК ФЛ,
	У.ПодразделениеПредприятия КАК Подр,
	СУММА(У.Сумма) КАК Сумма
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете.УдержаннаяЗарплата КАК У
ГДЕ У.Ссылка.А_ДокОтражениеЗПпоКазне = &Осн
	И У.Ссылка.Проведен
	И У.ПодразделениеПредприятия <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
СГРУППИРОВАТЬ ПО У.ФизическоеЛицо, У.ПодразделениеПредприятия
УПОРЯДОЧИТЬ ПО Сумма УБЫВ"""
try:
    тз = qm.Выполнить().Выгрузить()
    print(f"[OK] запрос дочернего ОЗФУ: {тз.Количество()} (ФЛ×подр) строк")
except Exception as e:
    info = getattr(e, 'excepinfo', None)
    print("[FAIL]", info[2] if info else e); sys.exit(1)

подр_по_фл = {}
for i in range(тз.Количество()):
    r = тз.Получить(i)
    k = erp.XMLСтрока(r.ФЛ)
    if k not in подр_по_фл:
        подр_по_фл[k] = r.Подр
print(f"Карта ПодрУдержПоФЛ: {len(подр_по_фл)} ФЛ")

# --- Симуляция исправленного _ПНМП_ЗаполнитьУдержания (fallback ИсхПодр из карты) ---
ту = doc.УдержанияБухгалтерия
прошло = 0; сумма_ок = 0.0
print(f"\nУдержанияБухгалтерия: {ту.Количество()} строк (с Fix 2):")
for i in range(ту.Количество()):
    r = ту.Получить(i)
    фл = r.ФизическоеЛицо
    summa = float(r.Сумма)
    flk = erp.XMLСтрока(фл) if зап(фл) else None
    исхподр = r.ПодразделениеПредприятия if зап(r.ПодразделениеПредприятия) else подр_по_фл.get(flk)
    подрн = исхподр.Наименование if (исхподр is not None and зап(исхподр)) else "(всё ещё ПУСТО)"
    флн = фл.Наименование if зап(фл) else "(пусто)"
    ok = (summa != 0 and зап(фл) and исхподр is not None and зап(исхподр))
    if ok: прошло += 1; сумма_ок += summa
    print(f"  {флн[:28]:28} | Σ {summa:>10.2f} | ИсхПодр={подрн[:18]:18} | {'✓' if ok else '✗'}")
print(f"\nИтог Fix 2: прошло бы {прошло}/{ту.Количество()} строк, Σ {round(сумма_ок,2)} (ожид. 4 / 12512.50)")
