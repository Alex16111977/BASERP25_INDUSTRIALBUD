# -*- coding: utf-8 -*-
# §5 симуляция фикса (Подход B): для всех 11 multi-org ФЛ проверить, что
#   target_орг = НачБух_орг − НДФЛ_орг − ВЗ_орг  == факт А_ВзСС-Расход per-org (эталон),
# а также == GROSS-пропорция NET. И что 5 «сбалансированных» уже совпадают (фикс их не тронет).
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
def run(t):
    q = erp.NewObject("Запрос"); q.Текст = t; return q.Выполнить().Выгрузить()
P = lambda a: f"ГОД({a})=2026 И МЕСЯЦ({a})=2"

# НачисленияБух GROSS per (ФЛ,Орг)
buh = {}
tz = run(f"""ВЫБРАТЬ НБ.ФизЛицо.Наименование КАК ФИО, НБ.Организация.Наименование КАК Орг, СУММА(НБ.Сумма) КАК С
ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленияБух КАК НБ ГДЕ {P('НБ.Ссылка.Дата')}
СГРУППИРОВАТЬ ПО НБ.ФизЛицо.Наименование, НБ.Организация.Наименование""")
for i in range(tz.Количество()):
    r = tz.Получить(i); buh.setdefault(r.ФИО,{})[r.Орг]=round(float(r.С),2)

# НалогиБухгалтерия per (ФЛ,Орг): НДФЛ, ВЗ
tax = {}
tz = run(f"""ВЫБРАТЬ НлБ.Сотрудник.ФизическоеЛицо.Наименование КАК ФИО, НлБ.Организация.Наименование КАК Орг,
  СУММА(ВЫБОР КОГДА НлБ.ТипНалога=ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.НДФЛ) ТОГДА НлБ.Сумма ИНАЧЕ 0 КОНЕЦ) КАК НДФЛ,
  СУММА(ВЫБОР КОГДА НлБ.ТипНалога=ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.ВоенныйСбор) ТОГДА НлБ.Сумма ИНАЧЕ 0 КОНЕЦ) КАК ВЗ
ИЗ Документ.А_ОтражениеЗПпоКазне.НалогиБухгалтерия КАК НлБ ГДЕ {P('НлБ.Ссылка.Дата')}
СГРУППИРОВАТЬ ПО НлБ.Сотрудник.ФизическоеЛицо.Наименование, НлБ.Организация.Наименование""")
for i in range(tz.Количество()):
    r = tz.Получить(i); tax.setdefault(r.ФИО,{})[r.Орг]=(round(float(r.НДФЛ),2),round(float(r.ВЗ),2))

# А_ВзСС Форма1 Приход/Расход per (ФЛ,Орг)
vp, vr = {}, {}
tz = run(f"""ВЫБРАТЬ ВзС.ФизическоеЛицо.Наименование КАК ФИО, ВзС.ОрганизацияБухгалтерия.Наименование КАК Орг,
  СУММА(ВЫБОР КОГДА ВзС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК П,
  СУММА(ВЫБОР КОГДА ВзС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) ТОГДА ВзС.СуммаВзаиморасчетов ИНАЧЕ 0 КОНЕЦ) КАК Р
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзС
ГДЕ {P('ВзС.Период')} И ВзС.ФормаPL=ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)
СГРУППИРОВАТЬ ПО ВзС.ФизическоеЛицо.Наименование, ВзС.ОрганизацияБухгалтерия.Наименование""")
for i in range(tz.Количество()):
    r = tz.Получить(i); vp.setdefault(r.ФИО,{})[r.Орг or "(пусто)"]=round(float(r.П),2); vr.setdefault(r.ФИО,{})[r.Орг or "(пусто)"]=round(float(r.Р),2)

multi = sorted([f for f in buh if len(buh[f])>1])
print(f"=== Симуляция фикса по {len(multi)} multi-org ФЛ ===")
print(f"{'ФИО':32} {'Орг':24} {'GROSS':>10} {'target(net)':>11} {'GROSSпроп':>10} {'фактРасход':>11} {'тек.Приход':>11} {'ok?':>4}")
all_ok = True
for f in multi:
    gtot = round(sum(buh[f].values()),2)
    nettot = round(sum(g - sum(tax.get(f,{}).get(o,(0,0))) for o,g in buh[f].items()),2)
    bad = False
    for o,g in sorted(buh[f].items()):
        ndfl,vz = tax.get(f,{}).get(o,(0,0))
        target = round(g-ndfl-vz,2)
        gp = round(nettot*g/gtot,2)
        rs = vr.get(f,{}).get(o,0.0); pr = vp.get(f,{}).get(o,0.0)
        ok = abs(target-rs)<=0.02
        if not ok: bad=True
        print(f"{f[:31]:32} {o[:23]:24} {g:10,.2f} {target:11,.2f} {gp:10,.2f} {rs:11,.2f} {pr:11,.2f} {'OK' if ok else 'XX':>4}")
    # текущее состояние сбалансировано?
    plug = round(sum(vp.get(f,{}).get(o,0)-vr.get(f,{}).get(o,0) for o in set(vp.get(f,{}))|set(vr.get(f,{}))),2)
    status = "СБАЛАНС (фикс не тронет)" if abs(plug)<=0.02 else f"ПЛУГ → фикс приведёт Приход к target"
    print(f"{'':32} -> NET={nettot:,.2f}  Σплуг(тек)={plug:,.2f}  {status}")
    print("-"*118)
    if bad: all_ok=False
print("ИТОГ: формула target==Расход для всех" if all_ok else "ИТОГ: ЕСТЬ расхождения target!=Расход — разобрать")
erp=None
