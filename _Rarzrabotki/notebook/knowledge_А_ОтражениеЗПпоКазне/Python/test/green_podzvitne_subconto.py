import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client as w
erp = w.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
ob = erp.Документы.А_ОтражениеЗПпоКазне.НайтиПоНомеру("000000001").ПолучитьОбъект()
ob.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()

ok_gun = False
print("УдержанияБухгалтерия:")
for i in range(ob.УдержанияБухгалтерия.Количество()):
    s = ob.УдержанияБухгалтерия.Получить(i)
    флн = s.ФизическоеЛицо.Наименование if erp.ЗначениеЗаполнено(s.ФизическоеЛицо) else ""
    суб = s.Субконто1.Наименование if erp.ЗначениеЗаполнено(s.Субконто1) else "<нет>"
    субтип = s.Субконто1.Метаданные().Имя if erp.ЗначениеЗаполнено(s.Субконто1) else "-"
    ст = s.СтатьяАктивовПассивов.Наименование if erp.ЗначениеЗаполнено(s.СтатьяАктивовПассивов) else "<нет>"
    сч = s.СчетУчета.Код if erp.ЗначениеЗаполнено(s.СчетУчета) else "<нет>"
    print(f"   {флн[:22]:22s} | счёт={сч} | статья={ст[:30]:30s} | Субконто1={суб} ({субтип})")
    if флн.startswith("Гуняга"):
        ok_gun = (сч == "3721" and ст.startswith("Денежные средства")
                  and субтип == "ФизическиеЛица" and суб == флн)
print("\nИТОГ Гуняга (3721 + статья подотчётных + Субконто1=ФЛ):", "GREEN ✅" if ok_gun else "RED ❌")
