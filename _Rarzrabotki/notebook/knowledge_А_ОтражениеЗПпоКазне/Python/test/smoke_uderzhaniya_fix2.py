# -*- coding: utf-8 -*-
"""GREEN приёмка Fix 2: кнопка на №000000001 (31.12.2025) → удержания переносятся.
Ожид: ТЧ Удержания 4 строки Σ 12 512,50; ПАП «Прочие пассивы» net=0; идемпотентно."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне "
          "ГДЕ Номер = &Н И Дата = ДАТАВРЕМЯ(2025,12,31,12,0,0)")
q.УстановитьПараметр("Н", "000000001")
s = q.Выполнить().Выбрать(); s.Следующий()
отр = s.Ссылка
print("Отражение:", отр.Номер, отр.Дата)

def найти_передачу(осн):
    qp = erp.NewObject("Запрос")
    qp.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями "
               "ГДЕ А_ДокументОснование = &О")
    qp.УстановитьПараметр("О", осн); sp = qp.Выполнить().Выбрать()
    return sp.Ссылка if sp.Следующий() else None

def удерж(пер):
    qn = erp.NewObject("Запрос")
    qn.Text = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К, СУММА(У.Сумма) КАК С "
               "ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Удержания КАК У "
               "ГДЕ У.Ссылка = &Д")
    qn.УстановитьПараметр("Д", пер); r = qn.Выполнить().Выбрать(); r.Следующий()
    return int(r.К or 0), round(float(r.С or 0), 2)

# === Прогон 1 ===
отр.ПолучитьОбъект().СоздатьПередачуНачисленийМеждуПодразделениями()
пер = найти_передачу(отр)
print("Передача:", пер.Номер, "Проведен =", пер.ПолучитьОбъект().Проведен)
к, сум = удерж(пер)
print(f"ТЧ Удержания: {к} строк, Σ {сум}  (ожид. 4 / 12512.5)")

# ПАП «Прочие пассивы» net по регистратору
qp = erp.NewObject("Запрос")
qp.Text = ("ВЫБРАТЬ СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) "
           "ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Нетто, СУММА(П.Сумма) КАК Оборот "
           "ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П "
           "ГДЕ П.Регистратор = &Д И П.Статья.Наименование = &Ст")
qp.УстановитьПараметр("Д", пер); qp.УстановитьПараметр("Ст", "Прочие пассивы")
r = qp.Выполнить().Выбрать(); r.Следующий()
print(f"ПАП(Прочие пассивы): net={round(float(r.Нетто or 0),2)} (ожид.~0), оборот={round(float(r.Оборот or 0),2)}")

# А_ВзСС не пишется из удержаний (только из Начислений) — проверим, что удержания туда НЕ попали
# (ЗаполнитьИзПередачиНачислений читает только ТЧ Начисления)

# === Прогон 2 — идемпотентность ===
отр.ПолучитьОбъект().СоздатьПередачуНачисленийМеждуПодразделениями()
к2, сум2 = удерж(найти_передачу(отр))
print(f"Идемпотентность: повтор Удержания {к2} строк Σ {сум2} (Δ строк={к2-к}, ΔΣ={round(сум2-сум,2)})")

ok = (к == 4 and abs(сум - 12512.5) < 0.05 and (к2, сум2) == (к, сум))
print("\n=== ВЕРДИКТ:", "PASS" if ok else "CHECK", "===")
