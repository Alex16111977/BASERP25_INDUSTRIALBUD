def run(text, params=None, title=""):
    q = erp.NewObject("Запрос"); q.Text = text
    for k, v in (params or {}).items():
        q.УстановитьПараметр(k, v)
    try:
        res = q.Выполнить().Выгрузить()
        print(f"[OK] {title}: строк={res.Количество()}")
        return res
    except Exception as e:
        info = getattr(e, 'excepinfo', None)
        print(f"[FAIL] {title}: {info[2] if info else e}")
        return None

