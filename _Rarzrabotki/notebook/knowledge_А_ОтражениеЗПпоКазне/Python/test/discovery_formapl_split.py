# -*- coding: utf-8 -*-
# Rule #-1 discovery для Этапа 2: валидация алгоритма Форма1 (zup_1 суммы × А_РаспределениеЗаработнойПлаты.Распределение)
# + оценка базиса Форма2. На эталоне №000000005 / апрель 2026. READ-ONLY (без записи).
import win32com.client, sys
from collections import defaultdict
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected ERP")

q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка, Номер КАК Номер ИЗ Документ.А_ОтражениеЗПпоКазне "
           "ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2026,4,1,0,0,0) И ДАТАВРЕМЯ(2026,4,30,23,59,59) УПОРЯДОЧИТЬ ПО Дата")
sel = q.Выполнить().Выбрать(); sel.Следующий()
print(f"Документ: №{sel.Номер}")
obj = sel.Ссылка.ПолучитьОбъект()

print("Загрузка РаспределениеКазна + zup_1 закладок в память...")
obj.ЗаполнитьОтражениеЗарплатыВФинансовомУчетеИзБазЗП()   # РаспределениеКазна (с ФормаPL)
obj.ЗагрузитьНалогиИУдержанияИзЗарплатыБух()              # НачисленияБух/НалогиБухгалтерия/УдержанияБухгалтерия

def fl_uid(ref):
    return erp.String(ref.УникальныйИдентификатор()) if erp.ЗначениеЗаполнено(ref) else None

# --- zup_1 суммы per ФизЛицо ---
нач_бух = defaultdict(float)   # НачисленияБух.Сумма (gross офиц)
нал_ндфл = defaultdict(float)  # НалогиБухгалтерия СуммаНДФЛ (НДФЛ+ВС)
нал_есв  = defaultdict(float)  # НалогиБухгалтерия СуммаФОТ (ЕСВ)
удерж    = defaultdict(float)  # УдержанияБухгалтерия.Сумма
for r in obj.НачисленияБух:
    u = fl_uid(r.ФизЛицо)
    if u: нач_бух[u] += float(r.Сумма)
for r in obj.НалогиБухгалтерия:
    u = fl_uid(r.Сотрудник.ФизическоеЛицо) if erp.ЗначениеЗаполнено(r.Сотрудник) else None
    if u:
        нал_ндфл[u] += float(r.СуммаНДФЛ)
        нал_есв[u]  += float(r.СуммаФОТ)
for r in obj.УдержанияБухгалтерия:
    u = fl_uid(r.ФизическоеЛицо)
    if u: удерж[u] += float(r.Сумма)

фл_все = set(нач_бух)|set(нал_ндфл)|set(нал_есв)|set(удерж)
net = {u: нач_бух[u]-нал_ндфл[u]-удерж[u] for u in фл_все}
Σnet = sum(net.values()); Σесв = sum(нал_есв.values()); Σндфл = sum(нал_ндфл.values())
print(f"\n[zup_1] ФЛ={len(фл_все)} | Σ НачБух={sum(нач_бух.values()):,.2f} | Σ NET={Σnet:,.2f} | Σ ЕСВ={Σесв:,.2f} | Σ НДФЛ/ВС={Σндфл:,.2f}")

# --- Ф1 документы А_РаспределениеЗаработнойПлаты из РаспределениеКазна ---
ф1_доки = {}
for r in obj.РаспределениеКазна:
    if erp.XMLСтрока(r.ФормаPL) == "Форма1" and erp.ЗначениеЗаполнено(r.ДокРаспределениеЗП):
        ф1_доки[fl_uid(r.ДокРаспределениеЗП)] = r.ДокРаспределениеЗП
масДоки = erp.NewObject("Массив")
for d in ф1_доки.values(): масДоки.Добавить(d)
print(f"[Ф1] уникальных А_РаспределениеЗаработнойПлаты = {масДоки.Количество()}")

# --- Распределение этих документов: per Сотрудник.ФизическоеЛицо ---
qр = erp.NewObject("Запрос")
qр.УстановитьПараметр("Доки", масДоки)
qр.Текст = """ВЫБРАТЬ
    Р.Сотрудник.ФизическоеЛицо КАК ФЛ,
    СУММА(Р.СуммаНачисления) КАК СуммаНачисления,
    СУММА(Р.СуммаФОТ) КАК СуммаФОТ,
    СУММА(Р.СуммаНалогов) КАК СуммаНалогов
ИЗ Документ.А_РаспределениеЗаработнойПлаты.Распределение КАК Р
ГДЕ Р.Ссылка В (&Доки)
СГРУППИРОВАТЬ ПО Р.Сотрудник.ФизическоеЛицо"""
расп = {}
вб = qр.Выполнить().Выбрать()
Σрасп_нач = Σрасп_фот = Σрасп_нал = 0.0
while вб.Следующий():
    u = fl_uid(вб.ФЛ)
    if not u: continue
    расп[u] = (float(вб.СуммаНачисления), float(вб.СуммаФОТ), float(вб.СуммаНалогов))
    Σрасп_нач += float(вб.СуммаНачисления); Σрасп_фот += float(вб.СуммаФОТ); Σрасп_нал += float(вб.СуммаНалогов)
print(f"[Распределение Ф1] ФЛ={len(расп)} | Σ СуммаНачисления={Σрасп_нач:,.2f} | Σ СуммаФОТ={Σрасп_фот:,.2f} | Σ СуммаНалогов={Σрасп_нал:,.2f}")

# --- РЕКОНСИЛЯЦИЯ totals ---
print("\n=== РЕКОНСИЛЯЦИЯ Ф1 (zup_1 vs Распределение) ===")
print(f"NET   : zup_1 {Σnet:,.2f}  vs  Распр.СуммаНачисления {Σрасп_нач:,.2f}  Δ={Σnet-Σрасп_нач:,.2f}")
print(f"ЕСВ   : zup_1 {Σесв:,.2f}  vs  Распр.СуммаФОТ        {Σрасп_фот:,.2f}  Δ={Σесв-Σрасп_фот:,.2f}")
print(f"НДФЛ/ВС: zup_1 {Σндфл:,.2f} vs  Распр.СуммаНалогов     {Σрасп_нал:,.2f}  Δ={Σндфл-Σрасп_нал:,.2f}")

# --- ПОКРЫТИЕ: ФЛ с NET>0 но без Распределения ---
без_покр = [u for u in фл_все if net[u] > 0.01 and u not in расп]
сум_без = sum(net[u] for u in без_покр)
print(f"\n[Покрытие] ФЛ с NET>0 без строк Распределение Ф1: {len(без_покр)} (Σ NET={сум_без:,.2f})")
расп_без_zup = [u for u in расп if u not in net or abs(net.get(u,0))<0.01]
print(f"[Покрытие] ФЛ в Распределение но без zup_1 NET: {len(расп_без_zup)}")

# --- ТЕКУЩЕЕ отражение (для оценки Ф2 = total - Ф1) ---
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
Σотр_net = sum(float(r.Сумма) for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам)
Σотр_есв = sum(float(r.ВзносыВсего) for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам)
Σотр_ндфл = sum(float(r.Сумма) for r in obj.НачисленныйНДФЛ)
print(f"\n=== ТЕКУЩЕЕ отражение (НачисленнаяЗарплата/НДФЛ) ===")
print(f"NET отражения  = {Σотр_net:,.2f}   →  Ф2(остаток)=total-Ф1 = {Σотр_net-Σnet:,.2f}")
print(f"ЕСВ отражения  = {Σотр_есв:,.2f}   →  Ф2 ЕСВ = {Σотр_есв-Σесв:,.2f}")
print(f"НДФЛ отражения = {Σотр_ндфл:,.2f}  →  Ф2 НДФЛ = {Σотр_ндфл-Σндфл:,.2f}")

erp = None
print("\nDone (не записан).")
