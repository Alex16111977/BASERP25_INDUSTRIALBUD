# -*- coding: utf-8 -*-
"""
Создаёт ObjectModule.bsl для внешней печатной формы "Рахунок на оплату (без зразка ПП)".
Берёт типовой ManagerModule.bsl из ПечатьСчетовНаОплату и:
1. Убирает блок СрокДействия + ОбразецЗаполненияПП (строки 102-187)
2. Оборачивает в структуру внешней обработки (СведенияОВнешнейОбработке + Печать)
3. Убирает #Если Сервер... #КонецЕсли обёртку
"""

import os

SRC = r"C:\Configuration_downloads\BASERP25\DataProcessors\ПечатьСчетовНаОплату\Ext\ManagerModule.bsl"
DST = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Печать счета\Ext\ObjectModule.bsl"

with open(SRC, "r", encoding="utf-8-sig") as f:
    lines = f.readlines()

print(f"Исходный файл: {len(lines)} строк")

# Находим строки для удаления:
# Блок 1: от "Если ЗначениеЗаполнено(ДатаПлатежа)" (строка ~102) до "КонецЕсли;" после ОбразецЗаполненияПП (строка ~187)
# Конкретно: убираем вывод СрокДействия в заголовок + весь блок ОбразецЗаполненияПП

# Ищем маркеры
start_delete = None
end_delete = None
bracket_count = 0

for i, line in enumerate(lines):
    stripped = line.strip()

    # Начало блока для удаления: "Если ЗначениеЗаполнено(ДатаПлатежа)"
    if start_delete is None and "ЗначениеЗаполнено(ДатаПлатежа)" in stripped and i < 200:
        start_delete = i
        print(f"  Начало удаления: строка {i+1}: {stripped[:60]}")

    # Конец блока: строка с "КолонкаКодов" после блока ОбразецЗаполнения
    if start_delete is not None and end_delete is None:
        if "КолонкаКодов" in stripped and "ИмяДополнительнойКолонки" in stripped:
            end_delete = i  # эту строку НЕ удаляем
            print(f"  Конец удаления перед строкой {i+1}: {stripped[:60]}")
            break

if start_delete is None or end_delete is None:
    print("ОШИБКА: не найдены маркеры удаления!")
    exit(1)

# Удаляем строки
deleted_lines = lines[start_delete:end_delete]
print(f"  Удаляю {len(deleted_lines)} строк ({start_delete+1}-{end_delete})")

remaining_lines = lines[:start_delete] + lines[end_delete:]

# Убираем первую строку #Если Сервер... и последнюю #КонецЕсли
clean_lines = []
skip_first_if = True
for line in remaining_lines:
    stripped = line.strip()
    if skip_first_if and stripped.startswith("#Если Сервер"):
        skip_first_if = False
        continue
    if stripped == "#КонецЕсли":
        # Проверяем - это последний #КонецЕсли? Пропускаем
        pass  # оставляем пока, уберём последний ниже
    clean_lines.append(line)

# Убираем последнюю строку "#КонецЕсли" (обёртка компиляции)
for i in range(len(clean_lines) - 1, -1, -1):
    if clean_lines[i].strip() == "#КонецЕсли":
        clean_lines.pop(i)
        break

# Формируем ObjectModule
header = '''// Внешняя печатная форма "Рахунок на оплату (без зразка ПП)"
// Создана из типового ManagerModule обработки ПечатьСчетовНаОплату
// Убран блок "Зразок заповнення платіжного доручення" и "Увага! Рахунок дійсний до..."

#Область СведенияОВнешнейОбработке

Функция СведенияОВнешнейОбработке() Экспорт

	ПараметрыРегистрации = Новый Структура;
	ПараметрыРегистрации.Вставить("Вид", "ПечатнаяФорма");
	ПараметрыРегистрации.Вставить("БезопасныйРежим", Ложь);
	ПараметрыРегистрации.Вставить("Версия", "2.0");
	ПараметрыРегистрации.Вставить("Информация", "Рахунок на оплату без зразка платіжного доручення та попередження");

	МассивНазначений = Новый Массив;
	МассивНазначений.Добавить("Документ.ЗаказКлиента");
	МассивНазначений.Добавить("Документ.РеализацияТоваровУслуг");
	МассивНазначений.Добавить("Документ.СчетНаОплатуКлиенту");
	ПараметрыРегистрации.Вставить("Назначение", МассивНазначений);

	ПараметрыРегистрации.Вставить("Наименование", "Рахунок на оплату (без зразка ПП)");

	ТаблицаКоманд = Новый ТаблицаЗначений;
	ТаблицаКоманд.Колонки.Добавить("Представление", Новый ОписаниеТипов("Строка"));
	ТаблицаКоманд.Колонки.Добавить("Идентификатор", Новый ОписаниеТипов("Строка"));
	ТаблицаКоманд.Колонки.Добавить("Использование", Новый ОписаниеТипов("Строка"));
	ТаблицаКоманд.Колонки.Добавить("ПоказыватьОповещение", Новый ОписаниеТипов("Булево"));
	ТаблицаКоманд.Колонки.Добавить("Модификатор", Новый ОписаниеТипов("Строка"));

	НоваяКоманда = ТаблицаКоманд.Добавить();
	НоваяКоманда.Представление    = "Рахунок на оплату (без зразка ПП)";
	НоваяКоманда.Идентификатор    = "СчетНаОплатуБезПП";
	НоваяКоманда.Использование    = "ВызовСерверногоМетода";
	НоваяКоманда.ПоказыватьОповещение = Ложь;
	НоваяКоманда.Модификатор      = "ПечатьMXL";

	ПараметрыРегистрации.Вставить("Команды", ТаблицаКоманд);

	Возврат ПараметрыРегистрации;

КонецФункции

#КонецОбласти

'''

# Заменяем вызов Печать — сигнатура для внешних обработок 4 параметра
# Типовая: Процедура Печать(МассивОбъектов, ПараметрыПечати, КоллекцияПечатныхФорм, ОбъектыПечати, ПараметрыВывода)
# Внешняя: Процедура Печать(МассивОбъектов, КоллекцияПечатныхФорм, ОбъектыПечати, ПараметрыВывода)

body = "".join(clean_lines)

# Заменяем сигнатуру Печать
body = body.replace(
    "Процедура Печать(МассивОбъектов, ПараметрыПечати, КоллекцияПечатныхФорм, ОбъектыПечати, ПараметрыВывода) Экспорт",
    "Процедура Печать(МассивОбъектов, КоллекцияПечатныхФорм, ОбъектыПечати, ПараметрыВывода) Экспорт\n\n\tПараметрыПечати = Новый Структура;"
)

# Заменяем имя макета
body = body.replace('"СчетНаОплату"', '"СчетНаОплатуБезПП"')
body = body.replace(
    "НСтр(\"ru='Счет на оплату';uk='Рахунок на оплату'\")",
    "НСтр(\"ru='Счет на оплату (без ПП)';uk='Рахунок на оплату (без зразка ПП)'\")"
)

# Убираем ссылки на Обработки.ПечатьСчетовНаОплату — заменяем на прямые вызовы
# (Макет получается через ОбщийМакет или через Обработки — нужно оставить как есть)

result = header + body

# Записываем
os.makedirs(os.path.dirname(DST), exist_ok=True)
with open(DST, "w", encoding="utf-8-sig") as f:
    f.write(result)

print(f"\nРезультат записан: {DST}")
print(f"Размер: {len(result)} символов, {result.count(chr(10))} строк")
