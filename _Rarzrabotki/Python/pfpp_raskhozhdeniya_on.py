# -*- coding: utf-8 -*-
"""Строки активных СС (BaseERP), где загальна назва СТРОКИ спецификации ≠ загальна назва КАРТОЧКИ.

С 04.09.2026 отчёт А_ПланФактныйПроизводствоПолный берёт назву плана из строки СС
(К.ОбщееНазвание), а факт закупок классифицируется карточной назвой
(Номенклатура.А_ОбщееНазваниеНоменклатуры). По строкам из этого списка план и факт попадут под
разные «Загальна назва» и не будут неттоваться в «План на факт». Лечится данными: выровнять назву
в строке СС или в карточке номенклатуры.

Запуск:  python pfpp_raskhozhdeniya_on.py
Выход:   _Rarzrabotki/Отчеты/А_ПланФактныйПроизводствоПолный_расхождения_ОН.md
"""
import sys
import datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
OUT = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ПланФактныйПроизводствоПолный_расхождения_ОН.md"

# Рабочие СС пользователя — выносим их вперёд в отчёте.
ПРИОРИТЕТ = ["МД ООН 2026", "МД ООН Админ", "МД IRC 2026 15 м", "МД IRC 2026 30 м"]

ТЕКСТ = """
ВЫБРАТЬ
	К.Ссылка.Наименование КАК СС,
	К.Ссылка.Подразделение.Наименование КАК Подр,
	К.НомерСтроки КАК N,
	К.Этап.Наименование КАК Этап,
	К.ОбщееНазвание.Наименование КАК ОН_Строки,
	К.НоменклатураСС КАК ТекстСС,
	К.Номенклатура.Наименование КАК Карточка,
	К.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ОН_Карточки,
	К.Количество КАК Кол,
	К.Сумма КАК Сумма
ИЗ
	Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	НЕ К.Ссылка.ЭтоГруппа
	И К.Ссылка.Активная
	И НЕ К.Ссылка.ПометкаУдаления
	И К.Номенклатура <> ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
	И К.ОбщееНазвание <> ЗНАЧЕНИЕ(Справочник.А_ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И К.Номенклатура.А_ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.А_ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И СокрЛП(К.ОбщееНазвание.Наименование) <> СокрЛП(К.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование)
УПОРЯДОЧИТЬ ПО
	СС, N
"""


def лат(s):
    return s.replace("С", "C").replace("с", "c")


def md(v):
    return str(v if v is not None else "").replace("|", r"\|").strip()


def приоритетная(имя):
    и = лат(имя)
    return any(и.startswith(лат(p)) for p in ПРИОРИТЕТ)


def main():
    b = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
    z = b.NewObject("Запрос")
    z.Текст = ТЕКСТ
    t = z.Выполнить().Выгрузить()

    строки = [t[i] for i in range(t.Количество())]
    по_сс = {}
    for r in строки:
        по_сс[r.СС] = по_сс.get(r.СС, 0) + 1

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# А_ПланФактныйПроизводствоПолный — расхождения загальної назви: строка СС ≠ карточка номенклатуры\n\n")
        f.write(f"Снято {datetime.date.today():%d.%m.%Y}, база BaseERP, активные СС. Всего строк: {len(строки)}.\n\n")
        f.write("План берёт назву из строки спецификации, факт закупок — из карточки номенклатуры.\n"
                "По этим строкам план и факт попадут под разные «Загальна назва» и не будут неттоваться\n"
                "в «План на факт». Чтобы сошлись, выровняйте назву в строке СС или в карточке.\n\n")
        f.write("| СС | строк | рабочая СС |\n|---|---:|---|\n")
        for k in sorted(по_сс, key=lambda x: (not приоритетная(x), x)):
            f.write(f"| {md(k)} | {по_сс[k]} | {'да' if приоритетная(k) else ''} |\n")
        f.write("\n| СС | N | Етап | Назва строки СС | НоменклатураСС | Карточка | Назва карточки | Кол | Сума |\n")
        f.write("|---|---:|---|---|---|---|---|---:|---:|\n")
        for r in sorted(строки, key=lambda x: (not приоритетная(x.СС), x.СС, x.N)):
            f.write(f"| {md(r.СС)} | {r.N} | {md(r.Этап)} | {md(r.ОН_Строки)} | {md(r.ТекстСС)} | "
                    f"{md(r.Карточка)} | {md(r.ОН_Карточки)} | {r.Кол} | {r.Сумма} |\n")

    print(f"OK: {len(строки)} строк → {OUT}")
    for k in sorted(по_сс, key=lambda x: (not приоритетная(x), x)):
        print(f"  {'*' if приоритетная(k) else ' '} {k}: {по_сс[k]}")


if __name__ == "__main__":
    main()
