# -*- coding: utf-8 -*-
"""Smoke: перепроведение А_ФинРез_Баланс янв2026/ТОВ после правки Аналитика1/2/3
в Свод_РасчетыСПартнерами. Гейты: Σ КО регистратора НЕ изменилась (sum-invariant),
Аналитика1 расчётных строк = виды контрагентов, идемпотентность."""
import sys
import win32com.client
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

орг = erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273")

# --- найти документ янв2026/ТОВ ---
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ Д.Ссылка КАК Ссылка, Д.Номер КАК Номер, Д.Проведен КАК Проведен
ИЗ Документ.А_ФинРез_Баланс КАК Д
ГДЕ Д.Организация = &Орг
    И Д.Месяц МЕЖДУ ДАТАВРЕМЯ(2026,1,1) И ДАТАВРЕМЯ(2026,1,31,23,59,59)
    И НЕ Д.ПометкаУдаления
"""
q.SetParameter("Орг", орг)
r = q.Execute().Выгрузить()
assert r.Количество() == 1, f"документов янв2026/ТОВ: {r.Количество()} (ожид 1)"
док = r.Получить(0).Ссылка
print(f"Документ: №{S(r.Получить(0).Номер)}, проведён={r.Получить(0).Проведен}")

def snapshot():
    qs = erp.NewObject("Запрос")
    qs.Text = """
    ВЫБРАТЬ
        КОЛИЧЕСТВО(*) КАК Строк,
        СУММА(Т.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
    ГДЕ Т.Регистратор = &Док
    """
    qs.SetParameter("Док", док)
    row = qs.Execute().Выгрузить().Получить(0)
    return int(row.Строк), round(float(row.КО or 0), 2)

def analitika_raschet():
    qa = erp.NewObject("Запрос")
    qa.Text = """
    ВЫБРАТЬ Т.Аналитика1 КАК А1, КОЛИЧЕСТВО(*) КАК Кол, СУММА(Т.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Т
    ГДЕ Т.Регистратор = &Док
        И Т.Source В (ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
            ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
    СГРУППИРОВАТЬ ПО Т.Аналитика1
    УПОРЯДОЧИТЬ ПО Кол УБЫВ
    """
    qa.SetParameter("Док", док)
    t = qa.Execute().Выгрузить()
    out = {}
    for i in range(t.Количество()):
        row = t.Получить(i)
        out[S(row.А1) or "(пусто)"] = (int(row.Кол), round(float(row.КО or 0), 2))
    return out

до = snapshot()
print(f"ДО:    строк={до[0]}, Σ КО={до[1]:,.2f}")
print(f"ДО Аналитика1 (расчёты): {analitika_raschet()}")

# --- перепроведение #1 ---
обј = док.ПолучитьОбъект()
обј.Записать(erp.РежимЗаписиДокумента.Проведение)
п1 = snapshot()
а1 = analitika_raschet()
print(f"\nПОСЛЕ: строк={п1[0]}, Σ КО={п1[1]:,.2f}")
print(f"ПОСЛЕ Аналитика1 (расчёты): {а1}")

# --- перепроведение #2 (идемпотентность) ---
обј2 = док.ПолучитьОбъект()
обј2.Записать(erp.РежимЗаписиДокумента.Проведение)
п2 = snapshot()
а2 = analitika_raschet()

fail = []
if abs(п1[1] - до[1]) > 0.01:
    fail.append(f"Σ КО изменилась: {до[1]:,.2f} -> {п1[1]:,.2f}")
if п2 != п1 or а2 != а1:
    fail.append("НЕ идемпотентно (второе проведение изменило данные)")
ожидаемые = {"Внешние", "Внутренние подразделения", "Внутригрупповые", "Собственники", "Кредиторы"}
if not (set(а1) - {"(пусто)"}) & ожидаемые:
    fail.append(f"Аналитика1 не содержит видов контрагентов: {list(а1)}")

print("\n" + "=" * 60)
if fail:
    for f in fail:
        print("FAIL:", f)
    sys.exit(1)
print("PASS: Σ КО инвариантна, Аналитика1=виды контрагентов, идемпотентно")
