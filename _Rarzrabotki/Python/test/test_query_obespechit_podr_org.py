# Тест запиту для функції ОбеспечитьПодразделенияОрганизацийПоПодразделению.
# Перевіряє синтаксис запиту через Python COM до ERP.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Знайти будь-який Подразделение для тесту
qPodr = erp.NewObject("Запрос")
qPodr.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Р, Наименование, Родитель "
    "ИЗ Справочник.СтруктураПредприятия "
    "ГДЕ НЕ ПометкаУдаления"
)
rPodr = qPodr.Execute().Выгрузить()
if rPodr.Количество() == 0:
    print("Немає підрозділів")
    sys.exit(1)
podr = rPodr.Получить(0).Р
print(f"Тестовий підрозділ: {S(podr)}")

# Знайти управлінську організацію
orgRef = None
qOrg = erp.NewObject("Запрос")
qOrg.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Р "
    "ИЗ Справочник.Организации "
    "ГДЕ Наименование ПОДОБНО \"%ІНДАСТРІАЛБУД%\""
)
rOrg = qOrg.Execute().Выгрузить()
if rOrg.Количество() > 0:
    orgRef = rOrg.Получить(0).Р
    print(f"Тестова організація: {S(orgRef)}")

# === Тест 1: ВАРІАНТ 1 — алиас "ПО" (поточний — має фейлити) ===
print()
print("=" * 70)
print("Тест 1: алиас 'ПО' (зарезервоване слово)")
print("=" * 70)
q1 = erp.NewObject("Запрос")
q1.Text = """
ВЫБРАТЬ
    Подр.Родитель      КАК РодительПодразделения,
    Подр.Наименование  КАК НаименованиеПодразделения,
    ЕСТЬNULL(ПО.Ссылка, ЗНАЧЕНИЕ(Справочник.ПодразделенияОрганизаций.ПустаяСсылка))   КАК СуществующаяСсылка,
    ЕСТЬNULL(ПО.Родитель, ЗНАЧЕНИЕ(Справочник.ПодразделенияОрганизаций.ПустаяСсылка)) КАК СуществующийРодитель,
    ЕСТЬNULL(ПО.Наименование, "")    КАК СуществующееНаименование
ИЗ
    Справочник.СтруктураПредприятия КАК Подр
        ЛЕВОЕ СОЕДИНЕНИЕ Справочник.ПодразделенияОрганизаций КАК ПО
        ПО ПО.А_Подразделение = Подр.Ссылка
            И ПО.Владелец = &Владелец
ГДЕ
    Подр.Ссылка = &Подразделение
"""
q1.SetParameter("Подразделение", podr)
q1.SetParameter("Владелец", orgRef if orgRef else erp.Справочники.Организации.ПустаяСсылка())
try:
    r = q1.Execute().Выгрузить()
    print(f"  [OK] Працює, рядків={r.Количество()}")
except Exception as e:
    msg = str(e)
    if hasattr(e, 'excepinfo') and e.excepinfo:
        msg = e.excepinfo[2][:200]
    print(f"  [FAIL] {msg}")

