import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
kazna = v8.Connect('Srvr="SQLSERVER";Ref="BuhKazn";Usr="cfo";Pwd="2442"')
S = kazna.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


# --- Метадані в Казні: чи є Справочник.Налоги? чи є реквізит А_Налог у СтатьиДвиженияДенежныхСредств?
print("=" * 70)
print("КРОК 0: метадані Казни")
print("=" * 70)

try:
    mo_налоги = kazna.Метаданные.Справочники.Найти("Налоги")
    print(f"  Справочник.Налоги існує: {mo_налоги is not None}")
except Exception as e:
    print(f"  ERR: {e}")

try:
    mo_ддс = kazna.Метаданные.Справочники.Найти("СтатьиДвиженияДенежныхСредств")
    if mo_ддс:
        print(f"  Справочник.СтатьиДвиженияДенежныхСредств: OK")
        cnt = mo_ддс.Реквизиты.Количество()
        налог_поле = None
        for i in range(cnt):
            attr = mo_ддс.Реквизиты.Получить(i)
            nm = S(attr.Имя)
            if "Налог" in nm:
                tp = S(attr.Тип)
                print(f"    {nm}: {tp[:80]}")
                if nm == "А_Налог":
                    налог_поле = attr
        if not налог_поле:
            print("  УВАГА: реквізит А_Налог НЕ ЗНАЙДЕНО у СтатьиДвиженияДенежныхСредств")
    else:
        print("  НЕТ СтатьиДвиженияДенежныхСредств")
except Exception as e:
    print(f"  ERR: {e}")


