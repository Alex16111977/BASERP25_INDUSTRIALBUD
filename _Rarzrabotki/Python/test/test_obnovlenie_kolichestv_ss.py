# -*- coding: utf-8 -*-
"""Приёмка команды «Оновити кількість за одиницею заг. назви» обработки «Загрузка материалов в СС».

Фазы:
  1. Распознавание колонок по реальной шапке файла: ожидаем N=1, Номенклатура=4,
     Одиниця заг.назва=6, Кількість згідно=8, Сума=9.
  2. Обновление тест-элемента «__ТЕСТ Загрузка материалов СС» (в нём та же выгрузка ООН,
     228 строк, номера строк совпадают): 21 обновлено, 3 пропущено, Σ Сумма неизменна,
     единицы и цены проверяются построчно, строки-дубли 210/217 не тронуты.
  3. Повтор — идемпотентность (значения те же, Σ Сумма та же).
  4. Негативные случаи: номера нет в спецификации, чужое наименование, чужая сумма.

Реальную «МД ООН 2026» тест НЕ трогает — её обновляет пользователь кнопкой.
"""
import sys
import win32com.client
from openpyxl import load_workbook

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\Загрузка материалов в СС.epf"
XLSX = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\12082026"
        r"\Копия Список змінити одиниці виміру Б1.xlsx")
# Фикстуру тест готовит сам: тот же файл ООН, из которого сделана выгрузка на обновление,
# иначе номера строк не совпадут (тест-элемент могли перезаписать другие тесты).
XLSX_ИСХОДНЫЙ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\09082026"
                 r"\14.07.2026 РАБОЧИЙ  ООН_Б1_НОВИЙ_ШАблон_СС_Виробництво_15_06_2026_ (002).xlsx")
ЛИСТ = "TDSheet"
ЛИСТ_ИСХОДНЫЙ = "Проект СС"
СС_ТЕСТ = "__ТЕСТ Загрузка материалов СС"

провалов = 0


def проверить(условие, текст):
    global провалов
    if not условие:
        провалов += 1
    print(f"  {'OK  ' if условие else 'FAIL'} {текст}")


buh = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
обр = buh.ВнешниеОбработки.Создать(EPF, False)


def запрос(текст, **параметры):
    z = buh.NewObject("Запрос")
    z.Text = текст
    for имя, значение in параметры.items():
        z.SetParameter(имя, значение)
    return z.Execute().Выгрузить()


def число_ячейки(значение):
    """Вторая таблица листа «Проект СС» подсовывает в числовые колонки текст — движок
    отбора это разбирает сам, тесту достаточно не падать."""
    try:
        return float(значение) if значение is not None else 0.0
    except (TypeError, ValueError):
        return 0.0


def найти_сс(наименование):
    т = запрос("ВЫБРАТЬ ПЕРВЫЕ 1 СС.Ссылка КАК Ссылка ИЗ Справочник.СтруктураСебестоимости КАК СС "
               "ГДЕ СС.Наименование = &Н", Н=наименование)
    return т.Получить(0).Ссылка if т.Количество() else None


def строки_тч(ссылка):
    т = запрос("""ВЫБРАТЬ К.НомерСтроки КАК Н, К.НоменклатураСС КАК Наим, К.ЕдиницаСС КАК ЕдСС,
        К.Единица.Наименование КАК ЕдСсылка, К.Количество КАК Кол, К.Сумма КАК Сум,
        К.Цена КАК Цена, К.НеСовпадает КАК НеСовпадает
        ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
        ГДЕ К.Ссылка = &Р УПОРЯДОЧИТЬ ПО Н""", Р=ссылка)
    d = {}
    for i in range(т.Количество()):
        r = т.Получить(i)
        d[int(r.Н)] = dict(наим=str(r.Наим), едсс=str(r.ЕдСС or ""), едссыл=str(r.ЕдСсылка or ""),
                           кол=float(r.Кол), сум=float(r.Сум), цена=float(r.Цена),
                           несовп=bool(r.НеСовпадает))
    return d


def строки_файла():
    ws = load_workbook(XLSX, data_only=True)[ЛИСТ]
    строки = []
    for ряд in range(2, ws.max_row + 1):
        наим = str(ws.cell(ряд, 4).value or "").strip()
        if not наим:
            continue
        строки.append(dict(ряд=ряд, n=ws.cell(ряд, 1).value, наим=наим,
                           ед=str(ws.cell(ряд, 6).value or "").strip(),
                           новкол=ws.cell(ряд, 8).value, сум=ws.cell(ряд, 9).value))
    return строки


def массив_1с(строки):
    массив = buh.NewObject("Массив")
    for с in строки:
        стр = buh.NewObject("Структура")
        стр.Вставить("Ряд", с["ряд"])
        стр.Вставить("НомерСтроки", с["n"] or 0)
        стр.Вставить("НоменклатураСС", с["наим"])
        стр.Вставить("ЕдиницаЗагНазвы", с["ед"])
        стр.Вставить("Количество", float(с["новкол"]) if с["новкол"] not in (None, "") else 0)
        стр.Вставить("Сумма", float(с["сум"]) if с["сум"] not in (None, "") else 0)
        массив.Добавить(стр)
    return массив


def печать_протокола(п, детали=False):
    for имя in ("Обновлено", "ПропущеноПустых", "НеНайдено", "НеСовпалоНаименование",
                "НеСовпалаСумма", "ОкруглениеКоличества", "СуммаДо", "СуммаПосле", "Ошибка"):
        print(f"    {имя} = {getattr(п, имя)}")
    if п.Ошибка:
        print(f"    ТекстОшибки = {п.ТекстОшибки}")
    for имя in ("Контроль", "Предупреждения") + (("Детали",) if детали else ()):
        м = getattr(п, имя)
        for i in range(м.Количество()):
            print(f"    [{имя}] {м.Получить(i)}")


# ===================== ФАЗА 1: распознавание колонок =====================
print("=== ФАЗА 1: распознавание колонок по шапке файла ===")
ws = load_workbook(XLSX, data_only=True)[ЛИСТ]
шапка = buh.NewObject("Массив")
заголовки = []
for c in range(1, ws.max_column + 1):
    текст = str(ws.cell(1, c).value or "").strip()
    заголовки.append(текст)
    шапка.Добавить(текст)
print(f"  шапка: {заголовки}")

номера = обр.НомераКолонокПоШапке(шапка)
ожидание = {"НомерСтроки": 1, "НоменклатураСС": 4, "ЕдиницаЗагНазвы": 6, "КолонкаКоличества": 8, "Сумма": 9}
for поле, ждём in ожидание.items():
    факт = int(getattr(номера, поле))
    проверить(факт == ждём, f"{поле}: колонка {факт}, ждём {ждём}")

# устойчивость к переименованию и перестановке
переставленная = buh.NewObject("Массив")
for текст in ["Сума", "Кільк. в од. заг. назви", "Номенклатура СС", "N", "Одиниця заг. назва"]:
    переставленная.Добавить(текст)
н2 = обр.НомераКолонокПоШапке(переставленная)
проверить(int(н2.КолонкаКоличества) == 2, f"переименованная колонка количества найдена: {н2.КолонкаКоличества} (ждём 2)")
проверить(int(н2.Сумма) == 1 and int(н2.НоменклатураСС) == 3 and int(н2.НомерСтроки) == 4
          and int(н2.ЕдиницаЗагНазвы) == 5, "перестановка колонок распознана верно")

# ===================== ФАЗА 2: обновление тест-элемента =====================
print("\n=== ФАЗА 2: обновление тест-элемента ===")
ссылка_тест = найти_сс(СС_ТЕСТ)
проверить(ссылка_тест is not None, f"тест-элемент «{СС_ТЕСТ}» найден")

# Фикстура: заливаем в тест-элемент исходную выгрузку ООН — файл обновления сделан из неё,
# и номера строк в нём привязаны именно к этому составу ТЧ.
ws_исх = load_workbook(XLSX_ИСХОДНЫЙ, data_only=True)[ЛИСТ_ИСХОДНЫЙ]
сырые = buh.NewObject("Массив")
for ряд in range(2, ws_исх.max_row + 1):
    с = buh.NewObject("Структура")
    с.Вставить("Ряд", ряд)
    с.Вставить("Тип", str(ws_исх.cell(ряд, 3).value or "").strip())
    с.Вставить("Этап", str(ws_исх.cell(ряд, 5).value or "").strip())
    с.Вставить("Наименование", str(ws_исх.cell(ряд, 7).value or "").strip())
    с.Вставить("ОбщееНазвание", str(ws_исх.cell(ряд, 8).value or "").strip())
    с.Вставить("Единица", str(ws_исх.cell(ряд, 9).value or "").strip())
    с.Вставить("Количество", число_ячейки(ws_исх.cell(ряд, 10).value))
    с.Вставить("Сумма", число_ячейки(ws_исх.cell(ряд, 15).value))
    сырые.Добавить(с)
подготовка = обр.ЗагрузитьМатериалыИзСырыхСтрок(ссылка_тест, сырые)
проверить(not подготовка.Ошибка, f"фикстура залита: загружено {подготовка.Загружено}")

до = строки_тч(ссылка_тест)
проверить(len(до) == 228, f"в тест-элементе {len(до)} строк (ждём 228 — та же выгрузка ООН)")

файл = строки_файла()
с_количеством = [с for с in файл if с["новкол"] not in (None, "")]
без_количества = [с for с in файл if с["новкол"] in (None, "")]
print(f"  строк в файле: {len(файл)}, с пересчитанным количеством: {len(с_количеством)}, "
      f"без количества: {len(без_количества)}")

протокол = обр.ОбновитьКоличестваИзМассива(ссылка_тест, массив_1с(файл))
печать_протокола(протокол)

проверить(not протокол.Ошибка, "обновление без ошибки")
проверить(int(протокол.Обновлено) == len(с_количеством),
          f"обновлено {протокол.Обновлено} = строк с количеством {len(с_количеством)}")
проверить(int(протокол.ПропущеноПустых) == len(без_количества),
          f"пропущено без количества {протокол.ПропущеноПустых} = {len(без_количества)}")
проверить(int(протокол.НеНайдено) == 0, f"не найдено по номеру {протокол.НеНайдено} (ждём 0)")
проверить(int(протокол.НеСовпалоНаименование) == 0,
          f"наименование не совпало {протокол.НеСовпалоНаименование} (ждём 0)")
проверить(int(протокол.НеСовпалаСумма) == 0, f"сумма не совпала {протокол.НеСовпалаСумма} (ждём 0)")
проверить(abs(float(протокол.СуммаДо) - float(протокол.СуммаПосле)) < 0.005,
          f"Σ Сумма не изменилась: {протокол.СуммаДо} → {протокол.СуммаПосле}")

после = строки_тч(ссылка_тест)
проверить(len(после) == len(до), f"строк в ТЧ не изменилось: {len(после)}")

# построчно: обновлённые
расхождений = 0
for с in с_количеством:
    н = int(с["n"])
    было, стало = до[н], после[н]
    ожид_кол = round(float(с["новкол"]), 3)
    ожид_цена = round(стало["сум"] / ожид_кол, 2) if ожид_кол else 0
    if (abs(стало["кол"] - ожид_кол) > 0.0005 or стало["едсс"].strip() != с["ед"].strip()
            or abs(стало["сум"] - было["сум"]) > 0.005 or abs(стало["цена"] - ожид_цена) > 0.011):
        расхождений += 1
        print(f"    строка {н}: кол {стало['кол']} (ждём {ожид_кол}), ед «{стало['едсс']}» "
              f"(ждём «{с['ед']}»), цена {стало['цена']} (ждём {ожид_цена}), сумма {стало['сум']} "
              f"(было {было['сум']})")
проверить(расхождений == 0, f"построчная сверка обновлённых: расхождений {расхождений}")

# флаг «Не совпадает» снят у обновлённых
осталось_несовп = [int(с["n"]) for с in с_количеством if после[int(с["n"])]["несовп"]]
проверить(not осталось_несовп, f"флаг «Не совпадает» снят у обновлённых (осталось: {осталось_несовп})")

# строки без количества не тронуты
нетронуты = all(до[int(с["n"])] == после[int(с["n"])] for с in без_количества)
проверить(нетронуты, "строки с пустым количеством не изменены")

# строки-дубли по наименованию (210, 217) не тронуты — ключ по номеру, а не по имени
for дубль in (210, 217):
    проверить(до[дубль] == после[дубль],
              f"строка-дубль {дубль} «{до[дубль]['наим'][:30]}» не изменена")

# ===================== ФАЗА 3: идемпотентность =====================
print("\n=== ФАЗА 3: повторный прогон ===")
протокол2 = обр.ОбновитьКоличестваИзМассива(ссылка_тест, массив_1с(файл))
проверить(not протокол2.Ошибка, "повтор без ошибки")
проверить(int(протокол2.Обновлено) == len(с_количеством),
          f"повтор: обновлено {протокол2.Обновлено}")
после2 = строки_тч(ссылка_тест)
одинаково = all(после[н] == после2[н] for н in после)
проверить(одинаково, "повтор ничего не изменил в данных")

# ===================== ФАЗА 4: негативные случаи =====================
print("\n=== ФАЗА 4: защита от кривого файла ===")
плохие = buh.NewObject("Массив")


def плохая_строка(ряд, номер, наим, ед, кол, сум):
    с = buh.NewObject("Структура")
    с.Вставить("Ряд", ряд)
    с.Вставить("НомерСтроки", номер)
    с.Вставить("НоменклатураСС", наим)
    с.Вставить("ЕдиницаЗагНазвы", ед)
    с.Вставить("Количество", кол)
    с.Вставить("Сумма", сум)
    return с


эталон = после[2]
плохие.Добавить(плохая_строка(2, 9999, эталон["наим"], "шт", 5, эталон["сум"]))          # номера нет
плохие.Добавить(плохая_строка(3, 2, "Чужое наименование", "шт", 5, эталон["сум"]))        # чужое имя
плохие.Добавить(плохая_строка(4, 2, эталон["наим"], "шт", 5, эталон["сум"] + 100))        # чужая сумма
плохие.Добавить(плохая_строка(5, 2, эталон["наим"], "шт", 0, эталон["сум"]))              # нет количества

протокол3 = обр.ОбновитьКоличестваИзМассива(ссылка_тест, плохие)
печать_протокола(протокол3, детали=True)
проверить(not протокол3.Ошибка, "кривой файл не роняет обработку")
проверить(int(протокол3.Обновлено) == 0, f"ничего не обновлено: {протокол3.Обновлено}")
проверить(int(протокол3.НеНайдено) == 1, f"не найдено по номеру: {протокол3.НеНайдено} (ждём 1)")
проверить(int(протокол3.НеСовпалоНаименование) == 1,
          f"наименование не совпало: {протокол3.НеСовпалоНаименование} (ждём 1)")
проверить(int(протокол3.НеСовпалаСумма) == 1, f"сумма не совпала: {протокол3.НеСовпалаСумма} (ждём 1)")
проверить(int(протокол3.ПропущеноПустых) == 1, f"пропущено без количества: {протокол3.ПропущеноПустых} (ждём 1)")
после3 = строки_тч(ссылка_тест)
проверить(все_равны := all(после2[н] == после3[н] for н in после2), "данные после кривого файла не изменились")

print(f"\n{'=' * 60}\nПРОВАЛОВ: {провалов}")
sys.exit(1 if провалов else 0)
