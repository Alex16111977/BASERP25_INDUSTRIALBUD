# -*- coding: utf-8 -*-
# Диагностика: почему у статьи «Денежные средства в пути» нет Аналитики.
# Phase 1 (systematic-debugging) — СБОР ДОКАЗАТЕЛЬСТВ, без правок.
# Имена резолвим в Python по карте XMLСтрока→Наим (ПРЕДСТАВЛЕНИЕ в
# агрегированном запросе ломается — известная грабля проекта).
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С

qg = conn.NewObject("Запрос")
qg.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qg.УстановитьПараметр("М", datetime(2026, 1, 1, 12, 0, 0))
rg = qg.Выполнить().Выбрать(); rg.Следующий()
НМ, КД = rg.НМ, rg.КД

# карты имён
qm = conn.NewObject("Запрос")
qm.Текст = ("ВЫБРАТЬ Ссылка КАК С, Наименование КАК Н ИЗ "
            "ПланВидовХарактеристик.СтатьиАктивовПассивов")
tm = qm.Выполнить().Выгрузить()
имСт = {conn.XMLСтрока(tm.Получить(i).С): str(tm.Получить(i).Н).strip()
        for i in range(tm.Количество())}
qsr = conn.NewObject("Запрос")
qsr.Текст = ("ВЫБРАТЬ Ссылка КАК С, ПРЕДСТАВЛЕНИЕ(Ссылка) КАК П ИЗ "
             "Перечисление.ИсточникиУправленческогоБаланса")
tsr = qsr.Выполнить().Выгрузить()
имИст = {conn.XMLСтрока(tsr.Получить(i).С): str(tsr.Получить(i).П).strip()
         for i in range(tsr.Количество())}

q = conn.NewObject("Запрос")
q.УстановитьПараметр("НМ", НМ); q.УстановитьПараметр("КД", КД)
q.Текст = """ВЫБРАТЬ
    Р.Статья КАК Ст, Р.Source КАК Ист, Р.Расхождение КАК Расх,
    КОЛИЧЕСТВО(*) КАК Н,
    СУММА(Р.СуммаКонечныйОстаток) КАК КО,
    СУММА(ВЫБОР КОГДА Р.Аналитика1 <> "" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК А1,
    СУММА(ВЫБОР КОГДА Р.Аналитика2 <> "" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК А2,
    СУММА(ВЫБОР КОГДА Р.Аналитика3 <> "" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК А3
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Р
ГДЕ Р.Регистратор В (ВЫБРАТЬ ФР.Ссылка ИЗ Документ.А_ФинРез_Баланс КАК ФР
        ГДЕ ФР.Проведен И НЕ ФР.ПометкаУдаления
            И ФР.Месяц >= &НМ И ФР.Месяц <= &КД)
    И Р.Статья.Наименование ПОДОБНО "Денежные средства%"
СГРУППИРОВАТЬ ПО Р.Статья, Р.Source, Р.Расхождение"""
t = q.Выполнить().Выгрузить()
rows = []
for i in range(t.Количество()):
    r = t.Получить(i)
    rows.append((имСт.get(conn.XMLСтрока(r.Ст), "?"),
                 имИст.get(conn.XMLСтрока(r.Ист), "(пусто)")
                 if conn.ЗначениеЗаполнено(r.Ист) else "(Source пусто)",
                 bool(r.Расх), int(r.Н), int(r.А1), int(r.А2), int(r.А3),
                 float(r.КО or 0)))
rows.sort(key=lambda x: (x[0], x[1], x[2]))
print("янв2026/ТОВ — РегистрСведений.А_ОтчетБаланс_Свод, ден.статьи:")
print(f"{'Статья':<40}{'Source':<32}{'тип':<5}{'Н':>5}{'А1':>5}{'А2':>5}"
      f"{'А3':>5}{'ΣКО':>17}")
for st, ист, расх, н, a1, a2, a3, ко in rows:
    print(f"{st:<40}{ист:<32}{('ПЛУГ' if расх else 'дет'):<5}{н:>5}"
          f"{a1:>5}{a2:>5}{a3:>5}{ко:>17,.2f}")

qp = conn.NewObject("Запрос")
qp.УстановитьПараметр("Орг", ORG); qp.УстановитьПараметр("КД", КД)
qp.Текст = """ВЫБРАТЬ Т.Источник КАК Ист, Т.Статья КАК Ст,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассывы КАК Т
ГДЕ Т.Организация=&Орг И Т.Период<=&КД
    И Т.Статья.Наименование ПОДОБНО "Денежные средства%"
СГРУППИРОВАТЬ ПО Т.Источник, Т.Статья""".replace(
    "ПрочиеАктивыПассывы", "ПрочиеАктивыПассивы")
tp = qp.Выполнить().Выгрузить()
print("\nПАП (ОСН.таблица, signed, на конец янв2026) — ден.статьи:")
for i in range(tp.Количество()):
    r = tp.Получить(i)
    ист = (имИст.get(conn.XMLСтрока(r.Ист), "?")
           if conn.ЗначениеЗаполнено(r.Ист) else "(Источник пусто)")
    print(f"  Источник={ист:<32} Статья={имСт.get(conn.XMLСтрока(r.Ст),'?'):<40}"
          f" КО={float(r.КО or 0):>16,.2f}")

print("\n[i] Свод_ДенежныеСредства: 3 детальные ветки втДС "
      "(Безналичные→БанкСчет, Наличные→Касса, Подотчетные→ФизЛицо). "
      "Ветки для РегистрНакопления.ДенежныеСредстваВПути НЕТ.")
