def прогнать(имя, текст, параметры):
    q = buh.NewObject("Запрос")
    q.Текст = текст
    for к, з in параметры.items():
        q.УстановитьПараметр(к, з)
    try:
        т = q.Execute().Выгрузить()
        print(f"  OK  {имя:22} рядків={т.Количество()}, колонок={т.Колонки.Количество()}")
        return т
    except Exception as e:
        инфо = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
        print(f"  FAIL {имя:22} {инфо}")
        return None


