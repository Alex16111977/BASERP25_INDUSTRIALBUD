    prm.ВключатьБизнесЛогику = False
    рез = erp.ОбщегоНазначения.ЗаменитьСсылки(соотв, prm)
    print("\n--- результат ЗаменитьСсылки (таблица ошибок) ---")
    print("колонки:", [col.Имя for col in рез.Колонки])
    print("строк ошибок:", рез.Количество())
    for i in range(рез.Количество()):
        r = рез.Получить(i)
        try: print("  ошибка:", r.Ссылка, "|", r.ТекстОшибки if hasattr(r,'ТекстОшибки') else "?")
        except Exception as e: print("  (чтение строки ошибки:", e, ")")
    # перечитать ключ
    keyo = key.ПолучитьОбъект()
    print("\nпосле: ПометкаУдаления ключа =", keyo.ПометкаУдаления, "| Партнер =", keyo.Партнер.Наименование)
    arr2 = erp.NewObject("Массив"); arr2.Добавить(key)
    res2 = erp.НайтиПоСсылкам(arr2)
    agg2 = {}
    for i in range(res2.Количество()):
        try: fn = res2.Получить(i).Метаданные.ПолноеИмя()
        except Exception: fn = "?"
        agg2[fn] = agg2.get(fn, 0) + 1
    print("ссылок на ключ ПОСЛЕ:", res2.Количество(), agg2)
