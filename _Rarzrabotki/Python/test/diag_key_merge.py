print("\nканонический ключ:", c.uid(erp, canon) if canon else None)

if canon is not None:
    соотв = erp.NewObject("Соответствие"); соотв.Вставить(key, canon)
    prm = erp.ОбщегоНазначения.ПараметрыЗаменыСсылок()
