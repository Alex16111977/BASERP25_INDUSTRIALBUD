# Диагностика: почему слитый ключ не помечается; что его держит; ошибки ЗаменитьСсылки
import sys
sys.path.insert(0, r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test')
import _common_neizv as c

erp = c.connect()
P = c.neizv(erp)
K = erp.Справочники.Контрагенты.НайтиПоНаименованию("ФОП Чміль І.М", True)
target = erp.Справочники.Партнеры.НайтиПоНаименованию("ФОП Чміль І.М", True)
print("target:", target.Наименование, c.uid(erp, target))

# один непомеченный ключ Чміля с Неизв
q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.КлючиАналитикиУчетаПоПартнерам "
          "ГДЕ Контрагент=&К И Партнер=&P И НЕ ПометкаУдаления")
q.УстановитьПараметр("К", K.Ссылка); q.УстановитьПараметр("P", P)
s = q.Execute().Выбрать()
if not s.Следующий():
    print("нет непомеченных ключей Чміля — всё уже слито/помечено")
    sys.exit(0)
key = s.Ссылка
print("ключ:", c.uid(erp, key), "| Договор:", key.Договор, "| Направление:", key.НаправлениеДеятельности)

# что ссылается на этот ключ
print("\n--- НайтиПоСсылкам на ключ ---")
arr = erp.NewObject("Массив"); arr.Добавить(key)
res = erp.НайтиПоСсылкам(arr)
agg = {}
for i in range(res.Количество()):
    try: fn = res.Получить(i).Метаданные.ПолноеИмя()
    except Exception: fn = "?"
    agg[fn] = agg.get(fn, 0) + 1
print("всего:", res.Количество(), agg)

# канонический (target, те же измерения)
qc = erp.NewObject("Запрос")
qc.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.КлючиАналитикиУчетаПоПартнерам ГДЕ Партнер=&T "
           "И Организация=&О И Контрагент=&К И Договор=&Д И НаправлениеДеятельности=&Н И Ссылка<>&С")
qc.УстановитьПараметр("T", target); qc.УстановитьПараметр("О", key.Организация)
qc.УстановитьПараметр("К", key.Контрагент); qc.УстановитьПараметр("Д", key.Договор)
qc.УстановитьПараметр("Н", key.НаправлениеДеятельности); qc.УстановитьПараметр("С", key.Ссылка)
sc = qc.Execute().Выбрать()
