# -*- coding: utf-8 -*-
"""Точечная чистка СИРОТ-движений от verify-прогонки (документы уже удалены).
Пишет ПУСТОЙ набор записей ровно по найденным мёртвым регистраторам — стирает только их движения.
Строгие фильтры: КР со статьёй Налоги (КР — не штатный регистратор Налогов); ОБ с маркером-Содержанием.
Боевые движения (ОЗФУ/СписаниеБезнал/ПередачаНачислений и пр.) не затрагиваются."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# --- КР: осиротевшие движения ПАП со статьёй Налоги ---
q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ РАЗЛИЧНЫЕ П.Регистратор КАК Рег "
           "ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П "
           "ГДЕ П.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.Налоги) "
           "И П.Регистратор ССЫЛКА Документ.КорректировкаРегистров")
крРеги = [r.Рег for r in q.Выполнить().Выгрузить()]
print(f"КР-регистраторов со статьёй Налоги: {len(крРеги)}")
for рег in крРеги:
    нз = erp.РегистрыНакопления.ПрочиеАктивыПассивы.СоздатьНаборЗаписей()
    нз.Отбор.Регистратор.Установить(рег)
    нз.Записать()  # пустой набор замещает → удаляет движения этого регистратора
    print("  очищены ПАП-движения регистратора КР")

# --- ОБ: осиротевшие проводки Хозрасчетного с маркером ---
q2 = erp.NewObject("Запрос")
q2.Текст = ("ВЫБРАТЬ РАЗЛИЧНЫЕ Х.Регистратор КАК Рег "
            "ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х "
            "ГДЕ Х.Содержание = \"Ввод начального остатка по налогам\" "
            "И Х.Регистратор ССЫЛКА Документ.ОперацияБух")
обРеги = [r.Рег for r in q2.Выполнить().Выгрузить()]
print(f"ОБ-регистраторов с маркером: {len(обРеги)}")
for рег in обРеги:
    нб = erp.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
    нб.Отбор.Регистратор.Установить(рег)
    нб.Записать()
    print("  очищены проводки Хозрасчетного регистратора ОБ")

# --- контроль ---
qc = erp.NewObject("Запрос")
qc.Текст = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.ПрочиеАктивыПассивы "
            "ГДЕ Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.Налоги) "
            "И Регистратор ССЫЛКА Документ.КорректировкаРегистров")
qc2 = erp.NewObject("Запрос")
qc2.Текст = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрБухгалтерии.Хозрасчетный "
             "ГДЕ Содержание = \"Ввод начального остатка по налогам\"")
остКР = int(f(qc.Выполнить().Выгрузить()[0].Н))
остОБ = int(f(qc2.Выполнить().Выгрузить()[0].Н))
print(f"\nОстаток после чистки: КР(Налоги)={остКР}  ОБ(маркер)={остОБ}")
print("CLEAN" if остКР == 0 and остОБ == 0 else "ВНИМАНИЕ: остались движения!")
