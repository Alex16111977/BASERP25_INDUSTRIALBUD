# -*- coding: utf-8 -*-
"""Acceptance тест для процедуры ЗаполнитьИзСписанияБезнал.

Шаги:
  1) Из sbds_candidates.json берёт все СБДС за дек 2025 с ПАП(ОТ)
  2) Перепроводит каждый
  3) Per Регистратор:
     - Σ signed А_ВзСС == −Σ signed ПАП(ОТ)  (финансистская инверсия)
     - 100% строк имеют ФизЛицо ≠ Пустая
     - 0 дублей ключа (Орг, Подр, ФизЛицо, ВидДв)
  4) Per (Орг, Подр) per Регистратор: |А_ВзСС + ПАП| ≤ 1 руб
  5) Идемпотентность
"""
import sys, io, json, os
from collections import Counter
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С
РежПров = conn.PredefinedValue("РежимЗаписиДокумента.Проведение")
ПустоеФЛ_str = conn.XMLСтрока(conn.PredefinedValue(
    "Справочник.ФизическиеЛица.ПустаяСсылка"))

cand_path = os.path.join(os.path.dirname(__file__), "sbds_candidates.json")
with open(cand_path, "r", encoding="utf-8") as f:
    КАНДИДАТЫ = json.load(f)
print(f"Кандидатов: {len(КАНДИДАТЫ)}\n")


def получить_док(uuid_str):
    uuid_obj = conn.NewObject("УникальныйИдентификатор", uuid_str)
    ref = conn.Документы.СписаниеБезналичныхДенежныхСредств.ПолучитьСсылку(uuid_obj)
    return ref if ref.ПолучитьОбъект() is not None else None


def сумма_signed_a_vzs(док):
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ СУММА(ВЫБОР КОГДА Зап.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                                  ТОГДА Зап.СуммаВзаиморасчетов ИНАЧЕ -Зап.СуммаВзаиморасчетов КОНЕЦ) КАК С
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Зап
    ГДЕ Зап.Регистратор = &Док"""
    q.УстановитьПараметр("Док", док)
    r = q.Выполнить().Выбрать(); r.Следующий()
    return float(r.С or 0)


def сумма_signed_pap_ot(док):
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК С
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор=&Док И Т.Источник=
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ"""
    q.УстановитьПараметр("Док", док); q.УстановитьПараметр("ОТ", ОТ)
    r = q.Выполнить().Выбрать(); r.Следующий()
    return float(r.С or 0)


def сверка_per_подр(док):
    qV = conn.NewObject("Запрос")
    qV.Текст = """ВЫБРАТЬ Зап.Организация КАК Орг, Зап.Подразделение КАК Подр,
        СУММА(ВЫБОР КОГДА Зап.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Зап.СуммаВзаиморасчетов ИНАЧЕ -Зап.СуммаВзаиморасчетов КОНЕЦ) КАК С
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Зап
    ГДЕ Зап.Регистратор=&Док
    СГРУППИРОВАТЬ ПО Зап.Организация, Зап.Подразделение"""
    qV.УстановитьПараметр("Док", док)
    tV = qV.Выполнить().Выгрузить()
    vzs = {}
    for i in range(tV.Количество()):
        e = tV.Получить(i)
        vzs[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр))] = float(e.С or 0)

    qP = conn.NewObject("Запрос")
    qP.Текст = """ВЫБРАТЬ Т.Организация КАК Орг,
        ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК С
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор=&Док И Т.Источник=
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ
    СГРУППИРОВАТЬ ПО Т.Организация, ЕСТЬNULL(Т.Подразделение,
        ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))"""
    qP.УстановитьПараметр("Док", док); qP.УстановитьПараметр("ОТ", ОТ)
    tP = qP.Выполнить().Выгрузить()
    pap = {}
    for i in range(tP.Количество()):
        e = tP.Получить(i)
        pap[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр))] = float(e.С or 0)

    все = set(vzs.keys()) | set(pap.keys())
    расх = 0; max_d = 0
    for k in все:
        d = abs(vzs.get(k, 0) + pap.get(k, 0))  # инверсия знака
        if d > max_d: max_d = d
        if d > TOL_RUB: расх += 1
    return расх, max_d


def стат(док):
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ Зап.Организация КАК Орг, Зап.Подразделение КАК Подр,
        Зап.ФизическоеЛицо КАК ФЛ, Зап.ВидДвижения КАК ВД
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Зап
    ГДЕ Зап.Регистратор=&Док"""
    q.УстановитьПараметр("Док", док)
    t = q.Выполнить().Выгрузить()
    rows = t.Количество()
    с_фл = 0
    keys = Counter()
    for i in range(rows):
        e = t.Получить(i)
        ф = conn.XMLСтрока(e.ФЛ)
        if ф != ПустоеФЛ_str: с_фл += 1
        keys[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр), ф,
              conn.XMLСтрока(e.ВД))] += 1
    return rows, с_фл, {k: c for k, c in keys.items() if c > 1}


all_pass = True
данные = []
сводка = {"ok_per_reg": 0, "ok_per_podr": 0, "ok_fl": 0, "ok_dup": 0,
          "fail_per_reg": [], "fail_per_podr": [], "fail_fl": [], "fail_dup": []}
for k in КАНДИДАТЫ:
    док = получить_док(k["uuid"])
    if док is None:
        print(f"❌ № {k['номер']}: документ не найден")
        all_pass = False
        continue
    try:
        док.ПолучитьОбъект().Записать(РежПров)
    except Exception as ex:
        print(f"❌ № {k['номер']}: ошибка перепроведения: {ex}")
        all_pass = False
        continue

    взс = сумма_signed_a_vzs(док)
    пап = сумма_signed_pap_ot(док)
    d_reg = abs(взс + пап)
    расх, max_d = сверка_per_подр(док)
    rows, с_фл, дубли = стат(док)
    доля = (с_фл / rows * 100) if rows > 0 else 0

    s_r = d_reg <= TOL_RUB
    s_p = расх == 0
    s_f = доля >= 99
    s_d = not дубли

    if s_r: сводка["ok_per_reg"] += 1
    else:
        сводка["fail_per_reg"].append((k["номер"], взс, пап, d_reg))
        all_pass = False
    if s_p: сводка["ok_per_podr"] += 1
    else:
        сводка["fail_per_podr"].append((k["номер"], расх, max_d))
        all_pass = False
    if s_f: сводка["ok_fl"] += 1
    else:
        сводка["fail_fl"].append((k["номер"], с_фл, rows, доля))
        all_pass = False
    if s_d: сводка["ok_dup"] += 1
    else:
        сводка["fail_dup"].append((k["номер"], len(дубли)))
        all_pass = False

    данные.append((k["номер"], док, взс))

print(f"=== Итоги по {len(КАНДИДАТЫ)} документам ===")
print(f"  Σ per Регистратор |А_ВзСС+ПАП|≤{TOL_RUB}₽:  {сводка['ok_per_reg']}/{len(КАНДИДАТЫ)}")
print(f"  Σ per (Орг,Подр) 0 расхождений:       {сводка['ok_per_podr']}/{len(КАНДИДАТЫ)}")
print(f"  Доля ФизЛиц ≥99%:                     {сводка['ok_fl']}/{len(КАНДИДАТЫ)}")
print(f"  0 дублей ключа:                       {сводка['ok_dup']}/{len(КАНДИДАТЫ)}")

if сводка["fail_per_reg"]:
    print(f"\n❌ Σ per Регистратор FAIL:")
    for n, в, п, d in сводка["fail_per_reg"][:10]:
        print(f"  № {n}: ВзС={в:,.2f} ПАП={п:,.2f} |Δ|={d:.2f}")
if сводка["fail_per_podr"]:
    print(f"\n❌ Σ per (Орг,Подр) FAIL:")
    for n, r, m in сводка["fail_per_podr"][:5]:
        print(f"  № {n}: {r} расхождений, max |Δ|={m:.2f}")
if сводка["fail_fl"]:
    print(f"\n❌ Доля ФизЛица FAIL:")
    for n, c, r, d in сводка["fail_fl"][:5]:
        print(f"  № {n}: {c}/{r} = {d:.1f}%")
if сводка["fail_dup"]:
    print(f"\n❌ Дубли FAIL:")
    for n, dl in сводка["fail_dup"][:5]:
        print(f"  № {n}: {dl} дублей")

# Идемпотентность — повтор проведения всех документов
print(f"\n=== Идемпотентность (повтор) ===")
idem_fail = 0
for ном, док, взс_было in данные:
    try:
        док.ПолучитьОбъект().Записать(РежПров)
    except Exception as ex:
        print(f"  ❌ № {ном}: {ex}")
        all_pass = False; idem_fail += 1; continue
    взс_стало = сумма_signed_a_vzs(док)
    d = abs(взс_было - взс_стало)
    if d > 0.01:
        print(f"  ❌ № {ном}: было {взс_было:,.2f} стало {взс_стало:,.2f} Δ={d:.4f}")
        all_pass = False; idem_fail += 1
print(f"  Идемпотентность: {len(данные)-idem_fail}/{len(данные)} OK")

# Отдельный assert для тестового № 19099 (4 468,23)
print(f"\n=== Особый assert: № 00000019099 (4 468,23) ===")
для_19099 = [d for d in данные if d[0] == "00000019099"]
if для_19099:
    n, док, взс = для_19099[0]
    ожид = -4468.23  # Σ signed = -сумма (ВидДв=Расход)
    delta_19099 = abs(взс - ожид)
    s = "✅" if delta_19099 <= 0.01 else "❌"
    print(f"  {s} Σ signed А_ВзСС = {взс:,.2f}; ожидаемое {ожид:,.2f}; |Δ|={delta_19099:.4f}")
    if delta_19099 > 0.01: all_pass = False

print()
print("=" * 60)
print("[OK] ВСЕ PASS" if all_pass else "[FAIL]")
sys.exit(0 if all_pass else 1)
