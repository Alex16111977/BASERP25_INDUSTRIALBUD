"""Проверка СведенияОВнешнейОбработке() — то, что БСП вызывает при подключении доп.обработки.
Сравнение нашей обработки с рабочим примером ПерепроведениеДокументов."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

def проверить(путь, метка):
    обр = buh.ВнешниеОбработки.Создать(путь, False)
    св = обр.СведенияОВнешнейОбработке()
    print(f"=== {метка} ===")
    print("  Вид:", св.Вид, "| Наименование:", св.Наименование, "| Версия:", св.Версия,
          "| БезопасныйРежим:", св.БезопасныйРежим, "| ВерсияБСП:", св.ВерсияБСП)
    к = св.Команды
    print("  команд:", к.Количество())
    for i in range(к.Количество()):
        r = к.Получить(i)
        print(f"    [{r.Идентификатор}] '{r.Представление}' Использование={r.Использование} Оповещ={r.ПоказыватьОповещение}")
    return св

NUL = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
ПР = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\ПерепроведениеДокументов.epf"
эталон = проверить(ПР, "ЭТАЛОН ПерепроведениеДокументов")
наша = проверить(NUL, "НАША СозданиеКомплектацийБух")

assert наша.Вид == "ДополнительнаяОбработка", "не тот Вид"
assert наша.Команды.Количество() >= 1, "нет команд"
assert наша.Команды.Получить(0).Использование == "ОткрытиеФормы", "команда не ОткрытиеФормы"
assert наша.Свойство("ВерсияБСП") and наша.Свойство("Команды"), "нет обяз. ключей"
print("\nVERIFY BSP: PASS — структура как у рабочего примера, подключение пройдёт")
