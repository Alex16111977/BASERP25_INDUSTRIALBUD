    нз.Отбор.Договор.Установить(договір)
    нз.Прочитать()
    з = нз[0] if нз.Количество() > 0 else нз.Добавить()
    з.Договор = договір
    if строк:
        з.СрокОплатыДней = строк
        з.БазаСрокаОплаты = база
    з.УсловияДоговора = (з.УсловияДоговора.strip() + умови) if дописати else умови
