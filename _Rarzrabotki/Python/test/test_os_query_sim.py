# -*- coding: utf-8 -*-
"""Симуляція запиту проведення: перевіряємо чи ПрочиеРасходы.Остатки()
знаходить дані для ОЗ з ПринятиеКУчетуОС ІБ00-000254.
"""
import win32com.client, datetime

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# 1. Знайти ОС з документа
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ
    Т.ОсновноеСредство КАК ОС,
    Т.Ссылка.Организация КАК Орг,
    Т.Ссылка.Подразделение КАК Подр,
    Т.Ссылка.НаправлениеДеятельности КАК Напр,
    Т.Ссылка.Дата КАК Период
ИЗ Документ.ПринятиеКУчетуОС.ОС КАК Т
ГДЕ Т.Ссылка.Номер ПОДОБНО &Н И Т.Ссылка.Дата >= &Д"""
q.SetParameter("Н", "%000254%")
q.SetParameter("Д", datetime.datetime(2025, 12, 1))

res = q.Execute()
sel = res.Select()
os_list = []
while sel.Next():
    os_list.append(sel.ОС)
    print(f"ОС: {S(sel.ОС)} | Орг: {S(sel.Орг)} | Подр: {S(sel.Подр)} | Напр: {S(sel.Напр)}")

print(f"\nВсього ОС: {len(os_list)}")

# 2. Перевірити ПрочиеРасходы.Остатки по кожному ОС
print("\n=== ПрочиеРасходы.Остатки() ===")
for os_ref in os_list:
    q2 = conn.NewObject("Запрос")
    q2.Text = """ВЫБРАТЬ
        ПР.Организация, ПР.Подразделение, ПР.НалоговоеНазначение,
        ПР.СтатьяРасходов, ПР.АналитикаРасходов,
        ПР.СуммаОстаток, ПР.СуммаРеглОстаток
    ИЗ РегистрНакопления.ПрочиеРасходы.Остатки(, АналитикаРасходов = &ОС) КАК ПР"""
    q2.SetParameter("ОС", os_ref)
    res2 = q2.Execute()
    sel2 = res2.Select()
    found = False
    while sel2.Next():
        found = True
        print(f"  ОС: {S(sel2.АналитикаРасходов)}")
        print(f"  Орг: {S(sel2.Организация)} Подр: {S(sel2.Подразделение)}")
        print(f"  Стаття: {S(sel2.СтатьяРасходов)}")
        print(f"  НалогНазн: {S(sel2.НалоговоеНазначение)}")
        print(f"  СуммаОстаток: {sel2.СуммаОстаток}")
        print(f"  СуммаРеглОстаток: {sel2.СуммаРеглОстаток}")
    if not found:
        print(f"  ОС {S(os_ref)}: ПУСТО!")

# 3. Перевірити фільтр ТипРасходов
print("\n=== З фільтром ТипРасходов ===")
for os_ref in os_list:
    q3 = conn.NewObject("Запрос")
    q3.Text = """ВЫБРАТЬ
        ПР.СтатьяРасходов, ПР.АналитикаРасходов,
        ПР.СуммаОстаток
    ИЗ РегистрНакопления.ПрочиеРасходы.Остатки(,
        АналитикаРасходов = &ОС
        И СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)
    ) КАК ПР"""
    q3.SetParameter("ОС", os_ref)
    res3 = q3.Execute()
    sel3 = res3.Select()
    found = False
    while sel3.Next():
        found = True
        print(f"  Стаття: {S(sel3.СтатьяРасходов)} Сума: {sel3.СуммаОстаток}")
    if not found:
        print(f"  ОС {S(os_ref)}: ПУСТО з фільтром ФормированиеСтоимостиВНА!")

# 4. Симуляція повного запиту як в Module.bsl
print("\n=== СИМУЛЯЦІЯ ЗАПИТУ МОДУЛЯ ===")
q4 = conn.NewObject("Запрос")
q4.Text = """ВЫБРАТЬ
    ТаблицаОС.ОсновноеСредство КАК Аналитика,
    ОстаткиРасходов.СуммаОстаток КАК Сумма
ИЗ
    (ВЫБРАТЬ Т.ОсновноеСредство ИЗ Документ.ПринятиеКУчетуОС.ОС КАК Т ГДЕ Т.Ссылка.Номер ПОДОБНО &Н И Т.Ссылка.Дата >= &Д) КАК ТаблицаОС
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрНакопления.ПрочиеРасходы.Остатки(
        ,
        АналитикаРасходов В (ВЫБРАТЬ РАЗЛИЧНЫЕ Т.ОсновноеСредство ИЗ Документ.ПринятиеКУчетуОС.ОС КАК Т ГДЕ Т.Ссылка.Номер ПОДОБНО &Н И Т.Ссылка.Дата >= &Д)
        И СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)
    ) КАК ОстаткиРасходов
    ПО ТаблицаОС.ОсновноеСредство = ОстаткиРасходов.АналитикаРасходов
ГДЕ
    ОстаткиРасходов.СуммаОстаток > 0"""
q4.SetParameter("Н", "%000254%")
q4.SetParameter("Д", datetime.datetime(2025, 12, 1))
try:
    res4 = q4.Execute()
    sel4 = res4.Select()
    cnt = 0
    while sel4.Next():
        cnt += 1
        print(f"  #{cnt} ОС: {S(sel4.Аналитика)} Сума: {sel4.Сумма}")
    if cnt == 0:
        print("  ПУСТО! Запит повернув 0 рядків.")
    else:
        print(f"  Всього: {cnt} — запит ПРАЦЮЄ!")
except Exception as e:
    print(f"  ПОМИЛКА: {e}")

print("\n=== DONE ===")
