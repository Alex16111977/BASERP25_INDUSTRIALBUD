N = M = 0


def проверка(cond, msg):
    global N, M
    N += 1
    if not cond:
        M += 1
        print(f"  FAIL: {msg}")
    return cond


def fmt(x):
    return f"{float(x):,.2f}".replace(",", " ")


def эталон_листов(порча=None):
    """{(лист, месяц): (безнал, нал, строк)} по листам, которые грузятся."""
    data = json.load(open(ЭТАЛОН, encoding="utf-8"))["etalon"]
    res = {}
    for лист, месяцы in data.items():
        if лист not in КАРТА:
            continue
        for m, e in месяцы.items():
            bn, nal = float(e["bn"]), float(e["nal"])
            if bn == 0 and nal == 0:
                continue
            res[(лист, m)] = [bn, nal, e["cells_bn"] + e["cells_nal"]]
    if порча:
        ключ, поле, дельта = порча
        if ключ in res:
            res[ключ][поле] += дельта
    return res


def сверить(факт, эталон, что):
    """факт: {(лист, месяц): (безнал, нал, строк)}"""
    ключи_э, ключи_ф = set(эталон), set(факт)
    проверка(ключи_э == ключи_ф,
             f"{что}: набор пар «лист × месяц» не совпал; нет в факте {sorted(ключи_э - ключи_ф)}; лишние {sorted(ключи_ф - ключи_э)}")
    и_бн = и_нал = 0.0
    э_бн = э_нал = 0.0
    for k in sorted(ключи_э & ключи_ф):
        э, ф = эталон[k], факт[k]
        проверка(abs(э[0] - ф[0]) <= ДОПУСК, f"{что} {k[0]} {k[1]} безнал: эталон {fmt(э[0])} факт {fmt(ф[0])} Δ {fmt(ф[0]-э[0])}")
        проверка(abs(э[1] - ф[1]) <= ДОПУСК, f"{что} {k[0]} {k[1]} нал: эталон {fmt(э[1])} факт {fmt(ф[1])} Δ {fmt(ф[1]-э[1])}")
        проверка(э[2] == ф[2], f"{что} {k[0]} {k[1]} строк: эталон {э[2]} факт {ф[2]}")
        э_бн += э[0]; э_нал += э[1]; и_бн += ф[0]; и_нал += ф[1]
    проверка(abs(э_бн - и_бн) <= ДОПУСК_ИТОГ, f"{что} ИТОГО безнал: эталон {fmt(э_бн)} факт {fmt(и_бн)}")
    проверка(abs(э_нал - и_нал) <= ДОПУСК_ИТОГ, f"{что} ИТОГО нал: эталон {fmt(э_нал)} факт {fmt(и_нал)}")
    print(f"  {что}: пар {len(ключи_э & ключи_ф)}, безнал эталон {fmt(э_бн)} / факт {fmt(и_бн)}, нал эталон {fmt(э_нал)} / факт {fmt(и_нал)}")
    return len(ключи_э & ключи_ф)


