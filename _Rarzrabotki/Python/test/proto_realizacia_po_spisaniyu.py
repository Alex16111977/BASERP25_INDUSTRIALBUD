# -*- coding: utf-8 -*-
# Rule #-1 prototype: движок ЗаполнитьПоСписаниюРеализацию 1:1 в Python COM (BuhBud).
# Зеркало ветки приобретения, но приёмник = РеализацияТоваровУслуг.
# Заполняет СУЩЕСТВУЮЩИЙ приёмник (как production), Записать без проведения,
# проверяет отсутствие искажений ПередЗаписью, ОТКАТЫВАЕТ. Продакшн не трогаем.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

НомерСписания = "СТ00-000001"   # 94 Кт-проводки
НомерПриёмника = "ІБ00-000110"  # существующая проведённая реализация

def full_name(val):
    try:
        return val.Метаданные().ПолноеИмя()
    except Exception:
        return ""

def find_ref(typ, nomer):
    q = buh.NewObject("Запрос")
    q.Text = f"ВЫБРАТЬ Ссылка, Проведен ИЗ Документ.{typ} ГДЕ Номер = &Н"
    q.SetParameter("Н", nomer)
    s = q.Execute().Выбрать()
    return (s.Ссылка, s.Проведен) if s.Следующий() else (None, None)

# Списание берём по Ref с максимальным числом Кт-проводок (Номер не уникален)
qm = buh.NewObject("Запрос")
qm.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Х.Регистратор КАК Рег, КОЛИЧЕСТВО(*) КАК Кво
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
ГДЕ Х.КоличествоКт > 0 И ТИПЗНАЧЕНИЯ(Х.Регистратор) = ТИП(Документ.СписаниеТоваров)
СГРУППИРОВАТЬ ПО Х.Регистратор УПОРЯДОЧИТЬ ПО Кво УБЫВ
"""
sm = qm.Execute().Выбрать(); sm.Следующий()
СписаниеСсылка, спПров = sm.Рег, sm.Рег.Проведен
ПриёмникСсылка, прПров = find_ref("РеализацияТоваровУслуг", НомерПриёмника)
print(f"Списание : {buh.String(СписаниеСсылка)}  Проведен={спПров}")
print(f"Приёмник : {buh.String(ПриёмникСсылка)}  Проведен={прПров}")

# --- читать проводки набором записей (субконто в запросе недоступны) ---
НЗ = buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
НЗ.Отбор.Регистратор.Установить(СписаниеСсылка)
НЗ.Прочитать()

Группы, Порядок = {}, []
for Запись in НЗ:
    if Запись.КоличествоКт == 0:
        continue
    nom = None
    for kv in Запись.СубконтоКт:
        if full_name(kv.Значение) == "Справочник.Номенклатура":
            nom = kv.Значение; break
    if nom is None:
        continue
    Счет, НалНазн = Запись.СчетКт, Запись.НалоговоеНазначениеКт
    ключ = (buh.String(nom.УникальныйИдентификатор()),
            buh.String(Счет.УникальныйИдентификатор()),
            buh.String(НалНазн.УникальныйИдентификатор()))
    g = Группы.get(ключ)
    if g is None:
        g = {"Ном": nom, "Счет": Счет, "Нал": НалНазн, "Кол": 0.0, "Сум": 0.0}
        Группы[ключ] = g; Порядок.append(ключ)
    g["Кол"] += Запись.КоличествоКт
    g["Сум"] += Запись.Сумма

print(f"Проводок прочитано: {НЗ.Количество()},  групп(строк): {len(Порядок)}")
if not Порядок:
    print("FAIL: нет строк с номенклатурой на Кт"); sys.exit()

СтавкаНДС20 = buh.Перечисления.СтавкиНДС.НДС20
ПроцентНДС = 20
ИтогоСумма = ИтогоНДС = 0.0

buh.НачатьТранзакцию()
try:
    Док = ПриёмникСсылка.ПолучитьОбъект()
    Док.Товары.Очистить()
    Док.СуммаВключаетНДС = False
    for ключ in Порядок:
        g = Группы[ключ]
        стр = Док.Товары.Добавить()
        стр.Номенклатура = g["Ном"]
        стр.СчетУчетаБУ = g["Счет"]
        стр.Количество = g["Кол"]
        стр.Сумма = g["Сум"]
        стр.Цена = (g["Сум"] / g["Кол"]) if g["Кол"] != 0 else 0
        стр.ЕдиницаИзмерения = g["Ном"].БазоваяЕдиницаИзмерения
        стр.Коэффициент = 1
        стр.СтавкаНДС = СтавкаНДС20
        стр.СуммаНДС = round(g["Сум"] * ПроцентНДС / 100, 2)
        стр.НалоговоеНазначение = g["Нал"]
        стр.НалоговоеНазначениеДоходовИЗатрат = g["Нал"]
        стр.Себестоимость = g["Сум"]
        стр.СебестоимостьНУ = g["Сум"]
        ИтогоСумма += g["Сум"]
        ИтогоНДС += round(g["Сум"] * ПроцентНДС / 100, 2)
    Док.СуммаДокумента = ИтогоСумма + ИтогоНДС
    режим = buh.РежимЗаписиДокумента.ОтменаПроведения if Док.Проведен else buh.РежимЗаписиДокумента.Запись
    Док.Записать(режим)

    Док2 = ПриёмникСсылка.ПолучитьОбъект()
    rСум = sum(s.Сумма for s in Док2.Товары)
    rНДС = sum(s.СуммаНДС for s in Док2.Товары)
    rСеб = sum(s.Себестоимость for s in Док2.Товары)
    rКол = sum(s.Количество for s in Док2.Товары)
    print("--- После Записать() (перечитано из объекта) ---")
    print(f"  Строк ТЧ Товары : {Док2.Товары.Количество()}  (ожидалось {len(Порядок)})")
    print(f"  Σ Количество     : {rКол:.3f}")
    print(f"  Σ Сумма          : {rСум:.2f}  (вход {ИтогоСумма:.2f})")
    print(f"  Σ СуммаНДС        : {rНДС:.2f}  (вход {ИтогоНДС:.2f})")
    print(f"  Σ Себестоимость   : {rСеб:.2f}")
    print(f"  СуммаДокумента    : {Док2.СуммаДокумента:.2f}  (ожид {ИтогоСумма+ИтогоНДС:.2f})")
    print(f"  Проведен после    : {Док2.Проведен}  АвторасчетНДС={Док2.АвторасчетНДС}")
    ok = (Док2.Товары.Количество() == len(Порядок)
          and abs(rСум - ИтогоСумма) < 0.01
          and abs(rНДС - ИтогоНДС) < 0.01
          and abs(rСеб - ИтогоСумма) < 0.01
          and (not Док2.Проведен))
    print("RESULT:", "OK — поля заполнены, искажений нет, распроведено" if ok
          else "CHECK — есть расхождение, разобрать")
finally:
    buh.ОтменитьТранзакцию()
    print("Транзакция откачена — продакшн не изменён.")
