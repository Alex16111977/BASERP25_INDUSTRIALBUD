"""Discovery #2: элементы А_ВидыКонтрагентовДляБаланса + состав _КОРПОРАТИВНІ + договоры."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

def run(title, text, params=None):
    print("=" * 70)
    print(title)
    print("=" * 70)
    q = erp.NewObject("Запрос")
    q.Text = text
    if params:
        for k, val in params.items():
            q.SetParameter(k, val)
    try:
        r = q.Execute().Выгрузить()
        print(f"OK, рядків={r.Количество()}")
        return r
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"FAIL: {e.excepinfo[2]}")
        else:
            print(f"FAIL: {e}")
        return None

