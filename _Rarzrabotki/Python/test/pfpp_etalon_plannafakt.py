# Эталон «План на факт» (ETC) для А_ПланФактныйПроизводствоПолный — НЕЗАВИСИМАЯ реализация
# утверждённой методологии (правила 1-4), не копия BSL:
#   грануле нетто: (Подразделение, «Загальна назва»); fallback без ОН — сама Номенклатура;
#   1) ФактКол=0  -> ПланНаФакт = ПланГрн группы (ровно, без цены*кол);
#   2) ФактКол>0  -> ПланНаФакт = max(0, ПланКол-ФактКол) * (ПланГрн/ПланКол);
#   3) строки без ОН участвуют (ключ - Номенклатура);
#   4) ПланКол=0 при ПланГрн>0 -> ПланНаФакт = max(0, ПланГрн - ФактГрн).
# Диагностика: строки без ОН, группы ПланКол=0, дубли ссылок ОН (план vs факт) — имя vs ссылка.
