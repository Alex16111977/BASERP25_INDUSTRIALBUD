def выгрузить(qtext, params):
    q = erp.NewObject("Запрос")
    q.Text = qtext
    for k, v in params.items():
        q.SetParameter(k, v)
    tz = q.Execute().Выгрузить()
    rows = []
    for i in range(tz.Количество()):
        r = tz.Получить(i)
        он_пусто = not str(S(r.ОН)).strip()  # пустая ссылка -> пустое представление
        rows.append({
            "ном_uuid": str(S(r.Номенклатура.УникальныйИдентификатор())) if not он_пусто or True else "",
            "ном_имя": str(r.НоменклатураИмя or ""),
            "он_uuid": "" if он_пусто else str(S(r.ОН.УникальныйИдентификатор())),
            "он_имя": str(r.ОНИмя or "").strip(),
            "кол": f(r.Кол),
            "грн": f(r.Грн),
        })
    return rows

def ключ_группы(row, по_имени=True):
    if row["он_uuid"]:
        if по_имени:
            return "ОН|" + (row["он_имя"] if row["он_имя"] else row["он_uuid"])
        return "ОН|" + row["он_uuid"]
    return "НОМ|" + row["ном_uuid"]

def нетто(план, факт, по_имени=True):
    групп = {}
    for src, rows in (("план", план), ("факт", факт)):
        for r in rows:
            k = ключ_группы(r, по_имени)
            g = групп.setdefault(k, {"ПланКол": 0.0, "ФактКол": 0.0, "ПланГрн": 0.0, "ФактГрн": 0.0,
                                     "он_имя": r["он_имя"], "ном_имя": r["ном_имя"],
                                     "он_uuids_план": set(), "он_uuids_факт": set()})
        # (setdefault выше — по первой строке; имена только для печати)
    for r in план:
        g = групп[ключ_группы(r, по_имени)]
        g["ПланКол"] += r["кол"]; g["ПланГрн"] += r["грн"]
        if r["он_uuid"]: g["он_uuids_план"].add(r["он_uuid"])
    for r in факт:
        g = групп[ключ_группы(r, по_имени)]
        g["ФактКол"] += r["кол"]; g["ФактГрн"] += r["грн"]
        if r["он_uuid"]: g["он_uuids_факт"].add(r["он_uuid"])
    return групп

def план_на_факт(g):
    """Правила 1-4 утверждённой методологии."""
    if g["ПланГрн"] <= 0:
        return 0.0
    if g["ПланКол"] <= 0:                      # правило 4: стоимостное нетто
        return max(0.0, g["ПланГрн"] - g["ФактГрн"])
    if g["ФактКол"] <= 0:                      # правило 1: ровно план
        return g["ПланГрн"]
    ост = max(0.0, g["ПланКол"] - g["ФактКол"])  # правило 2
    return ост * (g["ПланГрн"] / g["ПланКол"])

def старый_алгоритм(групп):
    """Текущий BSL (для справки): только ОН-группы с ПланКол>0, всегда через цену."""
    s = 0.0
    for k, g in групп.items():
        if not k.startswith("ОН|") or g["ПланКол"] <= 0:
            continue
        цена = g["ПланГрн"] / g["ПланКол"]
        ост = max(0.0, g["ПланКол"] - g["ФактКол"])
        s += ост * цена
    return s

def отчёт_по_сс(имя_сс, нач=None, кон=None, метка=""):
    сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(имя_сс)
    assert сс is not None and str(S(сс)).strip(), f"СС не найдена: {имя_сс}"
    подр = сс.Подразделение
    print(f"\n=== {метка or имя_сс} ===")
    print(f"СС: {S(сс)}; Подразделение: {S(подр)}")
    план = выгрузить(Q_PLAN, {"СС": сс.Ссылка})
    # COM не конвертирует граничные даты (год 1/3990+); «весь срок» = без условия периода
    if нач or кон:
        params = {"НачП": нач or datetime.datetime(2000, 1, 1), "КонП": кон, "Подр": подр}
        факт = выгрузить(Q_FACT.replace("%ПЕРИОД%", "СТ.Период МЕЖДУ &НачП И &КонП"), params)
    else:
        факт = выгрузить(Q_FACT.replace("%ПЕРИОД%", "ИСТИНА"), {"Подр": подр})
    пг = sum(r["грн"] for r in план); фг = sum(r["грн"] for r in факт)
    print(f"План: строк={len(план)} Грн={пг:.2f} | Факт: строк={len(факт)} Грн={фг:.2f}")

    без_он_план = [r for r in план if not r["он_uuid"]]
    print(f"Строк плана без ОН: {len(без_он_план)}, ПланГрн={sum(r['грн'] for r in без_он_план):.2f}")
    кол0 = [r for r in план if r["кол"] == 0 and r["грн"] > 0]
    print(f"Строк плана Кол=0 при Грн>0: {len(кол0)}, ПланГрн={sum(r['грн'] for r in кол0):.2f}")

    групп_имя = нетто(план, факт, по_имени=True)
    групп_ссылка = нетто(план, факт, по_имени=False)

    # дубли ссылок ОН: в одной имя-группе план и факт с разными ссылками
    дубли = []
    for k, g in групп_имя.items():
        все = g["он_uuids_план"] | g["он_uuids_факт"]
        if len(все) > 1:
            дубли.append((g["он_имя"], len(g["он_uuids_план"]), len(g["он_uuids_факт"])))
    print(f"Имя-групп с >1 ссылкой ОН (дубли карточек): {len(дубли)}")
    for имя, п, ф in дубли[:10]:
        print(f"   дубль: '{имя}' ссылок в плане={п}, в факте={ф}")

    итог_имя = sum(план_на_факт(g) for g in групп_имя.values())
    итог_ссылка = sum(план_на_факт(g) for g in групп_ссылка.values())
    старый = старый_алгоритм(групп_имя)
    старый_ссылка = старый_алгоритм(групп_ссылка)
    print(f"ЭТАЛОН ПланНаФакт (правила 1-4, ключ=имя ОН):   {итог_имя:.2f}")
    print(f"ЭТАЛОН ПланНаФакт (правила 1-4, ключ=ссылка ОН): {итог_ссылка:.2f}")
    print(f"Старый алгоритм (дыры), ключ=имя:    {старый:.2f}")
    print(f"Старый алгоритм (дыры), ключ=ссылка: {старый_ссылка:.2f}")
    print(f"Прогноз (эталон, имя) = Факт+ПНФ = {фг + итог_имя:.2f}; План = {пг:.2f}; "
          f"% вик. прогнозу = {(100.0 * (фг + итог_имя) / пг) if пг else 0:.1f}")

    # инвариант: группы с ФактКол=0 -> ПНФ = ПланГрн копейка в копейку
    плохие = []
    for k, g in групп_имя.items():
        if g["ФактКол"] <= 0 and g["ПланГрн"] > 0:
            if round(план_на_факт(g), 2) != round(g["ПланГрн"], 2):
                плохие.append((k, g))
    print(f"Групп ФактКол=0 с ПНФ != ПланГрн: {len(плохие)} (должно быть 0)")
    return {"план": пг, "факт": фг, "пнф_имя": итог_имя, "пнф_ссылка": итог_ссылка,
            "старый": старый, "группы": групп_имя}

