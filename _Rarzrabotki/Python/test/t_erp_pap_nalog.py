import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Движения ПАП за период по статьям, где Аналитика = ТипыНалогов
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    ПАП.Статья КАК Статья,
    ПАП.Аналитика КАК Аналитика,
    ПАП.Источник КАК Источник,
    ПАП.Организация КАК Организация,
    ПАП.Подразделение КАК Подразделение,
    ВЫРАЗИТЬ(ПАП.Регистратор КАК Документ.НачальнаяЗадолженностьПоЗарплате).Ссылка КАК РегНЗ,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) ТОГДА ПАП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Расход
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
    И ТИПЗНАЧЕНИЯ(ПАП.Аналитика) = ТИП(Перечисление.ТипыНалогов)
СГРУППИРОВАТЬ ПО
    ПАП.Статья, ПАП.Аналитика, ПАП.Источник, ПАП.Организация, ПАП.Подразделение,
    ВЫРАЗИТЬ(ПАП.Регистратор КАК Документ.НачальнаяЗадолженностьПоЗарплате).Ссылка
"""
try:
    r = q.Execute().Выгрузить()
    print("ПАП налоги (Аналитика=ТипыНалогов), rows:", r.Количество())
    for i in range(r.Количество()):
        s = r.Получить(i)
        ст = str(s.Статья.Наименование) if (s.Статья and not s.Статья.Пустая()) else "(пусто)"
        ан = erp.XMLСтрока(s.Аналитика) if s.Аналитика else "-"
        ист = erp.XMLСтрока(s.Источник) if s.Источник else "-"
        орг = str(s.Организация.Наименование) if not s.Организация.Пустая() else "-"
        подр = str(s.Подразделение.Наименование) if not s.Подразделение.Пустая() else "(пусто)"
        print(f"СТ={ст[:24]:<24}|АН={ан[:18]:<18}|ИСТ={ист[:18]:<18}|ОРГ={орг[:18]:<18}|ПОДР={подр[:22]:<22}|Прих={s.Приход:>14,.2f}|Расх={s.Расход:>14,.2f}")
except Exception as e:
    info = getattr(e,'excepinfo',None)
    print("FAIL:", info[2] if info else e)
