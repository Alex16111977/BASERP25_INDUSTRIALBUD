def rasschet_intervalov(ostatok0, dvizh, stavki, d1, d2, baza=365):
    """dvizh: [(date, сума)], stavki: [(date, %)] за зростанням, перша діє з d1. → [(з, по, днів, залишок, ставка, сума)]."""
    res, den = [], d1
    while den <= d2:
        bal = round(ostatok0 + sum(s for d, s in dvizh if d <= den), 2)
        st = [s for d, s in stavki if d <= den][-1]
        if res and res[-1][3] == bal and res[-1][4] == st and res[-1][1] == den - dt.timedelta(days=1):
            z = res[-1]
            res[-1] = (z[0], den, z[2] + 1, bal, st, bal * st / 100 / baza * (z[2] + 1))
        elif bal != 0:
            res.append((den, den, 1, bal, st, bal * st / 100 / baza))
        den += dt.timedelta(days=1)
    return res


def suma(intervaly):
    return round(sum(i[5] for i in intervaly), 2)


