def data1c(d, konec=False):
    """Дата для 1С через COM: конектор віднімає 3 години (пам'ять com-date-shift-3-hours) — компенсуємо."""
    base = dt.datetime(d.year, d.month, d.day, 23, 59, 59) if konec else dt.datetime(d.year, d.month, d.day)
    return base + dt.timedelta(hours=3)


