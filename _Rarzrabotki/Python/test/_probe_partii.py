# Списание/Реализация Кт-партія → Перемещение Кт-партія → ... → Поступление.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
def S(v):
    try: return buh.String(v) if v is not None else "None"
    except: return "<?>"
def full(v):
    try: return v.Метаданные().ПолноеИмя()
    except: return ""

# 1) виды субконто Хозрасчетного (через первую запись реализации)
def найти(typ,nomer,y2026=True):
    q=buh.NewObject("Запрос")
    c=" И Дата>=ДАТАВРЕМЯ(2026,1,1)" if y2026 else ""
    q.Text=f"ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.{typ} ГДЕ Номер=&Н{c} УПОРЯДОЧИТЬ ПО Дата УБЫВ"
    q.SetParameter("Н",nomer); s=q.Execute().Выбрать()
    return s.Ссылка if s.Следующий() else None

реал=найти("РеализацияТоваровУслуг","ІБ00-000113")
print("Реализация:", S(реал))
НЗ=buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
НЗ.Отбор.Регистратор.Установить(реал); НЗ.Прочитать()
print("\n--- Первая Кт-запись: виды субконто Кт ---")
for z in НЗ:
    if z.КоличествоКт==0: continue
    for kv in z.СубконтоКт:
        print(f"   ВидСубконто={S(kv.Ключ)}  Значение={S(kv.Значение)[:50]}  Тип={full(kv.Значение)}")
    break

# 2) функция: получить (Номенклатура, Партія) для Кт-постингов документа
def кт_партии(док):
    res=[]
    нз=buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
    нз.Отбор.Регистратор.Установить(док); нз.Прочитать()
    for z in нз:
        if z.КоличествоКт==0: continue
        ном=None; парт=None
        for kv in z.СубконтоКт:
            t=full(kv.Значение)
            if t=="Справочник.Номенклатура": ном=kv.Значение
            elif t.startswith("Документ.") or "Партии" in t or "Партія" in S(kv.Ключ):
                # партия может быть документом или ссылкой на партии
                if t.startswith("Документ."): парт=kv.Значение
        res.append((ном, парт, z.КоличествоКт, z.Сумма))
    return res

# 3) трейс для "Біта РН 2*50 мм": партія списання → ... → поступление
print("\n--- Трейс партии для 'Біта РН 2*50 мм' ---")
ЦЕЛЬ="Біта РН 2*50"
for ном,парт,кол,сум in кт_партии(реал):
    if ном is None or ЦЕЛЬ not in S(ном): continue
    print(f"Реализация Кт: Ном={S(ном)} Кол={S(кол)} ПартіяСписання={S(парт)[:55]} тип={full(парт)}")
    # рекурсия по перемещениям
    текущая=парт; глубина=0; цепочка=[]
    while текущая is not None and глубина<20:
        t=full(текущая)
        цепочка.append(S(текущая)[:55])
        if t=="Документ.ПеремещениеТоваров":
            # ищем в Кт перемещения ту же номенклатуру
            следы=[(n,p) for (n,p,k,s) in кт_партии(текущая) if n is not None and ЦЕЛЬ in S(n)]
            if not следы:
                print("  (в перемещении нет нужной номенклатуры на Кт)"); break
            текущая=следы[0][1]  # берём первую партію-источник
        elif t=="Документ.ПоступлениеТоваровУслуг" or "Поступление" in t or "Надходження" in S(текущая):
            print("  → ПОСТУПЛЕНИЕ (терминал):", S(текущая)); break
        else:
            print("  → терминал (не перемещение, не поступление):", S(текущая), "тип=",t); break
        глубина+=1
    print("  Цепочка:", " → ".join(цепочка))
