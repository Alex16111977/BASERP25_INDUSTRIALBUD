# -*- coding: utf-8 -*-
"""Pretest3 (Rule #-1): новый пакетный запрос ЕРП-стороны отчёта сверки —
остатки из А_ВзСС.ОстаткиИОбороты (полные) + обороты из движений с whitelist регистраторов:
Начисления = только ОтражениеЗарплатыВФинансовомУчете (Приход),
Выплаты = только РКО + СписаниеБезналичныхДенежныхСредств (Расход).
Эталон: Постернак (ДРФО 2742610332), декабрь 2025: Начисл=200000.00, Выпл=266013.53."""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

DRFO = "2742610332"
EXP_NACH = 200000.00
EXP_VYPL = 266013.53

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

Q = """ВЫБРАТЬ
	Ост.ФизическоеЛицо КАК ФизическоеЛицо,
	СУММА(Ост.СуммаВзаиморасчетовНачальныйОстаток) КАК НачальныйОстаток,
	СУММА(Ост.СуммаВзаиморасчетовКонечныйОстаток) КАК КонечныйОстаток
ПОМЕСТИТЬ ВТ_Остатки
ИЗ
	РегистрНакопления.А_ВзаиморасчетыССотрудниками.ОстаткиИОбороты(
		ДАТАВРЕМЯ(2025, 12, 1), ДАТАВРЕМЯ(2025, 12, 31, 23, 59, 59), , , ) КАК Ост
СГРУППИРОВАТЬ ПО
	Ост.ФизическоеЛицо
;
////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ
	Д.ФизическоеЛицо КАК ФизическоеЛицо,
	СУММА(ВЫБОР
			КОГДА Д.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
					И Д.Регистратор ССЫЛКА Документ.ОтражениеЗарплатыВФинансовомУчете
				ТОГДА Д.СуммаВзаиморасчетов
			ИНАЧЕ 0
		КОНЕЦ) КАК Начисления,
	СУММА(ВЫБОР
			КОГДА Д.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
					И (Д.Регистратор ССЫЛКА Документ.РасходныйКассовыйОрдер
						ИЛИ Д.Регистратор ССЫЛКА Документ.СписаниеБезналичныхДенежныхСредств)
				ТОГДА Д.СуммаВзаиморасчетов
			ИНАЧЕ 0
		КОНЕЦ) КАК Выплаты
ПОМЕСТИТЬ ВТ_Обороты
ИЗ
	РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Д
ГДЕ
	Д.Период МЕЖДУ ДАТАВРЕМЯ(2025, 12, 1) И ДАТАВРЕМЯ(2025, 12, 31, 23, 59, 59)
СГРУППИРОВАТЬ ПО
	Д.ФизическоеЛицо
;
////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ
	Ост.ФизическоеЛицо КАК ФизическоеЛицо,
	Ост.ФизическоеЛицо.КодПоДРФО КАК ДРФО,
	Ост.НачальныйОстаток КАК НачальныйОстаток,
	ЕСТЬNULL(Об.Начисления, 0) КАК Начисления,
	ЕСТЬNULL(Об.Выплаты, 0) КАК Выплаты,
	Ост.КонечныйОстаток КАК КонечныйОстаток
ИЗ
	ВТ_Остатки КАК Ост
		ЛЕВОЕ СОЕДИНЕНИЕ ВТ_Обороты КАК Об
		ПО Ост.ФизическоеЛицо = Об.ФизическоеЛицо"""

q = erp.NewObject("Запрос")
q.Text = Q
try:
    t = q.Execute().Выгрузить()
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
    print(f"[FAIL] пакетный запрос: {msg}")
    sys.exit(1)

print(f"[OK] пакетный запрос: строк={t.Количество()}")

found = False
s_nach = 0.0
s_vypl = 0.0
for i in range(t.Количество()):
    r = t.Получить(i)
    s_nach += float(r.Начисления or 0)
    s_vypl += float(r.Выплаты or 0)
    if (r.ДРФО or "").strip() == DRFO:
        found = True
        n = float(r.Начисления or 0)
        v = float(r.Выплаты or 0)
        print(f"  Постернак дек2025: НачОст={float(r.НачальныйОстаток or 0):,.2f} "
              f"Начисл={n:,.2f} Выпл={v:,.2f} КонОст={float(r.КонечныйОстаток or 0):,.2f}")
        ok_n = abs(n - EXP_NACH) <= 0.01
        ok_v = abs(v - EXP_VYPL) <= 0.01
        print(f"  CHECK Начисления==200000.00: {'OK' if ok_n else 'FAIL'}")
        print(f"  CHECK Выплаты==266013.53: {'OK' if ok_v else 'FAIL'}")
        if not (ok_n and ok_v):
            print("PRETEST3: FAIL")
            sys.exit(1)

print(f"  Σ Начисления(ОЗФУ)={s_nach:,.2f}  Σ Выплаты(РКО+СписБезнал)={s_vypl:,.2f}")
print("PRETEST3: " + ("PASS" if found else "FAIL (Постернак не найден)"))
sys.exit(0 if found else 1)
