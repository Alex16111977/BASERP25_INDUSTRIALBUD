# -*- coding: utf-8 -*-
"""ЦВБ: МАРШРУТНЫЙ БАЛАНС переводов (READ-ONLY) — правильная сверка переводов ERP.

Закон практики 10 (knowledge_ЦентрВыравниванияБаз/06): в ERP перевод = ДВА документа
через транзит 333 — Списание (ХозОперация «Перечисление ДС на другой счет») и
ПРОВЕДЁННАЯ выписка-Поступление («Поступление ДС с другого счета»). Значит на каждой
паре счетов (Организация × СчётОтправитель × СчётПолучатель) должно выполняться
    Σ списаний == Σ выписок.
Расхождение = недостающая сторона (реальный разрыв, дооформляет бухгалтерия).

⚠️ Наивный хронологический матчинг связей непригоден — сверять НАДО суммами по маршруту,
а не попарно по датам.

Запуск:
  python check_cvb_marshrutny_balans.py --from 2026-01-01 --to 2026-07-31
  python check_cvb_marshrutny_balans.py --from 2026-01-01 --to 2026-07-31 --details
"""
import argparse
import datetime
import sys
from pathlib import Path

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
REPORTS = Path(__file__).resolve().parent / "reports"

parser = argparse.ArgumentParser()
parser.add_argument("--from", dest="dt_from", default="2026-01-01")
parser.add_argument("--to", dest="dt_to", default="2026-07-31")
parser.add_argument("--details", action="store_true",
                    help="Показать документы маршрутов с ненулевой дельтой")
parser.add_argument("--out", default="cvb_marshrutny_balans.md")
args = parser.parse_args()

nach = datetime.datetime.strptime(args.dt_from, "%Y-%m-%d")
kon = datetime.datetime.strptime(args.dt_to, "%Y-%m-%d").replace(hour=23, minute=59, second=59)

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN_ERP)
S = erp.String

Q_SPIS = """
ВЫБРАТЬ
	Спис.Организация.Наименование КАК Организация,
	Спис.БанковскийСчет.Наименование КАК Отправитель,
	Спис.БанковскийСчетПолучатель.Наименование КАК Получатель,
	СУММА(Спис.СуммаДокумента) КАК Сумма,
	КОЛИЧЕСТВО(*) КАК Кол
ИЗ
	Документ.СписаниеБезналичныхДенежныхСредств КАК Спис
ГДЕ
	Спис.Проведен
	И Спис.Дата МЕЖДУ &Нач И &Кон
	И Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)
СГРУППИРОВАТЬ ПО
	Спис.Организация.Наименование,
	Спис.БанковскийСчет.Наименование,
	Спис.БанковскийСчетПолучатель.Наименование
"""

Q_POST = """
ВЫБРАТЬ
	Пост.Организация.Наименование КАК Организация,
	Пост.БанковскийСчетОтправитель.Наименование КАК Отправитель,
	Пост.БанковскийСчет.Наименование КАК Получатель,
	СУММА(Пост.СуммаДокумента) КАК Сумма,
	КОЛИЧЕСТВО(*) КАК Кол
ИЗ
	Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пост
ГДЕ
	Пост.Проведен
	И Пост.Дата МЕЖДУ &Нач И &Кон
	И Пост.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
СГРУППИРОВАТЬ ПО
	Пост.Организация.Наименование,
	Пост.БанковскийСчетОтправитель.Наименование,
	Пост.БанковскийСчет.Наименование
"""

Q_DOCS_SPIS = """
ВЫБРАТЬ
	Спис.Номер КАК Номер,
	Спис.Дата КАК Дата,
	Спис.СуммаДокумента КАК Сумма,
	ВЫБОР КОГДА Пара.Ссылка ЕСТЬ NULL ТОГДА "НЕМАЄ ВИПИСКИ" ИНАЧЕ "ok" КОНЕЦ КАК Пара
ИЗ
	Документ.СписаниеБезналичныхДенежныхСредств КАК Спис
		ЛЕВОЕ СОЕДИНЕНИЕ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пара
		ПО Пара.А_СписаниеБезналичныхДенежныхСредств = Спис.Ссылка
			И Пара.Проведен
ГДЕ
	Спис.Проведен
	И Спис.Дата МЕЖДУ &Нач И &Кон
	И Спис.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПеречислениеДенежныхСредствНаДругойСчет)
	И Спис.Организация.Наименование = &Орг
	И Спис.БанковскийСчет.Наименование = &Отпр
	И Спис.БанковскийСчетПолучатель.Наименование = &Пол
УПОРЯДОЧИТЬ ПО
	Дата
"""

Q_DOCS_POST = """
ВЫБРАТЬ
	Пост.Номер КАК Номер,
	Пост.Дата КАК Дата,
	Пост.СуммаДокумента КАК Сумма,
	ВЫБОР
		КОГДА Пост.А_СписаниеБезналичныхДенежныхСредств = ЗНАЧЕНИЕ(Документ.СписаниеБезналичныхДенежныхСредств.ПустаяСсылка)
			ТОГДА "БЕЗ ЗВ'ЯЗКУ"
		ИНАЧЕ "ok"
	КОНЕЦ КАК Пара
ИЗ
	Документ.ПоступлениеБезналичныхДенежныхСредств КАК Пост
ГДЕ
	Пост.Проведен
	И Пост.Дата МЕЖДУ &Нач И &Кон
	И Пост.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПоступлениеДенежныхСредствСДругогоСчета)
	И Пост.Организация.Наименование = &Орг
	И Пост.БанковскийСчетОтправитель.Наименование = &Отпр
	И Пост.БанковскийСчет.Наименование = &Пол
УПОРЯДОЧИТЬ ПО
	Дата
"""


def run(text, params):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, val in params.items():
        q.SetParameter(k, val)
    return q.Execute().Выгрузить()


base_params = {"Нач": nach, "Кон": kon}
routes = {}

for text, side in ((Q_SPIS, "spis"), (Q_POST, "post")):
    tz = run(text, base_params)
    for i in range(tz.Количество()):
        r = tz.Получить(i)
        key = (str(S(r.Организация)), str(S(r.Отправитель)), str(S(r.Получатель)))
        rec = routes.setdefault(key, {"spis": 0.0, "post": 0.0, "spis_n": 0, "post_n": 0})
        rec[side] = float(r.Сумма)
        rec[side + "_n"] = int(r.Кол)

print(f"=== Маршрутный баланс переводов {args.dt_from} .. {args.dt_to} ===", flush=True)
print(f"    маршрутов (пар счетов): {len(routes)}", flush=True)

bad = [(k, v) for k, v in routes.items() if abs(v["spis"] - v["post"]) >= 0.005]
bad.sort(key=lambda kv: -abs(kv[1]["spis"] - kv[1]["post"]))

out = [f"# ЦВБ: маршрутный баланс переводов {args.dt_from} .. {args.dt_to}", "",
       f"Маршрутов всего: {len(routes)}; с расхождением: **{len(bad)}**",
       f"Σ|Δ| = {sum(abs(v['spis'] - v['post']) for _, v in bad):,.2f}", "",
       "| Δ (списания−выписки) | Организация | Отправитель | Получатель | "
       "Σ списаний (шт) | Σ выписок (шт) |", "|---|---|---|---|---|---|"]

for (org, otpr, pol), v in bad:
    delta = v["spis"] - v["post"]
    print(f"  Δ={delta:>18,.2f}  {org} | {otpr[:40]} -> {pol[:40]} | "
          f"спис {v['spis']:,.2f}({v['spis_n']}) / вып {v['post']:,.2f}({v['post_n']})",
          flush=True)
    out.append(f"| {delta:,.2f} | {org} | {otpr} | {pol} | "
               f"{v['spis']:,.2f} ({v['spis_n']}) | {v['post']:,.2f} ({v['post_n']}) |")

if not bad:
    print("  РАСХОЖДЕНИЙ НЕТ — все маршруты сбалансированы", flush=True)
    out.append("")
    out.append("**Расхождений нет — все маршруты сбалансированы.**")

if args.details and bad:
    out += ["", "## Документы маршрутов с расхождением", ""]
    for (org, otpr, pol), v in bad:
        out.append(f"### {org} | {otpr} -> {pol} "
                   f"(Δ {v['spis'] - v['post']:,.2f})")
        p = dict(base_params, Орг=org, Отпр=otpr, Пол=pol)
        for label, text in (("Списания", Q_DOCS_SPIS), ("Выписки", Q_DOCS_POST)):
            tz = run(text, p)
            out.append(f"**{label}: {tz.Количество()}**")
            for i in range(tz.Количество()):
                r = tz.Получить(i)
                mark = str(S(r.Пара))
                out.append(f"- {S(r.Номер)} от {r.Дата:%d.%m.%Y} — {r.Сумма:,.2f}"
                           + ("" if mark == "ok" else f"  ⚠️ {mark}"))
            out.append("")

REPORTS.mkdir(exist_ok=True)
rep = REPORTS / args.out
rep.write_text("\n".join(out), encoding="utf-8")
print(f"\nОтчёт: {rep}", flush=True)

erp = None
print("BALANS DONE", flush=True)
