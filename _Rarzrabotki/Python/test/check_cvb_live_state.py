# -*- coding: utf-8 -*-
"""ЦВБ: смоук переналитой BaseERP (конфигурация свежая, данные из снимка BaseERPRazr).

Проверяет (только чтение, ничего не пишет):
  A. Объекты ЦВБ на месте (метаданные).
  B. Обработки создаются: А_ЦентрВыравниванияБаз + 4 плагина А_Синхронизировать*.
  C. Движок жив: ВсеИменаПлановОбмена() -> 2 плана; НастройкиОбменаПоИмениПлана().
  D. Контуры (4 предопределённых) и их КлючевыеПоля/СсылочныеПоля.
  E. Состояние данных ДО работ: РС правил пуст, РС исключений, журнал ЦВБ (сеансы),
     артефакты 000Ц-000778..000Ц-000837 отсутствуют.

Запуск: python check_cvb_live_state.py
"""
import sys

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

FAILS = []
WARNS = []


def ok(msg):
    print(f"  [OK]   {msg}", flush=True)


def fail(msg):
    FAILS.append(msg)
    print(f"  [FAIL] {msg}", flush=True)


def warn(msg):
    WARNS.append(msg)
    print(f"  [WARN] {msg}", flush=True)


print("=== Подключение к BaseERP ===", flush=True)
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN_ERP)
S = erp.String
print(f"  Конфигурация: {S(erp.Метаданные.Имя)} {S(erp.Метаданные.Версия)}", flush=True)

# --- A. Метаданные -----------------------------------------------------------
print("\n=== A. Объекты ЦВБ в метаданных ===", flush=True)
META = [
    ("Справочники", "А_КонтурыСверкиБаз"),
    ("РегистрыСведений", "А_ИсключенияСверкиБаз"),
    ("РегистрыСведений", "А_ЖурналВыравниванияБаз"),
    ("РегистрыСведений", "А_ПравилаКлассификацииСверкиБаз"),
    ("Перечисления", "А_СтатусыВыравниванияБаз"),
    ("ОбщиеМодули", "А_ВыравниваниеБазСервер"),
    ("Обработки", "А_ЦентрВыравниванияБаз"),
    ("Обработки", "А_СинхронизироватьДеньги"),
    ("Обработки", "А_СинхронизироватьТоварыТолькоТовары"),
    ("Обработки", "А_СинхронизироватьВзаиморасчеты"),
    ("Обработки", "А_СинхронизироватьДеньгиКасса"),
]
for kind, name in META:
    found = getattr(erp.Метаданные, kind).Найти(name)
    if str(S(found)).strip():
        ok(f"{kind}.{name}")
    else:
        fail(f"НЕТ в метаданных: {kind}.{name}")

# v3.1: измерение РеквизитФлаг в РС правил
rs_meta = erp.Метаданные.РегистрыСведений.Найти("А_ПравилаКлассификацииСверкиБаз")
if str(S(rs_meta)).strip():
    dims = [str(S(rs_meta.Измерения.Получить(i).Имя))
            for i in range(rs_meta.Измерения.Количество())]
    res = [str(S(rs_meta.Ресурсы.Получить(i).Имя))
           for i in range(rs_meta.Ресурсы.Количество())]
    print(f"    измерения: {dims}", flush=True)
    print(f"    ресурсы:   {res}", flush=True)
    if "РеквизитФлаг" in dims:
        ok("РеквизитФлаг — ИЗМЕРЕНИЕ (v3.1)")
    else:
        fail("РеквизитФлаг отсутствует/не измерение в А_ПравилаКлассификацииСверкиБаз")

# галочка v3.1 на документе
doc_oi = erp.Метаданные.Документы.Найти("ОприходованиеИзлишковТоваров")
if str(S(doc_oi)).strip():
    rq = doc_oi.Реквизиты.Найти("А_ДляЗакрытиеОтрицательныхОстатков")
    if str(S(rq)).strip():
        ok(f"ОприходованиеИзлишковТоваров.А_ДляЗакрытиеОтрицательныхОстатков "
           f"(ToolTip: {str(S(rq.Подсказка))[:60]!r})")
    else:
        fail("нет реквизита ОприходованиеИзлишковТоваров.А_ДляЗакрытиеОтрицательныхОстатков")

# --- B. Обработки создаются --------------------------------------------------
print("\n=== B. Обработки создаются (Создать()) ===", flush=True)
for name in ("А_ЦентрВыравниванияБаз", "А_СинхронизироватьДеньги",
             "А_СинхронизироватьТоварыТолькоТовары", "А_СинхронизироватьВзаиморасчеты",
             "А_СинхронизироватьДеньгиКасса"):
    try:
        obj = getattr(erp.Обработки, name).Создать()
        ok(f"Обработки.{name}.Создать() -> {S(obj.Метаданные().Имя)}")
    except Exception as e:
        info = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
        fail(f"Обработки.{name}.Создать(): {info}")

# --- C. Движок ---------------------------------------------------------------
print("\n=== C. Движок А_ВыравниваниеБазСервер ===", flush=True)
engine = erp.А_ВыравниваниеБазСервер
try:
    names = engine.ВсеИменаПлановОбмена()
    plans = [str(S(names.Получить(i))) for i in range(names.Количество())]
    if len(plans) == 2:
        ok(f"ВсеИменаПлановОбмена() -> {plans}")
    else:
        fail(f"ВсеИменаПлановОбмена() -> {plans} (ожидалось 2 плана)")
    for plan in plans:
        st = engine.НастройкиОбменаПоИмениПлана(plan)
        put = str(S(st.ПутьКОбработке))
        base = str(S(st.ИмяБазы))
        if put:
            ok(f"настройки '{plan}': база={base}, worker={put}")
        else:
            warn(f"настройки '{plan}': база={base}, ПутьКОбработке ПУСТ (обмен не пройдёт)")
except Exception as e:
    info = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
    fail(f"движок: {info}")

# --- D. Контуры --------------------------------------------------------------
print("\n=== D. Контуры сверки ===", flush=True)
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	К.Наименование КАК Наименование,
	К.ИмяОбработки КАК Плагин,
	К.ПланОбмена КАК План,
	К.КлючевыеПоля КАК КлючевыеПоля,
	К.СсылочныеПоля КАК СсылочныеПоля,
	К.ПоляСумм КАК ПоляСумм,
	К.НачалоПериодаВыравнивания КАК НачалоПериода,
	К.Отключен КАК Отключен
ИЗ
	Справочник.А_КонтурыСверкиБаз КАК К
ГДЕ
	НЕ К.ПометкаУдаления
УПОРЯДОЧИТЬ ПО
	К.Порядок
"""
try:
    r = q.Execute().Выгрузить()
    print(f"    контуров: {r.Количество()}", flush=True)
    for i in range(r.Количество()):
        row = r.Получить(i)
        print(f"    - {S(row.Наименование)} | плагин={S(row.Плагин)} | план={S(row.План)} | "
              f"ключ=[{S(row.КлючевыеПоля)}] | ссыл=[{S(row.СсылочныеПоля)}] | "
              f"суммы=[{S(row.ПоляСумм)}] | с {row.НачалоПериода} | "
              f"отключен={row.Отключен}", flush=True)
    if r.Количество() >= 4:
        ok("4 контура на месте")
    else:
        fail(f"контуров {r.Количество()}, ожидалось 4")
except Exception as e:
    info = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
    fail(f"запрос контуров: {info}")

# --- E. Состояние данных -----------------------------------------------------
print("\n=== E. Состояние данных ДО работ ===", flush=True)


def count_of(reg, alias):
    qq = erp.NewObject("Запрос")
    qq.Text = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.{reg} КАК {alias}"
    return int(qq.Execute().Выгрузить().Получить(0).К)


n_prav = count_of("А_ПравилаКлассификацииСверкиБаз", "Прав")
if n_prav == 0:
    ok("РС А_ПравилаКлассификацииСверкиБаз ПУСТ (seed требуется — как и ожидалось)")
else:
    warn(f"РС А_ПравилаКлассификацииСверкиБаз: {n_prav} записей (ожидался 0)")

n_iskl = count_of("А_ИсключенияСверкиБаз", "Искл")
print(f"    РС А_ИсключенияСверкиБаз: {n_iskl} записей", flush=True)
if n_iskl:
    q3 = erp.NewObject("Запрос")
    q3.Text = """
ВЫБРАТЬ
	Искл.Контур.Наименование КАК Контур,
	Искл.КлючСтроки КАК Ключ,
	Искл.Причина КАК Причина,
	Искл.Комментарий КАК Комментарий
ИЗ
	РегистрСведений.А_ИсключенияСверкиБаз КАК Искл
"""
    r3 = q3.Execute().Выгрузить()
    for i in range(r3.Количество()):
        row = r3.Получить(i)
        print(f"      [{S(row.Контур)}] {S(row.Ключ)} | {str(S(row.Причина))[:70]} | "
              f"{str(S(row.Комментарий))[:40]}", flush=True)

# журнал ЦВБ
q4 = erp.NewObject("Запрос")
q4.Text = """
ВЫБРАТЬ
	КОЛИЧЕСТВО(*) КАК Всего,
	МАКСИМУМ(Ж.ДатаСеанса) КАК Последний,
	МИНИМУМ(Ж.ДатаСеанса) КАК Первый
ИЗ
	РегистрСведений.А_ЖурналВыравниванияБаз КАК Ж
"""
r4 = q4.Execute().Выгрузить().Получить(0)
print(f"    Журнал ЦВБ: записей={r4.Всего}, период сеансов {r4.Первый} .. {r4.Последний}",
      flush=True)

q5 = erp.NewObject("Запрос")
q5.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	Ж.ДатаСеанса КАК ДатаСеанса
ИЗ
	РегистрСведений.А_ЖурналВыравниванияБаз КАК Ж
УПОРЯДОЧИТЬ ПО
	ДатаСеанса УБЫВ
"""
r5 = q5.Execute().Выгрузить()
print(f"    Сеансов (различных ДатаСеанса): {r5.Количество()}; последние 5:", flush=True)
for i in range(min(5, r5.Количество())):
    print(f"      {r5.Получить(i).ДатаСеанса}", flush=True)

# Артефакты аварии прошлой сессии (60 списаний-фантомов, помеченных на удаление).
# Опознаются НЕ по номеру (номера 000Ц-000778..782 заняты легальными документами
# 04-06.08 — «Перечисление ДС на другой счет»), а по паре признаков:
# помечено на удаление И/ИЛИ дата документа > даты снимка (07.08.2026 12:06).
q6 = erp.NewObject("Запрос")
q6.Text = """
ВЫБРАТЬ
	МАКСИМУМ(Сп.Номер) КАК МаксНомер,
	КОЛИЧЕСТВО(*) КАК Всего,
	СУММА(ВЫБОР КОГДА Сп.ПометкаУдаления ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Помеченных,
	МАКСИМУМ(Сп.Дата) КАК МаксДата
ИЗ
	Документ.СписаниеБезналичныхДенежныхСредств КАК Сп
ГДЕ
	Сп.Номер ПОДОБНО "000Ц-%"
"""
row6 = q6.Execute().Выгрузить().Получить(0)
print(f"    Серия 000Ц-: всего={row6.Всего}, макс номер={S(row6.МаксНомер)}, "
      f"помеченных={row6.Помеченных}, макс дата={row6.МаксДата}", flush=True)
if int(row6.Помеченных) == 0 and str(S(row6.МаксНомер)) <= "000Ц-000782":
    ok("артефактов аварии (60 помеченных списаний) НЕТ — снимок до data-операций")
else:
    warn(f"проверить серию 000Ц-: помеченных={row6.Помеченных}, "
         f"макс номер={S(row6.МаксНомер)} (ожидалось 0 и <=000Ц-000782)")

# ориентир: последний документ базы (насколько свежие данные)
q7 = erp.NewObject("Запрос")
q7.Text = """
ВЫБРАТЬ
	МАКСИМУМ(Сп.Дата) КАК МаксДата
ИЗ
	Документ.СписаниеБезналичныхДенежныхСредств КАК Сп
"""
print(f"    Последнее СписаниеБезналичных: {q7.Execute().Выгрузить().Получить(0).МаксДата}",
      flush=True)

# галочки Воронцова (пункт 4 из промта — проверить, не потерялись ли)
q8 = erp.NewObject("Запрос")
q8.Text = """
ВЫБРАТЬ
	Д.Наименование КАК Наименование,
	Д.Контрагент.Наименование КАК Контрагент,
	Д.А_ИсключитьиЗПроверкиСБухУчетом КАК Исключить
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	Д.Контрагент.Наименование ПОДОБНО "%оронцов%"
	И НЕ Д.ПометкаУдаления
УПОРЯДОЧИТЬ ПО
	Наименование
"""
r8 = q8.Execute().Выгрузить()
n_on = sum(1 for i in range(r8.Количество()) if r8.Получить(i).Исключить)
print(f"    Договоры Воронцова: {r8.Количество()}, галочка А_ИсключитьиЗПроверкиСБухУчетом "
      f"стоит у {n_on}", flush=True)
for i in range(r8.Количество()):
    row = r8.Получить(i)
    print(f"      [{'X' if row.Исключить else ' '}] {S(row.Наименование)}", flush=True)

# --- Итог --------------------------------------------------------------------
print("\n=== ИТОГ ===", flush=True)
print(f"  FAIL: {len(FAILS)}, WARN: {len(WARNS)}", flush=True)
for f in FAILS:
    print(f"    FAIL: {f}", flush=True)
for w in WARNS:
    print(f"    WARN: {w}", flush=True)

erp = None
print("SMOKE DONE" if not FAILS else "SMOKE FAILED", flush=True)
sys.exit(1 if FAILS else 0)
