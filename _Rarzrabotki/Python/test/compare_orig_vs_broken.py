"""Сравнение Оригинал 000Ц-000109 (Поступление) vs неисправл 000Ц-000228 (Списание)
по 6 регистрам + СтДДС в РП."""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def найти(имя_типа, номер):
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Номер", номер)
    qq.Текст = f'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.{имя_типа} КАК Д ГДЕ Д.Номер = &Номер УПОРЯДОЧИТЬ ПО Д.Дата'
    r = qq.Выполнить().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() else None


def дамп(док, метка):
    obj = док.ПолучитьОбъект()
    print(f"\n{'='*100}", flush=True)
    print(f"{метка}: {S(док)}  | Σ={obj.СуммаДокумента}  | Хозоп={S(obj.ХозяйственнаяОперация)}", flush=True)
    print(f"  Подразделение={('пусто' if obj.Подразделение is None or obj.Подразделение.Пустая() else S(obj.Подразделение))}, "
          f"А_ВведенВЕРП={obj.А_ВведенВЕРП}, А_Обработан={obj.А_Обработан}", flush=True)

    # РП — СтДДС
    print(f"\n  РП ({obj.РасшифровкаПлатежа.Количество()} строк):", flush=True)
    for i in range(obj.РасшифровкаПлатежа.Количество()):
        рп = obj.РасшифровкаПлатежа.Получить(i)
        стдс = "пусто" if рп.СтатьяДвиженияДенежныхСредств is None or рп.СтатьяДвиженияДенежныхСредств.Пустая() else S(рп.СтатьяДвиженияДенежныхСредств)
        ор = "пусто" if рп.ОбъектРасчетов is None or рп.ОбъектРасчетов.Пустая() else S(рп.ОбъектРасчетов)
        дог = "пусто" if not hasattr(рп, 'А_Договор') or рп.А_Договор is None or рп.А_Договор.Пустая() else S(рп.А_Договор)
        print(f"    Стр{i+1}: СтДДС={стдс}, ОР={ор}, А_Дог={дог}, Σ={рп.Сумма}", flush=True)

    # Движения по 6 регистрам
    print(f"\n  Движения:", flush=True)
    for имя in ["РасчетыСКлиентами", "РасчетыСПоставщиками",
                "РасчетыСКлиентамиПоСрокам", "РасчетыСПоставщикамиПоСрокам",
                "ДенежныеСредстваБезналичные", "ПрочиеАктивыПассивы"]:
        qq = erp.NewObject("Запрос")
        qq.УстановитьПараметр("Рег", док)
        qq.Текст = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.{имя} ГДЕ Регистратор = &Рег"
        try:
            k = int(qq.Выполнить().Выгрузить().Получить(0).К)
            print(f"    {имя:<40}: {k}", flush=True)
        except Exception:
            print(f"    {имя:<40}: ОШИБКА", flush=True)

    # Детальные ПАП-движения если есть
    if True:
        qq = erp.NewObject("Запрос")
        qq.УстановитьПараметр("Рег", док)
        qq.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ВидДвижения) КАК ВД,
    ПРЕДСТАВЛЕНИЕ(Р.Статья) КАК Статья,
    ПРЕДСТАВЛЕНИЕ(Р.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Р.Источник) КАК Источник,
    Р.Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Р
ГДЕ Р.Регистратор = &Рег
"""
        try:
            r = qq.Выполнить().Выгрузить()
            print(f"    ПАП детально: {r.Количество()} строк", flush=True)
            for i in range(r.Количество()):
                rec = r.Получить(i)
                print(f"      {str(rec.ВД):<8} | Статья={str(rec.Статья)[:30]:<30} | Подр={str(rec.Подр)[:14]:<14} | Источник={str(rec.Источник)[:25]:<25} | Σ={float(rec.Сумма):>13,.2f}", flush=True)
        except Exception as e:
            pass


# Оригинал
ориг = найти("ПоступлениеБезналичныхДенежныхСредств", "000Ц-000109")
