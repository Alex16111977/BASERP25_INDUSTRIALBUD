def find_discrepancies(erp, buh):
    """FULL OUTER JOIN и поиск расхождений (как СвестиТаблицы_Товары)"""
    all_keys = set(list(erp.keys()) + list(buh.keys()))
    disc = []
    for key in all_keys:
        e = erp.get(key, {'НачОст': 0, 'Приход': 0, 'Расход': 0, 'КонОст': 0})
        b = buh.get(key, {'НачОст': 0, 'Приход': 0, 'Расход': 0, 'КонОст': 0})
        d_n = round(e['НачОст'] - b['НачОст'], 3)
        d_p = round(e['Приход'] - b['Приход'], 3)
        d_r = round(e['Расход'] - b['Расход'], 3)
        d_k = round(e['КонОст'] - b['КонОст'], 3)
        if d_n == 0 and d_p == 0 and d_r == 0 and d_k == 0:
            continue
        nom = e.get('НомНаим', '') or b.get('НомНаим', '')
        skl = e.get('СклНаим', '') or b.get('СклНаим', '')
        disc.append({
            'key': key, 'nom': nom, 'skl': skl,
            'erp_k': e['КонОст'], 'buh_k': b['КонОст'], 'razn': d_k,
        })
    return disc


