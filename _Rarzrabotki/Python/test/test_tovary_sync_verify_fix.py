def get_erp_balances(conn_erp, start, end):
    """ERP остатки БЕЗ фильтра по типу (как после исправления)"""
    q = conn_erp.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ "
        "  Т.Номенклатура.А_ИдКод КАК НомИдКод, "
        "  ПРЕДСТАВЛЕНИЕ(Т.Номенклатура) КАК НомНаим, "
        "  Т.Склад.А_ИдКод КАК СклИдКод, "
        "  ПРЕДСТАВЛЕНИЕ(Т.Склад) КАК СклНаим, "
        "  Т.ВНаличииНачальныйОстаток КАК НачОст, "
        "  Т.ВНаличииПриход КАК Приход, "
        "  Т.ВНаличииРасход КАК Расход, "
        "  Т.ВНаличииКонечныйОстаток КАК КонОст "
        "ИЗ "
        "  РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты("
        "    &НачалоПериода, &КонецПериода, , , ) КАК Т"
    )
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(start))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(end))

    result = {}
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        nom_id = str(sel.НомИдКод).strip()
        skl_id = str(sel.СклИдКод).strip()
        key = nom_id + "|" + skl_id
        if key in result:
            result[key]['НачОст'] += float(sel.НачОст or 0)
            result[key]['Приход'] += float(sel.Приход or 0)
            result[key]['Расход'] += float(sel.Расход or 0)
            result[key]['КонОст'] += float(sel.КонОст or 0)
        else:
            result[key] = {
                'НомНаим': str(sel.НомНаим), 'СклНаим': str(sel.СклНаим),
                'НачОст': float(sel.НачОст or 0), 'Приход': float(sel.Приход or 0),
                'Расход': float(sel.Расход or 0), 'КонОст': float(sel.КонОст or 0),
            }
    return result


