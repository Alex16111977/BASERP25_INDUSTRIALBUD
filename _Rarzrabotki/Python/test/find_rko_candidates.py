# -*- coding: utf-8 -*-
"""Discovery: знайти всі РКО за дек 2025 з рухами ПАП(ОТ, Источник=Пуст).

Зберегти список у rko_candidates.json для verify-тесту.
Також зробити мікро-discovery по тестовому документу — які поля заповнені
(Ведомость / ВыплатаЗаработнойПлаты / РасшифровкаПлатежа / Подразделение).
"""
import sys, io, json
from datetime import datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Параметри
qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

print(f"[INFO] ОТ={ОТ}, ORG={ORG}")

# Період: дек 2025 + янв-фев 2026 (для перевірки)
НМ = datetime(2025, 12, 1, 12, 0, 0)
КД = datetime(2026, 3, 1, 12, 0, 0)  # ексклюзив

# 1) Знайти всі РКО з рухами ПАП(ОТ, Источник=Пуст)
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    ПАП.Регистратор КАК Док,
    МАКСИМУМ(ПАП.Регистратор.Номер) КАК Номер,
    МАКСИМУМ(ПАП.Регистратор.Дата) КАК Дата,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Σ_signed,
    СУММА(ПАП.Сумма) КАК Σ_abs
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Период МЕЖДУ &НМ И &КД
    И ПАП.Организация = &Орг
    И ПАП.Статья = &ОТ
    И ПАП.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И ТИПЗНАЧЕНИЯ(ПАП.Регистратор) = ТИП(Документ.РасходныйКассовыйОрдер)
СГРУППИРОВАТЬ ПО
    ПАП.Регистратор
УПОРЯДОЧИТЬ ПО Дата
"""
q.УстановитьПараметр("НМ", НМ)
q.УстановитьПараметр("КД", КД)
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("ОТ", ОТ)

res = q.Выполнить().Выгрузить()
print(f"[INFO] Знайдено РКО з ПАП(ОТ): {res.Количество()}")

candidates = []
for i in range(res.Количество()):
    r = res.Получить(i)
    док = r.Док
    uuid = str(док.УникальныйИдентификатор())
    candidates.append({
        "uuid": uuid,
        "number": r.Номер.strip(),
        "date": r.Дата.isoformat(),
        "sigma_signed": float(r.Σ_signed),
        "sigma_abs": float(r.Σ_abs),
    })
    print(f"  №{r.Номер.strip()} від {r.Дата.strftime('%Y-%m-%d')}: Σ_signed={r.Σ_signed:>14,.2f} Σ_abs={r.Σ_abs:>14,.2f}")

# Поділ дек/янв/фев
def month_count(month_str):
    return len([c for c in candidates if c["date"][:7] == month_str])
print(f"\n[INFO] За дек 2025: {month_count('2025-12')}; янв 2026: {month_count('2026-01')}; фев 2026: {month_count('2026-02')}")

# 2) Мікро-discovery по першому документу — які поля заповнені
if candidates:
    test_uuid = candidates[0]["uuid"]
    uuid_obj = conn.NewObject("УникальныйИдентификатор", test_uuid)
    test_ref = conn.Документы.РасходныйКассовыйОрдер.ПолучитьСсылку(uuid_obj)
    test_obj = test_ref.ПолучитьОбъект()
    print(f"\n[INFO] Тестовий доку №{candidates[0]['number']} ({candidates[0]['date'][:10]}):")
    print(f"  ХозОп               = {test_obj.ХозяйственнаяОперация}")
    print(f"  Подразделение       = {test_obj.Подразделение}")
    print(f"  Ведомость           = {test_obj.Ведомость}")
    print(f"  СуммаДокумента      = {test_obj.СуммаДокумента}")
    print(f"  ТЧ ВыплатаЗП рядків = {test_obj.ВыплатаЗаработнойПлаты.Количество()}")
    print(f"  ТЧ РасшПлатежа рядків = {test_obj.РасшифровкаПлатежа.Количество()}")

    # Якщо ВыплатаЗП заповнено — показати
    тч = test_obj.ВыплатаЗаработнойПлаты
    if тч.Количество() > 0:
        print(f"\n  [TC ВыплатаЗП] заповнено {тч.Количество()} рядків:")
        for j in range(min(3, тч.Количество())):
            рядок = тч.Получить(j)
            print(f"    {рядок.ФизическоеЛицо} — {рядок.Сумма}")
        sum_тч = sum(float(тч.Получить(j).Сумма) for j in range(тч.Количество()))
        print(f"    Σ ТЧ = {sum_тч:.2f}")

# 3) Зведена аналітика по 3 ХозОпераціям
print(f"\n[INFO] Зведена розкладка по ХозОпераціям...")
qX = conn.NewObject("Запрос")
qX.Текст = """
ВЫБРАТЬ
    ПАП.Регистратор.ХозяйственнаяОперация КАК ХозОп,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ПАП.Регистратор) КАК Кво_доків,
    СУММА(ПАП.Сумма) КАК Σ_abs
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Период МЕЖДУ &НМ И &КД
    И ПАП.Организация = &Орг
    И ПАП.Статья = &ОТ
    И ПАП.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И ТИПЗНАЧЕНИЯ(ПАП.Регистратор) = ТИП(Документ.РасходныйКассовыйОрдер)
СГРУППИРОВАТЬ ПО
    ПАП.Регистратор.ХозяйственнаяОперация
"""
qX.УстановитьПараметр("НМ", НМ)
qX.УстановитьПараметр("КД", КД)
qX.УстановитьПараметр("Орг", ORG)
qX.УстановитьПараметр("ОТ", ОТ)
rX = qX.Выполнить().Выгрузить()
for i in range(rX.Количество()):
    r = rX.Получить(i)
    print(f"  {r.ХозОп}: {r.Кво_доків} доків, Σ={r.Σ_abs:,.2f}")

# Зберегти JSON
out_path = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test\rko_candidates.json"
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(candidates, f, ensure_ascii=False, indent=2)
print(f"\n[OK] Збережено: {out_path} — {len(candidates)} кандидатів")
