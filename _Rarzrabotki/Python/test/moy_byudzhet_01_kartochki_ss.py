# -*- coding: utf-8 -*-
"""Аудит п.1–2: нормы на дом из карточек СС и бюджет объекта для проектов без карточки.

Карточка (Справочник.А_СтруктураСебестоимости, активная, не помеченная): цена дома с НДС, домов по договору,
на ОДИН дом — Комплектующие (статья ДДС пуста везде -> УТ-001067), Работы «чол/год» (ЗП, Ф2) и прочие
(-> УТ-001068 если статьи нет), Общепроизводственные (раздел IX) по статьям — свёрнуты по (статья,
наименование) БЕЗ сложения дублей: карточка 000000011 загружена дважды (50 строк вместо 25).
Бюджет объекта: РН.А_БюджетыНаМесяц, ВидПериода = Объект, по Подразделение + Статья (без Направления/Месяца).
Вывод: data/kartochki_ss.json, data/byudzhet_obekta.json.
"""
import collections
from moy_byudzhet_common import *

pm, root = projects()
art = articles()
erp = conn()

t = query("""ВЫБРАТЬ К.Ссылка КАК Ссылка, К.Код КАК Код, К.Наименование КАК Имя, К.Подразделение КАК Подр,
    К.ЦенаДомаСНДС КАК Цена, К.КоличествоДомов КАК Домов
ИЗ Справочник.А_СтруктураСебестоимости КАК К ГДЕ НЕ К.ПометкаУдаления И К.Активная""")
cards = {}
for i in range(t.Количество()):
    r = t.Получить(i)
    pu = uid(r.Подр) if erp.ЗначениеЗаполнено(r.Подр) else ""
    p = pm.get(pu, {"uid": "", "name": "?", "dept": S(r.Подр)})
    cards[uid(r.Ссылка)] = {"code": S(r.Код).strip(), "name": S(r.Имя).strip(), "proj": p["uid"], "projname": p["name"],
                            "dept": p["dept"], "price": float(r.Цена), "houses": float(r.Домов),
                            "materials": 0.0, "labor_f2": 0.0, "works_other": {}, "opr": {}, "labor_rows": 0}

t = query("""ВЫБРАТЬ Т.Ссылка КАК К, СУММА(Т.Сумма) КАК Сумма, КОЛИЧЕСТВО(*) КАК Строк
ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК Т ГДЕ НЕ Т.Ссылка.ПометкаУдаления И Т.Ссылка.Активная
СГРУППИРОВАТЬ ПО Т.Ссылка""")
for i in range(t.Количество()):
    r = t.Получить(i)
    cards[uid(r.К)]["materials"] = float(r.Сумма)

t = query("""ВЫБРАТЬ Т.Ссылка КАК К, СОКРЛП(Т.Единица.Наименование) КАК Ед, Т.СтатьяДДС КАК Ст,
    СУММА(Т.Сумма) КАК Сумма, КОЛИЧЕСТВО(*) КАК Строк
ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Т ГДЕ НЕ Т.Ссылка.ПометкаУдаления И Т.Ссылка.Активная
СГРУППИРОВАТЬ ПО Т.Ссылка, СОКРЛП(Т.Единица.Наименование), Т.СтатьяДДС""")
for i in range(t.Количество()):
    r = t.Получить(i)
    c = cards[uid(r.К)]
    if S(r.Ед) == "чол/год":
        c["labor_f2"] += float(r.Сумма)
        c["labor_rows"] += int(r.Строк)
    else:
        code = art[uid(r.Ст)]["code"] if erp.ЗначениеЗаполнено(r.Ст) else "УТ-001068"
        c["works_other"][code] = c["works_other"].get(code, 0.0) + float(r.Сумма)

t = query("""ВЫБРАТЬ Т.Ссылка КАК К, Т.СтатьяДДС КАК Ст, СОКРЛП(ВЫРАЗИТЬ(Т.Наименование КАК СТРОКА(200))) КАК Имя,
    МАКСИМУМ(Т.СуммаНаДом) КАК Сумма, КОЛИЧЕСТВО(*) КАК Строк
ИЗ Справочник.А_СтруктураСебестоимости.Общепроизводственные КАК Т
ГДЕ НЕ Т.Ссылка.ПометкаУдаления И Т.Ссылка.Активная И Т.СуммаНаДом <> 0
СГРУППИРОВАТЬ ПО Т.Ссылка, Т.СтатьяДДС, СОКРЛП(ВЫРАЗИТЬ(Т.Наименование КАК СТРОКА(200)))""")
for i in range(t.Количество()):
    r = t.Получить(i)
    c = cards[uid(r.К)]
    code = art[uid(r.Ст)]["code"] if erp.ЗначениеЗаполнено(r.Ст) else "?"
    c["opr"].setdefault(code, []).append({"name": S(r.Имя), "sum": float(r.Сумма), "dup": int(r.Строк)})
save("kartochki_ss.json", {"stamp": snapshot_stamp(), "cards": cards})

print(f"{'код':<10} {'карточка':<40} {'проект':<22} {'цена':>14} {'дом':>4} {'матер/дом':>12} {'ЗП Ф2/дом':>11} {'ОПР/дом':>10}")
for u, c in sorted(cards.items(), key=lambda x: x[1]["code"]):
    opr = sum(x["sum"] for v in c["opr"].values() for x in v)
    print(f"{c['code']:<10} {c['name'][:40]:<40} {c['projname'][:22]:<22} {fmt(c['price']):>14} {c['houses']:>4.0f} "
          f"{fmt(c['materials']):>12} {fmt(c['labor_f2']):>11} {fmt(opr):>10}  прочие работы {c['works_other']}")
    for code, lst in c["opr"].items():
        print(f"      ОПР {code}: " + "; ".join(f"{x['name'][:30]} {fmt(x['sum'])}{' ×' + str(x['dup']) if x['dup'] > 1 else ''}" for x in lst))

# бюджет объекта (лимит на весь срок)
t = query("""ВЫБРАТЬ Б.Подразделение КАК Подр, Б.СтатьяДвиженияДенежныхСредств КАК Статья, Б.ВидОплаты КАК Вид,
    СУММА(Б.Сумма) КАК Сумма, МАКСИМУМ(Б.Регистратор.Дата) КАК Свежесть
ИЗ РегистрНакопления.А_БюджетыНаМесяц КАК Б
ГДЕ Б.ВидПериода = ЗНАЧЕНИЕ(Перечисление.А_ВидыПериодовБюджетирования.Объект)
  И Б.Подразделение В ИЕРАРХИИ (ВЫБРАТЬ П.Ссылка ИЗ Справочник.СтруктураПредприятия КАК П ГДЕ П.Код = &Корень)
СГРУППИРОВАТЬ ПО Б.Подразделение, Б.СтатьяДвиженияДенежныхСредств, Б.ВидОплаты""", Корень=ROOT_CODE)
bo = []
for i in range(t.Количество()):
    r = t.Получить(i)
    p = pm[uid(r.Подр)]
    a = art.get(uid(r.Статья), {"code": "", "name": "<без статьи>", "type": ""}) if erp.ЗначениеЗаполнено(r.Статья) else {"code": "", "name": "<без статьи>", "type": ""}
    bo.append({"proj": p["uid"], "projname": p["name"], "art": a["code"], "artname": a["name"], "dir": a["type"],
               "type": S(r.Вид), "sum": float(r.Сумма), "fresh": ymd(r.Свежесть)})
save("byudzhet_obekta.json", {"stamp": snapshot_stamp(), "rows": bo})
agg = collections.defaultdict(lambda: [0.0, 0.0, ""])
for r in bo:
    a = agg[r["projname"]]
    a[0 if r["dir"] == "Приход" else 1] += r["sum"]
    a[2] = max(a[2], r["fresh"])
print("\nБюджет объекта (ВидПериода = Объект): проект | поступления | выплаты | свежесть")
for p, (inc, out, fr) in sorted(agg.items()):
    print(f"  {p[:32]:<32} {fmt(inc):>16} {fmt(out):>16}  {fr}")
