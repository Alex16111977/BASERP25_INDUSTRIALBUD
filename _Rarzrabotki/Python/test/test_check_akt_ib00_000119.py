"""Перевірити Акт виконаних робіт ІБ00-000119 — стан проведення і рухи."""
import win32com.client
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# 1) Знайти документ
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Ссылка,
    ПРЕДСТАВЛЕНИЕ(Ссылка) КАК Предст,
    Дата,
    Номер,
    Проведен,
    ПометкаУдаления,
    ПРЕДСТАВЛЕНИЕ(Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Контрагент) КАК Контр,
    СуммаДокумента,
    А_Обработан,
    А_ВведенВЕРП
ИЗ Документ.АктВыполненныхРабот
ГДЕ Номер = "ІБ00-000119"
"""
r = q.Execute().Выгрузить()
print(f"Знайдено документів з номером ІБ00-000119: {r.Количество()}")
for i in range(r.Количество()):
    row = r.Получить(i)
    print(f"\n[{i+1}] {row.Предст}")
    print(f"    Дата: {row.Дата}")
    print(f"    Проведен: {row.Проведен}")
    print(f"    ПометкаУдаления: {row.ПометкаУдаления}")
    print(f"    Подр: {row.Подр}")
    print(f"    Контр: {row.Контр}")
    print(f"    СуммаДокумента: {row.СуммаДокумента}")
    print(f"    А_Обработан: {row.А_Обработан}")
    print(f"    А_ВведенВЕРП: {row.А_ВведенВЕРП}")

if r.Количество() == 0:
    print("\nDocument not found — searching by number pattern...")
    q2 = erp.NewObject("Запрос")
    q2.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 10
        ПРЕДСТАВЛЕНИЕ(Ссылка) КАК Предст,
        Номер,
        Дата,
        Проведен
    ИЗ Документ.АктВыполненныхРабот
    ГДЕ Номер ПОДОБНО "%119%"
        И Дата МЕЖДУ ДАТАВРЕМЯ(2026,2,1) И ДАТАВРЕМЯ(2026,3,1)
    """
    r2 = q2.Execute().Выгрузить()
    print(f"  За шаблоном '*119*' за лютий: {r2.Количество()}")
    for i in range(r2.Количество()):
        row = r2.Получить(i)
        print(f"    {row.Предст}  Проведен={row.Проведен}")
    sys.exit(0)

# 2) Перевіряємо рухи документа в регістрі
ref = r.Получить(0).Ссылка
print(f"\n--- Рухи в РегистрНакопления.ВыручкаИСебестоимостьПродаж ---")
q3 = erp.NewObject("Запрос")
q3.Text = """
ВЫБРАТЬ
    Период,
    Активность,
    ПРЕДСТАВЛЕНИЕ(Регистратор) КАК Рег,
    ПРЕДСТАВЛЕНИЕ(Подразделение) КАК Подр,
    СуммаВыручки,
    СуммаВыручкиБезНДС
ИЗ РегистрНакопления.ВыручкаИСебестоимостьПродаж
ГДЕ Регистратор = &Док
"""
q3.SetParameter("Док", ref)
r3 = q3.Execute().Выгрузить()
print(f"Записів у регістрі за цим документом: {r3.Количество()}")
for i in range(r3.Количество()):
    row = r3.Получить(i)
    print(f"  [{i+1}] {row.Период}  Активн={row.Активность}  "
          f"СуммаВыручки={row.СуммаВыручки:,.2f}  Подр={row.Подр}")
