# -*- coding: utf-8 -*-
"""
Финальный тест: сравнение РасчетыСКлиентами vs РасчетыСКлиентамиПоСрокам
для Контрагент=Глобино-2 на 31.12.2025.

Гипотеза: отчёт «Сводная ведомость расчётов» (9 094 109,88) берёт ПоСрокам,
а РасчетыСКлиентами (7 421 354,86) рассинхронизирован на 1 672 755,02.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

КМ = datetime.datetime(2025, 12, 31, 23, 59, 59)

q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
орг = q.Выполнить().Выгрузить().Получить(0).Ссылка

q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты ГДЕ Наименование = "Глобино-2"'
контр_глобино = q.Выполнить().Выгрузить().Получить(0).Ссылка

print("=" * 110)
print("СРАВНЕНИЕ ДВУХ РЕГИСТРОВ ВЗАИМОРАСЧЁТОВ для Контрагент=Глобино-2 на 31.12.2025")
print("=" * 110)

# === [A] РасчетыСКлиентами (старый) ===
print("\n[A] РегистрНакопления.РасчетыСКлиентами")
print("-" * 110)
qA = erp.NewObject("Запрос")
qA.УстановитьПараметр("КМ", КМ)
qA.УстановитьПараметр("Орг", орг)
qA.УстановитьПараметр("Контр", контр_глобино)
qA.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК ПартнерИмя,
    СУММА(Р.СуммаОстаток) КАК КО
ИЗ
    РегистрНакопления.РасчетыСКлиентами.Остатки(&КМ, ) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И АП.Контрагент = &Контр
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов, АП.Партнер
ИМЕЮЩИЕ СУММА(Р.СуммаОстаток) <> 0
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
rA = qA.Выполнить().Выгрузить()
sumA = 0
for i in range(rA.Количество()):
    rec = rA.Получить(i)
    ко = float(rec.КО)
    sumA += ко
    print(f"   {str(rec.ОРИмя)[:48]:<48} | Партнёр={str(rec.ПартнерИмя)[:20]:<20} | КО={ко:>15,.2f}")
print(f"   {'Σ РасчетыСКлиентами':<48} | {' ':>30} | КО={sumA:>15,.2f}")

# === [B] РасчетыСКлиентамиПоСрокам (новый, балансовый) ===
print("\n[B] РегистрНакопления.РасчетыСКлиентамиПоСрокам — поле ДолгУпр")
print("-" * 110)
qB = erp.NewObject("Запрос")
qB.УстановитьПараметр("КМ", КМ)
qB.УстановитьПараметр("Орг", орг)
qB.УстановитьПараметр("Контр", контр_глобино)
qB.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК ПартнерИмя,
    СУММА(Р.ДолгУпрОстаток) КАК ДолгКО,
    СУММА(Р.ПредоплатаУпрОстаток) КАК ПредоплКО
ИЗ
    РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(&КМ, ) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И АП.Контрагент = &Контр
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов, АП.Партнер
ИМЕЮЩИЕ СУММА(Р.ДолгУпрОстаток) <> 0 ИЛИ СУММА(Р.ПредоплатаУпрОстаток) <> 0
УПОРЯДОЧИТЬ ПО ДолгКО УБЫВ
"""
rB = qB.Выполнить().Выгрузить()
sumDolg = 0
sumPred = 0
for i in range(rB.Количество()):
    rec = rB.Получить(i)
    dолг = float(rec.ДолгКО)
    pred = float(rec.ПредоплКО)
    sumDolg += dолг
    sumPred += pred
    print(f"   {str(rec.ОРИмя)[:42]:<42} | Партнёр={str(rec.ПартнерИмя)[:18]:<18} | Долг={dолг:>13,.2f} | Пред={pred:>13,.2f}")
print(f"   {'Σ Долг':<42} | {sumDolg:>15,.2f}")
print(f"   {'Σ Предоплата':<42} | {sumPred:>15,.2f}")
print(f"   {'Σ Сальдо (Долг − Предоплата)':<42} | {sumDolg - sumPred:>15,.2f}")

# === Сравнение
print("\n" + "=" * 110)
print("СРАВНЕНИЕ:")
print(f"   [A] РасчетыСКлиентами              КО = {sumA:>15,.2f}")
print(f"   [B] РасчетыСКлиентамиПоСрокам Долг = {sumDolg:>15,.2f}")
print(f"   [B] РасчетыСКлиентамиПоСрокам Предопл = {sumPred:>15,.2f}")
print(f"   [B] РасчетыСКлиентамиПоСрокам Сальдо= {sumDolg - sumPred:>15,.2f}")
print(f"   [скриншот «Сводная ведомость»]      = 9 094 109.88")
print(f"\n   ΔA−B(Долг): {sumA - sumDolg:>15,.2f}")
print(f"   Δскриншот−A: {9094109.88 - sumA:>15,.2f}")
print(f"   Δскриншот−B(Долг): {9094109.88 - sumDolg:>15,.2f}")
print("=" * 110)
