    print(f"  Код={str(s.Код):<8}|Наим={str(s.Наим):<24}|ИмяПД={str(s.ИмяПД):<22}|АктивПассив={ап:<12}|БезАнал={s.БезАн}|Типы={str(s.ТЗ)}")

