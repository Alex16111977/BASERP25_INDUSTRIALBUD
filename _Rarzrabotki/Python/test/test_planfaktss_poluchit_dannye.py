# -*- coding: utf-8 -*-
"""ПолучитьДанные отчёта ПланФактСС возвращает грейн с ожидаемыми колонками, типами и эталонами."""
import os
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\ПланФактССБухгалтерія.erf"
CONN = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'

ЭТАЛОН_ПЛАН_IRS = 11296725.24
ЭТАЛОН_ФАКТ_IRS = 4603160.77  # снято 04.09.2026: документы по 31.07 добавлены задним числом после 06.08 (было 4595459.79)

ОЖИДАЕМЫЕ_КОЛОНКИ = [
    "Подразделение", "Категория", "Этап", "ОбщееНазвание", "Аналитика", "Номенклатура", "Единица", "Документ",
    "ПланКол", "ЦенаПлан", "ПланГрн", "ФактКол", "ЦенаФакт", "ФактГрн",
    "ОтклонениеКол", "ОтклонениеГрн", "ПроцентКол", "ПроцентГрн",
    "ПланНаФактГрн", "ПрогнозГрн", "ОтклонениеПрогнозГрн", "ПроцентПрогнозГрн",
]


def лат(s):
    return s.replace("\u0421", "C").replace("\u0441", "c")


def main():
    assert os.path.exists(ERF), f"Не собран .erf: {ERF}"

    v8 = win32com.client.Dispatch("V83.COMConnector")
    b = v8.Connect(CONN)
    отчёт = b.ВнешниеОтчеты.Создать(ERF)

    период = b.NewObject("СтандартныйПериод")
    z = b.NewObject("Запрос")
    z.Текст = "ВЫБРАТЬ КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2026, 7, 31), ДЕНЬ) КАК К"
    период.ДатаОкончания = z.Выполнить().Выгрузить()[0].К

    тз = отчёт.ПолучитьДанные(период)
    assert тз.Количество() > 0, "ПолучитьДанные вернул пустую таблицу"

    колонки = [c.Имя for c in тз.Колонки]
    assert колонки == ОЖИДАЕМЫЕ_КОЛОНКИ, f"Состав колонок разошёлся: {колонки}"

    план = факт = 0.0
    план_строк = факт_строк = синтетика = 0
    for i in range(тз.Количество()):
        r = тз[i]
        assert isinstance(r.Аналитика, str), f"Аналитика не строка в строке {i}: {type(r.Аналитика)}"
        факт_ли = (r.ФактКол != 0) or (r.ФактГрн != 0)
        план_ли = (r.ПланКол != 0) or (r.ПланГрн != 0)
        if факт_ли:
            факт_строк += 1
            assert not r.Номенклатура.Пустая(), f"Факт без Номенклатуры: {r.Аналитика!r}"
            assert r.Аналитика == r.Номенклатура.Наименование.strip(), (
                f"Факт: {r.Аналитика!r} != {r.Номенклатура.Наименование.strip()!r}")
        elif план_ли:
            план_строк += 1
            assert r.Номенклатура.Пустая(), f"План с Номенклатурой: {r.Аналитика!r}"
            assert r.Аналитика != "", "План с пустой Аналитикой"
        elif r.ПланНаФактГрн != 0:
            # Синтетическая строка ETC: ни плана, ни факта, только прогноз.
            синтетика += 1
            assert r.Номенклатура.Пустая(), "Синтетическая строка ETC с Номенклатурой"
            assert r.Документ.Пустая(), "Синтетическая строка ETC с Документом"
        if лат(r.Подразделение.Наименование) == "МД IRC 2026":
            план += r.ПланГрн
            факт += r.ФактГрн
    assert abs(план - ЭТАЛОН_ПЛАН_IRS) < 0.01, f"План IRS = {план:,.2f}"
    assert abs(факт - ЭТАЛОН_ФАКТ_IRS) < 0.01, f"Факт IRS = {факт:,.2f}"
    assert план_строк > 0 and факт_строк > 0 and синтетика > 0, (
        f"план_строк={план_строк} факт_строк={факт_строк} синтетика={синтетика}")

    print(f"OK: строк={тз.Количество()} (план {план_строк}, факт {факт_строк}, ETC {синтетика}), "
          f"IRS план={план:,.2f} факт={факт:,.2f}")
    print("ПОЛУЧИТЬДАННЫЕ PASSED")


if __name__ == "__main__":
    main()
