import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Значения перечисления через метаданные (имена!), не через представления
meta = erp.Метаданные.Перечисления.РезультатыВыполненияОбмена
n = meta.ЗначенияПеречисления.Количество()
print(f"Перечисление.РезультатыВыполненияОбмена — {n} значений (Имя | Синоним):")
for i in range(n):
    v = meta.ЗначенияПеречисления.Получить(i)
    print(f"  {v.Имя} | {v.Синоним}")

# Какие результаты реально лежат в регистре
