START_DATE = datetime(2025, 1, 1)
END_DATE = datetime(2026, 1, 1)


def make_time(dt):
    return pywintypes.Time(dt)


def connect_buhbud():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Підключення до BuhBud встановлено")
    return conn


def test_variant(conn, variant_num, description, query_text):
    """Запускає тестовий запит і повертає True/False."""
    print(f"\n{'=' * 80}")
    print(f"ВАРІАНТ {variant_num}: {description}")
    print(f"{'=' * 80}")
    print(f"  Текст запиту:")
    for line in query_text.strip().split("\n"):
        print(f"    {line}")

    query = conn.NewObject("Запрос")
    query.Текст = query_text
    query.УстановитьПараметр("НачалоПериода", make_time(START_DATE))
    query.УстановитьПараметр("КонецПериода", make_time(END_DATE))

    try:
        result = query.Выполнить().Выбрать()
        count = 0
        while result.Следующий():
            count += 1
            if count <= 3:
                try:
                    print(f"    [{count}] Счет:{result.Счет} | НачОст:{result.НачОстДт} | ОбДт:{result.ОбДт} | ОбКт:{result.ОбКт} | КонОст:{result.КонОстДт}")
                except:
                    print(f"    [{count}] (є дані, але формат колонок інший)")
        print(f"  [OK] Варіант {variant_num} ПРАЦЮЄ! Записів: {count}")
        return True
    except Exception as e:
        err_msg = str(e)
        # Скорочуємо повідомлення про помилку
        if "Неверные параметры" in err_msg:
            print(f"  [ПОМИЛКА] Неверные параметры!")
        else:
            print(f"  [ПОМИЛКА] {err_msg[:200]}")
        return False


