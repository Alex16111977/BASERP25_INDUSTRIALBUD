# -*- coding: utf-8 -*-
"""Нарахування відсотків: параметри «Приобретения» і запит наявних ПТУ (план 2026-10-16, Task 5).

Документи в пам'яті, ПТУ не створюються. Код виходу 0 = OK.
"""
import datetime as dt
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ok = True
ORG = erp.Справочники.Организации.НайтиПоНаименованию('ТОВ "ІНДАСТРІАЛБУД"', True)
СП = erp.Перечисления.А_СпособыРасчетаПроцентов
PREF = "%% за использование от кредитора -- "
М = erp.А_НачислениеПроцентовПоКредитамСервер


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


def doc(y, m):
    d = erp.Документы.А_НачислениеПроцентовПоКредитам.СоздатьДокумент()
    d.Организация = ORG
    d.МесяцНачисления = dt.datetime(y, m, 1) + dt.timedelta(hours=3)  # COM −3 год
    d.СпособЗаполнения = СП.ПоВыплате
    d.ЗаполнитьНачисления()
    return d


def row(d, name):
    for i in range(d.Начисления.Количество()):
        if S(d.Начисления.Получить(i).Договор) == PREF + name:
            return d.Начисления.Получить(i)


d9 = doc(2026, 9)
p = М.ПараметрыПриобретения(d9, row(d9, "КРИВОЙ РОГ ЦЕМЕНТ-2"))
ш, т = p.Шапка, p.Товар
check(S(ш.Дата) == "30.09.2026 23:59:59" and S(ш.Договор) == PREF + "КРИВОЙ РОГ ЦЕМЕНТ-2"
      and S(ш.Подразделение) == "КРИВОЙ РОГ ЦЕМЕНТ-2" and float(ш.Курс) == 1 and float(ш.Кратность) == 1
      and ш.А_Обработан and ш.А_ВведенВЕРП and ш.А_Необновлять and S(ш.Контрагент) == "Воронцов Олександр Володимирович"
      and float(ш.СуммаДокумента) == 7550 and float(ш.СуммаВзаиморасчетов) == 7550,
      f"test_parametry_ptu_sentyabr_kr: шапка {S(ш.Дата)}, {S(ш.Подразделение)}, курс {S(ш.Курс)}/{S(ш.Кратность)}")
check(S(т.СтатьяРасходов) == "Послуги банків" and float(т.Сумма) == 7550 and float(т.СуммаСНДС) == 7550
      and S(т.Номенклатура) == "Відсотки за користування позикою" and т.СписатьНаРасходы
      and S(т.Подразделение) == "КРИВОЙ РОГ ЦЕМЕНТ-2" and float(т.СуммаНДС) == 0,
      f"test_parametry_ptu_sentyabr_kr: товар {S(т.Номенклатура)}, {S(т.СтатьяРасходов)}, {S(т.Сумма)}, ПДВ {S(т.СтавкаНДС)}")

d6 = doc(2026, 6)
p6 = М.ПараметрыПриобретения(d6, row(d6, "МД ПРООН Черкаси  ДСНС"))
check(S(p6.Шапка.Подразделение) == "МД ПРООН Черкаси  ДСНС" and S(p6.Товар.Подразделение) == "МД ПРООН Черкаси  ДСНС"
      and float(p6.Шапка.СуммаДокумента) == 295,
      f"test_parametry_ptu_podrazdelenie_iz_dogovora: {S(p6.Шапка.Подразделение)} / {S(p6.Товар.Подразделение)}")

# Rule #-1: запит СоздатьНачисленияНаСервере 1:1
z = erp.NewObject("Запрос")
z.Text = """ВЫБРАТЬ
	П.Ссылка КАК Ссылка,
	П.Договор КАК Договор,
	П.Проведен КАК Проведен,
	П.ПометкаУдаления КАК ПометкаУдаления
ИЗ
	Документ.ПриобретениеТоваровУслуг КАК П
ГДЕ
	П.А_НачислениеПроцентовПоКредитам = &Документ"""
z.SetParameter("Документ", erp.Документы.А_НачислениеПроцентовПоКредитам.ПолучитьСсылку(erp.NewObject("УникальныйИдентификатор")))  # не порожнє: порожнє збіглося б з усіма ПТУ без зв'язку (тому код спершу записує документ)
r = z.Execute().Выгрузить()
check(r.Количество() == 0, f"запит наявних ПТУ виконано: {r.Количество()} рядків для неіснуючого документа")

# --- виправлення після фінального рецензування
# C1: помічений на вилучення документ не створює ПТУ (перевірка в транзакції, що відкочується — база не змінюється)
q_ = erp.NewObject("Запрос")
q_.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.А_НачислениеПроцентовПоКредитам КАК Д ГДЕ Д.ПометкаУдаления"""
t_ = q_.Execute().Выгрузить()
if t_.Количество():
    erp.НачатьТранзакцию()
    try:
        o = t_.Получить(0).Получить(0).ПолучитьОбъект()
        try:
            o.СоздатьНачисленияНаСервере()
            check(False, f"test_pomechennyy_dokument_ne_sozdaet_ptu: {S(o.Ссылка)} створив ПТУ")
        except Exception as e:
            msg = (e.excepinfo[2] if getattr(e, 'excepinfo', None) else str(e)).replace(chr(10), " ")[:140]
            check("вилучення" in msg, f"test_pomechennyy_dokument_ne_sozdaet_ptu: відмова «{msg}»")
    finally:
        erp.ОтменитьТранзакцию()
else:
    check(False, "test_pomechennyy_dokument_ne_sozdaet_ptu: немає поміченого документа для перевірки")

# I2: ПТУ-гілка ЕстьДругоеНачисление бачить ПТУ навіть без документа (документ-джерело може бути помічений)
z2 = erp.NewObject("Запрос")
z2.Text = """ВЫБРАТЬ ПЕРВЫЕ 1
	ПРЕДСТАВЛЕНИЕ(П.Ссылка)
ИЗ
	Документ.ПриобретениеТоваровУслуг КАК П
ГДЕ
	П.Договор = &Договор
	И П.Организация = &Организация
	И П.Проведен
	И НЕ П.ПометкаУдаления
	И П.А_НачислениеПроцентовПоКредитам <> ЗНАЧЕНИЕ(Документ.А_НачислениеПроцентовПоКредитам.ПустаяСсылка)
	И П.А_НачислениеПроцентовПоКредитам <> &ИсключитьДокумент
	И П.Дата МЕЖДУ &НачалоМесяца И &КонецМесяца"""
z2.SetParameter("Договор", erp.Справочники.ДоговорыКонтрагентов.НайтиПоНаименованию(PREF + "КРИВОЙ РОГ ЦЕМЕНТ-2", True))
z2.SetParameter("Организация", ORG)
z2.SetParameter("ИсключитьДокумент", erp.Документы.А_НачислениеПроцентовПоКредитам.ПустаяСсылка())
z2.SetParameter("НачалоМесяца", dt.datetime(2026, 9, 1, 3))
z2.SetParameter("КонецМесяца", dt.datetime(2026, 10, 1, 2, 59, 59))
r2 = z2.Execute().Выгрузить()
check(r2.Количество() == 1 and "000Ц-000628" in S(r2.Получить(0).Получить(0)),
      f"test_dubl_cherez_ptu_pomechennogo: {S(r2.Получить(0).Получить(0)) if r2.Количество() else 'нічого'}")

# I2: межі місяця виплат — функція модуля
try:
    пер = М.ПериодВыплат(dt.datetime(2026, 9, 15, 12))
    check(S(пер.Начало) == "01.10.2026 0:00:00" and S(пер.Конец) == "31.10.2026 23:59:59",
          f"test_period_vyplat: {S(пер.Начало)} … {S(пер.Конец)}")
except Exception as e:
    check(False, f"test_period_vyplat: {getattr(e, 'excepinfo', None) and e.excepinfo[2] or e}")

# I3: «Вручну» в шапці заборонено
dv = erp.Документы.А_НачислениеПроцентовПоКредитам.СоздатьДокумент()
dv.Организация = ORG
dv.МесяцНачисления = dt.datetime(2026, 9, 1, 3)
dv.СпособЗаполнения = СП.Вручную
try:
    dv.ЗаполнитьНачисления()
    check(False, "test_sposob_shapki_vruchnu_zaboroneno: заповнилось зі способом «Вручну»")
except Exception as e:
    msg = (e.excepinfo[2] if getattr(e, 'excepinfo', None) else str(e)).replace(chr(10), " ")[:140]
    check("Вручну" in msg or "виплатою" in msg, f"test_sposob_shapki_vruchnu_zaboroneno: відмова «{msg}»")

sys.exit(0 if ok else 1)
