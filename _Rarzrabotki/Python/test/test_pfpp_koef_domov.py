# -*- coding: utf-8 -*-
# Тест ПФПП: коэффициент КоличествоДомов + расшифровка факта часов до табеля (2026-07-16).
# Data-независимые инварианты (живые данные, жёстких чисел нет):
#   1. План отчёта == нормы ТЧ СС × ВЫБОР(КоличествоДомов>0, иначе 1);
#      труд — ТОЛЬКО строки ТЧ Работы с единицей «чол/год» (шт-работы в отчёт не попадают целиком):
#      ПланЧасы == Σ Работы(чол/год).Количество × К;
#      ПланГрн == Σ Комплектующие.Сумма × К (блок «1. Праця» — ТОЛЬКО часы, грн=0 с 16.07.2026);
#      ПланКол == Σ Комплектующие.Количество × К;
#   2. Каждая строка с ФактЧасы<>0 несёт в «Документ» ссылку типа
#      ДокументСсылка.А_ТабельУчетаРабочегоВремени; Σ часов по табелю == регистру
#      (А_ДанныеТабелирования по Регистратор, Подразделение В ИЕРАРХИИ подразделения СС);
#   3. композиция дефолт H>0.
# Путь .erf: env PFPP_ERF или продакшн. Подключение: env PFPP_CONN или .v8-project.json (id="erp").
import win32com.client, sys, os, json

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = os.environ.get("PFPP_ERF") or r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ПланФактныйПроизводствоПолный.erf"
assert os.path.exists(ERF), f"нет .erf: {ERF}"

def conn_string():
    s = os.environ.get("PFPP_CONN")
    if s:
        return s
    with open(r"C:\Configuration_downloads\BASERP25\.v8-project.json", encoding="utf-8") as fp:
        for db in json.load(fp)["databases"]:
            if db.get("id") == "erp":
                return f'Srvr="{db["server"]}";Ref="{db["ref"]}";Usr="{db["user"]}";Pwd="{db["password"]}"'
    raise RuntimeError("нет PFPP_CONN и записи id='erp' в .v8-project.json")

def f(x):
    return float(x) if x is not None else 0.0

def пусто(ref):
    return ref is None or (hasattr(ref, 'Пустая') and ref.Пустая())

erp = win32com.client.Dispatch("V83.COMConnector").Connect(conn_string())
S = erp.String
отчет = erp.ВнешниеОтчеты.Создать(ERF)

# Имена карточек СС дрейфуют (переименования, кириллическая «С» в «IRС», суффиксы складов) —
# ищем по префиксу среди активных СС, нормализуя С→C.
def лат(x):
    return x.replace("С", "C").replace("с", "c")

СС_ПРЕФИКСЫ = [
    "МД МХП ОРІЛЬ",
    "МД Вооз ЕМS Мала 2026",
    "МД IRC 2026 15 м",
    "МД IRC 2026 30 м",
]

def активные_сс(erp):
    z = erp.NewObject("Запрос")
    z.Текст = ("ВЫБРАТЬ СС.Ссылка КАК Ссылка, СС.Наименование КАК Имя "
               "ИЗ Справочник.А_СтруктураСебестоимости КАК СС "
               "ГДЕ НЕ СС.ЭтоГруппа И СС.Активная И НЕ СС.ПометкаУдаления")
    t = z.Выполнить().Выгрузить()
    return [(t[i].Имя, t[i].Ссылка) for i in range(t.Количество())]

fails = []
ВСЕ_СС = активные_сс(erp)
for префикс in СС_ПРЕФИКСЫ:
    найдено = [(им, сс) for им, сс in ВСЕ_СС if лат(им).startswith(лат(префикс))]
    assert найдено, f"СС не найдена по префиксу: {префикс}"
    имя, сс = найдено[0]

    # нормы ТЧ + коэффициент
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ КАК К,
        ЕСТЬNULL(Р.Часы, 0) КАК Часы, ЕСТЬNULL(Р.Грн, 0) КАК ГрнР,
        ЕСТЬNULL(М.Кол, 0) КАК Кол, ЕСТЬNULL(М.Грн, 0) КАК ГрнМ
    ИЗ Справочник.А_СтруктураСебестоимости КАК СС
        ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ Р.Ссылка КАК Ссылка, СУММА(Р.Количество) КАК Часы, СУММА(Р.Сумма) КАК Грн
            ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р
            ГДЕ СокрЛП(Р.Единица.Наименование) = "чол/год"
            СГРУППИРОВАТЬ ПО Р.Ссылка) КАК Р
        ПО СС.Ссылка = Р.Ссылка
        ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ К.Ссылка КАК Ссылка, СУММА(К.Количество) КАК Кол, СУММА(К.Сумма) КАК Грн
            ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К СГРУППИРОВАТЬ ПО К.Ссылка) КАК М
        ПО СС.Ссылка = М.Ссылка
    ГДЕ СС.Ссылка = &СС
    """
    q.SetParameter("СС", сс.Ссылка)
    н = q.Execute().Выгрузить().Получить(0)
    К = f(н.К)

    # С 24.07.2026 ПолучитьДанные строит ВСЕ подразделения сразу, а план — по всем активным СС
    # подразделения; поэтому нормы тоже суммируем по подразделению, а строки фильтруем по нему.
    qn = erp.NewObject("Запрос")
    qn.Text = """
    ВЫБРАТЬ
        СУММА(ЕСТЬNULL(Р.Часы, 0) * ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ) КАК Часы,
        СУММА(ЕСТЬNULL(М.Кол, 0) * ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ) КАК Кол,
        СУММА(ЕСТЬNULL(М.Грн, 0) * ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ) КАК Грн
    ИЗ Справочник.А_СтруктураСебестоимости КАК СС
        ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ Р.Ссылка КАК Ссылка, СУММА(Р.Количество) КАК Часы
            ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р
            ГДЕ СокрЛП(Р.Единица.Наименование) = "чол/год"
            СГРУППИРОВАТЬ ПО Р.Ссылка) КАК Р
        ПО СС.Ссылка = Р.Ссылка
        ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ К.Ссылка КАК Ссылка, СУММА(К.Количество) КАК Кол, СУММА(К.Сумма) КАК Грн
            ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К СГРУППИРОВАТЬ ПО К.Ссылка) КАК М
        ПО СС.Ссылка = М.Ссылка
    ГДЕ СС.Подразделение = &Подр И НЕ СС.ЭтоГруппа И СС.Активная И НЕ СС.ПометкаУдаления
    """
    qn.SetParameter("Подр", сс.Подразделение)
    нп = qn.Execute().Выгрузить().Получить(0)

    ПОДР_ИМЯ = сс.Подразделение.Наименование.strip()
    тз = отчет.ПолучитьДанные(erp.NewObject("СтандартныйПериод"))
    план_ч = план_кол = план_грн = 0.0
    таб_часы = {}
    ok = True
    for i in range(тз.Количество()):
        r = тз.Получить(i)
        if r.Подразделение.Наименование.strip() != ПОДР_ИМЯ:
            continue
        план_ч += f(r.ПланЧасы); план_кол += f(r.ПланКол); план_грн += f(r.ПланГрн)
        ч = f(r.ФактЧасы)
        if ч != 0:
            d = r.Документ
            if d is None or пусто(d) or "Табель" not in str(S(d)):
                ok = False; print(f"  !! строка часов ({ч}) без Документ-табеля")
            else:
                таб_часы[str(S(d))] = round(таб_часы.get(str(S(d)), 0.0) + ч, 2)

    # 1) план == нормы × К (грн — только материалы: блок «Праця» без денег)
    d1 = план_ч - f(нп.Часы)
    d2 = план_кол - f(нп.Кол)
    d3 = план_грн - f(нп.Грн)
    if abs(d1) > 0.02 or abs(d2) > 0.02 or abs(d3) > 0.02:
        ok = False
        print(f"  !! план подразделения != Σ(нормы×КоличествоДомов): dЧасы={d1:.2f} dКол={d2:.2f} dГрн={d3:.2f}")

    # 2) часы по табелям == регистру
    q2 = erp.NewObject("Запрос")
    q2.Text = ("ВЫБРАТЬ Т.Регистратор КАК Рег, СУММА(Т.ЧасыФакт) КАК Ч "
               "ИЗ РегистрНакопления.А_ДанныеТабелирования КАК Т "
               "ГДЕ Т.Подразделение В ИЕРАРХИИ (&Подр) СГРУППИРОВАТЬ ПО Т.Регистратор")
    q2.SetParameter("Подр", сс.Подразделение)
    tr = q2.Execute().Выгрузить()
    рег_часы = {}
    for i in range(tr.Количество()):
        rr = tr.Получить(i)
        рег_часы[str(S(rr.Рег))] = round(f(rr.Ч), 2)
    mism = {k for k in set(таб_часы) | set(рег_часы)
            if abs(таб_часы.get(k, 0.0) - рег_часы.get(k, 0.0)) > 0.01}
    if mism:
        ok = False; print(f"  !! расхождение по табелям: {sorted(mism)[:3]}")

    print(f"{имя[:40]}: К={К:.0f} ПланЧ={план_ч:.2f} ПланГрн={план_грн:.2f} "
          f"табелей={len(таб_часы)} {'OK' if ok else 'FAIL'}")
    if not ok:
        fails.append(имя)

# 3) композиция
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
наст = отчет.КомпоновщикНастроек.ПолучитьНастройки()
вн = erp.NewObject("Структура"); вн.Вставить("Детали", тз)
м = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст)
пр = erp.NewObject("ПроцессорКомпоновкиДанных"); пр.Инициализировать(м, вн)
д = erp.NewObject("ТабличныйДокумент")
в = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
в.УстановитьДокумент(д); в.Вывести(пр)
print(f"Композиция: H={д.ВысотаТаблицы} W={д.ШиринаТаблицы}")
if д.ВысотаТаблицы <= 0:
    fails.append("COMP")

print("\n" + ("PASS" if not fails else f"FAIL: {fails}"))
sys.exit(0 if not fails else 1)
