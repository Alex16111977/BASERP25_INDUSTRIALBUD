# Adversarial smoke: ветки «по перемещениям» через собранную .epf.
# Заполняем Обр.ТабличнаяЧастьПеремещения списком перемещений, вызываем движок, проверяем
# поля/наценку/дедуп/пропуск непроведённых. Транзакции с откатом.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
EPF = r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Заполнить в бухучете приобритение по списанию.epf'
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
def S(v):
    try: return buh.String(v) if v is not None else "None"
    except: return "<?>"
def num(v):
    try: return float(str(v).replace('\xa0','').replace(' ','').replace(',','.'))
    except: return None

# 3 проведённых перемещения + эталонный агрегат Дт (Python)
qm=buh.NewObject("Запрос")
qm.Text="""ВЫБРАТЬ ПЕРВЫЕ 3 Х.Регистратор КАК Рег, КОЛИЧЕСТВО(*) КАК Кво
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
ГДЕ Х.КоличествоДт>0 И ТИПЗНАЧЕНИЯ(Х.Регистратор)=ТИП(Документ.ПеремещениеТоваров)
СГРУППИРОВАТЬ ПО Х.Регистратор УПОРЯДОЧИТЬ ПО Кво УБЫВ"""
sm=qm.Execute().Выбрать(); перем=[]
while sm.Следующий(): перем.append(sm.Рег)
# эталон: distinct posted, агрегат Дт по (ном,счёт,налназн)
ref={}
for p in перем:
    if not p.Проведен: continue
    НЗ=buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
    НЗ.Отбор.Регистратор.Установить(p); НЗ.Прочитать()
    for z in НЗ:
        if z.КоличествоДт==0: continue
        nom=None
        for kv in z.СубконтоДт:
            try:
                if kv.Значение.Метаданные().ПолноеИмя()=="Справочник.Номенклатура": nom=kv.Значение; break
            except: pass
        if nom is None: continue
        k=S(nom.УникальныйИдентификатор())+"|"+S(z.СчетДт.УникальныйИдентификатор())+"|"+S(z.НалоговоеНазначениеДт.УникальныйИдентификатор())
        ref[k]=ref.get(k,0.0)+z.Сумма
ref_строк=len(ref); ref_сумма=round(sum(ref.values()),2)
print(f"Эталон: распарсено перемещений={len(перем)}, групп={ref_строк}, Σсебест={ref_сумма:.2f}")

def find(typ, where=""):
    q=buh.NewObject("Запрос")
    q.Text=f"ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.{typ} {('ГДЕ '+where) if where else ''} УПОРЯДОЧИТЬ ПО Дата УБЫВ"
    s=q.Execute().Выбрать(); return s.Ссылка if s.Следующий() else None
prmPost=find("ПоступлениеТоваровУслуг")
prmReal=find("РеализацияТоваровУслуг","Номер=\"ІБ00-000110\"")

Обр=buh.ВнешниеОбработки.Создать(EPF)
print("Создать(.epf) — OK")
fails=[]

def залить_список(дубль=False):
    Обр.ТабличнаяЧастьПеремещения.Очистить()
    for p in перем:
        Обр.ТабличнаяЧастьПеремещения.Добавить().ДокументПеремещениеТоваров = p
    if дубль:  # добавить дубль первого — проверка дедупа
        Обр.ТабличнаяЧастьПеремещения.Добавить().ДокументПеремещениеТоваров = перем[0]

def проверить(имя, func, prm, нац, реализация, дубль=False):
    залить_список(дубль)
    buh.НачатьТранзакцию()
    try:
        Рез=func(Обр.ТабличнаяЧастьПеремещения, prm, нац)
        d=prm.ПолучитьОбъект(); bad=0
        сумНДС=0.0; сумСум=0.0
        for r in d.Товары:
            с=num(r.Сумма); ц=num(r.Цена); к=num(r.Количество); ндс=num(r.СуммаНДС)
            сумНДС+=ндс; сумСум+=с
            # построчно проверяем только то, чем владеет КОД (НДС у реализации пересчитывает авто-НДС документа)
            if нац!=0 and abs(с-round(ц*к,2))>0.02: bad+=1
            if not реализация and abs(ндс-round(с*20/100,2))>0.01: bad+=1  # поступление: НДС наш
            if реализация and abs(num(r.СуммаБезСкидки)-с)>0.01: bad+=1
            if реализация and S(r.СхемаРеализации)!="Товары": bad+=1
        # инвариант уровня документа: суммарный НДС ≈ 20% суммарной Суммы (авто-НДС округляет построчно)
        if abs(сумНДС - round(сумСум*20/100,2)) > max(1.0, d.Товары.Количество()*0.01): bad+=1
        # дедуп: при нац=0 ИтогоСумма должна совпасть с эталоном (дубль не задваивает)
        дедуп_ок = (нац!=0) or abs(Рез.ИтогоСумма-ref_сумма)<0.05
        строк_ок = (Рез.Строк==ref_строк)
        print(f"  {имя} нац={нац}%{' +дубль' if дубль else ''}: Успех={Рез.Успех} Строк={Рез.Строк}(эт {ref_строк}) Σ={Рез.ИтогоСумма:.2f} наруш={bad} дедуп={'ok' if дедуп_ок else 'FAIL'}")
        if not Рез.Успех or bad>0 or not строк_ок or not дедуп_ок: fails.append(f"{имя}/{нац}{'/dup' if дубль else ''}")
    finally: buh.ОтменитьТранзакцию()

print("=== Поступление по перемещениям ===")
проверить("Пост", Обр.ЗаполнитьПоПеремещениямПоступление, prmPost, 0, False)
проверить("Пост", Обр.ЗаполнитьПоПеремещениямПоступление, prmPost, 20, False)
проверить("Пост", Обр.ЗаполнитьПоПеремещениямПоступление, prmPost, 0, False, дубль=True)
print("=== Реализация по перемещениям ===")
проверить("Реал", Обр.ЗаполнитьПоПеремещениямРеализацию, prmReal, 0, True)
проверить("Реал", Обр.ЗаполнитьПоПеремещениямРеализацию, prmReal, 20, True)

