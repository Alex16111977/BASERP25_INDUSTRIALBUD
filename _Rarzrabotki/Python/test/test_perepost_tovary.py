# -*- coding: utf-8 -*-
"""
RED-фаза (Rule #-1) для обробки СинхронизироватьТоварыТолькоТовары:
прототип ПЕРЕПРОВЕДЕННЯ товарного документа в ЕРП (ОтменаПроведения + Проведение).

Перевіряємо ДВА сценарії пошуку документа ЕРП:
  1) пряме посилання (як НС.ДокументЕРП = DocumentRef у прямому аналізі);
  2) резолв через РегистрСведений.СоответствияОбъектовИнформационныхБаз
     за UID Бух (як у ПровестиВЕРП) — fallback.

І головне: що перепроведення РЕГЕНЕРУЄ рухи ТоварыНаСкладах ІДЕМПОТЕНТНО
(нетто рухів документа ДО == ПІСЛЯ, без задвоєння).

Безпека: беремо НЕрозрахунковий товарний документ (ПеремещениеТоваров —
чистий рух запасів, без РегистраторРасчётов), 1 документ. Решту історії
користувач перепроводить сам у UI.
"""
import win32com.client, sys, datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("[OK] Connected ERP")

S = erp.String  # англ. String працює через проксі (Cyrillic globals — ні)


def run(text, params=None):
    query = erp.NewObject("Запрос")
    query.Text = text
    if params:
        for k, val in params.items():
            query.SetParameter(k, val)
    return query.Execute().Unload()


def netto_map(reg_ref):
    """Нетто рух документа по (Номенклатура,Склад) -> число. Ключ — UUID-рядки."""
    tz = run(
        "ВЫБРАТЬ "
        "  Дв.Номенклатура КАК Ном, "
        "  Дв.Склад        КАК Скл, "
        "  СУММА(ВЫБОР КОГДА Дв.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) "
        "              ТОГДА Дв.ВНаличии ИНАЧЕ -Дв.ВНаличии КОНЕЦ) КАК Нетто "
        "ИЗ РегистрНакопления.ТоварыНаСкладах КАК Дв "
        "ГДЕ Дв.Регистратор = &Рег "
        "СГРУППИРОВАТЬ ПО Дв.Номенклатура, Дв.Склад",
        {"Рег": reg_ref})
    res = {}
    for i in range(tz.Count()):
        r = tz.Get(i)
        kn = S(r.Ном.УникальныйИдентификатор())
        ks = S(r.Скл.УникальныйИдентификатор())
        res[(kn, ks)] = round(float(r.Нетто), 3)
    return res


# Широке вікно — підхопити будь-який період з даними
d1 = datetime.datetime(2025, 1, 1, 12, 0, 0)
d2 = datetime.datetime(2026, 12, 31, 12, 0, 0)

# ── Крок 1: знайти проведений ПеремещениеТоваров з рухами ТоварыНаСкладах ──
# (records-таблиця: рухи є тільки в проведених; ПеремещениеТоваров — баланс-
#  ний трансфер, тому НЕ фільтруємо по нетто-обороту = 0)
tz = run(
    "ВЫБРАТЬ ПЕРВЫЕ 1 Дв.Регистратор КАК Рег, ПРЕДСТАВЛЕНИЕ(Дв.Регистратор) КАК Предст "
    "ИЗ РегистрНакопления.ТоварыНаСкладах КАК Дв "
    "ГДЕ ТИПЗНАЧЕНИЯ(Дв.Регистратор) = ТИП(Документ.ПеремещениеТоваров) "
    "УПОРЯДОЧИТЬ ПО Дв.Период УБЫВ")

if tz.Count() == 0:
    print("[SKIP] Не знайдено проведеного ПеремещениеТоваров з рухами ТоварыНаСкладах у вікні")
    sys.exit(0)

reg = tz.Get(0).Рег
print(f"[OK] Кандидат: {tz.Get(0).Предст}")
print(f"     Проведен={reg.Проведен}, UUID={S(reg.УникальныйИдентификатор())}")

# ── Крок 2: ДО — нетто рухів документа ──
before = netto_map(reg)
print(f"[OK] Рухів ТоварыНаСкладах ДО: позицій={len(before)}; "
      f"Σ|нетто|={round(sum(abs(x) for x in before.values()),3)}")

# ── Крок 3: перевірка пошуку ref → об'єкт (сценарій НС.ДокументЕРП) ──
obj = reg.GetObject()
assert obj is not None, "ПолучитьОбъект() повернув Неопределено для прямого ref"
print("[OK] Сценарій 1 (пряме посилання ДокументЕРП): GetObject() != None")

# ── Крок 4: ПЕРЕПРОВЕДЕННЯ (ОтменаПроведения + перечитати + Проведення) ──
try:
    if obj.Проведен:
        obj.Write(erp.DocumentWriteMode.UndoPosting)
        print("[OK] ОтменаПроведения виконано")
        obj = reg.GetObject()            # перечитати після відміни (закритий менеджер ВТ!)
    obj.Write(erp.DocumentWriteMode.Posting)
    print("[OK] Проведення виконано")
    reposted = True
except Exception as e:
    info = getattr(e, 'excepinfo', None)
    print(f"[BLOCKED] Перепроведення через COM не виконано: {info[2] if info else e}")
    reposted = False

# ── Крок 5: ПІСЛЯ — нетто рухів, порівняння (ідемпотентність) ──
if reposted:
    after = netto_map(reg)
    ok = (before == after)
    print(f"[OK] Рухів ТоварыНаСкладах ПІСЛЯ: позицій={len(after)}; "
          f"Σ|нетто|={round(sum(abs(x) for x in after.values()),3)}")
    print(f"[{'PASS' if ok else 'FAIL'}] Ідемпотентність: нетто ДО == ПІСЛЯ → {ok}")
    if not ok:
        diff = {k: (before.get(k), after.get(k)) for k in set(before) | set(after)
                if before.get(k) != after.get(k)}
        print("        Розбіжності (ключ: до/після):", diff)

# ── Крок 6: fallback-пошук через СоответствияОбъектовИнформационныхБаз ──
print("\n--- Перевірка fallback: резолв ЕРП-ref за UID Бух (як у ПровестиВЕРП) ---")
tzm = run(
    "ВЫБРАТЬ ПЕРВЫЕ 1 "
    "  Соотв.УникальныйИдентификаторИсточника КАК Источник, "
    "  Соотв.УникальныйИдентификаторПриемника КАК UIDБух, "
    "  ПРЕДСТАВЛЕНИЕ(Соотв.УникальныйИдентификаторИсточника) КАК Предст "
    "ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв "
    "ГДЕ Соотв.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20 "
    "  И ТИПЗНАЧЕНИЯ(Соотв.УникальныйИдентификаторИсточника) = ТИП(Документ.ПриобретениеТоваровУслуг)")
if tzm.Count() == 0:
    print("[SKIP] Немає записів відповідності для ПриобретениеТоваровУслуг")
else:
    uid_buh = tzm.Get(0).UIDБух
    src0 = tzm.Get(0).Источник
    print(f"[OK] Зразок відповідності: {tzm.Get(0).Предст}; UIDБух={uid_buh}")
    tzr = run(
        "ВЫБРАТЬ ПЕРВЫЕ 1 Соотв.УникальныйИдентификаторИсточника КАК Источник "
        "ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв "
        "ГДЕ Соотв.УникальныйИдентификаторПриемника = &UID "
        "  И Соотв.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20",
        {"UID": uid_buh})
    if tzr.Count() > 0:
        src1 = tzr.Get(0).Источник
        same = (S(src1.УникальныйИдентификатор()) == S(src0.УникальныйИдентификатор()))
        print(f"[{'PASS' if same else 'FAIL'}] Резолв за UIDБух повернув той самий ЕРП-документ → {same}")
        print(f"     obj після резолву: GetObject() != None → {src1.GetObject() is not None}")
    else:
        print("[FAIL] Резолв за UIDБух нічого не повернув")

print("\n=== DONE ===")
