import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="SQLSERVER";Ref="zup_1";Usr="cfo";Pwd="2442"')
S = zup.String


def com_date(y, m, d):
    return pywintypes.Time(datetime.datetime(y, m, d))


def try_query(label, text):
    q = zup.NewObject("Запрос")
    q.Text = text
    q.SetParameter("Н", com_date(2025, 12, 1))
    q.SetParameter("К", com_date(2025, 12, 31))
    try:
        r = q.Execute().Выгрузить()
        print(f"  [OK] {label} → рядків={r.Количество()}")
        if r.Количество() > 0:
            row = r.Получить(0)
            for i in range(r.Колонки.Количество()):
                имя = S(r.Колонки.Получить(i).Имя)
                val = S(getattr(row, имя))
                print(f"        {имя}={val}")
        return True
    except Exception as e:
        msg = str(e)
        if hasattr(e, 'excepinfo') and e.excepinfo:
            msg = e.excepinfo[2][:200]
        print(f"  [FAIL] {label}: {msg}")
        return False


