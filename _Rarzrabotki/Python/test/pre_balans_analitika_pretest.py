def плоский_запрос(тело):
    """Извлечь литерал Запрос.Текст = "..." и нормализовать в плоский SQL."""
    i = тело.index("Запрос.Текст =")
    j = тело.index('"', i) + 1
    буф = []
    while j < len(тело):
        c = тело[j]
        if c == '"':
            if j + 1 < len(тело) and тело[j + 1] == '"':
                буф.append('"'); j += 2; continue
            break
        буф.append(c); j += 1
    лит = "".join(буф)
    стр = []
    for k, ln in enumerate(лит.split("\n")):
        стр.append(ln if k == 0 else re.sub(r"^\s*\|", "", ln))
    return "\n".join(стр)


