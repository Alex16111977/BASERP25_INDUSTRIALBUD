# -*- coding: utf-8 -*-
"""Диагностика: попытка создать один РКО с минимальным набором полей."""
import win32com.client
import pythoncom
import sys
import io

# Переключаем stdout на UTF-8
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

CONN_STRING = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONN_STRING)
    print("[OK] Подключение установлено")

    # 1. Найти документ-источник
    q = conn.NewObject("Запрос")
    q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.А_ПриходДенегОтФинАгента ГДЕ Номер = &Н'
    q.УстановитьПараметр("Н", "N00023533")
    res = q.Выполнить()
    sel = res.Выбрать()
    sel.Следующий()
    doc_ref = sel.Ссылка
    print(f"[OK] Источник найден: {doc_ref}")

    # 2. Шапка
    q2 = conn.NewObject("Запрос")
    q2.Текст = (
        'ВЫБРАТЬ Док.Дата, Док.Организация, Док.Касса, '
        'Док.СтатьяДвиженияДенежныхСредств КАК СтатьяДДС, '
        'Док.Подразделение, Док.А_НаправлениеДеятельности КАК НапрДеят, '
        'Док.Касса.ВалютаДенежныхСредств КАК Валюта '
        'ИЗ Документ.А_ПриходДенегОтФинАгента КАК Док '
        'ГДЕ Док.Ссылка = &С'
    )
    q2.УстановитьПараметр("С", doc_ref)
    r2 = q2.Выполнить().Выбрать()
    r2.Следующий()
    print(f"  Дата={r2.Дата}, Орг={r2.Организация}, Касса={r2.Касса}")
    print(f"  СтатьяДДС={r2.СтатьяДДС}, Подр={r2.Подразделение}")
    print(f"  НапрДеят={r2.НапрДеят}, Валюта={r2.Валюта}")

    # 3. Первая строка
    q3 = conn.NewObject("Запрос")
    q3.Текст = (
        'ВЫБРАТЬ ПЕРВЫЕ 1 НомерСтроки, Контрагент, ОбъектРасчетов, СуммаКомиссии '
        'ИЗ Документ.А_ПриходДенегОтФинАгента.РасшифровкаПлатежа '
        'ГДЕ Ссылка = &С И СуммаКомиссии > 0 '
        'УПОРЯДОЧИТЬ ПО НомерСтроки'
    )
    q3.УстановитьПараметр("С", doc_ref)
    r3 = q3.Выполнить().Выбрать()
    r3.Следующий()
    контрагент = r3.Контрагент
    суммаКом = r3.СуммаКомиссии
    print(f"  Контрагент={контрагент}, СуммаКомиссии={суммаКом}")

    # 4. Партнёр
    q4 = conn.NewObject("Запрос")
    q4.Текст = "ВЫБРАТЬ Партнер ИЗ Справочник.Контрагенты ГДЕ Ссылка = &К"
    q4.УстановитьПараметр("К", контрагент)
    r4 = q4.Выполнить().Выбрать()
    r4.Следующий()
    партнер = r4.Партнер
    print(f"  Партнер={партнер}")

    # 5. Попытка 1: Создать РКО — ТОЛЬКО запись (без проведения)
    print("\n=== Тест 1: РКО — Записать(0) — только запись ===")
    try:
        rko = conn.Документы.РасходныйКассовыйОрдер.СоздатьДокумент()
        rko.Дата = r2.Дата
        rko.Организация = r2.Организация
        rko.ХозяйственнаяОперация = conn.Перечисления.ХозяйственныеОперации.ОплатаПоставщику
        rko.Касса = r2.Касса
        rko.Контрагент = контрагент
        rko.Партнер = партнер
        rko.Валюта = r2.Валюта
        rko.СуммаДокумента = суммаКом
        rko.СтатьяДвиженияДенежныхСредств = r2.СтатьяДДС
        rko.Подразделение = r2.Подразделение
        rko.НаправлениеДеятельности = r2.НапрДеят
        rko.А_ПриходДенегОтФинАгента = doc_ref
        print("  Поля заполнены, пробуем Записать(0)...")
        rko.Записать(0)  # Запись
        print(f"  [OK] РКО записан: {rko.Номер}")
        # Теперь пробуем провести
        print("  Пробуем Записать(1) — проведение...")
        rko.Записать(1)
        print(f"  [OK] РКО проведён: {rko.Номер}")
    except Exception as e:
        print(f"  [ERR] {e}")

    # 6. Попытка 2: Без А_ПриходДенегОтФинАгента
    print("\n=== Тест 2: РКО БЕЗ А_ПриходДенегОтФинАгента ===")
    try:
        rko2 = conn.Документы.РасходныйКассовыйОрдер.СоздатьДокумент()
        rko2.Дата = r2.Дата
        rko2.Организация = r2.Организация
        rko2.ХозяйственнаяОперация = conn.Перечисления.ХозяйственныеОперации.ОплатаПоставщику
        rko2.Касса = r2.Касса
        rko2.Контрагент = контрагент
        rko2.Партнер = партнер
        rko2.Валюта = r2.Валюта
        rko2.СуммаДокумента = суммаКом
        rko2.СтатьяДвиженияДенежныхСредств = r2.СтатьяДДС
        rko2.Подразделение = r2.Подразделение
        rko2.НаправлениеДеятельности = r2.НапрДеят
        # НЕ устанавливаем А_ПриходДенегОтФинАгента
        # ТЧ РасшифровкаПлатежа
        strRP = rko2.РасшифровкаПлатежа.Добавить()
        strRP.Сумма = суммаКом
        strRP.СуммаВзаиморасчетов = суммаКом
        strRP.ВалютаВзаиморасчетов = r2.Валюта
        strRP.СтатьяДвиженияДенежныхСредств = r2.СтатьяДДС
        strRP.Подразделение = r2.Подразделение
        strRP.НаправлениеДеятельности = r2.НапрДеят
        strRP.Партнер = партнер
        print("  Поля заполнены (без А_ПриходДенегОтФинАгента), пробуем Записать(1)...")
        rko2.Записать(1)
        print(f"  [OK] РКО2 проведён: {rko2.Номер}")
        # Помечаем на удаление
        rko2.УстановитьПометкуУдаления(True)
        print("  [OK] РКО2 помечен на удаление")
    except Exception as e:
        print(f"  [ERR] {e}")

    # 7. Попытка 3: С А_ПриходДенегОтФинАгента + ТЧ
    print("\n=== Тест 3: РКО С А_ПриходДенегОтФинАгента + ТЧ ===")
    try:
        rko3 = conn.Документы.РасходныйКассовыйОрдер.СоздатьДокумент()
        rko3.Дата = r2.Дата
        rko3.Организация = r2.Организация
        rko3.ХозяйственнаяОперация = conn.Перечисления.ХозяйственныеОперации.ОплатаПоставщику
        rko3.Касса = r2.Касса
        rko3.Контрагент = контрагент
        rko3.Партнер = партнер
        rko3.Валюта = r2.Валюта
        rko3.СуммаДокумента = суммаКом
        rko3.СтатьяДвиженияДенежныхСредств = r2.СтатьяДДС
        rko3.Подразделение = r2.Подразделение
        rko3.НаправлениеДеятельности = r2.НапрДеят
        rko3.А_ПриходДенегОтФинАгента = doc_ref
        # ТЧ РасшифровкаПлатежа
        strRP3 = rko3.РасшифровкаПлатежа.Добавить()
        strRP3.Сумма = суммаКом
        strRP3.СуммаВзаиморасчетов = суммаКом
        strRP3.ВалютаВзаиморасчетов = r2.Валюта
        strRP3.СтатьяДвиженияДенежныхСредств = r2.СтатьяДДС
        strRP3.Подразделение = r2.Подразделение
        strRP3.НаправлениеДеятельности = r2.НапрДеят
        strRP3.Партнер = партнер
        print("  Поля заполнены (с А_ПриходДенегОтФинАгента + ТЧ), пробуем Записать(1)...")
        rko3.Записать(1)
        print(f"  [OK] РКО3 проведён: {rko3.Номер}")
        # Помечаем на удаление
        rko3.Записать(2)  # отмена проведения
        rko3.УстановитьПометкуУдаления(True)
        print("  [OK] РКО3 помечен на удаление")
    except Exception as e:
        print(f"  [ERR] {e}")

    print("\n[DONE]")


if __name__ == "__main__":
    main()
