# Перевірка: report СуммаОстатка картки = Σ(register СуммаОстаток) × 1.2 (інваріант, не магічне число).
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
обр = buh.ВнешниеОбработки.Создать(EPF, False)
обр.Период = datetime.datetime(2026, 7, 7)
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000004").Ссылка
склады = []
вс = buh.Справочники.Склады.Выбрать()
while вс.Следующий():
    if "СТІЛ МД МХП ОРІЛЬ" in вс.Наименование and "виробнич" in вс.Наименование:
        обр.СкладыОстатков.Добавить().Склад = вс.Ссылка
        склады.append(вс.Ссылка)
for код in ("20", "22", "28"):
    обр.СчетаОстатков.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код).Ссылка
обр.РассчитатьАнализ()

# report СуммаОстатка по картці «Профнастил ПС-10»
тч = обр.ТабличнаяЧастьОстатков
рзвіт = 0.0
for i in range(тч.Количество()):
    р = тч.Получить(i)
    if str(р.Номенклатура.Наименование) == "Профнастил ПС-10":
        рзвіт += float(р.СуммаОстатка)

# raw собівартість (без ПДВ) того ж картки з регістру
м = buh.NewObject("Массив")
for s in склады: м.Добавить(s)
сч = buh.NewObject("Массив")
for k in ("20", "22", "28"): сч.Добавить(buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(k).Ссылка)
q = buh.NewObject("Запрос")
q.УстановитьПараметр("Д", datetime.datetime(2026, 7, 7, 23, 59, 59))
q.УстановитьПараметр("Склады", м); q.УстановитьПараметр("Счета", сч)
q.УстановитьПараметр("Ном", buh.Справочники.Номенклатура.НайтиПоНаименованию("Профнастил ПС-10").Ссылка)
q.Текст = ("ВЫБРАТЬ СУММА(Ост.СуммаОстаток) КАК С ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Д, Счет В ИЕРАРХИИ(&Счета), , ) КАК Ост "
           "ГДЕ Ост.КоличествоОстаток > 0 И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) В (&Склады) "
           "И ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) = &Ном")
вб = q.Выполнить().Выгрузить()
raw = float(вб.Получить(0).С) if вб.Количество() and вб.Получить(0).С is not None else 0.0

print(f"report СуммаОстатка(ПС-10) = {round(рзвіт,2)}; raw себівартість = {round(raw,2)}; ratio = {round(рзвіт/raw,4) if raw else 'n/a'}")
assert raw > 0, "немає собівартості ПС-10 у регістрі"
assert abs(рзвіт / raw - 1.2) < 0.001, f"факт у звіті має бути собівартість×1.2, ratio={рзвіт/raw}"
print("PASS: факт-суми приведені до бази норми (×1.2, з ПДВ)")
