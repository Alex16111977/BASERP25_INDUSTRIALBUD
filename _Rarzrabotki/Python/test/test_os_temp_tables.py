# -*- coding: utf-8 -*-
"""Перевірка: які поля є в втДанныеДокумента при проведенні ПринятиеКУчетуОС.
Імітуємо запит який виконується при проведенні.
"""
import win32com.client, datetime

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

print("=== Перевірка втДанныеДокумента для ПринятиеКУчетуОС ===\n")

# Знайти документ ІБ00-000254
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.ПринятиеКУчетуОС КАК Д ГДЕ Д.Номер ПОДОБНО &Н И Д.Дата >= &Д"""
q.SetParameter("Н", "%000254%")
q.SetParameter("Д", datetime.datetime(2025, 12, 1))
r = q.Execute().Select()
if not r.Next():
    print("Документ не знайдено!")
    exit()
ref = r.Ссылка
print(f"Документ: {S(ref)}\n")

# Виконати запит аналогічний ВременнаяТаблицаДанныеДокумента()
q2 = conn.NewObject("Запрос")
q2.Text = """ВЫБРАТЬ
    ТаблицаДокумента.Ссылка КАК Ссылка,
    ТаблицаДокумента.Дата КАК Дата,
    ТаблицаДокумента.Организация КАК Организация,
    ТаблицаДокумента.Подразделение КАК Подразделение,
    ТаблицаДокумента.Местонахождение КАК Местонахождение,
    ТаблицаДокумента.НаправлениеДеятельности КАК НаправлениеДеятельности,
    ТабличнаяЧасть.ОсновноеСредство КАК ОсновноеСредство,
    ТаблицаДокумента.НалоговоеНазначение КАК НалоговоеНазначение,
    ТаблицаДокумента.СтатьяРасходов КАК СтатьяРасходов,
    ТаблицаДокумента.АналитикаРасходов КАК АналитикаРасходов,
    ТабличнаяЧасть.СтоимостьНУ КАК СтоимостьНУ
ИЗ
    Документ.ПринятиеКУчетуОС КАК ТаблицаДокумента
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ПринятиеКУчетуОС.ОС КАК ТабличнаяЧасть
        ПО ТаблицаДокумента.Ссылка = ТабличнаяЧасть.Ссылка
ГДЕ
    ТаблицаДокумента.Ссылка = &Ссылка"""
q2.SetParameter("Ссылка", ref)

res = q2.Execute()
tbl = res.Unload()
print(f"Рядків: {tbl.Count()}\n")
for i in range(tbl.Count()):
    row = tbl.Get(i)
    print(f"  ОС: {S(row.ОсновноеСредство)}")
    print(f"  СтоимостьНУ: {row.СтоимостьНУ}")
    print(f"  Організація: {S(row.Организация)}")
    print(f"  Підрозділ: {S(row.Подразделение)}")
    print(f"  Напрямок: {S(row.НаправлениеДеятельности)}")
    print(f"  СтатьяРасходов: {S(row.СтатьяРасходов)}")
    print(f"  НалоговоеНазначение: {S(row.НалоговоеНазначение)}")
    print(f"  СтоимостьНУ * 1.2 = {row.СтоимостьНУ * 1.2}")
    print()

# Перевірити суму в ПрочиеРасходы для порівняння
print("=== Порівняння з ПрочиеРасходы ===")
q3 = conn.NewObject("Запрос")
q3.Text = """ВЫБРАТЬ ПР.АналитикаРасходов, ПР.СуммаОстаток
ИЗ РегистрНакопления.ПрочиеРасходы.Остатки(, АналитикаРасходов В
    (ВЫБРАТЬ Т.ОсновноеСредство ИЗ Документ.ПринятиеКУчетуОС.ОС КАК Т ГДЕ Т.Ссылка = &Ссылка)
) КАК ПР"""
q3.SetParameter("Ссылка", ref)
try:
    res3 = q3.Execute()
    sel3 = res3.Select()
    while sel3.Next():
        print(f"  АналитикаРасходов: {S(sel3.АналитикаРасходов)} Остаток: {sel3.СуммаОстаток}")
except Exception as e:
    print(f"  Помилка: {e}")

print("\n=== DONE ===")
