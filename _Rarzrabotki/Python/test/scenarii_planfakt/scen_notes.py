def note(text, w=360):
    cpl = max(20, int(w / 6.2))
    lines = sum(max(1, math.ceil(len(s) / cpl)) for s in text.split("\n"))
    return Comment(text, AUTHOR, width=w, height=min(600, 18 * lines + 14))


def docs_text(o, signed_only):
    out = []
    for d in o["dogs"]:
        part = []
        for x in d["docs"]:
            if signed_only and x["H"]:
                continue
            if x["H"]:
                part.append("  • %s — %s, %s" % (x["doc"], fmt(x["H"]), x["status"]))
            elif x["unpaid"]:
                part.append("  • %s — %s" % (x["doc"], x["N"]))
        amount = d["pess"] if signed_only else d["K"]
        if not part and amount:
            if d["G"] > 0:
                part.append("  • подписанный неоплаченный долг (кол. G) — %s" % fmt(d["G"]))
            if d["H"] and not signed_only:
                part.append("  • поданные акты на рассмотрении (кол. H) — %s, в расчёт по формуле договора" % fmt(d["H"]))
        if part or amount:
            out.append("%s: %s" % (d["name"][:60], fmt(amount)))
            out += part
    return "\n".join(out)


def receipts_note(name, val, pess):
    o = FO.get(name)
    if o and o["K"] > 0:
        if not pess:
            t = ("Оптимистичный = «ИТОГО сумма к получению» (кол. K) финотчёта 09.10 — %s: подписанный долг + поданные, "
                 "но не подписанные / не проведённые акты (за вычетом аванса и удержаний по формуле договора).\n%s"
                 % (fmt(o["K"]), docs_text(o, False)))
        else:
            t = ("Пессимистичный = только то, что получим «по-любому»: подписанные акты (оригинал получен) с неоплаченным "
                 "остатком; поданные, но не подписанные / не проведённые акты не ставим — %s.\n%s"
                 % (fmt(val), docs_text(o, True) or "Подписанных неоплаченных актов нет."))
            if name == "МК Каменец Цемент":
                t += "\nПо актам есть замечания заказчика по качеству — в пессимистичный не ставим."
        return t
    if pess:
        return PESS_MANUAL.get(name, "Поступлений по финотчёту нет → 0.")
    return MANUAL.get(name, "В финотчёте к получению 0 и плана поступлений нет → 0.")


def limit_note(p, M, N, O, val, col):
    if not p:
        return "Поступлений нет → лимит 0 (тратить можно только из прихода).\n=ЕСЛИ(%s+N>0;ЕСЛИ(%s<>0;ЕСЛИ(N+%s>M;%s+O;0);0);0)" % ((col,) * 4)
    gap = -O
    if val > 0:
        return ("Лимит = поступления %s − недобор маржи %s (маржа план %s − факт %s) = %s.\nПриход сначала закрывает разрыв "
                "по марже, тратить можно только остаток." % (fmt(p), fmt(gap), fmt(M), fmt(N), fmt(val)))
    return ("Поступления %s не покрывают недобор маржи %s (маржа план %s − факт %s) → лимит 0: весь приход уходит на "
            "восстановление маржи." % (fmt(p), fmt(gap), fmt(M), fmt(N)))


def need_note(name, r_val, I, J, prepaid):
    if not r_val:
        t = "Потребность (заявки) производство на 09.10 не дало → пусто. Вписать, когда дадут."
        if prepaid:
            t += "\nВлияет на доп. маржу этой строки: аванс получен ранее, затраты месяца пойдут из остатков Ф1."
        return t
    t = ("По умолчанию = остаток плана затрат месяца из казны (кол. L): план %s − факт %s = %s. Заменить заявками "
         "производства, если есть." % (fmt(-I), fmt(-J), fmt(r_val)))
    if prepaid:
        t += "\nВлияет на доп. маржу: аванс получен ранее, затраты месяца оплачиваются из остатков Ф1."
    return t


def margin_note(p, q, r, prepaid, val):
    if prepaid:
        return ("= поступления %s − лимит %s − потребность %s = %s.\nАванс получен ранее, поэтому затраты месяца уменьшают "
                "свободные деньги (как 18.09)." % (fmt(p), fmt(q), fmt(r), fmt(val)))
    if not p:
        return "Поступлений нет → 0."
    if val >= 0:
        return ("= поступления %s − лимит %s = %s: часть прихода, которая не идёт в затраты, а восстанавливает маржу."
                % (fmt(p), fmt(q), fmt(val)))
    return ("= поступления %s − лимит %s = %s: по плану затраты месяца больше поступлений (отрицательная плановая маржа)."
            % (fmt(p), fmt(q), fmt(val)))


