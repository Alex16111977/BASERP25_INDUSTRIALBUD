import win32com.client
import datetime

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String
VF = conn.ValueIsFilled

print("=== 1. Функціональні опції ===")
for opt in ["ИспользоватьВнеоборотныеАктивы2_2", "ИспользоватьВнеоборотныеАктивы2_4"]:
    try:
        val = conn.GetFunctionalOption(opt)
        print(f"  {opt} = {val}")
    except:
        print(f"  {opt} - not found")

print("\n=== 2. СтоимостьОС — є записи? ===")
q = conn.NewObject("Запрос")
q.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.СтоимостьОС"
r = q.Execute().Select()
r.Next()
print(f"  Всього записів: {r.К}")

if r.К > 0:
    print("\n  Останні 5:")
    q2 = conn.NewObject("Запрос")
    q2.Text = """ВЫБРАТЬ ПЕРВЫЕ 5
        Д.Период, Д.Регистратор, Д.ОсновноеСредство, Д.Стоимость, Д.ГруппаФинансовогоУчета
    ИЗ РегистрНакопления.СтоимостьОС КАК Д
    УПОРЯДОЧИТЬ ПО Д.Период УБЫВ"""
    r2 = q2.Execute().Select()
    while r2.Next():
        print(f"    {r2.Период} | {S(r2.Регистратор)} | {S(r2.ОсновноеСредство)} | {r2.Стоимость} | ГФУ={S(r2.ГруппаФинансовогоУчета)}")

print("\n=== 3. ПринятиеКУчетуОС ІБ00-000245 — рухи ===")
q3 = conn.NewObject("Запрос")
q3.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.ПринятиеКУчетуОС КАК Д
    ГДЕ Д.Номер ПОДОБНО &Н И Д.Дата >= &Д"""
q3.SetParameter("Н", "%000245%")
q3.SetParameter("Д", datetime.datetime(2025, 12, 1))
r3 = q3.Execute().Select()
if r3.Next():
    ref = r3.Ссылка
    # СтоимостьОС
    q4 = conn.NewObject("Запрос")
    q4.Text = """ВЫБРАТЬ Д.ВидДвижения, Д.ОсновноеСредство, Д.Стоимость, Д.ГруппаФинансовогоУчета
    ИЗ РегистрНакопления.СтоимостьОС КАК Д ГДЕ Д.Регистратор = &С"""
    q4.SetParameter("С", ref)
    r4 = q4.Execute().Select()
    cnt = 0
    while r4.Next():
        cnt += 1
        print(f"  СтоимостьОС: {S(r4.ВидДвижения)} | {S(r4.ОсновноеСредство)} | {r4.Стоимость} | ГФУ={S(r4.ГруппаФинансовогоУчета)}")
    if cnt == 0:
        print("  СтоимостьОС: ПУСТО!")

    # ПрочиеРасходы
    q5 = conn.NewObject("Запрос")
    q5.Text = """ВЫБРАТЬ Д.ВидДвижения, Д.СтатьяРасходов, Д.Сумма
    ИЗ РегистрНакопления.ПрочиеРасходы КАК Д ГДЕ Д.Регистратор = &С"""
    q5.SetParameter("С", ref)
    r5 = q5.Execute().Select()
    cnt = 0
    while r5.Next():
        cnt += 1
        print(f"  ПрочиеРасходы: {S(r5.ВидДвижения)} | {S(r5.СтатьяРасходов)} | {r5.Сумма}")
    if cnt == 0:
        print("  ПрочиеРасходы: ПУСТО!")

print("\n=== 4. АмортизацияОС — документи за грудень 2025 ===")
q6 = conn.NewObject("Запрос")
q6.Text = """ВЫБРАТЬ ПЕРВЫЕ 5 Д.Ссылка, Д.Номер, Д.Дата, Д.Проведен
ИЗ Документ.АмортизацияОС КАК Д
ГДЕ Д.Дата >= &Д1 И Д.Дата <= &Д2
УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ"""
q6.SetParameter("Д1", datetime.datetime(2025, 12, 1))
q6.SetParameter("Д2", datetime.datetime(2026, 3, 31))
r6 = q6.Execute().Select()
cnt = 0
while r6.Next():
    cnt += 1
    print(f"  #{r6.Номер} від {r6.Дата} Проведен={r6.Проведен}")
if cnt == 0:
    print("  НЕМАЄ документів амортизації!")

print("\n=== 5. ПрочиеРасходы: РАСХОД за Капітальні інвестиції ===")
q7 = conn.NewObject("Запрос")
q7.Text = """ВЫБРАТЬ ПЕРВЫЕ 10
    Д.Период, Д.Регистратор, Д.ВидДвижения, Д.СтатьяРасходов, Д.Сумма
ИЗ РегистрНакопления.ПрочиеРасходы КАК Д
ГДЕ Д.СтатьяРасходов.Наименование ПОДОБНО &С
    И Д.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
УПОРЯДОЧИТЬ ПО Д.Период УБЫВ"""
q7.SetParameter("С", "%Капітальні інвестиції%")
r7 = q7.Execute().Select()
cnt = 0
while r7.Next():
    cnt += 1
    print(f"  {r7.Период} | {S(r7.Регистратор)} | РАСХОД | {r7.Сумма}")
if cnt == 0:
    print("  НЕМАЄ РАСХОД записів!")

