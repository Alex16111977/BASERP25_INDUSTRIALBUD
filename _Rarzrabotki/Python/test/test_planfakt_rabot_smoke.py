# -*- coding: utf-8 -*-
"""
Smoke-тест внешнего отчёта А_ПланФактныйАнализРабот.erf через COM.
Проверяет:
  1) .erf загружается (ВнешниеОтчеты.Создать) — компиляция OK;
  2) СКД компонуется в ТабличныйДокумент без ошибок (totalField/выражения/деление на 0);
  3) результат непустой;
  4) контрольная строка: подразделение "МД МХП ОРІЛЬ" план=440 факт=1906 %~433.
"""
import sys, os
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ПланФактныйАнализРабот.erf"
TXT = os.path.join(os.environ.get("TEMP", r"C:\Temp"), "pfr_smoke.txt")

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# 1) загрузка внешнего отчёта
report = erp.ВнешниеОтчеты.Создать(ERF, False)
print("OK  отчёт загружен:", report.Метаданные().Имя)

# схема + настройки по умолчанию
schema = report.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
print("OK  схема получена, вариантов настроек:", schema.ВариантыНастроек.Количество())

# поля набора данных (для расшифровки важно поле "Документ")
поля = []
набор = schema.НаборыДанных.Получить(0)
for i in range(набор.Поля.Количество()):
    поля.append(набор.Поля.Получить(i).Поле)
print("OK  поля схемы:", ", ".join(поля))
for ожид in ("Документ", "ФактСумма", "РазницаСумма", "ПроцентВыполненияСумма"):
    assert ожид in поля, f"НЕТ поля '{ожид}'!"
print("OK  поля факт-ЗП (ФактСумма/РазницаСумма/ПроцентВыполненияСумма) + Документ присутствуют")

настройки = schema.НастройкиПоУмолчанию

# 2) компоновка (генератор макета по умолчанию — для табличного документа)
компоновщикМакета = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных")
макет = компоновщикМакета.Выполнить(schema, настройки)

процессор = erp.NewObject("ПроцессорКомпоновкиДанных")
процессор.Инициализировать(макет)

табДок = erp.NewObject("ТабличныйДокумент")
выводТД = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
выводТД.УстановитьДокумент(табДок)
выводТД.Вывести(процессор)

h = табДок.ВысотаТаблицы
print("OK  скомпонован ТабличныйДокумент, ВысотаТаблицы =", h)
assert h > 0, "ПУСТОЙ результат — компоновка ничего не вывела"

табДок.Записать(TXT)
with open(TXT, encoding="utf-8", errors="replace") as f:
    txt = f.read()

# 3) контроль: ОРІЛЬ присутствует
есть_ориль = ("ОРІЛЬ" in txt) or ("ОРIЛЬ" in txt)
print("OK  строк в выводе:", len(txt.splitlines()), "| есть ОРІЛЬ:", есть_ориль)

# контрольные подразделения с фактом (должны быть)
for ключ in ("Глобино", "Главный офис", "ОРІЛЬ"):
    print(f"    содержит '{ключ}':", ключ in txt)

print("\n=== первые 60 строк вывода ===")
for ln in txt.splitlines()[:60]:
    print(ln)

print("\nSMOKE: PASS")
