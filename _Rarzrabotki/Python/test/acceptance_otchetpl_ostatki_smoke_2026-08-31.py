import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ПРОВАЛОВ = [0]


def чек(имя, ок, подробно=""):
    if not ок:
        ПРОВАЛОВ[0] += 1
    print("  [%s] %s%s" % ("OK  " if ок else "FAIL", имя, ("  — " + подробно) if подробно else ""))


def скаляр(текст, **парам):
    q = erp.NewObject("Запрос")
    q.Text = текст
    for k, v in парам.items():
        q.SetParameter(k, v)
    r = q.Execute().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() else None


def подр(имя):
    return скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтруктураПредприятия ГДЕ Наименование = &Имя',
                  Имя=имя)


def вариант(имя):
    return скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Вар.Ссылка КАК Ссылка ИЗ Справочник.ВариантыОтчетов КАК Вар '
                  'ГДЕ Вар.Наименование = &Имя', Имя=имя)


def сформировать(менеджер, вар, подразделения):
    отчет = менеджер.Создать()
    к = отчет.КомпоновщикНастроек
    к.Инициализировать(erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных",
                                     отчет.СхемаКомпоновкиДанных))
    к.ЗагрузитьНастройки(вар.Настройки.Получить())
    н = к.Настройки
    г = erp.NewObject("Запрос")
    г.Text = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,7,1,0,0,0) КАК Н, ДАТАВРЕМЯ(2026,7,31,23,59,59) КАК К"
    гр = г.Execute().Выгрузить().Получить(0)
    п = erp.NewObject("СтандартныйПериод")
    п.ДатаНачала = гр.Н
    п.ДатаОкончания = гр.К
    эл = н.ПараметрыДанных.Элементы.Найти("Период")
    эл.Использование = True
    эл.Значение = п

    # отборы по Подразделению: как обработка выгрузки — пара «В списке»/«В группе из списка»
    def обойти(элементы):
        for i in range(элементы.Количество()):
            о = элементы.Получить(i)
            имя_типа = S(erp.NewObject("ОписаниеТипов").ПустаяСсылка) if False else ""
            try:
                поле = S(о.ЛевоеЗначение)
            except Exception:
                try:
                    обойти(о.Элементы)
                except Exception:
                    pass
                continue
            if поле == "Подразделение":
                видср = S(о.ВидСравнения)
                сп = erp.NewObject("СписокЗначений")
                for x in подразделения:
                    сп.Добавить(x)
                if видср == "В группе из списка":
                    о.ПравоеЗначение = сп
                    о.Использование = True
                elif видср == "В списке":
                    о.Использование = False
                elif "Не в" not in видср:
                    о.ПравоеЗначение = сп
                    о.Использование = True
    обойти(н.Отбор.Элементы)

    # Пользовательские группировки раскрытия (Аналитика/Документ/Контрагент) дробят
    # накопительные строки по регистраторам; источник накопительных сменился по дизайну,
    # поэтому сверяем статьи без раскрытия — как в приёмках v11 (агрегатная сверка).
    ЛИШНИЕ = {"Аналитика", "Аналитика1", "Документ", "Контрагент", "Комментарий"}

    def поля_группировки(гр):
        имена = set()
        try:
            пг = гр.ПоляГруппировки.Элементы
            for i in range(пг.Количество()):
                try:
                    имена.add(S(пг.Получить(i).Поле))
                except Exception:
                    pass
        except Exception:
            pass
        return имена

    def выключить_раскрытие(структура):
        for i in range(структура.Количество()):
            эл = структура.Получить(i)
            try:
                if поля_группировки(эл) & ЛИШНИЕ:
                    эл.Использование = False
                    continue
            except Exception:
                pass
            for кол in ("Структура", "Строки", "Колонки"):
                try:
                    выключить_раскрытие(getattr(эл, кол))
                except Exception:
                    pass
    выключить_раскрытие(н.Структура)

    таб = erp.NewObject("ТабличныйДокумент")
    отчет.СкомпоноватьРезультат(таб)
    return таб


def снимок(таб, пропустить_шапку=6):
    в, ш = int(таб.ВысотаТаблицы), int(таб.ШиринаТаблицы)
    ячейки = []
    for r in range(пропустить_шапку + 1, в + 1):
        строка = []
        for c in range(1, ш + 1):
            строка.append(S(таб.Область(r, c, r, c).Текст).strip())
        ячейки.append(строка)
    return в, ш, ячейки


СТАРЫЙ = erp.Отчеты.А_ОтчетPL_ПолныйЕРП
НОВЫЙ = erp.Отчеты.А_ОтчетPL_ПолныйЕРП_Остатки

СЦЕНАРИИ = [
    ("объектный лист МК Кривий ріг", "P&L: Месяц, PL с начала года", ["МК Кривий ріг"]),
    ("свод Логистика (3 MAN)", "P&L: Месяц, PL с начала года (для свода)",
     ["MAN №3 white KA7837HO", "MAN №4 white KA3597HO", "MAN №5 KA5697НВ"]),
]

for имя, имя_вар, имена_подр in СЦЕНАРИИ:
    print("=" * 92)
    print("Сценарий:", имя)
    print("=" * 92)
    вар = вариант(имя_вар)
    чек("вариант найден", вар is not None, имя_вар)
    подразделения = [подр(x) for x in имена_подр]
    чек("подразделения найдены", all(x is not None for x in подразделения))
    try:
        т_нов = сформировать(НОВЫЙ, вар, подразделения)
        чек("новый отчёт строится", int(т_нов.ВысотаТаблицы) > 10, "строк %d" % int(т_нов.ВысотаТаблицы))
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        чек("новый отчёт строится", False, msg[:200])
        continue
    т_стар = сформировать(СТАРЫЙ, вар, подразделения)
    в1, ш1, я1 = снимок(т_стар)
    в2, ш2, я2 = снимок(т_нов)
    чек("размеры совпадают", (в1, ш1) == (в2, ш2), "старый %sx%s, новый %sx%s" % (в1, ш1, в2, ш2))
    расх = 0
    первое = ""
    for i in range(min(len(я1), len(я2))):
        for j in range(min(len(я1[i]), len(я2[i]))):
            if я1[i][j] != я2[i][j]:
                расх += 1
                if not первое:
                    первое = "r%d c%d: «%s» → «%s»" % (i + 7, j + 1, я1[i][j][:30], я2[i][j][:30])
    чек("ячейки совпадают", расх == 0, ("расхождений %d, первое: %s" % (расх, первое)) if расх else "")

print("=" * 92)
print("ПРОВАЛОВ: %d" % ПРОВАЛОВ[0])
