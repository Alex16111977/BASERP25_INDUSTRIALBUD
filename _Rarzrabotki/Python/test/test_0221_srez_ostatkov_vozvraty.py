# -*- coding: utf-8 -*-
"""
Срез остатков РегистрБухгалтерии.Хозрасчетный по «Біта РZ 2*50 мм» на РЕАЛЬНЫЙ
МоментВремени каждого возврата + полные проводки документа по «Біті» (все счета).
Цель: показать, из какого остатка/счёта берётся себестоимость Кт 0221. Rule #-1.
"""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
def S(x):
    try: return buh.String(x)
    except Exception: return str(x)

счет0221 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("0221").Ссылка
видНом = buh.ПланыВидовХарактеристик.ВидыСубконтоХозрасчетные.Номенклатура
видКонтр = buh.ПланыВидовХарактеристик.ВидыСубконтоХозрасчетные.Контрагенты
видСклад = buh.ПланыВидовХарактеристик.ВидыСубконтоХозрасчетные.Склады

# триплет из резидуума 548.80
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Ост.Субконто1 КАК К, Ост.Субконто2 КАК Н, Ост.Субконто3 КАК С, Ост.СуммаОстатокДт КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет = &Счет) КАК Ост
ГДЕ Ост.КоличествоОстатокДт = 0 И Ост.СуммаОстатокДт <> 0
"""
q.УстановитьПараметр("Счет", счет0221)
q.УстановитьПараметр("НаДату", datetime.datetime(2026,7,13,23,59,59))
r = q.Выполнить().Выгрузить()
цель=None
for i in range(r.Количество()):
    s=r.Получить(i)
    if 548.0<float(s.Сумма)<549.0: цель=s; break
ном, контр, склад = цель.Н, цель.К, цель.С
имяНом = S(ном)
print(f"Біта={имяНом} | {S(контр)} | {S(склад)}\n")

номера = ["СТ00-000038","СТ00-000070","СТ00-000082","СТ00-000103"]
верх = datetime.datetime(2026,6,30,23,59,59)

def остаток_триплет(момент):
    q2 = buh.NewObject("Запрос")
    q2.Текст = """
    ВЫБРАТЬ СУММА(Ост.КоличествоОстатокДт) КАК Кол, СУММА(Ост.СуммаОстатокДт) КАК Сум
    ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Т, Счет=&Счет, , Субконто2=&Н И Субконто1=&К И Субконто3=&С) КАК Ост
    """
    q2.УстановитьПараметр("Счет",счет0221); q2.УстановитьПараметр("Н",ном)
    q2.УстановитьПараметр("К",контр); q2.УстановитьПараметр("С",склад); q2.УстановитьПараметр("Т",момент)
    row = q2.Выполнить().Выгрузить().Получить(0)
    return float(row.Кол or 0), float(row.Сум or 0)

def субк(колл, вид):
    try:
        v = колл.Получить(вид);  return S(v) if v else ""
    except Exception: return ""

print(f"{'Возврат':<14} | {'остаток 0221[триплет] ПЕРЕД проведением':^40} | списано Кт0221")
print(f"{'':<14} | {'кол':>6} {'сумма':>10} {'ср/ед':>8}  coef×Стоим? | ")
print("-"*92)
for н in номера:
    док = buh.Документы.ВозвратТоваровПоставщику.НайтиПоНомеру(н, верх)
    если_пусто = (док == buh.Документы.ВозвратТоваровПоставщику.ПустаяСсылка())
    if если_пусто:
        print(f"{н}: не найден"); continue
    мв = док.МоментВремени()
    к,с = остаток_триплет(мв)   # Остатки(МоментВремени) = баланс ПЕРЕД документом
    ср = с/к if к else 0
    print(f"{н:<14} | {к:>6.1f} {с:>10.2f} {ср:>8.2f} |")

print("\n=== Полные проводки Хозрасчетный по «Біті» в каждом возврате (все счета) ===")
for н in номера:
    док = buh.Документы.ВозвратТоваровПоставщику.НайтиПоНомеру(н, верх)
    об = док.ПолучитьОбъект()
    дв = об.Движения.Хозрасчетный
    дв.Прочитать()
    print(f"\n{н} ({S(док.Дата)}):")
    for i in range(дв.Количество()):
        з = дв.Получить(i)
        нД = субк(з.СубконтоДт, видНом); нК = субк(з.СубконтоКт, видНом)
        if имяНом not in (нД, нК):  # только строки по Біті
            continue
        счД = S(з.СчетДт) if з.СчетДт else "—"
        счК = S(з.СчетКт) if з.СчетКт else "—"
        колД = float(з.КоличествоДт or 0); колК = float(з.КоличествоКт or 0)
        сум = float(з.Сумма or 0)
        стор = субк(з.СубконтоКт, видСклад) or субк(з.СубконтоДт, видСклад)
        контрК = субк(з.СубконтоКт, видКонтр) or субк(з.СубконтоДт, видКонтр)
        print(f"   Дт {счД:<8} / Кт {счК:<8} | кол={max(колД,колК):>5.1f} | сум={сум:>9.2f} | ср/ед={(сум/max(колД,колК) if max(колД,колК) else 0):>8.2f} | {контрК[:18]} | {стор[:20]}")
