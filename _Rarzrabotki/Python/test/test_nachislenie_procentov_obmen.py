"""Нарахування відсотків: «Приобретения» відсотків лише в ЕРП (план 2026-10-16, Task 5; дизайн §6.4).

Структурна перевірка: жоден план обміну з непоміченими зовнішніми вузлами не містить у складі
Документ.ПриобретениеТоваровУслуг. Якщо тест впаде — ПТУ відсотків потрібно відсікати в реєстрації окремо.
Код виходу 0 = OK.
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ok = True
ПТУ = erp.Метаданные.Документы.ПриобретениеТоваровУслуг


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


з_вузлами = []
for i in range(erp.Метаданные.ПланыОбмена.Количество()):
    план = erp.Метаданные.ПланыОбмена.Получить(i)
    имя = S(план.Имя)
    if имя == "ОбновлениеИнформационнойБазы":
        continue  # службовий план БСП (черга відкладеного оновлення), не обмін з іншою базою
    z = erp.NewObject("Запрос")
    z.Text = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ ПланОбмена.{имя} КАК У ГДЕ НЕ У.ЭтотУзел И НЕ У.ПометкаУдаления"
    вузлів = int(z.Execute().Выгрузить().Получить(0).Получить(0))
    if вузлів:
        з_вузлами.append(имя)
        check(not план.Состав.Содержит(ПТУ), f"test_obmen_strukturno: {имя} ({вузлів} зовн. вузлів) — ПТУ не в складі")
check("ОбменУправлениеПредприятиемБухгалтерия20" in з_вузлами and "КазначействоBASERP" in з_вузлами,
      f"плани із зовнішніми вузлами знайдено: {з_вузлами}")
sys.exit(0 if ok else 1)
