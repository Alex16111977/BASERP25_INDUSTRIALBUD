# -*- coding: utf-8 -*-
"""Pre-test (Rule #-1): запрос с Партнёром через Контрагент.Партнер.
Путь ВЫРАЗИТЬ(Вз.КонтрагентДебитор КАК Справочник.Контрагенты).Партнер уже используется
в боевом запросе (.Партнер.А_Подразделение). Проверяем: Партнёр заполнен для всех боевых
проведённых взаимозачётов (иначе при замене измерения появятся пустые строки).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import pythoncom, win32com.client

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Вз.Ссылка КАК Взаимозачет,
    ПРЕДСТАВЛЕНИЕ(Вз.КонтрагентДебитор) КАК КонтрДеб,
    ВЫРАЗИТЬ(Вз.КонтрагентДебитор КАК Справочник.Контрагенты).Партнер КАК ПартнДебСсылка,
    ВЫРАЗИТЬ(Вз.КонтрагентКредитор КАК Справочник.Контрагенты).Партнер КАК ПартнКредСсылка,
    ПРЕДСТАВЛЕНИЕ(ВЫРАЗИТЬ(Вз.КонтрагентДебитор КАК Справочник.Контрагенты).Партнер) КАК ПартнДеб,
    ПРЕДСТАВЛЕНИЕ(ВЫРАЗИТЬ(Вз.КонтрагентКредитор КАК Справочник.Контрагенты).Партнер) КАК ПартнКред
ИЗ
    Документ.ВзаимозачетЗадолженности КАК Вз
ГДЕ
    Вз.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО
    И НЕ Вз.ПометкаУдаления
    И Вз.Проведен
"""
try:
    sel = q.Выполнить().Выбрать()
except Exception as e:
    msg = e.excepinfo[2] if (hasattr(e, 'excepinfo') and e.excepinfo) else str(e)
    print("FAIL запроса:", msg); sys.exit(1)

n = 0
пустДеб = 0
пустКред = 0
показано = 0
while sel.Следующий():
    n += 1
    dbf = erp.ЗначениеЗаполнено(sel.ПартнДебСсылка)
    krf = erp.ЗначениеЗаполнено(sel.ПартнКредСсылка)
    if not dbf:
        пустДеб += 1
    if not krf:
        пустКред += 1
    if показано < 6:
        print(f"  {sel.КонтрДеб!s:30.30} -> ПартнёрДеб={sel.ПартнДеб!s} | ПартнёрКред={sel.ПартнКред!s}")
        показано += 1

print(f"\nвсего проведённых взаимозачётов с основанием: {n}")
print(f"пустой Партнёр-дебитор: {пустДеб}; пустой Партнёр-кредитор: {пустКред}")
print("OK — Контрагент.Партнер заполнен везде" if (n > 0 and пустДеб == 0 and пустКред == 0)
      else "ВНИМАНИЕ: есть пустые партнёры — замена даст пустые строки")
