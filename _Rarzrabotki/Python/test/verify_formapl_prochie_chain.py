def depipe(lit):
    out = []
    for i, ln in enumerate(lit.split("\n")):
        if i == 0:
            out.append(ln)
        else:
            k = ln.find("|")
            out.append(ln[k+1:] if k >= 0 else ln)
    return "\n".join(out).replace('""', '"')

def extract(anchor):
    """Извлечь строковый литерал запроса, начиная с anchor (имя переменной/маркер)."""
    i = content.index(anchor)
    j = content.index('"', i)          # открывающая кавычка
    k = content.index('";', j + 1)     # закрывающая ";
    return depipe(content[j+1:k])

def extract_by_pomest(pomest_name):
    """Извлечь запрос по маркеру ПОМЕСТИТЬ <name>: открывающая кавычка — последняя перед маркером."""
    m = content.index("ПОМЕСТИТЬ " + pomest_name)
    j = content.rindex('"', 0, m)      # открывающая кавычка ДО ПОМЕСТИТЬ
    k = content.index('";', m)         # закрывающая ПОСЛЕ ПОМЕСТИТЬ
    return depipe(content[j+1:k])

