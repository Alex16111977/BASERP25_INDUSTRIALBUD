# -*- coding: utf-8 -*-
"""Пре-тест (Rule #-1) запросов правила 5 справочника А_Статьи_PL:
уникальность СтатьяРасходов между PL-статьями (зеркало проверки ДДС).

Тексты запросов 1:1 как в Catalogs/А_Статьи_PL/Ext/ObjectModule.bsl,
процедура ПроверитьУникальностьСтатьиРасходов().
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

FAILS = 0


def run(name, text, params=None):
    global FAILS
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    try:
        r = q.Execute().Выгрузить()
        print(f"[{name}] OK rows={r.Количество()}")
        return r
    except Exception as e:
        FAILS += 1
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"[{name}] FAIL: {msg}")
        return None


# --- подбор реальных параметров ---
r0 = run("подбор СтатьяРасходов", """
ВЫБРАТЬ ПЕРВЫЕ 1
    ТЧ.СтатьяРасходов КАК СР,
    ТЧ.Ссылка КАК PL
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ ТЧ.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
    И НЕ ТЧ.Ссылка.ПометкаУдаления
""")
if r0 is None or r0.Количество() == 0:
    print("Нет строк ТЧ с заполненной СтатьяРасходов — пре-тест невозможен")
    sys.exit(1)

СРМассив = erp.NewObject("Массив")
СРМассив.Добавить(r0.Получить(0).СР)
PLСсылка = r0.Получить(0).PL
print("   СР:", S(r0.Получить(0).СР), "| PL:", S(PLСсылка))

# Период: начало с временем 03:00 (COM сдвигает −3ч), конец — считает 1С
now = datetime.datetime.now()
НП = datetime.datetime(now.year - 1, now.month, 1, 3, 0, 0)
qk = erp.NewObject("Запрос")
qk.Text = "ВЫБРАТЬ КОНЕЦПЕРИОДА(&Д, МЕСЯЦ) КАК Д"
qk.SetParameter("Д", datetime.datetime(now.year, now.month, 1, 3, 0, 0))
КП = qk.Execute().Выгрузить().Получить(0).Д
print("   Период:", НП, "-", КП)

# --- Запрос 1: конфликты по другим PL-статьям (1:1 из BSL) ---
run("Запрос 1 конфликты", """
ВЫБРАТЬ
	ТЧ.СтатьяРасходов КАК СтатьяРасходов,
	ТЧ.Ссылка КАК PLСсылка
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ ТЧ.СтатьяРасходов В (&СРМассив)
	И ТЧ.Ссылка <> &Ссылка
	И НЕ ТЧ.Ссылка.ПометкаУдаления
""", {"СРМассив": СРМассив, "Ссылка": PLСсылка})

# --- Запрос 2: обороты ПрочиеРасходы по СтатьяРасходов за 12 мес (1:1 из BSL) ---
run("Запрос 2 обороты", """
ВЫБРАТЬ
	Об.СтатьяРасходов КАК СтатьяРасходов,
	СУММА(Об.СуммаРеглПриход) КАК Сумма
ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(&НП, &КП, , ) КАК Об
ГДЕ Об.СтатьяРасходов В (&СРМассив)
СГРУППИРОВАТЬ ПО Об.СтатьяРасходов
ИМЕЮЩИЕ СУММА(Об.СуммаРеглПриход) > 0
""", {"СРМассив": СРМассив, "НП": НП, "КП": КП})

print(f"ПРЕ-ТЕСТ: запросов 3, провалов {FAILS}")
sys.exit(1 if FAILS else 0)
