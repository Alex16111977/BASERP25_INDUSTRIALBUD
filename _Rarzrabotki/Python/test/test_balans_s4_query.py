qp.УстановитьПараметр("Орг",org); qp.УстановитьПараметр("Искл",ИсклСт)
tpp = qp.Выполнить().Выгрузить()
pap = {str(conn.XMLСтрока(tpp.Получить(i).Статья)): float(tpp.Получить(i).sK or 0) for i in range(tpp.Количество())}

bad=[]
for k in set(got)|set(pap):
    d=abs(got.get(k,0)-pap.get(k,0))
    lim = TOL_ОТ if k==ОТ_key else TOL
    if d>lim: bad.append((k,got.get(k,0),pap.get(k,0),d))
print(f"ОбъектРасчетов={cОР} Номенклатура={cНом} ДенежныеСредства={cДС} | ФизическоеЛицо(Оплата труда)={cФЛ_ОТ}")
print(f"Σ КонОст={sumK:,.2f} | «Оплата труда»: запит={got.get(ОТ_key,0):,.2f} ПАП={pap.get(ОТ_key,0):,.2f} Δ={abs(got.get(ОТ_key,0)-pap.get(ОТ_key,0)):,.4f}")
if bad:
    print(f"FAIL: {len(bad)} статей розбіжні понад допуск:")
    for k,a,b,d in sorted(bad,key=lambda x:-x[3])[:10]:
        print(f"  {k[:46]:<48} зап={a:>16,.2f} ПАП={b:>16,.2f} Δ={d:,.4f}")
    sys.exit(1)
assert abs(sumK) < 1.0, f"FAIL: Актив≠Пасив Σ={sumK:,.2f}"
assert cФЛ_ОТ > 0, "FAIL: ФизическоеЛицо для «Оплата труда» не заповнено (розклад не спрацював)"
assert cОР>0 and cНом>0 and cДС>0, "FAIL: субконто Етапів 2-3 втрачені"
print("PASS Етап4 запит (Rule #-1) — Σ==ПАП (ОТ розклад зберіг суму), ФизическоеЛицо заповнено")
