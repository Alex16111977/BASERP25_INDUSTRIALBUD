qo = conn.NewObject("Запрос")
qo.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Оплата труда"'
so = qo.Выполнить().Выбрать(); so.Следующий(); ОТ = so.С
ОТ_key = str(conn.XMLСтрока(ОТ))

QTEXT = open(r"C:\Configuration_downloads\BASERP25\.claude\worktrees\peaceful-knuth-51295b\_Rarzrabotki\Python\test\_s4_query.txt", encoding="utf-8").read()
q = conn.NewObject("Запрос")
q.Текст = QTEXT
q.УстановитьПараметр("НачалоПериода", НМ)
q.УстановитьПараметр("КонецПериода", КД)
q.УстановитьПараметр("Организация", org)
q.УстановитьПараметр("ВключатьДочерние", False)
q.УстановитьПараметр("ИсключенныеСтатьи", ИсклСт)
q.УстановитьПараметр("СтатьяОплатаТруда", ОТ)
tz = q.Выполнить().Выгрузить()
