print(f"rows={n}")
assert n > 0, "FAIL: 0 рядків"

got = {}; sumK=0.0; cОР=cНом=cДС=cФЛ_ОТ=0
for i in range(n):
    r = tz.Получить(i)
    k = str(conn.XMLСтрока(r.Статья))
    got[k] = got.get(k,0.0) + float(r.СуммаКонечныйОстаток or 0)
    sumK += float(r.СуммаКонечныйОстаток or 0)
    if r.ОбъектРасчетов and conn.ЗначениеЗаполнено(r.ОбъектРасчетов): cОР+=1
    if r.Номенклатура and conn.ЗначениеЗаполнено(r.Номенклатура): cНом+=1
    if r.ДенежныеСредства and conn.ЗначениеЗаполнено(r.ДенежныеСредства): cДС+=1
    if k == ОТ_key and r.ФизическоеЛицо and conn.ЗначениеЗаполнено(r.ФизическоеЛицо): cФЛ_ОТ+=1

qp = conn.NewObject("Запрос")
qp.Текст = """ВЫБРАТЬ Б.Статья КАК Статья, СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
    Организация=&Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
СГРУППИРОВАТЬ ПО Б.Статья ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток)<>0"""
