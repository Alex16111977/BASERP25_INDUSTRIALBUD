"""Етап 4 Rule #-1: ТОЧНИЙ текст запиту (1:1 з BSL, 3-частковий UNION +
розклад «Оплата труда» по ФизическоеЛицо) ПЕРЕД db-load.
Перевіряє: виконується; Σ по Статья == ПАП (пост-інваріант, розклад зберіг суму);
ФизическоеЛицо заповнено для «Оплата труда»; субконто Етапів 2-3 збережені;
Актив=Пасив Σ≈0. Період серверно січень. Типові регістри лише читаються."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
