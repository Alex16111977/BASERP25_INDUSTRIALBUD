def палітра(тд):
    h, w = тд.ВысотаТаблицы, тд.ШиринаТаблицы
    s = {}
    for r in range(1, h + 1):
        for c in range(1, w + 1):
            col = тд.Область(r, c, r, c).ЦветФона
            try:
                k = (int(col.R), int(col.G), int(col.B))
            except Exception:
                k = None
            s[k] = s.get(k, 0) + 1
    return h, w, s

