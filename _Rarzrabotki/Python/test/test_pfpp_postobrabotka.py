# -*- coding: utf-8 -*-
# Полная репликация ObjectModule.ПолучитьДанные (запрос + постобработка Этап/Категория)
# на реальной базе через Enterprise-COM — проверка разреза Вир/Монт факт-материалов
# БЕЗ пересборки .erf (Designer не нужен).
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
assert not сс.Пустая()
НП = datetime.datetime(2020, 1, 1)
КП = datetime.datetime(2030, 12, 31, 23, 59, 59)

# === Грейн ТЗ (как ВТ_Детали, сгруппированный по 5 измерениям) ===
q = erp.NewObject("Запрос")
q.УстановитьПараметр("СтруктураСебестоимости", сс.Ссылка)
q.УстановитьПараметр("НачП", НП)
q.УстановитьПараметр("КонП", КП)
q.Текст = """
ВЫБРАТЬ СС.Ссылка КАК СС, СС.Подразделение КАК Подр, СС.СкладПроизводство КАК СкладВир, СС.СкладМонтаж КАК СкладМонт
ПОМЕСТИТЬ ВТ_СС ИЗ Справочник.А_СтруктураСебестоимости КАК СС ГДЕ СС.Ссылка = &СтруктураСебестоимости
;
ВЫБРАТЬ ВТ_СС.Подр КАК Подразделение, "1. Праця" КАК Блок,
    ВЫБОР КОГДА Р.НаВыезде ТОГДА "Монтаж" ИНАЧЕ "Виробництво" КОНЕЦ КАК Категория,
    Р.Этап КАК Этап, Р.Работа КАК Аналитика,
    Р.Количество КАК ПланЧасы, 0 КАК ФактЧасы, Р.Сумма КАК ПланГрн, 0 КАК ФактГрн
ПОМЕСТИТЬ ВТ_Детали
ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТ_СС КАК ВТ_СС ПО Р.Ссылка = ВТ_СС.СС
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ ВТ_СС.Подр, "2. Матеріали",
    ВЫБОР КОГДА К.Этап.Наименование ПОДОБНО "%Монтаж%" ТОГДА "Монтаж" ИНАЧЕ "Виробництво" КОНЕЦ,
    К.Этап, К.Номенклатура, 0, 0, К.Сумма, 0
ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТ_СС КАК ВТ_СС ПО К.Ссылка = ВТ_СС.СС
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ Т.Подразделение, "1. Праця", "Виробництво", НЕОПРЕДЕЛЕНО, Т.Сотрудник.СотрудникЕРП.ФизическоеЛицо, 0, Т.ЧасыФакт, 0, 0
ИЗ РегистрНакопления.А_ДанныеТабелирования КАК Т ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТ_СС КАК ВТ_СС ПО Т.Подразделение = ВТ_СС.Подр
ГДЕ Т.Период МЕЖДУ &НачП И &КонП
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ ВЗ.Подразделение, "1. Праця", "Виробництво", НЕОПРЕДЕЛЕНО, ВЗ.ФизическоеЛицо, 0, 0, 0, ВЗ.СуммаВзаиморасчетов
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВЗ ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТ_СС КАК ВТ_СС ПО ВЗ.Подразделение = ВТ_СС.Подр
ГДЕ ВЗ.Регистратор ССЫЛКА Документ.ОтражениеЗарплатыВФинансовомУчете
    И ВЗ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) И ВЗ.Период МЕЖДУ &НачП И &КонП
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ ВТ_СС.Подр, "2. Матеріали", "Виробництво", НЕОПРЕДЕЛЕНО,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура, 0, 0, 0, СТ.СтоимостьБезНДС
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТ_СС КАК ВТ_СС
    ПО ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение = ВТ_СС.Подр
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
    И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг И СТ.Период МЕЖДУ &НачП И &КонП
;
ВЫБРАТЬ Подразделение, Блок, Категория, Этап, Аналитика,
    СУММА(ПланЧасы) КАК ПланЧасы, СУММА(ФактЧасы) КАК ФактЧасы, СУММА(ПланГрн) КАК ПланГрн, СУММА(ФактГрн) КАК ФактГрн
ИЗ ВТ_Детали СГРУППИРОВАТЬ ПО Подразделение, Блок, Категория, Этап, Аналитика
"""
тз = q.Выполнить().Выгрузить()

# === Маппинг ОбщееНазвание -> {Этап, Категория} (как МаппингОбщееНазваниеЭтап) ===
qm = erp.NewObject("Запрос")
qm.УстановитьПараметр("Имя", сс.Наименование)
qm.Текст = """
ВЫБРАТЬ К.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ОбщееНазвание, К.Этап КАК Этап,
    ВЫБОР КОГДА К.Этап.Наименование ПОДОБНО "%Монтаж%" ТОГДА "Монтаж" ИНАЧЕ "Виробництво" КОНЕЦ КАК Категория
ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Наименование = &Имя
    И К.Номенклатура.А_ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.А_ОбщиеНазванияНоменклатуры.ПустаяСсылка)
    И К.Этап <> ЗНАЧЕНИЕ(Справочник.А_ЭтапыРабот.ПустаяСсылка)
"""
маппинг = {}
выб = qm.Выполнить().Выбрать()
while выб.Следующий():
    ключ = (выб.ОбщееНазвание or "").strip()
    if not ключ:
        continue
    тек = маппинг.get(ключ)
    if тек is None or str(выб.Этап) > str(тек[0]):
        маппинг[ключ] = (выб.Этап, выб.Категория)

# === Постобработка: ставим Этап + Категория для факт-материалов ===
def пустой_этап(этап):
    if этап is None:
        return True
    try:
        return bool(этап.Пустая())
    except Exception:
        return False  # это заполненная ссылка

def это_номенклатура(ан):
    try:
        return str(type(ан)) and hasattr(ан, "А_ОбщееНазваниеНоменклатуры")
    except Exception:
        return False

смаплено = 0
for i in range(тз.Количество()):
    r = тз.Получить(i)
    if r.Блок != "2. Матеріали" or not пустой_этап(r.Этап):
        continue
    if not это_номенклатура(r.Аналитика):
        continue
    он = r.Аналитика.А_ОбщееНазваниеНоменклатуры
    if он is None or он.Пустая():
        continue
    ключ = (он.Наименование or "").strip()
    данные = маппинг.get(ключ)
    if данные is not None:
        r.Этап = данные[0]
        r.Категория = данные[1]
        смаплено += 1

# === Реагрегация Блок x Категория (как делает СКД) ===
агр = {}
for i in range(тз.Количество()):
    r = тз.Получить(i)
    k = (r.Блок, r.Категория)
    a = агр.setdefault(k, [0.0, 0.0, 0.0, 0.0])
    a[0] += float(r.ПланЧасы); a[1] += float(r.ФактЧасы); a[2] += float(r.ПланГрн); a[3] += float(r.ФактГрн)

print(f"Строк грейна={тз.Количество()}, факт-материалов смаплено по этапу={смаплено}\n")
print(f"{'Блок':14} {'Категория':12} {'ПланЧ':>7} {'ФактЧ':>7} {'ПланГрн':>14} {'ФактГрн':>14}")
итог = [0.0, 0.0, 0.0, 0.0]
for k in sorted(агр):
    a = агр[k]
    print(f"{k[0]:14} {k[1]:12} {a[0]:7.0f} {a[1]:7.0f} {a[2]:14.2f} {a[3]:14.2f}")
    for j in range(4): итог[j] += a[j]
print(f"{'ИТОГО':27} {итог[0]:7.0f} {итог[1]:7.0f} {итог[2]:14.2f} {итог[3]:14.2f}")
мат_вир = агр.get(("2. Матеріали", "Виробництво"), [0,0,0,0])[3]
мат_мон = агр.get(("2. Матеріали", "Монтаж"), [0,0,0,0])[3]
print(f"\nФакт-матеріали: Виробництво={мат_вир:.2f}  Монтаж={мат_мон:.2f}  Σ={мат_вир+мат_мон:.2f}")
print("Кросс-контроль Σ факт-матеріалів должен = 1620137.97 (reference-стиль по подразделению)")
