print("строк", len(R), "документов", len({r["Док"] for r in R}))
print("Σ нетто", fmt(sum(D(r["Нетто"]) for r in R)), "Σ НДС", fmt(sum(D(r["НДС"]) for r in R)), "Σ брутто", fmt(sum(D(r["Брутто"]) for r in R)))
