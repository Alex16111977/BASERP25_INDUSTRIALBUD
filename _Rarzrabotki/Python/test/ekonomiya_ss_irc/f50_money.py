"""Ф4. Деньги IRC в ERP: (1) факт оплат — зеркало казны РН.А_ДвиженияДенегИзКазны (подразделение в иерархии
«МД IRC 2026»), по статьям, месяцам, контрагентам; (2) бюджет экономиста РН.А_ПредварительныйБюджетНаМесяц,
сценарии 00007/00008 по статьям и месяцам. Только чтение."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from common import *
from collections import defaultdict

E = erp()
ROOT_Q = """
ВЫБРАТЬ ПЕРВЫЕ 1 СС.ПодразделениеЗакупки КАК Корень
ПОМЕСТИТЬ ВТ_Корень
ИЗ Справочник.А_СтруктураСебестоимости КАК СС
ГДЕ СС.Наименование ПОДОБНО "%IR%" И НЕ СС.ПометкаУдаления
;
"""
vt = q(E, ROOT_Q + """
ВЫБРАТЬ
	Д.Период КАК Период,
	Д.СтатьяДвиженияДенежныхСредств.Код КАК СтКод,
	Д.СтатьяДвиженияДенежныхСредств.Наименование КАК Статья,
	Д.Подразделение КАК Подр,
	Д.ПодразделениеКазна КАК ПодрКазна,
	Д.ТипДенежныхСредств КАК ТипДС,
	Д.Сумма КАК Сумма,
	Д.ДокументДвиженияКазны КАК Док,
	ВЫРАЗИТЬ(Д.ТекстДокументаКазны КАК СТРОКА(150)) КАК ТекстДок,
	ЕСТЬNULL(ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.СписаниеБезналичныхДенежныхСредств).Контрагент,
		ЕСТЬNULL(ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.РасходныйКассовыйОрдер).Контрагент,
			ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.ПоступлениеБезналичныхДенежныхСредств).Контрагент)) КАК Контрагент,
	ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.РасходныйКассовыйОрдер).ПодотчетноеЛицо КАК Подотчет
ИЗ
	РегистрНакопления.А_ДвиженияДенегИзКазны КАК Д
ГДЕ
	(Д.Подразделение В ИЕРАРХИИ (ВЫБРАТЬ ВТ_Корень.Корень ИЗ ВТ_Корень КАК ВТ_Корень)
		ИЛИ Д.ПодразделениеКазна В ИЕРАРХИИ (ВЫБРАТЬ ВТ_Корень.Корень ИЗ ВТ_Корень КАК ВТ_Корень))
	И Д.Период МЕЖДУ ДАТАВРЕМЯ(2026, 1, 1) И ДАТАВРЕМЯ(2026, 12, 31, 23, 59, 59)
""")
M = rows(E, vt, ["Период", "СтКод", "Статья", "Подр", "ПодрКазна", "ТипДС", "Сумма", "Док", "ТекстДок", "Контрагент", "Подотчет"])
for r in M: r["Период"] = str(r["Период"])[:19]
dump_json(M, "money_kazna.json")
st = defaultdict(lambda: defaultdict(Decimal))
for r in M:
    st[(r["СтКод"], r["Статья"])][r["Период"][:7]] += D(r["Сумма"])
print("ФАКТ КАЗНЫ IRC по статьям и месяцам (знак: + приход, − расход):")
for k in sorted(st, key=lambda x: sum(st[x].values())):
    v = st[k]
    print(f"  {k[0]} {k[1][:40]:<40} Σ {fmt(sum(v.values())):>15} | " + "; ".join(f"{m}:{fmt(s)}" for m, s in sorted(v.items())))

vt = q(E, ROOT_Q + """
ВЫБРАТЬ
	Б.Сценарий.Код КАК СцКод,
	Б.Сценарий.Наименование КАК Сценарий,
	Б.Месяц КАК Месяц,
	Б.СтатьяДвиженияДенежныхСредств.Код КАК СтКод,
	Б.СтатьяДвиженияДенежныхСредств.Наименование КАК Статья,
	Б.Подразделение КАК Подр,
	Б.ВидОплаты КАК ВидОплаты,
	Б.Регистратор КАК Рег,
	Б.Сумма КАК Сумма
ИЗ
	РегистрНакопления.А_ПредварительныйБюджетНаМесяц КАК Б
ГДЕ
	Б.Подразделение В ИЕРАРХИИ (ВЫБРАТЬ ВТ_Корень.Корень ИЗ ВТ_Корень КАК ВТ_Корень)
	И Б.Регистратор.Проведен
""")
B = rows(E, vt, ["СцКод", "Сценарий", "Месяц", "СтКод", "Статья", "Подр", "ВидОплаты", "Рег", "Сумма"])
for r in B: r["Месяц"] = str(r["Месяц"])[:10]
dump_json(B, "budget_irc.json")
bb = defaultdict(Decimal)
for r in B:
    bb[(r["СцКод"], r["СтКод"], r["Статья"][:35], r["Месяц"])] += D(r["Сумма"])
print("БЮДЖЕТ (А_ПредварительныйБюджетНаМесяц), IRC:")
for k in sorted(bb):
    if "атериал" in k[2] or "МШП" in k[2]:
        print("  ", k, fmt(bb[k]))
