from collections import defaultdict
def tot(lst):
    t = defaultdict(lambda: [D(0), D(0), 0])
    for r in lst:
        t[r["СС"]][0] += D(r["Кол"]); t[r["СС"]][1] += D(r["Сумма"]); t[r["СС"]][2] += 1
    return t
