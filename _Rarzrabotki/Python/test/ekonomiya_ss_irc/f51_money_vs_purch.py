# -*- coding: utf-8 -*-
"""Ф4. Свод денег и начислений IRC по поставщикам: закупки ERP (брутто, ≤30.09) против оплат из казны по статьям
«Строительные материалы»/«МШП» (зеркало А_ДвиженияДенегИзКазны, ≤30.09) — разница = долг (+) / предоплата (−) в
разрезе IRC. Плюс возвраты поставщикам в ERP (ВозвратТоваровПоставщику, подразделение IRC) и закупки после 30.09.
Только чтение (запрос возвратов/октября), остальное — расчёт по out/*.json."""
import os, sys, json
sys.path.insert(0, os.path.dirname(__file__))
from common import *
from collections import defaultdict

PU = json.load(open(os.path.join(OUT, "purch_erp.json"), encoding="utf-8"))
MO = json.load(open(os.path.join(OUT, "money_kazna.json"), encoding="utf-8"))
K = lambda s: " ".join(str(s or "").replace('"', "").split()).casefold()

byk = defaultdict(lambda: {"name": "", "pu": Decimal(0), "pay": Decimal(0), "pay_oct": Decimal(0), "ret": Decimal(0)})
for r in PU:
    b = byk[K(r["Контрагент"])]; b["name"] = r["Контрагент"]; b["pu"] += D(r["Стоимость"])
MAT = {"УТ-001067", "УТ-001065"}
other_art = defaultdict(Decimal)
for r in MO:
    if r["СтКод"] in MAT:
        who = r["Контрагент"] or r["Подотчет"] or "(без контрагента)"
        b = byk[K(who)]
        if not b["name"]: b["name"] = who
        if r["Период"] <= "2026-09-30 23:59:59": b["pay"] += -D(r["Сумма"])
        else: b["pay_oct"] += -D(r["Сумма"])
    elif r["СтКод"] in ("УТ-001147", "УТ-001204"):
        other_art[(r["СтКод"], r["Контрагент"] or r["Подотчет"])] += D(r["Сумма"])

E = erp()
vt = q(E, """
ВЫБРАТЬ ПЕРВЫЕ 1 СС.ПодразделениеЗакупки КАК Корень
ПОМЕСТИТЬ ВТ_Корень
ИЗ Справочник.А_СтруктураСебестоимости КАК СС
ГДЕ СС.Наименование ПОДОБНО "%IR%" И НЕ СС.ПометкаУдаления
;
ВЫБРАТЬ Д.Номер КАК Номер, Д.Дата КАК Дата, Д.Контрагент КАК Контрагент, Д.СуммаДокумента КАК Сумма, Д.Проведен КАК Проведен
ИЗ Документ.ВозвратТоваровПоставщику КАК Д
ГДЕ Д.Подразделение В ИЕРАРХИИ (ВЫБРАТЬ ВТ_Корень.Корень ИЗ ВТ_Корень КАК ВТ_Корень)
	И Д.Дата >= ДАТАВРЕМЯ(2026, 1, 1) И НЕ Д.ПометкаУдаления
""")
RET = rows(E, vt, ["Номер", "Дата", "Контрагент", "Сумма", "Проведен"])
for r in RET: byk[K(r["Контрагент"])]["ret"] += D(r["Сумма"])
vt = q(E, """
ВЫБРАТЬ ПЕРВЫЕ 1 СС.ПодразделениеЗакупки КАК Корень
ПОМЕСТИТЬ ВТ_Корень
ИЗ Справочник.А_СтруктураСебестоимости КАК СС
ГДЕ СС.Наименование ПОДОБНО "%IR%" И НЕ СС.ПометкаУдаления
;
ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК N, СУММА(СТ.Стоимость) КАК С
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
	И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
	И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (ВЫБРАТЬ ВТ_Корень.Корень ИЗ ВТ_Корень КАК ВТ_Корень)
	И СТ.Период > ДАТАВРЕМЯ(2026, 9, 30, 23, 59, 59)
""")
after = rows(E, vt, ["N", "С"])
print("Закупки IRC после 30.09.2026 (на момент выгрузки):", after)
print("Возвраты поставщикам IRC в ERP:", RET)
print("Прочие поступления по статьям возвратов:", {k: fmt(v) for k, v in other_art.items()})

T = defaultdict(Decimal)
lines = []
for k, b in sorted(byk.items(), key=lambda x: -(x[1]["pu"] - x[1]["pay"])):
    bal = b["pu"] - b["ret"] - b["pay"]
    T["pu"] += b["pu"]; T["pay"] += b["pay"]; T["pay_oct"] += b["pay_oct"]; T["ret"] += b["ret"]
    if bal > 0: T["debt"] += bal
    else: T["prepay"] += bal
    lines.append({"Контрагент": b["name"], "Закуплено": str(b["pu"]), "Возвраты": str(b["ret"]), "Оплачено≤30.09": str(b["pay"]),
                  "Оплачено после": str(b["pay_oct"]), "Сальдо(+долг/−аванс)": str(bal)})
dump_json({"lines": lines, "tot": {k: str(v) for k, v in T.items()}}, "money_vs_purch.json")
print("ИТОГ: закуплено", fmt(T["pu"]), "возвраты", fmt(T["ret"]), "оплачено ≤30.09", fmt(T["pay"]), "после", fmt(T["pay_oct"]),
      "| долг", fmt(T["debt"]), "аванс", fmt(T["prepay"]), "нетто", fmt(T["debt"] + T["prepay"]))
for l in lines[:12] + lines[-8:]:
    print(f"  {l['Контрагент'][:40]:<40} закуп {fmt(l['Закуплено']):>13} опл {fmt(l['Оплачено≤30.09']):>13} сальдо {fmt(l['Сальдо(+долг/−аванс)']):>13}")
