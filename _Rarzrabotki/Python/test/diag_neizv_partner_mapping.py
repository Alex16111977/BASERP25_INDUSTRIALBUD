# -*- coding: utf-8 -*-
# Диагностика 2: контрагенты/договоры с Партнер=Неизвестный, и есть ли реальный партнёр-кандидат
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

partner = erp.Справочники.Партнеры.НайтиПоНаименованию("Неизвестный партнер", True)

# 1. Контрагенты с Партнер = Неизвестный
q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ К.Ссылка КАК Контрагент, К.Наименование КАК Наим, К.Партнер КАК Партнер, "
          "К.ЮридическоеФизическоеЛицо КАК ЮрФиз "
          "ИЗ Справочник.Контрагенты КАК К ГДЕ К.Партнер = &П")
q.УстановитьПараметр("П", partner)
sel = q.Execute().Выбрать()
print("=== КОНТРАГЕНТЫ с Партнер=Неизвестный ===")
cnt = 0
while sel.Следующий():
    cnt += 1
    # есть ли реальный партнёр с тем же наименованием?
    pk = erp.Справочники.Партнеры.НайтиПоНаименованию(sel.Наим, True)
    est = "НЕТ"
    if erp.ЗначениеЗаполнено(pk) and not (pk == partner):
        est = "ЕСТЬ: " + pk.Наименование
    print(f"  [{cnt}] {sel.Наим}  | партнёр-тёзка: {est}")
print("Всего контрагентов:", cnt)

# 2. Договоры с Партнер = Неизвестный
q2 = erp.NewObject("Запрос")
q2.Text = ("ВЫБРАТЬ Д.Ссылка, Д.Наименование КАК Наим, Д.Контрагент КАК Контр "
           "ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ Д.Партнер = &П")
q2.УстановитьПараметр("П", partner)
sel2 = q2.Execute().Выбрать()
print("\n=== ДОГОВОРЫ с Партнер=Неизвестный ===")
c2 = 0
while sel2.Следующий():
    c2 += 1
    contr = sel2.Контр
    cn = contr.Наименование if erp.ЗначениеЗаполнено(contr) else "(пусто)"
    print(f"  [{c2}] {sel2.Наим} | Контрагент={cn}")
print("Всего договоров:", c2)

# 3. Сколько всего реальных партнёров в базе (для оценки 1:1)
q3 = erp.NewObject("Запрос")
q3.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(Ссылка) КАК К ИЗ Справочник.Партнеры ГДЕ НЕ ПометкаУдаления"
s3 = q3.Execute().Выбрать(); s3.Следующий()
print("\nВсего партнёров в базе:", s3.К)
