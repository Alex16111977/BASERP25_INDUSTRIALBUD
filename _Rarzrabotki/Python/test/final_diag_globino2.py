# -*- coding: utf-8 -*-
"""
ЦЕЛЕВОЙ АНАЛИЗ финансиста (исходная задача):
- Глобино-2 / Задолженность клиентов / декабрь 2025
- Расхождений по этой статье быть не должно
- Подразделение для расшифровки брать из ОбъектРасчетов.Подразделение
  (а НЕ из Договор.Подразделение — это про fallback в Свод_РасчетыСПартнерами)
- Изучить как строится отчёт УправленческийБаланс

Делаю 3 сравнения:
A. Σ КО ПАП(Глобино-2, ЗадКлиентов) на 31.12.2025 — это эталон (что показывает штатный УправленческийБаланс)
B. Σ КО РСК с ОР.Подразделение=Глобино-2 (без fallback к Договор.Подразделение) — как ХОЧЕТ финансист
C. Σ КО РСК с текущей свод-формулой (ОР.Подразделение → fallback Договор.Подразделение)

Если B = A → расхождение уходит просто заменой формулы (без fallback).
Если B ≠ A → проблема глубже, надо смотреть конкретные ОР с расхождением.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Параметры
КМ = datetime.datetime(2025, 12, 31, 23, 59, 59)
НМ_МЕС = datetime.datetime(2025, 12, 1, 0, 0, 0)

q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
орг = q.Выполнить().Выгрузить().Получить(0).Ссылка
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтруктураПредприятия ГДЕ Наименование = "Глобино-2"'
подр_глобино = q.Выполнить().Выгрузить().Получить(0).Ссылка

print("=" * 110, flush=True)
print(f"ЦЕЛЕВОЙ АНАЛИЗ — Глобино-2 / Задолженность клиентов / 31.12.2025", flush=True)
print(f"Организация: {S(орг)}", flush=True)
print("=" * 110, flush=True)


# === A. ПАП-итог (как видит штатный УправленческийБаланс) ===
print("\n[A] ЭТАЛОН: ПАП Σ КО на 31.12.2025 для (Орг, Подразделение=Глобино-2, Статья=ЗадКлиентов)", flush=True)
print("-" * 110, flush=True)
qa = erp.NewObject("Запрос")
qa.УстановитьПараметр("Орг", орг)
qa.УстановитьПараметр("Подр", подр_глобино)
qa.УстановитьПараметр("КМ", КМ)
qa.Текст = """
ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Подразделение = &Подр И Т.Период <= &КМ
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
    И Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьКлиентов)
"""
ra = qa.Выполнить().Выгрузить().Получить(0)
A_сумма = float(ra.КО)
print(f"   ПАП Σ КО = {A_сумма:>15,.2f}", flush=True)


# === B. Σ из РСК с ОР.Подразделение = Глобино-2 (без fallback) ===
print("\n[B] КАК ХОЧЕТ ФИНАНСИСТ: Σ КО РСК с ОР.Подразделение = Глобино-2 (БЕЗ fallback к Договор.Подразделение)", flush=True)
print("-" * 110, flush=True)
qb = erp.NewObject("Запрос")
qb.УстановитьПараметр("Орг", орг)
qb.УстановитьПараметр("Подр", подр_глобино)
qb.УстановитьПараметр("КМ", КМ)
qb.Текст = """
ВЫБРАТЬ
    Р.ОбъектРасчетов КАК ОР,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК Партнер,
    ПРЕДСТАВЛЕНИЕ(АП.Контрагент) КАК Контрагент,
    СУММА(Р.ДолгУпрОстаток) КАК КО
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(&КМ, ) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг
    И АП.Партнер <> ЗНАЧЕНИЕ(Справочник.Партнеры.НашеПредприятие)
    И Р.ОбъектРасчетов.Подразделение = &Подр
    И Р.ДолгУпрОстаток > 0
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов, АП.Партнер, АП.Контрагент
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
rb = qb.Выполнить().Выгрузить()
B_сумма = 0
print(f"   {'ОР':<45} | {'Партнёр':<22} | {'Контрагент':<25} | {'КО':>13}", flush=True)
for i in range(rb.Количество()):
    rec = rb.Получить(i)
    B_сумма += float(rec.КО)
    print(f"   {str(rec.ОРИмя)[:45]:<45} | {str(rec.Партнер)[:22]:<22} | {str(rec.Контрагент)[:25]:<25} | {float(rec.КО):>13,.2f}", flush=True)
print(f"   {'Σ B':<45} | {' ':<22} | {' ':<25} | {B_сумма:>13,.2f}", flush=True)


# === C. Σ из РСК со СВОД-формулой (с fallback) ===
print("\n[C] ТЕКУЩАЯ СВОД-ФОРМУЛА: ВЫБОР КОГДА ОР.Подр пуст ТОГДА Договор.Подр ИНАЧЕ ОР.Подр", flush=True)
print("-" * 110, flush=True)
qc = erp.NewObject("Запрос")
qc.УстановитьПараметр("Орг", орг)
qc.УстановитьПараметр("Подр", подр_глобино)
qc.УстановитьПараметр("КМ", КМ)
qc.Текст = """
ВЫБРАТЬ
    Р.ОбъектРасчетов КАК ОР,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК Партнер,
    СУММА(Р.ДолгУпрОстаток) КАК КО
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(&КМ, ) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг
    И АП.Партнер <> ЗНАЧЕНИЕ(Справочник.Партнеры.НашеПредприятие)
    И ЕСТЬNULL(ВЫБОР КОГДА Р.ОбъектРасчетов.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
                ТОГДА Р.ОбъектРасчетов.Договор.Подразделение
                ИНАЧЕ Р.ОбъектРасчетов.Подразделение КОНЕЦ,
            ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) = &Подр
    И Р.ДолгУпрОстаток > 0
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов, АП.Партнер
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
rc = qc.Выполнить().Выгрузить()
C_сумма = 0
print(f"   {'ОР':<45} | {'Партнёр':<22} | {'КО':>13}", flush=True)
for i in range(rc.Количество()):
    rec = rc.Получить(i)
    C_сумма += float(rec.КО)
    print(f"   {str(rec.ОРИмя)[:45]:<45} | {str(rec.Партнер)[:22]:<22} | {float(rec.КО):>13,.2f}", flush=True)
print(f"   {'Σ C':<45} | {' ':<22} | {C_сумма:>13,.2f}", flush=True)


# === ИТОГ ===
print("\n" + "=" * 110, flush=True)
print("ИТОГИ:", flush=True)
print(f"  A. ПАП (эталон отчёта УправленческийБаланс)       = {A_сумма:>15,.2f}", flush=True)
print(f"  B. РСК через ТОЛЬКО ОР.Подразделение              = {B_сумма:>15,.2f}", flush=True)
print(f"  C. РСК через свод-формулу (с fallback к Договору) = {C_сумма:>15,.2f}", flush=True)
print(f"", flush=True)
print(f"  Δ (B − A): если 0 → формула B даёт совпадение с ПАП", flush=True)
print(f"     B − A = {B_сумма - A_сумма:>+15,.2f}", flush=True)
print(f"  Δ (C − A): текущее расхождение (плуг свод-функции)", flush=True)
print(f"     C − A = {C_сумма - A_сумма:>+15,.2f}", flush=True)
print("=" * 110, flush=True)
