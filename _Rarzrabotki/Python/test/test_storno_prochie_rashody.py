# -*- coding: utf-8 -*-
"""Тест: допроведення РАСХОД в ПрочиеРасходы для документа 000Ц-000009.
Імітує логіку процедури А_СторноПрочиеРасходыВНА з ДвиженияАктивовПассивов.
"""
import win32com.client, datetime
v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String
VF = conn.ValueIsFilled

# 1. Знайти документ 000Ц-000009
print("=== 1. Пошук документа 000Ц-000009 ===")
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка
ИЗ Документ.ВнутреннееПотреблениеТоваров КАК Д
ГДЕ Д.Номер ПОДОБНО &Н И Д.Дата >= &Д1 И Д.Дата <= &Д2"""
q.SetParameter("Н", "%000Ц-000009%")
q.SetParameter("Д1", datetime.datetime(2025, 12, 11))
q.SetParameter("Д2", datetime.datetime(2025, 12, 11, 23, 59, 59))
res = q.Execute().Select()
if not res.Next():
    print("Документ не знайдено!")
    exit()
doc_ref = res.Ссылка
print(f"  Знайдено: {S(doc_ref)}")

# 2. Прочитати ПРИХОД записи цього документа в ПрочиеРасходы
print("\n=== 2. ПРИХОД записи в ПрочиеРасходы (до) ===")
q2 = conn.NewObject("Запрос")
q2.Text = """ВЫБРАТЬ
    ПР.ВидДвижения, ПР.Период, ПР.Организация, ПР.Подразделение,
    ПР.НаправлениеДеятельности, ПР.НалоговоеНазначение,
    ПР.СтатьяРасходов, ПР.АналитикаРасходов,
    ПР.Сумма, ПР.СуммаБезНДС, ПР.СуммаРегл, ПР.СуммаРеглБезНДС,
    ПР.НДСРегл, ПР.СуммаУпр, ПР.СуммаУпрБезНДС,
    ПР.ХозяйственнаяОперация, ПР.АналитикаУчетаНоменклатуры
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &Рег
    И ПР.СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)
    И ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл = ЗНАЧЕНИЕ(Перечисление.ВариантыРаспределенияРасходов.НаВнеоборотныеАктивы)"""
q2.SetParameter("Рег", doc_ref)
res2 = q2.Execute()
tbl = res2.Unload()
prikhod_count = 0
rashod_count = 0
for i in range(tbl.Count()):
    row = tbl.Get(i)
    vd = S(row.ВидДвижения)
    if "Приход" in vd or "Receipt" in vd:
        prikhod_count += 1
    else:
        rashod_count += 1
    print(f"  #{i+1} Вид={vd} Стаття={S(row.СтатьяРасходов)} Сума={row.Сумма}")
    print(f"     Аналітика={S(row.АналитикаРасходов)} Підр={S(row.Подразделение)}")

print(f"\n  ПРИХОД: {prikhod_count}, РАСХОД: {rashod_count}")

if prikhod_count == 0:
    print("\nНемає ПРИХОД записів — нічого сторнувати!")
    exit()

# 3. Допроведення: додати РАСХОД записи
print("\n=== 3. Додаємо РАСХОД записи ===")

# Прочитати набір записів документа
nabor = conn.AccumulationRegisters.ПрочиеРасходы.CreateRecordSet()
nabor.Filter.Регистратор.Set(doc_ref)
nabor.Read()
print(f"  Записів в наборі до: {nabor.Count()}")

# Знайти ПРИХОД записи для сторно
prihod_rows = []
for i in range(tbl.Count()):
    row = tbl.Get(i)
    vd = S(row.ВидДвижения)
    if "Приход" in vd or "Receipt" in vd:
        prihod_rows.append(row)

# Додати РАСХОД для кожного ПРИХОД
# В COM: RecordType для РАСХОД — просто присвоюємо через XML
for row in prihod_rows:
    new_rec = nabor.Add()
    # ВидДвижения: 0 = Приход, 1 = Расход
    new_rec.RecordType = 1
    new_rec.Period = row.Период
    new_rec.Организация = row.Организация
    new_rec.Подразделение = row.Подразделение
    new_rec.НаправлениеДеятельности = row.НаправлениеДеятельности
    new_rec.НалоговоеНазначение = row.НалоговоеНазначение
    new_rec.СтатьяРасходов = row.СтатьяРасходов
    new_rec.АналитикаРасходов = row.АналитикаРасходов
    new_rec.Сумма = row.Сумма
    new_rec.СуммаБезНДС = row.СуммаБезНДС if row.СуммаБезНДС else 0
    new_rec.СуммаРегл = row.СуммаРегл if row.СуммаРегл else 0
    new_rec.СуммаРеглБезНДС = row.СуммаРеглБезНДС if row.СуммаРеглБезНДС else 0
    new_rec.НДСРегл = row.НДСРегл if row.НДСРегл else 0
    new_rec.СуммаУпр = row.СуммаУпр if row.СуммаУпр else 0
    new_rec.СуммаУпрБезНДС = row.СуммаУпрБезНДС if row.СуммаУпрБезНДС else 0
    new_rec.ХозяйственнаяОперация = row.ХозяйственнаяОперация
    new_rec.АналитикаУчетаНоменклатуры = row.АналитикаУчетаНоменклатуры
    print(f"  + РАСХОД: {S(row.АналитикаРасходов)} = {row.Сумма}")

print(f"  Записів в наборі після: {nabor.Count()}")

# Записати БЕЗ заміни (додати до існуючих)
try:
    nabor.Write(False)
    print("  Записано успішно!")
except Exception as e:
    print(f"  ПОМИЛКА ЗАПИСУ: {e}")
    exit()

# 4. Перевірка після
print("\n=== 4. Перевірка ПІСЛЯ ===")
q3 = conn.NewObject("Запрос")
q3.Text = """ВЫБРАТЬ ПР.ВидДвижения, ПР.Сумма, ПР.АналитикаРасходов
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &Рег
    И ПР.СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)"""
q3.SetParameter("Рег", doc_ref)
res3 = q3.Execute().Select()
p = 0
r = 0
while res3.Next():
    vd = S(res3.ВидДвижения)
    if "Приход" in vd or "Receipt" in vd:
        p += 1
    else:
        r += 1
print(f"  ПРИХОД: {p}, РАСХОД: {r}")
print(f"  Баланс: {'OK (ПРИХОД = РАСХОД)' if p == r else 'НЕ OK!'}")

# 5. Залишок
print("\n=== 5. Залишок ПрочиеРасходы по аналітиці ===")
q4 = conn.NewObject("Запрос")
q4.Text = """ВЫБРАТЬ ПР.АналитикаРасходов, ПР.СуммаОстаток
ИЗ РегистрНакопления.ПрочиеРасходы.Остатки(,
    АналитикаРасходов В (ВЫБРАТЬ РАЗЛИЧНЫЕ Т.АналитикаРасходов ИЗ РегистрНакопления.ПрочиеРасходы КАК Т ГДЕ Т.Регистратор = &Рег)
    И СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)
) КАК ПР"""
q4.SetParameter("Рег", doc_ref)
try:
    res4 = q4.Execute().Select()
    while res4.Next():
        print(f"  {S(res4.АналитикаРасходов)}: залишок = {res4.СуммаОстаток}")
except Exception as e:
    print(f"  Помилка: {e}")

print("\n=== ТЕСТ ЗАВЕРШЕНО ===")
