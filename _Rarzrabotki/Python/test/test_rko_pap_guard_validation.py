"""Pre-test SQL: проверить наш гард (3 условия одновременно).

Тестируем что гард корректно работает:
1. ТИПЗНАЧЕНИЯ(Регистратор) = ТИП(РасходныйКассовыйОрдер) — TRUE
2. ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(ВедомостьНаВыплатуЗарплатыВКассу) — TRUE для нашего
3. РКО.ХозяйственнаяОперация В (3 зарплатные)
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Проверка гарда — должен пройти только наш РКО N0000052986, не пройти другие
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    РКО.Ссылка КАК Сс,
    РКО.Номер,
    РКО.ХозяйственнаяОперация КАК ХозОп,
    ВЫБОР
        КОГДА ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу) ТОГДА "ВКассу"
        КОГДА ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВБанк) ТОГДА "ВБанк"
        КОГДА РКО.Ведомость = НЕОПРЕДЕЛЕНО ТОГДА "Нет"
        ИНАЧЕ "Другая"
    КОНЕЦ КАК ТипВедомости,
    ВЫБОР
        КОГДА ТИПЗНАЧЕНИЯ(РКО.Ссылка) = ТИП(Документ.РасходныйКассовыйОрдер)
            И ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу)
            И РКО.ХозяйственнаяОперация В (
                ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу),
                ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаздатчиком),
                ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику))
            ТОГДА "ПРОХОДИТ"
        ИНАЧЕ "НЕ ПРОХОДИТ"
    КОНЕЦ КАК Гард
ИЗ Документ.РасходныйКассовыйОрдер КАК РКО
ГДЕ РКО.Номер = &Ном
"""
q.SetParameter("Ном", "N0000052986")
rows = q.Execute().Выгрузить()
assert rows.Количество() == 1
r = rows[0]
print(f"Наш РКО N0000052986:")
print(f"  ХозОп: {S(r.ХозОп)}")
print(f"  Тип Ведомости: {r.ТипВедомости}")
print(f"  Гард: {r.Гард}")
assert r.Гард == "ПРОХОДИТ", f"FAIL: гард не пропустил наш РКО"

# Контрольные — не должны пройти гард
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ ПЕРВЫЕ 10
    РКО.Ссылка КАК Сс,
    РКО.Номер,
    РКО.ХозяйственнаяОперация КАК ХозОп,
    ВЫБОР
        КОГДА ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу) ТОГДА "ВКассу"
        КОГДА ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВБанк) ТОГДА "ВБанк"
        ИНАЧЕ "Нет/Другая"
    КОНЕЦ КАК ТипВедомости,
    ВЫБОР
        КОГДА ТИПЗНАЧЕНИЯ(РКО.Ссылка) = ТИП(Документ.РасходныйКассовыйОрдер)
            И ТИПЗНАЧЕНИЯ(РКО.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу)
            И РКО.ХозяйственнаяОперация В (
                ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу),
                ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаздатчиком),
                ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику))
            ТОГДА "ПРОХОДИТ"
        ИНАЧЕ "НЕ ПРОХОДИТ"
    КОНЕЦ КАК Гард
ИЗ Документ.РасходныйКассовыйОрдер КАК РКО
ГДЕ РКО.Проведен И НЕ РКО.ПометкаУдаления
    И РКО.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ПрочаяВыдачаДенежныхСредств)
УПОРЯДОЧИТЬ ПО РКО.Дата УБЫВ
"""
rows2 = q2.Execute().Выгрузить()
print(f"\nПроверка не-зарплатных РКО ({rows2.Количество()}):")
for r in rows2:
    print(f"  {S(r.Номер)}: ХозОп={S(r.ХозОп)}, ТипВедомости={r.ТипВедомости}, Гард={r.Гард}")
    assert r.Гард == "НЕ ПРОХОДИТ", f"FAIL: гард пропустил не-зарплатный РКО {S(r.Номер)}"

print("\n✅ Гард корректно работает: наш РКО проходит, остальные — нет")
