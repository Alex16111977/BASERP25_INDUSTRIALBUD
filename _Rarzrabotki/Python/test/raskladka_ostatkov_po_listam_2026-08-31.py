# -*- coding: utf-8 -*-
"""Раскладка остатков PL по документам-листам (решение финансиста 31.08.2026).

Вместо одного документа А_ВводОстатковОтчетаPL — документ на каждый лист книги
выгрузки (РегистрСведений.А_СтруктураВыгрузкиОтчетаPLвЕксел), Комментарий = лист.

Правило распределения строки остатков (без пересечений между документами):
  - слой СВОД (СводНаправления=Истина, подразделение P):
      лист с ОтчетПоНаправлению=Истина и Подразделение=P; нет — «вне листов»;
  - слой ОБЪЕКТ (подразделение P):
      1) лист «Только это подразделение» с Подразделение=P;
      2) иначе самый глубокий обычный лист (не свод, не «только это»), в чьей
         группе (сам или по иерархии родителей) лежит P;
      3) иначе — «вне листов» (закрытые объекты и прочие без своего листа).
PL_Свод (оба измерения пустые) — агрегат, своих остатков не имеет.

Эталон до раскладки (единый документ №1, зафиксировано 31.08.2026):
  ОБЪЕКТ: 988 строк, Ф1СНГ=700 357 982,47  Ф2СНГ=62 764 109,19
          Ф1Нак=2 743 128 134,18  Ф2Нак=218 116 340,16
  СВОД:   258 строк, Ф1СНГ=731 174 855,68  Ф2СНГ=70 557 252,89
          Ф1Нак=2 923 045 194,15  Ф2Нак=267 919 499,01
После раскладки суммарный регистр обязан совпасть с эталоном до копейки.
"""
import sys
import datetime
from collections import defaultdict

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ЦЕЛЬ = datetime.datetime(2026, 6, 30, 23, 59, 59)

# --- 0. эталон: суммарный регистр ДО раскладки -------------------------------
def контрольные_суммы():
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        Ост.СводНаправления КАК Свод,
        СУММА(Ост.СуммаФ1СНачалаГода) КАК Ф1СНГ,
        СУММА(Ост.СуммаФ2СНачалаГода) КАК Ф2СНГ,
        СУММА(Ост.СуммаФ1Накопительно) КАК Ф1Нак,
        СУММА(Ост.СуммаФ2Накопительно) КАК Ф2Нак,
        КОЛИЧЕСТВО(*) КАК Строк
    ИЗ РегистрНакопления.А_ОстаткиОтчетаPL КАК Ост
    СГРУППИРОВАТЬ ПО Ост.СводНаправления
    """
    r = q.Execute().Выгрузить()
    итог = {}
    for i in range(r.Количество()):
        s = r.Получить(i)
        итог[bool(s.Свод)] = (round(float(s.Ф1СНГ), 2), round(float(s.Ф2СНГ), 2),
                              round(float(s.Ф1Нак), 2), round(float(s.Ф2Нак), 2), int(s.Строк))
    return итог

ЭТАЛОН = контрольные_суммы()
print("Эталон регистра:", ЭТАЛОН)
assert ЭТАЛОН, "регистр пуст — сначала заполните остатки"

# --- 1. листы из регистра структуры ------------------------------------------
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Рег.НомерПорядковыйСтраницы КАК Ном,
    Рег.ИмяСтраницы КАК Имя,
    Рег.Подразделение КАК Подр,
    Рег.ОтчетПоНаправлению КАК ПоНапр,
    Рег.ТолькоЭтоПодразделение КАК ТолькоЭто
ИЗ
    РегистрСведений.А_СтруктураВыгрузкиОтчетаPLвЕксел КАК Рег
ГДЕ
    Рег.Выгружать
УПОРЯДОЧИТЬ ПО
    Рег.НомерПорядковыйСтраницы
"""
r = q.Execute().Выгрузить()
листы = []
for i in range(r.Количество()):
    s = r.Получить(i)
    листы.append({"ном": int(s.Ном), "имя": S(s.Имя), "подр": s.Подр,
                  "подрС": S(s.Подр), "поНапр": bool(s.ПоНапр), "толькоЭто": bool(s.ТолькоЭто)})
print("листов к выгрузке:", len(листы))

# --- 2. полный набор остатков из документа №1 --------------------------------
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Док.Ссылка КАК ДокСсылка ИЗ Документ.А_ВводОстатковОтчетаPL КАК Док
ГДЕ Док.Проведен УПОРЯДОЧИТЬ ПО Док.Дата
"""
r = q.Execute().Выгрузить()
assert r.Количество() == 1, "ожидался ровно один проведённый документ-исходник"
ДокИсходник = r.Получить(0).ДокСсылка

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Стр.Подразделение КАК Подр,
    Стр.Подразделение.Родитель КАК Род1,
    Стр.Подразделение.Родитель.Родитель КАК Род2,
    Стр.Подразделение.Родитель.Родитель.Родитель КАК Род3,
    Стр.Подразделение.Родитель.Родитель.Родитель.Родитель КАК Род4,
    Стр.СводНаправления КАК Свод,
    Стр.СтатьяPL КАК Статья,
    Стр.СуммаФ1СНачалаГода КАК Ф1СНГ,
    Стр.СуммаФ2СНачалаГода КАК Ф2СНГ,
    Стр.СуммаФ1Накопительно КАК Ф1Нак,
    Стр.СуммаФ2Накопительно КАК Ф2Нак
ИЗ
    Документ.А_ВводОстатковОтчетаPL.Остатки КАК Стр
ГДЕ
    Стр.Ссылка = &Док
"""
q.SetParameter("Док", ДокИсходник)
строки = q.Execute().Выгрузить()
print("строк остатков к раскладке:", строки.Количество())

# --- 3. распределение ---------------------------------------------------------
свод_листы = {л["подрС"]: л for л in листы if л["поНапр"]}
только_листы = {л["подрС"]: л for л in листы if л["толькоЭто"] and not л["поНапр"]}
обычные_листы = {}   # подрС -> лист (обычные объектные)
for л in листы:
    if not л["поНапр"] and not л["толькоЭто"] and л["подрС"]:
        обычные_листы[л["подрС"]] = л

ВНЕ = {"ном": 999, "имя": "ВНЕ ЛИСТОВ (закрытые и прочие)", "поНапр": None}
раскладка = defaultdict(list)   # имя листа -> [индексы строк]
статистика = defaultdict(lambda: [0, 0.0])

for i in range(строки.Количество()):
    s = строки.Получить(i)
    подр = S(s.Подр)
    if bool(s.Свод):
        лист = свод_листы.get(подр) or ВНЕ
    else:
        лист = только_листы.get(подр)
        if лист is None:
            # вверх по цепочке родителей: сам → Род1..Род4, первый обычный лист
            for имя_узла in (подр, S(s.Род1), S(s.Род2), S(s.Род3), S(s.Род4)):
                if имя_узла and имя_узла in обычные_листы:
                    лист = обычные_листы[имя_узла]
                    break
        if лист is None:
            лист = ВНЕ
    раскладка[лист["имя"]].append(i)
    ст = статистика[лист["имя"]]
    ст[0] += 1
    ст[1] += float(s.Ф1Нак)

print("--- распределение (строк, Ф1 накопительно) ---")
for имя, (n, ф1) in sorted(статистика.items(), key=lambda x: -x[1][0]):
    print(f"  {имя:35} {n:5}  {ф1:,.2f}")

# --- 4. пересоздание документов -----------------------------------------------
# 4а. распровести и пометить исходник (переиспользуем его под первый лист)
объект = ДокИсходник.ПолучитьОбъект()
объект.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
print("Исходный документ распроведён")

порядок = sorted(раскладка.keys(),
                 key=lambda имя: next((л["ном"] for л in листы if л["имя"] == имя), 999))

qo = erp.NewObject("Запрос")
qo.Text = ('ВЫБРАТЬ ПЕРВЫЕ 1 Орг.Ссылка КАК ОргСсылка ИЗ Справочник.Организации КАК Орг '
           'ГДЕ НЕ Орг.ПометкаУдаления И Орг.Наименование ПОДОБНО "%НДАСТР%"')
Организация = qo.Execute().Выгрузить().Получить(0).ОргСсылка

# существующие документы по комментарию (идемпотентность повторного запуска)
qd = erp.NewObject("Запрос")
qd.Text = """
ВЫБРАТЬ Док.Ссылка КАК ДокСсылка, Док.Комментарий КАК Ком
ИЗ Документ.А_ВводОстатковОтчетаPL КАК Док
ГДЕ НЕ Док.ПометкаУдаления
"""
rd = qd.Execute().Выгрузить()
по_комментарию = {}
for i in range(rd.Количество()):
    по_комментарию[S(rd.Получить(i).Ком)] = rd.Получить(i).ДокСсылка

использован_исходник = False
итого_строк = 0
for имя in порядок:
    коммент = "Остатки PL на 30.06.2026 — лист «%s»" % имя
    ДокСсылка = по_комментарию.get(коммент)
    if ДокСсылка is not None:
        Об = ДокСсылка.ПолучитьОбъект()
    elif not использован_исходник:
        Об = ДокИсходник.ПолучитьОбъект()
        использован_исходник = True
    else:
        Об = erp.Документы.А_ВводОстатковОтчетаPL.СоздатьДокумент()
    Об.Дата = ЦЕЛЬ
    факт = Об.Дата
    делта = ЦЕЛЬ - datetime.datetime(факт.year, факт.month, факт.day, факт.hour, факт.minute, факт.second)
    if делта:
        Об.Дата = ЦЕЛЬ + делта
    Об.Организация = Организация
    Об.Комментарий = коммент
    Об.Остатки.Очистить()
    for i in раскладка[имя]:
        s = строки.Получить(i)
        стр = Об.Остатки.Добавить()
        стр.Подразделение = s.Подр
        стр.СводНаправления = s.Свод
        стр.СтатьяPL = s.Статья
        стр.СуммаФ1СНачалаГода = s.Ф1СНГ
        стр.СуммаФ2СНачалаГода = s.Ф2СНГ
        стр.СуммаФ1Накопительно = s.Ф1Нак
        стр.СуммаФ2Накопительно = s.Ф2Нак
    Об.Записать(erp.РежимЗаписиДокумента.Проведение)
    итого_строк += Об.Остатки.Количество()
    print(f"проведён: №{S(Об.Номер)} [{Об.Остатки.Количество():4} строк] {коммент}")

assert использован_исходник or ДокИсходник in по_комментарию.values(), "исходник не переиспользован"
print("итого строк в документах:", итого_строк)

# --- 5. сверка регистра с эталоном --------------------------------------------
ПОСЛЕ = контрольные_суммы()
print("После раскладки:", ПОСЛЕ)
assert ПОСЛЕ == ЭТАЛОН, f"РЕГИСТР РАЗЪЕХАЛСЯ!\nдо:    {ЭТАЛОН}\nпосле: {ПОСЛЕ}"
print("OK: суммарный регистр совпал с эталоном до копейки")
