"""Проверка org-опционального паттерна: пусто=все орг, заполнено=фильтр.
(&Орг = ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка) ИЛИ Ост.Организация = &Орг)"""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
НаДату = pywintypes.Time(datetime.datetime(2026, 6, 22, 23, 59, 59))
Счета = buh.NewObject("Массив")
for код in ("20", "22", "28"):
    Счета.Добавить(buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код))
qСк = buh.NewObject("Запрос")
qСк.Текст = 'ВЫБРАТЬ Склады.Ссылка КАК С ИЗ Справочник.Склады КАК Склады ГДЕ Склады.Наименование ПОДОБНО "%МХП%ОР%виробнич%"'
tСк = qСк.Выполнить().Выгрузить()
Склады = buh.NewObject("Массив")
for i in range(tСк.Количество()):
    Склады.Добавить(tСк.Получить(i).С)
qO = buh.NewObject("Запрос")
qO.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Организации.Ссылка КАК С ИЗ Справочник.Организации КАК Организации ГДЕ Организации.Наименование ПОДОБНО "%ІНДЕПТ%"'
tO = qO.Выполнить().Выгрузить()
ОргИндепт = tO.Получить(0).С if tO.Количество() > 0 else None

ТЕКСТ = """
ВЫБРАТЬ Ост.Счет КАК Счет, Ост.Организация КАК Орг, СУММА(Ост.КоличествоОстаток) КАК К
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ(&Счета), , ) КАК Ост
ГДЕ Ост.КоличествоОстаток > 0
	И (&Организация = ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка) ИЛИ Ост.Организация = &Организация)
	И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) В (&Склады)
СГРУППИРОВАТЬ ПО Ост.Счет, Ост.Организация
"""
def прогон(орг, метка):
    q = buh.NewObject("Запрос")
    q.УстановитьПараметр("НаДату", НаДату); q.УстановитьПараметр("Счета", Счета)
    q.УстановитьПараметр("Склады", Склады); q.УстановитьПараметр("Организация", орг)
    q.Текст = ТЕКСТ
    t = q.Выполнить().Выгрузить()
    орги = set(buh.String(t.Получить(i).Орг) for i in range(t.Количество()))
    print(f"{метка}: групп={t.Количество()} организаций={орги}")

прогон(buh.Справочники.Организации.ПустаяСсылка(), "ПУСТО (все орг)")
if ОргИндепт is not None:
    прогон(ОргИндепт, f"ФИЛЬТР [{buh.String(ОргИндепт)}]")
else:
    print("ІНДЕПТ не найден — пропускаю фильтр-прогон")
