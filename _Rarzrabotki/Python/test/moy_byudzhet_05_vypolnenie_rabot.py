"""Аудит п.5: темп цеха — заработанные часы (EV) по домам и месяцам и готовность домов на 30.09.2026.

РН.А_ВыполнениеРаботМодулей: ЧасыВыполнение — дельта EV-часов (план часов работы × прирост %).
Документ А_ВыполнениеРаботМодулей (последний проведённый снимок по дому): план часов дома = Σ ПланЧасыМодуля,
освоено = Σ ПланЧасыМодуля × Процент. Вывод: data/vypolnenie_rabot.json.
"""
import collections
from moy_byudzhet_common import *

pm, root = projects()
t = query("""ВЫБРАТЬ Р.СтруктураСебестоимости.Код КАК КодСС, Р.Подразделение КАК Дом,
    НАЧАЛОПЕРИОДА(Р.Период, МЕСЯЦ) КАК Мес, СУММА(Р.ЧасыВыполнение) КАК Часы
ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Р
СГРУППИРОВАТЬ ПО Р.СтруктураСебестоимости.Код, Р.Подразделение, НАЧАЛОПЕРИОДА(Р.Период, МЕСЯЦ)""")
ev = []
for i in range(t.Количество()):
    r = t.Получить(i)
    p = pm[uid(r.Дом)]
    ev.append({"card": S(r.КодСС).strip(), "house": p["dept"], "proj": p["uid"], "projname": p["name"],
               "month": ym(r.Мес), "hours": float(r.Часы)})
t = query("""ВЫБРАТЬ Д.СтруктураСебестоимости.Код КАК КодСС, Д.Подразделение КАК Дом, Д.Дата КАК Дата,
    СУММА(Т.ПланЧасыМодуля) КАК План, СУММА(Т.ПланЧасыМодуля * Т.Процент / 100) КАК Освоено
ИЗ Документ.А_ВыполнениеРаботМодулей.Работы КАК Т
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей КАК Д ПО Т.Ссылка = Д.Ссылка
ГДЕ Д.Проведен
СГРУППИРОВАТЬ ПО Д.СтруктураСебестоимости.Код, Д.Подразделение, Д.Дата""")
last = {}
for i in range(t.Количество()):
    r = t.Получить(i)
    p = pm[uid(r.Дом)]
    d = ymd(r.Дата)
    if p["dept"] not in last or d > last[p["dept"]]["date"]:
        last[p["dept"]] = {"card": S(r.КодСС).strip(), "house": p["dept"], "proj": p["uid"], "projname": p["name"],
                           "date": d, "plan_h": float(r.План), "done_h": float(r.Освоено)}
save("vypolnenie_rabot.json", {"stamp": snapshot_stamp(), "ev": ev, "houses": sorted(last.values(), key=lambda x: x["house"])})
m = collections.defaultdict(float)
for x in ev:
    m[(x["projname"], x["month"])] += x["hours"]
print("EV-часы: проект | месяц | часы")
for k, v in sorted(m.items()):
    print(f"  {k[0]:<22} {k[1]} {v:>8.0f}")
print("Готовность домов на последнюю дату снимка:")
for x in sorted(last.values(), key=lambda x: x["house"]):
    print(f"  {x['house'][:40]:<40} {x['date']} план {x['plan_h']:>6.0f} освоено {x['done_h']:>6.0f} ({x['done_h'] / x['plan_h'] * 100:5.1f} %)")
