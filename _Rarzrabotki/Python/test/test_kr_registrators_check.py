def try_query(label, text):
    q = erp.NewObject("Запрос")
    q.Text = text
    try:
        r = q.Execute().Выгрузить()
        print(f"  [{label}] OK, строк={r.Количество()}", end="")
        if r.Количество() > 0:
            print(f", значение={r.Получить(0).Получить(0)}")
        else:
            print()
        return True
    except Exception as e:
        msg = e.excepinfo[2] if (hasattr(e,'excepinfo') and e.excepinfo) else str(e)
        print(f"  [{label}] FAIL: {msg}")
        return False

