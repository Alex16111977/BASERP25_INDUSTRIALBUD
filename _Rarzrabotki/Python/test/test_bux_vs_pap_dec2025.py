    Бух_Кл_681 = float(row.Бух_Кл_681 or 0)
    Бух_Пост_631 = float(row.Бух_Пост_631 or 0)
    Бух_Пост_371 = float(row.Бух_Пост_371 or 0)

    # Сальдо-сдвиги
