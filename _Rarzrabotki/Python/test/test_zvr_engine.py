плёнка = [с for с in строки if с.РаботаТекст == "Гідроізоляційна плівка"]
проверить(len(плёнка) == 6 and all(float(с.Процент) == 0 for с in плёнка),
          "полностью пустая строка работы должна попасть в снимок нулями")


# ---------------------------------------------------------------- СоздатьДокументы
print("\n=== СоздатьДокументы (идемпотентность: документы 05.08 уже есть)")
обр, сводка = разобрать(Ф15)
обр.Проводить = True

ЗАПРОС_КОЛИЧЕСТВА = ("ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК К ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д "
                     "ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления")
было = int(запрос(ЗАПРОС_КОЛИЧЕСТВА, СС=обр.СтруктураСебестоимости)[0].К)
рез = обр.СоздатьДокументы()
стало = int(запрос(ЗАПРОС_КОЛИЧЕСТВА, СС=обр.СтруктураСебестоимости)[0].К)

print(f"  створено {рез.Створено} · оновлено {рез.Оновлено} · проведено {рез.Проведено} · "
      f"пропущено {рез.Пропущено} · помилка '{рез.Помилка}'")
print(f"  документов по СС: было {было}, стало {стало}")
проверить(рез.Помилка == "", f"ошибка создания: {рез.Помилка}")
проверить(стало == было, f"документы размножились: {было} -> {стало}")
проверить(int(рез.Створено) == 0 and int(рез.Оновлено) == 6, "должно быть обновление 6 документов")
проверить(int(рез.Проведено) == 6, "все 6 должны быть проведены")
проверить(all(str(обр.Дома[i].Документ) != "" for i in range(обр.Дома.Количество())),
          "не у всех домов проставлена ссылка на документ")

# состав ТЧ документов дня: 44 работы × 1 модуль
# Границы дня вписываем литералом ДАТАВРЕМЯ: кириллические глобальные функции 1С
# (НачалоДня/КонецДня) недоступны через COM-прокси, а параметр типа Дата COM сдвигает.
г, м, д = (int(x) for x in str(обр.ДатаЗагрузки)[:10].split("-"))
состав = запрос(
    "ВЫБРАТЬ Д.Номер КАК Номер, КОЛИЧЕСТВО(Т.НомерСтроки) КАК К "
    "ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д ЛЕВОЕ СОЕДИНЕНИЕ "
    "Документ.А_ВыполнениеРаботМодулей.Работы КАК Т ПО Т.Ссылка = Д.Ссылка "
    "ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления "
    f"И Д.Дата МЕЖДУ ДАТАВРЕМЯ({г},{м},{д},0,0,0) И ДАТАВРЕМЯ({г},{м},{д},23,59,59) "
    "СГРУППИРОВАТЬ ПО Д.Номер",
    СС=обр.СтруктураСебестоимости)
строк_в_доках = {int(состав[i].К) for i in range(состав.Количество())}
print(f"  строк в документах дня: {строк_в_доках}")
проверить(строк_в_доках == {44}, "в каждом документе должно быть 44 строки (полный снимок)")

print("\nПРОВАЛОВ:", провалов)
sys.exit(1 if провалов else 0)
