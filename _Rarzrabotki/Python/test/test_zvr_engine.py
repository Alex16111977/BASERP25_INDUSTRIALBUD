# -*- coding: utf-8 -*-
"""Тесты движка обработки «Загрузка выполнения работ».

Работают с объектом конфигурации Обработки.А_ЗагрузкаВыполненияРабот на живой BaseERP.
Запуск: python test_zvr_engine.py
"""
import os
import shutil
import sys
import tempfile

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')

ШАБЛОНЫ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\notebook"
           r"\knowledge_Загрузка файлов в выполнение работ\Шаблоны")
Ф15 = "МД IRS 2026 15 м (МД IRS 2026).xlsx"
Ф30 = "МД IRS 2026 30 м (МД IRS 2026).xlsx"

ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

провалов = 0


def проверить(условие, сообщение):
    global провалов
    if not условие:
        провалов += 1
        print("    ПРОВАЛ:", сообщение)
    return условие


def адрес_файла(имя):
    """Шаблон копируем (Excel держит лок) и кладём во временное хранилище сеанса."""
    dst = os.path.join(tempfile.gettempdir(), "zvr_test_" + имя)
    shutil.copyfile(os.path.join(ШАБЛОНЫ, имя), dst)
    return ERP.ПоместитьВоВременноеХранилище(ERP.NewObject("ДвоичныеДанные", dst))


def запрос(текст, **пар):
    z = ERP.NewObject("Запрос")
    z.Текст = текст
    for k, v in пар.items():
        z.УстановитьПараметр(k, v)
    return z.Выполнить().Выгрузить()


def новая_обработка():
    return ERP.Обработки.А_ЗагрузкаВыполненияРабот.Создать()


# ---------------------------------------------------------------- НормализоватьПроцент
print("=== НормализоватьПроцент")
обр = новая_обработка()

СЛУЧАИ = [
    ("100%", 100, ""), ("100", 100, ""), (" 80 %", 80, ""), ("76,7%", 76.7, ""),
    ("", 0, ""), ("0", 0, ""), ("0%", 0, ""), ("100.0%", 100, ""), ("50 %", 50, ""),
    ("0,5", 0, "Помилка"), ("120%", 0, "Помилка"), ("-5", 0, "Помилка"),
    ("в роботі", 0, "Помилка"), ("-", 0, "Помилка"),
    # «50%%» — описка человека, намерение однозначно: терпим и берём 50, ничего не теряя
    ("50%%", 50, ""),
    ("33,333%", 33.33, "Інфо"),
]
for текст_ячейки, ожид_значение, ожид_уровень in СЛУЧАИ:
    рез = обр.НормализоватьПроцент(текст_ячейки)
    ок = (abs(float(рез.Процент) - ожид_значение) < 0.001 and рез.Уровень == ожид_уровень)
    print(f"  {текст_ячейки!r:12} -> {float(рез.Процент):6} [{рез.Уровень}] {рез.Пояснение}")
    проверить(ок, f"{текст_ячейки!r}: ожидали {ожид_значение}/{ожид_уровень!r}, "
                  f"получили {float(рез.Процент)}/{рез.Уровень!r}")


# ---------------------------------------------------------------- ПрочитатьПаспортФайла
print("\n=== ПрочитатьПаспортФайла")
for имя, ожид_дата, ожид_домов, ожид_модулей, ожид_сс in (
        (Ф15, "2026-08-05", 6, 1, "МД IRS 2026 15 м (МД IRS 2026)"),
        (Ф30, "2026-07-31", 7, 2, "МД IRS 2026 30 м (МД IRS 2026)")):
    обр = новая_обработка()
    п = обр.ПрочитатьПаспортФайла(адрес_файла(имя), имя)
    print(f"  {имя}\n    дата={str(п.Дата)[:10]} СС='{п.ИмяСС}' домів={п.Домов} "
          f"модулів={п.Модулей} помилка='{п.Ошибка}'")
    проверить(п.Ошибка == "", f"паспорт вернул ошибку: {п.Ошибка}")
    проверить(str(п.Дата)[:10] == ожид_дата, f"дата {str(п.Дата)[:10]} вместо {ожид_дата}")
    проверить(п.ИмяСС == ожид_сс, f"СС '{п.ИмяСС}'")
    проверить(int(п.Домов) == ожид_домов and int(п.Модулей) == ожид_модулей, "домов/модулей")
    проверить(str(п.СтруктураСебестоимости) != "", "СС не найдена в базе")

# не тот файл — понятная ошибка, а не молчание
обр = новая_обработка()
чужой = os.path.join(tempfile.gettempdir(), "zvr_not_a_report.xlsx")
import openpyxl
книга = openpyxl.Workbook()
книга.active["A1"] = "просто таблиця"
книга.save(чужой)
п = обр.ПрочитатьПаспортФайла(
    ERP.ПоместитьВоВременноеХранилище(ERP.NewObject("ДвоичныеДанные", чужой)), "zvr_not_a_report.xlsx")
print(f"  чужой файл -> '{п.Ошибка}'")
проверить("Структура собівартості" in п.Ошибка, "чужой файл должен давать понятную ошибку")


# ---------------------------------------------------------------- РазобратьФайл
print("\n=== РазобратьФайл")


def разобрать(имя):
    """Полный цикл «выбрали файл -> заполнили шапку -> расшифровали»."""
    обработка = новая_обработка()
    обработка.ИмяФайла = имя
    паспорт = обработка.ПрочитатьПаспортФайла(адрес_файла(имя), имя)
    обработка.СтруктураСебестоимости = паспорт.СтруктураСебестоимости
    обработка.ДатаЗагрузки = паспорт.Дата
    итог = обработка.РазобратьФайл(адрес_файла(имя), имя)
    return обработка, итог


for имя, домов, модулей in ((Ф15, 6, 1), (Ф30, 7, 2)):
    обр, сводка = разобрать(имя)
    print(f"  {имя}\n    домів {обр.Дома.Количество()} · рядків {обр.Строки.Количество()} · "
          f"робіт {сводка.Работ} · помилок {сводка.Ошибок} · попереджень {сводка.Предупреждений}")
    print(f"    сводка: {обр.ТекстСводки}")
    проверить(сводка.Ошибка == "", f"фатальная ошибка: {сводка.Ошибка}")
    проверить(обр.Дома.Количество() == домов, f"домов {обр.Дома.Количество()} вместо {домов}")
    проверить(обр.Строки.Количество() == 44 * домов * модулей,
              f"строк {обр.Строки.Количество()} вместо {44 * домов * модулей}")
    проверить(сводка.Ошибок == 0, f"ошибок {сводка.Ошибок}")
    проверить(int(обр.КоличествоМодулейФайл) == модулей, "КоличествоМодулейФайл")

    # каждый дом сопоставлен с подразделением и знает, что будет с документом
    состояния = {обр.Дома[i].Состояние for i in range(обр.Дома.Количество())}
    print(f"    состояния домов: {состояния}")
    проверить(all(str(обр.Дома[i].Подразделение) != "" for i in range(обр.Дома.Количество())),
              "есть дом без подразделения")

    # план на модуль: ПланЧасыМодуля × M = норма СС
    нормы = запрос("ВЫБРАТЬ Р.Работа.Наименование КАК Наим, СУММА(Р.Количество) КАК Норма "
                   "ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р ГДЕ Р.Ссылка = &СС "
                   "СГРУППИРОВАТЬ ПО Р.Работа.Наименование", СС=обр.СтруктураСебестоимости)
    карта_норм = {нормы[i].Наим: float(нормы[i].Норма) for i in range(нормы.Количество())}
    плохие = [(обр.Строки[i].РаботаТекст, float(обр.Строки[i].ПланЧасыМодуля))
              for i in range(обр.Строки.Количество())
              if abs(float(обр.Строки[i].ПланЧасыМодуля) * модулей
                     - карта_норм.get(обр.Строки[i].РаботаТекст, 0)) > 0.0001]
    print(f"    инвариант ПланЧасыМодуля×{модулей}=норма: нарушений {len(плохие)}")
    проверить(not плохие, f"нарушен масштаб плана: {плохие[:2]}")

# точечные значения по файлу 15 м
обр, _ = разобрать(Ф15)
строки = [обр.Строки[i] for i in range(обр.Строки.Количество())]
приймання = [с for с in строки if с.РаботаТекст == "Приймання матеріалу"]
проверить(len(приймання) == 6 and all(float(с.Процент) == 100 for с in приймання),
          "«Приймання матеріалу» должно быть 100% во всех 6 домах")
грунт = [с for с in строки if с.РаботаТекст == "Грунтування металокаркасу"]
нули = [с for с in грунт if float(с.Процент) == 0]
