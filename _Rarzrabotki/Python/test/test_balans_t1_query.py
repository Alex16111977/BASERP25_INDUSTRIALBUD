# -*- coding: utf-8 -*-
"""Test 1 (Rule #-1, v1.3): запит А_ФинРез_Баланс Етап 1 — фільтр виключення
3 груп (як варіант штатного звіту). Період СІЧЕНЬ 2026 (закритий), межі —
серверно (1С НачалоПериода/КонецПериода) щоб уникнути TZ-зсуву.
Assert: rows>0; балансова рівність по рядках; ОЗ субконто; виключені статті
відсутні; Σ КонОст повного (відфільтрованого) набору ≈ 0 (Актив=Пасив)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)   # січень 2026, опівдні (TZ-safe anchor)
TOL = 0.01
EXCL = ["Собственные средства", "Доходы текущего периода", "Расходы текущего периода"]

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
print("[OK] BaseERP")

def make_array(items):
    a = conn.NewObject("Массив")
    for it in items: a.Добавить(it)
    return a

q0 = conn.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
s = q0.Выполнить().Выбрать(); s.Следующий(); org = s.С

# межі періоду серверно (1:1 як BSL)
qb = conn.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД"
qb.УстановитьПараметр("М", M)
rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ = rb.НМ; КД = rb.КД
print(f"період: {НМ} .. {КД}")

# 3 виключені статті за Наименование + перевірка ієрархії
qx = conn.NewObject("Запрос")
qx.Текст = """ВЫБРАТЬ Ссылка КАК С, Наименование КАК Н, ЭтоГруппа КАК Г
ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование В (&Сп)"""
qx.УстановитьПараметр("Сп", make_array(EXCL))
tzx = qx.Выполнить().Выгрузить()
excl_refs = []; found = {}
for i in range(tzx.Количество()):
    r = tzx.Получить(i); excl_refs.append(r.С); found[str(r.Н)] = bool(r.Г)
print(f"виключених статей: {tzx.Количество()} {list(found.items())}")
assert tzx.Количество() == 3, f"FAIL: очікувалось 3, знайдено {tzx.Количество()}"
assert found.get("Собственные средства") is True, "FAIL: 'Собственные средства' має бути ГРУПОЮ"

# основний запит Етапу 1 (1:1 як BSL): фільтр НЕ Статья В ИЕРАРХИИ(3 групи)
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Б.Статья) КАК СтатьяИмя,
    ВЫРАЗИТЬ(Б.Аналитика КАК Справочник.ОбъектыЭксплуатации) КАК ОЭ,
    ВЫРАЗИТЬ(Б.Аналитика КАК Справочник.НематериальныеАктивы) КАК НМА,
    СУММА(Б.СуммаНачальныйОстаток) КАК sN, СУММА(Б.СуммаПриход) КАК sP,
    СУММА(Б.СуммаРасход) КАК sR, СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(
        &Д1, &Д2, Авто, ,
        Организация = &Орг И НЕ Статья В ИЕРАРХИИ (&Искл)) КАК Б
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Б.Статья), Б.Аналитика
ИМЕЮЩИЕ НЕ (СУММА(Б.СуммаНачальныйОстаток)=0 И СУММА(Б.СуммаПриход)=0
        И СУММА(Б.СуммаРасход)=0 И СУММА(Б.СуммаКонечныйОстаток)=0)
"""
q.УстановитьПараметр("Д1", НМ); q.УстановитьПараметр("Д2", КД)
q.УстановитьПараметр("Орг", org); q.УстановитьПараметр("Искл", make_array(excl_refs))
tz = q.Выполнить().Выгрузить()
n = tz.Количество()
print(f"rows={n}")
assert n > 0, "FAIL: 0 рядків"

cnt_oe = bal_fail = 0
sumK = 0.0
excl_names = set(EXCL)
for i in range(n):
    r = tz.Получить(i)
    sN=float(r.sN or 0); sP=float(r.sP or 0); sR=float(r.sR or 0); sK=float(r.sK or 0)
    if abs(sK-(sN+sP-sR)) > TOL: bal_fail += 1
    sumK += sK
    if r.ОЭ and conn.ЗначениеЗаполнено(r.ОЭ): cnt_oe += 1
    nm = str(r.СтатьяИмя)
    assert nm not in excl_names, f"FAIL: виключена стаття '{nm}' присутня"

print(f"ОбъектыЭксплуатации непорожніх: {cnt_oe}")
print(f"балансова рівність порушена в {bal_fail} рядках")
print(f"Σ КонОст (відфільтр. набір, Актив−Пасив) = {sumK:,.2f}")
assert bal_fail == 0, f"FAIL: {bal_fail} рядків не балансуються"
assert cnt_oe > 0, "FAIL: немає субконто ОЗ"
assert abs(sumK) < 1.0, f"FAIL: Актив≠Пасив з фільтром (Σ={sumK:,.2f}; січень закритий — має ≈0)"
print("PASS Test 1")
