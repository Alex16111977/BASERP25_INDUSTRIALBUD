# -*- coding: utf-8 -*-
"""
Сверка ПАП vs РасчетыСКлиентами/РасчетыСПоставщиками по каждому регистратору
за декабрь 2025 для ТОВ ІНДАСТРІАЛБУД.

Цель (язык финансиста):
    По каждому первичному документу-регистратору, движущему взаиморасчёты в декабре
    2025, должен выполняться инвариант:

        (ΔПАП.ЗадолженностьКлиентов − ΔПАП.ПолученныеАвансы)
            == Σ РасчётыСКлиентами.Сумма (со знаком: Приход +, Расход −)

        (ΔПАП.ЗадолженностьПередПоставщиками − ΔПАП.ВыданныеАвансы)
            == Σ РасчётыСПоставщиками.Сумма (со знаком)

    Если по документу сальдо-сдвиг в ПАП ≠ сальдо-сдвигу в первичном регистре —
    этот документ сломал взаиморасчёты внутри декабря (он и есть кандидат на
    «искать ошибку в проведении конкретного документа»).

Логика:
    Δ-движения декабря по регистратору = (КонОст − НачОст) внутри декабря,
    поэтому свёртка движений за декабрь и есть «было OK на 01.12 → стало не OK на 31.12».

Исключения (нормальный шум, не баги):
    Регистраторы, которые ПО ОПРЕДЕЛЕНИЮ пишут только в ПАП и не пишут в первичку:
        - РегистраторРасчётов
        - КорректировкаРегистров
        - А_ФинРез_Баланс / А_БюджетМесяц / ЗакрытиеМесяца*
    Их помечаем как 'INFO: только в ПАП (служебный регистратор)' и НЕ включаем
    в основной топ-разлётов.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()

# Регистраторы, которые штатно пишут только в ПАП — не считать их аномалиями
СЛУЖЕБНЫЕ_РЕГИСТРАТОРЫ = {
    'РегистраторРасчётов',
    'РегистраторРасчетов',
    'КорректировкаРегистров',
    'А_ФинРез_Баланс',
    'А_БюджетМесяц',
    'ЗакрытиеМесяца',
    'РаспределениеДоходов',
    'РаспределениеРасходов',
}

ПОРОГ_КОПЕЕК = 0.01

v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# 1) Найти организацию
q = erp.NewObject('Запрос')
q.Текст = (
    'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации '
    'ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
)
орг = q.Выполнить().Выгрузить().Получить(0).Ссылка
print(f'Организация: {орг}', flush=True)

НМ = datetime.datetime(2025, 12, 1, 0, 0, 0)
КМ = datetime.datetime(2025, 12, 31, 23, 59, 59)

# 2) Основной запрос: свёртка по регистратору
qq = erp.NewObject('Запрос')
qq.УстановитьПараметр('Орг', орг)
qq.УстановитьПараметр('НМ', НМ)
qq.УстановитьПараметр('КМ', КМ)
qq.Текст = """
ВЫБРАТЬ
    Т.Регистратор КАК Рег,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьКлиентов)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ЗадКл,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ПолученныеАвансы)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ПолучАв,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьПередПоставщиками)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ЗадПост,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыданныеАвансы)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ВыдАв
ПОМЕСТИТЬ втПАП
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг
    И Т.Период МЕЖДУ &НМ И &КМ
    И Т.Источник В (
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
СГРУППИРОВАТЬ ПО Т.Регистратор
;
ВЫБРАТЬ
    К.Регистратор КАК Рег,
    СУММА(ВЫБОР КОГДА К.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА К.Сумма ИНАЧЕ -К.Сумма КОНЕЦ) КАК Регистр_Кл
ПОМЕСТИТЬ втКл
ИЗ РегистрНакопления.РасчетыСКлиентами КАК К
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО К.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И К.Период МЕЖДУ &НМ И &КМ
СГРУППИРОВАТЬ ПО К.Регистратор
;
ВЫБРАТЬ
    П.Регистратор КАК Рег,
    СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Регистр_Пост
ПОМЕСТИТЬ втПост
ИЗ РегистрНакопления.РасчетыСПоставщиками КАК П
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
        ПО П.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И П.Период МЕЖДУ &НМ И &КМ
СГРУППИРОВАТЬ ПО П.Регистратор
;
ВЫБРАТЬ
    ЕСТЬNULL(ПАП.Рег, ЕСТЬNULL(Кл.Рег, Пост.Рег)) КАК Рег,
    ЕСТЬNULL(ПАП.ПАП_ЗадКл, 0)    КАК ПАП_ЗадКл,
    ЕСТЬNULL(ПАП.ПАП_ПолучАв, 0)  КАК ПАП_ПолучАв,
    ЕСТЬNULL(ПАП.ПАП_ЗадПост, 0)  КАК ПАП_ЗадПост,
    ЕСТЬNULL(ПАП.ПАП_ВыдАв, 0)    КАК ПАП_ВыдАв,
    ЕСТЬNULL(Кл.Регистр_Кл, 0)    КАК Регистр_Кл,
    ЕСТЬNULL(Пост.Регистр_Пост, 0) КАК Регистр_Пост,
    (ЕСТЬNULL(ПАП.ПАП_ЗадКл,0)   - ЕСТЬNULL(ПАП.ПАП_ПолучАв,0)) - ЕСТЬNULL(Кл.Регистр_Кл,0)    КАК Дельта_Кл,
    (ЕСТЬNULL(ПАП.ПАП_ЗадПост,0) - ЕСТЬNULL(ПАП.ПАП_ВыдАв,0))   - ЕСТЬNULL(Пост.Регистр_Пост,0) КАК Дельта_Пост
ИЗ втПАП КАК ПАП
    ПОЛНОЕ СОЕДИНЕНИЕ втКл КАК Кл
        ПО ПАП.Рег = Кл.Рег
    ПОЛНОЕ СОЕДИНЕНИЕ втПост КАК Пост
        ПО ЕСТЬNULL(ПАП.Рег, Кл.Рег) = Пост.Рег
УПОРЯДОЧИТЬ ПО Рег
"""

r = qq.Выполнить().Выгрузить()
всего = r.Количество()
print(f'Всего регистраторов с движениями за декабрь: {всего}', flush=True)

# 3) Классифицируем
аномалии = []   # настоящие проблемы (есть классика, но Δ ≠ 0)
только_пап = [] # пишут только в ПАП (служебные или подозрительные)
только_рег = [] # пишут только в первичку, без ПАП (тоже подозрительно)
ok_строки = 0

for i in range(всего):
    row = r.Получить(i)
    рег = row.Рег
    если_заполнен = bool(рег) and erp.ЗначениеЗаполнено(рег)
    тип = ''
    если_заполнен_итог = если_заполнен
    if если_заполнен:
        try:
            тип = рег.Метаданные().Имя
        except Exception:
            если_заполнен_итог = False
            тип = '<неизвестно>'

    есть_пап = (abs(float(row.ПАП_ЗадКл or 0)) + abs(float(row.ПАП_ПолучАв or 0))
                + abs(float(row.ПАП_ЗадПост or 0)) + abs(float(row.ПАП_ВыдАв or 0))) > ПОРОГ_КОПЕЕК
    есть_кл = abs(float(row.Регистр_Кл or 0)) > ПОРОГ_КОПЕЕК
    есть_пост = abs(float(row.Регистр_Пост or 0)) > ПОРОГ_КОПЕЕК
    есть_реги = есть_кл or есть_пост

    дкл = float(row.Дельта_Кл or 0)
    дпост = float(row.Дельта_Пост or 0)

    запись = dict(
        тип=тип,
        рег=рег if если_заполнен_итог else None,
        пап_задкл=float(row.ПАП_ЗадКл or 0),
        пап_получав=float(row.ПАП_ПолучАв or 0),
        пап_задпост=float(row.ПАП_ЗадПост or 0),
        пап_выдав=float(row.ПАП_ВыдАв or 0),
        рег_кл=float(row.Регистр_Кл or 0),
        рег_пост=float(row.Регистр_Пост or 0),
        дкл=дкл,
        дпост=дпост,
    )

    if есть_пап and not есть_реги:
        запись['метка'] = 'только в ПАП (служебный)' if тип in СЛУЖЕБНЫЕ_РЕГИСТРАТОРЫ else 'ТОЛЬКО в ПАП'
        только_пап.append(запись)
    elif есть_реги and not есть_пап:
        запись['метка'] = 'только в первичке (нет ПАП!)'
        только_рег.append(запись)
    else:
        if abs(дкл) > ПОРОГ_КОПЕЕК or abs(дпост) > ПОРОГ_КОПЕЕК:
            запись['метка'] = 'РАЗЛЁТ'
            аномалии.append(запись)
        else:
            ok_строки += 1

# Сортировка аномалий по |Δ|
аномалии.sort(key=lambda x: max(abs(x['дкл']), abs(x['дпост'])), reverse=True)
только_рег.sort(key=lambda x: max(abs(x['рег_кл']), abs(x['рег_пост'])), reverse=True)

def фрм(x): return f'{x:>14,.2f}'
def подписать(зап):
    рег = зап['рег']
    if рег is None:
        return f'{зап["тип"]} <NULL>'
    try:
        ном = str(рег.Номер).strip()
    except Exception:
        ном = ''
    try:
        дата = рег.Дата.strftime('%Y-%m-%d')
    except Exception:
        дата = ''
    return f'{зап["тип"]} № {ном} от {дата}'

