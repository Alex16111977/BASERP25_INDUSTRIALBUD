# -*- coding: utf-8 -*-
"""ПАП «Оплата труда» — signed cumulative КО по Источник, на конец каждого месяца.
Цель: понять, отличается ли ПАП(Источник=ПустаяСсылка) [= свёртка/PowerBI]
от ПАП(все Источник) [= штатный Управленческий баланс]."""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# upr org — из самого проведённого документа А_ФинРез_Баланс
qo = erp.NewObject("Запрос")
qo.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Организация КАК О ИЗ Документ.А_ФинРез_Баланс "
            "ГДЕ Проведен УПОРЯДОЧИТЬ ПО Дата")
ОргУпр = qo.Выполнить().Выгрузить()[0].О
print(f"ОргУпр = {ОргУпр}")

q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов "
           "ГДЕ Наименование = \"Оплата труда\"")
ОТ = q.Выполнить().Выгрузить()[0].С

month_ends = [
    ("2025-12", datetime.datetime(2025,12,31,23,59,59)),
    ("2026-01", datetime.datetime(2026, 1,31,23,59,59)),
    ("2026-02", datetime.datetime(2026, 2,28,23,59,59)),
    ("2026-03", datetime.datetime(2026, 3,31,23,59,59)),
]

# карта Источник-ref -> представление
qm = erp.NewObject("Запрос")
qm.Текст = ("ВЫБРАТЬ Ссылка КАК С, ПРЕДСТАВЛЕНИЕ(Ссылка) КАК П "
            "ИЗ Перечисление.ИсточникиУправленческогоБаланса")
carta = {}
for r in qm.Выполнить().Выгрузить():
    carta[erp.XMLСтрока(r.С)] = (r.П if r.П else "(ПустаяСсылка)")

# ПАП signed cumulative по Источник (как втПАП в Своде, но без фильтра Источник)
TEXT = """
ВЫБРАТЬ
    Т.Источник КАК ИстРеф,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= &КонМес
    И Т.Статья = &ОТ
    {ОРГ}
СГРУППИРОВАТЬ ПО Т.Источник
"""

for orgflag, orglabel in [("", "ВСЕ организации"), ("И Т.Организация = &Орг", "ОргУпр")]:
    print(f"\n############## ПАП(ОТ) — фильтр организации: {orglabel} ##############")
    for label, dt in month_ends:
        qb = erp.NewObject("Запрос")
        qb.УстановитьПараметр("ОТ", ОТ)
        qb.УстановитьПараметр("КонМес", dt)
        if orgflag:
            qb.УстановитьПараметр("Орг", ОргУпр)
        qb.Текст = TEXT.replace("{ОРГ}", orgflag)
        rb = qb.Выполнить().Выгрузить()
        total = 0.0
        empty = 0.0
        print(f"  --- {label} (на {dt:%d.%m.%Y}) ---")
        for r in rb:
            src = carta.get(erp.XMLСтрока(r.ИстРеф), "?")
            ко = f(r.КО)
            total += ко
            if src == "(ПустаяСсылка)":
                empty = ко
            print(f"      Источник='{src:<34}' КО={ко:>16,.2f}")
        print(f"      >>> ИТОГО(все Источник) = {total:>16,.2f}  |  только ПустаяСсылка = {empty:>16,.2f}  |  Δ(прочие) = {total-empty:>16,.2f}")
