# заполнить ДокументиМалоценки: док + ФизЛицо + Способ на складе
for стр in обр.ДокументиМалоценки:
    стр.ДокументПоНормам = мавэДок; стр.ДокументДодаткова = мавэДок
    стр.ФизЛицо = физлицо; стр.СпособОтраженияРасходов = способ

рез = обр.ЗаполнитьДокументыПоАнализу()
