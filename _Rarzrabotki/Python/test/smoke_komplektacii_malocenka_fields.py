МАРКЕР = "ТЕСТ Малоценка-поля (Claude) — не проводить"
НаДату = datetime.datetime(2026, 7, 13, 23, 59, 59)
ok = True

сч22 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("22")
сч20 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("20")
сч28 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("28")
способ = buh.Справочники.СпособыОтраженияРасходовПоАмортизации.НайтиПоКоду("00-000055")
ндс_обл = buh.Справочники.НалоговыеНазначенияАктивовИЗатрат.НДС_Облагаемая
скл = None
vs = buh.Справочники.Склады.Выбрать()
while vs.Следующий():
    if "ІС МД МХП ОРІЛЬ" in vs.Наименование and "виробнич" in vs.Наименование:
        скл = vs.Ссылка; break
qf = buh.NewObject("Запрос")
qf.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.ФизическиеЛица ГДЕ НЕ ПометкаУдаления"
sf = qf.Выполнить().Выбрать(); sf.Следующий(); физлицо = sf.С
print("Склад:", скл.Наименование if скл else "НЕТ", "| Способ:", способ.Наименование, "| ФизЛицо:", физлицо.Наименование)

def первая_организация():
    q = buh.NewObject("Запрос"); q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ НЕ ПометкаУдаления"
    s = q.Выполнить().Выбрать(); return s.С if s.Следующий() else None
def имеет(об, имя):
    try: getattr(об, имя); return True
    except Exception: return False
def get_or_create(тип):
    q = buh.NewObject("Запрос"); q.УстановитьПараметр("М", МАРКЕР)
    q.Текст = f"ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.{тип} ГДЕ ВЫРАЗИТЬ(Комментарий КАК Строка(200)) = &М"
    s = q.Выполнить().Выбрать()
    if s.Следующий(): return s.С
    об = getattr(buh.Документы, тип).СоздатьДокумент(); об.Дата = НаДату
    if имеет(об, "Организация"): об.Организация = первая_организация()
    об.Комментарий = МАРКЕР; об.Записать(buh.РежимЗаписиДокумента.Запись); return об.Ссылка

мавэДок = get_or_create("ПередачаМалоценныхАктивовВЭксплуатацию")

