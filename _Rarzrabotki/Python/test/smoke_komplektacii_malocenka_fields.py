мавэ = мавэДок.ПолучитьОбъект()
кол = мавэ.МалоценныеАктивы.Количество()
плохой_налог = sum(1 for r in мавэ.МалоценныеАктивы if buh.String(r.НалоговоеНазначение) != buh.String(ндс_обл))
плохой_физл = sum(1 for r in мавэ.МалоценныеАктивы if buh.String(r.ФизЛицо) != buh.String(физлицо))
с_назн = sum(1 for r in мавэ.МалоценныеАктивы if buh.ЗначениеЗаполнено(r.НазначениеИспользования))
# проверить корректность НазначенияИспользования: владелец=номенклатура строки, способ=выбранный
плохой_назн = 0
for r in мавэ.МалоценныеАктивы:
    ни = r.НазначениеИспользования
    if buh.ЗначениеЗаполнено(ни):
        if buh.String(ни.Владелец) != buh.String(r.Номенклатура) or buh.String(ни.СпособОтраженияРасходов) != buh.String(способ):
            плохой_назн += 1
