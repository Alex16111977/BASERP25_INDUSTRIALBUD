# -*- coding: utf-8 -*-
"""Анализ: какие ТИПЫ документов пишут в РегистрНакопления.ПрочиеРасходы.
По каждому типу: кол-во документов, строк движений, Σ Приход, сколько движений с ПУСТОЙ ФормаPL
(= сколько уйдёт в Форма1 общим register-level дефолтом)."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    ПР.Регистратор КАК Рег,
    КОЛИЧЕСТВО(*) КАК Строк,
    СУММА(ВЫБОР КОГДА ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПР.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Пусто,
    СУММА(ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Ф1,
    СУММА(ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Ф2
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
СГРУППИРОВАТЬ ПО ПР.Регистратор
"""
t = q.Execute().Выгрузить()
agg = {}  # имя типа -> [докум, строк, приход, пусто, ф1, ф2]
for i in range(t.Количество()):
    r = t.Получить(i)
    имя = r.Рег.Метаданные().Имя
    a = agg.setdefault(имя, [0,0,0.0,0,0,0])
    a[0]+=1; a[1]+=r.Строк; a[2]+=r.Приход; a[3]+=r.Пусто; a[4]+=r.Ф1; a[5]+=r.Ф2

print(f"Типов документов-регистраторов с движениями: {len(agg)}; всего регистраторов: {t.Количество()}")
print(f"{'Тип документа':<48}{'Док':>6}{'Строк':>8}{'ΣПриход':>16}{'Пусто':>8}{'Ф1':>7}{'Ф2':>7}")
print("-"*100)
for имя, a in sorted(agg.items(), key=lambda kv: -kv[1][1]):
    print(f"{имя:<48}{a[0]:>6}{a[1]:>8}{a[2]:>16,.0f}{a[3]:>8}{a[4]:>7}{a[5]:>7}")
итого = [sum(a[i] for a in agg.values()) for i in range(6)]
print("-"*100)
print(f"{'ИТОГО':<48}{итого[0]:>6}{итого[1]:>8}{итого[2]:>16,.0f}{итого[3]:>8}{итого[4]:>7}{итого[5]:>7}")
