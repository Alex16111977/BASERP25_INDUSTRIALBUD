# -*- coding: utf-8 -*-
"""Аудит п.6: факт денег Казны по проектам × статьям × виду оплаты × месяцам (01.2025–09.2026).

Источник — РН.А_ДвиженияДенегИзКазны (оборотный, ЗНАКОВЫЙ: приход +, расход −). Транзит УТ-001210/1211
и финансирование помечаются в снимке, не выбрасываются (расчётчик решает сам). Поступления — ещё и
по дням и контрагентам (для профилей оплат заказчиков). Плюс справочники: проекты и статьи ДДС.
Вывод: data/projects.json, data/articles.json, data/fakt_deneg.json, data/fakt_postupleniya.json.
"""
import collections
from moy_byudzhet_common import *

print("снимок", snapshot_stamp())
pm, root = projects()
save("projects.json", {"root": root, "map": pm})
art = articles()
save("articles.json", art)

нач, кон = dt(2025, 1, 1), dt(2026, 9, 30, 23, 59, 59)
t = query("""ВЫБРАТЬ
    Д.Подразделение КАК Подр,
    Д.СтатьяДвиженияДенежныхСредств КАК Статья,
    Д.ТипДенежныхСредств КАК Тип,
    НАЧАЛОПЕРИОДА(Д.Период, МЕСЯЦ) КАК Месяц,
    СУММА(Д.Сумма) КАК Сумма,
    КОЛИЧЕСТВО(*) КАК Строк
ИЗ РегистрНакопления.А_ДвиженияДенегИзКазны КАК Д
ГДЕ Д.Период МЕЖДУ &Нач И &Кон
  И Д.Подразделение В ИЕРАРХИИ (ВЫБРАТЬ П.Ссылка ИЗ Справочник.СтруктураПредприятия КАК П ГДЕ П.Код = &Корень)
СГРУППИРОВАТЬ ПО Д.Подразделение, Д.СтатьяДвиженияДенежныхСредств, Д.ТипДенежныхСредств, НАЧАЛОПЕРИОДА(Д.Период, МЕСЯЦ)""",
          Нач=нач, Кон=кон, Корень=ROOT_CODE)
erp = conn()
out = []
for i in range(t.Количество()):
    r = t.Получить(i)
    pu = uid(r.Подр)
    au = uid(r.Статья) if erp.ЗначениеЗаполнено(r.Статья) else ""
    a = art.get(au, {"code": "", "name": "<без статьи>", "type": ""})
    out.append({"proj": pm[pu]["uid"], "projname": pm[pu]["name"], "dept": pm[pu]["dept"],
                "art": a["code"], "artname": a["name"], "type": S(r.Тип), "month": ym(r.Месяц),
                "sum": float(r.Сумма), "n": int(r.Строк)})
save("fakt_deneg.json", {"stamp": snapshot_stamp(), "rows": out})

# поступления по дням и контрагентам (документ-зеркало Казны)
t = query("""ВЫБРАТЬ
    Д.Подразделение КАК Подр, Д.СтатьяДвиженияДенежныхСредств КАК Статья, Д.ТипДенежныхСредств КАК Тип,
    ДЕНЬ(Д.Период) КАК Д, МЕСЯЦ(Д.Период) КАК М, ГОД(Д.Период) КАК Г,
    ВЫБОР КОГДА Д.ДокументДвиженияКазны ССЫЛКА Документ.ПоступлениеБезналичныхДенежныхСредств
        ТОГДА ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.ПоступлениеБезналичныхДенежныхСредств).Контрагент.Наименование
        КОГДА Д.ДокументДвиженияКазны ССЫЛКА Документ.ПриходныйКассовыйОрдер
        ТОГДА ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.ПриходныйКассовыйОрдер).Контрагент.Наименование
        ИНАЧЕ ВЫРАЗИТЬ(Д.ТекстДокументаКазны КАК СТРОКА(150)) КОНЕЦ КАК Контрагент,
    СУММА(Д.Сумма) КАК Сумма
ИЗ РегистрНакопления.А_ДвиженияДенегИзКазны КАК Д
ГДЕ Д.Период МЕЖДУ &Нач И &Кон И Д.Сумма > 0
  И Д.Подразделение В ИЕРАРХИИ (ВЫБРАТЬ П.Ссылка ИЗ Справочник.СтруктураПредприятия КАК П ГДЕ П.Код = &Корень)
  И НЕ Д.СтатьяДвиженияДенежныхСредств.Код В (&Исключить)
СГРУППИРОВАТЬ ПО Д.Подразделение, Д.СтатьяДвиженияДенежныхСредств, Д.ТипДенежныхСредств,
    ДЕНЬ(Д.Период), МЕСЯЦ(Д.Период), ГОД(Д.Период),
    ВЫБОР КОГДА Д.ДокументДвиженияКазны ССЫЛКА Документ.ПоступлениеБезналичныхДенежныхСредств
        ТОГДА ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.ПоступлениеБезналичныхДенежныхСредств).Контрагент.Наименование
        КОГДА Д.ДокументДвиженияКазны ССЫЛКА Документ.ПриходныйКассовыйОрдер
        ТОГДА ВЫРАЗИТЬ(Д.ДокументДвиженияКазны КАК Документ.ПриходныйКассовыйОрдер).Контрагент.Наименование
        ИНАЧЕ ВЫРАЗИТЬ(Д.ТекстДокументаКазны КАК СТРОКА(150)) КОНЕЦ""",
          Нач=нач, Кон=кон, Корень=ROOT_CODE, Исключить=list(ТРАНЗИТ | ФИНАНСИРОВАНИЕ))
rec = []
for i in range(t.Количество()):
    r = t.Получить(i)
    pu = uid(r.Подр)
    au = uid(r.Статья) if erp.ЗначениеЗаполнено(r.Статья) else ""
    a = art.get(au, {"code": "", "name": "<без статьи>"})
    rec.append({"proj": pm[pu]["uid"], "projname": pm[pu]["name"], "art": a["code"], "artname": a["name"],
                "type": S(r.Тип), "date": f"{int(r.Г):04d}-{int(r.М):02d}-{int(r.Д):02d}",
                "kontr": S(r.Контрагент).strip(), "sum": float(r.Сумма)})
save("fakt_postupleniya.json", {"stamp": snapshot_stamp(), "rows": rec})

# сводка: проект × месяц 2026, операционный поток (без транзита и финансирования)
agg = collections.defaultdict(lambda: [0.0, 0.0])
months = set()
for r in out:
    if r["art"] in ТРАНЗИТ or r["art"] in ФИНАНСИРОВАНИЕ or not r["month"].startswith("2026"):
        continue
    months.add(r["month"])
    k = (r["projname"], r["month"])
    agg[k][0 if r["sum"] > 0 else 1] += r["sum"]
months = sorted(months)
print("\nОперационный поток 2026 (поступления / выплаты), тыс. грн:")
print(f"{'проект':<28}" + "".join(f"{m[2:]:>15}" for m in months))
for p in sorted({k[0] for k in agg}):
    print(f"{p[:28]:<28}" + "".join(f"{agg[(p, m)][0]/1e3:>7.0f}/{-agg[(p, m)][1]/1e3:<7.0f}" for m in months))
пустые = [f"2026-{m:02d}" for m in range(1, 10) if f"2026-{m:02d}" not in months]
print("месяцы 2026 без движений:", пустые)
