def чек(имя, факт, эталон, допуск=ДОПУСК):
    ok = abs(факт - эталон) < допуск
    print(f"    {имя:14} = {факт:>16,.2f}   эталон {эталон:>16,.2f}   {'OK' if ok else 'РАСХОЖДЕНИЕ'}")
    if not ok:
        провалы.append(f"{имя}: {факт} vs {эталон}")
    return ok


def свод_по_подразделениям(erp):
    q = erp.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ Р.Подразделение.Наименование КАК Подр, "
        "СУММА(Р.ПланЧасы) КАК ПланЧасы, СУММА(Р.ФактЧасы) КАК ФактЧасы, "
        "СУММА(Р.ВиконанняЧасы) КАК EV, СУММА(Р.ПланГрн) КАК ПланГрн, "
        "СУММА(Р.ФактГрн) КАК ФактГрн, СУММА(Р.ПланНаФактГрн) КАК ETC, "
        "КОЛИЧЕСТВО(*) КАК Строк "
        "ИЗ РегистрСведений.А_ПланФактПроизводство_Свод КАК Р "
        "СГРУППИРОВАТЬ ПО Р.Подразделение.Наименование")
    t = q.Execute().Выгрузить()
    return {str(t.Получить(i).Подр): {k: float(getattr(t.Получить(i), k) or 0)
                                      for k in ("ПланЧасы", "ФактЧасы", "EV", "ПланГрн", "ФактГрн", "ETC", "Строк")}
            for i in range(t.Количество())}


