НП = datetime.datetime(2020, 1, 1); КП = datetime.datetime(2030, 12, 31, 23, 59, 59)
ТИП_ПТУ = "ПриобретениеТоваровУслуг"

def прогнать(имя_сс):
    сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(имя_сс)
    assert not сс.Пустая(), f"СС не найдена: {имя_сс}"
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("СС", сс.Ссылка)
    q.УстановитьПараметр("НачП", НП); q.УстановитьПараметр("КонП", КП)
    q.Текст = ТЕКСТ
    try:
        тз = q.Выполнить().Выгрузить()
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        open(ERR, "w", encoding="utf-8").write(str(info[2]) if info and len(info) > 2 else str(e))
        print(f"QUERY ERROR -> {ERR}"); raise
    cols = [c.Имя for c in тз.Колонки]
    assert "НоменклатураНаименование" in cols, "нет колонки НоменклатураНаименование"
    план_ч = факт_ч = вик_ч = мат_фг = 0.0
    с_именем = факт_строк = 0
    ключи = set()
    for i in range(тз.Количество()):
        r = тз.Получить(i)
        имя = str(r.НоменклатураНаименование or "").strip()
        # грейн-ключ БЕЗ нового поля — прежний ключ должен остаться уникальным (нет дробления)
        ключ = (к(r.Подразделение), r.Блок, r.Категория, к(r.Этап), к(r.Работа),
                к(r.ОбщееНазвание), к(r.Аналитика), к(r.Единица),
                "" if r.Документ is None else к(r.Документ))
        assert ключ not in ключи, f"дробление грейна: дубль ключа {ключ}"
        ключи.add(ключ)
        if имя:
            с_именем += 1
            assert r.Блок == "2. Матеріали", f"имя заполнено вне материалов: {r.Блок}"
            assert not пусто(r.Аналитика) and имя == str(r.Аналитика.Наименование).strip(), \
                f"имя '{имя}' != Аналитика.Наименование"
        # у факта закупок (Документ = ПриобретениеТоваровУслуг) имя обязано быть
        if r.Документ is not None and hasattr(r.Документ, 'Метаданные') \
                and str(r.Документ.Метаданные().Имя) == ТИП_ПТУ and not пусто(r.Аналитика):
            факт_строк += 1
            assert имя, "у факта закупок пустое НоменклатураНаименование"
        if r.Блок == "1. Праця":
            план_ч += f(r.ПланЧасы); факт_ч += f(r.ФактЧасы); вик_ч += f(r.ВиконанняЧасы)
            assert имя == "", "у труда имя должно быть пустым"
        if r.Блок == "2. Матеріали":
            мат_фг += f(r.ФактГрн)
    print(f"[{имя_сс[:20]}...] строк={тз.Количество()} с_именем={с_именем} факт_строк={факт_строк}")
    print(f"  Труд: ПланЧасы={план_ч:.2f} ФактЧасы={факт_ч:.2f} ВиконанняЧасы={вик_ч:.2f}; "
          f"Материалы ФактГрн={мат_фг:.2f}")
    return план_ч, факт_ч, вик_ч, мат_фг, с_именем, факт_строк

пч, фч, _, мфг, сим, фстр = прогнать("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
assert abs(пч - 2795) < 0.01, f"ОРІЛЬ ПланЧасы {пч} != 2795"
assert abs(фч - 2389) < 0.01, f"ОРІЛЬ ФактЧасы {фч} != 2389"
