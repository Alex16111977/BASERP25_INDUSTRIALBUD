# -*- coding: utf-8 -*-
"""Заполнение реквизита Направление=Производство у договоров класса А сверки (BuhBud).

Разведка 16.08.2026 (doc_finrep_razvedka_napravlenie*.py) по списку из шести позиций
показала: у пяти договоров Направление УЖЕ = «Производство», и только у одного ПУСТО:

  f35e3281-a4d3-11f0-8100-00155dce3d04  «Договір підряду 24/09/25 Глобине Форшахта»
      Номер=24/09/25, Дата=24.09.2025, Владелец=ІНДАСТРIАЛБУД ТОВ,
      Подразделение=<ПУСТО> (ожидалось МК Глобино), Направление=<ПУСТО>.

НЕ включены (уже «Производство», записывать нечего):
  d5016cf2-21ef-11f1-810b-00155dce3d04  БА 1103/2026 (ОРІЛЬ-ЛІДЕР, МД МХП ОРІЛЬ)
  df0f382e-a58c-11ef-80d4-00155d235309  № 28/10/24 (ДРУЖБА-НОВА, МД Кернел Кухня)
  27eebd71-276c-11f1-810c-00155dce3d04  20/01/26 Чорноморськ(компресорна)
  89c5af80-066e-11f1-8106-00155dce3d04  20/01/26 Чорноморськ(наливна ест)
  63d9d6c7-3d85-11f1-8110-00155dce3d04  № 10499944 CMS ID (ПРООН, МД ПРООН Черкаси  ДСНС)
Договоров с Направлением, заполненным ДРУГИМ значением, среди целевых нет; скрипт
на всякий случай проверяет это на живых данных и такие пропускает с пометкой.

Запуск:
    python doc_finrep_fix_napravlenie.py            — dry-run (ничего не пишет)
    python doc_finrep_fix_napravlenie.py --apply    — записать Направление=Производство
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ПРИМЕНЯТЬ = "--apply" in sys.argv

# UUID найден разведкой и проверяется ниже по наименованию
УИД_ПРОИЗВОДСТВО = "9d2c848e-1ae7-11f0-80dc-00155d235309"

# (UUID договора, комментарий, имя подразделения для заполнения ПУСТОГО или None)
# ТОЛЬКО договоры с ПУСТЫМ Направлением по разведке. Подразделение заполняется лишь
# если оно ПУСТО — заполненное другим значением скрипт не трогает.
ЦЕЛЕВЫЕ = [
    ("f35e3281-a4d3-11f0-8100-00155dce3d04",
     "Договір підряду 24/09/25 Глобине Форшахта (ІНДАСТРIАЛБУД ТОВ; "
     "подразделение у договора тоже пусто — ожидалось МК Глобино)",
     "МК Глобино"),
    ("bcc75bea-99f2-11f0-80fe-00155dce3d04",
     "Договір підряду 16/09/25-2 Глобине Пож рез-7.1-7.3 (Excel r28; "
     "как и у Форшахты, пусты Направление и Подразделение — братья -1/-3 на МК Глобино)",
     "МК Глобино"),
]

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# --- элемент «Производство» ---
напр = buh.Справочники.Направления.НайтиПоНаименованию("Производство", True)
if str(buh.String(напр)) == "":
    print("ОШИБКА: направление «Производство» не найдено")
    sys.exit(1)
уид_факт = str(buh.String(напр.УникальныйИдентификатор()))
if уид_факт != УИД_ПРОИЗВОДСТВО:
    print(f"ОШИБКА: UUID «Производство» {уид_факт} != ожидаемого {УИД_ПРОИЗВОДСТВО}")
    sys.exit(1)
print(f"Направление «Производство»: {уид_факт}")
print(f"Режим: {'ЗАПИСЬ (--apply)' if ПРИМЕНЯТЬ else 'DRY-RUN'}\n")

записано = пропущено_заполнено = пропущено_другое = ошибки = 0
for уид_стр, комментарий, имя_подр in ЦЕЛЕВЫЕ:
    уид = buh.NewObject("УникальныйИдентификатор", уид_стр)
    ссылка_дог = buh.Справочники.ДоговорыКонтрагентов.ПолучитьСсылку(уид)
    объект = ссылка_дог.ПолучитьОбъект()
    if объект is None:
        print(f"[ОШИБКА] {уид_стр}: договор не найден в базе — пропуск")
        ошибки += 1
        continue

    имя = " ".join(str(объект.Наименование).split())
    тек_напр = str(buh.String(объект.Направление))
    тек_подр = str(buh.String(объект.Подразделение))
    print(f"Договор: {имя}")
    print(f"  UUID: {уид_стр}")
    print(f"  Комментарий: {комментарий}")
    print(f"  Текущее Направление: {тек_напр if тек_напр else '<ПУСТО>'}")
    print(f"  Текущее Подразделение: {тек_подр if тек_подр else '<ПУСТО>'}")

    if тек_напр == "Производство":
        print("  -> уже «Производство», запись не нужна\n")
        пропущено_заполнено += 1
        continue
    if тек_напр:
        print(f"  -> ЗАПОЛНЕНО ДРУГИМ значением («{тек_напр}») — НЕ трогаем, в отчёт\n")
        пропущено_другое += 1
        continue

    ставим_подр = None
    if имя_подр and not тек_подр:
        ставим_подр = buh.Справочники.Подразделения.НайтиПоНаименованию(имя_подр, True)
        if str(buh.String(ставим_подр)) == "":
            print(f"  [ОШИБКА] подразделение «{имя_подр}» не найдено — Подразделение не заполняем")
            ставим_подр = None
    elif имя_подр and тек_подр:
        print(f"  -> Подразделение уже заполнено («{тек_подр}») — не трогаем")

    if ПРИМЕНЯТЬ:
        объект.Направление = напр
        if ставим_подр is not None:
            объект.Подразделение = ставим_подр
        объект.Записать()
        суффикс = f" + Подразделение = {имя_подр}" if ставим_подр is not None else ""
        print(f"  -> ЗАПИСАНО: Направление = Производство{суффикс}\n")
        записано += 1
    else:
        суффикс = f" + Подразделение = {имя_подр}" if ставим_подр is not None else ""
        print(f"  -> [dry-run] будет установлено Направление = Производство{суффикс}\n")
        записано += 1

print("=== ИТОГ ===")
print(f"  {'записано' if ПРИМЕНЯТЬ else 'к записи (dry-run)'}: {записано}")
print(f"  уже заполнено «Производство»: {пропущено_заполнено}")
print(f"  заполнено другим (пропуск): {пропущено_другое}")
print(f"  ошибки: {ошибки}")
if not ПРИМЕНЯТЬ:
    print("\n>>> DRY-RUN. Ничего не записано. Для записи: --apply")
