def тз(т):
    cols = [т.Колонки.Получить(i).Имя for i in range(т.Колонки.Количество())]
    return [{c: т.Получить(i).Получить(j) for j, c in enumerate(cols)}
            for i in range(т.Количество())]


def пусто(з):
    return S(з).strip() == ""


def да(з):
    return S(з) in ("Да", "True")


def ключ_свода(стр):
    return tuple(S(стр[f]) for f in КЛЮЧ)


def ключ_тч(стр):
    return tuple(S(getattr(стр, f)) for f in КЛЮЧ)


def чис(з, зн=2):
    try:
        return round(float(S(з).replace("\u00a0", "").replace(" ", "").replace(",", ".")), зн)
    except Exception:
        return None


def тч_совпадает(об, свод):
    if об.Товары.Количество() != len(свод):
        return False
    по_ключу = {}
    for i in range(об.Товары.Количество()):
        по_ключу[ключ_тч(об.Товары.Получить(i))] = об.Товары.Получить(i)
    for стр in свод:
        т = по_ключу.get(ключ_свода(стр))
        if т is None:
            return False
        for поле, зн in (("Количество", 3), ("КоличествоУпаковок", 3),
                         ("Сумма", 2), ("СуммаНДС", 2), ("СуммаСНДС", 2)):
            if чис(getattr(т, поле), зн) != чис(стр[поле], зн):
                return False
        if S(т.ДатаПоступления) != S(стр["ДатаПоступления"]):
            return False
    return True


