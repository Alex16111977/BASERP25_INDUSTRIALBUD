# -*- coding: utf-8 -*-
"""Тест функции УдалитьДокументыЗакрытия — фильтр по флагу
А_ДляЗакрытиеОтрицательныхОстатков, опциональный период.

Создаёт 3 тестовых документа с флагом:
  D1: 15.06.2026 (вне типичного периода)
  D2: 15.07.2026
  D3: 15.08.2026 — у этого флаг будет снят перед запуском удаления
Затем проверяет:
  [A] Удаление БЕЗ периода → удалятся D1 и D2 (D3 защищён двойной проверкой флага)
  [B] Повторное удаление → 0 (всё уже удалено)
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\build\ЗакрытиеОтрицательныхОстатков.epf"
ORG_UUID = "6bee36b2-53f0-11e6-80d3-000c29bbac23"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ДАТАВРЕМЯ(2026,6,15) КАК Д1, ДАТАВРЕМЯ(2026,7,15) КАК Д2, "
          "ДАТАВРЕМЯ(2026,8,15) КАК Д3")
r = q.Execute().Выгрузить().Получить(0)
date1, date2, date3 = r.Д1, r.Д2, r.Д3

org = erp.Справочники.Организации.ПолучитьСсылку(
    erp.NewObject("УникальныйИдентификатор", ORG_UUID))

q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Скл.Ссылка КАК С ИЗ Справочник.Склады КАК Скл ГДЕ Скл.Наименование = \"СТІЛ Глобино виробничий\""
sklad = q.Execute().Выгрузить().Получить(0).С

statya = erp.ПланыВидовХарактеристик.СтатьиДоходов.НайтиПоКоду("000001007")
valuta = erp.Константы.ВалютаРегламентированногоУчета.Получить()


def create_doc(dt):
    d = erp.Документы.ОприходованиеИзлишковТоваров.СоздатьДокумент()
    d.Дата = dt
    d.Организация = org
    d.Склад = sklad
    d.Подразделение = sklad.Подразделение
    d.СтатьяДоходов = statya
    d.АналитикаДоходов = org
    d.Валюта = valuta
    d.А_ДляЗакрытиеОтрицательныхОстатков = True
    d.Комментарий = "TEST для test_zakrytie_udalenie_v2.py"
    d.ОбменДанными.Загрузка = True
    d.Записать()
    return d.Ссылка


def count_docs():
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
    ИЗ Документ.ОприходованиеИзлишковТоваров КАК Д
    ГДЕ Д.А_ДляЗакрытиеОтрицательныхОстатков = ИСТИНА
      И Д.Комментарий ПОДОБНО "TEST для test_zakrytie_udalenie_v2%"
    """
    return q.Execute().Выгрузить().Получить(0).К


print("=" * 60)
print("[Подготовка] Создаю 3 тестовых документа...")
ref1 = create_doc(date1)
ref2 = create_doc(date2)
ref3 = create_doc(date3)
print(f"  D1={erp.String(ref1)} D2={erp.String(ref2)} D3={erp.String(ref3)}")
print(f"  Документов с флагом+TEST: {count_docs()}")

# Снимаю флаг у D3 — он не должен удалиться (защита двойной проверки)
print("[Подготовка] Снимаю флаг у D3...")
obj3 = ref3.ПолучитьОбъект()
obj3.А_ДляЗакрытиеОтрицательныхОстатков = False
obj3.ОбменДанными.Загрузка = True
obj3.Записать()

# [A] Удаление БЕЗ периода
print("\n[A] УдалитьДокументыЗакрытия() — без периода")
обработка = erp.ВнешниеОбработки.Создать(EPF)
обработка.Организация = org
рез = обработка.УдалитьДокументыЗакрытия()
print(f"  Удалено: {рез.Удалено}, Пропущено: {рез.Пропущено}, Ошибок: {рез.Ошибок}")
assert int(рез.Удалено) == 2, f"Ожидалось 2 удаления (D1, D2), получено {рез.Удалено}"
# D3 должен сохраниться (флаг снят, в запрос не попал — не пропущено)
after_a = count_docs()
print(f"  Тестовых с флагом осталось: {after_a}")
assert after_a == 0, f"Должно остаться 0 (D3 без флага не в счёте)"

# Проверяю что D3 физически жив (его флаг снят, но документ существует)
exists = ref3.ПолучитьОбъект() is not None
print(f"  D3 физически существует: {exists} (флаг был снят)")
assert exists, "D3 не должен быть удалён — у него снят флаг"

# [B] Повторный прогон — 0
print("\n[B] Повторный прогон — должно быть 0")
рез2 = обработка.УдалитьДокументыЗакрытия()
print(f"  Удалено: {рез2.Удалено}, Пропущено: {рез2.Пропущено}, Ошибок: {рез2.Ошибок}")
assert int(рез2.Удалено) == 0

# Чистка: удаляю D3
print("\n[Чистка] Удаляю D3 (с включённым флагом)...")
obj3 = ref3.ПолучитьОбъект()
obj3.А_ДляЗакрытиеОтрицательныхОстатков = True
obj3.ОбменДанными.Загрузка = True
obj3.Записать()
рез3 = обработка.УдалитьДокументыЗакрытия()
print(f"  Удалено: {рез3.Удалено}")

print("=" * 60)
print("OK")
