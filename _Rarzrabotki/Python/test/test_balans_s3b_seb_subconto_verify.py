def прочитать(ref):
    qr = conn.NewObject("Запрос")
    qr.Текст = """ВЫБРАТЬ
		Организация КАК Орг,
		ЕСТЬNULL(Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
		Статья КАК Ст, ПРЕДСТАВЛЕНИЕ(Статья) КАК СтП,
		Расхождение КАК Рх, Номенклатура КАК Ном, Склад КАК Скл,
		ДокументДвижения КАК ДД,
		СуммаНачальныйОстаток КАК НО, СуммаПриход КАК Пр,
		СуммаРасход КАК Рс, СуммаКонечныйОстаток КАК КО
	ИЗ РегистрСведений.А_ОтчетБаланс_Свод
	ГДЕ Регистратор=&Д И Source=&Ист"""
    qr.УстановитьПараметр("Д", ref); qr.УстановитьПараметр("Ист", ИСТ_СЕБ)
    t = qr.Выполнить().Выгрузить()
    свод = {}; скл = ном = плугов = докзап = всего = 0
    плуг_кпс = set(); дет_ключи = Counter()
    плуг_ном_скл_ошибок = 0
    for i in range(t.Количество()):
        r = t.Получить(i); всего += 1
        орг = conn.XMLСтрока(r.Орг)
        подр = conn.XMLСтрока(r.Подр) if conn.ЗначениеЗаполнено(r.Подр) else "∅"
        ст = conn.XMLСтрока(r.Ст)
        d = свод.setdefault((орг, подр, ст), [0.0, 0.0, 0.0, 0.0, str(r.СтП)])
        d[0] += float(r.НО or 0); d[1] += float(r.Пр or 0)
        d[2] += float(r.Рс or 0); d[3] += float(r.КО or 0)
        if conn.ЗначениеЗаполнено(r.ДД):
            докзап += 1
        if bool(r.Рх):
            плугов += 1; плуг_кпс.add((орг, подр, ст))
            if conn.ЗначениеЗаполнено(r.Ном) or conn.ЗначениеЗаполнено(r.Скл):
                плуг_ном_скл_ошибок += 1
        else:
            if conn.ЗначениеЗаполнено(r.Скл):
                скл += 1
            if conn.ЗначениеЗаполнено(r.Ном):
                ном += 1
            нм = conn.XMLСтрока(r.Ном) if conn.ЗначениеЗаполнено(r.Ном) else "∅"
            сл = conn.XMLСтрока(r.Скл) if conn.ЗначениеЗаполнено(r.Скл) else "∅"
            дет_ключи[(орг, подр, ст, нм, сл)] += 1
    дубл_дет = sum(1 for c in дет_ключи.values() if c > 1)
    return (свод, скл, ном, плугов, докзап, всего, плуг_кпс,
            дубл_дет, плуг_ном_скл_ошибок)


def получить_или_создать_док():
    """БЕЗ удаления документов: берём существующий А_ФинРез_Баланс за
    январь/ТОВ (или создаём ОДИН, если нет) и перепроводим. Перепроведение
    штатно замещает движения регистратора — сироты НЕ плодятся."""
    qf = conn.NewObject("Запрос")
    qf.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.А_ФинРез_Баланс
        ГДЕ НЕ ПометкаУдаления И Организация = &Орг
            И Месяц >= &НМ И Месяц <= &КД
            И ВключатьДочерние = ЛОЖЬ
        УПОРЯДОЧИТЬ ПО Дата"""
    qf.УстановитьПараметр("Орг", ORG)
    qf.УстановитьПараметр("НМ", НМ)
    qf.УстановитьПараметр("КД", КД)
    rf = qf.Выполнить().Выбрать()
    if rf.Следующий():
        об = rf.С.ПолучитьОбъект()
        об.Дата = DDATE
        return об
    об = conn.Документы.А_ФинРез_Баланс.СоздатьДокумент()
    об.Дата = DDATE; об.Организация = ORG
    об.Месяц = M; об.ВключатьДочерние = False
    return об


