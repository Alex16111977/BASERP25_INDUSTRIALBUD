# -*- coding: utf-8 -*-
"""
Тест документа Документ.А_ПереносДвиженийИзКазны:
1) Создаёт документ через COM
2) Вызывает ЗаполнитьИзКазны() (COM к BuhKazn → запрос к БДДС → маппинг → ТЧ СтрокиДвижений)
3) Проводит документ
4) Проверяет движения регистра РегистрНакопления.А_ДвиженияДенегИзКазны
"""

import sys
import io
import datetime
import win32com.client
import pythoncom

# Печать русских символов
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

CONN_ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

TEST_MONTH = datetime.datetime(2025, 12, 1)  # Декабрь 2025

print("=" * 70)
print("Тест: Документ.А_ПереносДвиженийИзКазны")
print(f"Период: {TEST_MONTH.strftime('%B %Y')}")
print("=" * 70)

pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")

try:
    erp = v8.Connect(CONN_ERP)
except Exception as e:
    print(f"[ERROR] Не удалось подключиться к BaseERP: {e}")
    sys.exit(1)

print("[OK] Подключение к BaseERP установлено")

# === 1. Поиск или создание документа на тестовый период ===
print("\n[1] Поиск/создание документа за период...")

query = erp.NewObject("Запрос")
query.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Док.Ссылка КАК Ссылка,
    Док.Проведен КАК Проведен
ИЗ
    Документ.А_ПереносДвиженийИзКазны КАК Док
ГДЕ
    Док.Месяц = &Месяц
    И НЕ Док.ПометкаУдаления
"""
query.УстановитьПараметр("Месяц", TEST_MONTH)
result = query.Выполнить()

if not result.Пустой():
    sel = result.Выбрать()
    sel.Следующий()
    print(f"  Найден документ: {sel.Ссылка}, Проведен={sel.Проведен}")
    doc_obj = sel.Ссылка.ПолучитьОбъект()
    print(f"  Текущее кол-во строк: {doc_obj.СтрокиДвижений.Количество()}")

    if sel.Проведен:
        print("  Отменяю проведение...")
        doc_obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
else:
    print("  Создаю новый документ...")
    doc_obj = erp.Документы.А_ПереносДвиженийИзКазны.СоздатьДокумент()
    doc_obj.Дата = datetime.datetime(TEST_MONTH.year, TEST_MONTH.month, 28, 23, 59, 59)
    doc_obj.Месяц = TEST_MONTH
    org = erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273")
    if not erp.ЗначениеЗаполнено(org):
        print("[ERROR] Не найдена организация ТОВ ІНДАСТРІАЛБУД")
        sys.exit(1)
    doc_obj.Организация = org
    doc_obj.Записать()
    print(f"  Создан документ: {doc_obj.Ссылка}")

# === 2. Заполнение через ЗаполнитьИзКазны ===
print("\n[2] Вызов ЗаполнитьИзКазны()...")
import time
t0 = time.time()
try:
    doc_obj.ЗаполнитьИзКазны()
    t_fill = time.time() - t0
    print(f"  [OK] Заполнено за {t_fill:.1f}с")
    print(f"  Строк в ТЧ СтрокиДвижений: {doc_obj.СтрокиДвижений.Количество()}")
except Exception as e:
    print(f"  [ERROR] Заполнение упало: {e}")
    sys.exit(1)

# === 3. Запись и проведение ===
print("\n[3] Запись и проведение документа...")
t0 = time.time()
try:
    doc_obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    t_post = time.time() - t0
    print(f"  [OK] Документ проведён за {t_post:.1f}с")
except Exception as e:
    print(f"  [ERROR] Проведение упало: {e}")
    sys.exit(1)

# === 4. Проверка движений регистра ===
print("\n[4] Проверка движений регистра А_ДвиженияДенегИзКазны...")

query = erp.NewObject("Запрос")
query.Текст = """
ВЫБРАТЬ
    КОЛИЧЕСТВО(*) КАК ВсегоЗаписей,
    СУММА(ВЫБОР КОГДА Сумма > 0 ТОГДА Сумма ИНАЧЕ 0 КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР КОГДА Сумма < 0 ТОГДА -Сумма ИНАЧЕ 0 КОНЕЦ) КАК Расход,
    МИНИМУМ(Период) КАК ДатаМин,
    МАКСИМУМ(Период) КАК ДатаМакс
ИЗ
    РегистрНакопления.А_ДвиженияДенегИзКазны
ГДЕ
    Регистратор = &Регистратор
"""
query.УстановитьПараметр("Регистратор", doc_obj.Ссылка)
result = query.Выполнить()
sel = result.Выбрать()
sel.Следующий()

print(f"  Записей в регистре: {sel.ВсегоЗаписей}")
print(f"  Сумма приход:       {sel.Приход:,.2f}")
print(f"  Сумма расход:       {sel.Расход:,.2f}")
print(f"  Период min/max:     {sel.ДатаМин} ... {sel.ДатаМакс}")

# === 5. Проверка пар ERP-документов ===
print("\n[5] Статистика по ДокументДвиженияКазны (парные ERP-документы)...")

query = erp.NewObject("Запрос")
query.Текст = """
ВЫБРАТЬ
    КОЛИЧЕСТВО(*) КАК Всего,
    СУММА(ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(ДокументДвиженияКазны) = ТИП(Документ.А_ПереносДвиженийИзКазны) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК БезПары,
    СУММА(ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(ДокументДвиженияКазны) = ТИП(Документ.ПриходныйКассовыйОрдер) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ПКО,
    СУММА(ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(ДокументДвиженияКазны) = ТИП(Документ.РасходныйКассовыйОрдер) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК РКО,
    СУММА(ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(ДокументДвиженияКазны) = ТИП(Документ.ПоступлениеБезналичныхДенежныхСредств) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ПостБезнал,
    СУММА(ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(ДокументДвиженияКазны) = ТИП(Документ.СписаниеБезналичныхДенежныхСредств) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК СписБезнал,
    СУММА(ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(ДокументДвиженияКазны) = ТИП(Документ.А_ПриходДенегОтФинАгента) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ОтФинАгента
ИЗ
    РегистрНакопления.А_ДвиженияДенегИзКазны
ГДЕ
    Регистратор = &Регистратор
"""
query.УстановитьПараметр("Регистратор", doc_obj.Ссылка)
sel = query.Выполнить().Выбрать()
sel.Следующий()
print(f"  Всего записей:                     {sel.Всего:>5d}")
print(f"  Без пары (fallback на регистратор): {sel.БезПары:>5d}")
print(f"  ПКО:                                {sel.ПКО:>5d}")
print(f"  РКО:                                {sel.РКО:>5d}")
print(f"  Поступление безнал:                 {sel.ПостБезнал:>5d}")
print(f"  Списание безнал:                    {sel.СписБезнал:>5d}")
print(f"  Приход от ФинАгента:                {sel.ОтФинАгента:>5d}")

# === 6. Сравнение с отчётом сверки (БДДС Казна обороты по статьям) ===
print("\n[6] Сравнение по статьям ДДС...")

query = erp.NewObject("Запрос")
query.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 10
    СтатьяДвиженияДенежныхСредств.Наименование КАК Статья,
    СУММА(ВЫБОР КОГДА Сумма > 0 ТОГДА Сумма ИНАЧЕ 0 КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР КОГДА Сумма < 0 ТОГДА -Сумма ИНАЧЕ 0 КОНЕЦ) КАК Расход
ИЗ
    РегистрНакопления.А_ДвиженияДенегИзКазны
ГДЕ
    Регистратор = &Регистратор
СГРУППИРОВАТЬ ПО
    СтатьяДвиженияДенежныхСредств.Наименование
УПОРЯДОЧИТЬ ПО
    СУММА(ВЫБОР КОГДА Сумма > 0 ТОГДА Сумма ИНАЧЕ -Сумма КОНЕЦ) УБЫВ
"""
query.УстановитьПараметр("Регистратор", doc_obj.Ссылка)
result = query.Выполнить()
sel = result.Выбрать()
print(f"  {'Статья ДДС':50s} {'Приход':>15s} {'Расход':>15s}")
print(f"  {'-' * 50} {'-' * 15} {'-' * 15}")
while sel.Следующий():
    statia = (sel.Статья or "<пустая>")[:48]
    print(f"  {statia:50s} {sel.Приход:>15,.2f} {sel.Расход:>15,.2f}")

print("\n" + "=" * 70)
print("[OK] Тест завершён успешно")
print(f"Документ: {doc_obj.Ссылка}")
print("=" * 70)
