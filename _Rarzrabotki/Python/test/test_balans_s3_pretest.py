"""Етап 3 пре-тест (Rule #-1): СебестоимостьТоваров → стаття «Товары на оптовых
складах», ключ Регистратор, субконто Номенклатура/Склад з
АналитикаУчетаНоменклатуры (Справочник.КлючиАналитикиУчетаНоменклатуры).
Період серверно січень. ТИПОВІ регістри лише читаються. Read-only."""
