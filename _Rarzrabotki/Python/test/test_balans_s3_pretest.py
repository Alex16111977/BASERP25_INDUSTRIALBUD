sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q0 = conn.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
s = q0.Выполнить().Выбрать(); s.Следующий(); org = s.С
qb = conn.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД"
qb.УстановитьПараметр("М", M); rb=qb.Выполнить().Выбрать(); rb.Следующий(); НМ=rb.НМ; КД=rb.КД
print(f"період: {НМ} .. {КД}")

# стаття «Товары на оптовых складах»
qa = conn.NewObject("Запрос")
qa.Текст = """ВЫБРАТЬ Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов
ГДЕ Наименование = "Товары на оптовых складах" """
ta = qa.Выполнить().Выгрузить()
assert ta.Количество() >= 1, "FAIL: стаття 'Товары на оптовых складах' не знайдена"
art = ta.Получить(0).С
arr = conn.NewObject("Массив"); arr.Добавить(art)

# 1) Покриття: ПАП-регістратори статті у СебестоимостьТоваров
q1 = conn.NewObject("Запрос")
q1.Текст = """
ВЫБРАТЬ
  КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Б.Регистратор) КАК РегПАП,
  КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВЫБОР КОГДА С.Регистратор ЕСТЬ NULL ТОГДА NULL ИНАЧЕ Б.Регистратор КОНЕЦ) КАК Матч
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.Обороты(&Д1,&Д2,Регистратор,
        Организация=&Орг И Статья В ИЕРАРХИИ(&Арт)) КАК Б
  ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ РАЗЛИЧНЫЕ Регистратор КАК Регистратор
                    ИЗ РегистрНакопления.СебестоимостьТоваров
                    ГДЕ Период МЕЖДУ &Д1 И &Д2) КАК С
  ПО Б.Регистратор = С.Регистратор
"""
q1.УстановитьПараметр("Д1",НМ); q1.УстановитьПараметр("Д2",КД)
q1.УстановитьПараметр("Орг",org); q1.УстановитьПараметр("Арт",arr)
r1 = q1.Выполнить().Выбрать(); r1.Следующий()
рег=int(r1.РегПАП or 0); матч=int(r1.Матч or 0)
покр = (матч/рег) if рег else 0
print(f"ПАП-регістраторів(Товары опт)={рег}, є в СебестоимостьТоваров={матч}, покриття={покр:.1%}")

# 2) Номенклатура/Склад з АналитикаУчетаНоменклатуры + унікальність на Регистратор
q2 = conn.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
  Т.Регистратор КАК Рег,
  КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.АналитикаУчетаНоменклатуры.Номенклатура) КАК КолНом,
  КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВЫРАЗИТЬ(Т.АналитикаУчетаНоменклатуры.МестоХранения КАК Справочник.Склады)) КАК КолСкл
ИЗ РегистрНакопления.СебестоимостьТоваров КАК Т
ГДЕ Т.Период МЕЖДУ &Д1 И &Д2
СГРУППИРОВАТЬ ПО Т.Регистратор
"""
q2.УстановитьПараметр("Д1",НМ); q2.УстановитьПараметр("Д2",КД)
t2 = q2.Выполнить().Выгрузить()
всего=t2.Количество()
многоНом=sum(1 for i in range(всего) if int(t2.Получить(i).КолНом)>1)
print(f"СебестоимостьТоваров регістраторів={всего}, з >1 Номенклатура={многоНом}, "
      f"унік Ном={(всего-многоНом)} ({((всего-многоНом)/всего if всего else 0):.1%})")

# 3) приклад: Номенклатура/Склад резолвляться
q3 = conn.NewObject("Запрос")
q3.Текст = """ВЫБРАТЬ ПЕРВЫЕ 3
  Т.АналитикаУчетаНоменклатуры.Номенклатура КАК Ном,
  ВЫРАЗИТЬ(Т.АналитикаУчетаНоменклатуры.МестоХранения КАК Справочник.Склады) КАК Скл
ИЗ РегистрНакопления.СебестоимостьТоваров КАК Т ГДЕ Т.Период МЕЖДУ &Д1 И &Д2
  И Т.АналитикаУчетаНоменклатуры.Номенклатура <> ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)"""
