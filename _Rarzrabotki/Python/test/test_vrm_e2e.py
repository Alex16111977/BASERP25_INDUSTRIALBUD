def норм(s):
    return re.sub(r"\s+", " ", str(s or "").strip().lower().replace("'", "").replace("’", ""))

def парс_проценты(текст):
    """'5 модулів --100%;1 модуль --50% 2 модулі --30%' -> [100]*5+[50]+[30]*2; '0%'->нули; мусор->None."""
    t = str(текст or "").strip()
    if not t:
        return None
    сегменты = re.findall(r"(\d+)\s*модул\w*\s*-*\s*(\d+(?:[.,]\d+)?)\s*%", t, re.I)
    if сегменты:
        из = []
        for кол, проц in сегменты:
            из += [float(проц.replace(",", "."))] * int(кол)
        из = (из + [0.0] * МОДУЛЕЙ)[:МОДУЛЕЙ]
        return из
    m = re.fullmatch(r"(\d+(?:[.,]\d+)?)\s*%", t)
    if m:
        return [float(m.group(1).replace(",", "."))] * МОДУЛЕЙ
    return None  # «в роботі», «не ставляться», комменты

