def get_or_create(дата, строки):
    qd = erp.NewObject("Запрос")
    qd.УстановитьПараметр("СС", сс.Ссылка); qd.УстановитьПараметр("Д", дата)
    qd.Текст = "ВЫБРАТЬ Д.Ссылка КАК С ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д ГДЕ Д.СтруктураСебестоимости = &СС И Д.Дата = &Д"
    вд = qd.Выполнить().Выбрать()
    if вд.Следующий():
        об = вд.С.ПолучитьОбъект()
    else:
        об = erp.Документы.А_ВыполнениеРаботМодулей.СоздатьДокумент()
        об.Дата = дата
    об.Организация = орг
    об.СтруктураСебестоимости = сс.Ссылка
    об.Подразделение = сс.Ссылка.Подразделение
    об.КоличествоМодулей = МОДУЛЕЙ
    об.Комментарий = "E2E из Excel ВООЗ"
    об.Работы.Очистить()
    ев = 0.0; сопост = 0
    for имя, (раб, этап, план) in работы_сс.items():
        проценты = строки.get(имя)
        if проценты is None:
            continue
        сопост += 1
        план_мод = план / МОДУЛЕЙ
        for н in range(1, МОДУЛЕЙ + 1):
            стр = об.Работы.Добавить()
            стр.Работа = раб; стр.Этап = этап
            стр.НомерМодуля = н
            стр.ПланЧасыМодуля = план_мод
            стр.Процент = проценты[н - 1]
            стр.ЧасыВыполнение = план_мод * проценты[н - 1] / 100
        ев += план / МОДУЛЕЙ * sum(проценты) / 100
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    return об.Ссылка, ев, сопост

