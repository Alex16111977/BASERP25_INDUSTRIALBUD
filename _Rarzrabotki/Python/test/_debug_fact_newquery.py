t = run_batch(FULL)
names = [t.Колонки.Получить(j).Имя for j in range(t.Колонки.Количество())]
idx = {names[j]: j for j in range(len(names))}
n = t.Количество()
sСС = sФакт = 0.0
обе = тплан = тфакт = 0
per_podr = {}
for i in range(n):
    r = t.Получить(i)
    ксс = float(r.Получить(idx["КоличествоСС"]) or 0); сс = float(r.Получить(idx["СуммаСС"]) or 0)
    кол = float(r.Получить(idx["Количество"]) or 0); сум = float(r.Получить(idx["Сумма"]) or 0)
    sСС += сс; sФакт += сум
    eп = (ксс != 0 or сс != 0); eф = (кол != 0 or сум != 0)
    if eп and eф: обе += 1
    elif eп: тплан += 1
    elif eф: тфакт += 1
    podr = str(r.Получить(idx["Подразделение"]))
    d = per_podr.setdefault(podr, [0.0, 0.0])
    d[0] += сс; d[1] += сум
print(f"строк={n}  Σ план={sСС:.2f}  Σ факт={sФакт:.2f}")
print(f"строки: и_план_и_факт={обе} | только_план={тплан} | только_факт={тфакт}")
print("по подразделениям (Σплан / Σфакт):")
for p, (pl, fa) in per_podr.items():
    print(f"  {p}: план={pl:.2f}  факт={fa:.2f}")
assert sФакт > 0, "ФАКТ ПУСТ!"
