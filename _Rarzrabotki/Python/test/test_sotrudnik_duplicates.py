# Пошук ФізОсіб у ТОВ "ІНДАСТРІАЛБУД" з декількома активними Сотрудниками.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Text = (
    'ВЫБРАТЬ '
    '    С.ФизическоеЛицо КАК ФизЛицо, '
    '    С.ФизическоеЛицо.Наименование КАК ФИО, '
    '    КОЛИЧЕСТВО(*) КАК КолСотр '
    'ИЗ Справочник.Сотрудники КАК С '
    'ГДЕ НЕ С.ПометкаУдаления '
    '    И С.ГоловнаяОрганизация.Наименование ПОДОБНО "%ІНДАСТРІАЛБУД%" '
    'СГРУППИРОВАТЬ ПО С.ФизическоеЛицо, С.ФизическоеЛицо.Наименование '
    'ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1 '
    'УПОРЯДОЧИТЬ ПО КолСотр УБЫВ'
)
r = q.Execute().Выгрузить()
print(f"ФізОсіб з >1 Сотрудник в ТОВ ІНДАСТРІАЛБУД: {r.Количество()}")
for i in range(min(30, r.Количество())):
    row = r.Получить(i)
    print(f"  {S(row.ФИО)[:40]:40s}  Сотрудників: {S(row.КолСотр)}")

# Перевірити конкретно Дубінько
