    '    С.Ссылка КАК Сотрудник, '
    '    С.ФизическоеЛицо.Наименование КАК ФИО, '
    '    С.ГоловнаяОрганизация.Наименование КАК Орг, '
    '    С.ПометкаУдаления КАК Удален '
    'ИЗ Справочник.Сотрудники КАК С '
    'ГДЕ С.ФизическоеЛицо.Наименование ПОДОБНО "Дубінько Сергій%"'
