print("\n=== 6. E2E: СформироватьОтчет — тело ПриКомпоновкеРезультата (путь пользователя) ===")


def прогон_как_в_форме(нач, кон, вкл_гп=False):
    отч = buh.ВнешниеОтчеты.Создать(ERF)
    схема = отч.СхемаКомпоновкиДанных
    отч.КомпоновщикНастроек.Инициализировать(
        buh.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    отч.КомпоновщикНастроек.ЗагрузитьНастройки(схема.НастройкиПоУмолчанию)

    п = buh.NewObject("СтандартныйПериод")
    п.ДатаНачала = нач
    п.ДатаОкончания = кон
    отч.КомпоновщикНастроек.Настройки.ПараметрыДанных.УстановитьЗначениеПараметра("Период", п)
    отч.КомпоновщикНастроек.Настройки.ПараметрыДанных.УстановитьЗначениеПараметра(
        "ВключатьГотовуюПродукцию", вкл_гп)

    док = buh.NewObject("ТабличныйДокумент")
    расшифровка = buh.NewObject("ДанныеРасшифровкиКомпоновкиДанных")
    отч.СформироватьОтчет(док, расшифровка)
    return док


