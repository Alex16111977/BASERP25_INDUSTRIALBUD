    for _ in range(5):
        q = buh.NewObject("Запрос")
        q.Text = ("ВЫБРАТЬ ГОД(&Д) КАК Г, МЕСЯЦ(&Д) КАК М, ДЕНЬ(&Д) КАК Д,"
                  " ЧАС(&Д) КАК Ч, МИНУТА(&Д) КАК Мин, СЕКУНДА(&Д) КАК С")
        q.SetParameter("Д", кандидат)
        r = q.Execute().Выгрузить().Получить(0)
        видит = datetime.datetime(int(r.Г), int(r.М), int(r.Д), int(r.Ч), int(r.Мин), int(r.С))
        if видит == цель:
            return кандидат
        кандидат = кандидат + (цель - видит)
    raise RuntimeError(f"не удалось подобрать дату под {цель}")


