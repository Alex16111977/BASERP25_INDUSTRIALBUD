# -*- coding: utf-8 -*-
"""Приёмка внешнего отчёта А_ОтчетПоСписаниюНаПроизводствоБухгалтерский на живой bas_industrialbud.

Сверяет результат ПолучитьДанные() с НЕЗАВИСИМЫМИ запросами в тот же момент времени.

Запуск:  python _Rarzrabotki/Python/test/smoke_spisanie_na_proizvodstvo_buh.py
"""
import win32com.client, pythoncom, sys, datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетПоСписаниюНаПроизводствоБухгалтерский.erf"
CONN = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
ДАТА_НАЧАЛА = datetime.datetime(2026, 1, 1, 0, 0, 0)
ДАТА_ОКОНЧАНИЯ = datetime.datetime(2026, 8, 31, 0, 0, 0)
ЭПС = 0.05

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect(CONN)
S = buh.String

провалов = 0
проверок = 0


def проверка(имя, условие, деталь=""):
    global провалов, проверок
    проверок += 1
    if not условие:
        провалов += 1
    print(f"  [{'OK  ' if условие else 'FAIL'}] {имя}" + (f" — {деталь}" if деталь else ""))


def дата_для_1с(цель):
    """COM сдвигает datetime на смещение TZ, величина сдвига зависит от даты. Подбираем итерацией."""
    кандидат = цель
    for _ in range(5):
        q = buh.NewObject("Запрос")
        q.Text = ("ВЫБРАТЬ ГОД(&Д) КАК Г, МЕСЯЦ(&Д) КАК М, ДЕНЬ(&Д) КАК Д,"
                  " ЧАС(&Д) КАК Ч, МИНУТА(&Д) КАК Мин, СЕКУНДА(&Д) КАК С")
        q.SetParameter("Д", кандидат)
        r = q.Execute().Выгрузить().Получить(0)
        видит = datetime.datetime(int(r.Г), int(r.М), int(r.Д), int(r.Ч), int(r.Мин), int(r.С))
        if видит == цель:
            return кандидат
        кандидат = кандидат + (цель - видит)
    raise RuntimeError(f"не удалось подобрать дату под {цель}")


# ---------------------------------------------------------------- 0. защита от коллизии драйверов
print("=== 0. Драйверы: коллизия = двойной счёт факта ===")
q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	СС.Наименование КАК ИмяСС,
	ЕСТЬNULL(Дочь.Ссылка, СС.Подразделение) КАК Драйвер
ИЗ Справочник.СтруктураСебестоимости КАК СС
	ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Подразделения КАК Дочь
	ПО Дочь.Родитель = СС.Подразделение И Дочь.Наименование = СС.Наименование
ГДЕ НЕ СС.ЭтоГруппа И СС.Активная И НЕ СС.ПометкаУдаления
УПОРЯДОЧИТЬ ПО ИмяСС
"""
r = q.Execute().Выгрузить()
пары = [(S(r.Получить(i).ИмяСС), S(r.Получить(i).Драйвер), r.Получить(i).Драйвер)
        for i in range(r.Количество())]
for имя, драйвер, _ in пары:
    print(f"    СС «{имя[:42]:44}» -> {драйвер}")
драйверы_список = [d for _, d, _ in пары]
дубли = {d for d in драйверы_список if драйверы_список.count(d) > 1}
проверка("жодна пара активних СС не ділить один драйвер (інакше факт задвоїться)",
         not дубли, f"колізії: {', '.join(дубли) if дубли else '—'}")
проверка("у кожної активної СС драйвер заповнений", all(d for _, d, _ in пары))

# ---------------------------------------------------------------- 1. открыть отчёт
print("\n=== 1. Открытие внешнего отчёта ===")
отчет = buh.ВнешниеОтчеты.Создать(ERF)
проверка("ВнешниеОтчеты.Создать отработал", отчет is not None)

НАЧ = дата_для_1с(ДАТА_НАЧАЛА)
КОН = дата_для_1с(ДАТА_ОКОНЧАНИЯ)
период = buh.NewObject("СтандартныйПериод")
период.ДатаНачала = НАЧ
период.ДатаОкончания = КОН

qd = buh.NewObject("Запрос")
qd.Text = ("ВЫБРАТЬ ГОД(&Д1) КАК Г1, МЕСЯЦ(&Д1) КАК М1, ДЕНЬ(&Д1) КАК Д1, ЧАС(&Д1) КАК Ч1,"
           " ДЕНЬ(&Д2) КАК Д2, МЕСЯЦ(&Д2) КАК М2")
qd.SetParameter("Д1", НАЧ)
qd.SetParameter("Д2", КОН)
д = qd.Execute().Выгрузить().Получить(0)
проверка("границы периода скомпенсированы под сдвиг COM",
         д.Г1 == 2026 and д.М1 == 1 and д.Д1 == 1 and д.Ч1 == 0 and д.Д2 == 31 and д.М2 == 8,
         f"1С видит {д.Д1:.0f}.{д.М1:.0f}.{д.Г1:.0f} {д.Ч1:.0f}ч — {д.Д2:.0f}.{д.М2:.0f}")

ТЗ = отчет.ПолучитьДанные(период, False)
проверка("ПолучитьДанные вернул строки", ТЗ.Количество() > 0, f"строк={ТЗ.Количество()}")

# ---------------------------------------------------------------- 2. свод
кол = ТЗ.Количество()
СВОД = {}
итог = dict(ПланКол=0.0, ПланГрн=0.0, ФактКол=0.0, ФактГрнБух=0.0, ФактГрнПлан=0.0)
по_статусу = {}
факт_без_этапа = факт_всего = 0
статус_нарушений = 0

for i in range(кол):
    с = ТЗ.Получить(i)
    др = S(с.Подразделение)
    г = СВОД.setdefault(др, dict(ПланКол=0.0, ПланГрн=0.0, ФактКол=0.0, ФактГрнБух=0.0,
                                 ФактГрнПлан=0.0, викон_план=set(), викон_факт=set()))
    for k in итог:
        v = float(getattr(с, k))
        г[k] += v
        итог[k] += v
    if с.ВидДокумента == "0. План":
        г["викон_план"].add(S(с.ПодразделениеИсполнитель))
    else:
        факт_всего += 1
        г["викон_факт"].add(S(с.ПодразделениеИсполнитель))
        if not S(с.Этап):
            факт_без_этапа += 1
        ст = S(с.СтатусПлана)
        а = по_статусу.setdefault(ст, dict(строк=0, бух=0.0, план=0.0))
        а["строк"] += 1
        а["бух"] += float(с.ФактГрнБух)
        а["план"] += float(с.ФактГрнПлан)
        if ст != "1. В плані" and float(с.ФактГрнПлан) != 0:
            статус_нарушений += 1

print(f"\n=== 2. Свод отчёта (драйверов={len(СВОД)}) ===")
for др, г in sorted(СВОД.items()):
    print(f"  {др[:44]:46} план {г['ПланКол']:>12,.3f} / {г['ПланГрн']:>14,.2f}"
          f" | факт {г['ФактКол']:>12,.3f} / {г['ФактГрнБух']:>14,.2f}"
          f" | вик.план={len(г['викон_план'])} вик.факт={len(г['викон_факт'])}")
print(f"  {'ИТОГО':46} план {итог['ПланКол']:>12,.3f} / {итог['ПланГрн']:>14,.2f}"
      f" | факт {итог['ФактКол']:>12,.3f} / {итог['ФактГрнБух']:>14,.2f}")

# ---------------------------------------------------------------- 3. эталон плана
print("\n=== 3. План: норма ТЧ × число исполнителей (независимый расчёт) ===")
ok_план = True
for имя, имя_др, ссылка in пары:
    qv = buh.NewObject("Запрос")
    qv.Text = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ Справочник.Подразделения КАК П "
               "ГДЕ П.Родитель = &Драйвер И НЕ П.ПометкаУдаления")
    qv.SetParameter("Драйвер", ссылка)
    n = int(qv.Execute().Выгрузить().Получить(0).Кол) or 1

    qp = buh.NewObject("Запрос")
    qp.Text = """
    ВЫБРАТЬ СУММА(К.Количество) КАК Кол, СУММА(К.Сумма) КАК Грн
    ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.СтруктураСебестоимости КАК СС ПО К.Ссылка = СС.Ссылка
            ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Подразделения КАК Дочь
            ПО Дочь.Родитель = СС.Подразделение И Дочь.Наименование = СС.Наименование
    ГДЕ НЕ СС.ЭтоГруппа И СС.Активная И НЕ СС.ПометкаУдаления
        И ЕСТЬNULL(Дочь.Ссылка, СС.Подразделение) = &Драйвер
    """
    qp.SetParameter("Драйвер", ссылка)
    э = qp.Execute().Выгрузить().Получить(0)
    ожид_кол = float(э.Кол or 0) * n
    ожид_грн = float(э.Грн or 0) * n
    г = СВОД.get(имя_др)
    if г is None:
        ok_план = False
        print(f"     нет в отчёте: {имя_др}")
        continue
    if abs(г["ПланКол"] - ожид_кол) > ЭПС or abs(г["ПланГрн"] - ожид_грн) > ЭПС:
        ok_план = False
        print(f"     {имя_др[:42]:44} отчёт {г['ПланКол']:.3f}/{г['ПланГрн']:.2f}"
              f" ожид {ожид_кол:.3f}/{ожид_грн:.2f} (виконавців={n})")
проверка("Σ план по исполнителям == норма × число исполнителей", ok_план)

# ---------------------------------------------------------------- 4. эталон факта
print("\n=== 4. Факт: независимый запрос по Хозрасчетному (Кт 20/22/28) ===")
ПОДР = """ВЫБОР
		КОГДА ТИПЗНАЧЕНИЯ(О.Регистратор) = ТИП(Документ.ТребованиеНакладная)
			ТОГДА ВЫРАЗИТЬ(О.Регистратор КАК Документ.ТребованиеНакладная).Подразделение
		КОГДА ТИПЗНАЧЕНИЯ(О.Регистратор) = ТИП(Документ.СписаниеТоваров)
			ТОГДА ВЫРАЗИТЬ(О.Регистратор КАК Документ.СписаниеТоваров).Подразделение
		КОГДА ТИПЗНАЧЕНИЯ(О.Регистратор) = ТИП(Документ.КомплектацияНоменклатуры)
			ТОГДА ВЫРАЗИТЬ(О.Регистратор КАК Документ.КомплектацияНоменклатуры).Подразделение
		КОГДА ТИПЗНАЧЕНИЯ(О.Регистратор) = ТИП(Документ.ПередачаМалоценныхАктивовВЭксплуатацию)
			ТОГДА ВЫРАЗИТЬ(О.Регистратор КАК Документ.ПередачаМалоценныхАктивовВЭксплуатацию).Подразделение
	КОНЕЦ"""
ЭТ_ФАКТ = """
ВЫБРАТЬ РАЗЛИЧНЫЕ Счет.Ссылка КАК Счет ПОМЕСТИТЬ ВТСч ИЗ ПланСчетов.Хозрасчетный КАК Счет
ГДЕ Счет.Ссылка В ИЕРАРХИИ (ВЫБРАТЬ Г.Ссылка ИЗ ПланСчетов.Хозрасчетный КАК Г ГДЕ Г.Код В ("20","22","28"))
;
ВЫБРАТЬ СУММА(О.КоличествоОборотКт) КАК Кол, СУММА(О.СуммаОборотКт) КАК Грн
ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(&НачП, &КонП, Регистратор,
		Счет В (ВЫБРАТЬ ВТСч.Счет ИЗ ВТСч), , , , ) КАК О
ГДЕ О.СуммаОборотКт <> 0
	И ТИПЗНАЧЕНИЯ(О.Регистратор) В (ТИП(Документ.ТребованиеНакладная), ТИП(Документ.СписаниеТоваров),
		ТИП(Документ.КомплектацияНоменклатуры), ТИП(Документ.ПередачаМалоценныхАктивовВЭксплуатацию))
	И """ + ПОДР + " В ИЕРАРХИИ (&Драйвер)"

qd2 = buh.NewObject("Запрос")
qd2.Text = "ВЫБРАТЬ КОНЕЦПЕРИОДА(&Д, ДЕНЬ) КАК КД"
qd2.SetParameter("Д", КОН)
конец_дня = qd2.Execute().Выгрузить().Получить(0).КД

ok_факт = True
for имя, имя_др, ссылка in пары:
    qq = buh.NewObject("Запрос")
    qq.Text = ЭТ_ФАКТ
    qq.SetParameter("Драйвер", ссылка)
    qq.SetParameter("НачП", НАЧ)
    qq.SetParameter("КонП", конец_дня)
    э = qq.Execute().Выгрузить().Получить(0)
    эк, эг = float(э.Кол or 0), float(э.Грн or 0)
    г = СВОД.get(имя_др, dict(ФактКол=0.0, ФактГрнБух=0.0))
    if abs(г["ФактКол"] - эк) > ЭПС or abs(г["ФактГрнБух"] - эг) > ЭПС:
        ok_факт = False
        print(f"     {имя_др[:42]:44} отчёт {г['ФактКол']:.3f}/{г['ФактГрнБух']:.2f}"
              f" эталон {эк:.3f}/{эг:.2f}")
проверка("Σ факт == Хозрасчетный Кт 20/22/28 по 4 документам списания", ok_факт)

# ---------------------------------------------------------------- 5. смысловые инварианты
print("\n=== 5. Смысловые инварианты ===")
IRS15 = [d for d in СВОД if "15 м" in d]
if IRS15:
    проверка("IRS 15 м: план роздано на 6 виконавців", len(СВОД[IRS15[0]]["викон_план"]) == 6,
             f"виконавців плану={len(СВОД[IRS15[0]]['викон_план'])}")
проверка("жодного драйвера без плану", all(г["ПланГрн"] > 0 for г in СВОД.values()))
проверка("ФактГрнПлан заповнена (гібрид працює)", итог["ФактГрнПлан"] > 0,
         f"{итог['ФактГрнПлан']:,.2f} грн")
доля = 100.0 * (факт_всего - факт_без_этапа) / факт_всего if факт_всего else 0
проверка("факт розкладено по Етапах > 40% рядків", доля > 40,
         f"{доля:.1f}% ({факт_всего - факт_без_этапа}/{факт_всего})")

print("  --- розподіл факту за статусом плану ---")
бух_всего = sum(а["бух"] for а in по_статусу.values())
for ст in sorted(по_статусу):
    а = по_статусу[ст]
    д = 100.0 * а["бух"] / бух_всего if бух_всего else 0
    print(f"      {ст:22} {а['строк']:5} рядків | бухоблік {а['бух']:>14,.2f} ({д:5.1f}%)"
          f" | у пл.цінах {а['план']:>14,.2f}")
проверка("ФактГрнПлан = 0 у всіх рядків поза статусом «1. В плані»", статус_нарушений == 0,
         f"порушень={статус_нарушений}")
проверка("статус проставлено всім фактовим рядкам", "" not in по_статусу)
покрытие = 100.0 * по_статусу.get("1. В плані", {}).get("бух", 0) / бух_всего if бух_всего else 0
проверка("планова ціна покриває > 60% фактичної суми", покрытие > 60, f"{покрытие:.1f}%")
отн = итог["ФактГрнПлан"] / итог["ФактГрнБух"] if итог["ФактГрнБух"] else 0
проверка("ФактГрнПлан / ФактГрнБух у розумних межах (0,5…2,5)", 0.5 < отн < 2.5,
         f"відношення={отн:.2f}")

# ---------------------------------------------------------------- 6. компоновка
print("\n=== 6. Полный прогон компоновки в табличный документ ===")
try:
    настройки = отчет.КомпоновщикНастроек.ПолучитьНастройки()
    компоновщик = buh.NewObject("КомпоновщикМакетаКомпоновкиДанных")
    макет = компоновщик.Выполнить(отчет.СхемаКомпоновкиДанных, настройки, pythoncom.Empty)
    процессор = buh.NewObject("ПроцессорКомпоновкиДанных")
    внешние = buh.NewObject("Структура", "Детали", ТЗ)
    процессор.Инициализировать(макет, внешние, pythoncom.Empty)
    вывод = buh.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    док = buh.NewObject("ТабличныйДокумент")
    вывод.УстановитьДокумент(док)
    вывод.Вывести(процессор)
    проверка("компоновка отработала, документ непустой", док.ВысотаТаблицы > 0,
             f"строк={док.ВысотаТаблицы}, колонок={док.ШиринаТаблицы}")
except Exception as e:
    проверка("компоновка отработала", False,
             e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e))

print(f"\n{'=' * 60}")
print(f"ПРОВЕРОК: {проверок}   ПРОВАЛОВ: {провалов}")
print("=" * 60)
sys.exit(1 if провалов else 0)
