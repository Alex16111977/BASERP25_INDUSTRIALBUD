ЭТ_ФАКТ = ЭТ_ФАКТ_БАЗА + "\n\tИ " + ПОДР + " В ИЕРАРХИИ (&Драйвер)"

qd2 = buh.NewObject("Запрос")
qd2.Text = "ВЫБРАТЬ КОНЕЦПЕРИОДА(&Д, ДЕНЬ) КАК КД"
