# -*- coding: utf-8 -*-
"""Smoke 3: РасчетКомплектаций — 6 печатных форм COM-инспекцией
(плоский Друк, 4 СКД-макета документа, новый Акт понаднормового списання)."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

MARKER = "SMOKE_DOC_KOMPL_v1"

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

q = buh.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Документ.РасчетКомплектаций КАК Д "
          "ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК Строка(200)) = &М И НЕ Д.ПометкаУдаления")
q.SetParameter("М", MARKER)
r = q.Execute().Выгрузить()
assert r.Количество() == 1, "сначала smoke_doc_kompl_analiz.py"
doc = r.Получить(0).Ссылка.ПолучитьОбъект()
assert doc.ТабличнаяЧастьОстатков.Количество() > 0

# 1. Плоский «Друк» (принимает строки анализа — объектная ТЧ итерируема движком)
td = doc.СформироватьПечать(doc.ТабличнаяЧастьОстатков)
h = td.ВысотаТаблицы
assert h > 5, f"Друк: высота {h}"
print(f"Друк: высота {h}")

# 2-5. СКД-макеты (проверка и того, что ПолучитьМакет находит макеты ДОКУМЕНТА — §39)
for fn, name in (("СформироватьПечатьПланФакт", "План-факт"),
                 ("СформироватьПечатьПланФактЕтапи", "За етапами"),
                 ("СформироватьПечатьАнализСС", "Аналіз СС"),
                 ("СформироватьПечатьАнализССОдна", "Аналіз СС (1 од.)")):
    td = getattr(doc, fn)(doc.ТабличнаяЧастьОстатков)
    h, w = td.ВысотаТаблицы, td.ШиринаТаблицы
    assert h > 5 and w > 5, f"{name}: {h}x{w}"
    print(f"{name}: {h}x{w}")

# 6. Акт-план понаднормового списання (причина и КоличествоКСписанию ставятся в памяти —
# тест самодостаточен; акт-план печатает ТОЛЬКО строки с КоличествоКСписанию > 0,
# заголовок с 2026-08 — «АКТ ... (план)», подпись — «Відповідальний»)
assert doc.СписаниеСверхНормы.Количество() > 0
стр0 = doc.СписаниеСверхНормы.Получить(0)
стр0.Причина = "Тест: ручний рядок"
if стр0.КоличествоКСписанию <= 0:
    стр0.КоличествоКСписанию = min(1, стр0.Количество) or стр0.Количество
td = doc.СформироватьПечатьАкт()
h = td.ВысотаТаблицы
assert h > 8, f"Акт: высота {h}"
# шапка «АКТ...» ровно один раз (объединение, §9) + причина ручной строки присутствует
akt_count = 0
prichina_found = False
for row in range(1, h + 1):
    for col in range(1, 10):
        t = td.Область(row, col, row, col).Текст or ""
        if t.startswith("АКТ на списання понаднормових матеріалів"):
            akt_count += 1
        if t == "Тест: ручний рядок":
            prichina_found = True
assert akt_count == 1, f"заголовок АКТ встречается {akt_count} раз"
assert prichina_found, "причина ручной строки не найдена в Акте"
# подпись ответственного
texts = []
for row in range(h - 6, h + 1):
    t = td.Область(row, 1, row, 1).Текст
    if t:
        texts.append(t)
assert any("Відповідальний" in t for t in texts), texts
print(f"Акт: высота {h}, заголовок 1 раз, причина и подпись на месте")
print("PECHAT PASS")
