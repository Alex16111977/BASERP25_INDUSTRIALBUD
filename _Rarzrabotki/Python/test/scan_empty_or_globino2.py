def скан_рег(имя_регистра, поле_суммы, период_д1, период_д2, метка):
    """Универсальный скан движений с ОР=ПустаяСсылка."""
    print(f"\n[{метка}] {имя_регистра}")
    print("-" * 110)
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Контр", контр)
    qq.УстановитьПараметр("Д1", период_д1)
    qq.УстановитьПараметр("Д2", период_д2)
    qq.Текст = f"""
ВЫБРАТЬ
    Р.Регистратор КАК Рег,
    ПРЕДСТАВЛЕНИЕ(Р.Регистратор) КАК РегИмя,
    Р.Регистратор.Дата КАК ДатаДок,
    Р.Период КАК Период,
    Р.ВидДвижения КАК ВидДв,
    Р.{поле_суммы} КАК Сумма,
    ПРЕДСТАВЛЕНИЕ(Р.ХозяйственнаяОперация) КАК Хозоп
ИЗ РегистрНакопления.{имя_регистра} КАК Р
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Контрагент = &Контр
    И Р.Период МЕЖДУ &Д1 И &Д2
    И Р.ОбъектРасчетов = ЗНАЧЕНИЕ(Справочник.ОбъектыРасчетов.ПустаяСсылка)
    И Р.{поле_суммы} <> 0
УПОРЯДОЧИТЬ ПО Р.Период
"""
    try:
        r = qq.Выполнить().Выгрузить()
    except Exception as e:
        # Возможно поле _Сумма_ не существует или другое имя
        емсг = e.excepinfo[2] if (hasattr(e,'excepinfo') and e.excepinfo) else str(e)
        print(f"   FAIL запрос: {емсг[:80]}")
        return 0, 0
    print(f"   Найдено строк: {r.Количество()}")
    if r.Количество() == 0:
        return 0, 0
    print(f"   {'ДатаДок':<19} | {'Регистратор':<55} | {'ВидДв':<8} | {'Хозоп':<22} | {'Сумма':>15}")
    print("   " + "-" * 130)
    σ = 0.0
    for i in range(r.Количество()):
        rec = r.Получить(i)
        вд = str(S(rec.ВидДв)) or "?"
        ε = float(rec.Сумма) * (1 if "Приход" in вд else -1)
        σ += ε
        print(f"   {rec.ДатаДок.strftime('%d.%m.%Y %H:%M:%S'):<19} | {str(rec.РегИмя)[:55]:<55} | {вд[:8]:<8} | {str(rec.Хозоп)[:22]:<22} | {float(rec.Сумма):>15,.2f}")
    print("   " + "-" * 130)
    print(f"   Σ signed (Приход − Расход): {σ:>15,.2f}")
    return r.Количество(), σ


