# -*- coding: utf-8 -*-
"""Все проводки Хозрасчетного, которые формирует возврат СТ00-000070 (не только Кт 0221).
Показать: Кт 0221 = себест. партий, и Разница цена-себест = доход. Rule #-1."""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
def S(x):
    try: return buh.String(x)
    except Exception: return str(x)
видНом = buh.ПланыВидовХарактеристик.ВидыСубконтоХозрасчетные.Номенклатура
def суб(колл):
    try:
        v = колл.Получить(видНом); return S(v) if v else ""
    except Exception: return ""

док = buh.Документы.ВозвратТоваровПоставщику.НайтиПоНомеру("СТ00-000070", datetime.datetime(2026,6,30,23,59,59))
об = док.ПолучитьОбъект()
дв = об.Движения.Хозрасчетный; дв.Прочитать()
print(f"Возврат СТ00-000070 ({S(док.Дата)}) — все проводки Хозрасчетного:\n")
print(f"{'#':<3} {'СчетДт':<10} {'СчетКт':<10} {'Сумма':>10} {'КолДт':>6} {'КолКт':>6}  {'Ном(Дт/Кт)':<20} {'Содержание'}")
print("-"*110)
for i in range(дв.Количество()):
    з = дв.Получить(i)
    счД = S(з.СчетДт) if з.СчетДт else "—"
    счК = S(з.СчетКт) if з.СчетКт else "—"
    ном = суб(з.СубконтоДт) or суб(з.СубконтоКт)
    сод = S(з.Содержание)
    print(f"{i+1:<3} {счД:<10} {счК:<10} {float(з.Сумма or 0):>10.2f} {float(з.КоличествоДт or 0):>6.1f} {float(з.КоличествоКт or 0):>6.1f}  {ном[:20]:<20} {сод[:40]}")
