def в_модуль(s):
    строки = s.split("\n")
    return "\n".join(("\t|" + l) if i < len(строки) - 1 else l for i, l in enumerate(строки))


def применить(текст, замены, форма):
    for старое, новое, n in замены:
        assert старое, "пустой шаблон замены"
        if форма == "bsl":
            старое, новое = в_модуль(старое), в_модуль(новое)
        k = текст.count(старое)
        assert k == n, "ожидалось %d вхождений, найдено %d: %r" % (n, k, старое[:70])
        текст = текст.replace(старое, новое)
    return текст


def удалить_ветку_документов_в_накопительные(текст):
    якорь = "ПО КЛ.КолонкаСорт = 900000\n"
    assert текст.count(якорь) == 1, текст.count(якорь)
    p = текст.index(якорь)
    start = текст.rfind("ОБЪЕДИНИТЬ ВСЕ", 0, p)
    end = текст.find("ОБЪЕДИНИТЬ ВСЕ", p)
    assert 0 < start < p < end
    кусок = текст[start:end]
    assert "&МесяцОстатков" in кусок and "Документ.А_ОтчетPL.ДанныеОтчета" in кусок, "не та ветка"
    assert 1200 < len(кусок) < 3500, len(кусок)
    return текст[:start] + текст[end:]


def патч_запроса(текст, форма):
    текст = применить(текст, ЗАМЕНЫ, форма)
    текст = удалить_ветку_документов_в_накопительные(текст)
    текст = применить(текст, ЗАМЕНЫ_ПОСЛЕ, форма)
    return текст


def читать(p):
    b = io.open(p, "rb").read()
    bom = b.startswith(b"\xef\xbb\xbf")
    t = b.decode("utf-8-sig")
    crlf = "\r\n" in t
    return t.replace("\r\n", "\n"), bom, crlf


def писать(p, t, bom, crlf):
    if crlf:
        t = t.replace("\n", "\r\n")
    io.open(p, "wb").write((b"\xef\xbb\xbf" if bom else b"") + t.encode("utf-8"))


НАЧАЛО_ЛИТЕРАЛА = '\tЗапрос.Текст =\n\t"ВЫБРАТЬ РАЗЛИЧНЫЕ\n'


def литерал_модуля(t):
    s = t.index(НАЧАЛО_ЛИТЕРАЛА) + len('\tЗапрос.Текст =\n\t"')
    e = t.index('";\n', s)
    строки = t[s:e].split("\n")
    out = [строки[0]] + [(l[2:] if l.startswith("\t|") else l) for l in строки[1:]]
    return ("\n".join(out) + "\n").replace('""', '"')


def проверить(sql_path):
    модуль, _, _ = читать(МОДУЛЬ)
    sql, _, _ = читать(sql_path)
    a, b = литерал_модуля(модуль), sql
    if a.rstrip("\n") == b.rstrip("\n"):
        print("OK: литерал модуля == %s (%d символов)" % (os.path.basename(sql_path), len(a)))
        return 0
    for i, (x, y) in enumerate(zip(a.split("\n"), b.split("\n"))):
        if x != y:
            print("РАСХОЖДЕНИЕ строка %d:\n  модуль: %r\n  sql:    %r" % (i + 1, x, y))
            break
    print("FAIL: длины %d / %d" % (len(a), len(b)))
    return 1


