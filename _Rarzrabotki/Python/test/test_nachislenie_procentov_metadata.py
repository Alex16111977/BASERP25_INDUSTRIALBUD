# -*- coding: utf-8 -*-
"""Нарахування відсотків за кредитами: метадані (план 2026-10-16, Task 1).

Перевіряє перелік способів, регістр ставок, документ з ТЧ, реквізит зв'язку в ПТУ, підсистему «Казначейство»
і константи загального модуля. Код виходу 0 = OK.
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
Мд = erp.Метаданные
ok = True


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


def типы(реквизит):
    return sorted(S(Мд.НайтиПоТипу(т).ПолноеИмя()) if Мд.НайтиПоТипу(т) is not None else S(т)
                  for т in [реквизит.Тип.Типы().Получить(i) for i in range(реквизит.Тип.Типы().Количество())])


def реквизиты(коллекция):
    return {S(коллекция.Получить(i).Имя): коллекция.Получить(i) for i in range(коллекция.Количество())}


# --- перелік
пер = Мд.Перечисления.Найти("А_СпособыРасчетаПроцентов")
check(пер is not None, "перелік А_СпособыРасчетаПроцентов")
if пер is not None:
    check([S(пер.ЗначенияПеречисления.Получить(i).Имя) for i in range(пер.ЗначенияПеречисления.Количество())]
          == ["ПоВыплате", "ПоФормуле", "Вручную"], "значення ПоВыплате, ПоФормуле, Вручную")

# --- регістр ставок
рег = Мд.РегистрыСведений.Найти("А_ПроцентныеСтавкиКредитов")
check(рег is not None, "регістр А_ПроцентныеСтавкиКредитов")
if рег is not None:
    check(S(рег.ПериодичностьРегистраСведений) == S(erp.Метаданные.СвойстваОбъектов.ПериодичностьРегистраСведений.День),
          "періодичність День")
    изм = реквизиты(рег.Измерения)
    check(list(изм) == ["Договор"] and типы(изм["Договор"]) == ["Справочник.ДоговорыКонтрагентов"],
          "вимір Договор: ДоговорыКонтрагентов")
    check("Ставка" in реквизиты(рег.Ресурсы), "ресурс Ставка")

# --- документ
док = Мд.Документы.Найти("А_НачислениеПроцентовПоКредитам")
check(док is not None, "документ А_НачислениеПроцентовПоКредитам")
if док is not None:
    check(S(док.Синоним) == "Нарахування відсотків за кредитами", f"синонім: {S(док.Синоним)}")
    шапка = реквизиты(док.Реквизиты)
    for имя, тип in [("Организация", ["Справочник.Организации"]), ("МесяцНачисления", None),
                     ("СпособЗаполнения", ["Перечисление.А_СпособыРасчетаПроцентов"]),
                     ("Ответственный", ["Справочник.Пользователи"]), ("Комментарий", None)]:
        check(имя in шапка and (тип is None or типы(шапка[имя]) == тип), f"шапка: {имя}")
    тч = реквизиты(док.ТабличныеЧасти)
    check("Начисления" in тч and "Расшифровка" in тч, "ТЧ Начисления і Расшифровка")
    if "Начисления" in тч:
        н = реквизиты(тч["Начисления"].Реквизиты)
        for имя in ["КодСтроки", "Договор", "Контрагент", "Подразделение", "Ставка", "ОстатокТела", "СуммаПоФормуле",
                    "СуммаВыплат", "СпособРасчета", "СуммаКНачислению", "ДокументНачисления", "Комментарий"]:
            check(имя in н, f"Начисления.{имя}")
        if "ДокументНачисления" in н:
            check(типы(н["ДокументНачисления"]) == ["Документ.ПриобретениеТоваровУслуг"], "ДокументНачисления: ПТУ")
    if "Расшифровка" in тч:
        р = реквизиты(тч["Расшифровка"].Реквизиты)
        for имя in ["Договор", "ВидСтроки", "ДатаНачала", "ДатаОкончания", "Дней", "Остаток", "Ставка", "Сумма",
                    "ДокументОплаты"]:
            check(имя in р, f"Расшифровка.{имя}")
        if "ДокументОплаты" in р:
            check(типы(р["ДокументОплаты"]) == ["Документ.РасходныйКассовыйОрдер",
                                                 "Документ.СписаниеБезналичныхДенежныхСредств"], "ДокументОплаты: РКО, списання")
    check(Мд.Подсистемы.Казначейство.Состав.Содержит(док), "документ у підсистемі «Казначейство»")

# --- реквізит ПТУ
птy = реквизиты(Мд.Документы.ПриобретениеТоваровУслуг.Реквизиты)
check("А_НачислениеПроцентовПоКредитам" in птy
      and типы(птy["А_НачислениеПроцентовПоКредитам"]) == ["Документ.А_НачислениеПроцентовПоКредитам"],
      "ПТУ.А_НачислениеПроцентовПоКредитам")

# --- загальний модуль
try:
    м = erp.А_НачислениеПроцентовПоКредитамСервер
    check(float(м.БазаДнейВГоду()) == 365, "БазаДнейВГоду() = 365")
    check(float(м.СтавкаПоУмолчанию()) == 18, "СтавкаПоУмолчанию() = 18")
    check(S(м.СтатьяРасходовПроцентов()) == "Послуги банків", "СтатьяРасходовПроцентов() = Послуги банків")
except Exception as e:
    check(False, f"загальний модуль А_НачислениеПроцентовПоКредитамСервер: {e}")

# --- дані налаштування (procenty_nastroyka.py)
try:
    import datetime as dt
    ном = erp.А_НачислениеПроцентовПоКредитамСервер.НоменклатураПроцентов()
    check(erp.ЗначениеЗаполнено(ном) and S(ном.ТипНоменклатуры) == S(erp.Перечисления.ТипыНоменклатуры.Услуга),
          f"послуга «Відсотки за користування позикою» є, тип Услуга: {S(ном)}")
    z = erp.NewObject("Запрос")
    z.Text = """ВЫБРАТЬ Д.Ссылка КАК Договор, ЕСТЬNULL(Ср.Ставка, 0) КАК Ставка
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.А_ПроцентныеСтавкиКредитов.СрезПоследних(&Дата, ) КАК Ср ПО Ср.Договор = Д.Ссылка
ГДЕ Д.А_ВидКредитногоДоговора = ЗНАЧЕНИЕ(Перечисление.А_ВидыКредитныхДоговоров.Проценты) И НЕ Д.ПометкаУдаления"""
    z.SetParameter("Дата", dt.datetime(2026, 9, 30, 12))
    r = z.Execute().Выгрузить()
    ставки = [float(r.Получить(i).Ставка) for i in range(r.Количество())]
    check(len(ставки) == 15 and all(s == 18 for s in ставки), f"зріз ставок на 30.09.2026: {len(ставки)} договорів, усі 18")
except Exception as e:
    check(False, f"дані налаштування: {getattr(e, 'excepinfo', None) and e.excepinfo[2] or e}")

sys.exit(0 if ok else 1)
