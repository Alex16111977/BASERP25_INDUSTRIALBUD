"""Verify: РКО с А_ОрганизацияБухгалтерия → А_ВзСС как Форма1 + ОргБух.

Перепроводит ІБ00-000006 (ОргБух=ІНДАСТРІАЛБУД) и СТ00-000001 (ОргБух=ІНДЕПТ СТІЛ),
проверяет ФормаPL=Форма1 + ОрганизацияБухгалтерия=ОргБух. Контроль: N0000053050
(без ОргБух) остаётся Форма2 / ОргБух пусто (без перепроводки).
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
XS = erp.XMLСтрока
errors = []


def find_rko(num):
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ Д.Ссылка КАК Ссылка, Д.СуммаДокумента КАК Сумма,
           ПРЕДСТАВЛЕНИЕ(Д.А_ОрганизацияБухгалтерия) КАК ОргБух
    ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ГДЕ Д.Номер = &Ном И Д.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику)
    """
    q.SetParameter("Ном", num)
    r = q.Execute().Выгрузить()
    return r[0] if r.Количество() else None


def vzs_breakdown(ref):
    """→ список (ФормаPL_xml, ОргБух_repr, ФЛ_count, Σ)."""
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        ПРЕДСТАВЛЕНИЕ(Р.ФормаPL) КАК ФормаPL,
        ПРЕДСТАВЛЕНИЕ(Р.ОрганизацияБухгалтерия) КАК ОргБух,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.ФизическоеЛицо) КАК ФЛ,
        СУММА(Р.СуммаВзаиморасчетов) КАК Сумма
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р
    ГДЕ Р.Регистратор = &Док
    СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Р.ФормаPL), ПРЕДСТАВЛЕНИЕ(Р.ОрганизацияБухгалтерия)
    """
    q.SetParameter("Док", ref)
    return q.Execute().Выгрузить()


def repost(ref):
    obj = ref.ПолучитьОбъект()
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)


# ── 1+2. Перепровести и проверить ІБ00-000006 и СТ00-000001 ─────────────────
for num, exp_orgbuh in [("ІБ00-000006", "ТОВ \"ІНДАСТРІАЛБУД\""), ("СТ00-000001", "ТОВ \"ІНДЕПТ СТІЛ\"")]:
    doc = find_rko(num)
    if doc is None:
        errors.append(f"{num}: не найден")
        continue
    repost(doc.Ссылка)
    rows = vzs_breakdown(doc.Ссылка)
    print(f"\n[{num}] СуммаДок={float(doc.Сумма):,.2f}, ОргБух(док)={S(doc.ОргБух)}")
    total = 0.0
    forms = set()
    orgbuhs = set()
    for r in rows:
        total += float(r.Сумма)
        forms.add(S(r.ФормаPL)); orgbuhs.add(S(r.ОргБух))
        print(f"    ФормаPL={S(r.ФормаPL)} | ОргБух={S(r.ОргБух)} | ФЛ={int(r.ФЛ)} | Σ={float(r.Сумма):,.2f}")
    if forms != {"Форма1"}:
        errors.append(f"{num}: ФормаPL={forms} != {{Форма1}}")
    if orgbuhs != {exp_orgbuh}:
        errors.append(f"{num}: ОргБух движений={orgbuhs} != {{{exp_orgbuh}}}")
    if abs(total - float(doc.Сумма)) > 0.01:
        errors.append(f"{num}: Σ А_ВзСС={total:,.2f} != СуммаДок={float(doc.Сумма):,.2f}")

# ── 3. Контроль: РКО без ОргБух остаётся Форма2 / пусто (без перепроводки) ───
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка, Д.Номер КАК Номер
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р ПО Р.Регистратор = Д.Ссылка
ГДЕ Д.А_ОрганизацияБухгалтерия = ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка)
    И ТИПЗНАЧЕНИЯ(Д.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу)
СГРУППИРОВАТЬ ПО Д.Ссылка, Д.Номер
"""
ctl = q.Execute().Выгрузить()
if ctl.Количество():
    cref, cnum = ctl[0].Ссылка, S(ctl[0].Номер)
    rows = vzs_breakdown(cref)
    forms = {S(r.ФормаPL) for r in rows}
    orgbuhs = {S(r.ОргБух) for r in rows}
    print(f"\n[Контроль {cnum} без ОргБух] ФормаPL={forms}, ОргБух={orgbuhs}")
    if forms != {"Форма2"}:
        errors.append(f"Контроль {cnum}: ФормаPL={forms} != {{Форма2}}")
    if orgbuhs - {""}:
        errors.append(f"Контроль {cnum}: ОргБух непуст={orgbuhs}")
else:
    print("\n[Контроль] нет РКО без ОргБух с движениями А_ВзСС — пропущено")

print("\n" + "=" * 80)
if errors:
    print("❌ VERIFY FAIL:")
    for e in errors:
        print("   - " + e)
    sys.exit(1)
print("✅ VERIFY PASS — ОргБух-РКО пишут Форма1 + ОрганизацияБухгалтерия; без ОргБух → Форма2")
print("=" * 80)
