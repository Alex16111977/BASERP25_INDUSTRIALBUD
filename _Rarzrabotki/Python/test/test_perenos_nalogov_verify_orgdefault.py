# -*- coding: utf-8 -*-
"""Проверка фикса: СоздатьДокументы() без шапочной Организации (дефолт own-org) + очистка."""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Перенос остатков налогов из бухгалтерии.epf"

def f(x):
    try: return float(x)
    except: return 0.0

o = erp.ВнешниеОбработки.Создать(EPF, False)
o.ОкончаниеПериода = datetime.datetime(2025, 11, 30)
# НЕ ставим o.Организация — проверяем дефолт own-org
o.ЗагрузитьОстатки()
n = o.Налоги.Количество()
print(f"Загружено строк: {n}")
assert n > 0, "ЗагрузитьОстатки вернул 0"

o.СоздатьДокументы()   # не должно падать «Организация пуста»
кр = o.ДокументКорректировкаРегистров
об = o.ДокументОперацияБух
print(f"КР={кр}  ОБ={об}")
assert erp.ЗначениеЗаполнено(кр) and erp.ЗначениеЗаполнено(об), "документы не созданы"

# ОБ проведён?
проведен = об.Проведен
print(f"ОперацияБух.Проведен = {проведен}")
# шапочная орг ОБ = own-org (40645273)?
шапкаЕДРПОУ = str(об.Организация.КодПоЕДРПОУ)
print(f"ОперацияБух.Организация ЕДРПОУ = {шапкаЕДРПОУ} (ожидаем 40645273)")
# ПАП движения КР по ТипНалога
q = erp.NewObject("Запрос"); q.УстановитьПараметр("Р", кр)
q.Текст = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.ПрочиеАктивыПассивы "
           "ГДЕ Регистратор=&Р И Статья=ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.Налоги)")
nпап = int(f(q.Выполнить().Выгрузить()[0].Н))
print(f"ПАП движений (Налоги) у КР = {nпап}")
assert проведен and шапкаЕДРПОУ == "40645273" and nпап > 0, "FAIL проверок"

# ===== Очистка =====
РЗ = erp.РежимЗаписиДокумента
обОбъект = об.ПолучитьОбъект()
