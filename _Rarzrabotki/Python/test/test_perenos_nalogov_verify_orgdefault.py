обОбъект = об.ПолучитьОбъект()
обОбъект.ОбменДанными.Загрузка = True
обОбъект.Удалить()
крОбъект = кр.ПолучитьОбъект()
крОбъект.ОбменДанными.Загрузка = True
крОбъект.Удалить()
# проверка чистоты
for имя, ссыл in (("КР", кр), ("ОБ", об)):
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("Р", ссыл)
    qq.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.ПрочиеАктивыПассивы ГДЕ Регистратор=&Р"
    qx = erp.NewObject("Запрос"); qx.УстановитьПараметр("Р", ссыл)
    qx.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрБухгалтерии.Хозрасчетный ГДЕ Регистратор=&Р"
    print(f"после удаления {имя}: ПАП={int(f(qq.Выполнить().Выгрузить()[0].Н))} ХР={int(f(qx.Выполнить().Выгрузить()[0].Н))}")
print("\nVERIFY PASS — фикс own-org работает, документы созданы и очищены")
