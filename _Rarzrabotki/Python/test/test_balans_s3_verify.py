qi.УстановитьПараметр("Сп", arr)
ИсклСт = qi.Выполнить().Выгрузить().ВыгрузитьКолонку("С")
qe = conn.NewObject("Запрос")
qe.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Б.Статья) КАК Н, СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
    Организация=&Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Б.Статья) ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток)<>0"""
qe.УстановитьПараметр("Д1",НМ); qe.УстановитьПараметр("Д2",КД)
