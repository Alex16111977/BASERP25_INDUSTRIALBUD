qr = conn.NewObject("Запрос")
qr.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Статья) КАК Н, СУММА(СуммаКонечныйОстаток) КАК sK
ИЗ РегистрСведений.А_ОтчетБаланс_Свод ГДЕ Регистратор=&Д
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Статья)"""
qr.УстановитьПараметр("Д", ref)
