qb = conn.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД"
qb.УстановитьПараметр("М", M); rb=qb.Выполнить().Выбрать(); rb.Следующий(); НМ=rb.НМ; КД=rb.КД
