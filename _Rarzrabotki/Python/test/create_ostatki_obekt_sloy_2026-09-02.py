# -*- coding: utf-8 -*-
"""Объектный слой остатков PL для корней направлений, которые ведутся ТОЛЬКО сводом
(решение финансиста 02.09.2026): Спецтехника и ЦО.

Копирует ТЧ «Остатки» документа-источника (свод-слой корня) в новый документ
А_ВводОстатковОтчетаPL той же датой/организацией, но СводНаправления = Ложь в каждой строке.
Идемпотентно: объектный документ корня ищется по ТЧ (Подразделение = корень, слой Ложь)
и при повторном запуске перезаполняется, а не дублируется.
Контроль: по каждому корню суммы 4 ресурсов регистра в слое Ложь == слою Истина;
суммы свод-слоя по регистру до и после — равны.
"""
import datetime
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ЦЕЛЬ = datetime.datetime(2026, 6, 30, 23, 59, 59)
КОРНИ = [
    ("Спецтехника", "Остатки PL на 30.06.2026 — лист «PL_Спецтехника_Свод» (объектный слой)"),
    ("ЦО", "Остатки PL на 30.06.2026 — лист «PL_ЦО» (объектный слой)"),
]
ПРОВАЛОВ = [0]


def чек(имя, ок, подробно=""):
    if not ок:
        ПРОВАЛОВ[0] += 1
    print("  [%s] %s%s" % ("OK  " if ок else "FAIL", имя, ("  — " + подробно) if подробно else ""))


def запрос(текст, **парам):
    q = erp.NewObject("Запрос")
    q.Text = текст
    for k, v in парам.items():
        q.SetParameter(k, v)
    return q.Execute().Выгрузить()


def документы_корня(имя, свод):
    r = запрос("""
    ВЫБРАТЬ РАЗЛИЧНЫЕ Стр.Ссылка КАК ДокСсылка
    ИЗ Документ.А_ВводОстатковОтчетаPL.Остатки КАК Стр
    ГДЕ Стр.Ссылка.Проведен И НЕ Стр.Ссылка.ПометкаУдаления
      И Стр.Подразделение.Наименование = &Имя И Стр.СводНаправления = &Свод""",
        Имя=имя, Свод=свод)
    return [r.Получить(i).ДокСсылка for i in range(r.Количество())]


def суммы_слоя(имя, свод):
    r = запрос("""
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Строк,
        СУММА(Ост.СуммаФ1СНачалаГода) КАК Ф1СНГ, СУММА(Ост.СуммаФ2СНачалаГода) КАК Ф2СНГ,
        СУММА(Ост.СуммаФ1Накопительно) КАК Ф1Нак, СУММА(Ост.СуммаФ2Накопительно) КАК Ф2Нак
    ИЗ РегистрНакопления.А_ОстаткиОтчетаPL КАК Ост
    ГДЕ Ост.Подразделение.Наименование = &Имя И Ост.СводНаправления = &Свод""", Имя=имя, Свод=свод)
    s = r.Получить(0)
    return (int(s.Строк or 0), round(float(s.Ф1СНГ or 0), 2), round(float(s.Ф2СНГ or 0), 2),
            round(float(s.Ф1Нак or 0), 2), round(float(s.Ф2Нак or 0), 2))


def итог_свод_слоя():
    r = запрос("""
    ВЫБРАТЬ СУММА(Ост.СуммаФ1СНачалаГода + Ост.СуммаФ2СНачалаГода) КАК СНГ,
        СУММА(Ост.СуммаФ1Накопительно + Ост.СуммаФ2Накопительно) КАК Нак
    ИЗ РегистрНакопления.А_ОстаткиОтчетаPL КАК Ост ГДЕ Ост.СводНаправления""")
    s = r.Получить(0)
    return (round(float(s.СНГ or 0), 2), round(float(s.Нак or 0), 2))


свод_до = итог_свод_слоя()
print("свод-слой до миграции: СНГ=%.2f Нак=%.2f" % свод_до)

for имя, коммент in КОРНИ:
    print("=" * 80)
    print(имя)
    источники = документы_корня(имя, True)
    чек("ровно один свод-документ", len(источники) == 1, "найдено %d" % len(источники))
    if len(источники) != 1:
        continue
    src = источники[0]
    существующие = документы_корня(имя, False)
    чек("объектных документов до запуска 0 или 1", len(существующие) <= 1, "найдено %d" % len(существующие))
    if len(существующие) > 1:
        continue
    Об = существующие[0].ПолучитьОбъект() if существующие else erp.Документы.А_ВводОстатковОтчетаPL.СоздатьДокумент()

    # Дата: COM сдвигает на −3 ч — выставляем, читаем обратно, корректируем дельту.
    Об.Дата = ЦЕЛЬ
    факт = Об.Дата
    дельта = ЦЕЛЬ - datetime.datetime(факт.year, факт.month, факт.day, факт.hour, факт.minute, факт.second)
    if дельта:
        Об.Дата = ЦЕЛЬ + дельта
    Об.Организация = src.Организация
    Об.Ответственный = src.Ответственный
    Об.Комментарий = коммент
    Об.Остатки.Очистить()
    n = 0
    for i in range(src.Остатки.Количество()):
        s = src.Остатки.Получить(i)
        стр = Об.Остатки.Добавить()
        стр.Подразделение = s.Подразделение
        стр.СтатьяPL = s.СтатьяPL
        стр.СводНаправления = False
        стр.СуммаФ1СНачалаГода = s.СуммаФ1СНачалаГода
        стр.СуммаФ2СНачалаГода = s.СуммаФ2СНачалаГода
        стр.СуммаФ1Накопительно = s.СуммаФ1Накопительно
        стр.СуммаФ2Накопительно = s.СуммаФ2Накопительно
        n += 1
    Об.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("  проведён №%s, строк %d, комментарий: %s" % (S(Об.Номер), n, коммент))

    a = суммы_слоя(имя, True)
    b = суммы_слоя(имя, False)
    чек("строк одинаково", a[0] == b[0], "свод %d / объект %d" % (a[0], b[0]))
    чек("Ф1СНГ равны", a[1] == b[1], "%.2f / %.2f" % (a[1], b[1]))
    чек("Ф2СНГ равны", a[2] == b[2], "%.2f / %.2f" % (a[2], b[2]))
    чек("Ф1Нак равны", a[3] == b[3], "%.2f / %.2f" % (a[3], b[3]))
    чек("Ф2Нак равны", a[4] == b[4], "%.2f / %.2f" % (a[4], b[4]))

свод_после = итог_свод_слоя()
print("=" * 80)
чек("свод-слой регистра не изменился", свод_до == свод_после, "%s -> %s" % (свод_до, свод_после))
print("ПРОВАЛОВ: %d" % ПРОВАЛОВ[0])
sys.exit(1 if ПРОВАЛОВ[0] else 0)
