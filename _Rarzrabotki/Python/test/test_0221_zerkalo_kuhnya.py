# -*- coding: utf-8 -*-
"""
Характеристика «зеркальных» ±пар на 0221 (напр. Кухня +5010.80 / -5010.80
на разных Контрагентах). Гипотеза: приход Дт 0221 и расход Кт 0221 попадают на
РАЗНЫЕ значения субконто Контрагент -> непарные остатки суммы при кол=0. Rule #-1.
"""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

def S(x):
    try: return buh.String(x)
    except Exception:
        try: return str(x)
        except Exception: return "<?>"
def имядок(рег):
    try: return S(рег.Метаданные().Имя)
    except Exception: return "<?>"

счет0221 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("0221").Ссылка

# --- найти обе строки Кухня (+/-5010.80) ---------------------------------
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Ост.Субконто1 КАК К, Ост.Субконто2 КАК Н, Ост.Субконто3 КАК С,
       Ост.СуммаОстатокДт КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет = &Счет) КАК Ост
ГДЕ Ост.КоличествоОстатокДт = 0 И Ост.СуммаОстатокДт <> 0
"""
q.УстановитьПараметр("Счет", счет0221)
q.УстановитьПараметр("НаДату", datetime.datetime(2026, 7, 13, 23, 59, 59))
r = q.Выполнить().Выгрузить()
кухни = []
ном = None
for i in range(r.Количество()):
    s = r.Получить(i)
    if abs(abs(float(s.Сумма)) - 5010.80) < 0.5:
        кухни.append(s); ном = s.Н
for s in кухни:
    print(f"остаток: Контрагент={S(s.К):<22} Ном={S(s.Н)} Склад={S(s.С)} -> {float(s.Сумма):.2f}")

# --- движения по Кухне, разрез Контрагент(Субконто1) x регистратор -------
q2 = buh.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    Об.Регистратор КАК Рег,
    ПРЕДСТАВЛЕНИЕ(Об.Субконто1) КАК К,
    Об.КоличествоОборотДт КАК КолДт, Об.СуммаОборотДт КАК СумДт,
    Об.КоличествоОборотКт КАК КолКт, Об.СуммаОборотКт КАК СумКт
ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(, , Регистратор, Счет = &Счет, , Субконто2 = &Ном) КАК Об
"""
q2.УстановитьПараметр("Счет", счет0221)
q2.УстановитьПараметр("Ном", ном)
d = q2.Выполнить().Выгрузить()
строки = [d.Получить(i) for i in range(d.Количество())]
def дата(s):
    try: return s.Рег.Дата
    except Exception: return datetime.datetime(1,1,1)
строки.sort(key=дата)

# --- баланс по каждому Контрагенту ---------------------------------------
покон = {}
print(f"\n{'Тип документа':<30} | {'Дата':<10} | {'Контрагент':<22} | {'КолДт':>6} {'СумДт':>9} | {'КолКт':>6} {'СумКт':>9}")
print("-"*104)
for s in строки:
    к = S(s.К)
    кд, сд, кк, ск = float(s.КолДт), float(s.СумДт), float(s.КолКт), float(s.СумКт)
    b = покон.setdefault(к, [0.0,0.0,0.0,0.0])
    b[0]+=кд; b[1]+=сд; b[2]+=кк; b[3]+=ск
    print(f"{имядок(s.Рег)[:30]:<30} | {S(дата(s))[:10]:<10} | {к[:22]:<22} | {кд:>6.1f} {сд:>9.2f} | {кк:>6.1f} {ск:>9.2f}")
print("-"*104)
print(f"\n{'Контрагент':<24} | {'приходКол':>9} {'приходСум':>10} | {'расходКол':>9} {'расходСум':>10} | {'остатокКол':>10} {'остатокСум':>10}")
for к,b in покон.items():
    print(f"{к[:24]:<24} | {b[0]:>9.1f} {b[1]:>10.2f} | {b[2]:>9.1f} {b[3]:>10.2f} | {b[0]-b[2]:>10.1f} {b[1]-b[3]:>10.2f}")
