"""Pre-test (Rule #-1): эталон 12 СтрПредпр из Ведомости == А_ВзСС.

Запускать ПЕРЕД правкой BSL. Подтверждает что данные в Ведомости корректны.
Если не подтверждается — проблема в Ведомости (откуда-то приходит неисправленное Подр).
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# 1. Эталон из А_ВзСС для тестового РКО N0000052986
q_vzs = erp.NewObject("Запрос")
q_vzs.Text = """
ВЫБРАТЬ
    Р.Подразделение КАК СтрПредпр,
    СУММА(ВЫБОР
            КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                ТОГДА Р.СуммаВзаиморасчетов
            ИНАЧЕ -Р.СуммаВзаиморасчетов
        КОНЕЦ) КАК СуммаРасход
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р
ГДЕ Р.Регистратор.Номер = &Ном
СГРУППИРОВАТЬ ПО Р.Подразделение
"""
q_vzs.SetParameter("Ном", "N0000052986")
vzs = q_vzs.Execute().Выгрузить()
ETALON = {S(row.СтрПредпр): float(row.СуммаРасход) for row in vzs}
print(f"А_ВзСС эталон для РКО N0000052986: {len(ETALON)} СтрПредпр, Σ={sum(ETALON.values()):.0f}")
for podr, sumv in sorted(ETALON.items(), key=lambda x: -x[1]):
    print(f"  {podr}: {sumv:,.2f}")
assert len(ETALON) == 12, f"Ожидаем 12 СтрПредпр в А_ВзСС, получили {len(ETALON)}"
assert abs(sum(ETALON.values()) - 348800.0) < 0.01, f"Σ А_ВзСС != 348800"

# 2. Прямой запрос к Ведомость.А_РасшифровкаВыплатыЗарплатаПоФизлицам — то что наша правка будет читать
q_ved = erp.NewObject("Запрос")
q_ved.Text = """
ВЫБРАТЬ
    Рш.Подразделение.А_Подразделение КАК СтрПредпр,
    СУММА(Рш.КВыплате) КАК Сумма
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Номер = &Ном
СГРУППИРОВАТЬ ПО Рш.Подразделение.А_Подразделение
"""
q_ved.SetParameter("Ном", "N0000052986")
vedrows = q_ved.Execute().Выгрузить()
VED = {S(row.СтрПредпр): float(row.Сумма) for row in vedrows}
print(f"\nВедомость эталон: {len(VED)} СтрПредпр, Σ={sum(VED.values()):.0f}")
for podr, sumv in sorted(VED.items(), key=lambda x: -x[1]):
    print(f"  {podr}: {sumv:,.2f}")

# 3. Сверка
diff = {k: (VED.get(k, 0) - ETALON.get(k, 0)) for k in set(VED) | set(ETALON)}
mismatches = {k: v for k, v in diff.items() if abs(v) > 0.01}
assert not mismatches, f"FAIL: Ведомость != А_ВзСС\nMismatches: {mismatches}\nVED: {VED}\nETALON: {ETALON}"

# 4. Дополнительно — детализация по ФЛ + СтатьеДДС (для acceptance #5)
q_ved_fl = erp.NewObject("Запрос")
q_ved_fl.Text = """
ВЫБРАТЬ
    Рш.ФизическоеЛицо КАК ФЛ,
    Рш.Подразделение.А_Подразделение КАК СтрПредпр,
    Рш.СтатьяДвиженияДенежныхСредств КАК СтатьяДДС,
    Рш.НаправлениеДеятельности КАК Направление,
    Рш.КВыплате КАК Сумма
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Номер = &Ном
УПОРЯДОЧИТЬ ПО Рш.Подразделение.А_Подразделение, Рш.ФизическоеЛицо
"""
q_ved_fl.SetParameter("Ном", "N0000052986")
fl_rows = q_ved_fl.Execute().Выгрузить()
print(f"\nДетализация по ФЛ: {fl_rows.Количество()} строк")
unique_stat_dds = {S(r.СтатьяДДС) for r in fl_rows}
unique_napr = {S(r.Направление) for r in fl_rows}
print(f"Уникальных СтатейДДС: {len(unique_stat_dds)} → {unique_stat_dds}")
print(f"Уникальных НаправленияхДеятельности: {len(unique_napr)} → {unique_napr}")
assert fl_rows.Количество() == 21, f"Ожидаем 21 строку per ФЛ, получили {fl_rows.Количество()}"
# Для этого РКО (все ФЛ из СпецТехники, направление "Спецтехника") в БДДС Казны
# одна общая статья — «Зарплата механизаторов» (НЕ «Оплата за выполненные работы»).
# Для других РКО (Производство, ИТР, АУП) — другие детальные статьи.
# Главное: не общая «Оплата за выполненные работы» из шапки РКО.
assert len(unique_stat_dds) >= 1, f"Ожидаем >=1 СтатьюДДС, получили {len(unique_stat_dds)}"
assert "Оплата за выполненные работы" not in unique_stat_dds, f"FAIL: всё ещё общая статья из шапки РКО: {unique_stat_dds}"

print("\n" + "=" * 80)
print("✅ pretest PASS — Ведомость и А_ВзСС согласованы, можно писать BSL правки")
print("=" * 80)
