    q.УстановитьПараметр("К", make_time(DATE_TO))
    if params:
        for k, v in params.items():
            q.УстановитьПараметр(k, v)
    try:
        r = q.Выполнить().Выбрать()
        count = 0
        while r.Следующий():
            count += 1
            if count <= 3:
                print(f"  [{count}] {str(r.Рег)[:60]}  К-ть={r.Кол}")
        print(f"  Записей: {count}")
        return count
    except Exception as e:
        print(f"  ОШИБКА: {str(e)[:200]}")
        return -1

