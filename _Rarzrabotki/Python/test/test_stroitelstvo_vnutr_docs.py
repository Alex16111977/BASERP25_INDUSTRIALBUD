# -*- coding: utf-8 -*-
"""
Углубление: природа документов, создавших остаток 7 194 594,73 по
ОР «Строительство внутр.(Реализация)» в Глобино-2.

На скриншоте видны 5 документов:
- Взаимозачет задолженности 000Ц-000516 от 03.12.2025
- Поступление безналичных ДС 000Ц-000053 от 16.12.2025
- Списание безналичных ДС 000Ц-000288 от 28.12.2025
- Списание безналичных ДС 000Ц-000286 от 28.12.2025
- Списание безналичных ДС 000Ц-000287 от 28.12.2025

Финансист подозревает: документ-реализация отсутствует, а долг растёт
через ПЛАТЁЖНЫЕ документы — это ОШИБКА в проведении (должна быть
ХозоперацияПеремещенияДС или ВнутригрупповойРасчёт, а не платёж клиенту).

Для каждого документа смотрим:
- ХозяйственнаяОперация (ключевое поле!)
- Контрагент / Получатель
- Договор
- СчётОтправитель / СчётПолучатель / ИхСчёт
- ВидВзаимозачёта
- ОР, в который пишет движение
- Реальные движения, которые создаёт в РасчетыСКлиентами + ДенежныеСредстваБезналичные
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Список искомых документов: (МетаИмя, Номер)
ИСКОМЫЕ = [
    ("Документ.ВзаимозачетЗадолженности",        "000Ц-000516"),
    ("Документ.ПоступлениеБезналичныхДенежныхСредств", "000Ц-000053"),
    ("Документ.СписаниеБезналичныхДенежныхСредств",    "000Ц-000288"),
    ("Документ.СписаниеБезналичныхДенежныхСредств",    "000Ц-000286"),
    ("Документ.СписаниеБезналичныхДенежныхСредств",    "000Ц-000287"),
]

def найти_док(тип, номер):
    """Найти документ по типу и номеру."""
    кр_тип = тип.split(".")[1]  # ВзаимозачетЗадолженности
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Номер", номер)
    qq.Текст = f'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.{кр_тип} ГДЕ Номер = &Номер'
    r = qq.Выполнить().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() else None

def показать_реквизиты(док, реквизиты_список):
    """Печать заданных реквизитов документа."""
    obj = док.ПолучитьОбъект()
    for р in реквизиты_список:
        try:
            знач = getattr(obj, р, None)
            строка = S(знач) if знач is not None else "(нет)"
            print(f"      {р:<35}: {строка}")
        except Exception as e:
            print(f"      {р:<35}: ОШИБКА — {e}")

def показать_движения_рск(док):
    """Все движения этого регистратора в РасчетыСКлиентами."""
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Рег", док)
    qq.Текст = """
ВЫБРАТЬ
    Р.Период,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОР,
    ПРЕДСТАВЛЕНИЕ(АП.Партнер) КАК Партнер,
    ПРЕДСТАВЛЕНИЕ(АП.Контрагент) КАК Контр,
    ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ КАК signed,
    Р.ХозяйственнаяОперация
ИЗ РегистрНакопления.РасчетыСКлиентами КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ Р.Регистратор = &Рег
УПОРЯДОЧИТЬ ПО Р.Период
"""
    rr = qq.Выполнить().Выгрузить()
    if rr.Количество() == 0:
        print(f"      РСК-движений нет")
        return
    print(f"      Движения в РасчетыСКлиентами ({rr.Количество()} строк):")
    for i in range(rr.Количество()):
        rec = rr.Получить(i)
        хо = S(rec.ХозяйственнаяОперация) or "(нет)"
        print(f"        Период={rec.Период.strftime('%d.%m.%Y')} | ОР={str(rec.ОР)[:35]:<35} | Контр={str(rec.Контр)[:18]:<18} | signed={float(rec.signed):>15,.2f} | Хозоп={хо[:30]}")

# Маппинг искомых реквизитов по типу документа
РЕКВИЗИТЫ = {
    "ВзаимозачетЗадолженности": [
        "Организация", "Дата", "Номер", "ХозяйственнаяОперация",
        "Контрагент", "Партнер", "ДоговорКонтрагента",
        "КонтрагентДебитор", "ПартнерДебитор",
        "СуммаДокумента", "Подразделение",
    ],
    "ПоступлениеБезналичныхДенежныхСредств": [
        "Организация", "Дата", "Номер", "ХозяйственнаяОперация",
        "СчетОрганизации", "Плательщик", "Партнер", "Контрагент",
        "СуммаДокумента", "Подразделение", "СтатьяДДС",
    ],
    "СписаниеБезналичныхДенежныхСредств": [
        "Организация", "Дата", "Номер", "ХозяйственнаяОперация",
        "СчетОрганизации", "Получатель", "Партнер", "Контрагент",
        "СуммаДокумента", "Подразделение", "СтатьяДДС",
    ],
}

print("=" * 110)
print("УГЛУБЛЕНИЕ: природа документов по ОР «Строительство внутр.(Реализация)»")
print("=" * 110)

for тип, номер in ИСКОМЫЕ:
    кр_тип = тип.split(".")[1]
    print(f"\n[{кр_тип} № {номер}]")
    print("-" * 110)
    док = найти_док(тип, номер)
    if not док:
        print(f"   Не найден")
        continue
    print(f"   Ссылка: {S(док)}")
    показать_реквизиты(док, РЕКВИЗИТЫ.get(кр_тип, ["Дата", "Номер", "СуммаДокумента"]))
    показать_движения_рск(док)

print("\n" + "=" * 110)
print("ВЫВОД: смотрим колонку ХозяйственнаяОперация — она задаёт смысл документа.")
