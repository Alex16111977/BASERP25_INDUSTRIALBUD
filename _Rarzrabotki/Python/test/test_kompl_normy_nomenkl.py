# Task 1 (Фаза 7): запит норм групує (ОбщееНазвание, Номенклатура); Σ по номенклатурах эталону = норма эталону.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
spec = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005").Ссылка
q = buh.NewObject("Запрос")
q.УстановитьПараметр("С", spec)
q.Текст = """
ВЫБРАТЬ К.ОбщееНазвание КАК Эталон, К.Номенклатура КАК Ном,
       СУММА(К.Количество) КАК Кол, СУММА(К.Сумма) КАК Сум
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка = &С
СГРУППИРОВАТЬ ПО К.ОбщееНазвание, К.Номенклатура
"""
t = q.Выполнить().Выгрузить()
эталон = {}; номенкл = {}
for i in range(t.Количество()):
    r = t.Получить(i)
    э = buh.String(r.Эталон); n = buh.String(r.Ном)
    эталон[э] = эталон.get(э, 0) + float(r.Кол)
    номенкл[(э, n)] = номенкл.get((э, n), 0) + float(r.Кол)
ok = all(abs(эталон[э] - sum(v for (e, n), v in номенкл.items() if e == э)) < 0.001 for э in эталон)
print(f"рядків={t.Количество()} эталонів={len(эталон)} (эталон,номенкл)-пар={len(номенкл)} Σ-консистентність={ok}")
assert t.Количество() > 0 and ok
print("PASS")
