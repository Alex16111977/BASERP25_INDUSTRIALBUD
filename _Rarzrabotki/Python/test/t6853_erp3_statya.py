# -*- coding: utf-8 -*-
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Счёт 6853
q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Сч.Ссылка КАК Ссылка ИЗ ПланСчетов.Хозрасчетный КАК Сч ГДЕ Сч.Код = "6853" """
счет = q.Execute().Выгрузить().Получить(0).Ссылка

# Регистраторы Кт6853
q1 = erp.NewObject("Запрос")
q1.Text = """ВЫБРАТЬ РАЗЛИЧНЫЕ Дв.Регистратор КАК Рег ИЗ РегистрБухгалтерии.Хозрасчетный КАК Дв ГДЕ Дв.СчетКт = &Счет"""
q1.SetParameter("Счет", счет)
r1 = q1.Execute().Выгрузить()
regs = erp.NewObject("Массив")
for i in range(r1.Количество()):
    regs.Добавить(r1.Получить(i).Рег)

# Агрегируем ПАП только по Статья + тип аналитики + ВидДвижения (свёртка, без конкретных значений)
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    ПАП.Статья.Наименование КАК СтатьяНаим,
    ТИПЗНАЧЕНИЯ(ПАП.Аналитика) КАК ТипАналитики,
    ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА "Приход" ИНАЧЕ "Расход" КОНЕЦ КАК Вид,
    СУММА(ПАП.Сумма) КАК Сумма,
    КОЛИЧЕСТВО(*) КАК Зап
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Регистратор В (&Регистраторы)
СГРУППИРОВАТЬ ПО
    ПАП.Статья.Наименование, ТИПЗНАЧЕНИЯ(ПАП.Аналитика),
    ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА "Приход" ИНАЧЕ "Расход" КОНЕЦ
УПОРЯДОЧИТЬ ПО СтатьяНаим
"""
q2.SetParameter("Регистраторы", regs)
r2 = q2.Execute().Выгрузить()
print(f"Свёртка ПАП регистраторов Кт6853 по статьям: рядкiв={r2.Количество()}")
for i in range(r2.Количество()):
    s=r2.Получить(i)
    ta = s.ТипАналитики
    taname = ""
    try:
        taname = str(ta)
    except Exception:
        taname = "?"
    print(f"  Статья='{s.СтатьяНаим}' | ТипАналитики={taname} | {s.Вид} | Σ={s.Сумма} зап={s.Зап}")
