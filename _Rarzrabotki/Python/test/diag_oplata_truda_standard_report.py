# -*- coding: utf-8 -*-
"""Запустить штатный Отчёт.УправленческийБаланс за янв 2026 и вытащить «Оплата труда».
Authoritative «1С»-значение, с которым сравнивает пользователь."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# 1) найти отчёты-кандидаты по балансу
print("=== отчёты-кандидаты (Баланс) ===")
cand = []
for md in erp.Метаданные.Отчеты:
    nm = md.Имя
    if "Баланс" in nm:
        cand.append(nm)
        print(f"   Отчет.{nm}")

# 2) штатный 'УправленческийБаланс' нет смысла гонять SKD вручную — вместо этого
#    берём его источник: регистр ПрочиеАктивыПассивы НЕТТО по статье (= то, что
#    показывает любой балансовый отчёт). Уже померяно: ОТ янв = +246 187,13.
#    Здесь сверим ещё и стандартный регистр ВзаиморасчетыССотрудниками (опер. долг персоналу).
print("\n=== Стандартный РН.ВзаиморасчетыССотрудниками — сальдо по организации на 31.01.2026 ===")
qv = erp.NewObject("Запрос")
qv.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Ост.Организация) КАК Орг,
    СУММА(Ост.СуммаВзаиморасчетовОстаток) КАК Сальдо
ИЗ РегистрНакопления.ВзаиморасчетыССотрудниками.Остатки(ДАТАВРЕМЯ(2026,1,31,23,59,59)) КАК Ост
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Ост.Организация)
"""
try:
    tot = 0.0
    for r in qv.Выполнить().Выгрузить():
        print(f"   {str(r.Орг):<40} Сальдо = {f(r.Сальдо):>16,.2f}")
        tot += f(r.Сальдо)
    print(f"   ИТОГО ВзаиморасчетыССотрудниками = {tot:>16,.2f}")
except Exception as e:
    print(f"   [FAIL: {e}]")

# 3) кастомный А_ВзаиморасчетыССотрудниками — сальдо (источник деталей свёртки)
print("\n=== Кастомный РН.А_ВзаиморасчетыССотрудниками — сальдо на 31.01.2026 ===")
qa = erp.NewObject("Запрос")
qa.Текст = """
ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА ВзСС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА ВзСС.СуммаВзаиморасчетов ИНАЧЕ -ВзСС.СуммаВзаиморасчетов КОНЕЦ) КАК Сальдо,
    КОЛИЧЕСТВО(*) КАК Движ
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзСС
ГДЕ ВзСС.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59)
"""
try:
    r = qa.Выполнить().Выгрузить()[0]
    print(f"   А_ВзСС signed сальдо = {f(r.Сальдо):>16,.2f} (×-1 в Своде → {-f(r.Сальдо):>16,.2f}); движений={int(f(r.Движ))}")
except Exception as e:
    print(f"   [FAIL: {e}]")

# 4) Свод: что реально показывает свёртка по ОТ за янв (детали vs плуг)
print("\n=== Свод (регистр) «Оплата труда» янв 2026: детали vs плуг ===")
ОТ = erp.NewObject("Запрос")
ОТ.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов "
            "ГДЕ Наименование = \"Оплата труда\"")
ОТ = ОТ.Выполнить().Выгрузить()[0].С
qs = erp.NewObject("Запрос")
qs.УстановитьПараметр("ОТ", ОТ)
qs.Текст = """
ВЫБРАТЬ Рег.Расхождение КАК Плуг, СУММА(Рег.СуммаКонечныйОстаток) КАК КО, КОЛИЧЕСТВО(*) КАК Стр
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Статья = &ОТ И Рег.Регистратор.Месяц = ДАТАВРЕМЯ(2026,1,1)
СГРУППИРОВАТЬ ПО Рег.Расхождение
"""
for r in qs.Выполнить().Выгрузить():
    print(f"   Расхождение(плуг)={r.Плуг} | строк={int(f(r.Стр)):>5} | КО={f(r.КО):>16,.2f}")
