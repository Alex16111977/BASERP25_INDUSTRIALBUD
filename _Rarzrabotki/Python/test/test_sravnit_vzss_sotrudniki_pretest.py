# -*- coding: utf-8 -*-
# Pretest (Rule #-1) для отчёта А_СравнитьОстаткиВзаиморасчетыСотрудникиЕРПсBASБухгалтерия
# Проверяет: ERP А_ВзСС.ОстаткиИОбороты (Форма1) + BuhBud Хозрасчетный 661/663,
# субсчета 661/663, покрытие А_ИдКод, сходимость КонОстаток ЕРП <-> Кт(661+663) BuhBud.
import win32com.client as wc
import sys
from datetime import datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

def fail(e):
    if hasattr(e, 'excepinfo') and e.excepinfo:
        return e.excepinfo[2]
    return str(e)

v8 = wc.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
print("OK connect ERP + BuhBud")

nach = datetime(2025, 1, 1)
kon  = datetime(2026, 12, 31, 23, 59, 59)

# ---------------------------------------------------------------------------
# T1. ERP: А_ВзСС.ОстаткиИОбороты с фильтром Форма1, группировка ФЛ+ОргБух
# ---------------------------------------------------------------------------
print("\n=== T1. ERP А_ВзСС ОстаткиИОбороты (Форма1) ===")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Н", nach)
q.УстановитьПараметр("К", kon)
q.Текст = """
ВЫБРАТЬ
    Ост.ФизическоеЛицо КАК ФЛ,
    Ост.ФизическоеЛицо.А_ИдКод КАК ИдКод,
    Ост.ОрганизацияБухгалтерия КАК ОргБух,
    Ост.ОрганизацияБухгалтерия.КодПоЕДРПОУ КАК ЕДРПОУ,
    СУММА(Ост.СуммаВзаиморасчетовНачальныйОстаток) КАК НачОст,
    СУММА(Ост.СуммаВзаиморасчетовПриход) КАК Приход,
    СУММА(Ост.СуммаВзаиморасчетовРасход) КАК Расход,
    СУММА(Ост.СуммаВзаиморасчетовКонечныйОстаток) КАК КонОст
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками.ОстаткиИОбороты(&Н, &К, , ,
        ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)) КАК Ост
СГРУППИРОВАТЬ ПО
    Ост.ФизическоеЛицо, Ост.ФизическоеЛицо.А_ИдКод,
    Ост.ОрганизацияБухгалтерия, Ост.ОрганизацияБухгалтерия.КодПоЕДРПОУ
"""
erp_map = {}
try:
    sel = q.Выполнить().Выбрать()
    rows = 0
    sum_kon = 0.0
    empty_idkod = 0
    empty_edrpou = 0
    while sel.Следующий():
        rows += 1
        idk = (str(sel.ИдКод) if sel.ИдКод is not None else "").strip()
        edr = (str(sel.ЕДРПОУ) if sel.ЕДРПОУ is not None else "").strip()
        kon_v = float(sel.КонОст)
        sum_kon += kon_v
        if not idk:
            empty_idkod += 1
        if not edr:
            empty_edrpou += 1
        if idk and edr:
            erp_map[(idk, edr)] = erp_map.get((idk, edr), 0.0) + kon_v
    print(f"T1 OK: строк={rows}, Σ КонОст={sum_kon:.2f}, без ИдКод={empty_idkod}, без ЕДРПОУ={empty_edrpou}")
    print(f"   уник.ключей (ИдКод,ЕДРПОУ) с заполнением={len(erp_map)}")
except Exception as e:
    print("T1 FAIL:", fail(e))

# ---------------------------------------------------------------------------
# Массив ЕДРПОУ организаций в балансе (из ERP) -> для BuhBud
# ---------------------------------------------------------------------------
qo = erp.NewObject("Запрос")
qo.Текст = ('ВЫБРАТЬ Орг.КодПоЕДРПОУ КАК Е ИЗ Справочник.Организации КАК Орг '
            'ГДЕ Орг.А_ВБалансе = ИСТИНА И Орг.КодПоЕДРПОУ <> ""')
edrpou_list = []
selo = qo.Выполнить().Выбрать()
while selo.Следующий():
    edrpou_list.append(str(selo.Е).strip())
print(f"\nОрганизаций в балансе (ЕДРПОУ): {len(edrpou_list)} -> {edrpou_list}")

mas = buh.NewObject("Массив")
for e in edrpou_list:
    mas.Добавить(e)

# ---------------------------------------------------------------------------
# T2. BuhBud субсчета 661/663
# ---------------------------------------------------------------------------
print("\n=== T2. BuhBud субсчета под 661/663 ===")
qs = buh.NewObject("Запрос")
qs.Текст = ('ВЫБРАТЬ Сч.Код КАК Код, Сч.Наименование КАК Имя, '
            'ВЫБОР КОГДА Сч.ЕстьСубсчета ТОГДА "группа" ИНАЧЕ "лист" КОНЕЦ КАК Тип '
            'ИЗ ПланСчетов.Хозрасчетный КАК Сч '
            'ГДЕ Сч.Код ПОДОБНО "661%" ИЛИ Сч.Код ПОДОБНО "663%" '
            'УПОРЯДОЧИТЬ ПО Сч.Код')
try:
    sel = qs.Выполнить().Выбрать()
    while sel.Следующий():
        print(f"   {str(sel.Код).strip():8} [{str(sel.Тип)}] {str(sel.Имя)}")
except Exception as e:
    print("T2 FAIL:", fail(e))

# ---------------------------------------------------------------------------
# T3. BuhBud: Хозрасчетный.ОстаткиИОбороты 661/663, субконто1 ФЛ, разрез ЕДРПОУ
# ---------------------------------------------------------------------------
print("\n=== T3. BuhBud 661/663 ОстаткиИОбороты ===")
qb = buh.NewObject("Запрос")
qb.УстановитьПараметр("Н", nach)
qb.УстановитьПараметр("К", kon)
qb.УстановитьПараметр("мас", mas)
qb.Текст = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод КАК ИдКод,
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).Наименование КАК Имя,
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    СУММА(Ост.СуммаНачальныйОстатокДт) КАК НДт,
    СУММА(Ост.СуммаНачальныйОстатокКт) КАК НКт,
    СУММА(Ост.СуммаОборотДт) КАК ОДт,
    СУММА(Ост.СуммаОборотКт) КАК ОКт,
    СУММА(Ост.СуммаКонечныйОстатокДт) КАК КДт,
    СУММА(Ост.СуммаКонечныйОстатокКт) КАК ККт
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&Н, &К) КАК Ост
ГДЕ Ост.Счет.Код В ("661", "663")
    И Ост.Субконто1 ССЫЛКА Справочник.ФизическиеЛица
    И Ост.Организация.КодПоЕДРПОУ В (&мас)
СГРУППИРОВАТЬ ПО
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод,
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).Наименование,
    Ост.Организация.КодПоЕДРПОУ
"""
buh_map = {}
buh_idkods = set()
try:
    sel = qb.Выполнить().Выбрать()
    rows = 0
    sum_saldo = 0.0
    empty_idkod = 0
    while sel.Следующий():
        rows += 1
        idk = (str(sel.ИдКод) if sel.ИдКод is not None else "").strip()
        edr = (str(sel.ЕДРПОУ) if sel.ЕДРПОУ is not None else "").strip()
        saldo = float(sel.ККт) - float(sel.КДт)   # пассив: Кт - Дт = долг
        sum_saldo += saldo
        if not idk:
            empty_idkod += 1
        else:
            buh_idkods.add(idk)
        if idk and edr:
            buh_map[(idk, edr)] = buh_map.get((idk, edr), 0.0) + saldo
    print(f"T3 OK: строк={rows}, Σ сальдо(Кт-Дт)={sum_saldo:.2f}, без ИдКод={empty_idkod}")
    print(f"   уник.ключей (ИдКод,ЕДРПОУ)={len(buh_map)}, уник.ИдКод={len(buh_idkods)}")
except Exception as e:
    print("T3 FAIL:", fail(e))

# ---------------------------------------------------------------------------
# T4. Покрытие А_ИдКод: резолв BuhBud ИдКод -> ERP ФизическиеЛица
# ---------------------------------------------------------------------------
print("\n=== T4. Резолв BuhBud ИдКод -> ERP ФизическиеЛица ===")
if buh_idkods:
    masid = erp.NewObject("Массив")
    for x in buh_idkods:
        masid.Добавить(x)
    qr = erp.NewObject("Запрос")
    qr.УстановитьПараметр("мас", masid)
    qr.Текст = ('ВЫБРАТЬ РАЗЛИЧНЫЕ ФЛ.А_ИдКод КАК ИдКод ИЗ Справочник.ФизическиеЛица КАК ФЛ '
                'ГДЕ ФЛ.А_ИдКод В (&мас) И ФЛ.А_ИдКод <> ""')
    matched = set()
    selr = qr.Выполнить().Выбрать()
    while selr.Следующий():
        matched.add(str(selr.ИдКод).strip())
    unmatched = buh_idkods - matched
    print(f"T4: BuhBud уник.ИдКод={len(buh_idkods)}, найдено в ERP={len(matched)}, НЕ найдено={len(unmatched)}")
    if unmatched:
        print("   примеры ненайденных ИдКод:", list(unmatched)[:10])
else:
    print("T4: нет BuhBud ИдКод для проверки")

# ---------------------------------------------------------------------------
# T5. Сходимость: КонОстаток ЕРП(Форма1) <-> сальдо(Кт-Дт) BuhBud 661/663
# ---------------------------------------------------------------------------
print("\n=== T5. Сходимость по (ИдКод, ЕДРПОУ) ===")
all_keys = set(erp_map) | set(buh_map)
tot_erp = sum(erp_map.values())
tot_buh = sum(buh_map.values())
tot_absdiff = 0.0
big = []
for k in all_keys:
    e = erp_map.get(k, 0.0)
    b = buh_map.get(k, 0.0)
    d = e - b
    tot_absdiff += abs(d)
    if abs(d) > 0.01:
        big.append((k, e, b, d))
print(f"T5: Σ КонОст ЕРП={tot_erp:.2f}, Σ сальдо BuhBud={tot_buh:.2f}, "
      f"Σ|разниц|={tot_absdiff:.2f}")
print(f"   ключей всего={len(all_keys)}, с |разн|>0.01: {len(big)}")
big.sort(key=lambda t: -abs(t[3]))
for (k, e, b, d) in big[:10]:
    print(f"   {k}: ЕРП={e:.2f} BuhBud={b:.2f} разн={d:.2f}")

print("\n=== DONE ===")
