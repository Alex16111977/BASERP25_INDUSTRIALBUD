def дозалить(ссылка_дог, c, d, прим, комментарий):
    """Возвращает 'записано'/'без изменений'/'ошибка'."""
    имя = " ".join(str(ссылка_дог.Наименование).split())
    подр = str(buh.String(ссылка_дог.Подразделение))
    напр = str(buh.String(ссылка_дог.Направление))
    print(f"{комментарий}")
    print(f"  Договор: {имя}  [{подр or '<без подразделения>'}; {напр or '<без направления>'}]")
    if напр != "Производство":
        print("  [ОШИБКА] направление договора не «Производство» — пропуск\n")
        return "ошибка"

    мз = РЕГИСТР.СоздатьМенеджерЗаписи()
    мз.Договор = ссылка_дог
    мз.Прочитать()
    if мз.Выбран():
        тек = {"Сумма": float(мз.СуммаСоглашения or 0), "ДЦ": float(мз.СуммаДЦ or 0),
               "Прим": str(buh.string(мз.ОбъектПримечание)),
               "Процент": float(мз.ПроцентГарантийногоУдержания or 0),
               "Вариант": str(buh.string(мз.ВариантФормулыИтога))}
        print(f"  В регистре сейчас: C={тек['Сумма']:,.2f} D={тек['ДЦ']:,.2f}"
              f" %={тек['Процент']:g} вариант={тек['Вариант'] or '—'}")
    else:
        тек = {"Сумма": 0.0, "ДЦ": 0.0, "Прим": "", "Процент": 0.0, "Вариант": ""}
        print("  В регистре сейчас: записи НЕТ")

    итог = dict(тек)
    изменено = []
    if c is not None and c != 0 and тек["Сумма"] != c:
        итог["Сумма"] = c
        изменено.append(f"C: {тек['Сумма']:,.2f} -> {c:,.2f}")
    if d is not None and d != 0 and тек["ДЦ"] != d:
        итог["ДЦ"] = d
        изменено.append(f"D: {тек['ДЦ']:,.2f} -> {d:,.2f}")
    if прим and тек["Прим"] != прим[:200]:
        итог["Прим"] = прим[:200]
        изменено.append("Примечание")

    if not изменено:
        print("  -> без изменений\n")
        return "без изменений"

    print(f"  -> {'ЗАПИСЬ' if ПРИМЕНЯТЬ else '[dry-run] будет записано'}: " + "; ".join(изменено))
    if ПРИМЕНЯТЬ:
        мз2 = РЕГИСТР.СоздатьМенеджерЗаписи()
        мз2.Договор = ссылка_дог
        мз2.СуммаСоглашения = итог["Сумма"]
        мз2.СуммаДЦ = итог["ДЦ"]
        мз2.ОбъектПримечание = итог["Прим"]
        мз2.ПроцентГарантийногоУдержания = итог["Процент"]
        мз2.ВариантФормулыИтога = итог["Вариант"]
        мз2.Записать(True)
    print()
    return "записано"


итоги = {"записано": 0, "без изменений": 0, "ошибка": 0}

for уид_стр, c, d, прим, комментарий in ПОЗИЦИИ:
    уид = buh.NewObject("УникальныйИдентификатор", уид_стр)
    ссылка = buh.Справочники.ДоговорыКонтрагентов.ПолучитьСсылку(уид)
    if ссылка.ПолучитьОбъект() is None:
        print(f"[ОШИБКА] {уид_стр}: договор не найден — пропуск ({комментарий})\n")
        итоги["ошибка"] += 1
        continue
    итоги[дозалить(ссылка, c, d, прим, комментарий)] += 1

for шаблон, имя_подр, c, прим, комментарий in ПОИСКОВЫЕ:
    q = buh.NewObject("Запрос")
    if шаблон:
        q.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С ИЗ Справочник.ДоговорыКонтрагентов КАК Д "
                   "ГДЕ НЕ Д.ПометкаУдаления И НЕ Д.ЭтоГруппа "
                   "И Д.Направление.Наименование = \"Производство\" "
                   "И Д.Наименование ПОДОБНО &Ш")
        q.УстановитьПараметр("Ш", шаблон)
    else:
        q.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С ИЗ Справочник.ДоговорыКонтрагентов КАК Д "
                   "ГДЕ НЕ Д.ПометкаУдаления И НЕ Д.ЭтоГруппа "
                   "И Д.Направление.Наименование = \"Производство\" "
                   "И Д.Подразделение.Наименование = &Подр")
        q.УстановитьПараметр("Подр", имя_подр)
    т = q.Execute().Выгрузить()
    if т.Количество() == 0:
        print(f"[ВОПРОС ПОЛЬЗОВАТЕЛЮ] {комментарий}: договор НЕ НАЙДЕН "
              f"(шаблон={шаблон!r}, подразделение={имя_подр!r})\n")
        итоги["ошибка"] += 1
        continue
    if т.Количество() > 1:
        print(f"[ВОПРОС ПОЛЬЗОВАТЕЛЮ] {комментарий}: кандидатов {т.Количество()}:")
        for i in range(т.Количество()):
            к = т.Получить(i).С
            print(f"    - {' '.join(str(к.Наименование).split())}"
                  f" [{buh.String(к.УникальныйИдентификатор())}]")
        print()
        итоги["ошибка"] += 1
        continue
    итоги[дозалить(т.Получить(0).С, c, None, прим, комментарий)] += 1

print("=== ИТОГ ===")
for к, v in итоги.items():
    print(f"  {к}: {v}")
