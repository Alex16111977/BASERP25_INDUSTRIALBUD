"""Чому регресія балансу впала після наших 2 РКО? Чи змінили перепроведення РКО рухи ПАП?"""
import sys, io
from datetime import datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

# 1) Σ ПАП(ОТ) per Регистратор для НАШИХ 2 РКО
for номер in ["000Ц-000284", "000Ц-000175"]:
    qD = conn.NewObject("Запрос")
    qD.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Д ИЗ Документ.РасходныйКассовыйОрдер КАК Д ГДЕ Д.Номер = &Н"
    qD.УстановитьПараметр("Н", номер)
    rD = qD.Выполнить().Выбрать(); rD.Следующий()
    ref = rD.Д

    # ВСІ рухи ПАП для цього РКО
    qP = conn.NewObject("Запрос")
    qP.Текст = """
    ВЫБРАТЬ П.ВидДвижения КАК ВД, П.Сумма КАК Сум, П.Статья КАК Стаття, П.Источник КАК Ист, П.Подразделение КАК Подр
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
    ГДЕ П.Регистратор = &Док
    УПОРЯДОЧИТЬ ПО П.Период
    """
    qP.УстановитьПараметр("Док", ref)
    rP = qP.Выполнить().Выгрузить()
    print(f"\n[РКО {номер}] Рухи ПАП ({rP.Количество()} шт):")
    for i in range(rP.Количество()):
        rec = rP.Получить(i)
        print(f"  {S(rec.ВД):>8} {rec.Сум:>12,.2f} | Стаття={S(rec.Стаття):30} | Ист={S(rec.Ист):30} | Подр={S(rec.Подр)}")

# 2) Σ ПАП по організації за дек+янв (для нас)
print(f"\n[Σ ПАП per Орг+Стаття за дек+янв]")
