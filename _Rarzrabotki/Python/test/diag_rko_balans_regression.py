qS.УстановитьПараметр("Орг", ORG); qS.УстановитьПараметр("ОТ", ОТ)
rS = qS.Выполнить().Выгрузить()
for i in range(rS.Количество()):
    rec = rS.Получить(i)
    print(f"  {rec.Місяць.strftime('%Y-%m')}: Σ={rec.Σ_signed:>+14,.2f}")

