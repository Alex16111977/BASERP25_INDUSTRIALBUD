import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Реквизит А_Подразделение у СтруктураПредприятия
sp = erp.Метаданные.Справочники.СтруктураПредприятия
print("=== Справочник.СтруктураПредприятия реквизиты (фильтр А_) ===")
for a in sp.Реквизиты:
    if a.Имя.startswith("А_") or "одразд" in a.Имя:
        print("  РЕКВ:", a.Имя, "|", a.Тип)

# Пример: для подразделения 'Глобино-2' что в А_Подразделение
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 12
    П.Наименование КАК Наим,
    П.Родитель.Наименование КАК Род,
    П.А_НаправлениеДеятельности КАК АНД,
    П.А_ЭтоПодразделениеНаправление КАК ЭПН
ИЗ Справочник.СтруктураПредприятия КАК П
ГДЕ П.ПометкаУдаления = ЛОЖЬ И П.Родитель = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
"""
try:
    r=q.Execute().Выгрузить()
    print("\n=== Корневые подразделения (Родитель пуст) — это корни структуры ===")
    for i in range(r.Количество()):
        s=r.Получить(i)
        анд=str(s.АНД.Наименование) if (s.АНД is not None and hasattr(s.АНД,'Пустая') and not s.АНД.Пустая()) else "(пусто)"
        print(f"  {str(s.Наим)[:34]:<34} А_НапрД={анд[:24]:<24} ЭтоПодрНаправление={s.ЭПН}")
except Exception as e:
    info=getattr(e,'excepinfo',None)
    print("FAIL:", info[2] if info else e)
