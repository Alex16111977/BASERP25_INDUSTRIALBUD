# -*- coding: utf-8 -*-
"""Pretest (Rule #-1): zup_2 Общий + Форма1(источник) → Форма2=Общий−Форма1 + корень подразделения.

ФОРМУЛА «Общего» (подтверждена пользователем 2026-06-02):
    Общий(ФЛ) = ВзаиморасчетыСРаботниками.Остатки(КонецДня(ДатаОстатков)).СуммаУпрОстаток
              + Σ(Начисления.Результат − Удержания.Результат_ВСЕ) за месяц(ДатаОстатков)
                из Документ.НачислениеЗарплатыРаботникам (проведённые), как в А_ОтражениеЗПпоКазне.
Смысл: управленческое сальдо МИНУС свежее начисление месяца = начальная (перенесённая) задолженность.
Эталон Буша (30.11.2025): сальдо=−35153,00, NET ноября=52000−16940=35060,00 → Общий=−93,00,
    Форма1=0,01, Форма2=−93,01, корень=Строительство."""
import sys
import win32com.client
sys.stdout.reconfigure(encoding="utf-8")
v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="SQLSERVER";Ref="zup_2";Usr="cfo";Pwd="2442"')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
EZ = erp.ЗначениеЗаполнено
УпрОрг = erp.А_Привилегированный.А_ПолучитьОрганизациюУпр()

def номер_дока(номер):
    q = erp.NewObject("Запрос"); q.УстановитьПараметр("Н", номер)
    q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.НачальнаяЗадолженностьПоЗарплате ГДЕ Номер = &Н"
    в = q.Выполнить().Выбрать()
    return в.С if в.Следующий() else None

ДОК_БУХ = номер_дока("000Ц-000001")   # источник Форма1
assert ДОК_БУХ is not None, "Не найден док-источник 000Ц-000001"

# === zup_2 составляющая 1: сальдо ВзаиморасчетыСРаботниками на КонецДня(30.11) per ФЛ ===
qb = zup.NewObject("Запрос")
qb.Текст = """ВЫБРАТЬ О.Физлицо.КодПоДРФО КАК ДРФО, О.Физлицо.Наименование КАК ИмяФЛ,
    СУММА(О.СуммаУпрОстаток) КАК Сальдо
ИЗ РегистрНакопления.ВзаиморасчетыСРаботниками.Остатки(КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2025,11,30),ДЕНЬ),) КАК О
СГРУППИРОВАТЬ ПО О.Физлицо.КодПоДРФО, О.Физлицо.Наименование"""
сальдо = {}; имена = {}
в = qb.Выполнить().Выбрать()
while в.Следующий():
    д = (в.ДРФО or "").strip()
    if д:
        сальдо[д] = сальдо.get(д, 0.0) + float(в.Сальдо or 0); имена[д] = в.ИмяФЛ

# === zup_2 составляющая 2: NET месяца = Σ(Начислено − Удержано_все) ноября per ФЛ ===
qn = zup.NewObject("Запрос")
qn.Текст = """ВЫБРАТЬ Т.ДРФО КАК ДРФО, МАКСИМУМ(Т.Имя) КАК ИмяФЛ, СУММА(Т.Сумма) КАК NET ИЗ (
    ВЫБРАТЬ Н.Физлицо.КодПоДРФО КАК ДРФО, Н.Физлицо.Наименование КАК Имя, Н.Результат КАК Сумма
    ИЗ Документ.НачислениеЗарплатыРаботникам.Начисления КАК Н
    ГДЕ Н.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025,11,1) И КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2025,11,1),МЕСЯЦ) И Н.Ссылка.Проведен
    ОБЪЕДИНИТЬ ВСЕ
    ВЫБРАТЬ У.Физлицо.КодПоДРФО, У.Физлицо.Наименование, -У.Результат
    ИЗ Документ.НачислениеЗарплатыРаботникам.Удержания КАК У
    ГДЕ У.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025,11,1) И КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2025,11,1),МЕСЯЦ) И У.Ссылка.Проведен
) КАК Т СГРУППИРОВАТЬ ПО Т.ДРФО"""
нет = {}
в = qn.Выполнить().Выбрать()
while в.Следующий():
    д = (в.ДРФО or "").strip()
    if д:
        нет[д] = float(в.NET or 0); имена.setdefault(д, в.ИмяФЛ)

# === Общий = сальдо + NET ===
общий = {}
for д in set(list(сальдо) + list(нет)):
    общий[д] = round(сальдо.get(д, 0.0) + нет.get(д, 0.0), 2)

строк = 0; матч_фл = 0; матч_сотр = 0; матч_подр = 0; буша = None
for дрфо, об in общий.items():
    if abs(об) < 0.005:
        continue
    строк += 1
    фл = erp.Справочники.ФизическиеЛица.НайтиПоРеквизиту("КодПоДРФО", дрфо) if дрфо else None
    if not (фл and EZ(фл)):
        continue
    матч_фл += 1
    # Форма1 из дока-источника
    qf = erp.NewObject("Запрос"); qf.УстановитьПараметр("Док", ДОК_БУХ); qf.УстановитьПараметр("ФЛ", фл)
    qf.Текст = """ВЫБРАТЬ СУММА(Т.Сумма) КАК Сумма ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате КАК Т
    ГДЕ Т.Ссылка = &Док И Т.Сотрудник.ФизическоеЛицо = &ФЛ
        И (Т.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ИЛИ Т.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.ПустаяСсылка))"""
    вф = qf.Выполнить().Выбрать(); вф.Следующий()
    форма1 = float(вф.Сумма) if вф.Сумма is not None else 0.0
    форма2 = round(об - форма1, 2)
    # Сотрудник
    qs = erp.NewObject("Запрос"); qs.УстановитьПараметр("ФЛ", фл); qs.УстановитьПараметр("Орг", УпрОрг)
    qs.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК С ИЗ Справочник.Сотрудники КАК С
    ГДЕ С.ФизическоеЛицо = &ФЛ И НЕ С.ПометкаУдаления
    УПОРЯДОЧИТЬ ПО ВЫБОР КОГДА С.ГоловнаяОрганизация = &Орг ТОГДА 0 ИНАЧЕ 1 КОНЕЦ, С.Код"""
    if not qs.Выполнить().Пустой():
        матч_сотр += 1
    # Подразделение: первая касса с 01.12.2025 → корень
    qp = erp.NewObject("Запрос"); qp.УстановитьПараметр("ФЛ", фл)
    qp.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Рш.Подразделение КАК Подр
    ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу КАК Вед ПО Вед.Ссылка = Рш.Ссылка
    ГДЕ Рш.ФизическоеЛицо = &ФЛ И Вед.Дата >= ДАТАВРЕМЯ(2025,12,1) И Вед.Проведен
    УПОРЯДОЧИТЬ ПО Вед.Дата"""
    впр = qp.Выполнить().Выбрать()
    корень = None
    if впр.Следующий() and EZ(впр.Подр):
        стрп = впр.Подр.А_Подразделение
        корень = стрп
        while корень is not None and EZ(корень) and EZ(корень.Родитель):
            корень = корень.Родитель
    if корень is not None and EZ(корень):
        матч_подр += 1
    if "Буша" in (имена.get(дрфо) or ""):
        буша = (об, форма1, форма2, корень.Наименование if (корень and EZ(корень)) else "FALLBACK")

print(f"Строк Общий<>0: {строк} | ФЛ-матч: {матч_фл} | Сотр: {матч_сотр} | Подр(касса): {матч_подр}")
print(f"Буша (Общий, Форма1, Форма2, корень): {буша}")
assert буша is not None, "Буша не найден"
assert abs(буша[0] - (-93.00)) < 0.005, f"Общий != -93.00: {буша[0]}"
assert abs(буша[1] - 0.01) < 0.005, f"Форма1 != 0.01: {буша[1]}"
assert abs(буша[2] - (-93.01)) < 0.005, f"Форма2 != -93.01: {буша[2]}"
assert буша[3] == "Строительство", f"корень != Строительство: {буша[3]}"
print("\nOK pretest: Общий=Сальдо+NET, Форма2=Общий−Форма1 и корень подразделения подтверждены на Буше")
