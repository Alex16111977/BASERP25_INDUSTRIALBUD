"""Диагностика: как хранится вариант отчёта 'Глобино' в Справочник.ВариантыОтчетов.
Ключевое: ТипОтчета (Внутренний/Дополнительный/Внешний/Расширение), Предопределённый,
Пользовательский, к какому Отчёту привязан, Автор. Это объяснит откат настроек.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import pythoncom, win32com.client

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    ВО.Ссылка КАК Ссылка,
    ВО.Наименование КАК Наименование,
    ВО.КлючВарианта КАК КлючВарианта,
    ВО.Предопределенный КАК Предопределенный,
    ВО.Пользовательский КАК Пользовательский,
    ВО.ПометкаУдаления КАК ПометкаУдаления,
    ПРЕДСТАВЛЕНИЕ(ВО.ТипОтчета) КАК ТипОтчета,
    ПРЕДСТАВЛЕНИЕ(ВО.Отчет) КАК ОтчетПредст,
    ПРЕДСТАВЛЕНИЕ(ВО.Автор) КАК Автор,
    ПРЕДСТАВЛЕНИЕ(ВО.ПредопределенныйВариант) КАК ПредопВариант
ИЗ
    Справочник.ВариантыОтчетов КАК ВО
ГДЕ
    ВО.Наименование ПОДОБНО "%лобино%"
"""
sel = q.Выполнить().Выбрать()
print("=== Варианты 'Глобино' ===")
n = 0
while sel.Следующий():
    n += 1
    print(f"[{n}] Наим='{sel.Наименование}'  Ключ='{sel.КлючВарианта}'")
    print(f"    ТипОтчета={sel.ТипОтчета}  Отчет='{sel.ОтчетПредст}'")
    print(f"    Предопределённый={sel.Предопределенный}  Пользовательский={sel.Пользовательский}  ПометкаУдал={sel.ПометкаУдаления}")
    print(f"    Автор='{sel.Автор}'  ПредопВариант='{sel.ПредопВариант}'")
    # размер сохранённых настроек
    об = sel.Ссылка.ПолучитьОбъект()
    есть = erp.ЗначениеЗаполнено(об.Настройки)
    print(f"    Настройки сохранены (Хранилище заполнено)={есть}")
print(f"\nвсего: {n}")

# Сколько всего вариантов у отчёта ВедомостьРасчетовСПартнерами (по строке-идентификатору и по типам)
print("\n=== Все варианты, привязанные к 'Сводная ведомость расчетов' / ВедомостьРасчетовСПартнерами ===")
