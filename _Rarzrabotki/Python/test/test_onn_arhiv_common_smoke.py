import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from onn_arhiv_common import (подключиться, выполнить, строки, uuid_ссылки,
                              пустая, ссылка_архива, порядок_по_иерархии,
                              NULL_UUID, РЕКВИЗИТЫ)

провалов = 0


def проверить(условие, описание):
    global провалов
    print(("PASS: " if условие else "FAIL: ") + описание)
    if not условие:
        провалов += 1


conn = подключиться()
проверить(True, "соединение с bas_industrialbud установлено")

тз = выполнить(conn, """
ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссылка, Т.Код КАК Код, Т.Родитель КАК Родитель
ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК Т
УПОРЯДОЧИТЬ ПО Т.Код
""")
список = строки(тз)
проверить(len(список) == 1, f"запрос вернул 1 строку (получено {len(список)})")

образец = список[0]
uid = uuid_ссылки(conn, образец.Ссылка)
проверить(uid is not None and uid != NULL_UUID, f"UUID образца получен: {uid}")
проверить(пустая(conn, образец.Родитель), "пустой Родитель распознан как пустой")
проверить(uuid_ссылки(conn, образец.Код) is None, "строка не принимается за ссылку")

арх = ссылка_архива(conn, uid)
проверить(uuid_ссылки(conn, арх) == uid, "ссылка архива построена с тем же UUID")

тз2 = выполнить(conn, """
ВЫБРАТЬ Т.Ссылка КАК Ссылка, Т.Код КАК Код, Т.Родитель КАК Родитель
ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК Т
ГДЕ Т.Код = &Код
""", Код=образец.Код)
проверить(len(строки(тз2)) == 1, "УстановитьПараметр работает")

упорядочено = порядок_по_иерархии(conn, строки(выполнить(conn, """
ВЫБРАТЬ Т.Ссылка КАК Ссылка, Т.Код КАК Код, Т.Родитель КАК Родитель
ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК Т
""")))
проверить(len(упорядочено) == 322, f"иерархия упорядочена, элементов {len(упорядочено)}")

conn.BeginTransaction()
conn.RollbackTransaction()
проверить(True, "BeginTransaction/RollbackTransaction резолвятся")

проверить(len(РЕКВИЗИТЫ) == 5, "список копируемых реквизитов = 5")

print(f"\nИТОГ: провалов {провалов}")
sys.exit(1 if провалов else 0)
