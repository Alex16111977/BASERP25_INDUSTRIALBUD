# -*- coding: utf-8 -*-
"""Discovery — связь между ПАП(статья=Расходы текущего периода) и ДвиженияДоходыРасходыПрочиеАктивыПассивы
через Регистратор. Проверим, что:
1. Все Регистраторы из ПАП имеют движения в ДвДохРасх с реальной статьёй СтатьиРасходов
2. Σ ПАП(Подр, Регистратор, Статья=Расх.тек.пер.) == Σ ДвДохРасх(Подр, Регистратор, Статья=РеальСтатьиРасх)?
3. Аналитика1 = ПРЕДСТАВЛЕНИЕ(ДвДохРасх.Статья) — это то что нужно user'у
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
S = erp.String

NM = datetime(2026, 4, 1, 0, 0, 0)
KM = datetime(2026, 4, 30, 23, 59, 59)

print("=" * 90)
print("ТЕСТ 1: По одному Регистратору сравним ПАП и ДвДохРасх — РКО строительство 5000")
print("=" * 90)
# Берём первый РКО из апреля который имеет движение по ПАП "Расходы текущего периода" в Глобино-2
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", erp.Справочники.Организации.НайтиПоНаименованию("ТОВ ІНДАСТРІАЛБУД"))
q.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 5
    ПАП.Регистратор,
    ТИПЗНАЧЕНИЯ(ПАП.Регистратор) КАК ТипРег,
    ПАП.Подразделение,
    ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК ПодрПред,
    ПАП.Источник,
    ПРЕДСТАВЛЕНИЕ(ПАП.Источник) КАК ИстПред,
    ПАП.Сумма,
    ПАП.ВидДвижения
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Организация = &Орг
    И ПАП.Период >= ДАТАВРЕМЯ(2026,4,1,0,0,0)
    И ПАП.Период <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
    И ПАП.Статья = &СтРасх
"""
r = q.Execute().Выгрузить()
print(f"Регистраторов в апреле: {r.Количество()}")
for i in range(r.Количество()):
    row = r.Получить(i)
    reg = row.Регистратор
    print(f"\n--- Регистратор: {S(reg)} ---")
    print(f"    ПАП: Подр={S(row.ПодрПред)} | Ист={S(row.ИстПред)} | {row.ВидДвижения}{row.Сумма}")

    # Запрос к ДвиженияДоходыРасходыПрочиеАктивыПассивы по тому же регистратору
    q2 = erp.NewObject("Запрос")
    q2.УстановитьПараметр("Рег", reg)
    q2.Text = """
    ВЫБРАТЬ
        Д.Период,
        Д.Подразделение,
        ПРЕДСТАВЛЕНИЕ(Д.Подразделение) КАК ПодрПред,
        Д.НаправлениеДеятельности,
        Д.Статья,
        ПРЕДСТАВЛЕНИЕ(Д.Статья) КАК СтатьяПред,
        ТИПЗНАЧЕНИЯ(Д.Статья) КАК ТипСтатьи,
        Д.АналитикаДоходов,
        ПРЕДСТАВЛЕНИЕ(Д.АналитикаДоходов) КАК АнДохПред,
        Д.АналитикаРасходов,
        ПРЕДСТАВЛЕНИЕ(Д.АналитикаРасходов) КАК АнРасхПред,
        Д.АналитикаАктивовПассивов,
        ПРЕДСТАВЛЕНИЕ(Д.АналитикаАктивовПассивов) КАК АнАПпред,
        Д.ХозяйственнаяОперация,
        Д.ВидДвижения,
        Д.Сумма
    ИЗ
        РегистрНакопления.ДвиженияДоходыРасходыПрочиеАктивыПассивы КАК Д
    ГДЕ Д.Регистратор = &Рег
    """
    r2 = q2.Execute().Выгрузить()
    print(f"    ДвДохРасх — движений: {r2.Количество()}")
    for j in range(r2.Количество()):
        row2 = r2.Получить(j)
        print(f"      {row2.ВидДвижения}{row2.Сумма:>12.2f} | Подр={S(row2.ПодрПред):<22} | ХОп={S(row2.ХозяйственнаяОперация):<30} | Тип={S(row2.ТипСтатьи):<60} | Статья={S(row2.СтатьяПред)}")

print()
print("=" * 90)
print("ТЕСТ 2: Σ по Подразделению ДвДохРасх vs ПАП за апрель 2026 для статьи Расходы текущего периода")
print("=" * 90)
# Сначала ПАП за апрель — нетто-движения (без учёта остатков ОстаткиИОбороты)
print("ПАП (Источник IN ПрочиеРасходы/ПартииПрочихРасходов, статья=Расх.тек.пер.) — движения за апрель:")
q3 = erp.NewObject("Запрос")
q3.УстановитьПараметр("Орг", erp.Справочники.Организации.НайтиПоНаименованию("ТОВ ІНДАСТРІАЛБУД"))
q3.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
q3.УстановитьПараметр("СтДох", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Доходы текущего периода"))
q3.УстановитьПараметр("НМ", NM)
q3.УстановитьПараметр("КМ", KM)
q3.Text = """
ВЫБРАТЬ
    ПАП.Подразделение,
    ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК ПодрПред,
    ПРЕДСТАВЛЕНИЕ(ПАП.Статья) КАК СтатьяПред,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК signedΣ
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Организация = &Орг
    И ПАП.Период >= ДАТАВРЕМЯ(2026,4,1,0,0,0)
    И ПАП.Период <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
    И (ПАП.Статья = &СтРасх ИЛИ ПАП.Статья = &СтДох)
СГРУППИРОВАТЬ ПО ПАП.Подразделение, ПАП.Статья
"""
r = q3.Execute().Выгрузить()
print(f"  ПАП по Подр: {r.Количество()} строк")
pap_map = {}
for i in range(r.Количество()):
    row = r.Получить(i)
    key = (S(row.ПодрПред), S(row.СтатьяПред))
    pap_map[key] = float(row.signedΣ)

# ДвДохРасх за апрель — нетто
q4 = erp.NewObject("Запрос")
q4.УстановитьПараметр("Орг", erp.Справочники.Организации.НайтиПоНаименованию("ТОВ ІНДАСТРІАЛБУД"))
q4.УстановитьПараметр("НМ", NM)
q4.УстановитьПараметр("КМ", KM)
q4.Text = """
ВЫБРАТЬ
    Д.Подразделение,
    ПРЕДСТАВЛЕНИЕ(Д.Подразделение) КАК ПодрПред,
    ТИПЗНАЧЕНИЯ(Д.Статья) КАК ТипСтатьи,
    СУММА(ВЫБОР КОГДА Д.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Д.Сумма ИНАЧЕ -Д.Сумма КОНЕЦ) КАК signedΣ
ИЗ
    РегистрНакопления.ДвиженияДоходыРасходыПрочиеАктивыПассивы КАК Д
ГДЕ
    Д.Организация = &Орг
    И Д.Период >= ДАТАВРЕМЯ(2026,4,1,0,0,0)
    И Д.Период <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
СГРУППИРОВАТЬ ПО Д.Подразделение, ТИПЗНАЧЕНИЯ(Д.Статья)
"""
r = q4.Execute().Выгрузить()
print(f"\n  ДвДохРасх по Подр + ТипСтатьи: {r.Количество()} строк")
ddr_map = {}
for i in range(r.Количество()):
    row = r.Получить(i)
    key = (S(row.ПодрПред), S(row.ТипСтатьи))
    ddr_map[key] = float(row.signedΣ)
    print(f"    {S(row.ПодрПред):<25} | {S(row.ТипСтатьи):<60} | signedΣ={row.signedΣ:>15.2f}")

print()
print("Сверка: ПАП(СтатьяБалансовая)←→ДвДохРасх(СтатьяРеальная) — должны совпадать ПО ПОДРАЗДЕЛЕНИЮ:")
print(f"  ПАП Расходы тек.пер. строк: {sum(1 for k in pap_map if k[1]=='Расходы текущего периода')}")
print(f"  ДвДохРасх ПВХ.СтатьиРасходов строк: {sum(1 for k in ddr_map if 'СтатьиРасходов' in k[1])}")
