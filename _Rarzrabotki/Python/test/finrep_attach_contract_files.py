# Приєднання файлів договорів (C:\public\Договори) до договорів фінзвіту виробництва в BuhBud.
# Лише точні збіги (рішення користувача 04.10.2026): договір + всі ДУ, без ENG-дублікатів і чернеток.
# Запуск: python finrep_attach_contract_files.py          — пробний прогін
#         python finrep_attach_contract_files.py --apply  — запис через БСП РаботаСФайлами.ДобавитьФайл
import os
import sys
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
APPLY = "--apply" in sys.argv
R = r"C:\public\Договори"
S26 = R + r"\Договори з Субпідрядниками\Індепт Стіл\2026\ІНДАСТРІАЛБУД"
DN = R + r"\Договори з Замовниками\Індастріалбуд\2024\ДРУЖБА НОВА\№ 28_10_24 від 28.10.2024 р"

ЗІСТАВЛЕННЯ = [
    ("Договір підряду 20/01/26  Чорноморськ(наливна ест)", [S26 + r"\Дог№20_01_26 СТІЛ.pdf", S26 + r"\ДУ1 до дог 20_01_26 СТІЛ.pdf"]),
    ("Договір підряду  19/01/26-1 Естакада 3.1.5 Глоб", [S26 + r"\Дог№19_01_26-1 СТІЛ.pdf"]),
    ("Договір підряду  21/01/26  Каналізаційна нас Глоб", [S26 + r"\Дог№21_01_26 СТІЛ.pdf"]),
    ("Договір підряду  15/10/25 Глобине Пункт нав 4.2",
     [R + r"\Договори з Субпідрядниками\Індастріалбуд\2025\ІНДЕПТ СТІЛ\КМД\Дог№15 10 25 Ідепт Стіл .pdf"]),
    ("Договір підряду 06/04/26-МК Кривий РІГ", [S26 + r"\Дог№06_04_26-МК СТІЛ.pdf"]),
    ("Договір поставки № 28/10/24 від 28.10.24",
     [DN + r"\Дог №28_10_24 від 28.10.2024.pdf", DN + r"\ДУ №1 від 04.12. 2024 до Дог №28_10_24 від 28.10.2024.pdf",
      DN + r"\ДУ 2 Договір поставки 28 10 24 (ІБ vs Дружба Нова).pdf", DN + r"\ДУ 3 до Договору поставки 28 10 24 ІБvsДружбаНова.pdf"]),
    ("РАМКОВИЙ ДОГОВІР НА НАДАННЯ БУДІВЕЛЬНИХ ПОСЛУГ",
     [R + r"\Договори з Замовниками\Індастріалбуд\2023\ООН Модульні будинки\FA 2023-DEC-212_signed_by_Industrialbud_signed_UKR.pdf"]),
]

c = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
q = c.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Д.Ссылка КАК Ссылка, Д.Наименование КАК Наименование ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ Д.Наименование = &Н И НЕ Д.ПометкаУдаления"""
qf = c.NewObject("Запрос")
qf.Text = """ВЫБРАТЬ Ф.Наименование КАК Наименование ИЗ Справочник.ДоговорыКонтрагентовПрисоединенныеФайлы КАК Ф
ГДЕ Ф.ВладелецФайла = &В И НЕ Ф.ПометкаУдаления"""
автор = c.Справочники.Пользователи.НайтиПоНаименованию("cfo")
помилок = додано = пропущено = 0
for назва, файли in ЗІСТАВЛЕННЯ:
    q.SetParameter("Н", назва)
    вибірка = q.Execute().Выгрузить()
    if вибірка.Количество() != 1:
        print("ПОМИЛКА: договорів з назвою", назва, "—", вибірка.Количество()); помилок += 1; continue
    договір = вибірка[0].Ссылка
    qf.SetParameter("В", договір)
    є = {r.Наименование.strip() for r in qf.Execute().Выгрузить()}
    print("==", назва)
    for шлях in файли:
        імя, розш = os.path.splitext(os.path.basename(шлях))
        if not os.path.isfile(шлях):
            print("   НЕМАЄ ФАЙЛУ:", шлях); помилок += 1; continue
        if імя.strip() in є:
            print("   вже приєднано:", імя); пропущено += 1; continue
        print("   +", імя + розш, os.path.getsize(шлях), "байт")
        if APPLY:
            дд = c.NewObject("ДвоичныеДанные", шлях)
            адреса = c.ПоместитьВоВременноеХранилище(дд)
            п = c.NewObject("Структура")
            п.Вставить("Автор", автор)
            п.Вставить("ВладелецФайлов", договір)
            п.Вставить("ИмяБезРасширения", імя.strip())
            п.Вставить("РасширениеБезТочки", розш.lstrip(".").lower())
            п.Вставить("ВремяИзмененияУниверсальное", c.ТекущаяУниверсальнаяДата())
            c.РаботаСФайлами.ДобавитьФайл(п, адреса)
        додано += 1
print(("ЗАПИСАНО" if APPLY else "ПРОБНИЙ ПРОГІН"), "| додати:", додано, "| вже є:", пропущено, "| помилок:", помилок)
