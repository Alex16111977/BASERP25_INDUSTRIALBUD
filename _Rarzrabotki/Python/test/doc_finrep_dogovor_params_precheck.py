# -*- coding: utf-8 -*-
"""Rule #-1: запрос параметров договоров для нового движка (1:1 как в BSL).

Движок после удаления ТЧ-реквизитов читает параметры расчёта из договора:
А_СуммаСоглашения, А_СуммаДЦ, А_ОбъектПримечание, А_ПроцентГарантийногоУдержания,
А_ВариантФормулыИтога. K считается на строке договора и суммируется в подразделение.
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String

# пара реальных договоров: Кривой Рог (параметры заполнены) + Глобино
q0 = buh.NewObject("Запрос")
q0.Text = """
ВЫБРАТЬ ПЕРВЫЕ 5 Д.Ссылка КАК Ссылка
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ Д.Наименование ПОДОБНО "Договір підряду%" И НЕ Д.ПометкаУдаления
"""
refs = q0.Execute().Выгрузить()
массив = buh.NewObject("Массив")
for i in range(refs.Количество()):
    массив.Добавить(refs.Получить(i).Ссылка)

q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	Д.Ссылка КАК Договор,
	Д.А_СуммаСоглашения КАК СуммаСоглашения,
	Д.А_СуммаДЦ КАК СуммаДЦ,
	Д.А_ОбъектПримечание КАК Примечание,
	Д.А_ПроцентГарантийногоУдержания КАК ПроцентУдержания,
	Д.А_ВариантФормулыИтога КАК ВариантФормулы
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	Д.Ссылка В (&Договоры)
"""
q.УстановитьПараметр("Договоры", массив)
try:
    r = q.Execute().Выгрузить()
    print(f"OK, рядків={r.Количество()}")
    for i in range(r.Количество()):
        row = r.Получить(i)
        print(f"  {S(row.Договор)[:50]} | СумСогл={row.СуммаСоглашения} | %={row.ПроцентУдержания}"
              f" | Прим='{S(row.Примечание)[:30]}'")
except Exception as e:
    print(f"FAIL: {e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e}")
    sys.exit(1)

# сравнение варианта формулы с перечислением (по ссылке, не по строке)
en = buh.Перечисления.А_ВариантыФормулыИтогаФинотчета
print(f"\nПеречисление доступно: ЗадолженностьПлюсАкты={S(buh.XMLСтрока(en.ЗадолженностьПлюсАкты))!r}")
print("OK")
