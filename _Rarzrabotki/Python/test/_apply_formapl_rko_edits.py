# -*- coding: utf-8 -*-
"""Атомарно вносит ФормаPL в проведение РКО → движения ПрочиеРасходы (правило: ОргБух заполнен→Ф1, пусто→Ф2).
3 правки. count==1 на каждый anchor, иначе НИЧЕГО не пишем. Бэкап. Сохранение BOM."""
import io, os, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

P = r"C:\Configuration_downloads\BASERP25\Documents\РасходныйКассовыйОрдер\Ext\ManagerModule.bsl"
raw = open(P, "rb").read()
has_bom = raw[:3] == b'\xef\xbb\xbf'
T = raw.decode("utf-8-sig")
crlf = "\r\n" in T
if crlf:
    T = T.replace("\r\n", "\n")   # нормализуем для редактирования (anchor'ы с \n)

EDITS = [
 # 1. Запрос реквизитов (ЗаполнитьПараметрыИнициализации): вычисляемая колонка ФормаPL → авто-параметр &ФормаPL
 ("1 Реквизиты: колонка ФормаPL",
  "КАК Проведен\n\t|\n\t|ИЗ\n\t|\tДокумент.РасходныйКассовыйОрдер КАК ДанныеДокумента",
  "КАК Проведен,\n"
  "\t|\tВЫБОР\n"
  "\t|\t\tКОГДА ДанныеДокумента.А_ОрганизацияБухгалтерия <> ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка)\n"
  "\t|\t\t\tТОГДА ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1)\n"
  "\t|\t\tИНАЧЕ ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2)\n"
  "\t|\tКОНЕЦ КАК ФормаPL\n"
  "\t|\n\t|ИЗ\n\t|\tДокумент.РасходныйКассовыйОрдер КАК ДанныеДокумента"),
 # 2. ВтИсходныеПрочиеРасходы: добавить &ФормаPL КАК ФормаPL
 ("2 ВтИсходныеПрочиеРасходы: &ФормаPL",
  "\t|\tНЕОПРЕДЕЛЕНО КАК АналитикаУчетаНоменклатуры\n\t|\n\t|ПОМЕСТИТЬ ВтИсходныеПрочиеРасходы",
  "\t|\tНЕОПРЕДЕЛЕНО КАК АналитикаУчетаНоменклатуры,\n\t|\t&ФормаPL КАК ФормаPL\n\t|\n\t|ПОМЕСТИТЬ ВтИсходныеПрочиеРасходы"),
 # 3a. Хелпер ПрочиеРасходы → "ФормаPL"
 ("3a helper ПрочиеРасходы",
  'РегистрыНакопления.ПрочиеРасходы.ТекстЗапросаТаблицаПрочиеРасходы();',
  'РегистрыНакопления.ПрочиеРасходы.ТекстЗапросаТаблицаПрочиеРасходы("ФормаPL");'),
 # 3b. Хелпер ВтПрочиеРасходы → "ФормаPL"
 ("3b helper ВтПрочиеРасходы",
  'РегистрыНакопления.ПрочиеРасходы.ТекстЗапросаТаблицаВтПрочиеРасходы();',
  'РегистрыНакопления.ПрочиеРасходы.ТекстЗапросаТаблицаВтПрочиеРасходы("ФормаPL");'),
]

ok = True
for name, old, new in EDITS:
    c = T.count(old)
    print(f"{'OK ' if c==1 else 'FAIL'} [{c}] {name}")
    if c != 1: ok = False
if not ok:
    print("\n❌ anchor != 1 — файл НЕ изменён."); sys.exit(1)

def to_bytes(text):
    out = (text.replace("\n", "\r\n") if crlf else text)
    b = out.encode("utf-8")
    return (b'\xef\xbb\xbf' + b) if has_bom else b

bak = P + ".bak_formapl"
if not os.path.exists(bak):
    open(bak, "wb").write(to_bytes(T))
    print(f"\nБэкап: {bak}")

for name, old, new in EDITS:
    T = T.replace(old, new, 1)
open(P, "wb").write(to_bytes(T))
print(f"\n✅ Применено правок: {len(EDITS)}. BOM={'да' if has_bom else 'нет'}, CRLF={'да' if crlf else 'нет'}. Вхождений 'ФормаPL': {T.count('ФормаPL')}")
