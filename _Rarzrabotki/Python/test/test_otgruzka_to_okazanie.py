"""
Тест процедури СоздатьДокументОказанияУслугМеждуПодразделениямиПоОтгрузкаПродукции().

Сценарій:
1. Знайти документ "Отгрузка продукции 000001202 от 06.04.2026 16:35:53"
2. Якщо вже проведений — зняти проведення
3. Якщо Організація порожня — підставити "ТОВ ІНДАСТРІАЛБУД"
4. Поставити А_НачислятьУслуги = Істина
5. Провести документ → платформа викличе нашу нову процедуру
6. Перечитати документ і перевірити що ДокОказаниеУслугМеждуПодразделениями заповнений
7. Завантажити підлеглий А_ОказаниеУслугМеждуПодразделениями і перевірити шапку + ТЧ Услуги
8. Перевірити що створились підлеглі Реализация + Приобретение
"""

import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
    S = erp.String  # хелпер для коректного відображення COM-посилань

    print("=" * 70)
    print("ТЕСТ: А_ОтгрузкаПродукции → А_ОказаниеУслугМеждуПодразделениями")
    print("=" * 70)

    # === 1. Знайти тестовий документ ===
    запит = erp.NewObject("Запрос")
    запит.УстановитьПараметр("Номер", "000001202")
    запит.Текст = """
    ВЫБРАТЬ ОП.Ссылка КАК Ссылка
    ИЗ Документ.А_ОтгрузкаПродукции КАК ОП
    ГДЕ ОП.Номер = &Номер
    """
    результат = запит.Выполнить().Выгрузить()
    if результат.Количество() == 0:
        print("FAIL: документ 000001202 не знайдено")
        sys.exit(1)
    ссылка_отгрузки = результат[0].Ссылка
    print(f"\n[1] Знайдено: {S(ссылка_отгрузки)}")

    obj = ссылка_отгрузки.ПолучитьОбъект()
    print(f"   Подразделение (Цех):       {S(obj.Подразделение)}")
    print(f"   ПодразделениеРасхода:       {S(obj.ПодразделениеРасхода)}")
    print(f"   СтатьяДенежныхСредств:      {S(obj.СтатьяДенежныхСредств)}")
    print(f"   Организация (до):           '{S(obj.Организация)}' (заповнена={erp.ЗначениеЗаполнено(obj.Организация)})")
    print(f"   СтороннийЗаказчик:          {bool(obj.СтороннийЗаказчик)}")
    print(f"   А_НачислятьУслуги (до):      {bool(obj.А_НачислятьУслуги)}")
    print(f"   Проведен (до):               {bool(ссылка_отгрузки.Проведен)}")
    print(f"   Состав строк:                {obj.Состав.Количество()}")
    for i in range(obj.Состав.Количество()):
        стр = obj.Состав[i]
        print(f"     {i+1}. {S(стр.Номенклатура)} | Сумма={стр.Сумма} | '{стр.Примечание}'")

    # === 2. Зняти проведення (якщо проведений) ===
    if ссылка_отгрузки.Проведен:
        print("\n[2] Знімаю проведення...")
        obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
        obj = ссылка_отгрузки.ПолучитьОбъект()

    # === 3. Заповнити Організацію якщо порожня ===
    if not erp.ЗначениеЗаполнено(obj.Организация):
        org = erp.Справочники.Организации.НайтиПоНаименованию("ТОВ \"ІНДАСТРІАЛБУД\"")
        if not erp.ЗначениеЗаполнено(org):
            print("FAIL: Організація 'ТОВ ІНДАСТРІАЛБУД' не знайдена")
            sys.exit(2)
        obj.Организация = org
        print(f"\n[3] Підставлено Організацію: {S(org)}")

    # === 4. Поставити галочку А_НачислятьУслуги і провести ===
    print("\n[4] А_НачислятьУслуги=True + Провести...")
    obj.А_НачислятьУслуги = True
    try:
        obj.Записать(erp.РежимЗаписиДокумента.Проведение)
        print("   OK: проведено успішно")
    except Exception as e:
        info = getattr(e, 'excepinfo', None)
        msg = info[2] if info else str(e)
        print(f"   FAIL: {msg}")
        sys.exit(3)

    # === 5. Перечитати + знайти створений підлеглий ===
    obj2 = ссылка_отгрузки.ПолучитьОбъект()
    print(f"\n[5] Стан після проведення:")
    print(f"   Проведен:                            {bool(ссылка_отгрузки.Проведен)}")
    print(f"   А_НачислятьУслуги:                    {bool(obj2.А_НачислятьУслуги)}")
    print(f"   А_Обработан:                          {bool(obj2.А_Обработан)}")

    ссылка_оказание = obj2.ДокОказаниеУслугМеждуПодразделениями
    if not erp.ЗначениеЗаполнено(ссылка_оказание):
        # fallback: пошук через запит
        q = erp.NewObject("Запрос")
        q.УстановитьПараметр("Источник", ссылка_отгрузки)
        q.Текст = """
        ВЫБРАТЬ А.Ссылка КАК Ссылка
        ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями КАК А
        ГДЕ А.ОтгрузкаПродукции = &Источник И НЕ А.ПометкаУдаления
        """
        р = q.Выполнить().Выгрузить()
        if р.Количество() == 0:
            print("   FAIL: А_ОказаниеУслугМеждуПодразделениями не створено")
            sys.exit(4)
        ссылка_оказание = р[0].Ссылка
    print(f"   ДокОказаниеУслугМеждуПодразделениями: {S(ссылка_оказание)}")

    # === 6. Шапка створеного А_ОказаниеУслуг ===
    print("\n[6] Шапка А_ОказаниеУслугМеждуПодразделениями:")
    док = ссылка_оказание.ПолучитьОбъект()
    print(f"   Дата:               {док.Дата}")
    print(f"   Организация:        {S(док.Организация)}")
    print(f"   ОтгрузкаПродукции:  {S(док.ОтгрузкаПродукции)}")
    print(f"   А_Обработан:        {bool(док.А_Обработан)}")
    print(f"   А_ВведенВЕРП:       {bool(док.А_ВведенВЕРП)}")
    print(f"   СуммаДокумента:     {док.СуммаДокумента}")
    print(f"   Комментарий:        {док.Комментарий}")
    print(f"   Проведен:           {bool(ссылка_оказание.Проведен)}")

    # === 7. ТЧ Услуги ===
    print(f"\n[7] ТЧ Услуги (рядків: {док.Услуги.Количество()}):")
    for i in range(док.Услуги.Количество()):
        у = док.Услуги[i]
        print(f"   {i+1}.")
        print(f"      ПодразделениеПродавец   = {S(у.ПодразделениеПродавец)}")
        print(f"      ПодразделениеПокупатель = {S(у.ПодразделениеПокупатель)}")
        print(f"      Номенклатура            = {S(у.Номенклатура)}")
        print(f"      СтатьяЗатрат            = {S(у.СтатьяЗатрат)}")
        print(f"      СДД Продавец            = {S(у.СтатьяДвиженияДенежныхСредствПродавец)}")
        print(f"      СДД Покупатель          = {S(у.СтатьяДвиженияДенежныхСредствПокупатель)}")
        print(f"      ФормаОплаты             = {S(у.ФормаОплаты)}")
        print(f"      Сумма                   = {у.Сумма}")
        print(f"      КодСтроки               = {у.КодСтроки}")
        print(f"      Комментарий             = '{у.Комментарий}'")

    # === 8. Підлеглі Реализация / Приобретение ===
    print("\n[8] Підлеглі Реализация / Приобретение:")
    запит3 = erp.NewObject("Запрос")
    запит3.УстановитьПараметр("Источник", ссылка_оказание)
    запит3.Текст = """
    ВЫБРАТЬ
        Реал.Ссылка КАК Ссылка,
        Реал.Дата КАК Дата,
        Реал.Номер КАК Номер,
        Реал.Проведен КАК Проведен,
        Реал.СуммаДокумента КАК Сумма,
        "Реализация" КАК Тип
    ИЗ Документ.РеализацияТоваровУслуг КАК Реал
    ГДЕ Реал.А_ОказаниеУслугМеждуПодразделениями = &Источник
    ОБЪЕДИНИТЬ ВСЕ
    ВЫБРАТЬ
        Прио.Ссылка, Прио.Дата, Прио.Номер, Прио.Проведен, Прио.СуммаДокумента, "Приобретение"
    ИЗ Документ.ПриобретениеТоваровУслуг КАК Прио
    ГДЕ Прио.А_ОказаниеУслугМеждуПодразделениями = &Источник
    """
    результат3 = запит3.Выполнить().Выгрузить()
    if результат3.Количество() == 0:
        print("   ⚠ Реализация/Приобретение не знайдено")
    else:
        for i in range(результат3.Количество()):
            р = результат3[i]
            print(f"   {р.Тип:14s} №{р.Номер} от {р.Дата.date()}  Проведен={bool(р.Проведен)}  Сумма={р.Сумма}")

    print("\n" + "=" * 70)
    print("✓ ТЕСТ ЗАВЕРШЕНО")
    print("=" * 70)


if __name__ == "__main__":
    main()
