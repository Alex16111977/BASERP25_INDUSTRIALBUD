"""Швидка діагностика: чи заповнена Організація у тестовому документі і у тестовому
довіднику Партнерів."""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Документ
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Номер", "000001202")
q.Текст = """
ВЫБРАТЬ
    ОП.Ссылка КАК Ссылка
ИЗ
    Документ.А_ОтгрузкаПродукции КАК ОП
ГДЕ
    ОП.Номер = &Номер
"""
sel = q.Выполнить().Выгрузить()
ref = sel[0].Ссылка
obj = ref.ПолучитьОбъект()
print("Документ:        ", S(ref))
print("Организация:     ", S(obj.Организация), "| заполнена=", erp.ЗначениеЗаполнено(obj.Организация))
print("Подразделение:   ", S(obj.Подразделение))
print("ПодразделениеРасхода:", S(obj.ПодразделениеРасхода))
print("СтатьяДенежныхСредств:", S(obj.СтатьяДенежныхСредств))
print("СтороннийЗаказчик:", bool(obj.СтороннийЗаказчик))
print("А_НачислятьУслуги:", bool(obj.А_НачислятьУслуги))
print("Проведен:        ", bool(ref.Проведен))
print("Состав строк:    ", obj.Состав.Количество())

# Партнери
q2 = erp.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    П.Ссылка КАК Партнер,
    П.А_Подразделение КАК А_Подразделение
ИЗ
    Справочник.Партнеры КАК П
ГДЕ
    (П.А_Подразделение.Наименование = "MAN №4 white KA3597HO"
        ИЛИ П.А_Подразделение.Наименование = "МД ПРООН Черкаси  ДСНС")
    И НЕ П.ПометкаУдаления
"""
print("\nПартнери:")
for r in q2.Выполнить().Выгрузить():
    print(" ", S(r.Партнер), "| А_Подразделение:", S(r.А_Подразделение))
