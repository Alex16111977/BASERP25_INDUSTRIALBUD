"""Pre-check для дизайна 2026-05-29: пропуск ВКассу с А_Необновлять=Истина
в процедуре _ОЗП_СоздатьВКассуИзФ2 документа А_ОтражениеЗПпоКазне.

Что проверяет:
1. Запрос с полем А_Необновлять принимается ERP (нет "Поле не найдено").
2. Для эталона А_ОтражениеЗПпоКазне №000000001 от 31.12.2025 печатает
   текущее состояние всех Ф2 → ВКассу и прогноз кода результата.
3. Сводка: сколько Ф2 даст "Создано" / "Обновлено" / "Пропущено".
"""

import sys
import win32com.client

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN_ERP)

print("=" * 70)
print("PRE-CHECK: _ОЗП_СоздатьВКассуИзФ2 — пропуск А_Необновлять=Истина")
print("=" * 70)

# 1. Найти эталон А_ОтражениеЗПпоКазне №000000001 от 31.12.2025
q_etalon = erp.NewObject("Запрос")
q_etalon.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Д.Ссылка КАК Ссылка,
    Д.Номер  КАК Номер,
    Д.Дата   КАК Дата
ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д
ГДЕ Д.Номер = "000000001"
    И Д.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
"""
res = q_etalon.Execute()
if res.Пустой():
    print("FAIL: эталон А_ОтражениеЗПпоКазне №000000001 от 31.12.2025 не найден")
    sys.exit(1)

выб = res.Выбрать()
выб.Следующий()
озп_ссылка = выб.Ссылка
print(f"Эталон: {озп_ссылка}")

# 2. Список уникальных Ф2 в ТЧ.РаспределениеКазна
q_f2 = erp.NewObject("Запрос")
q_f2.SetParameter("Ссылка", озп_ссылка)
q_f2.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    РК.ДокРаспределениеЗП КАК Ф2
ИЗ Документ.А_ОтражениеЗПпоКазне.РаспределениеКазна КАК РК
ГДЕ РК.Ссылка = &Ссылка
    И ТИПЗНАЧЕНИЯ(РК.ДокРаспределениеЗП) = ТИП(Документ.РаспределениеФ2)
"""
ф2_список = q_f2.Execute().Выгрузить()
print(f"Уникальных Ф2 в шапке: {ф2_список.Количество()}")
print()

# 3. Главный запрос — точно тот, что пойдёт в BSL (с новым полем А_Необновлять)
q_main = erp.NewObject("Запрос")
q_main.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Д.Ссылка          КАК Ссылка,
    Д.Проведен        КАК Проведен,
    Д.ПометкаУдаления КАК ПометкаУдаления,
    Д.А_Необновлять   КАК А_Необновлять
ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу КАК Д
ГДЕ Д.А_РаспределениеФ2 = &Основание
"""

# 4. Для каждой Ф2 — прогноз кода результата
прогноз = {"Создано": 0, "Обновлено": 0, "Пропущено": 0}
print(f"{'Ф2':<55} {'ВКассу':<32} {'Пров':<5} {'Уд':<4} {'НеОбн':<6} {'Прогноз'}")
print("-" * 130)
for стр_ф2 in range(1, ф2_список.Количество() + 1):
    ф2 = ф2_список[стр_ф2 - 1].Ф2
    q_main.SetParameter("Основание", ф2)
    try:
        результат = q_main.Execute()
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        msg = info[2] if info else str(e)
        print(f"FAIL запрос на Ф2 {ф2}: {msg}")
        sys.exit(2)

    if результат.Пустой():
        код = "Создано"
        прогноз[код] += 1
        print(f"{str(ф2)[:55]:<55} {'(нет)':<32} {'-':<5} {'-':<4} {'-':<6} {код}")
    else:
        выб = результат.Выбрать()
        выб.Следующий()
        вкассу = выб.Ссылка
        пров = "ДА" if выб.Проведен else "нет"
        уд = "ДА" if выб.ПометкаУдаления else "нет"
        необн = "ИСТИНА" if выб.А_Необновлять else "ложь"
        код = "Пропущено" if выб.А_Необновлять else "Обновлено"
        прогноз[код] += 1
        print(f"{str(ф2)[:55]:<55} {str(вкассу)[:32]:<32} {пров:<5} {уд:<4} {необн:<6} {код}")

print("-" * 130)
print(f"Прогноз: создано={прогноз['Создано']}, обновлено={прогноз['Обновлено']}, пропущено={прогноз['Пропущено']}")

# 5. Acceptance: должен пройти запрос (нет "Поле не найдено") + полезен ли smoke
if прогноз["Пропущено"] == 0:
    print()
    print("ВНИМАНИЕ: ни одна Ф2 не даст пропуск (все А_Необновлять=Ложь).")
    print("Smoke-тест бессмысленен — нечего пропускать.")
    print("Решение: либо провести РКО для одной из ВКассу (тогда А_Необновлять=Истина),")
    print("либо указать другую А_ОтражениеЗПпоКазне, где есть проведённые РКО.")
    sys.exit(3)

print("OK: запрос принимается, есть хотя бы одна ВКассу для пропуска.")
