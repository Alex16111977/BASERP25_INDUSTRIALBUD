"""Етап 2 пре-тест (Rule #-1): чи дає ПАП.Регистратор 1:1 з РасчетыСКлиентами/
Поставщиками для статей 7-10, і чи унікальний ОбъектРасчетов на Регистратор.
Період серверно (січень 2026, закритий). Read-only (ТИПОВІ регістри лише читаємо)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q0 = conn.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
s = q0.Выполнить().Выбрать(); s.Следующий(); org = s.С

qb = conn.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД"
qb.УстановитьПараметр("М", M)
rb = qb.Выполнить().Выбрать(); rb.Следующий(); НМ = rb.НМ; КД = rb.КД
print(f"період: {НМ} .. {КД}")

# 1) Чи має ПАП.Обороты поле Регистратор (ОстаткиИОбороты його НЕ дає)
q1 = conn.NewObject("Запрос")
q1.Текст = """ВЫБРАТЬ ПЕРВЫЕ 5 Б.Регистратор КАК Рег, Б.Статья КАК Статья
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.Обороты(&Д1,&Д2,Регистратор,) КАК Б"""
q1.УстановитьПараметр("Д1",НМ); q1.УстановитьПараметр("Д2",КД)
try:
    t1 = q1.Выполнить().Выгрузить()
    print(f"[OK] ПАП.Обороты(...,Регистратор,) має Регистратор (приклад рядків={t1.Количество()})")
    pap_oboroty_ok = True
except Exception as e:
    info = e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else str(e)
    print(f"[!] ПАП.Обороты з Регистратор: {info}")
    pap_oboroty_ok = False

# 2) Покриття: ПАП-регістратори статей Етапу2(клієнти) які є в РасчетыСКлиентами
ART = ["Задолженность клиентов","Полученные авансы"]
qa = conn.NewObject("Запрос")
qa.Текст = """ВЫБРАТЬ Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование В (&Сп)"""
arr = conn.NewObject("Массив")
for a in ART: arr.Добавить(a)
qa.УстановитьПараметр("Сп", arr)
tza = qa.Выполнить().Выгрузить()
art_refs = conn.NewObject("Массив")
for i in range(tza.Количество()): art_refs.Добавить(tza.Получить(i).С)
print(f"статей Етапу2(клієнти) знайдено: {tza.Количество()}")

q2 = conn.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
  КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Б.Регистратор) КАК РегПАП,
  КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВЫБОР КОГДА Р.Регистратор ЕСТЬ NULL ТОГДА NULL ИНАЧЕ Б.Регистратор КОНЕЦ) КАК РегЗматч
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.Обороты(&Д1,&Д2,Регистратор,
        Организация=&Орг И Статья В ИЕРАРХИИ(&Арт)) КАК Б
  ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ РАЗЛИЧНЫЕ Регистратор КАК Регистратор
                    ИЗ РегистрНакопления.РасчетыСКлиентами
                    ГДЕ Период МЕЖДУ &Д1 И &Д2) КАК Р
  ПО Б.Регистратор = Р.Регистратор
"""
q2.УстановитьПараметр("Д1",НМ); q2.УстановитьПараметр("Д2",КД)
q2.УстановитьПараметр("Орг",org); q2.УстановитьПараметр("Арт",art_refs)
r2 = q2.Выполнить().Выбрать(); r2.Следующий()
рег = int(r2.РегПАП or 0); матч = int(r2.РегЗматч or 0)
покриття = (матч/рег) if рег else 0
print(f"ПАП-регістраторів(клієнти)={рег}, є в РасчетыСКлиентами={матч}, покриття={покриття:.1%}")

# 3) Унікальність ОбъектРасчетов на Регистратор у РасчетыСКлиентами
q3 = conn.NewObject("Запрос")
q3.Текст = """ВЫБРАТЬ Регистратор КАК Рег, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ОбъектРасчетов) КАК КолОР
ИЗ РегистрНакопления.РасчетыСКлиентами ГДЕ Период МЕЖДУ &Д1 И &Д2
СГРУППИРОВАТЬ ПО Регистратор"""
q3.УстановитьПараметр("Д1",НМ); q3.УстановитьПараметр("Д2",КД)
t3 = q3.Выполнить().Выгрузить()
много = sum(1 for i in range(t3.Количество()) if int(t3.Получить(i).КолОР) > 1)
всего = t3.Количество()
print(f"РасчетыСКлиентами регістраторів={всего}, з >1 ОбъектРасчетов={много}, "
      f"унікальних={всего-много} ({((всего-много)/всего if всего else 0):.1%})")

ok = pap_oboroty_ok and покриття > 0.5
print("=" * 60)
print(f">>> GATE Етап2: {'PASS' if ok else 'FAIL — ескалація фінансисту (OD-2: скл. ключ Регистратор+АналитикаУчетаПоПартнерам)'}")
print(f"    ОбъектРасчетов на неунікальних регістраторах → порожньо (канон OD-2).")
assert ok, "FAIL: ключ Регистратор непридатний — STOP, ескалація (без silent-fallback)"
print("PASS Етап2 пре-тест")
