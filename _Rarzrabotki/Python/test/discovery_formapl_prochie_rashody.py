# -*- coding: utf-8 -*-
"""Rule #-1 discovery ПЕРЕД правкой ОЗФУ → ПрочиеРасходы.ФормаPL.
Проверяет:
  1) ФормаPL заполнена в ТЧ НачисленнаяЗарплатаИВзносы (свод) и …ПоФизлицам (детально);
  2) бухгалтерский инвариант: в строках Ф2 ВзносыВсего(ЕСВ)=0 (ЕСВ остаётся Ф1);
  3) эталон Σ движений ПрочиеРасходы по выбранному ОЗФУ (для сверки после правки).
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def q(text, **p):
    query = erp.NewObject("Запрос")
    query.Text = text
    for k, v in p.items():
        query.SetParameter(k, v)
    return query.Execute().Выгрузить()

# --- 1. Кандидаты: проведённые ОЗФУ с движениями в ПрочиеРасходы ---
t = q("""
ВЫБРАТЬ ПЕРВЫЕ 12
    Док.Ссылка КАК Ссылка, Док.Номер КАК Номер, Док.Дата КАК Дата, Док.Сводно КАК Сводно,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ПР.НомерСтроки) КАК ДвиженийПР
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете КАК Док
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрНакопления.ПрочиеРасходы КАК ПР
    ПО ПР.Регистратор = Док.Ссылка
ГДЕ Док.Проведен
СГРУППИРОВАТЬ ПО Док.Ссылка, Док.Номер, Док.Дата, Док.Сводно
УПОРЯДОЧИТЬ ПО Дата УБЫВ
""")
print("=== Проведённые ОЗФУ (последние 12) ===")
выбран = None
for i in range(t.Количество()):
    r = t.Получить(i)
    flag = "СВОД" if r.Сводно else "детально"
    print(f"  №{r.Номер} от {r.Дата:%Y-%m-%d} [{flag}] движенийПР={r.ДвиженийПР}")
    if выбран is None and r.ДвиженийПР and r.ДвиженийПР > 0:
        выбран = r.Ссылка

if выбран is None:
    print("НЕ найден ОЗФУ с движениями ПрочиеРасходы"); sys.exit()

инфо = q("""ВЫБРАТЬ Док.Номер КАК Номер, Док.Дата КАК Дата, Док.Сводно КАК Сводно,
                  Док.Организация КАК Организация
           ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете КАК Док ГДЕ Док.Ссылка = &С""", С=выбран)
ии = инфо.Получить(0)
print(f"\n=== ВЫБРАН: №{ии.Номер} от {ии.Дата:%Y-%m-%d}  Сводно={ии.Сводно}  Орг={ии.Организация} ===")

ФормаPL_CASE = """ВЫБОР
    КОГДА {p}.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ТОГДА "Ф1"
    КОГДА {p}.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2) ТОГДА "Ф2"
    ИНАЧЕ "ПУСТО" КОНЕЦ"""

# --- 2. ФормаPL в ТЧ детально (НачисленнаяЗарплатаИВзносыПоФизлицам) ---
for тч, поляСумм in [
    ("НачисленнаяЗарплатаИВзносыПоФизлицам", "Сумма, ВзносыВсего"),
    ("НачисленнаяЗарплатаИВзносы",            "Сумма, ВзносыВсего"),
]:
    try:
        tt = q(f"""
        ВЫБРАТЬ
            {ФормаPL_CASE.format(p='ТЧ')} КАК Форма,
            КОЛИЧЕСТВО(*) КАК Строк,
            СУММА(ТЧ.Сумма) КАК СуммаЗП,
            СУММА(ТЧ.ВзносыВсего) КАК ЕСВ
        ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете.{тч} КАК ТЧ
        ГДЕ ТЧ.Ссылка = &С
        СГРУППИРОВАТЬ ПО {ФормаPL_CASE.format(p='ТЧ')}
        УПОРЯДОЧИТЬ ПО Форма
        """, С=выбран)
        print(f"\n--- ТЧ {тч}: ФормаPL × (ЗП, ЕСВ) ---")
        if tt.Количество() == 0:
            print("   (пусто)")
        for i in range(tt.Количество()):
            r = tt.Получить(i)
            print(f"   {r.Форма}: строк={r.Строк}  ЗП={r.СуммаЗП:,.2f}  ЕСВ={r.ЕСВ:,.2f}")
    except Exception as e:
        info = getattr(e, 'excepinfo', None)
        print(f"\n--- ТЧ {тч}: FAIL {info[2] if info else e}")

# --- 3. Текущие движения ПрочиеРасходы по ОЗФУ (эталон Σ + текущая ФормаPL) ---
pr = q(f"""
ВЫБРАТЬ
    {ФормаPL_CASE.format(p='ПР')} КАК Форма,
    КОЛИЧЕСТВО(*) КАК Строк,
    СУММА(ПР.Сумма) КАК Сумма,
    СУММА(ПР.СуммаУпр) КАК СуммаУпр,
    СУММА(ПР.СуммаРегл) КАК СуммаРегл
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &С
СГРУППИРОВАТЬ ПО {ФормаPL_CASE.format(p='ПР')}
""", С=выбран)
print("\n=== ЭТАЛОН: движения ПрочиеРасходы по ОЗФУ (ДО правки) ===")
итог = 0
for i in range(pr.Количество()):
    r = pr.Получить(i)
    print(f"   ФормаPL={r.Форма}: строк={r.Строк}  Сумма={r.Сумма:,.2f}  Упр={r.СуммаУпр:,.2f}  Регл={r.СуммаРегл:,.2f}")
    итог += r.Сумма
print(f"   ИТОГО Сумма движений ПР = {итог:,.2f}  (этот Σ должен остаться неизменным после правки)")
