import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\А_ОбработкаДисбалансаПоПодразделениям.erf"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def подр(наим):
    q = erp.NewObject("Запрос")
    q.Text = ('ВЫБРАТЬ ПЕРВЫЕ 1 Сп.Ссылка КАК Ссылка ИЗ Справочник.СтруктураПредприятия КАК Сп '
              'ГДЕ Сп.Наименование = "%s" И НЕ Сп.ПометкаУдаления' % наим)
    s = q.Execute().Выбрать()
    return s.Ссылка if s.Следующий() else None

specteh = подр("Спецтехника")
proizv = подр("Производство")

try:
    obr = erp.ВнешниеОтчеты.Создать(ERF, False)
except Exception:
    obr = erp.ВнешниеОтчеты.Создать(ERF)
print("ERF загружен (модуль объекта скомпилирован) OK")

ok = True

def dump_rows():
    тч = obr.ДокументыДисбаланса
    rows = []
    for i in range(тч.Количество()):
        с = тч.Получить(i)
        rows.append({
            "приход": erp.String(с.ПодразделениеПриход) if erp.ЗначениеЗаполнено(с.ПодразделениеПриход) else "",
            "расход": erp.String(с.ПодразделениеРасход) if erp.ЗначениеЗаполнено(с.ПодразделениеРасход) else "",
            "статья": erp.String(с.СтатьяДисбаланса) if erp.ЗначениеЗаполнено(с.СтатьяДисбаланса) else "(пусто)",
            "док": erp.String(с.Документ),
            "сумма": с.СуммаДокумента,
        })
    return rows

# === A: Передача начислений (per-статья) ===
obr.НачалоПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.ОкончаниеПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.Подразделение = specteh
obr.ПоказыватьВсе = True
obr.АнализДокументов()
A = dump_rows()
деб_налоги = any(r["приход"] == "Спецтехника" and "Налоги" in r["статья"] for r in A)
кред_оплата = any(r["расход"] == "Спецтехника" and "Оплата труда" in r["статья"] for r in A)
print(f"\n[A] Передача начислений, строк={len(A)}")
print(f"    Спецтехника дебитор 'Налоги': {'OK' if деб_налоги else 'FAIL'}")
print(f"    Спецтехника кредитор 'Оплата труда': {'OK' if кред_оплата else 'FAIL'}")
if not (деб_налоги and кред_оплата): ok = False

# === B: Приобретение СТ00-000023 (cross-статья остаток) ===
obr.НачалоПериода = datetime.datetime(2025, 12, 15, 12, 0, 0)
obr.ОкончаниеПериода = datetime.datetime(2025, 12, 15, 12, 0, 0)
obr.Подразделение = proizv
obr.ПоказыватьВсе = True
obr.АнализДокументов()
B = dump_rows()
cross = [r for r in B if "СТ00-000023" in r["док"]]
print(f"\n[B] Приобретение СТ00-000023, всего строк Производство={len(B)}, по СТ00-000023={len(cross)}")
for r in cross:
    print(f"    {r['приход']} <- {r['расход']} | {r['статья']} | {r['сумма']:.2f}")
ожид = any("Товары на оптовых складах - Задолженность перед поставщиками" == r["статья"]
           and r["приход"] == "Производство" and abs(r["сумма"] - 8800.20) < 0.01 for r in cross)
print(f"    cross-статья 'Товары на оптовых складах - Задолженность перед поставщиками' 8800.20: {'OK' if ожид else 'FAIL'}")
if not ожид: ok = False


# === C: Списание недостач ВН-СТ00-000367 (cross-статья, Расходы - Товары) ===
obr.НачалоПериода = datetime.datetime(2025, 12, 25, 12, 0, 0)
obr.ОкончаниеПериода = datetime.datetime(2025, 12, 25, 12, 0, 0)
obr.Подразделение = подр("Производство")
obr.ПоказыватьВсе = True
obr.АнализДокументов()
C = dump_rows()
cross_c = [r for r in C if "ВН-СТ00-000367" in r["док"]]
print(f"\n[C] Списание ВН-СТ00-000367, по нему строк={len(cross_c)}")
for r in cross_c:
    print(f"    {r['приход']} <- {r['расход']} | {r['статья']} | {r['сумма']:.2f}")
ожид_c = any(r["статья"] == "Расходы текущего периода - Товары на оптовых складах"
             and r["расход"] == "Производство" and abs(r["сумма"] - 21522.29) < 0.01 for r in cross_c)
print(f"    cross-статья 'Расходы текущего периода - Товары на оптовых складах' 21522.29: {'OK' if ожид_c else 'FAIL'}")
if not ожид_c: ok = False

print("\n=== SMOKE PASS ===" if ok else "\n=== SMOKE FAIL ===")
