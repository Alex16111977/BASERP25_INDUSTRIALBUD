# -*- coding: utf-8 -*-
"""Приёмка ОрганизацияБухгалтерия: все Ф1-строки заполнены и организация = из бух-закладок
(НачисленияБух/НалогиБухгалтерия/УдержанияБухгалтерия через ДокРаспределениеЗП.Организация)."""
import sys
import win32com.client
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Текст = ('ВЫБРАТЬ А.Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне КАК А '
           'ГДЕ А.Дата >= ДАТАВРЕМЯ(2025,12,1,0,0,0) И А.Дата <= ДАТАВРЕМЯ(2025,12,31,23,59,59) УПОРЯДОЧИТЬ ПО А.Дата')
sel = q.Выполнить().Выбрать(); sel.Следующий()
obj = sel.Ссылка.ПолучитьОбъект()
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()

ф1 = erp.XMLСтрока(erp.Перечисления.А_ФормыPL.Форма1)

# Эталон: множество бух-организаций по ФЛ (НачисленияБух + НалогиБух + УдержанияБух)
бух_орг = {}  # ФЛ(имя) -> set(орг имена)
def собрать(тч, поле_фл):
    for r in тч:
        фл_ссыл = getattr(r, поле_фл)
        фл = S(фл_ссыл)
        if not фл:
            continue
        if erp.ЗначениеЗаполнено(r.Организация):
            бух_орг.setdefault(фл, set()).add(S(r.Организация))
собрать(obj.НачисленияБух, "ФизЛицо")
for r in obj.НалогиБухгалтерия:
    if erp.ЗначениеЗаполнено(r.Сотрудник):
        фл = S(r.Сотрудник.ФизическоеЛицо)
        if erp.ЗначениеЗаполнено(r.Организация):
            бух_орг.setdefault(фл, set()).add(S(r.Организация))
собрать(obj.УдержанияБухгалтерия, "ФизическоеЛицо")

всего = с_орг = без_орг = чужая = 0
for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
    if erp.XMLСтрока(r.ФормаPL) != ф1:
        continue
    всего += 1
    if not erp.ЗначениеЗаполнено(r.ОрганизацияБухгалтерия):
        без_орг += 1
        фл2 = S(r.ФизическоеЛицо)
        print(f"  БЕЗ ОргБух: {фл2[:28]:28} | {S(r.ПодразделениеПредприятия)[:12]:12} | "
              f"{S(r.СпособОтраженияЗарплатыВБухучете)[:28]:28} | Σ={float(r.Сумма):>10,.2f} | "
              f"Внз={float(r.ВзносыВсего):>9,.2f} | бух-орг={бух_орг.get(фл2,'НЕТ')}")
        continue
    с_орг += 1
    орг = S(r.ОрганизацияБухгалтерия)
    фл = S(r.ФизическоеЛицо)
    if фл in бух_орг and орг not in бух_орг[фл]:
        чужая += 1
        if чужая <= 5:
            print(f"  ЧУЖАЯ орг: {фл[:30]} → {орг} (в бух: {бух_орг[фл]})")

print(f"Ф1-строк: {всего};  с ОргБух: {с_орг};  БЕЗ ОргБух: {без_орг};  орг-не-из-бух: {чужая}")

# Воронцов: ЦО должен разнестись на 2 юр.лица
print("\nВоронцов — Ф1 «Зарплата управл» (multi-org, ЦО в 2 юр.лицах):")
for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
    if "Воронцов" not in S(r.ФизическоеЛицо) or erp.XMLСтрока(r.ФормаPL) != ф1:
        continue
    if "правл" not in S(r.СпособОтраженияЗарплатыВБухучете):
        continue
    print(f"  {S(r.ПодразделениеПредприятия)[:14]:14} | ОргБух={S(r.ОрганизацияБухгалтерия)[:22]:22} | Σ={float(r.Сумма):>12,.2f}")

ok = (без_орг == 0 and чужая == 0)
print("\n" + ("OK: все Ф1-строки заполнены, организация из бух" if ok
             else f"FAIL: без_орг={без_орг}, чужая={чужая}"))
sys.exit(0 if ok else 1)
