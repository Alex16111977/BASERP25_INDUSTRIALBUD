# -*- coding: utf-8 -*-
"""Task1 discovery: перечень Источник + набор ВидИсточника дающий
Σ == ПАП.ОстаткиИОбороты по статьям источника (январь/ТОВ). Источник истины
для всех Свод_* задач (как _Fld discovery канона v1.4)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime
pythoncom.CoInitialize()
ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q0 = ERP.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qm = ERP.NewObject("Запрос")
qm.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qm.УстановитьПараметр("М", datetime(2026, 1, 1, 12, 0, 0))
rm = qm.Выполнить().Выбрать(); rm.Следующий(); НМ, КД = rm.НМ, rm.КД

# (a) РАЗЛИЧНЫЕ Источник + ВидИсточника (основная таблица, январь+декабрь)
q1 = ERP.NewObject("Запрос")
q1.Текст = """ВЫБРАТЬ
 ПРЕДСТАВЛЕНИЕ(Т.Источник) КАК Источник, ПРЕДСТАВЛЕНИЕ(Т.ВидИсточника) КАК ВидИст,
 КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Статья) КАК КолСтатей,
 СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
   ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК Оборот
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация=&Орг И Т.Период МЕЖДУ ДОБАВИТЬКДАТЕ(&НМ,МЕСЯЦ,-1) И &КД
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Источник), ПРЕДСТАВЛЕНИЕ(Т.ВидИсточника)"""
q1.УстановитьПараметр("Орг", ORG); q1.УстановитьПараметр("НМ", НМ)
q1.УстановитьПараметр("КД", КД)
try:
    t1 = q1.Выполнить().Выгрузить()
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    print(f"FAIL q1: {msg}")
    sys.exit(1)
print("=== (a) Источник x ВидИсточника ===")
for i in range(t1.Количество()):
    r = t1.Получить(i)
    print(f"  Источник='{r.Источник}' | ВидИст='{r.ВидИст}' | "
          f"статей={int(r.КолСтатей)} | оборот={float(r.Оборот or 0):,.2f}")

# (b) Эталон ПАП.ОстаткиИОбороты по статьям (январь)
q2 = ERP.NewObject("Запрос")
q2.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Б.Статья) КАК Ст,
 СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
 Организация=&Орг) КАК Б
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Б.Статья)
ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток)<>0"""
q2.УстановитьПараметр("Д1", НМ); q2.УстановитьПараметр("Д2", КД)
q2.УстановитьПараметр("Орг", ORG)
t2 = q2.Выполнить().Выгрузить()
etalon = {str(t2.Получить(i).Ст): float(t2.Получить(i).sK or 0)
          for i in range(t2.Количество())}

# (c) КонОст из ОСНОВНОЙ таблицы по статьям (Σ signed весь период до КД)
#     набор ВидИсточника = ВСЕ (берём все слои) — проверяем == эталон
q3 = ERP.NewObject("Запрос")
q3.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст,
 СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
   ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация=&Орг И Т.Период <= &КД
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)"""
q3.УстановитьПараметр("Орг", ORG); q3.УстановитьПараметр("КД", КД)
t3 = q3.Выполнить().Выгрузить()
osnov = {str(t3.Получить(i).Ст): float(t3.Получить(i).sK or 0)
         for i in range(t3.Количество())}

print("\n=== (c) сверка ОСНОВНАЯ(все ВидИсточника) КонОст vs ПАП.ОстаткиИОбороты ===")
bad = []
for k in set(etalon) | set(osnov):
    d = abs(etalon.get(k, 0) - osnov.get(k, 0))
    if d > 0.01:
        bad.append((k, etalon.get(k, 0), osnov.get(k, 0), d))
for k, a, b, dd in bad[:15]:
    print(f"  ДЕЛЬТА {k[:40]}: ОстИОб={a:,.2f} основн={b:,.2f} Δ={dd:,.4f}")
print(f"\nстатей расхождений (все слои): {len(bad)} "
      f"(0 → НачОст/КонОст из основной таблицы по всем ВидИсточника == ПАП)")
print("\nИтог Task1: список Источник (a) → перечень Свод_* процедур; "
      "если len(bad)=0 → набор ВидИсточника = ВСЕ слои (DR-7 решён); "
      "если >0 → подобрать фильтр ВидИсточника (исключить РасчетБаланса/отложенный) "
      "и повторить (c) до len(bad)=0.")
print("PASS test_balans_m_discovery (см. вывод — это вход для Task 4+)")
