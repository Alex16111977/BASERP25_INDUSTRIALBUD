"""
Тест: Пошук платіжки (СписаниеБезналичныхДС) для А_ПриходДенегОтФинАгента
коли ДокументПередачи пустий в А_РасшифровкаФинАгент.

Логіка: шукаємо ПЕРШУ платіжку по регістру А_ДенежныеСредстваФинАгенты
по критеріях: ФинАгент + Подразделение + Период >= ДатаДокумента
"""
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

print("=" * 70)
print("ТЕСТ: Пошук платіжки для А_ПриходДенегОтФинАгента")
print("=" * 70)

# 1. Знайти документи з пустим ДокументПередачи
q1 = conn.NewObject("Запрос")
q1.Текст = """ВЫБРАТЬ
    Р.Ссылка КАК Док,
    Р.Ссылка.Номер КАК НомерДок,
    Р.Ссылка.Дата КАК ДатаДок,
    Р.ФинАгент КАК ФинАгент,
    Р.ФинАгент.Наименование КАК ФА,
    Р.Направление.Наименование КАК Напр,
    Р.Сумма КАК Сум,
    Р.Ссылка.Подразделение КАК Подразделение,
    Р.Ссылка.Подразделение.Наименование КАК ПодрНаим,
    Р.Ссылка.А_Подразделение КАК А_Подразделение,
    Р.Ссылка.А_НаправлениеДеятельности КАК А_Направление
ИЗ Документ.А_ПриходДенегОтФинАгента.А_РасшифровкаФинАгент КАК Р
ГДЕ Р.ДокументПередачи = ЗНАЧЕНИЕ(Документ.СписаниеБезналичныхДенежныхСредств.ПустаяСсылка)
    И Р.Ссылка.Проведен
УПОРЯДОЧИТЬ ПО Р.Ссылка.Дата УБЫВ"""

res1 = q1.Выполнить().Выбрать()
problems = []
while res1.Следующий():
    problems.append({
        'doc': res1.Док,
        'num': res1.НомерДок,
        'date': res1.ДатаДок,
        'fin_agent': res1.ФинАгент,
        'fa_name': res1.ФА,
        'napr': res1.Напр,
        'sum': res1.Сум,
        'podr': res1.Подразделение,
        'podr_name': res1.ПодрНаим,
        'a_podr': res1.А_Подразделение,
        'a_napr': res1.А_Направление,
    })

print(f"\nЗнайдено {len(problems)} рядків з пустим ДокументПередачи\n")

# 2. Для кожного шукаємо платіжку по регістру
found = 0
not_found = 0

for p in problems:
    q2 = conn.NewObject("Запрос")
    q2.УстановитьПараметр("ФинАгент", p['fin_agent'])
    q2.УстановитьПараметр("Подразделение", p['podr'])
    q2.УстановитьПараметр("ДатаДокумента", p['date'])
    q2.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1
        ДокументПередачи КАК Платежка,
        ДокументПередачи.Номер КАК НомерПлат,
        ДокументПередачи.Дата КАК ДатаПлат,
        Сумма КАК СумПлат
    ИЗ РегистрНакопления.А_ДенежныеСредстваФинАгенты
    ГДЕ ФинАгент = &ФинАгент
        И Подразделение = &Подразделение
        И ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        И ДокументПередачи <> ЗНАЧЕНИЕ(Документ.СписаниеБезналичныхДенежныхСредств.ПустаяСсылка)
        И Период >= &ДатаДокумента
    УПОРЯДОЧИТЬ ПО Период"""

    res2 = q2.Выполнить().Выбрать()
    if res2.Следующий():
        found += 1
        print(f"OK: Док {p['num']} ({p['date']}) ФА={p['fa_name']} Подр={p['podr_name']} Сума={p['sum']:,.2f}")
        print(f"    -> Знайдено платіжку: {res2.НомерПлат} від {res2.ДатаПлат} сума={res2.СумПлат:,.2f}")
    else:
        not_found += 1
        # Спробуємо без Подразделение
        q3 = conn.NewObject("Запрос")
        q3.УстановитьПараметр("ФинАгент", p['fin_agent'])
        q3.УстановитьПараметр("ДатаДокумента", p['date'])
        q3.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1
            ДокументПередачи.Номер КАК НомерПлат,
            ДокументПередачи.Дата КАК ДатаПлат,
            Подразделение.Наименование КАК ПодрРег,
            Сумма КАК СумПлат
        ИЗ РегистрНакопления.А_ДенежныеСредстваФинАгенты
        ГДЕ ФинАгент = &ФинАгент
            И ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            И ДокументПередачи <> ЗНАЧЕНИЕ(Документ.СписаниеБезналичныхДенежныхСредств.ПустаяСсылка)
            И Период >= &ДатаДокумента
        УПОРЯДОЧИТЬ ПО Период"""
        res3 = q3.Выполнить().Выбрать()
        if res3.Следующий():
            print(f"!! Док {p['num']} ({p['date']}) ФА={p['fa_name']} Подр={p['podr_name']} Сума={p['sum']:,.2f}")
            print(f"    -> БЕЗ Подразделение знайдено: {res3.НомерПлат} від {res3.ДатаПлат} ПодрРег={res3.ПодрРег} сума={res3.СумПлат:,.2f}")
        else:
            print(f"XX Док {p['num']} ({p['date']}) ФА={p['fa_name']} Подр={p['podr_name']} Сума={p['sum']:,.2f}")
            print(f"    -> НЕ ЗНАЙДЕНО жодної платіжки!")

print(f"\n{'=' * 70}")
print(f"Знайдено: {found}, Не знайдено: {not_found}, Всього: {len(problems)}")
print(f"{'=' * 70}")
