def водопад_старый(данные, кс):
    """Формулы СТАРОЙ формы — дословно из версии 4."""
    ОД = v4гр(данные, кс, "Операционный доход")
    СС = v4гр(данные, кс, "Себестоимость проданой продукции (переменные производственные затраты)")
    ДР = v4гр(данные, кс, "Дополнительные  расходы")
    ОПЗ = v4гр(данные, кс, "Общепроизводственные затраты")          # вместе с амортизацией
    МЗ = v4гр(данные, кс, "Маркетинговые затраты")
    АЗ = v4гр(данные, кс, "Административные затраты")
    НС = v4ст(данные, кс, "НДС/ Прочие налоги")
    ФД = v4ст(данные, кс, "Финансовый доход")
    # Статья 000000056 переименована 20.08.2026 («Финансовые расходы» -> «...комиссии»).
    # Запрос v4 читает ЖИВОЙ справочник, поэтому имя здесь тоже новое; плюс две статьи,
    # заведённые под расщепление, — иначе эталон недосчитает финрасходы.
    ФР = (v4ст(данные, кс, "Финансовые расходы комиссии")
          + v4ст(данные, кс, "Финансовые расходы %%")
          + v4ст(данные, кс, "Курсовые разницы"))
    НП = v4ст(данные, кс, "Затраты на налог на прибыль")
    ДИВ = v4ст(данные, кс, "Дивиденды")
    Марж = ОД - СС
    Опер = Марж - ОПЗ - МЗ - АЗ
    ПослеФин = Опер + ФД - ФР
    ДоНалогов = ПослеФин - ДР
    Чистый = ДоНалогов - НС - НП
    # «В распоряжении» (Чистый - Дивиденды) из отчёта удалена 21.08.2026 — не сверяется.
    return {"ОД": ОД, "Марж": Марж, "Опер": Опер, "Чистый": Чистый}


