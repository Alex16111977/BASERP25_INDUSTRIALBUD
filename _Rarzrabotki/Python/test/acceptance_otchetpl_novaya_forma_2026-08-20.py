def норм(текст):
    return re.sub(r"\s+", " ", (текст or "")).strip().lower()


def в_число(текст):
    т = (текст or "").strip().replace("\xa0", "").replace(" ", "").replace("%", "")
    if not т:
        return None
    try:
        return float(т.replace(",", "."))
    except ValueError:
        return None


