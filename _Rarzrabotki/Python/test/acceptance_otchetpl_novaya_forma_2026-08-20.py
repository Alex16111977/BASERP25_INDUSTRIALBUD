def снять_отборы_группировок(структура):
    """Вариант построен ТАБЛИЦЕЙ: отборы живут в Таблица.Строки/Колонки, а не в Структуре.

    Отбор группировки «Статья PL» («СуммаФ1 Заполнено ИЛИ СуммаФ2») прячет статью
    с нулевым фактом — для проверки полного шаблона его надо снять."""
    for i in range(структура.Количество()):
        эл = структура.Получить(i)
        for имя in ("Отбор",):
            try:
                отбор = getattr(эл, имя)
            except Exception:
                continue
            for j in range(отбор.Элементы.Количество()):
                отбор.Элементы.Получить(j).Использование = False
        for ветка in ("Структура", "Строки", "Колонки"):
            try:
                вложенная = getattr(эл, ветка)
            except Exception:
                continue
            снять_отборы_группировок(вложенная)


def разобрать(таб):
    """{блок: {строка: (Ф1, Ф2, Итого)}} + порядок строк."""
    в, ш = int(таб.ВысотаТаблицы), int(таб.ШиринаТаблицы)
    g = [[S(таб.Область(r, c, r, c).Текст).strip() for c in range(1, ш + 1)] for r in range(1, в + 1)]

    строка_ресурсов = None
    for r in range(в):
        if any(норм(g[r][c]).startswith("сумма по ф1") for c in range(ш)):
            строка_ресурсов = r
            break
    if строка_ресурсов is None:
        raise RuntimeError("не найдена строка ресурсов «Сумма по Ф1, грн»")

    ф1 = [c for c in range(ш) if норм(g[строка_ресурсов][c]).startswith("сумма по ф1")]
    блоки = {}
    for c in ф1:
        подпись = ""
        for r in range(строка_ресурсов - 1, -1, -1):
            if g[r][c]:
                подпись = g[r][c]
                break
        блоки[подпись] = c

    данные = {имя: {} for имя in блоки}
    порядок = []
    for r in range(строка_ресурсов + 1, в):
        подпись = ""
        for c in range(ш):
            if g[r][c]:
                подпись = g[r][c]
                break
        if not подпись:
            continue
        порядок.append(норм(подпись))
        for имя, c0 in блоки.items():
            данные[имя][норм(подпись)] = (
                в_число(g[r][c0]), в_число(g[r][c0 + 1]), в_число(g[r][c0 + 2]))
    return данные, порядок


def ит(данные, блок, строка):
    v = данные.get(блок, {}).get(норм(строка))
    return None if v is None else v[2]


