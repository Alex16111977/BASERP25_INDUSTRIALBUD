    # 2. Выполнить запрос и получить ТаблицаЗначений (как ПолучитьОбъединенныеДанные)
    q = conn.NewObject("Запрос")
    q.Текст = query_text
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(datetime(2025, 12, 1)))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(datetime(2025, 12, 31, 23, 59, 59)))
    table = q.Выполнить().Выгрузить()
    print(f"[OK] Full query returned {table.Количество()} rows (13 columns)")

    # 3. Проверить что колонка «Документ» имеет ссылки на документ.А_ОтчетPL
    found_doc = 0
    found_empty_doc = 0
    for row in table:
        doc = row.Документ
        if doc is None:
            continue
        if conn.ЗначениеЗаполнено(doc):
            found_doc += 1
        else:
            found_empty_doc += 1
    print(f"  Документ — непустых ссылок: {found_doc}; пустых (ЗНАЧЕНИЕ(ПустаяСсылка)): {found_empty_doc}")

    # 4. Проверить Комментарий
    non_empty_comments = 0
    for row in table:
        if row.Комментарий and len(str(row.Комментарий).strip()) > 0:
            non_empty_comments += 1
    print(f"  Комментарий — непустых: {non_empty_comments}")

    # 5. Теперь — запустить СКД компоновку
    print("\n--- Запуск СКД компоновки (Основной вариант) ---")
    report_manager = conn.Reports.А_ОтчетPL
    schema = report_manager.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")

    settings_composer = conn.NewObject("КомпоновщикНастроекКомпоновкиДанных")
    settings_source = conn.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", schema)
    settings_composer.Инициализировать(settings_source)
    # Загрузить первый вариант (Основной)
    settings_composer.ЗагрузитьНастройки(schema.НастройкиПоУмолчанию)

    # Установить период (через ПараметрКомпоновкиДанных)
    param_id = conn.NewObject("ПараметрКомпоновкиДанных", "Период")
    period_param = settings_composer.Настройки.ПараметрыДанных.НайтиЗначениеПараметра(param_id)
