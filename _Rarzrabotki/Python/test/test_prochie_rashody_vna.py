# -*- coding: utf-8 -*-
"""Тест: запит до ПрочиеРасходы для статей НаВнеоборотныеАктивы.
Перевіряємо що записи існують і яка структура потрібна для РАСХОД.
"""
import win32com.client, datetime
v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# 1. Знайти всі ПРИХОД записи НаВнеоборотныеАктивы
print("=== ПРИХОД записи в ПрочиеРасходы (НаВнеоборотныеАктивы) ===")
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ
    ПР.Период, ПР.Регистратор, ПР.Организация, ПР.Подразделение,
    ПР.НалоговоеНазначение, ПР.СтатьяРасходов, ПР.АналитикаРасходов,
    ПР.Сумма, ПР.СуммаБезНДС, ПР.СуммаРегл, ПР.СуммаРеглБезНДС,
    ПР.НДСРегл, ПР.СуммаУпр, ПР.СуммаУпрБезНДС,
    ПР.ХозяйственнаяОперация, ПР.АналитикаУчетаНоменклатуры
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Активность
    И ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл = ЗНАЧЕНИЕ(Перечисление.ВариантыРаспределенияРасходов.НаВнеоборотныеАктивы)
    И ПР.Период >= &Дата1 И ПР.Период <= &Дата2"""
q.SetParameter("Дата1", datetime.datetime(2025, 12, 1))
q.SetParameter("Дата2", datetime.datetime(2025, 12, 31, 23, 59, 59))
res = q.Execute()
sel = res.Select()
cnt = 0
total = 0
while sel.Next():
    cnt += 1
    total += sel.Сумма if sel.Сумма else 0
    if cnt <= 5:
        print(f"  #{cnt} Період={sel.Период} Стаття={S(sel.СтатьяРасходов)}")
        print(f"     Аналітика={S(sel.АналитикаРасходов)} Сума={sel.Сумма}")
        print(f"     Орг={S(sel.Организация)} Підр={S(sel.Подразделение)}")
        print(f"     Реєстратор={S(sel.Регистратор)}")
print(f"\nВсього ПРИХОД: {cnt} записів, сума={total}")

# 2. Перевірити чи є РАСХОД
print("\n=== РАСХОД записи (НаВнеоборотныеАктивы) ===")
q2 = conn.NewObject("Запрос")
q2.Text = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол, СУММА(ПР.Сумма) КАК Сума
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Активность
    И ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
    И ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл = ЗНАЧЕНИЕ(Перечисление.ВариантыРаспределенияРасходов.НаВнеоборотныеАктивы)
    И ПР.Период >= &Дата1 И ПР.Период <= &Дата2"""
q2.SetParameter("Дата1", datetime.datetime(2025, 12, 1))
q2.SetParameter("Дата2", datetime.datetime(2025, 12, 31, 23, 59, 59))
res2 = q2.Execute()
sel2 = res2.Select()
sel2.Next()
print(f"  РАСХОД: {sel2.Кол} записів, сума={sel2.Сума}")

# 3. Перевірити виміри регістру
print("\n=== Виміри регістру ПрочиеРасходы ===")
meta = conn.Metadata.AccumulationRegisters.ПрочиеРасходы
print("Виміри:")
for i in range(meta.Dimensions.Count()):
    print(f"  {meta.Dimensions.Get(i).Name}")
print("Ресурси:")
for i in range(meta.Resources.Count()):
    print(f"  {meta.Resources.Get(i).Name}")
print("Реквізити (перші 10):")
for i in range(min(10, meta.Attributes.Count())):
    print(f"  {meta.Attributes.Get(i).Name}")

print("\n=== DONE ===")
