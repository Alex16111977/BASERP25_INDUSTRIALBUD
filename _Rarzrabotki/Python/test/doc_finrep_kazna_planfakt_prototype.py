def ошибка(e):
    return e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)


def выполнить(conn, текст, параметры=None):
    q = conn.NewObject("Запрос")
    q.Text = текст
    for имя, знач in (параметры or {}).items():
        q.УстановитьПараметр(имя, знач)
    return q.Execute().Выгрузить()


def карта_корней(conn):
    """Имя подразделения -> имя корня верхнего уровня."""
    S = conn.String
    r = выполнить(conn, ЗАПРОС_ИЕРАРХИЯ)
    родитель = {}
    for i in range(r.Количество()):
        row = r.Получить(i)
        имя, род = S(row.Имя).strip(), S(row.РодительИмя).strip()
        родитель[имя] = род if род and род != "None" else ""
    корни = {}
    for имя in родитель:
        тек, глубина = имя, 0
        while родитель.get(тек, "") and глубина < 20:
            тек = родитель[тек]
            глубина += 1
        корни[имя] = тек
    return корни


def прочитать_эталон():
    """Топ-уровневые строки эталона: имя -> (ПланДоход, ФактДоход, ПланРасход, ФактРасход)."""
    fixed = os.path.join(os.environ.get("TEMP", "."), "planfakt_etalon_fixed.xlsx")
    with zipfile.ZipFile(ETALON) as zin, zipfile.ZipFile(fixed, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            name = item.filename
            if name.lower() == "xl/sharedstrings.xml":
                name = "xl/sharedStrings.xml"
            zout.writestr(name, zin.read(item.filename))
    import openpyxl
    ws = openpyxl.load_workbook(fixed, data_only=True)["TDSheet"]
    строки, итог = {}, None
    for row in ws.iter_rows(min_row=6):
        имя = row[0].value
        if имя is None:
            continue
        имя = str(имя).strip()
        числа = [row[i].value or 0 for i in (3, 5, 8, 9)]  # D, F, I, J
        if имя == "Разом":
            итог = tuple(float(x) for x in числа)
            break
        if "(" in имя:  # вложенные строки вида «Имя (Родитель)»
            continue
        if имя not in строки:  # у «МД IRC 2026» первая строка — иерархия (полная)
            строки[имя] = tuple(float(x) for x in числа)
    return строки, итог


def расчет(conn, гр_доход, гр_расход, направление, корни, гг, мм, дд):
    """Возвращает: имя_корня -> [ПланДоход, ФактДоход, ПланРасход, ФактРасход]."""
    S = conn.String
    табл = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])
    п = {"ГруппаДоход": гр_доход, "ГруппаРасход": гр_расход, "Направление": направление}

    факт_текст = ЗАПРОС_ФАКТ.replace("{ГГ}", str(гг)).replace("{ММ}", str(мм)).replace("{ДД}", str(дд))
    r = выполнить(conn, факт_текст, п)
    for i in range(r.Количество()):
        row = r.Получить(i)
        корень = корни.get(S(row.ПодразделениеИмя).strip(), S(row.ПодразделениеИмя).strip())
        табл[корень][1] += float(row.Доход)
        табл[корень][3] += float(row.Расход)

    r = выполнить(conn, ЗАПРОС_ПЛАН, п)
    for i in range(r.Количество()):
        row = r.Получить(i)
        корень = корни.get(S(row.ПодразделениеИмя).strip(), S(row.ПодразделениеИмя).strip())
        табл[корень][0] += float(row.ПланДоход)
        табл[корень][2] += float(row.ПланРасход)
    return табл, факт_текст


def сравнить(табл, эт_строки, эт_итог, метка):
    ок = True
    print(f"\n===== Сравнение с эталоном (граница факта: {метка}) =====")
    print(f"{'Подразделение':40} {'ПланП':>14} {'ФактП':>14} {'ПланЗ':>15} {'ФактЗ':>14}")
    итог = [0.0, 0.0, 0.0, 0.0]
    for имя in sorted(set(табл) | set(эт_строки)):
        мои = табл.get(имя, [0, 0, 0, 0])
        эт = эт_строки.get(имя)
        for j in range(4):
            итог[j] += мои[j]
        расхожд = ""
        if эт is None:
            расхожд = "  << нет в эталоне" if any(abs(x) > 0.005 for x in мои) else "  (нули, в эталоне скрыто)"
            if "нет в эталоне" in расхожд:
                ок = False
        else:
            дельты = [мои[j] - эт[j] for j in range(4)]
            if any(abs(d) > 0.005 for d in дельты):
                расхожд = "  << РАСХОЖДЕНИЕ " + str([round(d, 2) for d in дельты])
                ок = False
        print(f"{имя[:40]:40} {мои[0]:>14,.2f} {мои[1]:>14,.2f} {мои[2]:>15,.2f} {мои[3]:>14,.2f}{расхожд}")
    for имя in эт_строки:
        if имя not in табл and any(abs(x) > 0.005 for x in эт_строки[имя]):
            print(f"  !! в эталоне есть, у нас нет: {имя}")
            ок = False
    print(f"{'ИТОГО':40} {итог[0]:>14,.2f} {итог[1]:>14,.2f} {итог[2]:>15,.2f} {итог[3]:>14,.2f}")
    print(f"{'ЭТАЛОН Разом':40} {эт_итог[0]:>14,.2f} {эт_итог[1]:>14,.2f} {эт_итог[2]:>15,.2f} {эт_итог[3]:>14,.2f}")
    дельты_итог = [итог[j] - эт_итог[j] for j in range(4)]
    print("Дельта итогов:", [round(d, 2) for d in дельты_итог])
    if any(abs(d) > 0.005 for d in дельты_итог):
        ок = False
    return ок, итог


