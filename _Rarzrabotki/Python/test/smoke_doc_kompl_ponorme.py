# -*- coding: utf-8 -*-
"""Smoke: РасчетКомплектаций — АВТОПРОСТАВЛЕНИЕ признака ПоНорме при заполнении документов.

Доработка 2026-08-25 (СформироватьДокументыПоСоответствию + ПризнакиПоНормеДокументов):
документ из колонки «ДокументПоНормам» получает ПоНорме = Истина, из «ДокументДодаткова» — Ложь.

Сценарий: scratch-расчёт (маркер SMOKE_DOC_KOMPL_v1, создан smoke_doc_kompl_analiz.py),
те же 4 scratch-целевых документа, что у smoke_doc_kompl_zapolnenie.py. Флаги предварительно
ПОРТЯТСЯ (наоборот), затем «Заповнити документи» — флаги обязаны стать правильными.
Ничего не удаляем, боевые документы не трогаем, запись без проведения.
"""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import datetime
import win32com.client

MARKER = "SMOKE_DOC_KOMPL_v1"

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String

провалов = 0


def проверка(имя, условие, деталь=""):
    global провалов
    if not условие:
        провалов += 1
    print(f"  [{'OK  ' if условие else 'FAIL'}] {имя}" + (f" — {деталь}" if деталь else ""))



def выровнять_документ(ref, row):
    """Контроль складу документа (28.09.2026): документ у рядку «Документи» має склад і організацію рядка.
    Scratch-документ вирівнюємо під рядок (запис БЕЗ проведення)."""
    uid = lambda x: buh.String(x.УникальныйИдентификатор())
    obj = ref.ПолучитьОбъект()
    змінено = False
    if uid(obj.Склад) != uid(row.Склад):
        obj.Склад = row.Склад
        змінено = True
    if buh.ЗначениеЗаполнено(row.Организация) and uid(obj.Организация) != uid(row.Организация):
        obj.Организация = row.Организация
        змінено = True
    if змінено:
        obj.Записать()

def find_by_comment(doc_type, marker):
    q = buh.NewObject("Запрос")
    q.Text = (f"ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Документ.{doc_type} КАК Д "
              "ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК Строка(200)) = &М И НЕ Д.ПометкаУдаления")
    q.SetParameter("М", marker)
    r = q.Execute().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() > 0 else None


def get_or_create_target(doc_type, marker, org):
    ref = find_by_comment(doc_type, marker)
    if ref is not None:
        return ref
    d = getattr(buh.Документы, doc_type).СоздатьДокумент()
    d.Дата = datetime.datetime.now().replace(microsecond=0)
    d.Организация = org
    d.Комментарий = marker
    d.Записать()
    return d.Ссылка


def испортить_флаг(ref, значение):
    obj = ref.ПолучитьОбъект()
    obj.ПоНорме = значение
    obj.Записать()


# --- scratch-расчёт ---
ref = find_by_comment("РасчетКомплектаций", MARKER)
assert ref is not None, "сначала прогнать smoke_doc_kompl_analiz.py (нет scratch-расчёта)"
doc = ref.ПолучитьОбъект()
assert doc.СписаниеПоНормам.Количество() > 0, "СписаниеПоНормам пусто — расчёт не выполнен"
assert doc.СписаниеСверхНормы.Количество() > 0, "СписаниеСверхНормы пусто"

qorg = buh.NewObject("Запрос")
qorg.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК Ссылка ИЗ Справочник.Организации КАК О ГДЕ НЕ О.ПометкаУдаления"
org = qorg.Execute().Выгрузить().Получить(0).Ссылка

kn_norm = get_or_create_target("КомплектацияНоменклатуры", MARKER + "_КН_НОРМ", org)
kn_over = get_or_create_target("КомплектацияНоменклатуры", MARKER + "_КН_ПОНАД", org)
mal_norm = get_or_create_target("ПередачаМалоценныхАктивовВЭксплуатацию", MARKER + "_МАЛ_НОРМ", org)
mal_over = get_or_create_target("ПередачаМалоценныхАктивовВЭксплуатацию", MARKER + "_МАЛ_ПОНАД", org)
print(f"Целевые: КН {kn_norm.Номер}/{kn_over.Номер}, Мал {mal_norm.Номер}/{mal_over.Номер}")

# --- прописать документы в строки складов ---
assert doc.ДокументиКомплектації.Количество() > 0, "нет строк ДокументиКомплектації"
for i in range(doc.ДокументиКомплектації.Количество()):
    row = doc.ДокументиКомплектації.Получить(i)
    row.ДокументПоНормам = kn_norm
    row.ДокументДодаткова = kn_over
    выровнять_документ(kn_norm, row)
    выровнять_документ(kn_over, row)
for i in range(doc.ДокументиМалоценки.Количество()):
    row = doc.ДокументиМалоценки.Получить(i)
    row.ДокументПоНормам = mal_norm
    row.ДокументДодаткова = mal_over
    выровнять_документ(mal_norm, row)
    выровнять_документ(mal_over, row)

# понаднорма списывается по КоличествоКСписанию — гарантируем непустые строки «Додаткова»
for i in range(doc.СписаниеСверхНормы.Количество()):
    row = doc.СписаниеСверхНормы.Получить(i)
    if row.Количество > 0 and row.КоличествоКСписанию == 0:
        row.КоличествоКСписанию = row.Количество

# --- испортить флаги НАОБОРОТ (доказываем, что заполнение их перезапишет) ---
испортить_флаг(kn_norm, False)
испортить_флаг(kn_over, True)
испортить_флаг(mal_norm, False)
испортить_флаг(mal_over, True)
print("Флаги предварительно испорчены наоборот (норм=Ложь, понад=Истина)")

# --- заполнение ---
res = doc.ЗаполнитьДокументыПоАнализу(True, True)
print(f"Результат: Заповнено={res.Заповнено}, Пропущено={res.Пропущено}, Помилок={res.Помилки.Количество()}")
for i in range(res.Помилки.Количество()):
    print("  Помилка:", S(res.Помилки.Получить(i)))
проверка("заполнение без ошибок", res.Помилки.Количество() == 0)
проверка("заполнено >= 2 документов", res.Заповнено >= 2, f"Заповнено={res.Заповнено}")

# --- проверка флагов: только у документов, реально получивших строки (записанных) ---
def строк_тч(ref, малоценка):
    obj = ref.ПолучитьОбъект()
    return (obj.МалоценныеАктивы if малоценка else obj.Комплектующие).Количество()


цели = [("КН ПоНормам", kn_norm, False, True),
        ("КН Додаткова", kn_over, False, False),
        ("Мал ПоНормам", mal_norm, True, True),
        ("Мал Додаткова", mal_over, True, False)]
непроверенные = []
for имя, целевой, малоценка, ожид in цели:
    n = строк_тч(целевой, малоценка)
    if n > 0:
        факт = bool(целевой.ПоНорме)
        проверка(f"{имя}: ПоНорме = {'Истина' if ожид else 'Ложь'} (строк {n})", факт == ожид,
                 f"факт={факт}")
    else:
        непроверенные.append((имя, целевой, ожид))
        print(f"  [....] {имя}: строк нет — заполнением не записывался, флаг не проверен данными")

проверка("оба документа комплектации проверены данными",
         all(имя not in [н[0] for н in непроверенные] for имя in ("КН ПоНормам", "КН Додаткова")))

# --- идемпотентность: повторное заполнение флаги не ломает ---
res2 = doc.ЗаполнитьДокументыПоАнализу(True, True)
проверка("повторное заполнение без ошибок", res2.Помилки.Количество() == 0)
проверка("повторно: КН ПоНормам = Истина, КН Додаткова = Ложь",
         bool(kn_norm.ПоНорме) is True and bool(kn_over.ПоНорме) is False)

# --- навести порядок: незаписанным заполнением scratch-документам вернуть правильные флаги ---
for имя, целевой, ожид in непроверенные:
    испортить_флаг(целевой, ожид)
    print(f"  scratch {имя}: флаг восстановлен вручную ({ожид})")

doc.Записать()
print(f"\nПРОВАЛОВ: {провалов}")
print("PONORME " + ("PASS" if провалов == 0 else "FAIL"))
sys.exit(1 if провалов else 0)
