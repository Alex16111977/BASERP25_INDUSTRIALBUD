# -*- coding: utf-8 -*-
"""Инвариант Ф1: по каждому (ФЛ, подразделение) Начислено - НачисленныйНДФЛ == «Зарплата управл».
Если выполняется — Приход(ОЗФУ) = перенос(ПередачаНачислений) до копейки.

Rule #-1: пересчёт ТЧ в памяти через COM (obj.ЗаполнитьДляОтражения_...), БЕЗ проведения.
(Проведение/перепроведение — только через UI 1С Enterprise.)

ВАЖНО про COM-сравнения: str() от ссылок/перечислений 1С даёт '<COMObject>', поэтому
перечисления сравниваем через erp.XMLСтрока(...), пустые ссылки — через erp.ЗначениеЗаполнено(...).

Запуск:
    C:\\Python313\\python.exe test_vzss_f1_accrual_transfer_match.py          # эталон Шишкіна
    C:\\Python313\\python.exe test_vzss_f1_accrual_transfer_match.py --all     # все документы, все ФЛ
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
ФЛ_ЭТАЛОН = "Шишк"   # подстрока без 'і' (Ukr/Rus неоднозначность), сравнение регистронезависимое


def проверить_документ(erp, ссылка, только_фл=None):
    """Пересчитывает ТЧ в памяти, возвращает список нарушений (ФЛ, Подр, Приход, ЗПупр, Δ)."""
    obj = ссылка.ПолучитьОбъект()
    obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()

    XML = erp.XMLСтрока
    ВО = erp.Перечисления.ВидыОперацийПоЗарплате
    искл = {XML(ВО.ЕжегодныйОтпускОценочныеОбязательстваИРезервы),
            XML(ВО.НачисленоСдельноДоход),
            XML(ВО.КомпенсацияЕжегодногоОтпускаОценочныеОбязательства),
            XML(ВО.ЕжегодныйОтпускОценочныеОбязательства)}
    нф = (только_фл or "").lower()

    начислено, зп_упр, ндфл = {}, {}, {}

    тч = obj.НачисленнаяЗарплатаИВзносыПоФизлицам
    for i in range(тч.Количество()):
        с = тч.Получить(i)
        if XML(с.ФормаPL) != "Форма1":
            continue
        флн = с.ФизическоеЛицо.Наименование
        if нф and нф not in флн.lower():
            continue
        подр = с.ПодразделениеПредприятия.Наименование if erp.ЗначениеЗаполнено(с.ПодразделениеПредприятия) else "<пусто>"
        k = (флн, подр)
        способ = с.СпособОтраженияЗарплатыВБухучете
        это_удерж = bool(способ.А_ЭтоУдержание) if erp.ЗначениеЗаполнено(способ) else False
        if (not erp.ЗначениеЗаполнено(с.Налог)) and XML(с.ВидОперации) not in искл:
            начислено[k] = начислено.get(k, 0.0) + float(с.Сумма)
        if (not это_удерж) and float(с.ВзносыВсего) == 0 and float(с.Сумма) != 0:
            зп_упр[k] = зп_упр.get(k, 0.0) + float(с.Сумма)

    тчн = obj.НачисленныйНДФЛ
    for i in range(тчн.Количество()):
        с = тчн.Получить(i)
        if XML(с.ФормаPL) != "Форма1":
            continue
        флн = с.ФизическоеЛицо.Наименование
        if нф and нф not in флн.lower():
            continue
        подр = с.ПодразделениеПредприятия.Наименование if erp.ЗначениеЗаполнено(с.ПодразделениеПредприятия) else "<пусто>"
        k = (флн, подр)
        ндфл[k] = ндфл.get(k, 0.0) + float(с.Сумма)

    нарушения = []
    for k in set(начислено) | set(зп_упр) | set(ндфл):
        лев = начислено.get(k, 0.0) - ндфл.get(k, 0.0)   # регистр Приход
        прав = зп_упр.get(k, 0.0)                          # перенос ПередачаНач
        if abs(лев - прав) >= 0.005:
            нарушения.append((k[0], k[1], round(лев, 2), round(прав, 2), round(лев - прав, 2)))
    return нарушения


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect(CONN)

    if "--all" in sys.argv:
        qd = erp.NewObject("Запрос")
        qd.Text = "ВЫБРАТЬ Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне ГДЕ НЕ ПометкаУдаления"
        вд = qd.Execute().Выбрать()
        всего = 0
        while вд.Следующий():
            нар = проверить_документ(erp, вд.Ссылка, None)
            всего += len(нар)
            for флн, подр, лев, прав, d in нар:
                print(f"  [{вд.Ссылка}] {флн} / {подр}: Приход={лев} != ЗПупр={прав} (Δ={d})")
        print(f"{'OK' if всего == 0 else 'FAIL'}: глобально нарушений Ф1 = {всего}")
        sys.exit(0 if всего == 0 else 1)

    q = erp.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне "
              "ГДЕ Номер = &Н И Дата >= &Д1 И Дата < &Д2")
    q.SetParameter("Н", "000000001")
    q.SetParameter("Д1", datetime.datetime(2025, 12, 1))
    q.SetParameter("Д2", datetime.datetime(2026, 1, 1))
    выб = q.Execute().Выбрать()
    assert выб.Следующий(), "Эталонный А_ОтражениеЗПпоКазне №1 (дек.2025) не найден"
    нар = проверить_документ(erp, выб.Ссылка, ФЛ_ЭТАЛОН)
    if нар:
        print(f"FAIL: {len(нар)} нарушений инварианта Ф1 по '{ФЛ_ЭТАЛОН}':")
        for флн, подр, лев, прав, d in нар:
            print(f"  {флн} / {подр}: Приход={лев} != ЗПупр={прав} (Δ={d})")
        sys.exit(1)
    print(f"OK: инвариант Ф1 выполняется для '{ФЛ_ЭТАЛОН}' (Приход = «Зарплата управл» до копейки)")


if __name__ == "__main__":
    main()
