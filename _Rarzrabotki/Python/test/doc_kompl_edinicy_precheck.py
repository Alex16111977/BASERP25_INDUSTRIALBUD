# -*- coding: utf-8 -*-
"""Rule #-1: запрос кэша единиц эталонов (ОбщиеНазванияНоменклатуры.Единица) + разведка данных."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# боевой текст ЕдиницыЭталонов
q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	ОН.Ссылка КАК Эталон,
	ОН.Единица КАК Единица
ИЗ
	Справочник.ОбщиеНазванияНоменклатуры КАК ОН
ГДЕ
	ОН.Ссылка В (&Эталоны)
"""
arr = buh.NewObject("Массив")
q2 = buh.NewObject("Запрос")
q2.Text = "ВЫБРАТЬ ПЕРВЫЕ 5 ОН.Ссылка КАК Ссылка ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК ОН ГДЕ НЕ ОН.ПометкаУдаления"
vb = q2.Execute().Выбрать()
while vb.Следующий():
    arr.Добавить(vb.Ссылка)
q.SetParameter("Эталоны", arr)
r = q.Execute().Выгрузить()
print(f"OK кэш-запрос, строк={r.Количество()}")
assert r.Количество() == 5

# разведка: сколько эталонов с пустой единицей / всего
q3 = buh.NewObject("Запрос")
q3.Text = """
ВЫБРАТЬ
	КОЛИЧЕСТВО(*) КАК Всего,
	СУММА(ВЫБОР КОГДА ОН.Единица = ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК БезЕдиницы
ИЗ
	Справочник.ОбщиеНазванияНоменклатуры КАК ОН
ГДЕ
	НЕ ОН.ПометкаУдаления
	И НЕ ОН.ЭтоГруппа
"""
try:
    st = q3.Execute().Выгрузить().Получить(0)
    print(f"Эталонов всего={st.Всего}, с пустой единицей={st.БезЕдиницы}")
except Exception as e:
    # ЭтоГруппа может отсутствовать (неиерархический справочник)
    q3.Text = q3.Text.replace("\n\tИ НЕ ОН.ЭтоГруппа", "")
    st = q3.Execute().Выгрузить().Получить(0)
    print(f"(без ЭтоГруппа) Эталонов всего={st.Всего}, с пустой единицей={st.БезЕдиницы}")
print("PRECHECK PASS")
