# -*- coding: utf-8 -*-
"""Как устроены входящие остатки в ПАП: контр-статья (Собственные средства),
регистраторы-ВводОстатков, полный баланс ПАП включая Собственные средства."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

LIT = "ДАТАВРЕМЯ(2025,12,31,23,59,59)"   # конец декабря (после ноябрьских вводов остатков)

# 1) ПАП ПОЛНЫЙ баланс по статьям ВКЛЮЧАЯ Собственные средства (signed cumul на дек)
print("=== 1. ПАП по статьям (ВКЛЮЧАЯ Собственные средства), signed cumul на 31.12.2025 ===")
q = erp.NewObject("Запрос")
q.Текст = f"""
ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= {LIT}
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
tot = 0.0
for r in q.Выполнить().Выгрузить():
    tot += f(r.КО)
    print(f"   {str(r.Ст):<42} {f(r.КО):>18,.2f}")
print(f"   {'ИТОГО ВСЕ статьи (должно быть ~0 если баланс полный)':<42} {tot:>18,.2f}")

# 2) Кто пишет «Собственные средства» в ПАП — типы регистраторов
print("\n=== 2. ПАП «Собственные средства»: типы регистраторов ===")
q2 = erp.NewObject("Запрос")
q2.Текст = f"""
ВЫБРАТЬ Т.Регистратор.Метаданные.Имя КАК Тип,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Регистратор) КАК Док
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= {LIT} И Т.Статья.Наименование = "Собственные средства"
СГРУППИРОВАТЬ ПО Т.Регистратор.Метаданные.Имя
"""
try:
    for r in q2.Выполнить().Выгрузить():
        print(f"   {str(r.Тип):<46} док={int(f(r.Док)):>4} КО={f(r.КО):>18,.2f}")
except Exception as e:
    ei=getattr(e,'excepinfo',None); print(f"   [{ei[2] if ei else e}] — пробую через ТИПЗНАЧЕНИЯ")
    q2b=erp.NewObject("Запрос")
    q2b.Текст=f"""ВЫБРАТЬ ТИПЗНАЧЕНИЯ(Т.Регистратор) КАК Тип,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
        ГДЕ Т.Период <= {LIT} И Т.Статья.Наименование = "Собственные средства"
        СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(Т.Регистратор)"""
    for r in q2b.Выполнить().Выгрузить():
        print(f"   {str(r.Тип):<46} КО={f(r.КО):>18,.2f}")

# 3) Есть ли ВВОД ОСТАТКОВ зарплаты в ПАП у кого-то (опорная статья «Оплата труда» на ноябрь)?
print("\n=== 3. ПАП «Оплата труда»: signed cumul по концам месяцев (видно ли что входящего НЕТ) ===")
for lbl, lit in [("на 30.11.2025","ДАТАВРЕМЯ(2025,11,30,23,59,59)"),
                 ("на 31.12.2025","ДАТАВРЕМЯ(2025,12,31,23,59,59)")]:
    q3=erp.NewObject("Запрос")
    q3.Текст=f"""ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Период <= {lit} И Т.Статья.Наименование = "Оплата труда" """
    print(f"   ПАП(ОТ) {lbl} = {f(q3.Выполнить().Выгрузить()[0].КО):>16,.2f}")

# 4) Как ОЗФУ пишет ПАП(ОТ): структура (Источник, ВидДвижения, парные статьи документа)
print("\n=== 4. Пример: какие статьи ПАП пишет ОДИН документ ОЗФУ (двойная запись) ===")
qd=erp.NewObject("Запрос")
qd.Текст="""ВЫБРАТЬ ПЕРВЫЕ 1 Регистратор КАК Р
ИЗ РегистрНакопления.ПрочиеАктивыПассивы
ГДЕ Регистратор ССЫЛКА Документ.ОтражениеЗарплатыВФинансовомУчете И Статья.Наименование = "Оплата труда" """
rr=qd.Выполнить().Выгрузить()
if rr.Количество():
    док=rr[0].Р
    q4=erp.NewObject("Запрос"); q4.УстановитьПараметр("Д",док)
    q4.Текст="""ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст, ПРЕДСТАВЛЕНИЕ(Т.Источник) КАК Ист,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т ГДЕ Т.Регистратор=&Д
        СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья), ПРЕДСТАВЛЕНИЕ(Т.Источник)"""
    print(f"   Документ ОЗФУ: {док}")
    s=0.0
    for r in q4.Выполнить().Выгрузить():
        s+=f(r.КО)
        print(f"      Статья={str(r.Ст):<32} Источник={str(r.Ист):<24} КО={f(r.КО):>16,.2f}")
    print(f"      Σ по документу (двойная запись → ~0?) = {s:,.2f}")
