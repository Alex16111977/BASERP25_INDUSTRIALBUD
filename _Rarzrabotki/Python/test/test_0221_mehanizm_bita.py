# -*- coding: utf-8 -*-
"""
§4.2 Верификация механизма 0221 по «завислой» номенклатуре (Біта РZ 2*50 мм).
Показать движения по регистраторам (Обороты, Периодичность=Регистратор) и
сравнить Сумму Кт 0221 у ВозвратТоваровПоставщику с ценой строки ТЧ (СуммаБезНДС)
и с балансовой стоимостью прихода. Rule #-1.
"""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

def S(x):
    try: return buh.String(x)
    except Exception:
        try: return str(x)
        except Exception: return "<?>"

def имядок(рег):
    try: return S(рег.Метаданные().Имя)
    except Exception: return "<?>"

def uid(x):
    try: return S(x.УникальныйИдентификатор())
    except Exception: return S(x)

счет0221 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("0221").Ссылка

# --- 1. целевая номенклатура (резидуум ~548.80) --------------------------
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Ост.Субконто1 КАК К, Ост.Субконто2 КАК Н, Ост.Субконто3 КАК С,
       Ост.Организация КАК Орг, Ост.СуммаОстатокДт КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет = &Счет) КАК Ост
ГДЕ Ост.КоличествоОстатокДт = 0 И Ост.СуммаОстатокДт <> 0
"""
q.УстановитьПараметр("Счет", счет0221)
q.УстановитьПараметр("НаДату", datetime.datetime(2026, 7, 13, 23, 59, 59))
r = q.Выполнить().Выгрузить()
цель = None
for i in range(r.Количество()):
    s = r.Получить(i)
    if 548.0 < float(s.Сумма) < 549.0:
        цель = s; break
print(f"ЦЕЛЬ: Контрагент={S(цель.К)} | Номенклатура={S(цель.Н)} | Склад={S(цель.С)} | Орг={S(цель.Орг)} | резидуум={float(цель.Сумма):.2f}")
ном_uid = uid(цель.Н)

# --- 2. движения 0221 по номенклатуре, по регистраторам ------------------
q2 = buh.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    Об.Регистратор КАК Рег,
    Об.КоличествоОборотДт КАК КолДт, Об.СуммаОборотДт КАК СумДт,
    Об.КоличествоОборотКт КАК КолКт, Об.СуммаОборотКт КАК СумКт
ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(, , Регистратор, Счет = &Счет, , Субконто2 = &Ном) КАК Об
"""
q2.УстановитьПараметр("Счет", счет0221)
q2.УстановитьПараметр("Ном", цель.Н)
try:
    d = q2.Выполнить().Выгрузить()
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e
    print("Обороты-запрос упал:", msg); sys.exit(0)

строки = [d.Получить(i) for i in range(d.Количество())]
def дата(s):
    try: return s.Рег.Дата
    except Exception: return datetime.datetime(1,1,1)
строки.sort(key=дата)

прих_кол = прих_сум = расх_кол = расх_сум = 0.0
возвраты = []
print(f"\n{'Тип документа':<34} | {'Дата':<10} | {'КолДт':>6} {'СумДт':>10} | {'КолКт':>6} {'СумКт':>10} | {'цена/ед':>9}")
print("-"*104)
for s in строки:
    кд, сд = float(s.КолДт), float(s.СумДт)
    кк, ск = float(s.КолКт), float(s.СумКт)
    прих_кол += кд; прих_сум += сд; расх_кол += кк; расх_сум += ск
    цена = (сд/кд) if кд else ((ск/кк) if кк else 0)
    тип = имядок(s.Рег)
    print(f"{тип[:34]:<34} | {S(дата(s))[:10]:<10} | {кд:>6.1f} {сд:>10.2f} | {кк:>6.1f} {ск:>10.2f} | {цена:>9.4f}")
    if "Возврат" in тип and кк:
        возвраты.append((s.Рег, кк, ск))
print("-"*104)
print(f"ПРИХОД Дт: кол={прих_кол:.1f} сум={прих_сум:.2f} цена/ед={(прих_сум/прих_кол if прих_кол else 0):.4f}")
print(f"РАСХОД Кт: кол={расх_кол:.1f} сум={расх_сум:.2f} цена/ед={(расх_сум/расх_кол if расх_кол else 0):.4f}")
print(f"РЕЗИДУУМ : кол={прих_кол-расх_кол:.2f} сум={прих_сум-расх_сум:.2f}")

# --- 3. РЕШАЮЩИЙ ТЕСТ: Сумма Кт 0221 == цена строки ТЧ? или партия-стоимость? ---
print("\n=== Сверка Кт 0221 c ТЧ Товары документа возврата ===")
for рег, кк, ск in возвраты:
    try:
        об = рег.ПолучитьОбъект() if hasattr(рег, "ПолучитьОбъект") else рег
    except Exception:
        об = рег
    print(f"\nДок: {S(рег)} | движение Кт 0221: кол={кк:.1f} сумма={ск:.2f}")
    try:
        for стр in об.Товары:
            if uid(стр.Номенклатура) == ном_uid:
                поля = []
                for имя in ["Количество","Сумма","СуммаБезНДС","Себестоимость","СписыватьПоУказаннойСтоимости","СчетУчетаБУ","КорСчетСписанияБУ"]:
                    try: поля.append(f"{имя}={S(getattr(стр, имя))}")
                    except Exception: поля.append(f"{имя}=<нет>")
                print("   ТЧ Товары:", " | ".join(поля))
    except Exception as e:
        print("   не удалось прочитать ТЧ:", e)
