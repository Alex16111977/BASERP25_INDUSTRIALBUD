erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
TOL = 0.01
ПЕРИОД = datetime.datetime(2025, 12, 31, 23, 59, 59)


def forma(f):
    if not erp.ЗначениеЗаполнено(f):
        return "(пусто)"
    x = erp.XMLСтрока(f)
    return "Форма1" if "Форма1" in x else ("Форма2" if "Форма2" in x else x)


q = erp.NewObject("Запрос")
q.Текст = ('ВЫБРАТЬ Р.Ссылка КАК С, Р.Организация КАК Орг ИЗ Документ.РаспределениеПрочихЗатрат КАК Р '
           'ГДЕ Р.Номер="00000000279" И Р.Дата=ДАТАВРЕМЯ(2025,12,31,23,59,59)')
s = q.Выполнить().Выбрать(); s.Следующий(); doc = s.С; org = s.Орг


def by_form():
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("Рег", doc)
    qq.Текст = ("ВЫБРАТЬ П.ФормаPL КАК Ф, КОЛИЧЕСТВО(*) КАК К, СУММА(П.Сумма) КАК С "
                "ИЗ РегистрНакопления.ПрочиеРасходы КАК П ГДЕ П.Регистратор=&Рег И П.Активность СГРУППИРОВАТЬ ПО П.ФормаPL")
    r = {}; sel = qq.Выполнить().Выбрать()
    while sel.Следующий():
        r[forma(sel.Ф)] = (int(sel.К), float(sel.С) if sel.С is not None else 0.0)
    return r


