        зап.НаправлениеДеятельности = ст.НаправлениеДеятельности; зап.НалоговоеНазначение = ст.НалоговоеНазначение
        зап.СтатьяРасходов = ст.СтатьяРасходов; зап.АналитикаРасходов = ст.АналитикаРасходов
        зап.ФормаPL = ст.ФормаPL
        зап.Сумма = ст.Сумма; зап.СуммаБезНДС = ст.СуммаБезНДС; зап.СуммаУпр = ст.СуммаУпр; зап.СуммаУпрБезНДС = ст.СуммаУпрБезНДС
        зап.СуммаРегл = ст.СуммаРегл; зап.СуммаРеглБезНДС = ст.СуммаРеглБезНДС; зап.НДСРегл = ст.НДСРегл
        зап.ПостояннаяРазница = ст.ПостояннаяРазница; зап.ВременнаяРазница = ст.ВременнаяРазница
