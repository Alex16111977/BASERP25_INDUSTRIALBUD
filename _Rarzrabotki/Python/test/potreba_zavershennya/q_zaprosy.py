def run(name, params=None):
    q = erp.NewObject("Запрос")
    q.Текст = ZAPROSY[name]
    for k, v in (params or {}).items():
        q.УстановитьПараметр(k, v)
    try:
        tz = q.Выполнить().Выгрузить()
    except Exception as e:  # noqa: BLE001
        info = getattr(e, "excepinfo", None)
        print(f"FAIL {name}: {info[2] if info else e}")
        raise SystemExit(1)
    print(f"OK   {name}: строк {tz.Количество()}")
    return tz


