# -*- coding: utf-8 -*-
"""Касса-нога named-источника: сверка «Денежные средства (наличные)» —
регистр свёртки vs ПАП(по источникам) vs ПАП(все источники net) vs штатный остаток кассы.
Нужно понять: занижать/завышать ли кассу при захвате named-ноги."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# статья «Денежные средства (наличные)»
qs = erp.NewObject("Запрос")
qs.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов "
            "ГДЕ Наименование = \"Денежные средства (наличные)\"")
КАС = qs.Выполнить().Выгрузить()[0].С
print(f"Статья КАС UUID = {erp.String(КАС.УникальныйИдентификатор())}")

LIT = "ДАТАВРЕМЯ(2026,1,31,23,59,59)"

# 1) Регистр свёртки А_ОтчетБаланс_Свод по статье «ДенСр наличные» — янв
print("\n=== (1) Регистр свёртки «ДенСр наличные» (док января, по Source) ===")
q1 = erp.NewObject("Запрос")
q1.УстановитьПараметр("КАС", КАС)
q1.Текст = """
ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Рег.Source) КАК Src, СУММА(Рег.СуммаКонечныйОстаток) КАК КО, КОЛИЧЕСТВО(*) КАК Стр
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Статья = &КАС И Рег.Регистратор.Месяц = ДАТАВРЕМЯ(2026,1,1)
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Рег.Source)
"""
reg_total = 0.0
for r in q1.Выполнить().Выгрузить():
    src = r.Src if r.Src else "(пусто)"
    reg_total += f(r.КО)
    print(f"   Source='{src:<28}' строк={int(f(r.Стр)):>4} КО={f(r.КО):>16,.2f}")
print(f"   >>> РЕГИСТР ИТОГО (PowerBI) = {reg_total:>16,.2f}")

# 2) ПАП(КАС) по источникам, all
print("\n=== (2) ПАП «ДенСр наличные» по источникам (cumul янв) ===")
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("КАС", КАС)
q2.Текст = f"""
ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Т.Источник) КАК Src,
    ВЫБОР КОГДА Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка) ТОГДА "пусто" ИНАЧЕ "named" КОНЕЦ КАК Тип,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= {LIT} И Т.Статья = &КАС
СГРУППИРОВАТЬ ПО Т.Источник
"""
pap_all = 0.0
for r in q2.Выполнить().Выгрузить():
    src = r.Src if r.Src else "(пусто)"
    pap_all += f(r.КО)
    print(f"   Источник='{src:<28}' КО={f(r.КО):>16,.2f}")
print(f"   >>> ПАП ИТОГО все источники (штатный баланс) = {pap_all:>16,.2f}")

# 3) штатный остаток кассы РН.ДенежныеСредстваНаличные
print("\n=== (3) Штатный РН.ДенежныеСредстваНаличные.Остатки на 31.01.2026 ===")
q3 = erp.NewObject("Запрос")
q3.Текст = f"""
ВЫБРАТЬ СУММА(Ост.СуммаОстаток) КАК Ост
ИЗ РегистрНакопления.ДенежныеСредстваНаличные.Остатки({LIT}) КАК Ост
"""
try:
    print(f"   ДенежныеСредстваНаличные остаток = {f(q3.Выполнить().Выгрузить()[0].Ост):>16,.2f}")
except Exception as e:
    print(f"   [FAIL: {e}]")

print("\n=== ВЫВОД ===")
print(f"   Регистр/PowerBI касса  = {reg_total:>16,.2f}")
print(f"   ПАП касса все источники= {pap_all:>16,.2f}")
print(f"   Δ (нужно скорректировать) = {pap_all-reg_total:>16,.2f}")
