# -*- coding: utf-8 -*-
"""Pre-тест Rule #-1: перенос остатков налогов BuhBud->ERP.
Валидирует БЕЗ записи в боевые данные (in-memory объекты, Записать НЕ вызываем):
  A: BuhBud-запрос налоговых сальдо (синтаксис, субконто 'Податки', фильтр А_ВБалансе);
  B: ERP - у всех орг с А_ВБалансе заполнен А_ПодразделениеЗарплатаБух;
  C: карта счёт->Перечисление.ТипыНалогов (каждый тип существует);
  D: in-memory наборы движений КорректировкаРегистров.Движения.ПрочиеАктивыПассивы и
     механизм записи ОперацияБух в Хозрасчетный (набор движений или ТЧ)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom, datetime
pythoncom.CoInitialize()

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
fails = []


def errmsg(e):
    return e.excepinfo[2] if getattr(e, 'excepinfo', None) else str(e)


# ======================================================================
# B (выполняем первым - даёт список ЕДРПОУ для фильтра BuhBud):
# А_ВБалансе и А_ПодразделениеЗарплатаБух живут ТОЛЬКО в ERP.
# BuhBud.Справочник.Организации НЕ имеет реквизита А_ВБалансе,
# поэтому фильтр А_ВБалансе применяем ERP-side по списку ЕДРПОУ.
# ======================================================================
print("=" * 60)
print("B: А_ВБалансе + А_ПодразделениеЗарплатаБух (ERP)")
print("=" * 60)
qo = erp.NewObject("Запрос")
qo.Текст = """ВЫБРАТЬ
    Орг.Наименование КАК Наим,
    Орг.КодПоЕДРПОУ КАК ЕДРПОУ,
    Орг.А_ПодразделениеЗарплатаБух КАК Подр
ИЗ Справочник.Организации КАК Орг
ГДЕ Орг.А_ВБалансе"""
to = qo.Выполнить().Выгрузить()
все_орг = []
пусто = []
список_едрпоу = []
for r in to:
    все_орг.append(str(r.Наим))
    список_едрпоу.append(str(r.ЕДРПОУ).strip())
    if not erp.ЗначениеЗаполнено(r.Подр):
        пусто.append(str(r.Наим))
print(f"B: орг с А_ВБалансе = {to.Количество()}: {все_орг}")
print(f"B: ЕДРПОУ-список (фильтр BuhBud) = {список_едрпоу}")
print(f"B: без А_ПодразделениеЗарплатаБух = {len(пусто)}: {пусто}")
if len(пусто) > 0:
    fails.append(f"B: у орг {пусто} пуст А_ПодразделениеЗарплатаБух - подразделение ПАП не определить")
if not список_едрпоу:
    fails.append("B: нет орг с А_ВБалансе - нечего фильтровать")


# ======================================================================
# A: BuhBud-запрос налоговых сальдо (Кт-Дт) по налоговым счетам.
# Субконто: ПРЕДСТАВЛЕНИЕ(Ост.Субконто1) -> вид налога (наименование).
# Фильтр организаций: по списку ЕДРПОУ (ERP-side А_ВБалансе).
# Глобальные Дата/КонецДня недоступны через COM-прокси -> datetime.
# ======================================================================
СЧЕТА = "6411,6412,6413,6414,6415,6417,642,651"
print("\n" + "=" * 60)
print("A: BuhBud налоговые сальдо на КонецДня(30.11.2025)")
print("=" * 60)

ДатаОст = datetime.datetime(2025, 11, 30, 23, 59, 59)
МассивСчетов = buh.NewObject("Массив")
for код in СЧЕТА.split(","):
    МассивСчетов.Добавить(код.strip())
МассивЕДРПОУ = buh.NewObject("Массив")
for е in список_едрпоу:
    МассивЕДРПОУ.Добавить(е)

ТекстA = """ВЫБРАТЬ
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    Ост.Организация.Наименование КАК ОргНаим,
    Ост.Счет.Код КАК КодСчета,
    ПРЕДСТАВЛЕНИЕ(Ост.Субконто1) КАК ВидНалогаНаим,
    Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт КАК Сальдо
ИЗ
    РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&Дата, &Дата, , , Счет.Код В (&Счета), , ) КАК Ост
ГДЕ
    Ост.Организация.КодПоЕДРПОУ В (&СписокЕДРПОУ)
    И (Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) <> 0"""

q = buh.NewObject("Запрос")
q.Текст = ТекстA
q.УстановитьПараметр("Дата", ДатаОст)
q.УстановитьПараметр("Счета", МассивСчетов)
q.УстановитьПараметр("СписокЕДРПОУ", МассивЕДРПОУ)
try:
    tb = q.Выполнить().Выгрузить()
    print(f"A: строк сальдо!=0 = {tb.Количество()}")
    seen = {}
    примеры = []
    for r in tb:
        код = str(r.КодСчета).strip()
        seen[код] = seen.get(код, 0) + 1
        if len(примеры) < 3:
            примеры.append((str(r.ОргНаим), код, str(r.ВидНалогаНаим), float(r.Сальдо)))
    print(f"A: счета с остатками = {seen}")
    print("A: примеры (орг/счёт/видналога/сальдо):")
    for p in примеры:
        print(f"     {p[0]} | {p[1]} | {p[2]} | {p[3]:.2f}")
    if tb.Количество() == 0:
        fails.append("A: пусто - нет налоговых остатков (проверить дату/счета)")
except Exception as e:
    fails.append(f"A: BuhBud-запрос упал: {errmsg(e)}")


# ======================================================================
# C: карта счёт->ТипНалога
# ======================================================================
print("\n" + "=" * 60)
print("C: карта счёт->Перечисление.ТипыНалогов")
print("=" * 60)
МАП = {"6411": "НДФЛ", "642": "ВоенныйСбор", "651": "НачисленныйЕСВ", "6412": "НДС",
       "6413": "НалогНаПрибыль", "6414": "ЕдиныйНалог", "6415": "ДругиеНалоги", "6417": "ДругиеНалоги"}
for код, имя in МАП.items():
    try:
        зн = getattr(erp.Перечисления.ТипыНалогов, имя)
        if not erp.ЗначениеЗаполнено(зн):
            fails.append(f"C: ТипыНалогов.{имя} пуст")
        else:
            print(f"  {код} -> ТипыНалогов.{имя} OK")
    except Exception:
        fails.append(f"C: Перечисления.ТипыНалогов.{имя} не существует")


# ======================================================================
# D: in-memory наборы движений (БЕЗ Записать!)
# ======================================================================
print("\n" + "=" * 60)
print("D: in-memory наборы движений (без Записать)")
print("=" * 60)

# --- D-ПАП: КорректировкаРегистров.Движения.ПрочиеАктивыПассивы ---
try:
    дк = erp.Документы.КорректировкаРегистров.СоздатьДокумент()
    нп = дк.Движения.ПрочиеАктивыПассивы
    дв = нп.Добавить()
    дв.ВидДвижения = erp.ВидДвиженияНакопления.Приход
    дв.Период = ДатаОст
    дв.Активность = True
    дв.Статья = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.Налоги
    дв.Аналитика = erp.Перечисления.ТипыНалогов.НДФЛ
    дв.Источник = erp.Перечисления.ИсточникиУправленческогоБаланса.ПустаяСсылка()
    дв.ВидИсточника = erp.Перечисления.ВидыИсточниковДвижений.ПустаяСсылка()
    дв.Сумма = 100
    # Организация / Подразделение - присвоим первую А_ВБалансе-орг для проверки приёма
    орг1 = erp.Справочники.Организации.НайтиПоРеквизиту("КодПоЕДРПОУ", "40645273")
    if erp.ЗначениеЗаполнено(орг1):
        дв.Организация = орг1
        дв.Подразделение = орг1.А_ПодразделениеЗарплатаБух
    print("D-ПАП: КорректировкаРегистров.Движения.ПрочиеАктивыПассивы - поля приняты (in-memory)")
except Exception as e:
    fails.append(f"D-ПАП: {errmsg(e)}")

# --- D-Хозрасчетный: ОперацияБух - выяснить механизм ---
try:
    об = erp.Документы.ОперацияБух.СоздатьДокумент()
    # Перечислим, какие наборы движений есть у ОперацияБух
    наборы = []
    try:
        for н in об.Движения:
            наборы.append(н.Метаданные().Имя)
    except Exception as e2:
        print(f"D-ОБ: не удалось перечислить .Движения: {errmsg(e2)}")
    print(f"D-ОБ: наборы движений ОперацияБух = {наборы}")

    if "Хозрасчетный" in наборы:
        нх = об.Движения.Хозрасчетный
        дх = нх.Добавить()
        дх.Период = ДатаОст
        дх.Активность = True
        дх.СчетДт = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду("00")
        дх.СчетКт = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду("6411")
        дх.Сумма = 100
        try:
            дх.Содержание = "Ввод начального остатка по налогам"
        except Exception:
            pass
        try:
            дх.Организация = орг1
        except Exception as e3:
            print(f"D-ОБ: поле Организация не принято движением Хозрасчетный: {errmsg(e3)}")
        print("D-Хозрасчетный(ОперацияБух): набор есть, поля приняты (in-memory)")
        print(f"D: счёт00 заполнен={erp.ЗначениеЗаполнено(дх.СчетДт)}, 6411 заполнен={erp.ЗначениеЗаполнено(дх.СчетКт)}")
        # Покажем доступные поля движения через метаданные регистра
        try:
            рег = erp.Метаданные.РегистрыБухгалтерии.Хозрасчетный
            изм = [x.Имя for x in рег.Измерения]
            рес = [x.Имя for x in рег.Ресурсы]
            рекв = [x.Имя for x in рег.Реквизиты]
            print(f"D: РБ.Хозрасчетный Измерения={изм}")
            print(f"D: РБ.Хозрасчетный Ресурсы={рес}")
            print(f"D: РБ.Хозрасчетный Реквизиты={рекв}")
        except Exception as em:
            print(f"D: не удалось прочитать метаданные регистра: {errmsg(em)}")
    else:
        # запасной механизм - ТЧ операций
        fails.append("D-Хозрасчетный(ОперацияБух): набора Движения.Хозрасчетный НЕТ - проверить ТЧ операций")
        # перечислим ТЧ документа
        try:
            тч = [t.Имя for t in erp.Метаданные.Документы.ОперацияБух.ТабличныеЧасти]
            print(f"D-ОБ: ТЧ документа ОперацияБух = {тч}")
        except Exception as et:
            print(f"D-ОБ: не удалось прочитать ТЧ: {errmsg(et)}")
except Exception as e:
    fails.append(f"D-Хозрасчетный(ОперацияБух): {errmsg(e)}")


print("\n" + "=" * 60)
print("PRETEST PASS" if not fails else f"PRETEST FAIL: {fails}")
print("=" * 60)
sys.exit(1 if fails else 0)
