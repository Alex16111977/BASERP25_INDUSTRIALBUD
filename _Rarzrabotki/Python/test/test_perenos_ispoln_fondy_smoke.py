def хозрасчетный_нетто_по_счету(reg_ob):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("ОБ", reg_ob)
    q.Текст = """ВЫБРАТЬ Х.СчетДт.Код КАК КодДт, Х.СчетКт.Код КАК КодКт, Х.Сумма КАК Сумма
        ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х ГДЕ Х.Регистратор = &ОБ"""
    нетто, сумДт, сумКт = {}, 0.0, 0.0
    в = q.Выполнить().Выбрать()
    while в.Следующий():
        с = float(в.Сумма)
        кд = str(в.КодДт).strip() if в.КодДт is not None else ""
        кк = str(в.КодКт).strip() if в.КодКт is not None else ""
        сумДт += с; сумКт += с
        if кк and кк != "00":
            нетто[кк] = round(нетто.get(кк, 0.0) + с, 2)
        if кд and кд != "00":
            нетто[кд] = round(нетто.get(кд, 0.0) - с, 2)
    return нетто, round(сумДт, 2), round(сумКт, 2)


def субконто_по_счетам(reg_ob):
    """Через НАБОР ЗАПИСЕЙ: для каждой записи 6853 — заполнен ли Контрагент; для 378 — пуст ли."""
    сч6853 = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду("6853")
    вс6853 = None
    for вс in сч6853.ВидыСубконто:
        вс6853 = вс.ВидСубконто; break
    нб = erp.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
    нб.Отбор.Регистратор.Установить(reg_ob)
    нб.Прочитать()
    есть6853 = 0; с_контр6853 = 0; есть378 = 0; с_суб378 = 0
    for i in range(нб.Количество()):
        зап = нб.Получить(i)
        кодДт = str(зап.СчетДт.Код).strip()
        кодКт = str(зап.СчетКт.Код).strip()
        if "6853" in (кодДт, кодКт):
            есть6853 += 1
            колл = зап.СубконтоКт if кодКт == "6853" else зап.СубконтоДт
            знач = колл.Получить(вс6853) if вс6853 is not None else None
            if ЗАП(знач):
                с_контр6853 += 1
        if "378" in (кодДт, кодКт):
            есть378 += 1
            # 378 субконто = «Статьи деклараций»; контрагент-вид у него отсутствует -> Получить даст Неопределено
            знач378 = (зап.СубконтоДт if кодДт == "378" else зап.СубконтоКт).Получить(вс6853) if вс6853 is not None else None
            if ЗАП(знач378):
                с_суб378 += 1
    return есть6853, с_контр6853, есть378, с_суб378


