def агрегат_тч_по_статье(o):
    """Σ СуммаСальдо (signed Кт-Дт) по СтатьяПАП; ключ = XMLСтрока(СтатьяПАП)."""
    res = {}
    for i in range(o.Остатки.Количество()):
        стр = o.Остатки.Получить(i)
        к = XML(стр.СтатьяПАП)
        res[к] = round(res.get(к, 0.0) + float(стр.СуммаСальдо), 2)
    return res


def агрегат_тч_по_счету_signed(o):
    signed = {}
    for i in range(o.Остатки.Количество()):
        стр = o.Остатки.Получить(i)
        if not ЗАП(стр.Счет):
            continue
        код = str(стр.КодСчета).strip()
        signed[код] = round(signed.get(код, 0.0) + float(стр.СуммаСальдо), 2)
    return signed


def пап_по_статье(reg_kr):
    """ПАП этого регистратора: signed по Статья (Расход:+ / Приход:-) == ТЧ (т.к. статья Пассив)."""
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("КР", reg_kr)
    q.Текст = """ВЫБРАТЬ П.Статья КАК Статья,
        СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
            ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Сумма
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
        ГДЕ П.Регистратор = &КР СГРУППИРОВАТЬ ПО П.Статья"""
    res = {}
    в = q.Выполнить().Выбрать()
    while в.Следующий():
        res[XML(в.Статья)] = round(float(в.Сумма), 2)
    return res


