"""
Тест #1: Запит дисбалансу по підрозділах з регістру ПрочиеАктивыПассивы
для конкретного документа-реєстратора.

Перевіряємо на прикладі: Перемещение товаров ІБ00-001591 от 17.12.2025 12:13:48
Очікуємо: 2 підрозділи з протилежними знаками (Глобіно-2 і КМД-2)

Використання:
  python test_balance_disbalance_query.py
"""

import sys
import win32com.client
import pythoncom
from datetime import datetime

CONN_STR = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def connect():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONN_STR)
    print("Підключення до BaseERP — OK")
    return conn


def find_document(conn, doc_type, number_like, date_from, date_to):
    """Знайти документ за номером і періодом"""
    q = conn.NewObject("Запрос")
    q.Текст = (
        f"ВЫБРАТЬ Док.Ссылка КАК Ссылка, Док.Номер КАК Номер, Док.Дата КАК Дата"
        f" ИЗ Документ.{doc_type} КАК Док"
        f" ГДЕ Док.Номер ПОДОБНО &Номер"
        f"   И Док.Дата МЕЖДУ &НачДата И &КонДата"
    )
    q.УстановитьПараметр("Номер", f"%{number_like}%")
    q.УстановитьПараметр("НачДата", date_from)
    q.УстановитьПараметр("КонДата", date_to)

    res = q.Выполнить()
    sel = res.Выбрать()
    if sel.Следующий():
        return sel.Ссылка
    return None


def query_disbalance(conn, doc_ref):
    """Запит дисбалансу по підрозділах для конкретного документа-реєстратора.
    Використовуємо пряму таблицю рухів (не віртуальну Обороты),
    бо Регистратор — стандартний реквізит, а не вимір."""
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ"
        "   АП.Подразделение КАК Подразделение,"
        "   АП.Организация КАК Организация,"
        "   СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)"
        "       ТОГДА АП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Дебет,"
        "   СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)"
        "       ТОГДА АП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Кредит,"
        "   СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)"
        "       ТОГДА АП.Сумма ИНАЧЕ -АП.Сумма КОНЕЦ) КАК Контроль"
        " ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК АП"
        " ГДЕ АП.Регистратор = &Регистратор"
        "   И НЕ АП.Статья В ("
        "       ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),"
        "       ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))"
        " СГРУППИРОВАТЬ ПО АП.Подразделение, АП.Организация"
        " ИМЕЮЩИЕ СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)"
        "       ТОГДА АП.Сумма ИНАЧЕ 0 КОНЕЦ)"
        "   <> СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)"
        "       ТОГДА АП.Сумма ИНАЧЕ 0 КОНЕЦ)"
    )
    q.УстановитьПараметр("Регистратор", doc_ref)

    res = q.Выполнить()
    sel = res.Выбрать()

    departments = []
    while sel.Следующий():
        dept_name = ""
        if conn.ЗначениеЗаполнено(sel.Подразделение):
            dept_name = sel.Подразделение.Наименование
        org_name = ""
        if conn.ЗначениеЗаполнено(sel.Организация):
            org_name = sel.Организация.Наименование
        departments.append({
            'Подразделение': dept_name,
            'ПодразделениеСсылка': sel.Подразделение,
            'Организация': org_name,
            'ОрганизацияСсылка': sel.Организация,
            'Дебет': float(sel.Дебет) if sel.Дебет else 0,
            'Кредит': float(sel.Кредит) if sel.Кредит else 0,
            'Контроль': float(sel.Контроль) if sel.Контроль else 0,
        })

    return departments


def query_details(conn, doc_ref):
    """Деталі по статтях для документа"""
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ"
        "   АП.Подразделение КАК Подразделение,"
        "   АП.Статья КАК Статья,"
        "   СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)"
        "       ТОГДА АП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Дебет,"
        "   СУММА(ВЫБОР КОГДА АП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)"
        "       ТОГДА АП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Кредит"
        " ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК АП"
        " ГДЕ АП.Регистратор = &Регистратор"
        "   И НЕ АП.Статья В ("
        "       ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),"
        "       ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))"
        " СГРУППИРОВАТЬ ПО АП.Подразделение, АП.Статья"
    )
    q.УстановитьПараметр("Регистратор", doc_ref)
    return q.Выполнить()


def main():
    conn = connect()

    date_from = datetime(2025, 12, 1)
    date_to = datetime(2025, 12, 31, 23, 59, 59)

    # === Тест 1: ПеремещениеТоваров ІБ00-001591 (очікуємо 2 підрозділи) ===
    print("\n" + "=" * 60)
    print("ТЕСТ 1: ПеремещениеТоваров ІБ00-001591")
    print("=" * 60)

    doc_ref = find_document(conn, "ПеремещениеТоваров", "001591", date_from, date_to)
    if not doc_ref:
        print("  ПОМИЛКА: документ не знайдено!")
        return

    print(f"  Знайдено: {doc_ref}")

    departments = query_disbalance(conn, doc_ref)
    for d in departments:
        role = "ДЕБІТОР" if d['Контроль'] > 0 else "КРЕДИТОР"
        print(f"  {d['Подразделение']}: Дебет={d['Дебет']:.2f}, Кредит={d['Кредит']:.2f}, "
              f"Контроль={d['Контроль']:.2f} [{role}]")

    print(f"\n  Кількість підрозділів з дисбалансом: {len(departments)}")
    if len(departments) >= 2:
        print("  РЕЗУЛЬТАТ: OK — 2+ підрозділи, можна створювати Взаємозалік")
        debtors = [d for d in departments if d['Контроль'] > 0]
        creditors = [d for d in departments if d['Контроль'] < 0]
        for d in debtors:
            print(f"    Дебітор: {d['Подразделение']} сума={d['Контроль']:.2f}")
        for c in creditors:
            print(f"    Кредитор: {c['Подразделение']} сума={abs(c['Контроль']):.2f}")
    elif len(departments) == 1:
        print("  РЕЗУЛЬТАТ: Тільки 1 підрозділ — Взаємозалік НЕ створюється")
    else:
        print("  РЕЗУЛЬТАТ: Немає дисбалансу")

    # Деталі по статтях
    print("\n  Деталі по статтях:")
    res = query_details(conn, doc_ref)
    sel = res.Выбрать()
    while sel.Следующий():
        deb = float(sel.Дебет) if sel.Дебет else 0
        kre = float(sel.Кредит) if sel.Кредит else 0
        dept = sel.Подразделение.Наименование if conn.ЗначениеЗаполнено(sel.Подразделение) else "<пусто>"
        stat = sel.Статья.Наименование if conn.ЗначениеЗаполнено(sel.Статья) else "<пусто>"
        print(f"    {dept} | {stat} | Дб={deb:.2f} | Кр={kre:.2f}")

    # === Тест 2: СписаниеНедостачТоваров ІБ00-000752 (очікуємо 1 підрозділ) ===
    print("\n" + "=" * 60)
    print("ТЕСТ 2: СписаниеНедостачТоваров ІБ00-000752")
    print("=" * 60)

    doc_ref2 = find_document(conn, "СписаниеНедостачТоваров", "000752", date_from, date_to)
    if not doc_ref2:
        print("  Документ не знайдено")
    else:
        print(f"  Знайдено: {doc_ref2}")
        departments2 = query_disbalance(conn, doc_ref2)
        for d in departments2:
            print(f"  {d['Подразделение']}: Контроль={d['Контроль']:.2f}")

        print(f"\n  Кількість підрозділів: {len(departments2)}")
        if len(departments2) == 1:
            print("  РЕЗУЛЬТАТ: OK — 1 підрозділ, Взаємозалік НЕ створюється")
        elif len(departments2) == 0:
            print("  РЕЗУЛЬТАТ: Немає дисбалансу для цього документа")
        else:
            print(f"  РЕЗУЛЬТАТ: {len(departments2)} підрозділів")

    # === Тест 3: ПеремещениеТоваров ІБ00-001666 (ще один приклад з Глобіно-2) ===
    print("\n" + "=" * 60)
    print("ТЕСТ 3: ПеремещениеТоваров ІБ00-001666")
    print("=" * 60)

    doc_ref3 = find_document(conn, "ПеремещениеТоваров", "001666", date_from, date_to)
    if not doc_ref3:
        print("  Документ не знайдено")
    else:
        print(f"  Знайдено: {doc_ref3}")
        departments3 = query_disbalance(conn, doc_ref3)
        for d in departments3:
            role = "ДЕБІТОР" if d['Контроль'] > 0 else "КРЕДИТОР"
            print(f"  {d['Подразделение']}: Контроль={d['Контроль']:.2f} [{role}]")
        print(f"\n  Кількість підрозділів: {len(departments3)}")

    print("\n=== Тести завершено ===")


if __name__ == "__main__":
    main()
