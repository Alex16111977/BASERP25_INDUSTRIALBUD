FAILS = 0


def run(label, fn):
    global FAILS
    try:
        msg = fn()
        print(f"{label} OK{(', ' + msg) if msg else ''}")
    except Exception as e:
        FAILS += 1
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"{label} FAIL: {e.excepinfo[2]}")
        else:
            print(f"{label} FAIL: {e}")


