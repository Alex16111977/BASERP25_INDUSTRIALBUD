# --- Q4: BuhBud обороты по регистратору, Субконто1 = счёт (И:1535-1545) ---
Q4_REG = None


def q4():
    global Q4_REG
    assert Q3_ACCOUNT is not None, "нет ERP-счёта"
    iban = str(erp.String(Q3_ACCOUNT.НомерСчета)).strip()
    qb = buh.NewObject("Запрос")
    qb.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 1
    	Ссылка, Наименование
    ИЗ Справочник.БанковскиеСчета
    ГДЕ НомерСчета = &НомерСчета
    	И Наименование <> ""
    	И Наименование НЕ ПОДОБНО "%$$$%"
    УПОРЯДОЧИТЬ ПО Наименование
    """
    qb.SetParameter("НомерСчета", iban)
    rb = qb.Execute().Выгрузить()
    if rb.Количество() == 0:
        return f"SKIP: рахунок BuhBud по IBAN {iban} не знайдено"
    bank = rb.Получить(0).Ссылка

    q = buh.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
    	Т.Регистратор КАК Регистратор,
    	ПРЕДСТАВЛЕНИЕ(Т.Регистратор) КАК Представление,
    	Т.СуммаОборотДт КАК Приход,
    	Т.СуммаОборотКт КАК Расход
    ИЗ
    	РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(
    		&НачалоПериода, &КонецПериода, Регистратор, ,
    		Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках)), ,
    		Субконто1 = &БанкРахунок) КАК Т
    """
    q.SetParameter("НачалоПериода", NACH)
    q.SetParameter("КонецПериода", KON)
    q.SetParameter("БанкРахунок", bank)
    r = q.Execute().Выгрузить()
    if r.Количество() > 0:
        Q4_REG = r.Получить(0).Регистратор
    return f"рядків={r.Количество()}"


# --- Q5: BuhBud сумма Дт/Кт по регистратору, UNION ALL (И:1821-1835) ---
def q5():
    if Q4_REG is None:
        return "SKIP: немає регістратора з Q4"
    q = buh.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
    	СУММА(Т.Приход) - СУММА(Т.Расход) КАК Сумма
    ИЗ
    	(ВЫБРАТЬ Д.Сумма КАК Приход, 0 КАК Расход
    	ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д
    	ГДЕ Д.Регистратор = &Регистратор
    		И Д.СчетДт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))

    	ОБЪЕДИНИТЬ ВСЕ

    	ВЫБРАТЬ 0, Д.Сумма
    	ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д
    	ГДЕ Д.Регистратор = &Регистратор
    		И Д.СчетКт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))) КАК Т
    """
    q.SetParameter("Регистратор", Q4_REG)
    r = q.Execute().Выгрузить()
    s = r.Получить(0).Сумма if r.Количество() > 0 else 0
    return f"сума={s}"


