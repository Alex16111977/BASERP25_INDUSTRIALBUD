# -*- coding: utf-8 -*-
# Smoke: .erf с измерением Работа. Эталоны ОРІЛЬ/ВООЗ, инварианты Работы, композиция
# с дефолтными настройками (вариант A — вид не менялся) и с группировкой по Работе.
# Путь .erf: env PFPP_ERF или %TEMP%\pfpp_rabota.erf.
import win32com.client, sys, os
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
def f(x): return float(x) if x is not None else 0.0
def пусто(ref):
    return ref is None or (hasattr(ref, 'Пустая') and ref.Пустая())
ERF = os.environ.get("PFPP_ERF") or os.path.join(os.environ["TEMP"], "pfpp_rabota.erf")
assert os.path.exists(ERF), f"нет .erf: {ERF}"
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
отчет = erp.ВнешниеОтчеты.Создать(ERF)
def период():
    return erp.NewObject("СтандартныйПериод")
def тип(имя):
    return erp.NewObject("ОписаниеТипов", имя).Типы().Получить(0)

# --- ОРІЛЬ: эталоны + инварианты ---
сс_о = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
тз = отчет.ПолучитьДанные(период(), сс_о.Ссылка)
cols = [c.Имя for c in тз.Колонки]
assert "Работа" in cols, "нет колонки Работа в ТЗ"
пч = фч = мфг = пнф = 0.0
раб_имя = None
for i in range(тз.Количество()):
    r = тз.Получить(i)
    if r.Блок == "1. Труд":
        пч += f(r.ПланЧасы); фч += f(r.ФактЧасы)
    if r.Блок == "2. Материалы":
        мфг += f(r.ФактГрн); пнф += f(r.ПланНаФактГрн)
        assert пусто(r.Работа), "у материалов/синт.строк Работа не пустая"
    if not пусто(r.Работа):
        assert r.Блок == "1. Труд"
        if раб_имя is None: раб_имя = str(r.Работа.Наименование)
print(f"ОРІЛЬ: ПланЧасы={пч:.2f} ФактЧасы={фч:.2f} МатФактГрн={мфг:.2f} ПланНаФакт={пнф:.2f}")
assert abs(пч - 2795) < 0.01 and abs(фч - 2389) < 0.01
assert abs(мфг - 1620137.97) < 0.01 and abs(пнф - 625675.03) < 0.01

# --- ВООЗ: EV-эталон + Работа у EV-строк ---
сс_в = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД Вооз ЕМS Мала 2026 / Цех_МД Вооз ЕМS Мала 2026")
тз_в = отчет.ПолучитьДанные(период(), сс_в.Ссылка)
вик = 0.0; раб_в = None
for i in range(тз_в.Количество()):
    r = тз_в.Получить(i)
    if r.Блок == "1. Труд":
        вик += f(r.ВиконанняЧасы)
        if f(r.ВиконанняЧасы) != 0:
            assert not пусто(r.Работа), "EV-строка без Работы"
            if раб_в is None: раб_в = str(r.Работа.Наименование)
print(f"ВООЗ: ВиконанняЧасы={вик:.2f} работа_EV='{раб_в}'")
assert abs(вик - 2401.52) < 0.01

# --- Поле доступно в настройках (отбор) ---
дп = отчет.КомпоновщикНастроек.Настройки.Отбор.ДоступныеПоляОтбора
поле = erp.NewObject("ПолеКомпоновкиДанных", "Работа")
assert дп.НайтиПоле(поле) is not None, "поле Работа недоступно в отборе"

# --- Композиция 1: дефолтные настройки (вариант A — вид прежний) ---
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
наст = отчет.КомпоновщикНастроек.ПолучитьНастройки()
вн = erp.NewObject("Структура"); вн.Вставить("Детали", тз)
м = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст)
пр = erp.NewObject("ПроцессорКомпоновкиДанных"); пр.Инициализировать(м, вн)
д = erp.NewObject("ТабличныйДокумент")
в = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
в.УстановитьДокумент(д); в.Вывести(пр)
print(f"Композиция (дефолт): H={д.ВысотаТаблицы} W={д.ШиринаТаблицы}")
assert д.ВысотаТаблицы > 0

# --- Композиция 2: группировка по Работе (ВООЗ) ---
наст2 = отчет.КомпоновщикНастроек.ПолучитьНастройки()
наст2.Структура.Очистить()
гр = наст2.Структура.Добавить(тип("ГруппировкаКомпоновкиДанных"))
пг = гр.ПоляГруппировки.Элементы.Добавить(тип("ПолеГруппировкиКомпоновкиДанных"))
пг.Поле = erp.NewObject("ПолеКомпоновкиДанных", "Работа")
гр.Выбор.Элементы.Добавить(тип("АвтоВыбранноеПолеКомпоновкиДанных"))
вн2 = erp.NewObject("Структура"); вн2.Вставить("Детали", тз_в)
м2 = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст2)
пр2 = erp.NewObject("ПроцессорКомпоновкиДанных"); пр2.Инициализировать(м2, вн2)
д2 = erp.NewObject("ТабличныйДокумент")
в2 = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
в2.УстановитьДокумент(д2); в2.Вывести(пр2)
тексты = set()
for rr in range(1, min(д2.ВысотаТаблицы, 80) + 1):
    for cc in range(1, д2.ШиринаТаблицы + 1):
        try:
            t = str(д2.Область(rr, cc, rr, cc).Текст).strip()
            if t: тексты.add(t)
        except Exception:
            pass
print(f"Композиция (Работа): H={д2.ВысотаТаблицы}; работа '{раб_в}' видна={раб_в in тексты}")
assert д2.ВысотаТаблицы > 1
assert раб_в in тексты, "наименование работы не видно в группировке по Работе"

print("\nSMOKE PASS")
