import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="localhost";Ref="zup";Usr="cfo";Pwd="2442"')
S = zup.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


# 1. Через .Обороты — реквізит Сотрудник
print("=" * 70)
print("1. ВзаиморасчетыПоВзносамВФонды.Обороты — Постернак грудень")
