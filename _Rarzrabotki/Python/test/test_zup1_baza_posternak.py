q.Text = (
    "ВЫБРАТЬ "
    "Т.Сотрудник.Физлицо.КодПоДРФО КАК ИНН, "
    "Т.Сотрудник.Физлицо.Наименование КАК ФИО, "
    "Т.Налог.Наименование КАК Налог, "
    "Т.СтатьяНалоговойДекларации.Наименование КАК СтатьяДекл, "
    "Т.Организация.Наименование КАК Орг, "
    "СУММА(Т.БазаПриход) КАК База, "
    "СУММА(Т.БазаВзносаПриход) КАК БазаВзноса, "
    "СУММА(Т.РезультатПриход) КАК Результат "
    "ИЗ РегистрНакопления.ВзаиморасчетыПоВзносамВФонды.Обороты(&Н, &К, , ) КАК Т "
    "ГДЕ Т.Сотрудник.Физлицо.Наименование ПОДОБНО \"Постернак Андрій%\" "
    "СГРУППИРОВАТЬ ПО "
    "Т.Сотрудник.Физлицо.КодПоДРФО, "
    "Т.Сотрудник.Физлицо.Наименование, "
    "Т.Налог.Наименование, "
    "Т.СтатьяНалоговойДекларации.Наименование, "
    "Т.Организация.Наименование "
    "УПОРЯДОЧИТЬ ПО Т.Организация.Наименование, Т.Налог.Наименование"
)
q.SetParameter("Н", com_date(2025, 12, 1))
q.SetParameter("К", com_date(2025, 12, 31, 23, 59, 59))
try:
    r = q.Execute().Выгрузить()
    print(f"Рядків: {r.Количество()}")
    for i in range(r.Количество()):
        row = r.Получить(i)
        print(f"\n  [{i+1}] {S(row.ФИО)[:35]}  (ІНН {S(row.ИНН)})")
        print(f"       Орг={S(row.Орг)}")
        print(f"       Налог={S(row.Налог)}")
        print(f"       Стаття декл={S(row.СтатьяДекл)}")
        print(f"       База={S(row.База)}  БазаВзноса={S(row.БазаВзноса)}  Результат={S(row.Результат)}")
except Exception as e:
    print(f"ERR: {e}")

