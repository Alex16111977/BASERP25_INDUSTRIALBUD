"""
Smoke возврата изменений: симулирует «удалить старые строки ФЛ + добавить новые
из подформы» — точно так же как делает А_РасшифровкаЗакрытаНаСервере в основной
форме ВКассу.

Сценарий:
1. Найти первую ВКассу с заполненной А_Расшифровкой
2. Выбрать любого ФЛ из А_Расшифровки
3. Запомнить его строки → изменить одну сумму
4. Применить паттерн возврата: удалить старые строки этого ФЛ, добавить изменённые
5. Записать ВКассу (БЕЗ проведения — не теряем тест на проведение)
6. Перепрочитать → убедиться что изменение сохранилось
7. Откатить изменение (вернуть к исходной сумме) — чтобы тест был идемпотентным
"""
import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8")

import win32com.client

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)

# 1. Найти ВКассу с непустой А_Расшифровкой
q = erp.NewObject("Запрос")
q.Текст = '''ВЫБРАТЬ ПЕРВЫЕ 1 Вед.Ссылка КАК Ссылка
ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу КАК Вед
ГДЕ Вед.А_РаспределениеФ2 <> ЗНАЧЕНИЕ(Документ.РаспределениеФ2.ПустаяСсылка)
    И НЕ Вед.ПометкаУдаления
УПОРЯДОЧИТЬ ПО Вед.Дата УБЫВ'''
rs = q.Выполнить()
if rs.Пустой():
    print("FAIL: ВКассу с заполненной А_РаспределениеФ2 не найдена")
    sys.exit(1)
sel = rs.Выбрать(); sel.Следующий()
vk_ref = sel.Ссылка
vk = vk_ref.ПолучитьОбъект()
print(f"ВКассу: {vk.Номер}")

if vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество() == 0:
    print("FAIL: ТЧ А_Расшифровка пуста")
    sys.exit(1)

# 2. Выбрать любого ФЛ с непустой строкой
ФЛ_тест = None
for i in range(vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество()):
    r = vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Получить(i)
    if r.ФизическоеЛицо and not r.ФизическоеЛицо.Пустая():
        ФЛ_тест = r.ФизическоеЛицо
        break

if ФЛ_тест is None:
    print("FAIL: не нашли ни одной строки с заполненным ФЛ")
    sys.exit(1)
print(f"Тестируем для ФЛ: {ФЛ_тест.Наименование}")

# 3. Сохранить исходные строки этого ФЛ
исходные = []
ФЛ_uid = erp.string(ФЛ_тест.УникальныйИдентификатор())
for i in range(vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество()):
    r = vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Получить(i)
    if r.ФизическоеЛицо and not r.ФизическоеЛицо.Пустая():
        if erp.string(r.ФизическоеЛицо.УникальныйИдентификатор()) == ФЛ_uid:
            исходные.append({
                "Сумма": float(r.Сумма or 0),
                "Часы":  float(r.ОтработаноЧасов or 0),
                "Сотр":  r.Сотрудник,
                "Подр":  r.Подразделение,
                "Стат":  r.СтатьяДвиженияДенежныхСредств,
                "Напр":  r.НаправлениеДеятельности,
            })

if len(исходные) == 0:
    print("FAIL: не нашли строки для теста")
    sys.exit(1)
print(f"Исходных строк для {ФЛ_тест.Наименование}: {len(исходные)}, Σ исх. = {sum(s['Сумма'] for s in исходные):,.2f}")

# 4. Симуляция возврата: удалить старые строки ФЛ → добавить копию с одной изменённой строкой
УДАЛЕНО = 0
for i in reversed(range(vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество())):
    r = vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Получить(i)
    if r.ФизическоеЛицо and not r.ФизическоеЛицо.Пустая() and \
       erp.string(r.ФизическоеЛицо.УникальныйИдентификатор()) == ФЛ_uid:
        vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Удалить(r)
        УДАЛЕНО += 1
print(f"Удалено: {УДАЛЕНО} строк")

# Добавить новую строку (тест — увеличить сумму первой на 1)
тест_прибавка = 1.0
новая = vk.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Добавить()
новая.ФизическоеЛицо = ФЛ_тест
новая.Сумма          = исходные[0]["Сумма"] + тест_прибавка
новая.ОтработаноЧасов = исходные[0]["Часы"]
новая.Сотрудник      = исходные[0]["Сотр"]
новая.Подразделение  = исходные[0]["Подр"]
новая.СтатьяДвиженияДенежныхСредств = исходные[0]["Стат"]
новая.НаправлениеДеятельности       = исходные[0]["Напр"]
print(f"Добавлено: 1 новая строка с Σ = {новая.Сумма:,.2f}")

# 5. Записать (БЕЗ проведения — не теряем уже проведённый документ)
vk.ОбменДанными.Загрузка = True  # блокируем типовую логику
vk.Записать(erp.РежимЗаписиДокумента.Запись)
print("OK: ВКассу записана")

# 6. Перепрочитать и проверить
vk2 = vk_ref.ПолучитьОбъект()
найдено = 0
сумма_найдена = 0.0
for i in range(vk2.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество()):
    r = vk2.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Получить(i)
    if r.ФизическоеЛицо and not r.ФизическоеЛицо.Пустая() and \
       erp.string(r.ФизическоеЛицо.УникальныйИдентификатор()) == ФЛ_uid:
        найдено += 1
        сумма_найдена += float(r.Сумма or 0)

ожидаемая_сумма = исходные[0]["Сумма"] + тест_прибавка
if найдено != 1:
    print(f"FAIL: ожидали 1 строку для {ФЛ_тест.Наименование}, нашли {найдено}")
    sys.exit(1)
if abs(сумма_найдена - ожидаемая_сумма) > 0.01:
    print(f"FAIL: Σ = {сумма_найдена:,.2f}, ожидали {ожидаемая_сумма:,.2f}")
    sys.exit(1)
print(f"  Проверка: 1 строка, Σ = {сумма_найдена:,.2f} (ожидали {ожидаемая_сумма:,.2f}) ✓")

# 7. Откат — восстановить исходное состояние
vk3 = vk_ref.ПолучитьОбъект()
for i in reversed(range(vk3.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество())):
    r = vk3.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Получить(i)
    if r.ФизическоеЛицо and not r.ФизическоеЛицо.Пустая() and \
       erp.string(r.ФизическоеЛицо.УникальныйИдентификатор()) == ФЛ_uid:
        vk3.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Удалить(r)

for ис in исходные:
    нс = vk3.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Добавить()
    нс.ФизическоеЛицо = ФЛ_тест
    нс.Сумма          = ис["Сумма"]
    нс.ОтработаноЧасов = ис["Часы"]
    нс.Сотрудник      = ис["Сотр"]
    нс.Подразделение  = ис["Подр"]
    нс.СтатьяДвиженияДенежныхСредств = ис["Стат"]
    нс.НаправлениеДеятельности       = ис["Напр"]

vk3.ОбменДанными.Загрузка = True
vk3.Записать(erp.РежимЗаписиДокумента.Запись)
print(f"OK: исходное состояние восстановлено ({len(исходные)} строк)")

print("\nPASS: паттерн возврата изменений работает корректно")
