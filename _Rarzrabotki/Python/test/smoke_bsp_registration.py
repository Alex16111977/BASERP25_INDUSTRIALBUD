def S(v):
    try: return buh.String(v) if v is not None else "None"
    except: return "<?>"

Обр = buh.ВнешниеОбработки.Создать(EPF)
print("Создать(.epf) — OK")

св = Обр.СведенияОВнешнейОбработке()
print("\n=== СведенияОВнешнейОбработке ===")
fails = []
def want(key, cond, got):
    print(f"  {key:18}= {got}")
    if not cond: fails.append(key)

want("Вид", S(св.Вид) == "ДополнительнаяОбработка", S(св.Вид))
want("Наименование", len(S(св.Наименование)) > 0, S(св.Наименование))
want("Версия", len(S(св.Версия)) > 0, S(св.Версия))
want("БезопасныйРежим", св.БезопасныйРежим == False, S(св.БезопасныйРежим))
want("Информация", len(S(св.Информация)) > 0, S(св.Информация))
want("ВерсияБСП", len(S(св.ВерсияБСП)) > 0, S(св.ВерсияБСП))

cmds = св.Команды
print(f"  Команды: {cmds.Количество()} строк, колонки: " +
      ", ".join(S(c.Имя) for c in cmds.Колонки))
okcols = all(cmds.Колонки.Найти(c) is not None for c in
             ["Представление","Идентификатор","Использование","ПоказыватьОповещение","Модификатор"])
if not okcols: fails.append("колонки команд")
if cmds.Количество() >= 1:
    k = cmds[0]
    print(f"    [0] Представление={S(k.Представление)!r} Идентификатор={S(k.Идентификатор)!r} "
          f"Использование={S(k.Использование)!r} Оповещение={S(k.ПоказыватьОповещение)}")
    if S(k.Использование) != "ОткрытиеФормы": fails.append("Использование!=ОткрытиеФормы")
    if S(k.Идентификатор) == "": fails.append("пустой Идентификатор")
else:
    fails.append("нет команд")

print("\nРЕГИСТРАЦИЯ:", "✅ валидна для БСП" if not fails else f"❌ проблемы: {fails}")

# регрессия заполнения
