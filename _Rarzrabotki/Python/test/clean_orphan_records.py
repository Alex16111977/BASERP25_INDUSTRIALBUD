# -*- coding: utf-8 -*-
"""
Очистка осиротевших записей в РасчетыСПоставщикамиПоСрокам.
После удаления РегистраторовРасчетов их движения остались в регистре
с Регистратор = <Объект не найден>. Нужно удалить эти записи.
"""
import win32com.client
import sys

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

print("=" * 60)
print("Очистка осиротевших записей в РасчетыСПоставщикамиПоСрокам")
print("=" * 60)

print("\nПодключение к BaseERP...")
conn = v8.Connect(CONN_ERP)
print("OK")

query = conn.NewObject("Запрос")

# Шаг 1: Проверить количество осиротевших записей
print("\n--- Шаг 1: Подсчёт осиротевших записей ---")
query.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам ГДЕ Регистратор.Ссылка ЕСТЬ NULL"
result = query.Execute().Выбрать()
result.Следующий()
orphan_count = result.Кол
print(f"Осиротевших записей: {orphan_count}")

if orphan_count == 0:
    print("Нечего очищать!")
    sys.exit(0)

# Шаг 2: Получить уникальные осиротевшие регистраторы
print("\n--- Шаг 2: Поиск уникальных осиротевших регистраторов ---")
query.Text = """
    ВЫБРАТЬ РАЗЛИЧНЫЕ Регистратор КАК Рег
    ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам
    ГДЕ Регистратор.Ссылка ЕСТЬ NULL
"""
result = query.Execute().Выбрать()

orphan_refs = []
while result.Следующий():
    orphan_refs.append(result.Рег)

print(f"Уникальных осиротевших регистраторов: {len(orphan_refs)}")

# Шаг 3: Для каждого — очистить набор записей
print(f"\n--- Шаг 3: Очистка {len(orphan_refs)} наборов записей ---")
cleaned = 0
errors = 0

for ref in orphan_refs:
    try:
        record_set = conn.РегистрыНакопления.РасчетыСПоставщикамиПоСрокам.СоздатьНаборЗаписей()
        record_set.Отбор.Регистратор.Установить(ref)
        record_set.Записать()
        cleaned += 1
        if cleaned % 100 == 0:
            print(f"  Очищено: {cleaned}...")
    except Exception as e:
        errors += 1
        if errors <= 5:
            print(f"  ОШИБКА: {str(e)[:100]}")

print(f"Очищено: {cleaned}, ошибок: {errors}")

# Шаг 4: Проверка
print("\n--- Шаг 4: Проверка ---")
query.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам ГДЕ Регистратор.Ссылка ЕСТЬ NULL"
result = query.Execute().Выбрать()
result.Следующий()
remaining = result.Кол
print(f"Осталось осиротевших: {remaining} (было: {orphan_count})")

# Проверка конкретных документов
