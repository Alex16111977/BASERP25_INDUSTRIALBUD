# Анализ для дизайна: совпадают ли ОбщееНазвание-ссылки плана (Комплектующие) и факта
# (закупки) для одной СС, или дубли имён разводят их по разным группам.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
подр = сс.Ссылка.Подразделение

q = erp.NewObject("Запрос")
q.УстановитьПараметр("СС", сс.Ссылка)
q.УстановитьПараметр("Имя", сс.Наименование)
q.УстановитьПараметр("Подр", подр)
q.Текст = """
ВЫБРАТЬ РАЗЛИЧНЫЕ "ПЛАН" КАК Сторона,
    К.Номенклатура.А_ОбщееНазваниеНоменклатуры КАК ОН,
    К.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ОНИмя
ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Наименование = &Имя И К.Номенклатура.А_ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.А_ОбщиеНазванияНоменклатуры.ПустаяСсылка)
ОБЪЕДИНИТЬ
ВЫБРАТЬ РАЗЛИЧНЫЕ "ФАКТ",
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.А_ОбщееНазваниеНоменклатуры,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
    И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
    И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение = &Подр
    И СТ.АналитикаУчетаНоменклатуры.Номенклатура.А_ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.А_ОбщиеНазванияНоменклатуры.ПустаяСсылка)
"""
t = q.Выполнить().Выгрузить()
from collections import defaultdict
имя2ссылки = defaultdict(set)
план_сс, факт_сс = set(), set()
for i in range(t.Количество()):
    r = t.Получить(i)
    ид = str(r.ОН.УникальныйИдентификатор())
    имя2ссылки[r.ОНИмя].add(ид)
    (план_сс if r.Сторона == "ПЛАН" else факт_сс).add(ид)
dup = {n: s for n, s in имя2ссылки.items() if len(s) > 1}
print(f"Уникальных имён ОбщееНазвание={len(имя2ссылки)}, из них с >1 ссылкой (дубли)={len(dup)}")
for n, s in list(dup.items())[:15]:
    print(f"  ДУБЛЬ '{n}': {len(s)} ссылок")
# имена, где план и факт указывают на РАЗНЫЕ ссылки -> группировка по ссылке их разведёт
разрыв = [n for n, s in имя2ссылки.items() if len(s) > 1]
print(f"\nИмён, где ссылки расходятся (план/факт по ref НЕ сойдутся)={len(разрыв)}")
print("ВЫВОД: если 0 — группировка по ССЫЛКЕ безопасна; если >0 — нужна нормализация по имени")
