"""Discovery тест-РКО N0000053062 ПЕРЕД правкой: ХозОп, А_ОрганизацияБухгалтерия (Ф1/Ф2?),
текущие движения ПрочиеРасходы (эталон Σ + текущая ФормаPL)."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def q(text, **p):
    query = erp.NewObject("Запрос"); query.Text = text
    for k, v in p.items(): query.SetParameter(k, v)
    return query.Execute().Выгрузить()

# 1. Найти РКО по номеру
t = q("""ВЫБРАТЬ Ссылка, Номер, Дата, Организация, СуммаДокумента, Проведен
ИЗ Документ.РасходныйКассовыйОрдер ГДЕ Номер = &Н""", Н="N0000053062")
if t.Количество() == 0:
    print("НЕ найден по номеру N0000053062, пробую по дате 12.12.2025...")
    import datetime
    t = q("""ВЫБРАТЬ Ссылка, Номер, Дата, Организация, СуммаДокумента, Проведен
    ИЗ Документ.РасходныйКассовыйОрдер
    ГДЕ Дата МЕЖДУ &Н И &К""",
        Н=datetime.datetime(2025,12,12,14,20,0), К=datetime.datetime(2025,12,12,14,21,0))
if t.Количество() == 0:
    print("НЕ НАЙДЕН"); sys.exit()

doc = t.Получить(0).Ссылка
obj = doc.ПолучитьОбъект()
r = t.Получить(0)
оргбух = obj.А_ОрганизацияБухгалтерия
заполнен = erp.ЗначениеЗаполнено(оргбух)
хозоп = erp.XMLСтрока(obj.ХозяйственнаяОперация)
print(f"=== РКО №{r.Номер} от {r.Дата:%Y-%m-%d %H:%M:%S}  Проведен={r.Проведен} ===")
print(f"  ХозяйственнаяОперация = {хозоп}")
print(f"  А_ОрганизацияБухгалтерия заполнен? = {заполнен}  ({erp.String(оргбух) if заполнен else 'ПУСТО'})")
print(f"  Организация = {erp.String(obj.Организация)}")
print(f"  СуммаДокумента = {r.СуммаДокумента:,.2f}")
ожид = "Форма1" if заполнен else "Форма2"
print(f"  >>> ОЖИДАЕМАЯ ФормаPL после правки = {ожид}")
пишет_пр = (хозоп == "ПрочаяВыдачаДенежныхСредств")
print(f"  Пишет ли ПрочиеРасходы (ХозОп=ПрочаяВыдачаДенежныхСредств)? = {пишет_пр}")

# 2. Текущие движения ПрочиеРасходы по этому РКО
pr = q("""
ВЫБРАТЬ
    ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ТОГДА "Ф1"
         КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2) ТОГДА "Ф2"
         ИНАЧЕ "ПУСТО" КОНЕЦ КАК Форма,
    КОЛИЧЕСТВО(*) КАК Строк, СУММА(ПР.Сумма) КАК Сумма,
    СУММА(ПР.СуммаУпр) КАК СуммаУпр, СУММА(ПР.СуммаРегл) КАК СуммаРегл
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &Р
СГРУППИРОВАТЬ ПО ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ТОГДА "Ф1"
         КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2) ТОГДА "Ф2" ИНАЧЕ "ПУСТО" КОНЕЦ
""", Р=doc)
print("\n=== ЭТАЛОН: движения ПрочиеРасходы по РКО (ДО правки) ===")
итог = 0.0
for i in range(pr.Количество()):
    x = pr.Получить(i)
    print(f"   ФормаPL={x.Форма}: строк={x.Строк}  Сумма={x.Сумма:,.2f}  Упр={x.СуммаУпр:,.2f}  Регл={x.СуммаРегл:,.2f}")
    итог += x.Сумма
print(f"   ИТОГО Сумма = {итог:,.2f}  (должно остаться неизменным после правки; ФормаPL=ПУСТО → станет {ожид})")
if pr.Количество() == 0:
    print("   (нет движений ПрочиеРасходы — проверить ХозОп)")
