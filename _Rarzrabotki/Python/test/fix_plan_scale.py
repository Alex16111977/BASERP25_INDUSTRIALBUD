# -*- coding: utf-8 -*-
# Фикс масштаба плана: во ВСЕХ 18 доках ВРМ СС «МД IRS 2026 15 м»
# ПланЧасыМодуля = ПОЛНАЯ норма работы из СС (без /КоличествоДомов); ЧасыВыполнення = норма×%/100.
# Перепроведение по хронологии → EV в РН вырастет до шкалы плана (норма×КоличествоДомов).
import win32com.client, sys, re
sys.stdout.reconfigure(encoding='utf-8')
def норм(s): return re.sub(r"\s+"," ",str(s or "").strip().lower().replace("'","").replace("’",""))

erp=win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
сс=erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД IRS 2026 15 м (МД IRS 2026)")
воз=erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД Вооз ЕМS Мала 2026 / Цех_МД Вооз ЕМS Мала 2026")
Реж=erp.РежимЗаписиДокумента.Проведение

def обороты(ссылка):
    q=erp.NewObject("Запрос"); q.УстановитьПараметр("СС",ссылка)
    q.Текст="ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т ГДЕ Т.СтруктураСебестоимости=&СС"
    return float(q.Execute().Выгрузить().Получить(0).Ч or 0)

воз_до=обороты(воз.Ссылка)

# норма по имени работы (полная, на 1 дом)
q=erp.NewObject("Запрос"); q.УстановитьПараметр("СС",сс.Ссылка)
q.Текст=("ВЫБРАТЬ Р.Работа.Наименование КАК Н, СУММА(Р.Количество) КАК П "
         "ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р ГДЕ Р.Ссылка=&СС СГРУППИРОВАТЬ ПО Р.Работа.Наименование")
т=q.Execute().Выгрузить()
норма={норм(т.Получить(i).Н):float(т.Получить(i).П) for i in range(т.Количество())}

# 18 доков по хронологии
q=erp.NewObject("Запрос"); q.УстановитьПараметр("СС",сс.Ссылка)
q.Текст=("ВЫБРАТЬ Д.Ссылка КАК С, ДЕНЬ(Д.Дата) КАК Дн, Д.Подразделение.Наименование КАК Подр "
         "ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д ГДЕ Д.СтруктураСебестоимости=&СС И НЕ Д.ПометкаУдаления "
         "УПОРЯДОЧИТЬ ПО Дн, Подр")
т=q.Execute().Выгрузить()
доки=[(т.Получить(i).С,int(т.Получить(i).Дн),str(т.Получить(i).Подр)) for i in range(т.Количество())]
print(f"Правлю {len(доки)} документов (ПланЧасыМодуля = полная норма, без /6):")
for ссыл,дн,подр in доки:
    об=ссыл.ПолучитьОбъект(); часы=0.0; нев=[]
    for j in range(об.Работы.Количество()):
        s=об.Работы.Получить(j); n=норма.get(норм(s.Работа.Наименование))
        if n is None: нев.append(str(s.Работа)); continue
        s.ПланЧасыМодуля=n
        s.ЧасыВыполнение=n*float(s.Процент)/100.0
        часы+=n*float(s.Процент)/100.0
    assert not нев, f"работы не в СС: {нев}"
    об.Записать(Реж)
    m=re.search(r"№(\d+)",подр)
    print(f"   {дн:02d}.07 дом №{m.group(1) if m else '?'}: Разом виконання {часы:.2f}")

# === Проверка ===
print("\n=== Накопленный EV по домикам к 24.07 (обороты РН, ×6 к прежним) ===")
q=erp.NewObject("Запрос"); q.УстановитьПараметр("СС",сс.Ссылка)
q.Текст=("ВЫБРАТЬ Т.Подразделение.Наименование КАК Подр, СУММА(Т.ЧасыВыполнение) КАК Ч "
         "ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т ГДЕ Т.СтруктураСебестоимости=&СС "
         "СГРУППИРОВАТЬ ПО Т.Подразделение.Наименование УПОРЯДОЧИТЬ ПО Подр")
т=q.Execute().Выгрузить(); итого=0.0
ожид={1:253.46,2:253.46,3:253.46,4:150.15,5:78.15,6:78.15}
for i in range(т.Количество()):
    ч=float(т.Получить(i).Ч); итого+=ч; m=re.search(r"№(\d+)",str(т.Получить(i).Подр)); k=int(m.group(1)) if m else 0
    o=ожид.get(k); ok="OK" if o and abs(ч-o)<0.1 else "?"
    print(f"   дом №{k}: {ч:.2f}  (ожид ~{o}) {ok}")
print(f"   Всего EV по СС IRS: {итого:.2f}")

# отрицательные дельты (регрессий быть не должно) + ВООЗ
q=erp.NewObject("Запрос"); q.УстановитьПараметр("СС",сс.Ссылка)
q.Текст="ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т ГДЕ Т.СтруктураСебестоимости=&СС И Т.ЧасыВыполнение<0"
neg=int(q.Execute().Выгрузить().Получить(0).К)
воз_после=обороты(воз.Ссылка)
print(f"\n   Отрицательных дельт: {neg} {'OK' if neg==0 else '!!!'}")
print(f"   ВООЗ обороты: до={воз_до:.2f}, после={воз_после:.2f} {'— не тронут' if abs(воз_после-воз_до)<0.01 else 'ИЗМЕНИЛСЯ!'}")
assert abs(воз_после-воз_до)<0.01 and neg==0
print("\nФИКС МАСШТАБА ПЛАНА УСПЕШЕН.")
