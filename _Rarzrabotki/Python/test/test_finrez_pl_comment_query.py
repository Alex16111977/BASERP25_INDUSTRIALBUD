"""Precheck для додавання Комментарий у запит А_ФинРез_PL.

Тест 1: чи можна звертатись Р.Регистратор.Комментарий напряму на composite-полі.
Тест 2: чи є рядки з різними коментарями за однаковою PL-статтею у документах А_ОтчетPL.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect(CONN)

    # Тест 1: пряме звернення Регистратор.Комментарий
    print("=== Test 1: direct Регистратор.Комментарий ===")
    q1 = erp.NewObject("Запрос")
    q1.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 5
        Р.Регистратор КАК Документ,
        Р.Регистратор.Комментарий КАК КомментарийПрямой
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(
        ДАТАВРЕМЯ(2026,2,1), ДАТАВРЕМЯ(2026,2,28,23,59,59), Регистратор, ) КАК Р
    """
    try:
        r1 = q1.Execute().Выгрузить()
        print(f"  OK: rows={r1.Количество()}")
        for i in range(min(3, r1.Количество())):
            row = r1.Получить(i)
            print(f"    [{i}] {row.Документ} → '{row.КомментарийПрямой[:60] if row.КомментарийПрямой else ''}'")
    except Exception as e:
        err = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"  FAIL: {err}")

    # Тест 2: per-row комментарі у А_ОтчетPL за PL-статтею
    print("\n=== Test 2: PL комментарі — duplicates per (Документ, Статья) ===")
    q2 = erp.NewObject("Запрос")
    q2.Text = """
    ВЫБРАТЬ
        ТЧ.Ссылка КАК Документ,
        ТЧ.Статья КАК Статья,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВЫРАЗИТЬ(ТЧ.Комментарий КАК Строка(1000))) КАК UniqComm
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
    ГДЕ ТЧ.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2026,1,1) И ДАТАВРЕМЯ(2026,4,30,23,59,59)
        И НЕ ТЧ.Ссылка.ПометкаУдаления
    СГРУППИРОВАТЬ ПО ТЧ.Ссылка, ТЧ.Статья
    ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВЫРАЗИТЬ(ТЧ.Комментарий КАК Строка(1000))) > 1
    """
    try:
        r2 = q2.Execute().Выгрузить()
        print(f"  rows with multi-comment per (Doc,Article)={r2.Количество()}")
        for i in range(min(5, r2.Количество())):
            row = r2.Получить(i)
            print(f"    [{i}] {row.Документ} | {row.Статья} → {row.UniqComm} unique comments")
        if r2.Количество() == 0:
            print("  → МАКСИМУМ безпечний (нема дублів за статтею)")
        else:
            print("  → УВАГА: МАКСИМУМ втратить альтернативні коментарі")
    except Exception as e:
        err = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"  FAIL: {err}")

    # Тест 3: ВЫРАЗИТЬ через CASE — sample (для CTE втЕРП_Расх)
    print("\n=== Test 3: ВЫРАЗИТЬ КАК Документ.X для Расходів ===")
    q3 = erp.NewObject("Запрос")
    q3.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 3
        Р.Регистратор КАК Документ,
        ВЫБОР
            КОГДА Р.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
                ТОГДА ВЫРАЗИТЬ(Р.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Комментарий
            КОГДА Р.Регистратор ССЫЛКА Документ.РасходныйКассовыйОрдер
                ТОГДА ВЫРАЗИТЬ(Р.Регистратор КАК Документ.РасходныйКассовыйОрдер).Комментарий
            ИНАЧЕ ""
        КОНЕЦ КАК КомментарийCASE
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(
        ДАТАВРЕМЯ(2026,2,1), ДАТАВРЕМЯ(2026,2,28,23,59,59), Регистратор, ) КАК Р
    """
    try:
        r3 = q3.Execute().Выгрузить()
        print(f"  OK: rows={r3.Количество()}")
        for i in range(min(3, r3.Количество())):
            row = r3.Получить(i)
            print(f"    [{i}] {row.Документ} → '{row.КомментарийCASE[:60] if row.КомментарийCASE else ''}'")
    except Exception as e:
        err = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"  FAIL: {err}")


if __name__ == "__main__":
    main()
