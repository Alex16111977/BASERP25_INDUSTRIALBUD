"""Приёмка А_ЦентрВыравниванияБаз: режим «Только отчёт» по всем 4 контурам.
Фазы 1-2 плагинов + метрика + классификация. БЕЗ изменений в базах:
проверяем Автоисправлено = НаОбмен = 0 и отсутствие фатальных ошибок."""
import datetime
import sys
import time
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\А_ЦентрВыравниванияБаз.epf"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

obj = erp.ВнешниеОбработки.Создать(EPF, False)
obj.ИнициализироватьРеестрПоУмолчанию()
obj.НачалоПериода = datetime.datetime(2026, 7, 1)
obj.ОкончаниеПериода = datetime.datetime(2026, 7, 18)
obj.ЛимитРегистраций = 500
obj.МаксИтераций = 3

итого_ошибок = 0
for idx in range(obj.РеестрКонтуров.Количество()):
    имя = str(obj.РеестрКонтуров.Получить(idx).ИмяКонтура)
    t0 = time.time()
    м = obj.ОбработатьКонтур(idx, False)  # False = режим «Только отчёт»
    dt = time.time() - t0
    print("=" * 70)
    print("Контур «%s» (%.0f сек)" % (имя, dt))
    print("  ЕстьОшибка:        ", bool(м.ЕстьОшибка))
    print("  КлючейРасходится:  ", int(м.КлючейРасходится))
    print("  КлючейОбъяснено:   ", int(м.КлючейОбъяснено))
    print("  Сумма|Дельта|:     ", float(м.СуммаДельта))
    print("  КлассА (потенциал):", int(м.КлассА))
    print("  Автоисправлено:    ", int(м.Автоисправлено))
    print("  НаОбмен:           ", int(м.НаОбмен))
    print("  КПодтверждению:    ", int(м.КПодтверждению))
    print("  РучнойРазбор:      ", int(м.РучнойРазбор))
    print("  БитыхСсылок:       ", int(м.БитыхСсылок))
    nмsg = м.Сообщения.Количество()
    for i in range(min(nмsg, 8)):
        print("   |", str(м.Сообщения.Получить(i))[:160])
    if bool(м.ЕстьОшибка):
        итого_ошибок += 1
    assert int(м.Автоисправлено) == 0, "отчётный режим что-то исправил!"
    assert int(м.НаОбмен) == 0, "отчётный режим что-то зарегистрировал!"
    assert int(м.БитыхСсылок) == 0, "отчётный режим выполнил санацию!"

print("=" * 70)
print("Строк КПодтверждению:", obj.КПодтверждению.Количество())
print("Строк РучнойРазбор:  ", obj.РучнойРазбор.Количество())
assert итого_ошибок == 0, "фатальные ошибки контуров: %d" % итого_ошибок
print("ACCEPTANCE OK")
