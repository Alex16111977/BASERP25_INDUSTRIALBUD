# -*- coding: utf-8 -*-
"""Pre-тест Rule #-1 для рефайнмента НачальнаяЗадолженностьПоЗарплате.
Валидирует НА ТЕКУЩЕМ состоянии базы (Фаза 1 в базе, контр-нога ещё есть):
  FACT1: вид субконто[0] счёта 661 принимает Справочник.ФизическиеЛица, и
         Сотрудник.ФизическоеЛицо имеет тип ФизическиеЛица (Правка 2 валидна);
  FACT2: штатный ВводОстатков пишет ПАП одноногой (signed Σ != 0) — эталон Правки 1 (инфо);
  FACT3: текущий вклад НЗ в ПАП «Прибыли и убытки» (signed) = +3 165 970,77
         => после удаления контр-ноги управленческий Σ уедет на -3 165 970,77 (Фаза 1 в базе);
  FACT4: текущий вклад НЗ в ПАП «Оплата труда» (signed) = -3 165 970,77 (нога-зеркало, НЕ меняется)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

fails = []
OPENING = 3165970.77
TOL = 0.05

# --- FACT1: тип субконто 661 = ФизическиеЛица; Сотрудник.ФизическоеЛицо тоже ФизическиеЛица ---
сч661 = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду("661")
видСуб = сч661.ВидыСубконто[0].ВидСубконто
print(f"FACT1: 661 вид субконто[0] = {видСуб} ({видСуб.Наименование})")

# реальные движения 661 на Кт: тип субконто Кт1 в существующих проводках (виртуальная ДвиженияССубконто)
qr = erp.NewObject("Запрос")
qr.Текст = """ВЫБРАТЬ ПЕРВЫЕ 20 Х.СубконтоКт1 КАК С
ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто КАК Х
ГДЕ Х.СчетКт.Код = "661" И Х.СубконтоКт1 <> НЕОПРЕДЕЛЕНО"""
типы_существующие = set()
for r in qr.Выполнить().Выгрузить():
    типы_существующие.add(str(r.С.Метаданные().Имя))
print(f"FACT1: существующие типы субконто Кт 661 = {типы_существующие}")
if "ФизическиеЛица" not in типы_существующие:
    fails.append("FACT1: существующие 661 НЕ по ФизическиеЛица — проверить вид субконто/позицию")

# Сотрудник.ФизическоеЛицо из ТЧ документа НЗ
qs = erp.NewObject("Запрос")
qs.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 ЗадолженностьПоЗарплате.Сотрудник.ФизическоеЛицо КАК ФЛ
ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате КАК ЗадолженностьПоЗарплате"""
строкиФЛ = qs.Выполнить().Выгрузить()
if строкиФЛ.Количество() == 0:
    fails.append("FACT1: не нашёл Сотрудника в ТЧ НЗ")
else:
    имяНаш = str(строкиФЛ[0].ФЛ.Метаданные().Имя)
    print(f"FACT1: Сотрудник.ФизическоеЛицо тип = {имяНаш}")
    if имяНаш != "ФизическиеЛица":
        fails.append(f"FACT1: Сотрудник.ФизическоеЛицо тип {имяНаш} != ФизическиеЛица")

# --- FACT2 (инфо): штатный ВводОстатков одноногий в ПАП (signed Σ != 0) ---
qv = erp.NewObject("Запрос")
qv.Текст = """ВЫБРАТЬ
    П.Регистратор КАК Рег,
    СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Signed,
    КОЛИЧЕСТВО(*) КАК Стр
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
ГДЕ П.Регистратор ССЫЛКА Документ.ВводОстатков
СГРУППИРОВАТЬ ПО П.Регистратор
ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 0"""
вв = qv.Выполнить().Выгрузить()
одноногих = sum(1 for r in вв if abs(f(r.Signed)) > TOL)
print(f"FACT2 (инфо): ВводОстатков-регистраторов в ПАП = {вв.Количество()}, из них signed!=0 (одноногих) = {одноногих}")

# --- FACT3: вклад НЗ в ПАП «Прибыли и убытки» (signed) = +OPENING ---
def pap_contrib_nz(statya):
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("Н", statya)
    qq.Текст = """ВЫБРАТЬ СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Signed
        ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
        ГДЕ П.Регистратор ССЫЛКА Документ.НачальнаяЗадолженностьПоЗарплате
            И П.Статья.Наименование = &Н"""
    return f(qq.Выполнить().Выгрузить()[0].Signed)

пу = pap_contrib_nz("Прибыли и убытки")
print(f"FACT3: вклад НЗ в «Прибыли и убытки» (signed) = {пу:,.2f} (ожидаем +{OPENING:,.2f})")
if abs(пу - OPENING) > TOL:
    fails.append(f"FACT3: вклад ПУ {пу:.2f} != +{OPENING:.2f} (Фаза 1 не в базе?)")

# --- FACT4: вклад НЗ в ПАП «Оплата труда» (signed) = -OPENING (нога-зеркало) ---
от = pap_contrib_nz("Оплата труда")
print(f"FACT4: вклад НЗ в «Оплата труда» (signed) = {от:,.2f} (ожидаем -{OPENING:,.2f})")
if abs(от + OPENING) > TOL:
    fails.append(f"FACT4: вклад ОТ {от:.2f} != -{OPENING:.2f}")

print("\nPRETEST PASS" if not fails else f"PRETEST FAIL: {fails}")
sys.exit(1 if fails else 0)
