# -*- coding: utf-8 -*-
"""Приёмка обработки «Загрузка выполнения работ».

Полный путь пользователя на обоих шаблонах: паспорт -> разбор -> создание документов.
Проверяет идемпотентность, инвариант масштаба плана, состав ТЧ, телескопичность дельт
в РН.А_ВыполнениеРаботМодулей и отсутствие необъяснённых минусов.

Запуск: python verify_zvr_load.py
"""
import os
import shutil
import sys
import tempfile

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Загрузка выполнения работ.epf"
ШАБЛОНЫ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\notebook"
           r"\knowledge_Загрузка файлов в выполнение работ\Шаблоны")

ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

провалов = 0


def проверить(условие, сообщение):
    global провалов
    if not условие:
        провалов += 1
        print("    ПРОВАЛ:", сообщение)


def адрес(имя):
    dst = os.path.join(tempfile.gettempdir(), "zvr_verify_" + имя)
    shutil.copyfile(os.path.join(ШАБЛОНЫ, имя), dst)
    return ERP.ПоместитьВоВременноеХранилище(ERP.NewObject("ДвоичныеДанные", dst))


def запрос(текст, **пар):
    z = ERP.NewObject("Запрос")
    z.Текст = текст
    for k, v in пар.items():
        z.УстановитьПараметр(k, v)
    return z.Выполнить().Выгрузить()


ШАБЛОНЫ_ПРИЁМКИ = (
    ("МД IRS 2026 15 м (МД IRS 2026).xlsx", 6, 1, 44),
    ("МД IRS 2026 30 м (МД IRS 2026).xlsx", 7, 2, 88),
)

for имя, домов, модулей, строк_в_доке in ШАБЛОНЫ_ПРИЁМКИ:

    обр = ERP.ВнешниеОбработки.Создать(EPF, False)
    обр.ИмяФайла = имя
    паспорт = обр.ПрочитатьПаспортФайла(адрес(имя), имя)
    обр.СтруктураСебестоимости = паспорт.СтруктураСебестоимости
    обр.ДатаЗагрузки = паспорт.Дата
    обр.Проводить = True
    сводка = обр.РазобратьФайл(адрес(имя), имя)

    ЗАПРОС_КОЛИЧЕСТВА = ("ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК К "
                         "ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д "
                         "ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления")
    было = int(запрос(ЗАПРОС_КОЛИЧЕСТВА, СС=обр.СтруктураСебестоимости)[0].К)
    рез = обр.СоздатьДокументы()
    стало = int(запрос(ЗАПРОС_КОЛИЧЕСТВА, СС=обр.СтруктураСебестоимости)[0].К)

    print(f"\n=== {имя}")
    print(f"  розбір: помилок {сводка.Ошибок} · попереджень {сводка.Предупреждений} · "
          f"рядків {сводка.Строк}")
    print(f"  запис: створено {рез.Створено} · оновлено {рез.Оновлено} · "
          f"проведено {рез.Проведено} · помилка '{рез.Помилка}'")
    print(f"  документів по СС: було {было}, стало {стало}")

    проверить(сводка.Ошибок == 0, "в эталонном файле не должно быть ошибок")
    проверить(рез.Помилка == "", f"ошибка записи: {рез.Помилка}")
    проверить(стало == было, f"идемпотентность: {было} -> {стало}")
    проверить(int(рез.Створено) + int(рез.Оновлено) == домов, "обработано не столько домов")

    # границы дня — литералом: кириллические глобальные функции недоступны через COM-прокси
    г, м, д = (int(x) for x in str(обр.ДатаЗагрузки)[:10].split("-"))
    ДЕНЬ = f"Д.Дата МЕЖДУ ДАТАВРЕМЯ({г},{м},{д},0,0,0) И ДАТАВРЕМЯ({г},{м},{д},23,59,59)"

    состав = запрос(
        "ВЫБРАТЬ Д.Номер КАК Номер, КОЛИЧЕСТВО(Т.НомерСтроки) КАК К "
        "ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д ЛЕВОЕ СОЕДИНЕНИЕ "
        "Документ.А_ВыполнениеРаботМодулей.Работы КАК Т ПО Т.Ссылка = Д.Ссылка "
        f"ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления И {ДЕНЬ} "
        "СГРУППИРОВАТЬ ПО Д.Номер", СС=обр.СтруктураСебестоимости)
    строк = {int(состав[i].К) for i in range(состав.Количество())}
    print(f"  рядків у документах дня: {строк} (очікуємо {строк_в_доке})")
    проверить(строк == {строк_в_доке}, "состав ТЧ не совпал")

    # инвариант масштаба плана: ПланЧасыМодуля × M = норма СС
    инв = запрос(
        "ВЫБРАТЬ Р.Работа КАК Работа, СУММА(Р.Количество) КАК Норма ПОМЕСТИТЬ ВТ_Нормы "
        "ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р ГДЕ Р.Ссылка = &СС "
        "СГРУППИРОВАТЬ ПО Р.Работа;"
        "ВЫБРАТЬ Т.Работа.Наименование КАК Раб, МАКСИМУМ(Т.ПланЧасыМодуля) КАК ПЧМ, "
        "МАКСИМУМ(Н.Норма) КАК Норма "
        "ИЗ Документ.А_ВыполнениеРаботМодулей.Работы КАК Т "
        "ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей КАК Д ПО Д.Ссылка = Т.Ссылка "
        "ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТ_Нормы КАК Н ПО Н.Работа = Т.Работа "
        f"ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления И {ДЕНЬ} "
        "СГРУППИРОВАТЬ ПО Т.Работа.Наименование", СС=обр.СтруктураСебестоимости)
    плохие = [(инв[i].Раб, float(инв[i].ПЧМ), float(инв[i].Норма))
              for i in range(инв.Количество())
              if abs(float(инв[i].ПЧМ) * модулей - float(инв[i].Норма)) > 0.01]
    print(f"  інваріант ПланЧасыМодуля×{модулей}=норма: порушень {len(плохие)}")
    проверить(not плохие, f"нарушен масштаб плана: {плохие[:2]}")

    # регистр = последний снимок каждого дома (дельты телескопируются), минусов нет
    снимок = запрос(
        "ВЫБРАТЬ Д.Подразделение КАК П, МАКСИМУМ(Д.Дата) КАК Д ПОМЕСТИТЬ ВТ "
        "ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д ГДЕ Д.СтруктураСебестоимости = &СС "
        "И Д.Проведен И НЕ Д.ПометкаУдаления СГРУППИРОВАТЬ ПО Д.Подразделение;"
        "ВЫБРАТЬ ВТ.П.Наименование КАК Подр, СУММА(Т.ПланЧасыМодуля * Т.Процент / 100) КАК EV "
        "ИЗ ВТ КАК ВТ ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей КАК Док "
        "ПО ВТ.П = Док.Подразделение И ВТ.Д = Док.Дата И Док.СтруктураСебестоимости = &СС "
        "ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей.Работы КАК Т "
        "ПО Т.Ссылка = Док.Ссылка СГРУППИРОВАТЬ ПО ВТ.П.Наименование",
        СС=обр.СтруктураСебестоимости)
    рег = запрос(
        "ВЫБРАТЬ Р.Подразделение.Наименование КАК Подр, СУММА(Р.ЧасыВыполнение) КАК EV "
        "ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Р "
        "ГДЕ Р.СтруктураСебестоимости = &СС СГРУППИРОВАТЬ ПО Р.Подразделение.Наименование",
        СС=обр.СтруктураСебестоимости)
    карта_рег = {рег[i].Подр: float(рег[i].EV) for i in range(рег.Количество())}
    расхождений = sum(1 for i in range(снимок.Количество())
                      if abs(float(снимок[i].EV) - карта_рег.get(снимок[i].Подр, 0)) > 0.05)
    всего_ev = sum(карта_рег.values())
    минусов = int(запрос("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей "
                         "КАК Р ГДЕ Р.СтруктураСебестоимости = &СС И Р.ЧасыВыполнение < 0",
                         СС=обр.СтруктураСебестоимости)[0].К)
    print(f"  EV усього {всего_ev:.2f} · регістр = знімок: розбіжностей {расхождений} · "
          f"від'ємних рухів {минусов}")
    проверить(расхождений == 0, "регистр разошёлся с последним снимком")
    проверить(минусов == 0, "появились отрицательные движения")

print(f"\nПРОВАЛОВ: {провалов}")
print("ПРИЁМКА ПРОЙДЕНА" if провалов == 0 else "ПРИЁМКА НЕ ПРОЙДЕНА")
sys.exit(1 if провалов else 0)
