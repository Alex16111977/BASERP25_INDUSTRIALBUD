# -*- coding: utf-8 -*-
"""Поиск всех СБДС за декабрь 2025 с движениями ПАП(Статья=ОТ).
Сохраняет в sbds_candidates.json для verify-теста."""
import sys, io, json, os
from datetime import datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
r = q0.Выполнить().Выбрать(); r.Следующий(); ORG = r.С

qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Т.Регистратор КАК Док,
    Т.Регистратор.Номер КАК Номер,
    Т.Регистратор.Дата КАК Дата,
    Т.Регистратор.ХозяйственнаяОперация КАК ХозОп,
    Т.Регистратор.Подразделение КАК Подр,
    Т.Регистратор.СуммаДокумента КАК СуммаДок,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
              ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК Σ_signed
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация=&Орг И Т.Период МЕЖДУ &НМ И &КД
    И Т.Источник=ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Статья=&ОТ
    И ТИПЗНАЧЕНИЯ(Т.Регистратор)=ТИП(Документ.СписаниеБезналичныхДенежныхСредств)
СГРУППИРОВАТЬ ПО Т.Регистратор, Т.Регистратор.Номер, Т.Регистратор.Дата,
    Т.Регистратор.ХозяйственнаяОперация, Т.Регистратор.Подразделение,
    Т.Регистратор.СуммаДокумента
УПОРЯДОЧИТЬ ПО Т.Регистратор.Дата"""
q.УстановитьПараметр("Орг", ORG)
q.УстановитьПараметр("НМ", datetime(2025, 12, 1, 0, 0, 0))
q.УстановитьПараметр("КД", datetime(2025, 12, 31, 23, 59, 59))
q.УстановитьПараметр("ОТ", ОТ)
t = q.Выполнить().Выгрузить()
print(f"СБДС с ПАП(ОТ) за декабрь 2025: {t.Количество()}\n")
найдено = []
for i in range(t.Количество()):
    e = t.Получить(i)
    uuid = conn.XMLСтрока(e.Док)
    print(f"  № {e.Номер} от {e.Дата}  СуммаДок={float(e.СуммаДок or 0):>10,.2f}  "
          f"Σsigned={float(e.Σ_signed or 0):>10,.2f}")
    print(f"    ХозОп={conn.String(e.ХозОп)} Подр={conn.String(e.Подр)}")
    print(f"    UUID={uuid}")
    найдено.append({
        "номер": str(e.Номер),
        "дата": e.Дата.isoformat() if hasattr(e.Дата, "isoformat") else str(e.Дата),
        "хозоп": conn.String(e.ХозОп),
        "подр": conn.String(e.Подр),
        "сумма_док": float(e.СуммаДок or 0),
        "Σ_signed_expected": float(e.Σ_signed or 0),
        "uuid": uuid,
    })
out_path = os.path.join(os.path.dirname(__file__), "sbds_candidates.json")
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(найдено, f, ensure_ascii=False, indent=2)
print(f"\nСохранено {len(найдено)} кандидатов в {out_path}")
