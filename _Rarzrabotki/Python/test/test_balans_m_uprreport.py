"""Task2 discovery: механизм извлечения данных штатного Отчет.УправленческийБаланс
по Статья. СКД-схема отчёта (Templates/ОсновнаяСхемаКомпоновкиДанных, стр.712) =
РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты LEFT JOIN
ПланВидовХарактеристик.СтатьиАктивовПассивов, суммы × Коэффициент валют
(=1 при ВалютаОтчета=ВалютаУправленческогоУчета — дефолт финансиста, ObjectModule.bsl:122,165).
Выполняем РОВНО этот dataset-запрос отчёта напрямую (без форменной машинерии
динам.периода/валют) — это данные отчёта до презентации. Возвращает {Статья: КонОст}.
Используется как ядро основного acceptance Task 13."""
