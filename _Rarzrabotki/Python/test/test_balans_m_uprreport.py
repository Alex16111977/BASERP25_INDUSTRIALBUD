def отчет_упрбаланс_по_статья(conn, org, нм, кд):
    """Данные штатного Отчет.УправленческийБаланс по Статья (КонОст, упр.валюта).
    1:1 с dataset-запросом СКД-схемы отчёта (ПАП.ОстаткиИОбороты + СтатьиАП)."""
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ
        ПРЕДСТАВЛЕНИЕ(АктивыПассивы.Статья) КАК Показатель,
        ПРЕДСТАВЛЕНИЕ(ДанныеСтатьи.АктивПассив) КАК ТипПоказателя,
        СУММА(АктивыПассивы.СуммаНачальныйОстаток) КАК СуммаНачальныйОстаток,
        СУММА(АктивыПассивы.СуммаПриход) КАК СуммаПриход,
        СУММА(АктивыПассивы.СуммаРасход) КАК СуммаРасход,
        СУММА(АктивыПассивы.СуммаКонечныйОстаток) КАК СуммаКонечныйОстаток
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(
            &НачалоПериода, &КонецПериода, Авто, , Организация = &Организация) КАК АктивыПассивы
        ЛЕВОЕ СОЕДИНЕНИЕ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК ДанныеСтатьи
        ПО АктивыПассивы.Статья = ДанныеСтатьи.Ссылка
    СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(АктивыПассивы.Статья),
        ПРЕДСТАВЛЕНИЕ(ДанныеСтатьи.АктивПассив)
    ИМЕЮЩИЕ СУММА(АктивыПассивы.СуммаКонечныйОстаток) <> 0
        ИЛИ СУММА(АктивыПассивы.СуммаПриход) <> 0
        ИЛИ СУММА(АктивыПассивы.СуммаРасход) <> 0
        ИЛИ СУММА(АктивыПассивы.СуммаНачальныйОстаток) <> 0"""
    q.УстановитьПараметр("НачалоПериода", нм)
    q.УстановитьПараметр("КонецПериода", кд)
    q.УстановитьПараметр("Организация", org)
    try:
        t = q.Выполнить().Выгрузить()
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        raise RuntimeError(f"запрос отчёта УправленческийБаланс: {msg}")
    res = {}
    for i in range(t.Количество()):
        r = t.Получить(i)
        res[str(r.Показатель)] = {
            "НачОст": float(r.СуммаНачальныйОстаток or 0),
            "Приход": float(r.СуммаПриход or 0),
            "Расход": float(r.СуммаРасход or 0),
            "КонОст": float(r.СуммаКонечныйОстаток or 0),
            "Тип": str(r.ТипПоказателя),
        }
    return res


