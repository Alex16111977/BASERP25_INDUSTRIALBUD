# -*- coding: utf-8 -*-
"""Acceptance тест для процедуры
РегистрыНакопления.А_ВзаиморасчетыССотрудниками.ЗаполнитьИзОтраженияЗП().

Семантика знаков (финансистская — как типовой ВзаиморасчетыССотрудниками):
  Начисление зарплаты    → Приход  (долг работодателя перед ФЛ растёт)
  НДФЛ                   → Расход  (часть долга списывается в бюджет)
  Удержания              → Расход  (часть долга списывается)

  Σ signed А_ВзСС = (Приход − Расход) = чистый долг к выплате на руки.
  Σ signed ПАП(ОТ) = (Приход_ПАП − Расход_ПАП) — инверсия знака для пассивной статьи ОТ.
  ИНВАРИАНТ: Σ А_ВзСС = −Σ ПАП(ОТ) per Регистратор и per (Орг, Подр).

Шаги:
  1) Загружает кандидатов из ozfu_candidates.json (Σ_signed_expected — со знаком ПАП)
  2) Перепроводит каждый ОЗФУ
  3) Per Регистратор:
     - Σ signed А_ВзСС == −Σ signed ПАП(ОТ) до 1 руб
     - 100% строк имеют ФизЛицо ≠ ПустаяСсылка
     - 0 дублей ключа (Орг, Подр, ФизЛицо, ВидДвижения)
  4) Per (Орг, Подр) per Регистратор: А_ВзСС + ПАП ≈ 0 до 1 руб
  5) Идемпотентность: 2-й прогон → Δ=0
"""
import sys, io, json, os
from collections import Counter
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Параметры
qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С
РежПров = conn.PredefinedValue("РежимЗаписиДокумента.Проведение")
ПустоеФЛ_str = conn.XMLСтрока(conn.PredefinedValue(
    "Справочник.ФизическиеЛица.ПустаяСсылка"))

# Загрузка кандидатов
cand_path = os.path.join(os.path.dirname(__file__), "ozfu_candidates.json")
with open(cand_path, "r", encoding="utf-8") as f:
    КАНДИДАТЫ = json.load(f)

print(f"=== Verify А_ВзаиморасчетыССотрудниками от ОЗФУ ===")
print(f"Кандидатов: {len(КАНДИДАТЫ)}\n")


def найти_док_по_uuid(uuid_str):
    """Получить ссылку на документ по UUID."""
    uuid_obj = conn.NewObject("УникальныйИдентификатор", uuid_str)
    ref = conn.Документы.ОтражениеЗарплатыВФинансовомУчете.ПолучитьСсылку(uuid_obj)
    obj = ref.ПолучитьОбъект()
    return ref if obj is not None else None


def сумма_signed_a_vzs(док):
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ СУММА(ВЫБОР КОГДА Зап.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                                  ТОГДА Зап.СуммаВзаиморасчетов ИНАЧЕ -Зап.СуммаВзаиморасчетов КОНЕЦ) КАК С
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Зап
    ГДЕ Зап.Регистратор = &Док"""
    q.УстановитьПараметр("Док", док)
    r = q.Выполнить().Выбрать(); r.Следующий()
    return float(r.С or 0)


def сумма_signed_pap_ot(док):
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК С
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор=&Док И Т.Источник=
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ"""
    q.УстановитьПараметр("Док", док); q.УстановитьПараметр("ОТ", ОТ)
    r = q.Выполнить().Выбрать(); r.Следующий()
    return float(r.С or 0)


def сравнение_per_подр(док):
    qV = conn.NewObject("Запрос")
    qV.Текст = """ВЫБРАТЬ Зап.Организация КАК Орг, Зап.Подразделение КАК Подр,
        СУММА(ВЫБОР КОГДА Зап.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Зап.СуммаВзаиморасчетов ИНАЧЕ -Зап.СуммаВзаиморасчетов КОНЕЦ) КАК С
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Зап
    ГДЕ Зап.Регистратор=&Док
    СГРУППИРОВАТЬ ПО Зап.Организация, Зап.Подразделение"""
    qV.УстановитьПараметр("Док", док)
    tV = qV.Выполнить().Выгрузить()
    vzs = {}
    for i in range(tV.Количество()):
        e = tV.Получить(i)
        vzs[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр))] = float(e.С or 0)

    qP = conn.NewObject("Запрос")
    qP.Текст = """ВЫБРАТЬ Т.Организация КАК Орг,
        ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК С
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор=&Док И Т.Источник=
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ
    СГРУППИРОВАТЬ ПО Т.Организация, ЕСТЬNULL(Т.Подразделение,
        ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))"""
    qP.УстановитьПараметр("Док", док); qP.УстановитьПараметр("ОТ", ОТ)
    tP = qP.Выполнить().Выгрузить()
    pap = {}
    for i in range(tP.Количество()):
        e = tP.Получить(i)
        pap[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр))] = float(e.С or 0)

    все_ключи = set(vzs.keys()) | set(pap.keys())
    расхождений = 0; max_дельта = 0.0
    примеры = []
    # ИНВЕРСИЯ ЗНАКА: А_ВзСС хранит ПРЯМОЙ долг работодателя, ПАП — пассивная статья
    # Эквивалентность: А_ВзСС + ПАП ≈ 0 per (Орг,Подр)
    for ключ in все_ключи:
        delta = abs(vzs.get(ключ, 0) + pap.get(ключ, 0))
        if delta > max_дельта:
            max_дельта = delta
        if delta > TOL_RUB:
            расхождений += 1
            if len(примеры) < 3:
                примеры.append(f"      {ключ}: ВзС={vzs.get(ключ,0):,.2f} ПАП={pap.get(ключ,0):,.2f} |ВзС+ПАП|={delta:.2f}")
    return расхождений, max_дельта, примеры


def стат_строк(док):
    q = conn.NewObject("Запрос")
    q.Текст = """ВЫБРАТЬ Зап.Организация КАК Орг, Зап.Подразделение КАК Подр,
        Зап.ФизическоеЛицо КАК ФЛ, Зап.ВидДвижения КАК ВД
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Зап
    ГДЕ Зап.Регистратор=&Док"""
    q.УстановитьПараметр("Док", док)
    t = q.Выполнить().Выгрузить()
    rows = t.Количество()
    с_фл = 0
    keys = Counter()
    for i in range(rows):
        e = t.Получить(i)
        ф = conn.XMLСтрока(e.ФЛ)
        if ф != ПустоеФЛ_str:
            с_фл += 1
        keys[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр), ф,
              conn.XMLСтрока(e.ВД))] += 1
    дубли = {k: c for k, c in keys.items() if c > 1}
    return rows, с_фл, дубли


all_pass = True
данные_перепроведения = []  # для идемпотентности

for k in КАНДИДАТЫ:
    period = k["period"]
    номер = k["номер"]
    expected = k["Σ_signed_expected"]
    uuid = k["uuid"]
    print(f"--- {period} № {номер} (expected Σ={expected:,.2f}) ---")

    док = найти_док_по_uuid(uuid)
    if док is None:
        print(f"  ❌ Документ не найден (UUID {uuid})")
        all_pass = False
        continue

    объ = док.ПолучитьОбъект()
    if объ is None:
        print(f"  ❌ Получить объект не удалось")
        all_pass = False; continue
    try:
        объ.Записать(РежПров)
        print(f"  ✓ Перепроведено")
    except Exception as e:
        print(f"  ❌ Ошибка перепроведения: {e}")
        all_pass = False; continue

    # Σ per Регистратор — ИНВЕРСИЯ: А_ВзСС = −ПАП(ОТ)
    взс = сумма_signed_a_vzs(док)
    пап = сумма_signed_pap_ot(док)
    delta_reg = abs(взс + пап)                  # сумма должна быть ~0
    delta_exp = abs(взс + expected)             # expected = знак ПАП (отрицат.); взс положит.
    s1 = "✅" if delta_reg <= TOL_RUB else "❌"
    s2 = "✅" if delta_exp <= TOL_RUB else "❌"
    print(f"  {s1} Σ А_ВзСС = {взс:>16,.2f}; Σ ПАП(ОТ) = {пап:>16,.2f}; |ВзС+ПАП|={delta_reg:.4f}")
    print(f"  {s2} expected_ПАП={expected:>14,.2f}; |ВзС+exp|={delta_exp:.4f}")
    if delta_reg > TOL_RUB or delta_exp > TOL_RUB:
        all_pass = False

    # Per (Орг,Подр)
    расх, max_d, примеры = сравнение_per_подр(док)
    s3 = "✅" if расх == 0 else "❌"
    print(f"  {s3} per (Орг,Подр): {расх} расхождений > {TOL_RUB}₽, max |Δ|={max_d:.4f}")
    for пример in примеры:
        print(пример)
    if расх > 0:
        all_pass = False

    # Строки
    rows, с_фл, дубли = стат_строк(док)
    доля = (с_фл / rows * 100) if rows > 0 else 0
    s4 = "✅" if доля >= 99 else "❌"
    s5 = "✅" if not дубли else "❌"
    print(f"  {s4} ФизЛицо ≠ Пустая: {с_фл}/{rows} ({доля:.1f}%)")
    print(f"  {s5} Дубли (Орг,Подр,ФЛ,ВидДв): {len(дубли)}")
    if доля < 99 or дубли:
        all_pass = False

    данные_перепроведения.append((period, номер, док, взс))
    print()

# Идемпотентность
print("=== Идемпотентность: 2-й прогон ===")
for period, номер, док, взс_было in данные_перепроведения:
    try:
        док.ПолучитьОбъект().Записать(РежПров)
    except Exception as e:
        print(f"  ❌ {period} № {номер}: ошибка повторного провед.: {e}")
        all_pass = False; continue
    взс_стало = сумма_signed_a_vzs(док)
    delta_idem = abs(взс_было - взс_стало)
    s = "✅" if delta_idem <= 0.01 else "❌"
    print(f"  {s} {period} № {номер}: было {взс_было:,.2f} стало {взс_стало:,.2f} |Δ|={delta_idem:.4f}")
    if delta_idem > 0.01:
        all_pass = False

print()
print("=" * 60)
print("[OK] ВСЕ PASS" if all_pass else "[FAIL] есть падения")
sys.exit(0 if all_pass else 1)
