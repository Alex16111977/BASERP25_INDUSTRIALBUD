# -*- coding: utf-8 -*-
"""
Приёмка ПРОМТ_ФиксПарсераСокращений: BSL-парсер обработки == Python-эталон,
сокращения распознаются, старые форматы не сломаны, «fail loud» срабатывает.
"""
import win32com.client, sys, re
sys.stdout.reconfigure(encoding='utf-8')

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\А_ПланФактныйПроизводствоПолный\По часам\Загрузка А_ВыполнениеРаботМодулей.epf"
N = 6
ОСНОВЫ = "мод|буд|дом|шт"
СЕГМЕНТ = re.compile(r"(\d+)\s*(?:" + ОСНОВЫ + r")[a-zA-Zа-яА-ЯіїєґІЇЄҐ'’.]*\s*[-–—:]*\s*(\d+(?:[.,]\d+)?)\s*%", re.I)
ОДИНОЧНЫЙ = re.compile(r"^(\d+(?:[.,]\d+)?)\s*%$")

def эталон(t, n):
    t = str(t or "").strip()
    if not t: return None
    с = СЕГМЕНТ.findall(t)
    if с:
        o = []
        for к, п in с: o += [float(п.replace(",", "."))] * int(к)
        return (o + [0.0]*n)[:n]
    m = ОДИНОЧНЫЙ.match(t)
    return [float(m.group(1).replace(",", "."))]*n if m else None

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
proc = erp.ВнешниеОбработки.Создать(EPF, False)

def bsl(t):
    r = proc.РазобратьПроцентыФакта(t, N)
    return None if r is None else [float(r.Получить(i)) for i in range(N)]
def флаги(t):
    r = proc.ФлагиТекстаФакта(t, N)
    return [str(r.Получить(i)) for i in range(r.Количество())]

ТЕСТЫ = [
    # (текст, ожидаемые проценты, должны ли быть флаги)
    ("3 МОДУЛІ - 100%; 1 МОД.- 60%; 2 МОД. - 0%", [100,100,100,60,0,0], False),   # ← боевой случай
    ("6 МОДУЛІВ - 100%",                          [100]*6,              True),    # Σ=6 ок, но 1 сегмент
    ("6 МОДУЛІВ 100%",                            [100]*6,              None),
    ("70%",                                       [70]*6,               False),
    ("3 МОДУЛІ - 40%; 3 МОДУЛІ - 0%",             [40,40,40,0,0,0],     False),
    ("4 МОДУЛІ - 100%; 2 МОДУЛІ - 0%",            [100,100,100,100,0,0],False),
    ("2 МОДУЛІ - 100%; 1 буд.- 50%; 3 БУД. - 0%", [100,100,50,0,0,0],   False),   # сокращение «буд.»
    ("3 МОДУЛІ – 100%; 3 МОДУЛІ — 0%",            [100,100,100,0,0,0],  False),   # en/em dash
    ("в роботі",                                  None,                 None),
    ("",                                          None,                 None),
]

print(f"{'Текст':46} {'BSL':28} {'Python':28} {'=='}")
ошибок = 0
for текст, ожид, _ in ТЕСТЫ:
    b, p = bsl(текст), эталон(текст, N)
    совп = (b == p) and (b == ожид if ожид is not None else b is None)
    ошибок += 0 if совп else 1
    показ = lambda v: "None" if v is None else ",".join(str(int(x)) for x in v)
    print(f"{текст[:46]:46} {показ(b):28} {показ(p):28} {'OK' if совп else 'FAIL'}")

print("\n=== «fail loud»: нераспознанный фрагмент даёт флаг ===")
проба = "2 МОДУЛІ - 100%; 1 ШТ.- 50%"
print(f"  «{проба}» -> {bsl(проба)}, флаги: {флаги(проба)}")
неполный = "3 МОДУЛІ - 100%"      # Σ домов 3 != 6
print(f"  «{неполный}» -> флаги: {флаги(неполный)}")
битый = "виконано 50 % частково"
print(f"  «{битый}» -> {bsl(битый)}, флаги: {флаги(битый)}")
assert флаги(неполный), "контроль Σ домов не сработал"
assert not флаги("3 МОДУЛІ - 100%; 1 МОД.- 60%; 2 МОД. - 0%"), "боевая строка не должна давать флагов"

assert ошибок == 0, f"расхождений BSL vs Python: {ошибок}"
print("\nПРИЁМКА ПАРСЕРА: PASS")
