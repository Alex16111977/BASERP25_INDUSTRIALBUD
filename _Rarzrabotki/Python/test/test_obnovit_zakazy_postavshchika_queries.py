# --- границы периода строим на стороне 1С (COM-дата теряет день) ---
def дата1С(y, m, d, h=0, mi=0, s=0):
    q = erp.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ ДАТАВРЕМЯ(%d,%d,%d,%d,%d,%d) КАК Д" % (y, m, d, h, mi, s)
    return q.Execute().Выгрузить().Получить(0).Получить(0)


