def run(title, text, params=None, limit=12):
    q = erp.NewObject("Запрос"); q.Text = text
    for k, val in (params or {}).items():
        q.SetParameter(k, val)
    print("=" * 78); print(title)
    try:
        r = q.Execute().Выгрузить()
    except Exception as e:
        info = getattr(e, 'excepinfo', None)
        print("FAIL:", info[2] if info else e); return None
    cols = [r.Колонки.Получить(i).Имя for i in range(r.Колонки.Количество())]
    print("OK, рядків =", r.Количество())
    print("   ", " | ".join(cols))
    for i in range(min(r.Количество(), limit)):
        row = r.Получить(i)
        print("   ", " | ".join(S(row.Получить(j)) for j in range(len(cols))))
    return r


