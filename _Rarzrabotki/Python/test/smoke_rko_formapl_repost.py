# -*- coding: utf-8 -*-
"""Смоук: COM-перепроведение РКО N0000053062 ПОСЛЕ правки → движения ПрочиеРасходы получают ФормаPL.
Защита: подписка чистит РасшифровкаПлатежа если А_ОбработанКазна=Ложь → перед записью гарантируем флаги.
Проверки: РасшифровкаПлатежа НЕ обнулилась; Σ=2500 неизменна; ФормаPL=Форма2 (ОргБух пуст)."""
import sys
import win32com.client
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def dvizh(doc):
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ТОГДА "Форма1"
             КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2) ТОГДА "Форма2"
             ИНАЧЕ "ПУСТО" КОНЕЦ КАК Форма,
        КОЛИЧЕСТВО(*) КАК Строк, СУММА(ПР.Сумма) КАК Сумма,
        СУММА(ПР.СуммаУпр) КАК Упр, СУММА(ПР.СуммаРегл) КАК Регл
    ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР ГДЕ ПР.Регистратор = &Р
    СГРУППИРОВАТЬ ПО ВЫБОР КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ТОГДА "Форма1"
             КОГДА ПР.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма2) ТОГДА "Форма2" ИНАЧЕ "ПУСТО" КОНЕЦ
    """
    q.SetParameter("Р", doc)
    return q.Execute().Выгрузить()

def show(t, tag):
    print(f"  [{tag}] движения ПрочиеРасходы:")
    s = 0.0
    for i in range(t.Количество()):
        x = t.Получить(i); s += x.Сумма
        print(f"     ФормаPL={x.Форма}: строк={x.Строк} Сумма={x.Сумма:,.2f} Упр={x.Упр:,.2f} Регл={x.Регл:,.2f}")
    if t.Количество()==0: print("     (нет движений)")
    print(f"     ИТОГО Сумма={s:,.2f}")
    return s

# найти документ
q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ Ссылка ИЗ Документ.РасходныйКассовыйОрдер ГДЕ Номер = &Н"
q.SetParameter("Н", "N0000053062")
sel = q.Execute().Выбрать(); sel.Следующий(); doc = sel.Ссылка
obj = doc.ПолучитьОбъект()

расш_до = obj.РасшифровкаПлатежа.Количество()
обрКазна = erp.ЗначениеЗаполнено(obj.А_ОбработанКазна) if hasattr(obj,'А_ОбработанКазна') else 'нет реквизита'
print(f"=== ДО перепроведения ===")
print(f"  А_ОбработанКазна = {obj.А_ОбработанКазна}; РасшифровкаПлатежа строк = {расш_до}")
s_до = show(dvizh(doc), "ДО")

# Защита: гарантируем флаги, чтобы подписка не очистила РасшифровкаПлатежа
if hasattr(obj, 'А_ОбработанКазна') and obj.А_ОбработанКазна != True:
    obj.А_ОбработанКазна = True
    print("  (А_ОбработанКазна был Ложь → выставлен Истина для защиты РасшифровкаПлатежа)")

# перепроведение
try:
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("\n✅ Перепроведён через COM")
except Exception as e:
    info = getattr(e, 'excepinfo', None)
    print("❌ Ошибка перепроведения:", info[2] if info else e); sys.exit(1)

# перечитать
obj2 = doc.ПолучитьОбъект()
расш_после = obj2.РасшифровкаПлатежа.Количество()
print(f"\n=== ПОСЛЕ перепроведения ===")
print(f"  РасшифровкаПлатежа строк = {расш_после} (было {расш_до})")
s_после = show(dvizh(doc), "ПОСЛЕ")

print("\n=== ВЕРДИКТ ===")
print(f"  РасшифровкаПлатежа сохранена: {'✅' if расш_после==расш_до and расш_после>0 else '❌'}")
print(f"  Σ неизменна (2500.00): {'✅' if abs(s_после-2500.0)<=0.01 else '❌ '+format(s_после,',.2f')}")
t = dvizh(doc)
формы = [t.Получить(i).Форма for i in range(t.Количество())]
print(f"  ФормаPL = {формы}  → {'✅ Форма2' if формы==['Форма2'] else '⚠️ '+str(формы)}")
