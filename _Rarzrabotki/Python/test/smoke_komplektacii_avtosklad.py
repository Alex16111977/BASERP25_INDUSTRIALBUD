"""Проверка авто-заполнения ДокументиКомплектації складами из СкладыОстатков по «Розрахувати».
Только in-memory ТЧ обработки, БД не пишется."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

qС = buh.NewObject("Запрос")
qС.Текст = 'ВЫБРАТЬ Склады.Ссылка КАК С ИЗ Справочник.Склады КАК Склады ГДЕ Склады.Наименование ПОДОБНО "%МХП%ОР%виробнич%"'
tС = qС.Выполнить().Выгрузить()
склады = [tС.Получить(i).С for i in range(tС.Количество())]
print("складів остатків:", len(склады), "->", [buh.String(s) for s in склады])
assert len(склады) >= 2, "нужно >=2 склада для теста"

def новаяОбр():
    о = buh.ВнешниеОбработки.Создать(EPF, False)
    for код in ("20", "22", "28"):
        о.СчетаОстатков.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код)
    о.Период = pywintypes.Time(datetime.datetime(2026, 6, 22, 12, 0, 0))
    о.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005")
    qO = buh.NewObject("Запрос"); qO.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК С ИЗ Справочник.Организации КАК О ГДЕ О.Наименование ПОДОБНО "%ІНДЕПТ%"'
    о.Организация = qO.Выполнить().Выгрузить().Получить(0).С
    for s in склады:
        о.СкладыОстатков.Добавить().Склад = s
    return о

def склады_дк(о):
    return [buh.String(о.ДокументиКомплектації.Получить(i).Склад) for i in range(о.ДокументиКомплектації.Количество())]

# A) авто-заполнение: ДокументиКомплектації пуст -> после Розрахувати = склады остатков
о = новаяОбр()
print("A до:", о.ДокументиКомплектації.Количество())
о.РассчитатьАнализ()
a = склады_дк(о)
print("A после Розрахувати:", len(a), a)
assert len(a) == len(склады) and set(a) == set(buh.String(s) for s in склады), "склады не заполнились"

# B) идемпотентность: повторный Розрахувати не дублирует
о.РассчитатьАнализ()
b = склады_дк(о)
print("B повторный Розрахувати:", len(b))
assert len(b) == len(склады), "дубликаты при повторном расчёте"

# C) пропуск существующего: предзаполнен 1 склад -> добавится только недостающий
о2 = новаяОбр()
стр = о2.ДокументиКомплектації.Добавить(); стр.Склад = склады[0]
о2.РассчитатьАнализ()
c = склады_дк(о2)
print("C предзаполнен 1, после:", len(c), c)
assert len(c) == len(склады) and c.count(buh.String(склады[0])) == 1, "существующий склад задвоился или не дополнилось"

