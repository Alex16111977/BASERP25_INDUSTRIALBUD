# -*- coding: utf-8 -*-
"""Проверка: СоздатьДокументы() грузит в ВЫБРАННЫЕ документы (реквизиты ДокументКорректировкаРегистров/
ДокументОперацияБух), очищая их. Создаём throwaway КР+ОБ, выбираем их, прогоняем, проверяем что движения
легли в ИХ ссылки (а не в новые), затем чистим по ТОЧНЫМ ссылкам."""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Перенос остатков налогов из бухгалтерии.epf"
РЗ = erp.РежимЗаписиДокумента

def f(x):
    try: return float(x)
    except: return 0.0
def uid(ref):
    return str(erp.XMLСтрока(ref))

fails = []
дата99 = datetime.datetime(2099, 11, 30)

# --- создаём throwaway КР (пустой) и ОБ (пустой, БЕЗ орг — проверим дефолт own-org на reuse) ---
кр0 = erp.Документы.КорректировкаРегистров.СоздатьДокумент()
кр0.Дата = дата99
кр0.Операция = erp.Перечисления.ОперацииКорректировкиРегистров.РучнаяКорректировка
кр0.Записать(РЗ.Запись)
крРеф = кр0.Ссылка
об0 = erp.Документы.ОперацияБух.СоздатьДокумент()
об0.Дата = дата99
об0.Записать(РЗ.Запись)
обРеф = об0.Ссылка
print(f"throwaway создан: КР={uid(крРеф)}  ОБ={uid(обРеф)}")

# --- обработка: выбираем эти документы как приёмники ---
o = erp.ВнешниеОбработки.Создать(EPF, False)
o.ОкончаниеПериода = datetime.datetime(2025, 11, 30)
o.ДокументКорректировкаРегистров = крРеф
o.ДокументОперацияБух = обРеф
o.ЗагрузитьОстатки()
print(f"загружено строк: {o.Налоги.Количество()}")
o.СоздатьДокументы()

# --- проверка: движения легли в ВЫБРАННЫЕ ссылки (реквизиты не сменились на новые) ---
крПосле = o.ДокументКорректировкаРегистров
обПосле = o.ДокументОперацияБух
print(f"после СоздатьДокументы: КР={uid(крПосле)}  ОБ={uid(обПосле)}")
if uid(крПосле) != uid(крРеф): fails.append("КР: реквизит сменился на новый документ (не reuse)")
if uid(обПосле) != uid(обРеф): fails.append("ОБ: реквизит сменился на новый документ (не reuse)")

q = erp.NewObject("Запрос"); q.УстановитьПараметр("Р", крРеф)
q.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.ПрочиеАктивыПассивы ГДЕ Регистратор=&Р"
nпап = int(f(q.Выполнить().Выгрузить()[0].Н))
q2 = erp.NewObject("Запрос"); q2.УстановитьПараметр("Р", обРеф)
q2.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрБухгалтерии.Хозрасчетный ГДЕ Регистратор=&Р"
nхр = int(f(q2.Выполнить().Выгрузить()[0].Н))
print(f"движений на ВЫБРАННЫХ: ПАП(КР)={nпап}  Хозрасчетный(ОБ)={nхр}")
if nпап == 0: fails.append("ПАП-движения не легли в выбранный КР")
if nхр == 0: fails.append("Хозрасчетный-проводки не легли в выбранный ОБ")
# ОБ проведён и орг подставлена (дефолт own-org, т.к. throwaway был без орг)?
обОбъ = обРеф.ПолучитьОбъект()
if обОбъ is not None:
    print(f"ОБ Проведен={обОбъ.Проведен} Орг.ЕДРПОУ={обОбъ.Организация.КодПоЕДРПОУ}")
    if not обОбъ.Проведен: fails.append("ОБ не проведён")

# --- очистка по ТОЧНЫМ ссылкам (только эти 2 документа) ---
нз = erp.РегистрыНакопления.ПрочиеАктивыПассивы.СоздатьНаборЗаписей()
нз.Отбор.Регистратор.Установить(крРеф); нз.Записать()
нб = erp.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
нб.Отбор.Регистратор.Установить(обРеф); нб.Записать()
обОбъ = обРеф.ПолучитьОбъект()
if обОбъ is not None:
    обОбъ.ОбменДанными.Загрузка = True; обОбъ.Удалить()
крОбъ = крРеф.ПолучитьОбъект()
if крОбъ is not None:
    крОбъ.ОбменДанными.Загрузка = True; крОбъ.Удалить()
# контроль
q3 = erp.NewObject("Запрос"); q3.УстановитьПараметр("Р", крРеф)
q3.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.ПрочиеАктивыПассивы ГДЕ Регистратор=&Р"
q4 = erp.NewObject("Запрос"); q4.УстановитьПараметр("Р", обРеф)
q4.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрБухгалтерии.Хозрасчетный ГДЕ Регистратор=&Р"
ост = int(f(q3.Выполнить().Выгрузить()[0].Н)) + int(f(q4.Выполнить().Выгрузить()[0].Н))
print(f"после очистки движений на throwaway: {ост} (ожидаем 0)")
if ост != 0: fails.append("очистка throwaway не полная")

print("\nREUSE PASS — грузит в выбранные документы, чистит, база чиста" if not fails else f"REUSE FAIL: {fails}")
sys.exit(1 if fails else 0)
