"""
Тест: запрос остатков денежных средств из BaseERP
Проверяем что запрос к ДенежныеСредстваБезналичные.ОстаткиИОбороты работает
и UUID можно извлечь из ссылки БанковскийСчет в коде (не в запросе).
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
CONN_BUH = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'


def test_erp_money_query():
    """Step 1: Тест запроса к ERP — ДенежныеСредстваБезналичные"""
    print("=" * 60)
    print("Step 1: ERP — РегистрНакопления.ДенежныеСредстваБезналичные")
    print("=" * 60)

    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONN_ERP)
    print("OK: Підключення до BaseERP")

    q = conn.NewObject("Запрос")
    q.Текст = (
        'ВЫБРАТЬ '
        '   Т.БанковскийСчет КАК БанковскийСчет, '
        '   ПРЕДСТАВЛЕНИЕ(Т.БанковскийСчет) КАК БанковскийСчетПредставление, '
        '   Т.СуммаНачальныйОстаток КАК НачОстаток, '
        '   Т.СуммаПриход КАК Приход, '
        '   Т.СуммаРасход КАК Расход, '
        '   Т.СуммаКонечныйОстаток КАК КонОстаток '
        'ИЗ '
        '   РегистрНакопления.ДенежныеСредстваБезналичные.ОстаткиИОбороты('
        '       &НачалоПериода, &КонецПериода, , , ) КАК Т'
    )
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(datetime(2026, 2, 1)))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(datetime(2026, 2, 28)))

    result = q.Выполнить()
    print("OK: Запит виконано без помилок")

    if result.Пустой():
        print("WARN: Запит повернув порожній результат")
        conn = None
        v8 = None
        return

    sel = result.Выбрать()
    count = 0
    while sel.Следующий():
        count += 1
        # Тест: отримати UUID через BSL-метод на ссылке
        ref = sel.БанковскийСчет
        uid = str(ref.УникальныйИдентификатор())
        представление = str(sel.БанковскийСчетПредставление)
        кон_остаток = sel.КонОстаток
        print(f"  [{count}] UUID={uid}  {представление}  КонОстаток={кон_остаток}")

    print(f"OK: Всього рядків: {count}")
    print("OK: UUID витягується з посилання в коді (не в запиті) — працює!\n")

    conn = None
    v8 = None


