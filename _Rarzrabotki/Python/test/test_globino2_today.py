# -*- coding: utf-8 -*-
"""
Гипотеза финальная: «Сводная ведомость расчётов» берёт остаток на МОМЕНТ
формирования отчёта (текущее «сейчас», май 2026), а не на 31.12.2025.

Проверка: остаток в РасчетыСКлиентами на сегодня по Контрагент=Глобино-2.
Если = 9 094 109,88 → подтверждено.
И детализация — какие документы создали разницу +1 672 755,02 в 2026 г.?
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

К31 = datetime.datetime(2025, 12, 31, 23, 59, 59)
СЕЙЧАС = datetime.datetime(2026, 5, 22, 23, 59, 59)

q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
орг = q.Выполнить().Выгрузить().Получить(0).Ссылка

q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты ГДЕ Наименование = "Глобино-2"'
контр = q.Выполнить().Выгрузить().Получить(0).Ссылка

print("=" * 110)
print(f"Контрагент: {S(контр)}")
print("=" * 110)

# === Остаток на сегодня (22.05.2026) — без даты ===
print("\n[1] Остаток на ТЕКУЩИЙ момент (без даты — самый свежий)")
print("-" * 110)
q1 = erp.NewObject("Запрос")
q1.УстановитьПараметр("Орг", орг)
q1.УстановитьПараметр("Контр", контр)
q1.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    СУММА(Р.СуммаОстаток) КАК КО
ИЗ РегистрНакопления.РасчетыСКлиентами.Остатки(, ) КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И АП.Контрагент = &Контр
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов
ИМЕЮЩИЕ СУММА(Р.СуммаОстаток) <> 0
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
r1 = q1.Выполнить().Выгрузить()
sum_now = 0
for i in range(r1.Количество()):
    rec = r1.Получить(i)
    ко = float(rec.КО)
    sum_now += ко
    print(f"   {str(rec.ОРИмя)[:60]:<60} | КО={ко:>15,.2f}")
print(f"   {'Σ на текущий момент':<60} | КО={sum_now:>15,.2f}")

# === Все движения между 01.01.2026 и сегодня ===
print("\n[2] Движения после 01.01.2026 (период регистра > 31.12.2025)")
print("-" * 110)
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("К31", К31)
q2.УстановитьПараметр("Орг", орг)
q2.УстановитьПараметр("Контр", контр)
q2.Текст = """
ВЫБРАТЬ
    Р.Регистратор.Дата КАК Дата,
    Р.Период КАК Период,
    ПРЕДСТАВЛЕНИЕ(Р.Регистратор) КАК РегИмя,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ) КАК signed
ИЗ РегистрНакопления.РасчетыСКлиентами КАК Р
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И АП.Контрагент = &Контр И Р.Период > &К31
СГРУППИРОВАТЬ ПО Р.Регистратор, Р.Регистратор.Дата, Р.Период, Р.ОбъектРасчетов
ИМЕЮЩИЕ СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ) <> 0
УПОРЯДОЧИТЬ ПО Дата
"""
r2 = q2.Выполнить().Выгрузить()
sum2 = 0
print(f"   {'Дата':<12} | {'Период':<12} | {'Регистратор':<40} | {'ОР':<28} | {'signed':>15}")
print("   " + "-" * 120)
for i in range(r2.Количество()):
    rec = r2.Получить(i)
    s = float(rec.signed)
    sum2 += s
    print(f"   {rec.Дата.strftime('%d.%m.%Y'):<12} | {rec.Период.strftime('%d.%m.%Y'):<12} | {str(rec.РегИмя)[:40]:<40} | {str(rec.ОРИмя)[:28]:<28} | {s:>15,.2f}")
print("   " + "-" * 120)
print(f"   Σ движений ПОСЛЕ 31.12.2025: {sum2:>15,.2f}")
print(f"   Ожидаем: +1 672 755,02 (если эта гипотеза правильная)")

print("\n" + "=" * 110)
print(f"ИТОГ:  КО (на 31.12.2025) = 7 421 354,86")
print(f"       КО (на текущий момент) = {sum_now:,.2f}")
print(f"       Дельта = {sum_now - 7421354.86:,.2f}")
print(f"       На скриншоте «Сводная ведомость» = 9 094 109,88")
print("=" * 110)
