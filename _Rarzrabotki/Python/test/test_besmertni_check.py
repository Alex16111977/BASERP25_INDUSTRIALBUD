# Це перший рядок НДФЛ який фейлить регістр.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# 1. У ФізОсобах Справочник.ФизическиеЛица є Безсмертний?
q1 = erp.NewObject("Запрос")
q1.Text = (
    'ВЫБРАТЬ ПЕРВЫЕ 5 ФЛ.Ссылка, ФЛ.Наименование '
    'ИЗ Справочник.ФизическиеЛица КАК ФЛ '
    'ГДЕ ФЛ.Наименование ПОДОБНО "Безсмертний%"'
)
r1 = q1.Execute().Выгрузить()
print(f"1. Безсмертний у Справочник.ФизическиеЛица: {r1.Количество()}")
безс_fl = None
for i in range(r1.Количество()):
    row = r1.Получить(i)
    print(f"   {S(row.Наименование)}")
    безс_fl = row.Ссылка

# 2. Сотрудники Безсмертний у ТОВ ІНДАСТРІАЛБУД
if безс_fl:
    q2 = erp.NewObject("Запрос")
    q2.Text = (
        'ВЫБРАТЬ С.Ссылка, С.ГоловнаяОрганизация.Наименование КАК Орг, С.ПометкаУдаления '
        'ИЗ Справочник.Сотрудники КАК С '
        'ГДЕ С.ФизическоеЛицо = &ФЛ'
    )
    q2.SetParameter("ФЛ", безс_fl)
    r2 = q2.Execute().Выгрузить()
    print(f"\n2. Сотрудники Безсмертний: {r2.Количество()}")
    for i in range(r2.Количество()):
        row = r2.Получить(i)
        print(f"   {S(row.Ссылка)}  Орг={S(row.Орг)}  Удал={S(row.ПометкаУдаления)}")

# 3. Чи є Безсмертний у НЗ 000Ц-000003 в ТЧ Начисления?
q3 = erp.NewObject("Запрос")
q3.Text = (
    'ВЫБРАТЬ ПЕРВЫЕ 1 НЗ.Ссылка '
    'ИЗ Документ.НачислениеЗарплаты КАК НЗ '
    'ГДЕ НЗ.А_ДокОтражениеЗПпоКазне.Номер = "000000001" '
    'УПОРЯДОЧИТЬ ПО НЗ.Дата УБЫВ'
)
sel3 = q3.Execute().Выбрать()
sel3.Следующий()
нз = sel3.Ссылка.ПолучитьОбъект()

# Початково перезавантажити
try:
    q4 = erp.NewObject("Запрос")
    q4.Text = 'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д ГДЕ Д.Номер = "000000001"'
    sel4 = q4.Execute().Выбрать()
    sel4.Следующий()
    sel4.Ссылка.ПолучитьОбъект().СоздатьДокументНачисления()
    # Перечитати
    sel3 = q3.Execute().Выбрать()
    sel3.Следующий()
    нз = sel3.Ссылка.ПолучитьОбъект()
    print(f"\nНЗ перезаписано: {S(нз.Ссылка)}")
except Exception as e:
    print(f"СоздатьДокументНачисления err: {e}")

print(f"\n3. Начисления у НЗ: {нз.Начисления.Количество()}")
print(f"   НДФЛ у НЗ: {нз.НДФЛ.Количество()}")

# Скільки рядків НДФЛ = Безсмертний
count_besm_ndfl = 0
for i in range(нз.НДФЛ.Количество()):
    r = нз.НДФЛ.Получить(i)
    if "Безсмертний" in S(r.ФизическоеЛицо):
        count_besm_ndfl += 1
print(f"   Рядків НДФЛ для Безсмертний: {count_besm_ndfl}")

# Скільки рядків Начисления = Безсмертний
count_besm_nach = 0
for i in range(нз.Начисления.Количество()):
    r = нз.Начисления.Получить(i)
    if "Безсмертний" in S(r.Сотрудник):
        count_besm_nach += 1
print(f"   Рядків Начисления для Безсмертний: {count_besm_nach}")

# ТЧ ФизическиеЛица: чи є Безсмертний?
count_besm_fl = 0
for i in range(нз.ФизическиеЛица.Количество()):
    r = нз.ФизическиеЛица.Получить(i)
    if "Безсмертний" in S(r.ФизическоеЛицо):
        count_besm_fl += 1
print(f"   Рядків ФизическиеЛица Безсмертний: {count_besm_fl}")
print(f"\n   Всього ФизическиеЛица: {нз.ФизическиеЛица.Количество()}")
