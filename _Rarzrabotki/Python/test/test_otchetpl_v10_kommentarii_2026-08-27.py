def тип_дока(представление):
    for тип, преф in ПРЕФИКСЫ.items():
        if представление.startswith(преф):
            return тип
    if представление.startswith(ПРЕФ_ВПТ_ДОП):
        return "ВнутреннееПотреблениеТоваров"
    return None

