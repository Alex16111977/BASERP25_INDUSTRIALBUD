"""Перевірка: чи є поле ВариантРаспределенияРасходовРегл в джерелі."""
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# 1. Перевірка: чи є в тимч. таблиці поле ВариантРаспределенияРасходовРегл?
# Таблиця ВтПрочиеРасходыНаЗатраты = дані з регістру ПрочиеРасходы
# Виміри ПрочиеРасходы: Организация, Подразделение, НаправлениеДеятельности,
#   НалоговоеНазначение, СтатьяРасходов, АналитикаРасходов
# Реквізити ПрочиеРасходы: ХозяйственнаяОперация, АналитикаУчетаНоменклатуры, ...

# ВариантРаспределенияРасходовРегл — це реквізит ПланВидовХарактеристик.СтатьиРасходов
# В тимч. таблиці його НЕМАЄ як окремого поля
# Але стандартний код (рядок 8037-8038) бере його як
#   СтатьяРасходовСписания.ВариантРаспределенияРасходовРегл
# де СтатьяРасходовСписания = СебестоимостьТоваров.СтатьяРасходовСписания

# Наша джерельна таблиця = ВтПрочиеРасходыНаЗатраты
# Там СтатьяРасходов = вимір (ПВХСсылка.СтатьиРасходов)
# Можна звернутися через крапку: СтатьяРасходов.ВариантРаспределенияРасходовРегл

q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 3
    ПР.СтатьяРасходов КАК СтатьяРасходов,
    ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл КАК Вариант,
    ПР.СтатьяРасходов.ТипРасходов КАК ТипРасходов
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.СтатьяРасходов.ВариантРаспределенияРасходовРегл = ЗНАЧЕНИЕ(Перечисление.ВариантыРаспределенияРасходов.НаВнеоборотныеАктивы)"""

try:
    res = q.Execute()
    sel = res.Select()
    while sel.Next():
        print(f"Стаття: {S(sel.СтатьяРасходов)} | Варіант: {S(sel.Вариант)} | Тип: {S(sel.ТипРасходов)}")
    print("ЗАПИТ ПРАЦЮЄ через крапку!")
except Exception as e:
    print(f"ПОМИЛКА: {e}")

