# -*- coding: utf-8 -*-
# Discovery: чи має Комплектующие спец 000000005 заповнену Номенклатуру (план по номенклатурі),
# і чи збігається вона з номенклатурою залишків (план∩факт).
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
spec = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005").Ссылка

# 1) Комплектующие: скільки рядків мають заповнену Номенклатуру vs лише ОбщееНазвание
q = buh.NewObject("Запрос")
q.УстановитьПараметр("С", spec)
q.Текст = """
ВЫБРАТЬ
    К.ОбщееНазвание КАК Эталон,
    К.Номенклатура КАК Номенклатура,
    К.Количество КАК Кол,
    К.Единица КАК Единица
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка = &С
УПОРЯДОЧИТЬ ПО Эталон, Номенклатура
"""
t = q.Выполнить().Выгрузить()
n = t.Количество()
с_номенкл = 0; без_номенкл = 0
print(f"=== Комплектующие спец 000000005: {n} рядків ===")
for i in range(n):
    r = t.Получить(i)
    ном = r.Номенклатура
    есть = ном is not None and not ном.Пустая()
    if есть: с_номенкл += 1
    else: без_номенкл += 1
    if i < 30:
        print(f"  Эталон='{buh.String(r.Эталон)}' | Номенкл={'<ПУСТО>' if not есть else buh.String(ном)} | Кол={float(r.Кол)} | Од={buh.String(r.Единица)}")
print(f"--- з номенклатурою: {с_номенкл}, лише ОбщееНазвание (Номенкл пусто): {без_номенкл}")

# 2) Скільки СПЕЦ-номенклатур реально є в залишках (план∩факт) — груба перевірка по 1 еталону
print("\n=== чи спец-номенклатура = номенклатура залишків? (перетин по Номенклатура) ===")
q2 = buh.NewObject("Запрос")
q2.УстановитьПараметр("С", spec)
q2.Текст = """
ВЫБРАТЬ РАЗЛИЧНЫЕ К.Номенклатура КАК Ном
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка = &С И К.Номенклатура <> ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
"""
спец_ном = set()
tt = q2.Выполнить().Выгрузить()
for i in range(tt.Количество()):
    спец_ном.add(buh.String(tt.Получить(i).Ном))
print(f"унікальних спец-номенклатур (Номенкл заповнено): {len(спец_ном)}")
