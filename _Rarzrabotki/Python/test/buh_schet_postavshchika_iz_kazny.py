def норм_текст(s):
    s = str(s).lower()
    for a, b in (("і", "и"), ("ї", "и"), ("й", "и"), ("є", "е"), ("ё", "е"), ("ґ", "г")):
        s = s.replace(a, b)
    s = re.sub(r"[ьъ'’ʼ\"«»]", "", s)
    return re.sub(r"\s+", " ", s).strip()


# вхідний номер: великі літери, без пробілів/№; ключ = (ЄДРПОУ, номер, дата)
def вхідний_ключ(код, номер, г, м, д):
    номер = re.sub(r"[\s №#]", "", str(номер or "")).upper()
    код = str(код or "").strip()
    if not номер or not код or int(г or 1) <= 1:
        return None
    return (код, номер, f"{int(г):04d}-{int(м):02d}-{int(д):02d}")


