# -*- coding: utf-8 -*-
"""Pre-test (Rule #-1) для процедуры РегистрыНакопления.А_ВзаиморасчетыССотрудниками.
ЗаполнитьИзОтраженияЗП(ДокОбъект) — заполнение нового регистра из документа
ОтражениеЗарплатыВФинансовомУчете.

Алгоритм: 3 ТЧ документа (НачисленнаяЗарплатаИВзносыПоФизлицам + НачисленныйНДФЛ
+ УдержаннаяЗарплата) с теми же фильтрами, что в типовом ManagerModule.bsl
для статьи ОплатаТруда, signed convention 1:1 ПАП:
  - Начисления (ТипНалога=пуст, ВидОперации ≠ 4 исключения) → ВидДвижения=Расход
  - НДФЛ                                                    → ВидДвижения=Приход
  - Удержания (ИспользоватьУчетПрочихАктивовПассивов)        → ВидДвижения=Приход

Asserts per Регистратор:
 1) rows > 0 хотя бы в одном из 3 блоков
 2) 0 дублей ключа (Орг, Подр, ФизЛицо)
 3) Σ signed А_ВзСС per (Орг, Подр) ≡ Σ signed ПАП(Статья=ОТ, Источник=Пуст,
    Регистратор=&Док) per (Орг, Подр) до tol=1.0 руб
 4) Доля строк с ФизЛицо ≠ ПустаяСсылка > 90% (ФизЛицо в ТЧ заполнено всегда)

Если PASS — значит блок 2 (сдельная зп через ВыработкаСотрудников) для тестируемых
документов не работает (нет сдельной части); идём в production только с 3 блоками.
Если FAIL по Σ — расхождение покажет величину; нужно добавить блок 2.
"""
import sys, io
from collections import defaultdict, Counter
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Организация
q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
r = q0.Выполнить().Выбрать(); r.Следующий(); ORG = r.С

# ОТ
qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

# Жирные регистраторы ОтражениеЗарплатыВФинансовомУчете за дек/янв/фев с ПАП(ОТ)
print("=== Поиск кандидатов: ОтражениеЗарплатыВФинансовомУчете с ПАП(Статья=ОТ) ===\n")
ПЕРИОДЫ = [
    ("декабрь2025", datetime(2025, 12, 1)),
    ("январь2026",  datetime(2026, 1, 1)),
    ("февраль2026", datetime(2026, 2, 1)),
]
ВСЕ_ДОКИ = []
for name, мдата in ПЕРИОДЫ:
    qG = conn.NewObject("Запрос")
    qG.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
                "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
    qG.УстановитьПараметр("М", мдата)
    rG = qG.Выполнить().Выбрать(); rG.Следующий(); НМ, КД = rG.НМ, rG.КД

    qR = conn.NewObject("Запрос")
    qR.Текст = """
    ВЫБРАТЬ ПЕРВЫЕ 2 Т.Регистратор КАК Док,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                       ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК Σ_signed_ПАП_ОТ
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Организация=&Орг И Т.Период МЕЖДУ &НМ И &КД
        И Т.Источник=ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ
        И ТИПЗНАЧЕНИЯ(Т.Регистратор)=ТИП(Документ.ОтражениеЗарплатыВФинансовомУчете)
    СГРУППИРОВАТЬ ПО Т.Регистратор
    УПОРЯДОЧИТЬ ПО СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) УБЫВ
    """
    qR.УстановитьПараметр("Орг", ORG); qR.УстановитьПараметр("НМ", НМ)
    qR.УстановитьПараметр("КД", КД); qR.УстановитьПараметр("ОТ", ОТ)
    tR = qR.Выполнить().Выгрузить()
    for i in range(tR.Количество()):
        e = tR.Получить(i)
        ВСЕ_ДОКИ.append((name, e.Док, float(e.Σ_signed_ПАП_ОТ or 0)))
        print(f"  {name}: {e.Док} → ПАП(ОТ) signed = {float(e.Σ_signed_ПАП_ОТ or 0):>20,.2f}")

if not ВСЕ_ДОКИ:
    print("\n❌ Не найден ни один документ ОтражениеЗарплатыВФинансовомУчете с движениями ПАП(ОТ). СТОП.")
    sys.exit(1)

# === ОСНОВНОЙ ЗАПРОС ===
# 3 блока ОБЪЕДИНИТЬ ВСЕ, источник = ТЧ документа, signed convention 1:1 ПАП.
ЗАПРОС_VZS = """
// Блок 1: НачисленнаяЗарплатаИВзносыПоФизлицам → Расход (ОТ Пассив, начисление = рост долга)
// Фильтр: ТипНалога=пуст (только зарплата, не взносы), ВидОперации НЕ В 4 исключения,
// убраны блоки про сдельную и ежегодный отпуск (они отдельно в ManagerModule.bsl)
ВЫБРАТЬ
    Н.Организация КАК Организация,
    Н.ПодразделениеПредприятия КАК Подразделение,
    Н.ФизическоеЛицо КАК ФизическоеЛицо,
    -СУММА(Н.Сумма) КАК Σ_signed,
    0 КАК Приход,
    СУММА(Н.Сумма) КАК Расход,
    "Начисление" КАК Источник
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете.НачисленнаяЗарплатаИВзносыПоФизлицам КАК Н
ГДЕ Н.Ссылка = &Док
    И Н.Налог = ЗНАЧЕНИЕ(Справочник.Налоги.ПустаяСсылка)
    И Н.ВидОперации НЕ В (
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.ЕжегодныйОтпускОценочныеОбязательстваИРезервы),
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.НачисленоСдельноДоход),
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.КомпенсацияЕжегодногоОтпускаОценочныеОбязательства),
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.ЕжегодныйОтпускОценочныеОбязательства))
СГРУППИРОВАТЬ ПО Н.Организация, Н.ПодразделениеПредприятия, Н.ФизическоеЛицо
ИМЕЮЩИЕ СУММА(Н.Сумма) <> 0

ОБЪЕДИНИТЬ ВСЕ

// Блок 2: НачисленныйНДФЛ → Приход (уменьшение долга работодателя — ушло в бюджет)
ВЫБРАТЬ
    &Орг КАК Организация,
    НДФЛ.ПодразделениеПредприятия КАК Подразделение,
    НДФЛ.ФизическоеЛицо КАК ФизическоеЛицо,
    СУММА(НДФЛ.Сумма) КАК Σ_signed,
    СУММА(НДФЛ.Сумма) КАК Приход,
    0 КАК Расход,
    "НДФЛ" КАК Источник
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете.НачисленныйНДФЛ КАК НДФЛ
ГДЕ НДФЛ.Ссылка = &Док
СГРУППИРОВАТЬ ПО НДФЛ.ПодразделениеПредприятия, НДФЛ.ФизическоеЛицо
ИМЕЮЩИЕ СУММА(НДФЛ.Сумма) <> 0

ОБЪЕДИНИТЬ ВСЕ

// Блок 3: УдержаннаяЗарплата → Приход (уменьшение долга)
ВЫБРАТЬ
    &Орг КАК Организация,
    У.ПодразделениеПредприятия КАК Подразделение,
    У.ФизическоеЛицо КАК ФизическоеЛицо,
    СУММА(У.Сумма) КАК Σ_signed,
    СУММА(У.Сумма) КАК Приход,
    0 КАК Расход,
    "Удержания" КАК Источник
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете.УдержаннаяЗарплата КАК У
ГДЕ У.Ссылка = &Док
СГРУППИРОВАТЬ ПО У.ПодразделениеПредприятия, У.ФизическоеЛицо
ИМЕЮЩИЕ СУММА(У.Сумма) <> 0
"""


def сумма_пап_per_подр(док):
    """Σ signed ПАП(Статья=ОТ, Источник=Пуст, Регистратор=&Док) per (Орг, Подр)."""
    q = conn.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ Т.Организация КАК Орг,
        ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                  ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК С
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Регистратор=&Док И Т.Источник=
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ
    СГРУППИРОВАТЬ ПО Т.Организация, ЕСТЬNULL(Т.Подразделение,
        ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))"""
    q.УстановитьПараметр("Док", док); q.УстановитьПараметр("ОТ", ОТ)
    t = q.Выполнить().Выгрузить()
    res = {}
    for i in range(t.Количество()):
        e = t.Получить(i)
        res[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр))] = float(e.С or 0)
    return res


print("\n=== Pre-test: 3-блочный запрос для А_ВзСС vs ПАП(ОТ) per (Орг,Подр) ===\n")
all_pass = True
for name, док, sumПАП in ВСЕ_ДОКИ:
    print(f"--- {name}: {док} (Σ ПАП ОТ = {sumПАП:,.2f}) ---")
    qV = conn.NewObject("Запрос")
    qV.Текст = ЗАПРОС_VZS
    qV.УстановитьПараметр("Док", док)
    qV.УстановитьПараметр("Орг", ORG)
    try:
        t = qV.Выполнить().Выгрузить()
    except Exception as e:
        print(f"  ❌ Запрос упал: {e}")
        all_pass = False
        continue

    rows = t.Количество()
    by_подр = defaultdict(float)
    by_подр_fl = defaultdict(int)  # счётчик строк с ФизЛицом
    by_подр_total_rows = defaultdict(int)
    by_источник = Counter()
    keys_for_dup = Counter()
    for i in range(rows):
        e = t.Получить(i)
        ключ = (conn.XMLСтрока(e.Организация), conn.XMLСтрока(e.Подразделение))
        by_подр[ключ] += float(e.Σ_signed or 0)
        by_подр_total_rows[ключ] += 1
        if conn.XMLСтрока(e.ФизическоеЛицо) != conn.XMLСтрока(
                conn.PredefinedValue("Справочник.ФизическиеЛица.ПустаяСсылка")):
            by_подр_fl[ключ] += 1
        by_источник[str(e.Источник).strip()] += 1
        keys_for_dup[(conn.XMLСтрока(e.Организация),
                      conn.XMLСтрока(e.Подразделение),
                      conn.XMLСтрока(e.ФизическоеЛицо),
                      str(e.Источник).strip())] += 1

    дубли = {k: c for k, c in keys_for_dup.items() if c > 1}
    print(f"  rows = {rows}; разрезы: {dict(by_источник)}")
    print(f"  Подразделений в запросе: {len(by_подр)}")
    print(f"  Дубли ключа (Орг,Подр,ФизЛицо,Источник): {len(дубли)}")

    # Сравнить per (Орг,Подр)
    pap = сумма_пап_per_подр(док)
    все_подр = set(by_подр.keys()) | set(pap.keys())
    несоответствий = 0
    max_дельта = 0.0
    for ключ in все_подр:
        vzs = by_подр.get(ключ, 0)
        p = pap.get(ключ, 0)
        delta = abs(vzs - p)
        if delta > max_дельта:
            max_дельта = delta
        if delta > TOL_RUB:
            несоответствий += 1
            if несоответствий <= 5:
                print(f"    ❌ Подр {ключ}: А_ВзСС={vzs:,.2f} ПАП={p:,.2f} |Δ|={delta:.2f}")

    Σ_vzs = sum(by_подр.values())
    print(f"  Σ_всех А_ВзСС signed = {Σ_vzs:,.2f}; Σ ПАП(ОТ) = {sumПАП:,.2f}; "
          f"|Δ|={abs(Σ_vzs - sumПАП):.2f}")

    # Σ всех строк / Σ строк с ФизЛицом для расчёта доли
    total_rows = sum(by_подр_total_rows.values())
    rows_with_fl = sum(by_подр_fl.values())
    доля_fl = (rows_with_fl / total_rows * 100) if total_rows > 0 else 0
    print(f"  Доля строк с ФизЛицо ≠ Пустая: {доля_fl:.1f}% ({rows_with_fl}/{total_rows})")

    if несоответствий == 0 and not дубли and rows > 0:
        print(f"  ✅ PASS — Σ per (Орг,Подр) совпадает с ПАП до {TOL_RUB} руб")
    else:
        print(f"  ❌ FAIL — несоответствий {несоответствий}, дублей {len(дубли)}, "
              f"max |Δ|={max_дельта:.2f}")
        all_pass = False

print()
print("=" * 70)
print("[OK] ВСЕ PASS" if all_pass else "[FAIL] есть падения")
sys.exit(0 if all_pass else 1)
