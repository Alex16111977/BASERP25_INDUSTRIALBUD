# -*- coding: utf-8 -*-
# КРИТИЧЕСКАЯ проверка: баланс по подразделениям НЕ ломается после гибрид-доработки.
# Документ: Передача начислений между подразделениями 000000001 от 31.12.2025 12:00.
#
# Инвариант: взаимозачёт двигает ПАП "Задолженность" на сумму пары, значит для КАЖДОГО
# подразделения  Σ(суммы где оно Дебитор=Приход) - Σ(где Кредитор=Расход)  ДОЛЖНО РАВНЯТЬСЯ
# чистому ПАП-сальдо этого подразделения из документа. Тогда source_net + взаимозачёт = 0.
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\А_ОбработкаДисбалансаПоПодразделениям.erf"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# 1) Ссылка на Передачу начислений 000000001
q = erp.NewObject("Запрос")
q.Text = ('ВЫБРАТЬ ПЕРВЫЕ 1 Док.Ссылка КАК Ссылка ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями КАК Док '
          'ГДЕ Док.Номер = "000000001" И Док.Дата = ДАТАВРЕМЯ(2025,12,31,12,0,0)')
s = q.Execute().Выбрать(); s.Следующий()
ref = s.Ссылка
ref_key = erp.XMLСтрока(ref)
print("Основание:", erp.String(ref))

# 2) ИСТИНА: чистое ПАП-сальдо по подразделению из документа
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Рег", ref)
q.Text = """
ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК Подр,
	СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Нетто
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Регистратор = &Рег
	И НЕ ПАП.Статья В (ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),
		ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение)
ИМЕЮЩИЕ СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) <> 0
"""
истина = {}
s = q.Execute().Выбрать()
while s.Следующий():
    истина[s.Подр] = round(s.Нетто, 2)
орг_итог = round(sum(истина.values()), 2)
print(f"Подразделений с дисбалансом в документе: {len(истина)}, орг-итог ПАП = {орг_итог}")

# 3) Анализ (read-only) гибрид-обработкой
try:
    obr = erp.ВнешниеОтчеты.Создать(ERF, False)
except Exception:
    obr = erp.ВнешниеОтчеты.Создать(ERF)
obr.НачалоПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.ОкончаниеПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.ПоказыватьВсе = True   # все пары, без фильтра подразделения
obr.АнализДокументов()

# 4) Покрытие из ТЧ: Σ(где Приход) - Σ(где Расход), только строки нашего основания
покрытие = {}
n_пар = 0
тч = obr.ДокументыДисбаланса
for i in range(тч.Количество()):
    стр = тч.Получить(i)
    if стр.СуммаДокумента <= 0:
        continue
    if not erp.ЗначениеЗаполнено(стр.Документ) or erp.XMLСтрока(стр.Документ) != ref_key:
        continue
    n_пар += 1
    if erp.ЗначениеЗаполнено(стр.ПодразделениеПриход):
        п = erp.String(стр.ПодразделениеПриход)
        покрытие[п] = round(покрытие.get(п, 0) + стр.СуммаДокумента, 2)
    if erp.ЗначениеЗаполнено(стр.ПодразделениеРасход):
        п = erp.String(стр.ПодразделениеРасход)
        покрытие[п] = round(покрытие.get(п, 0) - стр.СуммаДокумента, 2)
print(f"Сгенерировано пар (взаимозачётов) по документу: {n_пар}\n")

# 5) Сверка по каждому подразделению
все_подр = sorted(set(истина) | set(покрытие))
ok = True
плохие = []
for п in все_подр:
    t = истина.get(п, 0)
    c = покрытие.get(п, 0)
    if abs(t - c) > 0.01:
        ok = False
        плохие.append((п, t, c, round(t - c, 2)))

if плохие:
    print("!!! РАСХОЖДЕНИЯ (подразделение | ПАП-сальдо | покрытие взаимозачётами | разница):")
    for п, t, c, d in плохие:
        print(f"   {п:45} | {t:>15.2f} | {c:>15.2f} | Δ={d:>12.2f}")
else:
    print("Все подразделения: покрытие взаимозачётами == ПАП-сальдо (баланс сойдётся).")

# 6) Орг-итог покрытия (должен быть 0)
итог_покр = round(sum(покрытие.values()), 2)
print(f"\nОрг-итог ПАП = {орг_итог}  | орг-итог покрытия = {итог_покр}")

if ok and abs(орг_итог) < 0.01 and abs(итог_покр) < 0.01:
    print("\n=== БАЛАНС ПО ПОДРАЗДЕЛЕНИЯМ СОЙДЁТСЯ (PASS) ===")
else:
    print("\n=== ВНИМАНИЕ: БАЛАНС МОЖЕТ СЛОМАТЬСЯ (FAIL) ===")
