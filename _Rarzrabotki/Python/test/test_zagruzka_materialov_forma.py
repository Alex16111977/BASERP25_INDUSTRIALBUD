def запрос(текст, **параметры):
    z = buh.NewObject("Запрос")
    z.Text = текст
    for имя, значение in параметры.items():
        z.SetParameter(имя, значение)
    return z.Execute().Выгрузить()


def сырые_строки_из_excel():
    """Читает лист как форма: колонки C,E,G,H,I,J,O в массив структур 1С."""
    книга = load_workbook(XLSX, data_only=True)
    лист = книга[ЛИСТ]
    массив = buh.NewObject("Массив")
    for ряд in range(2, лист.max_row + 1):
        стр = buh.NewObject("Структура")
        стр.Вставить("Ряд", ряд)
        стр.Вставить("Тип", str(лист.cell(ряд, 3).value or "").strip())
        стр.Вставить("Этап", str(лист.cell(ряд, 5).value or "").strip())
        стр.Вставить("Наименование", str(лист.cell(ряд, 7).value or "").strip())
        стр.Вставить("ОбщееНазвание", str(лист.cell(ряд, 8).value or "").strip())
        стр.Вставить("Единица", str(лист.cell(ряд, 9).value or "").strip())
        стр.Вставить("Количество", число(лист.cell(ряд, 10).value))
        стр.Вставить("Сумма", число(лист.cell(ряд, 15).value))
        массив.Добавить(стр)
    return массив


def число(значение):
    try:
        return float(значение) if значение is not None else 0.0
    except (TypeError, ValueError):
        return 0.0


def синтетическая_строка(этап, название, наименование, единица, количество, сумма, ряд):
    стр = buh.NewObject("Структура")
    стр.Вставить("Ряд", ряд)
    стр.Вставить("Тип", "Матеріал")
    стр.Вставить("Этап", этап)
    стр.Вставить("Наименование", наименование)
    стр.Вставить("ОбщееНазвание", название)
    стр.Вставить("Единица", единица)
    стр.Вставить("Количество", количество)
    стр.Вставить("Сумма", сумма)
    return стр


def эталон_из_excel():
    """Ожидание считаем независимо от 1С — правилами отбора по тексту спеки."""
    книга = load_workbook(XLSX, data_only=True)
    лист = книга[ЛИСТ]
    строки, этап = [], ""
    for ряд in range(2, лист.max_row + 1):
        тип = str(лист.cell(ряд, 3).value or "").strip()
        эт = str(лист.cell(ряд, 5).value or "").strip()
        наим = str(лист.cell(ряд, 7).value or "").strip()
        ед = str(лист.cell(ряд, 9).value or "").strip()
        кол, сум = число(лист.cell(ряд, 10).value), число(лист.cell(ряд, 15).value)
        if наим == "№" or ед.lower() == "од. виміру":
            break
        if эт:
            этап = эт
        числоподобно = lambda s: bool(s.replace(" ", "")) and all(
            c in "0123456789.,-" for c in s.replace(" ", ""))
        if тип == "Матеріал":
            if not наим:
                continue
        elif not тип:
            if not (наим and not числоподобно(наим) and ед and not числоподобно(ед)
                    and кол > 0 and сум > 0):
                continue
        else:
            continue
        строки.append((ряд, этап, наим, ед, round(кол, 3), round(сум, 2)))
    return строки


def найти_сс(наименование):
    т = запрос(
        "ВЫБРАТЬ ПЕРВЫЕ 1 СС.Ссылка КАК Ссылка ИЗ Справочник.СтруктураСебестоимости КАК СС "
        "ГДЕ СС.Наименование = &Наименование", Наименование=наименование)
    return т.Получить(0).Ссылка if т.Количество() else None


def получить_или_создать_сс(наименование):
    ссылка = найти_сс(наименование)
    if ссылка is not None:
        return ссылка.ПолучитьОбъект()
    объект = buh.Справочники.СтруктураСебестоимости.СоздатьЭлемент()
    объект.Наименование = наименование
    объект.Записать()
    return объект


def итоги_тч(объект):
    строк = объект.Комплектующие.Количество()
    кол = сум = 0.0
    for i in range(строк):
        строка = объект.Комплектующие.Получить(i)
        кол += round(строка.Количество, 3)
        сум += round(строка.Сумма, 2)
    return строк, round(кол, 3), round(сум, 2)


def печать_протокола(протокол, префикс="    "):
    for имя in ("Загружено", "СозданоЭтапов", "СозданоНазваний", "ЗаполненоЕдиниц",
                "ДозаполненоЕдиниц", "Пропущено", "ПодхваченоБезТипа", "КонтрольПройден", "Ошибка"):
        print(f"{префикс}{имя} = {getattr(протокол, имя)}")
    if протокол.Ошибка:
        print(f"{префикс}ТекстОшибки = {протокол.ТекстОшибки}")
    for имя in ("Контроль", "Предупреждения", "Инфо"):
        массив = getattr(протокол, имя)
        for i in range(массив.Количество()):
            print(f"{префикс}[{имя}] {массив.Получить(i)}")


