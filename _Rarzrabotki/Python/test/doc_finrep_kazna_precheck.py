# -*- coding: utf-8 -*-
"""Rule #-1: прогон запроса к kazna (БюджетыНаМесяц.Обороты) ДО вставки в BSL.

Запрос 1:1 как будет в ЗаполнитьПодразделенияИзКазны():
подразделения направления «Производство» за период с начала месяца по дату расчёта.
Плюс сверка имён с Справочник.Подразделения в bas_industrialbud (ожидание 14/14).
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
kazna = v8.Connect('Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"')
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = kazna.String

napr = kazna.Справочники.Направления.НайтиПоНаименованию("Производство", True)
print(f"Направление kazna: '{S(napr.Наименование)}'")

q = kazna.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
  Об.Подразделение.Наименование КАК Имя
ИЗ РегистрНакопления.БюджетыНаМесяц.Обороты(&НачалоМесяца, &ДатаРасчета, , Направление = &Направление) КАК Об
ГДЕ Об.Подразделение <> ЗНАЧЕНИЕ(Справочник.Подразделения.ПустаяСсылка)
УПОРЯДОЧИТЬ ПО Имя
"""


def дата(base, г, м, д, ч=0, мин=0, с=0):
    qd = base.NewObject("Запрос")
    qd.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({г},{м},{д},{ч},{мин},{с}) КАК Д"
    return qd.Execute().Выгрузить().Получить(0).Д


q.УстановитьПараметр("НачалоМесяца", дата(kazna, 2026, 8, 1))
q.УстановитьПараметр("ДатаРасчета", дата(kazna, 2026, 8, 7, 23, 59, 59))
q.УстановитьПараметр("Направление", napr)

try:
    r = q.Execute().Выгрузить()
except Exception as e:
    print(f"FAIL запрос: {e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e}")
    sys.exit(1)

имена = [S(r.Получить(i).Имя) for i in range(r.Количество())]
print(f"\nПодразделений из kazna: {len(имена)} (ожидание 15)")

найдено, не_найдено = 0, []
for имя in имена:
    метка = ""
    if имя == "Главный офис":
        метка = "  << исключаем по имени"
    else:
        под = buh.Справочники.Подразделения.НайтиПоНаименованию(имя, True)
        if buh.string(под) == "":
            не_найдено.append(имя)
            метка = "  !! НЕ НАЙДЕНО в BuhBud"
        else:
            найдено += 1
    print(f"  '{имя}'{метка}")

print(f"\nБез «Главного офиса»: {len([и for и in имена if и != 'Главный офис'])} (ожидание 14)")
print(f"Сопоставлено с BuhBud по имени: {найдено} (ожидание 14)")
if не_найдено:
    print(f"НЕ найдено: {не_найдено}")
print("\nOK" if len(имена) == 15 and найдено == 14 and not не_найдено else "\nПРОВЕРИТЬ ОЖИДАНИЯ")
