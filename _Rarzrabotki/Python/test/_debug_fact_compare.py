def run(conn, text):
    q = conn.NewObject("Запрос")
    q.Текст = text
    t = q.Выполнить().Выгрузить()
    names = [t.Колонки.Получить(j).Имя for j in range(t.Колонки.Количество())]
    rows = []
    for i in range(t.Количество()):
        r = t.Получить(i)
        rows.append([r.Получить(j) for j in range(len(names))])
    return names, rows

def show(title, names, rows, limit=12):
    print("\n" + "=" * 72 + f"\n{title}\n" + "=" * 72)
    print("  " + " | ".join(names))
    tot = 0.0
    for row in rows[:limit]:
        print("  " + " | ".join(str(x) for x in row))
    for row in rows:
        try: tot += float(row[-1] or 0)
        except: pass
    print(f"  ... строк={len(rows)}  Σпоследней колонки={tot:.2f}")

