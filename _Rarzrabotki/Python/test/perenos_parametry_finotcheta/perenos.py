def структура(c):
    """Підпис регістру: періодичність, режим запису, кожне поле з типами й кваліфікаторами."""
    md = c.Метаданные.РегистрыСведений.Найти(РЕГ)
    if md is None:
        return None, None
    поля = {}
    for вид, кол in (("вимір", md.Измерения), ("ресурс", md.Ресурсы), ("реквізит", md.Реквизиты)):
        for i in range(кол.Количество()):
            x = кол.Получить(i)
            т = x.Тип
            типи = sorted(c.String(т.Типы().Получить(j)) for j in range(т.Типы().Количество()))
            поля[x.Имя] = (вид, tuple(типи), int(т.КвалификаторыЧисла.Разрядность), int(т.КвалификаторыЧисла.РазрядностьДробнойЧасти),
                           int(т.КвалификаторыСтроки.Длина), c.String(т.КвалификаторыДаты.ЧастиДаты))
    return (c.String(md.ПериодичностьРегистраСведений), c.String(md.РежимЗаписи), поля), md


