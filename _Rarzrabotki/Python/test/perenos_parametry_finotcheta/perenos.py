print("структура однакова: %d ресурсів (дати: %s, числа: %d)" % (len(РЕСУРСИ), ДАТИ, len(ЧИСЛА)))


def прочитати(c):
    """Усі записи регістру: ключ — UUID договору; дати покомпонентно; реквізити договору для запасного ключа."""
    вибір = ["Р.Договор КАК Договор", "Р.Договор.Наименование КАК ДогИмя", "Р.Договор.Номер КАК ДогНомер",
             "Р.Договор.Владелец КАК Влад", "Р.Договор.Владелец.Наименование КАК ВладИмя",
             "Р.Договор.Владелец.КодПоЕДРПОУ КАК ВладКод", "Р.Договор.Организация.Наименование КАК ОргИмя",
             "Р.Договор.ПометкаУдаления КАК ДогПом"]
    for к in РЕСУРСИ:
        if к in ДАТИ:
            вибір += ["%s(Р.%s) КАК %s_%s" % (ф, к, к, ф) for ф in ("ГОД", "МЕСЯЦ", "ДЕНЬ", "ЧАС", "МИНУТА", "СЕКУНДА")]
        else:
            вибір.append("Р.%s КАК %s" % (к, к))
    q = c.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ " + ", ".join(вибір) + " ИЗ РегистрСведений.%s КАК Р" % РЕГ
    т = q.Execute().Выгрузить()
    рез = {}
    for i in range(т.Количество()):
        р = т.Получить(i)
        u = c.String(р.Договор.УникальныйИдентификатор()).lower()
        зап = {"dog_uuid": u, "dog_name": str(р.ДогИмя or "").strip(), "dog_num": str(р.ДогНомер or "").strip(),
               "owner_name": str(р.ВладИмя or "").strip(), "owner_code": str(р.ВладКод or "").strip(),
               "org_name": str(р.ОргИмя or "").strip(), "dog_mark": bool(р.ДогПом), "values": {}}
        for к in РЕСУРСИ:
            if к in ДАТИ:
                зап["values"][к] = [int(getattr(р, "%s_%s" % (к, ф)) or 0) for ф in ("ГОД", "МЕСЯЦ", "ДЕНЬ", "ЧАС", "МИНУТА", "СЕКУНДА")]
            elif к in ЧИСЛА:
                зап["values"][к] = str(Decimal(repr(float(getattr(р, к) or 0))).quantize(Decimal(1).scaleb(-ЧИСЛА[к]), ROUND_HALF_UP))
            else:
                зап["values"][к] = str(getattr(р, к) or "")
        рез[u] = зап
    return рез


def знайти_договір(зап):
    """Договір приймача: за UUID (з перевіркою, що об'єкт існує), інакше — однозначний запасний ключ."""
    реф = dst.Справочники.ДоговорыКонтрагентов.ПолучитьСсылку(dst.NewObject("УникальныйИдентификатор", зап["dog_uuid"]))
    if реф.ПолучитьОбъект() is not None:
        return реф, "UUID"
    q = dst.NewObject("Запрос")
    q.Text = """ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д
        ГДЕ НЕ Д.ПометкаУдаления И Д.Наименование = &Имя И Д.Номер = &Номер И Д.Организация.Наименование = &Орг
          И (&Код <> "" И Д.Владелец.КодПоЕДРПОУ = &Код ИЛИ &Код = "" И Д.Владелец.Наименование = &ВладИмя)"""
    for п, з in (("Имя", зап["dog_name"]), ("Номер", зап["dog_num"]), ("Орг", зап["org_name"]),
                 ("Код", зап["owner_code"]), ("ВладИмя", зап["owner_name"])):
        q.SetParameter(п, з)
    т = q.Execute().Выгрузить()
    if т.Количество() == 1:
        return т.Получить(0).Ссылка, "ключ"
    return None, "НЕМАЄ" if т.Количество() == 0 else "НЕОДНОЗНАЧНО (%d)" % т.Количество()


def значення_для_запису(values):
    рез = {}
    for к, в in values.items():
        if к in ДАТИ:
            if в[0] > 1:  # порожню дату (01.01.0001) не присвоюємо — ресурс і так порожній
                рез[к] = pywintypes.Time(datetime.datetime(*в) + datetime.timedelta(hours=3))  # COM зсуває на −3 год
        elif к in ЧИСЛА:
            рез[к] = Decimal(в)
        else:
            рез[к] = в
    return рез


def записати(реф, values):
    менеджер = getattr(dst.РегистрыСведений, РЕГ)
    н = менеджер.СоздатьНаборЗаписей()
    н.Отбор.Договор.Установить(реф)
    if values is not None:
        з = н.Добавить()
        з.Договор = реф
        for к, в in значення_для_запису(values).items():
            setattr(з, к, в)
    н.ОбменДанными.Загрузка = True
    н.ДополнительныеСвойства.Вставить("ОтключитьМеханизмРегистрацииОбъектов", True)
    н.Записать(True)


