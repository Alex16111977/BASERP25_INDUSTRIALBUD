# -*- coding: utf-8 -*-
"""
Приёмка Части A+B: реальный BSL заполняет НачисленнаяЗарплатаИВзносыПоФизлицам
по новому алгоритму. Заполнение В ПАМЯТИ (без записи/проведения).

Проверяет:
  - Постернак: 4 строки (ЕСВ Ф1; Зарплата управл Ф1=27913.53; Ф2=172086.47; Удержание Ф1=8337.81),
    ОргБух Ф1=ІНДАСТРІАЛБУД, Ф2 пусто;
  - Шишкина: ОргБух Ф1=ІНДЕПТ СТІЛ; инвариант=65000;
  - Глобально: для всех ФЛ с НачисленияУпр≠0  Σ(Сумма где А_ЭтоУдержание=Ложь)=Σ НачисленияУпр;
    ни одной строки-удержания (А_ЭтоУдержание=Истина) с ФормаPL=Форма2.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Текст = ('ВЫБРАТЬ А.Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне КАК А '
           'ГДЕ А.Дата >= ДАТАВРЕМЯ(2025,12,1,0,0,0) И А.Дата <= ДАТАВРЕМЯ(2025,12,31,23,59,59) '
           'УПОРЯДОЧИТЬ ПО А.Дата')
sel = q.Выполнить().Выбрать()
sel.Следующий()
obj = sel.Ссылка.ПолучитьОбъект()
print(f"Заповнюємо №{S(obj.Номер)} в пам'яті...")
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()

ф1 = erp.XMLСтрока(erp.Перечисления.А_ФормыPL.Форма1)

def строки(fio):
    res = []
    for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
        if fio not in S(r.ФизическоеЛицо):
            continue
        sp = r.СпособОтраженияЗарплатыВБухучете
        res.append({
            "форма": erp.XMLСтрока(r.ФормаPL),
            "способ": S(sp),
            "удерж": bool(sp.А_ЭтоУдержание) if erp.ЗначениеЗаполнено(sp) else False,
            "подр": S(r.ПодразделениеПредприятия),
            "оргбух": S(r.ОрганизацияБухгалтерия),
            "сумма": float(r.Сумма),
            "взносы": float(r.ВзносыВсего),
        })
    return res

def упр_сумма(fio):
    z = erp.NewObject("Запрос")
    z.Текст = ('ВЫБРАТЬ СУММА(Ф.Сумма) КАК С ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленияУпр КАК Ф '
               'ГДЕ Ф.Ссылка = &С И Ф.ФизЛицо.Наименование ПОДОБНО &Ф')
    z.УстановитьПараметр("С", obj.Ссылка)
    z.УстановитьПараметр("Ф", fio + "%")
    t = z.Выполнить().Выгрузить()
    return float(t[0][0]) if t.Количество() and t[0][0] is not None else 0.0

ok = True
for fio, эталон_орг in [("Постернак", 'ІНДАСТРІАЛБУД'), ("Шишкіна", 'ІНДЕПТ СТІЛ')]:
    rows = строки(fio)
    net = упр_сумма(fio)
    print(f"\n=== {fio} ===  (НачисленияУпр={net:,.2f}, рядків={len(rows)})")
    inv = 0.0
    for r in rows:
        if not r["удерж"]:
            inv += r["сумма"]
        flag = ""
        if r["удерж"] and r["форма"] == "Форма2":
            flag = "  <-- FAIL: удержание в Ф2!"; ok = False
        print(f"  {r['форма']:7} | {r['способ'][:32]:32} | {r['подр'][:14]:14} | "
              f"ОргБух={r['оргбух'][:18]:18} | Σ={r['сумма']:>12,.2f} | Внз={r['взносы']:>10,.2f}{flag}")
    print(f"  ИНВАРИАНТ Σ(нач,А_ЭтоУдержание=Ложь)={inv:,.2f}  vs НачисленияУпр={net:,.2f}  ->",
          "OK" if abs(inv - net) < 0.02 else "FAIL")
    if abs(inv - net) >= 0.02:
        ok = False
    # ОргБух у Ф1-начислений
    for r in rows:
        if r["форма"] == ф1 and not r["удерж"] and r["взносы"] == 0 and эталон_орг not in r["оргбух"]:
            print(f"    WARN ОргБух Ф1 = '{r['оргбух']}' (очікувалось {эталон_орг})")

# === Глобальный инвариант по всем ФЛ с НачисленияУпр≠0 ===
print("\n=== ГЛОБАЛЬНЫЙ инвариант (все ФЛ с НачисленияУпр≠0) ===")
upr = {}
z = erp.NewObject("Запрос")
z.Текст = ('ВЫБРАТЬ Ф.ФизЛицо КАК ФЛ, СУММА(Ф.Сумма) КАК С '
           'ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленияУпр КАК Ф ГДЕ Ф.Ссылка = &С '
           'СГРУППИРОВАТЬ ПО Ф.ФизЛицо')
z.УстановитьПараметр("С", obj.Ссылка)
t = z.Выполнить().Выгрузить()
for i in range(t.Количество()):
    if erp.ЗначениеЗаполнено(t[i].ФЛ):
        upr[S(t[i].ФЛ)] = float(t[i].С)

нз_нач = {}
удерж_ф2 = 0
for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
    fl = S(r.ФизическоеЛицо)
    sp = r.СпособОтраженияЗарплатыВБухучете
    udr = bool(sp.А_ЭтоУдержание) if erp.ЗначениеЗаполнено(sp) else False
    if udr and erp.XMLСтрока(r.ФормаPL) == "Форма2":
        удерж_ф2 += 1
    if not udr:
        нз_нач[fl] = нз_нач.get(fl, 0) + float(r.Сумма)

плохих = 0
for fl, net in upr.items():
    got = нз_нач.get(fl, 0)
    if abs(got - net) >= 0.02:
        плохих += 1
        if плохих <= 10:
            print(f"  FAIL {fl[:40]:40} НачУпр={net:,.2f} != Σнач={got:,.2f}  Δ={got-net:,.2f}")
print(f"  ФЛ с НачисленияУпр≠0: {len(upr)};  нарушений инварианта: {плохих};  удержаний в Ф2: {удерж_ф2}")
if плохих or удерж_ф2:
    ok = False

print("\n" + ("OK: приёмка Части A+B пройдена" if ok else "FAIL: есть ошибки (см. выше)"))
sys.exit(0 if ok else 1)
