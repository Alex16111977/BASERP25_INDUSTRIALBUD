def check(condition, title, detail=""):
    global ok_count, fail_count
    if condition:
        ok_count += 1
        print(f"  OK   {title}")
    else:
        fail_count += 1
        print(f"  FAIL {title}" + (f" — {detail}" if detail else ""))


def найти_документ(conn, номер):
    q = conn.NewObject("Запрос")
    q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.РасчетКомплектаций ГДЕ Номер = &Номер"
    q.УстановитьПараметр("Номер", номер)
    таблица = q.Выполнить().Выгрузить()
    assert таблица.Количество() > 0, f"нет расчёта {номер}"
    return таблица.Получить(0).Ссылка


def разметка_печати(conn, таб_док):
    """Строка шапки и номера колонок названия / кода / комментария."""
    for строка in range(1, min(таб_док.ВысотаТаблицы, 30) + 1):
        назв = код = комм = 0
        for колонка in range(1, таб_док.ШиринаТаблицы + 1):
            текст = str(таб_док.Область(строка, колонка, строка, колонка).Текст or "").strip()
            if текст == "Загальна назва":
                назв = колонка
            elif текст == "Код":
                код = колонка
            elif текст == "Коментар цеху":
                комм = колонка
        if назв and комм:
            return {"строка": строка, "назв": назв, "код": код, "комм": комм}
    return None


def область_жирная(область):
    try:
        шрифт = область.Шрифт
        return bool(шрифт is not None and шрифт.Жирный)
    except Exception:
        return False


def строки_печати(таб_док, разметка):
    """[(номер строки, название, код, жирная)] от шапки до «Итого»."""
    результат = []
    for строка in range(разметка["строка"] + 1, таб_док.ВысотаТаблицы + 1):
        область = таб_док.Область(строка, разметка["назв"], строка, разметка["назв"])
        название = str(область.Текст or "").strip()
        if not название:
            continue
        if название.upper() in ("ИТОГО", "РАЗОМ", "ВСЬОГО"):
            break
        if название.upper() == "НОМЕНКЛАТУРА" and строка <= разметка["строка"] + 2:
            continue
        код = ""
        if разметка["код"]:
            код = str(таб_док.Область(строка, разметка["код"], строка, разметка["код"]).Текст or "").strip()
        результат.append((строка, название, код, область_жирная(область)))
    return результат


def снимок_списания(conn, объект):
    """Числовые/ссылочные колонки списания — для проверки «ничего лишнего не тронуто»."""
    снимок = []
    тч = объект.СписаниеСверхНормы
    for i in range(тч.Количество()):
        с = тч.Получить(i)
        снимок.append((conn.String(с.Номенклатура), conn.String(с.Склад), conn.String(с.Счет),
                       conn.String(с.Организация), conn.String(с.Единица),
                       str(с.Количество), str(с.Цена), str(с.Сумма),
                       str(с.КоличествоКСписанию), str(с.КоличествоСС), str(с.СуммаСС)))
    return снимок


def записать_книгу(conn, таб_док, путь):
    таб_док.Записать(путь, conn.ТипФайлаТабличногоДокумента.XLSX)
    return путь


