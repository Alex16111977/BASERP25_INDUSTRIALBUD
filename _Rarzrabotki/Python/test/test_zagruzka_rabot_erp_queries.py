# -*- coding: utf-8 -*-
"""RED-фаза (Rule #-1): проверка ВСЕХ запросов движка «Загрузка работ в СС для базы ЕРП»
на живой BaseERP через COM — 1:1 с текстами, которые пойдут в BSL (ObjectModule.bsl).

Запуск: C:\\Python313\\python.exe test_zagruzka_rabot_erp_queries.py
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

FAILED = []


def run(title, text, params=None, show=0):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, val in (params or {}).items():
        q.SetParameter(k, val)
    try:
        r = q.Execute().Выгрузить()
        print(f"OK   {title}: рядків={r.Количество()}")
        for i in range(min(show, r.Количество())):
            row = r.Получить(i)
            cols = []
            for c in range(r.Колонки.Количество()):
                cols.append(str(row.Получить(c)))
            print("     |", " ; ".join(cols))
        return r
    except Exception as e:
        msg = e.excepinfo[2] if getattr(e, 'excepinfo', None) else str(e)
        print(f"FAIL {title}: {msg}")
        FAILED.append(title)
        return None


# --- 1. Группа _Роботи (код 0Ц-00000016) ---
r1 = run("ГруппаРоботи", """ВЫБРАТЬ Ссылка ИЗ Справочник.Номенклатура
ГДЕ Код = &Код И ЭтоГруппа""", {"Код": "0Ц-00000016"})
группа = r1.Получить(0).Ссылка if r1 is not None and r1.Количество() > 0 else None
print("     группа =", erp.String(группа) if группа is not None else "НЕ НАЙДЕНА")

# --- 2. Образец работы (артикул 1.1.1 в иерархии группы) ---
r2 = run("ОбразецРаботы", """ВЫБРАТЬ Ссылка ИЗ Справочник.Номенклатура
ГДЕ Артикул = &Арт И НЕ ЭтоГруппа И Родитель В ИЕРАРХИИ(&Гр)""",
         {"Арт": "1.1.1", "Гр": группа})
образец = r2.Получить(0).Ссылка if r2 is not None and r2.Количество() > 0 else None
print("     образец =", erp.String(образец) if образец is not None else "НЕ НАЙДЕН")

# --- 3. Кэш этапов ---
r3 = run("КэшЭтапов", "ВЫБРАТЬ Наименование, Ссылка ИЗ Справочник.А_ЭтапыРабот")
if r3 is not None:
    имена = [r3.Получить(i).Наименование for i in range(r3.Количество())]
    print("     этапы:", "; ".join(имена))
    цель = "загальновиробничі витрати"
    print("     «Загальновиробничі витрати» в базе:",
          "ЕСТЬ" if any(цель == (n or "").strip().lower() for n in имена) else "НЕТ (get-or-create создаст)")

# --- 4. Кэш работ группы _Роботи ---
r4 = run("КэшРабот", """ВЫБРАТЬ Наименование, Ссылка ИЗ Справочник.Номенклатура
ГДЕ НЕ ЭтоГруппа И Родитель В ИЕРАРХИИ(&Гр)""", {"Гр": группа})

# --- элемент А_СтруктураСебестоимости для контрольных запросов ---
r5 = run("ЛюбаяСтруктура", """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.А_СтруктураСебестоимости
ГДЕ НЕ ЭтоГруппа""")
структура = r5.Получить(0).Ссылка if r5 is not None and r5.Количество() > 0 else None
print("     структура =", erp.String(структура) if структура is not None else "нет элементов")

# --- 5. Контроль: итоги ТЧ Работы ---
run("КонтрольИтоги", """ВЫБРАТЬ
	КОЛИЧЕСТВО(*) КАК Строк,
	СУММА(Р.Количество) КАК СуммаКоличество,
	СУММА(Р.Сумма) КАК СуммаСумма
ИЗ
	Справочник.А_СтруктураСебестоимости.Работы КАК Р
ГДЕ
	Р.Ссылка = &Структура""", {"Структура": структура}, show=1)

# --- 6. Контроль: суммы по этапам ---
run("КонтрольПоЭтапам", """ВЫБРАТЬ
	Р.Этап КАК Этап,
	СУММА(Р.Сумма) КАК СуммаСумма
ИЗ
	Справочник.А_СтруктураСебестоимости.Работы КАК Р
ГДЕ
	Р.Ссылка = &Структура

СГРУППИРОВАТЬ ПО
	Р.Этап""", {"Структура": структура})

# --- 7. Инфо-блок ---
run("ИнфоБлок", """ВЫБРАТЬ
	КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.Работа) КАК УникальныхРабот,
	СУММА(ВЫБОР КОГДА Р.Этап = ЗНАЧЕНИЕ(Справочник.А_ЭтапыРабот.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК БезЭтапа,
	СУММА(ВЫБОР КОГДА Р.Работа = ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК БезРаботы
ИЗ
	Справочник.А_СтруктураСебестоимости.Работы КАК Р
ГДЕ
	Р.Ссылка = &Структура""", {"Структура": структура}, show=1)

print()
print("ИТОГ:", "ВСЕ ЗАПРОСЫ OK" if not FAILED else f"ПРОВАЛЫ: {FAILED}")
sys.exit(1 if FAILED else 0)
