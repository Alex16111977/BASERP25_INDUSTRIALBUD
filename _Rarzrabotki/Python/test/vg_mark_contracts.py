# -*- coding: utf-8 -*-
"""Разметка договоров _КОРПОРАТИВНІ по видам контрагентов (А_ВидКонтрагента).

Маппинг по иерархии Справочник.Партнеры:
  «Група наших компаній»  -> Внутригрупповые
  «Підрозділи»            -> Внутренние
  Воронцов*               -> Собственники

Режимы:  python vg_mark_contracts.py          — DRY RUN (только отчёт)
         python vg_mark_contracts.py APPLY    — запись (ОбменДанными.Загрузка=Истина)
Идемпотентно: договоры с уже верным видом пропускаются.
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

APPLY = len(sys.argv) > 1 and sys.argv[1].upper() == "APPLY"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# --- 1. Предопределённые виды ---
МенВидов = erp.Справочники.А_ВидыКонтрагентовДляБаланса
ВидВнутригрупповые = МенВидов.Внутригрупповые
ВидВнутренние      = МенВидов.Внутренние
ВидСобственники    = МенВидов.Собственники
ВидВнешние         = МенВидов.Внешние
ВидКредиторы       = МенВидов.Кредиторы
print("Виды (предопределённые):")
for назв, ссыл in [("Внутригрупповые", ВидВнутригрупповые), ("Внутренние", ВидВнутренние),
                   ("Собственники", ВидСобственники), ("Внешние", ВидВнешние), ("Кредиторы", ВидКредиторы)]:
    ок = erp.ЗначениеЗаполнено(ссыл)
    print(f"  {назв}: {'OK — ' + S(ссыл) if ок else 'НЕ НАЙДЕН!'}")
    if not ок:
        sys.exit(1)

# --- 2. Узлы иерархии партнёров ---
МенПартнеры = erp.Справочники.Партнеры
УзелГруппа  = МенПартнеры.НайтиПоНаименованию("Група наших компаній")
УзелПодр    = МенПартнеры.НайтиПоНаименованию("Підрозділи")
КореньКорп  = МенПартнеры.НайтиПоНаименованию("_КОРПОРАТИВНІ")
for назв, ссыл in [("Група наших компаній", УзелГруппа), ("Підрозділи", УзелПодр), ("_КОРПОРАТИВНІ", КореньКорп)]:
    if not erp.ЗначениеЗаполнено(ссыл):
        print(f"Узел партнёров «{назв}» НЕ найден"); sys.exit(1)

# Воронцов — элемент прямо под корнем, ищем ПОДОБНО
qv = erp.NewObject("Запрос")
qv.Text = """
ВЫБРАТЬ П.Ссылка КАК Ссылка, П.Наименование КАК Наименование
ИЗ Справочник.Партнеры КАК П
ГДЕ П.Родитель = &Корень И П.Наименование ПОДОБНО "Воронцов%" И НЕ П.ПометкаУдаления
"""
qv.SetParameter("Корень", КореньКорп)
rv = qv.Execute().Выгрузить()
if rv.Количество() != 1:
    print(f"Воронцов: ожидали 1 партнёра, найдено {rv.Количество()}"); sys.exit(1)
УзелВоронцов = rv.Получить(0).Ссылка
print(f"Воронцов: OK — {S(rv.Получить(0).Наименование)}")

# --- 3. Договоры по веткам ---
ЗАДАНИЯ = [
    ("Внутригрупповые", УзелГруппа,   ВидВнутригрупповые, True),   # в иерархии
    ("Внутренние",      УзелПодр,     ВидВнутренние,      True),
    ("Собственники",    УзелВоронцов, ВидСобственники,    False),  # элемент без детей
]

итого_изменить, итого_ок = 0, 0
объекты_к_записи = []  # (ссылка, вид, метка)

for метка, узел, вид, в_иерархии in ЗАДАНИЯ:
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        Д.Ссылка КАК Ссылка,
        Д.Наименование КАК Наименование,
        Д.Контрагент.Наименование КАК Контрагент,
        ВЫБОР КОГДА Д.А_ВидКонтрагента = &Вид ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК УжеВерно
    ИЗ
        Справочник.ДоговорыКонтрагентов КАК Д
    ГДЕ
        НЕ Д.ПометкаУдаления
        И """ + ("Д.Партнер В ИЕРАРХИИ (&Узел)" if в_иерархии else "Д.Партнер = &Узел")
    q.SetParameter("Узел", узел)
    q.SetParameter("Вид", вид)
    r = q.Execute().Выгрузить()
    н_изм, н_ок = 0, 0
    for i in range(r.Количество()):
        row = r.Получить(i)
        if row.УжеВерно:
            н_ок += 1
        else:
            н_изм += 1
            объекты_к_записи.append((row.Ссылка, вид, метка))
    print(f"[{метка}] договоров: {r.Количество()} (изменить: {н_изм}, уже верно: {н_ок})")
    итого_изменить += н_изм
    итого_ок += н_ок

# --- 3б. Неохваченные договоры в иерархии _КОРПОРАТИВНІ (вне 3 веток) ---
qn = erp.NewObject("Запрос")
qn.Text = """
ВЫБРАТЬ Д.Наименование КАК Наименование, Д.Партнер.Наименование КАК Партнер
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ НЕ Д.ПометкаУдаления
    И Д.Партнер В ИЕРАРХИИ (&Корень)
    И НЕ Д.Партнер В ИЕРАРХИИ (&Группа)
    И НЕ Д.Партнер В ИЕРАРХИИ (&Подр)
    И Д.Партнер <> &Воронцов
"""
qn.SetParameter("Корень", КореньКорп)
qn.SetParameter("Группа", УзелГруппа)
qn.SetParameter("Подр", УзелПодр)
qn.SetParameter("Воронцов", УзелВоронцов)
rn = qn.Execute().Выгрузить()
print(f"[ВНЕ ВЕТОК] договоров в _КОРПОРАТИВНІ вне 3 веток: {rn.Количество()} (вид НЕ ставим)")
for i in range(min(rn.Количество(), 15)):
    row = rn.Получить(i)
    print(f"    {S(row.Партнер)} | {S(row.Наименование)}")

print(f"\nИТОГО: к изменению {итого_изменить}, уже верно {итого_ок}")

# --- 4. Запись ---
if not APPLY:
    print("\nDRY RUN — запись не выполнялась. Для записи: python vg_mark_contracts.py APPLY")
    sys.exit(0)

print("\nЗАПИСЬ...")
ошибки, записано = 0, 0
for ссылка, вид, метка in объекты_к_записи:
    try:
        обј = ссылка.ПолучитьОбъект()
        обј.А_ВидКонтрагента = вид
        обј.ОбменДанными.Загрузка = True   # без бизнес-логики/подписок
        обј.Записать()
        записано += 1
        if записано % 200 == 0:
            print(f"  ...{записано}/{итого_изменить}")
    except Exception as e:
        ошибки += 1
        if ошибки <= 5:
            msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
            print(f"  ОШИБКА [{метка}] {S(ссылка)}: {msg}")
print(f"Записано: {записано}, ошибок: {ошибки}")

# --- 5. Контрольный пересчёт ---
qc = erp.NewObject("Запрос")
qc.Text = """
ВЫБРАТЬ Д.А_ВидКонтрагента.Наименование КАК Вид, КОЛИЧЕСТВО(*) КАК Кол
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ Д.А_ВидКонтрагента <> ЗНАЧЕНИЕ(Справочник.А_ВидыКонтрагентовДляБаланса.ПустаяСсылка)
    И НЕ Д.ПометкаУдаления
СГРУППИРОВАТЬ ПО Д.А_ВидКонтрагента.Наименование
"""
rc = qc.Execute().Выгрузить()
print("\nКонтроль — договоров с видом:")
for i in range(rc.Количество()):
    row = rc.Получить(i)
    print(f"  {S(row.Вид)}: {row.Кол}")
