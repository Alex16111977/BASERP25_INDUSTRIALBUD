def дата_в_1с(текст):
    """'dd.mm.yyyy h:mm:ss' з S() -> значення для COM (порожня дата -> None)."""
    if not текст or текст.startswith("01.01.0001"):
        return None
    д = datetime.datetime.strptime(текст.split(" ")[0], "%d.%m.%Y")
    return д + datetime.timedelta(hours=3)


def знайти_договір(назва):
    q = c.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д "
              "ГДЕ Д.Наименование = &Н И НЕ Д.ПометкаУдаления И Д.Подразделение.Наименование ПОДОБНО \"М_ %\"")
    q.SetParameter("Н", назва)
    в = q.Execute().Выгрузить()
    if в.Количество() != 1:
        raise SystemExit(f"ПОМИЛКА: договір «{назва}» знайдено {в.Количество()} разів")
    return в.Получить(0).Ссылка


def знайти_акт(номер, сума):
    q = c.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ Р.Ссылка КАК Ссылка ИЗ Документ.АктОбОказанииПроизводственныхУслуг КАК Р "
              "ГДЕ Р.Номер = &Н И Р.СуммаДокумента = &С")
    q.SetParameter("Н", номер)
    q.SetParameter("С", сума)
    в = q.Execute().Выгрузить()
    if в.Количество() != 1:
        raise SystemExit(f"ПОМИЛКА: акт {номер} на {сума} знайдено {в.Количество()} разів")
    return в.Получить(0).Ссылка


