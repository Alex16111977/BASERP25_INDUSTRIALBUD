# -*- coding: utf-8 -*-
"""
Проверка типизации колонок ТаблицаЗначений (Object dataset для СКД).

Вопрос: если запрос уже возвращает типизированные значения
(ЗНАЧЕНИЕ(Документ.А_ОтчетPL.ПустаяСсылка) в UNION ALL ветках,
ТЧ.Ссылка как ДокументСсылка в основной ветке),
то правильный ли тип у результирующей колонки ТаблицаЗначений?

Также проверяем правильность fix: ТаблицаДанных.Колонки.Документ.ТипЗначения = ...
падает с «Поле объекта недоступно для записи (ТипЗначения)» —
значит надо пересоздавать колонку или менять подход.
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONNECTION_STRING = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected to BaseERP")

    # Полный запрос из ПолучитьОбъединенныеДанные
    query_text = """
    ВЫБРАТЬ
        ТЧ.Ссылка КАК Документ,
        ТЧ.Ссылка.Подразделение КАК Подразделение,
        ТЧ.Статья КАК СтатьяPL,
        СУММА(ТЧ.Сумма) КАК СуммаPL,
        МАКСИМУМ(ВЫРАЗИТЬ(ТЧ.Комментарий КАК Строка(1000))) КАК Комментарий
    ПОМЕСТИТЬ втPL
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
    ГДЕ ТЧ.Ссылка.Дата МЕЖДУ &НачалоПериода И &КонецПериода
        И НЕ ТЧ.Ссылка.ПометкаУдаления
    СГРУППИРОВАТЬ ПО ТЧ.Ссылка, ТЧ.Ссылка.Подразделение, ТЧ.Статья
    ;
    ВЫБРАТЬ
        PL.Подразделение, PL.СтатьяPL, PL.СуммаPL, PL.Документ, PL.Комментарий
    ИЗ втPL КАК PL

    ОБЪЕДИНИТЬ ВСЕ

    ВЫБРАТЬ
        NULL, NULL, 0,
        ЗНАЧЕНИЕ(Документ.А_ОтчетPL.ПустаяСсылка),
        ВЫРАЗИТЬ("" КАК Строка(1000))
    """
    q = conn.NewObject("Запрос")
    q.Текст = query_text
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(datetime(2025, 12, 1)))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(datetime(2025, 12, 31, 23, 59, 59)))

    table = q.Выполнить().Выгрузить()
    print(f"[OK] Query returned {table.Количество()} rows")

    # === Тест 1: типы колонок из запроса ===
    print("\n--- Колонки таблицы результата ---")
    for i in range(table.Колонки.Количество()):
        col = table.Колонки.Получить(i)
        # ТипЗначения — это ОписаниеТипов
        types = col.ТипЗначения.Типы()
        type_names = [str(t) for t in list(types)]
        print(f"  [{i}] {col.Имя}: {type_names}")

    # === Тест 2: попытка присвоить ТипЗначения ===
    print("\n--- Попытка col.ТипЗначения = ... (как в ObjectModule.bsl) ---")
    try:
        col_doc = table.Колонки.Найти("Документ")
        new_type = conn.NewObject("ОписаниеТипов", "ДокументСсылка.А_ОтчетPL")
        col_doc.ТипЗначения = new_type
        print("[?] Присваивание прошло (неожиданно)")
    except Exception as e:
        print(f"[CONFIRMED ERROR] {e}")

    # === Тест 3: правильный способ — пересоздать колонку ===
    print("\n--- Альтернатива: пересоздать колонку ---")
    try:
        # Сохраняем значения
        old_col = table.Колонки.Найти("Комментарий")
        values = []
        for row in table:
            values.append(row.Комментарий)
        # Удаляем и добавляем с новым типом
        table.Колонки.Удалить(old_col)
        new_type = conn.NewObject("ОписаниеТипов", "Строка", None,
                                   conn.NewObject("КвалификаторыСтроки", 1000))
        table.Колонки.Добавить("Комментарий", new_type)
        for idx, row in enumerate(table):
            row.Комментарий = values[idx]
        print(f"[OK] Колонка Комментарий пересоздана, тип: {list(table.Колонки.Найти('Комментарий').ТипЗначения.Типы())}")
    except Exception as e:
        print(f"[FAIL] Пересоздание: {e}")

    # === Тест 4: вообще нужна ли типизация? ===
    # Если в запросе все значения типизированы (ЗНАЧЕНИЕ + ТЧ.Ссылка),
    # то колонка ТаблицаЗначений уже имеет правильный тип.
    print("\n--- Конечный ответ: типы колонок из запроса ДОСТАТОЧНЫ? ---")
    print("Документ в UNION ALL: ТЧ.Ссылка (ДокументСсылка) + ЗНАЧЕНИЕ(ПустаяСсылка) → ОписаниеТипов = ДокументСсылка.А_ОтчетPL")
    print("Если да — блок типизации в ObjectModule.bsl НЕ нужен (удалить строки 17-18).")

    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
