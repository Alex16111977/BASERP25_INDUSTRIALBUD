"""Verify (acceptance) для фикса РКО «Выплата работнику».

Запускать ПОСЛЕ: загрузки конфигурации + перепроводки РКО ІБ00-000006.
Проверяет, что во ВСЕХ 5 регистрах движения только по одному работнику (Марчук),
Σ = СуммаДокумента (21 612,50), а не вся ведомость (94 323,00).

Регистры:
  1. А_ВзаиморасчетыССотрудниками         — 1 ФЛ, Σ СуммаВзаиморасчетов
  2. ПрочиеАктивыПассивы (ОплатаТруда)     — Приход, Σ
  3. ПрочиеАктивыПассивы (ДенСрНаличные)   — Расход, Σ
  4. ДенежныеСредстваНаличные              — Σ Сумма = СуммаДокумента (физкасса)
  5. ДвиженияДенежныеСредстваДоходыРасходы — 1 ФЛ (АналитикаАктивовПассивов), Σ
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
XS = erp.XMLСтрока

NUM = "ІБ00-000006"
TOL = 0.01
errors = []

# ── Найти РКО ───────────────────────────────────────────────────────────────
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ Д.Ссылка КАК Ссылка, Д.ПодотчетноеЛицо КАК Работник,
       Д.СуммаДокумента КАК СуммаДок, Д.Проведен КАК Проведен, Д.ХозяйственнаяОперация КАК ХозОп
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
ГДЕ Д.Номер = &Ном
"""
q.SetParameter("Ном", NUM)
sel = q.Execute().Выгрузить()
target = None
for r in sel:
    if XS(r.ХозОп) == "ВыплатаЗарплатыРаботнику":
        target = r
assert target is not None, f"РКО {NUM} (ВыплатаЗарплатыРаботнику) не найден"
DOC = target.Ссылка
РАБОТНИК = S(target.Работник)
СУММА = float(target.СуммаДок)
assert target.Проведен, "РКО не проведён — сначала перепроведите документ!"
print(f"РКО {NUM} | Работник={РАБОТНИК} | СуммаДок={СУММА:,.2f} | Проведен={target.Проведен}\n")


def check(name, query, expect_fl=None, expect_sum=None, fl_field="ФЛ", sum_field="Сумма"):
    qq = erp.NewObject("Запрос")
    qq.Text = query
    qq.SetParameter("Док", DOC)
    res = qq.Execute().Выгрузить()
    rows = [(S(getattr(r, fl_field)) if expect_fl is not None else None, float(getattr(r, sum_field))) for r in res]
    total = sum(s for _, s in rows)
    fls = {fl for fl, _ in rows if fl is not None}
    print(f"[{name}] строк={len(rows)}, Σ={total:,.2f}" + (f", ФЛ={fls}" if expect_fl is not None else ""))
    for fl, s in rows:
        print(f"    {fl if fl else ''} | {s:,.2f}")
    if expect_sum is not None and abs(total - expect_sum) > TOL:
        errors.append(f"{name}: Σ={total:,.2f} != ожидаемо {expect_sum:,.2f}")
    if expect_fl is not None and fls != {expect_fl}:
        errors.append(f"{name}: ФЛ={fls} != {{{expect_fl}}}")
    return total, fls


# 1. А_ВзаиморасчетыССотрудниками
check("1. А_ВзСС", """
ВЫБРАТЬ Р.ФизическоеЛицо КАК ФЛ, Р.Подразделение КАК Подр,
       СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                   ТОГДА Р.СуммаВзаиморасчетов ИНАЧЕ -Р.СуммаВзаиморасчетов КОНЕЦ) КАК Сумма
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р
ГДЕ Р.Регистратор = &Док
СГРУППИРОВАТЬ ПО Р.ФизическоеЛицо, Р.Подразделение
""", expect_fl=РАБОТНИК, expect_sum=СУММА)

# 2. ПрочиеАктивыПассивы — Оплата труда (Приход = +)
check("2. ПАП ОплатаТруда", """
ВЫБРАТЬ Р.Подразделение КАК Подр,
       СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                   ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ) КАК Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Р
ГДЕ Р.Регистратор = &Док
    И Р.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОплатаТруда)
СГРУППИРОВАТЬ ПО Р.Подразделение
""", expect_sum=СУММА, sum_field="Сумма")

# 3. ПрочиеАктивыПассивы — ДенежныеСредстваНаличные (Расход = abs)
check("3. ПАП ДенСрНаличные", """
ВЫБРАТЬ Р.Подразделение КАК Подр,
       СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
                   ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ) КАК Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Р
ГДЕ Р.Регистратор = &Док
    И Р.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ДенежныеСредстваНаличные)
СГРУППИРОВАТЬ ПО Р.Подразделение
""", expect_sum=СУММА, sum_field="Сумма")

# 4. ДенежныеСредстваНаличные (физическая касса) — Σ = СуммаДокумента
check("4. ДенСрНаличные(касса)", """
ВЫБРАТЬ Р.Касса КАК Касса, Р.Подразделение КАК Подр, СУММА(Р.Сумма) КАК Сумма
ИЗ РегистрНакопления.ДенежныеСредстваНаличные КАК Р
ГДЕ Р.Регистратор = &Док
СГРУППИРОВАТЬ ПО Р.Касса, Р.Подразделение
""", expect_sum=СУММА, sum_field="Сумма")

# 5. ДвиженияДенежныеСредстваДоходыРасходы — 1 ФЛ
check("5. ДСДоходыРасходы", """
ВЫБРАТЬ Р.АналитикаАктивовПассивов КАК ФЛ, СУММА(Р.СуммаВВалюте) КАК Сумма
ИЗ РегистрНакопления.ДвиженияДенежныеСредстваДоходыРасходы КАК Р
ГДЕ Р.Регистратор = &Док
СГРУППИРОВАТЬ ПО Р.АналитикаАктивовПассивов
""", expect_fl=РАБОТНИК, expect_sum=СУММА, sum_field="Сумма")

print("\n" + "=" * 80)
if errors:
    print("❌ VERIFY FAIL:")
    for e in errors:
        print("   - " + e)
    sys.exit(1)
else:
    print(f"✅ VERIFY PASS — все 5 регистров: только {РАБОТНИК}, Σ={СУММА:,.2f} (не вся ведомость)")
print("=" * 80)
