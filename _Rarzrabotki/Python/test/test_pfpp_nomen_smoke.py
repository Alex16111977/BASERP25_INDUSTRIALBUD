# -*- coding: utf-8 -*-
# Smoke: .erf с полем НоменклатураНаименование (строка, факт закупок = Номенклатура.Наименование).
# Путь .erf: env PFPP_ERF или %TEMP%\pfpp_nomen.erf.
import win32com.client, sys, os
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
def f(x): return float(x) if x is not None else 0.0
def пусто(ref):
    return ref is None or (hasattr(ref, 'Пустая') and ref.Пустая())
ERF = os.environ.get("PFPP_ERF") or os.path.join(os.environ["TEMP"], "pfpp_nomen.erf")
assert os.path.exists(ERF), f"нет .erf: {ERF}"
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
отчет = erp.ВнешниеОтчеты.Создать(ERF)

сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
тз = отчет.ПолучитьДанные(erp.NewObject("СтандартныйПериод"), сс.Ссылка)
cols = [c.Имя for c in тз.Колонки]
assert "НоменклатураНаименование" in cols, "нет колонки НоменклатураНаименование"

пч = фч = мфг = пнф = 0.0
с_именем = 0; пример = None
for i in range(тз.Количество()):
    r = тз.Получить(i)
    имя = str(r.НоменклатураНаименование or "").strip()
    if r.Блок == "1. Труд":
        пч += f(r.ПланЧасы); фч += f(r.ФактЧасы)
        assert имя == "", "у труда имя должно быть пустым"
    if r.Блок == "2. Материалы":
        мфг += f(r.ФактГрн); пнф += f(r.ПланНаФактГрн)
    if имя:
        с_именем += 1
        assert r.Блок == "2. Материалы"
        assert not пусто(r.Аналитика) and имя == str(r.Аналитика.Наименование).strip()
        if пример is None: пример = имя
print(f"ОРІЛЬ: ПланЧасы={пч:.2f} ФактЧасы={фч:.2f} МатФактГрн={мфг:.2f} ПланНаФакт={пнф:.2f}")
print(f"строк с именем={с_именем}, пример='{пример}'")
assert abs(пч - 2795) < 0.01 and abs(фч - 2389) < 0.01
assert abs(мфг - 1620137.97) < 0.01 and abs(пнф - 625675.03) < 0.01
assert с_именем > 0, "ни одной строки с НоменклатураНаименование"

дп = отчет.КомпоновщикНастроек.Настройки.Отбор.ДоступныеПоляОтбора
поле = erp.NewObject("ПолеКомпоновкиДанных", "НоменклатураНаименование")
assert дп.НайтиПоле(поле) is not None, "поле НоменклатураНаименование недоступно в отборе"

# Композиция с дефолтными настройками — вид не сломан
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
наст = отчет.КомпоновщикНастроек.ПолучитьНастройки()
вн = erp.NewObject("Структура"); вн.Вставить("Детали", тз)
м = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст)
пр = erp.NewObject("ПроцессорКомпоновкиДанных"); пр.Инициализировать(м, вн)
д = erp.NewObject("ТабличныйДокумент")
в = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
в.УстановитьДокумент(д); в.Вывести(пр)
print(f"Композиция (дефолт): H={д.ВысотаТаблицы} W={д.ШиринаТаблицы}")
assert д.ВысотаТаблицы > 0

print("\nSMOKE PASS")
