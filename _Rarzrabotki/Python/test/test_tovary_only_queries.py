# -*- coding: utf-8 -*-
"""
RED-проверка товарных запросов обработки СинхронизироватьТоварыТолькоТовары.
Прогоняем 1:1 тексты запросов из товарной ветки ObjectModule на живых базах
BaseERP + BuhBud за январь 2026 ДО правок BSL (Rule #-1 / #5).

Запуск: python _Rarzrabotki/Python/test/test_tovary_only_queries.py
Успех: все 3 запроса -> "OK, рядків=N" без FAIL.
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
CONN_BUH = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'

# Полдень — чтобы pywintypes не сдвигал день (грабли win32com)
NP = datetime.datetime(2026, 1, 1, 12, 0, 0)
KP = datetime.datetime(2026, 1, 31, 12, 0, 0)


def err(e):
    if hasattr(e, 'excepinfo') and e.excepinfo:
        return str(e.excepinfo[2])
    return str(e)


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect(CONN_ERP)
    buh = v8.Connect(CONN_BUH)
    fails = 0

    # ---- Запрос 1: остатки ERP товаров (ТоварыНаСкладах.ОстаткиИОбороты) ----
    try:
        q = erp.NewObject("Запрос")
        q.Текст = """
        ВЫБРАТЬ
            Т.Номенклатура КАК Номенклатура,
            Т.Номенклатура.А_ИдКод КАК НоменклатураИдКод,
            Т.Склад КАК Склад,
            Т.Склад.А_ИдКод КАК СкладИдКод,
            Т.ВНаличииНачальныйОстаток КАК НачОстаток,
            Т.ВНаличииПриход КАК Приход,
            Т.ВНаличииРасход КАК Расход,
            Т.ВНаличииКонечныйОстаток КАК КонОстаток
        ИЗ
            РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты(&НачалоПериода, &КонецПериода, , , ) КАК Т
        ГДЕ
            Т.Номенклатура.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
        """
        q.УстановитьПараметр("НачалоПериода", NP)
        q.УстановитьПараметр("КонецПериода", KP)
        r = q.Выполнить().Выгрузить()
        print(f"[1] ERP ТоварыНаСкладах: OK, рядків={r.Количество()}")
    except Exception as e:
        fails += 1
        print(f"[1] ERP ТоварыНаСкладах: FAIL: {err(e)}")

    # ---- ЕДРПОУ организаций в балансе (для фильтра BuhBud) ----
    edrpou = []
    try:
        qo = erp.NewObject("Запрос")
        qo.Текст = ('ВЫБРАТЬ Организации.КодПоЕДРПОУ КАК КодПоЕДРПОУ '
                    'ИЗ Справочник.Организации КАК Организации '
                    'ГДЕ Организации.А_ВБалансе = ИСТИНА И Организации.КодПоЕДРПОУ <> ""')
        sel = qo.Выполнить().Выбрать()
        while sel.Следующий():
            edrpou.append(sel.КодПоЕДРПОУ)
        print(f"    Организаций в балансе: {len(edrpou)} ({', '.join(edrpou)})")
    except Exception as e:
        fails += 1
        print(f"    ЕДРПОУ: FAIL: {err(e)}")

    # ---- Запрос 2: остатки BuhBud (Хозрасчетный, товарные счета) ----
    try:
        mas = buh.NewObject("Массив")
        for k in edrpou:
            mas.Добавить(k)
        qb = buh.NewObject("Запрос")
        qb.Текст = """
        ВЫБРАТЬ
            ВложенныйЗапрос.НоменклатураИдКод КАК НоменклатураИдКод,
            ВложенныйЗапрос.СкладИдКод КАК СкладИдКод,
            СУММА(ВложенныйЗапрос.НачОстаток) КАК НачОстаток,
            СУММА(ВложенныйЗапрос.Приход) КАК Приход,
            СУММА(ВложенныйЗапрос.Расход) КАК Расход,
            СУММА(ВложенныйЗапрос.КонОстаток) КАК КонОстаток
        ИЗ
            (ВЫБРАТЬ
                ВЫБОР
                    КОГДА ПозицияНоменклатуры.НомерСтроки = 1 ТОГДА ВЫРАЗИТЬ(Остатки.Субконто1 КАК Справочник.Номенклатура).А_ИдКод
                    КОГДА ПозицияНоменклатуры.НомерСтроки = 2 ТОГДА ВЫРАЗИТЬ(Остатки.Субконто2 КАК Справочник.Номенклатура).А_ИдКод
                    КОГДА ПозицияНоменклатуры.НомерСтроки = 3 ТОГДА ВЫРАЗИТЬ(Остатки.Субконто3 КАК Справочник.Номенклатура).А_ИдКод
                    ИНАЧЕ ""
                КОНЕЦ КАК НоменклатураИдКод,
                ВЫБОР
                    КОГДА ПозицияСклада.НомерСтроки = 1 ТОГДА ВЫРАЗИТЬ(Остатки.Субконто1 КАК Справочник.Склады).А_ИдКод
                    КОГДА ПозицияСклада.НомерСтроки = 2 ТОГДА ВЫРАЗИТЬ(Остатки.Субконто2 КАК Справочник.Склады).А_ИдКод
                    КОГДА ПозицияСклада.НомерСтроки = 3 ТОГДА ВЫРАЗИТЬ(Остатки.Субконто3 КАК Справочник.Склады).А_ИдКод
                    ИНАЧЕ ""
                КОНЕЦ КАК СкладИдКод,
                Остатки.КоличествоНачальныйОстаток КАК НачОстаток,
                Остатки.КоличествоОборотДт КАК Приход,
                Остатки.КоличествоОборотКт КАК Расход,
                Остатки.КоличествоКонечныйОстаток КАК КонОстаток
            ИЗ
                РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(
                        &НачалоПериода, &КонецПериода, , ,
                        Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.Товары))
                            ИЛИ Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.ПроизводственныеЗапасы))
                            ИЛИ Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.ПриобретениеИзготовлениеОсновныхСредств))
                            ИЛИ Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.ПриобретениеДругихНеоборотныхМатериальныхАктивов))
                            ИЛИ Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.ГотоваяПродукция))
                            ИЛИ Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.МалоценныеИБыстроизнашивающиесяПредметы)),
                        , ) КАК Остатки
                    ЛЕВОЕ СОЕДИНЕНИЕ ПланСчетов.Хозрасчетный.ВидыСубконто КАК ПозицияНоменклатуры
                    ПО Остатки.Счет = ПозицияНоменклатуры.Ссылка
                        И (ПозицияНоменклатуры.ВидСубконто = ЗНАЧЕНИЕ(ПланВидовХарактеристик.ВидыСубконтоХозрасчетные.Номенклатура))
                    ЛЕВОЕ СОЕДИНЕНИЕ ПланСчетов.Хозрасчетный.ВидыСубконто КАК ПозицияСклада
                    ПО Остатки.Счет = ПозицияСклада.Ссылка
                        И (ПозицияСклада.ВидСубконто = ЗНАЧЕНИЕ(ПланВидовХарактеристик.ВидыСубконтоХозрасчетные.Склады))
            ГДЕ
                Остатки.Организация.КодПоЕДРПОУ В (&масКодПоЕДРПОУ)
                И (Остатки.КоличествоНачальныйОстаток <> 0
                        ИЛИ Остатки.КоличествоОборотДт <> 0
                        ИЛИ Остатки.КоличествоОборотКт <> 0)) КАК ВложенныйЗапрос
        СГРУППИРОВАТЬ ПО
            ВложенныйЗапрос.НоменклатураИдКод,
            ВложенныйЗапрос.СкладИдКод
        """
        qb.УстановитьПараметр("НачалоПериода", NP)
        qb.УстановитьПараметр("КонецПериода", KP)
        qb.УстановитьПараметр("масКодПоЕДРПОУ", mas)
        rb = qb.Выполнить().Выгрузить()
        print(f"[2] BuhBud Хозрасчетный (товары): OK, рядків={rb.Количество()}")
    except Exception as e:
        fails += 1
        print(f"[2] BuhBud Хозрасчетный (товары): FAIL: {err(e)}")

    # ---- Запрос 3: обороты по документам ERP + Соответствия ----
    try:
        q3 = erp.NewObject("Запрос")
        q3.Текст = """
        ВЫБРАТЬ
            Об.Регистратор КАК Регистратор,
            ПРЕДСТАВЛЕНИЕ(Об.Регистратор) КАК РегистраторПредст,
            Об.ВНаличииПриход КАК Приход,
            Об.ВНаличииРасход КАК Расход,
            Соотв.УникальныйИдентификаторПриемника КАК UIDвBuhBud,
            Соотв.ТипПриемника КАК ТипПриемника
        ИЗ
            РегистрНакопления.ТоварыНаСкладах.Обороты(&НачалоПериода, &КонецПериода, Авто, ) КАК Об
            ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
            ПО Об.Регистратор = Соотв.УникальныйИдентификаторИсточника
                И (Соотв.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20)
        """
        q3.УстановитьПараметр("НачалоПериода", NP)
        q3.УстановитьПараметр("КонецПериода", KP)
        r3 = q3.Выполнить().Выгрузить()
        print(f"[3] ERP ТоварыНаСкладах.Обороты + Соответствия: OK, рядків={r3.Количество()}")
    except Exception as e:
        fails += 1
        print(f"[3] ERP Обороты + Соответствия: FAIL: {err(e)}")

    print(f"\n=== ИТОГ: {'ALL GREEN' if fails == 0 else str(fails) + ' FAIL'} ===")
    return fails


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
