# -*- coding: utf-8 -*-
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Счёт 6853
q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Сч.Ссылка КАК Ссылка ИЗ ПланСчетов.Хозрасчетный КАК Сч ГДЕ Сч.Код = "6853" """
счет = q.Execute().Выгрузить().Получить(0).Ссылка

# Регистраторы, которые двигают 6853 по Кт (начисление долга/удержание)
q1 = erp.NewObject("Запрос")
q1.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    Дв.Регистратор КАК Рег,
    ТИПЗНАЧЕНИЯ(Дв.Регистратор) КАК ТипРег
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Дв
ГДЕ Дв.СчетКт = &Счет
"""
q1.SetParameter("Счет", счет)
r1 = q1.Execute().Выгрузить()
print(f"Регистраторы Кт6853: рядкiв={r1.Количество()}")
regs = erp.NewObject("Массив")
typecount = {}
for i in range(r1.Количество()):
    s=r1.Получить(i)
    regs.Добавить(s.Рег)
    tn = s.Рег.Метаданные().Имя
    typecount[tn] = typecount.get(tn,0)+1
print("  типы регистраторов:", typecount)

# Какие движения ПАП делают эти регистраторы (Статья, Аналитика, знак, Источник)
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    ПАП.ВидДвижения КАК ВидДвижения,
    ПАП.Статья КАК Статья,
    ПАП.Статья.Наименование КАК СтатьяНаим,
    ПАП.Аналитика КАК Аналитика,
    ПАП.Подразделение КАК Подразделение,
    ПАП.Организация КАК Организация,
    ПАП.ВидИсточника КАК ВидИсточника,
    ПАП.Источник КАК Источник,
    ТИПЗНАЧЕНИЯ(ПАП.Регистратор) КАК ТипРег,
    СУММА(ПАП.Сумма) КАК Сумма,
    КОЛИЧЕСТВО(*) КАК Зап
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Регистратор В (&Регистраторы)
СГРУППИРОВАТЬ ПО
    ПАП.ВидДвижения, ПАП.Статья, ПАП.Статья.Наименование, ПАП.Аналитика,
    ПАП.Подразделение, ПАП.Организация, ПАП.ВидИсточника, ПАП.Источник,
    ТИПЗНАЧЕНИЯ(ПАП.Регистратор)
"""
q2.SetParameter("Регистраторы", regs)
try:
    r2 = q2.Execute().Выгрузить()
    print(f"\nДвижения ПАП регистраторов Кт6853: рядкiв={r2.Количество()}")
    for i in range(r2.Количество()):
        s=r2.Получить(i)
        vd = erp.XMLСтрока(s.ВидДвижения)
        anlt = ""
        if erp.ЗначениеЗаполнено(s.Аналитика):
            anlt = f"{s.Аналитика.Метаданные().Имя}:{s.Аналитика}"
        else:
            anlt = "ПУСТО"
        ист=""
        if erp.ЗначениеЗаполнено(s.Источник):
            ист=f"{s.Источник.Метаданные().Имя}:{s.Источник}"
        else:
            ист="ПУСТО"
        vi=""
        if erp.ЗначениеЗаполнено(s.ВидИсточника):
            vi=str(s.ВидИсточника)
        else:
            vi="ПУСТО"
        print(f"  [{vd}] Статья={s.СтатьяНаим} | Аналитика={anlt}")
        print(f"        Подр={s.Подразделение} Орг={s.Организация} | ВидИст={vi} Ист={ист}")
        print(f"        ТипРег={s.ТипРег} Сумма={s.Сумма} зап={s.Зап}")
except Exception as e:
    if hasattr(e,'excepinfo') and e.excepinfo:
        print("FAIL:", e.excepinfo[2])
    else:
        print("FAIL:", e)
