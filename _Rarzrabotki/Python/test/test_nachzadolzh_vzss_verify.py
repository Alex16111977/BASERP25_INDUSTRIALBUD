"""Verify: перепровести НачальнаяЗадолженность через COM, сверить А_ВзСС с ТЧ per ключ
+ идемпотентность + период (= НачалоМесяца(Месяц), НЕ Дата)."""
import sys, win32com.client
if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
XML = erp.XMLСтрока

def ключ(фл, подр, форма, оргб):
    return (фл, подр, форма, оргб)

# Ожидаемое из ТЧ (signed per ключ)
def ожидаемое(ref):
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ З.Сотрудник.ФизическоеЛицо.Наименование КАК ФЛ, З.Подразделение.А_Подразделение.Наименование КАК Подр,
        ВЫБОР КОГДА З.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.ПустаяСсылка)
            ТОГДА ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ИНАЧЕ З.ФормаPL КОНЕЦ КАК ФормаPL,
        ПРЕДСТАВЛЕНИЕ(З.ОрганизацияБухгалтерия) КАК ОргБух, З.Сумма КАК Сумма
    ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате КАК З ГДЕ З.Ссылка = &С"""
    q.SetParameter("С", ref)
    d = {}
    вб = q.Execute().Выбрать()
    while вб.Следующий():
        k = ключ(вб.ФЛ, вб.Подр, XML(вб.ФормаPL), вб.ОргБух)
        d[k] = d.get(k, 0.0) + float(вб.Сумма)
    return {k: round(v, 2) for k, v in d.items() if abs(v) > 0.005}

# Фактическое из А_ВзСС (signed per ключ)
def фактическое(ref):
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ Р.ФизическоеЛицо.Наименование КАК ФЛ, Р.Подразделение.Наименование КАК Подр,
        Р.ФормаPL КАК ФормаPL, ПРЕДСТАВЛЕНИЕ(Р.ОрганизацияБухгалтерия) КАК ОргБух,
        Р.ВидДвижения КАК ВД, Р.СуммаВзаиморасчетов КАК Сумма
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р ГДЕ Р.Регистратор = &С"""
    q.SetParameter("С", ref)
    d = {}
    вб = q.Execute().Выбрать()
    while вб.Следующий():
        знак = 1 if XML(вб.ВД) == "Receipt" else -1   # Receipt=Приход
        k = ключ(вб.ФЛ, вб.Подр, XML(вб.ФормаPL), вб.ОргБух)
        d[k] = d.get(k, 0.0) + знак * float(вб.Сумма)
    return {k: round(v, 2) for k, v in d.items() if abs(v) > 0.005}

# Период движений (множество НачалоМесяца) — должно быть ровно {НМ(Месяц)}
def периоды(ref):
    q = erp.NewObject("Запрос")
    q.Text = """ВЫБРАТЬ РАЗЛИЧНЫЕ НАЧАЛОПЕРИОДА(Р.Период, МЕСЯЦ) КАК П
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р ГДЕ Р.Регистратор = &С"""
    q.SetParameter("С", ref)
    s = set()
    вб = q.Execute().Выбрать()
    while вб.Следующий():
        s.add(XML(вб.П)[:7])
    return s

q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.НачальнаяЗадолженностьПоЗарплате ГДЕ Проведен"
вб = q.Execute().Выбрать(); assert вб.Следующий(), "Проведённый документ не найден"
ref = вб.С

obj = ref.ПолучитьОбъект()
obj.Записать(erp.РежимЗаписиДокумента.Проведение)
ож = ожидаемое(ref); фк = фактическое(ref)
