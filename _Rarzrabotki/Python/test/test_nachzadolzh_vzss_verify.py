print("OK #2: идемпотентность (2-й перепровод идентичен)")

# #6: типовые движения документа НЕ сломаны + период согласован с нашим регистром
def колвоПериод(регистр):
    q = erp.NewObject("Запрос")
    q.Text = (f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К, МИНИМУМ(Р.Период) КАК П "
              f"ИЗ РегистрНакопления.{регистр} КАК Р ГДЕ Р.Регистратор = &С")
    q.SetParameter("С", ref)
    в = q.Execute().Выбрать(); в.Следующий()
    return (в.К or 0, XML(в.П)[:7] if в.К else "—")

