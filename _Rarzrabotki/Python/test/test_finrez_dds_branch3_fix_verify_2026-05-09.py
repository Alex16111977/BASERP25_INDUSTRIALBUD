def fmt(v, w=20):
    if v is None:
        return " " * w
    if isinstance(v, (int, float)):
        return f"{v:>{w},.2f}".replace(",", " ")
    s = str(v)
    return s[: w - 1].ljust(w) if len(s) > w else s.ljust(w)


