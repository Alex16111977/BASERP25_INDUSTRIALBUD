# ════════════════════════════════════════════ профили оплат
def профили_оплат(д, н):
    """Ритм денег из факта: IRC (FIFO отгрузка → оплата), УВБК ООН (20 % после поставки, 50 % после приёмки),
    материалы (за 1 мес. до отгрузки), ЗП (ядро по EV-часам), комиссия ФА и услуги банка (доля от наличных расходов)."""
    пф = {}
    # IRC: FIFO по домам IRC 15 м (отгружены 6 в августе)
    отгр = sorted(x for x in д["shipped"]["МД IRC 2026"] if x < "2026-09-01")
    plat = sorted((r["date"], r["sum"]) for r in REC if r["projname"] == "МД IRC 2026" and r["art"] == "УТ-001146")
    цена15 = CARDS["000000008"]["price"]
    события = []
    for дата, сумма in plat:
        события += [дата] * int(round(сумма / цена15))
    пары = list(zip(отгр, события))
    def дни(a, b):
        return (datetime.date.fromisoformat(b) - datetime.date.fromisoformat(a)).days
    лаги = [дни(a, b) for a, b in пары]
    тот_же = sum(1 for a, b in пары if a[:7] == b[:7]) / len(пары)
    пф["irc"] = {"same": тот_же, "next": 1 - тот_же, "lags": лаги, "mean": sum(лаги) / len(лаги), "n": len(пары)}
    # УВБК ООН: 20 % через 12 дней после поставки (ООН Админ №1: 17.09 → 29.09)
    отгр_адм = д["shipped"]["МД ООН Админ"][0]
    доп = {(d, round(s, 2)) for d, s, _ in ДОП_ЗАКАЗЫ["МД ООН Админ"]}
    плат_адм = [r for r in REC if r["projname"] == "МД ООН Админ" and r["art"] == "УТ-001146" and r["date"] > отгр_адм
                and (r["date"], round(r["sum"], 2)) not in доп]
    лаг20 = дни(отгр_адм, плат_адм[0]["date"])
    доля20 = плат_адм[0]["sum"] / CARDS["000000011"]["price"]
    пф["un"] = {"p20": round(доля20, 4), "lag20_days": лаг20, "same20": max(0.0, 1 - лаг20 / 30), "p50": 0.5, "lag50": 2,
                "adv": 0.3}
    # финагент: комиссия и услуги банка — доля от наличных расходов (факт 01–09.2026, без транзита и финансирования)
    искл = ТРАНЗИТ | ФИНАНСИРОВАНИЕ | ФИН_ПОМОЩЬ | ВНУТР | {"УТ-001097", "УТ-001063"}  # ВНУТР: дубль ЗП Ф2 не база
    нал, ком, банк = 0.0, 0.0, 0.0
    for r in FAKT["rows"]:
        if not ("2026-01" <= r["month"] <= "2026-09"):
            continue
        if r["art"] == "УТ-001097":
            ком += -r["sum"]
        elif r["art"] == "УТ-001063" and r["type"] == НАЛ:
            банк += -r["sum"]
        elif r["type"] == НАЛ and r["sum"] < 0 and r["art"] not in искл and r["art"]:
            нал += -r["sum"]
    пф["fa"] = {"cash": нал, "commission": ком, "rate": ком / нал, "bank": банк, "bank_rate": банк / нал}
    пф["mat_lead"] = 1
    пф["labor_kernel"] = {-1: 0.45, 0: 0.55}
    return пф


