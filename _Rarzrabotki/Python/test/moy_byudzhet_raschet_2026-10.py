        r = t.Получить(i)
        k = (uid(r.Подр), ym(r.Мес), S(r.Код).strip(), S(r.Вид))
        факт_[k] += float(r.Сумма)
        текст = S(r.Расш)
        if not текст.strip():
            без_расш += 1
            continue
        m_ = re.findall(r"= ([\d  ]+,\d\d)\s*$", текст.strip())
        if not m_ or abs(float(m_[-1].replace(" ", "").replace(" ", "").replace(",", ".")) - float(r.Сумма)) > 0.005:
            не_сходится += 1
