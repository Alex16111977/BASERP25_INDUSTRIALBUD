            нем = len(части)
            hdr = (f"Матеріали: буд. {дома_txt} ({нем} шт., відвантаження — {', '.join(sorted({мес(ship(h)) for h, _ in части}))}, графік {гр})"
                   f" × норма {ч(нр['bom'])} — оплата за {пф['mat_lead']} міс. до відвантаження")
