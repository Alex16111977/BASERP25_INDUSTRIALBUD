                        б.add(проект, ПЕРВЫЙ, "УТ-001075", НАЛ, объект, РАСЧЕТ,
                              f"ЗП (Ф2) доробки на об'єкті буд. {h['id']} (відвантажено у вересні): "
                              f"{h['plan_h'] - max(h['thr'], h['done_h']):.0f} год × {ч(ставка)} грн/год (СС {h['card']}: {ч(нр['labor'])} / {h['plan_h']:.0f} год)")
