    д["houses"]["МД ООН Админ"] = подомово("МД ООН Админ", "000000011", д["thr_adm"], темп_адм, план_проекта("ООН АДМИН"))
    # ООН 2026 — без ВРМ: 10 домов, темп 2 / 3 / 3, остаток — январь 2027
    план_оон = план_проекта("ООН 2026")
    реал_оон = {"2026-10": 2, "2026-11": 3, "2026-12": 3, "2027-01": 2}
    hh, i = [], 0
    for м, n in sorted(реал_оон.items()):
        for _ in range(n):
            i += 1
            hh.append({"id": f"№{i}", "card": "000000010", "plan_h": 0, "done_h": 0, "thr": 0, "shipped": False,
                       "ship_real": м})
    k = 0
    for м in sorted(план_оон):
        for _ in range(int(план_оон[м])):
            if k < len(hh):
                hh[k]["ship_plan"] = м
                k += 1
    д["houses"]["МД ООН 2026"] = hh
    д["houses"]["МХП санітарний вузол"] = [{"id": "№1", "card": "", "plan_h": 0, "done_h": 0, "thr": 0, "shipped": False,
                                           "ship_real": "2026-11", "ship_plan": "2026-11"}]
    # МК — тонны (план = реалистичный: октябрь ≤ лучшего месяца цеха 64,7 т в июле)
    def тонны(ключ):
        out = collections.defaultdict(float)
        for x in PLAN["mk"]:
            if x["item"].lower().startswith(ключ.lower()):
                for м, v in x["months"].items():
                    if "plan" in v and м >= ПЕРВЫЙ:
                        out[м] += v["plan"]
        return dict(out)

    def тонны_факт(ключ, м):
        return sum(v["months"].get(м, {}).get("fact", 0.0) for v in PLAN["mk"] if v["item"].lower().startswith(ключ.lower()))
