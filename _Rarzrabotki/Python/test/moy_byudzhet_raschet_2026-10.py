def сверки(строки, сц):
    """6.4: документы = расчёт до копейки; регистр = расчёт по месяцам; расшифровка у каждой строки = сумма строки;
    отчёт ОИБ и режим сравнения отчёта PL строятся со сценарием; перепроведение не меняет регистр."""
    import re
    ошибки = []
    ожид = collections.defaultdict(float)
    for r in строки:
        ожид[(ПРОЕКТ[r["proj"]], r["month"], r["art"], r["vid"])] += r["sum"]
    t = query("""ВЫБРАТЬ Д.Подразделение КАК Подр, Т.Месяц КАК Мес, Т.СтатьяДДС.Код КАК Код, Т.ВидОплаты КАК Вид, Т.Сумма КАК Сумма,
        Т.Расшифровка КАК Расш
        ИЗ Документ.А_ПредварительныйБюджет.ПоказателиБДДС КАК Т ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ПредварительныйБюджет КАК Д ПО Т.Ссылка = Д.Ссылка
        ГДЕ Д.Сценарий = &Сц И НЕ Д.ПометкаУдаления""", Сц=сц)
    факт_ = collections.defaultdict(float)
    без_расш, не_сходится = 0, 0
    for i in range(t.Количество()):
        r = t.Получить(i)
        k = (uid(r.Подр), ym(r.Мес), S(r.Код).strip(), S(r.Вид))
        факт_[k] += float(r.Сумма)
        текст = S(r.Расш)
        if not текст.strip():
            без_расш += 1
            continue
        m_ = re.findall(r"= ([\d  ]+,\d\d)\s*$", текст.strip())
        if not m_ or abs(float(m_[-1].replace(" ", "").replace(" ", "").replace(",", ".")) - float(r.Сумма)) > 0.005:
            не_сходится += 1
    for k in set(ожид) | set(факт_):
        if abs(ожид.get(k, 0) - факт_.get(k, 0)) > 0.005:
            ошибки.append(f"ТЧ ≠ расчёт: {k} {ожид.get(k, 0)} / {факт_.get(k, 0)}")
    print(f"1. документы = расчёт по (проект, месяц, статья, вид): {'OK' if not ошибки else 'РАСХОЖДЕНИЯ ' + str(len(ошибки))}")
    print(f"3. строк без расшифровки: {без_расш}; расшифровка ≠ сумма строки: {не_сходится}")
    if без_расш or не_сходится:
        ошибки.append("расшифровка")
    t = query("""ВЫБРАТЬ Рег.Месяц КАК Мес, СУММА(Рег.Сумма) КАК Сум ИЗ РегистрНакопления.А_ПредварительныйБюджетНаМесяц КАК Рег
        ГДЕ Рег.Сценарий = &Сц СГРУППИРОВАТЬ ПО Рег.Месяц""", Сц=сц)
    рег = {ym(t.Получить(i).Мес): float(t.Получить(i).Сум) for i in range(t.Количество())}
    расч = collections.defaultdict(float)
    for r in строки:
        расч[r["month"]] += r["sum"]
    for м in МЕСЯЦЫ:
        ok = abs(рег.get(м, 0) - расч[м]) < 0.005
        print(f"2. регистр {м}: {ч(рег.get(м, 0))} / расчёт {ч(расч[м])} {'OK' if ok else 'FAIL'}")
        if not ok:
            ошибки.append(f"регистр {м}")
    # перепроведение одного своего документа не меняет движения (реквизит Расшифровка на проведение не влияет)
    t = query("ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК С ИЗ Документ.А_ПредварительныйБюджет КАК Д ГДЕ Д.Сценарий = &Сц И Д.Проведен", Сц=сц)
    док = t.Получить(0).С
    def движения():
        tt = query("""ВЫБРАТЬ Рег.СтатьяДвиженияДенежныхСредств.Код КАК Код, Рег.ВидОплаты КАК Вид, Рег.Месяц КАК Мес, Рег.Сумма КАК Сум
            ИЗ РегистрНакопления.А_ПредварительныйБюджетНаМесяц КАК Рег ГДЕ Рег.Регистратор = &Док""", Док=док)
        return sorted((S(tt.Получить(i).Код), S(tt.Получить(i).Вид), ym(tt.Получить(i).Мес), float(tt.Получить(i).Сум)) for i in range(tt.Количество()))
    до = движения()
    док.ПолучитьОбъект().Записать(conn().РежимЗаписиДокумента.Проведение)
    после = движения()
    print(f"   перепроведение {S(док)}: движений {len(до)} -> {len(после)}, {'совпадают' if до == после else 'ИЗМЕНИЛИСЬ'}")
    if до != после:
        ошибки.append("перепроведение")
    # документ 00008 открывается (новый реквизит не ломает чтение)
    t = query("ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК С ИЗ Документ.А_ПредварительныйБюджет КАК Д ГДЕ Д.Сценарий.Код = \"00008\" И Д.Проведен")
    о8 = t.Получить(0).С.ПолучитьОбъект()
    print(f"   документ 00008 {S(о8.Ссылка)} открыт: строк ТЧ {о8.ПоказателиБДДС.Количество()}")
    # 4. отчёты
    erp = conn()
    root = query("ВЫБРАТЬ П.Ссылка КАК С ИЗ Справочник.СтруктураПредприятия КАК П ГДЕ П.Код = &К", К=ROOT_CODE).Получить(0).С
    pl4 = query('ВЫБРАТЬ С.Ссылка КАК С ИЗ Справочник.Сценарии КАК С ГДЕ С.Код = "00004"').Получить(0).С
    try:
        оиб = erp.ВнешниеОтчеты.Создать(r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетДеньгиКазна_Бюджет_PL_ПредварительныйPL.erf", False)
        тз = оиб.ПолучитьДанные(root, dt(2026, 1, 1), dt(2026, 12, 31, 23, 59, 59), dt(2026, 9, 30), dt(2026, 8, 31), сц, pl4)
        прогноз = sum(float(тз.Получить(i).Прогноз or 0) for i in range(тз.Количество())) if тз.Колонки.Найти("Прогноз") is not None else None
        print(f"4. отчёт ОИБ со сценарием «мой расчет»: строк {тз.Количество()} — OK" + (f", прогноз {ч(прогноз)}" if прогноз is not None else ""))
    except Exception as e:
        ошибки.append(f"ОИБ: {getattr(e, 'excepinfo', [None, None, e])[2]}")
        print("4. отчёт ОИБ: FAIL", ошибки[-1])
    try:
        отчет = erp.Отчеты.А_ОтчетPL_ПолныйЕРП_СПредварительнымРасчетомPL.Создать()
        тз = отчет.ДанныеСравнения(dt(2026, 10, 1), dt(2026, 12, 31, 23, 59, 59), False, pl4, сц, True)
        print(f"   режим сравнения отчёта PL со сценарием «мой расчет»: строк {тз.Количество()} — OK")
    except Exception as e:
        ошибки.append(f"PL сравнение: {getattr(e, 'excepinfo', [None, None, e])[2]}")
        print("   режим сравнения PL: FAIL", ошибки[-1])
    return ошибки


