def факт(проект, коды=None, с="2025-01", по="2026-09", вид=None):
    """Сумма факта Казны (со знаком) по проекту и статьям за месяцы [с, по]."""
    s = 0.0
    for r in FAKT["rows"]:
        if r["projname"] == проект and с <= r["month"] <= по and (коды is None or r["art"] in коды) \
                and (вид is None or r["type"] == вид):
            s += r["sum"]
    return s


