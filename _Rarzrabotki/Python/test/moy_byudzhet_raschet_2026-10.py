def сдвиг(м, k):
    y, mm = int(м[:4]), int(м[5:]) + k
    while mm > 12:
        y, mm = y + 1, mm - 12
    while mm < 1:
        y, mm = y - 1, mm + 12
    return f"{y:04d}-{mm:02d}"


