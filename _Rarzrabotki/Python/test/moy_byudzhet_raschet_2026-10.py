            профиль_txt = (f"IRC платить 100 % ціни будинку без авансу; профіль — FIFO 6 буд. IRC 15 м (серпень): {пр(пф_['same'])} у місяці "
                           f"відвантаження, решта — наступного, лаг 15–43 дні, у середньому {пф_['mean']:.0f}; графік {гр}")
