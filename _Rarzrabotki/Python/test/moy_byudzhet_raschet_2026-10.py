# ════════════════════════════════════════════ расшифровка
def расшифровка(б):
    """Строки бюджета = (проект, месяц, статья, вид оплаты, источник); текст — части через «; » и итог."""
    гр = collections.OrderedDict()
    for x in б.lines:
        k = (x["proj"], x["month"], x["art"], x["vid"], x["src"])
        гр.setdefault(k, []).append(x)
    out = []
    for (проект, м, ст, вид, ист), части in гр.items():
        сумма = окр(sum(x["sum"] for x in части))
        основы = list(dict.fromkeys(x["basis"] for x in части if x["basis"]))
        if len(части) == 1:
            текст = части[0]["text"]
        else:
            текст = "; ".join(x["text"] for x in части) + f"; разом = {ч(сумма)}"
        if основы:
            текст = "Підстава: " + "; ".join(основы) + ". " + текст
        out.append({"proj": проект, "month": м, "art": ст, "artname": ART[ст]["name"], "dir": ART[ст]["type"], "vid": вид,
                    "src": ист, "sum": сумма, "text": текст})
    return out


def итоги(строки, ключ=lambda r: (r["proj"], r["month"])):
    t = collections.defaultdict(lambda: [0.0, 0.0])
    for r in строки:
        t[ключ(r)][0 if r["dir"] == "Приход" else 1] += r["sum"]
    return t


