class Бюджет:
    def __init__(self, сценарий):
        self.сц = сценарий
        self.lines = []
        self.outside = collections.defaultdict(float)  # (проект, статья) -> сумма за горизонтом (январь 2027+)
        self.diag = []

    def add(self, проект, м, ст, вид, сумма, источник, текст, основа=""):
        сумма = окр(сумма)
        if abs(сумма) < 0.005:
            return
        if м < ПЕРВЫЙ:
            м = ПЕРВЫЙ
        if м > ПОСЛЕДНИЙ:
            self.outside[(проект, ст)] += сумма
            return
        assert ст in ART, f"нет статьи {ст}"
        self.lines.append({"proj": проект, "month": м, "art": ст, "vid": вид, "sum": сумма, "src": источник,
                           "text": f"{текст} = {ч(сумма)}", "basis": основа})


