"""Rule #-1: запрос заполнения по направлению + фильтр направления в оборотах —
проверяются на живой базе ДО загрузки модуля."""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')


def дата(г, м, д, ч=0, мин=0, с=0):
    q = buh.NewObject("Запрос")
    q.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({г},{м},{д},{ч},{мин},{с}) КАК Д"
    return q.Execute().Выгрузить().Получить(0).Д


def массив(значения):
    m = buh.NewObject("Массив")
    for з in значения:
        m.Добавить(з)
    return m


НАПР = buh.Справочники.Направления.НайтиПоНаименованию("Производство", True)
СЧЕТА = массив([buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("361")])
НАЧАЛО = дата(1, 1, 1)
КОНЕЦ = дата(2026, 8, 7, 23, 59, 59)

ЗАПОЛНЕНИЕ = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	Д.Подразделение КАК Подразделение
ПОМЕСТИТЬ ВТПодразделенияНаправления
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	Д.Направление = &Направление
	И НЕ Д.ПометкаУдаления
	И Д.Подразделение <> ЗНАЧЕНИЕ(Справочник.Подразделения.ПустаяСсылка)
	И НЕ Д.Подразделение.ПометкаУдаления
;

////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ РАЗЛИЧНЫЕ
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение КАК Подразделение
ПОМЕСТИТЬ ВТСДвижениями
ИЗ
	РегистрБухгалтерии.Хозрасчетный.Обороты(&НачалоПериода, &ДатаРасчета, ,
		Счет В (&Счета), , , , ) КАК Об
ГДЕ
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Направление = &Направление

ОБЪЕДИНИТЬ

ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ДоговорКонтрагента.Подразделение
ИЗ Документ.РеализацияТоваровУслуг КАК Р
ГДЕ НЕ Р.Проведен И НЕ Р.ПометкаУдаления И Р.Дата <= &ДатаРасчета
	И Р.ДоговорКонтрагента.Направление = &Направление

ОБЪЕДИНИТЬ

ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ДоговорКонтрагента.Подразделение
ИЗ Документ.РеализацияУслугПоПереработке КАК Р
ГДЕ НЕ Р.Проведен И НЕ Р.ПометкаУдаления И Р.Дата <= &ДатаРасчета
	И Р.ДоговорКонтрагента.Направление = &Направление

ОБЪЕДИНИТЬ

ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ДоговорКонтрагента.Подразделение
ИЗ Документ.АктОбОказанииПроизводственныхУслуг КАК Р
ГДЕ НЕ Р.Проведен И НЕ Р.ПометкаУдаления И Р.Дата <= &ДатаРасчета
	И Р.ДоговорКонтрагента.Направление = &Направление

ОБЪЕДИНИТЬ

ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ДоговорКонтрагента.Подразделение
ИЗ Документ.ИмпРеализацияСтроительныхРаботУслуг КАК Р
ГДЕ НЕ Р.Проведен И НЕ Р.ПометкаУдаления И Р.Дата <= &ДатаРасчета
	И Р.ДоговорКонтрагента.Направление = &Направление
;

////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ
	П.Подразделение КАК Подразделение,
	П.Подразделение.Наименование КАК Наименование,
	ВЫБОР КОГДА Д.Подразделение ЕСТЬ NULL ТОГДА ЛОЖЬ ИНАЧЕ ИСТИНА КОНЕЦ КАК ЕстьДвижения
ИЗ
	ВТПодразделенияНаправления КАК П
		ЛЕВОЕ СОЕДИНЕНИЕ ВТСДвижениями КАК Д
		ПО Д.Подразделение = П.Подразделение

УПОРЯДОЧИТЬ ПО
	Наименование
"""

print("=== 1. Запит заповнення підрозділів за напрямком «Производство» ===")
q = buh.NewObject("Запрос")
q.Текст = ЗАПОЛНЕНИЕ
q.УстановитьПараметр("Направление", НАПР)
q.УстановитьПараметр("НачалоПериода", НАЧАЛО)
q.УстановитьПараметр("ДатаРасчета", КОНЕЦ)
q.УстановитьПараметр("Счета", СЧЕТА)
try:
    т = q.Execute().Выгрузить()
except Exception as e:
    print("  FAIL:", e.excepinfo[2] if getattr(e, "excepinfo", None) else e)
    sys.exit(1)

с_движ = [str(т.Получить(i).Наименование) for i in range(т.Количество()) if т.Получить(i).ЕстьДвижения]
без_движ = т.Количество() - len(с_движ)
print(f"  OK  усього підрозділів напрямку: {т.Количество()}, з рухом: {len(с_движ)}, без руху: {без_движ}")
for имя in с_движ:
    print("      ", имя)

# 2. Фильтр направления в оборотах: «Главный офис» имеет договоры двух направлений
ОБОРОТЫ = """
ВЫБРАТЬ
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение.Наименование КАК Подр,
	СУММА(Об.СуммаОборотДт) КАК Дт
ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(&НачалоПериода, &ДатаРасчета, Регистратор,
	Счет В (&Счета), , , , ) КАК Об
ГДЕ
	(ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение В (&Подразделения)
		ИЛИ Об.Субконто2 В (&Договоры))
	И (&БезФильтраНаправления
		ИЛИ ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Направление = &Направление)
СГРУППИРОВАТЬ ПО
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение.Наименование
"""
го = buh.Справочники.Подразделения.НайтиПоНаименованию("Главный офис", True)
print("\n=== 2. Фільтр напрямку в оборотах (перевірка на «Главный офис») ===")
for метка, без_фильтра in (("БЕЗ фільтра напрямку", True), ("З фільтром «Производство»", False)):
    q2 = buh.NewObject("Запрос")
    q2.Текст = ОБОРОТЫ
    q2.УстановитьПараметр("НачалоПериода", НАЧАЛО)
    q2.УстановитьПараметр("ДатаРасчета", КОНЕЦ)
    q2.УстановитьПараметр("Счета", СЧЕТА)
    q2.УстановитьПараметр("Подразделения", массив([го]))
    q2.УстановитьПараметр("Договоры", массив([]))
    q2.УстановитьПараметр("Направление", НАПР)
    q2.УстановитьПараметр("БезФильтраНаправления", без_фильтра)
    т2 = q2.Execute().Выгрузить()
    итог = sum(float(т2.Получить(i).Дт or 0) for i in range(т2.Количество()))
    print(f"  {метка:28} ОборотДт = {итог:>16,.2f}")

# 3. Эталоны не должны сдвинуться: у трёх контрольных подразделений всё «Производство»
print("\n=== 3. Еталонні підрозділи під фільтром напрямку ===")
for имя, эталон in (("МК Кривий ріг", 6195391.00), ("МД МХП ОРІЛЬ", 3355204.73)):
    подр = buh.Справочники.Подразделения.НайтиПоНаименованию(имя, True)
    q3 = buh.NewObject("Запрос")
    q3.Текст = ОБОРОТЫ
    q3.УстановитьПараметр("НачалоПериода", НАЧАЛО)
    q3.УстановитьПараметр("ДатаРасчета", КОНЕЦ)
    q3.УстановитьПараметр("Счета", СЧЕТА)
    q3.УстановитьПараметр("Подразделения", массив([подр]))
    q3.УстановитьПараметр("Договоры", массив([]))
    q3.УстановитьПараметр("Направление", НАПР)
    q3.УстановитьПараметр("БезФильтраНаправления", False)
    т3 = q3.Execute().Выгрузить()
    итог = sum(float(т3.Получить(i).Дт or 0) for i in range(т3.Количество()))
    статус = "✓" if abs(итог - эталон) < 0.01 else "✗"
    print(f"  {статус} {имя:16} ОборотДт = {итог:>15,.2f}  (еталон {эталон:,.2f})")

print("\nусі запити валідні")
