# -*- coding: utf-8 -*-
"""Rule #-1: запрос автоподбора ДокументСравнения (последний документ того же
направления с меньшей ДатаРасчета). Только чтение."""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

направление = buh.Справочники.Направления.НайтиПоНаименованию("Производство", True)

# Найдём документ № 2 (14.08) — для него должен подобраться № 1 (07.08)
q0 = buh.NewObject("Запрос")
q0.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С, Д.Номер КАК Номер, Д.ДатаРасчета КАК ДР "
            "ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д "
            "ГДЕ НЕ Д.ПометкаУдаления УПОРЯДОЧИТЬ ПО Д.ДатаРасчета УБЫВ")
т0 = q0.Execute().Выгрузить()
print(f"Всего документов: {т0.Количество()}")
for i in range(т0.Количество()):
    s = т0.Получить(i)
    print(f"  № {s.Номер}  ДатаРасчета={s.ДР}")

текущий = т0.Получить(0).С  # № 2

q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1
	Д.Ссылка КАК ДокументПрошлый
ИЗ
	Документ.А_ФинансовыйОтчетПроизводства КАК Д
ГДЕ
	НЕ Д.ПометкаУдаления
	И Д.Направление = &Направление
	И Д.ДатаРасчета < &ДатаРасчета
	И Д.Ссылка <> &ТекущийДокумент

УПОРЯДОЧИТЬ ПО
	Д.ДатаРасчета УБЫВ
"""
q.УстановитьПараметр("Направление", направление)
q.УстановитьПараметр("ДатаРасчета", текущий.ДатаРасчета)
q.УстановитьПараметр("ТекущийДокумент", текущий)
try:
    т = q.Execute().Выгрузить()
    print(f"\nOK, рядків={т.Количество()}")
    if т.Количество():
        найденный = т.Получить(0).ДокументПрошлый
        print(f"Подобран: № {найденный.Номер} от {найденный.ДатаРасчета} "
              f"(ожидался № 00000000001 от 07.08)")
except Exception as e:
    if hasattr(e, "excepinfo") and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")
