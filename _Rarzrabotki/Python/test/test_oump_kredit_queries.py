# -*- coding: utf-8 -*-
"""ОУМП, кредитные договоры: запросы модуля 1:1 (Rule #-1) — подбор договора и контрагента кредитора.

16.10.2026: ключ поиска договора дополнен получателем (`А_ПодразделениеОказаниеУслугПодразделению`) —
у Воронцова договор тела на каждую пару «ЦО → заёмщик», у заёмщиков, %% и НП получатель пуст.
"""
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ok = True


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


def run(text, **p):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in p.items():
        q.SetParameter(k, v)
    return q.Execute().Выгрузить()


ЗАПРОС_ДОГОВОРА = """ВЫБРАТЬ
	Дог.Ссылка КАК Договор
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Дог
ГДЕ
	Дог.Контрагент = &Контрагент
	И Дог.Организация = &Организация
	И Дог.Подразделение = &Подразделение
	И Дог.А_ВидКредитногоДоговора = &ВидДоговора
	И Дог.ТипДоговора = &ТипДоговора
	И Дог.А_ПодразделениеОказаниеУслугПодразделению = &ПодразделениеПолучатель
	И НЕ Дог.ПометкаУдаления

УПОРЯДОЧИТЬ ПО
	Дог.Дата,
	Дог.Наименование"""

Контр = erp.Справочники.Контрагенты.НайтиПоНаименованию("Воронцов Олександр Володимирович", True)
Орг = erp.Справочники.Организации.НайтиПоНаименованию('ТОВ "ІНДАСТРІАЛБУД"', True)
СП = erp.Справочники.СтруктураПредприятия
Стр = СП.НайтиПоНаименованию("Строительство", True)
Глоб = СП.НайтиПоНаименованию("Глобино-2", True)
МДIRC = СП.НайтиПоНаименованию("МД IRC 2026", True)
В = erp.Перечисления.А_ВидыКредитныхДоговоров
Т = erp.Перечисления.ТипыДоговоров


def dogovory(kontr, podr, vid, tip, poluchatel):
    r = run(ЗАПРОС_ДОГОВОРА, Контрагент=kontr, Организация=Орг, Подразделение=podr, ВидДоговора=vid,
            ТипДоговора=tip, ПодразделениеПолучатель=poluchatel)
    return [r.Получить(i).Получить(0) for i in range(r.Количество())]


# сторона кредитора: пара «Строительство → Глобино-2»
пара = dogovory(Контр, Стр, В.ТелоКредита, Т.СПоставщиком, Глоб)
check(all(S(d.А_ПодразделениеОказаниеУслугПодразделению) == "Глобино-2" and S(d.Подразделение) == "Строительство"
          for d in пара), f"запрос договора пары выполнен, строк {len(пара)}, у всех получатель Глобино-2")
# пустой получатель (Неопределено → ПустаяСсылка) — договоры без пары, получатель пуст у всех найденных
без = dogovory(Контр, Стр, В.ТелоКредита, Т.СПоставщиком, СП.ПустаяСсылка())
check(all(not erp.ЗначениеЗаполнено(d.А_ПодразделениеОказаниеУслугПодразделению) for d in без),
      f"пустой получатель: строк {len(без)}, у всех реквизит пуст")
# заёмщик: договор тела у контрагента подразделения, получатель пуст
Заём = erp.Справочники.Контрагенты.НайтиПоНаименованию("МД IRS 2026", True)
заём = dogovory(Заём, МДIRC, В.ТелоКредита, Т.СПокупателем, СП.ПустаяСсылка())
check(len(заём) >= 1 and S(заём[0]) == "Кредитование от кредитора -- МД IRC 2026",
      f"заёмщик МД IRS 2026 без получателя → {S(заём[0]) if заём else 'нет'}")
check(not dogovory(Заём, МДIRC, В.ТелоКредита, Т.СПокупателем, Стр), "у заёмщика с получателем договоров нет")

П = erp.Справочники.Партнеры.НайтиПоНаименованию("Воронцов Олександр Володимирович", True)
r = run("""ВЫБРАТЬ ПЕРВЫЕ 1
	Контр.Ссылка КАК Контрагент
ИЗ
	Справочник.Контрагенты КАК Контр
ГДЕ
	Контр.Партнер = &Партнер
	И НЕ Контр.ПометкаУдаления

УПОРЯДОЧИТЬ ПО
	ВЫБОР
		КОГДА Контр.Ссылка В
				(ВЫБРАТЬ
					Дог.Контрагент
				ИЗ
					Справочник.ДоговорыКонтрагентов КАК Дог
				ГДЕ
					Дог.А_ВидКредитногоДоговора <> ЗНАЧЕНИЕ(Перечисление.А_ВидыКредитныхДоговоров.ПустаяСсылка))
			ТОГДА 0
		ИНАЧЕ 1
	КОНЕЦ,
	Контр.Ссылка""", Партнер=П)
check(r.Количество() == 1 and S(r.Получить(0).Получить(0)) == "Воронцов Олександр Володимирович",
      "запрос контрагента кредитора → Воронцов Олександр Володимирович")
sys.exit(0 if ok else 1)
