"""Откат 60 списаний-артефактов, созданных подпиской во время санации 09.08 11:46.

Критерии (тройная защита): номер 000Ц-000778..000Ц-000837, заполнен
А_ПоступлениеБезналичныхДенежныхСредств, НЕТ UUID-соответствия в Бух (не из обмена).
Действие: ОтменаПроведения + ПометкаУдаления, ОбменДанными.Загрузка=Истина.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

nums = erp.NewObject("Массив")
for n in range(778, 838):
    nums.Добавить(f"000Ц-000{n}")

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ Сп.Ссылка КАК Док, Сп.Номер КАК Номер, Сп.СуммаДокумента КАК Сумма,
	ВЫБОР КОГДА Соотв.УникальныйИдентификаторИсточника ЕСТЬ NULL ТОГДА ЛОЖЬ ИНАЧЕ ИСТИНА КОНЕЦ КАК ИзОбмена
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Сп
	ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
		ПО Соотв.УникальныйИдентификаторИсточника = Сп.Ссылка
ГДЕ Сп.Номер В(&Номера) И ГОД(Сп.Дата) = 2026
	И НЕ Сп.А_ПоступлениеБезналичныхДенежныхСредств = ЗНАЧЕНИЕ(Документ.ПоступлениеБезналичныхДенежныхСредств.ПустаяСсылка)
"""
q.SetParameter("Номера", nums)
r = q.Execute().Выгрузить()
print(f"кандидатов: {r.Количество()}")
ok = skip = err = 0
total = 0.0
for i in range(r.Количество()):
    row = r.Получить(i)
    if bool(row.ИзОбмена):
        skip += 1
        print(f"  [SKIP из обмена] {S(row.Док)}")
        continue
    try:
        obj = row.Док.ПолучитьОбъект()
        obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
        obj = row.Док.ПолучитьОбъект()
        obj.УстановитьПометкуУдаления(True)
        ok += 1
        total += float(row.Сумма)
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        err += 1
        print(f"  [FAIL] {S(row.Док)}: {str(msg)[:90]}")

print(f"откачено: {ok} (Σ {total:,.2f}); пропущено: {skip}; ошибок: {err}")
erp = None
print("DONE")
