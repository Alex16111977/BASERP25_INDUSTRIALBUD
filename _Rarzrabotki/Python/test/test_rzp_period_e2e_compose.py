# -*- coding: utf-8 -*-
"""E2E: повторяет тело ПриКомпоновкеРезультата 1:1 после фикса (идиом эталона).

  ПериодОтчета = КомпоновкаДанныхКлиентСервер.ПолучитьПараметр(КомпоновщикНастроек,"Период").Значение
  Параметры.НачалоПериода   = ПериодОтчета.ДатаНачала
  Параметры.ОкончаниеПериода= КонецДня(ПериодОтчета.ДатаОкончания)
  ТаблицаРасшифровки = ПолучитьТаблицуРасшифровки(Параметры)
  компоновка СхемаКомпоновкиДанных -> ТабличныйДокумент

Ставит Период=март2026 на КомпоновщикНастроек отчёта, проверяет:
  - БСП ПолучитьПараметр(КомпоновщикНастроек,"Период") видит март (как в боевом коде);
  - ТЗ только март; компоновка без рантайм-ошибок.
"""
import sys, io, os
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import pythoncom, win32com.client

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_РасшифровкаЗадолженностиПодразделений.erf"
CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
assert os.path.exists(ERF)

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
report = erp.ВнешниеОтчеты.Создать(ERF, False)
print("Загружен OK")

q = erp.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,3,1) КАК Н, ДАТАВРЕМЯ(2026,3,31,23,59,59) КАК К"
rr = q.Выполнить().Выбрать(); rr.Следующий()

# Ставим Период=март2026 на КомпоновщикНастроек отчёта (как пользователь в форме)
кн = report.КомпоновщикНастроек
сп = erp.NewObject("СтандартныйПериод"); сп.ДатаНачала = rr.Н; сп.ДатаОкончания = rr.К
элП = кн.Настройки.ПараметрыДанных.Элементы.Найти("Период")
элП.Значение = сп; элП.Использование = True

# === повтор inline-кода ПриКомпоновкеРезультата ===
ПериодОтчета = erp.КомпоновкаДанныхКлиентСервер.ПолучитьПараметр(кн, "Период").Значение
print(f"БСП ПолучитьПараметр('Период'): {ПериодОтчета.ДатаНачала} .. {ПериодОтчета.ДатаОкончания}")
g_read = str(ПериодОтчета.ДатаНачала)[:10] == "2026-03-01" and str(ПериодОтчета.ДатаОкончания)[:10] == "2026-03-31"

# ПолучитьТаблицуРасшифровки больше НЕ требует Организация/ТолькоРасхождения/ВключатьНепроведенные
Параметры = erp.NewObject("Структура")
Параметры.Вставить("НачалоПериода", ПериодОтчета.ДатаНачала)
Параметры.Вставить("ОкончаниеПериода", ПериодОтчета.ДатаОкончания)  # ПолучитьТаблицуРасшифровки сам делает КонецДня
ТаблицаРасшифровки = report.ПолучитьТаблицуРасшифровки(Параметры)
print(f"ТЗ строк: {ТаблицаРасшифровки.Количество()}")

вне_марта = 0
непроведённые = 0
партнёр_пуст = 0
есть_расхождения = 0
for i in range(ТаблицаРасшифровки.Количество()):
    r = ТаблицаРасшифровки.Получить(i)
    dt = r.Дата
    if dt is None or dt.year != 2026 or dt.month != 3:
        вне_марта += 1
    if not r.Проведен:
        непроведённые += 1
    if not erp.ЗначениеЗаполнено(r.Партнер):
        партнёр_пуст += 1
    if r.ФлагРасхождения:
        есть_расхождения += 1
print(f"строк вне марта 2026: {вне_марта}")
print(f"непроведённых строк:  {непроведённые} (должно быть 0)")
print(f"пустой Партнёр:        {партнёр_пуст} (должно быть 0)")
print(f"строк с расхождением:  {есть_расхождения} (выводятся вместе с остальными — фильтра нет)")

# === реальная компоновка ===
др = erp.NewObject("ДанныеРасшифровкиКомпоновкиДанных")
кмакета = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных")
макет = кмакета.Выполнить(report.СхемаКомпоновкиДанных, кн.ПолучитьНастройки(), др)
вн = erp.NewObject("Структура"); вн.Вставить("Расшифровка", ТаблицаРасшифровки)
проц = erp.NewObject("ПроцессорКомпоновкиДанных")
проц.Инициализировать(макет, вн, др)
табдок = erp.NewObject("ТабличныйДокумент")
вывод = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
вывод.УстановитьДокумент(табдок)
вывод.Вывести(проц)
print(f"ТабличныйДокумент: строк={табдок.ВысотаТаблицы} колонок={табдок.ШиринаТаблицы}")

ok = (g_read and ТаблицаРасшифровки.Количество() > 0 and вне_марта == 0
      and непроведённые == 0 and партнёр_пуст == 0 and табдок.ВысотаТаблицы > 0)
print("\n" + "=" * 60)
print("E2E PASS — Период через БСП фильтрует март2026; только проведённые; измерение Партнёр; компоновка OK"
      if ok else "E2E FAIL")
assert ok
