# -*- coding: utf-8 -*-
"""
Проверяем: есть ли в хранилище настроек пользовательские настройки для А_ОтчетPL.
Если есть — они переопределяют XML. Нужно удалить чтобы XML настройки варианта
(viewMode=Normal) вступили в силу.
"""
import win32com.client
import pythoncom

CONNECTION_STRING = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected")

    # Получить список сохранённых настроек для отчёта А_ОтчетPL
    # БСП хранит настройки вариантов в ХранилищеВариантовОтчетов
    # А пользовательские — в ХранилищеПользовательскихНастроекОтчетов

    q = conn.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ
        Вариант.Ссылка КАК Вариант,
        Вариант.Наименование КАК Имя,
        Вариант.Отчет КАК Отчет,
        Вариант.КлючВарианта КАК КлючВарианта,
        Вариант.Автор КАК Автор,
        Вариант.Пользовательский КАК Пользовательский
    ИЗ Справочник.ВариантыОтчетов КАК Вариант
    ГДЕ Вариант.Отчет ПОДОБНО "%А_ОтчетPL%"
        И НЕ Вариант.ПометкаУдаления
    """
    try:
        res = q.Выполнить().Выгрузить()
        print(f"\n=== Варианты отчёта в хранилище (Справочник.ВариантыОтчетов): {res.Количество()} ===")
        for row in res:
            print(f"  [{row.КлючВарианта}] {row.Имя}  Автор: {row.Автор}  Пользовательский: {row.Пользовательский}")
    except Exception as e:
        print(f"FAIL: {e}")

    # Проверим - есть ли в ХранилищеОбщихНастроек записи
    print("\n=== Проверка ХранилищеОбщихНастроек для отчёта А_ОтчетPL ===")
    try:
        # Отбор по имени объекта
        sel = conn.NewObject("СтруктураОтбораХранилищаНастроек")
        sel.ИмяОбъекта = "Отчет.А_ОтчетPL"
        storage = conn.ХранилищеОбщихНастроек
        # Попробуем прочитать стандартный набор
        if storage is not None:
            print(f"  ХранилищеОбщихНастроек доступно")
    except Exception as e:
        print(f"  Ошибка: {e}")

    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
