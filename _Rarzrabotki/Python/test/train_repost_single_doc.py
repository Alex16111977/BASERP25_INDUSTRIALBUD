# -*- coding: utf-8 -*-
"""
Тренировка: один документ — Списание 000Ц-000228 от 16.12.2025 (897.45).
Дамп ДО → перепроведение → дамп ПОСЛЕ → сравнение.

Цель: понять создаются ли движения в ПоСрокам после простого перепроведения.
Если НЕТ — будем изучать типовой код документа.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Найти контрагента
qk = erp.NewObject("Запрос")
qk.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты ГДЕ Наименование = "Глобино-2"'
контр = qk.Выполнить().Выгрузить().Получить(0).Ссылка

# Минимальный по сумме Списание по Глобино-2 декабрь 2025 от обработки А_ОказаниеУслуг
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Контр", контр)
q.УстановитьПараметр("Д1", datetime.datetime(2025, 12, 1))
q.УстановитьПараметр("Д2", datetime.datetime(2025, 12, 31, 23, 59, 59))
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка, Д.Дата, Д.Номер, Д.СуммаДокумента
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Д
ГДЕ Д.Контрагент = &Контр И Д.Дата МЕЖДУ &Д1 И &Д2
    И Д.А_ОказаниеУслугМеждуПодразделениями <> ЗНАЧЕНИЕ(Документ.А_ОказаниеУслугМеждуПодразделениями.ПустаяСсылка)
    И Д.Проведен
УПОРЯДОЧИТЬ ПО Д.СуммаДокумента
"""
r = q.Выполнить().Выгрузить()
if r.Количество() == 0:
    print("Не найден!")
    sys.exit(1)
док = r.Получить(0).Ссылка
print(f"  Выбран: {S(док)} | Σ={float(r.Получить(0).СуммаДокумента):,.2f}")
print(f"Документ: {S(док)}")


def дамп_движений(метка: str):
    print(f"\n=== {метка} ===")
    регистры = [
        ("РасчетыСКлиентами",            "Сумма"),
        ("РасчетыСПоставщиками",         "Сумма"),
        ("РасчетыСКлиентамиПоСрокам",    "ДолгРегл"),
        ("РасчетыСПоставщикамиПоСрокам", "ДолгРегл"),
    ]
    итог = {}
    for имя, поле_сум in регистры:
        qq = erp.NewObject("Запрос")
        qq.УстановитьПараметр("Рег", док)
        qq.Текст = f"""
ВЫБРАТЬ
    Р.Период,
    Р.ВидДвижения,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОР,
    Р.{поле_сум} КАК Σ,
    ПРЕДСТАВЛЕНИЕ(Р.ХозяйственнаяОперация) КАК Хозоп
ИЗ РегистрНакопления.{имя} КАК Р
ГДЕ Р.Регистратор = &Рег
УПОРЯДОЧИТЬ ПО Р.Период
"""
        rr = qq.Выполнить().Выгрузить()
        итог[имя] = rr.Количество()
        print(f"  [{имя}] строк: {rr.Количество()}")
        for i in range(rr.Количество()):
            rec = rr.Получить(i)
            print(f"    {S(rec.ВидДвижения):<8} | {float(rec.Σ):>12,.2f} | ОР={str(rec.ОР)[:42]:<42} | {str(rec.Хозоп)[:25]}")
    return итог


# === Дамп ДО ===
итог_до = дамп_движений("ДО перепроведения")

# === Реквизиты документа перед перепроведением ===
obj = док.ПолучитьОбъект()
print(f"\n  Реквизиты документа:")
print(f"    Проведён: {obj.Проведен}")
print(f"    А_Обработан: {obj.А_Обработан}")
print(f"    А_ВведенВЕРП: {obj.А_ВведенВЕРП}")
print(f"    А_ОбработанКазна: {obj.А_ОбработанКазна}")
print(f"    А_Необновлять: {obj.А_Необновлять}")
print(f"    Контрагент: {S(obj.Контрагент)}")
print(f"    Партнер: {S(obj.Партнер)}")
print(f"    Подразделение: {S(obj.Подразделение)}")
print(f"    Договор: {('(None)' if obj.Договор is None else ('(ПустаяСсылка)' if obj.Договор.Пустая() else S(obj.Договор)))}")
print(f"    ОбъектРасчетов: {('(None)' if obj.ОбъектРасчетов is None else ('(ПустаяСсылка)' if obj.ОбъектРасчетов.Пустая() else S(obj.ОбъектРасчетов)))}")
print(f"    ХозяйственнаяОперация: {S(obj.ХозяйственнаяОперация)}")
print(f"    СуммаДокумента: {obj.СуммаДокумента}")

# === Перепровести ===
print("\n  → Перепровожу (отмена + проведение)...")
try:
    if obj.Проведен:
        obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
        obj = док.ПолучитьОбъект()
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("  ✓ Готово.")
except Exception as e:
    емсг = e.excepinfo[2] if (hasattr(e,'excepinfo') and e.excepinfo) else str(e)
    print(f"  ✗ FAIL: {емсг[:120]}")
    sys.exit(1)

# === Дамп ПОСЛЕ ===
итог_после = дамп_движений("ПОСЛЕ перепроведения")

# === Сравнение
print("\n" + "=" * 100)
print("СРАВНЕНИЕ:")
print(f"  {'Регистр':<40} | {'ДО':>5} | {'ПОСЛЕ':>5} | Δ")
print("  " + "-" * 80)
for имя in итог_до.keys():
    д = итог_до[имя]
    п = итог_после[имя]
    дельта = п - д
    маркер = " ❗" if abs(дельта) > 0 else ""
    print(f"  {имя:<40} | {д:>5} | {п:>5} | {дельта:>+3}{маркер}")
