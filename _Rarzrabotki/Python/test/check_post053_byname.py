# -*- coding: utf-8 -*-
"""Найти Поступление 000Ц-000053 от 16.12.2025 БЕЗ фильтра контрагента."""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Д.Ссылка, Д.Дата, Д.Номер, Д.Контрагент, Д.Партнер,
    Д.СуммаДокумента, Д.Проведен, Д.ПометкаУдаления, Д.ХозяйственнаяОперация
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Д
ГДЕ Д.Номер = "000Ц-000053"
УПОРЯДОЧИТЬ ПО Д.Дата
"""
r = q.Выполнить().Выгрузить()
print(f"Поступлений с номером 000Ц-000053: {r.Количество()}")
for i in range(r.Количество()):
    rec = r.Получить(i)
    контр = S(rec.Контрагент) if rec.Контрагент and not rec.Контрагент.Пустая() else "(пусто)"
    партн = S(rec.Партнер) if rec.Партнер and not rec.Партнер.Пустая() else "(пусто)"
    print(f"  {rec.Дата.strftime('%d.%m.%Y %H:%M:%S')} | Контр={контр:<20} | Партн={партн:<20} | Σ={float(rec.СуммаДокумента):,.2f} | Пров={rec.Проведен} | Удал={rec.ПометкаУдаления} | {S(rec.ХозяйственнаяОперация)}")

# Также — все Поступления в декабре 2025 связанные с А_ОказаниеУслугМеждуПодразделениями (по Глобино-2)
print("\n--- Все Поступления декабрь 2025 от обработки А_ОказаниеУслуг (любой контрагент) ---")
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("Д1", datetime.datetime(2025, 12, 1))
q2.УстановитьПараметр("Д2", datetime.datetime(2025, 12, 31, 23, 59, 59))
q2.Текст = """
ВЫБРАТЬ Д.Ссылка, Д.Дата, Д.Номер, Д.Контрагент, Д.СуммаДокумента, Д.Проведен, Д.ПометкаУдаления
ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Д
ГДЕ Д.Дата МЕЖДУ &Д1 И &Д2
    И Д.А_ОказаниеУслугМеждуПодразделениями <> ЗНАЧЕНИЕ(Документ.А_ОказаниеУслугМеждуПодразделениями.ПустаяСсылка)
УПОРЯДОЧИТЬ ПО Д.Дата
"""
r2 = q2.Выполнить().Выгрузить()
print(f"  Найдено: {r2.Количество()}")
for i in range(r2.Количество()):
    rec = r2.Получить(i)
    контр = S(rec.Контрагент) if rec.Контрагент and not rec.Контрагент.Пустая() else "(пусто)"
    print(f"    {rec.Дата.strftime('%d.%m.%Y %H:%M:%S')} | {rec.Номер} | Контр={контр:<25} | Σ={float(rec.СуммаДокумента):>15,.2f}")
