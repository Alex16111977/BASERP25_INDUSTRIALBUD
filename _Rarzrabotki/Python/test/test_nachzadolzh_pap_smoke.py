"""Smoke ПАП: перепровести НачальнаяЗадолженность (запишет ПАП) + А_ФинРез_Баланс,
проверить плуг=0, «Оплата труда»=А_ВзСС, Σ КО=-3 165 970,77 (одноногая, by-design)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0
РЗ = erp.РежимЗаписиДокумента.Проведение
РП = erp.РежимПроведенияДокумента.Неоперативный

def repost(ссылки, имя):
    for s in ссылки:
        s.ПолучитьОбъект().Записать(РЗ, РП)
    print(f"  перепроведено {имя}: {len(ссылки)}")

# 1) перепровести 3 НачальнаяЗадолженность
q = erp.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ Документ.НачальнаяЗадолженностьПоЗарплате ГДЕ Проведен"
nz = [r.С for r in q.Выполнить().Выгрузить()]
repost(nz, "НачальнаяЗадолженность")

# 2) ПАП(ОТ, Источник=Пустая) на 30.11 теперь != 0 (входящий долг записан)
def pap(statya, lit, src_empty=True):
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("Н", statya)
    flt = "И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)" if src_empty else ""
    qq.Текст = f"""ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
        ГДЕ Т.Период <= {lit} И Т.Статья.Наименование = &Н {flt}"""
    return f(qq.Выполнить().Выгрузить()[0].КО)
ot_nov = pap("Оплата труда", "ДАТАВРЕМЯ(2025,11,30,23,59,59)")
