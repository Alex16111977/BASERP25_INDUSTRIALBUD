# 4) проверки свёртки
print("\n=== Свёртка после фикса ===")
ETALON = {"дек2025":-1252868.97,"янв2026":-2919783.64,"фев2026":-2917774.84,"мар2026":-3291625.64}
MONTHS = [("дек2025","ДАТАВРЕМЯ(2025,12,1)"),("янв2026","ДАТАВРЕМЯ(2026,1,1)"),
          ("фев2026","ДАТАВРЕМЯ(2026,2,1)"),("мар2026","ДАТАВРЕМЯ(2026,3,1)")]
TOL=0.05; fails=[]; SIGMA_ETALON=-3165970.77  # by-design: ПАП одноногая (без «Прибыли и убытки»)
for label, nm in MONTHS:
    qo=erp.NewObject("Запрос")
    qo.Текст=f"""ВЫБРАТЬ Рег.Расхождение КАК Плуг, СУММА(Рег.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Статья.Наименование="Оплата труда" И Рег.Регистратор.Месяц={nm}
    СГРУППИРОВАТЬ ПО Рег.Расхождение"""
    plug=det=0.0
    for r in qo.Выполнить().Выгрузить():
        if r.Плуг: plug=f(r.КО)
        else: det=f(r.КО)
    qs=erp.NewObject("Запрос")
    qs.Текст=f"""ВЫБРАТЬ СУММА(Рег.СуммаКонечныйОстаток) КАК КО ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Регистратор.Месяц={nm}"""
    sigma=f(qs.Выполнить().Выгрузить()[0].КО)
    ot=plug+det
    ok = abs(plug)<=TOL and abs(ot-ETALON[label])<=TOL and abs(sigma-SIGMA_ETALON)<=0.5
    if not ok: fails.append(label)
    print(f"  {label}: ОТ={ot:>14,.2f} (эт.{ETALON[label]:>14,.2f}) плуг={plug:>12,.2f} Σбаланс={sigma:>10,.2f} {'OK' if ok else 'FAIL'}")

print("\nSMOKE PASS" if not fails else f"SMOKE FAIL: {fails}")
sys.exit(1 if fails else 0)
