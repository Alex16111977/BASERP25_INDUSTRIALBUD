# -*- coding: utf-8 -*-
# СКД-smoke собранного .erf: создание внешнего отчёта (компиляция модуля),
# ПолучитьДанные (логика из .erf) + композиция СКД в ТабличныйДокумент (ВысотаТаблицы>0).
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import os
ERF = os.path.join(os.environ["TEMP"], "pfpp_new.erf")
assert os.path.exists(ERF), "нет собранного .erf"

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# 1) Создать внешний отчёт из .erf — компилирует модуль (ловит синтаксис BSL)
отчет = erp.ВнешниеОтчеты.Создать(ERF)
print("ВнешниеОтчеты.Создать: OK (модуль скомпилирован)")

сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
assert not сс.Пустая()
период = erp.NewObject("СтандартныйПериод")  # пустой -> весь срок

# 2) ПолучитьДанные из .erf
тз = отчет.ПолучитьДанные(период, сс.Ссылка)
print(f"ПолучитьДанные: строк={тз.Количество()}")
assert тз.Количество() > 0, "ПолучитьДанные вернул пусто"

# 3) Композиция СКД в ТабличныйДокумент (как ПриКомпоновкеРезультата)
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
компоновщикНастроек = отчет.КомпоновщикНастроек
настройки = компоновщикНастроек.ПолучитьНастройки()
внешние = erp.NewObject("Структура")
внешние.Вставить("Детали", тз)
кмакета = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных")
макет = кмакета.Выполнить(схема, настройки)
проц = erp.NewObject("ПроцессорКомпоновкиДанных")
проц.Инициализировать(макет, внешние)
докрез = erp.NewObject("ТабличныйДокумент")
вывод = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
вывод.УстановитьДокумент(докрез)
вывод.Вывести(проц)
print(f"Композиция СКД: ВысотаТаблицы={докрез.ВысотаТаблицы}, ШиринаТаблицы={докрез.ШиринаТаблицы}")
assert докрез.ВысотаТаблицы > 0, "пустая таблица"
print("\nSMOKE PASS")
