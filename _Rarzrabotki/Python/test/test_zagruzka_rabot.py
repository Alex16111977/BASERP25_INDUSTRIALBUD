def _ч(v):
    return float(v) if v not in (None, "") else 0.0


def читать_excel():
    wb = openpyxl.load_workbook(XLSX, data_only=True)
    ws = wb.active
    rows = []
    for i, row in enumerate(ws.iter_rows(values_only=True), start=1):
        if i >= 2 and row[1]:
            кол = _ч(row[2]) if len(row) > 2 else 0
            цена = _ч(row[3]) if len(row) > 3 else 0
            сумма = _ч(row[4]) if len(row) > 4 else 0
            rows.append((str(row[0]).strip(), str(row[1]).strip(), кол, цена, сумма))
    return rows


def построить_массив(rows):
    mass = erp.NewObject("Массив")
    for этап, работа, кол, цена, сумма in rows:
        s = erp.NewObject("Структура")
        s.Вставить("Этап", этап)
        s.Вставить("Работа", работа)
        s.Вставить("Количество", кол)
        s.Вставить("Цена", цена)
        s.Вставить("Сумма", сумма)
        mass.Добавить(s)
    return mass


def создать_temp_структуру():
    об = erp.Справочники.А_СтруктураСебестоимости.СоздатьЭлемент()
    об.Наименование = "ТЕСТ_ЗАГРУЗКА_РАБОТ_DELETE"
    об.Записать()
    return об.Ссылка


def test_smoke_pipeline():
    rows = читать_excel()
    print("Строк в Excel:", len(rows))
    структура = создать_temp_структуру()
    обр = erp.ВнешниеОбработки.Создать(EPF)
    try:
        # 1-й прогон: создаются недостающие работы
        рез = обр.ЗагрузитьРаботыИзМассива(структура, построить_массив(rows))
        print("ПРОГОН1: Загружено=%s Работ=%s Этапов=%s Пропущено=%s Ошибка=%s %s" % (
            рез.Загружено, рез.СозданоРабот, рез.СозданоЭтапов, рез.Пропущено,
            рез.Ошибка, рез.ТекстОшибки))
        assert not рез.Ошибка, рез.ТекстОшибки
        assert рез.Загружено == len(rows), f"ожидалось {len(rows)} строк, факт {рез.Загружено}"
        assert рез.СозданоЭтапов == 0, "все 8 этапов уже есть"

        # Проверить ТЧ: заполненность ссылок
        об = структура.ПолучитьОбъект()
        assert об.Работы.Количество() == len(rows)
        пустых = 0
        for стр in об.Работы:
            if not erp.ЗначениеЗаполнено(стр.Этап) or not erp.ЗначениеЗаполнено(стр.Работа):
                пустых += 1
        assert пустых == 0, f"{пустых} строк с пустым Этап/Работа"
        print("ТЧ заполнена корректно, строк:", об.Работы.Количество())

        # Сверка Цена/Сумма: суммы по ТЧ совпадают с Excel
        сумма_тч_цена = sum(float(стр.Цена) for стр in об.Работы)
        сумма_тч_сумма = sum(float(стр.Сумма) for стр in об.Работы)
        сумма_xls_цена = sum(r[3] for r in rows)
        сумма_xls_сумма = sum(r[4] for r in rows)
        print("Σ Цена  ТЧ=%.2f Excel=%.2f" % (сумма_тч_цена, сумма_xls_цена))
        print("Σ Сумма ТЧ=%.2f Excel=%.2f" % (сумма_тч_сумма, сумма_xls_сумма))
        assert abs(сумма_тч_цена - сумма_xls_цена) < 0.01, "Цена не совпала"
        assert abs(сумма_тч_сумма - сумма_xls_сумма) < 0.01, "Сумма не совпала"

        # 2-й прогон: идемпотентность
        рез2 = обр.ЗагрузитьРаботыИзМассива(структура, построить_массив(rows))
        print("ПРОГОН2: Работ=%s Этапов=%s" % (рез2.СозданоРабот, рез2.СозданоЭтапов))
        assert рез2.СозданоРабот == 0, "повтор не должен создавать работы"
        assert рез2.СозданоЭтапов == 0
        об2 = структура.ПолучитьОбъект()
        assert об2.Работы.Количество() == len(rows), "ТЧ перезаписана без задвоения"
        print("OK smoke: пайплайн + идемпотентность")
    finally:
        структура.ПолучитьОбъект().Удалить()
        print("   temp-структура удалена")


