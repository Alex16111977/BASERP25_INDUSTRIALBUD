# -*- coding: utf-8 -*-
"""Разметка кредитных договоров Воронцова и статей ДДС (ОУМП, кредитные договоры).

    python oump_kredit_razmetka.py --dry   # только план
    python oump_kredit_razmetka.py         # записать
"""
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
DRY = "--dry" in sys.argv
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
В = erp.Перечисления.А_ВидыКредитныхДоговоров
ЗПК = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьПоКредитам
СОБ = erp.Справочники.А_ВидыКонтрагентовДляБаланса.Собственники
tag = "DRY " if DRY else "SET "

q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ
	Дог.Ссылка КАК Договор,
	Дог.Наименование КАК Имя
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Дог
ГДЕ
	Дог.Контрагент.Наименование = "Воронцов Олександр Володимирович"
	И НЕ Дог.ПометкаУдаления
	И (Дог.Наименование ПОДОБНО "Кредитование от кредитора -- %"
		ИЛИ Дог.Наименование ПОДОБНО "[%][%] за использование от кредитора -- %"
		ИЛИ Дог.Наименование ПОДОБНО "Нераспределенная прибыль -- %")"""
v = q.Execute().Выгрузить()
for i in range(v.Количество()):
    ref, name = v.Получить(i).Получить(0), S(v.Получить(i).Получить(1))
    if name.startswith("Кредитование"):
        vid = В.ТелоКредита
    elif name.startswith("%%"):
        vid = В.Проценты
    else:
        vid = В.НераспределеннаяПрибыль
    print(tag + "договор " + name + " → " + S(vid))
    if not DRY:
        o = ref.ПолучитьОбъект()
        o.А_ВидКредитногоДоговора = vid
        o.А_ВидКонтрагента = СОБ
        if vid != В.НераспределеннаяПрибыль:
            o.А_СтатьяБаланса = ЗПК
        o.Записать()

ПВ = erp.Справочники.Партнеры.НайтиПоНаименованию("Воронцов Олександр Володимирович", True)
for name, vid in [("Финансовая помощь", В.НераспределеннаяПрибыль),
                  ("Получение финансовой помощи", В.ТелоКредита),
                  ("Возврат Финансовой помощи", В.ТелоКредита)]:
    q.Text = """ВЫБРАТЬ С.Ссылка ИЗ Справочник.СтатьиДвиженияДенежныхСредств КАК С
ГДЕ С.Наименование = &Н И НЕ С.ПометкаУдаления И НЕ С.ЭтоГруппа"""
    q.SetParameter("Н", name)
    r = q.Execute().Выгрузить()
    for i in range(r.Количество()):
        ref = r.Получить(i).Получить(0)
        print(tag + f"статья «{name}» ({S(ref.Код)}) партнёр было «{S(ref.А_ПартнерРасчетов)}» → Воронцов, {S(vid)}")
        if not DRY:
            o = ref.ПолучитьОбъект()
            o.А_ПартнерРасчетов = ПВ
            o.А_ВидКредитногоДоговора = vid
            o.Записать()
