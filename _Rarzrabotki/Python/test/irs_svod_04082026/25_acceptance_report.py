# -*- coding: utf-8 -*-
"""Приймання звіту А_МатериалыПроизводстваКУплате.

Перевіряє інваріанти на живій базі, а не константи (база жива).
"""
import win32com.client, sys, os
from collections import defaultdict
sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_МатериалыПроизводстваКУплате.erf"
PODR = "МД IRS 2026"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

RES = []
def chk(name, got, exp, tol=0.05):
    ok = abs(got - exp) <= tol
    RES.append((name, ok))
    print("  [%s] %-46s %16s | %16s" % ("OK " if ok else "FAIL", name,
                                        "{:,.2f}".format(got), "{:,.2f}".format(exp)))

print("erf: %s (%s байт)" % (os.path.basename(ERF), "{:,}".format(os.path.getsize(ERF))))

rep = erp.ВнешниеОтчеты.Создать(ERF)
print("звіт скомпільовано й створено через COM")

tz = rep.ПолучитьДанные(None)
cols = [S(tz.Колонки.Получить(i).Имя) for i in range(tz.Колонки.Количество())]
print("колонок ТЗ: %d -> %s" % (len(cols), ", ".join(cols)))
print("рядків ТЗ: %d" % tz.Количество())

agg = defaultdict(float)
by_kind = defaultdict(lambda: defaultdict(float))
for i in range(tz.Количество()):
    r = tz.Получить(i)
    if S(r.Подразделение) != PODR:
        continue
    kind = S(r.ВидСтроки)
    for k in ("СуммаПлан", "Получено", "Оплачено", "Кредиторка", "ЩеНеКуплено"):
        v = f(getattr(r, k))
        agg[k] += v
        by_kind[kind][k] += v

print("\n=== ПО ВИДАХ РЯДКІВ (%s) ===" % PODR)
print("%-30s%15s%15s%15s%15s%15s" % ("Вид рядка", "План", "Отримано", "Оплачено", "Кредиторка", "Ще не куплено"))
for kind in sorted(by_kind):
    d = by_kind[kind]
    print("%-30s%15s%15s%15s%15s%15s" % (kind[:28],
        "{:,.2f}".format(d["СуммаПлан"]), "{:,.2f}".format(d["Получено"]),
        "{:,.2f}".format(d["Оплачено"]), "{:,.2f}".format(d["Кредиторка"]),
        "{:,.2f}".format(d["ЩеНеКуплено"])))

# ---- еталони з бази ----
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)
def q1(text, **p):
    z = erp.NewObject("Запрос")
    for k, v in p.items(): z.SetParameter(k, v)
    z.Text = text
    return z.Execute().Выгрузить().Получить(0)

prih = f(q1("""
ВЫБРАТЬ СУММА(СТ.Стоимость) КАК С ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
 И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
 И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
 И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (&Подр)
""", Подр=podr).С)

plan_reg = f(q1("""
ВЫБРАТЬ СУММА(Р.СуммаПланОборот) КАК С
ИЗ РегистрНакопления.А_ПланОплатМатериалов.Обороты(, , Регистратор, ) КАК Р
ГДЕ Р.Подразделение В ИЕРАРХИИ (&Подр)
""", Подр=podr).С)

print("\n=== ІНВАРІАНТИ ===")
chk("Отримано (накладні) = регістр собівартості", by_kind["2. Накладна"]["Получено"], prih)
chk("Оплачено + Кредиторка = Отримано",
    by_kind["2. Накладна"]["Оплачено"] + by_kind["2. Накладна"]["Кредиторка"],
    by_kind["2. Накладна"]["Получено"])
chk("Оплачено по платежах = Оплачено по накладних",
    by_kind["3. Платіж"]["Оплачено"], by_kind["2. Накладна"]["Оплачено"])
chk("План звіту = регістр плану", by_kind["1. План оплати"]["СуммаПлан"], plan_reg)

potrebno = by_kind["2. Накладна"]["Кредиторка"] + by_kind["4. Ще не куплено"]["ЩеНеКуплено"]
print("\n=== ПІДСУМОК ФІНАНСИСТА ===")
print("  План оплат (графік)      %16s" % "{:,.2f}".format(by_kind["1. План оплати"]["СуммаПлан"]))
print("  Кредиторка               %16s" % "{:,.2f}".format(by_kind["2. Накладна"]["Кредиторка"]))
print("  Ще не куплено            %16s" % "{:,.2f}".format(by_kind["4. Ще не куплено"]["ЩеНеКуплено"]))
print("  ПОТРІБНО ДО СПЛАТИ       %16s" % "{:,.2f}".format(potrebno))
print("  Відхилення (план - треба)%16s" % "{:,.2f}".format(by_kind["1. План оплати"]["СуммаПлан"] - potrebno))
print("  Послуги поза кошторисом  %16s" % "{:,.2f}".format(by_kind["5. Послуги поза кошторисом"]["Получено"]))

# розшифровка дверей
print("\n=== РОЗШИФРОВКА «Вхідні двері металеві» ===")
for i in range(tz.Количество()):
    r = tz.Получить(i)
    if S(r.Подразделение) != PODR or S(r.ОбщееНазвание) != "Вхідні двері металеві":
        continue
    if S(r.ВидСтроки) not in ("2. Накладна", "3. Платіж"):
        continue
    print("  %-16s %-40s %-40s опл=%12s кред=%12s" % (
        S(r.ВидСтроки), S(r.Документ)[:38], S(r.Платеж)[:38],
        "{:,.2f}".format(f(r.Оплачено)), "{:,.2f}".format(f(r.Кредиторка))))

bad = [x for x in RES if not x[1]]
print("\n" + "=" * 78)
print("перевірок: %d, провалено: %d" % (len(RES), len(bad)))
print("ЗВІТ ПРИЙНЯТО" if not bad else "!!! Є ПОМИЛКИ !!!")
sys.exit(0 if not bad else 1)
