# -*- coding: utf-8 -*-
"""Завантаження ВСІЄЇ книги МАТЕРИАЛИ.xlsx у документ — як це зробить форма.

Передаємо всі 1000 рядків з усіх 7 аркушів (у т.ч. чужі проєкти ООН/ВООЗ/МХП).
Очікуємо: модуль лишить тільки IRS 15 + IRS 30 = 338 рядків на 11 286 390,58,
решту аркушів позначить як чужі й пропустить.
"""
import win32com.client, sys, json, datetime
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

PODR = "МД IRS 2026"
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)

rows = json.load(open("data_form_replica.json", encoding="utf-8"))
print("рядків із книги (усі аркуші): %d на %s грн"
      % (len(rows), "{:,.2f}".format(sum(x["Сумма"] for x in rows))))
by_sheet = {}
for x in rows:
    by_sheet[x["Лист"]] = by_sheet.get(x["Лист"], 0) + 1
print("  аркуші: %s" % ", ".join("%s=%d" % (k, v) for k, v in sorted(by_sheet.items())))

arr = erp.NewObject("Массив")
for p in rows:
    st = erp.NewObject("Структура")
    st.Вставить("Лист", p["Лист"])
    st.Вставить("НоменклатураСС", p["НоменклатураСС"])
    y, m, _d = (int(x) for x in p["Месяц"].split("-"))
    st.Вставить("Месяц", datetime.datetime(y, m, 15))   # COM зсуває дату на день
    st.Вставить("Количество", p["Количество"])
    st.Вставить("Сумма", p["Сумма"])
    arr.Добавить(st)

q = erp.NewObject("Запрос")
q.SetParameter("Подр", podr)
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Док
ИЗ Документ.А_ГрафикОплатМатериалов КАК Д
ГДЕ Д.Подразделение = &Подр И НЕ Д.ПометкаУдаления
УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ
"""
r = q.Execute().Выгрузить()
if r.Количество() > 0:
    obj = r.Получить(0).Док.ПолучитьОбъект()
    print("\nдокумент: %s (перезаливаємо)" % S(obj.Номер).strip())
else:
    obj = erp.Документы.А_ГрафикОплатМатериалов.СоздатьДокумент()
    obj.Дата = datetime.datetime(2026, 8, 5, 10, 0, 0)
    obj.Подразделение = podr
    print("\nстворюємо новий документ")

prot = obj.ЗагрузитьГрафикИзМассива(arr)
print("\n=== ПРОТОКОЛ ===")
print("  Помилка     : %s %s" % (prot.Ошибка, S(prot.ТекстОшибки)))
print("  Завантажено : %s" % prot.Загружено)
print("  Пропущено   : %s" % prot.Пропущено)
print("  Без ЗН      : %s" % prot.БезОН.Количество())
print("  ПРИЙНЯТІ аркуші:")
for i in range(prot.Листы.Количество()):
    L = prot.Листы.Получить(i)
    print("      %-14s -> %-34s %s з %s (%s %%)"
          % (S(L.Лист), S(L.СС), L.Совпадений, L.Позиций, L.Доля))
print("  ЧУЖІ аркуші (пропущено):")
for i in range(prot.ЧужиеЛисты.Количество()):
    L = prot.ЧужиеЛисты.Получить(i)
    print("      %-14s  збігів %s з %s (%s %%)" % (S(L.Лист), L.Совпадений, L.Позиций, L.Доля))

if prot.Ошибка:
    sys.exit(1)

summ = sum(f(obj.Строки.Получить(i).Сумма) for i in range(obj.Строки.Количество()))
print("\n  рядків у ТЧ: %d, сума: %s" % (obj.Строки.Количество(), "{:,.2f}".format(summ)))

obj.Записать(erp.РежимЗаписиДокумента.Проведение)
print("  документ проведено")

q2 = erp.NewObject("Запрос")
q2.SetParameter("Подр", podr)
q2.Text = """
ВЫБРАТЬ Р.Месяц КАК М, СУММА(Р.СуммаПланОборот) КАК С
ИЗ РегистрНакопления.А_ПланОплатМатериалов.Обороты(, , Регистратор, ) КАК Р
ГДЕ Р.Подразделение В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО Р.Месяц УПОРЯДОЧИТЬ ПО М
"""
r2 = q2.Execute().Выгрузить()
tot = 0.0
print("\n=== РЕГІСТР ===")
for i in range(r2.Количество()):
    s = r2.Получить(i); tot += f(s.С)
    print("  %-12s %16s" % (S(s.М)[:10], "{:,.2f}".format(f(s.С))))
print("  %-12s %16s" % ("РАЗОМ", "{:,.2f}".format(tot)))

ok = (abs(tot - 11286390.58) < 0.05 and obj.Строки.Количество() == 338
      and prot.БезОН.Количество() == 0)
print("\n%s" % ("ФІЛЬТР ЧУЖИХ АРКУШІВ ПРАЦЮЄ — у документі лише IRS"
                if ok else "!!! ПЕРЕВІРКА НЕ ПРОЙДЕНА !!!"))
sys.exit(0 if ok else 1)
