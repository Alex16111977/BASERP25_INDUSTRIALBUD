# -*- coding: utf-8 -*-
"""Нова логіка: серпень = НЕОПЛАЧЕНА кредиторка.
По кожній «закритій» ЗН перевіряємо, чи оплачені накладні приходу."""
import win32com.client, sys, json
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("МД IRS 2026", True)
ZNS = ["Вхідні двері металеві", "Профільна труба", "Лист ГК", "лист пвл", "АВР",
       "Гратка", " Кутики сталеві"]

# частка ЗН у накладній + борг накладної -> неоплачена частина ЗН
q = erp.NewObject("Запрос")
q.SetParameter("Подр", podr)
q.Text = """
ВЫБРАТЬ
    Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ЗН,
    Т.Ссылка КАК Док, Т.Ссылка.Номер КАК Номер, Т.Ссылка.Дата КАК Дата,
    Т.Ссылка.Контрагент.Наименование КАК Контрагент,
    Т.Ссылка.СуммаДокумента КАК СумаДок,
    СУММА(Т.Количество) КАК Кіл, СУММА(Т.СуммаСНДС) КАК СумаЗН
ПОМЕСТИТЬ втРядки
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
СГРУППИРОВАТЬ ПО Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование,
    Т.Ссылка, Т.Ссылка.Номер, Т.Ссылка.Дата, Т.Ссылка.Контрагент.Наименование,
    Т.Ссылка.СуммаДокумента
;
ВЫБРАТЬ
    Р.РасчетныйДокумент КАК Док, СУММА(Р.ДолгОстаток) КАК Борг
ПОМЕСТИТЬ втБорг
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам.Остатки() КАК Р
СГРУППИРОВАТЬ ПО Р.РасчетныйДокумент
;
ВЫБРАТЬ
    ВР.ЗН КАК ЗН, ВР.Номер КАК Номер, ВР.Дата КАК Дата, ВР.Контрагент КАК Контрагент,
    ВР.Кіл КАК Кіл, ВР.СумаЗН КАК СумаЗН, ВР.СумаДок КАК СумаДок,
    ЕСТЬNULL(БР.Борг, 0) КАК БоргДок
ИЗ втРядки КАК ВР
ЛЕВОЕ СОЕДИНЕНИЕ втБорг КАК БР ПО БР.Док = ВР.Док
УПОРЯДОЧИТЬ ПО ЗН, Дата
"""
try:
    r = q.Execute().Выгрузить()
except Exception as e:
    print("FAIL:", e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e)
    sys.exit(1)

by = {}
for i in range(r.Количество()):
    s = r.Получить(i)
    zn = S(s.ЗН)
    sum_zn, sum_doc, debt = f(s.СумаЗН), f(s.СумаДок), f(s.БоргДок)
    share = (sum_zn / sum_doc) if sum_doc else 0.0
    unpaid = round(debt * share, 2)          # неоплачена частина, що припадає на цю ЗН
    d = by.setdefault(zn, {"Приход": 0.0, "Неоплачено": 0.0, "Кіл": 0.0, "накл": []})
    d["Приход"] += sum_zn; d["Неоплачено"] += unpaid; d["Кіл"] += f(s.Кіл)
    d["накл"].append({"Номер": S(s.Номер).strip(), "Дата": S(s.Дата)[:10],
                      "Контрагент": S(s.Контрагент), "Кіл": f(s.Кіл), "СумаЗН": sum_zn,
                      "СумаДок": sum_doc, "БоргДок": debt, "Частка": round(share, 4),
                      "Неоплачено": unpaid, "Оплачено": round(sum_zn - unpaid, 2)})

json.dump(by, open("data_paid_by_zn.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)

ar = {x["ЗН"]: x for x in json.load(open("data_august_risk.json", encoding="utf-8"))["rows"]}
print("=" * 122)
print("%-26s%14s%14s%14s%15s%15s  %s" % ("Загальна назва", "Прихід", "Оплачено",
                                          "НЕоплачено", "Графік серпня", "Зайве в серп.", "Висновок"))
print("=" * 122)
tot_over = 0.0
for zn in ZNS:
    d = by.get(zn)
    if not d:
        print("%-26s  немає приходу" % zn[:24]); continue
    graf = ar.get(zn, {}).get("ГрафікСерпень", 0.0)
    unpaid = round(d["Неоплачено"], 2)
    over = round(max(graf - unpaid, 0.0), 2)
    tot_over += over
    verdict = ("зняти з серпня %s" % "{:,.2f}".format(over)) if over > 0.005 else "залишити як є"
    print("%-26s%14s%14s%14s%15s%15s  %s" % (
        zn[:24], "{:,.2f}".format(d["Приход"]), "{:,.2f}".format(d["Приход"] - unpaid),
        "{:,.2f}".format(unpaid), "{:,.2f}".format(graf), "{:,.2f}".format(over), verdict))
print("=" * 122)
print("Разом зняти з серпня по цих позиціях: %s грн" % "{:,.2f}".format(tot_over))
print("\n-> data_paid_by_zn.json")
