# -*- coding: utf-8 -*-
"""Етап 1, приймання: завантаження графіка оплат у документ і проведення.

Get-or-create: якщо документ по підрозділу вже є — беремо його, не створюємо дубль
і не видаляємо (memory feedback_no_doc_delete_in_tests).

Перевіряє заодно автопідбір СС за аркушем: у масив кладемо «IRS 15» / «IRS 30»,
модуль сам має зіставити їх зі структурами собівартості за максимумом збігів.
"""
import win32com.client, sys, json, datetime
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

PODR = "МД IRS 2026"
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)
SS2TAG = {"МД IRS 2026 15 м (МД IRS 2026)": "IRS 15",
          "МД IRS 2026 30 м (МД IRS 2026)": "IRS 30"}

payload = json.load(open("data_graph_payload.json", encoding="utf-8"))["rows"]
print("рядків у payload: %d" % len(payload))

arr = erp.NewObject("Массив")
for p in payload:
    st = erp.NewObject("Структура")
    st.Вставить("Лист", SS2TAG.get(p["СС"], p["СС"]))
    st.Вставить("НоменклатураСС", p["НоменклатураСС"])
    y, m, _d = (int(x) for x in p["Месяц"].split("-"))
    # 15-е число: COM-міст Python->1С зсуває дату на день назад
    # (01.07 приїжджає як 30.06 -> НачалоМесяца дає червень). Середина місяця стійка.
    st.Вставить("Месяц", datetime.datetime(y, m, 15))
    st.Вставить("Количество", p["Количество"])
    st.Вставить("Сумма", p["Сумма"])
    arr.Добавить(st)
print("передаємо в модуль: %d структур" % arr.Количество())

# --- get-or-create ---
q = erp.NewObject("Запрос")
q.SetParameter("Подр", podr)
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Док
ИЗ Документ.А_ГрафикОплатМатериалов КАК Д
ГДЕ Д.Подразделение = &Подр И НЕ Д.ПометкаУдаления
УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ
"""
r = q.Execute().Выгрузить()
if r.Количество() > 0:
    obj = r.Получить(0).Док.ПолучитьОбъект()
    print("знайдено наявний документ: %s" % S(obj.Номер).strip())
else:
    obj = erp.Документы.А_ГрафикОплатМатериалов.СоздатьДокумент()
    obj.Дата = datetime.datetime(2026, 8, 5, 10, 0, 0)
    obj.Подразделение = podr
    obj.Комментарий = "Графік оплат матеріалів із кошторису МАТЕРИАЛИ.xlsx"
    print("створюємо новий документ")

# --- завантаження ---
prot = obj.ЗагрузитьГрафикИзМассива(arr)
print("\n=== ПРОТОКОЛ ЗАВАНТАЖЕННЯ ===")
print("  Помилка      : %s %s" % (prot.Ошибка, S(prot.ТекстОшибки)))
print("  Завантажено  : %s" % prot.Загружено)
print("  Пропущено    : %s" % prot.Пропущено)
print("  Без ЗН       : %s" % prot.БезОН.Количество())
for i in range(min(prot.БезОН.Количество(), 8)):
    print("      %s" % S(prot.БезОН.Получить(i)))
print("  Аркуші:")
for i in range(prot.Листы.Количество()):
    L = prot.Листы.Получить(i)
    print("      %-10s -> %-34s збігів=%s" % (S(L.Лист), S(L.СС), L.Совпадений))

if prot.Ошибка:
    print("\nЗАВАНТАЖЕННЯ ВПАЛО — документ не записуємо")
    sys.exit(1)

print("\n  рядків у ТЧ: %d, сума ТЧ: %s" % (
    obj.Строки.Количество(),
    "{:,.2f}".format(sum(f(obj.Строки.Получить(i).Сумма) for i in range(obj.Строки.Количество())))))

# --- запис і проведення ---
try:
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("\nдокумент проведено: %s від %s" % (S(obj.Номер).strip(), S(obj.Дата)[:10]))
except Exception as e:
    print("\nПОМИЛКА ПРОВЕДЕННЯ:", e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e)
    sys.exit(1)

# --- контроль регістру ---
q2 = erp.NewObject("Запрос")
q2.SetParameter("Подр", podr)
q2.Text = """
ВЫБРАТЬ Р.Месяц КАК М, СУММА(Р.СуммаПланОборот) КАК С, СУММА(Р.КоличествоПланОборот) КАК К,
    КОЛИЧЕСТВО(*) КАК Рядків
ИЗ РегистрНакопления.А_ПланОплатМатериалов.Обороты(, , Регистратор, ) КАК Р
ГДЕ Р.Подразделение В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО Р.Месяц
УПОРЯДОЧИТЬ ПО М
"""
r2 = q2.Execute().Выгрузить()
tot = 0.0
print("\n=== РЕГІСТР А_ПланОплатМатериалов ===")
for i in range(r2.Количество()):
    s = r2.Получить(i); tot += f(s.С)
    print("  %-12s %16s" % (S(s.М)[:10], "{:,.2f}".format(f(s.С))))
exp = round(sum(p["Сумма"] for p in payload), 2)
print("  %-12s %16s" % ("РАЗОМ", "{:,.2f}".format(tot)))
print("  %-12s %16s" % ("еталон Excel", "{:,.2f}".format(exp)))
ok = abs(tot - exp) < 0.05
print("\n%s" % ("ЕТАП 1 ПРИЙНЯТО — регістр = кошторис" if ok else "!!! РОЗБІЖНІСТЬ !!!"))
sys.exit(0 if ok else 1)
