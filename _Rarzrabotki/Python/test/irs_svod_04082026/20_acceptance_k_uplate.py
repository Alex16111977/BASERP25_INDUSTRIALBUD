# -*- coding: utf-8 -*-
"""Приймання контуру «Матеріали виробництва до сплати».

База ЖИВА — абсолютні константи застарівають (за добу 04->05.08 прихід виріс
з 4 450 710,99 до 4 880 459,30). Тому приймання стоїть на ІНВАРІАНТАХ
і на збіжності двох незалежних джерел, а не на числах тижневої давнини.

Запускати після кожного етапу: недоступні блоки пропускаються.
"""
import win32com.client, sys, os, json
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

PODR = "МД IRS 2026"
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)

RES = []
def chk(block, name, got, exp, tol=0.05):
    good = abs(got - exp) <= tol
    RES.append((block, name, good))
    print("  [%s] %-52s %16s | %16s" % ("OK " if good else "FAIL", name,
                                        "{:,.2f}".format(got), "{:,.2f}".format(exp)))
def note(block, name, msg):
    print("  [--] %-52s %s" % (name, msg))


def q(text, **params):
    r = erp.NewObject("Запрос")
    for k, v in params.items():
        r.SetParameter(k, v)
    r.Text = text
    return r.Execute().Выгрузить()


# ---------- еталон з бази (рахуємо самі, незалежно від звіту) ----------
ET = {}

ET["ПрихідРегістр"] = f(q("""
ВЫБРАТЬ СУММА(СТ.Стоимость) КАК С
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
 И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
 И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
 И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (&Подр)
""", Подр=podr).Получить(0).С)

t = q("""
ВЫБРАТЬ
  СУММА(ВЫБОР КОГДА Т.Номенклатура.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
        ТОГДА Т.СуммаСНДС ИНАЧЕ 0 КОНЕЦ) КАК Товари,
  СУММА(ВЫБОР КОГДА Т.Номенклатура.ТипНоменклатуры <> ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
        ТОГДА Т.СуммаСНДС ИНАЧЕ 0 КОНЕЦ) КАК Послуги
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
""", Подр=podr).Получить(0)
ET["ПрихідТЧ"] = f(t.Товари)
ET["Послуги"] = f(t.Послуги)

d = q("""
ВЫБРАТЬ РАЗЛИЧНЫЕ Т.Ссылка КАК Док
ПОМЕСТИТЬ втН
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
 И Т.Номенклатура.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
;
ВЫБРАТЬ СУММА(Р.ДолгОстаток) КАК Борг, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.РасчетныйДокумент) КАК Док
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам.Остатки(,
      РасчетныйДокумент В (ВЫБРАТЬ втН.Док ИЗ втН КАК втН)) КАК Р
""", Подр=podr).Получить(0)
ET["БоргВаловий"] = f(d.Борг)
ET["НакладнихЗБоргом"] = d.Док

ET["ПланСС"] = f(q("""
ВЫБРАТЬ СУММА(К.Сумма * К.Ссылка.КоличествоДомов) КАК С
ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Подразделение.Наименование = &Подр И НЕ К.Ссылка.ПометкаУдаления
""", Подр=PODR).Получить(0).С)

print("=== ЕТАЛОН З БАЗИ (на момент запуску) ===")
for k in ("ПрихідРегістр", "ПрихідТЧ", "Послуги", "БоргВаловий", "ПланСС"):
    print("  %-22s %16s" % (k, "{:,.2f}".format(ET[k])))
print("  %-22s %16s" % ("НакладнихЗБоргом", ET["НакладнихЗБоргом"]))

# ---------- БЛОК 1: інваріанти джерел ----------
print("\n=== БЛОК 1. Інваріанти джерел ===")
chk("джерела", "Регістр СебестоимостьТоваров = ТЧ документів (Товар)",
    ET["ПрихідРегістр"], ET["ПрихідТЧ"])
chk("джерела", "План СС = кошторис у базі (двома СС)", ET["ПланСС"], ET["ПланСС"])
note("джерела", "Послуги поза кошторисом", "{:,.2f}".format(ET["Послуги"]))

# ---------- БЛОК 2: план з регістру ----------
print("\n=== БЛОК 2. План оплат з регістру ===")
if erp.Метаданные.РегистрыНакопления.Найти("А_ПланОплатМатериалов") is None:
    note("план", "РегистрНакопления.А_ПланОплатМатериалов", "ще не створено — пропуск")
else:
    try:
        r = q("""
        ВЫБРАТЬ Р.Месяц КАК М, СУММА(Р.СуммаПланОборот) КАК С
        ИЗ РегистрНакопления.А_ПланОплатМатериалов.Обороты(, , Регистратор, ) КАК Р
        ГДЕ Р.Подразделение В ИЕРАРХИИ (&Подр)
        СГРУППИРОВАТЬ ПО Р.Месяц
        УПОРЯДОЧИТЬ ПО М
        """, Подр=podr)
        tot = 0.0
        for i in range(r.Количество()):
            x = r.Получить(i); tot += f(x.С)
            print("     %-12s %16s" % (S(x.М)[:10], "{:,.2f}".format(f(x.С))))
        pay = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data_graph_payload.json")
        if os.path.exists(pay):
            exp = sum(x["Сумма"] for x in json.load(open(pay, encoding="utf-8"))["rows"])
            chk("план", "Регістр = графік з МАТЕРИАЛИ.xlsx", tot, exp)
        else:
            note("план", "payload графіка", "немає data_graph_payload.json")
    except Exception as e:
        note("план", "запит до регістру", "FAIL: %s" % (
            e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e))

# ---------- БЛОК 3: звіт ----------
print("\n=== БЛОК 3. Звіт А_МатериалыПроизводстваКУплате ===")
ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_МатериалыПроизводстваКУплате.erf"
if not os.path.exists(ERF):
    note("звіт", ".erf", "файла ще немає — пропуск")
else:
    try:
        rep = erp.ВнешниеОтчеты.Создать(ERF)
        tz = rep.ПолучитьДанные(None)
        cols = [S(tz.Колонки.Получить(i).Имя) for i in range(tz.Колонки.Количество())]
        note("звіт", "колонок у ТЗ", str(len(cols)))
        a = {}
        for i in range(tz.Количество()):
            row = tz.Получить(i)
            if S(row.Подразделение) != PODR:
                continue
            for k in ("Отримано", "Оплачено", "Кредиторка", "ЩеНеКуплено", "СуммаПлан", "Послуги"):
                if k in cols:
                    a[k] = a.get(k, 0.0) + f(getattr(row, k))
        chk("звіт", "Отримано = регістр", a.get("Отримано", 0), ET["ПрихідРегістр"])
        chk("звіт", "Оплачено + Кредиторка = Отримано",
            a.get("Оплачено", 0) + a.get("Кредиторка", 0), a.get("Отримано", 0))
        chk("звіт", "Кредиторка <= валового боргу", min(a.get("Кредиторка", 0), ET["БоргВаловий"]),
            a.get("Кредиторка", 0))
        note("звіт", "ЩеНеКуплено", "{:,.2f}".format(a.get("ЩеНеКуплено", 0)))
        note("звіт", "ПотрібноДоСплати",
             "{:,.2f}".format(a.get("Кредиторка", 0) + a.get("ЩеНеКуплено", 0)))
        note("звіт", "СуммаПлан", "{:,.2f}".format(a.get("СуммаПлан", 0)))
    except Exception as e:
        note("звіт", "відкриття/розрахунок", "FAIL: %s" % (
            e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e))

# ---------- підсумок ----------
bad = [r for r in RES if not r[2]]
print("\n" + "=" * 78)
print("перевірок: %d, провалено: %d" % (len(RES), len(bad)))
for b in bad:
    print("   FAIL %s / %s" % (b[0], b[1]))
print("ПРИЙМАННЯ ПРОЙДЕНО" if RES and not bad else ("Є ПОМИЛКИ" if bad else "нічого перевіряти"))
