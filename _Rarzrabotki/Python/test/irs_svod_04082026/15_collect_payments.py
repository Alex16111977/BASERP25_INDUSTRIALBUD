# -*- coding: utf-8 -*-
"""Повний збір: прихід -> оплати -> неоплачена кредиторка, по всіх ЗН підрозділу МД IRS 2026.

Логіка (узгоджено з користувачем 04.08.2026):
  колонка «Серпень» у кошторисі = ГРОШІ ДО СПЛАТИ, а не план закупівлі.
  Правильна сума серпня по ЗН = неоплачена кредиторка по вже отриманих матеріалах
                                + залишок вартості того, що ще не куплено.

Зв'язка «оплата <-> накладна» — через РегістраторРозрахунків:
у ньому одночасно Расход Долга по накладній і Расход Предоплаты по платіжці
(та сама дата й сума). Це підтверджено на «Вхідні двері металеві».
"""
import win32com.client, sys, json
from collections import defaultdict
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

PODR = "МД IRS 2026"
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)

# ---------- 1. рядки приходу по ЗН ----------
q = erp.NewObject("Запрос"); q.SetParameter("Подр", podr)
q.Text = """
ВЫБРАТЬ
    Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ЗН,
    Т.Ссылка КАК Док, Т.Ссылка.Номер КАК Номер, Т.Ссылка.Дата КАК Дата,
    Т.Ссылка.Контрагент.Наименование КАК Контрагент,
    Т.Ссылка.СуммаДокумента КАК СумаДок,
    СУММА(Т.Количество) КАК Кіл, СУММА(Т.СуммаСНДС) КАК СумаЗН
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
    И Т.Номенклатура.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
СГРУППИРОВАТЬ ПО Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование,
    Т.Ссылка, Т.Ссылка.Номер, Т.Ссылка.Дата,
    Т.Ссылка.Контрагент.Наименование, Т.Ссылка.СуммаДокумента
УПОРЯДОЧИТЬ ПО ЗН, Дата
"""
r = q.Execute().Выгрузить()
lines = []
docs_arr = erp.NewObject("Массив")
seen_docs = set()
for i in range(r.Количество()):
    s = r.Получить(i)
    key = S(s.Док)
    lines.append({"ЗН": S(s.ЗН), "ДокКлюч": key, "Номер": S(s.Номер).strip(),
                  "Дата": S(s.Дата)[:10], "Контрагент": S(s.Контрагент),
                  "СумаДок": f(s.СумаДок), "Кіл": f(s.Кіл), "СумаЗН": f(s.СумаЗН)})
    if key not in seen_docs:
        seen_docs.add(key); docs_arr.Добавить(s.Док)
print("рядків приходу (ЗН × накладна): %d, накладних: %d" % (len(lines), len(seen_docs)))

# ---------- 2. борг по накладних ----------
q2 = erp.NewObject("Запрос"); q2.SetParameter("Доки", docs_arr)
q2.Text = """
ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент) КАК ДокП,
        Р.РасчетныйДокумент КАК Док,
        СУММА(Р.ДолгОстаток) КАК Борг
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам.Остатки(, РасчетныйДокумент В (&Доки)) КАК Р
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент), Р.РасчетныйДокумент
"""
debt = {}
r2 = q2.Execute().Выгрузить()
for i in range(r2.Количество()):
    s = r2.Получить(i)
    debt[S(s.Док)] = f(s.Борг)
print("накладних із боргом: %d на %.2f грн" % (len([1 for v in debt.values() if v > 0.005]),
                                               sum(v for v in debt.values() if v > 0.005)))

# ---------- 3. рухи розрахунків: зв'язка платіж <-> накладна ----------
q3 = erp.NewObject("Запрос"); q3.SetParameter("Доки", docs_arr)
q3.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ОбъектРасчетов КАК ОР
ПОМЕСТИТЬ втОР
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ГДЕ Р.РасчетныйДокумент В (&Доки)
;
ВЫБРАТЬ
    Р.Регистратор КАК Рег,
    Р.Период КАК Період,
    Р.ВидДвижения КАК Вид,
    Р.РасчетныйДокумент КАК РД,
    ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент) КАК РДп,
    Р.РасчетныйДокумент.Дата КАК ДатаРД,
    СУММА(Р.Долг) КАК Борг,
    СУММА(Р.Предоплата) КАК Передоплата
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ВНУТРЕННЕЕ СОЕДИНЕНИЕ втОР КАК О ПО О.ОР = Р.ОбъектРасчетов
СГРУППИРОВАТЬ ПО Р.Регистратор, Р.Период, Р.ВидДвижения, Р.РасчетныйДокумент,
    ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент), Р.РасчетныйДокумент.Дата
"""
r3 = q3.Execute().Выгрузить()
# (Регистратор, Период) -> {погашення боргу по накладних}, {зачет авансу по платіжках}
buckets = defaultdict(lambda: {"debt_out": [], "pre_out": []})
for i in range(r3.Количество()):
    s = r3.Получить(i)
    vid = S(s.Вид); is_out = ("асход" in vid or "Expense" in vid)
    k = (S(s.Рег), S(s.Період)[:10])
    if is_out and f(s.Борг) > 0.005:
        buckets[k]["debt_out"].append({"РД": S(s.РД), "РДп": S(s.РДп), "Сума": f(s.Борг)})
    if is_out and f(s.Передоплата) > 0.005:
        buckets[k]["pre_out"].append({"РДп": S(s.РДп), "ДатаРД": S(s.ДатаРД)[:10],
                                      "Сума": f(s.Передоплата)})

# зіставлення в межах (регістратор, період) за сумою
pay_by_doc = defaultdict(list)
for (reg, per), b in buckets.items():
    pool = list(b["pre_out"])
    for d in b["debt_out"]:
        hit = next((p for p in pool if abs(p["Сума"] - d["Сума"]) < 0.02), None)
        if hit:
            pool.remove(hit)
            pay_by_doc[d["РД"]].append({"Платіж": hit["РДп"], "ДатаПлатежу": hit["ДатаРД"],
                                        "Сума": d["Сума"], "Період": per, "Тип": "зарахування авансу"})
        else:
            pay_by_doc[d["РД"]].append({"Платіж": "(оплата після постачання)", "ДатаПлатежу": per,
                                        "Сума": d["Сума"], "Період": per, "Тип": "оплата"})
print("накладних із розшифровкою оплат: %d" % len(pay_by_doc))

json.dump({"lines": lines, "debt": debt,
           "pays": {k: v for k, v in pay_by_doc.items()}},
          open("data_pay_raw.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("-> data_pay_raw.json")
