# -*- coding: utf-8 -*-
"""Позиции плана (СС.Комплектующие) по подразделению МД IRS 2026."""
import win32com.client, sys, json
sys.stdout.reconfigure(encoding='utf-8')
PODR = "МД IRS 2026"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v): return round(float(v),4) if v is not None else 0.0
q = erp.NewObject("Запрос"); q.SetParameter("Подр", PODR)
q.Text = """
ВЫБРАТЬ
    К.Ссылка.Наименование КАК СС, К.Ссылка.КоличествоДомов КАК Домов,
    К.НоменклатураСС КАК ТекстСС,
    К.Номенклатура.Код КАК КодНом, К.Номенклатура.Наименование КАК ИмяНом,
    ВЫБОР КОГДА К.Номенклатура = ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
         ТОГДА К.ОбщееНазвание.Наименование
         ИНАЧЕ К.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КОНЕЦ КАК ОН,
    К.Этап.Наименование КАК Этап, К.Единица.Наименование КАК Ед,
    К.Количество КАК Кол, К.Цена КАК Цена, К.Сумма КАК Сумма
ИЗ Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Подразделение.Наименование = &Подр И НЕ К.Ссылка.ПометкаУдаления
УПОРЯДОЧИТЬ ПО СС, К.НомерСтроки
"""
r = q.Execute().Выгрузить()
plan=[]
for i in range(r.Количество()):
    s=r.Получить(i)
    plan.append({"СС":S(s.СС),"Домов":int(s.Домов or 1),"ТекстСС":S(s.ТекстСС).strip(),
                 "КодНом":S(s.КодНом).strip(),"ИмяНом":S(s.ИмяНом),"ОН":S(s.ОН),
                 "Этап":S(s.Этап),"Ед":S(s.Ед),"КолДом":f(s.Кол),"Цена":f(s.Цена),"СуммаДом":f(s.Сумма)})
print(f"Строк плана: {len(plan)}")
for ss in sorted(set(p['СС'] for p in plan)):
    rows=[p for p in plan if p['СС']==ss]
    print(f"  {ss}: {len(rows)} поз., Σ/дім={sum(p['СуммаДом'] for p in rows):,.2f}, домів={rows[0]['Домов']}")
json.dump({"plan":plan}, open("data_positions.json","w",encoding="utf-8"), ensure_ascii=False, indent=1)
print("-> data_positions.json")
