# -*- coding: utf-8 -*-
"""Оплачены ли накладные по «Вхідні двері металеві» — расшифровка приход/оплата."""
import win32com.client, sys, json
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("МД IRS 2026", True)
ZN = "Вхідні двері металеві"

# ---------- 1. накладні ----------
q = erp.NewObject("Запрос")
q.SetParameter("Подр", podr); q.SetParameter("ЗН", ZN)
q.Text = """
ВЫБРАТЬ
    Т.Ссылка КАК Док, Т.Ссылка.Номер КАК Номер, Т.Ссылка.Дата КАК Дата,
    Т.Ссылка.Контрагент.Наименование КАК Контрагент,
    Т.Ссылка.СуммаДокумента КАК СумаДок,
    СУММА(Т.Количество) КАК Кіл, СУММА(Т.СуммаСНДС) КАК Сума
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
    И Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование = &ЗН
СГРУППИРОВАТЬ ПО Т.Ссылка, Т.Ссылка.Номер, Т.Ссылка.Дата,
    Т.Ссылка.Контрагент.Наименование, Т.Ссылка.СуммаДокумента
УПОРЯДОЧИТЬ ПО Дата
"""
r = q.Execute().Выгрузить()
docs = []
arr = erp.NewObject("Массив")
for i in range(r.Количество()):
    s = r.Получить(i)
    docs.append({"ref": s.Док, "Номер": S(s.Номер).strip(), "Дата": S(s.Дата)[:10],
                 "Контрагент": S(s.Контрагент), "СумаДок": f(s.СумаДок),
                 "Кіл": f(s.Кіл), "Сума": f(s.Сума)})
    arr.Добавить(s.Док)
print("накладних: %d, дверей: %g шт на %.2f грн" %
      (len(docs), sum(d["Кіл"] for d in docs), sum(d["Сума"] for d in docs)))

# ---------- 2. борг по кожній накладній ----------
q2 = erp.NewObject("Запрос"); q2.SetParameter("Доки", arr)
q2.Text = """
ВЫБРАТЬ
    Р.РасчетныйДокумент КАК РозрДок,
    СУММА(Р.ДолгОстаток) КАК Борг,
    СУММА(Р.ПредоплатаОстаток) КАК Передоплата
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам.Остатки(, РасчетныйДокумент В (&Доки)) КАК Р
СГРУППИРОВАТЬ ПО Р.РасчетныйДокумент
"""
debt = {}
try:
    r2 = q2.Execute().Выгрузить()
    for i in range(r2.Количество()):
        s = r2.Получить(i)
        debt[S(s.РозрДок)] = (f(s.Борг), f(s.Передоплата))
except Exception as e:
    print("FAIL борг:", e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e)

# ---------- 3. обороти розрахунків: чим гасили ----------
q3 = erp.NewObject("Запрос"); q3.SetParameter("Доки", arr)
q3.Text = """
ВЫБРАТЬ
    Р.РасчетныйДокумент КАК РозрДок,
    Р.Регистратор КАК Реєстратор,
    ПРЕДСТАВЛЕНИЕ(Р.Регистратор) КАК РеєстраторПредст,
    Р.Период КАК Період,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
          ТОГДА Р.Долг ИНАЧЕ -Р.Долг КОНЕЦ) КАК ЗмінаБоргу
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ГДЕ Р.РасчетныйДокумент В (&Доки)
СГРУППИРОВАТЬ ПО Р.РасчетныйДокумент, Р.Регистратор, ПРЕДСТАВЛЕНИЕ(Р.Регистратор), Р.Период
УПОРЯДОЧИТЬ ПО Період
"""
moves = {}
try:
    r3 = q3.Execute().Выгрузить()
    for i in range(r3.Количество()):
        s = r3.Получить(i)
        moves.setdefault(S(s.РозрДок), []).append(
            {"Реєстратор": S(s.РеєстраторПредст), "Період": S(s.Період)[:10],
             "Зміна": f(s.ЗмінаБоргу)})
except Exception as e:
    print("FAIL обороти:", e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e)

# ---------- вивід ----------
print("\n" + "=" * 118)
print("%-14s%-12s%-30s%9s%14s%14s%14s  %s" %
      ("Накладна", "Дата", "Постачальник", "Дверей", "Сума з ПДВ", "Оплачено", "Борг", "Статус"))
print("=" * 118)
out = []
for d in docs:
    key = S(d["ref"])
    b, pre = debt.get(key, (0.0, 0.0))
    paid = round(d["СумаДок"] - b, 2)
    st = "ОПЛАЧЕНО" if b <= 0.005 else ("частково" if paid > 0.005 else "НЕ ОПЛАЧЕНО")
    out.append({**{k: v for k, v in d.items() if k != "ref"},
                "Борг": b, "Оплачено": paid, "Статус": st,
                "Рухи": moves.get(key, []), "Ключ": key})
    print("%-14s%-12s%-30s%9g%14s%14s%14s  %s" %
          (d["Номер"], d["Дата"], d["Контрагент"][:28], d["Кіл"],
           "{:,.2f}".format(d["Сума"]), "{:,.2f}".format(paid),
           "{:,.2f}".format(b), st))
print("=" * 118)
print("%-14s%-12s%-30s%9g%14s%14s%14s" %
      ("РАЗОМ", "", "", sum(d["Кіл"] for d in docs),
       "{:,.2f}".format(sum(d["Сума"] for d in docs)),
       "{:,.2f}".format(sum(o["Оплачено"] for o in out)),
       "{:,.2f}".format(sum(o["Борг"] for o in out))))

print("\nРУХИ РОЗРАХУНКІВ ПО КОЖНІЙ НАКЛАДНІЙ:")
for o in out:
    print("\n  %s (%s):" % (o["Номер"], o["Статус"]))
    if not o["Рухи"]:
        print("      рухів немає")
    for m in o["Рухи"]:
        znak = "+" if m["Зміна"] > 0 else ""
        print("      %-11s %-64s %s%s" % (m["Період"], m["Реєстратор"][:62], znak, "{:,.2f}".format(m["Зміна"])))

json.dump(out, open("data_doors_payments.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("\n-> data_doors_payments.json")
