# -*- coding: utf-8 -*-
"""ПРОТОТИП ПолучитьДанные() звіту А_МатериалыПроизводстваКУплате.

Будує рівно ту ТЗ, яку потім віддасть BSL, і перевіряє інваріанти.
Мета — відпрацювати алгоритм на живій базі ДО написання BSL (Rule #-1).

Грейн ТЗ (одна колонка = одне поле СКД):
  Подразделение, СтруктураСебестоимости, ОбщееНазвание, Месяц,
  ВидСтроки, Документ, Платеж, Контрагент, Аналитика, Признак,
  СуммаПлан, Отримано, Оплачено, Кредиторка, ЩеНеКуплено

ВидСтроки: "План" | "Накладна" | "Платіж" | "ЩеНеКуплено" | "Послуги"
"""
import win32com.client, sys, json
from collections import defaultdict
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v):
    try: return float(v)
    except: return 0.0

PODR = "МД IRS 2026"
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)


def query(text, **p):
    q = erp.NewObject("Запрос")
    for k, v in p.items():
        q.SetParameter(k, v)
    q.Text = text
    return q.Execute().Выгрузить()


TZ = []
def row(**kw):
    r = {"Подразделение": PODR, "СтруктураСебестоимости": "", "ОбщееНазвание": "",
         "Месяц": "", "ВидСтроки": "", "Документ": "", "Платеж": "", "Контрагент": "",
         "Аналитика": "", "Признак": "",
         "СуммаПлан": 0.0, "Отримано": 0.0, "Оплачено": 0.0,
         "Кредиторка": 0.0, "ЩеНеКуплено": 0.0}
    r.update(kw)
    TZ.append(r)
    return r


# ============ 1. ПРИХІД: рядки накладних по ЗН ============
r = query("""
ВЫБРАТЬ
    Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ЗН,
    Т.Ссылка КАК Док, Т.Ссылка.Номер КАК Номер, Т.Ссылка.Дата КАК Дата,
    Т.Ссылка.Контрагент.Наименование КАК Контрагент,
    Т.Ссылка.СуммаДокумента КАК СумаДок,
    СУММА(Т.СуммаСНДС) КАК СумаЗН
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
    И Т.Номенклатура.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
СГРУППИРОВАТЬ ПО Т.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование,
    Т.Ссылка, Т.Ссылка.Номер, Т.Ссылка.Дата,
    Т.Ссылка.Контрагент.Наименование, Т.Ссылка.СуммаДокумента
УПОРЯДОЧИТЬ ПО ЗН, Дата
""", Подр=podr)

lines, docs = [], erp.NewObject("Массив")
seen = set()
for i in range(r.Количество()):
    s = r.Получить(i)
    k = S(s.Док)
    lines.append({"ЗН": S(s.ЗН).strip(), "ДокКлюч": k, "Док": s.Док,
                  "Номер": S(s.Номер).strip(), "Дата": S(s.Дата)[:10],
                  "Контрагент": S(s.Контрагент), "СумаДок": f(s.СумаДок),
                  "СумаЗН": f(s.СумаЗН)})
    if k not in seen:
        seen.add(k); docs.Добавить(s.Док)
print("рядків приходу: %d, накладних: %d" % (len(lines), len(seen)))

# ============ 2. БОРГ по накладних ============
r = query("""
ВЫБРАТЬ Р.РасчетныйДокумент КАК Док, СУММА(Р.ДолгОстаток) КАК Борг
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам.Остатки(,
        РасчетныйДокумент В (&Доки)) КАК Р
СГРУППИРОВАТЬ ПО Р.РасчетныйДокумент
""", Доки=docs)
debt = {S(r.Получить(i).Док): f(r.Получить(i).Борг) for i in range(r.Количество())}

# ============ 3. ЗВ'ЯЗКА платіж <-> накладна через регістратор розрахунків ============
r = query("""
ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ОбъектРасчетов КАК ОР
ПОМЕСТИТЬ втОР
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ГДЕ Р.РасчетныйДокумент В (&Доки)
;
ВЫБРАТЬ
    Р.Регистратор КАК Рег, Р.Период КАК Період, Р.ВидДвижения КАК Вид,
    Р.РасчетныйДокумент КАК РД, ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент) КАК РДп,
    Р.РасчетныйДокумент.Дата КАК ДатаРД,
    СУММА(Р.Долг) КАК Борг, СУММА(Р.Предоплата) КАК Передоплата
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ВНУТРЕННЕЕ СОЕДИНЕНИЕ втОР КАК О ПО О.ОР = Р.ОбъектРасчетов
СГРУППИРОВАТЬ ПО Р.Регистратор, Р.Период, Р.ВидДвижения, Р.РасчетныйДокумент,
    ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент), Р.РасчетныйДокумент.Дата
""", Доки=docs)

buckets = defaultdict(lambda: {"d": [], "p": []})
pre_in = defaultdict(float)   # для детекції задвоєння авансу
pre_out = defaultdict(float)
for i in range(r.Количество()):
    s = r.Получить(i)
    out = "асход" in S(s.Вид)
    key = (S(s.Рег), S(s.Період)[:10])
    if out and f(s.Борг) > 0.005:
        buckets[key]["d"].append({"РД": S(s.РД), "Сума": f(s.Борг)})
    if out and f(s.Передоплата) > 0.005:
        buckets[key]["p"].append({"РДп": S(s.РДп), "Дата": S(s.ДатаРД)[:10],
                                  "Сума": f(s.Передоплата)})
        pre_out[S(s.РДп)] += f(s.Передоплата)
    if (not out) and f(s.Передоплата) > 0.005:
        pre_in[S(s.РДп)] += f(s.Передоплата)

pays = defaultdict(list)
for (_reg, per), b in buckets.items():
    pool = list(b["p"])
    for d in b["d"]:
        hit = next((x for x in pool if abs(x["Сума"] - d["Сума"]) < 0.02), None)
        if hit:
            pool.remove(hit)
            pays[d["РД"]].append({"Платіж": hit["РДп"], "Дата": hit["Дата"],
                                  "Сума": d["Сума"], "Тип": "зарахування авансу"})
        else:
            pays[d["РД"]].append({"Платіж": "(оплата після постачання)", "Дата": per,
                                  "Сума": d["Сума"], "Тип": "оплата"})

# АНОМАЛІЯ = прихід авансу в регістрі БІЛЬШИЙ за суму самої платіжки.
# Незарахований аванс (прихід > зарахування) аномалією НЕ Є — це нормальна передоплата
# під ще не отриманий товар. Перевірка 05.08.2026: Σ прихід = Σ СуммаДокумента
# (2 935 824,59 = 2 935 824,59) по всіх 39 платіжках — задвоєнь немає.
ra = query("""
ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ОбъектРасчетов КАК ОР
ПОМЕСТИТЬ втОР2
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ГДЕ Р.РасчетныйДокумент В (&Доки)
;
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент) КАК Плат,
    МАКСИМУМ(ВЫРАЗИТЬ(Р.РасчетныйДокумент КАК Документ.СписаниеБезналичныхДенежныхСредств).СуммаДокумента) КАК СумаДок,
    СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
          ТОГДА Р.Предоплата ИНАЧЕ 0 КОНЕЦ) КАК Прих
ИЗ РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ВНУТРЕННЕЕ СОЕДИНЕНИЕ втОР2 КАК О2 ПО О2.ОР = Р.ОбъектРасчетов
ГДЕ Р.РасчетныйДокумент ССЫЛКА Документ.СписаниеБезналичныхДенежныхСредств
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Р.РасчетныйДокумент)
""", Доки=docs)
anomalies = {}
for i in range(ra.Количество()):
    s = ra.Получить(i)
    delta = round(f(s.Прих) - f(s.СумаДок), 2)
    if delta > 0.02:
        anomalies[S(s.Плат)] = delta

# ============ 4. ЩЕ НЕ КУПЛЕНО — з методики звіту ПланФакт ============
rep = erp.Отчеты.А_ПланФактныйПроизводствоПолный.Создать()
tzp = rep.ПолучитьДанные(None)
etc = defaultdict(float)
for i in range(tzp.Количество()):
    x = tzp.Получить(i)
    if S(x.Подразделение) != PODR or S(x.Блок) != "2. Матеріали":
        continue
    if f(x.ПланНаФактГрн):
        etc[S(x.ОбщееНазвание).strip()] += f(x.ПланНаФактГрн)

# ============ 5. ПЛАН з payload (поки регістру немає) ============
plan = defaultdict(float)
try:
    for p in json.load(open("data_graph_payload.json", encoding="utf-8"))["rows"]:
        plan[(p["ОбщееНазвание"].strip(), p["Месяц"], p["СС"])] += p["Сумма"]
except FileNotFoundError:
    print("! data_graph_payload.json відсутній — план порожній")

# ============ 6. ПОСЛУГИ поза кошторисом ============
r = query("""
ВЫБРАТЬ Т.Ссылка.Номер КАК Номер, Т.Ссылка.Дата КАК Дата,
    Т.Ссылка.Контрагент.Наименование КАК Контрагент,
    Т.Номенклатура.Наименование КАК Ном, СУММА(Т.СуммаСНДС) КАК Сума
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
ГДЕ Т.Ссылка.Подразделение В ИЕРАРХИИ (&Подр) И Т.Ссылка.Проведен
    И Т.Номенклатура.ТипНоменклатуры <> ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)
СГРУППИРОВАТЬ ПО Т.Ссылка.Номер, Т.Ссылка.Дата,
    Т.Ссылка.Контрагент.Наименование, Т.Номенклатура.Наименование
УПОРЯДОЧИТЬ ПО Дата
""", Подр=podr)
services = [{"Номер": S(r.Получить(i).Номер).strip(), "Дата": S(r.Получить(i).Дата)[:10],
             "Контрагент": S(r.Получить(i).Контрагент), "Ном": S(r.Получить(i).Ном),
             "Сума": f(r.Получить(i).Сума)} for i in range(r.Количество())]

# ============ ЗБІРКА ТЗ ============
for (on, mon, ss), summ in sorted(plan.items()):
    row(ОбщееНазвание=on, Месяц=mon, СтруктураСебестоимости=ss,
        ВидСтроки="План", СуммаПлан=round(summ, 2))

for ln in lines:
    share = (ln["СумаЗН"] / ln["СумаДок"]) if ln["СумаДок"] else 0.0
    unpaid = round(debt.get(ln["ДокКлюч"], 0.0) * share, 2)
    row(ОбщееНазвание=ln["ЗН"], ВидСтроки="Накладна",
        Документ="%s від %s" % (ln["Номер"], ln["Дата"]), Контрагент=ln["Контрагент"],
        Отримано=round(ln["СумаЗН"], 2), Оплачено=round(ln["СумаЗН"] - unpaid, 2),
        Кредиторка=unpaid)
    for p in pays.get(ln["ДокКлюч"], []):
        row(ОбщееНазвание=ln["ЗН"], ВидСтроки="Платіж",
            Документ="%s від %s" % (ln["Номер"], ln["Дата"]),
            Платеж="%s від %s" % (p["Платіж"], p["Дата"]),
            Признак=p["Тип"] + (" | АНОМАЛІЯ: задвоєний аванс"
                                if p["Платіж"] in anomalies else ""),
            Оплачено=round(p["Сума"] * share, 2))

for on, v in sorted(etc.items()):
    if v > 0.005:
        row(ОбщееНазвание=on, ВидСтроки="ЩеНеКуплено", ЩеНеКуплено=round(v, 2))

for s in services:
    row(ОбщееНазвание="(послуги поза кошторисом)", ВидСтроки="Послуги",
        Документ="%s від %s" % (s["Номер"], s["Дата"]), Контрагент=s["Контрагент"],
        Аналитика=s["Ном"], Отримано=round(s["Сума"], 2), Признак="не матеріал")

# ============ ІНВАРІАНТИ ============
def sm(key, vid=None):
    return round(sum(r[key] for r in TZ if vid is None or r["ВидСтроки"] == vid), 2)

print("\nрядків ТЗ: %d" % len(TZ))
print("  План           %16s" % "{:,.2f}".format(sm("СуммаПлан")))
print("  Отримано(накл) %16s" % "{:,.2f}".format(sm("Отримано", "Накладна")))
print("  Оплачено(накл) %16s" % "{:,.2f}".format(sm("Оплачено", "Накладна")))
print("  Кредиторка     %16s" % "{:,.2f}".format(sm("Кредиторка")))
print("  ЩеНеКуплено    %16s" % "{:,.2f}".format(sm("ЩеНеКуплено")))
print("  Послуги        %16s" % "{:,.2f}".format(sm("Отримано", "Послуги")))
print("  Оплачено(плат) %16s" % "{:,.2f}".format(sm("Оплачено", "Платіж")))

ok = True
def inv(name, a, b, tol=0.05):
    global ok
    g = abs(a - b) <= tol; ok = ok and g
    print("  [%s] %-46s %16s | %16s" % ("OK " if g else "FAIL", name,
                                        "{:,.2f}".format(a), "{:,.2f}".format(b)))

print("\nІНВАРІАНТИ:")
prih = f(query("""
ВЫБРАТЬ СУММА(СТ.Стоимость) КАК С ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
 И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
 И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
 И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (&Подр)
""", Подр=podr).Получить(0).С)
inv("Отримано = регістр СебестоимостьТоваров", sm("Отримано", "Накладна"), prih)
inv("Оплачено + Кредиторка = Отримано",
    sm("Оплачено", "Накладна") + sm("Кредиторка"), sm("Отримано", "Накладна"))
inv("Оплачено по платежах = Оплачено по накладних",
    sm("Оплачено", "Платіж"), sm("Оплачено", "Накладна"))

print("\nАНОМАЛІЇ (задвоєний аванс): %d" % len(anomalies))
for k, v in list(anomalies.items())[:5]:
    print("   %-58s +%s" % (k[:56], "{:,.2f}".format(v)))

json.dump({"TZ": TZ, "anomalies": anomalies}, open("data_proto_tz.json", "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)
print("\n" + ("ПРОТОТИП ЗІЙШОВСЯ" if ok else "!!! ІНВАРІАНТИ ПОРУШЕНО !!!"))
print("-> data_proto_tz.json")
