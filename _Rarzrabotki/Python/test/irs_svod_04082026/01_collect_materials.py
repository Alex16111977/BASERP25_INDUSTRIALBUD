# -*- coding: utf-8 -*-
"""Сбор факта по материалам МД IRS 2026 из отчёта + прямых запросов BaseERP."""
import win32com.client, sys, json
from collections import defaultdict
sys.stdout.reconfigure(encoding='utf-8')

PODR = "МД IRS 2026"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v): return round(float(v), 2) if v is not None else 0.0

# ---------- A. Данные ОТЧЁТА ----------
rep = erp.Отчеты.А_ПланФактныйПроизводствоПолный.Создать()
tz = rep.ПолучитьДанные(None)
n = tz.Количество()

byON = {}
plan_by_obj = defaultdict(float)
tot = defaultdict(float)
for i in range(n):
    r = tz.Получить(i)
    if S(r.Подразделение) != PODR: continue
    if S(r.Блок) != "2. Матеріали": continue
    on = S(r.ОбщееНазвание) or ""
    key = on if on else "(без загальної назви)"
    d = byON.setdefault(key, {"ОН": key, "Этап": "", "Единица": "",
                              "ПланКол":0.0,"ПланГрн":0.0,"ФактКол":0.0,"ФактГрн":0.0,"Осталось":0.0,
                              "План15":0.0,"План30":0.0})
    d["ПланКол"] += f(r.ПланКол);  d["ПланГрн"] += f(r.ПланГрн)
    d["ФактКол"] += f(r.ФактКол);  d["ФактГрн"] += f(r.ФактГрн)
    d["Осталось"] += f(r.ПланНаФактГрн)
    if not d["Этап"] and S(r.Этап): d["Этап"] = S(r.Этап)
    if not d["Единица"] and S(r.Единица): d["Единица"] = S(r.Единица)
    po = S(r.ПодразделениеОбъекта)
    if f(r.ПланГрн):
        if "15 м" in po: d["План15"] += f(r.ПланГрн); plan_by_obj["15"] += f(r.ПланГрн)
        elif "30 м" in po: d["План30"] += f(r.ПланГрн); plan_by_obj["30"] += f(r.ПланГрн)
        else: plan_by_obj["?"] += f(r.ПланГрн)
    for k in ("ПланГрн","ФактГрн","Осталось"):
        tot[k] += d and 0
tot = {"ПланГрн": round(sum(d["ПланГрн"] for d in byON.values()),2),
       "ФактГрн": round(sum(d["ФактГрн"] for d in byON.values()),2),
       "Осталось": round(sum(d["Осталось"] for d in byON.values()),2)}
tot["Прогноз"] = round(tot["ФактГрн"] + tot["Осталось"], 2)
tot["ОтклонениеПрогноз"] = round(tot["ПланГрн"] - tot["Прогноз"], 2)
for d in byON.values():
    for k in ("ПланКол","ПланГрн","ФактКол","ФактГрн","Осталось","План15","План30"): d[k]=round(d[k],2)
    d["ЦенаПлан"] = round(d["ПланГрн"]/d["ПланКол"],2) if d["ПланКол"] else 0.0
    d["ЦенаФакт"] = round(d["ФактГрн"]/d["ФактКол"],2) if d["ФактКол"] else 0.0
    d["Процент"]  = round(d["ФактГрн"]/d["ПланГрн"]*100,1) if d["ПланГрн"] else 0.0

print(f"ОН всего={len(byON)}  План={tot['ПланГрн']:,.2f}  Факт={tot['ФактГрн']:,.2f}  Осталось={tot['Осталось']:,.2f}")
print(f"Прогноз={tot['Прогноз']:,.2f}  Отклонение={tot['ОтклонениеПрогноз']:,.2f}")
print(f"План 15м={plan_by_obj['15']:,.2f}  30м={plan_by_obj['30']:,.2f}  без объекта={plan_by_obj['?']:,.2f}")

# ---------- B. Помесячный факт закупок + документы ----------
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)
q = erp.NewObject("Запрос"); q.SetParameter("Подр", podr)
q.Text = """
ВЫБРАТЬ
    НАЧАЛОПЕРИОДА(СТ.Период, МЕСЯЦ) КАК Мес,
    ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Номер КАК Номер,
    ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Дата КАК Дата,
    ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Контрагент.Наименование КАК Контрагент,
    СУММА(СТ.Стоимость) КАК Сумма
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
    И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
    И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(СТ.Период, МЕСЯЦ),
    ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Номер,
    ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Дата,
    ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Контрагент.Наименование
УПОРЯДОЧИТЬ ПО Дата
"""
r = q.Execute().Выгрузить()
docs = []; by_month = defaultdict(float)
for i in range(r.Количество()):
    s = r.Получить(i)
    m = S(s.Мес)[:7]
    docs.append({"Мес":m,"Номер":S(s.Номер).strip(),"Дата":S(s.Дата)[:10],
                 "Контрагент":S(s.Контрагент),"Сумма":f(s.Сумма)})
    by_month[m] += f(s.Сумма)
print(f"\nДокументов закупки: {len(docs)}; по месяцам: " +
      ", ".join(f"{k}={v:,.2f}" for k,v in sorted(by_month.items())))
print(f"Контроль Σ документов = {sum(d['Сумма'] for d in docs):,.2f}")

json.dump({"byON":list(byON.values()),"tot":tot,"plan_by_obj":dict(plan_by_obj),
           "docs":docs,"by_month":dict(by_month)},
          open("data_materials.json","w",encoding="utf-8"), ensure_ascii=False, indent=1)
print("\n-> data_materials.json")
