# -*- coding: utf-8 -*-
"""Факт закупок в разрезе номенклатуры (путь через АналитикаУчетаНоменклатуры — как в отчёте)."""
import win32com.client, sys, json
sys.stdout.reconfigure(encoding='utf-8')
PODR = "МД IRS 2026"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
def f(v): return round(float(v),4) if v is not None else 0.0
podr = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR, True)

q = erp.NewObject("Запрос"); q.SetParameter("Подр", podr)
q.Text = """
ВЫБРАТЬ
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.Код КАК Код,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.Наименование КАК Имя,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК ОН,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.ЕдиницаИзмерения.Наименование КАК Ед,
    СУММА(СТ.Количество) КАК Кол,
    СУММА(СТ.Стоимость) КАК Сумма
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
    И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
    И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО СТ.АналитикаУчетаНоменклатуры.Номенклатура.Код,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.Наименование,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование,
    СТ.АналитикаУчетаНоменклатуры.Номенклатура.ЕдиницаИзмерения.Наименование
УПОРЯДОЧИТЬ ПО Сумма УБЫВ
"""
try:
    r = q.Execute().Выгрузить()
except Exception as e:
    print("FAIL:", e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else e); sys.exit(1)

fact=[]
for i in range(r.Количество()):
    s=r.Получить(i); kol=f(s.Кол); sm=f(s.Сумма)
    fact.append({"Код":S(s.Код).strip(),"Имя":S(s.Имя),"ОН":S(s.ОН),"Ед":S(s.Ед),
                 "Кол":kol,"Сумма":round(sm,2),"Цена":round(sm/kol,2) if kol else 0.0})
print(f"OK номенклатур={len(fact)}  Σ={sum(x['Сумма'] for x in fact):,.2f}")
no_on=[x for x in fact if not x['ОН']]
print(f"  без ОН на карточке: {len(no_on)} на {sum(x['Сумма'] for x in no_on):,.2f}")
print("\nТОП-10 по сумме:")
for x in fact[:10]: print(f"  {x['Код']:<14}{x['Имя'][:42]:<44}{x['Сумма']:>13,.2f}  ОН={x['ОН']}")
json.dump(fact, open("data_fact_nom.json","w",encoding="utf-8"), ensure_ascii=False, indent=1)
print("-> data_fact_nom.json")
