# -*- coding: utf-8 -*-
"""Факт денег по МД IRS 2026 из Казны (РегистрНакопления.БДДС), в разрезе статей ДДС и месяцев."""
import win32com.client, sys, json
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
k = v8.Connect('Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"')
S = k.String
def f(v): return round(float(v),2) if v is not None else 0.0
podr = k.Справочники.Подразделения.НайтиПоНаименованию("МД IRS 2026", True)

q = k.NewObject("Запрос"); q.УстановитьПараметр("Подр", podr)
q.Текст = """
ВЫБРАТЬ
    Б.ПланФакт КАК ПФ,
    ГОД(Б.Период) КАК Г, МЕСЯЦ(Б.Период) КАК М,
    Б.СтатьяДвиженияДенежныхСредств.Наименование КАК Стаття,
    Б.СтатьяДвиженияДенежныхСредств.Код КАК КодСтатті,
    Б.Подразделение.Наименование КАК Підрозділ,
    СУММА(Б.СуммаПриход) КАК Прих, СУММА(Б.СуммаРасход) КАК Расх
ИЗ РегистрНакопления.БДДС КАК Б
ГДЕ Б.Подразделение В ИЕРАРХИИ (&Подр)
СГРУППИРОВАТЬ ПО Б.ПланФакт, ГОД(Б.Период), МЕСЯЦ(Б.Период),
    Б.СтатьяДвиженияДенежныхСредств.Наименование, Б.СтатьяДвиженияДенежныхСредств.Код,
    Б.Подразделение.Наименование
УПОРЯДОЧИТЬ ПО Расх УБЫВ
"""
try:
    r = q.Выполнить().Выгрузить()
except Exception as e:
    print("FAIL:", e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else e); sys.exit(1)

rows=[]
for i in range(r.Количество()):
    s=r.Получить(i)
    rows.append({"ПФ":S(s.ПФ),"Період":f"{int(s.Г)}-{int(s.М):02d}","Стаття":S(s.Стаття),
                 "Код":S(s.КодСтатті).strip(),"Підрозділ":S(s.Підрозділ),
                 "Прихід":f(s.Прих),"Розхід":f(s.Расх)})
print(f"строк={len(rows)}  Σ прихід={sum(x['Прихід'] for x in rows):,.2f}  Σ розхід={sum(x['Розхід'] for x in rows):,.2f}")
print(f"\n{'Період':<9}{'Стаття ДДС':<44}{'Прихід':>14}{'Розхід':>14}")
for x in rows:
    print(f"{x['Період']:<9}{x['Стаття'][:42]:<44}{x['Прихід']:>14,.2f}{x['Розхід']:>14,.2f}")
json.dump(rows, open("data_kazna.json","w",encoding="utf-8"), ensure_ascii=False, indent=1)
print("-> data_kazna.json")
