def субконто_расчёты(ref):
    """Source∈расчётные ПоСрокам, построчно: проверка субконто
    Контрагент/Партнер/Договор на деталях (Расхождение=Ложь) и
    пустоты на плугах (Расхождение=Истина)."""
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Д", ref); q.УстановитьПараметр("Ист", МассивРасч)
    q.Текст = """ВЫБРАТЬ
        Организация КАК Орг,
        ЕСТЬNULL(Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        Статья КАК Ст, ПРЕДСТАВЛЕНИЕ(Статья) КАК СтП, Source КАК Src,
        Расхождение КАК Рх, ОбъектРасчетов КАК ОР,
        Контрагент КАК Кн, Договор КАК Дг, Партнер КАК Пн
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод
    ГДЕ Регистратор=&Д И Source В (&Ист)"""
    t = q.Выполнить().Выгрузить()
    дет = плуг = ор = кн = дг = пн = 0
    плуг_суб = собств_плохо = 0
    ключи = Counter()
    for i in range(t.Количество()):
        r = t.Получить(i)
        if bool(r.Рх):
            плуг += 1
            if (conn.ЗначениеЗаполнено(r.ОР) or conn.ЗначениеЗаполнено(r.Кн)
                    or conn.ЗначениеЗаполнено(r.Дг) or conn.ЗначениеЗаполнено(r.Пн)):
                плуг_суб += 1
        else:
            дет += 1
            орз = conn.ЗначениеЗаполнено(r.ОР)
            кнз = conn.ЗначениеЗаполнено(r.Кн)
            дгз = conn.ЗначениеЗаполнено(r.Дг)
            пнз = conn.ЗначениеЗаполнено(r.Пн)
            ор += орз; кн += кнз; дг += дгз; пн += пнз
            if "обствен" in str(r.СтП):
                if not пнз or conn.XMLСтрока(r.Пн) != НАШЕ:
                    собств_плохо += 1
            субк = conn.XMLСтрока(r.ОР) if орз else "∅"
            ккн = conn.XMLСтрока(r.Кн) if кнз else "∅"
            кдг = conn.XMLСтрока(r.Дг) if дгз else "∅"
            ключи[(conn.XMLСтрока(r.Орг),
                    conn.XMLСтрока(r.Подр) if conn.ЗначениеЗаполнено(r.Подр) else "∅",
                    conn.XMLСтрока(r.Ст), conn.XMLСтрока(r.Src),
                    субк, ккн, кдг)] += 1
    дубл = sum(1 for c in ключи.values() if c > 1)
    return dict(дет=дет, плуг=плуг, ор=ор, кн=кн, дг=дг, пн=пн,
                плуг_суб=плуг_суб, собств_плохо=собств_плохо, дубл=дубл)


