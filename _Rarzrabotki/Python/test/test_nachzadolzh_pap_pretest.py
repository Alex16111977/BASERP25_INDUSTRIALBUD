# -*- coding: utf-8 -*-
"""Rule #-1 pre-тест Фаза 1 (ПАП): входящий долг в ПАП «Оплата труда» (−opening) + «Прибыли и убытки» (+opening)
делает плуг свёртки = 0, «Оплата труда» = А_ВзСС, Σ КО = 0."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0
TOL = 0.05
fails = []

# 1) opening per подразделение (ТЧ, агрегат по А_Подразделение)
q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ З.Подразделение.А_Подразделение КАК Подр, СУММА(З.Сумма) КАК Σ
ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате КАК З
СГРУППИРОВАТЬ ПО З.Подразделение.А_Подразделение
"""
opening = {}
for r in q.Выполнить().Выгрузить():
    opening[erp.XMLСтрока(r.Подр)] = f(r.Σ)
opening_tot = sum(opening.values())
print(f"opening: подразделений={len(opening)}, Σ={opening_tot:,.2f}")

# 2) текущий плуг per подразделение (дек 2025) — должен == opening_подр
print("\n=== Плуг(дек) per подразделение == opening per подразделение? ===")
q2 = erp.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ Рег.Подразделение КАК ПодрРеф, ПРЕДСТАВЛЕНИЕ(Рег.Подразделение) КАК Подр,
    СУММА(Рег.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Статья.Наименование = "Оплата труда" И Рег.Расхождение
    И Рег.Регистратор.Месяц = ДАТАВРЕМЯ(2025,12,1)
СГРУППИРОВАТЬ ПО Рег.Подразделение, ПРЕДСТАВЛЕНИЕ(Рег.Подразделение)
"""
plug_tot = 0.0; mism = 0
for r in q2.Выполнить().Выгрузить():
    k = erp.XMLСтрока(r.ПодрРеф); plug = f(r.КО); plug_tot += plug
    op = opening.get(k, 0.0)
    if abs(plug - op) > TOL:
        mism += 1
        print(f"   MISMATCH {str(r.Подр):<38} плуг={plug:>14,.2f} opening={op:>14,.2f}")
print(f"   Σ плуг={plug_tot:,.2f}  Σ opening={opening_tot:,.2f}  mismatch подразд.={mism}")
if abs(plug_tot - opening_tot) > TOL: fails.append("Σплуг != Σopening")
if mism: fails.append(f"{mism} подразделений плуг != opening")

# 3) новая «Оплата труда» per месяц = текущая КО − opening == А_ВзСС (детали)
print("\n=== Новая «Оплата труда» (= текущая − opening) == А_ВзСС детали? ===")
MONTHS = [("дек2025","ДАТАВРЕМЯ(2025,12,1)","ДАТАВРЕМЯ(2025,12,31,23,59,59)"),
          ("янв2026","ДАТАВРЕМЯ(2026,1,1)","ДАТАВРЕМЯ(2026,1,31,23,59,59)"),
          ("фев2026","ДАТАВРЕМЯ(2026,2,1)","ДАТАВРЕМЯ(2026,2,28,23,59,59)"),
          ("мар2026","ДАТАВРЕМЯ(2026,3,1)","ДАТАВРЕМЯ(2026,3,31,23,59,59)")]
for label, nm, end in MONTHS:
    qc = erp.NewObject("Запрос")
    qc.Текст = f"""ВЫБРАТЬ СУММА(Рег.СуммаКонечныйОстаток) КАК КО ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Статья.Наименование = "Оплата труда" И Рег.Регистратор.Месяц = {nm}"""
    cur = f(qc.Выполнить().Выгрузить()[0].КО)
    new_ot = cur - opening_tot
    # А_ВзСС детали (ПАП-формат) = -(А_ВзСС direct cumul)
    qa = erp.NewObject("Запрос")
    qa.Текст = f"""ВЫБРАТЬ СУММА(ВЫБОР КОГДА ВзСС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА ВзСС.СуммаВзаиморасчетов ИНАЧЕ -ВзСС.СуммаВзаиморасчетов КОНЕЦ) КАК С
        ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзСС ГДЕ ВзСС.Период <= {end}"""
    avzs_details = -f(qa.Выполнить().Выгрузить()[0].С)
    ok = abs(new_ot - avzs_details) <= TOL
    if not ok: fails.append(f"{label} new_ot != А_ВзСС")
    print(f"   {label}: текущая={cur:>14,.2f}  новая={new_ot:>14,.2f}  А_ВзСС детали={avzs_details:>14,.2f}  {'OK' if ok else 'FAIL'}")

# 4) баланс: добавляем «Оплата труда» −opening + «Прибыли и убытки» +opening → Σ КО без изменений
print("\n=== Баланс: контр в «Прибыли и убытки» сохраняет Σ КО=0 (арифм. инвариант) ===")
print(f"   «Оплата труда» Δ = −{opening_tot:,.2f}; «Прибыли и убытки» Δ = +{opening_tot:,.2f}; сумма Δ = 0 → Σ КО неизменна ✓")

print("\n" + "="*60)
print("PRE-TEST PASS — добавление в ПАП обнулит плуг, «Оплата труда»=А_ВзСС, баланс цел." if not fails
      else f"PRE-TEST FAIL: {fails}")
sys.exit(1 if fails else 0)
