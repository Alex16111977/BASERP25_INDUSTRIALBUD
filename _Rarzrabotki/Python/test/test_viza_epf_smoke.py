# -*- coding: utf-8 -*-
"""
Smoke внешней обработки А_ВизированиеЗаказовПоставщику.epf через win32com:
  1) завести заказ в контур визирования (НаВизировании) — чтобы журнал был не пуст;
  2) ВнешниеОбработки.Создать(path) → ЗаполнитьТаблицуЖурнала(режим 1) → строк >= 1;
  3) ЗаполнитьИсториюВиз(заказ) → строк >= 1.
Форму headless проверить нельзя — только серверные методы движка обработки.
"""
import win32com.client, sys, datetime

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\А_ВизированиеЗаказовПоставщику.epf"
MARKER = "ТЕСТ ВИЗИРОВАНИЯ (автоприёмка)"
def S(x): return erp.String(x)
ok = fail = 0
def check(n, got, exp):
    global ok, fail
    if got == exp: ok+=1; print(f"  [OK]   {n:<50} {got}")
    else: fail+=1; print(f"  [FAIL] {n:<50} получено={got!r} ожидалось={exp!r}")

print("="*90); print("SMOKE .epf А_ВизированиеЗаказовПоставщику"); print("="*90)
адм = erp.Пользователи.ТекущийПользователь()

# --- тестовые роли/схема/адресация (get-or-create) ---
def роль(имя, вид):
    r = erp.Справочники.А_РолиВизирования.НайтиПоНаименованию(имя, True)
    if not erp.ЗначениеЗаполнено(r):
        o = erp.Справочники.А_РолиВизирования.СоздатьЭлемент(); o.Наименование=имя; o.ВидАдресации=вид; o.Записать(); r=o.Ссылка
    return r
роль1 = роль("Тест Снабженец", erp.Перечисления.А_ВидыАдресацииРолейВизирования.ПоПодразделению)
роль2 = роль("Тест Финдиректор", erp.Перечисления.А_ВидыАдресацииРолейВизирования.ПоОрганизации)
схема = erp.Справочники.А_СхемыВизирования.НайтиПоНаименованию("Тестовая схема", True)
if not erp.ЗначениеЗаполнено(схема):
    o=erp.Справочники.А_СхемыВизирования.СоздатьЭлемент(); o.Наименование="Тестовая схема"
    o.Роли.Добавить().Роль=роль1; o.Роли.Добавить().Роль=роль2; o.Записать(); схема=o.Ссылка

# --- заказ в контуре (get-or-create по маркеру) ---
q=erp.NewObject("Запрос")
q.Text="ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссыл ИЗ Документ.ЗаказПоставщику КАК Т ГДЕ ВЫРАЗИТЬ(Т.Комментарий КАК СТРОКА(200))=&М И НЕ Т.ПометкаУдаления"
q.SetParameter("М", MARKER)
r=q.Execute().Выгрузить()
if r.Количество():
    заказ=r.Получить(0).Ссыл
else:
    qd=erp.NewObject("Запрос")
    qd.Text="ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссыл ИЗ Документ.ЗаказПоставщику КАК Т ГДЕ Т.Проведен И НЕ Т.ПометкаУдаления И Т.Ссылка В (ВЫБРАТЬ Тов.Ссылка ИЗ Документ.ЗаказПоставщику.Товары КАК Тов) УПОРЯДОЧИТЬ ПО Т.Дата УБЫВ"
    донор=qd.Execute().Выгрузить().Получить(0).Ссыл
    o=донор.ПолучитьОбъект().Скопировать(); o.Дата=datetime.datetime.now(); o.Комментарий=MARKER
    o.Записать(erp.РежимЗаписиДокумента.Проведение); заказ=o.Ссылка
об=заказ.ПолучитьОбъект()
print(f"  тестовый заказ: {S(заказ)} | виза={S(об.А_Виза_Состояние).strip()}")

# правило схемы + адресация (get-or-create)
рс=erp.РегистрыСведений.А_ОпределениеСхемыВизирования.СоздатьМенеджерЗаписи()
рс.Подразделение=об.Подразделение; рс.Организация=об.Организация; рс.Сумма=0; рс.СхемаВизирования=схема; рс.Приоритет=1; рс.Записать(True)
for рл,об2 in ((роль1,об.Подразделение),(роль2,об.Организация)):
    м=erp.РегистрыСведений.А_ИдентификацияВизирующихПоРолям.СоздатьМенеджерЗаписи()
    м.Роль=рл; м.Объект=об2; м.Пользователь=адм; м.Записать(True)

# привести заказ в НаВизировании (сброс → отправка)
об=заказ.ПолучитьОбъект()
об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Черновик); об.Записать(erp.РежимЗаписиДокумента.Проведение)
об=заказ.ПолучитьОбъект()
рез=об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Утвержден)
об.Записать(erp.РежимЗаписиДокумента.Проведение)
об=заказ.ПолучитьОбъект()
check("заказ переведён в НаВизировании", S(об.А_Виза_Состояние).strip(), "На визировании")

# --- SMOKE .epf ---
print("\n[.epf] ВнешниеОбработки.Создать + методы движка")
try:
    обр = erp.ВнешниеОбработки.Создать(EPF, False)
    print(f"  [OK]   Создать(.epf) — объект получен")
    ok+=1
except Exception as e:
    m=e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else e
    print(f"  [FAIL] Создать(.epf): {str(m)[:120]}"); fail+=1; обр=None

if обр is not None:
    отбор = erp.NewObject("Структура")
    отбор.Вставить("РежимОчереди", 0)
    отбор.Вставить("ТекущийПользователь", адм)
    тз = обр.ЗаполнитьТаблицуЖурнала(отбор)
    check("ЗаполнитьТаблицуЖурнала режим 0 — есть строки", тз.Количество() >= 1, True)

    отбор1 = erp.NewObject("Структура")
    отбор1.Вставить("РежимОчереди", 1)
    отбор1.Вставить("ТекущийПользователь", адм)
    тз1 = обр.ЗаполнитьТаблицуЖурнала(отбор1)
    check("режим 1 (мне на визу) — наш заказ виден", тз1.Количество() >= 1, True)

    ист = обр.ЗаполнитьИсториюВиз(заказ)
    check("ЗаполнитьИсториюВиз — есть строки", ист.Количество() >= 1, True)
    print(f"         (журнал строк={тз.Количество()}, история строк={ист.Количество()})")

# уборка: заказ распровести (движений не оставить)
об=заказ.ПолучитьОбъект(); об.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)

print("\n"+"="*90); print(f"ИТОГО OK={ok} FAIL={fail}"); print("="*90)
sys.exit(1 if fail else 0)
