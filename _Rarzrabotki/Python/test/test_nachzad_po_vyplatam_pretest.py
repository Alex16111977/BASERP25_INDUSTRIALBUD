# -*- coding: utf-8 -*-
"""Pretest (Rule #-1): 3 запроса обработки А_НачальнаяЗадолженностьПоЗарплатеСозданнаяПоВыплатам.
Q1 — отбор ведомостей (Дата в месяце ведомостей, ПериодРегистрации = месяц остатков, Проведен);
Q2 — строки ТЧ Зарплата по ведомостям, группировка по ключу аналитики;
Q3 — остаток ЗКВ records-level на границу по ключу, исключая регистратор-цель.
Грабли: алиас "В" зарезервирован -> "Вед"."""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

FAILED = False

def run(name, text):
    global FAILED
    q = erp.NewObject("Запрос")
    q.Text = text
    try:
        t = q.Execute().Выгрузить()
        print(f"[OK] {name}: строк={t.Количество()}")
        return t
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"[FAIL] {name}: {msg}")
        FAILED = True
        return None

# Q1: отбор ведомостей
t1 = run("Q1 ведомости", """ВЫБРАТЬ
	Вед.Ссылка КАК Ведомость,
	Вед.Дата КАК Дата,
	Вед.Номер КАК Номер,
	Вед.Организация КАК Организация,
	Вед.СуммаПоДокументу КАК СуммаПоДокументу
ИЗ
	Документ.ВедомостьНаВыплатуЗарплатыВКассу КАК Вед
ГДЕ
	Вед.Дата МЕЖДУ ДАТАВРЕМЯ(2025, 12, 1) И ДАТАВРЕМЯ(2025, 12, 31, 23, 59, 59)
	И Вед.ПериодРегистрации = ДАТАВРЕМЯ(2025, 11, 1)
	И Вед.Проведен
УПОРЯДОЧИТЬ ПО
	Вед.Дата,
	Вед.Номер""")

# Q2: строки превью (ключ аналитики, per ведомость)
t2 = run("Q2 строки ТЧ", """ВЫБРАТЬ
	З.Ссылка КАК Ведомость,
	З.Сотрудник КАК Сотрудник,
	З.ФизическоеЛицо КАК ФизическоеЛицо,
	З.Подразделение КАК Подразделение,
	З.ПериодВзаиморасчетов КАК ПериодВзаиморасчетов,
	З.ГруппаУчетаНачислений КАК ГруппаУчетаНачислений,
	СУММА(З.КВыплате) КАК СуммаПоВедомостям
ИЗ
	Документ.ВедомостьНаВыплатуЗарплатыВКассу.Зарплата КАК З
ГДЕ
	З.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025, 12, 1) И ДАТАВРЕМЯ(2025, 12, 31, 23, 59, 59)
	И З.Ссылка.ПериодРегистрации = ДАТАВРЕМЯ(2025, 11, 1)
	И З.Ссылка.Проведен
СГРУППИРОВАТЬ ПО
	З.Ссылка,
	З.Сотрудник,
	З.ФизическоеЛицо,
	З.Подразделение,
	З.ПериодВзаиморасчетов,
	З.ГруппаУчетаНачислений
УПОРЯДОЧИТЬ ПО
	Ведомость,
	Сотрудник""")

# Q3: остатки ЗКВ records-level на 30.11 по ключу, исключая регистратор-цель (тут — пустая ссылка)
t3 = run("Q3 остатки по ключу", """ВЫБРАТЬ
	Д.ФизическоеЛицо КАК ФизическоеЛицо,
	Д.Сотрудник КАК Сотрудник,
	Д.Подразделение КАК Подразделение,
	Д.ПериодВзаиморасчетов КАК ПериодВзаиморасчетов,
	Д.ГруппаУчетаНачислений КАК ГруппаУчетаНачислений,
	СУММА(ВЫБОР
			КОГДА Д.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
				ТОГДА Д.СуммаКВыплате
			ИНАЧЕ -Д.СуммаКВыплате
		КОНЕЦ) КАК Остаток
ИЗ
	РегистрНакопления.ЗарплатаКВыплате КАК Д
ГДЕ
	Д.Период <= ДАТАВРЕМЯ(2025, 11, 30, 23, 59, 59)
	И Д.Регистратор <> ЗНАЧЕНИЕ(Документ.НачальнаяЗадолженностьПоЗарплате.ПустаяСсылка)
	И Д.ФизическоеЛицо В
		(ВЫБРАТЬ РАЗЛИЧНЫЕ З.ФизическоеЛицо
		ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу.Зарплата КАК З
		ГДЕ З.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2025, 12, 1) И ДАТАВРЕМЯ(2025, 12, 31, 23, 59, 59)
			И З.Ссылка.ПериодРегистрации = ДАТАВРЕМЯ(2025, 11, 1)
			И З.Ссылка.Проведен)
СГРУППИРОВАТЬ ПО
	Д.ФизическоеЛицо,
	Д.Сотрудник,
	Д.Подразделение,
	Д.ПериодВзаиморасчетов,
	Д.ГруппаУчетаНачислений""")

# Сводный контроль: дефицит = МИН(СуммаПоВедомостям, МАКС(0, -Остаток)) по ключам
if t2 is not None and t3 is not None:
    ost = {}
    for i in range(t3.Количество()):
        r = t3.Получить(i)
        key = (erp.String(r.ФизическоеЛицо), erp.String(r.Сотрудник), erp.String(r.Подразделение),
               str(r.ПериодВзаиморасчетов), erp.String(r.ГруппаУчетаНачислений))
        ost[key] = ost.get(key, 0.0) + float(r.Остаток or 0)
    s_ved = 0.0
    s_fill = 0.0
    covered = 0
    for i in range(t2.Количество()):
        r = t2.Получить(i)
        key = (erp.String(r.ФизическоеЛицо), erp.String(r.Сотрудник), erp.String(r.Подразделение),
               str(r.ПериодВзаиморасчетов), erp.String(r.ГруппаУчетаНачислений))
        sv = float(r.СуммаПоВедомостям or 0)
        deficit = max(0.0, -ost.get(key, 0.0))
        fill = min(sv, deficit)
        # последовательное покрытие: уменьшаем дефицит ключа
        ost[key] = ost.get(key, 0.0) + fill
        s_ved += sv
        s_fill += fill
        if fill < sv - 0.005:
            covered += 1
    print(f"  Σ по ведомостям = {s_ved:,.2f}; Σ к заполнению = {s_fill:,.2f}; строк с частичным/нулевым заполнением = {covered}")

print("PRETEST: " + ("FAIL" if FAILED else "PASS"))
sys.exit(1 if FAILED else 0)
