def extract_query(src):
    """Из функции ПолучитьОбъединенныеДанные вытащить чистый текст запроса (Запрос.Текст = "...";)."""
    fseg = re.search(r'Функция\s+ПолучитьОбъединенныеДанные.*?КонецФункции', src, re.S).group(0)
    raw = re.search(r'Запрос\.Текст\s*=\s*"(.*?)";\s*Запрос\.УстановитьПараметр', fseg, re.S).group(1)
    lines = raw.split("\n")
    out = [lines[0]] + [re.sub(r'^\t\|', '', ln) for ln in lines[1:]]
    return "\n".join(out).replace('""', '"')


def to_query_literal(clean):
    """Чистый текст → BSL-литерал \t"..." с \t| continuation и "";-экранированием."""
    esc = clean.replace('"', '""')
    lines = esc.split("\n")
    body = '\t"' + lines[0] + "\n"
    for ln in lines[1:]:
        body += "\t|" + ln + "\n"
    return body.rstrip("\n") + '";'


