# Перевіряємо чи Дубінько і Старіков (ФізОсоби з Удержания) мають рядки в Начисления.
# Якщо ні — можливо проблема у тому, що регістр Взаиморасчеты вимагає нарахування
# перед утриманням.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Знайти НЗ
q = erp.NewObject("Запрос")
q.Text = (
    'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка '
    'ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д '
    'ГДЕ Д.Номер = "000000001" И НЕ Д.ПометкаУдаления'
)
sel = q.Execute().Выбрать()
sel.Следующий()
dok_ref = sel.Ссылка

# Перезаписати НЗ
obj = dok_ref.ПолучитьОбъект()
obj.СоздатьДокументНачисления()

# Знайти НЗ
q2 = erp.NewObject("Запрос")
q2.Text = (
    'ВЫБРАТЬ ПЕРВЫЕ 1 НЗ.Ссылка '
    'ИЗ Документ.НачислениеЗарплаты КАК НЗ '
    'ГДЕ НЗ.А_ДокОтражениеЗПпоКазне.Номер = "000000001" И НЕ НЗ.ПометкаУдаления '
    'УПОРЯДОЧИТЬ ПО НЗ.Дата УБЫВ'
)
sel2 = q2.Execute().Выбрать()
sel2.Следующий()
нз = sel2.Ссылка.ПолучитьОбъект()

print(f"НЗ: {S(sel2.Ссылка)}")
print(f"Начисления: {нз.Начисления.Количество()}, Удержания: {нз.Удержания.Количество()}")

# Перевірити: чи є Дубінько і Старіков у Начисления
targets = ["Дубінько", "Старіков"]
for target in targets:
    n_nach = 0
    for i in range(нз.Начисления.Количество()):
        r = нз.Начисления.Получить(i)
        if target in S(r.Сотрудник):
            n_nach += 1
    n_ud = 0
    for i in range(нз.Удержания.Количество()):
        r = нз.Удержания.Получить(i)
        if target in S(r.ФизическоеЛицо):
            n_ud += 1
    n_ndfl = 0
    for i in range(нз.НДФЛ.Количество()):
        r = нз.НДФЛ.Получить(i)
        if target in S(r.ФизическоеЛицо):
            n_ndfl += 1
    n_vzn = 0
    for i in range(нз.ВзносыФОТ.Количество()):
        r = нз.ВзносыФОТ.Получить(i)
        if target in S(r.ФизическоеЛицо):
            n_vzn += 1
    print(f"\n{target}: Начисления={n_nach}, Удержания={n_ud}, НДФЛ={n_ndfl}, ВзносыФОТ={n_vzn}")

# Знайти в джерелах А_ОтражениеЗПпоКазне
print("\n--- Джерела А_ОтражениеЗПпоКазне ---")
obj_dok = dok_ref.ПолучитьОбъект()
for target in targets:
    nach_upr = 0
    for i in range(obj_dok.НачисленияУпр.Количество()):
        r = obj_dok.НачисленияУпр.Получить(i)
        if target in S(r.ФизЛицо):
            nach_upr += 1
    ud_upr = 0
    for i in range(obj_dok.УдержанияУпр.Количество()):
        r = obj_dok.УдержанияУпр.Получить(i)
        if target in S(r.ФизЛицо):
            ud_upr += 1
    nach_zp = 0
    for i in range(obj_dok.НачисленнаяЗарплатаИВзносыПоФизлицам.Количество()):
        r = obj_dok.НачисленнаяЗарплатаИВзносыПоФизлицам.Получить(i)
        if target in S(r.ФизическоеЛицо):
            nach_zp += 1
    print(f"  {target}: НачисленияУпр={nach_upr}, УдержанияУпр={ud_upr}, НачисленнаяЗарплатаИВзносыПоФизлицам={nach_zp}")

# Конкретний рядок 66 в регістрі
# 63 Начисления + 3 Удержания = 66
# Тобто 3-й рядок Удержания = Дубінько 3-й алимент
if нз.Удержания.Количество() >= 3:
    r3 = нз.Удержания.Получить(2)
    print(f"\n3-й рядок Удержания (= рядок 66 реєстра):")
    print(f"  ФизическоеЛицо: {S(r3.ФизическоеЛицо)}")
    print(f"  Удержание: {S(r3.Удержание)}")
    print(f"  Результат: {S(r3.Результат)}")
    print(f"  Получатель: {S(r3.Получатель)}")
