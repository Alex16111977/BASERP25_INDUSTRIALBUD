"""Структуры регистров для записи: ПАП (измерения/ресурсы), Хозрасчетный, субконто счёта 661 и 00."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

md = erp.Метаданные

print("=== ПАП (РегистрНакопления.ПрочиеАктивыПассивы) ===")
рег = md.РегистрыНакопления.Найти("ПрочиеАктивыПассивы")
print("  Измерения:", [d.Имя for d in рег.Измерения])
print("  Ресурсы:  ", [r.Имя for r in рег.Ресурсы])
print("  Реквизиты:", [a.Имя for a in рег.Реквизиты])

print("\n=== Хозрасчетный (РегистрБухгалтерии) ===")
хоз = md.РегистрыБухгалтерии.Найти("Хозрасчетный")
print("  Измерения:", [d.Имя for d in хоз.Измерения])
print("  Ресурсы:  ", [r.Имя for r in хоз.Ресурсы])
print("  Реквизиты:", [a.Имя for a in хоз.Реквизиты])
print("  Признаки учёта субконто:", хоз.ПризнакиУчетаСубконто.Количество() if hasattr(хоз,'ПризнакиУчетаСубконто') else '?')

# счёт 661 и 00 — субконто
print("\n=== Счета 661 / 00: виды субконто ===")
q = erp.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ Ссылка КАК С, Код, Наименование, Вид, Забалансовый
ИЗ ПланСчетов.Хозрасчетный ГДЕ Код В ("661","00")"""
for r in q.Выполнить().Выгрузить():
    сч = r.С
    виды = []
    for вс in сч.ВидыСубконто:
        виды.append(вс.ВидСубконто.Наименование)
    print(f"  Счёт {str(r.Код):<5} '{r.Наименование}' Вид={r.Вид} Забаланс={r.Забалансовый}")
    print(f"     Субконто: {виды}")

# Источник ПустаяСсылка enum
