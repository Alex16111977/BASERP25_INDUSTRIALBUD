print("  Перечисление.ИсточникиУправленческогоБаланса существует:",
      md.Перечисления.Найти("ИсточникиУправленческогоБаланса") is not None)

# Статьи ПАП: Оплата труда, Прибыли и убытки
print("\n=== Статьи ПВХ: Оплата труда / Прибыли и убытки ===")
