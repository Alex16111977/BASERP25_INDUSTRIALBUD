def сформировать(имя_сценария, дата_нач, дата_кон):
    """Программно собирает отчёт ВедомостьРасчетовСПартнерами и возвращает суммы."""
    print(f"\n{'='*100}")
    print(f"СЦЕНАРИЙ {имя_сценария}")
    print(f"  ДатаНачала: {'(пусто)' if дата_нач is None else дата_нач.strftime('%d.%m.%Y')}")
    print(f"  ДатаОкончания: {дата_кон.strftime('%d.%m.%Y')}")
    print(f"{'='*100}")

    отчёт = erp.Отчеты.ВедомостьРасчетовСПартнерами.Создать()
    кн = отчёт.КомпоновщикНастроек

    # Установка параметра «Период»
    параметр_период = кн.Настройки.ПараметрыДанных.Элементы.Найти("Период")
    период = erp.NewObject("СтандартныйПериод")
    период.ДатаНачала    = дата_нач if дата_нач else erp.NewObject("Дата", 0, 0, 0)  # Дата(0,0,0) = пусто
    период.ДатаОкончания = дата_кон
    параметр_период.Значение = период
    параметр_период.Использование = True

    # Орг и Контрагент — отбор
    отбор = кн.Настройки.Отбор
    orgEl = отбор.Элементы.Добавить(erp.NewObject("Тип", "ЭлементОтбораКомпоновкиДанных"))
    orgEl.ЛевоеЗначение = erp.NewObject("ПолеКомпоновкиДанных", "Организация")
    orgEl.ВидСравнения = erp.ВидСравненияКомпоновкиДанных.Равно
    orgEl.ПравоеЗначение = орг
    orgEl.Использование = True

    contrEl = отбор.Элементы.Добавить(erp.NewObject("Тип", "ЭлементОтбораКомпоновкиДанных"))
    contrEl.ЛевоеЗначение = erp.NewObject("ПолеКомпоновкиДанных", "Контрагент")
    contrEl.ВидСравнения = erp.ВидСравненияКомпоновкиДанных.Равно
    contrEl.ПравоеЗначение = контр
    contrEl.Использование = True

    # Валюта взаиморасчётов
    if валюта:
        valEl = отбор.Элементы.Добавить(erp.NewObject("Тип", "ЭлементОтбораКомпоновкиДанных"))
        valEl.ЛевоеЗначение = erp.NewObject("ПолеКомпоновкиДанных", "Валюта")
        valEl.ВидСравнения = erp.ВидСравненияКомпоновкиДанных.Равно
        valEl.ПравоеЗначение = валюта
        valEl.Использование = True

    # Запуск компоновки
    табДок = erp.NewObject("ТабличныйДокумент")
    данныеРасшифровки = erp.NewObject("ДанныеРасшифровкиКомпоновкиДанных")
    try:
        отчёт.ПриКомпоновкеРезультата(табДок, данныеРасшифровки, True)
    except Exception as e:
        print(f"FAIL ПриКомпоновкеРезультата: {e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else e}")
        return None
    print(f"   ОК. Высота отчёта: {табДок.ВысотаТаблицы} строк, ширина {табДок.ШиринаТаблицы} столбцов")

    # Вытащим суммы из отчёта — ищем строки с числами
    итог_но, итог_ув, итог_ум, итог_ко = 0.0, 0.0, 0.0, 0.0
    for row in range(1, табДок.ВысотаТаблицы + 1):
        # Попытаемся прочитать строки и поискать "Итого"
        first_cell_text = ""
        try:
            first_cell = табДок.Область(row, 1, row, 1)
            first_cell_text = str(first_cell.Текст or "")
        except:
            pass
        if "тог" in first_cell_text.lower() or "сего" in first_cell_text.lower():
            # печатаем эту строку
            row_text = []
            for col in range(1, табДок.ШиринаТаблицы + 1):
                try:
                    cell = табДок.Область(row, col, row, col)
                    txt = str(cell.Текст or "").strip()
                    if txt:
                        row_text.append(f"col{col}={txt}")
                except:
                    pass
            print(f"   row{row}: {' | '.join(row_text)}")

    # Сохранить отчёт в файл для просмотра
    import os
    out_path = f"C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\test\\out_vedomost_{имя_сценария}.xlsx"
    try:
        if os.path.exists(out_path):
            os.remove(out_path)
        табДок.Записать(out_path, erp.ТипФайлаТабличногоДокумента.XLSX)
        print(f"   Сохранено: {out_path}")
    except Exception as e:
        print(f"   Не удалось сохранить: {e}")

    return табДок

# СЦЕНАРИЙ A: ДатаНачала пустая (как на скриншоте финансиста)
сформировать("A_empty_start", None, datetime.datetime(2025, 12, 31, 23, 59, 59))

# СЦЕНАРИЙ B: ДатаНачала = 01.01.2025
