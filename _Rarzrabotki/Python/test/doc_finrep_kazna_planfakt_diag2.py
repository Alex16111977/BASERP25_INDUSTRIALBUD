import sys
sys.stdout.reconfigure(encoding="utf-8")
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"')
S = conn.String

гр_расход = conn.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("1В")
направление = conn.Справочники.Направления.НайтиПоНаименованию("Производство", True)

q = conn.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	БДДС.Подразделение.Наименование КАК ПодрИмя,
	БДДС.СтатьяДвиженияДенежныхСредств.Наименование КАК СтатьяИмя,
	БДДС.Регистратор КАК Регистратор,
	ПРЕДСТАВЛЕНИЕ(БДДС.Регистратор) КАК РегистраторТекст,
	БДДС.Период КАК Период,
	БДДС.НаправлениеДДС КАК НаправлениеДДС,
	ПРЕДСТАВЛЕНИЕ(БДДС.НаправлениеДДС) КАК НаправлениеТекст,
	БДДС.СуммаПриход КАК СуммаПриход,
	БДДС.СуммаРасход КАК СуммаРасход,
	БДДС.ПланФакт КАК ПланФакт,
	ПРЕДСТАВЛЕНИЕ(БДДС.ПланФакт) КАК ПланФактТекст
ИЗ
	РегистрНакопления.БДДС КАК БДДС
ГДЕ
	БДДС.Период МЕЖДУ ДАТАВРЕМЯ(2026,8,1,0,0,0) И ДАТАВРЕМЯ(2026,8,14,23,59,59)
	И БДДС.Направление = &Направление
	И БДДС.СтатьяДвиженияДенежныхСредств В ИЕРАРХИИ (&ГруппаРасход)
	И (БДДС.Подразделение.Наименование ПОДОБНО "МД ПРООН%"
		ИЛИ БДДС.Подразделение.Наименование ПОДОБНО "МД ООН Админ%")
УПОРЯДОЧИТЬ ПО
	ПодрИмя, СтатьяИмя, Период
"""
q.УстановитьПараметр("ГруппаРасход", гр_расход)
q.УстановитьПараметр("Направление", направление)
r = q.Execute().Выгрузить()
print(f"строк: {r.Количество()}")
for i in range(r.Количество()):
    row = r.Получить(i)
    знак = -1 if "Расход" in S(row.НаправлениеТекст) else 1
    сумма = знак * (float(row.СуммаПриход) + float(row.СуммаРасход))
    print(f"{S(row.ПодрИмя)[:24]:24} | {S(row.СтатьяИмя)[:34]:34} | {S(row.РегистраторТекст)[:55]:55} | ПФ={S(row.ПланФактТекст):6} | {сумма:>12,.2f}")
