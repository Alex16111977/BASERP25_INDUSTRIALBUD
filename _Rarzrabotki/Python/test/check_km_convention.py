# -*- coding: utf-8 -*-
"""
Контроль конвенции модулей по проектам МД IRS 2026 (другие СС не рассматриваем).

Инвариант:
    Д.КоличествоМодулей = СС.А_КоличествоМодулей = M   (15 м -> 1, 30 м -> 2)
    МАКС(НомерМодуля)   = M
    ПланЧасыМодуля × M  = СС.Работы.Количество          (делим на МОДУЛИ, не на ДОМА)

Запускать после каждой загрузки снимка (регламент §7).
"""
import sys
sys.stdout.reconfigure(encoding='utf-8')
import win32com.client

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def запрос(текст, **п):
    z = erp.NewObject("Запрос")
    for k, v in п.items():
        z.УстановитьПараметр(k, v)
    z.Текст = текст
    return z.Execute().Выгрузить()


ОТБОР = 'И Д.СтруктураСебестоимости.Наименование ПОДОБНО "МД IRS 2026%" '

print("=== Паспорт СС и документов (МД IRS 2026) ===")
т = запрос(
    "ВЫБРАТЬ Д.СтруктураСебестоимости.Наименование КАК СС, "
    "Д.СтруктураСебестоимости.А_КоличествоМодулей КАК МодулейСС, "
    "Д.СтруктураСебестоимости.КоличествоДомов КАК ДомовСС, "
    "МИНИМУМ(Д.КоличествоМодулей) КАК КМмин, МАКСИМУМ(Д.КоличествоМодулей) КАК КМмакс, "
    "МАКСИМУМ(Т.НомерМодуля) КАК МаксНомерМодуля, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Ссылка) КАК Доков "
    "ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д "
    "ЛЕВОЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей.Работы КАК Т ПО Т.Ссылка = Д.Ссылка "
    "ГДЕ НЕ Д.ПометкаУдаления " + ОТБОР +
    "СГРУППИРОВАТЬ ПО Д.СтруктураСебестоимости.Наименование, "
    "Д.СтруктураСебестоимости.А_КоличествоМодулей, Д.СтруктураСебестоимости.КоличествоДомов "
    "УПОРЯДОЧИТЬ ПО СС")
все_ок = True
for i in range(т.Количество()):
    s = т.Получить(i)
    M_сс = max(int(s.МодулейСС or 0), 1)
    км_мин, км_макс, макс_нм = int(s.КМмин), int(s.КМмакс), int(s.МаксНомерМодуля or 0)
    ок = км_мин == км_макс == M_сс and макс_нм == M_сс
    все_ок = все_ок and ок
    print(f"   {str(s.СС)[:50]:50} | СС: домів={int(s.ДомовСС or 0)} модулів={M_сс} | "
          f"доків={s.Доков} КМ={км_мин}..{км_макс} МАКС(НомерМодуля)={макс_нм} "
          f"{'OK' if ок else '❌ РОЗБІЖНІСТЬ'}")

print("\n=== ПланЧасыМодуля × КоличествоМодулей == норма СС ? (допуск 0,01) ===")
# ⚠ Допуск обязателен: ПланЧасыМодуля хранится с 4 знаками, поэтому норма/M округляется и
# обратное умножение не даёт точного равенства. В языке запросов 1С нет АБС() -> два неравенства.
т = запрос(
    "ВЫБРАТЬ Д.СтруктураСебестоимости.Наименование КАК СС, "
    "МАКСИМУМ(Д.КоличествоМодулей) КАК M, КОЛИЧЕСТВО(*) КАК Строк, "
    "СУММА(ВЫБОР КОГДА Т.ПланЧасыМодуля * Д.КоличествоМодулей - ЕСТЬNULL(Р.Количество, -1) > 0.01 "
    "  ИЛИ Т.ПланЧасыМодуля * Д.КоличествоМодулей - ЕСТЬNULL(Р.Количество, -1) < -0.01 "
    "  ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Плохих "
    "ИЗ Документ.А_ВыполнениеРаботМодулей.Работы КАК Т "
    "ЛЕВОЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей КАК Д ПО Д.Ссылка = Т.Ссылка "
    "ЛЕВОЕ СОЕДИНЕНИЕ Справочник.А_СтруктураСебестоимости.Работы КАК Р "
    "  ПО Р.Ссылка = Д.СтруктураСебестоимости И Р.Работа = Т.Работа "
    "ГДЕ НЕ Д.ПометкаУдаления " + ОТБОР +
    "СГРУППИРОВАТЬ ПО Д.СтруктураСебестоимости.Наименование УПОРЯДОЧИТЬ ПО СС")
for i in range(т.Количество()):
    s = т.Получить(i)
    плох = int(s.Плохих or 0)
    все_ок = все_ок and плох == 0
    print(f"   {str(s.СС)[:50]:50} M={int(s.M)} строк={s.Строк:>4} "
          f"розбіжностей={плох} {'OK' if плох == 0 else '❌'}")

print("\n=== Обороты РН (EV) по домах ===")
т = запрос("ВЫБРАТЬ Т.СтруктураСебестоимости.Наименование КАК СС, "
           "Т.Подразделение.Наименование КАК Подр, СУММА(Т.ЧасыВыполнение) КАК Ч "
           "ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т "
           'ГДЕ Т.СтруктураСебестоимости.Наименование ПОДОБНО "МД IRS 2026%" '
           "СГРУППИРОВАТЬ ПО Т.СтруктураСебестоимости.Наименование, Т.Подразделение.Наименование "
           "УПОРЯДОЧИТЬ ПО СС, Подр")
итоги = {}
for i in range(т.Количество()):
    s = т.Получить(i)
    итоги.setdefault(str(s.СС), []).append((str(s.Подр), float(s.Ч)))
for сс, дома in итоги.items():
    print(f"   {сс[:50]:50} разом {sum(ч for _, ч in дома):9.2f}")
    for подр, ч in дома:
        print(f"      {подр[:46]:46} {ч:9.2f}")

print("\n" + ("✔ КОНВЕНЦИЯ СОБЛЮДЕНА (МД IRS 2026)" if все_ок else "❌ ЕСТЬ РАСХОЖДЕНИЯ — СМОТРЕТЬ ВЫШЕ"))
sys.exit(0 if все_ок else 1)
