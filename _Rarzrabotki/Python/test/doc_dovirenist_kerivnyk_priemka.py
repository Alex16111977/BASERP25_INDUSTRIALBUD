def печать(док, ид):
    мас = bh.NewObject("Массив")
    мас.Добавить(док)
    колл = bh.УправлениеПечатью.ПодготовитьКоллекциюПечатныхФорм(ид)
    пв = bh.УправлениеПечатью.ПодготовитьСтруктуруПараметровВывода()
    bh.Документы.Доверенность.Печать(мас, bh.NewObject("Структура"), колл, bh.NewObject("СписокЗначений"), пв)
    путь = os.path.join(tempfile.gettempdir(), f"dov_priemka_{ид}_{S(док.Номер)}.xlsx")
    колл.Получить(0).ТабличныйДокумент.Записать(путь, bh.ТипФайлаТабличногоДокумента.XLSX)
    return путь


def ячейки(путь):
    ws = openpyxl.load_workbook(путь).worksheets[0]
    return {c.coordinate: str(c.value).strip() for row in ws.iter_rows() for c in row if c.value not in (None, "")}


def подвал(яч):
    """(подпись руководителя, ФИО руководителя, ФИО главбуха) — строка с «Головний бухгалтер» и ближайшая строка выше."""
    строки = {}
    for к, т in яч.items():
        р = int("".join(ч for ч in к if ч.isdigit()))
        строки.setdefault(р, {})["".join(ч for ч in к if ч.isalpha())] = т
    рг = max(р for р, кол in строки.items() if кол.get("B") == "Головний бухгалтер")
    рр = max(р for р in строки if р < рг and строки[р].get("B"))
    return строки[рр].get("B", ""), строки[рр].get("K", ""), строки[рг].get("K", "")


