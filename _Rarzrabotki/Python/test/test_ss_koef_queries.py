TEXT = """ВЫБРАТЬ
	КоэффициентыПересчета.Ссылка КАК ОбщееНазвание,
	КоэффициентыПересчета.ЕдиницаСС КАК ЕдиницаСС,
	КоэффициентыПересчета.НоменклатураСС КАК НоменклатураСС,
	КоэффициентыПересчета.Коэффициент КАК Коэффициент
ИЗ
	Справочник.ОбщиеНазванияНоменклатуры.КоэффициентыПересчета КАК КоэффициентыПересчета
ГДЕ
	КоэффициентыПересчета.Ссылка В(&ОбщиеНазвания)
;

////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ
	ОбщиеНазвания.Ссылка КАК ОбщееНазвание,
	ОбщиеНазвания.Единица КАК Единица,
	ЕСТЬNULL(ОбщиеНазвания.Единица.Наименование, "") КАК ЕдиницаНаименование
ИЗ
	Справочник.ОбщиеНазванияНоменклатуры КАК ОбщиеНазвания
ГДЕ
	ОбщиеНазвания.Ссылка В(&ОбщиеНазвания)"""

q0 = b.NewObject("Запрос")
q0.Text = """ВЫБРАТЬ РАЗЛИЧНЫЕ К.ОбщееНазвание КАК ОН ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Наименование ПОДОБНО "%IR%15%" """
arr = b.NewObject("Массив")
t0 = q0.Execute().Выгрузить()
for i in range(t0.Количество()):
    arr.Добавить(t0.Получить(i).ОН)

q = b.NewObject("Запрос")
q.Text = TEXT
q.SetParameter("ОбщиеНазвания", arr)
fails = 0
try:
    res = q.ВыполнитьПакет()
    rules, units = res.Получить(0).Выгрузить(), res.Получить(1).Выгрузить()
    print(f"OK правил={rules.Количество()} названий={units.Количество()} (ожидание названий={arr.Количество()})")
    if units.Количество() != arr.Количество():
        fails += 1
    for i in range(min(5, units.Количество())):
        s = units.Получить(i)
        print('  ', s.ОбщееНазвание, '|', s.ЕдиницаНаименование)
except Exception as e:
    fails += 1
    print("FAIL:", e.excepinfo[2] if getattr(e, 'excepinfo', None) else e)
print("PASS" if not fails else f"FAILS={fails}")
sys.exit(1 if fails else 0)
