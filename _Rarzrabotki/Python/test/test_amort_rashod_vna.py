# -*- coding: utf-8 -*-
"""Тест: списання ПрочиеРасходы ВНА через АмортизацияОС.

Кроки:
1. Знайти проведений АмортизацияОС
2. Запитати ПрочиеРасходы.Остатки() по статтях ВНА
3. Прочитати існуючий НаборЗаписей
4. Додати РАСХОД записи (з правильним ВидДвижения через перерахування)
5. Перевірити залишок = 0
"""
import win32com.client, datetime
v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String
VF = conn.ValueIsFilled

# ============================================================
# DRY_RUN = True  -> тільки показує що буде зроблено
# DRY_RUN = False -> реально записує РАСХОД
DRY_RUN = True
# ============================================================

# === 0. Отримати значення перерахувань ===
print("=== 0. Значення перерахувань ===")
q0 = conn.NewObject("Запрос")
q0.Text = """ВЫБРАТЬ
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) КАК Расход,
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) КАК Приход"""
res0 = q0.Execute().Select()
res0.Next()
VD_RASHOD = res0.Расход
VD_PRIHOD = res0.Приход
print(f"  Приход: {S(VD_PRIHOD)} (XML: {conn.XMLString(VD_PRIHOD)})")
print(f"  Расход: {S(VD_RASHOD)} (XML: {conn.XMLString(VD_RASHOD)})")

# === 1. Знайти АмортизацияОС ===
print("\n=== 1. Пошук АмортизацияОС ===")
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка, Д.Дата, Д.Номер, Д.Организация
ИЗ Документ.АмортизацияОС КАК Д
ГДЕ Д.Проведен = ИСТИНА
УПОРЯДОЧИТЬ ПО Д.Дата"""
res = q.Execute().Select()
if not res.Next():
    print("Не знайдено проведений АмортизацияОС!")
    exit()
doc_ref = res.Ссылка
doc_date = res.Дата
doc_org = res.Организация
print(f"  Документ: {S(doc_ref)}")
print(f"  Дата: {doc_date}, Організація: {S(doc_org)}")

# === 2. Поточні рухи ПрочиеРасходы цього документа ===
print(f"\n=== 2. Рухи ПрочиеРасходы документа ===")
q2 = conn.NewObject("Запрос")
q2.Text = """ВЫБРАТЬ
    ПР.ВидДвижения, ПР.Период, ПР.СтатьяРасходов,
    ПР.АналитикаРасходов, ПР.Сумма, ПР.СуммаРегл
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &Рег"""
q2.SetParameter("Рег", doc_ref)
tbl2 = q2.Execute().Unload()
prihod = 0
rashod = 0
for i in range(tbl2.Count()):
    row = tbl2.Get(i)
    vd_xml = conn.XMLString(row.ВидДвижения)
    if vd_xml == "Receipt":
        prihod += 1
    else:
        rashod += 1
print(f"  Всього: {tbl2.Count()}, ПРИХОД={prihod}, РАСХОД={rashod}")

# === 3. Остатки ПрочиеРасходы по ВНА ===
print(f"\n=== 3. ПрочиеРасходы.Остатки (ВНА, організація) ===")
q3 = conn.NewObject("Запрос")
q3.Text = """ВЫБРАТЬ
    О.Организация, О.Подразделение, О.НаправлениеДеятельности,
    О.НалоговоеНазначение, О.СтатьяРасходов, О.АналитикаРасходов,
    О.СуммаОстаток, О.СуммаБезНДСОстаток,
    О.СуммаРеглОстаток, О.СуммаРеглБезНДСОстаток,
    О.НДСРеглОстаток, О.СуммаУпрОстаток, О.СуммаУпрБезНДСОстаток
ИЗ РегистрНакопления.ПрочиеРасходы.Остатки(,
    Организация = &Орг
    И СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)
    И СтатьяРасходов.ВариантРаспределенияРасходовРегл = ЗНАЧЕНИЕ(Перечисление.ВариантыРаспределенияРасходов.НаВнеоборотныеАктивы)
) КАК О
ГДЕ О.СуммаОстаток > 0"""
q3.SetParameter("Орг", doc_org)
try:
    tbl3 = q3.Execute().Unload()
    total_sum = 0
    for i in range(tbl3.Count()):
        row = tbl3.Get(i)
        total_sum += row.СуммаОстаток
    print(f"  Рядків з додатним залишком: {tbl3.Count()}")
    print(f"  ВСЬОГО залишок: {total_sum}")
except Exception as e:
    print(f"  ПОМИЛКА: {e}")
    exit()

if tbl3.Count() == 0:
    print("\nНемає залишків ВНА для списання. Тест завершено.")
    exit()

# === 4. Створення РАСХОД записів ===
print(f"\n=== 4. {'DRY RUN' if DRY_RUN else 'ЗАПИС'}: РАСХОД записи ===")

# Прочитати набір записів
nabor = conn.AccumulationRegisters.ПрочиеРасходы.CreateRecordSet()
nabor.Filter.Регистратор.Set(doc_ref)
nabor.Read()
print(f"  Записів в наборі (до): {nabor.Count()}")

added = 0
for i in range(tbl3.Count()):
    row = tbl3.Get(i)
    new_rec = nabor.Add()
    # КРИТИЧНО: використовуємо ЗНАЧЕННЯ перерахування, НЕ число!
    new_rec.RecordType = VD_RASHOD
    new_rec.Period = doc_date
    new_rec.Организация = row.Организация
    new_rec.Подразделение = row.Подразделение
    new_rec.НаправлениеДеятельности = row.НаправлениеДеятельности
    new_rec.НалоговоеНазначение = row.НалоговоеНазначение
    new_rec.СтатьяРасходов = row.СтатьяРасходов
    new_rec.АналитикаРасходов = row.АналитикаРасходов
    new_rec.Сумма = row.СуммаОстаток
    new_rec.СуммаБезНДС = row.СуммаБезНДСОстаток if row.СуммаБезНДСОстаток else 0
    new_rec.СуммаРегл = row.СуммаРеглОстаток if row.СуммаРеглОстаток else 0
    new_rec.СуммаРеглБезНДС = row.СуммаРеглБезНДСОстаток if row.СуммаРеглБезНДСОстаток else 0
    new_rec.НДСРегл = row.НДСРеглОстаток if row.НДСРеглОстаток else 0
    new_rec.СуммаУпр = row.СуммаУпрОстаток if row.СуммаУпрОстаток else 0
    new_rec.СуммаУпрБезНДС = row.СуммаУпрБезНДСОстаток if row.СуммаУпрБезНДСОстаток else 0
    added += 1

print(f"  Додано РАСХОД: {added}. Всього в наборі: {nabor.Count()}")

# Перевіримо тип запису останнього доданого
last_rec = nabor.Get(nabor.Count() - 1)
print(f"  Перевірка RecordType останнього: XML={conn.XMLString(last_rec.RecordType)}")

if not DRY_RUN:
    try:
        nabor.Write(True)
        print("  ЗАПИСАНО!")
    except Exception as e:
        print(f"  ПОМИЛКА ЗАПИСУ: {e}")
        exit()
else:
    print("  [DRY RUN — запис не виконано]")

# === 5. Перевірка залишку ===
if not DRY_RUN:
    print(f"\n=== 5. Перевірка залишку після ===")
    q5 = conn.NewObject("Запрос")
    q5.Text = """ВЫБРАТЬ О.АналитикаРасходов, О.СуммаОстаток
    ИЗ РегистрНакопления.ПрочиеРасходы.Остатки(,
        Организация = &Орг
        И СтатьяРасходов.ТипРасходов = ЗНАЧЕНИЕ(Перечисление.ТипыРасходов.ФормированиеСтоимостиВНА)
        И СтатьяРасходов.ВариантРаспределенияРасходовРегл = ЗНАЧЕНИЕ(Перечисление.ВариантыРаспределенияРасходов.НаВнеоборотныеАктивы)
    ) КАК О
    ГДЕ О.СуммаОстаток <> 0"""
    q5.SetParameter("Орг", doc_org)
    res5 = q5.Execute().Select()
    has_balance = False
    while res5.Next():
        has_balance = True
        print(f"  {S(res5.АналитикаРасходов)}: залишок = {res5.СуммаОстаток}")
    if not has_balance:
        print("  Залишок = 0 по всіх аналітиках ВНА [OK]")
    else:
        print("  УВАГА: є ненульові залишки!")

print("\n=== ТЕСТ ЗАВЕРШЕНО ===")
