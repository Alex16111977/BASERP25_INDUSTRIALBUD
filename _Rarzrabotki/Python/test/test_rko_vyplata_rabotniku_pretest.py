"""Pre-test (Rule #-1) для фикса РКО «Выплата работнику».

Баг: РКО с ХозОп=ВыплатаЗарплатыРаботнику + Ведомость=ВКассу проводит ВСЮ
расшифровку ведомости (всех ФЛ) вместо одного работника (Д.ПодотчетноеЛицо).

Проверяем ПЕРЕД правкой BSL:
  1. РКО ІБ00-000006: ХозОп=Работнику, Работник=Марчук, Ведомость=ВКассу, СуммаДок=21612.50
  2. Текущий запрос (без фильтра) воспроизводит баг → 5 ФЛ, Σ=94323.00
  3. Новый запрос (фильтр Рш.ФизическоеЛицо = Д.ПодотчетноеЛицо для Работнику)
     → 1 ФЛ (Марчук), Σ = СуммаДокумента = 21612.50
  4. Sanity: тот же фильтр на ЧерезКассу N0000052986 НЕ срабатывает → полная ведомость
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
XS = erp.XMLСтрока

NUM = "ІБ00-000006"

# ── 1. Найти РКО и показать реквизиты ───────────────────────────────────────
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Д.Ссылка КАК Ссылка,
    Д.Номер КАК Номер,
    Д.Дата КАК Дата,
    Д.ХозяйственнаяОперация КАК ХозОп,
    Д.ПодотчетноеЛицо КАК Работник,
    Д.Ведомость КАК Ведомость,
    Д.СуммаДокумента КАК СуммаДокумента,
    Д.Организация КАК Организация,
    Д.Проведен КАК Проведен
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
ГДЕ Д.Номер = &Ном
"""
q.SetParameter("Ном", NUM)
sel = q.Execute().Выгрузить()
print(f"Найдено РКО с номером {NUM}: {sel.Количество()}")

target = None
for row in sel:
    hozop = XS(row.ХозОп)
    ved_type = "ВКассу" if "ВедомостьНаВыплатуЗарплатыВКассу" in XS(row.Ведомость) else XS(row.Ведомость)
    print(f"  {S(row.Номер)} от {row.Дата} | ХозОп={hozop} | Работник={S(row.Работник)} | "
          f"Ведомость={ved_type} | СуммаДок={float(row.СуммаДокумента):,.2f} | Проведен={row.Проведен}")
    if hozop == "ВыплатаЗарплатыРаботнику":
        target = row

assert target is not None, "Не найден РКО с ХозОп=ВыплатаЗарплатыРаботнику"
DOC = target.Ссылка
print(f"\nТестовый РКО: {S(target.Номер)} | Работник={S(target.Работник)} | СуммаДок={float(target.СуммаДокумента):,.2f}")
assert XS(target.ХозОп) == "ВыплатаЗарплатыРаботнику"
assert erp.ЗначениеЗаполнено(target.Работник), "Работник (ПодотчетноеЛицо) пуст!"
СУММА_ДОК = float(target.СуммаДокумента)

# ── 2. ТЕКУЩИЙ запрос (без фильтра) — воспроизводим баг ──────────────────────
q_bug = erp.NewObject("Запрос")
q_bug.Text = """
ВЫБРАТЬ
    Рш.ФизическоеЛицо КАК ФизическоеЛицо,
    Рш.Подразделение.А_Подразделение КАК Подразделение,
    СУММА(Рш.КВыплате) КАК Сумма
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Ссылка = &Док
СГРУППИРОВАТЬ ПО Рш.ФизическоеЛицо, Рш.Подразделение.А_Подразделение
"""
q_bug.SetParameter("Док", DOC)
bug = q_bug.Execute().Выгрузить()
sum_bug = sum(float(r.Сумма) for r in bug)
print(f"\n[ТЕКУЩИЙ — баг] строк={bug.Количество()}, Σ={sum_bug:,.2f}")
for r in bug:
    print(f"    {S(r.ФизическоеЛицо)} | {S(r.Подразделение)} | {float(r.Сумма):,.2f}")
assert bug.Количество() > 1, "Ожидали воспроизвести баг (>1 строки на всю ведомость)"

# ── 3. НОВЫЙ запрос (с фильтром по ПодотчетноеЛицо для Работнику) ─────────────
q_fix = erp.NewObject("Запрос")
q_fix.Text = """
ВЫБРАТЬ
    Рш.ФизическоеЛицо КАК ФизическоеЛицо,
    Рш.Подразделение.А_Подразделение КАК Подразделение,
    СУММА(Рш.КВыплате) КАК Сумма
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Ссылка = &Док
    И (Д.ХозяйственнаяОперация <> ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику)
       ИЛИ Рш.ФизическоеЛицо = Д.ПодотчетноеЛицо)
СГРУППИРОВАТЬ ПО Рш.ФизическоеЛицо, Рш.Подразделение.А_Подразделение
"""
q_fix.SetParameter("Док", DOC)
fix = q_fix.Execute().Выгрузить()
sum_fix = sum(float(r.Сумма) for r in fix)
print(f"\n[НОВЫЙ — фикс] строк={fix.Количество()}, Σ={sum_fix:,.2f}")
for r in fix:
    print(f"    {S(r.ФизическоеЛицо)} | {S(r.Подразделение)} | {float(r.Сумма):,.2f}")

assert fix.Количество() >= 1, "Фикс не вернул ни одной строки!"
fl_set = {S(r.ФизическоеЛицо) for r in fix}
assert fl_set == {S(target.Работник)}, f"Ожидали только {S(target.Работник)}, получили {fl_set}"
assert abs(sum_fix - СУММА_ДОК) < 0.01, f"Σ фикса {sum_fix} != СуммаДокумента {СУММА_ДОК}"
print(f"  ✓ только 1 ФЛ ({S(target.Работник)}), Σ={sum_fix:,.2f} = СуммаДокумента")

# ── 4. Sanity: ЧерезКассу — фильтр НЕ срабатывает (filtered == unfiltered) ───
# Тестовый РКО ищем ДИНАМИЧЕСКИ (урок §3.13: не хардкодить — доки меняются).
q_find = erp.NewObject("Запрос")
q_find.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Д.Ссылка КАК Ссылка,
    Д.Номер КАК Номер
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Проведен
    И Д.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу)
СГРУППИРОВАТЬ ПО Д.Ссылка, Д.Номер
ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Рш.ФизическоеЛицо) > 1
"""
found = q_find.Execute().Выгрузить()
if found.Количество() == 0:
    print("\n[SANITY] ⚠ не найден проведённый ЧерезКассу+ВКассу РКО (>1 ФЛ) — sanity пропущен")
else:
    san_ref = found[0].Ссылка
    san_num = S(found[0].Номер)
    tmpl = """
    ВЫБРАТЬ Рш.ФизическоеЛицо КАК ФЛ, СУММА(Рш.КВыплате) КАК Сумма
    ИЗ Документ.РасходныйКассовыйОрдер КАК Д
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
            ПО Рш.Ссылка = Д.Ведомость
    ГДЕ Д.Ссылка = &Док {ФИЛЬТР}
    СГРУППИРОВАТЬ ПО Рш.ФизическоеЛицо
    """
    ФИЛЬТР = ("И (Д.ХозяйственнаяОперация <> ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику)"
              " ИЛИ Рш.ФизическоеЛицо = Д.ПодотчетноеЛицо)")
    def run(flt):
        qq = erp.NewObject("Запрос")
        qq.Text = tmpl.replace("{ФИЛЬТР}", flt)
        qq.SetParameter("Док", san_ref)
        res = qq.Execute().Выгрузить()
        return res.Количество(), sum(float(r.Сумма) for r in res)
    n_un, s_un = run("")
    n_fl, s_fl = run(ФИЛЬТР)
    print(f"\n[SANITY ЧерезКассу {san_num}] без фильтра: {n_un} ФЛ / {s_un:,.2f} | с фильтром: {n_fl} ФЛ / {s_fl:,.2f}")
    assert n_un == n_fl and abs(s_un - s_fl) < 0.01, "FAIL: фильтр изменил ЧерезКассу (должен быть no-op)!"
    print("  ✓ полная ведомость сохранена (фильтр не задел ЧерезКассу)")

print("\n" + "=" * 80)
print("✅ PRETEST PASS — фильтр корректен, можно вносить в BSL (4 файла / 5 запросов)")
print("=" * 80)
