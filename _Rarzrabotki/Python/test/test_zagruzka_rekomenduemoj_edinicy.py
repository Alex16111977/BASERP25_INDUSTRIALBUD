# -*- coding: utf-8 -*-
"""Smoke-тест обработки «Загрузка рекомендуемой единицы» (две кнопки: Бухгалтерия и ЕРП).

Сценарии:
1. Из ЕРП кнопка «Бухгалтерия» -> COM в bas_industrialbud (идемпотентно после первичной загрузки).
2. Из ЕРП кнопка «ЕРП» -> локально А_ОбщиеНазванияНоменклатуры.ЕдиницаРекомендуемая
   (если реквизита нет - корректный отказ без записи).
3. Из Бухгалтерии кнопка «Бухгалтерия» -> локальный движок.
4. Из Бухгалтерии кнопка «ЕРП» -> понятный отказ.
Плюс проверка данных в Бухгалтерии: 191 заполнено, канонический «шт» код 2009.
"""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import re
import openpyxl
import win32com.client

EXCEL = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Виробництво\Копия Аналіз одиниць виміру.xlsx"
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\Загрузка рекомендуемой единицы.epf"

ОЖИД_СТРОК = 201
ОЖИД_БУХ = 191      # карточек с единицей в Бухгалтерии
ОЖИД_ЕРП = 191      # карточек с единицей в ЕРП: найдено названий 194, минус 3 с нераспознанной единицей
ОЖИД_НЕТ_НАЗВАНИЙ = 7
ОЖИД_НЕТ_ЕДИНИЦ = 3


def norm(s):
    return re.sub(r"\s+", " ", str(s or "")).strip()


def читать_excel():
    wb = openpyxl.load_workbook(EXCEL, data_only=True)
    ws = wb["TDSheet"]
    pairs = []
    for r in range(4, ws.max_row + 1):
        lvl = ws.row_dimensions[r].outline_level if r in ws.row_dimensions else 0
        if lvl != 0:
            continue
        a = norm(ws.cell(row=r, column=1).value)
        d = norm(ws.cell(row=r, column=4).value)
        if a and d:
            pairs.append((a, d))
    return pairs


def com_массив(c, pairs):
    arr = c.NewObject("Массив")
    for name, unit in pairs:
        arr.Добавить(c.NewObject("Структура", "ОбщееНазвание, Единица", name, unit))
    return arr


def печать(тег, res):
    print(f"[{тег}] Ошибка={res.Ошибка} Всего={res.ВсегоСтрок} Обновлено={res.Обновлено} "
          f"БезИзменений={res.БезИзменений} НетНазваний={res.НеНайденоНазваний.Количество()} "
          f"НетЕдиниц={res.НеНайденоЕдиниц.Количество()}")
    if res.Ошибка:
        print("   Текст:", str(res.ТекстОшибки))


def main():
    pairs = читать_excel()
    assert len(pairs) == ОЖИД_СТРОК, f"Excel: {len(pairs)}, ожид {ОЖИД_СТРОК}"
    print(f"Excel: {len(pairs)} пар уровня 0")
    v8 = win32com.client.Dispatch("V83.COMConnector")

    # --- из ЕРП ---
    erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
    md = erp.Метаданные.Справочники.Найти("А_ОбщиеНазванияНоменклатуры")
    есть_рекв = md.Реквизиты.Найти("ЕдиницаРекомендуемая") is not None
    print("Реквизит ЕдиницаРекомендуемая в ЕРП:", "есть" if есть_рекв else "НЕТ")

    proc = erp.ВнешниеОбработки.Создать(EPF, False)
    arr = com_массив(erp, pairs)

    res1 = proc.ЗагрузитьЕдиницыБух(arr)
    печать("ЕРП→Бух COM", res1)
    assert not res1.Ошибка
    assert res1.Обновлено + res1.БезИзменений == ОЖИД_БУХ
    assert res1.НеНайденоНазваний.Количество() == ОЖИД_НЕТ_НАЗВАНИЙ
    assert res1.НеНайденоЕдиниц.Количество() == ОЖИД_НЕТ_ЕДИНИЦ

    res2 = proc.ЗагрузитьЕдиницыЕРП(arr)
    печать("ЕРП локально", res2)
    if есть_рекв:
        assert not res2.Ошибка
        assert res2.Обновлено + res2.БезИзменений == ОЖИД_ЕРП
        # повтор идемпотентен
        res2b = proc.ЗагрузитьЕдиницыЕРП(arr)
        assert not res2b.Ошибка and res2b.Обновлено == 0 and res2b.БезИзменений == ОЖИД_ЕРП
        print("   повтор ЕРП: 0 обновлено /", res2b.БезИзменений, "без изменений")
    else:
        assert res2.Ошибка and "ЕдиницаРекомендуемая" in str(res2.ТекстОшибки)
        print("   -> корректный отказ (реквизит не создан)")

    # --- из Бухгалтерии ---
    buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
    procB = buh.ВнешниеОбработки.Создать(EPF, False)
    res3 = procB.ЗагрузитьЕдиницыБух(com_массив(buh, pairs))
    печать("Бух локально", res3)
    assert not res3.Ошибка and res3.Обновлено + res3.БезИзменений == ОЖИД_БУХ

    res4 = procB.ЗагрузитьЕдиницыЕРП(com_массив(buh, pairs))
    печать("Бух: кнопка ЕРП", res4)
    assert res4.Ошибка

    # --- данные в Бухгалтерии: заполненность и канонический шт 2009 ---
    q = buh.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        Спр.ЕдиницаРекомендуемая.Код КАК Код,
        Спр.ЕдиницаРекомендуемая.Наименование КАК Ед,
        КОЛИЧЕСТВО(Спр.Ссылка) КАК Кол
    ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК Спр
    ГДЕ Спр.ЕдиницаРекомендуемая <> ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)
    СГРУППИРОВАТЬ ПО
        Спр.ЕдиницаРекомендуемая.Код,
        Спр.ЕдиницаРекомендуемая.Наименование
    """
    tz = q.Execute().Выгрузить()
    итого = 0
    for i in range(tz.Количество()):
        row = tz.Получить(i)
        итого += row.Кол
        assert str(row.Ед) != " шт", "записан дубль ' шт' вместо канонического 2009"
    assert итого == ОЖИД_БУХ, f"в Бухгалтерии заполнено {итого}, ожид {ОЖИД_БУХ}"
    print(f"Бухгалтерия: заполнено {итого}, канон шт=2009 подтверждён")

    print("\nSMOKE OK")


if __name__ == "__main__":
    main()
