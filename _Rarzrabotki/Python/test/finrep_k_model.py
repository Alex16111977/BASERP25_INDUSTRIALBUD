def ндс(база):
    """Незареєстрований ПДВ за ставки 20 %: −база / (1 + 100/20), зі знаком мінус."""
    return round(-база / (1 + 100 / 20), 2)


def k_договору(варіант, p, E, F, H, A=0.0, оплата_до_першого_акта=0.0, дата_заліку_діє=False,
               залишок_на_дату=0.0, виконано_після_дати=0.0, правило_ндс="", утримання=0.0):
    доля = p / 100
    G = round(E - F, 2)
    if варіант not in ("ЗадолженностьПлюсАкты", "ВыполнениеМинусОплата", "ТолькоРучной", "ЗачетПредоплаты"):
        варіант = "ЗадолженностьПлюсАкты"   # BSL: К22 і як Z
    if варіант == "ЗачетПредоплаты" and A <= 0:
        варіант = "ЗадолженностьПлюсАкты"
    a_ост = 0.0
    if варіант == "ЗачетПредоплаты":
        a_факт = min(A, оплата_до_першого_акта)
        if дата_заліку_діє:
            a_ост = max(0.0, залишок_на_дату - виконано_після_дати * доля)
        else:
            a_ост = max(0.0, a_факт - E * доля)
    покрито_авансом = min(a_ост, H * доля) if варіант == "ЗачетПредоплаты" else 0.0
    правило = (правило_ндс or "ОтАктов").strip()
    if правило == "НеУчитывать":
        J = 0.0
    elif правило == "ОтЗадолженности":
        J = ндс(max(0.0, G))
    else:
        J = ндс(H - покрито_авансом)
    I = -round(min(утримання, max(0.0, G + H)), 2) if утримання > 0 else 0.0
    if варіант == "ЗадолженностьПлюсАкты":
        сире = G + I + J + H * (1 - доля)
    elif варіант == "ВыполнениеМинусОплата":
        сире = (E + H) * (1 - доля) + J - F + I
    elif варіант == "ЗачетПредоплаты":
        сире = G + a_ост + H - min(a_ост, H * доля) + J + I
    else:
        сире = 0.0
    return {"G": G, "J": J, "I": I, "A_ост": a_ост, "K_сире": round(сире, 2), "K": round(max(0.0, сире), 2)}
