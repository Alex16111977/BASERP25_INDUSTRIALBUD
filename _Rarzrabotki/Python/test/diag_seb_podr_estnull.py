sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qb = conn.NewObject("Запрос")
qb.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qb.УстановитьПараметр("М", M); rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ, КД = rb.НМ, rb.КД

ИСТОЧНИК = """
	РегистрНакопления.СебестоимостьТоваров.ОстаткиИОбороты(
			&НачМес, &КонМес, , ,
			Организация = &Орг
				И (РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
					ИЛИ РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыПереданныеНаКомиссию))) КАК СТ
		ЛЕВОЕ СОЕДИНЕНИЕ Справочник.КлючиАналитикиУчетаНоменклатуры КАК Аналитика
		ПО СТ.АналитикаУчетаНоменклатуры = Аналитика.Ссылка
ГДЕ
	(СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
			ИЛИ СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыПереданныеНаКомиссию))
"""

def прогон(подр_выр, заголовок):
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НачМес", НМ)
    q.УстановитьПараметр("КонМес", КД)
    q.Текст = f"""ВЫБРАТЬ
	СТ.Организация КАК Организация,
	{подр_выр} КАК Подразделение,
	ВЫБОР
		КОГДА Аналитика.СкладскаяТерритория.ТипСклада = ЗНАЧЕНИЕ(Перечисление.ТипыСкладов.РозничныйМагазин)
			ТОГДА ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыВРознице)
		КОГДА Аналитика.СкладскаяТерритория.ТипСклада = ЗНАЧЕНИЕ(Перечисление.ТипыСкладов.ОптовыйСклад)
			ТОГДА ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыНаОптовыхСкладах)
		КОГДА Аналитика.ТипМестаХранения = ЗНАЧЕНИЕ(Перечисление.ТипыМестХранения.Партнер)
			ТОГДА ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыКОформлениюОтчетовКомитенту)
		ИНАЧЕ ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыПереданныеНаКомиссию)
	КОНЕЦ КАК Статья,
	Аналитика.Номенклатура КАК Номенклатура,
	ВЫРАЗИТЬ(Аналитика.МестоХранения КАК Справочник.Склады) КАК Склад,
	СУММА(СТ.СтоимостьКонечныйОстаток) КАК КО
ИЗ {ИСТОЧНИК}
СГРУППИРОВАТЬ ПО
	СТ.Организация,
	{подр_выр},
	ВЫБОР
		КОГДА Аналитика.СкладскаяТерритория.ТипСклада = ЗНАЧЕНИЕ(Перечисление.ТипыСкладов.РозничныйМагазин)
			ТОГДА ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыВРознице)
		КОГДА Аналитика.СкладскаяТерритория.ТипСклада = ЗНАЧЕНИЕ(Перечисление.ТипыСкладов.ОптовыйСклад)
			ТОГДА ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыНаОптовыхСкладах)
		КОГДА Аналитика.ТипМестаХранения = ЗНАЧЕНИЕ(Перечисление.ТипыМестХранения.Партнер)
			ТОГДА ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыКОформлениюОтчетовКомитенту)
		ИНАЧЕ ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ТоварыПереданныеНаКомиссию)
	КОНЕЦ,
	Аналитика.Номенклатура,
	ВЫРАЗИТЬ(Аналитика.МестоХранения КАК Справочник.Склады)"""
    t = q.Выполнить().Выгрузить()
    n = t.Количество()
    # уникальность по 1С-равенству реальных значений Подразделения через
    # приведение к одиночному типу СтруктураПредприятия (как измерение)
    keyfull = Counter()
    nullподр = 0
    типы = Counter()
    for i in range(n):
        r = t.Получить(i)
        подр = r.Подразделение
        if not conn.ЗначениеЗаполнено(подр):
            nullподр += 1
        типы[type(подр).__name__] += 1
        # как запишется в измерение (одиночный СтруктураПредприятия):
        # ВЫРАЗИТЬ значение к Справочник.СтруктураПредприятия
        keyfull[(conn.ЗначениеВСтрокуВнутр(r.Организация),
                 conn.ЗначениеВСтрокуВнутр(подр),
                 conn.ЗначениеВСтрокуВнутр(r.Статья),
                 conn.ЗначениеВСтрокуВнутр(r.Номенклатура),
                 conn.ЗначениеВСтрокуВнутр(r.Склад))] += 1
    dup = sum(1 for c in keyfull.values() if c > 1)
    print(f"\n[{заголовок}] строк={n} уникальных(5кл)={len(keyfull)} "
          f"дублей={dup} NULL-Подр={nullподр}")
    print(f"  типы Python значения Подразделения: {dict(типы)}")
    return n

# вариант 1: доказанно рабочая модель (БЕЗ ЕСТЬNULL)
