# -*- coding: utf-8 -*-
"""Контрольная сверка класса А: документ № 2 (14.08.2026) против Excel 14.08 по C/D.

Логика:
  1) находит боевой документ с ДатаРасчета 14.08.2026;
  2) проверяет состав ТЧ Подразделения (целевые подразделения включены?);
  3) пересчитывает объект В ПАМЯТИ (Рассчитать(); без --apply база не меняется);
  4) целевые договоры без движений, выпавшие из расчёта, добавляет в ТЧ
     ДоговорыДополнительно (в памяти) и пересчитывает повторно;
  5) сводит ТЧ Расчет по подразделениям и сравнивает C (СуммаСоглашения) и
     D (СуммаДЦ) с эталонами Excel 14.08 (лист «24,07,2026», уровень секций);
  6) с --apply СОХРАНЯЕТ документ (ДоговорыДополнительно + результат пересчёта).

Известные ОТКРЫТЫЕ позиции (пользователю, кодом не чинится):
  * МК Глобино: Excel 10 300 518,60 = наш свод + 62 871,90 («Навіс» r38 — договора нет);
  * МД МХП ОРІЛЬ: в Excel есть ещё r60 «1203/2026» C=462 727,10 — договора нет в базе;
  * МК Подгорцы: Excel 41 500 («Забор» r151) — у подразделения нет договоров;
  * МК Кривий ріг: у нас C=7 961 800, в Excel «?» — решение директора.

Запуск:
    python doc_finrep_sverka_klassA.py            — пересчёт в памяти, отчёт
    python doc_finrep_sverka_klassA.py --apply    — то же + запись документа
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ПРИМЕНЯТЬ = "--apply" in sys.argv

# Эталоны Excel 14.08 на уровне секций-подразделений (только закрываемое кодом).
ЦЕЛЕВЫЕ_C = {
    "МД IRC 2026":            19681200.00,
    "МД ООН 2025":            33485281.78,
    "МД Кернел Кухня":        12178525.57,
    "МД ПРООН Черкаси  ДСНС":  8913680.73,
    "МД Вооз ЕМS Мала 2026":   5192818.40,
    "МК Каменец Цемент":       3032016.00,
    "МК Чорноморськ":           612720.00,
    "МД МХП ОРІЛЬ":            3355204.73,
    "МК Глобино":             10237646.70,
    "МК Кривий ріг":           7961800.00,
}
ЦЕЛЕВЫЕ_D = {"МД Кернел Кухня": 716773.00}

# Переопределение подразделения строки отчёта для договоров, чьё собственное
# подразделение не входит в ТЧ Подразделения (IRC-дети сворачиваются в корень).
ПЕРЕОПРЕДЕЛЕНИЕ_ПОДР = {
    "bb554515-7aba-11f1-8119-00155dce3d04": "МД IRC 2026",
    "7531c0c8-7abc-11f1-8119-00155dce3d04": "МД IRC 2026",
}

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# --- 1. Боевой документ 14.08 ---
q = buh.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С, Д.Номер КАК Номер, Д.ДатаРасчета КАК ДР "
           "ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д "
           "ГДЕ НЕ Д.ПометкаУдаления И ГОД(Д.ДатаРасчета) = 2026 "
           "И МЕСЯЦ(Д.ДатаРасчета) = 8 И ДЕНЬ(Д.ДатаРасчета) = 14")
т = q.Execute().Выгрузить()
if т.Количество() != 1:
    print(f"ОШИБКА: документов с ДатаРасчета 14.08.2026 найдено {т.Количество()}, ожидался 1")
    sys.exit(1)
док_ссылка = т.Получить(0).С
print(f"Документ: № {т.Получить(0).Номер} (ДатаРасчета {т.Получить(0).ДР})")
print(f"Режим: {'ЗАПИСЬ (--apply)' if ПРИМЕНЯТЬ else 'DRY-RUN (пересчёт в памяти)'}\n")

объект = док_ссылка.ПолучитьОбъект()

# Целевые договоры = ВСЕ договоры с записями регистра параметров (динамически):
# каждый из них должен быть виден в отчёте, иначе его C/D не сверить с Excel.
q = buh.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ П.Договор КАК Дог, "
           "ЕСТЬNULL(П.Договор.Подразделение.Наименование, \"\") КАК Подр "
           "ИЗ РегистрСведений.А_ПараметрыДоговоровФинотчета КАК П "
           "ГДЕ НЕ П.Договор.ПометкаУдаления")
тр = q.Execute().Выгрузить()
ЦЕЛЕВЫЕ_ДОГОВОРЫ = []
for i in range(тр.Количество()):
    с = тр.Получить(i)
    уид = str(buh.String(с.Дог.УникальныйИдентификатор()))
    ЦЕЛЕВЫЕ_ДОГОВОРЫ.append((уид, ПЕРЕОПРЕДЕЛЕНИЕ_ПОДР.get(уид, str(с.Подр))))
print(f"Договоров с параметрами в регистре: {len(ЦЕЛЕВЫЕ_ДОГОВОРЫ)}")

# --- 2. Состав ТЧ Подразделения ---
включённые = {}
for i in range(объект.Подразделения.Количество()):
    с = объект.Подразделения.Получить(i)
    имя = str(с.Подразделение.Наименование) if str(buh.string(с.Подразделение)) else "<пусто>"
    включённые[имя] = bool(с.Включать)
print(f"ТЧ Подразделения: {len(включённые)} строк, включено {sum(включённые.values())}")
for имя in ЦЕЛЕВЫЕ_C:
    метка = "ВКЛ" if включённые.get(имя) else ("выкл" if имя in включённые else "НЕТ В ТЧ!")
    print(f"  {имя:26} {метка}")

# --- 3. Первый пересчёт ---
Результат = объект.Рассчитать()
print(f"\nПересчёт 1: Выполнено={bool(Результат.Выполнено)} "
      f"Ошибок={int(Результат.Ошибок)} Строк={int(Результат.СтрокРасчета)}")

def уиды_договоров_расчёта():
    уиды = set()
    for i in range(объект.Расчет.Количество()):
        с = объект.Расчет.Получить(i)
        if str(buh.string(с.Договор)) != "":
            уиды.add(str(buh.String(с.Договор.УникальныйИдентификатор())))
    return уиды

в_расчёте = уиды_договоров_расчёта()
отсутствуют = [(у, п) for у, п in ЦЕЛЕВЫЕ_ДОГОВОРЫ if у not in в_расчёте]

# --- 4. Добавление выпавших в ДоговорыДополнительно ---
if отсутствуют:
    уже_доп = set()
    for i in range(объект.ДоговорыДополнительно.Количество()):
        с = объект.ДоговорыДополнительно.Получить(i)
        if str(buh.string(с.Договор)) != "":
            уже_доп.add(str(buh.String(с.Договор.УникальныйИдентификатор())))
    print(f"\nВ расчёт не попали {len(отсутствуют)} целевых договоров — "
          f"добавляю в «Договоры дополнительно»:")
    for у, имя_подр in отсутствуют:
        if у in уже_доп:
            print(f"  {у} — уже в ТЧ ДоговорыДополнительно, пропуск")
            continue
        уид = buh.NewObject("УникальныйИдентификатор", у)
        дог = buh.Справочники.ДоговорыКонтрагентов.ПолучитьСсылку(уид)
        подр = buh.Справочники.Подразделения.НайтиПоНаименованию(имя_подр, True)
        if str(buh.String(подр)) == "":
            print(f"  [ОШИБКА] подразделение «{имя_подр}» не найдено — пропуск {у}")
            continue
        с = объект.ДоговорыДополнительно.Добавить()
        с.Договор = дог
        с.Подразделение = подр
        print(f"  + {' '.join(str(дог.Наименование).split())[:55]:55} -> {имя_подр}")
    Результат = объект.Рассчитать()
    print(f"Пересчёт 2: Выполнено={bool(Результат.Выполнено)} "
          f"Ошибок={int(Результат.Ошибок)} Строк={int(Результат.СтрокРасчета)}")
    в_расчёте = уиды_договоров_расчёта()
    всё_ещё = [(у, п) for у, п in ЦЕЛЕВЫЕ_ДОГОВОРЫ if у not in в_расчёте]
    for у, п in всё_ещё:
        print(f"  [ПРОБЛЕМА] договор {у} ({п}) так и не попал в расчёт")
else:
    print("Все целевые договоры уже в расчёте — «Договоры дополнительно» не нужны.")

# --- 5. Свод и сравнение ---
свод = {}
for i in range(объект.Расчет.Количество()):
    с = объект.Расчет.Получить(i)
    имя = str(с.Подразделение.Наименование) if str(buh.string(с.Подразделение)) else "<пусто>"
    а = свод.setdefault(имя, {"C": 0.0, "D": 0.0, "E": 0.0, "F": 0.0,
                              "G": 0.0, "H": 0.0, "K": 0.0})
    а["C"] += float(с.СуммаСоглашения)
    а["D"] += float(с.СуммаДЦ)
    а["E"] += float(с.ВыполненныеРаботы)
    а["F"] += float(с.Оплачено)
    а["G"] += float(с.Задолженность)
    а["H"] += float(с.АктыПоданные)
    а["K"] += float(с.ИтогоКПолучению)

print(f"\n{'ПІДРОЗДІЛ':28}|{'C розрах.':>16}|{'C Excel':>16}|{'дельта':>14}| статус")
print("-" * 96)
ок = сбой = 0
for имя, цель in ЦЕЛЕВЫЕ_C.items():
    факт = свод.get(имя, {}).get("C", 0.0)
    дельта = факт - цель
    статус = "OK" if abs(дельта) < 0.01 else "РАСХОЖДЕНИЕ"
    if abs(дельта) < 0.01:
        ок += 1
    else:
        сбой += 1
    print(f"{имя:28}|{факт:>16,.2f}|{цель:>16,.2f}|{дельта:>14,.2f}| {статус}")
for имя, цель in ЦЕЛЕВЫЕ_D.items():
    факт = свод.get(имя, {}).get("D", 0.0)
    дельта = факт - цель
    статус = "OK" if abs(дельта) < 0.01 else "РАСХОЖДЕНИЕ"
    if abs(дельта) < 0.01:
        ок += 1
    else:
        сбой += 1
    print(f"{имя + ' (D)':28}|{факт:>16,.2f}|{цель:>16,.2f}|{дельта:>14,.2f}| {статус}")

print(f"\nИтог сверки: OK={ок}, расхождений={сбой}")

# Прочие подразделения свода (справочно)
прочие = sorted(set(свод) - set(ЦЕЛЕВЫЕ_C))
if прочие:
    print("\nПрочие подразделения расчёта (C, справочно):")
    for имя in прочие:
        print(f"  {имя:28} C={свод[имя]['C']:>15,.2f}")

# --- 6. Запись ---
if ПРИМЕНЯТЬ:
    объект.Записать()
    print("\nДокумент ЗАПИСАН (Договоры дополнительно + результат пересчёта).")
else:
    print("\n>>> DRY-RUN: база не изменена (расчёт был в памяти).")
