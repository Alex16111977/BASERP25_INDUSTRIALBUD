"""Документ «Фінансовий звіт виробництва» на 25.09.2026 заново (№4 видалено) — за новою методикою (частини 1/1а).
Get-or-create: якщо непомічений документ з ДатаРасчета 25.09 вже є — нічого не створює.
Підрозділи — 13 об'єктів директорського звіту 25.09 у його порядку; «Договори додатково» — з №3 + «(забор)» → МК Подгорцы.
    python doc_finrep_create_2509.py           — перевірка без запису
    python doc_finrep_create_2509.py --apply   — розрахувати і записати"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ЗАПИС = "--apply" in sys.argv
buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String
ПІДРОЗДІЛИ = ["МК Чорноморськ", "МК Глобино", "МК Кривий ріг", "МК Каменец Цемент", "МД МХП ОРІЛЬ", "МД ООН 2025",
              "МД ПРООН Черкаси  ДСНС", "МД ООН Админ", "МД ООН 2026", "МД Кернел Кухня", "МД Вооз ЕМS Мала 2026",
              "МД IRC 2026", "МК Подгорцы"]


def запит(текст, **п):
    q = buh.NewObject("Запрос")
    q.Текст = текст
    for к, з in п.items():
        q.УстановитьПараметр(к, з)
    return q.Execute().Выгрузить()


Д = запит("ВЫБРАТЬ ДАТАВРЕМЯ(2026,9,25,23,59,59) КАК Д").Получить(0).Д
є = запит("ВЫБРАТЬ Д.Номер КАК Н ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д "
          "ГДЕ НЕ Д.ПометкаУдаления И НАЧАЛОПЕРИОДА(Д.ДатаРасчета, ДЕНЬ) = НАЧАЛОПЕРИОДА(&Д, ДЕНЬ)", Д=Д)
if є.Количество():
    sys.exit(f"Документ на 25.09 уже є: № {S(є.Получить(0).Н)} — нічого не створюю")

д = buh.Документы.А_ФинансовыйОтчетПроизводства.СоздатьДокумент()
д.Заполнить(None)
д.Дата = Д
д.ДатаРасчета = Д
д.ВключатьНепроведенные = True
д.Подразделения.Очистить()
for і in ПІДРОЗДІЛИ:
    п = buh.Справочники.Подразделения.НайтиПоНаименованию(і, True)
    assert not п.Пустая(), і
    р = д.Подразделения.Добавить()
    р.Подразделение = п
    р.Включать = True

прош = запит('ВЫБРАТЬ Д.Ссылка КАК С ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д ГДЕ Д.Номер = "00000000003"')
прош = прош.Получить(0).С.ПолучитьОбъект()
д.ДоговорыДополнительно.Очистить()
for i in range(прош.ДоговорыДополнительно.Количество()):
    с = прош.ДоговорыДополнительно.Получить(i)
    if S(с.Подразделение) in ПІДРОЗДІЛИ:
        н = д.ДоговорыДополнительно.Добавить()
        н.Договор = с.Договор
        н.Подразделение = с.Подразделение
забор = запит('ВЫБРАТЬ Д.Ссылка КАК С ИЗ Справочник.ДоговорыКонтрагентов КАК Д '
              'ГДЕ Д.Наименование ПОДОБНО "%(забор)%" И Д.Подразделение.Наименование = "МК Подгорцы.Забор"')
assert забор.Количество() == 1, f"договорів «(забор)»: {забор.Количество()}"
н = д.ДоговорыДополнительно.Добавить()
н.Договор = забор.Получить(0).С
н.Подразделение = buh.Справочники.Подразделения.НайтиПоНаименованию("МК Подгорцы", True)
if д.СтатьиИсключенияКазны.Количество() == 0:
    д.ЗаполнитьСтатьиИсключенияПоУмолчанию()

р = д.Рассчитать()
K = sum(float(д.Расчет.Получить(i).ИтогоКПолучению) for i in range(д.Расчет.Количество()))
print(f"Выполнено={р.Выполнено} Ошибок={int(р.Ошибок)} рядків={д.Расчет.Количество()} "
      f"дод.договорів={д.ДоговорыДополнительно.Количество()} K разом={K:,.2f}")
for i in range(д.Контроль.Количество()):
    к = д.Контроль.Получить(i)
    if S(к.Уровень) == "Помилка":
        print("  ПОМИЛКА", S(к.КодЗамечания), S(к.Текст)[:200])
if ЗАПИС and р.Выполнено and int(р.Ошибок) == 0:
    д.Записать()
    print("Записано: №", S(д.Номер))
