"""Discovery (Rule #0/#-1) для Свод_ОплатаТруда — ТОЛЬКО чтение, период СЕРВЕРНО.

Фиксирует эталон signed НО/КО статьи «Оплата труда»:
  ПАП(Источник=ПустаяСсылка, Статья=&ОТ, OD-3, signed) per (Орг,Подр) и Σ
  — для дек2025 / янв2026 / фев2026 / ТОВ ІНДАСТРІАЛБУД.
Границы НМ/КД — СЕРВЕРНО (НАЧАЛОПЕРИОДА/КОНЕЦПЕРИОДА), как оркестратор.
Перекрёстно: ПАП.ОстаткиИОбороты(Статья=ОТ, ВСЕ Источник) == штатный
Отчет.УправленческийБаланс (контрольное число полной статьи).
Плюс: «Оплата труда» аналитика пуста? (карточка «Без аналитики»).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
print(f"ORG = {ORG} (ЕДРПОУ 40645273)")

# &ОТ = СтатьяОплатаТруда() 1:1
qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать()
ОТ = rOT.С if rOT.Следующий() else conn.ПланыВидовХарактеристик.СтатьиАктивовПассивов.ПустаяСсылка()
print(f"ОТ  = {ОТ}")

# &Искл = ИсключенныеСтатьи()
qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка КАК Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for n in ("Собственные средства", "Доходы текущего периода",
          "Расходы текущего периода"):
    имена.Добавить(n)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
Искл = conn.NewObject("Массив")
for i in range(tI.Количество()):
    Искл.Добавить(tI.Получить(i).Ссылка)

ПЕРИОДЫ = [
    ("декабрь2025", datetime(2025, 12, 1, 12, 0, 0)),
    ("январь2026",  datetime(2026, 1, 1, 12, 0, 0)),
    ("февраль2026", datetime(2026, 2, 1, 12, 0, 0)),
]

# карта Подразделение: XMLСтрока(ссылка) -> Наименование (резолв в Python,
# как канон-Прямой — без ПРЕДСТАВЛЕНИЕ в основном запросе)
картаПодр = {}
qPm = conn.NewObject("Запрос")
qPm.Текст = ("ВЫБРАТЬ Ссылка КАК С, Наименование КАК Н "
             "ИЗ Справочник.СтруктураПредприятия")
tPm = qPm.Выполнить().Выгрузить()
for i in range(tPm.Количество()):
    картаПодр[conn.XMLСтрока(tPm.Получить(i).С)] = str(tPm.Получить(i).Н)


def границы(мид):
    qg = conn.NewObject("Запрос")
    qg.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
                "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
    qg.УстановитьПараметр("М", мид)
    rg = qg.Выполнить().Выбрать(); rg.Следующий()
    return rg.НМ, rg.КД


for имя, мид in ПЕРИОДЫ:
    НМ, КД = границы(мид)
    print(f"\n========== {имя}: период {НМ} .. {КД} ==========")

    # 1) ПАП(Источник=ПустаяСсылка, Статья=ОТ, OD-3, signed) per (Орг,Подр)
    qP = conn.NewObject("Запрос")
    qP.УстановитьПараметр("Орг", ORG); qP.УстановитьПараметр("НачМес", НМ)
    qP.УстановитьПараметр("КонМес", КД); qP.УстановитьПараметр("Искл", Искл)
    qP.УстановитьПараметр("ОТ", ОТ)
    qP.Текст = """ВЫБРАТЬ
        ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        СУММА(ВЫБОР КОГДА Т.Период < &НачМес ТОГДА
            ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ ИНАЧЕ 0 КОНЕЦ) КАК НО,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Организация=&Орг И Т.Период<=&КонМес
        И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И НЕ Т.Статья В ИЕРАРХИИ(&Искл)
        И Т.Статья = &ОТ
    СГРУППИРОВАТЬ ПО ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))
    УПОРЯДОЧИТЬ ПО КО"""
    tP = qP.Выполнить().Выгрузить()
    sНО = sКО = 0.0
    print(f"  ПАП(Источник=ПустаяСсылка, Статья=ОТ, OD-3, signed) per Подразделение:")
    for i in range(tP.Количество()):
        r = tP.Получить(i)
        но = float(r.НО or 0); ко = float(r.КО or 0)
        sНО += но; sКО += ко
        пнм = картаПодр.get(conn.XMLСтрока(r.Подр), "∅(пусто)")
        print(f"    {пнм[:34]:34} НО={но:>18,.2f}  КО={ко:>18,.2f}")
    print(f"  Σ Источник=ПустаяСсылка: НО={sНО:,.2f}  КО={sКО:,.2f}  "
          f"(строк-подр={tP.Количество()})")

    # 2) ПАП.ОстаткиИОбороты(Статья=ОТ, ВСЕ Источник) == УпрБаланс контр.число
    qB = conn.NewObject("Запрос")
    qB.УстановитьПараметр("Орг", ORG); qB.УстановитьПараметр("НачМес", НМ)
    qB.УстановитьПараметр("КонМес", КД); qB.УстановитьПараметр("ОТ", ОТ)
    qB.Текст = """ВЫБРАТЬ
        СУММА(Б.СуммаНачальныйОстаток) КАК НО,
        СУММА(Б.СуммаПриход) КАК П, СУММА(Б.СуммаРасход) КАК Р,
        СУММА(Б.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&НачМес, &КонМес, Авто, ,
        Организация = &Орг И Статья = &ОТ) КАК Б"""
    rB = qB.Выполнить().Выбрать(); rB.Следующий()
    print(f"  ПАП.ОстаткиИОбороты(Статья=ОТ, ВСЕ Источник) [== УпрБаланс]: "
          f"НО={float(rB.НО or 0):,.2f}  П={float(rB.П or 0):,.2f}  "
          f"Р={float(rB.Р or 0):,.2f}  КО={float(rB.КО or 0):,.2f}")

    # 3) аналитика «Оплата труда» Источник=ПустаяСсылка — пуста? (карточка «Без аналитики»)
    qA = conn.NewObject("Запрос")
    qA.УстановитьПараметр("Орг", ORG); qA.УстановитьПараметр("КонМес", КД)
    qA.УстановитьПараметр("ОТ", ОТ)
    qA.Текст = """ВЫБРАТЬ
        КОЛИЧЕСТВО(*) КАК Движений,
        СУММА(ВЫБОР КОГДА ВЫРАЗИТЬ(Т.Аналитика КАК Справочник.ФизическиеЛица) ЕСТЬ НЕ NULL
                ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК СФизЛицо,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Аналитика) КАК РазнАналитик
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Организация=&Орг И Т.Период<=&КонМес
        И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья = &ОТ"""
    rA = qA.Выполнить().Выбрать(); rA.Следующий()
    print(f"  Аналитика ОТ (Источник=пусто): движений={int(rA.Движений)} "
          f"ФизЛицо={int(rA.СФизЛицо)} разнАналитик={int(rA.РазнАналитик)} "
          f"(карточка «Без аналитики» → ожидаем разнАналитик<=1, ФизЛицо=0)")

print("\n[DISCOVERY DONE] эталоны зафиксированы серверно")
