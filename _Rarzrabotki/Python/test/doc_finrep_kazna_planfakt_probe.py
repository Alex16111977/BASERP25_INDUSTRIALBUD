# -*- coding: utf-8 -*-
"""Probe: структура регистров БДДС / БюджетыНаМесяц в kazna, группы статей, иерархия подразделений."""
import sys
sys.stdout.reconfigure(encoding="utf-8")
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
kazna = v8.Connect('Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"')
S = kazna.String

for reg in ("БДДС", "БюджетыНаМесяц"):
    m = getattr(kazna.Метаданные.РегистрыНакопления, reg)
    dims = [S(d.Имя) for d in m.Измерения]
    ress = [S(d.Имя) for d in m.Ресурсы]
    attrs = [S(d.Имя) for d in m.Реквизиты]
    print(f"{reg}: Измерения={dims} Ресурсы={ress} Реквизиты={attrs}")

for code in ("УТ-001053", "1В", "УТ-001097"):
    st = kazna.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду(code)
    print(f"Статья {code}: '{S(st.Наименование)}' ЭтоГруппа={st.ЭтоГруппа}")

# направление
napr = kazna.Справочники.Направления.НайтиПоНаименованию("Производство", True)
print(f"Направление: '{S(napr.Наименование)}'")

# верхний уровень статей внутри групп
q = kazna.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ Ст.Наименование КАК Имя, Ст.ЭтоГруппа КАК Гр, Ст.Родитель.Наименование КАК Род
ИЗ Справочник.СтатьиДвиженияДенежныхСредств КАК Ст
ГДЕ Ст.Родитель = &Родитель
УПОРЯДОЧИТЬ ПО Имя
"""
for code, label in (("УТ-001053", "ДОХОД"), ("1В", "РАСХОД")):
    st = kazna.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду(code)
    q.УстановитьПараметр("Родитель", st)
    r = q.Execute().Выгрузить()
    print(f"\n=== Дети группы {label} ({code}) : {r.Количество()} ===")
    for i in range(r.Количество()):
        row = r.Получить(i)
        print(f"  {'[G] ' if row.Гр else ''}{S(row.Имя)}")

# подразделения: верхний уровень с направлением Производство? проверим реквизиты справочника
mp = kazna.Метаданные.Справочники.Подразделения
print("\nПодразделения реквизиты:", [S(a.Имя) for a in mp.Реквизиты], "Иерархический:", mp.Иерархический)
