"""Pre-test (Rule #-1): для статті "Прибыли и убытки" перевірити що
запит-кандидат дає правильні дані для нової логіки Аналитика1=ПРЕДСТАВЛЕНИЕ(Подразделение).

Asserts:
  1) Рядків > 0 (очікувано ~122 за janv 2026 / ТОВ ІНДАСТРІАЛБУД)
  2) 100% рядків мають заповнений Подразделение → ПРЕДСТАВЛЕНИЕ(Подразделение) ≠ ""
  3) Σ КО (signed) per Орг — мінімум 110+ млн (як baseline)
  4) 0 дублів ключа (Орг, Подр)
"""
import sys, io
from collections import defaultdict
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

qПУ = conn.NewObject("Запрос")
qПУ.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Прибыли и убытки"')
rПУ = qПУ.Выполнить().Выбрать(); rПУ.Следующий(); ПУ = rПУ.С
print(f"[INFO] Стаття ПУ: {S(ПУ)}")

# Запит-кандидат — той самий що буде в BSL Свод_Прямой (детальна гілка)
qT = conn.NewObject("Запрос")
qT.Текст = """
ВЫБРАТЬ
    Т.Подразделение КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК Ан1_очікувано,
    СУММА(ВЫБОР КОГДА Т.Период < ДАТАВРЕМЯ(2026,1,1)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                    ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК НО,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59)
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Статья = &ПУ
СГРУППИРОВАТЬ ПО Т.Подразделение
"""
qT.УстановитьПараметр("Орг", ORG); qT.УстановитьПараметр("ПУ", ПУ)
res = qT.Выполнить().Выгрузить()
print(f"[TEST] Рядків деталей (Подр): {res.Количество()}")

fl_total = 0; fl_empty = 0
Σ_НО = 0; Σ_КО = 0
keys = defaultdict(int)
для_5_прикл = []
for i in range(res.Количество()):
    r = res.Получить(i)
    fl_total += 1
    подр = r.Подр
    ан1 = S(r.Ан1_очікувано)
    if not conn.ЗначениеЗаполнено(подр) or ан1 == "":
        fl_empty += 1
    Σ_НО += float(r.НО or 0)
    Σ_КО += float(r.КО or 0)
    keys[S(подр)] += 1
    if i < 5:
        для_5_прикл.append((ан1, float(r.КО or 0)))

print(f"\nПриклади перших 5 рядків:")
for ан, ко in для_5_прикл:
    print(f"  Подразделение='{ан}', КО={ко:>+14,.2f}")

print(f"\n[Σ]")
print(f"  Рядків: {fl_total}")
print(f"  З заповн. Подразделение: {fl_total - fl_empty}/{fl_total}")
print(f"  Σ НО: {Σ_НО:>+14,.2f}")
print(f"  Σ КО: {Σ_КО:>+14,.2f}")
дублі = sum(1 for v in keys.values() if v > 1)
print(f"  Дублі ключа (Подр): {дублі}")

# Asserts
fl_pct = 100.0 * (fl_total - fl_empty) / max(1, fl_total)
all_pass = (
    fl_total > 0
    and fl_pct >= 99.0
    and дублі == 0
    and abs(Σ_КО) > 1_000_000  # розумна перевірка що Σ > 1 млн
)
print(f"\n[VERDICT]")
print(f"  Рядків > 0:                 {'PASS' if fl_total > 0 else 'FAIL'}")
print(f"  Доля Подразд >= 99%:        {'PASS' if fl_pct >= 99 else 'FAIL'} ({fl_pct:.1f}%)")
print(f"  Дублі = 0:                  {'PASS' if дублі == 0 else 'FAIL'}")
print(f"  Σ КО розумне:               {'PASS' if abs(Σ_КО) > 1e6 else 'FAIL'} ({Σ_КО:+,.2f})")
print(f"\n{'[OK] PASS' if all_pass else '[FAIL]'}")
sys.exit(0 if all_pass else 1)
