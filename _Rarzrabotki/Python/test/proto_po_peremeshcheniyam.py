# -*- coding: utf-8 -*-
# Rule #-1 прототип: агрегация Дт-проводок проведённых ПеремещениеТоваров → заполнение
# Поступления/Реализации с наценкой. Транзакции с откатом.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
def S(v):
    try: return buh.String(v) if v is not None else "None"
    except: return "<?>"
def num(v):
    try: return float(str(v).replace('\xa0','').replace(' ','').replace(',','.'))
    except: return None

# найти 3 проведённых перемещения с Дт-проводками по номенклатуре
qm=buh.NewObject("Запрос")
qm.Text="""ВЫБРАТЬ ПЕРВЫЕ 3 Х.Регистратор КАК Рег, КОЛИЧЕСТВО(*) КАК Кво
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
ГДЕ Х.КоличествоДт>0 И ТИПЗНАЧЕНИЯ(Х.Регистратор)=ТИП(Документ.ПеремещениеТоваров)
СГРУППИРОВАТЬ ПО Х.Регистратор УПОРЯДОЧИТЬ ПО Кво УБЫВ"""
sm=qm.Execute().Выбрать()
перемещения=[]
while sm.Следующий(): перемещения.append(sm.Рег)
print(f"Перемещений найдено: {len(перемещения)}")
for p in перемещения: print("  ", S(p), "Проведен=", p.Проведен)

# агрегация Дт-проводок по (Номенклатура, СчётДт, НалНазнДт)
ТипНом = "Справочник.Номенклатура"
groups=[]; idx={}
пропущено=0
for p in перемещения:
    if not p.Проведен:
        пропущено+=1; continue
    НЗ=buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
    НЗ.Отбор.Регистратор.Установить(p); НЗ.Прочитать()
    for z in НЗ:
        if z.КоличествоДт==0: continue
        nom=None
        for kv in z.СубконтоДт:
            try:
                if kv.Значение.Метаданные().ПолноеИмя()==ТипНом: nom=kv.Значение; break
            except: pass
        if nom is None: continue
        счет=z.СчетДт; нн=z.НалоговоеНазначениеДт
        k=S(nom.УникальныйИдентификатор())+"|"+S(счет.УникальныйИдентификатор())+"|"+S(нн.УникальныйИдентификатор())
        g=idx.get(k)
        if g is None:
            g={"Ном":nom,"Счет":счет,"Нал":нн,"Кол":0.0,"Сум":0.0}; idx[k]=g; groups.append(g)
        g["Кол"]+=z.КоличествоДт; g["Сум"]+=z.Сумма
print(f"Групп(строк) агрегировано: {len(groups)}, пропущено непроведённых: {пропущено}")
if not groups:
    print("FAIL: нет Дт-строк"); sys.exit()
for g in groups[:5]:
    print(f"  {S(g['Ном'])[:26]:26} счёт={S(g['Счет'])} кол={g['Кол']:.3f} себест={g['Сум']:.2f}")

def find(typ, where=""):
    q=buh.NewObject("Запрос")
    q.Text=f"ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.{typ} {('ГДЕ '+where) if where else ''} УПОРЯДОЧИТЬ ПО Дата УБЫВ"
    s=q.Execute().Выбрать(); return s.Ссылка if s.Следующий() else None
prmPost=find("ПоступлениеТоваровУслуг")
prmReal=find("РеализацияТоваровУслуг","Номер=\"ІБ00-000110\"")
Ст20=buh.Перечисления.СтавкиНДС.НДС20
def режим(d): return buh.РежимЗаписиДокумента.ОтменаПроведения if d.Проведен else buh.РежимЗаписиДокумента.Запись
def цс(себест,кол,нац):
    if нац==0: return ((себест/кол) if кол else 0, себест)
    ц=round((себест/кол)*(1+нац/100.0),2) if кол else 0
    return ц, round(ц*кол,2)

def fill_post(нац):
    buh.НачатьТранзакцию()
    try:
        d=prmPost.ПолучитьОбъект(); d.Товары.Очистить(); d.СуммаВключаетНДС=False
        for g in groups:
            ц,с=цс(g["Сум"],g["Кол"],нац)
            r=d.Товары.Добавить()
            r.Номенклатура=g["Ном"]; r.СчетУчетаБУ=g["Счет"]; r.Количество=g["Кол"]
            r.Цена=ц; r.Сумма=с; r.ЕдиницаИзмерения=g["Ном"].БазоваяЕдиницаИзмерения; r.Коэффициент=1
            r.СтавкаНДС=Ст20; r.СуммаНДС=round(с*20/100,2); r.НалоговоеНазначение=g["Нал"]
        d.Записать(режим(d))
        d2=prmPost.ПолучитьОбъект(); bad=0
        for i,g in enumerate(groups):
            r=d2.Товары[i]; ц,с=цс(g["Сум"],g["Кол"],нац)
            if abs(num(r.Сумма)-с)>0.02 or abs(num(r.СуммаНДС)-round(с*20/100,2))>0.01: bad+=1
        print(f"  Поступление наценка={нац}%: строк={d2.Товары.Количество()} наруш={bad}")
    finally: buh.ОтменитьТранзакцию()

def fill_real(нац):
    buh.НачатьТранзакцию()
    try:
        d=prmReal.ПолучитьОбъект(); d.Товары.Очистить(); d.СуммаВключаетНДС=False
        for g in groups:
            ц,с=цс(g["Сум"],g["Кол"],нац)
            r=d.Товары.Добавить()
            r.Номенклатура=g["Ном"]; r.СчетУчетаБУ=g["Счет"]; r.Количество=g["Кол"]
            r.Цена=ц; r.Сумма=с; r.ЕдиницаИзмерения=g["Ном"].БазоваяЕдиницаИзмерения; r.Коэффициент=1
            r.СтавкаНДС=Ст20; r.СуммаНДС=round(с*20/100,2); r.НалоговоеНазначение=g["Нал"]
            r.СуммаБезСкидки=с; r.СуммаСкидки=0; r.СхемаРеализации=buh.Справочники.СхемыРеализации.Товары
        d.Записать(режим(d))
        d2=prmReal.ПолучитьОбъект(); bad=0
        for i,g in enumerate(groups):
            r=d2.Товары[i]; ц,с=цс(g["Сум"],g["Кол"],нац)
            if abs(num(r.Сумма)-с)>0.02 or abs(num(r.СуммаБезСкидки)-с)>0.01 or S(r.СхемаРеализации)!="Товары": bad+=1
        print(f"  Реализация наценка={нац}%: строк={d2.Товары.Количество()} наруш={bad}")
    finally: buh.ОтменитьТранзакцию()

print("--- заполнение из агрегата перемещений ---")
fill_post(0); fill_post(20); fill_real(0); fill_real(20)
print("Откачено — продакшн не изменён.")
