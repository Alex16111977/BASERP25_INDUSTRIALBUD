import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

print("=" * 60)
print("ТЕСТ: Перевірка ланцюга видалення А_ОтгрузкаПродукции")
print("=" * 60)

# 1. Знайти А_ОтгрузкаПродукции з підлеглими документами
q = erp.NewObject('Запрос')
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 5
    О.Ссылка,
    О.Проведен
ИЗ
    Документ.А_ОтгрузкаПродукции КАК О
ГДЕ
    НЕ О.ПометкаУдаления
    И О.Проведен = ИСТИНА
    И О.А_НачислятьУслуги = ИСТИНА
"""
r = q.Execute().Выгрузить()
print(f"\n[1] Знайдено А_ОтгрузкаПродукции (проведених, з послугами): {r.Количество()}")

ok_count = 0
for i in range(r.Количество()):
    отгрузка_ref = r.Получить(i).Ссылка
    print(f"\n--- Документ: {S(отгрузка_ref)} ---")

    # 2. Знайти А_ОказаниеУслуг
    q2 = erp.NewObject('Запрос')
    q2.Text = """
    ВЫБРАТЬ
        Д.Ссылка,
        Д.Проведен,
        Д.ПометкаУдаления
    ИЗ
        Документ.А_ОказаниеУслугМеждуПодразделениями КАК Д
    ГДЕ
        Д.ОтгрузкаПродукции = &ОтгрузкаПродукции
    """
    q2.SetParameter('ОтгрузкаПродукции', отгрузка_ref)
    r2 = q2.Execute().Выгрузить()
    print(f"  [2] А_ОказаниеУслуг знайдено: {r2.Количество()}")

    if r2.Количество() == 0:
        print("      (немає підлеглих — пропускаємо)")
        continue

    for j in range(r2.Количество()):
        оказание_ref = r2.Получить(j).Ссылка
        оказание_пометка = r2.Получить(j).ПометкаУдаления
        print(f"  [2] {S(оказание_ref)} | ПометкаУдаления={оказание_пометка}")

        # 3. Знайти РеализацияТоваровУслуг
        q3 = erp.NewObject('Запрос')
        q3.Text = """
        ВЫБРАТЬ
            Д.Ссылка,
            Д.Проведен,
            Д.ПометкаУдаления
        ИЗ
            Документ.РеализацияТоваровУслуг КАК Д
        ГДЕ
            Д.А_ОказаниеУслугМеждуПодразделениями = &ДокОснование
        """
        q3.SetParameter('ДокОснование', оказание_ref)
        r3 = q3.Execute().Выгрузить()
        print(f"  [3] РеализацияТоваровУслуг знайдено: {r3.Количество()}")

        for k in range(r3.Количество()):
            реализ_ref = r3.Получить(k).Ссылка
            реализ_пометка = r3.Получить(k).ПометкаУдаления
            print(f"  [3] {S(реализ_ref)} | ПометкаУдаления={реализ_пометка}")

            # 4. Знайти ПриобретениеТоваровУслуг через А_РеализацияТоваровУслуг
            q4 = erp.NewObject('Запрос')
            q4.Text = """
            ВЫБРАТЬ
                Д.Ссылка,
                Д.Проведен,
                Д.ПометкаУдаления,
                Д.А_РеализацияТоваровУслуг,
                Д.А_ОказаниеУслугМеждуПодразделениями
            ИЗ
                Документ.ПриобретениеТоваровУслуг КАК Д
            ГДЕ
                Д.А_РеализацияТоваровУслуг = &Реализация
            """
            q4.SetParameter('Реализация', реализ_ref)
            r4 = q4.Execute().Выгрузить()
            print(f"  [4] ПриобретениеТоваровУслуг знайдено: {r4.Количество()}")

            for m in range(r4.Количество()):
                row = r4.Получить(m)
                приобр_ref = row.Ссылка
                приобр_пометка = row.ПометкаУдаления
                поле_реализ = S(row.А_РеализацияТоваровУслуг)
                поле_оказание = S(row.А_ОказаниеУслугМеждуПодразделениями)
                print(f"  [4] {S(приобр_ref)} | ПометкаУдаления={приобр_пометка}")
                print(f"      А_РеализацияТоваровУслуг={поле_реализ}")
                print(f"      А_ОказаниеУслугМеждуПодразделениями={поле_оказание}")

        # 5. Перевірити запит з BSL (той самий що у процедурі)
        print(f"\n  [5] Перевірка BSL-запиту для ДокОснование={S(оказание_ref)}")
        q5 = erp.NewObject('Запрос')
        q5.Text = """
        ВЫБРАТЬ
            Dok.Ссылка КАК Ссылка,
            Dok.Проведен КАК Проведен
        ИЗ
            Документ.ПриобретениеТоваровУслуг КАК Dok
        ГДЕ
            Dok.А_РеализацияТоваровУслуг В
                (ВЫБРАТЬ Р.Ссылка ИЗ Документ.РеализацияТоваровУслуг КАК Р
                 ГДЕ Р.А_ОказаниеУслугМеждуПодразделениями = &ДокОснование)
            И НЕ Dok.ПометкаУдаления

        ОБЪЕДИНИТЬ ВСЕ

        ВЫБРАТЬ
            Dok.Ссылка,
            Dok.Проведен
        ИЗ
            Документ.РеализацияТоваровУслуг КАК Dok
        ГДЕ
            Dok.А_ОказаниеУслугМеждуПодразделениями = &ДокОснование
            И НЕ Dok.ПометкаУдаления
        """
        q5.SetParameter('ДокОснование', оказание_ref)
        r5 = q5.Execute().Выгрузить()
        print(f"  [5] BSL-запит повернув: {r5.Количество()} рядків")
        for m in range(r5.Количество()):
            print(f"       -> {S(r5.Получить(m).Ссылка)}")

        if r5.Количество() >= 2:
            print(f"  [5] OK: знайдено >=2 дочірніх документів ✓")
            ok_count += 1
        else:
            print(f"  [5] ПРОБЛЕМА: знайдено {r5.Количество()} — очікувалось 2 (Реализация + Приобретение)")

print("\n" + "=" * 60)
print(f"Результат: {ok_count} документів з повним ланцюгом")
print("=" * 60)
