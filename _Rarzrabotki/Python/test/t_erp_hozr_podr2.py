import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Дв.СчетДт КАК СчетДт, Дв.СчетКт КАК СчетКт,
    Дв.ПодразделениеДт КАК ПодрДт, Дв.ПодразделениеКт КАК ПодрКт,
    Дв.Сумма КАК Сумма
ИЗ
    РегистрБухгалтерии.Хозрасчетный КАК Дв
ГДЕ
    Дв.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
    И (Дв.СчетДт В ИЕРАРХИИ (&Счета) ИЛИ Дв.СчетКт В ИЕРАРХИИ (&Счета))
"""
сч = erp.NewObject("Массив")
for code in ["6411","651","642","6412","6413"]:
    a = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду(code)
    if not a.Пустая():
        сч.Добавить(a)
q.УстановитьПараметр("Счета", сч)
r = q.Execute().Выгрузить()
total = r.Количество()

# Для каждой проводки определяем сторону с налоговым счётом и берём её подразделение
nalog_codes = set(["6411","651","642","6412","6413"])
def is_nalog(acc):
    if acc.Пустая(): return False
    return str(acc.Код) in nalog_codes
пусто=0; sпусто=0.0; sзап=0.0; подр={}
for i in range(total):
    s = r.Получить(i)
    # выбираем сторону с налоговым счётом
    if is_nalog(s.СчетДт):
        p = s.ПодрДт
    elif is_nalog(s.СчетКт):
        p = s.ПодрКт
    else:
        p = s.ПодрДт
    su = float(s.Сумма)
    empty = (p is None) or (hasattr(p,'Пустая') and p.Пустая())
    if empty:
        пусто+=1; sпусто+=su
    else:
        sзап+=su
        nm=str(p.Наименование); подр[nm]=подр.get(nm,0.0)+su
print(f"Проводок налог.счетов: {total}; налоговая сторона с ПУСТЫМ подразд: {пусто} (Σ={sпусто:,.2f}); заполнено Σ={sзап:,.2f}")
print(f"Уник.подразделений (налоговая сторона): {len(подр)}")
for nm,su in sorted(подр.items(), key=lambda x:-abs(x[1]))[:20]:
    print(f"  {nm[:42]:<42} Σ={su:>16,.2f}")
