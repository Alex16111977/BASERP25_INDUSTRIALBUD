def k(v):
    """Ключ КАК У ПЛАТФОРМЫ: для ссылочных/составных измерений
    НЕОПРЕДЕЛЕНО и пустая ссылка ЭКВИВАЛЕНТНЫ (оба → ·∅·)."""
    if isinstance(v, bool):
        return f"B{int(v)}"
    if v is None:
        return "·∅·"
    try:
        if not conn.ЗначениеЗаполнено(v):
            return "·∅·"
    except Exception:
        pass
    try:
        return conn.XMLСтрока(v)
    except Exception:
        return str(v)

def raw(v):
    none = v is None
    try:
        зап = conn.ЗначениеЗаполнено(v)
    except Exception:
        зап = "?"
    try:
        xs = conn.XMLСтрока(v)
    except Exception:
        xs = "?"
    return f"None={none} Запол={зап} тип={type(v).__name__} XML={str(xs)[:36]}"

