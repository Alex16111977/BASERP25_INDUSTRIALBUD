# -*- coding: utf-8 -*-
"""Приёмка этапа 2: объекты конфигурации, общий модуль-движок, встроенные плагины,
фильтр договоров, исключения из РС, журнал в РС. Режим «Только отчёт» (без изменений
учётных данных; пишутся только РС журнала/исключений — служебные наши регистры)."""
import datetime
import sys
import time
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
M = erp.А_ВыравниваниеБазСервер

print("1. Общий модуль А_ВыравниваниеБазСервер виден через COM: OK")

M.ЗаполнитьПредопределенныеКонтуры()
cat = erp.Справочники.А_КонтурыСверкиБаз
контуры = {
    "ДеньгиБезнал": cat.ДеньгиБезнал,
    "Товары": cat.Товары,
    "Взаиморасчеты": cat.Взаиморасчеты,
    "Касса": cat.Касса,
}
for имя, ссылка in контуры.items():
    обр = str(ссылка.ИмяОбработки)
    план = erp.String(ссылка.ПланОбмена)
    assert обр.startswith("А_Синхронизировать"), (имя, обр)
    print("   %-14s -> %-38s | план: %s" % (имя, обр, план))
print("2. Предопределённые контуры заполнены")

for имя in ("А_СинхронизироватьДеньги", "А_СинхронизироватьТоварыТолькоТовары",
            "А_СинхронизироватьВзаиморасчеты", "А_СинхронизироватьДеньгиКасса",
            "А_ЦентрВыравниванияБаз"):
    объект = getattr(erp.Обработки, имя).Создать()
    assert объект is not None
print("3. Все 5 встроенных обработок создаются (модули компилируются)")

планы = M.ИменаПлановГрупп()
assert планы.Количество() == 2, планы.Количество()
print("4. Группы планов:", ", ".join(str(планы.Получить(i)) for i in range(планы.Количество())))

# --- «Только отчёт» по всем контурам (июль) ---
итоги = {}
for имя, ссылка in контуры.items():
    p = M.НовыеПараметрыСеанса(False, False)
    p.НачалоПериода = datetime.datetime(2026, 7, 1)
    p.ОкончаниеПериода = datetime.datetime(2026, 7, 19)
    t0 = time.time()
    рез = M.ОбработатьКонтур(ссылка, p)
    м = рез.Метрика
    итоги[имя] = (int(м.КлючейРасходится), int(м.КлючейОбъяснено), float(м.СуммаДельта))
    print("5. %-14s: расходится %4d | объяснено %3d | Σ|Δ| %14.3f | подтв. %d | разбор %d | %.0f сек"
          % (имя, м.КлючейРасходится, м.КлючейОбъяснено, float(м.СуммаДельта),
             м.КПодтверждению, м.РучнойРазбор, time.time() - t0))
    assert not bool(м.ЕстьОшибка), "контур %s: ЕстьОшибка" % имя
    assert int(м.Автоисправлено) == 0 and int(м.НаОбмен) == 0 and int(м.БитыхСсылок) == 0

# фильтр договоров: ключей взаиморасчётов должно быть НЕ БОЛЬШЕ 167 (было без фильтра)
assert итоги["Взаиморасчеты"][0] <= 167, итоги["Взаиморасчеты"]
print("6. Фильтр договоров: взаиморасчёты %d ключей (было 167 без фильтра)" % итоги["Взаиморасчеты"][0])

# --- исключение из РС снижает метрику (на Кассе, быстрый контур) ---
q = erp.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ж.Контур КАК Контур, Ж.КлючейРасходится КАК К
ИЗ РегистрСведений.А_ЖурналВыравниванияБаз КАК Ж ГДЕ Ж.Контур = &Контур
УПОРЯДОЧИТЬ ПО Ж.ДатаСеанса УБЫВ"""
q.SetParameter("Контур", контуры["Касса"])
r = q.Execute().Выгрузить()
assert r.Количество() >= 1, "журнал не пишется"
print("7. РС журнала пишется (записей по Кассе >= 1)")

# ключ первой расходящейся кассы возьмём повторным прогоном фазы 1 плагина
pk = erp.Обработки.А_СинхронизироватьДеньгиКасса.Создать()
pk.НачалоПериода = datetime.datetime(2026, 7, 1)
pk.ОкончаниеПериода = datetime.datetime(2026, 7, 19)
pk.СравнитьОстатки()
ключ_кассы = None
for i in range(pk.ТаблицаРасхождений.Количество()):
    row = pk.ТаблицаРасхождений.Получить(i)
    if abs(float(row.Разница)) > 0.0005:
        ключ_кассы = str(row.КассаUID)
        break
assert ключ_кассы
до = итоги["Касса"][0]
M.ДобавитьИсключение(контуры["Касса"], ключ_кассы, "ПРИЁМКА этап 2 (временное)", "удалить после теста")
p = M.НовыеПараметрыСеанса(False, False)
p.НачалоПериода = datetime.datetime(2026, 7, 1)
p.ОкончаниеПериода = datetime.datetime(2026, 7, 19)
рез2 = M.ОбработатьКонтур(контуры["Касса"], p)
м2 = рез2.Метрика
assert int(м2.КлючейРасходится) == до - 1, (до, int(м2.КлючейРасходится))
assert int(м2.КлючейОбъяснено) >= 1
print("8. Исключение из РС работает: касса %d -> %d расходится, объяснено %d"
      % (до, м2.КлючейРасходится, м2.КлючейОбъяснено))

# убрать тестовое исключение
rs = erp.РегистрыСведений.А_ИсключенияСверкиБаз.СоздатьМенеджерЗаписи()
rs.Контур = контуры["Касса"]
rs.КлючСтроки = ключ_кассы
rs.Прочитать()
if bool(rs.Выбран()):
    rs.Удалить()
print("9. Тестовое исключение удалено")

# затереть ХранилищеОбщихНастроек MVP
erp.ХранилищеОбщихНастроек.Сохранить("А_ЦентрВыравниванияБаз", "РеестрКонтуров", None)
erp.ХранилищеОбщихНастроек.Сохранить("А_ЦентрВыравниванияБаз", "Исключения", None)
erp.ХранилищеОбщихНастроек.Сохранить("А_ЦентрВыравниванияБаз", "ПоследнийСеанс", None)
assert erp.ХранилищеОбщихНастроек.Загрузить("А_ЦентрВыравниванияБаз", "РеестрКонтуров") is None
print("10. ХранилищеОбщихНастроек затёрто (антипаттерн MVP устранён)")

print("STAGE2 ACCEPTANCE OK")
