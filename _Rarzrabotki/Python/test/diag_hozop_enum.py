"""Знайти точне імя ENUM для ХозОп 'Выплата по ведомости через кассу' +
  з якого блоку коду генерується рух ПАП(ОТ) для нашого тестового РКО."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# Знайти РКО за номером
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Д ИЗ Документ.РасходныйКассовыйОрдер КАК Д ГДЕ Д.Номер = &Н"
q.УстановитьПараметр("Н", "000Ц-000284")
r = q.Выполнить().Выбрать(); r.Следующий()
ref = r.Д
obj = ref.ПолучитьОбъект()

# Імʼя enum
print(f"[Тестовий доку] {S(obj.ХозяйственнаяОперация)}")
print(f"  Метадані ХозОп: {S(obj.ХозяйственнаяОперация.Метаданные().Имя)}")
# Спробуємо через XMLРядок щоб отримати тип
hozop = obj.ХозяйственнаяОперация
# Через Менеджер пройтись
q2 = conn.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ Х.Ссылка КАК Х, Х.Порядок КАК Порядок
ИЗ Перечисление.ХозяйственныеОперации КАК Х
ГДЕ Х.Ссылка = &Х
"""
q2.УстановитьПараметр("Х", hozop)
r2 = q2.Выполнить().Выбрать()
if r2.Следующий():
    print(f"  Порядок: {r2.Порядок}")

# Метадані: Імʼя точне
xmlrep = conn.XMLСтрока(hozop)
print(f"  XMLСтрока: {xmlrep}")

# Точне імʼя ENUM-значення (через UUID lookup)
print(f"\n[Імена з enum ХозОперации]")
mh = conn.Перечисления.ХозяйственныеОперации
# Спробуємо безпосередньо через предефіновані
for имя in [
    "ВыплатаЗарплатыЧерезКассу", "ВыплатаЗарплатыРаздатчиком", "ВыплатаЗарплатыРаботнику",
    "ВыплатаПоВедомостиЧерезКассу", "ВыплатаЗарплатыПоВедомостям",
    "ВыплатаЗП", "ПогашениеЗадолженностиПередПерсоналом"
]:
    try:
        v = conn.Eval(f"Перечисления.ХозяйственныеОперации.{имя}")
        print(f"  {имя:50} = {S(v)}")
    except:
        try:
            v2 = getattr(mh, имя)
            print(f"  {имя:50} = {S(v2)}")
        except Exception as e:
            err = getattr(e, 'excepinfo', None)
            err = err[2] if err else str(e)
            print(f"  {имя:50} = ERR ({err[:60]})")
