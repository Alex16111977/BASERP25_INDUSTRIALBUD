# -*- coding: utf-8 -*-
# RED-фаза домикового режима (IRS) на BaseERP:
#  - эталонный EV снимка «ЗВіт 10.07» от плана СС BaseERP (через парс_проценты);
#  - запрос детей подразделения СС (1:1 как будет в BSL) + выделение номера домика после «№»;
#  - запрос поиска документа по СС+Подразделение+интервал дня (1:1 в BSL);
#  - базовые обороты ВООЗ в BaseERP (контроль неизменности после загрузки IRS).
import win32com.client, sys, re
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import openpyxl

XLSX = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\Виробництво\ЗВіт  виконання IRS 15 м.кв..xlsx"
СС_ИМЯ = "МД IRS 2026 15 м (МД IRS 2026)"
ДОМОВ = 6

def норм(s):
    return re.sub(r"\s+", " ", str(s or "").strip().lower().replace("'", "").replace("’", ""))

def парс_проценты(текст, n):
    t = str(текст or "").strip()
    if not t:
        return None
    сегменты = re.findall(r"(\d+)\s*модул\w*\s*-*\s*(\d+(?:[.,]\d+)?)\s*%", t, re.I)
    if сегменты:
        из = []
        for кол, проц in сегменты:
            из += [float(проц.replace(",", "."))] * int(кол)
        return (из + [0.0] * n)[:n]
    m = re.fullmatch(r"(\d+(?:[.,]\d+)?)\s*%", t)
    if m:
        return [float(m.group(1).replace(",", "."))] * n
    return None

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(СС_ИМЯ)
assert сс is not None and not сс.Пустая()
assert int(сс.КоличествоДомов) == ДОМОВ, f"КоличествоДомов={сс.КоличествоДомов}"

def тест_запроса(имя, текст, параметры):
    q = erp.NewObject("Запрос")
    q.Текст = текст
    for к, з in параметры.items():
        q.УстановитьПараметр(к, з)
    try:
        r = q.Execute().Выгрузить()
        print(f"OK  [{имя}] строк={r.Количество()}")
        return r
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"FAIL [{имя}]: {msg}")
        raise

# === Запрос 1: работы СС (существующий) ===
ТЗ = тест_запроса("РаботыСС", """
ВЫБРАТЬ
	Р.Работа КАК Работа,
	Р.Работа.Наименование КАК Наименование,
	МАКСИМУМ(Р.Этап) КАК Этап,
	СУММА(Р.Количество) КАК План
ИЗ
	Справочник.А_СтруктураСебестоимости.Работы КАК Р
ГДЕ
	Р.Ссылка = &СС
СГРУППИРОВАТЬ ПО
	Р.Работа,
	Р.Работа.Наименование
""", {"СС": сс.Ссылка})
работы_сс = {}
for i in range(ТЗ.Количество()):
    с = ТЗ.Получить(i)
    работы_сс[норм(с.Наименование)] = float(с.План)
print(f"    работ СС={len(работы_сс)}, Σплан={sum(работы_сс.values()):.2f}")

# === Запрос 2: дети подразделения СС (1:1 в BSL — ПодразделенияДомиков) ===
ТЗ_Д = тест_запроса("ДетиПодразделения", """
ВЫБРАТЬ
	П.Ссылка КАК Ссылка,
	П.Наименование КАК Наименование
ИЗ
	Справочник.СтруктураПредприятия КАК П
ГДЕ
	П.Родитель = &Родитель
УПОРЯДОЧИТЬ ПО
	П.Наименование
""", {"Родитель": сс.Подразделение})
домики = {}
for i in range(ТЗ_Д.Количество()):
    н = str(ТЗ_Д.Получить(i).Наименование)
    m = re.search(r"№(\d+)", н)
    if m:
        домики[int(m.group(1))] = н
print(f"    детей={ТЗ_Д.Количество()}, с номерами: {sorted(домики)}")
assert sorted(домики) == list(range(1, ДОМОВ + 1)), "домики №1..№6 не полны"

# === Запрос 3: поиск дока по СС+Подразделение+день (1:1 в BSL) ===
тест_запроса("ПоискДокаПоПодразделению", """
ВЫБРАТЬ ПЕРВЫЕ 1
	Д.Ссылка КАК Ссылка
ИЗ
	Документ.А_ВыполнениеРаботМодулей КАК Д
ГДЕ
	Д.СтруктураСебестоимости = &СС
	И Д.Подразделение = &Подразделение
	И Д.Дата МЕЖДУ &НачалоДня И &КонецДня
УПОРЯДОЧИТЬ ПО
	Д.Дата
""", {"СС": сс.Ссылка, "Подразделение": сс.Подразделение,
      "НачалоДня": __import__("datetime").datetime(2026, 7, 10, 12, 0, 0),
      "КонецДня": __import__("datetime").datetime(2026, 7, 10, 12, 0, 1)})

# === Excel: эталонный EV снимка ===
wb = openpyxl.load_workbook(XLSX, data_only=True)
листы = [и for и in wb.sheetnames if и.lower().startswith("звіт") and и.lower().strip() != "звіт"]
print(f"\nЛисты снимков: {листы}")
assert листы == ["ЗВіт 10.07"]
ws = wb["ЗВіт 10.07"]
кол_факта = 7
for c in range(1, min(ws.max_column, 15) + 1):
    з = str(ws.cell(1, c).value or "").lower()
    if "факт виконання робіт" in з:
        кол_факта = c
        break
print(f"Колонка факта: {кол_факта} (ожидаем 8=H)")
assert кол_факта == 8

ev = 0.0
сопоставлено = 0
ненулевые = []
for r in range(2, ws.max_row + 1):
    назв = str(ws.cell(r, 1).value or "").strip()
    if not назв or "Загальна" in назв or назв.lower() == "табель":
        continue
    план = работы_сс.get(норм(назв))
    if план is None:
        print(f"  НЕ В СС: {назв!r}")
        continue
    сопоставлено += 1
    проценты = парс_проценты(ws.cell(r, кол_факта).value, ДОМОВ) or [0.0] * ДОМОВ
    вклад = план / ДОМОВ * sum(проценты) / 100
    ev += вклад
    if вклад:
        ненулевые.append((назв, str(ws.cell(r, кол_факта).value).strip(), план, вклад))

print(f"\nСопоставлено работ: {сопоставлено}")
for назв, факт, план, вклад in ненулевые:
    print(f"  {назв!r}: {факт!r}, план {план}, вклад EV {вклад:.2f}")
print(f"ЭТАЛОН EV снимка 10.07 = {ev:.2f} (на домик = {ev/ДОМОВ:.4f})")

# === Базовые обороты ВООЗ в BaseERP (регресс-контроль) ===
q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Ссылка) КАК К
ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д
"""
т = q.Execute().Выгрузить()
q2 = erp.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т
"""
т2 = q2.Execute().Выгрузить()
print(f"\nBaseERP ДО загрузки IRS: всего доков ВРМ={int(т.Получить(0).К or 0)}, Σ РН часов={float(т2.Получить(0).Ч or 0):.2f}")
print("\nRED PASS")
