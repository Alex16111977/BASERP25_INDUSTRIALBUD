if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетPL_ПолныйЕРП.erf"
YTD_ИМЯ = "PL с начала года"
НАКОП_ИМЯ = "Накопительный PL"
ДОПУСК = 0.02

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ПРОВАЛОВ = [0]
ПРОВЕРОК = [0]


def чек(имя, ок, подробно=""):
    ПРОВЕРОК[0] += 1
    if not ок:
        ПРОВАЛОВ[0] += 1
    print("  [%s] %s%s" % ("OK  " if ок else "FAIL", имя, ("  — " + подробно) if подробно else ""))


def норм(текст):
    return re.sub(r"\s+", " ", (текст or "")).strip().lower()


def скаляр(текст, **парам):
    q = erp.NewObject("Запрос")
    q.Text = текст
    for k, v in парам.items():
        q.SetParameter(k, v)
    r = q.Execute().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() else None


ВАР = скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Вар.Ссылка КАК Ссылка ИЗ Справочник.ВариантыОтчетов КАК Вар '
             'ГДЕ Вар.Наименование = &Имя И НЕ Вар.ПометкаУдаления',
             Имя="1.P&L Производство (Месяц, Накопительный PL)")
ПОДР = скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтруктураПредприятия '
              'ГДЕ Наименование = "МК Кривий ріг" И НЕ ПометкаУдаления')
assert ВАР is not None and ПОДР is not None


def период():
    q = erp.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,1,1,0,0,0) КАК Н, ДАТАВРЕМЯ(2026,7,31,23,59,59) КАК К"
    г = q.Execute().Выгрузить().Получить(0)
    п = erp.NewObject("СтандартныйПериод")
    п.ДатаНачала = г.Н
    п.ДатаОкончания = г.К
    return п


def отключить_аналитику(структура):
    """Вариант — живые данные пользователя (в нём есть группировка «Аналитика»)."""
    for i in range(структура.Количество()):
        эл = структура.Получить(i)
        try:
            пг = эл.ПоляГруппировки
            for j in range(пг.Элементы.Количество()):
                try:
                    if S(пг.Элементы.Получить(j).Поле) == "Аналитика":
                        эл.Использование = False
                except Exception:
                    pass
        except Exception:
            pass
        for кол in ("Структура", "Строки", "Колонки"):
            try:
                отключить_аналитику(getattr(эл, кол))
            except Exception:
                pass


def параметр(н, имя, значение):
    п = н.ПараметрыДанных.Элементы.Найти(имя)
    if п is None:
        raise RuntimeError("параметр %s не найден" % имя)
    п.Использование = True
    п.Значение = значение


def построить(ytd=None, рус=None):
    отчет = erp.ВнешниеОтчеты.Создать(ERF)
    схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    к = отчет.КомпоновщикНастроек
    к.Инициализировать(erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    к.ЗагрузитьНастройки(ВАР.Настройки.Получить())
    н = к.Настройки
    отключить_аналитику(н.Структура)
    параметр(н, "Период", период())
    if ytd is not None:
        параметр(н, "ВыводитьСНачалаГода", ytd)
    if рус is not None:
        параметр(н, "НазванияНаРусском", рус)
    for i in range(н.Отбор.Элементы.Количество()):
        о = н.Отбор.Элементы.Получить(i)
        try:
            if S(о.ЛевоеЗначение) == "Подразделение":
                сп = erp.NewObject("СписокЗначений")
                сп.Добавить(ПОДР)
                о.ПравоеЗначение = сп
                о.Использование = True
        except Exception:
            pass
    таб = erp.NewObject("ТабличныйДокумент")
    отчет.СкомпоноватьРезультат(таб)
    return таб


def сетка(таб):
    в, ш = int(таб.ВысотаТаблицы), int(таб.ШиринаТаблицы)
    return [[S(таб.Область(r, c, r, c).Текст).strip() for c in range(1, ш + 1)]
            for r in range(1, в + 1)], в, ш


def блоки_шапки(g, ш):
    """{метка блока: столбец начала} по первой строке-шапке с метками блоков."""
    for r in range(min(4, len(g))):
        поз = {}
        for c in range(ш):
            x = g[r][c]
            if x and (re.match(r"^[А-ЯЁа-яё]+ \d{4}$", x) or x in (YTD_ИМЯ, НАКОП_ИМЯ, "План итого")):
                поз[x] = c
        if len(поз) >= 2:
            return поз
    return {}


def значение(g, поз, блок, строка, смещ=2):
    """Число ресурса «Сумма, грн» (смещ=2 от начала блока: Ф1, Ф2, Сумма) строки листа."""
    if блок not in поз:
        return None
    c = поз[блок] + смещ
    for ряд in g:
        первая = ""
        for x in ряд:
            if x:
                первая = x
                break
        if норм(первая) == норм(строка):
            т = (ряд[c] or "").replace("\xa0", "").replace(" ", "").replace(",", ".")
            try:
                return float(т) if т else 0.0
            except ValueError:
                return None
    return None


