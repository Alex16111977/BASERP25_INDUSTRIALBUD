# -*- coding: utf-8 -*-
"""Заповнення ДоговорыКонтрагентов.Ответственный у BuhBud (bas_industrialbud) за рахунками постачальників казни 2026.

Договори казни і BuhBud — РІЗНІ об'єкти (обмін їх не зв'язує: за UUID збіглося 3 з 837), тому:
  1) договір BuhBud (вид «С поставщиком») ↔ договір казни за (ЄДРПОУ контрагента, дата, номер «5/03» = «05/03»);
  2) не знайшовся — усі рахунки 2026 цього контрагента (ЄДРПОУ) по тій самій організації (і без договору).
Відповідальний = найчастіший автор рахунків 2026, при рівності — у кого рахунок пізніший. «cfo» казни = Постернак Андрій.
Користувачі казни → BuhBud за ім'ям, інакше за нормалізованими ПІБ (і/й→и, без ь/апострофа, порядок слів байдужий);
кого немає — пропускається (береться наступний за частотою), список у звіті.
За замовчуванням заповнюється лише ПОРОЖНІЙ реквізит.
    python buh_dogovory_otvetstvenny_iz_kazny.py            — dry-run, звіт CSV
    python buh_dogovory_otvetstvenny_iz_kazny.py --apply    — запис (бекап поточних значень у json)"""
import csv, datetime, io, json, os, re, sys
from collections import Counter, defaultdict
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ЗАПИС = "--apply" in sys.argv
ПЕРЕЗАПИС = "--overwrite" in sys.argv
ПАПКА = os.path.dirname(os.path.abspath(__file__))
# службовий логін казни «cfo» — це Постернак Андрій (вказівка користувача 30.09.2026)
ПСЕВДОНІМИ = {"cfo": "Постернак Андрій"}
com = win32com.client.Dispatch("V83.COMConnector")
kz = com.Connect('Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"')
bh = com.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = bh.String


def норм_текст(s):
    s = str(s).lower()
    for a, b in (("і", "и"), ("ї", "и"), ("й", "и"), ("є", "е"), ("ё", "е"), ("ґ", "г")):
        s = s.replace(a, b)
    s = re.sub(r"[ьъ'’ʼ\"«»]", "", s)
    return re.sub(r"\s+", " ", s).strip()


def норм_номер(s):
    групи = re.findall(r"\d+", str(s))
    return "/".join(str(int(г)) for г in групи) if групи else ""


# --- рахунки казни 2026
q = kz.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ
	С.Дата КАК Дата,
	С.Ответственный.Наименование КАК Відп,
	С.Контрагент.ЕГРПОУ КАК Код,
	С.Организация.Наименование КАК Орг,
	ЕСТЬNULL(С.ДоговорКонтрагента.Номер, "") КАК Номер,
	ЕСТЬNULL(С.ДоговорКонтрагента.Дата, ДАТАВРЕМЯ(1, 1, 1)) КАК ДатаДог
ИЗ
	Документ.СчетНаОплатуПоставщика КАК С
ГДЕ
	С.Дата >= ДАТАВРЕМЯ(2026, 1, 1)
	И НЕ С.ПометкаУдаления"""
т = q.Execute().Выгрузить()
рахунки = []
for i in range(т.Количество()):
    р = т.Получить(i)
    дд = р.ДатаДог
    рахунки.append({"дата": str(р.Дата)[:19], "відп": str(р.Відп).strip(), "код": str(р.Код).strip(),
                    "орг": норм_текст(р.Орг), "номер": норм_номер(р.Номер),
                    "датадог": "" if дд.year <= 1 else дд.strftime("%Y-%m-%d")})
print("рахунків казни 2026:", len(рахунки))

# --- користувачі BuhBud
qb = bh.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ П.Ссылка КАК С, П.Наименование КАК Н ИЗ Справочник.Пользователи КАК П ГДЕ НЕ П.ПометкаУдаления"
тб = qb.Execute().Выгрузить()
корист = [(тб.Получить(i).С, str(тб.Получить(i).Н).strip()) for i in range(тб.Количество())]
за_іменем = {н: с for с, н in корист}
за_ключем = defaultdict(list)
for с, н in корист:
    за_ключем[" ".join(sorted(норм_текст(н).split()))].append((с, н))
кеш_корист, нема_корист, неоднозначні = {}, Counter(), Counter()


def користувач(ім):
    if ім in кеш_корист:
        return кеш_корист[ім]
    знайдено = None
    if ім in за_іменем:
        знайдено = (за_іменем[ім], ім)
    else:
        варіанти = за_ключем.get(" ".join(sorted(норм_текст(ім).split())), [])
        if len(варіанти) == 1:
            знайдено = варіанти[0]
        elif len(варіанти) > 1:
            неоднозначні[ім] += 1
    кеш_корист[ім] = знайдено
    return знайдено


# --- організації: назва казни → BuhBud (для обмеження за організацією)
qo = bh.NewObject("Запрос")
qo.Текст = "ВЫБРАТЬ О.Наименование КАК Н ИЗ Справочник.Организации КАК О"
то = qo.Execute().Выгрузить()
орг_бух = {норм_текст(то.Получить(i).Н) for i in range(то.Количество())}

# --- договори BuhBud «С поставщиком»
qd = bh.NewObject("Запрос")
qd.Текст = """ВЫБРАТЬ
	Д.Ссылка КАК Дог,
	Д.Наименование КАК Назва,
	Д.Номер КАК Номер,
	Д.Дата КАК Дата,
	Д.Владелец.КодПоЕДРПОУ КАК Код,
	Д.Владелец.Наименование КАК Контр,
	Д.Организация.Наименование КАК Орг,
	ПРЕДСТАВЛЕНИЕ(Д.Ответственный) КАК Відп
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	НЕ Д.ПометкаУдаления
	И НЕ Д.ЭтоГруппа
	И Д.ВидДоговора = ЗНАЧЕНИЕ(Перечисление.ВидыДоговоровКонтрагентов.СПоставщиком)"""
тд = qd.Execute().Выгрузить()
print("договорів BuhBud «С поставщиком»:", тд.Количество())

за_ключем_договору = defaultdict(list)
за_контрагентом = defaultdict(list)
for р in рахунки:
    if р["код"] and р["номер"] and р["датадог"]:
        за_ключем_договору[(р["код"], р["датадог"], р["номер"])].append(р)
    if р["код"]:
        за_контрагентом[р["код"]].append(р)


def вибрати(рахунки_дог):
    лічильник, останній = Counter(), {}
    for р in рахунки_дог:
        ім = ПСЕВДОНІМИ.get(р["відп"], р["відп"])
        if not ім:
            continue
        к = користувач(ім)
        if к is None:
            нема_корист[ім] += 1
            continue
        лічильник[ім] += 1
        останній[ім] = max(останній.get(ім, ""), р["дата"])
    if not лічильник:
        return None, лічильник
    найкращий = max(лічильник, key=lambda ім: (лічильник[ім], останній[ім]))
    return найкращий, лічильник


рядки, зміни = [], []
стат = Counter()
for i in range(тд.Количество()):
    р = тд.Получить(i)
    код = str(р.Код).strip()
    дата = "" if р.Дата.year <= 1 else р.Дата.strftime("%Y-%m-%d")
    ключ = (код, дата, норм_номер(р.Номер))
    орг = норм_текст(р.Орг)
    if код and дата and ключ[2] and ключ in за_ключем_договору:
        набір, спосіб = за_ключем_договору[ключ], "договір (ЄДРПОУ+дата+номер)"
    elif код in за_контрагентом:
        набір = [х for х in за_контрагентом[код] if х["орг"] == орг or х["орг"] not in орг_бух]
        спосіб = "контрагент+організація" if набір else "контрагент"
        набір = набір or за_контрагентом[код]
    else:
        стат["немає рахунків у казні"] += 1
        continue
    ім, лічильник = вибрати(набір)
    поточний = str(р.Відп).strip()
    if ім is None:
        стат["лише cfo/невідомі користувачі"] += 1
        continue
    стат[спосіб] += 1
    к = користувач(ім)
    рядок = {"договір": str(р.Назва), "контрагент": str(р.Контр), "організація": str(р.Орг), "спосіб": спосіб,
             "відповідальний": к[1], "рахунків": лічильник[ім], "усі": "; ".join(f"{н}×{к_}" for н, к_ in лічильник.most_common(4)),
             "поточний": поточний}
    рядки.append(рядок)
    if поточний == к[1]:
        стат["вже так"] += 1
    elif поточний and not ПЕРЕЗАПИС:
        стат["заповнено інше — не чіпаю"] += 1
    else:
        зміни.append((р.Дог, к[0], рядок))

print("підсумок:", dict(стат))
print("буде записано:", len(зміни))
print("користувачів казни немає в BuhBud (рахунків):", нема_корист.most_common(20))
if неоднозначні:
    print("неоднозначні імена:", dict(неоднозначні))
звіт = os.path.join(ПАПКА, "buh_dogovory_otvetstvenny_report.csv")
with io.open(звіт, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(рядки[0].keys()) if рядки else ["договір"], delimiter=";")
    w.writeheader()
    w.writerows(рядки)
print("звіт:", звіт)

if not ЗАПИС:
    print("DRY-RUN. Для запису: --apply")
    sys.exit(0)
бекап = os.path.join(ПАПКА, f"buh_dogovory_otvetstvenny_backup_{datetime.datetime.now():%Y%m%d_%H%M}.json")
with io.open(бекап, "w", encoding="utf-8") as f:
    json.dump([{"uuid": S(д.УникальныйИдентификатор()), "договір": р["договір"], "було": р["поточний"]}
               for д, _, р in зміни], f, ensure_ascii=False, indent=1)
записано, помилки = 0, []
for д, користувач_реф, р in зміни:
    try:
        о = д.ПолучитьОбъект()
        о.Ответственный = користувач_реф
        о.Записать()
        записано += 1
    except Exception as e:
        помилки.append((р["договір"], str(e.excepinfo[2] if getattr(e, "excepinfo", None) else e)[:150]))
print(f"записано: {записано}; помилок: {len(помилки)} {помилки[:5]}; бекап: {бекап}")
