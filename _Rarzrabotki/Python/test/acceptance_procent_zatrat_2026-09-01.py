def сформировать(менеджер):
    отчет = менеджер.Создать()
    к = отчет.КомпоновщикНастроек
    к.Инициализировать(erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных",
                                     отчет.СхемаКомпоновкиДанных))
    к.ЗагрузитьНастройки(ВАР.Настройки.Получить())
    н = к.Настройки
    п = erp.NewObject("СтандартныйПериод")
    п.ДатаНачала = г.Н; п.ДатаОкончания = г.К
    эл = н.ПараметрыДанных.Элементы.Найти("Период")
    эл.Использование = True; эл.Значение = п

    def обойти(элементы):
        for i in range(элементы.Количество()):
            о = элементы.Получить(i)
            try:
                поле = S(о.ЛевоеЗначение)
            except Exception:
                try:
                    обойти(о.Элементы)
                except Exception:
                    pass
                continue
            if поле == "Подразделение":
                видср = S(о.ВидСравнения)
                сп = erp.NewObject("СписокЗначений"); сп.Добавить(СТРОИТ)
                if видср == "В группе из списка":
                    о.ПравоеЗначение = сп; о.Использование = True
                elif видср == "В списке":
                    о.Использование = False
    обойти(н.Отбор.Элементы)
    таб = erp.NewObject("ТабличныйДокумент")
    отчет.СкомпоноватьРезультат(таб)
    return таб


def разбор(таб):
    в, ш = int(таб.ВысотаТаблицы), int(таб.ШиринаТаблицы)
    кп = []
    for r in range(1, min(в, 30) + 1):
        for c in range(1, ш + 1):
            if "% суммы затрат" in S(таб.Область(r, c, r, c).Текст):
                кп.append(c)
        if кп:
            break
    строки = {}
    for r in range(1, в + 1):
        for c in range(1, 4):
            х = S(таб.Область(r, c, r, c).Текст).strip()
            if х:
                проц = []
                for cc in кп:
                    x = S(таб.Область(r, cc, r, cc).Текст).strip().replace("%", "").replace("\xa0", "")
                    проц.append(int(x) if re.fullmatch(r"-?\d+", x) else None)
                строки.setdefault(х, проц)
                break
    return кп, строки


