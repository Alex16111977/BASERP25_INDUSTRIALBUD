# -*- coding: utf-8 -*-
"""
Тест: убедиться что СуммаПриход для ПТУ даёт сумму С НДС (как в примере пользователя).
ПТУ от 10.01.2026 по Курьерские (Астарта. Тищенки) должен дать Сумма=176.70 (не 147.25).
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONNECTION_STRING = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected")

    # Пример пользователя: ПТУ 10.01.2026, Курьерские, Астарта.Тищенки, должно быть 176.70 с НДС.
    q = conn.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ
        Р.Регистратор КАК Документ,
        Р.Подразделение.Наименование КАК Подразделение,
        Р.СтатьяРасходов.Наименование КАК СтатьяРасходов,
        Р.СуммаПриход КАК Сумма_сНДС,
        Р.СуммаРеглПриход КАК СуммаРегл_безНДС,
        Р.НДСРеглПриход КАК НДСРегл
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(&НачалоПериода, &КонецПериода, Регистратор, ) КАК Р
    ГДЕ ТИПЗНАЧЕНИЯ(Р.Регистратор) = ТИП(Документ.ПриобретениеТоваровУслуг)
        И Р.СтатьяРасходов.Наименование ПОДОБНО "%урєрські%"
        И Р.Регистратор.Дата МЕЖДУ &НачалоПериода И &КонецПериода
    УПОРЯДОЧИТЬ ПО Р.Регистратор.Дата
    """
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(datetime(2026, 1, 1)))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(datetime(2026, 1, 31, 23, 59, 59)))

    res = q.Выполнить().Выгрузить()
    print(f"\n=== Курьерские расходы январь 2026: {res.Количество()} движений ===")
    print(f"{'Документ':60} {'Подразд':20} {'Сумма с НДС':>12} {'СуммаРегл':>10} {'НДСРегл':>8}")
    total_vat = 0.0
    total_no_vat = 0.0
    for row in res:
        doc_str = str(row.Документ)[:60]
        podr = str(row.Подразделение)[:20]
        s_vat = float(row.Сумма_сНДС)
        s_no_vat = float(row.СуммаРегл_безНДС)
        nds = float(row.НДСРегл)
        total_vat += s_vat
        total_no_vat += s_no_vat
        print(f"{doc_str:60} {podr:20} {s_vat:>12.2f} {s_no_vat:>10.2f} {nds:>8.2f}")
    print(f"{'ИТОГО':60} {'':20} {total_vat:>12.2f} {total_no_vat:>10.2f}")
    print(f"\nОжидаем: Σ с НДС ≈ 1013.70 (сумма из PL документа)")
    print(f"Факт: Σ с НДС = {total_vat:.2f}")
    if abs(total_vat - 1013.70) < 1.0:
        print("[PASS] СуммаПриход даёт сумму с НДС, совпадает с PL!")
        return 0
    else:
        print(f"[WARN] Не совпадает с PL-ожиданием 1013.70; расхождение = {total_vat - 1013.70:.2f}")
        return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
