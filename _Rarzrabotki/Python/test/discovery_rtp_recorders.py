# -*- coding: utf-8 -*-
"""Discovery — какие Регистраторы делают движения по «Расходы текущего периода»
для ТОВ ИНДАСТРИАЛБУД, какие реквизиты у них есть (СтатьяРасходов, etc).
Цель: найти источник «СтатьиДоходыРасходы» для расшифровки.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client
from datetime import datetime
from collections import Counter

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
S = erp.String

NM = datetime(2026, 4, 1, 0, 0, 0)
KM = datetime(2026, 4, 30, 23, 59, 59)

print("=" * 90)
print("РАЗДЕЛ 1: Какие типы Регистраторов делают движения по 'Расходы/Доходы текущего периода'")
print("=" * 90)
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", erp.Справочники.Организации.НайтиПоНаименованию("ТОВ ІНДАСТРІАЛБУД"))
q.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
q.УстановитьПараметр("СтДох", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Доходы текущего периода"))
q.Text = """
ВЫБРАТЬ
    ТИПЗНАЧЕНИЯ(ПАП.Регистратор) КАК ТипРег,
    ПАП.Статья,
    ПРЕДСТАВЛЕНИЕ(ПАП.Статья) КАК СтатьяПред,
    КОЛИЧЕСТВО(*) КАК Кол,
    СУММА(ПАП.Сумма) КАК СуммаВсего
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Организация = &Орг
    И (ПАП.Статья = &СтРасх ИЛИ ПАП.Статья = &СтДох)
СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(ПАП.Регистратор), ПАП.Статья
УПОРЯДОЧИТЬ ПО Кол УБЫВ
"""
r = q.Execute().Выгрузить()
print(f"  Всего комбинаций (ТипРег, Статья): {r.Количество()}")
type_set = set()
for i in range(r.Количество()):
    row = r.Получить(i)
    t = S(row.ТипРег)
    type_set.add(t)
    print(f"    {t:<60} | {S(row.СтатьяПред):<28} | {row.Кол:>6} | {row.СуммаВсего:>15.2f}")

print()
print("=" * 90)
print("РАЗДЕЛ 2: Получим РЕКВИЗИТЫ ВСЕХ типов Регистраторов — что у них есть для расшифровки?")
print("=" * 90)
# Достаём примеры регистраторов каждого типа за апрель 2026
for type_name in type_set:
    if "Документ." not in type_name:
        continue
    doc_short = type_name.replace("Документ.", "")
    print(f"\n  --- Тип: {doc_short} ---")

    # Получим один регистратор этого типа с СтатьёйРасходов
    q2 = erp.NewObject("Запрос")
    q2.УстановитьПараметр("Орг", erp.Справочники.Организации.НайтиПоНаименованию("ТОВ ІНДАСТРІАЛБУД"))
    q2.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
    q2.УстановитьПараметр("СтДох", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Доходы текущего периода"))
    q2.УстановитьПараметр("НМ", NM)
    q2.УстановитьПараметр("КМ", KM)
    q2.Text = f"""
    ВЫБРАТЬ ПЕРВЫЕ 3
        ПАП.Регистратор,
        ПАП.Период,
        ПАП.Статья,
        ПРЕДСТАВЛЕНИЕ(ПАП.Статья) КАК СтатьяПред,
        ПАП.Сумма,
        ПАП.ВидДвижения
    ИЗ
        РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
    ГДЕ
        ПАП.Организация = &Орг
        И ПАП.Период МЕЖДУ &НМ И &КМ
        И (ПАП.Статья = &СтРасх ИЛИ ПАП.Статья = &СтДох)
        И ТИПЗНАЧЕНИЯ(ПАП.Регистратор) = ТИП({type_name})
    """
    r2 = q2.Execute().Выгрузить()
    if r2.Количество() == 0:
        # Попробуем без апрельского фильтра
        q2.УстановитьПараметр("НМ", datetime(2025, 1, 1))
        q2.УстановитьПараметр("КМ", datetime(2026, 12, 31))
        r2 = q2.Execute().Выгрузить()
    if r2.Количество() == 0:
        print(f"    (нет регистраторов для примера)")
        continue
    for j in range(r2.Количество()):
        rec = r2.Получить(j).Регистратор
        try:
            # Получим metadata реквизитов документа
            meta = rec.Метаданные()
            attrs = []
            for a in meta.Реквизиты:
                attrs.append(S(a.Имя))
            # Только статьи в имени
            stat_attrs = [a for a in attrs if "Статья" in a or "Расход" in a or "Доход" in a or "АналитикаУчета" in a or "Аналитика" in a]
            print(f"    {S(rec)[:70]:<70} | {r2.Получить(j).Период}")
            if stat_attrs:
                # Достаём значения этих реквизитов
                for a in stat_attrs:
                    try:
                        val = getattr(rec, a)
                        if val is not None and str(val).strip() != "":
                            print(f"      .{a:<30} = {S(val)}")
                    except Exception as e:
                        print(f"      .{a:<30} = ERR: {e}")
            else:
                print(f"      (нет реквизитов СтатьяРасходов/Доходов/АналитикаУчета)")
                # покажем все реквизиты
                print(f"      ALL attrs: {', '.join(attrs)}")
        except Exception as e:
            print(f"      ERROR: {e}")
        break  # Один пример достаточно
