def remaining_for_K(verbose=False):
    """Непомеченные ссылки Неизвестного, привязанные к контрагенту (помеченные на удаление не в счёт)."""
    detail = {}
    for tbl, fld, is_cat in PARTNER_OBJECTS:
        q = erp.NewObject("Запрос")
        усл = " И НЕ ПометкаУдаления" if is_cat else ""
        q.Text = "ВЫБРАТЬ " + fld + " ИЗ " + tbl + " ГДЕ Контрагент=&К И " + fld + "=&P" + усл
        q.УстановитьПараметр("К", K.Ссылка); q.УстановитьПараметр("P", P)
        s = q.Execute().Выбрать()
        cnt = 0
        while s.Следующий():
            cnt += 1
        if cnt:
            detail[tbl] = cnt
    if c.same(erp, K.Партнер, P):
        detail["Контрагент.Партнер"] = 1
    for dt in DOC_TYPES:
        q = erp.NewObject("Запрос")
        q.Text = "ВЫБРАТЬ РАЗЛИЧНЫЕ Ссылка ИЗ Документ." + dt + " ГДЕ Контрагент=&К И Партнер=&P"
        q.УстановитьПараметр("К", K.Ссылка); q.УстановитьПараметр("P", P)
        s = q.Execute().Выбрать()
        cnt = 0
        while s.Следующий():
            cnt += 1
        if cnt:
            detail["Документ." + dt] = cnt
    if verbose:
        print("  остаток-детализация:", detail)
    return sum(detail.values())


