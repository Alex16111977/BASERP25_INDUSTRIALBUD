def is_real(p):
    return erp.ЗначениеЗаполнено(p) and not c.same(erp, p, P) and \
        not erp.ОбщегоНазначения.ЗначениеРеквизитаОбъекта(p, "ПометкаУдаления")


def resolve_target(k, create=False):
    """Приоритет: 0) Контрагент.Партнер реальный 1) головной 2) тёзка 3) ЕДРПОУ 4) создать."""
    # 0
    if is_real(k.Партнер):
        return k.Партнер
    # 1
    gk = k.ГоловнойКонтрагент
    if erp.ЗначениеЗаполнено(gk) and is_real(gk.Партнер):
        return gk.Партнер
    # 2
    tz = erp.Справочники.Партнеры.НайтиПоНаименованию(k.Наименование, True)
    if is_real(tz):
        return tz
    # 3
    for fld in ("КодПоЕДРПОУ", "НалоговыйНомер"):
        val = getattr(k, fld)
        if val:
            q = erp.NewObject("Запрос")
            q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 К.Партнер КАК Партнер ИЗ Справочник.Контрагенты КАК К "
                      "ГДЕ К." + fld + " = &В И К.Партнер <> &P И НЕ К.Партнер.ПометкаУдаления И К.Ссылка <> &К")
            q.УстановитьПараметр("В", val); q.УстановитьПараметр("P", P); q.УстановитьПараметр("К", k.Ссылка)
            s = q.Execute().Выбрать()
            if s.Следующий() and is_real(s.Партнер):
                return s.Партнер
    # 4 create
    if not create:
        return None  # сигнал "нужно создать"
    return erp.А_Привилегированный.ОбеспечитьРеальногоПартнераПоКонтрагенту(k.Ссылка)


def find_canonical_key(key, target):
    q = erp.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.КлючиАналитикиУчетаПоПартнерам "
              "ГДЕ Партнер=&T И Организация=&О И Контрагент=&К И Договор=&Д И НаправлениеДеятельности=&Н И Ссылка<>&С")
    q.УстановитьПараметр("T", target); q.УстановитьПараметр("О", key.Организация)
    q.УстановитьПараметр("К", key.Контрагент); q.УстановитьПараметр("Д", key.Договор)
    q.УстановитьПараметр("Н", key.НаправлениеДеятельности); q.УстановитьПараметр("С", key.Ссылка)
    s = q.Execute().Выбрать()
    return s.Ссылка if s.Следующий() else None


def find_canonical_or(o, target):
    if erp.ЗначениеЗаполнено(o.Объект):
        prm = erp.NewObject("Структура")
        prm.Вставить("Объект", o.Объект); prm.Вставить("Организация", o.Организация)
        prm.Вставить("Контрагент", o.Контрагент); prm.Вставить("Партнер", target)
        prm.Вставить("ТипРасчетов", o.ТипРасчетов)
        et = erp.ОбъектыРасчетовСервер.НайтиНовыйОбъектРасчетов(prm)
    else:
        prm = erp.ОбъектыРасчетовСервер.ПолучитьПараметрыОбъектаРасчетов()
        prm.Организация = o.Организация; prm.Партнер = target; prm.Контрагент = o.Контрагент
        prm.Договор = o.Договор; prm.НаправлениеДеятельности = o.НаправлениеДеятельности
        prm.ТипРасчетов = o.ТипРасчетов
        et = erp.ОбъектыРасчетовСервер.НайтиОбъектРасчетовПоАналитикеУчетаПоПартнерам(prm)
    if erp.ЗначениеЗаполнено(et) and not c.same(erp, et, o.Ссылка):
        return et
    return None


