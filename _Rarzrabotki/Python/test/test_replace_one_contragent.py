def create_mirror_partner(k):
    np = erp.Справочники.Партнеры.СоздатьЭлемент()
    np.Наименование = k.Наименование
    np.НаименованиеПолное = k.НаименованиеПолное or k.Наименование
    yfl = erp.XMLСтрока(k.ЮрФизЛицо) if erp.ЗначениеЗаполнено(k.ЮрФизЛицо) else ""
    if yfl in ("ФизЛицо", "ИндивидуальныйПредприниматель"):
        np.ЮрФизЛицо = erp.Перечисления.КомпанияЧастноеЛицо.ЧастноеЛицо
    else:
        np.ЮрФизЛицо = erp.Перечисления.КомпанияЧастноеЛицо.Компания
    np.Клиент = True; np.Поставщик = True; np.ПрочиеОтношения = True
    np.Записать()
    print("  СОЗДАН партнёр:", np.Наименование, c.uid(erp, np))
    return np.Ссылка


def replace_pair(old, new):
    соотв = erp.NewObject("Соответствие"); соотв.Вставить(old, new)
    prm = erp.ОбщегоНазначения.ПараметрыЗаменыСсылок()
    prm.СпособУдаления = "Пометить"
    prm.ВключатьБизнесЛогику = False
    erp.ОбщегоНазначения.ЗаменитьСсылки(соотв, prm)


def write_load(obj):
    obj.ОбменДанными.Загрузка = True
    obj.Записать()


def mark_deletion(ref):
    """Пометить дубль на удаление (ЗаменитьСсылки не помечает уже-сироту)."""
    o = ref.ПолучитьОбъект()
    o.ПометкаУдаления = True
    o.ОбменДанными.Загрузка = True
    o.Записать()


def fix_ref_field(obj, attr, target):
    """Если у объекта реквизит attr == Неизвестный -> target. Возврат True если менял."""
    try:
        if c.same(erp, getattr(obj, attr), P):
            setattr(obj, attr, target); return True
    except Exception:
        pass
    return False


