# -*- coding: utf-8 -*-
"""Rule #-1: проверка нового облика запросов под доработку (этап/счета/организация).
Остатки: Организация=&Орг И Счет В ИЕРАРХИИ(&Счета[20,22,28]) + субконто (Ном/Склад) + Счет на строку.
Нормы: Комплектующие с фильтром Этап В (&Этапы)."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
НаДату = pywintypes.Time(datetime.datetime(2026, 6, 22, 23, 59, 59))

# --- группы счетов 20/22/28 существуют? ---
Счета = buh.NewObject("Массив")
for код in ("20", "22", "28"):
    сч = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код)
    print(f"счёт-группа {код}: {'НЕТ' if сч.Пустая() else сч.Наименование}")
    if not сч.Пустая():
        Счета.Добавить(сч)

# --- найдём организацию + склад с остатками класса 2 ---
qOrg = buh.NewObject("Запрос")
qOrg.УстановитьПараметр("НаДату", НаДату)
qOrg.Текст = ('ВЫБРАТЬ РАЗЛИЧНЫЕ Ост.Организация КАК Орг ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, , , ) КАК Ост '
              'ГДЕ Ост.КоличествоОстаток > 0 И Ост.Счет.Код ПОДОБНО "2%"')
tOrg = qOrg.Выполнить().Выгрузить()
print("организаций с остатками кл.2:", tOrg.Количество())
Орг = tOrg.Получить(0).Орг if tOrg.Количество() > 0 else None
print("  тестовая орг:", buh.String(Орг) if Орг else "—")

qСк = buh.NewObject("Запрос")
qСк.Текст = ('ВЫБРАТЬ Склады.Ссылка КАК С ИЗ Справочник.Склады КАК Склады '
             'ГДЕ Склады.Наименование ПОДОБНО "%ПРО%ООН%виробнич%"')
tСк = qСк.Выполнить().Выгрузить()
Склады = buh.NewObject("Массив")
for i in range(tСк.Количество()):
    Склады.Добавить(tСк.Получить(i).С)
print("складов:", Склады.Количество())

# --- ОСТАТКИ: орг + В ИЕРАРХИИ(счета) + субконто + Счет на строку ---
q = buh.NewObject("Запрос")
q.УстановитьПараметр("НаДату", НаДату)
q.УстановитьПараметр("Счета", Счета)
q.УстановитьПараметр("Орг", Орг)
q.УстановитьПараметр("Склады", Склады)
q.Текст = """
ВЫБРАТЬ
	ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) КАК Номенклатура,
	ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) КАК Склад,
	Ост.Счет КАК Счет,
	Ост.Организация КАК Организация,
	СУММА(Ост.КоличествоОстаток) КАК Остаток
ИЗ
	РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ(&Счета), , ) КАК Ост
ГДЕ
	Ост.КоличествоОстаток > 0
	И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) В (&Склады)
СГРУППИРОВАТЬ ПО
	ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура),
	ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады),
	Ост.Счет,
	Ост.Организация
"""
try:
    t = q.Выполнить().Выгрузить()
    n = t.Количество()
    счета_set = {}
    орг_set = {}
    s = 0.0
    for i in range(n):
        r = t.Получить(i)
        s += float(r.Остаток)
        k = str(r.Счет.Код)
        счета_set[k] = счета_set.get(k, 0) + 1
        o = buh.String(r.Организация)
        орг_set[o] = орг_set.get(o, 0) + 1
    print(f"ОСТАТКИ OK rows={n} Σ={round(s,2)}")
    print(f"  счета={dict(sorted(счета_set.items()))}")
    print(f"  организации={орг_set}")
except Exception as e:
    print("ОСТАТКИ FAIL:", getattr(e,'excepinfo',[None,None,e])[2] if hasattr(e,'excepinfo') else e)

# --- НОРМЫ с фильтром этапа (include) ---
qN = buh.NewObject("Запрос")
spec = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005")  # МД Вооз EMS Мала 2026 (со скрина)
if spec.Пустая():
    spec = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000003")
Этапы = buh.NewObject("Массив")
этКаркас = buh.Справочники.ЭтапыРабот.НайтиПоНаименованию("Каркас", True)
if not этКаркас.Пустая():
    Этапы.Добавить(этКаркас.Ссылка)
qN.УстановитьПараметр("Спецификация", spec)
qN.УстановитьПараметр("Этапы", Этапы)
qN.Текст = """
ВЫБРАТЬ К.ОбщееНазвание КАК ОбщееНазвание, СУММА(К.Количество) КАК Норма
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка = &Спецификация И К.Этап В (&Этапы)
СГРУППИРОВАТЬ ПО К.ОбщееНазвание
"""
try:
    tn = qN.Выполнить().Выгрузить()
    print(f"НОРМЫ(этап=Каркас) OK строк={tn.Количество()} спец={buh.String(spec)}")
except Exception as e:
    print("НОРМЫ FAIL:", getattr(e,'excepinfo',[None,None,e])[2] if hasattr(e,'excepinfo') else e)
