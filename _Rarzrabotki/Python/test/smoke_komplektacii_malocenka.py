# -*- coding: utf-8 -*-
"""Task 8: end-to-end smoke маршрутизации малоценки.
Счёт 22 -> ТЧ .МалоценныеАктивы (ПередачаМалоценныхАктивовВЭксплуатацию);
счёт 20/28 -> ТЧ .Комплектующие (КомплектацияНоменклатуры).
Один тестовый док на семейство (ПоНормам=Додаткова). Документы НЕ проводятся, НЕ удаляются."""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8': sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
EPF = r"C:\temp_epf_kompl\Создания комплектаций для бух учета.epf"
МАРКЕР = "ТЕСТ Малоценка-роутинг (Claude) — не проводить"
НаДату = datetime.datetime(2026, 7, 13, 23, 59, 59)
ok = True

сч22 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("22")
сч20 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("20")
сч28 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("28")
сч2028 = buh.NewObject("Массив")
for c in (сч20, сч28): сч2028.Добавить(c)

def склады_по_счетам(параметр_счетов):
    q = buh.NewObject("Запрос")
    q.УстановитьПараметр("НаДату", НаДату)
    q.УстановитьПараметр("Сч", параметр_счетов)
    q.Текст = """
    ВЫБРАТЬ ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) КАК Склад, СУММА(Ост.КоличествоОстаток) КАК Кол
    ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ(&Сч), , ) КАК Ост
    ГДЕ Ост.КоличествоОстаток > 0
    СГРУППИРОВАТЬ ПО ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады)
    УПОРЯДОЧИТЬ ПО Кол УБЫВ"""
    res, s = {}, q.Выполнить().Выбрать()
    while s.Следующий():
        res[buh.String(s.Склад)] = s.Склад
    return res

скл22 = склады_по_счетам(сч22)
скл2028 = склады_по_счетам(сч2028)
оба = [k for k in скл22 if k in скл2028]
if оба:
    выбраны = [скл22[k] for k in оба[:2]]
    print(f"Склады с ОБОИМИ семействами: {len(оба)}; берём {min(2,len(оба))}")
else:
    выбраны = [скл22[k] for k in list(скл22)[:2]]
    print("Складов с обоими семействами нет — тестируем только малоценку")
for s in выбраны: print("  ", s.Наименование)

# --- спецификация (для непустой нормы; сама корректность норм не проверяется) ---
спец = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005")
if not buh.ЗначениеЗаполнено(спец):
    qs = buh.NewObject("Запрос")
    qs.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.СтруктураСебестоимости.Комплектующие"
    s = qs.Выполнить().Выбрать()
    спец = s.С.Ссылка if s.Следующий() else спец
print("Спецификація:", спец.Наименование if buh.ЗначениеЗаполнено(спец) else "НЕ НАЙДЕНА")

# --- get-or-create тестовых документов (по маркеру, идемпотентно) ---
def первая_организация():
    qo = buh.NewObject("Запрос")
    qo.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ НЕ ПометкаУдаления"
    s = qo.Выполнить().Выбрать()
    return s.С if s.Следующий() else None
орг = первая_организация()

def имеет(об, имя):
    try: getattr(об, имя); return True
    except Exception: return False

def get_or_create(тип_дока):
    qd = buh.NewObject("Запрос")
    qd.УстановитьПараметр("М", МАРКЕР)
    qd.Текст = f"ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.{тип_дока} ГДЕ ВЫРАЗИТЬ(Комментарий КАК Строка(200)) = &М"
    s = qd.Выполнить().Выбрать()
    if s.Следующий(): return s.С
    об = getattr(buh.Документы, тип_дока).СоздатьДокумент()
    об.Дата = НаДату
    if имеет(об, "Организация"): об.Организация = орг
    об.Комментарий = МАРКЕР
    об.Записать(buh.РежимЗаписиДокумента.Запись)
    return об.Ссылка

комплДок = get_or_create("КомплектацияНоменклатуры")
мавэДок  = get_or_create("ПередачаМалоценныхАктивовВЭксплуатацию")
print("Тестовые доки створені/знайдені:", buh.String(комплДок) != "", "/", buh.String(мавэДок) != "")

# --- обработка ---
обр = buh.ВнешниеОбработки.Создать(EPF, False)
обр.Период = НаДату
обр.Спецификация = спец
for s in выбраны: обр.СкладыОстатков.Добавить().Склад = s
обр.СчетаОстатков.Добавить().Счет = сч20
обр.СчетаОстатков.Добавить().Счет = сч28
обр.СчетаМалоценки.Добавить().Счет = сч22
обр.РассчитатьАнализ()

n = обр.ТабличнаяЧастьОстатков.Количество()
n22 = sum(1 for r in обр.ТабличнаяЧастьОстатков if r.Счет.Код.startswith("22"))
n_other = n - n22
внорме = sum(1 for r in обр.ТабличнаяЧастьОстатков if float(r.ВНорме) > 0)
print(f"Анализ: строк={n}, счёт22={n22}, счёт20/28={n_other}, из них В нормі={внорме}")
ok = ok and n22 > 0

# один док на семейство: и ПоНормам, и Додаткова -> тот же док
for стр in обр.ДокументиКомплектації:
    стр.ДокументПоНормам = комплДок; стр.ДокументДодаткова = комплДок
for стр in обр.ДокументиМалоценки:
    стр.ДокументПоНормам = мавэДок; стр.ДокументДодаткова = мавэДок

рез = обр.ЗаполнитьДокументыПоАнализу()
помилки = [рез.Помилки.Получить(i) for i in range(рез.Помилки.Количество())]
print(f"Заповнено={рез.Заповнено} Пропущено={рез.Пропущено} БезЕдиниці={рез.БезЕдиниці} Помилок={len(помилки)}")
for p in помилки: print("   ПОМИЛКА:", p)
ok = ok and len(помилки) == 0

# --- проверка ---
мавэ = мавэДок.ПолучитьОбъект(); компл = комплДок.ПолучитьОбъект()
кол_мавэ = мавэ.МалоценныеАктивы.Количество(); кол_компл = компл.Комплектующие.Количество()
плохие_мавэ = sum(1 for r in мавэ.МалоценныеАктивы if not r.СчетУчетаБУ.Код.startswith("22"))
плохие_компл = sum(1 for r in компл.Комплектующие if r.СчетУчетаБУ.Код.startswith("22"))
# у МалоценныеАктивы не должно быть Сумма (проверяем что реквизита нет)
имеет_сумму_мавэ = имеет(мавэ.МалоценныеАктивы.Добавить(), "Сумма"); мавэ.МалоценныеАктивы.Удалить(мавэ.МалоценныеАктивы.Количество()-1)
print(f"МАВЭ.МалоценныеАктивы={кол_мавэ} (чужой счёт={плохие_мавэ}) | Компл.Комплектующие={кол_компл} (счёт22={плохие_компл})")
print(f"МалоценныеАктивы имеет реквизит Сумма: {имеет_сумму_мавэ} (ожидаем False)")

ok = ok and кол_мавэ > 0 and плохие_мавэ == 0 and плохие_компл == 0 and (not имеет_сумму_мавэ)
if n_other > 0:
    ok = ok and кол_компл > 0
print("RESULT:", "PASS" if ok else "FAIL")
