# -*- coding: utf-8 -*-
# Тест Op 2b: fallback на РаспределениеКазна.СуммаНачисления для ФізОсіб,
# які є в Казні але відсутні в НачисленияУпр (128 людей за грудень 2025).
#
# ПЕРЕДУМОВА: оновлений ObjectModule.bsl завантажений у конфігурацію (F7).
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


def parse_num(s):
    return float(S(s).replace('\xa0', '').replace(' ', '').replace(',', '.') or "0")


# Знайти документ
q = erp.NewObject("Запрос")
q.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка "
    "ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д "
    "ГДЕ Д.Номер = &Н И Д.Дата МЕЖДУ &Д1 И &Д2"
)
q.SetParameter("Н", "000000001")
q.SetParameter("Д1", com_date(2025, 12, 31, 0, 0, 0))
q.SetParameter("Д2", com_date(2025, 12, 31, 23, 59, 59))
sel = q.Execute().Выбрать()
if not sel.Следующий():
    print("ПОМИЛКА: документ не знайдено")
    sys.exit(1)

obj = sel.Ссылка.ПолучитьОбъект()
print(f"Документ: {S(obj.Ссылка)}")

# Виклик
print("\n>>> Виклик ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете() ...")
try:
    obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
    print(">>> OK")
except Exception as e:
    print(f">>> ПОМИЛКА: {e}")
    sys.exit(1)

# Стан ТЧ
nz = obj.НачисленнаяЗарплатаИВзносыПоФизлицам
nd = obj.НачисленныйНДФЛ
print(f"\nНачисленнаяЗарплатаИВзносыПоФизлицам: {nz.Количество()} рядків")
print(f"НачисленныйНДФЛ:                      {nd.Количество()} рядків")

# Збираємо унікальні ФізОсоби в НЗ+ВзносыВсего/Сумма
фіз_в_НЗ = set()
total_сума_нз = 0.0
total_взноси_нз = 0.0
for i in range(nz.Количество()):
    r = nz.Получить(i)
    if erp.ЗначениеЗаполнено(r.ФизическоеЛицо):
        фіз_в_НЗ.add(S(r.ФизическоеЛицо))
    total_сума_нз += parse_num(r.Сумма)
    total_взноси_нз += parse_num(r.ВзносыВсего)

print(f"\n=== Підсумок НачисленнаяЗарплатаИВзносыПоФизлицам ===")
print(f"  Унікальних ФізОсіб: {len(фіз_в_НЗ)}")
print(f"  Σ Сумма:            {total_сума_нз:>15,.2f}")
print(f"  Σ ВзносыВсего:      {total_взноси_нз:>15,.2f}")

# Запит на SQL-side: кого з РаспределениеКазна з СуммаНачисления > 0 НЕМА в НачисленнаяЗарплатаИВзносыПоФизлицам
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    РК.Сотрудник.ФизическоеЛицо КАК ФизЛицо
ПОМЕСТИТЬ КазнаФЛ
ИЗ Документ.А_ОтражениеЗПпоКазне.РаспределениеКазна КАК РК
ГДЕ РК.Ссылка = &Ссылка И РК.СуммаНачисления > 0
;
ВЫБРАТЬ РАЗЛИЧНЫЕ
    НЗ.ФизическоеЛицо КАК ФизЛицо
ПОМЕСТИТЬ НЗФЛ
ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленнаяЗарплатаИВзносыПоФизлицам КАК НЗ
ГДЕ НЗ.Ссылка = &Ссылка И НЗ.Сумма > 0
;
ВЫБРАТЬ
    К.ФизЛицо.Наименование КАК Имя
ИЗ КазнаФЛ КАК К
    ЛЕВОЕ СОЕДИНЕНИЕ НЗФЛ КАК Н ПО К.ФизЛицо = Н.ФизЛицо
ГДЕ Н.ФизЛицо ЕСТЬ NULL
"""
q2.SetParameter("Ссылка", obj.Ссылка)
r2 = q2.Execute().Выгрузить()
print(f"\n=== ФізОсоби з Казни (СуммаНачисления>0) ВІДСУТНІ у НЗ ===")
print(f"  Кількість: {r2.Количество()}")
for i in range(min(10, r2.Количество())):
    print(f"    - {S(r2.Получить(i).Имя)}")
if r2.Количество() > 10:
    print(f"    ... і ще {r2.Количество() - 10}")

# Критерій: після Op 2b таких має бути ~0 (або дуже мало — ті що мають порожній Сотрудник)
print("\n=== ПЕРЕВІРКИ ===")
checks = [
    (nz.Количество() > 0, "НачисленнаяЗарплатаИВзносыПоФизлицам не пуста"),
    (len(фіз_в_НЗ) >= 100, f"У НЗ є >= 100 ФізОсіб (зараз {len(фіз_в_НЗ)}) — 63 з zup_2 + 128 з Казни"),
    (r2.Количество() <= 5, f"Майже всі ФізОсоби з Казни (СумНач>0) потрапили в НЗ (відсутніх: {r2.Количество()})"),
]
all_ok = True
for ok, desc in checks:
    mark = "OK" if ok else "FAIL"
    print(f"  [{mark}] {desc}")
    if not ok:
        all_ok = False

print()
if all_ok:
    print("==> ЧАСТИНА B (Op 2b fallback) ПРОЙДЕНА")
    sys.exit(0)
else:
    print("==> ПОМИЛКИ")
    sys.exit(1)
