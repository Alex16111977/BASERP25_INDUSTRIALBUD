def q(text, **p):
    z = erp.NewObject("Запрос")
    z.Text = text
    for k, v in p.items():
        z.SetParameter(k, v)
    return z.Execute().Выгрузить()


def excel_procenty():
    """{(колонка «Доход», месяц): сумма %%} — только дневные ячейки вида =<Итого><r>*NN%/365, без подытогов."""
    from openpyxl.utils import column_index_from_string as CI, get_column_letter as L
    wf = openpyxl.load_workbook(XLSX)[ЛИСТ]
    wv = openpyxl.load_workbook(XLSX, data_only=True)[ЛИСТ]
    res = {}
    for col, _ in КАРТА.values():
        pc = CI(col) + 3
        for r in range(3, 398):
            d, f = wf.cell(r, 1).value, wf.cell(r, pc).value
            if not isinstance(d, dt.datetime) or d.year != 2026:
                continue
            if isinstance(f, str) and re.fullmatch(r"=%s%d\*\d+%%/365" % (L(pc - 1), r), f):
                res[(col, d.month)] = res.get((col, d.month), 0) + (wv.cell(r, pc).value or 0)
    return res


