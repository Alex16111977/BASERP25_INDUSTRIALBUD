# -*- coding: utf-8 -*-
"""Платёжки кредитных ОУМП (Кредитование = Истина) — «Создать оплаты» через COM и сверка с ОУМП.

    python sozdat_oplaty_kredit.py 000000581,000000582          # только сверка (по умолчанию)
    python sozdat_oplaty_kredit.py 000000581,000000582 --apply  # пересоздать оплаты, потом сверка
    python sozdat_oplaty_kredit.py 000000594 --beznal          # сверка только безналичных строк и платёжек
    python sozdat_oplaty_kredit.py 000000594 --apply --beznal-only --dry  # что получит каждая сторона, без записи
    python sozdat_oplaty_kredit.py 000000594 --apply --beznal-only --beznal  # только безнал: перенос + сверка
    python sozdat_oplaty_kredit.py 000000577 --apply --kassa="Касса для бюджетных операций" --dry  # наличка: план
    python sozdat_oplaty_kredit.py 000000577 --apply --kassa="Касса для бюджетных операций"        # наличка + сверка

--apply по каждому ОУМП:
  - «Деньги» пусты → «Заполнить» (НачислитьУслугиНаСервере) и запись документа без перепроведения;
  - СоздатьОплатыНаСервере() — то же, что кнопка «Создать оплаты»: безналичные платёжки переиспользуются
    (тот же номер), кассовые ордера помечаются на удаление и создаются заново.
Проверено 15.10.2026: при вызове через COM РегистраторРасчетов и записи «ПоСрокам» создаются.

--beznal-only (16.10.2026): перед «Создать оплаты» из «Деньги» В ПАМЯТИ удаляются небезналичные строки, ОУМП не
  записывается — кассовые ордера по ним не создаются. Фаза 1 «Создать оплаты» помечает на удаление ВСЕ ордера ОУМП,
  поэтому при найденном непомеченном РКО/ПКО документа ОУМП пропускается (наличку не трогаем).
--kassa=<наименование> (16.10.2026, решение пользователя): в наличных строках «Деньги» обе кассы (расход и приход)
  заменяются этой кассой и ОУМП записывается (режим «Запись», движений у ОУМП нет). Без ключа код взял бы кассу из
  строки, а если там банковский счёт — «Касса ЦО». Сверка проверяет кассу РКО/ПКО.
--dry: вместо «Создать оплаты» печатает договор каждой кредитной стороны (недостающий кредитный договор при этом
  создаётся — как это сделала бы кнопка), платёжки не трогает.

Сверка: на каждую сторону строки «Деньги» ровно одна непомеченная проведённая платёжка; её контрагент =
контрагент стороны, договор того же контрагента, вида стороны и подразделения стороны, сумма = сумме строки.
Перекидки кредита между подразделениями (обе статьи — заёмщика, например ОУМП 599) сюда не относятся.
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
NUMS = sys.argv[1].split(",")
APPLY = "--apply" in sys.argv
BEZNAL = "--beznal" in sys.argv
BEZNAL_ONLY = "--beznal-only" in sys.argv
DRY = "--dry" in sys.argv
KASSA_NAME = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--kassa=")), None)
KASSA = None
if KASSA_NAME:
    KASSA = erp.Справочники.Кассы.НайтиПоНаименованию(KASSA_NAME, True)
    if not erp.ЗначениеЗаполнено(KASSA):
        sys.exit(f"касса «{KASSA_NAME}» не найдена")


def q(text, **p):
    z = erp.NewObject("Запрос")
    z.Text = text
    for k, v in p.items():
        z.SetParameter(k, v)
    return z.Execute().Выгрузить()


def uid(ref):
    return S(ref.УникальныйИдентификатор())


if APPLY:
    for num in NUMS:
        t = q("""ВЫБРАТЬ Д.Ссылка ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями КАК Д
ГДЕ Д.Номер = &Н И Д.Кредитование И НЕ Д.ПометкаУдаления""", Н=num)
        if t.Количество() != 1:
            print(num, "— кредитный ОУМП не найден, пропуск")
            continue
        ref = t.Получить(0).Получить(0)
        obj = ref.ПолучитьОбъект()
        if obj.Деньги.Количество() == 0:
            obj.НачислитьУслугиНаСервере()
            if DRY:
                obj.А_ЗаполнитьКредитныеКолонкиДеньги()  # при записи это делает ПередЗаписью
                print(num, "— «Деньги» заполнены по Казне В ПАМЯТИ (--dry):", obj.Деньги.Количество())
            else:
                obj.Записать(erp.РежимЗаписиДокумента.Запись)
                obj = ref.ПолучитьОбъект()
                print(num, "— «Деньги» заполнены по Казне:", obj.Деньги.Количество())
        if KASSA is not None:
            нал = erp.Перечисления.ФормыОплаты.Наличная
            замен = 0
            for i in range(obj.Деньги.Количество()):
                стр = obj.Деньги.Получить(i)
                if S(стр.ФормаОплаты) != S(нал):
                    continue
                for поле in ("СчетКассаРасход", "СчетКассаПриход"):
                    было = getattr(стр, поле)
                    if not (erp.ЗначениеЗаполнено(было) and S(было) == S(KASSA) and uid(было) == uid(KASSA)):
                        print(num, f"— строка {S(стр.КодСтроки)} {поле}: «{S(было)}» → «{S(KASSA)}»")
                        setattr(стр, поле, KASSA)
                        замен += 1
            if замен and not DRY:
                obj.Записать(erp.РежимЗаписиДокумента.Запись)
                obj = ref.ПолучитьОбъект()
                print(num, "— касса в наличных строках записана")
        if BEZNAL_ONLY:
            ордера = q("""ВЫБРАТЬ Д.Ссылка ИЗ Документ.РасходныйКассовыйОрдер КАК Д
ГДЕ Д.А_ОказаниеУслугМеждуПодразделениями = &О И НЕ Д.ПометкаУдаления
ОБЪЕДИНИТЬ ВСЕ ВЫБРАТЬ Д.Ссылка ИЗ Документ.ПриходныйКассовыйОрдер КАК Д
ГДЕ Д.А_ОказаниеУслугМеждуПодразделениями = &О И НЕ Д.ПометкаУдаления""", О=ref)
            if ордера.Количество():
                print(num, "— есть кассовые ордера:", ", ".join(S(ордера.Получить(i).Получить(0)) for i in range(ордера.Количество())),
                      "— «Создать оплаты» пометил бы их на удаление, пропуск")
                continue
            безнал = erp.Перечисления.ФормыОплаты.Безналичная
            for i in reversed(range(obj.Деньги.Количество())):
                стр = obj.Деньги.Получить(i)
                if S(стр.ФормаОплаты) != S(безнал):
                    print(num, f"— строка {S(стр.КодСтроки)} ({S(стр.ФормаОплаты)}, {S(стр.Сумма)}) убрана в памяти, ОУМП не записывается")
                    obj.Деньги.Удалить(стр)
        if DRY:
            Т = erp.Перечисления.ТипыДоговоров
            for i in range(obj.Деньги.Количество()):
                стр = obj.Деньги.Получить(i)
                возврат = S(стр.ТипыРасчетаДенежнымиСредствами) == S(erp.Перечисления.ТипыРасчетаДенежнымиСредствами.ВозвратДенежныхСредств)
                for расход, тип in ((True, Т.СПокупателем if возврат else Т.СПоставщиком),
                                    (False, Т.СПоставщиком if возврат else Т.СПокупателем)):
                    р = obj.А_КредитнаяСторона(стр, расход, тип)
                    сторона = "Расход" if расход else "Приход"
                    if р is None:
                        print(num, сторона, "— не кредитная сторона, прежний подбор")
                    else:
                        print(num, S(стр.КодСтроки), S(стр.ФормаОплаты), S(стр.Сумма), сторона, "→", S(р.Контрагент), "/",
                              S(р.Договор), "/", S(р.Договор.ТипДоговора),
                              "/ получатель:", S(р.Договор.А_ПодразделениеОказаниеУслугПодразделению) or "—",
                              "/ касса:", S(стр.СчетКассаРасход if расход else стр.СчетКассаПриход))
            continue
        obj.СоздатьОплатыНаСервере()
        print(num, "— оплаты созданы")

arr = erp.NewObject("Массив")
for n in NUMS:
    arr.Добавить(n)
dn = q("""ВЫБРАТЬ Т.Ссылка.Номер КАК Н, Т.Сумма КАК Сум, Т.ФормаОплаты КАК Ф, Т.СчетКассаРасход КАК КассаР, Т.СчетКассаПриход КАК КассаП, Т.ПодразделениеРасход КАК ПР, Т.КонтрагентРасход КАК КР,
 Т.ВидДоговораРасход КАК ВР, Т.ПодразделениеПриход КАК ПП, Т.КонтрагентПриход КАК КП, Т.ВидДоговораПриход КАК ВП,
 Т.СтатьяДвиженияДенежныхСредствРасход.А_ПартнерРасчетов <> ЗНАЧЕНИЕ(Справочник.Партнеры.ПустаяСсылка) КАК КредРасх,
 Т.СтатьяДвиженияДенежныхСредствПриход.А_ПартнерРасчетов <> ЗНАЧЕНИЕ(Справочник.Партнеры.ПустаяСсылка) КАК КредПрих
ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями.Деньги КАК Т ГДЕ Т.Ссылка.Номер В (&Н) И Т.Ссылка.Кредитование"""
       + (" И Т.ФормаОплаты = ЗНАЧЕНИЕ(Перечисление.ФормыОплаты.Безналичная)" if BEZNAL else ""), Н=arr)

ПЛАТЕЖКИ = """ВЫБРАТЬ Д.А_ОказаниеУслугМеждуПодразделениями.Номер КАК Н, "{сторона}" КАК Ст, "{форма}" КАК Ф, {касса} КАК Касса,
 Д.Ссылка КАК Док, Д.Контрагент КАК К,
 Д.Договор КАК Дог, ВЫРАЗИТЬ(Д.Договор КАК Справочник.ДоговорыКонтрагентов).Контрагент КАК КонтрДог,
 ВЫРАЗИТЬ(Д.Договор КАК Справочник.ДоговорыКонтрагентов).А_ВидКредитногоДоговора КАК Вид,
 ВЫРАЗИТЬ(Д.Договор КАК Справочник.ДоговорыКонтрагентов).Подразделение КАК ПодрДог, Д.Подразделение КАК Подр,
 ВЫРАЗИТЬ(Д.Договор КАК Справочник.ДоговорыКонтрагентов).А_ПодразделениеОказаниеУслугПодразделению КАК Получ,
 Д.СуммаДокумента КАК Сум, Д.Проведен КАК Пр
ИЗ Документ.{док} КАК Д ГДЕ Д.А_ОказаниеУслугМеждуПодразделениями.Номер В (&Н) И НЕ Д.ПометкаУдаления"""
безнал_ф, нал_ф = S(erp.Перечисления.ФормыОплаты.Безналичная), S(erp.Перечисления.ФормыОплаты.Наличная)
виды = [("Расход", "СписаниеБезналичныхДенежныхСредств", безнал_ф, "НЕОПРЕДЕЛЕНО"),
        ("Приход", "ПоступлениеБезналичныхДенежныхСредств", безнал_ф, "НЕОПРЕДЕЛЕНО")]
if not BEZNAL:
    виды += [("Расход", "РасходныйКассовыйОрдер", нал_ф, "Д.Касса"), ("Приход", "ПриходныйКассовыйОрдер", нал_ф, "Д.Касса")]
текст = "\nОБЪЕДИНИТЬ ВСЕ\n".join(ПЛАТЕЖКИ.format(сторона=ст, док=док, форма=ф, касса=к) for ст, док, ф, к in виды)
pay = q(текст, Н=arr)
P = {}
for i in range(pay.Количество()):
    r = pay.Получить(i)
    P.setdefault((S(r.Н), S(r.Ст), S(r.Ф)), []).append(r)

# 16.10.2026: договор стороны кредитора — пара «ЦО → заёмщик» (получатель = подразделение другой стороны),
# у стороны заёмщика получатель пуст.
fails = 0
for i in range(dn.Количество()):
    d = dn.Получить(i)
    for side, podr, kontr, vid, kred, drug in (("Расход", d.ПР, d.КР, d.ВР, d.КредРасх, d.ПП),
                                                ("Приход", d.ПП, d.КП, d.ВП, d.КредПрих, d.ПР)):
        lst = P.get((S(d.Н), side, S(d.Ф)), [])
        if len(lst) != 1:
            fails += 1
            print(S(d.Н), side, S(d.Ф), "— документов:", len(lst))
            continue
        p = lst[0]
        ok = (uid(p.К) == uid(kontr) and uid(p.КонтрДог) == uid(kontr) and S(p.Вид) == S(vid)
              and S(p.ПодрДог) == S(podr) and S(p.Подр) == S(podr) and float(p.Сум) == float(d.Сум) and p.Пр
              and S(p.Получ) == (S(drug) if kred else "")
              and (S(d.Ф) != нал_ф or uid(p.Касса) == uid(d.КассаР if side == "Расход" else d.КассаП))
              and (KASSA is None or S(d.Ф) != нал_ф or uid(p.Касса) == uid(KASSA)))
        fails += 0 if ok else 1
        print(" | ".join([S(d.Н), side, S(p.Док), S(p.К), S(p.Дог), S(p.Сум)]
                         + ([S(p.Касса)] if S(d.Ф) == нал_ф else []) + ["OK" if ok else "РАСХОЖДЕНИЕ"]))
print("ПРОВАЛОВ:", fails)
sys.exit(1 if fails else 0)
