# -*- coding: utf-8 -*-
"""ОУМП с галочкой «Кредитование»: контрагенты расхода/прихода в ТЧ «Деньги».

Правило (подтверждено пользователем 14.10.2026):
  - сторона с видом «Тело кредита» (подразделение, которое получает или возвращает кредит) — контрагент самого
    подразделения (партнёр с А_Подразделение = подразделение стороны); как «Плательщик» во входящей платёжке;
  - другая сторона — кредитор Воронцов О.В.
  Пустые документы сначала заполняются стандартно из Казны (НачислитьУслугиНаСервере).
  Документы только записываются (РежимЗаписиДокумента.Запись), НЕ перепроводятся.
  Наличные пока не трогаем (решение пользователя 14.10.2026): документ, где после заполнения есть строка с формой
  оплаты «Наличная», пропускается целиком и не записывается.

    python zapolnit_kontragenty.py          # пробный прогон: таблица «было → станет», без записи
    python zapolnit_kontragenty.py --write  # записать
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
WRITE = "--write" in sys.argv
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ТЕЛО = erp.Перечисления.А_ВидыКредитныхДоговоров.ТелоКредита
ВОЗВРАТ = erp.Перечисления.ТипыРасчетаДенежнымиСредствами.ВозвратДенежныхСредств
ВОРОНЦОВ = None
НАЛИЧНАЯ = erp.Перечисления.ФормыОплаты.Наличная


def q(text, **p):
    z = erp.NewObject("Запрос")
    z.Text = text
    for k, v in p.items():
        z.SetParameter(k, v)
    return z.Execute().Выгрузить()


r = q('ВЫБРАТЬ К.Ссылка ИЗ Справочник.Контрагенты КАК К ГДЕ К.Наименование = "Воронцов Олександр Володимирович" '
      'И К.Партнер.Наименование = "Воронцов Олександр Володимирович"')
ВОРОНЦОВ = r.Получить(0).Получить(0)


def kontragent_podrazdeleniya(podr):
    t = q("""ВЫБРАТЬ ПЕРВЫЕ 1 Контр.Ссылка ИЗ Справочник.Контрагенты КАК Контр
ГДЕ Контр.Партнер.А_Подразделение = &П И НЕ Контр.ПометкаУдаления И НЕ Контр.Партнер.ПометкаУдаления""", П=podr)
    return t.Получить(0).Получить(0) if t.Количество() else None


docs = q("""ВЫБРАТЬ Д.Ссылка ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями КАК Д
ГДЕ Д.Кредитование И НЕ Д.ПометкаУдаления УПОРЯДОЧИТЬ ПО Д.Дата, Д.Номер""")
print(("ЗАПИСЬ" if WRITE else "ПРОБНЫЙ ПРОГОН (без записи)") + f", документов: {docs.Количество()}\n")
print("Документ | Дата | Строка | Подр. расход → контрагент расход | Подр. приход → контрагент приход | Сумма | Заполнено из Казны")
errors = 0
for i in range(docs.Количество()):
    o = docs.Получить(i).Получить(0).ПолучитьОбъект()
    filled = False
    if o.Деньги.Количество() == 0:
        o.НачислитьУслугиНаСервере()
        filled = True
    наличные = [o.Деньги.Получить(j) for j in range(o.Деньги.Количество())
                if S(o.Деньги.Получить(j).ФормаОплаты) == S(НАЛИЧНАЯ)]
    if наличные:
        print(f"-- {S(o.Номер)} | {S(o.Дата)[:10]} | ПРОПУЩЕН: наличная форма оплаты в {len(наличные)} строке(ах), "
              f"сумма {S(наличные[0].Сумма)}")
        continue
    for j in range(o.Деньги.Количество()):
        s = o.Деньги.Получить(j)
        # вид сторон по статьям (если пусто)
        if not S(s.ВидДоговораРасход) and S(s.СтатьяДвиженияДенежныхСредствРасход):
            s.ВидДоговораРасход = s.СтатьяДвиженияДенежныхСредствРасход.А_ВидКредитногоДоговора
        if not S(s.ВидДоговораПриход) and S(s.СтатьяДвиженияДенежныхСредствПриход):
            s.ВидДоговораПриход = s.СтатьяДвиженияДенежныхСредствПриход.А_ВидКредитногоДоговора
        возврат = S(s.ТипыРасчетаДенежнымиСредствами) == S(ВОЗВРАТ)
        # сторона-заёмщик: при выдаче — приход, при возврате — расход
        if возврат:
            заём_расход = True
        else:
            заём_расход = S(s.ВидДоговораРасход) == S(ТЕЛО) and S(s.ВидДоговораПриход) != S(ТЕЛО)
        было = (S(s.КонтрагентРасход), S(s.КонтрагентПриход))
        if заём_расход:
            кр, кп = kontragent_podrazdeleniya(s.ПодразделениеРасход), ВОРОНЦОВ
        else:
            кр, кп = ВОРОНЦОВ, kontragent_podrazdeleniya(s.ПодразделениеПриход)
        if кр is None or кп is None:
            errors += 1
            print(f"!! {S(o.Номер)}: не найден контрагент подразделения "
                  f"{S(s.ПодразделениеРасход) if кр is None else S(s.ПодразделениеПриход)}")
            continue
        s.КонтрагентРасход, s.КонтрагентПриход = кр, кп
        print(f"{S(o.Номер)} | {S(o.Дата)[:10]} | {j + 1} | {S(s.ПодразделениеРасход)} → {S(кр)}"
              f" (было «{было[0]}») | {S(s.ПодразделениеПриход)} → {S(кп)} (было «{было[1]}») | {S(s.Сумма)}"
              f" | {'да' if filled else 'нет'}")
    if WRITE:
        o.Записать(erp.РежимЗаписиДокумента.Запись)
print(f"\nошибок: {errors}")
