# -*- coding: utf-8 -*-
"""Налаштування для документа «Нарахування відсотків за кредитами» (план 2026-10-16, Task 1, крок 8).

    python procenty_nastroyka.py           # сухий прогін: що буде створено
    python procenty_nastroyka.py --apply   # створити послугу і записати ставки 18%

1. Послуга «Відсотки за користування позикою» — клон «Фінансова послуга для звіту P&L» (послуга, яку ставить ОУМП):
   вид номенклатури, група, одиниця; ставка ПДВ — «Без ПДВ», якщо знайдеться.
2. Ставка 18% з 01.01.2025 у РегистрСведений.А_ПроцентныеСтавкиКредитов для кожного договору з
   А_ВидКредитногоДоговора = «Проценты» без жодного запису. Записи 20% (Excel: 01.06–30.07.2026 у «Производство …»,
   AV, ПРООН, Спецтехника) не пишуться — однозначного зіставлення колонок Excel з договорами немає, вирішує користувач.
"""
import datetime as dt
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
APPLY = "--apply" in sys.argv
ИМЯ = "Відсотки за користування позикою"
ОБРАЗЕЦ = "Фінансова послуга для звіту P&L"
ПЕРИОД = dt.datetime(2025, 1, 1) + dt.timedelta(hours=3)  # COM віднімає 3 год (пам'ять com-date-shift-3-hours)
СТАВКА = 18


def q(text, **p):
    z = erp.NewObject("Запрос")
    z.Text = text
    for k, v in p.items():
        z.SetParameter(k, v)
    return z.Execute().Выгрузить()


# --- 1. послуга
ном = erp.А_НачислениеПроцентовПоКредитамСервер.НоменклатураПроцентов()
if erp.ЗначениеЗаполнено(ном):
    print("послуга вже є:", S(ном))
else:
    обр = q("""ВЫБРАТЬ ПЕРВЫЕ 1 Н.Ссылка ИЗ Справочник.Номенклатура КАК Н
ГДЕ Н.Наименование = &Имя И НЕ Н.ЭтоГруппа И НЕ Н.ПометкаУдаления
 И Н.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Услуга)""", Имя=ОБРАЗЕЦ)
    assert обр.Количество() == 1, "зразок не знайдено"
    обр = обр.Получить(0).Получить(0)
    print("послуга буде створена клоном", S(обр), "| група", S(обр.Родитель), "| вид", S(обр.ВидНоменклатуры))
    if APPLY:
        нов = обр.ПолучитьОбъект().Скопировать()  # копія без коду і посилання
        нов.Наименование = ИМЯ
        нов.НаименованиеПолное = ИМЯ
        тип = S(erp.Метаданные.Справочники.Номенклатура.Реквизиты.СтавкаНДС.Тип)
        без = erp.Справочники.СтавкиНДС.НайтиПоНаименованию("Без ПДВ") if "Ставки НДС" in тип or "СтавкиНДС" in тип else None
        if без is not None and erp.ЗначениеЗаполнено(без):
            нов.СтавкаНДС = без
        нов.Записать()
        print("створено:", S(нов.Ссылка), "| ставка ПДВ:", S(нов.СтавкаНДС))

# --- 2. ставки
дог = q("""ВЫБРАТЬ Д.Ссылка КАК Договор ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ Д.А_ВидКредитногоДоговора = ЗНАЧЕНИЕ(Перечисление.А_ВидыКредитныхДоговоров.Проценты) И НЕ Д.ПометкаУдаления
 И НЕ Д.Ссылка В (ВЫБРАТЬ Р.Договор ИЗ РегистрСведений.А_ПроцентныеСтавкиКредитов КАК Р)
УПОРЯДОЧИТЬ ПО Д.Наименование""")
print("договорів %% без ставки:", дог.Количество())
for i in range(дог.Количество()):
    д = дог.Получить(i).Договор
    print(f"  {S(д)} → {СТАВКА}% з 01.01.2025")
    if APPLY:
        м = erp.РегистрыСведений.А_ПроцентныеСтавкиКредитов.СоздатьМенеджерЗаписи()
        м.Период = ПЕРИОД
        м.Договор = д
        м.Ставка = СТАВКА
        м.Записать(True)
if not APPLY:
    print("сухий прогін — запуск з --apply для запису")
