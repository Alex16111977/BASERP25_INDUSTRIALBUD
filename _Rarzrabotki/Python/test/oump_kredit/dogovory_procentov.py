# -*- coding: utf-8 -*-
"""Договоры «%% за использование от кредитора -- <подразделение>» у Воронцова (решение пользователя 15.10.2026).

    python dogovory_procentov.py          # только план
    python dogovory_procentov.py --apply  # создать недостающие и поставить «Форма расчетов» = «Наличная»

Договоры создаются функцией ОУМП А_НайтиИлиСоздатьКредитныйДоговор (вид «Проценты», тип «С поставщиком»):
тот же ключ поиска, что у «Создать оплаты», поэтому дублей не будет. Проценты платятся через кассу проекта —
всем договорам %% Воронцова ставится форма расчетов «Наличная».
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
APPLY = "--apply" in sys.argv
ПОДРАЗДЕЛЕНИЯ = ["КРИВОЙ РОГ ЦЕМЕНТ-2", "Каменец Цемент", "МД IRC 2026", "Производство", "Спецтехника", "Чорноморськ"]
# Другие подразделения можно передать в командной строке: python dogovory_procentov.py "МК Кривий ріг" --apply
ПОДРАЗДЕЛЕНИЯ = [a for a in sys.argv[1:] if not a.startswith("--")] or ПОДРАЗДЕЛЕНИЯ
ПРОЦЕНТЫ = erp.Перечисления.А_ВидыКредитныхДоговоров.Проценты
НАЛИЧНАЯ = erp.Перечисления.ФормыОплаты.Наличная


def q(text, **p):
    z = erp.NewObject("Запрос")
    z.Text = text
    for k, v in p.items():
        z.SetParameter(k, v)
    return z.Execute().Выгрузить()


# Контрагент и организация — из договора тела кредита ЦО, на котором уже стоят кредитные платёжки.
t = q("""ВЫБРАТЬ Дог.Контрагент КАК К, Дог.Организация КАК О ИЗ Справочник.ДоговорыКонтрагентов КАК Дог
ГДЕ Дог.Наименование = "Кредитование от кредитора -- Строительство (Закупка)" И НЕ Дог.ПометкаУдаления""")
assert t.Количество() == 1, "договор тела ЦО не найден однозначно"
КОНТРАГЕНТ, ОРГ = t.Получить(0).К, t.Получить(0).О
print("Контрагент:", S(КОНТРАГЕНТ), "| Организация:", S(ОРГ))

подр = {}
for имя in ПОДРАЗДЕЛЕНИЯ:
    t = q("""ВЫБРАТЬ П.Ссылка ИЗ Справочник.СтруктураПредприятия КАК П
ГДЕ П.Наименование = &И И НЕ П.ПометкаУдаления""", И=имя)
    assert t.Количество() == 1, f"подразделение «{имя}»: найдено {t.Количество()}"
    подр[имя] = t.Получить(0).Получить(0)

ОУМП = erp.Документы.А_ОказаниеУслугМеждуПодразделениями.СоздатьДокумент()  # только для вызова функций, не пишется
for имя, ref in подр.items():
    t = q("""ВЫБРАТЬ Дог.Наименование ИЗ Справочник.ДоговорыКонтрагентов КАК Дог
ГДЕ Дог.Контрагент = &К И Дог.Подразделение = &П И Дог.А_ВидКредитногоДоговора = &В И НЕ Дог.ПометкаУдаления""",
          К=КОНТРАГЕНТ, П=ref, В=ПРОЦЕНТЫ)
    if t.Количество():
        print("есть    ", S(t.Получить(0).Получить(0)))
        continue
    if APPLY:
        дог = ОУМП.А_НайтиИлиСоздатьКредитныйДоговор(КОНТРАГЕНТ, ОРГ, ref, ПРОЦЕНТЫ,
                                                     erp.Перечисления.ТипыДоговоров.СПоставщиком)
        print("создан  ", S(дог.Наименование))
    else:
        print("создать ", "%% за использование от кредитора --", имя)

t = q("""ВЫБРАТЬ Дог.Ссылка КАК Р, Дог.ФормаРасчетов КАК Ф ИЗ Справочник.ДоговорыКонтрагентов КАК Дог
ГДЕ Дог.Контрагент = &К И Дог.А_ВидКредитногоДоговора = &В И НЕ Дог.ПометкаУдаления""", К=КОНТРАГЕНТ, В=ПРОЦЕНТЫ)
for i in range(t.Количество()):
    r = t.Получить(i)
    if S(r.Ф) == S(НАЛИЧНАЯ):
        continue
    if APPLY:
        o = r.Р.ПолучитьОбъект()
        o.ФормаРасчетов = НАЛИЧНАЯ
        o.Записать()
    print(("форма → «Наличная» " if APPLY else "поставить «Наличная» ") + S(r.Р.Наименование))

print("\nДоговоры %% Воронцова:")
t = q("""ВЫБРАТЬ Дог.Наименование КАК Имя, Дог.Подразделение КАК Подр, Дог.ТипДоговора КАК Тип, Дог.ФормаРасчетов КАК Ф,
 Дог.А_СтатьяБаланса КАК Ст, Дог.А_ВидКонтрагента КАК ВидК, Дог.Партнер КАК Парт, Дог.ВалютаВзаиморасчетов КАК Вал,
 Дог.ПорядокРасчетов КАК ПР, Дог.Статус КАК Статус
ИЗ Справочник.ДоговорыКонтрагентов КАК Дог
ГДЕ Дог.Контрагент = &К И Дог.А_ВидКредитногоДоговора = &В И НЕ Дог.ПометкаУдаления
УПОРЯДОЧИТЬ ПО Дог.Наименование""", К=КОНТРАГЕНТ, В=ПРОЦЕНТЫ)
for i in range(t.Количество()):
    print(" | ".join(S(t.Получить(i).Получить(c)) for c in range(10)))
