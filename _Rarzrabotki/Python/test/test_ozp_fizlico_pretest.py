# -*- coding: utf-8 -*-
"""Pretest: снимок текущего состояния регистра ПрочиеРасходы для ОЗП 000Ц-000003.

Сохраняет в JSON:
  - Σ Сумма
  - КоличествоДвижений
  - Свод по (Подр, Статья, Аналитика) → Сумма  (с какой ключи нам сравнивать после правки)
  - % с заполненным А_ФизическоеЛицо
"""
import sys, io, json, os
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Р.Подразделение КАК Подразделение,
    Р.СтатьяРасходов КАК Статья,
    Р.АналитикаРасходов КАК Аналитика,
    Р.НалоговоеНазначение КАК НН,
    Р.НаправлениеДеятельности КАК НД,
    Р.А_ФизическоеЛицо КАК ФЛ,
    Р.Сумма КАК Сумма,
    Р.СуммаБезНДС КАК СуммаБезНДС,
    Р.СуммаРегл КАК СуммаРегл
ИЗ РегистрНакопления.ПрочиеРасходы КАК Р
ГДЕ Р.Регистратор.Номер = "000Ц-000003"
    И Р.Регистратор.Дата = ДАТАВРЕМЯ(2025,12,31,12,0,0)
    И ТИПЗНАЧЕНИЯ(Р.Регистратор) = ТИП(Документ.ОтражениеЗарплатыВФинансовомУчете)
"""
tz = q.Выполнить().Выгрузить()

всего = tz.Количество()
сумма = sum(r.Сумма for r in tz)
сумма_безндс = sum(r.СуммаБезНДС for r in tz)
сумма_регл = sum(r.СуммаРегл for r in tz)
фл_зап = sum(1 for r in tz if r.ФЛ and conn.ЗначениеЗаполнено(r.ФЛ))

print("=== PRETEST ОЗП 000Ц-000003 от 31.12.2025 ===")
print(f"  ВсегоДвижений:    {всего}")
print(f"  Σ Сумма:          {сумма:.2f}")
print(f"  Σ СуммаБезНДС:    {сумма_безндс:.2f}")
print(f"  Σ СуммаРегл:      {сумма_регл:.2f}")
print(f"  С заполненным ФЛ: {фл_зап} ({100.0*фл_зап/max(всего,1):.1f}%)")

# Сводка по (Подр, Статья, Аналитика, НН)
свод = {}
for r in tz:
    key = (
        conn.XMLСтрока(r.Подразделение) if r.Подразделение and conn.ЗначениеЗаполнено(r.Подразделение) else "",
        conn.XMLСтрока(r.Статья) if r.Статья and conn.ЗначениеЗаполнено(r.Статья) else "",
        conn.XMLСтрока(r.Аналитика) if r.Аналитика and conn.ЗначениеЗаполнено(r.Аналитика) else "",
        conn.XMLСтрока(r.НН) if r.НН and conn.ЗначениеЗаполнено(r.НН) else "",
    )
    if key not in свод:
        свод[key] = {"Сумма": 0.0, "СуммаБезНДС": 0.0, "СуммаРегл": 0.0, "Строк": 0}
    свод[key]["Сумма"] += float(r.Сумма)
    свод[key]["СуммаБезНДС"] += float(r.СуммаБезНДС)
    свод[key]["СуммаРегл"] += float(r.СуммаРегл)
    свод[key]["Строк"] += 1

print(f"  Уникальных (Подр,Статья,Аналитика,НН): {len(свод)}")

data = {
    "doc_number": "000Ц-000003",
    "doc_date": "2025-12-31T12:00:00",
    "total_movements": всего,
    "sum_total": сумма,
    "sum_without_vat": сумма_безндс,
    "sum_regl": сумма_регл,
    "fl_filled": фл_зап,
    "fl_pct": 100.0*фл_зап/max(всего,1),
    "groups": [
        {"key": list(k), "sum": v["Сумма"], "rows": v["Строк"]}
        for k, v in свод.items()
    ]
}
path = os.path.join(os.path.dirname(__file__), "ozp_fizlico_pretest.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)
print(f"  Saved: {path}")
