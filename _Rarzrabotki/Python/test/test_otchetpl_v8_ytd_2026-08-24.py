ПУСТО = q.Execute().Выгрузить().Получить(0).Д


def дата(г, м, д, ч=0, мин=0, с=0):
    qq = erp.NewObject("Запрос")
    qq.Text = "ВЫБРАТЬ ДАТАВРЕМЯ(%d,%d,%d,%d,%d,%d) КАК Д" % (г, м, д, ч, мин, с)
    return qq.Execute().Выгрузить().Получить(0).Д


def прогон(текст, месяцы, ytd, накоп, начало, конец, фиксы=False):
    кол = erp.NewObject("ТаблицаЗначений")
    кол.Колонки.Добавить("КолонкаСорт", описание("Число", erp.NewObject("КвалификаторыЧисла", 10, 0)))
    кол.Колонки.Добавить("КолонкаПредставление", описание("Строка", erp.NewObject("КвалификаторыСтроки", 30)))
    кол.Колонки.Добавить("МесяцДата", описание("Дата"))
    for м in месяцы:
        с = кол.Добавить()
        с.КолонкаСорт = м
        с.КолонкаПредставление = "%d-%02d" % (м // 100, м % 100)
        с.МесяцДата = ПУСТО
    if ytd:
        с = кол.Добавить(); с.КолонкаСорт = YTD
        с.КолонкаПредставление = "PL с начала года"; с.МесяцДата = ПУСТО
    if накоп:
        с = кол.Добавить(); с.КолонкаСорт = НАКОП
        с.КолонкаПредставление = "Накопительный PL"; с.МесяцДата = ПУСТО

    z = erp.NewObject("Запрос")
    z.Text = текст
    z.SetParameter("НачалоПериода", начало)
    z.SetParameter("КонецПериода", конец)
    z.SetParameter("СводыНаправлений", True)
    z.SetParameter("КолонкиPL", кол)
    z.SetParameter("ДДСCoGS", ДДС_COGS)
    z.SetParameter("СтатьяДоходовТовар", СТ_ТОВАР)
    z.SetParameter("ПоследнийМесяц", ПОСЛЕДНИЙ)
    z.SetParameter("ВыводитьФиксы", фиксы)
    if "&КлючНачалаГода" in текст:
        z.SetParameter("КлючНачалаГода", КЛЮЧ_ЯНВ)
    return z.Execute().Выгрузить()


def свод(таб):
    """{колонка: [итого, ф1, ф2, фикс_итого]}"""
    из = {}
    for i in range(таб.Количество()):
        с = таб.Получить(i)
        к = int(с.КолонкаСорт)
        а = из.setdefault(к, [0.0, 0.0, 0.0, 0.0])
        а[0] += float(с.СуммаИтого or 0)
        а[1] += float(с.СуммаФ1 or 0)
        а[2] += float(с.СуммаФ2 or 0)
        а[3] += float(с.ФиксИтого or 0)
    return из


def строчный_ключ(таб):
    """мультимножество строк для побайтовой сверки v7 == v8 (без 890000)."""
    из = {}
    for i in range(таб.Количество()):
        с = таб.Получить(i)
        к = (int(с.КолонкаСорт), S(с.Подразделение), S(с.СтатьяPL) if с.СтатьяPL else "",
             S(с.ДДС) if с.ДДС else "", S(с.Документ) if с.Документ else "",
             round(float(с.СуммаФ1 or 0), 2), round(float(с.СуммаФ2 or 0), 2),
             round(float(с.СуммаИтого or 0), 2))
        из[к] = из.get(к, 0) + 1
    return из


