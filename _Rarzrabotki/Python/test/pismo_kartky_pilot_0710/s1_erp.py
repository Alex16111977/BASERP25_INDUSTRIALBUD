# -*- coding: utf-8 -*-
"""Шаг 1: ERP ПолучитьДанные на 07.10.2026, выгрузка блока «2. Матеріали» двух проектов в json."""
import sys, json, time
from conn import erp as connect_erp, dt, uid

t0 = time.time()
c = connect_erp()
print("connect %.1fs" % (time.time() - t0))

п = c.NewObject("СтандартныйПериод")
п.ДатаНачала = dt(2000, 1, 1, 12, 0, 0)
п.ДатаОкончания = dt(2026, 10, 7, 23, 59, 59)
print("период:", c.String(п.ДатаНачала), "—", c.String(п.ДатаОкончания))

t1 = time.time()
тз = c.Отчеты.А_ПланФактныйПроизводствоПолный.Создать().ПолучитьДанные(п)
print("ПолучитьДанные %.1fs, строк %d" % (time.time() - t1, тз.Количество()))
кол = [тз.Колонки.Получить(i).Имя for i in range(тз.Колонки.Количество())]
print("колонки:", кол)

q = c.NewObject("Запрос")
q.SetParameter("ТЗ", тз)
q.Text = """
ВЫБРАТЬ
	Т.Подразделение КАК Подразделение,
	Т.ПодразделениеОбъекта КАК ПодразделениеОбъекта,
	Т.Блок КАК Блок,
	Т.Категория КАК Категория,
	Т.Этап КАК Этап,
	Т.ОбщееНазвание КАК ОбщееНазвание,
	Т.Аналитика КАК Аналитика,
	Т.НоменклатураНаименование КАК НоменклатураНаименование,
	Т.Номенклатура КАК Номенклатура,
	Т.Единица КАК Единица,
	Т.Документ КАК Документ,
	Т.ПланКол КАК ПланКол,
	Т.ФактКол КАК ФактКол,
	Т.ПланГрн КАК ПланГрн,
	Т.ФактГрн КАК ФактГрн,
	Т.ПланНаФактГрн КАК ПланНаФактГрн
ПОМЕСТИТЬ ВТ
ИЗ
	&ТЗ КАК Т
ГДЕ
	Т.Блок = "2. Матеріали"
;
ВЫБРАТЬ
	ВТ.Подразделение.Наименование КАК ПодрИмя,
	ВТ.ПодразделениеОбъекта.Наименование КАК ПодрОбъектаИмя,
	ВТ.Категория КАК Категория,
	ВТ.Этап КАК Этап,
	ВТ.Этап.Наименование КАК ЭтапИмя,
	ВТ.Этап.Код КАК ЭтапКод,
	ВТ.ОбщееНазвание КАК ОН,
	ВТ.ОбщееНазвание.Наименование КАК ОНИмя,
	ВТ.Аналитика КАК Аналитика,
	ВТ.НоменклатураНаименование КАК НоменклатураНаименование,
	ВТ.Номенклатура КАК Ном,
	ВТ.Номенклатура.Код КАК НомКод,
	ВТ.Номенклатура.Наименование КАК НомИмя,
	ВТ.Номенклатура.ЕдиницаИзмерения.Наименование КАК НомЕд,
	ВТ.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование КАК НомОН,
	ВТ.Единица.Наименование КАК ЕдИмя,
	ВЫБОР
		КОГДА ВТ.Документ ССЫЛКА Справочник.А_СтруктураСебестоимости
			ТОГДА "СС"
		КОГДА ВТ.Документ ССЫЛКА Документ.ПриобретениеТоваровУслуг
				И ВТ.Документ <> ЗНАЧЕНИЕ(Документ.ПриобретениеТоваровУслуг.ПустаяСсылка)
			ТОГДА "ПТУ"
		КОГДА ВТ.ПланНаФактГрн <> 0
			ТОГДА "СИНТ"
		ИНАЧЕ "ПРОЧЕЕ"
	КОНЕЦ КАК ТипДок,
	ВТ.Документ КАК Док,
	ПРЕДСТАВЛЕНИЕ(ВТ.Документ) КАК ДокПредст,
	ВТ.ПланКол КАК ПланКол,
	ВТ.ФактКол КАК ФактКол,
	ВТ.ПланГрн КАК ПланГрн,
	ВТ.ФактГрн КАК ФактГрн,
	ВТ.ПланНаФактГрн КАК ПланНаФактГрн
ИЗ
	ВТ КАК ВТ
"""
t2 = time.time()
r = q.Execute().Выгрузить()
print("запрос %.1fs, строк материалов (все подр.) %d" % (time.time() - t2, r.Количество()))

ПОДР = ("МД IRC 2026", "МД ООН Админ")
out = []
подр_все = {}
for i in range(r.Количество()):
    s = r.Получить(i)
    pn = s.ПодрИмя or ""
    подр_все[pn] = подр_все.get(pn, 0) + 1
    if pn not in ПОДР:
        continue
    a = s.Аналитика
    if isinstance(a, str):
        a_txt, a_kind = a, "str"
    elif a is None:
        a_txt, a_kind = "", "none"
    else:
        a_txt, a_kind = c.String(a), "ref"
    out.append({
        "podr": pn, "podr_obj": s.ПодрОбъектаИмя or "", "cat": s.Категория,
        "etap": s.ЭтапИмя or "", "etap_code": s.ЭтапКод or "", "etap_uuid": uid(c, s.Этап) if s.Этап is not None and not isinstance(s.Этап, str) else "",
        "on": s.ОНИмя or "", "on_uuid": uid(c, s.ОН) if s.ОН is not None and not isinstance(s.ОН, str) else "",
        "an": a_txt, "an_kind": a_kind,
        "nom_naim": s.НоменклатураНаименование or "",
        "nom_uuid": uid(c, s.Ном) if s.Ном is not None and not isinstance(s.Ном, str) else "",
        "nom_code": s.НомКод or "", "nom_name": s.НомИмя or "", "nom_ed": s.НомЕд or "", "nom_on": s.НомОН or "",
        "ed": s.ЕдИмя or "", "type": s.ТипДок,
        "doc": s.ДокПредст or "", "doc_uuid": uid(c, s.Док) if s.Док is not None and not isinstance(s.Док, str) else "",
        "pk": float(s.ПланКол), "fk": float(s.ФактКол), "pg": float(s.ПланГрн), "fg": float(s.ФактГрн), "pnf": float(s.ПланНаФактГрн),
    })
print("подразделения в материалах:", подр_все)
json.dump(out, open("erp_mat_0710.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print("выгружено строк:", len(out), "всего %.1fs" % (time.time() - t0))
