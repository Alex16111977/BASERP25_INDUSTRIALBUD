# Внутрішні договори ІНДЕПТ СТІЛ -> ІНДАСТРІАЛБУД за оригіналами (04.10.2026): аванс 30 % по кожному конструктиву
# (п. 4.2.1, Дод. 1 п. 2), утримань договір не передбачає. Варіант «ЗачетПредоплаты», p = 30, аванс = 30 % ціни
# конструктиву з Дод. 1. Запуск: python finrep_internal_advance_30_0410.py [--apply]
import sys
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
APPLY = "--apply" in sys.argv
# назва запису договору в 1С -> ціна конструктиву з ПДВ (Дод. 1 / ДУ1)
ЦІНИ = {
    "Договір підряду 20/01/26  Чорноморськ(наливна ест)": 566100.00,
    "Договір підряду 20/01/26  Чорноморськ(компресорна)": 62604.00,
    "Договір підряду  19/01/26-1 Естакада 3.1.5 Глоб": 31649.80,
    "Договір підряду  19/01/26-1 Ав рез розчин Глоб": 119459.90,
    "Договір підряду  19/01/26-1 Естакада 6.4  Глоб": 203749.70,
    "Договір підряду  21/01/26  Каналізаційна нас Глоб": 24609.20,
    "Договір підряду  21/01/26  Пост охорони Глоб": 53725.70,
    "Договір підряду  15/10/25 Глобине Пункт нав 4.2": 1926821.40,
}
c = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
рег = c.РегистрыСведений.А_ПараметрыДоговоровФинотчета
q = c.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ Д.Наименование = &Н И НЕ Д.ПометкаУдаления И Д.Подразделение.Наименование ПОДОБНО "М_ %" """
for назва, ціна in ЦІНИ.items():
    q.SetParameter("Н", назва)
    в = q.Execute().Выгрузить()
    if в.Количество() != 1:
        print("ПОМИЛКА", назва, в.Количество()); continue
    нз = рег.СоздатьНаборЗаписей(); нз.Отбор.Договор.Установить(в[0].Ссылка); нз.Прочитать()
    з = нз[0] if нз.Количество() > 0 else нз.Добавить()
    print(назва, "| було:", з.ВариантФормулыИтога or "(порожньо)", з.ПроцентГарантийногоУдержания, "% аванс", з.СуммаПредоплаты,
          "C", з.СуммаСоглашения, "-> ЗачетПредоплаты 30 % аванс", round(ціна * 0.3, 2))
    з.Договор = в[0].Ссылка
    з.ВариантФормулыИтога = "ЗачетПредоплаты"
    з.ПроцентГарантийногоУдержания = 30
    з.СуммаПредоплаты = round(ціна * 0.3, 2)
    з.ПроцентУдержанияПослеАванса = 0
    з.СуммаСоглашения = ціна  # сума угоди — з Дод. 1 / ДУ1 (компресорна: 46 620 -> 62 604 за ДУ1)
    if APPLY:
        нз.ДополнительныеСвойства.Вставить("ОтключитьМеханизмРегистрацииОбъектов", True)
        нз.Записать(True)
print("ЗАПИСАНО" if APPLY else "ПРОБНИЙ ПРОГІН")
