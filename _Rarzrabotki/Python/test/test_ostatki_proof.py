"""
Доказательство через прямое обращение к виртуальной таблице:
- РасчетыСКлиентамиПоСрокам.Остатки(Дата(1,1,1))   → актуальный остаток (текущий момент)
- РасчетыСКлиентамиПоСрокам.Остатки(31.12.2025)    → остаток на 31.12.2025

Это то же, что делает штатный отчёт ВедомостьРасчетовСПартнерами:
- если Период.ДатаНачала пустая → &КонецПериодаГраница = Дата(1,1,1) (актуальный)
- если заполнена → &КонецПериодаГраница = КонецДня(ДатаОкончания)

Заодно проверим: есть ли в регистре строки с ОбъектРасчетов = ПустаяСсылка?
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
орг = q.Выполнить().Выгрузить().Получить(0).Ссылка
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты ГДЕ Наименование = "Глобино-2"'
контр = q.Выполнить().Выгрузить().Получить(0).Ссылка

К31 = datetime.datetime(2025, 12, 31, 23, 59, 59)
МИН_ДАТА = None  # будем передавать None → запрос без даты = текущий момент

print("=" * 110)
print(f"ДОКАЗАТЕЛЬСТВО: какие данные возвращает .Остатки() при двух значениях параметра")
print("=" * 110)

def получить_остатки(имя, дата_параметр):
    """Прямой вызов РасчетыСКлиентамиПоСрокам.Остатки(дата) — точно как в штатном отчёте.
    Если дата_параметр=None → используется .Остатки(, ) без параметра = текущий момент.
    Это полностью эквивалентно тому, что делает 1С при значении Дата(1,1,1)."""
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Орг", орг)
    qq.УстановитьПараметр("Контр", контр)
    if дата_параметр is None:
        текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    Р.ОбъектРасчетов КАК ОР,
    СУММА(Р.ДолгРеглОстаток) КАК Долг,
    СУММА(Р.ПредоплатаРеглОстаток) КАК Пред
ИЗ
    РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(, ) КАК Р
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И АП.Контрагент = &Контр
    И АП.Партнер <> ЗНАЧЕНИЕ(Справочник.Партнеры.НашеПредприятие)
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов
ИМЕЮЩИЕ СУММА(Р.ДолгРеглОстаток) <> 0 ИЛИ СУММА(Р.ПредоплатаРеглОстаток) <> 0
УПОРЯДОЧИТЬ ПО Долг УБЫВ
"""
        метка = '.Остатки(, ) — без даты = текущий момент'
    else:
        qq.УстановитьПараметр("Дата", дата_параметр)
        текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОРИмя,
    Р.ОбъектРасчетов КАК ОР,
    СУММА(Р.ДолгРеглОстаток) КАК Долг,
    СУММА(Р.ПредоплатаРеглОстаток) КАК Пред
ИЗ
    РегистрНакопления.РасчетыСКлиентамиПоСрокам.Остатки(&Дата, ) КАК Р
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрСведений.АналитикаУчетаПоПартнерам КАК АП
    ПО Р.АналитикаУчетаПоПартнерам = АП.КлючАналитики
ГДЕ АП.Организация = &Орг И АП.Контрагент = &Контр
    И АП.Партнер <> ЗНАЧЕНИЕ(Справочник.Партнеры.НашеПредприятие)
СГРУППИРОВАТЬ ПО Р.ОбъектРасчетов
ИМЕЮЩИЕ СУММА(Р.ДолгРеглОстаток) <> 0 ИЛИ СУММА(Р.ПредоплатаРеглОстаток) <> 0
УПОРЯДОЧИТЬ ПО Долг УБЫВ
"""
        метка = f'.Остатки(&Дата={дата_параметр.strftime("%d.%m.%Y")})'
    qq.Текст = текст
    print(f"\n[{имя}] {метка}")
    print("-" * 110)
    r = qq.Выполнить().Выгрузить()
    sum_д, sum_п = 0, 0
    print(f"   {'ОР':<50} | {'ОР_UUID':<40} | {'Долг':>13} | {'Предопл':>13}")
    print("   " + "-" * 130)
    for i in range(r.Количество()):
        rec = r.Получить(i)
        д = float(rec.Долг)
        п = float(rec.Пред)
        sum_д += д
        sum_п += п
        uuid_str = S(rec.ОР.УникальныйИдентификатор()) if not rec.ОР.Пустая() else "*** ПУСТАЯ ССЫЛКА ***"
        ор_имя = str(rec.ОРИмя) if str(rec.ОРИмя) else "*** ПУСТО ***"
        print(f"   {ор_имя[:50]:<50} | {uuid_str[:40]:<40} | {д:>13,.2f} | {п:>13,.2f}")
    print("   " + "-" * 130)
    print(f"   Σ Долг:     {sum_д:>13,.2f}")
    print(f"   Σ Предопл:  {sum_п:>13,.2f}")
    print(f"   Σ Сальдо:   {sum_д - sum_п:>13,.2f}")
    return sum_д, sum_п

# === Сценарий A (как штатный отчёт при пустой ДатаНачала) ===
sA, _ = получить_остатки("СЦЕНАРИЙ A — параметр = Дата(1,1,1) — то что отчёт подставляет при пустой ДатаНачала", МИН_ДАТА)

# === Сценарий B (как должно быть с фильтром) ===
sB, _ = получить_остатки("СЦЕНАРИЙ B — параметр = 31.12.2025 — корректный фильтр", К31)

# === Проверка: есть ли строки с ОбъектРасчетов = ПустаяСсылка вообще?
