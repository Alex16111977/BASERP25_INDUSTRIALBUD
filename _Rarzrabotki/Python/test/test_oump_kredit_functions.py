# -*- coding: utf-8 -*-
"""ОУМП, кредитные договоры: функции модуля объекта (документ в памяти, не записывается)."""
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
В = erp.Перечисления.А_ВидыКредитныхДоговоров
Т = erp.Перечисления.ТипыДоговоров
Док = erp.Документы.А_ОказаниеУслугМеждуПодразделениями.СоздатьДокумент()
Док.Организация = erp.Справочники.Организации.НайтиПоНаименованию('ТОВ "ІНДАСТРІАЛБУД"', True)
Док.Кредитование = True
Контр = erp.Справочники.Контрагенты.НайтиПоНаименованию("Воронцов Олександр Володимирович", True)
Глоб = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Глобино-2", True)
# заёмщик — контрагент подразделения (тело кредита живёт у него, не у Воронцова)
МДIRC = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("МД IRC 2026", True)
Заём = erp.Справочники.Контрагенты.НайтиПоНаименованию("МД IRS 2026", True)
ok = True


def uid(ref):
    return S(ref.УникальныйИдентификатор())


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


def count():
    q = erp.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ Справочник.ДоговорыКонтрагентов"
    return q.Execute().Выгрузить().Получить(0).Получить(0)


check(S(Док.А_ИмяКредитногоДоговора(В.ТелоКредита, Глоб, Т.СПокупателем)) == "Кредитование от кредитора -- Глобино-2", "имя тела")
check(S(Док.А_ИмяКредитногоДоговора(В.НераспределеннаяПрибыль, Глоб, Т.СПокупателем)).endswith(" (Реализация)"), "суффикс типа для НП-СПокупателем")

n0 = count()
Д1 = Док.А_НайтиИлиСоздатьКредитныйДоговор(Заём, Док.Организация, МДIRC, В.ТелоКредита, Т.СПокупателем)
Д2 = Док.А_НайтиИлиСоздатьКредитныйДоговор(Заём, Док.Организация, МДIRC, В.ТелоКредита, Т.СПокупателем)
check(S(Д1) == "Кредитование от кредитора -- МД IRC 2026" and S(Д1.Контрагент) == "МД IRS 2026", f"подобран существующий договор тела у заёмщика: {S(Д1)}")
check(uid(Д1) == uid(Д2) and count() == n0, "идемпотентно, договоров не прибавилось")

Стр = Док.Деньги.Добавить()
Стр.КодСтроки = 1
Стр.ПодразделениеРасход = МДIRC
Стр.ВидДоговораРасход = В.ТелоКредита
Р = Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем)
check(Р.Ошибка, "вид без контрагента → Ошибка")
Стр.КонтрагентРасход = Заём
Р = Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем)
check((not Р.Ошибка) and uid(Р.Договор) == uid(Д1), "сторона возврата тела → договор Кредитование")
Стр.ВидДоговораРасход = В.ПустаяСсылка()
check(Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем) is None, "без вида → Неопределено (прежний подбор)")

ФП = erp.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001144")  # по имени находится одноимённая группа
check(uid(Док.А_КонтрагентКредитаПоСтатье(ФП)) == uid(Контр), "контрагент по статье «Финансовая помощь» = Воронцов (карточка с кредитными договорами)")
Стр.ВидДоговораРасход = В.ТелоКредита
Док.Кредитование = False
check(Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем) is None, "флаг «Кредитование» снят → Неопределено (прежний подбор)")
Док.Кредитование = True
check(S(Док.А_КонтрагентПодразделения(МДIRC)) == "МД IRS 2026", "контрагент подразделения МД IRC 2026 = МД IRS 2026")
ПФП = erp.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001181")  # Получение финансовой помощи — без партнёра
check(S(Док.А_КонтрагентСтороныКредита(В.ТелоКредита, ПФП, МДIRC)) == "МД IRS 2026", "заёмщик (статья без партнёра) → контрагент подразделения")
check(uid(Док.А_КонтрагентСтороныКредита(В.ТелоКредита, ФП, МДIRC)) == uid(Контр), "кредитор (статья с партнёром) → Воронцов, вид тоже «Тело кредита»")
sys.exit(0 if ok else 1)
