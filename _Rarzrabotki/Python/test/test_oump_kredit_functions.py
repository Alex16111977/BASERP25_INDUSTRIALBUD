# -*- coding: utf-8 -*-
"""ОУМП, кредитные договоры: функции модуля объекта (документ в памяти, не записывается)."""
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
В = erp.Перечисления.А_ВидыКредитныхДоговоров
Т = erp.Перечисления.ТипыДоговоров
Док = erp.Документы.А_ОказаниеУслугМеждуПодразделениями.СоздатьДокумент()
Док.Организация = erp.Справочники.Организации.НайтиПоНаименованию('ТОВ "ІНДАСТРІАЛБУД"', True)
Док.Кредитование = True
Контр = erp.Справочники.Контрагенты.НайтиПоНаименованию("Воронцов Олександр Володимирович", True)
Глоб = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Глобино-2", True)
# заёмщик — контрагент подразделения (тело кредита живёт у него, не у Воронцова)
МДIRC = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("МД IRC 2026", True)
Заём = erp.Справочники.Контрагенты.НайтиПоНаименованию("МД IRS 2026", True)
ok = True


def uid(ref):
    return S(ref.УникальныйИдентификатор())


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


def count():
    q = erp.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ Справочник.ДоговорыКонтрагентов"
    return q.Execute().Выгрузить().Получить(0).Получить(0)


check(S(Док.А_ИмяКредитногоДоговора(В.ТелоКредита, Глоб, Т.СПокупателем)) == "Кредитование от кредитора -- Глобино-2", "имя тела")
check(S(Док.А_ИмяКредитногоДоговора(В.НераспределеннаяПрибыль, Глоб, Т.СПокупателем)).endswith(" (Реализация)"), "суффикс типа для НП-СПокупателем")

n0 = count()
Д1 = Док.А_НайтиИлиСоздатьКредитныйДоговор(Заём, Док.Организация, МДIRC, В.ТелоКредита, Т.СПокупателем)
Д2 = Док.А_НайтиИлиСоздатьКредитныйДоговор(Заём, Док.Организация, МДIRC, В.ТелоКредита, Т.СПокупателем)
check(S(Д1) == "Кредитование от кредитора -- МД IRC 2026" and S(Д1.Контрагент) == "МД IRS 2026", f"подобран существующий договор тела у заёмщика: {S(Д1)}")
check(uid(Д1) == uid(Д2) and count() == n0, "идемпотентно, договоров не прибавилось")

Стр = Док.Деньги.Добавить()
Стр.КодСтроки = 1
Стр.ПодразделениеРасход = МДIRC
Стр.ВидДоговораРасход = В.ТелоКредита
Р = Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем)
check(Р.Ошибка, "вид без контрагента → Ошибка")
Стр.КонтрагентРасход = Заём
Р = Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем)
check((not Р.Ошибка) and uid(Р.Договор) == uid(Д1), "сторона возврата тела → договор Кредитование")
Стр.ВидДоговораРасход = В.ПустаяСсылка()
check(Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем) is None, "без вида → Неопределено (прежний подбор)")

ФП = erp.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001144")  # по имени находится одноимённая группа
check(uid(Док.А_КонтрагентКредитаПоСтатье(ФП)) == uid(Контр), "контрагент по статье «Финансовая помощь» = Воронцов (карточка с кредитными договорами)")
Стр.ВидДоговораРасход = В.ТелоКредита
Док.Кредитование = False
check(Док.А_КредитнаяСторона(Стр, True, Т.СПокупателем) is None, "флаг «Кредитование» снят → Неопределено (прежний подбор)")
Док.Кредитование = True
check(S(Док.А_КонтрагентПодразделения(МДIRC)) == "МД IRS 2026", "контрагент подразделения МД IRC 2026 = МД IRS 2026")
ПФП = erp.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001181")  # Получение финансовой помощи — без партнёра
check(S(Док.А_КонтрагентСтороныКредита(В.ТелоКредита, ПФП, МДIRC)) == "МД IRS 2026", "заёмщик (статья без партнёра) → контрагент подразделения")
check(uid(Док.А_КонтрагентСтороныКредита(В.ТелоКредита, ФП, МДIRC)) == uid(Контр), "кредитор (статья с партнёром) → Воронцов, вид тоже «Тело кредита»")

# === 16.10.2026: договор кредитора на пару «ЦО → заёмщик» ===
Стро = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Строительство", True)
ВПФ = erp.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001149")  # Возврат поворотной Финансовой помощи
ПустоеПодр = erp.Справочники.СтруктураПредприятия.ПустаяСсылка()
check(S(Док.А_ИмяКредитногоДоговора(В.ТелоКредита, Стро, Т.СПоставщиком, Глоб)) == "Кредит: Строительство → Глобино-2",
      "имя пары «Кредит: Строительство → Глобино-2» (Закупка без суффикса)")
check(S(Док.А_ИмяКредитногоДоговора(В.ТелоКредита, Стро, Т.СПокупателем, Глоб)) == "Кредит: Строительство → Глобино-2 (Реализация)",
      "имя пары с типом «Реализация» → суффикс")
check(S(Док.А_ИмяКредитногоДоговора(В.Проценты, Глоб, Т.СПоставщиком, Стро)) == "%% за использование от кредитора -- Глобино-2",
      "получатель не меняет имя %%")

# выдача: кредитор — расход ЦО, заёмщик — приход проекта
Глоб_контр = erp.Справочники.Контрагенты.НайтиПоНаименованию("Глобино-2", True)
Выд = Док.Деньги.Добавить()
Выд.КодСтроки = 2
Выд.ПодразделениеРасход, Выд.СтатьяДвиженияДенежныхСредствРасход = Стро, ФП
Выд.КонтрагентРасход, Выд.ВидДоговораРасход = Контр, В.ТелоКредита
Выд.ПодразделениеПриход, Выд.СтатьяДвиженияДенежныхСредствПриход = Глоб, ПФП
Выд.КонтрагентПриход, Выд.ВидДоговораПриход = Глоб_контр, В.ТелоКредита
n0 = count()
Р1 = Док.А_КредитнаяСторона(Выд, True, Т.СПоставщиком)
n1 = count()
Р2 = Док.А_КредитнаяСторона(Выд, True, Т.СПоставщиком)
Д = Р1.Договор
check(not Р1.Ошибка and S(Д) == "Кредит: Строительство → Глобино-2" and uid(Д.Контрагент) == uid(Контр),
      f"сторона кредитора при выдаче → договор пары у Воронцова: {S(Д)}")
check(S(Д.Подразделение) == "Строительство" and S(Д.А_ПодразделениеОказаниеУслугПодразделению) == "Глобино-2"
      and S(Д.ТипДоговора) == S(Т.СПоставщиком) and S(Д.А_ВидКредитногоДоговора) == S(В.ТелоКредита),
      "реквизиты договора пары: Строительство → Глобино-2, Закупка, Тело кредита")
check(S(Д.А_ВидКонтрагента) == "Собственники" and S(Д.А_СтатьяБаланса) == "Задолженность по кредитам",
      "договор пары: Собственники, «Задолженность по кредитам» (подписка не переименовала, вид не сбросила)")
check(uid(Р2.Договор) == uid(Д) and count() == n1 and n1 - n0 in (0, 1),
      f"идемпотентно: второй вызов тот же договор, создано {n1 - n0}, после второго вызова +0")
Рз = Док.А_КредитнаяСторона(Выд, False, Т.СПокупателем)
check(not Рз.Ошибка and S(Рз.Договор) == "Кредитование от кредитора -- Глобино-2"
      and not erp.ЗначениеЗаполнено(Рз.Договор.А_ПодразделениеОказаниеУслугПодразделению),
      "сторона заёмщика → «Кредитование от кредитора -- Глобино-2», получатель пуст")

# возврат: заёмщик — расход проекта, кредитор — приход ЦО; тип кредитора тоже «Закупка» → тот же договор пары
Взв = Док.Деньги.Добавить()
Взв.КодСтроки = 3
Взв.ТипыРасчетаДенежнымиСредствами = erp.Перечисления.ТипыРасчетаДенежнымиСредствами.ВозвратДенежныхСредств
Взв.ПодразделениеРасход, Взв.СтатьяДвиженияДенежныхСредствРасход = Глоб, ПФП
Взв.КонтрагентРасход, Взв.ВидДоговораРасход = Глоб_контр, В.ТелоКредита
Взв.ПодразделениеПриход, Взв.СтатьяДвиженияДенежныхСредствПриход = Стро, ВПФ
Взв.КонтрагентПриход, Взв.ВидДоговораПриход = Контр, В.ТелоКредита
n2 = count()
check(uid(Док.А_КредитнаяСторона(Взв, False, Т.СПоставщиком).Договор) == uid(Д) and count() == n2,
      "возврат: сторона кредитора (приход ЦО) → тот же договор пары, договоров не прибавилось")
check(S(Док.А_КредитнаяСторона(Взв, True, Т.СПокупателем).Договор) == "Кредитование от кредитора -- Глобино-2",
      "возврат: сторона заёмщика → договор тела заёмщика")

# %% и НП — без получателя, существующие договоры
Кр = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("КРИВОЙ РОГ ЦЕМЕНТ-2", True)
n3 = count()
Дп = Док.А_НайтиИлиСоздатьКредитныйДоговор(Контр, Док.Организация, Кр, В.Проценты, Т.СПоставщиком)
Дп2 = Док.А_НайтиИлиСоздатьКредитныйДоговор(Контр, Док.Организация, Кр, В.Проценты, Т.СПоставщиком, ПустоеПодр)
check(S(Дп) == "%% за использование от кредитора -- КРИВОЙ РОГ ЦЕМЕНТ-2" and uid(Дп) == uid(Дп2) and count() == n3,
      "%%: Неопределено и ПустаяСсылка получателя → существующий договор %%, новых нет")
Днп = Док.А_НайтиИлиСоздатьКредитныйДоговор(Контр, Док.Организация, Стро, В.НераспределеннаяПрибыль, Т.СПоставщиком)
check(S(Днп) == "Нераспределенная прибыль -- Строительство" and count() == n3, "НП без получателя → существующий договор")
sys.exit(0 if ok else 1)
