# -*- coding: utf-8 -*-
"""Шаг 2 контроль — извлекает текст запроса РОВНО как он лежит в BSL
(Документ.А_ФинРез_Баланс ObjectModule.bsl, функция Свод_РасчетыСПартнерами,
литерал Запрос.Текст = "..."), реконструирует строку (снять '|'-продолжения)
и прогоняет через COM за дек2025+янв2026/ТОВ. Доказывает, что перенос в BSL
точный: запрос валиден, субконто Контрагент/Партнёр/Договор заполнены,
0 дублей, Σ(детали+плуг) по (Орг,Подр,Статья,Source) == ПАП, Приход=Расход=0.
"""
import sys, io, re
from collections import Counter
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

BSL = (r"C:\Configuration_downloads\BASERP25\.claude\worktrees"
       r"\naughty-neumann-691338\Documents\А_ФинРез_Баланс\Ext\ObjectModule.bsl")
CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
TOL = 0.01
МЕСЯЦЫ = [datetime(2025, 12, 1, 12), datetime(2026, 1, 1, 12)]

src = open(BSL, encoding="utf-8-sig").read().split("\n")
fs = next(i for i, l in enumerate(src)
          if "Функция Свод_РасчетыСПартнерами(" in l)
fe = next(i for i in range(fs + 1, len(src)) if src[i].strip() == "КонецФункции")
# найти 'Запрос.Текст =' и литерал, начинающийся со следующей строки с '"'
ti = next(i for i in range(fs, fe) if src[i].strip().startswith("Запрос.Текст ="))
li = next(i for i in range(ti, fe) if src[i].lstrip().startswith('"'))
# собрать строковый литерал: 1-я строка с '"', продолжения с '|' до закрывающей '"'
буфер = []
i = li
first = src[i].lstrip()
assert first.startswith('"'), first
буфер.append(first[1:])  # снять открывающую "
i += 1
while i <= fe:
    s = src[i]
    j = s.find("|")
    assert j != -1, f"нет '|' в продолжении строки {i+1}: {s!r}"
    cont = s[j + 1:]
    if cont.rstrip().endswith('";'):
        буфер.append(cont.rstrip()[:-2])  # снять закрывающую ";
        break
    буфер.append(cont)
    i += 1
ЗАПРОС = "\n".join(буфер)
assert '"' not in ЗАПРОС, "в извлечённом тексте остались кавычки — литерал собран неверно"
assert "ВЫБРАТЬ" in ЗАПРОС and "втКлючи" in ЗАПРОС and "втРасч" in ЗАПРОС
assert ЗАПРОС.count("ОБЪЕДИНИТЬ ВСЕ") >= 4, "ожидалось >=4 ОБЪЕДИНИТЬ ВСЕ"
print(f"извлечён запрос из BSL: {len(ЗАПРОС)} симв., "
      f"строк {li+1}..{i+1}, ОБЪЕДИНИТЬ ВСЕ={ЗАПРОС.count('ОБЪЕДИНИТЬ ВСЕ')}")

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С

qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка КАК Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for n in ("Собственные средства", "Доходы текущего периода",
          "Расходы текущего периода"):
    имена.Добавить(n)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
Искл = conn.NewObject("Массив")
for k in range(tI.Количество()):
    Искл.Добавить(tI.Получить(k).Ссылка)


def месяц(M):
    qb = conn.NewObject("Запрос")
    qb.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
                "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
    qb.УстановитьПараметр("М", M)
    rb = qb.Выполнить().Выбрать(); rb.Следующий()
    НМ, КД = rb.НМ, rb.КД

    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Орг", ORG)
    q.УстановитьПараметр("НачМес", НМ)
    q.УстановитьПараметр("КонМес", КД)
    q.УстановитьПараметр("Искл", Искл)
    q.Текст = ЗАПРОС
    try:
        t = q.Выполнить().Выгрузить()
    except Exception as e:
        m = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        raise RuntimeError(f"FAIL BSL-запрос ({M:%Y-%m}): {m}")

    rows = t.Количество()
    дет = плуг = кз = дз = пз = 0
    своды = {}
    дет_ключи = Counter()
    for x in range(rows):
        r = t.Получить(x)
        расх = bool(r.Расхождение)
        орг = conn.XMLСтрока(r.Организация)
        подр = (conn.XMLСтрока(r.Подразделение)
                if conn.ЗначениеЗаполнено(r.Подразделение) else "∅")
        ст = conn.XMLСтрока(r.Статья)
        srcc = conn.XMLСтрока(r.Source) if conn.ЗначениеЗаполнено(r.Source) else "∅"
        но = float(r.СуммаНачальныйОстаток or 0)
        ко = float(r.СуммаКонечныйОстаток or 0)
        d = своды.setdefault((орг, подр, ст, srcc), [0.0, 0.0])
        d[0] += но; d[1] += ко
        assert abs(float(r.СуммаПриход or 0)) < TOL, "Приход<>0"
        assert abs(float(r.СуммаРасход or 0)) < TOL, "Расход<>0"
        if расх:
            плуг += 1
            assert not conn.ЗначениеЗаполнено(r.Контрагент), "плуг Контрагент"
            assert not conn.ЗначениеЗаполнено(r.Договор), "плуг Договор"
            assert not conn.ЗначениеЗаполнено(r.Партнер), "плуг Партнер"
        else:
            дет += 1
            if conn.ЗначениеЗаполнено(r.Контрагент): кз += 1
            if conn.ЗначениеЗаполнено(r.Договор): дз += 1
            if conn.ЗначениеЗаполнено(r.Партнер): пз += 1
            субк = conn.XMLСтрока(r.ОбъектРасчетов)
            кн = conn.XMLСтрока(r.Контрагент) if conn.ЗначениеЗаполнено(r.Контрагент) else "∅"
            дг = conn.XMLСтрока(r.Договор) if conn.ЗначениеЗаполнено(r.Договор) else "∅"
            дет_ключи[(орг, подр, ст, srcc, субк, кн, дг)] += 1

    qE = conn.NewObject("Запрос")
    qE.УстановитьПараметр("Орг", ORG); qE.УстановитьПараметр("НачМес", НМ)
    qE.УстановитьПараметр("КонМес", КД); qE.УстановитьПараметр("Искл", Искл)
    qE.Текст = """ВЫБРАТЬ Т.Организация КАК О,
        ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК П,
        Т.Статья КАК С, Т.Источник КАК Ист,
        СУММА(ВЫБОР КОГДА Т.Период < &НачМес ТОГДА
            ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ ИНАЧЕ 0 КОНЕЦ) КАК НО,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Организация=&Орг И Т.Период<=&КонМес
        И Т.Источник В (ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
            ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
        И НЕ Т.Статья В ИЕРАРХИИ(&Искл)
    СГРУППИРОВАТЬ ПО Т.Организация,
        ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)),
        Т.Статья, Т.Источник"""
    tE = qE.Выполнить().Выгрузить()
    пап = {}
    for x in range(tE.Количество()):
        e = tE.Получить(x)
        пп = conn.XMLСтрока(e.П) if conn.ЗначениеЗаполнено(e.П) else "∅"
        пап[(conn.XMLСтрока(e.О), пп, conn.XMLСтрока(e.С),
             conn.XMLСтрока(e.Ист))] = [float(e.НО or 0), float(e.КО or 0)]

    плохо = []
    for k in set(своды) | set(пап):
        a = своды.get(k, [0, 0]); b = пап.get(k, [0, 0])
        for j in (0, 1):
            if abs(a[j] - b[j]) > TOL:
                плохо.append((k, j, a[j] - b[j]))
    дубл = sum(1 for v in дет_ключи.values() if v > 1)
    print(f"  {M:%Y-%m}: rows={rows} дет={дет} плуг={плуг} "
          f"Контр={кз}/{дет} Дог={дз}/{дет} Партн={пз}/{дет} "
          f"дубл={дубл} расхожд_vs_ПАП={len(плохо)}")
    assert rows > 0, "пусто"
    assert дет > 0, "нет деталей"
    assert кз > 0 and дз > 0 and пз == дет, \
        f"FAIL субконто: Контр={кз} Дог={дз} Партн={пз}/{дет}"
    assert дубл == 0, f"FAIL дублей деталей {дубл}"
    assert not плохо, f"FAIL свод != ПАП по (Орг,Подр,Статья,Source) ({len(плохо)})"


for M in МЕСЯЦЫ:
    месяц(M)
print("PASS Шаг 2: запрос из BSL извлечён и валиден; перенос точный; "
      "субконто заполнено; Σ==ПАП; 0 дублей; Приход=Расход=0")
