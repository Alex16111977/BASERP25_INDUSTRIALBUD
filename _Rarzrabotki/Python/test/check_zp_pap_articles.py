def xs(v):
    try:
        return erp.XMLСтрока(v) if erp.ЗначениеЗаполнено(v) else "(пусто)"
    except Exception as e:
        return f"<err {e}>"

print("=== 1. Способ отражения 'Больничные за счет ФСС' ===")
sp = erp.Справочники.СпособыОтраженияЗарплатыВБухУчете.НайтиПоНаименованию("Больничные за счет ФСС")
if erp.ЗначениеЗаполнено(sp):
    o = sp.ПолучитьОбъект()
    print("  Найден:", o.Наименование)
    for r in o.Метаданные().Реквизиты:
        nm = r.Имя
        try:
            val = o[nm]
            print(f"    {nm} = {xs(val) if erp.ЗначениеЗаполнено(val) else val}")
        except Exception as e:
            print(f"    {nm} <err {e}>")
else:
    print("  НЕ найден")

