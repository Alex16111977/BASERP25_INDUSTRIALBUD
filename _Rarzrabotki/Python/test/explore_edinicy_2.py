import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

print("=== ТЧ справочника Номенклатура (есть ли упаковки/единицы с коэффициентом) ===")
for тч in buh.Метаданные.Справочники.Номенклатура.ТабличныеЧасти:
    print(f"   ТЧ {тч.Имя}: {[r.Имя for r in тч.Реквизиты]}")

print("=== Любой справочник с реквизитом 'Коэффициент' + единица в имени ===")
for с in buh.Метаданные.Справочники:
    им = [r.Имя for r in с.Реквизиты]
    if any("оэффициент" in x or "оефіцієнт" in x for x in им):
        print(f"   {с.Имя}: {им}")

print("=== Спец 000000005: Единица(спец) vs Номенклатура.БазоваяЕдиницаИзмерения ===")
q = buh.NewObject("Запрос")
q.УстановитьПараметр("С", buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005"))
q.Текст = """ВЫБРАТЬ К.Номенклатура КАК Ном, К.Единица КАК ЕдСпец, К.Номенклатура.БазоваяЕдиницаИзмерения КАК ЕдБаза,
К.Количество КАК Кол, К.Сумма КАК Сум
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К ГДЕ К.Ссылка = &С"""
t = q.Выполнить().Выгрузить()
совп = разн = 0; примеры = []
for i in range(t.Количество()):
    r = t.Получить(i)
    eq = buh.String(r.ЕдСпец) == buh.String(r.ЕдБаза)
    if eq: совп += 1
    else:
        разн += 1
        if len(примеры) < 6: примеры.append(f"{buh.String(r.Ном)[:30]}: спец={buh.String(r.ЕдСпец)} база={buh.String(r.ЕдБаза)} кол={r.Кол} сум={r.Сум}")
print(f"   строк={t.Количество()} единица_совпадает={совп} различается={разн}")
for p in примеры: print("    ", p)

print("=== Остаток с Суммой (есть ли КоличествоОстаток и СуммаОстаток) ===")
q2 = buh.NewObject("Запрос")
