# -*- coding: utf-8 -*-
"""COM-smoke: колонка Економія (инвариант с ПонадНорму) + друк (ТабличныйДокумент) + 3 режима заполнения."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime
from collections import defaultdict

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

обр = buh.ВнешниеОбработки.Создать(EPF, False)
print("OK загружена:", обр.Метаданные().Имя)
for код in ("20", "22", "28"):
    обр.СчетаОстатков.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код)
обр.Период = pywintypes.Time(datetime.datetime(2026, 6, 22, 12, 0, 0))
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005")
qС = buh.NewObject("Запрос")
qС.Текст = 'ВЫБРАТЬ Склады.Ссылка КАК С ИЗ Справочник.Склады КАК Склады ГДЕ Склады.Наименование ПОДОБНО "%МХП%ОР%виробнич%"'
tС = qС.Выполнить().Выгрузить()
for i in range(tС.Количество()):
    обр.СкладыОстатков.Добавить().Склад = tС.Получить(i).С

обр.РассчитатьАнализ()
тч = обр.ТабличнаяЧастьОстатков

# === Економія-инвариант на уровне эталона: НЕ (Економія>0 И ΣПонадНорму>0) ===
эталоны = defaultdict(lambda: {"понад": 0.0, "эконом": 0.0})
for i in range(тч.Количество()):
    r = тч.Получить(i)
    k = buh.String(r.ОбщееНазвание)
    эталоны[k]["понад"] += float(r.ПонадНорму)
    эталоны[k]["эконом"] = max(эталоны[k]["эконом"], float(r.Экономия))
наруш = [k for k, v in эталоны.items() if v["эконом"] > 0.001 and v["понад"] > 0.001]
сЭкономией = [k for k, v in эталоны.items() if v["эконом"] > 0.001]
print(f"АНАЛИЗ строк={тч.Количество()} еталонів={len(эталоны)} з_економією={len(сЭкономией)} порушень_інваріанту={len(наруш)}")
assert len(наруш) == 0, f"нарушение Економія⟺Понад: {наруш}"
assert len(сЭкономией) > 0, "ожидалась хотя бы одна экономия (МХП ОРІЛЬ)"

# === Друк: ТабличныйДокумент строится и инспектируется ===
табдок = обр.СформироватьПечать(тч)
h = табдок.ВысотаТаблицы
шапка = табдок.Область(1, 1, 1, 9).Текст
print(f"ДРУК ВысотаТаблицы={h} шапка='{шапка}'")
assert h >= тч.Количество() + 6, "печать слишком мала"
assert "Аналіз залишків" in шапка, "нет шапки"
# шапка НЕ должна дублироваться по колонкам (строки 2-4 объединены -> текст в якорной ячейке)
for р, метка in ((2, "Період"), (3, "Склади"), (4, "Специфікація")):
    дубли = sum(1 for c in range(1, 10) if метка in табдок.Область(р, c, р, c).Текст)
    print(f"  рядок {р} ('{метка}') у скількох клітинках: {дубли}")
    assert дубли == 1, f"шапка строки {р} дублируется в {дубли} ячейках (ожидалось 1)"
# стиль: жирный заголовок таблицы + заданная ширина колонок + авто-масштаб
загЖирный = табдок.Область(6, 1, 6, 1).Шрифт.Жирный
ширКол2 = табдок.Область(6, 2, 6, 2).ШиринаКолонки
автомасштаб = табдок.АвтоМасштаб
print(f"СТИЛЬ заголовок_жирный={загЖирный} ширина_кол2={ширКол2} автомасштаб={автомасштаб}")
assert загЖирный, "заголовок таблицы не жирный"
assert float(ширКол2) > 0, "ширина колонки 'Номенклатура' не задана"  # Фаза 6: друк перелаштований на 13 колонок (кол2=30), перевіряємо що ширина задана
assert автомасштаб, "АвтоМасштаб не включён"

# === 3 режима: вызовы с опц. параметрами не падают (документы не выбраны -> Заповнено=0) ===
ro = обр.ЗаполнитьДокументыПоАнализу(True, True)
rn = обр.ЗаполнитьДокументыПоАнализу(True, False)
rp = обр.ЗаполнитьДокументыПоАнализу(False, True)
rd = обр.ЗаполнитьДокументыПоАнализу()  # без аргументов — обратная совместимость
print(f"РЕЖИМИ Заповнено: обидва={ro.Заповнено} тількиВНормі={rn.Заповнено} тількиПонад={rp.Заповнено} безАрг={rd.Заповнено}")
assert ro.Заповнено == 0 and rn.Заповнено == 0 and rp.Заповнено == 0 and rd.Заповнено == 0
print("SMOKE ekonomiya/pechat/rezhimy: PASS")
