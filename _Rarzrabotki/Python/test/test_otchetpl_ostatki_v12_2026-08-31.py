def агрегаты(таб):
    """{(подр, статья, колонка): [Ф1, Ф2]} + наличие регистратора остатков в 890000/900000."""
    акк = defaultdict(lambda: [0.0, 0.0])
    остатки_в_накопительных = False
    for i in range(таб.Количество()):
        с = таб.Получить(i)
        ключ = (S(с.Подразделение), S(с.СтатьяPL), int(с.КолонкаСорт))
        акк[ключ][0] += float(с.СуммаФ1)
        акк[ключ][1] += float(с.СуммаФ2)
        if int(с.КолонкаСорт) in (890000, 900000) and "Ввод остатков" in S(с.Документ):
            остатки_в_накопительных = True
    return акк, остатки_в_накопительных


def сравнить(имя, а11, а12, колонка):
    ключи = set(k for k in а11 if k[2] == колонка) | set(k for k in а12 if k[2] == колонка)
    расх = []
    for k in sorted(ключи):
        ф1_11, ф2_11 = а11.get(k, [0.0, 0.0])
        ф1_12, ф2_12 = а12.get(k, [0.0, 0.0])
        if abs(ф1_11 - ф1_12) > 0.005 or abs(ф2_11 - ф2_12) > 0.005:
            расх.append("%s|%s: Ф1 %.2f→%.2f, Ф2 %.2f→%.2f" % (k[0][:30], k[1][:25], ф1_11, ф1_12, ф2_11, ф2_12))
    чек(имя, not расх, ("расхождений %d, первые: %s" % (len(расх), "; ".join(расх[:3]))) if расх else "ключей %d" % len(ключи))


