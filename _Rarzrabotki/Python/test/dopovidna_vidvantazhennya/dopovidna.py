def docx_(тіло, path):
    import docx
    from docx.shared import Pt
    doc = docx.Document()
    st = doc.styles["Normal"]; st.font.name = "Calibri"; st.font.size = Pt(11)
    for блок in тіло:
        for частина in re.split(r"(<table>.*?</table>|<ul>.*?</ul>|<h1>.*?</h1>|<h2>.*?</h2>|<p[^>]*>.*?</p>)", блок, flags=re.S):
            if not частина.strip():
                continue
            if частина.startswith("<h1>"):
                doc.add_heading(текст(частина), level=1)
            elif частина.startswith("<h2>"):
                doc.add_heading(текст(частина), level=2)
            elif частина.startswith("<ul>"):
                for li in re.findall(r"<li>(.*?)</li>", частина, flags=re.S):
                    runs(doc.add_paragraph(style="List Bullet"), li)
            elif частина.startswith("<table>"):
                рядки = re.findall(r"<tr[^>]*>(.*?)</tr>", частина, flags=re.S)
                клітинки = [re.findall(r"<t[hd]>(.*?)</t[hd]>", r, flags=re.S) for r in рядки]
                t = doc.add_table(rows=0, cols=len(клітинки[0])); t.style = "Table Grid"
                for i, rr in enumerate(клітинки):
                    rc = t.add_row().cells
                    for j, c in enumerate(rr):
                        p = rc[j].paragraphs[0]
                        runs(p, c.replace("<br>", "\n"), розмір=8.5, жирний=(i == 0 or "Разом" in rr[0]))
            elif частина.startswith("<p"):
                runs(doc.add_paragraph(), re.sub(r"^<p[^>]*>|</p>$", "", частина))
    doc.save(path)


def текст(f):
    return H.unescape(re.sub(r"<[^>]+>", "", f.replace("<br>", "\n")))


def runs(par, frag, розмір=None, жирний=False):
    from docx.shared import Pt
    for m in re.finditer(r"<b>(.*?)</b>|([^<]+)|<br>", frag.replace("<br>", "\n"), flags=re.S):
        s = m.group(1) if m.group(1) is not None else m.group(2)
        if not s:
            continue
        r = par.add_run(H.unescape(s)); r.bold = жирний or m.group(1) is not None
        if розмір:
            r.font.size = Pt(розмір)


