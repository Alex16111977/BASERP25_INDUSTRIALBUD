def тонни(м, об=None):
    """Тонни за актами і вага з назв рейсів без акта (верхня оцінка) за місяцем документа ERP."""
    акти = sum(a[2] for x in МЕТАЛ if x[0] == м and (об is None or x[3] == об) for a in x[5])
    без = sum(x[6] for x in МЕТАЛ if x[0] == м and (об is None or x[3] == об) and not x[5] and x[6])
    return акти, без


def коеф(об):
    """Співвідношення «акт / вага з назви рейсу» по рейсах об'єкта, що вже мають акт."""
    пари = [(sum(a[2] for a in x[5]), x[6]) for x in МЕТАЛ if x[3] == об and x[5] and x[6]]
    return sum(a for a, _ in пари) / sum(n for _, n in пари)


def оцінка(м, об=None):
    """Рейси без акта, перераховані на співвідношення акт/назва свого об'єкта."""
    return sum(x[6] * коеф(x[3]) for x in МЕТАЛ if x[0] == м and (об is None or x[3] == об) and not x[5] and x[6])


