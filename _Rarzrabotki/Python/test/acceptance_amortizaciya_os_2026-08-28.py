# -*- coding: utf-8 -*-
"""ПРИЁМКА: аналитика АмортизацияОС = карточка ОС — полный путь пользователя.

.erf + вариант «1.P&L Производство (Месяц, Накопительный PL)» С ЖИВОЙ группировкой
«Аналитика», период июль-2026, отбор по подразделению с максимумом строк амортизации
(июль-2026: Кам'янець_Цемент, 47 карточек на 571 504,21).

Проверки:
  1. Есть подразделение с амортизацией за июль (данные для сценария).
  2. Отчёт строится; наименования карточек ОС видны в табличном документе.
  3. Итог строки статьи «Амортизация» не изменился (сверка с прямым запросом).

Запуск:
    python _Rarzrabotki\\Python\\test\\acceptance_amortizaciya_os_2026-08-28.py
"""
import re
import sys

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетPL_ПолныйЕРП.erf"

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ПРОВАЛОВ = [0]
ПРОВЕРОК = [0]
ДОПУСК = 0.02


def чек(имя, ок, подробно=""):
    ПРОВЕРОК[0] += 1
    if not ок:
        ПРОВАЛОВ[0] += 1
    print("  [%s] %s%s" % ("OK  " if ок else "FAIL", имя, ("  — " + подробно) if подробно else ""))


def норм(текст):
    return re.sub(r"\s+", " ", (текст or "")).strip()


def скаляр(текст, **парам):
    q = erp.NewObject("Запрос")
    q.Text = текст
    for k, v in парам.items():
        q.SetParameter(k, v)
    r = q.Execute().Выгрузить()
    return r.Получить(0) if r.Количество() else None


# 1. Подразделение-лидер по строкам амортизации июля + его карточки и итог
г = скаляр("""
ВЫБРАТЬ ПЕРВЫЕ 1 Р.Подразделение КАК Подр, КОЛИЧЕСТВО(*) КАК Строк, СУММА(Р.Сумма) КАК Сумма
ИЗ РегистрНакопления.ПрочиеРасходы КАК Р
ГДЕ Р.Регистратор ССЫЛКА Документ.АмортизацияОС
	И Р.Период МЕЖДУ ДАТАВРЕМЯ(2026,7,1) И ДАТАВРЕМЯ(2026,7,31,23,59,59)
	И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	И Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
	И Р.Подразделение <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
СГРУППИРОВАТЬ ПО Р.Подразделение
УПОРЯДОЧИТЬ ПО Строк УБЫВ
""")
чек("есть подразделение с амортизацией за июль", г is not None)
ПОДР = г.Подр
ИТОГ_РЕГ = float(г.Сумма)
print("      подразделение: %s | строк %d | сумма %.2f" % (S(ПОДР), int(г.Строк), ИТОГ_РЕГ))

q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ ПРЕДСТАВЛЕНИЕ(Р.АналитикаРасходов) КАК Карточка
ИЗ РегистрНакопления.ПрочиеРасходы КАК Р
ГДЕ Р.Регистратор ССЫЛКА Документ.АмортизацияОС
	И Р.Период МЕЖДУ ДАТАВРЕМЯ(2026,7,1) И ДАТАВРЕМЯ(2026,7,31,23,59,59)
	И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	И Р.Подразделение = &Подр
	И Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
"""
q2.SetParameter("Подр", ПОДР)
рк = q2.Execute().Выгрузить()
КАРТОЧКИ = [норм(S(рк.Получить(i).Карточка)) for i in range(рк.Количество())]
print("      карточек:", len(КАРТОЧКИ), "| пример:", КАРТОЧКИ[0][:50] if КАРТОЧКИ else "-")

# 2. Отчёт полным путём с живой группировкой «Аналитика»
ВАР = скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Вар.Ссылка КАК Ссылка ИЗ Справочник.ВариантыОтчетов КАК Вар '
             'ГДЕ Вар.Наименование = &Имя И НЕ Вар.ПометкаУдаления',
             Имя="1.P&L Производство (Месяц, Накопительный PL)").Ссылка
отчет = erp.ВнешниеОтчеты.Создать(ERF)
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
к = отчет.КомпоновщикНастроек
к.Инициализировать(erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
к.ЗагрузитьНастройки(ВАР.Настройки.Получить())
н = к.Настройки
гг = скаляр("ВЫБРАТЬ ДАТАВРЕМЯ(2026,7,1,0,0,0) КАК Н, ДАТАВРЕМЯ(2026,7,31,23,59,59) КАК К")
п = erp.NewObject("СтандартныйПериод")
п.ДатаНачала = гг.Н
п.ДатаОкончания = гг.К
эл = н.ПараметрыДанных.Элементы.Найти("Период")
эл.Использование = True
эл.Значение = п
for i in range(н.Отбор.Элементы.Количество()):
    о = н.Отбор.Элементы.Получить(i)
    try:
        if S(о.ЛевоеЗначение) == "Подразделение":
            сп = erp.NewObject("СписокЗначений")
            сп.Добавить(ПОДР)
            о.ПравоеЗначение = сп
            о.Использование = True
    except Exception:
        pass
таб = erp.NewObject("ТабличныйДокумент")
отчет.СкомпоноватьРезультат(таб)
в, ш = int(таб.ВысотаТаблицы), int(таб.ШиринаТаблицы)
чек("отчёт строится", в > 10, "строк %d" % в)

тексты = set()
for r in range(1, в + 1):
    for c in range(1, min(ш, 4) + 1):
        x = норм(S(таб.Область(r, c, r, c).Текст))
        if x:
            тексты.add(x)
видно = sum(1 for км in КАРТОЧКИ if км in тексты)
чек("карточки ОС видны в готовом отчёте (группировка «Аналитика»)",
    видно > 0 and видно >= len(КАРТОЧКИ) * 3 // 4,
    "видно %d из %d" % (видно, len(КАРТОЧКИ)))

# 3. Итог строки статьи «Амортизация» (июльский блок, «Сумма, грн» = 3-я колонка блока)
итог_найден = None
for r in range(1, в + 1):
    первая = ""
    for c in range(1, ш + 1):
        x = норм(S(таб.Область(r, c, r, c).Текст))
        if x:
            первая = x
            break
    if первая.lower() == "амортизация":
        for c in range(1, ш + 1):
            x = S(таб.Область(r, c, r, c).Текст).strip()
            ч = x.replace("\xa0", "").replace(" ", "").replace(",", ".")
            try:
                v = float(ч)
                if abs(v - ИТОГ_РЕГ) < ДОПУСК:
                    итог_найден = v
                    break
            except ValueError:
                continue
        break
чек("итог строки «Амортизация» = сумме регистра (не изменился)",
    итог_найден is not None, "ждали %.2f" % ИТОГ_РЕГ)

print("")
print("=" * 96)
итог = "ЗЕЛЁНО" if ПРОВАЛОВ[0] == 0 else "ЕСТЬ ПРОВАЛЫ"
print("ИТОГ: %s — проверок %d, провалов %d" % (итог, ПРОВЕРОК[0], ПРОВАЛОВ[0]))
print("=" * 96)
sys.exit(1 if ПРОВАЛОВ[0] else 0)
