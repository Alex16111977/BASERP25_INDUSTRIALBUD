# ---------------------------------------------------------------- парсер
ОСНОВЫ = "мод|буд|дом|шт"
_ХВОСТ = r"[a-zA-Zа-яА-ЯіїєґІЇЄҐ'’.]*"
# порядковая форма: «1-й модуль (1-1; 1-2) — 100%» -> ДОМ №1, модули из скобок
ПОРЯДКОВЫЙ = re.compile(
    r"(\d+)\s*[-–—]\s*(?:й|го|ий|а|я)\s*(?:" + ОСНОВЫ + r")" + _ХВОСТ +
    r"\s*(\([^)]*\))?\s*[-–—:]*\s*(\d+(?:[.,]\d+)?)\s*%", re.IGNORECASE)
# количественная форма: «5 модулів — 0%», «1 МОД.- 60%» -> следующие N свободных домов целиком
КОЛИЧЕСТВЕННЫЙ = re.compile(
    r"(\d+)\s*(?:" + ОСНОВЫ + r")" + _ХВОСТ + r"\s*[-–—:]*\s*(\d+(?:[.,]\d+)?)\s*%", re.IGNORECASE)
# «сегментоподобный» фрагмент для контроля полноты разбора (обе формы)
ФРАГМЕНТ = re.compile(r"(\d+)\s*(?:[-–—]\s*(?:й|го|ий|а|я)\s*)?(?:" + ОСНОВЫ + r")", re.IGNORECASE)
ОДИНОЧНЫЙ = re.compile(r"^(\d+(?:[.,]\d+)?)\s*%$")
ПАРА = re.compile(r"(\d+)\s*[-–—]\s*(\d+)")          # «1-2» = дом 1, модуль 2
СКОБКИ = re.compile(r"\([^)]*\)")


def _затереть(текст, начало, конец):
    """Заменить участок пробелами той же длины — позиции остальных сегментов не сдвигаются."""
    return текст[:начало] + " " * (конец - начало) + текст[конец:]


def парс(текст, n, m):
    """-> (матрица[n][m] процентов, сегменты[list[str]], флаги[list[str]]).
    n — домов (СС.КоличествоДомов), m — модулей в доме (СС.А_КоличествоМодулей).
    «K-й модуль (K-1; K-2) — P%» -> дом K, перечисленные модули = P; скобок нет -> все модули дома.
    «N модулів — P%» -> следующие N свободных домов целиком.
    Никогда не молчит: всё сомнительное -> флаг (регламент §3 «fail loud»)."""
    сырой = str(текст or "").strip()
    флаги, сегменты = [], []
    пусто = [[0.0] * m for _ in range(n)]
    if not сырой:
        return пусто, сегменты, флаги

    остаток, найдено = сырой, []
    # 1) порядковые сегменты — по сырому тексту (скобки нужны для разбора модулей)
    for сег in ПОРЯДКОВЫЙ.finditer(сырой):
        найдено.append((сег.start(), "ord", int(сег.group(1)), сег.group(2), float(сег.group(3).replace(",", "."))))
        остаток = _затереть(остаток, сег.start(), сег.end())
    # 2) скобки-уточнения вне порядковых сегментов на проценты не влияют — гасим
    for ск in СКОБКИ.finditer(остаток):
        остаток = _затереть(остаток, ск.start(), ск.end())
    # 3) количественные сегменты — по тому, что осталось
    for сег in КОЛИЧЕСТВЕННЫЙ.finditer(остаток):
        найдено.append((сег.start(), "cnt", int(сег.group(1)), None, float(сег.group(2).replace(",", "."))))
    найдено.sort()

    if найдено:
        матрица = [[None] * m for _ in range(n)]
        занятдом = [False] * n          # дом «закрыт» (получил значение хотя бы по одному модулю)
        курсор, охвачено = 0, 0
        for _, вид, к, скобка, p in найдено:
            if p < 0 or p > 100:
                флаги.append(f"процент {p} вне 0..100")
            if вид == "ord":                                     # «K-й модуль» -> дом №K
                модули = []
                if скобка:
                    for д, мод in ПАРА.findall(скобка):
                        if int(д) != к:
                            флаги.append(f"у сегменті «{к}-й» скобка вказує дім {д} — перевірити")
                        if 1 <= int(мод) <= m:
                            модули.append(int(мод))
                        else:
                            флаги.append(f"модуль {мод} поза 1..{m}")
                if not модули:
                    модули = list(range(1, m + 1))
                    if скобка:
                        флаги.append(f"скобка «{скобка}» не розібрана — % поставлено на всі {m} модулі")
                сегменты.append(f"дім №{к} М{'/М'.join(map(str, модули))}={p:g}%")
                охвачено += 1
                if 1 <= к <= n:
                    for мод in модули:
                        if матрица[к - 1][мод - 1] is not None:
                            флаги.append(f"дім №{к} модуль {мод} заданий двічі")
                        матрица[к - 1][мод - 1] = p
                    занятдом[к - 1] = True
                    курсор = max(курсор, к)
                else:
                    флаги.append(f"порядковий номер {к} поза 1..{n}")
            else:                                                # «K модулів» -> K свободных домов
                сегменты.append(f"{к} домів×{p:g}%")
                охвачено += к
                поставлено = 0
                while поставлено < к:
                    while курсор < n and занятдом[курсор]:
                        курсор += 1
                    if курсор >= n:
                        флаги.append(f"сегменти дають більше {n} домів — хвіст відкинуто")
                        break
                    for мод in range(m):
                        матрица[курсор][мод] = p
                    занятдом[курсор] = True
                    курсор += 1
                    поставлено += 1
        фрагм = len(ФРАГМЕНТ.findall(СКОБКИ.sub(" ", сырой)))
        if фрагм > len(найдено):
            флаги.append(f"РОЗПІЗНАНО {len(найдено)} сегм. з {фрагм} — частину тексту ВТРАЧЕНО")
        if охвачено != n:
            флаги.append(f"Σ домів у сегментах = {охвачено}, а домів {n}")
        return [[0.0 if x is None else x for x in ряд] for ряд in матрица], сегменты, флаги

    один = ОДИНОЧНЫЙ.match(СКОБКИ.sub(" ", сырой).strip())
    if один:
        p = float(один.group(1).replace(",", "."))
        if p < 0 or p > 100:
            флаги.append(f"процент {p} вне 0..100")
        сегменты.append(f"одиночний {p:g}% -> всі {n} домів × {m} модулі")
        return [[p] * m for _ in range(n)], сегменты, флаги
    if "%" in сырой and re.search(r"\d", сырой):
        флаги.append("є цифри і «%», але сегменти НЕ розпізнані")
    return пусто, сегменты, флаги


def факт_текст(v, nf):
    """percent-aware: число 0,2 при формате «0%» = 20% (регламент §1)."""
    if v is None or isinstance(v, bool):
        return ""
    if isinstance(v, (int, float)):
        return (f"{v * 100:g}%" if "%" in (nf or "") else f"{v:g}")
    return str(v).strip()


def норм(s):
    s = str(s or "").strip().lower()
    for a, b in (("'", " "), ("’", " "), ("ʼ", " "), ("`", " "), ("ґ", "г"), ("\u00a0", " ")):
        s = s.replace(a, b)
    s = re.sub(r"[;.,:]+$", "", s)
    return re.sub(r"\s+", " ", s).strip()


def показ(матрица, m):
    """Компактно: «100» если все модули дома равны, иначе «100/10»."""
    куски = []
    for ряд in матрица:
        куски.append(f"{ряд[0]:g}" if len(set(ряд)) == 1 else "/".join(f"{x:g}" for x in ряд))
    return ",".join(куски)


