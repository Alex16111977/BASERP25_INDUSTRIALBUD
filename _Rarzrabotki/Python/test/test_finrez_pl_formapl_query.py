RES_COLS = ["СуммаФ1_Excel", "СуммаФ2_Excel", "Сумма_Excel", "СуммаФ1", "СуммаФ2", "Сумма"]


def test_month(label, nach, konec, dds, org):
    print("\n" + "=" * 78)
    print(f"  ТЕСТ-МЕСЯЦ: {label}  ({nach:%Y-%m-%d} .. {konec:%Y-%m-%d})")
    print("=" * 78)

    f1_reg, f2_reg, empty_reg = forma_distribution(nach, konec)
    print(f"ПрочиеРасходы.Обороты (фильтр расхода): Ф1={f1_reg:,.2f}  Ф2={f2_reg:,.2f}  Пусто={empty_reg:,.2f}")

    # BASELINE
    try:
        base = run(BASE_Q, nach, konec, dds, org)
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        print(f"!! BASE_Q FAIL: {msg}")
        raise
    base_cols = [c.Имя for c in base.Колонки]
    base_sums = sums(base, RES_COLS)
    print(f"\nBASE: rows={base.Количество()}, cols={len(base_cols)} (ФормаPL отсутствует: {'ФормаPL' not in base_cols})")

    # MODIFIED
    try:
        mod = run(MOD_Q, nach, konec, dds, org)
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        print(f"!! MOD_Q FAIL: {msg}")
        raise
    mod_cols = [c.Имя for c in mod.Колонки]
    mod_sums = sums(mod, RES_COLS)
    print(f"MOD : rows={mod.Количество()}, cols={len(mod_cols)} (ФормаPL присутствует: {'ФормаPL' in mod_cols})")

    # --- проверки ---
    errs = []
    if "ФормаPL" not in mod_cols:
        errs.append("в MOD нет колонки ФормаPL")

    # ФормаPL заполнена только Форма1/Форма2
    f1v = ERP.Перечисления.А_ФормыPL.Форма1
    f2v = ERP.Перечисления.А_ФормыPL.Форма2
    empty_forms = 0
    bad_row_fact = 0
    bad_row_excel = 0
    cnt_f1 = cnt_f2 = 0
    for r in range(mod.Количество()):
        row = mod[r]
        fv = S(row.ФормаPL)
        if fv == S(f1v):
            cnt_f1 += 1
        elif fv == S(f2v):
            cnt_f2 += 1
        else:
            empty_forms += 1
        if abs(float(row.СуммаФ1) + float(row.СуммаФ2) - float(row.Сумма)) > 0.01:
            bad_row_fact += 1
        if abs(float(row.СуммаФ1_Excel) + float(row.СуммаФ2_Excel) - float(row.Сумма_Excel)) > 0.01:
            bad_row_excel += 1
    if empty_forms:
        errs.append(f"{empty_forms} строк MOD с пустой/иной ФормаPL")
    if bad_row_fact:
        errs.append(f"{bad_row_fact} строк ломают Ф1+Ф2=Сумма (факт)")
    if bad_row_excel:
        errs.append(f"{bad_row_excel} строк ломают Ф1_Excel+Ф2_Excel=Сумма_Excel (план)")

    # Σ-инварианты
    def near(a, b):
        return abs(a - b) < 0.5

    if not near(mod_sums["Сумма"], base_sums["Сумма"]):
        errs.append(f"Σ Сумма изменилась: BASE={base_sums['Сумма']:.2f} MOD={mod_sums['Сумма']:.2f}")
    if not near(mod_sums["Сумма_Excel"], base_sums["Сумма_Excel"]):
        errs.append(f"Σ Сумма_Excel изменилась: BASE={base_sums['Сумма_Excel']:.2f} MOD={mod_sums['Сумма_Excel']:.2f}")
    if not near(mod_sums["СуммаФ1_Excel"], base_sums["СуммаФ1_Excel"]):
        errs.append(f"Σ СуммаФ1_Excel изменилась: BASE={base_sums['СуммаФ1_Excel']:.2f} MOD={mod_sums['СуммаФ1_Excel']:.2f}")
    if not near(mod_sums["СуммаФ2_Excel"], base_sums["СуммаФ2_Excel"]):
        errs.append(f"Σ СуммаФ2_Excel изменилась: BASE={base_sums['СуммаФ2_Excel']:.2f} MOD={mod_sums['СуммаФ2_Excel']:.2f}")
    if not near(mod_sums["СуммаФ1"] + mod_sums["СуммаФ2"], mod_sums["Сумма"]):
        errs.append(f"Σ(Ф1+Ф2)={mod_sums['СуммаФ1']+mod_sums['СуммаФ2']:.2f} != Σ Сумма={mod_sums['Сумма']:.2f}")

    print(f"\n  Σ Сумма (факт):        BASE={base_sums['Сумма']:>18,.2f}  MOD={mod_sums['Сумма']:>18,.2f}")
    print(f"  Σ Сумма_Excel (план):  BASE={base_sums['Сумма_Excel']:>18,.2f}  MOD={mod_sums['Сумма_Excel']:>18,.2f}")
    print(f"  Σ СуммаФ1_Excel:       BASE={base_sums['СуммаФ1_Excel']:>18,.2f}  MOD={mod_sums['СуммаФ1_Excel']:>18,.2f}")
    print(f"  Σ СуммаФ2_Excel:       BASE={base_sums['СуммаФ2_Excel']:>18,.2f}  MOD={mod_sums['СуммаФ2_Excel']:>18,.2f}")
    print(f"  Σ СуммаФ1 (факт):      BASE={base_sums['СуммаФ1']:>18,.2f}  MOD={mod_sums['СуммаФ1']:>18,.2f}  <-- разбивка меняется")
    print(f"  Σ СуммаФ2 (факт):      BASE={base_sums['СуммаФ2']:>18,.2f}  MOD={mod_sums['СуммаФ2']:>18,.2f}  <-- разбивка меняется")
    print(f"  строк ФормаPL: Ф1={cnt_f1}  Ф2={cnt_f2}")

    if errs:
        print("\n  === ОШИБКИ ===")
        for e in errs:
            print(f"    !! {e}")
        return False, base_sums, mod_sums
    print("\n  [OK] все инварианты выполнены для месяца")
    return True, base_sums, mod_sums


