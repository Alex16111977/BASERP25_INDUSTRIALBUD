def from_bsl_func(src):
    m = re.search(r'Функция\s+СформироватьЗапросСверткиPL\(\)(.*?)КонецФункции', src, re.S)
    if not m:
        raise RuntimeError("Функция СформироватьЗапросСверткиPL не найдена")
    seg = m.group(1)
    m2 = re.search(r'"(.*)"\s*;', seg, re.S)   # greedy → последняя ";
    raw = m2.group(1)
    lines = raw.split("\n")
    out = [lines[0]]
    for ln in lines[1:]:
        out.append(re.sub(r'^\t\|', '', ln))   # снять \t| continuation
    return "\n".join(out).replace('""', '"')

def to_bsl_func(query_clean):
    esc = query_clean.replace('"', '""')
    lines = esc.split("\n")
    body = "\tВозврат\n\t\"" + lines[0] + "\n"
    for ln in lines[1:]:
        body += "\t|" + ln + "\n"
    body = body.rstrip("\n") + "\";\n"
    return "Функция СформироватьЗапросСверткиPL()\n" + body + "КонецФункции"

