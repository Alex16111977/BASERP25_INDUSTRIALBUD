# --- 2. Остатки на счёте 22 (В ИЕРАРХИИ) на текущую дату, по номенклатуре ---
print("\n=== Остатки счёта 22 (все склады) ===")
import datetime
НаДату = datetime.datetime(2026, 7, 13, 23, 59, 59)
сч22 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("22")
print("  Счёт 22 найден:", (сч22 is not None and buh.String(сч22) != ""), "->", (сч22.Наименование if сч22 else "—"))

q = buh.NewObject("Запрос")
q.УстановитьПараметр("НаДату", НаДату)
q.УстановитьПараметр("Сч22", сч22)
q.Текст = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) КАК Номенклатура,
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).ОбщееНазваниеНоменклатуры КАК ОбщееНазвание,
    Ост.Счет КАК Счет,
    СУММА(Ост.КоличествоОстаток) КАК Остаток,
    СУММА(Ост.СуммаОстаток) КАК Сумма
ИЗ
    РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ(&Сч22), , ) КАК Ост
ГДЕ
    Ост.КоличествоОстаток > 0
СГРУППИРОВАТЬ ПО
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура),
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).ОбщееНазваниеНоменклатуры,
    Ост.Счет
"""
cards22 = []
try:
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        cards22.append({
            'ном': sel.Номенклатура.Наименование if sel.Номенклатура else "",
            'общ': (sel.ОбщееНазвание.Наименование if (sel.ОбщееНазвание and buh.String(sel.ОбщееНазвание) != "") else ""),
            'общ_ref': buh.String(sel.ОбщееНазвание) if sel.ОбщееНазвание else "",
            'счет': sel.Счет.Код if sel.Счет else "",
            'ост': float(sel.Остаток),
            'сум': float(sel.Сумма),
        })
    print(f"  Карточек с остатком на 22: {len(cards22)}")
    subaccs = {}
    for c in cards22:
        subaccs[c['счет']] = subaccs.get(c['счет'], 0) + 1
    print("  По субсчетам:", subaccs)
    with_obsh = [c for c in cards22 if c['общ_ref']]
    print(f"  С заполненным ОбщееНазвание: {len(with_obsh)} / {len(cards22)}")
except Exception as e:
    ei = getattr(e, 'excepinfo', None)
    print("  FAIL остатки:", ei[2] if ei else e)

# --- 3. Множество ОбщееНазвание, у которых ЕСТЬ норма в СтруктураСебестоимости.Комплектующие ---
print("\n=== Покрытие нормами (СтруктураСебестоимости.Комплектующие) ===")
q2 = buh.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    К.ОбщееНазвание КАК ОбщееНазвание
ИЗ
    Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
    К.ОбщееНазвание <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
"""
norm_set = set()
try:
    sel2 = q2.Выполнить().Выбрать()
    while sel2.Следующий():
        norm_set.add(buh.String(sel2.ОбщееНазвание))
    print(f"  Различных ОбщееНазвание с нормой (во всех спецификациях): {len(norm_set)}")
    if cards22:
        covered = [c for c in cards22 if c['общ_ref'] in norm_set]
        print(f"  Карточек 22 с нормой (ОбщееНазвание в спецификациях): {len(covered)} / {len(cards22)}")
        print(f"  БЕЗ нормы (пойдут в 'понад норму'): {len(cards22) - len(covered)} / {len(cards22)}")
        print("\n  Примеры карточек 22 (первые 12):")
        for c in cards22[:12]:
            mark = "НОРМА" if c['общ_ref'] in norm_set else "без-нормы"
            print(f"    [{mark}] сч{c['счет']} | {c['ном'][:45]:45} | общ='{c['общ'][:30]}' | ост={c['ост']:.2f}")
except Exception as e:
    ei = getattr(e, 'excepinfo', None)
    print("  FAIL нормы:", ei[2] if ei else e)

