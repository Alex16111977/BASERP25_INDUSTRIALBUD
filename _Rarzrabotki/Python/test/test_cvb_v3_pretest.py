# -*- coding: utf-8 -*-
"""ЦВБ v3: претесты запросов (Rule #-1) перед BSL.

1. Договоры-исключения С ССЫЛКОЙ (для фильтра плагина Взаиморасчёты по ссылке).
2. Все планы обмена из РС А_НастройкиПодключенияБаз (для полного обмена).
3. Синтаксис ВЫБОР в УПОРЯДОЧИТЬ (сортировка «точный контур первым» правил).
4. Внутренние договоры Воронцова (список для пользователя под галочку).
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
fails = 0


def run(name, text, params=None, setup=None):
    global fails
    q = erp.NewObject("Запрос")
    q.Text = text
    if params:
        for k, val in params.items():
            q.SetParameter(k, val)
    try:
        r = q.Execute().Выгрузить()
        print(f"[OK] {name}: строк={r.Количество()}")
        return r
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"[FAIL] {name}: {msg}")
        fails += 1
        return None


# --- 1. Договоры-исключения со ссылкой ---
r1 = run("договоры-исключения по ссылке", """
ВЫБРАТЬ
	Д.Ссылка КАК Договор,
	Д.А_ИдКод КАК ИдКод
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	(Д.А_ЭтоДоговорФинАгента
		ИЛИ Д.А_ИсключитьиЗПроверкиСБухУчетом)
""")
if r1 is not None:
    pust = 0
    for i in range(r1.Количество()):
        if not str(S(r1.Получить(i).ИдКод)).strip():
            pust += 1
    print(f"     всего={r1.Количество()}, с ПУСТЫМ А_ИдКод={pust}")

# --- 2. Планы обмена из регистра подключений ---
r2 = run("планы обмена из регистра", """
ВЫБРАТЬ
	Настройки.ПланОбмена КАК ПланОбмена,
	Настройки.ИдентификаторБазы КАК ИдБазы
ИЗ
	РегистрСведений.А_НастройкиПодключенияБаз КАК Настройки

УПОРЯДОЧИТЬ ПО
	Настройки.ИдентификаторБазы
""")
if r2 is not None:
    for i in range(r2.Количество()):
        row = r2.Получить(i)
        plan = row.ПланОбмена
        zap = ""
        try:
            zap = plan.Метаданные().Имя if str(S(plan)).strip() else "(пусто)"
        except Exception:
            zap = "(пусто)"
        print(f"     {S(row.ИдБазы)} -> {zap}")

# --- 3. ВЫБОР в УПОРЯДОЧИТЬ (на существующем РС) ---
kontur = erp.Справочники.А_КонтурыСверкиБаз.НайтиПоНаименованию("Взаиморасчёты", True)
run("сортировка ВЫБОР точный-контур-первым", """
ВЫБРАТЬ
	Искл.КлючСтроки КАК КлючСтроки,
	ВЫБОР КОГДА Искл.Контур = &Контур ТОГДА 0 ИНАЧЕ 1 КОНЕЦ КАК Порядок
ИЗ
	РегистрСведений.А_ИсключенияСверкиБаз КАК Искл

УПОРЯДОЧИТЬ ПО
	Порядок
""", {"Контур": kontur})

# --- 4. Внутренние договоры Воронцова ---
r4 = run("внутренние договоры Воронцова", """
ВЫБРАТЬ
	Д.Ссылка КАК Договор,
	Д.Наименование КАК Наименование,
	Д.А_ИдКод КАК ИдКод,
	Д.А_ИсключитьиЗПроверкиСБухУчетом КАК УжеИсключен
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	Д.Контрагент.Наименование ПОДОБНО "%Воронцов%"
	И (Д.Наименование ПОДОБНО "%кредитор%"
		ИЛИ Д.Наименование ПОДОБНО "%Нераспределенная%"
		ИЛИ Д.Наименование ПОДОБНО "%Кредитование%")
""")
if r4 is not None:
    for i in range(r4.Количество()):
        row = r4.Получить(i)
        print(f"     {S(row.Наименование)} | ИдКод='{S(row.ИдКод)}' | УжеИсключен={row.УжеИсключен}")

erp = None
print("\n" + ("PRETEST PASS" if fails == 0 else f"PRETEST FAIL ({fails})"))
sys.exit(0 if fails == 0 else 1)
