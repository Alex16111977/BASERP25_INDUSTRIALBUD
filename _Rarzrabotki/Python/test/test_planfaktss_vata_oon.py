# -*- coding: utf-8 -*-
"""Кейс пользователя 04.09.2026: план «Мінеральна вата 100» не должен уезжать под «Мінеральна вата 50».

В СС «МД ООН Админ» строки IZOVAT 100 привязаны к карточке «EKOBOARD 50*610*1250» с карточной
общей назвой «Мінеральна вата 50». Отчёт обязан брать общую назву плана из СТРОКИ СС:
  - план под ОН «Мінеральна вата 100» = сумма Количество строк СС с этой ОН × КоличествоДомов;
  - под ОН «Мінеральна вата 50» нет плановых строк с аналитикой «EKOBOARD…»;
  - факт закупок по-прежнему классифицируется карточной ОН.
"""
import os
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\ПланФактССБухгалтерія.erf"
CONN = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
СС_ИМЯ = "МД ООН Админ"


def план_по_тч(b, он_имя):
    z = b.NewObject("Запрос")
    z.Текст = """
    ВЫБРАТЬ
    	СУММА(К.Количество * ВЫБОР КОГДА К.Ссылка.КоличествоДомов > 0 ТОГДА К.Ссылка.КоличествоДомов ИНАЧЕ 1 КОНЕЦ) КАК Кол
    ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
    ГДЕ К.Ссылка.Наименование = &СС И К.Ссылка.Активная И НЕ К.Ссылка.ПометкаУдаления
    	И К.ОбщееНазвание.Наименование = &ОН
    """
    z.УстановитьПараметр("СС", СС_ИМЯ)
    z.УстановитьПараметр("ОН", он_имя)
    v = z.Выполнить().Выгрузить()[0].Кол
    return float(v or 0)


def main():
    assert os.path.exists(ERF), f"Не собран .erf: {ERF}"
    v8 = win32com.client.Dispatch("V83.COMConnector")
    b = v8.Connect(CONN)
    отчёт = b.ВнешниеОтчеты.Создать(ERF)

    z = b.NewObject("Запрос")
    z.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2026, 7, 1) КАК Н, КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2026, 9, 30), ДЕНЬ) КАК К"
    гр = z.Выполнить().Выгрузить()[0]
    период = b.NewObject("СтандартныйПериод")
    период.ДатаНачала = гр.Н
    период.ДатаОкончания = гр.К

    тз = отчёт.ПолучитьДанные(период)

    план100 = план50 = факт100 = факт50 = 0.0
    ekoboard_под_50 = []
    for i in range(тз.Количество()):
        r = тз[i]
        if r.Подразделение.Наименование != СС_ИМЯ or r.ОбщееНазвание.Пустая():
            continue
        он = r.ОбщееНазвание.Наименование.strip()
        if он == "Мінеральна вата 100":
            план100 += r.ПланКол
            факт100 += r.ФактКол
        elif он == "Мінеральна вата 50":
            план50 += r.ПланКол
            факт50 += r.ФактКол
            if r.ПланКол != 0 and r.Аналитика.upper().startswith("EKOBOARD"):
                ekoboard_под_50.append((r.Аналитика, r.ПланКол))

    ожид100 = план_по_тч(b, "Мінеральна вата 100")
    ожид50 = план_по_тч(b, "Мінеральна вата 50")
    assert ожид100 > 0 and ожид50 > 0, f"В ТЧ нет строк: вата100={ожид100} вата50={ожид50}"
    assert abs(план100 - ожид100) < 0.001, f"План «вата 100» {план100} != ТЧ×домов {ожид100}"
    assert abs(план50 - ожид50) < 0.001, f"План «вата 50» {план50} != ТЧ×домов {ожид50}"
    assert not ekoboard_под_50, f"Под «вата 50» остался план EKOBOARD: {ekoboard_под_50}"
    # Замер 04.09.2026: факт «вата 100» = 198 (EKOBOARD 100), «вата 50» = 54 (EKOBOARD 50). Закупки только растут.
    assert факт100 >= 198 and факт50 >= 54, f"Факт разошёлся с замером 04.09.2026: вата100={факт100} вата50={факт50}"

    print(f"OK: вата100 план={план100} факт={факт100}; вата50 план={план50} факт={факт50}")
    print("VATA CASE PASSED")


if __name__ == "__main__":
    main()
