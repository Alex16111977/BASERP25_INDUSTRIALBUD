import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
обр = buh.ВнешниеОбработки.Создать(EPF, False)
обр.Период = datetime.datetime(2026, 7, 7)
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000004").Ссылка
выб = buh.Справочники.Склады.Выбрать()
while выб.Следующий():
    н = выб.Наименование
    if "СТІЛ" in н and "МХП" in н and "ОР" in н and "виробнич" in н:
        обр.СкладыОстатков.Добавить().Склад = выб.Ссылка
обр.РассчитатьАнализ()

# --- 1) ЕдиницаСС у ТЧ заповнена на норм-картках ---
тч = обр.ТабличнаяЧастьОстатков
n_ess = 0
n_norm_ess = 0
приклад = ""
for i in range(тч.Количество()):
    с = тч.Получить(i)
    ess = (not с.ЕдиницаСС.Пустая())
    if ess:
        n_ess += 1
    # норм-картка = НормаНоменкл>0
    if float(с.НормаНоменкл) > 0:
        assert ess, f"норм-картка {с.Номенклатура.Наименование} без ЕдиницаСС"
        n_norm_ess += 1
        if not приклад:
            приклад = f"{с.Номенклатура.Наименование} -> {с.ЕдиницаСС.Наименование}"
assert n_norm_ess > 0, "не знайдено норм-карток (НормаНоменкл>0)"
print(f"ЕдиницаСС заповнена: рядків={n_ess}; норм-карток={n_norm_ess}; приклад: {приклад}")

# --- 2) рендер Аналіз СС: дві одиниці + порядок колонок + колір заголовка ---
табдок = обр.СформироватьПечатьАнализСС(тч)
h, w = табдок.ВысотаТаблицы, табдок.ШиринаТаблицы
print(f"ВысотаТаблицы={h} ШиринаТаблицы={w}")

# позиції заголовків (перша клітинка з точним текстом)
pos = {}
for r in range(1, h + 1):
    for c in range(1, w + 1):
        t = str(табдок.Область(r, c, r, c).Текст).strip()
        for hd in ("Залишок", "Одиниця виміру залишків", "Згідно з СС", "Одиниця виміру СС"):
            if t == hd and hd not in pos:
                pos[hd] = (r, c)
missing = [hd for hd in ("Залишок", "Одиниця виміру залишків", "Згідно з СС", "Одиниця виміру СС") if hd not in pos]
assert not missing, f"немає заголовків колонок: {missing} (pos={pos})"
print("Позиції заголовків (r,c):", pos)

# порядок: Залишок < Одиниця виміру залишків < Згідно СС < Одиниця виміру СС (у тій самій шапці)
c_zal = pos["Залишок"][1]
c_oz = pos["Одиниця виміру залишків"][1]
c_ss = pos["Згідно з СС"][1]
c_oss = pos["Одиниця виміру СС"][1]
assert c_zal < c_oz < c_ss < c_oss, (
    f"порядок колонок невірний: Залишок={c_zal}, Од.залишки={c_oz}, ЗгідноСС={c_ss}, Од.СС={c_oss}")
print(f"Порядок OK: Залишок({c_zal}) < Од.залишки({c_oz}) < ЗгідноСС({c_ss}) < Од.СС({c_oss})")

# --- 3) шапка-заголовок звіту НЕ янтарна (255,230,153) ---
AMBER = (255, 230, 153)
знайдено_заг = False
for r in range(1, min(8, h) + 1):
    for c in range(1, w + 1):
        обл = табдок.Область(r, c, r, c)
        if "Аналіз СС" in str(обл.Текст):
            цф = обл.ЦветФона
            rgb = (цф.R, цф.G, цф.B)
            знайдено_заг = True
            assert rgb != AMBER, f"заголовок звіту досі янтарний {rgb}"
            print(f"Заголовок ЦветФона={rgb} (не янтар) OK")
            break
    if знайдено_заг:
        break
assert знайдено_заг, "не знайдено клітинку заголовка звіту"

