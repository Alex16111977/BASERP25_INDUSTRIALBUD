# -*- coding: utf-8 -*-
"""Rule #-1: претест договорных фильтров взаиморасчётов (этап 2).
1. Запрос исключённых договоров ERP (обе галочки) + их А_ИдКод (для фильтрации Бух-стороны по ключу).
2. Фильтр в основном запросе остатков ERP: НЕ(галочка1 ИЛИ галочка2).
Только чтение."""
import sys
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# П.1: исключённые договоры + ключи
q = erp.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ
	Д.Ссылка КАК ДоговорСсылка,
	Д.Наименование КАК Имя,
	Д.А_ИдКод КАК ИдКод,
	Д.А_ЭтоДоговорФинАгента КАК ФинАгент,
	Д.А_ИсключитьиЗПроверкиСБухУчетом КАК ИсклБух
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	(Д.А_ЭтоДоговорФинАгента
		ИЛИ Д.А_ИсключитьиЗПроверкиСБухУчетом)
	И НЕ Д.ПометкаУдаления"""
r = q.Execute().Выгрузить()
n = r.Количество()
fin = sum(1 for i in range(n) if bool(r.Получить(i).ФинАгент))
excl = sum(1 for i in range(n) if bool(r.Получить(i).ИсклБух))
empty_id = sum(1 for i in range(n) if not str(r.Получить(i).ИдКод).strip())
print("П.1 Исключённых договоров: %d (ФинАгент=%d, ИсклБух=%d, без А_ИдКод=%d)" % (n, fin, excl, empty_id))
for i in range(min(n, 8)):
    row = r.Получить(i)
    print("   %-55s | ИдКод=%s | ФА=%s ИБ=%s"
          % (str(row.Имя)[:55], str(row.ИдКод)[:36], bool(row.ФинАгент), bool(row.ИсклБух)))

# П.2: фильтр в запросе остатков РСК (фрагмент как в плагине, с добавленным условием)
q2 = erp.NewObject("Запрос")
q2.Текст = """ВЫБРАТЬ ПЕРВЫЕ 5
	Т.АналитикаУчетаПоПартнерам.Контрагент КАК Контрагент,
	Т.АналитикаУчетаПоПартнерам.Договор КАК Договор,
	Т.СуммаОстаток КАК Остаток
ИЗ
	РегистрНакопления.РасчетыСКлиентами.Остатки(&Дата, ) КАК Т
ГДЕ
	НЕ (Т.АналитикаУчетаПоПартнерам.Договор.А_ЭтоДоговорФинАгента
		ИЛИ Т.АналитикаУчетаПоПартнерам.Договор.А_ИсключитьиЗПроверкиСБухУчетом)"""
q2.SetParameter("Дата", erp.NewObject("УникальныйИдентификатор") if False else None)
# дату передаём литералом через ДАТАВРЕМЯ во избежание TZ-граблей
q2.Текст = q2.Текст.replace("&Дата", "ДАТАВРЕМЯ(2026, 7, 19)")
r2 = q2.Execute().Выгрузить()
print("П.2 Фильтрованный запрос РСК.Остатки: OK, строк=%d" % r2.Количество())

print("PRETEST DOGOVOR FILTERS OK")
