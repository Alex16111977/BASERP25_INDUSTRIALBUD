"""Разведка-2: расширенный поиск ненайденных договоров (BuhBud, только чтение)."""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Д.Ссылка КАК С,
    Д.Наименование КАК Имя,
    Д.Номер КАК Ном,
    Д.Дата КАК Дат,
    ЕСТЬNULL(Д.Владелец.Наименование, "") КАК Влад,
    ЕСТЬNULL(Д.Подразделение.Наименование, "") КАК Подр,
    ЕСТЬNULL(Д.Направление.Наименование, "") КАК Напр,
    Д.ПометкаУдаления КАК ПУ
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ НЕ Д.ЭтоГруппа
  И (Д.Номер ПОДОБНО &Ш ИЛИ Д.Наименование ПОДОБНО &Ш)
УПОРЯДОЧИТЬ ПО Дат"""


def показать(шаблон, заголовок):
    print(f"\n--- {заголовок}: LIKE «{шаблон}» ---")
    q.УстановитьПараметр("Ш", шаблон)
    т = q.Execute().Выгрузить()
    if т.Количество() == 0:
        print("  НИЧЕГО")
        return
    for i in range(т.Количество()):
        s = т.Получить(i)
        uид = str(buh.String(s.С.УникальныйИдентификатор()))
        имя = " ".join(str(s.Имя).split())
        напр = str(s.Напр) if str(s.Напр).strip() else "<ПУСТО>"
        метка = " [ПОМЕЧЕН]" if s.ПУ else ""
        дата = str(buh.String(s.Дат))
        print(f"  {uид}{метка} | {имя}")
        print(f"      Ном={s.Ном} Дата={дата} Влад={s.Влад} Подр=[{s.Подр}] Напр={напр}")


# 1203/2026 — возможные написания
показать("%1203%", "1203 в любом виде")
# 20/01/25 — возможные написания
показать("%20/01%25%", "20/01...25")
показать("%20.01.25%", "20.01.25")
показать("%20/01/2025%", "20/01/2025")
# ПРООН / 10499944
показать("%10499944%", "10499944")
