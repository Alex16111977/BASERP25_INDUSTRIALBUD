# -*- coding: utf-8 -*-
"""Шаг 1 пре-тест (Rule #-1) — карта Статья→ТипПоказателя для
централизованного заполнения измерения ТипПоказателя в А_ОтчетБаланс_Свод.
Формула штатного Отчет.УправленческийБаланс (SKD ОборотныеСредства b2):
  ВЫБОР КОГДА ДанныеСтатьи.АктивПассив =
      ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.АктивПассив)
    ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Пассив)
    ИНАЧЕ ДанныеСтатьи.АктивПассив КОНЕЦ
(АктивПассив→Пассив, иначе как есть; «Налоги»→Пассив).

Период СЕРВЕРНО (НАЧАЛОПЕРИОДА/КОНЕЦПЕРИОДА).

Asserts:
 - карта строится без ошибок; ключевые статьи классифицированы верно
   (Налоги/Оплата труда/Прибыли и убытки/Полученные авансы/
   Задолженность перед поставщиками→Пассив; Основные средства/
   Денежные средства*/Задолженность клиентов/Выданные авансы/
   Товары на оптовых складах→Актив);
 - на ПАП.ОстаткиИОбороты(OD-3) дек2025+янв2026/ТОВ, разрез по
   ТипПоказателя через эту карту: Σ(Актив)+Σ(Пассив)=0 (баланс),
   |Σ Актив| == штатный Отчет.УправленческийБаланс
   (дек2025 278 093 267,32 / янв2026 288 787 750,11).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
TOL = 0.01
ЭТ_АКТИВ = {"декабрь2025": 278_093_267.32, "январь2026": 288_787_750.11}
ПЕРИОДЫ = [
    ("декабрь2025", datetime(2025, 12, 1, 12, 0, 0)),
    ("январь2026",  datetime(2026, 1, 1, 12, 0, 0)),
]
# «Собственные средства»/«Доходы/Расходы текущего периода» — OD-3-
# исключены, НЕ в регистре, АктивПассив в карточке пуст → не проверяем.
ОЖИД_ПАССИВ = ("Налоги", "Оплата труда", "Прибыли и убытки",
               "Полученные авансы", "Задолженность перед поставщиками")
ОЖИД_АКТИВ = ("Основные средства", "Денежные средства (безналичные)",
              "Денежные средства (наличные)", "Задолженность клиентов",
              "Выданные авансы", "Товары на оптовых складах")
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С

qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка КАК Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for n in ("Собственные средства", "Доходы текущего периода",
          "Расходы текущего периода"):
    имена.Добавить(n)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
Искл = conn.NewObject("Массив")
for i in range(tI.Количество()):
    Искл.Добавить(tI.Получить(i).Ссылка)

# карта ВидыСтатейУправленческогоБаланса XMLСтрока->имя
qVS = conn.NewObject("Запрос")
qVS.Текст = ("ВЫБРАТЬ Ссылка КАК С, ПРЕДСТАВЛЕНИЕ(Ссылка) КАК П "
             "ИЗ Перечисление.ВидыСтатейУправленческогоБаланса")
tVS = qVS.Выполнить().Выгрузить()
картаВС = {}
for i in range(tVS.Количество()):
    картаВС[conn.XMLСтрока(tVS.Получить(i).С)] = str(tVS.Получить(i).П).strip()

# === КАРТА Статья→ТипПоказателя 1:1 как пойдёт в BSL оркестратор ===
qK = conn.NewObject("Запрос")
qK.Текст = """ВЫБРАТЬ
    СА.Ссылка КАК С,
    ПРЕДСТАВЛЕНИЕ(СА.Ссылка) КАК СтП,
    ВЫБОР КОГДА СА.АктивПассив =
            ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.АктивПассив)
        ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Пассив)
        ИНАЧЕ СА.АктивПассив КОНЕЦ КАК ТП
ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК СА"""
tK = qK.Выполнить().Выгрузить()
КартаТП = {}            # XMLСтрока(статья) -> ссылка ТП
КартаТП_имя = {}        # имя статьи -> имя ТП
for i in range(tK.Количество()):
    r = tK.Получить(i)
    тпX = conn.XMLСтрока(r.ТП) if conn.ЗначениеЗаполнено(r.ТП) else None
    КартаТП[conn.XMLСтрока(r.С)] = тпX
    КартаТП_имя[str(r.СтП)] = картаВС.get(тпX, "∅") if тпX else "∅"

print(f"карта Статья→ТипПоказателя: статей={tK.Количество()}")
плохо_класс = []
for наим in ОЖИД_ПАССИВ:
    тп = КартаТП_имя.get(наим, "?")
    print(f"  «{наим[:34]:34}» → {тп}  (ожид Пассив)")
    if тп != "Пассив":
        плохо_класс.append(f"{наим}→{тп}≠Пассив")
for наим in ОЖИД_АКТИВ:
    тп = КартаТП_имя.get(наим, "?")
    print(f"  «{наим[:34]:34}» → {тп}  (ожид Актив)")
    if тп != "Актив":
        плохо_класс.append(f"{наим}→{тп}≠Актив")


def границы(мид):
    qg = conn.NewObject("Запрос")
    qg.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
                "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
    qg.УстановитьПараметр("М", мид)
    rg = qg.Выполнить().Выбрать(); rg.Следующий()
    return rg.НМ, rg.КД


провал = 0
for имя, мид in ПЕРИОДЫ:
    НМ, КД = границы(мид)
    # ПАП.ОстаткиИОбороты(OD-3) по Статья → разрез через КартаТП
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НМ", НМ)
    q.УстановитьПараметр("КД", КД); q.УстановитьПараметр("Искл", Искл)
    q.Текст = """ВЫБРАТЬ Б.Статья КАК Ст, СУММА(Б.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&НМ, &КД, Авто, ,
        Организация = &Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
    СГРУППИРОВАТЬ ПО Б.Статья"""
    t = q.Выполнить().Выгрузить()
    sА = sП = sПусто = 0.0
    for i in range(t.Количество()):
        r = t.Получить(i)
        ко = float(r.КО or 0)
        тпX = КартаТП.get(conn.XMLСтрока(r.Ст))
        тпИмя = картаВС.get(тпX, "∅") if тпX else "∅"
        if тпИмя == "Актив":
            sА += ко
        elif тпИмя == "Пассив":
            sП += ко
        else:
            sПусто += ко
    нетто = sА + sП + sПусто
    эА = ЭТ_АКТИВ[имя]
    print(f"\n[{имя}] {НМ}..{КД}")
    print(f"  Σ Актив={sА:,.2f}  Σ Пассив={sП:,.2f}  безТипа={sПусто:,.2f}  "
          f"НЕТТО={нетто:,.2f} (ожид 0)")
    print(f"  |Σ Актив|={abs(sА):,.2f}  эталон Отчет.УпрБаланс={эА:,.2f}")
    ok = True
    if abs(нетто) > TOL:
        print(f"  [FAIL] НЕТТО {нетто:,.2f} != 0 (классификация неверна)"); ok = False
    if abs(sПусто) > TOL:
        print(f"  [FAIL] есть статьи без ТипПоказателя на {sПусто:,.2f}"); ok = False
    if abs(abs(sА) - эА) > TOL:
        print(f"  [FAIL] |Актив| {abs(sА):,.2f} != отчёт {эА:,.2f}"); ok = False
    if ok:
        print(f"  [OK] {имя}: Актив=|Пассив|=={эА:,.2f}, баланс сходится")
    else:
        провал += 1

print("=" * 64)
assert not плохо_класс, f"FAIL классификация: {плохо_класс}"
assert провал == 0, f"FAIL: провалов = {провал}"
print("PASS Шаг 1: карта Статья→ТипПоказателя (формула УпрБаланс) валидна; "
      "«Налоги»/«Оплата труда»/«Прибыли и убытки»→Пассив, активы→Актив; "
      "Σ Актив=|Σ Пассив| (баланс=0) дек2025/янв2026, |Актив|==штатный "
      "Отчет.УправленческийБаланс (278 093 267,32 / 288 787 750,11)")
