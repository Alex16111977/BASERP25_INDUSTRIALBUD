def час(x):
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def проц(x, знаков=1):
    """Процент по-украински: десятичная запятая и неразрывный пробел перед знаком."""
    return f"{x:.{знаков}f}".replace(".", ",") + " %"


ИМЕНА = {"мшп": "МШП", "генератор": "Генератор", "лист пвл": "Лист ПВЛ"}


def имя_позиции(имя):
    """Отчёт отдаёт названия как заведены в карточках — приводим к виду письма."""
    ключ = " ".join(имя.split()).lower()
    if ключ in ИМЕНА:
        return ИМЕНА[ключ]
    return имя[0].upper() + имя[1:] if имя and имя[0].islower() else имя


def знак(x, форматтер=Д):
    return ("+" if x > 0 else "−") + форматтер(abs(x))


def класс(x, лучше_меньше=True):
    хорошо = (x < 0) if лучше_меньше else (x > 0)
    return "good" if хорошо else "bad"


def дата_из(имя):
    m = re.search(r"(\d{2})-(\d{2})-(\d{4})", имя)
    return f"{m.group(1)}.{m.group(2)}.{m.group(3)}" if m else "?"


def прошлая_папка(папка, текущая_дата=None):
    """Ближайшая папка с ПОЛНЫМ комплектом прошлой недели.

    ⚠ Соседняя папка по имени не годится: рядом лежат сборные каталоги (14082026 несёт
    план-факт на 14.08 и звіт на 12.08 — разные даты, это материалы другого доклада).
    Берём только те, где обе выгрузки одной даты и дата раньше текущей.
    """
    родитель, имя = os.path.dirname(папка), os.path.basename(папка)
    ключ = lambda д: re.sub(r"\D", "", д)[:8]
    порядок = lambda д: (ключ(д)[4:8], ключ(д)[2:4], ключ(д)[0:2])
    кандидаты = sorted([д for д in os.listdir(родитель)
                        if os.path.isdir(os.path.join(родитель, д)) and re.match(r"^\d{8}", д)
                        and порядок(д) < порядок(имя)], key=порядок, reverse=True)
    for д in кандидаты:
        путь = os.path.join(родитель, д)
        пф = pfa.найти_файл(путь, "План факт на") or pfa.найти_файл(путь, "План-факт")
        роб = pfa.найти_файл(путь, "Звіт з виконання СС")
        if пф and роб and дата_из(os.path.basename(пф)) == дата_из(os.path.basename(роб)):
            if текущая_дата is None or дата_из(os.path.basename(пф)) != текущая_дата:
                return путь
    return None


def собрать(папка, база=None):
    прошлая = база or прошлая_папка(папка)
    ф_детально = pfa.найти_файл(папка, "План на факт за матеріалами детально")
    ф_планфакт = pfa.найти_файл(папка, "План факт на") or pfa.найти_файл(папка, "План-факт")
    ф_роботи = pfa.найти_файл(папка, "Звіт з виконання СС")
    п_планфакт = (pfa.найти_файл(прошлая, "План факт на")
                  or pfa.найти_файл(прошлая, "План-факт")) if прошлая else None
    п_роботи = pfa.найти_файл(прошлая, "Звіт з виконання СС") if прошлая else None

    итог, позиции = pfa.читать_детальный(ф_детально)
    строки = pfa.факторы(позиции)
    шапка = pfa.читать_шапку(ф_планфакт, "планфакт")
    работы = pfa.читать_шапку(ф_роботи, "роботи")
    шапка_п = pfa.читать_шапку(п_планфакт, "планфакт")
    работы_п = pfa.читать_шапку(п_роботи, "роботи")

    поз_нов = pfa.позиции_планфакт(ф_планфакт)
    поз_стар = pfa.позиции_планфакт(п_планфакт)
    безымянная = next((с for с in строки if с["имя"].startswith("«без")), None)

    дельты = []
    for имя in set(поз_нов) | set(поз_стар):
        н = поз_нов.get(имя, {"План": 0.0, "ПНФ": 0.0})
        с = поз_стар.get(имя, {"План": 0.0, "ПНФ": 0.0})
        if abs(н["ПНФ"] - с["ПНФ"]) > 0.005:
            дельты.append(dict(имя=имя, дельта=н["ПНФ"] - с["ПНФ"], было=с["ПНФ"],
                               стало=н["ПНФ"], план=н["План"]))
    if безымянная and безымянная["Факт"] > 0.005:
        дельты.append(dict(имя="Матеріали без загальної назви", дельта=безымянная["Факт"],
                           было=0.0, стало=безымянная["Факт"], план=0.0))
    дельты.sort(key=lambda д: -abs(д["дельта"]))

    этапы_н, этапы_с = pfa.этапы(ф_роботи), pfa.этапы(п_роботи)

    return dict(итог=итог, строки=строки, шапка=шапка, работы=работы, шапка_п=шапка_п,
                работы_п=работы_п, дельты=дельты, этапы_н=этапы_н, этапы_с=этапы_с,
                дата=дата_из(os.path.basename(ф_детально)),
                дата_п=дата_из(os.path.basename(п_планфакт)),
                файлы=[os.path.basename(ф_планфакт), os.path.basename(ф_роботи),
                       os.path.basename(ф_детально)])


def строка_топ(с, поле):
    """Строка ТОП-таблицы. Два процента рядом: деньги (прогноз к смете) и ОБЪЁМ —
    сколько количества уже закуплено. Экономия по позиции, закупленной наполовину,
    ещё не окончательная: остаток возьмут по текущим ценам."""
    сумма = abs(с[поле] if поле != "Отклонение" else с["Отклонение"])
    доля_грн = (с["ПНФ"] / с["План"] * 100) if с["План"] else None
    доля_кол = (с["ФактКол"] / с["ПланКол"] * 100) if с["ПланКол"] else None
    return (f'<tr><td>{имя_позиции(с["имя"])}</td>'
            f'<td class="num">{Д(с["План"]) if с["План"] else "—"}</td>'
            f'<td class="num">{Д(с["ПНФ"])}</td>'
            f'<td class="num">{Д(сумма)}</td>'
            f'<td class="num">{проц(доля_грн) if доля_грн is not None else "—"}</td>'
            f'<td class="num">{проц(доля_кол, 0) if доля_кол is not None else "—"}</td>'
            f'<td>{с["Тип"]}</td></tr>')


ПОРІГ_ЧАСТКИ = 3.0   # % від суми — нижче цього позиція 8..10 у таблицю не йде


def топ_позицій(позиции, сума, ключ):
    """Первые 7 позиций всегда, места 8–10 — если каждая даёт не меньше ПОРІГ_ЧАСТКИ.

    Расширять таблицу механически до 10 нельзя: в иные недели восьмая позиция весит
    процент-полтора и только удлиняет письмо. На 19.08 места 8–10 дают по 3,2–4,8 %,
    одиннадцатая — уже 2,1 %, поэтому таблицы выходят ровно на 10 строк.
    """
    отобранные = list(позиции[:7])
    for с in позиции[7:10]:
        if сума and abs(ключ(с)) / сума * 100 >= ПОРІГ_ЧАСТКИ:
            отобранные.append(с)
        else:
            break
    return отобранные


def фраза_обсягів(позиции, перевитрата=False):
    """Одно предложение под ТОП-таблицей: где объём ещё не выбран, где уже перебран."""
    закуплено = lambda с: (с["ФактКол"] / с["ПланКол"] * 100) if с["ПланКол"] else None
    неповні = sorted([(с, закуплено(с)) for с in позиции
                      if закуплено(с) is not None and закуплено(с) < 80], key=lambda п: п[1])
    перебрані = sorted([(с, закуплено(с)) for с in позиции
                        if закуплено(с) is not None and закуплено(с) > 105],
                       key=lambda п: -п[1])
    список = lambda пары: ", ".join(f"{имя_позиции(с['имя'])} — {проц(з, 0)}" for с, з in пары[:3])

    if перевитрата:
        части = []
        if перебрані:
            части.append(f"обсяг уже перебрано ({список(перебрані)} кошторисної кількості), "
                         f"тому перевитрата за цими позиціями остаточна")
        if неповні:
            части.append(f"за позиціями {список(неповні)} решту обсягу ще докуплять — "
                         f"перевитрата зросте")
        return ("Колонка «закуплено»: " + "; ".join(части) + ".") if части else ""

    if неповні:
        return (f"Обсяг вибрано не повністю ({список(неповні)}) — там економія попередня, "
                f"решту куплять за поточними цінами; де закуплено 100 % і більше, "
                f"економія вже остаточна.")
    return "Обсяг за всіма позиціями вибрано повністю — економія остаточна."


