# Task 2: прототип логики резолва партнёра по контрагенту (read-only, без создания)
import sys
sys.path.insert(0, r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test')
import _common_neizv as c

erp = c.connect()
P = c.neizv(erp)


def is_real(p):
    return erp.ЗначениеЗаполнено(p) and not c.same(erp, p, P) and not p.ПометкаУдаления


def resolve_readonly(k):
    # 1. головной контрагент
    gk = k.ГоловнойКонтрагент
    if erp.ЗначениеЗаполнено(gk) and is_real(gk.Партнер):
        return ("головной", gk.Партнер.Наименование)
    # 2. тёзка по наименованию
    tz = erp.Справочники.Партнеры.НайтиПоНаименованию(k.Наименование, True)
    if is_real(tz):
        return ("тёзка", tz.Наименование)
    # 3. контрагент с тем же ЕДРПОУ/налоговым -> его реальный партнёр
    for fld in ("КодПоЕДРПОУ", "НалоговыйНомер"):
        val = getattr(k, fld)
        if val:
            q = erp.NewObject("Запрос")
            q.Text = (
                "ВЫБРАТЬ ПЕРВЫЕ 1 К.Партнер КАК Партнер ИЗ Справочник.Контрагенты КАК К "
                "ГДЕ К." + fld + " = &В И К.Партнер <> &P И НЕ К.Партнер.ПометкаУдаления И К.Ссылка <> &К"
            )
            q.УстановитьПараметр("В", val)
            q.УстановитьПараметр("P", P)
            q.УстановитьПараметр("К", k.Ссылка)
            s = q.Execute().Выбрать()
            if s.Следующий() and erp.ЗначениеЗаполнено(s.Партнер):
                return ("едрпоу:" + fld, s.Партнер.Наименование)
    # 4. создать зеркального
    return ("создать", k.Наименование)


q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ Ссылка ИЗ Справочник.Контрагенты ГДЕ Партнер = &P"
q.УстановитьПараметр("P", P)
s = q.Execute().Выбрать()
res = {}
n = 0
while s.Следующий():
    n += 1
    how, who = resolve_readonly(s.Ссылка)
    res[how] = res.get(how, 0) + 1
    print(f"  {s.Ссылка.Наименование:55} -> [{how}] {who}")
print("ИТОГО по способам:", res)
assert n == 15, f"ожидалось 15 контрагентов, получено {n}"
print("OK: классификация 15 контрагентов")
