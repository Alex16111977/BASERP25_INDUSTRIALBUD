def run(text, params=None, label=""):
    global N, M
    N += 1
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    try:
        tz = q.Execute().Выгрузить()
    except Exception as e:
        M += 1
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"  FAIL [{label}]: {msg}")
        return None
    cols = [tz.Колонки.Получить(i).Имя for i in range(tz.Колонки.Количество())]
    rows = []
    for i in range(tz.Количество()):
        row = tz.Получить(i)
        d = {}
        for c in cols:
            val = getattr(row, c)
            if isinstance(val, (int, float, str, bool)) or val is None:
                d[c] = val
            elif hasattr(val, 'year'):
                d[c] = val.isoformat()
            else:
                d[c] = S(val)
        rows.append(d)
    print(f"  OK [{label}]: строк {len(rows)}")
    return rows


def ref_by_code(code):
    q = erp.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ П.Ссылка КАК Ссылка ИЗ Справочник.СтруктураПредприятия КАК П ГДЕ П.Код = &Код"
    q.SetParameter("Код", code)
    sel = q.Execute().Выбрать()
    sel.Следующий()
    return sel.Ссылка


