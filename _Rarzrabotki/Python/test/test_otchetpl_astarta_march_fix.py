# -*- coding: utf-8 -*-
"""Verify: после фикса формулы СуммаЕРП = только Приход.
Подразделение "Астарта. Тищенки", март 2026, группа "Себестоимость".
Ожидается Σ СуммаЕРП по подразделению ≈ 505 868,05 ₽ (из регистра только Приход).
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

НМ = datetime.datetime(2026,3,1)
КМ = datetime.datetime(2026,3,31,23,59,59)

отчёт = conn.Отчеты.А_ОтчетPL.Создать()
тз = отчёт.ПолучитьОбъединенныеДанные(НМ, КМ, False, True, True, True)
print(f"=== Март 2026 (после фикса) Всего строк: {тз.Количество()} ===\n")

# Σ для Астарта.Тищенки по СуммаЕРП (без двойного счёта по аналитике)
σ_астарта = 0.0
для_астарта = 0
по_статьям = {}
for r in тз:
    if r.Подразделение and r.Подразделение.Наименование == "Астарта. Тищенки":
        # Только расходные регистраторы (не доходы, не Каса, не PL-строки)
        if r.Документ and conn.ЗначениеЗаполнено(r.Документ):
            тип = r.Документ.Метаданные().Имя
            расх = {"ПриобретениеТоваровУслуг","РасходныйКассовыйОрдер","СписаниеБезналичныхДенежныхСредств",
                    "АктВыполненныхРабот","ВозвратТоваровПоставщику","ПриходныйКассовыйОрдер",
                    "ПоступлениеБезналичныхДенежныхСредств","ВозвратТоваровОтКлиента",
                    "АвансовыйОтчет","ОтражениеЗарплатыВФинансовомУчете",
                    "СписаниеНедостачТоваров","ВнутреннееПотреблениеТоваров","РасчетКурсовыхРазниц",
                    "ОприходованиеИзлишковТоваров","РаспределениеПрочихЗатрат"}
            if тип in расх:
                σ_астарта += float(r.СуммаЕРП)
                для_астарта += 1
                ст = r.СтатьяPL.Наименование if r.СтатьяPL and conn.ЗначениеЗаполнено(r.СтатьяPL) else "(без PL)"
                по_статьям[ст] = по_статьям.get(ст, 0.0) + float(r.СуммаЕРП)

print(f"Астарта.Тищенки расходные строк: {для_астарта}")
print(f"Σ СуммаЕРП: {σ_астарта:.2f} (ожидается ~505 868,05 + ОЗП/ПТУ-расходы)\n")
print("По статьям PL (топ-15):")
for ст, сумма in sorted(по_статьям.items(), key=lambda x: -x[1])[:15]:
    print(f"  {ст:<40} {сумма:>15.2f}")

# Контроль из регистра напрямую (только Приход)
q = conn.NewObject("Запрос")
q.УстановитьПараметр("НМ", НМ)
q.УстановитьПараметр("КМ", КМ)
q.Текст = """
ВЫБРАТЬ СУММА(Р.Сумма) КАК Σ
ИЗ РегистрНакопления.ПрочиеРасходы КАК Р
ГДЕ Р.Период МЕЖДУ &НМ И &КМ
    И Р.Подразделение.Наименование = "Астарта. Тищенки"
    И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
"""
r = q.Выполнить().Выгрузить()
σ_регистр = float(r[0].Σ)
print(f"\nΣ из регистра ПрочиеРасходы (только Приход, Астарта.Тищенки): {σ_регистр:.2f}")
print(f"Δ в отчёте vs регистр (без CoGS): {σ_астарта - σ_регистр:.4f}")
