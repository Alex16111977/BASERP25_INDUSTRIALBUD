# -*- coding: utf-8 -*-
# Тест Find-Or-Create: СоздатьДокументНачисления() для А_ОтражениеЗПпоКазне
#
# ПЕРЕДУМОВА: оновлений ObjectModule.bsl завантажений у конфігурацію (F7).
# Документ А_ОтражениеЗПпоКазне 000000001 ПРОВЕДЕНИЙ з заповненими ТЧ.
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


def parse_num(s):
    return float(S(s).replace('\xa0', '').replace(' ', '').replace(',', '.') or "0")


# Знайти документ
q = erp.NewObject("Запрос")
q.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка, Д.Проведен "
    "ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д "
    "ГДЕ Д.Номер = &Н И Д.Дата МЕЖДУ &Д1 И &Д2"
)
q.SetParameter("Н", "000000001")
q.SetParameter("Д1", com_date(2025, 12, 31, 0, 0, 0))
q.SetParameter("Д2", com_date(2025, 12, 31, 23, 59, 59))
sel = q.Execute().Выбрать()
if not sel.Следующий():
    print("ПОМИЛКА: документ не знайдено")
    sys.exit(1)

doc_ref = sel.Ссылка
proveden = S(sel.Проведен)
print(f"Документ: {S(doc_ref)}, Проведен={proveden}")

obj = doc_ref.ПолучитьОбъект()

# Виклик 1: створити/оновити
print("\n>>> Виклик 1: СоздатьДокументНачисления() ...")
try:
    obj.СоздатьДокументНачисления()
    print(">>> OK")
except Exception as e:
    print(f">>> ПОМИЛКА: {e}")
    sys.exit(1)

# Перевірити що НачислениеЗарплаты створено
q2 = erp.NewObject("Запрос")
q2.Text = (
    "ВЫБРАТЬ НЗ.Ссылка, НЗ.Проведен, НЗ.Дата, НЗ.МесяцНачисления "
    "ИЗ Документ.НачислениеЗарплаты КАК НЗ "
    "ГДЕ НЗ.А_ДокОтражениеЗПпоКазне = &Осн И НЕ НЗ.ПометкаУдаления"
)
q2.SetParameter("Осн", doc_ref)
r2 = q2.Execute().Выгрузить()
print(f"\nЗнайдено НачислениеЗарплаты: {r2.Количество()}")
if r2.Количество() == 0:
    print("FAIL: жодного НачислениеЗарплаты не створено")
    sys.exit(1)

нз_row = r2.Получить(0)
нз_ref = нз_row.Ссылка
print(f"  {S(нз_ref)}  Проведен={S(нз_row.Проведен)}  Дата={S(нз_row.Дата)}  МесяцНач={S(нз_row.МесяцНачисления)}")

нз_uuid_1 = S(нз_ref.УникальныйИдентификатор())

# Кількість рядків у кожній ТЧ
нз_obj = нз_ref.ПолучитьОбъект()
nach = нз_obj.Начисления.Количество()
ud = нз_obj.Удержания.Количество()
ndfl = нз_obj.НДФЛ.Количество()
vf = нз_obj.ВзносыФОТ.Количество()
fl = нз_obj.ФизическиеЛица.Количество()
print(f"\n=== ТЧ НачислениеЗарплаты (виклик 1) ===")
print(f"  Начисления:     {nach}")
print(f"  Удержания:      {ud}")
print(f"  НДФЛ:           {ndfl}")
print(f"  ВзносыФОТ:      {vf}")
print(f"  ФизическиеЛица: {fl}")

# Виклик 2: повторний — має оновити ТОЙ САМИЙ документ (Find-Or-Create)
print("\n>>> Виклик 2 (повторний — має знайти існуючий): СоздатьДокументНачисления() ...")
try:
    obj.СоздатьДокументНачисления()
    print(">>> OK")
except Exception as e:
    print(f">>> ПОМИЛКА: {e}")

# Перевірити що той самий документ
r3 = q2.Execute().Выгрузить()
print(f"\nЗнайдено НачислениеЗарплаты після виклику 2: {r3.Количество()}")
if r3.Количество() != 1:
    print(f"FAIL: очікувався 1, отримано {r3.Количество()} (дубль!)")
    sys.exit(1)

нз_ref_2 = r3.Получить(0).Ссылка
нз_uuid_2 = S(нз_ref_2.УникальныйИдентификатор())
print(f"  UUID виклику 1: {нз_uuid_1}")
print(f"  UUID виклику 2: {нз_uuid_2}")

# Зразки рядків Начисления
print(f"\n=== Перші 5 рядків Начисления ===")
for i in range(min(5, nach)):
    r = нз_obj.Начисления.Получить(i)
    print(f"  [{i+1}] {S(r.Сотрудник)[:30]:30s}  {S(r.Начисление)[:25]:25s}  Рез={parse_num(r.Результат):>10.2f}")

print(f"\n=== Перші 5 рядків Удержания ===")
for i in range(min(5, ud)):
    r = нз_obj.Удержания.Получить(i)
    print(f"  [{i+1}] {S(r.ФизическоеЛицо)[:30]:30s}  {S(r.Удержание)[:20]:20s}  Рез={parse_num(r.Результат):>10.2f}  Получ={S(r.Получатель)[:25]}")

print(f"\n=== Перші 5 рядків НДФЛ ===")
for i in range(min(5, ndfl)):
    r = нз_obj.НДФЛ.Получить(i)
    print(f"  [{i+1}] {S(r.ФизическоеЛицо)[:30]:30s}  Налог={parse_num(r.Налог):>10.2f}")

print(f"\n=== Перші 5 рядків ВзносыФОТ ===")
for i in range(min(5, vf)):
    r = нз_obj.ВзносыФОТ.Получить(i)
    print(f"  [{i+1}] {S(r.ФизическоеЛицо)[:30]:30s}  {S(r.Налог)[:15]:15s}  Рез={parse_num(r.Результат):>10.2f}")

# Перевірки
print("\n=== ПЕРЕВІРКИ ===")
checks = [
    (r2.Количество() == 1, "Створено рівно 1 НачислениеЗарплаты"),
    (r3.Количество() == 1, "Повторний виклик НЕ створює дубль"),
    (нз_uuid_1 == нз_uuid_2, "UUID збігається між викликами (Find-Or-Create)"),
    (nach > 0, "ТЧ Начисления не пуста"),
    (ud >= 0, "ТЧ Удержания існує"),
    (ndfl >= 0, "ТЧ НДФЛ існує (порожня — як у еталоні 28.02.2026)"),
    (vf >= 0, "ТЧ ВзносыФОТ існує (порожня — як у еталоні)"),
    (fl > 0, "ТЧ ФизическиеЛица не пуста"),
    (S(нз_row.Проведен) == "Да", "Документ ПРОВЕДЕНО"),
]
all_ok = True
for ok, desc in checks:
    mark = "OK" if ok else "FAIL"
    print(f"  [{mark}] {desc}")
    if not ok:
        all_ok = False

print()
if all_ok:
    print("==> ЧАСТИНА C (СоздатьДокументНачисления Find-Or-Create) ПРОЙДЕНА")
    sys.exit(0)
else:
    print("==> ПОМИЛКИ")
    sys.exit(1)
