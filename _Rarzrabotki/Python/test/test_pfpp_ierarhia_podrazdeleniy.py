# -*- coding: utf-8 -*-
# Тест ПФПП: иерархия подразделений + измерение «Підрозділ-виконавець» (2026-07-16).
# Data-независимые инварианты (живые данные, жёстких чисел нет):
#   1. ФактЧасы блока «1. Праця» == СУММА(А_ДанныеТабелирования.ЧасыФакт) В ИЕРАРХИИ подразделения СС;
#   2. ФактГрн «1. Праця» == СУММА(А_ВзаиморасчетыССотрудниками, ОЗФУ/Приход) В ИЕРАРХИИ;
#   3. ВиконанняЧасы == СУММА(А_ВыполнениеРаботМодулей.ЧасыВыполнение) по СС;
#   4. ПодразделениеИсполнитель непустой <=> строка факта «1. Праця» (табель/ЗП/EV);
#      на таких строках Подразделение == подразделение СС (родитель);
#   5. поле доступно в настройках (отбор); композиция дефолт H>0.
# Путь .erf: env PFPP_ERF или продакшн _Rarzrabotki\Отчеты.
# Подключение: env PFPP_CONN или локальный реестр .v8-project.json (id="erp") — без кредов в коде.
import win32com.client, sys, os, json

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = os.environ.get("PFPP_ERF") or r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ПланФактныйПроизводствоПолный.erf"
assert os.path.exists(ERF), f"нет .erf: {ERF}"

def conn_string():
    s = os.environ.get("PFPP_CONN")
    if s:
        return s
    reg = r"C:\Configuration_downloads\BASERP25\.v8-project.json"
    with open(reg, encoding="utf-8") as fp:
        for db in json.load(fp)["databases"]:
            if db.get("id") == "erp":
                return f'Srvr="{db["server"]}";Ref="{db["ref"]}";Usr="{db["user"]}";Pwd="{db["password"]}"'
    raise RuntimeError("нет PFPP_CONN и записи id='erp' в .v8-project.json")

def f(x):
    return float(x) if x is not None else 0.0

def пусто(ref):
    return ref is None or (hasattr(ref, 'Пустая') and ref.Пустая())

erp = win32com.client.Dispatch("V83.COMConnector").Connect(conn_string())
S = erp.String
отчет = erp.ВнешниеОтчеты.Создать(ERF)

def регистр(текст, подр=None, сс=None):
    q = erp.NewObject("Запрос")
    q.Text = текст
    if подр is not None:
        q.SetParameter("Подр", подр)
    if сс is not None:
        q.SetParameter("СС", сс)
    t = q.Execute().Выгрузить()
    return f(t.Получить(0).Ч) if t.Количество() else 0.0

СС_ИМЕНА = [
    "МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ",
    "МД Вооз ЕМS Мала 2026 / Цех_МД Вооз ЕМS Мала 2026",
    "МД IRS 2026 15 м (МД IRS 2026) / ІБ _МД IRS 2026",
    "МД IRS 2026 30 м (МД IRS 2026)",
]

fails = []
for имя in СС_ИМЕНА:
    сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(имя)
    assert not пусто(сс), f"СС не найдена: {имя}"
    подр = сс.Подразделение
    имя_подр = str(S(подр))
    тз = отчет.ПолучитьДанные(erp.NewObject("СтандартныйПериод"), сс.Ссылка)

    cols = [c.Имя for c in тз.Колонки]
    assert "ПодразделениеИсполнитель" in cols, "нет колонки ПодразделениеИсполнитель"

    факт_ч = зп_грн = ев_ч = 0.0
    ok = True
    for i in range(тз.Количество()):
        r = тз.Получить(i)
        исп = r.ПодразделениеИсполнитель
        if r.Блок == "1. Праця":
            факт_ч += f(r.ФактЧасы)
            ев_ч += f(r.ВиконанняЧасы)
            if f(r.ПланГрн) == 0:
                зп_грн += f(r.ФактГрн)
        # инварианты нового измерения
        if not пусто(исп):
            if r.Блок != "1. Праця":
                ok = False; print(f"  !! исполнитель у блока {r.Блок}")
            if str(S(r.Подразделение)) != имя_подр:
                ok = False; print("  !! Подразделение != подразделение СС на строке факта")
            # строки табеля с 0 часов (сотрудник в табеле без часов) легитимны —
            # исполнитель на них заполнен, нулевой факт НЕ ошибка
        else:
            if f(r.ФактЧасы) != 0 or f(r.ВиконанняЧасы) != 0:
                ok = False; print("  !! факт-часы/EV без исполнителя")

    # контрольные суммы по регистрам (та же семантика периодов: весь срок)
    рег_табель = регистр(
        "ВЫБРАТЬ СУММА(Т.ЧасыФакт) КАК Ч ИЗ РегистрНакопления.А_ДанныеТабелирования КАК Т "
        "ГДЕ Т.Подразделение В ИЕРАРХИИ (&Подр)", подр=подр)
    рег_зп = регистр(
        "ВЫБРАТЬ СУММА(ВЗ.СуммаВзаиморасчетов) КАК Ч ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВЗ "
        "ГДЕ ВЗ.Подразделение В ИЕРАРХИИ (&Подр) "
        "И ВЗ.Регистратор ССЫЛКА Документ.ОтражениеЗарплатыВФинансовомУчете "
        "И ВЗ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)", подр=подр)
    рег_ев = регистр(
        "ВЫБРАТЬ СУММА(ВРМ.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК ВРМ "
        "ГДЕ ВРМ.СтруктураСебестоимости = &СС", сс=сс.Ссылка)

    d1, d2, d3 = факт_ч - рег_табель, зп_грн - рег_зп, ев_ч - рег_ев
    print(f"{имя[:40]}: ФактЧ={факт_ч:.2f}(рег {рег_табель:.2f}) ЗП={зп_грн:.2f}(рег {рег_зп:.2f}) "
          f"EV={ев_ч:.2f}(рег {рег_ев:.2f}) инв={'OK' if ok else 'FAIL'}")
    if abs(d1) > 0.005 or abs(d2) > 0.005 or abs(d3) > 0.005 or not ok:
        fails.append(имя)

# поле в настройках
дп = отчет.КомпоновщикНастроек.Настройки.Отбор.ДоступныеПоляОтбора
if дп.НайтиПоле(erp.NewObject("ПолеКомпоновкиДанных", "ПодразделениеИсполнитель")) is None:
    print("!! поле недоступно в отборе"); fails.append("SETTINGS")

# композиция дефолт (последняя ТЗ)
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
наст = отчет.КомпоновщикНастроек.ПолучитьНастройки()
вн = erp.NewObject("Структура"); вн.Вставить("Детали", тз)
м = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст)
пр = erp.NewObject("ПроцессорКомпоновкиДанных"); пр.Инициализировать(м, вн)
д = erp.NewObject("ТабличныйДокумент")
в = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
в.УстановитьДокумент(д); в.Вывести(пр)
print(f"Композиция: H={д.ВысотаТаблицы} W={д.ШиринаТаблицы}")
if д.ВысотаТаблицы <= 0:
    fails.append("COMP")

print("\n" + ("PASS" if not fails else f"FAIL: {fails}"))
sys.exit(0 if not fails else 1)
