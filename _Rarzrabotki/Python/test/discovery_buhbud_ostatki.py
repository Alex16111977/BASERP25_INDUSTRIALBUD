"""Какие счета Хозрасчетного держат Номенклатуру и есть ли субконто Склад."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

q = buh.NewObject("Запрос")
q.Текст = '''
ВЫБРАТЬ
    ВС.Ссылка.Код КАК Код,
    ВС.Ссылка.Наименование КАК Счет,
    ВС.НомерСтроки КАК Поз,
    ВС.ВидСубконто.Наименование КАК ВидСубконто
ИЗ
    ПланСчетов.Хозрасчетный.ВидыСубконто КАК ВС
ГДЕ
    ВС.ВидСубконто.Наименование ПОДОБНО "%Склад%"
    ИЛИ ВС.ВидСубконто.Наименование ПОДОБНО "%Номенклат%"
УПОРЯДОЧИТЬ ПО Код, Поз
'''
try:
    t = q.Выполнить().Выгрузить()
    print(f"Счета с субконто Склад/Номенклатура ({t.Количество()} строк):")
    for i in range(t.Количество()):
        s = t.Получить(i)
        print(f"  {s.Код:>8} {s.Счет[:32]:32} #{s.Поз} -> {s.ВидСубконто}")
except Exception as e:
    info = getattr(e, 'excepinfo', None)
    print("FAIL subconto:", info[2] if info else e)

