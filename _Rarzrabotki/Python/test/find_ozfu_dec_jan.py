# -*- coding: utf-8 -*-
"""Поиск регистраторов Документ.ОтражениеЗарплатыВФинансовомУчете
за декабрь 2025 и январь 2026 с движениями ПАП(Статья=ОплатаТруда).
Выводит UUID каждого + ожидаемую Σ signed ПАП(ОТ) per документ.
Сохраняет в ozfu_candidates.json для последующего verify."""
import sys, io, json, os
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
r = q0.Выполнить().Выбрать(); r.Следующий(); ORG = r.С

qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

ПЕРИОДЫ = [
    ("декабрь2025", datetime(2025, 12, 15, 12, 0, 0)),  # midmonth + полдень — антирtz-сдвиг
    ("январь2026",  datetime(2026, 1, 15, 12, 0, 0)),
]

print("# Кандидаты для verify (UUID + Σ signed ПАП(ОТ))\n")
найдено = []
for name, мдата in ПЕРИОДЫ:
    qG = conn.NewObject("Запрос")
    qG.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
                "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
    qG.УстановитьПараметр("М", мдата)
    rG = qG.Выполнить().Выбрать(); rG.Следующий(); НМ, КД = rG.НМ, rG.КД

    qR = conn.NewObject("Запрос")
    qR.Текст = """
    ВЫБРАТЬ Т.Регистратор КАК Док,
        Т.Регистратор.Номер КАК Номер,
        Т.Регистратор.Дата КАК Дата,
        Т.Регистратор.ПериодРегистрации КАК ПериодРегистрации,
        СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                       ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК Σ_signed
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Организация=&Орг И Т.Период МЕЖДУ &НМ И &КД
        И Т.Источник=ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
        И Т.Статья=&ОТ
        И ТИПЗНАЧЕНИЯ(Т.Регистратор)=ТИП(Документ.ОтражениеЗарплатыВФинансовомУчете)
    СГРУППИРОВАТЬ ПО Т.Регистратор, Т.Регистратор.Номер, Т.Регистратор.Дата,
        Т.Регистратор.ПериодРегистрации
    УПОРЯДОЧИТЬ ПО Т.Регистратор.Дата
    """
    qR.УстановитьПараметр("Орг", ORG); qR.УстановитьПараметр("НМ", НМ)
    qR.УстановитьПараметр("КД", КД); qR.УстановитьПараметр("ОТ", ОТ)
    tR = qR.Выполнить().Выгрузить()
    print(f"## {name} (период {НМ.strftime('%Y-%m-%d')} … {КД.strftime('%Y-%m-%d')})")
    if tR.Количество() == 0:
        print(f"  ⚠️ Документов ОЗФУ за {name} не найдено\n")
    else:
        for i in range(tR.Количество()):
            e = tR.Получить(i)
            uuid = conn.XMLСтрока(e.Док)
            print(f"  - № {e.Номер} от {e.Дата} (ПериодРег {e.ПериодРегистрации}) "
                  f"Σ_signed={float(e.Σ_signed or 0):,.2f} UUID={uuid}")
            найдено.append({
                "period": name,
                "номер": str(e.Номер),
                "дата": e.Дата.isoformat() if hasattr(e.Дата, "isoformat") else str(e.Дата),
                "период_регистрации": (e.ПериодРегистрации.isoformat()
                                       if hasattr(e.ПериодРегистрации, "isoformat")
                                       else str(e.ПериодРегистрации)),
                "Σ_signed_expected": float(e.Σ_signed or 0),
                "uuid": uuid,
            })
        print()

out_path = os.path.join(os.path.dirname(__file__), "ozfu_candidates.json")
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(найдено, f, ensure_ascii=False, indent=2)
print(f"Сохранено {len(найдено)} кандидатов в {out_path}")
