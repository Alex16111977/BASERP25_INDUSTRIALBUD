# -*- coding: utf-8 -*-
"""TDD-тест: больничный «за счёт ФСС» должен давать А_ВзСС Форма1 Приход = NET (take-home),
а не GROSS. In-memory (obj.ЗаполнитьДляОтражения_...), БЕЗ записи и проведения.

Инвариант per ФЛ (Форма1):
  in-memory А_ВзСС Ф1 signed = Σ НачЗарплата(Налог пусто, кроме 4 ВидОп) − Σ НачисленныйНДФЛ − Σ Удержано
  должен равняться официальному take-home = (Σ НачисленияБух[661] + Σ НачисленияБухЗасчетФондов[663] − Σ НачисленныйНДФЛ_Ф1).

RED (текущий код): Григоренко 2 585,83 (GROSS) ≠ 1 991,09 (NET) — осиротевший gross-up «Удержание»
гасит НДФЛ, больничный GROSS не нетится. Хурсін/Ямковий — регресс-гарды (GROSSбух≥НДФЛ → уже NET).
GREEN (после фикса гарда `ГБ > 0`→`ГБ >= 0` в _ОтрЗП_ЗаполнитьБольничныеИзФондов step-4): все 3 PASS.

Эталон: А_ОтражениеЗПпоКазне №000000003 (Лютий 2026).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL = 0.01
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
def S(v): return conn.XMLСтрока(v)

Ф1 = S(conn.PredefinedValue("Перечисление.А_ФормыPL.Форма1"))
ИСКЛ = {S(conn.PredefinedValue("Перечисление.ВидыОперацийПоЗарплате." + n)) for n in (
    "ЕжегодныйОтпускОценочныеОбязательстваИРезервы", "НачисленоСдельноДоход",
    "КомпенсацияЕжегодногоОтпускаОценочныеОбязательства", "ЕжегодныйОтпускОценочныеОбязательства")}
ТЕСТ_ФЛ = ["Григоренко Олександр%", "Хурсін Тарас%", "Ямковий%"]

def фл_ref(шаблон):
    q = conn.NewObject("Запрос")
    q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 ССЫЛКА КАК Р, ПРЕДСТАВЛЕНИЕ(Ссылка) КАК Имя "
               "ИЗ Справочник.ФизическиеЛица ГДЕ Наименование ПОДОБНО &Ш")
    q.УстановитьПараметр("Ш", шаблон); r = q.Выполнить().Выбрать()
    return (r.Р, r.Имя) if r.Следующий() else (None, None)

# Эталонный документ
q = conn.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 ССЫЛКА КАК Р ИЗ Документ.А_ОтражениеЗПпоКазне "
           "ГДЕ Номер = &Н И Дата >= ДАТАВРЕМЯ(2026,2,1) И Дата < ДАТАВРЕМЯ(2026,3,1)")
q.УстановитьПараметр("Н", "000000003")
r = q.Выполнить().Выбрать()
if not r.Следующий():
    print("[FAIL] не найден А_ОтражениеЗПпоКазне №000000003 за лютий 2026"); sys.exit(1)
obj = r.Р.ПолучитьОбъект()
print(f"Документ: {obj.Номер} от {obj.Дата}")

# In-memory пересчёт ТЧ (БЕЗ записи!)
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()
print("ЗаполнитьДляОтражения_... выполнено in-memory (без записи)\n")

def сумма_тч(тч, имя_фл_кол, флxml, доп=None):
    итог = 0.0
    for i in range(тч.Количество()):
        стр = тч.Получить(i)
        if S(getattr(стр, имя_фл_кол)) != флxml:
            continue
        if доп is not None and not доп(стр):
            continue
        итог += float(стр.Сумма or 0)
    return итог

def налог_пусто_не_искл(стр):
    return (not conn.ЗначениеЗаполнено(стр.Налог)) and (S(стр.ВидОперации) not in ИСКЛ)

def только_ф1(стр):
    return S(стр.ФормаPL) == Ф1

def нз_ф1_доход(стр):
    return только_ф1(стр) and налог_пусто_не_искл(стр)

# Есть ли ТЧ УдержаннаяЗарплата у родителя
есть_удерж = False
try:
    _ = obj.УдержаннаяЗарплата.Количество(); есть_удерж = True
except Exception:
    есть_удерж = False

print(f"{'ФизЛицо':<34} {'А_ВзСС Ф1 (in-mem)':>18} {'take-home (NET)':>16} {'Δ':>9}  результат")
all_pass = True
for ш in ТЕСТ_ФЛ:
    фл, имя = фл_ref(ш)
    if фл is None:
        print(f"  {ш}: НЕ найден"); all_pass = False; continue
    флx = S(фл)
    доход = сумма_тч(obj.НачисленнаяЗарплатаИВзносыПоФизлицам, "ФизическоеЛицо", флx, нз_ф1_доход)
    ндфл  = сумма_тч(obj.НачисленныйНДФЛ, "ФизическоеЛицо", флx, только_ф1)
    удерж = сумма_тч(obj.УдержаннаяЗарплата, "ФизическоеЛицо", флx, только_ф1) if есть_удерж else 0.0
    взсс_ф1 = доход - ндфл - удерж

    gross661 = сумма_тч(obj.НачисленияБух, "ФизЛицо", флx)
    gross663 = сумма_тч(obj.НачисленияБухЗасчетФондов, "ФизЛицо", флx)
    takehome = gross661 + gross663 - ндфл

    дельта = взсс_ф1 - takehome
    ok = abs(дельта) <= TOL
    all_pass = all_pass and ok
    имяк = (имя or "")[:33]
    print(f"  {имяк:<34} {взсс_ф1:>18,.2f} {takehome:>16,.2f} {дельта:>9,.2f}  {'✅ PASS' if ok else '❌ FAIL'}")

print()
print("=" * 60)
print("[OK] ВСЕ PASS — больничный нетится" if all_pass else "[FAIL] есть фантом (больничный GROSS не нетится)")
sys.exit(0 if all_pass else 1)
