# -*- coding: utf-8 -*-
"""Заливка параметров договоров из ручного Excel в РегистрСведений.А_ПараметрыДоговоровФинотчета.

Адаптация doc_finrep_zalivka_dogovorov.py после переезда параметров в регистр (14.08.2026):
пишет СуммаСоглашения (кол. C), СуммаДЦ (кол. D) и ОбъектПримечание (кол. B) по совпадению
договоров. Процент удержания и вариант формулы ставятся ТОЛЬКО там, где выведены арифметикой
из Excel — гадать нельзя. Пустое в Excel НЕ затирает заполненное в регистре.

Три вещи, из-за которых нельзя лить «в лоб»:
  * имена в Excel сокращены и содержат опечатки («Договід підряду» вместо «Договір»);
  * несколько строк Excel могут ссылаться на ОДИН договор (ООН — 33 строки-объекта);
  * один номер вида 21/01/26 встречается у нескольких договоров разных подразделений.

Запуск:
    python doc_finrep_zalivka_rs.py <путь к xlsx>            — dry-run
    python doc_finrep_zalivka_rs.py <путь к xlsx> --apply    — записать в регистр
"""
import re
import sys

import openpyxl
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
ПРИМЕНЯТЬ = "--apply" in sys.argv
аргументы = [а for а in sys.argv[1:] if а != "--apply"]
if not аргументы:
    print("Використання: python doc_finrep_zalivka_rs.py <шлях до xlsx> [--apply]")
    sys.exit(2)
EXCEL = аргументы[0]
ЛИСТ = "24,07,2026"

# Проценты и варианты, ВЫВЕДЕННЫЕ АРИФМЕТИКОЙ из формул Excel 07.08. Ключ — номер строки листа;
# сигнатура рядом — страховка: если шаблон листа съехал, процент НЕ применяется.
ДОКАЗАННЫЕ = {
    32: ("09/04/25", 20, "ЗадолженностьПлюсАкты"),
    34: ("15/10/25", 0,  "ЗадолженностьПлюсАкты"),
    39: ("21/01/26", 20, "ЗадолженностьПлюсАкты"),
    51: ("06/04/26", 15, "ВыполнениеМинусОплата"),
}


def нормализовать(текст):
    т = (текст or "").lower().strip()
    for а, б in (("і", "и"), ("ї", "и"), ("є", "е"), ("ґ", "г"), ("ё", "е"),
                 ("’", ""), ("'", ""), ("«", ""), ("»", ""), ("\xa0", " ")):
        т = т.replace(а, б)
    return re.sub(r"\s+", " ", т)


def сигнатуры(текст):
    """Числовые «отпечатки»: 16/09/25, 06/04/26, БА1103/2026. Год приводим к двум цифрам."""
    т = нормализовать(текст).replace("-", "/").replace(".", "/")
    найдено = set(re.findall(r"\d{1,2}/\d{1,2}/\d{2,4}", т))
    найдено |= set(re.findall(r"\d{3,4}/\d{4}", т))
    итог = set()
    for с in найдено:
        части = с.split("/")
        итог.add("/".join(ч[-2:] if len(ч) == 4 and ч.startswith("20") else ч for ч in части))
    return итог


def число(значение):
    if isinstance(значение, (int, float)):
        return float(значение)
    if isinstance(значение, str):
        try:
            return float(значение.replace("\xa0", "").replace(" ", "").replace(",", "."))
        except ValueError:
            return None
    return None


print(f"=== Читаємо Excel: {EXCEL.split(chr(92))[-1]} ===")
wb = openpyxl.load_workbook(EXCEL, data_only=True)
ws = wb[ЛИСТ]
строки = []
for r in range(6, ws.max_row + 1):
    a = ws.cell(r, 1)
    имя = str(a.value).strip() if a.value is not None else ""
    if not имя or a.font.bold or имя.lower().startswith("итого"):
        continue
    строки.append({"r": r, "Имя": имя,
                   "Примечание": str(ws.cell(r, 2).value).strip() if ws.cell(r, 2).value else "",
                   "Сумма": число(ws.cell(r, 3).value),
                   "СуммаДЦ": число(ws.cell(r, 4).value),
                   "Сигнатуры": сигнатуры(имя)})
wb.close()
print(f"  рядків-кандидатів у договори: {len(строки)}")

print("\n=== Читаємо договори напрямку «Производство» ===")
buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Д.Ссылка КАК С, Д.Наименование КАК Имя,
  ЕСТЬNULL(Д.Подразделение.Наименование, "") КАК Подр
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ НЕ Д.ПометкаУдаления И НЕ Д.ЭтоГруппа И Д.Направление = &Напр"""
q.УстановитьПараметр("Напр", buh.Справочники.Направления.НайтиПоНаименованию("Производство", True))
т = q.Execute().Выгрузить()
договоры = []
for i in range(т.Количество()):
    s = т.Получить(i)
    договоры.append({"Ссылка": s.С, "Имя": str(s.Имя), "Подр": str(s.Подр),
                     "УИД": str(buh.String(s.С.УникальныйИдентификатор())),
                     "Сигнатуры": сигнатуры(str(s.Имя)),
                     "Слова": set(нормализовать(str(s.Имя)).split())})
print(f"  договорів напрямку: {len(договоры)}")

print("\n=== Зіставлення ===")
сопоставлено, неоднозначно, ненайдено = [], [], []
for стр in строки:
    if not стр["Сигнатуры"]:
        ненайдено.append((стр, "немає числової сигнатури"))
        continue
    кандидаты = [д for д in договоры if стр["Сигнатуры"] <= д["Сигнатуры"]]
    if not кандидаты:
        ненайдено.append((стр, "не знайдено серед договорів напрямку"))
        continue
    if len(кандидаты) == 1:
        сопоставлено.append((стр, кандидаты[0]))
        continue
    слова = set(нормализовать(стр["Имя"] + " " + стр["Примечание"]).split())
    скор = lambda д: len(слова & д["Слова"])
    лучший = max(кандидаты, key=скор)
    если_ничья = [д for д in кандидаты if д is not лучший and скор(д) == скор(лучший)]
    if если_ничья:
        неоднозначно.append((стр, кандидаты))
    else:
        сопоставлено.append((стр, лучший))

счёт = {}
for _, д in сопоставлено:
    счёт[д["УИД"]] = счёт.get(д["УИД"], 0) + 1
коллизии = [(с, д) for с, д in сопоставлено if счёт[д["УИД"]] > 1]
сопоставлено = [(с, д) for с, д in сопоставлено if счёт[д["УИД"]] == 1]

print(f"  зіставлено однозначно : {len(сопоставлено)}")
print(f"  колізій N→1 (пропуск) : {len(коллизии)}")
print(f"  неоднозначних (пропуск): {len(неоднозначно)}")
print(f"  не знайдено (пропуск) : {len(ненайдено)}")

print("\n--- ЗІСТАВЛЕНІ ---")
for стр, дог in сопоставлено:
    сумма = f"{стр['Сумма']:,.2f}" if стр["Сумма"] is not None else "—"
    доказан = ""
    if стр["r"] in ДОКАЗАННЫЕ and ДОКАЗАННЫЕ[стр["r"]][0] in дог["Сигнатуры"]:
        доказан = f"  %={ДОКАЗАННЫЕ[стр['r']][1]}"
    print(f"  r{стр['r']:3d} {стр['Имя'][:36]:36} → {дог['Имя'][:40]:40}"
          f" [{дог['Подр'][:14]:14}] C={сумма:>13}{доказан}")

if коллизии:
    print("\n--- КОЛІЗІЇ: кілька рядків Excel на ОДИН договір (пропускаємо) ---")
    групы = {}
    for стр, дог in коллизии:
        групы.setdefault(дог["Имя"], []).append(стр)
    for имя_дог, спис in групы.items():
        сумма = sum(с["Сумма"] for с in спис if с["Сумма"] is not None)
        print(f"  {имя_дог[:50]:50} ← {len(спис)} рядків, сума C={сумма:,.2f}")

if неоднозначно:
    print("\n--- НЕОДНОЗНАЧНІ (пропускаємо) ---")
    for стр, канд in неоднозначно:
        print(f"  r{стр['r']:3d} {стр['Имя'][:40]:40} | {стр['Примечание'][:30]}")

if ненайдено:
    print("\n--- НЕ ЗНАЙДЕНО (пропускаємо) ---")
    for стр, причина in ненайдено:
        print(f"  r{стр['r']:3d} {стр['Имя'][:46]:46} — {причина}")

if not ПРИМЕНЯТЬ:
    print("\n>>> DRY-RUN. Нічого не записано. Для запису: --apply")
    sys.exit(0)

print("\n=== ЗАПИС У РЕГІСТР ===")
РЕГИСТР = buh.РегистрыСведений.А_ПараметрыДоговоровФинотчета
записано = с_процентом = 0
for стр, дог in сопоставлено:
    мз = РЕГИСТР.СоздатьМенеджерЗаписи()
    мз.Договор = дог["Ссылка"]
    мз.Прочитать()
    if мз.Выбран():
        тек = {"Сумма": float(мз.СуммаСоглашения or 0), "ДЦ": float(мз.СуммаДЦ or 0),
               "Прим": str(buh.string(мз.ОбъектПримечание)),
               "Процент": float(мз.ПроцентГарантийногоУдержания or 0),
               "Вариант": str(buh.string(мз.ВариантФормулыИтога))}
    else:
        тек = {"Сумма": 0.0, "ДЦ": 0.0, "Прим": "", "Процент": 0.0, "Вариант": ""}

    итог = dict(тек)
    изменено = False
    if стр["Сумма"] is not None and стр["Сумма"] != 0 and тек["Сумма"] != стр["Сумма"]:
        итог["Сумма"] = стр["Сумма"]
        изменено = True
    if стр["СуммаДЦ"] is not None and стр["СуммаДЦ"] != 0 and тек["ДЦ"] != стр["СуммаДЦ"]:
        итог["ДЦ"] = стр["СуммаДЦ"]
        изменено = True
    if стр["Примечание"] and тек["Прим"] != стр["Примечание"][:200]:
        итог["Прим"] = стр["Примечание"][:200]
        изменено = True
    if стр["r"] in ДОКАЗАННЫЕ:
        сигн, процент, вариант = ДОКАЗАННЫЕ[стр["r"]]
        if сигн in дог["Сигнатуры"]:
            итог["Процент"] = процент
            итог["Вариант"] = вариант
            изменено = True
            с_процентом += 1

    if изменено:
        мз2 = РЕГИСТР.СоздатьМенеджерЗаписи()
        мз2.Договор = дог["Ссылка"]
        мз2.СуммаСоглашения = итог["Сумма"]
        мз2.СуммаДЦ = итог["ДЦ"]
        мз2.ОбъектПримечание = итог["Прим"]
        мз2.ПроцентГарантийногоУдержания = итог["Процент"]
        мз2.ВариантФормулыИтога = итог["Вариант"]
        мз2.Записать(True)
        записано += 1

print(f"  записано у регістр: {записано}, з них із доведеним відсотком: {с_процентом}")
