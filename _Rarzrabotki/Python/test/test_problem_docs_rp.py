# -*- coding: utf-8 -*-
"""
Проверка: что лежит в РасшифровкаПлатежа у проблемных документов
000Ц-000286 и 000Ц-000287 (Списания безналичных ДС от 28.12.2025).

Ожидаем по гипотезе финансиста:
- СтрокаРП.ОбъектРасчетов = ПустаяСсылка  ← вот ошибка
- СтрокаРП.А_Договор = заполнен/пустой?
- ДокОснование = А_ОказаниеУслугМеждуПодразделениями
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ПРОВЕРИТЬ = [
    "000Ц-000288",  # 664 000
    "000Ц-000286",  # 5 194 594,73
    "000Ц-000287",  # 2 000 000
    "000Ц-000053",  # Поступление 664 000
]

for номер in ПРОВЕРИТЬ:
    print("=" * 110)
    тип_док = "ПоступлениеБезналичныхДенежныхСредств" if номер == "000Ц-000053" else "СписаниеБезналичныхДенежныхСредств"
    print(f"{тип_док} № {номер}")
    print("=" * 110)
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Номер", номер)
    qq.Текст = f'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.{тип_док} ГДЕ Номер = &Номер УПОРЯДОЧИТЬ ПО Дата УБЫВ'
    r = qq.Выполнить().Выгрузить()
    if r.Количество() == 0:
        print("   Не найден")
        continue
    док = r.Получить(0).Ссылка
    obj = док.ПолучитьОбъект()
    print(f"   Ссылка: {S(док)}")
    print(f"   Дата: {obj.Дата.strftime('%d.%m.%Y %H:%M:%S')}")
    print(f"   ХозОперация: {S(obj.ХозяйственнаяОперация)}")
    print(f"   Контрагент: {S(obj.Контрагент)}  Партнёр: {S(obj.Партнер)}")
    print(f"   Подразделение: {S(obj.Подразделение)}")
    print(f"   Договор: {S(obj.Договор)}")
    print(f"   СуммаДокумента: {obj.СуммаДокумента}")
    # А_ОказаниеУслугМеждуПодразделениями
    try:
        док_осн = obj.А_ОказаниеУслугМеждуПодразделениями
        print(f"   А_ОказаниеУслугМеждуПодразделениями: {S(док_осн) if not док_осн.Пустая() else '(пусто)'}")
    except:
        print("   А_ОказаниеУслугМеждуПодразделениями: реквизит отсутствует")
    print(f"\n   РасшифровкаПлатежа ({obj.РасшифровкаПлатежа.Количество()} строк):")
    for i in range(obj.РасшифровкаПлатежа.Количество()):
        рп = obj.РасшифровкаПлатежа.Получить(i)
        ор_знач = рп.ОбъектРасчетов
        ор_пуст = "*** ПУСТОЙ ***" if ор_знач.Пустая() else S(ор_знач)
        дог_знач = рп.А_Договор if hasattr(рп, 'А_Договор') else None
        дог_str = S(дог_знач) if (дог_знач and not дог_знач.Пустая()) else "(пусто)"
        партн = S(рп.Партнер) if not рп.Партнер.Пустая() else "(пусто)"
        print(f"      #{i+1}: Партнёр={партн}, Сумма={рп.Сумма}, СВзаим={рп.СуммаВзаиморасчетов}")
        print(f"           ОбъектРасчетов: {ор_пуст}")
        print(f"           А_Договор:       {дог_str}")
