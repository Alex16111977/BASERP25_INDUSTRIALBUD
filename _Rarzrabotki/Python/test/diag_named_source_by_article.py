# -*- coding: utf-8 -*-
"""ПАП named-источник «Прочие активы пассивы» — по каким статьям он используется?
Если только «Оплата труда» → фикс простой (Свод_ОплатаТруда читает все источники).
Если по многим статьям → нужен общий захват named-партиции."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО,
    КОЛИЧЕСТВО(*) КАК Движ
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59)
    И Т.Источник <> ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
print("=== ПАП(Источник <> ПустаяСсылка) по статьям, cumul до 31.01.2026 (только источники-РЕГИСТРЫ) ===")
print("    (это источники типа РасчетыСКлиентами/Себест/ДенСр + named 'Прочие активы пассивы')")
rows = q.Выполнить().Выгрузить()
for r in rows:
    print(f"   {str(r.Статья):<46} | движ={int(f(r.Движ)):>6} | КО={f(r.КО):>18,.2f}")

# Конкретно named «Прочие активы пассивы» (order 0) по статьям
print("\n=== ПАП(Источник = named 'Прочие активы пассивы') по статьям ===")
# найдём ссылку на named-значение по представлению
qm = erp.NewObject("Запрос")
qm.Текст = ("ВЫБРАТЬ Ссылка КАК С, ПРЕДСТАВЛЕНИЕ(Ссылка) КАК П "
            "ИЗ Перечисление.ИсточникиУправленческогоБаланса")
named = None
for r in qm.Выполнить().Выгрузить():
    if str(r.П).strip() == "Прочие активы пассивы":
        named = r.С
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("Named", named)
q2.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Статья,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО,
    КОЛИЧЕСТВО(*) КАК Движ
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59) И Т.Источник = &Named
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
tot = 0.0
for r in q2.Выполнить().Выгрузить():
    v = f(r.КО); tot += v
    print(f"   {str(r.Статья):<46} | движ={int(f(r.Движ)):>6} | КО={v:>18,.2f}")
print(f"   {'ИТОГО named-источник (все статьи)':<46} | {'':>6} | КО={tot:>18,.2f}")
print("   >>> если ИТОГО ≈ 0 и доминирует 'Оплата труда' → named-партиция почти только ОТ")
