# Інваріант req-4: у межах эталону норма споживається СПОЧАТКУ норм-картками.
# Тобто: якщо НЕ-норм картка має ВНорме>0, то УСІ норм-картки цього эталону мають ПонадНорму=0
# (норму вичерпали норм-картки раніше, ніж не-норм отримала хоч щось у норму).
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
обр = buh.ВнешниеОбработки.Создать(EPF, False)
обр.Период = datetime.datetime(2026, 7, 7)
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000004").Ссылка
вс = buh.Справочники.Склады.Выбрать()
while вс.Следующий():
    if "СТІЛ МД МХП ОРІЛЬ" in вс.Наименование and "виробнич" in вс.Наименование:
        обр.СкладыОстатков.Добавить().Склад = вс.Ссылка
for код in ("20", "22", "28"):
    обр.СчетаОстатков.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код).Ссылка

обр.РассчитатьАнализ()
тч = обр.ТабличнаяЧастьОстатков
def нм(x):
    try: return str(x.Наименование)
    except Exception: return ""
# норм-картка = та, для якої BSL проставив НормаНоменкл>0 (BSL зробив звірку ref коректно).
from collections import defaultdict
норм_ном = set()
for i in range(тч.Количество()):
    р = тч.Получить(i)
    if float(р.НормаНоменкл) > 0.0001:
        норм_ном.add(нм(р.Номенклатура))
print("DEBUG: норм-карток у залишках (НормаНоменкл>0) =", len(норм_ном), "| всього рядків =", тч.Количество())
эталоны = defaultdict(list)
for i in range(тч.Количество()):
    р = тч.Получить(i)
    эталоны[нм(р.ОбщееНазвание)].append({
        "ном": нм(р.Номенклатура)[:30], "норм": нм(р.Номенклатура) in норм_ном,
        "внорме": float(р.ВНорме), "понад": float(р.ПонадНорму), "ост": float(р.Остаток)})

порушень = 0
перевірено_змішаних = 0
for эт, рядки in эталоны.items():
    норм = [r for r in рядки if r["норм"]]
    ненорм = [r for r in рядки if not r["норм"]]
    if not норм or not ненорм:
        continue
    перевірено_змішаних += 1
    ненорм_у_нормі = any(r["внорме"] > 0.0001 for r in ненорм)
    норм_є_понад = any(r["понад"] > 0.0001 for r in норм)
    if ненорм_у_нормі and норм_є_понад:
        порушень += 1
        print(f"  ⚠ '{эт}': не-норм картка в нормі, АЛЕ норм-картка має понад → пріоритет порушено")
        for r in норм: print(f"      [норм] {r['ном']:30} ост={r['ост']} внорме={r['внорме']} понад={r['понад']}")
        for r in ненорм: print(f"      [не-норм] {r['ном']:30} ост={r['ост']} внорме={r['внорме']} понад={r['понад']}")

print(f"эталонів зі змішаними картками (норм+не-норм): {перевірено_змішаних}; порушень пріоритету: {порушень}")
assert порушень == 0, "пріоритет req-4 ПОРУШЕНО"
print("PASS: норма у межах эталону споживається спочатку норм-картками (req-4 інваріант тримається)")
