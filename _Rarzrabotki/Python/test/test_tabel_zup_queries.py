fails = 0


def check(cond, msg):
    global fails
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond:
        fails += 1


def rows(t):
    cols = [t.Колонки.Получить(i).Имя for i in range(t.Колонки.Количество())]
    return [{c: getattr(t.Получить(i), c) for c in cols} for i in range(t.Количество())]


def run(base, txt, params):
    q = base.NewObject("Запрос")
    q.Text = txt
    for k, v in params.items():
        q.SetParameter(k, v)
    try:
        return rows(q.Execute().Выгрузить())
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        print("   QUERY FAIL:", msg[:400])
        return None


def bounds(base, y, m, d1, d2):
    """Границы периода считает 1С: начало дня и конец дня (COM сдвигает даты на -3 ч)."""
    q = base.NewObject("Запрос")
    q.Text = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&Н, ДЕНЬ) КАК Н, КОНЕЦПЕРИОДА(&К, ДЕНЬ) КАК К"
    q.SetParameter("Н", pywintypes.Time(datetime.datetime(y, m, d1, 12, 0, 0)))
    q.SetParameter("К", pywintypes.Time(datetime.datetime(y, m, d2, 12, 0, 0)))
    r = q.Execute().Выгрузить().Получить(0)
    return r.Н, r.К


