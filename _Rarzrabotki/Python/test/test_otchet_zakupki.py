# -*- coding: utf-8 -*-
"""Smoke-тест внешнего отчёта «Отчет по общим названиям в СС по закупкам» (BuhBud).

1) Прямой пакетный запрос (1:1 из СКД) -> эталон по каждому ВидСтроки:
   число строк и Σ (СуммаПлан для «План СС», СуммаФакт для «Факт закупки»).
2) ВнешниеОтчеты.Создать(.erf) -> ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных").
3) Программная компоновка с настройками по умолчанию -> ТаблицаЗначений.
4) Детальные строки ТЗ (ВидСтроки заполнен и Документ заполнен) группируются
   по ВидСтроки: счёт == эталон, |Σ - эталон| < 0.05.
Без Удалить(). Строк ~29 тыс. — компоновка может занять пару минут.
"""
import sys
import pythoncom
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС"
       r"\Отчет по общим названиям в СС по закупкам.erf")

QUERY = """ВЫБРАТЬ РАЗЛИЧНЫЕ
	К.ОбщееНазвание КАК ОбщееНазвание
ПОМЕСТИТЬ АктивныеОН
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Активная
	И НЕ К.Ссылка.ПометкаУдаления
	И К.ОбщееНазвание <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
;

////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ
	"План СС" КАК ВидСтроки,
	К.ОбщееНазвание КАК ОбщееНазвание,
	К.ОбщееНазвание.Единица КАК ЕдиницаОбщая,
	К.Номенклатура КАК Номенклатура,
	К.Единица КАК Единица,
	К.ЕдиницаСС КАК ЕдиницаСС,
	К.Этап КАК Этап,
	К.НоменклатураСС КАК НоменклатураСС,
	К.Ссылка КАК Документ,
	К.Количество КАК КоличествоПлан,
	К.Сумма КАК СуммаПлан,
	NULL КАК КоличествоФакт,
	NULL КАК СуммаФакт
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Активная
	И НЕ К.Ссылка.ПометкаУдаления

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
	"Факт закупки",
	Т.Номенклатура.ОбщееНазваниеНоменклатуры,
	Т.Номенклатура.ОбщееНазваниеНоменклатуры.Единица,
	Т.Номенклатура,
	Т.ЕдиницаИзмерения,
	"",
	NULL,
	"",
	Т.Ссылка,
	NULL,
	NULL,
	Т.Количество,
	ВЫБОР КОГДА Т.Ссылка.СуммаВключаетНДС ТОГДА Т.Сумма ИНАЧЕ Т.Сумма + Т.СуммаНДС КОНЕЦ
ИЗ
	Документ.ПоступлениеТоваровУслуг.Товары КАК Т
ГДЕ
	Т.Ссылка.Проведен
	И Т.Номенклатура.ОбщееНазваниеНоменклатуры В
		(ВЫБРАТЬ АктивныеОН.ОбщееНазвание ИЗ АктивныеОН КАК АктивныеОН)"""

PLAN = "План СС"
FACT = "Факт закупки"


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
    S = buh.String

    # --- 1. Эталон: прямой пакетный запрос (1:1 из СКД) ---
    q = buh.NewObject("Запрос")
    q.Text = QUERY
    et = q.Execute().Выгрузить()
    et_n = {PLAN: 0, FACT: 0}
    et_s = {PLAN: 0.0, FACT: 0.0}
    for i in range(et.Количество()):
        row = et.Получить(i)
        vid = S(row.ВидСтроки)
        et_n[vid] += 1
        if vid == PLAN:
            et_s[vid] += float(row.СуммаПлан or 0)
        else:
            et_s[vid] += float(row.СуммаФакт or 0)
    print(f"[Эталон] {PLAN}: строк={et_n[PLAN]}, Σ={et_s[PLAN]:.2f}")
    print(f"[Эталон] {FACT}: строк={et_n[FACT]}, Σ={et_s[FACT]:.2f}")

    # --- 2. Отчёт из .erf ---
    rep = buh.ВнешниеОтчеты.Создать(ERF, False)
    schema = rep.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    settings = schema.НастройкиПоУмолчанию

    # --- 3. Программная компоновка -> ТаблицаЗначений ---
    # COM-грабли: Тип(...) недоступен через V83 -> трюк через ОписаниеТипов
    generator_type = buh.NewObject(
        "ОписаниеТипов",
        "ГенераторМакетаКомпоновкиДанныхДляКоллекцииЗначений"
    ).Типы().Получить(0)
    # COM-грабли: пропуск параметров = pythoncom.Empty (VT_EMPTY = Неопределено)
    composer = buh.NewObject("КомпоновщикМакетаКомпоновкиДанных")
    layout = composer.Выполнить(schema, settings, pythoncom.Empty,
                                pythoncom.Empty, generator_type)
    processor = buh.NewObject("ПроцессорКомпоновкиДанных")
    processor.Инициализировать(layout)
    vt = buh.NewObject("ТаблицаЗначений")
    output = buh.NewObject(
        "ПроцессорВыводаРезультатаКомпоновкиДанныхВКоллекциюЗначений")
    output.УстановитьОбъект(vt)
    output.Вывести(processor)
    total_rows = vt.Количество()

    # --- 4. Детальные строки: ВидСтроки заполнен и Документ заполнен
    #        (в группировках/итогах не-группировочные поля -> Неопределено=None)
    skd_n = {PLAN: 0, FACT: 0}
    skd_s = {PLAN: 0.0, FACT: 0.0}
    for i in range(total_rows):
        row = vt.Получить(i)
        vid = row.ВидСтроки
        if vid is None or row.Документ is None:
            continue  # группировка ОбщееНазвание/Номенклатура или общий итог
        vid = S(vid)
        skd_n[vid] += 1
        if vid == PLAN:
            skd_s[vid] += float(row.СуммаПлан or 0)
        else:
            skd_s[vid] += float(row.СуммаФакт or 0)
    print(f"[СКД] строк всего={total_rows}")
    print(f"[СКД] {PLAN}: детальных={skd_n[PLAN]}, Σ={skd_s[PLAN]:.2f}")
    print(f"[СКД] {FACT}: детальных={skd_n[FACT]}, Σ={skd_s[FACT]:.2f}")

    # --- Ассерты ---
    for vid in (PLAN, FACT):
        assert skd_n[vid] == et_n[vid], (
            f"FAIL [{vid}]: детальных строк {skd_n[vid]} != эталон {et_n[vid]}")
        diff = abs(skd_s[vid] - et_s[vid])
        assert diff < 0.05, (
            f"FAIL [{vid}]: |ΣСКД - ΣЭталон| = {diff:.4f} >= 0.05")
        print(f"OK [{vid}]: строк {skd_n[vid]} == эталон, "
              f"расхождение суммы {diff:.4f} < 0.05")


if __name__ == "__main__":
    main()
