# -*- coding: utf-8 -*-
"""Извлекает РЕАЛЬНУЮ сохранённую структуру варианта 'Глобино-2' из
Справочник.ВариантыОтчетов.Настройки (Хранилище) — порядок группировок.
Цель: понять, лежит ли Регистратор НА ВЕРХУ в хранилище (тогда вариант так и
сохранён), или это подмена при загрузке.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import pythoncom, win32com.client

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

# найти вариант
q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ВО.Ссылка КАК Ссылка, ВО.Наименование КАК Наим
ИЗ Справочник.ВариантыОтчетов КАК ВО
ГДЕ ВО.Наименование ПОДОБНО "%лобино-2%"
"""
sel = q.Выполнить().Выбрать()
if not sel.Следующий():
    print("Вариант 'Глобино-2' не найден"); sys.exit(1)
ref = sel.Ссылка
print(f"Вариант: {sel.Наим}")

об = ref.ПолучитьОбъект()
настройки = об.Настройки.Получить()
print("Тип Настроек:", erp.XMLТипЗнч(настройки) if False else type(настройки).__name__)

def имя_поля(поле):
    # поле — ПолеКомпоновкиДанных; пытаемся получить строку разными способами
    try:
        s = str(поле)
        if s and "COMObject" not in s:
            return s
    except Exception:
        pass
    try:
        return erp.String(поле)
    except Exception:
        return "<?>"

def обойти(структура, уровень):
    # структура — КоллекцияЭлементовСтруктурыКомпоновкиДанных
    кол = структура
    n = кол.Количество()
    for i in range(n):
        эл = кол.Получить(i)
        тип = type(эл).__name__
        # ГруппировкаКомпоновкиДанных имеет .ПоляГруппировки и .Структура
        try:
            пг = эл.ПоляГруппировки
            поля = []
            for j in range(пг.Элементы.Количество()):
                пэ = пг.Элементы.Получить(j)
                try:
                    поля.append(имя_поля(пэ.Поле))
                except Exception:
                    поля.append("<детали>")
            метка = ", ".join(поля) if поля else "<Детальные записи>"
            print("  " * уровень + f"• {метка}")
            обойти(эл.Структура, уровень + 1)
        except Exception as e:
            print("  " * уровень + f"• [{тип}] (не группировка)")

print("\n=== СОХРАНЁННАЯ структура (порядок группировок сверху вниз) ===")
обойти(настройки.Структура, 0)

print("\n=== Отбор варианта ===")
try:
    for i in range(настройки.Отбор.Элементы.Количество()):
        э = настройки.Отбор.Элементы.Получить(i)
        try:
            лев = имя_поля(э.ЛевоеЗначение)
        except Exception:
            лев = "<?>"
        исп = getattr(э, "Использование", "?")
        print(f"  {лев}  Использование={исп}")
except Exception as e:
    print("  (отбор не прочитан):", e)
