# -*- coding: utf-8 -*-
"""ДИАГНОСТИКА (systematic-debugging RED): почему Загрузить(А_ОтчетБаланс_Свод)
падает «Запись с такими ключевыми полями существует!».

1) выполняем ТОТ ЖЕ запрос, что в BSL Свод_СебестоимостьТоваров;
2) строим ключ из выводимых измерений (Орг,Подр,Статья,Ном,Склад,Source,
   Расхождение) — это полный ключ, остальные 12 измерений пусты у всех строк;
3) ищем дубли по ключу, печатаем конфликтующие строки со ВСЕМИ полями
   (XMLСтрока + ПРЕДСТАВЛЕНИЕ + тип) — видно, что регистр считает равным.
Также печатаем результат проведения документа с НОРМАЛЬНО декодированной
ошибкой (без mojibake).
"""
import sys, io
from collections import defaultdict
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qb = conn.NewObject("Запрос")
qb.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qb.УстановитьПараметр("М", M); rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ, КД = rb.НМ, rb.КД

qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка КАК Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for n in ("Собственные средства", "Доходы текущего периода",
          "Расходы текущего периода"):
    имена.Добавить(n)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
Искл = conn.NewObject("Массив")
for i in range(tI.Количество()):
    Искл.Добавить(tI.Получить(i).Ссылка)

q = conn.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НачМес", НМ)
q.УстановитьПараметр("КонМес", КД); q.УстановитьПараметр("Искл", Искл)
q.Текст = open(
    r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test"
    r"\_seb_query_text.txt", encoding="utf-8").read()
t = q.Выполнить().Выгрузить()
rows = t.Количество()
print(f"строк результата = {rows}")

groups = defaultdict(list)
for i in range(rows):
    r = t.Получить(i)
    key = (conn.XMLСтрока(r.Организация),
           conn.XMLСтрока(r.Подразделение),
           conn.XMLСтрока(r.Статья),
           conn.XMLСтрока(r.Номенклатура),
           conn.XMLСтрока(r.Склад),
           conn.XMLСтрока(r.Source),
           str(bool(r.Расхождение)))
    groups[key].append(i)

дубли = {k: v for k, v in groups.items() if len(v) > 1}
print(f"дублей по 7-польному ключу (XMLСтрока) = {len(дубли)}")

# прицельный дамп конфликтной группы из ошибки 1С:
# Ном=«Дизельне паливо», Статья содержит «оптов»
print("\n=== строки с Ном='Дизельне паливо' и Статья ~ 'оптов' ===")
показ = 0
for i in range(rows):
    r = t.Получить(i)
    ном_п = str(r.Номенклатура)
    ст_п = str(r.Статья)
    if ном_п.strip().lower() != "дизельне паливо":
        continue
    if "оптов" not in ст_п.lower():
        continue
    показ += 1
    if показ > 25:
        continue
    подр = r.Подразделение
    скл = r.Склад
    print(f"#{i}: Подр[{conn.XMLСтрока(подр)}] '{подр}' "
          f"тип={type(подр).__name__} | "
          f"Скл[{conn.XMLСтрока(скл)}] '{скл}' | "
          f"Расх={bool(r.Расхождение)} "
          f"НО={float(r.СуммаНачальныйОстаток or 0):,.2f} "
          f"КО={float(r.СуммаКонечныйОстаток or 0):,.2f}")
print(f"всего строк Ном='Дизельне паливо' & Статья~оптов: {показ}")

# по этой группе: уникальность по XMLСтрока(Подр)+XMLСтрока(Скл)
от_кл = {}
for i in range(rows):
    r = t.Получить(i)
    if (str(r.Номенклатура).strip().lower() != "дизельне паливо"
            or "оптов" not in str(r.Статья).lower()):
        continue
    kk = (conn.XMLСтрока(r.Подразделение), conn.XMLСтрока(r.Склад),
          bool(r.Расхождение))
    от_кл.setdefault(kk, 0)
    от_кл[kk] += 1
print("уник (XMLПодр,XMLСклад,Расх) в группе:")
for kk, c in от_кл.items():
    print(f"  {kk} -> {c}")

# повторим попытку провести и НОРМАЛЬНО декодируем ошибку
print("\n" + "=" * 64)
qd = conn.NewObject("Запрос")
qd.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ Документ.А_ФинРез_Баланс"
tzz = qd.Выполнить().Выгрузить()
for i in range(tzz.Количество()):
    об = tzz.Получить(i).С.ПолучитьОбъект()
    if об is not None:
        об.ОбменДанными.Загрузка = True
        об.Удалить()
doc = conn.Документы.А_ФинРез_Баланс.СоздатьДокумент()
doc.Дата = datetime(2026, 1, 31, 14, 0, 0); doc.Организация = ORG
doc.Месяц = M; doc.ВключатьДочерние = False
try:
    doc.Записать(conn.PredefinedValue("РежимЗаписиДокумента.Проведение"))
    print(f"ПРОВЕДЕНО OK №{doc.Номер} Проведен={doc.Проведен}")
except Exception as e:
    if hasattr(e, "excepinfo") and e.excepinfo:
        msg = e.excepinfo[2]
        if isinstance(msg, bytes):
            msg = msg.decode("cp1251", "replace")
        print("ОШИБКА ПРОВЕДЕНИЯ (decoded):")
        print(msg)
    else:
        print(f"ОШИБКА: {e}")
