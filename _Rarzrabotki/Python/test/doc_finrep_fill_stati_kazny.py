# -*- coding: utf-8 -*-
"""Заполнение ТЧ СтатьиИсключенияКазны боевых документов ССЫЛКАМИ справочника
СтатьиДвиженияДенежныхСредств (после смены типа реквизита 16.08.2026).

Для каждого документа августа: если ТЧ пуста — ЗаполнитьСтатьиИсключенияПоУмолчанию()
(экспортная процедура модуля), пересчёт и запись. Если заполнена — только показывает.

Запуск:
    python doc_finrep_fill_stati_kazny.py            — dry-run (расчёт в памяти)
    python doc_finrep_fill_stati_kazny.py --apply    — записать документы
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ПРИМЕНЯТЬ = "--apply" in sys.argv

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

q = buh.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С, Д.Номер КАК Номер "
           "ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д "
           "ГДЕ НЕ Д.ПометкаУдаления УПОРЯДОЧИТЬ ПО Д.ДатаРасчета")
т = q.Execute().Выгрузить()
print(f"Документов: {т.Количество()}. Режим: {'ЗАПИСЬ' if ПРИМЕНЯТЬ else 'DRY-RUN'}\n")

ошибок = 0
for i in range(т.Количество()):
    ссылка_док = т.Получить(i).С
    объект = ссылка_док.ПолучитьОбъект()
    номер = str(т.Получить(i).Номер)
    print(f"Документ № {номер}:")

    if объект.СтатьиИсключенияКазны.Количество() == 0:
        объект.ЗаполнитьСтатьиИсключенияПоУмолчанию()
        print(f"  ТЧ заполнена по умолчанию: {объект.СтатьиИсключенияКазны.Количество()} статей")
    else:
        print(f"  ТЧ уже заполнена: {объект.СтатьиИсключенияКазны.Количество()} строк")

    for j in range(объект.СтатьиИсключенияКазны.Количество()):
        статья = объект.СтатьиИсключенияКазны.Получить(j).Статья
        print(f"    - {buh.string(статья)}")

    рез = объект.Рассчитать()
    ок = bool(рез.Выполнено) and int(рез.Ошибок) == 0
    print(f"  Пересчёт: Выполнено={bool(рез.Выполнено)} Ошибок={int(рез.Ошибок)} "
          f"Казна строк={объект.Казна.Количество()}")
    if not ок:
        ошибок += 1
        print("  [ОШИБКА] пересчёт с замечаниями-ошибками — документ НЕ записываю")
        continue

    if ПРИМЕНЯТЬ:
        объект.Записать()
        print("  → записан")
    print()

print(f"ИТОГ: {'ошибок ' + str(ошибок) if ошибок else 'без ошибок'}")
if not ПРИМЕНЯТЬ:
    print(">>> DRY-RUN: база не изменена. Для записи: --apply")
sys.exit(1 if ошибок else 0)
