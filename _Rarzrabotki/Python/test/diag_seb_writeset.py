"""Точная репродукция БЕЗ модуля документа: создаём А_ФинРез_Баланс (запись
без проведения → регистратор), формируем НаборЗаписей А_ОтчетБаланс_Свод по
регистратору ровно как оркестратор (ЗаполнитьЗначенияСвойств → Свернуть(19)),
и ФИЗИЧЕСКИ Записываем. Если падает — порциями локализуем 1-ю конфликтную
строку и печатаем её + дубликат по 19 измерениям.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
DDATE = datetime(2026, 1, 31, 14, 0, 0)
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qb = conn.NewObject("Запрос")
qb.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qb.УстановитьПараметр("М", M); rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ, КД = rb.НМ, rb.КД
qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка КАК Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for nn in ("Собственные средства", "Доходы текущего периода",
           "Расходы текущего периода"):
    имена.Добавить(nn)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
Искл = conn.NewObject("Массив")
for i in range(tI.Количество()):
    Искл.Добавить(tI.Получить(i).Ссылка)

# чистим старые доки
qd = conn.NewObject("Запрос")
qd.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ Документ.А_ФинРез_Баланс"
tzz = qd.Выполнить().Выгрузить()
for i in range(tzz.Количество()):
    об = tzz.Получить(i).С.ПолучитьОбъект()
    if об is not None:
        об.ОбменДанными.Загрузка = True
        об.Удалить()

doc = conn.Документы.А_ФинРез_Баланс.СоздатьДокумент()
doc.Дата = DDATE; doc.Организация = ORG
doc.Месяц = M; doc.ВключатьДочерние = False
doc.Записать(conn.PredefinedValue("РежимЗаписиДокумента.Запись"))  # БЕЗ проведения
рег = doc.Ссылка
print(f"документ записан (без проведения): {рег}")

q = conn.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НачМес", НМ)
q.УстановитьПараметр("КонМес", КД); q.УстановитьПараметр("Искл", Искл)
q.Текст = open(r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python"
               r"\test\_seb_query_text.txt", encoding="utf-8").read()
t = q.Выполнить().Выгрузить()
print(f"строк запроса = {t.Количество()}")

нз = conn.РегистрыСведений.А_ОтчетБаланс_Свод.СоздатьНаборЗаписей()
нз.Отбор.Регистратор.Установить(рег)
тз = нз.Выгрузить()
for i in range(t.Количество()):
    conn.ЗаполнитьЗначенияСвойств(тз.Добавить(), t.Получить(i))
изм = ("Организация,Подразделение,Статья,Номенклатура,Контрагент,Партнер,"
       "Склад,ОбъектыЭксплуатации,Договор,ФизическоеЛицо,ДенежныеСредства,"
       "Source,Расхождение,Аналитика1,Аналитика2,Аналитика3,ОбъектРасчетов,"
       "НематериальныйАктив,ДокументДвижения")
рес = "СуммаНачальныйОстаток,СуммаПриход,СуммаРасход,СуммаКонечныйОстаток"
до = тз.Количество()
тз.Свернуть(изм, рес)
print(f"тз ДО={до} ПОСЛЕ Свернуть={тз.Количество()}")

нз.Загрузить(тз)
try:
    нз.Записать(True)
    print(f"ЗАПИСАНО OK, строк набора = {нз.Количество()}  "
          f"=> свод КОРРЕКТЕН, дубль НЕ от Свод_СебестоимостьТоваров")
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    if isinstance(msg, bytes):
        msg = msg.decode("cp1251", "replace")
    print(f"ОШИБКА Записать набора: {msg}")
    # дубли по 19 изм точным 1С-равенством
    from collections import Counter
    имена19 = изм.split(",")
    c = Counter()
    for i in range(тз.Количество()):
        r = тз.Получить(i)
        c[tuple(conn.ЗначениеВСтрокуВнутр(getattr(r, nm))
                for nm in имена19)] += 1
    d = [(k, v) for k, v in c.items() if v > 1]
    print(f"дублей по 19 изм (ЗначениеВСтрокуВнутр) в наборе = {len(d)}")
    if not d:
        print(">>> 0 дублей по 19 изм, но Записать падает => ключ "
              "уникальности РС НЕ равен 19 измерениям (ведущее/осн.отбор)")
    # бинарный поиск: минимальный префикс, который падает
    lo, hi = 1, тз.Количество()
    while lo < hi:
        mid = (lo + hi) // 2
        н2 = conn.РегистрыСведений.А_ОтчетБаланс_Свод.СоздатьНаборЗаписей()
        н2.Отбор.Регистратор.Установить(рег)
        т2 = н2.Выгрузить()
        for j in range(mid):
            conn.ЗаполнитьЗначенияСвойств(т2.Добавить(), тз.Получить(j))
        н2.Загрузить(т2)
        try:
            н2.Записать(True)
            lo = mid + 1
        except Exception:
            hi = mid
    p = lo - 1  # индекс первой конфликтной строки
    кон = тз.Получить(p)
    клкон = tuple(conn.ЗначениеВСтрокуВнутр(getattr(кон, nm))
                  for nm in имена19)
    print(f"\nПЕРВАЯ конфликтная строка #{p}:")
    print(f"  Орг='{кон.Организация}' Подр='{кон.Подразделение}' "
          f"Ст='{кон.Статья}' Ном='{кон.Номенклатура}' Скл='{кон.Склад}' "
          f"Src='{кон.Source}' Расх={bool(кон.Расхождение)}")
    for k in range(p):
        пр = тз.Получить(k)
        if tuple(conn.ЗначениеВСтрокуВнутр(getattr(пр, nm))
                 for nm in имена19) == клкон:
            print(f"  совпадает по 19 изм со строкой #{k}: "
                  f"Подр='{пр.Подразделение}' Ном='{пр.Номенклатура}' "
                  f"Скл='{пр.Склад}'")
            break
    else:
        # ключ не 19 изм — ищем по подмножеству (без Подразделения и т.п.)
        print("  по 19 изм дубликата нет. Пробуем без Подразделения:")
        безподр = [n2 for n2 in имена19 if n2 != "Подразделение"]
        for k in range(p):
            пр = тз.Получить(k)
            if (tuple(conn.ЗначениеВСтрокуВнутр(getattr(пр, nm))
                      for nm in безподр)
                    == tuple(conn.ЗначениеВСтрокуВнутр(getattr(кон, nm))
                             for nm in безподр)):
                print(f"  СОВПАЛО БЕЗ Подразделения со строкой #{k}: "
                      f"Подр_кон='{кон.Подразделение}' "
                      f"Подр_дубль='{пр.Подразделение}' "
                      f"Ном='{пр.Номенклатура}' Скл='{пр.Склад}'")
                break
# подчистим
об = рег.ПолучитьОбъект()
if об is not None:
    об.ОбменДанными.Загрузка = True
    об.Удалить()
