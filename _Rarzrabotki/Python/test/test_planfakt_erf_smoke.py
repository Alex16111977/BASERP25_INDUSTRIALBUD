# -*- coding: utf-8 -*-
"""Смок собранного ПланФакт.erf в базе kazna (после доработки: разрез СтатьяДДС).

Проверки:
1. .erf загружается через ВнешниеОтчеты.Создать (БезопасныйРежим=Ложь).
2. Типы/значения параметров СКД не деградировали при сборке через BaseERPRazr:
   - ГруппаДоход: 2 типа (ПоказателиБюджетов + СтатьиДвиженияДенежныхСредств);
   - НаправлениеДДСПриход/Расход: значения по умолчанию = Приход/Расход.
3. Поле СтатьяДвиженияДенежныхСредств в наборе данных с ролью измерения.
4. Компоновка варианта «Основной» (СкомпоноватьРезультат) работает,
   подразделения не размножились, итоги Доход/Расход совпадают с контрольным запросом.
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="localhost";Ref="kazna";Usr="cfo";Pwd="2442"'
ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\ПланФакт.erf"

CONTROL_QUERY = """
ВЫБРАТЬ РАЗРЕШЕННЫЕ
	БДДСОбороты.Подразделение,
	0 КАК ПланДоход,
	ВЫБОР
		КОГДА БДДСОбороты.СтатьяДвиженияДенежныхСредств В ИЕРАРХИИ (&ГруппаДоход)
				И БДДСОбороты.НаправлениеДДС = &НаправлениеДДСПриход
			ТОГДА БДДСОбороты.СуммаПриходОборот + БДДСОбороты.СуммаРасходОборот
		КОГДА БДДСОбороты.СтатьяДвиженияДенежныхСредств В ИЕРАРХИИ (&ГруппаДоход)
				И БДДСОбороты.НаправлениеДДС = &НаправлениеДДСРасход
			ТОГДА -(БДДСОбороты.СуммаПриходОборот + БДДСОбороты.СуммаРасходОборот)
		ИНАЧЕ 0
	КОНЕЦ КАК Доход,
	NULL КАК ПланРасход,
	ВЫБОР
		КОГДА БДДСОбороты.СтатьяДвиженияДенежныхСредств В ИЕРАРХИИ (&ГруппаРасход)
			ТОГДА (БДДСОбороты.СуммаПриходОборот + БДДСОбороты.СуммаРасходОборот) * ВЫБОР
					КОГДА БДДСОбороты.НаправлениеДДС = &НаправлениеДДСРасход
						ТОГДА -1
					ИНАЧЕ 1
				КОНЕЦ
		ИНАЧЕ 0
	КОНЕЦ КАК Расход
ПОМЕСТИТЬ ТЧВременно
ИЗ
	РегистрНакопления.БДДС.Обороты(НАЧАЛОПЕРИОДА(&Начало, ДЕНЬ), КОНЕЦПЕРИОДА(&Конец, ДЕНЬ), Авто, ) КАК БДДСОбороты

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
	БДДСОбороты.Подразделение,
	ВЫБОР
		КОГДА БДДСОбороты.ПоказательБюджета В ИЕРАРХИИ (&ГруппаДоход)
			ТОГДА БДДСОбороты.СуммаОборот
		ИНАЧЕ 0
	КОНЕЦ,
	0,
	ВЫБОР
		КОГДА БДДСОбороты.ПоказательБюджета В ИЕРАРХИИ (&ГруппаРасход)
			ТОГДА -БДДСОбороты.СуммаОборот
		ИНАЧЕ 0
	КОНЕЦ,
	NULL
ИЗ
	РегистрНакопления.БюджетыНаМесяц.Обороты(НАЧАЛОПЕРИОДА(&Начало, ДЕНЬ), КОНЕЦПЕРИОДА(&Конец, ДЕНЬ), Авто, ВидПериода = ЗНАЧЕНИЕ(Перечисление.ВидыПериодовБюджетирования.МЕСЯЦ)) КАК БДДСОбороты
;

////////////////////////////////////////////////////////////////////////////////
ВЫБРАТЬ
	СУММА(ВложенныйЗапрос.ПланДоход) КАК ПланДоход,
	СУММА(ВложенныйЗапрос.Доход) КАК Доход,
	СУММА(ВложенныйЗапрос.ПланРасход) КАК ПланРасход,
	СУММА(ВложенныйЗапрос.Расход) КАК Расход,
	КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВложенныйЗапрос.Подразделение) КАК КолПодразделений
ИЗ
	ТЧВременно КАК ВложенныйЗапрос
"""


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    kazna = v8.Connect(CONN)
    S = kazna.String

    # Полдень — обход сдвига дат при COM-маршалинге (реквизиты отчёта с
    # квалификатором Дата усекают время; полночь уезжает на предыдущий день).
    # Контрольный запрос выравнивает границы серверно: НАЧАЛОПЕРИОДА/КОНЕЦПЕРИОДА(ДЕНЬ).
    начало = datetime.datetime(2026, 6, 1, 12, 0, 0)
    конец = datetime.datetime(2026, 6, 30, 12, 0, 0)  # отчёт сам сделает КонецДня()

    # --- 1. Загрузка .erf ---
    отчет = kazna.ВнешниеОтчеты.Создать(ERF, False)
    print("1. OK: .erf загружен:", S(отчет.Метаданные().Синоним) or отчет.Метаданные().Имя)

    # --- 2. Параметры СКД ---
    схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    ok = True
    параметры = {}
    for i in range(схема.Параметры.Количество()):
        п = схема.Параметры.Получить(i)
        параметры[п.Имя] = п
    гд = параметры.get("ГруппаДоход")
    типы = гд.ТипЗначения.Типы()
    имена_типов = [S(типы.Получить(k)) for k in range(типы.Количество())]
    print("2. ГруппаДоход типы:", имена_типов)
    if len(имена_типов) != 2:
        ok = False
        print("   FAIL: ожидалось 2 типа (ПоказателиБюджетов + СтатьиДвиженияДенежныхСредств)")
    for имя in ("НаправлениеДДСПриход", "НаправлениеДДСРасход"):
        знач = S(параметры[имя].Значение)
        print(f"   {имя} = '{знач}'")
        if not знач:
            ok = False
            print(f"   FAIL: {имя} — значение по умолчанию потеряно при сборке")

    # --- 3. Поле СтатьяДвиженияДенежныхСредств ---
    поля = схема.НаборыДанных.Получить(0).Поля
    найдено = False
    for i in range(поля.Количество()):
        поле = поля.Получить(i)
        try:
            if поле.ПутьКДанным == "СтатьяДвиженияДенежныхСредств":
                найдено = True
                роль = поле.Роль
                print("3. Поле СтатьяДвиженияДенежныхСредств: есть, Измерение =", bool(роль.Измерение))
                if not роль.Измерение:
                    ok = False
        except Exception:
            continue
    if not найдено:
        ok = False
        print("3. FAIL: поле СтатьяДвиженияДенежныхСредств не найдено в наборе данных")

    # --- 4. Компоновка варианта «Основной» ---
    отчет.НачалоПериода = начало
    отчет.КонецПериода = конец
    табдок = kazna.NewObject("ТабличныйДокумент")
    отчет.СкомпоноватьРезультат(табдок, None)
    высота = табдок.ВысотаТаблицы
    ширина = табдок.ШиринаТаблицы
    print(f"4. Компоновка OK: таблица {высота}x{ширина}")

    # Контрольный запрос: общие итоги и число подразделений
    q = kazna.NewObject("Запрос")
    q.Text = CONTROL_QUERY
    q.SetParameter("Начало", начало)
    q.SetParameter("Конец", конец)
    q.SetParameter("ГруппаДоход",
                   kazna.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001053"))
    q.SetParameter("ГруппаРасход",
                   kazna.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("1В"))
    q.SetParameter("НаправлениеДДСПриход",
                   kazna.Перечисления.НаправленияДвиженийДенежныхСредств.Приход)
    q.SetParameter("НаправлениеДДСРасход",
                   kazna.Перечисления.НаправленияДвиженийДенежныхСредств.Расход)
    итог = q.Execute().Выгрузить().Получить(0)
    к_доход = float(итог.Доход or 0)
    к_расход = float(итог.Расход or 0)
    к_подр = int(итог.КолПодразделений)
    print(f"   Контроль: Доход={к_доход:.2f} Расход={к_расход:.2f} Подразделений={к_подр}")

    if высота <= 3:
        ok = False
        print("   FAIL: табличный документ пуст")
    if высота > к_подр * 4 + 60:
        ok = False
        print(f"   FAIL: высота {высота} подозрительно велика — похоже, строки размножились по статьям")

    # Числа из табдока: ищем контрольные итоги
    числа = set()
    for r in range(1, высота + 1):
        for c in range(1, ширина + 1):
            текст = табдок.Область(r, c, r, c).Текст
            if not текст:
                continue
            t = текст.replace("\xa0", "").replace(" ", "").replace(",", ".")
            try:
                числа.add(round(float(t), 2))
            except ValueError:
                continue

    def найден(x):
        return any(abs(x - ч) < 0.01 for ч in числа)

    for имя, знач in (("Доход", к_доход), ("Расход", к_расход)):
        if найден(round(знач, 2)):
            print(f"   OK: итог {имя} {знач:.2f} найден в отчёте")
        else:
            ok = False
            print(f"   FAIL: итог {имя} {знач:.2f} НЕ найден в отчёте")

    print("\nСМОК:", "OK — все проверки пройдены" if ok else "FAIL")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"FAIL: {e.excepinfo[2]}")
        else:
            print(f"FAIL: {e}")
        sys.exit(1)
