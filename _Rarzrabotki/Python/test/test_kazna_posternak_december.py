def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


def print_row(i, r, fields):
    print(f"  [{i}]", end="")
    for f in fields:
        try:
            v = getattr(r, f)
            s = S(v).replace('\xa0', ' ')
            if len(s) > 40:
                s = s[:37] + "..."
            print(f"  {f}={s}", end="")
        except:
            pass
    print()


