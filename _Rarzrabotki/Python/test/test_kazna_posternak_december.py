r2 = q2.Execute().Выгрузить()
for i in range(r2.Количество()):
    reg = r2.Получить(i).Р
    print(f"\n  Регистратор: {S(reg)}")
    try:
        obj = reg.ПолучитьОбъект()
        if obj is None:
            print(f"    ОБ'ЄКТ НЕ ЗНАЙДЕНО")
            continue
        print(f"    Дата: {S(obj.Дата)}")
        for attr in ["КассаДатаС", "КассаДатаПо", "Организация"]:
            try:
                v = getattr(obj, attr)
                print(f"    {attr}: {S(v)}")
            except:
                pass
        # Тест чи проходить фільтр поточного коду
        try:
            kds = obj.КассаДатаС
            kdp = obj.КассаДатаПо
            in_range = (S(kds) >= "01.12.2025" and S(kdp) <= "31.12.2025 23:59:59")
            print(f"    ПРОХОДИТЬ фільтр КассаДатаС>=01.12 И КассаДатаПо<=31.12 ? {in_range}")
        except:
            pass
        # Для А_РаспределениеЗаработнойПлаты — перевірити прапор А_ПереносЕРП
        try:
            если_перенос = obj.Организация.А_ПереносЕРП
            print(f"    Организация.А_ПереносЕРП: {S(если_перенос)}")
        except:
            pass
    except Exception as e:
        print(f"    ERR: {e}")

