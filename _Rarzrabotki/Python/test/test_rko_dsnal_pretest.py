"""Pre-test SQL (Rule #-1): валидация Локализации-1 для ДенежныеСредстваНаличные.

Имитирует SQL новой ветки UNION ALL — должен дать 12 строк per СтрПредпр,
одну Кассу, детальную СтатьюДДС, Σ=348800 для РКО N0000052986.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q_doc = erp.NewObject("Запрос")
q_doc.Text = "ВЫБРАТЬ Д.Ссылка КАК Сс, Д.ХозяйственнаяОперация КАК ХО ИЗ Документ.РасходныйКассовыйОрдер КАК Д ГДЕ Д.Номер = &Ном"
q_doc.SetParameter("Ном", "N0000052986")
docrow = q_doc.Execute().Выгрузить()[0]
ref = docrow.Сс
hozop = docrow.ХО
print(f"РКО: {S(hozop)}")

# Локализация-1 SQL — 1:1 как будет в BSL
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    1 КАК НомерСтроки,
    ДанныеДокумента.Дата КАК Период,
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) КАК ВидДвижения,
    ДанныеДокумента.Организация КАК Организация,
    ДанныеДокумента.Касса КАК Касса,
    Рш.Подразделение.А_Подразделение КАК Подразделение,
    ДанныеДокумента.ХозяйственнаяОперация КАК ХозяйственнаяОперация,
    Рш.СтатьяДвиженияДенежныхСредств КАК СтатьяДвиженияДенежныхСредств,
    НЕОПРЕДЕЛЕНО КАК ОбъектРасчетов,
    НЕОПРЕДЕЛЕНО КАК АналитикаУчетаПоПартнерам,
    СУММА(Рш.КВыплате) КАК Сумма,
    СУММА(ВЫРАЗИТЬ(Рш.КВыплате * 1 КАК ЧИСЛО(31,2))) КАК СуммаРегл,
    СУММА(ВЫРАЗИТЬ(Рш.КВыплате * 1 КАК ЧИСЛО(31,2))) КАК СуммаУпр
ИЗ
    Документ.РасходныйКассовыйОрдер КАК ДанныеДокумента
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
            ПО Рш.Ссылка = ДанныеДокумента.Ведомость
ГДЕ
    ДанныеДокумента.Ссылка = &Ссылка
    И ТИПЗНАЧЕНИЯ(ДанныеДокумента.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу)
    И ДанныеДокумента.ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаздатчиком),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику))
СГРУППИРОВАТЬ ПО
    ДанныеДокумента.Дата,
    ДанныеДокумента.Организация,
    ДанныеДокумента.Касса,
    Рш.Подразделение.А_Подразделение,
    ДанныеДокумента.ХозяйственнаяОперация,
    Рш.СтатьяДвиженияДенежныхСредств
УПОРЯДОЧИТЬ ПО Подразделение
"""
q.SetParameter("Ссылка", ref)
try:
    rows = q.Execute().Выгрузить()
    print(f"\nПолучено строк: {rows.Количество()}")
    total = 0
    касса_set = set()
    подр_set = set()
    дсс_set = set()
    for r in rows:
        касса_set.add(S(r.Касса))
        подр_set.add(S(r.Подразделение))
        дсс_set.add(S(r.СтатьяДвиженияДенежныхСредств))
        total += float(r.Сумма)
        print(f"  {S(r.Подразделение):<32} | {S(r.Касса):<25} | {S(r.СтатьяДвиженияДенежныхСредств):<25} | {float(r.Сумма):>10,.2f}")

    assert rows.Количество() == 12, f"Ожидаем 12 строк per СтрПредпр, получили {rows.Количество()}"
    assert len(касса_set) == 1, f"Ожидаем 1 Касса, получили {len(касса_set)}: {касса_set}"
    assert len(подр_set) == 12, f"Ожидаем 12 СтрПредпр, получили {len(подр_set)}"
    assert "Оплата за выполненные работы" not in дсс_set, f"FAIL: общая статья: {дсс_set}"
    assert abs(total - 348800.0) < 0.01, f"FAIL: Σ != 348800, фактически {total}"

    print(f"\n✅ Pretest PASS: 12 строк, {len(подр_set)} СтрПредпр, {len(касса_set)} Касса, СтатьиДДС={дсс_set}, Σ={total:,.2f}")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")
    raise
