import sys
import win32com.client
import pythoncom
from datetime import datetime

CONN_STR = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def connect():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONN_STR)
    print("Підключення до BaseERP — OK")
    return conn


def find_contragent_by_dept_name(conn, dept_name):
    """Знайти контрагента по назві підрозділу"""
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 1"
        "   К.Ссылка КАК Ссылка,"
        "   К.Наименование КАК Наименование,"
        "   К.Партнер КАК Партнер"
        " ИЗ Справочник.Контрагенты КАК К"
        " ГДЕ К.Наименование = &Наименование"
        "   И НЕ К.ПометкаУдаления"
    )
    q.УстановитьПараметр("Наименование", dept_name)

    res = q.Выполнить()
    sel = res.Выбрать()
    if sel.Следующий():
        return {
            'Ссылка': sel.Ссылка,
            'Наименование': sel.Наименование,
            'Партнер': sel.Партнер,
        }
    return None


def find_partner_by_dept_name(conn, dept_name):
    """Знайти партнера по назві підрозділу"""
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 1"
        "   П.Ссылка КАК Ссылка,"
        "   П.Наименование КАК Наименование"
        " ИЗ Справочник.Партнеры КАК П"
        " ГДЕ П.Наименование = &Наименование"
        "   И НЕ П.ПометкаУдаления"
    )
    q.УстановитьПараметр("Наименование", dept_name)

    res = q.Выполнить()
    sel = res.Выбрать()
    if sel.Следующий():
        return sel.Ссылка
    return None


def find_existing_vzaimozachet(conn, doc_osnov_ref):
    """Знайти існуючий ВзаимозачетЗадолженности по А_ДокументОснованиеДляБаланса"""
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ"
        "   Док.Ссылка КАК Ссылка,"
        "   Док.Номер КАК Номер,"
        "   Док.Дата КАК Дата,"
        "   Док.Проведен КАК Проведен,"
        "   Док.КонтрагентДебитор КАК Дебитор,"
        "   Док.КонтрагентКредитор КАК Кредитор,"
        "   Док.СуммаРегл КАК СуммаРегл"
        " ИЗ Документ.ВзаимозачетЗадолженности КАК Док"
        " ГДЕ Док.А_ДокументОснованиеДляБаланса = &ДокОснование"
        "   И НЕ Док.ПометкаУдаления"
    )
    q.УстановитьПараметр("ДокОснование", doc_osnov_ref)

    res = q.Выполнить()
    sel = res.Выбрать()
    if sel.Следующий():
        return {
            'Ссылка': sel.Ссылка,
            'Номер': sel.Номер,
            'Дата': sel.Дата,
            'Проведен': sel.Проведен,
            'Дебитор': str(sel.Дебитор),
            'Кредитор': str(sel.Кредитор),
            'СуммаРегл': float(sel.СуммаРегл) if sel.СуммаРегл else 0,
        }
    return None


def find_dogovor(conn, contragent_ref, dept_ref):
    """Знайти договір по контрагенту та підрозділу"""
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 5"
        "   Д.Ссылка КАК Ссылка,"
        "   Д.Наименование КАК Наименование,"
        "   Д.ТипДоговора КАК ТипДоговора,"
        "   Д.Подразделение КАК Подразделение"
        " ИЗ Справочник.ДоговорыКонтрагентов КАК Д"
        " ГДЕ Д.Контрагент = &Контрагент"
        "   И НЕ Д.ПометкаУдаления"
    )
    q.УстановитьПараметр("Контрагент", contragent_ref)

    res = q.Выполнить()
    sel = res.Выбрать()
    contracts = []
    while sel.Следующий():
        contracts.append({
            'Ссылка': sel.Ссылка,
            'Наименование': sel.Наименование,
            'ТипДоговора': str(sel.ТипДоговора),
            'Подразделение': str(sel.Подразделение) if conn.ЗначениеЗаполнено(sel.Подразделение) else "",
        })
    return contracts


def main():
    conn = connect()

    date_from = datetime(2025, 12, 1)
    date_to = datetime(2025, 12, 31, 23, 59, 59)

    # === Тест 1: Пошук контрагентів по назвах підрозділів ===
    print("\n" + "=" * 60)
    print("ТЕСТ 1: Пошук контрагентів по назвах підрозділів")
    print("=" * 60)

    for dept_name in ["Глобино-2", "КМД-2", "ЦО", "Астарта. Тищенки"]:
        result = find_contragent_by_dept_name(conn, dept_name)
        if result:
            partner_name = ""
            if conn.ЗначениеЗаполнено(result['Партнер']):
                partner_name = result['Партнер'].Наименование
            print(f"  '{dept_name}' -> Контрагент: {result['Наименование']}, Партнер: {partner_name}")
        else:
            # Спробуємо знайти партнера напряму
            partner = find_partner_by_dept_name(conn, dept_name)
            if partner:
                print(f"  '{dept_name}' -> Контрагент НЕ знайдено, але Партнер знайдено: {partner.Наименование}")
            else:
                print(f"  '{dept_name}' -> НЕ знайдено ні контрагента ні партнера")

    # === Тест 2: Пошук існуючого ВзаимозачетЗадолженности ===
    print("\n" + "=" * 60)
    print("ТЕСТ 2: Пошук існуючого Взаємозаліку по А_ДокументОснованиеДляБаланса")
    print("=" * 60)

    # Знайти ПеремещениеТоваров ІБ00-001591
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ Док.Ссылка ИЗ Документ.ПеремещениеТоваров КАК Док"
        " ГДЕ Док.Номер ПОДОБНО &Номер И Док.Дата МЕЖДУ &Нач И &Кон"
    )
    q.УстановитьПараметр("Номер", "%001591%")
    q.УстановитьПараметр("Нач", date_from)
    q.УстановитьПараметр("Кон", date_to)
    res = q.Выполнить()
    sel = res.Выбрать()

    if sel.Следующий():
        doc_ref = sel.Ссылка
        print(f"  Документ-основание: {doc_ref}")

        vzaimozachet = find_existing_vzaimozachet(conn, doc_ref)
        if vzaimozachet:
            print(f"  Знайдено Взаємозалік: №{vzaimozachet['Номер']} від {vzaimozachet['Дата']}")
            print(f"    Проведен: {vzaimozachet['Проведен']}")
            print(f"    Дебитор: {vzaimozachet['Дебитор']}")
            print(f"    Кредитор: {vzaimozachet['Кредитор']}")
            print(f"    СуммаРегл: {vzaimozachet['СуммаРегл']:.2f}")
        else:
            print("  Взаємозалік НЕ знайдено — потрібно створювати")
    else:
        print("  Документ-основание не знайдено")

    # === Тест 3: Пошук договорів ===
    print("\n" + "=" * 60)
    print("ТЕСТ 3: Пошук договорів по контрагентах")
    print("=" * 60)

    for dept_name in ["Глобино-2", "КМД-2"]:
        result = find_contragent_by_dept_name(conn, dept_name)
        if result:
            contracts = find_dogovor(conn, result['Ссылка'], None)
            print(f"\n  Контрагент '{dept_name}': {len(contracts)} договорів")
            for c in contracts[:3]:  # показати перші 3
                print(f"    {c['Наименование']} | Тип: {c['ТипДоговора']} | Підрозділ: {c['Подразделение']}")

    # === Тест 4: Перевірити що Взаємозалік 000Ц-000001 має правильне А_ДокументОснованиеДляБаланса ===
    print("\n" + "=" * 60)
    print("ТЕСТ 4: Перевірити зв'язок 000Ц-000001 -> ІБ00-001591")
    print("=" * 60)

    q2 = conn.NewObject("Запрос")
    q2.Текст = (
        "ВЫБРАТЬ"
        "   Док.Ссылка,"
        "   Док.А_ДокументОснованиеДляБаланса"
        " ИЗ Документ.ВзаимозачетЗадолженности КАК Док"
        " ГДЕ Док.Номер ПОДОБНО &Номер"
    )
    q2.УстановитьПараметр("Номер", "%000Ц-000001%")
    res2 = q2.Выполнить()
    sel2 = res2.Выбрать()
    if sel2.Следующий():
        dok_osn = sel2.А_ДокументОснованиеДляБаланса
        if conn.ЗначениеЗаполнено(dok_osn):
            print(f"  000Ц-000001.А_ДокументОснованиеДляБаланса = {dok_osn}")
        else:
            print("  А_ДокументОснованиеДляБаланса ПОРОЖНІЙ!")

    print("\n=== Тести завершено ===")


if __name__ == "__main__":
    main()
