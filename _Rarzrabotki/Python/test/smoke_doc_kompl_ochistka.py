# -*- coding: utf-8 -*-
"""Smoke: РасчетКомплектаций — очистка целевых документов, которым расчёт не дал строк.

Дефект (найден заказчиком 25.08.2026): карта заполнения строилась лениво — документ без
строк в новом расчёте вообще не перезаписывался, оставался со СТАРОЙ ТЧ и проводился
устаревшим составом. Фикс: карта предсоздаётся для ВСЕХ целевых документов активных
режимов; пустой состав -> ТЧ очищается, проведённый документ распроводится (Результат.Очищено).

Сценарий (scratch, ничего не удаляем, не проводим):
  A: понаднорма заявлена -> КН Додаткова заполнена (N строк);
  B: вся понаднорма снята (КоличествоКСписанию = 0) -> КН Додаткова ОЧИЩЕНА (главная проверка);
  C: понаднорма возвращена -> КН Додаткова снова заполнена.
"""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import datetime
import win32com.client

MARKER = "SMOKE_DOC_KOMPL_v1"

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String

провалов = 0


def проверка(имя, условие, деталь=""):
    global провалов
    if not условие:
        провалов += 1
    print(f"  [{'OK  ' if условие else 'FAIL'}] {имя}" + (f" — {деталь}" if деталь else ""))



def выровнять_документ(ref, row):
    """Контроль складу документа (28.09.2026): документ у рядку «Документи» має склад і організацію рядка.
    Scratch-документ вирівнюємо під рядок (запис БЕЗ проведення)."""
    uid = lambda x: buh.String(x.УникальныйИдентификатор())
    obj = ref.ПолучитьОбъект()
    змінено = False
    if uid(obj.Склад) != uid(row.Склад):
        obj.Склад = row.Склад
        змінено = True
    if buh.ЗначениеЗаполнено(row.Организация) and uid(obj.Организация) != uid(row.Организация):
        obj.Организация = row.Организация
        змінено = True
    if змінено:
        obj.Записать()

def find_by_comment(doc_type, marker):
    q = buh.NewObject("Запрос")
    q.Text = (f"ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Документ.{doc_type} КАК Д "
              "ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК Строка(200)) = &М И НЕ Д.ПометкаУдаления")
    q.SetParameter("М", marker)
    r = q.Execute().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() > 0 else None


def get_or_create_target(doc_type, marker, org):
    ref = find_by_comment(doc_type, marker)
    if ref is not None:
        return ref
    d = getattr(buh.Документы, doc_type).СоздатьДокумент()
    d.Дата = datetime.datetime.now().replace(microsecond=0)
    d.Организация = org
    d.Комментарий = marker
    d.Записать()
    return d.Ссылка


ref = find_by_comment("РасчетКомплектаций", MARKER)
assert ref is not None, "сначала прогнать smoke_doc_kompl_analiz.py"
doc = ref.ПолучитьОбъект()
assert doc.СписаниеПоНормам.Количество() > 0 and doc.СписаниеСверхНормы.Количество() > 0

qorg = buh.NewObject("Запрос")
qorg.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК Ссылка ИЗ Справочник.Организации КАК О ГДЕ НЕ О.ПометкаУдаления"
org = qorg.Execute().Выгрузить().Получить(0).Ссылка

kn_norm = get_or_create_target("КомплектацияНоменклатуры", MARKER + "_КН_НОРМ", org)
kn_over = get_or_create_target("КомплектацияНоменклатуры", MARKER + "_КН_ПОНАД", org)
mal_norm = get_or_create_target("ПередачаМалоценныхАктивовВЭксплуатацию", MARKER + "_МАЛ_НОРМ", org)
mal_over = get_or_create_target("ПередачаМалоценныхАктивовВЭксплуатацию", MARKER + "_МАЛ_ПОНАД", org)

for i in range(doc.ДокументиКомплектації.Количество()):
    row = doc.ДокументиКомплектації.Получить(i)
    row.ДокументПоНормам = kn_norm
    row.ДокументДодаткова = kn_over
    выровнять_документ(kn_norm, row)
    выровнять_документ(kn_over, row)
for i in range(doc.ДокументиМалоценки.Количество()):
    row = doc.ДокументиМалоценки.Получить(i)
    row.ДокументПоНормам = mal_norm
    row.ДокументДодаткова = mal_over
    выровнять_документ(mal_norm, row)
    выровнять_документ(mal_over, row)


def задать_понаднорму(доля_количества):
    for i in range(doc.СписаниеСверхНормы.Количество()):
        row = doc.СписаниеСверхНормы.Получить(i)
        row.КоличествоКСписанию = row.Количество if доля_количества else 0


def строк(ref, малоценка=False):
    obj = ref.ПолучитьОбъект()
    return (obj.МалоценныеАктивы if малоценка else obj.Комплектующие).Количество()


print("=== A. Понаднорма заявлена -> Додаткова заполнена ===")
задать_понаднорму(True)
res = doc.ЗаполнитьДокументыПоАнализу(True, True)
проверка("без ошибок", res.Помилки.Количество() == 0)
n_a = строк(kn_over)
проверка("КН Додаткова заполнена", n_a > 0, f"строк={n_a}")
проверка("малоценка без остатков сч.22 -> оба мал-документа ОЧИЩЕНЫ (Очищено=2)",
         res.Очищено == 2 and строк(mal_norm, True) == 0 and строк(mal_over, True) == 0,
         f"Очищено={res.Очищено}")
проверка("флаги ПоНорме проставлены и пустым мал-документам",
         bool(mal_norm.ПоНорме) is True and bool(mal_over.ПоНорме) is False)

print("=== B. Понаднорма снята (КоличествоКСписанию = 0) -> Додаткова ОЧИЩЕНА ===")
задать_понаднорму(False)
res = doc.ЗаполнитьДокументыПоАнализу(True, True)
проверка("без ошибок", res.Помилки.Количество() == 0)
n_b = строк(kn_over)
проверка("ГЛАВНАЯ: КН Додаткова очищена (раньше оставалась со старыми строками)",
         n_b == 0, f"строк={n_b}")
проверка("КН ПоНормам по-прежнему заполнена", строк(kn_norm) > 0)
проверка("Очищено=3 (КН Додаткова + 2 мал), Заповнено=1",
         res.Очищено == 3 and res.Заповнено == 1,
         f"Очищено={res.Очищено}, Заповнено={res.Заповнено}")

print("=== C. Понаднорма возвращена -> Додаткова снова заполнена ===")
задать_понаднорму(True)
res = doc.ЗаполнитьДокументыПоАнализу(True, True)
проверка("без ошибок", res.Помилки.Количество() == 0)
n_c = строк(kn_over)
проверка("КН Додаткова восстановлена", n_c == n_a, f"строк={n_c} (было {n_a})")

doc.Записать()
print(f"\nПРОВАЛОВ: {провалов}")
print("OCHISTKA " + ("PASS" if провалов == 0 else "FAIL"))
sys.exit(1 if провалов else 0)
