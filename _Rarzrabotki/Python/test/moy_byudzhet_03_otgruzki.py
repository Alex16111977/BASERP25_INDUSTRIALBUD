# -*- coding: utf-8 -*-
"""Аудит п.3: факт отгрузок домов и металла (реальная дата — документ ЕРП А_ОтгрузкаПродукции).

ТЧ «ДоставкаДомов» мертва (0 строк во всех документах), поэтому дома — по реквизиту КоличествоДомов
(рейсы «Доставка модулів/модкуля»), металл — документы цеха «Цех металлоконструкций»
(КоличествоДокумента = тонны, СуммаДокумента = тонны × 32 900). Заказчик -> проект.
Вывод: data/otgruzki.json (все рейсы с датой, проектом, домами, тоннами, суммой).
"""
import collections
from moy_byudzhet_common import *

pm, root = projects()
erp = conn()
t = query("""ВЫБРАТЬ Д.Дата КАК Дата, Д.Номер КАК Номер, Д.Проведен КАК Пров, Д.Подразделение.Наименование КАК Цех,
    Д.Заказчик КАК Зак, Д.КоличествоДомов КАК Домов, Д.КоличествоДокумента КАК Кол, Д.СуммаДокумента КАК Сумма,
    ВЫРАЗИТЬ(Д.НазваниеЗаказа КАК СТРОКА(150)) КАК Заказ
ИЗ Документ.А_ОтгрузкаПродукции КАК Д
ГДЕ НЕ Д.ПометкаУдаления И Д.Дата >= &Н
УПОРЯДОЧИТЬ ПО Д.Дата""", Н=dt(2026, 1, 1))
out = []
for i in range(t.Количество()):
    r = t.Получить(i)
    zu = uid(r.Зак) if erp.ЗначениеЗаполнено(r.Зак) else ""
    p = pm.get(zu)
    if not p:
        continue
    цех = S(r.Цех).strip()
    out.append({"date": ymd(r.Дата), "num": S(r.Номер).strip(), "posted": bool(r.Пров), "shop": цех,
                "proj": p["uid"], "projname": p["name"], "houses": float(r.Домов),
                "tonnes": float(r.Кол) if цех == "Цех металлоконструкций" else 0.0,
                "sum": float(r.Сумма), "order": S(r.Заказ).strip()})
save("otgruzki.json", {"stamp": snapshot_stamp(), "rows": out})
agg = collections.defaultdict(lambda: [0.0, 0.0])
for x in out:
    agg[(x["projname"], x["date"][:7])][0] += x["houses"]
    agg[(x["projname"], x["date"][:7])][1] += x["tonnes"]
print("Отгрузки: проект | месяц | домов | тонн")
for k, v in sorted(agg.items()):
    if v[0] or v[1]:
        print(f"  {k[0]:<26} {k[1]}  {v[0]:>4.0f} {v[1]:>9.3f}")
