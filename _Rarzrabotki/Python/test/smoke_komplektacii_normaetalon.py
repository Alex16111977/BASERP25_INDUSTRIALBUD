# Приклад «Профнастил»: норма еталона = 210 (а не 120, як було при Σ НормаНоменкл).
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
обр = buh.ВнешниеОбработки.Создать(EPF, False)
обр.Период = datetime.datetime(2026, 7, 7)
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000004").Ссылка
вс = buh.Справочники.Склады.Выбрать()
while вс.Следующий():
    if "СТІЛ МД МХП ОРІЛЬ" in вс.Наименование and "виробнич" in вс.Наименование:
        обр.СкладыОстатков.Добавить().Склад = вс.Ссылка
for код in ("20", "22", "28"):
    обр.СчетаОстатков.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код).Ссылка
обр.РассчитатьАнализ()
тд = обр.СформироватьПечатьАнализСС(обр.ТабличнаяЧастьОстатков)
h, w = тд.ВысотаТаблицы, тд.ШиринаТаблицы

def cell(r, c): return str(тд.Область(r, c, r, c).Текст).strip()

# знайти колонки «Згідно СС» і «В нормі»
col_сс = col_вн = None
for r in range(1, min(h, 8) + 1):
    for c in range(1, w + 1):
        if cell(r, c) == "Згідно з СС": col_сс = c
        if cell(r, c) == "В нормі": col_вн = c
assert col_сс and col_вн, f"не знайдено заголовки (СС={col_сс}, ВН={col_вн})"

def num(s):
    s = s.replace("\xa0", "").replace(" ", "").replace(",", ".")
    return float(s) if s else None

# Норма ПО КАРТЦІ: еталон Профнастил=210 (Σ), ПС-10=120, Профіль ПК-20=90, субститут «Профілі сталеві»=0/порожньо.
рядки = {}
for r in range(1, h + 1):
    name = cell(r, 1)
    if name in ("Профнастил", "Профнастил ПС-10", "Профіль ПК-20") and name not in рядки:
        рядки[name] = r
    elif name.startswith("Профілі сталеві") and "субститут" not in рядки:
        рядки["субститут"] = r
for k in ("Профнастил", "Профнастил ПС-10", "Профіль ПК-20", "субститут"):
    assert k in рядки, f"не знайдено рядок '{k}'"
сс_etalon = num(cell(рядки["Профнастил"], col_сс))
сс_ps10 = num(cell(рядки["Профнастил ПС-10"], col_сс))
сс_pk20 = num(cell(рядки["Профіль ПК-20"], col_сс))
сс_sub_raw = cell(рядки["субститут"], col_сс)
сс_sub = num(сс_sub_raw)
print(f"Еталон Профнастил Згідно СС={сс_etalon}; ПС-10={сс_ps10}; Профіль ПК-20={сс_pk20}; субститут='{сс_sub_raw}'")
assert сс_etalon == 210.0, f"еталон-підсумок має бути 210 (Σ по картках), отримано {сс_etalon}"
assert сс_ps10 == 120.0, f"Профнастил ПС-10 норма має бути 120, отримано {сс_ps10}"
assert сс_pk20 == 90.0, f"Профіль ПК-20 (норм-картка без залишку) норма має бути 90, отримано {сс_pk20}"
assert сс_sub in (None, 0.0), f"субститут (не в нормах) має бути 0/порожньо, отримано '{сс_sub_raw}'"
print("PASS: норма ПО КАРТЦІ — ПС-10=120, Профіль ПК-20=90, субститут=0; еталон Σ=210")
