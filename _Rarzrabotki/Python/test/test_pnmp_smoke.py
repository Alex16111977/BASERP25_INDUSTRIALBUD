# -*- coding: utf-8 -*-
"""bas-verify smoke для А_ПередачаНачисленийМеждуПодразделениями (read-only).
   1) метаданные: формы зарегистрированы, осн. формы заданы;
   2) запрос ОбработкаПроведения 1:1 как в BSL — выполняется без ошибок;
   3) если есть проведённые документы — Σ движений ПАП = 0 (net-zero инвариант)."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# --- 1. Метаданные: формы и осн. формы ---
МД = erp.Метаданные.Документы.Найти("А_ПередачаНачисленийМеждуПодразделениями")
if МД is None:
    print("FAIL: документ не найден в метаданных")
    sys.exit(1)
формы = [f.Имя for f in МД.Формы]
оф = erp.String(МД.ОсновнаяФормаОбъекта)
осл = erp.String(МД.ОсновнаяФормаСписка)
print(f"OK метаданные: формы={формы}; ОснФормаОбъекта={оф}; ОснФормаСписка={осл}")
assert "ФормаДокумента" in формы and "ФормаСписка" in формы, "формы не зарегистрированы"

# --- 2. Запрос из ОбработкаПроведения 1:1 (Rule #-1) на фиктивной ссылке ---
q = erp.NewObject("Запрос")
СтОТ      = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Оплата труда")
СтНалоги  = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Налоги")
СтПрочПас = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Прочие пассивы")
print(f"OK статьи: ОТ={erp.ЗначениеЗаполнено(СтОТ)} Налоги={erp.ЗначениеЗаполнено(СтНалоги)} ПрочПас={erp.ЗначениеЗаполнено(СтПрочПас)}")
q.УстановитьПараметр("Ссылка", erp.Документы.А_ПередачаНачисленийМеждуПодразделениями.ПустаяСсылка())
q.УстановитьПараметр("СтОТ", СтОТ)
q.УстановитьПараметр("СтНалоги", СтНалоги)
q.УстановитьПараметр("СтПрочПас", СтПрочПас)
q.Text = """
ВЫБРАТЬ &СтОТ КАК Статья, ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.ПустаяСсылка) КАК ТипНалога,
    Н.ИсходноеПодразделение КАК Исходное, Н.ЦелевоеПодразделение КАК Целевое, СУММА(Н.Сумма) КАК Сумма
ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Начисления КАК Н
ГДЕ Н.Ссылка = &Ссылка СГРУППИРОВАТЬ ПО Н.ИсходноеПодразделение, Н.ЦелевоеПодразделение
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ &СтНалоги, Нл.ТипНалога, Нл.ИсходноеПодразделение, Нл.ЦелевоеПодразделение, СУММА(Нл.Сумма)
ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Налоги КАК Нл
ГДЕ Нл.Ссылка = &Ссылка СГРУППИРОВАТЬ ПО Нл.ТипНалога, Нл.ИсходноеПодразделение, Нл.ЦелевоеПодразделение
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ &СтПрочПас, ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.ПустаяСсылка), У.ИсходноеПодразделение,
    У.ЦелевоеПодразделение, СУММА(У.Сумма)
ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Удержания КАК У
ГДЕ У.Ссылка = &Ссылка СГРУППИРОВАТЬ ПО У.ИсходноеПодразделение, У.ЦелевоеПодразделение
"""
try:
    res = q.Execute().Выгрузить()
    print(f"OK запрос ОбработкаПроведения выполнен, строк={res.Количество()}")
except Exception as e:
    msg = e.excepinfo[2] if getattr(e, 'excepinfo', None) else e
    print(f"FAIL запрос: {msg}")
    sys.exit(1)

# --- 3. Net-zero по существующим проведённым документам (если есть) ---
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ Д.Регистратор КАК Рег, СУММА(ВЫБОР КОГДА Д.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    ТОГДА Д.Сумма ИНАЧЕ -Д.Сумма КОНЕЦ) КАК Сальдо
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Д
ГДЕ ТИПЗНАЧЕНИЯ(Д.Регистратор) = ТИП(Документ.А_ПередачаНачисленийМеждуПодразделениями)
СГРУППИРОВАТЬ ПО Д.Регистратор
"""
try:
    t = q2.Execute().Выгрузить()
    n = t.Количество()
    if n == 0:
        print("INFO: проведённых документов этого типа в базе нет — net-zero проверять не на чем (норм для нового объекта)")
    else:
        плохо = 0
        for i in range(n):
            с = t.Получить(i).Сальдо
            if abs(с) > 0.01:
                плохо += 1
                print(f"  WARN регистратор {i}: Σ ПАП = {с} (ожидалось 0)")
        if плохо == 0:
            print(f"OK net-zero: {n} документ(ов), Σ движений ПАП = 0 у всех")
        else:
            print(f"FAIL net-zero: {плохо} из {n} документов с дисбалансом")
            sys.exit(1)
except Exception as e:
    msg = e.excepinfo[2] if getattr(e, 'excepinfo', None) else e
    print(f"FAIL net-zero запрос: {msg}")
    sys.exit(1)

print("=== SMOKE PASSED ===")
