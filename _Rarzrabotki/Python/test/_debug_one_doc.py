# -*- coding: utf-8 -*-
"""Трассировка ОДНОГО прихода: документ ПриобретениеТоваровУслуг -> его движения
по РегистрНакопления.СебестоимостьТоваров. Почему мой запрос не ловит часть прихода?"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def run(text, params=None):
    q = erp.NewObject("Запрос")
    q.Текст = text
    if params:
        for k, val in params.items():
            q.УстановитьПараметр(k, val)
    t = q.Выполнить().Выгрузить()
    names = [t.Колонки.Получить(j).Имя for j in range(t.Колонки.Количество())]
    rows = [[t.Получить(i).Получить(j) for j in range(len(names))] for i in range(t.Количество())]
    return names, rows

def pr(names, rows, limit=40):
    print("  " + " | ".join(names))
    for r in rows[:limit]:
        print("  " + " | ".join(str(x) for x in r))

# 1) Приходы для МД МХП ОРІЛЬ (берём самый крупный)
print("=" * 74, "\n1) Документы ПриобретениеТоваровУслуг для 'МД МХП ОРІЛЬ' (топ по сумме)\n", "=" * 74)
n1, r1 = run("""ВЫБРАТЬ ПЕРВЫЕ 8
    П.Ссылка КАК Ссылка,
    П.Номер КАК Номер,
    П.Дата КАК Дата,
    СУММА(Т.Сумма) КАК СуммаТовары
ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Т
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ПриобретениеТоваровУслуг КАК П ПО П.Ссылка = Т.Ссылка
ГДЕ П.Проведен И П.Подразделение.Наименование = "МД МХП ОРІЛЬ"
СГРУППИРОВАТЬ ПО П.Ссылка, П.Номер, П.Дата
УПОРЯДОЧИТЬ ПО СуммаТовары УБЫВ""")
pr(["Номер", "Дата", "СуммаТовары"], [[r[1], r[2], r[3]] for r in r1])
if not r1:
    print("НЕТ документов!"); sys.exit()
док = r1[0][0]
print(f"\n>>> Берём документ: Номер={r1[0][1]} Дата={r1[0][2]} СуммаТовары={r1[0][3]}")

# 2) ВСЕ движения этого документа по СебестоимостьТоваров (разбивка)
print("\n" + "=" * 74, "\n2) Движения этого документа в РН.СебестоимостьТоваров (все разделы/виды)\n", "=" * 74)
n2, r2 = run("""ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(СТ.ВидДвижения) КАК ВидДв,
    ПРЕДСТАВЛЕНИЕ(СТ.РазделУчета) КАК РазделУчета,
    ПРЕДСТАВЛЕНИЕ(СТ.Подразделение) КАК ПодрРеквизит,
    ПРЕДСТАВЛЕНИЕ(ВЫРАЗИТЬ(СТ.АналитикаФинансовогоУчета КАК Справочник.СтруктураПредприятия)) КАК ПодрАналитика,
    СУММА(СТ.Количество) КАК Кол,
    СУММА(СТ.СтоимостьБезНДС) КАК СтоимБезНДС,
    СУММА(СТ.Стоимость) КАК Стоим
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.Регистратор = &Док
СГРУППИРОВАТЬ ПО
    ПРЕДСТАВЛЕНИЕ(СТ.ВидДвижения), ПРЕДСТАВЛЕНИЕ(СТ.РазделУчета),
    ПРЕДСТАВЛЕНИЕ(СТ.Подразделение),
    ПРЕДСТАВЛЕНИЕ(ВЫРАЗИТЬ(СТ.АналитикаФинансовогоУчета КАК Справочник.СтруктураПредприятия))
УПОРЯДОЧИТЬ ПО СтоимБезНДС УБЫВ""", {"Док": док})
pr(n2, r2)

# 3) Что ловит мой ТЕКУЩИЙ фильтр для этого документа
print("\n" + "=" * 74, "\n3) Что захватывает текущий запрос (ВидДв=Приход, РазделУчета=ТоварыНаСкладах, Подр-реквизит В план)\n", "=" * 74)
n3, r3 = run("""ВЫБРАТЬ
    СУММА(СТ.СтоимостьБезНДС) КАК СтоимБезНДС_ловится
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.Регистратор = &Док
    И СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
    И СТ.Подразделение В (ВЫБРАТЬ РАЗЛИЧНЫЕ СС.Подразделение ИЗ Справочник.А_СтруктураСебестоимости КАК СС ГДЕ НЕ СС.ПометкаУдаления)""", {"Док": док})
pr(n3, r3)

# 4) Весь Приход документа по регистру (без фильтров подр/раздел)
print("\n" + "=" * 74, "\n4) Весь Приход документа по регистру (только ВидДвижения=Приход)\n", "=" * 74)
n4, r4 = run("""ВЫБРАТЬ
    СУММА(СТ.СтоимостьБезНДС) КАК Приход_СтоимБезНДС,
    СУММА(СТ.Стоимость) КАК Приход_Стоим,
    СУММА(СТ.Количество) КАК Приход_Кол
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.Регистратор = &Док
    И СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)""", {"Док": док})
pr(n4, r4)
