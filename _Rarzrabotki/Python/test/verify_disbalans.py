# -*- coding: utf-8 -*-
# Verify-запросы для миграции А_ОбработкаДисбалансаПоПодразделениям -> гибрид per-статья + cross-fallback.
# Гонится ДО и ПОСЛЕ массовых действий пользователя в UI Enterprise.
#
# Использование:
#   python verify_disbalans.py           # полный отчёт (вся история)
#   python verify_disbalans.py 2025-12   # только указанный месяц
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def exec_q(text, **params):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in params.items():
        q.УстановитьПараметр(k, v)
    return q.Execute().Выбрать()

период = None
if len(sys.argv) > 1:
    y, m = sys.argv[1].split("-")
    # Полдень + следующий месяц минус 1 секунда (известная гранка проекта: TZ-сдвиг при 00:00)
    нач = datetime.datetime(int(y), int(m), 1, 12, 0, 0)
    след_год = int(y) + (1 if int(m) == 12 else 0)
    след_мес = 1 if int(m) == 12 else int(m) + 1
    кон = datetime.datetime(след_год, след_мес, 1, 12, 0, 0) - datetime.timedelta(days=1)
    кон = кон.replace(hour=23, minute=59, second=59)
    период = (нач, кон)
    print(f"=== Период: {y}-{m} ===\n")
else:
    print("=== Период: ВСЯ ИСТОРИЯ авто-взаимозачётов ===\n")

# 1) Сводка по А_СтатьяДисбаланса (X-X vs cross-статья)
филььтр_дата = "И Док.Дата МЕЖДУ &Нач И &Кон" if период else ""
q1 = """
ВЫБРАТЬ
	ПРЕДСТАВЛЕНИЕ(Док.А_СтатьяДисбалансаПоПодразделению) КАК Статья,
	КОЛИЧЕСТВО(*) КАК Кол,
	СУММА(ВЫБОР КОГДА Док.Проведен ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Проведенных,
	СУММА(Док.СуммаРегл) КАК Сумма
ИЗ Документ.ВзаимозачетЗадолженности КАК Док
ГДЕ Док.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО
	И НЕ Док.ПометкаУдаления
	{}
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Док.А_СтатьяДисбалансаПоПодразделению)
""".format(филььтр_дата)

print("--- (1) Сводка по статьям дисбаланса ---")
params = {"Нач": период[0], "Кон": период[1]} if период else {}
s = exec_q(q1, **params)
xx = cross = 0
while s.Следующий():
    тип = "X-X" if s.Статья and " - " in s.Статья and s.Статья.split(" - ")[0] == s.Статья.split(" - ")[1] else "cross"
    if тип == "X-X": xx += s.Кол
    else: cross += s.Кол
    print(f"  [{тип:5}] {s.Статья!r:60} кол={s.Кол:5} провед={s.Проведенных:5} Σ={s.Сумма:>14.2f}")
print(f"  ВСЕГО: X-X={xx}, cross={cross}\n")

# 2) Документы-основания, у которых ВСЕ статьи дают X-X (чистые переносы)
# vs у которых есть cross (Приобретение/Списание/смешанные)
print("--- (2) Типы оснований (первые 30) ---")
q2 = """
ВЫБРАТЬ
	ВЫРАЗИТЬ(Док.А_ДокументОснованиеДляБаланса КАК Документ.А_ПередачаНачисленийМеждуПодразделениями).Ссылка КАК Передача,
	ВЫРАЗИТЬ(Док.А_ДокументОснованиеДляБаланса КАК Документ.ПриобретениеУслугПрочихАктивов).Ссылка КАК Приобрет,
	ВЫРАЗИТЬ(Док.А_ДокументОснованиеДляБаланса КАК Документ.СписаниеНедостачТоваров).Ссылка КАК Списание,
	КОЛИЧЕСТВО(*) КАК Кол
ИЗ Документ.ВзаимозачетЗадолженности КАК Док
ГДЕ Док.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО И НЕ Док.ПометкаУдаления {}
СГРУППИРОВАТЬ ПО ВЫРАЗИТЬ(Док.А_ДокументОснованиеДляБаланса КАК Документ.А_ПередачаНачисленийМеждуПодразделениями).Ссылка,
	ВЫРАЗИТЬ(Док.А_ДокументОснованиеДляБаланса КАК Документ.ПриобретениеУслугПрочихАктивов).Ссылка,
	ВЫРАЗИТЬ(Док.А_ДокументОснованиеДляБаланса КАК Документ.СписаниеНедостачТоваров).Ссылка
""".format(филььтр_дата.replace("Док.Дата", "Док.Дата"))
s = exec_q(q2, **params)
типы = {"Передача": 0, "Приобретение": 0, "Списание": 0, "Прочие": 0}
n = 0
while s.Следующий():
    if erp.ЗначениеЗаполнено(s.Передача): типы["Передача"] += s.Кол
    elif erp.ЗначениеЗаполнено(s.Приобрет): типы["Приобретение"] += s.Кол
    elif erp.ЗначениеЗаполнено(s.Списание): типы["Списание"] += s.Кол
    else: типы["Прочие"] += s.Кол
    n += 1
for k, v in типы.items():
    print(f"  {k}: {v} взаимозачётов")

# 3) Дубли пары (Основа, КонтрДт, КонтрКт) — должны исчезнуть после миграции
print("\n--- (3) Дубли (Основа, КонтрДт, КонтрКт) — >1 взаимозачёта на одну пару ---")
q3 = """
ВЫБРАТЬ
	ПРЕДСТАВЛЕНИЕ(Док.А_ДокументОснованиеДляБаланса) КАК Основание,
	ПРЕДСТАВЛЕНИЕ(Док.КонтрагентДебитор) КАК КонтрДт,
	ПРЕДСТАВЛЕНИЕ(Док.КонтрагентКредитор) КАК КонтрКт,
	КОЛИЧЕСТВО(*) КАК Кол
ИЗ Документ.ВзаимозачетЗадолженности КАК Док
ГДЕ Док.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО И НЕ Док.ПометкаУдаления {}
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Док.А_ДокументОснованиеДляБаланса),
	ПРЕДСТАВЛЕНИЕ(Док.КонтрагентДебитор), ПРЕДСТАВЛЕНИЕ(Док.КонтрагентКредитор)
ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1
""".format(филььтр_дата)
s = exec_q(q3, **params)
дубли = 0
while s.Следующий():
    дубли += 1
    if дубли <= 10:
        print(f"  {s.Основание} | {s.КонтрДт} <- {s.КонтрКт} | кол={s.Кол}")
if дубли == 0: print("  (нет дублей пары — четвёрка-дедуп работает или база чистая)")
elif дубли > 10: print(f"  ... ещё {дубли - 10}")

# 4) Дубли четвёркой (Основа, КонтрДт, КонтрКт, Статья) — НЕ должно быть НИКОГДА
print("\n--- (4) Дубли ЧЕТВЁРКОЙ — НИКОГДА не должно быть ---")
q4 = """
ВЫБРАТЬ
	Док.А_ДокументОснованиеДляБаланса КАК Осн, Док.КонтрагентДебитор КАК КДт,
	Док.КонтрагентКредитор КАК ККт, Док.А_СтатьяДисбалансаПоПодразделению КАК Статья,
	КОЛИЧЕСТВО(*) КАК Кол
ИЗ Документ.ВзаимозачетЗадолженности КАК Док
ГДЕ Док.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО И НЕ Док.ПометкаУдаления {}
СГРУППИРОВАТЬ ПО Док.А_ДокументОснованиеДляБаланса, Док.КонтрагентДебитор,
	Док.КонтрагентКредитор, Док.А_СтатьяДисбалансаПоПодразделению
ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1
""".format(филььтр_дата)
s = exec_q(q4, **params)
дубли4 = 0
while s.Следующий(): дубли4 += 1
print(f"  Дублей четвёркой: {дубли4} {'OK' if дубли4 == 0 else 'FAIL'}")

print("\n=== ГОТОВО ===")
