    строки_лимита = []
    итог_лимита = 0.0
    for п in подразделения:
        сумма, комментарий = лимит(п)
        if сумма is not None:
            итог_лимита += сумма
        строки_лимита.append((п["Имя"], сумма, комментарий))
    строки_лимита.sort(key=lambda с: (-1 if с[1] is None else -с[1], с[0]))

    ч.append('<h2>Плановый лимит по направлению «Производство»</h2>')
    ч.append('<table><thead><tr><th>Подразделение</th><th>Лимит, грн</th>'
             '<th>Комментарий</th></tr></thead><tbody>')
