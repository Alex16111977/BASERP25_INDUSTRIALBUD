ЛИСТ_ФИНОТЧЁТА = "24,07,2026"          # имя устарело и не меняется от недели к неделе
NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"

# Короткое имя подразделения для секций, где его нет в скобках
КОРОТКИЕ_ИМЕНА = {
    "Глобино-2": "Глобино",
    "ПрАТ \"ОРІЛЬ-ЛІДЕР\"": "МД МХП ОРІЛЬ",
}


def деньги(значение, ноль="0,00"):
    if значение is None:
        return ноль
    if abs(значение) < 0.005:
        return ноль
    return f"{значение:,.2f}".replace(",", " ").replace(".", ",")


def процент(значение):
    return f"{значение:,.2f}".replace(",", " ").replace(".", ",") + " %"


def html_экран(текст):
    # кавычки НЕ экранируем: имена объектов идут в тексте, а не в атрибутах,
    # и «ПАТ &quot;Кривий Ріг Цемент&quot;» плохо читается при копировании из HTML
    return текст.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def ключ_секции(имя):
    """Ключ сопоставления секций между неделями: 14.08 «МД IRC 2026» = 07.08 «МД IRS 2026»."""
    к = re.sub(r"\s+", " ", имя).strip().lower()
    к = к.replace("«", "").replace("»", "").replace('"', "")
    return к.replace("irs", "irc")


# ---------------------------------------------------------------- финотчёт

def секции_финотчёта(путь):
    """Строки-объекты листа «24,07,2026» в порядке файла.

    Объект = ЖИРНАЯ строка (кроме «Итого»). Отступы ячейки A в файле обнулены
    пересохранением, поэтому правило промта «indent = 0» не работает: по нему в итог
    попадают и договоры, и выходит 11,2 млн вместо 5,6 млн.
    Строка-контрагент, идущая сразу под объектом и повторяющая его E/F/H/K
    («АСТАРТА АГРО ПРОТЕЇН ТОВ» под «Глобино-2»), отсеивается — иначе итог задваивается.
    """
    ws = openpyxl.load_workbook(путь, data_only=True)[ЛИСТ_ФИНОТЧЁТА]

    def ч(r, c):
        v = ws.cell(r, c).value
        return float(v) if isinstance(v, (int, float)) else 0.0

    сырые = []
    for r in range(1, ws.max_row + 1):
        ячейка = ws.cell(r, 1)
        имя = " ".join(str(ячейка.value).split()) if ячейка.value else ""
        if not имя or not ячейка.font.bold:
            continue
        if имя.lower().startswith(("итого", "разом", "объект", "заказчик")):
            continue
        строка = {"r": r, "Имя": имя, "C": ч(r, 3), "E": ч(r, 5), "F": ч(r, 6),
                  "G": ч(r, 7), "H": ч(r, 8), "K": ч(r, 11)}
        if not any(строка[к] for к in ("C", "E", "F", "G", "H", "K")):
            continue
        сырые.append(строка)

    объекты = []
    for строка in сырые:
        предыдущая = объекты[-1] if объекты else None
        дубль = (предыдущая is not None
                 and строка["r"] - предыдущая["r"] == 1
                 and all(abs(строка[к] - предыдущая[к]) < 0.005
                         for к in ("E", "F", "H", "K")))
        if дубль:
            continue
        объекты.append(строка)
    return объекты


def подпись_объекта(имя):
    короткое = КОРОТКИЕ_ИМЕНА.get(имя)
    return f"{имя} ({короткое})" if короткое else имя


def состояние_актов(о):
    """Формулировка состояния по правилам промта (признака подписания в отчёте нет)."""
    if о["H"] > 0.005:
        return "поданы, не подписаны"
    if о["K"] > 0.005:
        return "все акты подписаны"
    if о["G"] > 0.005:
        return f"новых актов нет, задолженность заказчика {деньги(о['G'])}"
    if о["G"] < -0.005:
        return f"новых актов нет, предоплата {деньги(-о['G'])}"
    if abs(о["E"] - о["F"]) < 0.005 and о["E"] > 0.005:
        return "расчёты закрыты"
    return "движений нет"


def фраза_объекта(о, было):
    """Абзац по объекту: сумма к получению, состояние актов, что изменилось за неделю."""
    имя = html_экран(подпись_объекта(о["Имя"]))
    начало = f'<b>{имя}</b> — сумма к получению <b class="k num">{деньги(о["K"])}</b>'

    if о["H"] > 0.005:
        хвост = f', акты поданы на {деньги(о["H"])} и не подписаны'
    elif о["K"] > 0.005:
        хвост = ", все акты подписаны"
    elif о["G"] > 0.005:
        хвост = f", новых актов нет; задолженность заказчика {деньги(о['G'])}"
    elif о["G"] < -0.005:
        хвост = f", новых актов нет, предоплата {деньги(-о['G'])}"
    elif abs(о["E"] - о["F"]) < 0.005 and о["E"] > 0.005:
        хвост = f", расчёты закрыты: выполнено и оплачено по {деньги(о['E'])}"
    else:
        хвост = ", движений нет"

    изменения = []
    if было is not None:
        dE, dF, dH, dK = (о[к] - было[к] for к in ("E", "F", "H", "K"))
        if dF > 0.005:
            изменения.append(f"за неделю получено {деньги(dF)}")
        if dE > 0.005:
            изменения.append(f"подписаны акты на {деньги(dE)}")
        if dH > 0.005:
            изменения.append(f"подано новых актов на {деньги(dH)}")
        elif dH < -0.005 and о["H"] > 0.005:
            # прошлые акты ушли в подписанные (dE ≈ прошлому H), значит текущее H — новые
            изменения.append(f"подано новых актов на {деньги(о['H'])}")
        if dK < -0.005:
            изменения.append(f"сумма к получению снизилась с {деньги(было['K'])}")
        elif dK > 0.005:
            изменения.append(f"сумма к получению выросла с {деньги(было['K'])}")

    if изменения:
        хвост += ". " + ", ".join(изменения).capitalize()
    return начало + хвост + "."


# ---------------------------------------------------------------- план-факт

def план_факт(путь):
    """Прямой разбор zip+XML: 1С пишет xl/SharedStrings.xml с ЗАГЛАВНОЙ S, openpyxl падает.

    Строка «МД IRC 2026» встречается дважды (свёртка и сама) — берём строки
    ДО первого повтора имени, иначе затраты задваиваются.
    """
    z = zipfile.ZipFile(путь)
    имя_строк = next((n for n in z.namelist() if n.lower() == "xl/sharedstrings.xml"), None)
    строки = []
    if имя_строк:
        for si in ET.fromstring(z.read(имя_строк)).findall(f"{NS}si"):
            строки.append("".join(t.text or "" for t in si.iter(f"{NS}t")))

    имя_листа = next(n for n in z.namelist() if re.match(r"xl/worksheets/sheet1\.xml$", n))
    корень = ET.fromstring(z.read(имя_листа))

    def значение(c):
        v = c.find(f"{NS}v")
        if v is None or v.text is None:
            return None
        if c.get("t") == "s":
            return строки[int(v.text)]
        try:
            return float(v.text)
        except ValueError:
            return v.text

    подразделения, итог, встреченные = [], None, set()
    набор_закрыт = False   # после первого повтора имени идут дочерние строки свёртки
    for row in корень.iter(f"{NS}row"):
        ячейки = {}
        for c in row.findall(f"{NS}c"):
            ячейки[re.match(r"([A-Z]+)", c.get("r")).group(1)] = значение(c)
        имя = ячейки.get("A")
        if not isinstance(имя, str) or not имя.strip():
            continue
        имя = " ".join(имя.split())
        числа = {к: (ячейки.get(к) if isinstance(ячейки.get(к), float) else None)
                 for к in ("D", "F", "G", "I", "J", "K", "M", "N")}
        if имя == "Разом":
            итог = числа
            break                        # итог — последняя строка листа
        if имя in ("Подразделение", "Відбір:"):
            continue
        if имя in встреченные:
            набор_закрыт = True          # дальше только дочерние — их не берём,
            continue                     # но лист дочитываем ради строки «Разом»
        if набор_закрыт:
            continue
        встреченные.add(имя)
        подразделения.append({"Имя": имя, **числа})
    return подразделения, итог


def лимит(п):
    """Правило лимита из доклада 10.08 (порядок проверок важен)."""
    M, F = п["M"], п["F"]
    if M is None:
        return None, "маржа в отчёте не определена"
    if M < -0.005:
        return -M, "отрицательная маржа"
    if F and F > 0.005:
        return F, f"есть приход денег на {деньги(F)}"
    return 0.0, "положительная маржа и нет прихода"


