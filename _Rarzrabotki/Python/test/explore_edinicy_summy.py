# -*- coding: utf-8 -*-
"""Разведка под суммы + единицы измерения: ресурсы Хозрасчетный, единицы номенклатуры/спецификации,
коэффициенты приведения к базовой единице."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

def типы(р):
    return ", ".join(buh.String(t) for t in р.Тип.Типы())

print("=== Хозрасчетный РЕСУРСЫ (есть ли Сумма) ===")
for р in buh.Метаданные.РегистрыБухгалтерии.Хозрасчетный.Ресурсы:
    print(f"   {р.Имя}: {типы(р)}")

print("=== Номенклатура: реквизиты-единицы ===")
for р in buh.Метаданные.Справочники.Номенклатура.Реквизиты:
    if "диниц" in р.Имя or "Единиц" in р.Имя or "Одиниц" in р.Имя:
        print(f"   {р.Имя}: {типы(р)}")

print("=== СтруктураСебестоимости.Комплектующие: Единица + Сумма ===")
тч = buh.Метаданные.Справочники.СтруктураСебестоимости.ТабличныеЧасти.Найти("Комплектующие")
for р in тч.Реквизиты:
    print(f"   {р.Имя}: {типы(р)}")

print("=== Справочники единиц измерения в конфигурации ===")
for с in buh.Метаданные.Справочники:
    n = с.Имя
    if "диницы" in n or "диниць" in n or "ЕдиницИзмерения" in n or "ОдиницьВиміру" in n or "Упаковки" in n:
        реквы = [r.Имя for r in с.Реквизиты]
        print(f"   Справочник.{n}: реквизиты={реквы}")

print("=== Пример: номенклатура с остатком 2051 -> её базовая единица + коэффициент ===")
q = buh.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ ПЕРВЫЕ 5 ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) КАК Ном
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(, Счет В ИЕРАРХИИ(&С), , ) КАК Ост
ГДЕ Ост.КоличествоОстаток > 0"""
q.УстановитьПараметр("С", buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("20"))
t = q.Выполнить().Выгрузить()
for i in range(t.Количество()):
    ном = t.Получить(i).Ном
    об = ном.ПолучитьОбъект() if not ном.Пустая() else None
    if об is None: continue
    # перечислим реквизиты-единицы объекта номенклатуры
    поля = {}
    for им in ("ЕдиницаИзмерения", "БазоваяЕдиницаИзмерения", "ЕдиницаХраненияОстатков", "ОдиницяВиміру"):
        try: поля[им] = buh.String(getattr(об, им))
        except Exception: pass
    print(f"   {buh.String(ном)[:34]} -> {поля}")
