def count_vt(prefix_parts, имя_вт, поля_ключа):
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НачМес", НМ)
    q.УстановитьПараметр("КонМес", КД); q.УстановитьПараметр("Искл", Искл)
    txt = "\n;\n".join(prefix_parts) + (
        f"\n;\nВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Всего, "
        f"КОЛИЧЕСТВО(РАЗЛИЧНЫЕ {поля_ключа}) КАК Уник "
        f"ИЗ {имя_вт}")
    q.Текст = txt
    r = q.Выполнить().Выбрать(); r.Следующий()
    return int(r.Всего), int(r.Уник)


