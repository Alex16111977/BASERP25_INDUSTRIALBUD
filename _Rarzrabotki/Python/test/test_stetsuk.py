# -*- coding: utf-8 -*-
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
conn_kazn = v8.Connect('Srvr="localhost";Ref="kazna";Usr="cfo";Pwd="2442"')
S = conn_kazn.String

# Check Stetsuk in Kazna БДДС for December 2025
q = conn_kazn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ
    БДДС.Регистратор КАК Рег,
    БДДС.СтатьяДвиженияДенежныхСредств КАК Статья,
    БДДС.Подразделение КАК Подр,
    БДДС.Сумма КАК Сумма,
    БДДС.Регистратор.Организация.ЕГРПОУ КАК ЕДРПОУ,
    БДДС.Регистратор.Организация.А_ПереносЕРП КАК ПереносЕРП
ИЗ РегистрНакопления.БДДС КАК БДДС
ГДЕ БДДС.Период МЕЖДУ &Н И &К
    И БДДС.Сотрудник.Наименование ПОДОБНО "%Стецюк%Тетяна%"
"""
q.SetParameter("Н", datetime.datetime(2025, 12, 1))
q.SetParameter("К", datetime.datetime(2025, 12, 31, 23, 59, 59))
r = q.Execute().Choose()

print("Стецюк в БДДС за грудень 2025:")
print("-" * 100)
total = 0
cnt = 0
while r.Next():
    rec = S(r.Рег)
    stat = S(r.Статья)
    dept = S(r.Подр)
    summ = float(S(r.Сумма).replace('\xa0', '').replace(' ', '').replace(',', '.'))
    edr = S(r.ЕДРПОУ)
    perenos = r.ПереносЕРП
    total += summ
    cnt += 1
    print(f"  [{rec[:50]:50s}] Статья=[{stat[:30]:30s}] Подр={dept[:15]:15s} Сум={summ:>10.2f} ЕДРПОУ={edr} Перенос={perenos}")

print(f"\nВсего: {cnt} строк, сумма={total:.2f}")

