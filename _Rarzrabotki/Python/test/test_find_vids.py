# Точний пошук видів розрахунку: "Оплата по окладу", "Штраф (упр)", "Штраф"
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# === ПланВидовРасчета.Начисления — шукаємо "Оплата по окладу" та "Штраф" ===
print("=" * 70)
print("ПланыВидовРасчета.Начисления")
print("=" * 70)
q = erp.NewObject("Запрос")
q.Text = (
    "ВЫБРАТЬ "
    "ВЫРАЗИТЬ(Н.Код КАК СТРОКА(20)) КАК Код, "
    "ВЫРАЗИТЬ(Н.Наименование КАК СТРОКА(100)) КАК Наименование, "
    "Н.Ссылка КАК Ссылка "
    "ИЗ ПланВидовРасчета.Начисления КАК Н "
    "ГДЕ (Н.Наименование ПОДОБНО \"Оплата по окладу%\" ИЛИ Н.Наименование ПОДОБНО \"%Штраф%\" ИЛИ Н.Код ПОДОБНО \"ОКЛ%\") "
    "И НЕ Н.ПометкаУдаления"
)
r = q.Execute().Выгрузить()
print(f"  Рядків: {r.Количество()}")
for i in range(r.Количество()):
    row = r.Получить(i)
    код = S(row.Код)
    print(f"    код='{код}' (len={len(код)}) наим='{S(row.Наименование)}'")

