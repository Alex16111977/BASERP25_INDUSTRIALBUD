def тест_множители(b):
    z = b.NewObject("Запрос")
    z.Текст = """
    ВЫБРАТЬ
    	СС.Наименование КАК СС,
    	ВЫБОР
    		КОГДА КОЛИЧЕСТВО(РАЗЛИЧНЫЕ П.Ссылка) = 0
    			ТОГДА 1
    		ИНАЧЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ П.Ссылка)
    	КОНЕЦ КАК Домиков
    ИЗ
    	Справочник.СтруктураСебестоимости КАК СС
    		ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Подразделения КАК Дочь
    		ПО Дочь.Родитель = СС.Подразделение
    			И Дочь.Наименование = СС.Наименование
    			И НЕ Дочь.ПометкаУдаления
    		ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Подразделения КАК П
    		ПО П.Родитель = ЕСТЬNULL(Дочь.Ссылка, СС.Подразделение)
    			И НЕ П.ПометкаУдаления
    ГДЕ
    	НЕ СС.ЭтоГруппа
    	И СС.Активная
    	И НЕ СС.ПометкаУдаления
    СГРУППИРОВАТЬ ПО
    	СС.Наименование
    """
    t = z.Выполнить().Выгрузить()
    факт = {t[i].СС: int(t[i].Домиков) for i in range(t.Количество())}
    assert факт == МНОЖИТЕЛИ, f"Множители домиков разошлись: {факт}"
    print("OK: множители домиков", факт)


def тест_суммы(b):
    z = b.NewObject("Запрос")
    z.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(1, 1, 1) КАК Н, КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2026, 7, 31), ДЕНЬ) КАК К"
    гр = z.Выполнить().Выгрузить()[0]

    z = b.NewObject("Запрос")
    z.Текст = """
    ВЫБРАТЬ РАЗЛИЧНЫЕ СС.Подразделение КАК Подр
    ИЗ Справочник.СтруктураСебестоимости КАК СС
    ГДЕ НЕ СС.ЭтоГруппа И СС.Активная И НЕ СС.ПометкаУдаления
    	И СС.Подразделение <> ЗНАЧЕНИЕ(Справочник.Подразделения.ПустаяСсылка)
    """
    зонтики = z.Выполнить().Выгрузить()

    зонтик = None
    for i in range(зонтики.Количество()):
        if зонтики[i].Подр.Наименование == "МД IRS 2026":
            зонтик = зонтики[i].Подр
    assert зонтик is not None, "Не найден зонтик «МД IRS 2026»"

    z = b.NewObject("Запрос")
    z.Текст = ТЕКСТ_ГРЕЙНА
    z.УстановитьПараметр("Зонтик", зонтик)
    z.УстановитьПараметр("НачП", гр.Н)
    z.УстановитьПараметр("КонП", гр.К)
    t = z.Выполнить().Выгрузить()

    план = sum(t[i].ПланГрн for i in range(t.Количество()))
    факт = sum(t[i].ФактГрн for i in range(t.Количество()))
    assert abs(план - ЭТАЛОН_ПЛАН_IRS) < 0.01, f"План IRS = {план:,.2f}, эталон {ЭТАЛОН_ПЛАН_IRS:,.2f}"
    assert abs(факт - ЭТАЛОН_ФАКТ_IRS) < 0.01, f"Факт IRS = {факт:,.2f}, эталон {ЭТАЛОН_ФАКТ_IRS:,.2f}"
