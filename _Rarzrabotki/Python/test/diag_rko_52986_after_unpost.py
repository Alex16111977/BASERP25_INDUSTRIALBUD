"""Проверка: после unpost РКО остаются ли движения в ПАП?"""
import sys, win32com.client
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Найти РКО, сделать unpost
qDoc = erp.NewObject("Запрос")
qDoc.Text = "ВЫБРАТЬ Д.Ссылка КАК Сс ИЗ Документ.РасходныйКассовыйОрдер КАК Д ГДЕ Д.Номер = &Н"
qDoc.SetParameter("Н", "N0000052986")
ssylka = qDoc.Execute().Выгрузить()[0].Сс

obj = ssylka.ПолучитьОбъект()
print(f"Проведен до unpost: {obj.Проведен}")
obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
print(f"Проведен после unpost: {obj.Проведен}")

# Сколько записей в ПАП для регистратора?
qPAP = erp.NewObject("Запрос")
qPAP.Text = """
ВЫБРАТЬ Р.Период, Р.ВидДвижения, Р.Подразделение, Р.НаправлениеДеятельности, Р.Статья, Р.Сумма, Р.ВидИсточника
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Р
ГДЕ Р.Регистратор = &Сс
УПОРЯДОЧИТЬ ПО Р.Сумма УБЫВ
"""
qPAP.SetParameter("Сс", ssylka)
r = qPAP.Execute().Выгрузить()
print(f"\nЗаписей ПАП после UNPOST: {r.Количество()}")
for row in r:
    print(f"  {erp.XMLСтрока(row.ВидДвижения):8} | {S(row.Статья):40} | Подр={S(row.Подразделение):30} | Направ={S(row.НаправлениеДеятельности):20} | {row.Сумма} | ВидИст={S(row.ВидИсточника)}")

print()
print("Теперь делаем POST")
# Перепровести
obj = ssylka.ПолучитьОбъект()
obj.Записать(erp.РежимЗаписиДокумента.Проведение)
print(f"Проведен после post: {obj.Проведен}")

# Сколько записей в ПАП теперь?
r2 = qPAP.Execute().Выгрузить()
print(f"\nЗаписей ПАП после POST: {r2.Количество()}")
for row in r2:
    print(f"  {erp.XMLСтрока(row.ВидДвижения):8} | {S(row.Статья):40} | Подр={S(row.Подразделение):30} | Направ={S(row.НаправлениеДеятельности):20} | {row.Сумма} | ВидИст={S(row.ВидИсточника)}")
