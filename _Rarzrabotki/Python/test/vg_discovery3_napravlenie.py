# -*- coding: utf-8 -*-
"""Discovery #3: заполненность Договор.А_НаправлениеОказаниеУслуг + раскладка по направлениям."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Д.А_НаправлениеОказаниеУслуг.Наименование КАК Направление,
    КОЛИЧЕСТВО(*) КАК Кол
ИЗ
    Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
    НЕ Д.ПометкаУдаления
    И Д.А_НаправлениеОказаниеУслуг <> ЗНАЧЕНИЕ(Справочник.НаправленияДеятельности.ПустаяСсылка)
СГРУППИРОВАТЬ ПО
    Д.А_НаправлениеОказаниеУслуг.Наименование
УПОРЯДОЧИТЬ ПО
    Кол УБЫВ
"""
r = q.Execute().Выгрузить()
всего = 0
print("Договоры с заполненным А_НаправлениеОказаниеУслуг:")
for i in range(r.Количество()):
    row = r.Получить(i)
    print(f"  {S(row.Направление)}: {row.Кол}")
    всего += row.Кол
print(f"ИТОГО: {всего}")

# сколько из них корпоративные (партнёр в _КОРПОРАТИВНІ)
корень = erp.Справочники.Партнеры.НайтиПоНаименованию("_КОРПОРАТИВНІ")
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ НЕ Д.ПометкаУдаления
    И Д.А_НаправлениеОказаниеУслуг <> ЗНАЧЕНИЕ(Справочник.НаправленияДеятельности.ПустаяСсылка)
    И Д.Партнер В ИЕРАРХИИ (&Корень)
"""
q2.SetParameter("Корень", корень)
r2 = q2.Execute().Выгрузить()
print(f"Из них с партнёром в _КОРПОРАТИВНІ: {r2.Получить(0).Кол}")
