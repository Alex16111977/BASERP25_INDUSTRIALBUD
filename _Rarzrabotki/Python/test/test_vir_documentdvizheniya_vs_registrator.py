"""
Перевірити: чому в А_ОтчетPL запит повертає Регистратор=None.
Гіпотеза: запит бере Выр.ДокументДвижения (окремий реквізит реєстру),
яке порожнє, замість системного Выр.Регистратор.
"""
import win32com.client
import sys
import datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Знайти підрозділ
q_podr = erp.NewObject("Запрос")
q_podr.Text = """
ВЫБРАТЬ Ссылка ИЗ Справочник.СтруктураПредприятия
ГДЕ Наименование = &Имя
"""
q_podr.SetParameter("Имя", "MAN №5 KA5697НВ")
podr = q_podr.Execute().Выгрузить().Получить(0).Ссылка

start = datetime.datetime(2026, 2, 1, 0, 0, 0)
# Розширимо період до 1 березня щоб не пропустити документ від 28.02 23:59:59
end = datetime.datetime(2026, 3, 1, 0, 0, 0)

# Запит обох полів
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Выр.Период                                  КАК Период,
    Выр.Регистратор                             КАК Регистратор,
    Выр.ДокументДвижения                        КАК ДокументДвижения,
    ТИПЗНАЧЕНИЯ(Выр.Регистратор)                КАК ТипРегистр,
    ТИПЗНАЧЕНИЯ(Выр.ДокументДвижения)           КАК ТипДокДв,
    Выр.СуммаВыручки                            КАК СуммаВыручки,
    Выр.Активность,
    ВЫБОР
        КОГДА Выр.Регистратор ССЫЛКА Документ.РеализацияТоваровУслуг
            ТОГДА ВЫРАЗИТЬ(Выр.Регистратор КАК Документ.РеализацияТоваровУслуг).Контрагент
        КОГДА Выр.Регистратор ССЫЛКА Документ.АктВыполненныхРабот
            ТОГДА ВЫРАЗИТЬ(Выр.Регистратор КАК Документ.АктВыполненныхРабот).Контрагент
        ИНАЧЕ ЗНАЧЕНИЕ(Справочник.Контрагенты.ПустаяСсылка)
    КОНЕЦ                                       КАК КонтрагентИзРегистратора,
    Выр.Регистратор.Представление               КАК ПредстРегистратора,
    Выр.ДокументДвижения.Представление          КАК ПредстДокДвижения
ИЗ РегистрНакопления.ВыручкаИСебестоимостьПродаж КАК Выр
ГДЕ Выр.Период МЕЖДУ &Нач И &Кон
    И Выр.Подразделение = &Подр
    И Выр.СуммаВыручки <> 0
УПОРЯДОЧИТЬ ПО Выр.Период
"""
q.SetParameter("Нач", start)
q.SetParameter("Кон", end)
q.SetParameter("Подр", podr)
r = q.Execute().Выгрузить()
print(f"Записів: {r.Количество()}")
total = 0.0
for i in range(r.Количество()):
    row = r.Получить(i)
    total += float(row.СуммаВыручки)
    reg_str = str(row.ПредстРегистратора) if row.ПредстРегистратора else "None"
    dd_str = str(row.ПредстДокДвижения) if row.ПредстДокДвижения else "None"
    contr_str = str(row.КонтрагентИзРегистратора) if row.КонтрагентИзРегистратора else "(пусто)"
    print(f"\n[{i+1}] Період: {row.Период}  Сума: {row.СуммаВыручки:>12,.2f}")
    print(f"    Регистратор (системний): {reg_str}")
    print(f"    ДокументДвижения (реквізит): {dd_str}")
    print(f"    Контрагент з Регистратора: {contr_str}")
print(f"\nИТОГО: {total:,.2f}")
