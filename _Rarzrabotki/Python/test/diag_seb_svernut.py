# -*- coding: utf-8 -*-
"""Эмуляция Отразить_Свод+Свернуть+Загрузить через COM.
Выполняем запрос, выгружаем в ТЗ, вызываем РЕАЛЬНЫЙ .Свернуть(...) (как
оркестратор), затем ищем дубли по 7 значащим измерениям, используя
ЗначениеВСтрокуВнутр (точное 1С-равенство, не XMLСтрока).
"""
import sys, io
from collections import defaultdict
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qb = conn.NewObject("Запрос")
qb.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qb.УстановитьПараметр("М", M); rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ, КД = rb.НМ, rb.КД
qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка КАК Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for n in ("Собственные средства", "Доходы текущего периода",
          "Расходы текущего периода"):
    имена.Добавить(n)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
Искл = conn.NewObject("Массив")
for i in range(tI.Количество()):
    Искл.Добавить(tI.Получить(i).Ссылка)

q = conn.NewObject("Запрос")
q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НачМес", НМ)
q.УстановитьПараметр("КонМес", КД); q.УстановитьПараметр("Искл", Искл)
q.Текст = open(
    r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test"
    r"\_seb_query_text.txt", encoding="utf-8").read()
t = q.Выполнить().Выгрузить()
до = t.Количество()
print(f"строк ДО Свернуть = {до}")

# реальный Свернуть, как в оркестраторе (по тем полям что есть в ТЗ)
t.Свернуть("Организация,Подразделение,Статья,Номенклатура,Склад,Source,"
           "Расхождение",
           "СуммаНачальныйОстаток,СуммаПриход,СуммаРасход,СуммаКонечныйОстаток")
после = t.Количество()
print(f"строк ПОСЛЕ Свернуть(7 изм) = {после}  (схлопнуто {до - после})")

# дубли по точному 1С-равенству значений (ЗначениеВСтрокуВнутр)
grp = defaultdict(list)
for i in range(после):
    r = t.Получить(i)
    key = "|".join(conn.ЗначениеВСтрокуВнутр(v) for v in (
        r.Организация, r.Подразделение, r.Статья, r.Номенклатура,
        r.Склад, r.Source, r.Расхождение))
    grp[key].append(i)
dups = {k: v for k, v in grp.items() if len(v) > 1}
print(f"дублей по ЗначениеВСтрокуВнутр(7) ПОСЛЕ Свернуть = {len(dups)}")
showed = 0
for k, idxs in dups.items():
    if showed >= 6:
        break
    showed += 1
    print(f"\n--- ДУБЛЬ x{len(idxs)} ---")
    for j in idxs[:4]:
        r = t.Получить(j)
        print(f"  Подр='{r.Подразделение}' "
              f"XML={conn.XMLСтрока(r.Подразделение)} | "
              f"ВнутрПодр={conn.ЗначениеВСтрокуВнутр(r.Подразделение)[:60]}")
        print(f"  Ном='{r.Номенклатура}' Склад='{r.Склад}' "
              f"Статья='{r.Статья}' Расх={bool(r.Расхождение)} "
              f"НО={float(r.СуммаНачальныйОстаток or 0):,.2f} "
              f"КО={float(r.СуммаКонечныйОстаток or 0):,.2f}")

# Доп: сравнить XMLСтрока-ключ vs Внутр-ключ ДО свёртки
t2 = q.Выполнить().Выгрузить()
xmlk = defaultdict(int)
intk = defaultdict(int)
for i in range(t2.Количество()):
    r = t2.Получить(i)
    xmlk[(conn.XMLСтрока(r.Организация), conn.XMLСтрока(r.Подразделение),
          conn.XMLСтрока(r.Статья), conn.XMLСтрока(r.Номенклатура),
          conn.XMLСтрока(r.Склад), conn.XMLСтрока(r.Source),
          str(bool(r.Расхождение)))] += 1
    intk["|".join(conn.ЗначениеВСтрокуВнутр(v) for v in (
        r.Организация, r.Подразделение, r.Статья, r.Номенклатура,
        r.Склад, r.Source, r.Расхождение))] += 1
print(f"\nДО Свёртки: уник XML-ключей={len(xmlk)} "
      f"уник Внутр-ключей={len(intk)} всего={t2.Количество()}")
print(f"дублей по XML={sum(1 for c in xmlk.values() if c>1)} "
      f"по Внутр={sum(1 for c in intk.values() if c>1)}")
