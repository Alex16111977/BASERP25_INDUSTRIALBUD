"""
Тест: Перевірка логіки створення А_ОказаниеУслугМеждуПодразделениями з А_АрендаТехники.
НЕ створює документи — тільки перевіряє що дані доступні і логіка коректна.
"""
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

print("=== Тест: А_АрендаТехники -> А_ОказаниеУслугМеждуПодразделениями ===\n")

# 1. Перевірка довідкових даних
print("1. Перевірка довідкових даних:")
q = conn.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ Код, Наименование ИЗ ПланВидовХарактеристик.СтатьиРасходов ГДЕ Код = "00-000024"'
res = q.Выполнить().Выбрать()
if res.Следующий():
    print(f"  OK: СтатьяЗатрат = {res.Наименование} (код {res.Код})")
else:
    print("  ПОМИЛКА: Стаття затрат 00-000024 не знайдена!")

q2 = conn.NewObject("Запрос")
q2.Текст = 'ВЫБРАТЬ Код, Наименование ИЗ Справочник.СтатьиДвиженияДенежныхСредств ГДЕ Код = "УТ-001130"'
res2 = q2.Выполнить().Выбрать()
if res2.Следующий():
    print(f"  OK: СДД = {res2.Наименование} (код {res2.Код})")
else:
    print("  ПОМИЛКА: СДД УТ-001130 не знайдена!")

q3 = conn.NewObject("Запрос")
q3.Текст = 'ВЫБРАТЬ Код, Наименование ИЗ Справочник.Номенклатура ГДЕ Код = "0Ц-00000002"'
res3 = q3.Выполнить().Выбрать()
if res3.Следующий():
    print(f"  OK: Номенклатура = {res3.Наименование} (код {res3.Код})")
else:
    print("  ПОМИЛКА: Номенклатура 0Ц-00000002 не знайдена!")

# 2. Перевірка документа А_АрендаТехники 76 (зі скріншота)
print("\n2. Дані документа А_АрендаТехники 000000076:")
q4 = conn.NewObject("Запрос")
q4.Текст = '''ВЫБРАТЬ
    Состав.Подразделение.Наименование КАК Продавец,
    Состав.ПодразделениеЗаказчик.Наименование КАК Покупатель,
    Состав.Сумма КАК Сум,
    Состав.СтороннийЗаказчик КАК Сторонний
ИЗ Документ.А_АрендаТехники.Состав КАК Состав
ГДЕ Состав.Ссылка.Номер = "000000076"'''

res4 = q4.Выполнить().Выбрать()
total = 0
count = 0
skip = 0
while res4.Следующий():
    count += 1
    if res4.Сторонний:
        skip += 1
        continue
    if res4.Сум == 0:
        skip += 1
        continue
    total += res4.Сум
    print(f"  {count}. {res4.Продавец} -> {res4.Покупатель} = {res4.Сум:,.2f}")

print(f"\n  Всього рядків: {count}, пропущено: {skip}, для ОказаниеУслуг: {count-skip}")
print(f"  Сума документа: {total:,.2f}")

# 3. Перевірка чи є вже А_ОказаниеУслугМеждуПодразделениями з АрендаТехники
print("\n3. Існуючі А_ОказаниеУслугМеждуПодразделениями з АрендаТехники:")
q5 = conn.NewObject("Запрос")
q5.Текст = '''ВЫБРАТЬ
    Номер, Дата, Проведен,
    АрендаТехники.Номер КАК НомерАренды,
    СуммаДокумента КАК Сума
ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями
ГДЕ АрендаТехники <> ЗНАЧЕНИЕ(Документ.А_АрендаТехники.ПустаяСсылка)
УПОРЯДОЧИТЬ ПО Дата УБЫВ'''

res5 = q5.Выполнить().Выбрать()
found = False
while res5.Следующий():
    found = True
    print(f"  Номер={res5.Номер} Дата={res5.Дата} Проведен={res5.Проведен} Аренда={res5.НомерАренды} Сума={res5.Сума:,.2f}")

if not found:
    print("  Немає (ще не створювались) — це нормально, код ще не запускався")

print("\n=== Тест завершено ===")
