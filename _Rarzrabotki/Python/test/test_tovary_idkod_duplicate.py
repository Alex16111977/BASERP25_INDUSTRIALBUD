# -*- coding: utf-8 -*-
"""
Проверка: почему при выборе "Кутик внутр на плінтус низький №201"
обработка показывает "Кут для плінтуса зов".

Гипотеза: два товара в ERP имеют одинаковый А_ИдКод.
"""

import win32com.client
import pythoncom

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")

    print("=== ERP ===")
    conn_erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

    # 1. Найти А_ИдКод для "Кутик внутр на плінтус низький №201"
    q = conn_erp.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ Н.Ссылка, Н.Наименование, Н.А_ИдКод, Н.Код "
        "ИЗ Справочник.Номенклатура КАК Н "
        "ГДЕ Н.Наименование ПОДОБНО &Имя"
    )
    q.УстановитьПараметр("Имя", "%Кутик внутр на плінтус низький%201%")
    sel = q.Выполнить().Выбрать()
    idkod = ""
    while sel.Следующий():
        idkod = str(sel.А_ИдКод).strip()
        print(f"Целевой товар: {sel.Наименование}")
        print(f"  Код: {sel.Код}")
        print(f"  А_ИдКод: {idkod}")

    if not idkod:
        print("Товар не найден!")
        return

    # 2. Найти ВСЕ товары с таким же А_ИдКод в ERP
    print(f"\n--- ВСЕ товары в ERP с А_ИдКод = '{idkod}' ---")
    q2 = conn_erp.NewObject("Запрос")
    q2.Текст = (
        "ВЫБРАТЬ Н.Ссылка, Н.Наименование, Н.Код, Н.А_ИдКод, Н.ТипНоменклатуры "
        "ИЗ Справочник.Номенклатура КАК Н "
        "ГДЕ Н.А_ИдКод = &ИдКод"
    )
    q2.УстановитьПараметр("ИдКод", idkod)
    sel2 = q2.Выполнить().Выбрать()
    erp_items = []
    while sel2.Следующий():
        erp_items.append({
            'ref': sel2.Ссылка,
            'name': str(sel2.Наименование),
            'code': str(sel2.Код),
            'type': str(sel2.ТипНоменклатуры),
        })
        print(f"  {sel2.Наименование} | Код: {sel2.Код} | Тип: {sel2.ТипНоменклатуры}")

    print(f"\n  ИТОГО в ERP: {len(erp_items)} товаров с одинаковым А_ИдКод!")

    # 3. Проверить остатки в ТоварыНаСкладах для каждого
    import pywintypes
    from datetime import datetime
    print(f"\n--- Остатки в ТоварыНаСкладах (дек 2025) ---")
    for item in erp_items:
        q3 = conn_erp.NewObject("Запрос")
        q3.Текст = (
            "ВЫБРАТЬ "
            "  ПРЕДСТАВЛЕНИЕ(Т.Склад) КАК Склад, "
            "  Т.ВНаличииКонечныйОстаток КАК КонОст "
            "ИЗ РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты("
            "  &Нач, &Кон, , , Номенклатура = &Ном) КАК Т"
        )
        q3.УстановитьПараметр("Нач", pywintypes.Time(datetime(2025, 12, 1)))
        q3.УстановитьПараметр("Кон", pywintypes.Time(datetime(2025, 12, 31, 23, 59, 59)))
        q3.УстановитьПараметр("Ном", item['ref'])
        sel3 = q3.Выполнить().Выбрать()
        has_balance = False
        while sel3.Следующий():
            has_balance = True
            print(f"  {item['name'][:50]:50s} | {sel3.Склад[:30]:30s} | Кон={sel3.КонОст}")
        if not has_balance:
            print(f"  {item['name'][:50]:50s} | НЕТ остатков в ТоварыНаСкладах")

    # 4. Проверить в BuhBud
    print(f"\n=== BuhBud ===")
    conn_buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

    print(f"--- ВСЕ товары в BuhBud с А_ИдКод = '{idkod}' ---")
    q4 = conn_buh.NewObject("Запрос")
    q4.Текст = (
        "ВЫБРАТЬ Н.Наименование, Н.Код, Н.А_ИдКод "
        "ИЗ Справочник.Номенклатура КАК Н "
        "ГДЕ Н.А_ИдКод = &ИдКод"
    )
    q4.УстановитьПараметр("ИдКод", idkod)
    sel4 = q4.Выполнить().Выбрать()
    buh_count = 0
    while sel4.Следующий():
        buh_count += 1
        print(f"  {sel4.Наименование} | Код: {sel4.Код}")
    print(f"  ИТОГО в BuhBud: {buh_count} товаров с одинаковым А_ИдКод!")

    print(f"\n=== ВЫВОД ===")
    if len(erp_items) > 1:
        print(f"  ПРОБЛЕМА: {len(erp_items)} товаров в ERP имеют одинаковый А_ИдКод = '{idkod}'")
        print(f"  Обработка сравнивает по А_ИдКод, поэтому данные СМЕШИВАЮТСЯ")
        print(f"  Нужно исправить А_ИдКод — он должен быть уникальным для каждого товара!")
    else:
        print(f"  А_ИдКод уникален в ERP — проблема в другом")

    pythoncom.CoUninitialize()

if __name__ == "__main__":
    main()
