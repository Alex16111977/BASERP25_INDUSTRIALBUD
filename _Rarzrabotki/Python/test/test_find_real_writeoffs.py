# -*- coding: utf-8 -*-
"""
Найти правильные документы Списание безналичных ДС от 28.12.2025
по Контрагент=Глобино-2 — посмотреть их РасшифровкаПлатежа.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты ГДЕ Наименование = "Глобино-2"'
контр = q.Выполнить().Выгрузить().Получить(0).Ссылка

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Контр", контр)
q.УстановитьПараметр("Д1", datetime.datetime(2025, 12, 28, 0, 0, 0))
q.УстановитьПараметр("Д2", datetime.datetime(2025, 12, 28, 23, 59, 59))
q.Текст = """
ВЫБРАТЬ
    Док.Ссылка КАК Ссылка
ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Док
ГДЕ Док.Контрагент = &Контр И Док.Дата МЕЖДУ &Д1 И &Д2
УПОРЯДОЧИТЬ ПО Док.Дата
"""
r = q.Выполнить().Выгрузить()
print(f"Найдено Списаний 28.12.2025 по Контр=Глобино-2: {r.Количество()}\n")

for i in range(r.Количество()):
    док = r.Получить(i).Ссылка
    obj = док.ПолучитьОбъект()
    print("=" * 110)
    print(f"  {S(док)}")
    print(f"  Номер={obj.Номер}, Дата={obj.Дата.strftime('%d.%m.%Y %H:%M:%S')}, Сумма={obj.СуммаДокумента}")
    print(f"  ХозОперация={S(obj.ХозяйственнаяОперация)}")
    print(f"  Контрагент={S(obj.Контрагент)}  Партнёр={S(obj.Партнер)}")
    дог_шапка = obj.Договор
    if дог_шапка is None:
        print("  Договор шапка: '(None — реквизит не заполнен)'")
    elif дог_шапка.Пустая():
        print("  Договор шапка: '(ПУСТО — ПустаяСсылка)'")
    else:
        print(f"  Договор шапка: '{S(дог_шапка)}'")
    print(f"  Подразделение={S(obj.Подразделение)}")
    try:
        д_осн = obj.А_ОказаниеУслугМеждуПодразделениями
        print(f"  Док-основание (А_ОказаниеУслуг): {S(д_осн) if not д_осн.Пустая() else '(пусто)'}")
    except:
        print("  Док-основание: реквизит отсутствует")
    print(f"  РасшифровкаПлатежа ({obj.РасшифровкаПлатежа.Количество()} строк):")
    for j in range(obj.РасшифровкаПлатежа.Количество()):
        рп = obj.РасшифровкаПлатежа.Получить(j)
        ор = рп.ОбъектРасчетов
        ор_str = "*** ПУСТОЙ ***" if ор.Пустая() else S(ор)
        дог = рп.А_Договор if hasattr(рп, 'А_Договор') else None
        дог_str = S(дог) if (дог and not дог.Пустая()) else "(пусто)"
        print(f"    Строка #{j+1}: Партнёр={S(рп.Партнер)}, Сумма={рп.Сумма}, СуммаВзаим={рп.СуммаВзаиморасчетов}")
        print(f"      ОбъектРасчетов: {ор_str}")
        print(f"      А_Договор:       {дог_str}")
