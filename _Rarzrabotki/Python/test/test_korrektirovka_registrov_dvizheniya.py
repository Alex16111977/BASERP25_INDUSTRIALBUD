def run(text, params=None):
    q = erp.NewObject("Запрос")
    q.Text = text
    if params:
        for k, v in params.items():
            q.SetParameter(k, v)
    try:
        return q.Execute().Выгрузить()
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"FAIL: {e.excepinfo[2]}")
        else:
            print(f"FAIL: {e}")
        return None

