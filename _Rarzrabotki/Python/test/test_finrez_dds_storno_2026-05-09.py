def run_query(text, params):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in params.items():
        q.SetParameter(k, v)
    try:
        return q.Execute().Выгрузить()
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        print(f"FAIL: {msg}")
        traceback.print_exc()
        return None


def print_table(tz, columns, max_rows=50):
    if tz is None:
        return
    cnt = tz.Количество()
    print(" | ".join(c[:18].ljust(18) for c in columns))
    print("-" * (21 * len(columns)))
    for i in range(min(cnt, max_rows)):
        row = tz.Получить(i)
        cells = []
        for c in columns:
            v = getattr(row, c, None)
            if c.lower().startswith("сумма"):
                cells.append(fmt(v if v is not None else 0))
            elif c == "Регистратор":
                cells.append(fmt(S(v).split(",")[0] if v else "", 50))
            else:
                cells.append(fmt(S(v) if v else "", 18))
        print(" | ".join(cells))
    print(f"Σ rows = {cnt}")


