# -*- coding: utf-8 -*-
"""Дамп ПАП движений 4-х документов + РегРасчётов 000006370 в одной картине."""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def найти(тип, номер, дата_от=None, дата_до=None):
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Номер", номер)
    where = "ГДЕ Д.Номер = &Номер"
    if дата_от and дата_до:
        qq.УстановитьПараметр("Д1", дата_от)
        qq.УстановитьПараметр("Д2", дата_до)
        where += " И Д.Дата МЕЖДУ &Д1 И &Д2"
    qq.Текст = f'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.{тип} КАК Д {where} УПОРЯДОЧИТЬ ПО Д.Дата'
    r = qq.Выполнить().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() else None


доки = [
    ("ПоступлениеБезналичныхДенежныхСредств", "000Ц-000109",
     datetime.datetime(2025, 12, 16), datetime.datetime(2025, 12, 17), "Поступление 664К"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000288",
     datetime.datetime(2025, 12, 28), datetime.datetime(2025, 12, 29), "Возврат 664К"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000286",
     datetime.datetime(2025, 12, 28), datetime.datetime(2025, 12, 29), "Возврат 5.2М"),
    ("СписаниеБезналичныхДенежныхСредств", "000Ц-000287",
     datetime.datetime(2025, 12, 28), datetime.datetime(2025, 12, 29), "Возврат 2М"),
    ("РегистраторРасчетов", "000006370",
     datetime.datetime(2026, 3, 27), datetime.datetime(2026, 3, 28), "РР 000006370 от 27.03.2026"),
]

for тип, номер, д1, д2, метка in доки:
    print(f"\n{'='*100}", flush=True)
    док = найти(тип, номер, д1, д2)
    if not док:
        print(f"{метка}: НЕ НАЙДЕН", flush=True)
        continue
    print(f"{метка}: {S(док)}", flush=True)
    # ПАП движения
    qq = erp.NewObject("Запрос")
    qq.УстановитьПараметр("Рег", док)
    qq.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ВидДвижения) КАК ВД,
    ПРЕДСТАВЛЕНИЕ(Р.Статья) КАК Статья,
    ПРЕДСТАВЛЕНИЕ(Р.Подразделение) КАК Подр,
    ПРЕДСТАВЛЕНИЕ(Р.Источник) КАК Источник,
    ПРЕДСТАВЛЕНИЕ(ВЫРАЗИТЬ(Р.Аналитика КАК Справочник.ОбъектыРасчетов)) КАК Аналит_ОР,
    Р.Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Р
ГДЕ Р.Регистратор = &Рег
УПОРЯДОЧИТЬ ПО Р.Период
"""
    try:
        r = qq.Выполнить().Выгрузить()
        print(f"  ПАП: {r.Количество()} строк", flush=True)
        for i in range(r.Количество()):
            rec = r.Получить(i)
            ан = str(rec.Аналит_ОР).strip() if str(rec.Аналит_ОР).strip() else "(аналит пуст)"
            print(f"    {str(rec.ВД):<8} | {str(rec.Статья)[:35]:<35} | {str(rec.Подр)[:14]:<14} | Ист={str(rec.Источник)[:28]:<28} | Аналит_ОР={ан[:40]:<40} | Σ={float(rec.Сумма):>13,.2f}", flush=True)
    except Exception as e:
        print(f"  ПАП ERR: {e}", flush=True)

    # РасчетыСКлиентамиПоСрокам
    qq.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ВидДвижения) КАК ВД,
    ПРЕДСТАВЛЕНИЕ(Р.ОбъектРасчетов) КАК ОР,
    Р.ДолгРегл, Р.ПредоплатаРегл
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
ГДЕ Р.Регистратор = &Рег
"""
    try:
        r = qq.Выполнить().Выгрузить()
        print(f"  РасчСКлПоСр: {r.Количество()} строк", flush=True)
        for i in range(r.Количество()):
            rec = r.Получить(i)
            print(f"    {str(rec.ВД):<8} | ОР={str(rec.ОР)[:40]:<40} | Долг={float(rec.ДолгРегл):>13,.2f} | Пред={float(rec.ПредоплатаРегл):>13,.2f}", flush=True)
    except Exception as e:
        print(f"  ПоСр ERR: {e}", flush=True)
