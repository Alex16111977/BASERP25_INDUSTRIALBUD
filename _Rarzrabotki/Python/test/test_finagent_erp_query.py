# -*- coding: utf-8 -*-
"""
Тест: Проверка структуры регистра А_ДенежныеСредстваФинАгенты в ERP
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    print("Подключение к ERP...")
    conn = v8.Connect(CONN_ERP)
    print("OK\n")

    # === 1. Запрос ОстаткиИОбороты ===
    print("=== 1. А_ДенежныеСредстваФинАгенты.ОстаткиИОбороты ===")
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ "
        "  ДС.ФинАгент КАК ФинАгент, "
        "  ДС.СуммаНачальныйОстаток КАК НачОст, "
        "  ДС.СуммаПриход КАК Приход, "
        "  ДС.СуммаРасход КАК Расход, "
        "  ДС.СуммаКонечныйОстаток КАК КонОст "
        "ИЗ "
        "  РегистрНакопления.А_ДенежныеСредстваФинАгенты.ОстаткиИОбороты(&НачалоПериода, &КонецПериода, , , ) КАК ДС"
    )

    start = pywintypes.Time(datetime(2025, 1, 1))
    end = pywintypes.Time(datetime(2026, 3, 17, 23, 59, 59))
    q.УстановитьПараметр("НачалоПериода", start)
    q.УстановитьПараметр("КонецПериода", end)

    res = q.Выполнить()
    sel = res.Выбрать()
    count = 0
    while sel.Следующий():
        count += 1
        fa = str(sel.ФинАгент) if sel.ФинАгент else "<пусто>"
        print(f"  {count}. ФинАгент={fa}, НачОст={sel.НачОст}, Приход={sel.Приход}, Расход={sel.Расход}, КонОст={sel.КонОст}")
        if count >= 20:
            print("  ... (показано первые 20)")
            break
    print(f"  Итого строк: {count}\n")

    # === 2. Сырые движения (проверка измерений) ===
    print("=== 2. Сырые движения А_ДенежныеСредстваФинАгенты ===")
    q2 = conn.NewObject("Запрос")
    q2.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 10 "
        "  Д.Период, "
        "  Д.Регистратор, "
        "  Д.ВидДвижения, "
        "  Д.ФинАгент, "
        "  Д.НаправлениеДеятельности, "
        "  Д.Подразделение, "
        "  Д.Контрагент, "
        "  Д.ДокументПередачи, "
        "  Д.Сумма КАК СуммаДвиж "
        "ИЗ "
        "  РегистрНакопления.А_ДенежныеСредстваФинАгенты КАК Д "
        "ГДЕ "
        "  Д.Период МЕЖДУ &НачалоПериода И &КонецПериода "
        "  И Д.Активность "
        "УПОРЯДОЧИТЬ ПО Д.Период УБЫВ"
    )

    q2.УстановитьПараметр("НачалоПериода", start)
    q2.УстановитьПараметр("КонецПериода", end)

    res2 = q2.Выполнить()
    sel2 = res2.Выбрать()
    cnt2 = 0
    while sel2.Следующий():
        cnt2 += 1
        print(f"  {cnt2}. Период={sel2.Период}, ФинАгент={sel2.ФинАгент}, "
              f"Направление={sel2.НаправлениеДеятельности}, Подразделение={sel2.Подразделение}, "
              f"Контрагент={sel2.Контрагент}, ДокПередачи={sel2.ДокументПередачи}, "
              f"Сумма={sel2.СуммаДвиж}, ВидДвиж={sel2.ВидДвижения}")
    print(f"  Итого строк: {cnt2}\n")

    # === 3. Справочник А_ФинАгенты ===
    print("=== 3. Справочник А_ФинАгенты ===")
    q3 = conn.NewObject("Запрос")
    q3.Текст = (
        "ВЫБРАТЬ "
        "  ФА.Код, "
        "  ФА.Наименование "
        "ИЗ "
        "  Справочник.А_ФинАгенты КАК ФА "
        "ГДЕ НЕ ФА.ПометкаУдаления "
        "УПОРЯДОЧИТЬ ПО ФА.Наименование"
    )

    res3 = q3.Выполнить()
    sel3 = res3.Выбрать()
    cnt3 = 0
    while sel3.Следующий():
        cnt3 += 1
        print(f"  {cnt3}. Код={sel3.Код}, Наименование={sel3.Наименование}")
    print(f"  Итого ФинАгентов: {cnt3}")

    print("\n=== ТЕСТ ЗАВЕРШЁН УСПЕШНО ===")

if __name__ == "__main__":
    main()
