    print("ТЕСТ В: Запит у стилі ERP — GROUP BY без КодСчета")
    print("=" * 80)

    query = conn.NewObject("Запрос")
    query.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 10\n"
        "  ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ОсновныеСредства).А_ИдКод КАК ОС_А_ИдКод,\n"
        "  ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ОсновныеСредства).Наименование КАК ОС_Наименование,\n"
        "  СУММА(Ост.СуммаНачальныйОстатокДт) КАК НачальныйОстаток,\n"
        "  СУММА(Ост.СуммаОборотДт) КАК ОборотДт,\n"
        "  СУММА(Ост.СуммаОборотКт) КАК ОборотКт,\n"
        "  СУММА(Ост.СуммаКонечныйОстатокДт) КАК КонечныйОстаток,\n"
        "  СУММА(Ост.КоличествоКонечныйОстатокДт) КАК КолВо\n"
        "ИЗ\n"
        "  РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(\n"
        "    &НачалоПериода,\n"
        "    &КонецПериода\n"
        "  ) КАК Ост\n"
        "ГДЕ\n"
        "  Ост.Счет В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.ОсновныеСредства))\n"
        "  И Ост.Субконто1 ССЫЛКА Справочник.ОсновныеСредства\n"
        "  И (Ост.СуммаКонечныйОстатокДт > 0\n"
        "    ИЛИ Ост.СуммаОборотДт > 0\n"
        "    ИЛИ Ост.СуммаОборотКт > 0\n"
        "    ИЛИ Ост.СуммаНачальныйОстатокДт > 0)\n"
        "СГРУППИРОВАТЬ ПО\n"
        "  ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ОсновныеСредства).А_ИдКод,\n"
        "  ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ОсновныеСредства).Наименование"
    )
    query.УстановитьПараметр("НачалоПериода", make_time(START_DATE))
    query.УстановитьПараметр("КонецПериода", make_time(END_DATE))

    try:
        result = query.Выполнить().Выбрать()
        count = 0
        total_kon = 0
        while result.Следующий():
            count += 1
            a_id = str(result.ОС_А_ИдКод).strip() if result.ОС_А_ИдКод else ""
            name = str(result.ОС_Наименование)[:50] if result.ОС_Наименование else ""
            nach = result.НачальныйОстаток or 0
            obd = result.ОборотДт or 0
            obk = result.ОборотКт or 0
            kon = result.КонечныйОстаток or 0
            kol = result.КолВо or 0
            total_kon += kon
            print(f"  [{count:3d}] А_ИдКод:{a_id}")
            print(f"         {name}")
            print(f"         НачОст:{nach:>12.2f} + Об.Дт:{obd:>12.2f} - Об.Кт:{obk:>12.2f} = {nach+obd-obk:>12.2f} | Рег.КонОст:{kon:>12.2f} | Кіл:{kol}")
            # Перевірка: НачОст + ОбДт - ОбКт = КонОст
            calc = nach + obd - obk
            if abs(calc - kon) > 0.01:
                print(f"         [!] РОЗБІЖНІСТЬ: Розрахунковий={calc:.2f}, Реєстровий={kon:.2f}, Різниця={calc-kon:.2f}")
        print(f"\n  Всього записів: {count}")
        print(f"  Сума КонОстДт: {total_kon:>15.2f}")
        print(f"  [OK] Тест В ПРАЦЮЄ! Записів: {count}")
        return True
    except Exception as e:
        print(f"  [ПОМИЛКА] {e}")
        traceback.print_exc()
        return False


