# -*- coding: utf-8 -*-
# Спроба провести створений НачислениеЗарплаты вручну щоб побачити ТОЧНУ помилку.
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Знайти створений НачислениеЗарплаты для документа 000000001
q = erp.NewObject("Запрос")
q.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 НЗ.Ссылка, НЗ.Проведен, НЗ.Номер "
    "ИЗ Документ.НачислениеЗарплаты КАК НЗ "
    "ГДЕ НЗ.А_ДокОтражениеЗПпоКазне.Номер = \"000000001\" "
    "И НЕ НЗ.ПометкаУдаления"
)
sel = q.Execute().Выбрать()
if not sel.Следующий():
    print("Документ не знайдено")
    sys.exit(1)

нз_ref = sel.Ссылка
print(f"НЗ: {S(нз_ref)}, Проведен={S(sel.Проведен)}")

obj = нз_ref.ПолучитьОбъект()
print(f"Начисления: {obj.Начисления.Количество()}")
print(f"Удержания:  {obj.Удержания.Количество()}")
print(f"НДФЛ:       {obj.НДФЛ.Количество()}")
print(f"ВзносыФОТ:  {obj.ВзносыФОТ.Количество()}")

# Перевірити поля першого рядка ВзносыФОТ
if obj.ВзносыФОТ.Количество() > 0:
    r = obj.ВзносыФОТ.Получить(0)
    print("\n=== Перший рядок ВзносыФОТ ===")
    for f in ["ФизическоеЛицо", "ВидЕСВ", "КатегорияЕСВ", "Налог", "База", "Результат",
              "ДатаНачала", "ДатаОкончания", "ДатаПолученияДохода", "Ставка", "СтавкаПолная"]:
        try:
            v = getattr(r, f)
            print(f"  {f}: '{S(v)}'")
        except Exception as e:
            print(f"  {f}: ERR {e}")

# Перевірити перший рядок НДФЛ
if obj.НДФЛ.Количество() > 0:
    r = obj.НДФЛ.Получить(0)
    print("\n=== Перший рядок НДФЛ ===")
    for f in ["ФизическоеЛицо", "НалоговыйПериод", "Налог", "Доход", "ВидСтавки", "КодДохода", "Подразделение"]:
        try:
            v = getattr(r, f)
            print(f"  {f}: '{S(v)}'")
        except Exception as e:
            print(f"  {f}: ERR {e}")

# Перевірити перший рядок Начисления
if obj.Начисления.Количество() > 0:
    r = obj.Начисления.Получить(0)
    print("\n=== Перший рядок Начисления ===")
    for f in ["Сотрудник", "Начисление", "Результат", "ДатаНачала", "ДатаОкончания",
              "Подразделение", "ИдентификаторСтрокиВидаРасчета", "ПериодДействия"]:
        try:
            v = getattr(r, f)
            print(f"  {f}: '{S(v)}'")
        except Exception as e:
            print(f"  {f}: ERR {e}")

# Спробуємо провести
print("\n>>> Спроба провести через COM ...")
try:
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print(">>> УСПІХ: документ проведено")
except Exception as e:
    # pywintypes.com_error — шукаємо текст помилки
    msg = str(e)
    print(f">>> ПОМИЛКА:")
    print(f"  {msg}")
    # Інколи детальний текст є у e.args[2]
    if hasattr(e, 'excepinfo') and e.excepinfo:
        for i, part in enumerate(e.excepinfo):
            print(f"  excepinfo[{i}]: {part}")
