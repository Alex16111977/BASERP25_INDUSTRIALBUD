# -*- coding: utf-8 -*-
"""Приёмка А_ОтчетПоСписаниюНаПроизводствоУправленческий: ПОЛНЫЙ путь пользователя
(СформироватьОтчет) + данные-независимые инварианты. Числа не хардкодим."""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетПоСписаниюНаПроизводствоУправленческий.erf"
ERF_DONOR = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетПоСписаниюНаПроизводство.erf"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

ПРОВЕРОК = 0
ПРОВАЛОВ = 0

def чек(условие, текст):
    global ПРОВЕРОК, ПРОВАЛОВ
    ПРОВЕРОК += 1
    метка = "PASS" if условие else "FAIL"
    if not условие:
        ПРОВАЛОВ += 1
    print(f"[{метка}] {текст}")

отчет = erp.ВнешниеОтчеты.Создать(ERF, False)

# Период НЕ задаём (пустой StandardPeriod = весь период) — сдвиги COM-дат не влияют.
период = erp.NewObject("СтандартныйПериод")

тз = отчет.ПолучитьДанные(период)
n = тз.Количество()
чек(n > 0, f"ПолучитьДанные вернул строки: {n}")

# --- агрегаты и инварианты по ТЗ (факт-строки и план-строки «0. План» раздельно) ---
итого_кол = 0.0
итого_соб = 0.0
итого_снд = 0.0
итого_план_кол = 0.0
итого_план_грн = 0.0
назва_этап = {}          # (драйвер, имя назвы) -> set(ЭтапСтрока)
суммы_по_этапам = {}     # ЭтапСтрока -> сумма СуммаСНДС
драйверы_тз = {}         # имя драйвера -> [кол, соб]
ошибок_источник = 0
ошибок_цена = 0
ошибок_план_нули = 0
план_со_складом = 0
факт_без_склада = 0
план_строк = 0
for i in range(n):
    стр = тз.Получить(i)
    ключ_д = erp.String(стр.Подразделение)
    этап_стр = str(стр.ЭтапСтрока)
    имя_назвы = erp.String(стр.ОбщееНазвание).strip().upper()
    if имя_назвы:
        назва_этап.setdefault((ключ_д, имя_назвы), set()).add(этап_стр)
    if str(стр.ВидДокумента) == "0. План":
        план_строк += 1
        итого_план_кол += стр.ПланКол
        итого_план_грн += стр.ПланГрн
        if стр.Количество != 0 or стр.СуммаСоб != 0 or стр.СуммаСНДС != 0 or стр.ЦенаСНДС != 0:
            ошибок_план_нули += 1
        if erp.String(стр.Склад):
            план_со_складом += 1
        continue
    кол = стр.Количество
    соб = стр.СуммаСоб
    снд = стр.СуммаСНДС
    план = стр.СуммаПлан
    итого_кол += кол
    итого_соб += соб
    итого_снд += снд
    драйверы_тз.setdefault(ключ_д, [0.0, 0.0])
    драйверы_тз[ключ_д][0] += кол
    драйверы_тз[ключ_д][1] += соб
    суммы_по_этапам[этап_стр] = суммы_по_этапам.get(этап_стр, 0.0) + снд
    if not erp.String(стр.Склад):
        факт_без_склада += 1
    ист = str(стр.ИсточникЦены)
    if ист == "Собівартість" and not (соб != 0 and abs(снд - соб) < 0.001):
        ошибок_источник += 1
    if ист == "Планова ціна" and not (соб == 0 and план != 0 and abs(снд - план) < 0.001):
        ошибок_источник += 1
    if ист == "Без ціни" and not (соб == 0 and снд == 0):
        ошибок_источник += 1
    ожид_цена = 0 if кол == 0 else снд / кол
    if abs(стр.ЦенаСНДС - ожид_цена) > 0.01:
        ошибок_цена += 1

чек(ошибок_источник == 0, f"ИсточникЦены согласован с СуммаСоб/СуммаПлан/СуммаСНДС (ошибок {ошибок_источник})")
чек(ошибок_цена == 0, f"ЦенаСНДС = СуммаСНДС/Количество на детали (ошибок {ошибок_цена})")
чек(план_строк > 0, f"план-строки присутствуют: {план_строк}")
чек(ошибок_план_нули == 0, f"план-строки не искажают факт (ненулевых факт-колонок {ошибок_план_нули})")
чек(план_со_складом == 0, f"склад план-строк пуст (нарушений {план_со_складом})")
чек(факт_без_склада == 0, f"склад факт-строк заполнен (пустых {факт_без_склада})")

дубли = {k: v for k, v in назва_этап.items() if len(v) > 1}
чек(len(дубли) == 0,
    f"каждая назва ровно в одном разделе В РАМКАХ драйвера (дублей {len(дубли)}): {list(дубли.items())[:3]}")

# один этап (по имени) = один сквозной номер во всех проектах
номер_по_имени = {}
for s in суммы_по_этапам:
    номер_по_имени.setdefault(s[4:], set()).add(s[:2])
кривые_номера = {k: v for k, v in номер_по_имени.items() if len(v) > 1}
чек(len(кривые_номера) == 0, f"сквозная нумерация этапов едина (нарушений {len(кривые_номера)}): {кривые_номера}")

сумма_разделов = sum(суммы_по_этапам.values())
чек(abs(сумма_разделов - итого_снд) < 0.01, f"Σ разделов {сумма_разделов:.2f} == Σ СуммаСНДС {итого_снд:.2f}")

номера = sorted(суммы_по_этапам.keys())
чек(all(s[:2].isdigit() and s[2:4] == ". " for s in номера), f"подписи разделов 'NN. Имя': {номера}")
if "99. Позапланово" in суммы_по_этапам:
    чек(номера[-1] == "99. Позапланово", "раздел Позапланово — последний по сортировке")

# --- сверка с прямым запросом регистра ---
q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	ВЫБОР
		КОГДА СС.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА СС.ПодразделениеОбъекта
		ИНАЧЕ СС.Подразделение
	КОНЕЦ КАК Драйвер
ИЗ Справочник.А_СтруктураСебестоимости КАК СС
ГДЕ НЕ СС.ЭтоГруппа И СС.Активная
	И ВЫБОР
		КОГДА СС.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА СС.ПодразделениеОбъекта
		ИНАЧЕ СС.Подразделение
	КОНЕЦ <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
"""
драйверы = q.Выполнить().Выгрузить()
прям_кол = 0.0
прям_соб = 0.0
for i in range(драйверы.Количество()):
    драйвер = драйверы.Получить(i).Драйвер
    q2 = erp.NewObject("Запрос")
    q2.Текст = """
ВЫБРАТЬ ЕСТЬNULL(СУММА(СТ.Количество), 0) КАК Кол, ЕСТЬNULL(СУММА(СТ.Стоимость), 0) КАК Соб
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
	И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
	И ТИПЗНАЧЕНИЯ(СТ.Регистратор) В (ТИП(Документ.СборкаТоваров), ТИП(Документ.ВнутреннееПотреблениеТоваров))
	И СТ.Подразделение В ИЕРАРХИИ (&Драйвер)
"""
    q2.УстановитьПараметр("Драйвер", драйвер)
    итог = q2.Выполнить().Выгрузить().Получить(0)
    прям_кол += итог.Кол
    прям_соб += итог.Соб
чек(abs(итого_кол - прям_кол) < 0.01, f"Σ Количество {итого_кол:.3f} == регистр {прям_кол:.3f}")
чек(abs(итого_соб - прям_соб) < 0.01, f"Σ СуммаСоб {итого_соб:.2f} == регистр {прям_соб:.2f}")

# --- кросс-сверка с донором (факт И план) ---
донор = erp.ВнешниеОтчеты.Создать(ERF_DONOR, False)
тз_донор = донор.ПолучитьДанные(период)
дон_кол = 0.0
дон_соб = 0.0
дон_план_кол = 0.0
дон_план_грн = 0.0
for i in range(тз_донор.Количество()):
    стр = тз_донор.Получить(i)
    дон_кол += стр.ФактКол
    дон_соб += стр.ФактГрнСоб
    дон_план_кол += стр.ПланКол
    дон_план_грн += стр.ПланГрн
чек(abs(итого_кол - дон_кол) < 0.01, f"факт кол == донор ({итого_кол:.3f} vs {дон_кол:.3f})")
чек(abs(итого_соб - дон_соб) < 0.01, f"факт соб == донор ({итого_соб:.2f} vs {дон_соб:.2f})")
чек(abs(итого_план_кол - дон_план_кол) < 0.01, f"план кол == донор ({итого_план_кол:.3f} vs {дон_план_кол:.3f})")
чек(abs(итого_план_грн - дон_план_грн) < 0.01, f"план грн == донор ({итого_план_грн:.2f} vs {дон_план_грн:.2f})")

# --- ПОЛНЫЙ путь пользователя: СформироватьОтчет ---
табдок = erp.NewObject("ТабличныйДокумент")
отчет.СформироватьОтчет(табдок)
чек(табдок.ВысотаТаблицы > 0, f"композиция: ВысотаТаблицы = {табдок.ВысотаТаблицы}")
чек(табдок.ШиринаТаблицы >= 4, f"композиция: ШиринаТаблицы = {табдок.ШиринаТаблицы}")

# заголовок первого раздела виден в выводе
искать = номера[0] if номера else ""
найдено = False
for r in range(1, min(табдок.ВысотаТаблицы, 200) + 1):
    for c in range(1, min(табдок.ШиринаТаблицы, 10) + 1):
        if искать and искать in str(табдок.Область(r, c, r, c).Текст):
            найдено = True
            break
    if найдено:
        break
чек(найдено, f"в выводе найден раздел '{искать}'")

print(f"\nИТОГО: {ПРОВЕРОК} проверок, {ПРОВАЛОВ} провалов")
print(f"Контроль: кол={итого_кол:.3f} соб={итого_соб:.2f} с_ндс={итого_снд:.2f} "
      f"план_кол={итого_план_кол:.3f} план_грн={итого_план_грн:.2f}")
for имя, (к, с) in драйверы_тз.items():
    print(f"  {имя}: кол={к:.3f} соб={с:.2f}")
sys.exit(0 if ПРОВАЛОВ == 0 else 1)
