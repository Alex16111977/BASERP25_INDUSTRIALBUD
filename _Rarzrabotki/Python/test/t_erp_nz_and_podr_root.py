# 2) Свод ПАП налоги по подразделению ВЕРХНЕГО уровня (корень структуры)
print("\n=== ПАП налоги: свод по подразделению верхнего уровня + тип налога ===")
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    ПАП.Подразделение КАК Подр,
    ПАП.Аналитика КАК Налог,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Нетто
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
    И ТИПЗНАЧЕНИЯ(ПАП.Аналитика)=ТИП(Перечисление.ТипыНалогов)
СГРУППИРОВАТЬ ПО ПАП.Подразделение, ПАП.Аналитика
"""
r2 = q2.Execute().Выгрузить()
# группируем по корню (подъём по Родитель)
def root(p):
    cur=p
    while not cur.Родитель.Пустая():
        cur=cur.Родитель
    return cur
agg={}
for i in range(r2.Количество()):
    s=r2.Получить(i)
    if s.Подр.Пустая():
        rn="(пусто)"
    else:
        rn=str(root(s.Подр).Наименование)
    нал=erp.XMLСтрока(s.Налог)
    agg.setdefault(rn,{}).setdefault(нал,0.0)
    agg[rn][нал]+=float(s.Нетто)
print(f"{'Корень подразделения':<22}|{'НДФЛ':>13}|{'ЕСВ':>13}|{'ВоенСбор':>12}|{'Прибыль':>13}|{'НДС':>14}|{'Другие':>11}")
cols=["НДФЛ","НачисленныйЕСВ","ВоенныйСбор","НалогНаПрибыль","НДС","ДругиеНалоги"]
for rn in sorted(agg, key=lambda x:-sum(abs(v) for v in agg[x].values())):
    row=agg[rn]
    print(f"{rn[:22]:<22}|"+"|".join(f"{row.get(c,0.0):>13,.0f}" for c in cols))
