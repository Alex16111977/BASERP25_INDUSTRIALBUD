"""Діагностика: документи в ТЧ «Документи» розрахунків РасчетКомплектаций, чий склад/організація не
збігаються з рядком (контроль 28.09.2026, промт PROMPT_dorabotka_KontrolSkladaDokumentov.md).

Лише читання. Виправлення — вручну бухгалтером (перевибрати документ свого складу): автовиправлення
заборонене, бо чужий документ може належати іншому домику (РК №11 → документи домика №3).
Джерело правди — функція модуля обʼєкта РасхожденияСкладовДокументов().
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
b = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

q = b.NewObject("Запрос")
q.Text = ('ВЫБРАТЬ Р.Ссылка КАК Ссылка ИЗ Документ.РасчетКомплектаций КАК Р '
          'ГДЕ НЕ Р.ПометкаУдаления УПОРЯДОЧИТЬ ПО Р.Дата')
rk = q.Execute().Выгрузить()

total = 0
for i in range(rk.Количество()):
    ref = rk.Получить(i).Ссылка
    arr = ref.ПолучитьОбъект().РасхожденияСкладовДокументов()
    if arr.Количество() == 0:
        continue
    print(b.String(ref), "| підрозділ:", b.String(ref.Подразделение))
    for j in range(arr.Количество()):
        x = arr.Получить(j)
        print(f"   {x.ИмяТЧ} / {x.ИмяКолонки}: {x.Текст}")
    total += arr.Количество()

print()
print(f"Розрахунків: {rk.Количество()}, розбіжностей: {total}")
