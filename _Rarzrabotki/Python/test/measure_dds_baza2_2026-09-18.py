S = erp.String


def run(text, params=None, label=""):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    try:
        tz = q.Execute().Выгрузить()
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"  FAIL [{label}]: {msg}")
        return None
    cols = [tz.Колонки.Получить(i).Имя for i in range(tz.Колонки.Количество())]
    rows = []
    for i in range(tz.Количество()):
        row = tz.Получить(i)
        rows.append({c: (getattr(row, c) if isinstance(getattr(row, c), (int, float, str, bool)) or getattr(row, c) is None else S(getattr(row, c))) for c in cols})
    print(f"  OK [{label}]: строк {len(rows)}")
    return rows


