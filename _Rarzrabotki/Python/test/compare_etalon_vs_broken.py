"""
Сравнение эталона 000Ц-000286 (исправил финансист) vs неисправленного 000Ц-000228.
Цель: понять что отличается и почему один пишет в ПоСрокам, а другой нет.
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def найти_по_дате_сумме(дата_от: datetime.datetime, дата_до: datetime.datetime, сумма: float, тип_док: str):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Д1", дата_от)
    q.УстановитьПараметр("Д2", дата_до)
    q.УстановитьПараметр("Σ", сумма)
    q.Текст = f"""
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка
ИЗ Документ.{тип_док} КАК Д
ГДЕ Д.Дата МЕЖДУ &Д1 И &Д2 И Д.СуммаДокумента = &Σ
"""
    r = q.Выполнить().Выгрузить()
    return r.Получить(0).Ссылка if r.Количество() else None


def дамп(док, метка):
    obj = док.ПолучитьОбъект()
    print(f"\n{'='*100}\n{метка}: {S(док)}\n{'='*100}")
    print(f"  Дата: {obj.Дата.strftime('%d.%m.%Y %H:%M:%S')}, Сумма: {obj.СуммаДокумента}")
    fields = ["Проведен", "А_Обработан", "А_ВведенВЕРП", "А_ОбработанКазна", "А_Необновлять",
              "Контрагент", "Партнер", "Подразделение", "Договор", "ОбъектРасчетов",
              "ХозяйственнаяОперация", "ФормаОплаты", "БанковскийСчет", "СтатьяДвиженияДенежныхСредств",
              "НаправлениеДеятельности", "Валюта", "ГруппаФинансовогоУчета", "А_ОказаниеУслугМеждуПодразделениями"]
    for f in fields:
        try:
            v = getattr(obj, f, None)
            if v is None:
                print(f"  {f:<40}: (None)")
            elif isinstance(v, bool):
                print(f"  {f:<40}: {v}")
            elif hasattr(v, 'Пустая') and v.Пустая():
                print(f"  {f:<40}: (ПустаяСсылка)")
            else:
                print(f"  {f:<40}: {str(S(v))[:60]}")
        except Exception as e:
            print(f"  {f:<40}: <ОШИБКА: {e}>")
    # Расшифровка платежа
    print(f"\n  РасшифровкаПлатежа ({obj.РасшифровкаПлатежа.Количество()} строк):")
    for i in range(obj.РасшифровкаПлатежа.Количество()):
        рп = obj.РасшифровкаПлатежа.Получить(i)
        for f in ["Партнер", "ДоговорСЗаказчиком", "А_Договор", "ОбъектРасчетов",
                  "Сумма", "СуммаВзаиморасчетов", "ВалютаВзаиморасчетов",
                  "Подразделение", "Организация", "СтатьяДвиженияДенежныхСредств"]:
            try:
                v = getattr(рп, f, None)
                if v is None:
                    s = "(None)"
                elif hasattr(v, 'Пустая') and v.Пустая():
                    s = "(ПустаяСсылка)"
                else:
                    s = str(S(v))[:55]
                print(f"    [Стр{i+1}] {f:<35}: {s}")
            except Exception as e:
                print(f"    [Стр{i+1}] {f:<35}: <ОШИБКА: {e}>")
    # Движения в 4 регистрах
    print(f"\n  Движения в регистрах:")
    for имя in ["РасчетыСКлиентами", "РасчетыСПоставщиками", "РасчетыСКлиентамиПоСрокам", "РасчетыСПоставщикамиПоСрокам"]:
        qq = erp.NewObject("Запрос")
        qq.УстановитьПараметр("Рег", док)
        qq.Текст = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.{имя} ГДЕ Регистратор = &Рег"
        try:
            к = int(qq.Выполнить().Выгрузить().Получить(0).К)
            print(f"    {имя:<40}: {к}")
        except Exception as e:
            print(f"    {имя:<40}: ОШИБКА")


# Эталон: 000Ц-000286 от 28.12.2025 19:01:15 (5 194 594,73 UAH) — Возврат оплаты клиенту
