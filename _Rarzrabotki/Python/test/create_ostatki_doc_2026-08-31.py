# -*- coding: utf-8 -*-
"""Создание/заполнение/проведение документа А_ВводОстатковОтчетаPL на 30.06.2026 23:59:59.

Get-or-create (документов не удаляем — правило тестов):
1. Ищем существующий документ за 30.06.2026; нет — создаём.
2. Дату ставим с контролем COM-сдвига (−3 часа теряют сутки → выставляем и перечитываем).
3. ТЧ заполняем серверной процедурой объекта ЗаполнитьИзДокументовPL().
4. Записываем, проводим, печатаем контрольные суммы по слоям.
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

ЦЕЛЬ = datetime.datetime(2026, 6, 30, 23, 59, 59)

# --- 1. get-or-create -------------------------------------------------------
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
    Док.Ссылка КАК ДокСсылка,
    Док.Номер КАК Номер,
    Док.Проведен КАК Проведен
ИЗ
    Документ.А_ВводОстатковОтчетаPL КАК Док
УПОРЯДОЧИТЬ ПО
    Док.Дата УБЫВ
"""
r = q.Execute().Выгрузить()
if r.Количество() > 0:
    ДокОбъект = r.Получить(0).ДокСсылка.ПолучитьОбъект()
    print(f"Найден существующий документ №{r.Получить(0).Номер}, использую его")
else:
    ДокОбъект = erp.Документы.А_ВводОстатковОтчетаPL.СоздатьДокумент()
    print("Создаю новый документ")

# --- 2. дата с контролем COM-сдвига ----------------------------------------
ДокОбъект.Дата = ЦЕЛЬ
факт = ДокОбъект.Дата
делта = ЦЕЛЬ - datetime.datetime(факт.year, факт.month, факт.day, факт.hour, факт.minute, факт.second)
if делта:
    ДокОбъект.Дата = ЦЕЛЬ + делта
    факт = ДокОбъект.Дата
    print(f"COM-сдвиг даты компенсирован: {делта}")
assert (факт.year, факт.month, факт.day, факт.hour, факт.minute, факт.second) == \
    (2026, 6, 30, 23, 59, 59), f"дата не встала: {факт}"

# Организация — ТОВ ІНДАСТРІАЛБУД (ЕДРПОУ 40645273)
qo = erp.NewObject("Запрос")
qo.Text = ('ВЫБРАТЬ ПЕРВЫЕ 1 Орг.Ссылка КАК ОргСсылка ИЗ Справочник.Организации КАК Орг '
           'ГДЕ НЕ Орг.ПометкаУдаления И Орг.Наименование ПОДОБНО "%НДАСТР%"')
ro = qo.Execute().Выгрузить()
assert ro.Количество() > 0, "организация ІНДАСТРІАЛБУД не найдена"
ДокОбъект.Организация = ro.Получить(0).ОргСсылка
ДокОбъект.Комментарий = "Фиксация остатков PL на 30.06.2026 (PL с начала года + Накопительный PL) из документов А_ОтчетPL"

# --- 3. заполнение ТЧ серверной процедурой ----------------------------------
ДокОбъект.ЗаполнитьИзДокументовPL()
n = ДокОбъект.Остатки.Количество()
print(f"ТЧ Остатки заполнена: {n} строк")
assert n > 0, "ТЧ пуста!"

# --- 4. запись + проведение -------------------------------------------------
ДокОбъект.Записать(erp.РежимЗаписиДокумента.Проведение)
print(f"Документ №{erp.String(ДокОбъект.Номер)} проведён, дата {ДокОбъект.Дата}")

# --- контрольные суммы по слоям ---------------------------------------------
qc = erp.NewObject("Запрос")
qc.Text = """
ВЫБРАТЬ
    Ост.СводНаправления КАК Свод,
    СУММА(Ост.СуммаФ1СНачалаГода) КАК Ф1СНГ,
    СУММА(Ост.СуммаФ2СНачалаГода) КАК Ф2СНГ,
    СУММА(Ост.СуммаФ1Накопительно) КАК Ф1Накоп,
    СУММА(Ост.СуммаФ2Накопительно) КАК Ф2Накоп,
    КОЛИЧЕСТВО(*) КАК Строк
ИЗ
    РегистрНакопления.А_ОстаткиОтчетаPL КАК Ост
СГРУППИРОВАТЬ ПО
    Ост.СводНаправления
"""
rc = qc.Execute().Выгрузить()
for i in range(rc.Количество()):
    s = rc.Получить(i)
    слой = "СВОД " if s.Свод else "ОБЪЕКТ"
    print(f"{слой}: строк={int(s.Строк)}  Ф1СНГ={s.Ф1СНГ:,.2f}  Ф2СНГ={s.Ф2СНГ:,.2f}  "
          f"Ф1Накоп={s.Ф1Накоп:,.2f}  Ф2Накоп={s.Ф2Накоп:,.2f}")
print("OK")
