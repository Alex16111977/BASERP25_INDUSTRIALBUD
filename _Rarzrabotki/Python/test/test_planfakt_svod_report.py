# -*- coding: utf-8 -*-
"""
Приёмка этапа 5: отчёт Отчеты.А_ПланФактныйПроизводствоСвод поверх регистра.

  5.1 все варианты настроек РЕАЛЬНО компонуются и рисуются (ТабличныйДокумент, высота > 0);
  5.2 числа за ВЕСЬ период == рабочий отчёт А_ПланФактныйПроизводствоПолный;
  5.3 семантика периода: при сужении окна План и ПланНаФакт не меняются, Факт и EV падают;
  5.4 рабочий отчёт не тронут — он и служит эталоном.

Запрос набора данных берётся ИЗ САМОЙ СХЕМЫ (Template.xml), а не из копии в тесте —
иначе тест проверял бы не то, что реально исполняет отчёт.

Вывод в КоллекциюЗначений через COM недоступен: он требует
Тип("ГенераторМакетаКомпоновкиДанныхДляКоллекцииЗначений"), а COMConnector не отдаёт
глобальную функцию Тип() (проверено: ни Тип/type/Type, ни русское/английское имя типа).
Поэтому валидность вариантов проверяется рендером в ТабличныйДокумент, а числа — запросом схемы.

Запуск: python test_planfakt_svod_report.py
"""
import win32com.client, sys, xml.etree.ElementTree as ET
sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
SCHEMA = (r'C:/Configuration_downloads/BASERP25/Reports/А_ПланФактныйПроизводствоСвод'
          r'/Templates/ОсновнаяСхемаКомпоновкиДанных/Ext/Template.xml')
РЕСУРСЫ = ["ПланЧасы", "ФактЧасы", "ВиконанняЧасы", "ПланКол", "ФактКол",
           "ПланГрн", "ФактГрн", "ПланНаФактГрн"]
провалы = []


def запрос_из_схемы():
    root = ET.parse(SCHEMA).getroot()
    q = None
    for el in root.iter():
        if el.tag.endswith('}query') or el.tag == 'query':
            q = el
            break
    assert q is not None and q.text, 'в схеме не найден текст запроса набора данных'
    return q.text


def суммы_запроса(erp, текст, нач, кон):
    q = erp.NewObject("Запрос")
    q.Текст = текст
    q.УстановитьПараметр("НачалоПериода", нач)
    q.УстановитьПараметр("КонецПериода", кон)
    q.УстановитьПараметр("ТипПлан", erp.Перечисления.А_ТипыСтрокПланФактПроизводство.План)
    q.УстановитьПараметр("ТипПланНаФакт", erp.Перечисления.А_ТипыСтрокПланФактПроизводство.ПланНаФакт)
    r = q.Execute().Выгрузить()
    итог = {x: 0.0 for x in РЕСУРСЫ}
    for i in range(r.Количество()):
        s = r.Получить(i)
        for x in РЕСУРСЫ:
            итог[x] += float(getattr(s, x) or 0)
    итог["_строк"] = r.Количество()
    return итог


def отрисовать(erp, индекс, нач, кон):
    """Компонует вариант по индексу в ТабличныйДокумент, возвращает (высота, ширина)."""
    отчет = erp.Отчеты.А_ПланФактныйПроизводствоСвод.Создать()
    схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")

    компоновщик = erp.NewObject("КомпоновщикНастроекКомпоновкиДанных")
    источник = erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема)
    компоновщик.Инициализировать(источник)
    компоновщик.ЗагрузитьНастройки(схема.ВариантыНастроек.Получить(индекс).Настройки)

    настройки = компоновщик.ПолучитьНастройки()
    for имя, значение in (("НачалоПериода", нач), ("КонецПериода", кон),
                          ("ТипПлан", erp.Перечисления.А_ТипыСтрокПланФактПроизводство.План),
                          ("ТипПланНаФакт", erp.Перечисления.А_ТипыСтрокПланФактПроизводство.ПланНаФакт)):
        эл = настройки.ПараметрыДанных.Элементы.Найти(имя)
        if эл is None:
            провалы.append(f"вариант#{индекс}: параметр {имя} отсутствует в схеме")
            continue
        эл.Значение = значение
        эл.Использование = True

    км = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных")
    макет = км.Выполнить(схема, настройки)
    пк = erp.NewObject("ПроцессорКомпоновкиДанных")
    пк.Инициализировать(макет)
    тд = erp.NewObject("ТабличныйДокумент")
    пв = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    пв.УстановитьДокумент(тд)
    пв.Вывести(пк)
    return int(тд.ВысотаТаблицы), int(тд.ШиринаТаблицы)


def main():
    erp = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
    текст = запрос_из_схемы()
    есть_фильтр = 'ТипСтроки' in текст
    print(f"Запрос набора взят из схемы: {len(текст)} симв., "
          f"{'отбор по ТипСтроки найден' if есть_фильтр else 'ОТБОР ПО ТипСтроки ОТСУТСТВУЕТ'}")
    if not есть_фильтр:
        провалы.append("в запросе схемы нет отбора по ТипСтроки")

    qb = erp.NewObject("Запрос")
    qb.Текст = ("ВЫБРАТЬ ДАТАВРЕМЯ(1,1,1,0,0,0) КАК Н0, ДАТАВРЕМЯ(3999,12,31,23,59,59) КАК К0, "
                "ДАТАВРЕМЯ(2026,6,1,0,0,0) КАК Н1, ДАТАВРЕМЯ(2026,7,24,23,59,59) КАК К1")
    b = qb.Execute().Выгрузить().Получить(0)

    # ---------------------------------------------------------------- 5.1
    print()
    print("=" * 96)
    print("5.1 — реальная компоновка всех вариантов")
    print("=" * 96)
    отчет = erp.Отчеты.А_ПланФактныйПроизводствоСвод.Создать()
    схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    варианты = [str(схема.ВариантыНастроек.Получить(i).Имя) for i in range(схема.ВариантыНастроек.Количество())]
    for i, в in enumerate(варианты):
        try:
            h, w = отрисовать(erp, i, b.Н0, b.К0)
            ok = h > 0 and w > 0
            print(f"  [{в:34}] таблица {h} x {w}  {'OK' if ok else 'ПУСТО'}")
            if not ok:
                провалы.append(f"{в}: пустой результат компоновки")
        except Exception as e:
            msg = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
            print(f"  [{в:34}] ОШИБКА: {msg}")
            провалы.append(f"{в}: {msg}")

    # ---------------------------------------------------------------- 5.2
    print()
    print("=" * 96)
    print("5.2 — числа за весь период vs рабочий отчёт")
    print("=" * 96)
    старый = erp.Отчеты.А_ПланФактныйПроизводствоПолный.Создать()
    тзстар = старый.ПолучитьДанные(erp.NewObject("СтандартныйПериод"))
    эталон = {x: 0.0 for x in РЕСУРСЫ}
    for i in range(тзстар.Количество()):
        с = тзстар.Получить(i)
        for x in РЕСУРСЫ:
            эталон[x] += float(getattr(с, x) or 0)
    полный = суммы_запроса(erp, текст, b.Н0, b.К0)
    print(f"  строк: рабочий отчёт {тзстар.Количество()}, новый набор {полный['_строк']}")
    # ВиконанняЧасы и ФактКол в ТЗ рабочего отчёта — колонки Число(18,2), т.е. округляются
    # ПОСТРОЧНО до суммирования. Регистр хранит 3 знака, поэтому по этим двум величинам
    # эталоном служит ПЕРВОИСТОЧНИК, а не отчёт (проверено 01.08.2026:
    # СебестоимостьТоваров.Количество = 218 575,249 — новый контур Δ=0,000, отчёт Δ=0,061;
    # А_ВыполнениеРаботМодулей.ЧасыВыполнение = 3 930,958 против 3 931,00 в отчёте).
    ОКРУГЛЯЕТСЯ_В_ОТЧЁТЕ = {"ВиконанняЧасы": 0.05, "ФактКол": 0.10}
    for x in РЕСУРСЫ:
        допуск = ОКРУГЛЯЕТСЯ_В_ОТЧЁТЕ.get(x, 0.011)
        d = abs(полный[x] - эталон[x])
        прим = "  (отчёт округляет построчно до 2 знаков; регистр точнее)" if x in ОКРУГЛЯЕТСЯ_В_ОТЧЁТЕ else ""
        итог = "OK" if d < допуск else f"РАСХОЖДЕНИЕ Δ={d:,.3f}"
        print(f"    {x:14} новый {полный[x]:>16,.3f}   старый {эталон[x]:>16,.3f}   {итог}{прим}")
        if d >= допуск:
            провалы.append(f"5.2 {x}: {полный[x]} vs {эталон[x]}")

    # 5.2b — по округляемым величинам сверяемся с ПЕРВОИСТОЧНИКОМ, а не с отчётом
    print()
    print("  5.2b — сверка с первоисточником (там, где отчёт округляет):")
    qs = erp.NewObject("Запрос")
    qs.Текст = ("ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК EV "
                "ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т")
    ev_ист = float(qs.Execute().Выгрузить().Получить(0).EV or 0)
    d = abs(полный["ВиконанняЧасы"] - ev_ист)
    print(f"    ВиконанняЧасы  регистр свёртки {полный['ВиконанняЧасы']:>14,.3f}   "
          f"РН.А_ВыполнениеРаботМодулей {ev_ист:>14,.3f}   {'OK' if d < 0.011 else f'Δ={d:.3f}'}")
    if d >= 0.011:
        провалы.append(f"5.2b EV не совпал с первоисточником: {полный['ВиконанняЧасы']} vs {ev_ист}")

    # ---------------------------------------------------------------- 5.3
    print()
    print("=" * 96)
    print("5.3 — семантика периода (01.06.2026 - 24.07.2026)")
    print("=" * 96)
    узкий = суммы_запроса(erp, текст, b.Н1, b.К1)
    print(f"  строк: полный {полный['_строк']}, узкий {узкий['_строк']}")
    for x in РЕСУРСЫ:
        п, у = полный[x], узкий[x]
        if x in ("ПланЧасы", "ПланКол", "ПланГрн", "ПланНаФактГрн"):
            ok = abs(п - у) < 0.011
            вердикт = "НЕ МЕНЯЕТСЯ — OK" if ok else "ИЗМЕНИЛСЯ — ОШИБКА"
            if not ok:
                провалы.append(f"5.3 {x} изменился при сужении периода")
        else:
            if п == 0:
                ok, вердикт = (у == 0), "оба нуля — OK"
            else:
                ok = у < п - 0.011
                вердикт = "сузился — OK" if ok else "НЕ СУЗИЛСЯ — ОШИБКА"
            if not ok:
                провалы.append(f"5.3 {x} не сузился при сужении периода")
        print(f"    {x:14} полный {п:>16,.2f}  узкий {у:>16,.2f}   {вердикт}")

    if провалы:
        print("\nFAIL:")
        for p in провалы:
            print("   ", p)
        sys.exit(1)
    print("\nПРИЁМКА ЭТАПА 5 ПРОЙДЕНА.")


if __name__ == "__main__":
    main()
