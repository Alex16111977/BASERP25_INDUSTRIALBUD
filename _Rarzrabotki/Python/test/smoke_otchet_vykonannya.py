# -*- coding: utf-8 -*-
"""
Smoke внешнего отчёта А_ОтчетПоВыполнениюРаботвПроизводстве:
создаёт отчёт из .erf, ставит параметры, компонует результат, сохраняет в .xlsx
и проверяет ключевые числа (План / Виконано / матрица домів×модулів).

Запуск: python smoke_otchet_vykonannya.py ["Наименование СС"] [--all] [--вариант Полный]

Варианты схемы: «Основной» (краткий, по умолчанию) и «Полный».
"""
import sys, os, re
sys.stdout.reconfigure(encoding='utf-8')
import win32com.client

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетПоВыполнениюРаботвПроизводстве.erf"
ВЫХОД_ДИР = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты"

ВАРИАНТ = "Основной"
if "--вариант" in sys.argv:
    ВАРИАНТ = sys.argv[sys.argv.index("--вариант") + 1]
аргс = [a for a in sys.argv[1:] if not a.startswith("--") and a != ВАРИАНТ]
СС_ИМЯ = аргс[0] if аргс else "МД IRS 2026 30 м (МД IRS 2026)"
ВСЕ_РАБОТЫ = "--all" in sys.argv

# --razr — прогон против копии BaseERPRazr (когда рабочая база закрыта для сеансов)
СТРОКА = ('Srvr="SQLSERVER";Ref="BaseERPRazr";Usr="Администратор";Pwd="24043"' if "--razr" in sys.argv
          else 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(СТРОКА)

сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(СС_ИМЯ)
assert сс is not None and str(сс) != "", f"СС не найдена: {СС_ИМЯ}"

print(f"Отчёт: {ERF}")
print(f"СС: {СС_ИМЯ} | Вариант: {ВАРИАНТ} | ПоказыватьВсеРаботы = {ВСЕ_РАБОТЫ}")

отчет = erp.ВнешниеОтчеты.Создать(ERF)

# --- инициализация компоновщика настроек из основной схемы
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
источник = erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема)
отчет.КомпоновщикНастроек.Инициализировать(источник)
варианты = [схема.ВариантыНастроек.Получить(i) for i in range(схема.ВариантыНастроек.Количество())]
print("Варианты схемы (по порядку):", [str(в.Имя) for в in варианты])
выбранный = схема.ВариантыНастроек.Найти(ВАРИАНТ)
assert выбранный is not None, f"вариант «{ВАРИАНТ}» не найден"
отчет.КомпоновщикНастроек.ЗагрузитьНастройки(выбранный.Настройки)

# --- параметры
q = erp.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,7,1,0,0,0) КАК Н, ДАТАВРЕМЯ(2026,7,31,23,59,59) КАК К"
г = q.Execute().Выгрузить().Получить(0)

период = erp.NewObject("СтандартныйПериод")
период.ДатаНачала = г.Н
период.ДатаОкончания = г.К

парам = отчет.КомпоновщикНастроек.Настройки.ПараметрыДанных
for имя, значение in (("Период", период), ("СтруктураСебестоимости", сс.Ссылка),
                      ("ПоказыватьВсеРаботы", ВСЕ_РАБОТЫ)):
    эл = парам.Элементы.Найти(имя)
    assert эл is not None, f"параметр {имя} не найден в схеме"
    эл.Использование = True
    эл.Значение = значение

# --- компоновка
таб = erp.NewObject("ТабличныйДокумент")
try:
    отчет.СкомпоноватьРезультат(таб)
except Exception as e:
    msg = e.excepinfo[2] if getattr(e, "excepinfo", None) else str(e)
    print(f"\n❌ ОШИБКА КОМПОНОВКИ:\n{msg}")
    raise SystemExit(1)

суффикс = ("_все" if ВСЕ_РАБОТЫ else "") + "_" + ВАРИАНТ
имя_файла = ("smoke_" + re.sub(r"[^\w]+", "_", СС_ИМЯ)[:40] + суффикс)
путь_xlsx = os.path.join(ВЫХОД_ДИР, имя_файла + ".xlsx")
таб.Записать(путь_xlsx, erp.ТипФайлаТабличногоДокумента.XLSX)
print(f"\nСкомпоновано: строк={таб.ВысотаТаблицы} колонок={таб.ШиринаТаблицы}")
print(f"Сохранено: {путь_xlsx}")

# --- проверка содержимого через openpyxl
import openpyxl
wb = openpyxl.load_workbook(путь_xlsx, data_only=True)
ws = wb[wb.sheetnames[0]]
print(f"\n--- Первые строки результата ---")
for r in range(1, min(ws.max_row, 10) + 1):
    куски = []
    for c in range(1, min(ws.max_column, 30) + 1):
        v = ws.cell(r, c).value
        if v is not None and str(v).strip() != "":
            куски.append(f"[{c}]{str(v)[:28]}")
    if куски:
        print(f"  r{r:>3}: " + " | ".join(куски))
print(f"\n--- Подвал ---")
for r in range(max(1, ws.max_row - 2), ws.max_row + 1):
    куски = []
    for c in range(1, min(ws.max_column, 30) + 1):
        v = ws.cell(r, c).value
        if v is not None and str(v).strip() != "":
            куски.append(f"[{c}]{str(v)[:28]}")
    if куски:
        print(f"  r{r:>3}: " + " | ".join(куски))
wb.close()
print("\nSMOKE OK")
