# -*- coding: utf-8 -*-
"""Негативная приёмка: портит копию шаблона типичными человеческими ошибками
и проверяет, что обработка ловит КАЖДУЮ и называет её понятным текстом.

Ничего в базу не пишет: проверяется только разбор (создание блокирует форма).
Запуск: python make_broken_zvit.py
"""
import os
import shutil
import sys
import tempfile

import openpyxl
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')

ШАБЛОН = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\notebook"
          r"\knowledge_Загрузка файлов в выполнение работ\Шаблоны"
          r"\МД IRS 2026 15 м (МД IRS 2026).xlsx")
ПОРЧЕНЫЙ = os.path.join(tempfile.gettempdir(), "zvr_broken.xlsx")

shutil.copyfile(ШАБЛОН, ПОРЧЕНЫЙ)
книга = openpyxl.load_workbook(ПОРЧЕНЫЙ)
лист = книга["TDSheet"]
лист["C9"] = "0,5"                                  # неоднозначное значение
лист["D9"] = "120%"                                 # вне диапазона
лист["E9"] = "в роботі"                             # не число
лист["F9"] = "-"                                    # не число
лист["G9"] = "80"                                   # так писать МОЖНО — не ошибка
лист["B10"] = "Нарізання деталей ЗА кресленнями"    # имя работы изменили
лист["B11"] = "Приймання матеріалу"                 # дубль работы из строки 8
книга.save(ПОРЧЕНЫЙ)
print("порченый файл:", ПОРЧЕНЫЙ)

ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def адрес():
    return ERP.ПоместитьВоВременноеХранилище(ERP.NewObject("ДвоичныеДанные", ПОРЧЕНЫЙ))


обр = ERP.Обработки.А_ЗагрузкаВыполненияРабот.Создать()
обр.ИмяФайла = "zvr_broken.xlsx"
паспорт = обр.ПрочитатьПаспортФайла(адрес(), обр.ИмяФайла)
обр.СтруктураСебестоимости = паспорт.СтруктураСебестоимости
обр.ДатаЗагрузки = паспорт.Дата
сводка = обр.РазобратьФайл(адрес(), обр.ИмяФайла)

пояснения = sorted({обр.Строки[i].Пояснение for i in range(обр.Строки.Количество())
                    if обр.Строки[i].Уровень == "Помилка"})
print(f"\nпомилок {сводка.Ошибок}, унікальних пояснень {len(пояснения)}:")
for текст in пояснения:
    print("   •", текст)

ОЖИДАЕМ = {
    "неоднозначне значення": "0,5 без знака % — уточнение",
    "від 0 до 100": "120% вне диапазона",
    'не розпізнано як число: "в роботі"': "текст вместо числа",
    'не розпізнано як число: "-"': "прочерк вместо числа",
    "немає в структурі собівартості": "изменённое имя работы",
    "двічі": "дубль работы",
}
провалов = 0
for фрагмент, что in ОЖИДАЕМ.items():
    if not any(фрагмент in т for т in пояснения):
        провалов += 1
        print(f"    ПРОВАЛ: не спіймано — {что} (шукали '{фрагмент}')")

# «80» без знака % — законная запись, ошибкой быть не должно
восьмидесятки = [обр.Строки[i] for i in range(обр.Строки.Количество())
                 if обр.Строки[i].ТекстЯчейки == "80"]
if not (восьмидесятки and all(float(с.Процент) == 80 and с.Уровень == ""
                              for с in восьмидесятки)):
    провалов += 1
    print("    ПРОВАЛ: «80» без знака % должно читаться как 80% без замечаний")

# проблемные строки не должны попасть в документы
не_грузим = sum(1 for i in range(обр.Строки.Количество()) if not обр.Строки[i].Грузить)
print(f"\nрядків не буде завантажено: {не_грузим} (проблемні позначені Грузить = Ложь)")
if не_грузим < 4:
    провалов += 1
    print("    ПРОВАЛ: проблемные строки должны исключаться из загрузки")

# подсказка по похожей работе
подсказки = [т for т in пояснения if "Схоже на" in т]
print(f"підказок «Схоже на …»: {len(подсказки)}")

print(f"\nПРОВАЛОВ: {провалов}")
print("НЕГАТИВНАЯ ПРИЁМКА ПРОЙДЕНА" if провалов == 0 else "НЕГАТИВНАЯ ПРИЁМКА НЕ ПРОЙДЕНА")
sys.exit(1 if провалов else 0)
