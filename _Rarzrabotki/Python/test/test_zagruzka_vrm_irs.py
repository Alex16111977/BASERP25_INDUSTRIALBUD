# -*- coding: utf-8 -*-
# Smoke домикового режима «Загрузки выполнения» (IRS) на BaseERP.
#  1. Юнит: РазобратьДатуЛиста «ЗВіт 10.07» (без скобок); парсер «6 МОДУЛІВ 100%» при N=6.
#  2. Прогон: 6 проведённых документов 10.07.2026 9:00 по подразделениям-домикам №1..№6.
#  3. Обороты РН по СС IRS: суммарно = эталон EV (19.19), по каждому домику = EV/6.
#  4. Идемпотентность: повтор — «обновлён» x6, обороты/состав не меняются.
#  5. ВООЗ в BaseERP не тронут: документы и обороты той СС неизменны.
import win32com.client, sys, re
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import openpyxl

XLSX = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\Виробництво\ЗВіт  виконання IRS 15 м.кв..xlsx"
EPF  = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\А_ПланФактныйПроизводствоПолный\По часам\Загрузка А_ВыполнениеРаботМодулей.epf"
СС_ИМЯ = "МД IRS 2026 15 м (МД IRS 2026)"
ВООЗ_ИМЯ = "МД Вооз ЕМS Мала 2026 / Цех_МД Вооз ЕМS Мала 2026"
ДОМОВ = 6

def норм(s):
    return re.sub(r"\s+", " ", str(s or "").strip().lower().replace("'", "").replace("’", ""))

def парс_проценты(текст, n):
    t = str(текст or "").strip()
    if not t:
        return None
    сегменты = re.findall(r"(\d+)\s*модул\w*\s*-*\s*(\d+(?:[.,]\d+)?)\s*%", t, re.I)
    if сегменты:
        из = []
        for кол, проц in сегменты:
            из += [float(проц.replace(",", "."))] * int(кол)
        return (из + [0.0] * n)[:n]
    m = re.fullmatch(r"(\d+(?:[.,]\d+)?)\s*%", t)
    if m:
        return [float(m.group(1).replace(",", "."))] * n
    return None

# === Excel -> сырые листы (как клиент формы: фильтр «звіт*», колонка факта по заголовку) ===
wb = openpyxl.load_workbook(XLSX, data_only=True)
листы = []
for имя in wb.sheetnames:
    имя_н = имя.strip().lower()
    if not имя_н.startswith("звіт") or имя_н == "звіт":
        continue
    ws = wb[имя]
    кол_факта = 7
    for c in range(1, min(ws.max_column, 15) + 1):
        if "факт виконання робіт" in str(ws.cell(1, c).value or "").lower():
            кол_факта = c
            break
    строки = []
    for r in range(2, ws.max_row + 1):
        назв = str(ws.cell(r, 1).value or "").strip()
        if not назв or "Загальна" in назв or назв.lower() == "табель":
            continue
        строки.append((назв, str(ws.cell(r, кол_факта).value or "").strip()))
    листы.append((имя, строки))
print(f"Листов снимков: {[и for и, _ in листы]}, колонка факта {кол_факта}")
assert [и for и, _ in листы] == ["ЗВіт 10.07"] and кол_факта == 8

# === 1С BaseERP ===
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
proc = erp.ВнешниеОбработки.Создать(EPF, False)
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(СС_ИМЯ)
воз = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(ВООЗ_ИМЯ)
assert сс is not None and not сс.Пустая() and int(сс.КоличествоДомов) == ДОМОВ

# === 1. Юниты: дата без скобок; парсер при N=6 ===
д = proc.РазобратьДатуЛиста("ЗВіт 10.07", 2026, 9 * 3600)
assert д is not None and erp.String(д) in ("10.07.2026 9:00:00", "10.07.2026 09:00:00"), \
    f"дата: {None if д is None else erp.String(д)}"
assert proc.РазобратьДатуЛиста("ЗВіт (19.06)", 2026, 9 * 3600) is not None  # скобки живы
assert proc.РазобратьДатуЛиста("Зразок", 2026, 0) is None
p100 = proc.РазобратьПроцентыФакта("6 МОДУЛІВ 100%", ДОМОВ)
p40  = proc.РазобратьПроцентыФакта("6 МОДУЛІВ 40%", ДОМОВ)
assert [float(p100.Получить(i)) for i in range(ДОМОВ)] == [100.0] * ДОМОВ
assert [float(p40.Получить(i)) for i in range(ДОМОВ)] == [40.0] * ДОМОВ
assert proc.РазобратьПроцентыФакта("в роботі", ДОМОВ) is None
print("Юниты: дата «ЗВіт 10.07» и парсер N=6 — OK")

# === Эталонный EV от работ СС ===
q = erp.NewObject("Запрос"); q.УстановитьПараметр("СС", сс.Ссылка)
q.Текст = """
ВЫБРАТЬ Р.Работа.Наименование КАК Наименование, СУММА(Р.Количество) КАК План
ИЗ Справочник.А_СтруктураСебестоимости.Работы КАК Р ГДЕ Р.Ссылка = &СС
СГРУППИРОВАТЬ ПО Р.Работа.Наименование
"""
т = q.Execute().Выгрузить()
работы_сс = {норм(т.Получить(i).Наименование): float(т.Получить(i).План) for i in range(т.Количество())}
эталон_ev = 0.0
for назв, факт in листы[0][1]:
    план = работы_сс.get(норм(назв))
    if план is None:
        continue
    проценты = парс_проценты(факт, ДОМОВ) or [0.0] * ДОМОВ
    эталон_ev += план / ДОМОВ * sum(проценты) / 100
print(f"Эталон EV снимка: {эталон_ev:.2f} (ожидаем ~19.19), на домик {эталон_ev/ДОМОВ:.4f}")

# === Baseline ВООЗ (неизменность) ===
def обороты_сс(ссылка):
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("СС", ссылка)
    qq.Текст = "ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т ГДЕ Т.СтруктураСебестоимости = &СС"
    тт = qq.Execute().Выгрузить()
    return float(тт.Получить(0).Ч or 0)

def доки_ирс():
    qq = erp.NewObject("Запрос"); qq.УстановитьПараметр("СС", сс.Ссылка)
    qq.Текст = """
    ВЫБРАТЬ ГОД(Д.Дата) КАК Г, МЕСЯЦ(Д.Дата) КАК М, ДЕНЬ(Д.Дата) КАК Дн, ЧАС(Д.Дата) КАК Ч,
        Д.Подразделение.Наименование КАК Подр, ВЫБОР КОГДА Д.Проведен ТОГДА 1 ИНАЧЕ 0 КОНЕЦ КАК Пр,
        Д.КоличествоМодулей КАК КМ
    ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д
    ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления
    УПОРЯДОЧИТЬ ПО Подр
    """
    тт = qq.Execute().Выгрузить()
    return [(int(тт.Получить(i).Г), int(тт.Получить(i).М), int(тт.Получить(i).Дн), int(тт.Получить(i).Ч),
             str(тт.Получить(i).Подр), int(тт.Получить(i).Пр), int(тт.Получить(i).КМ))
            for i in range(тт.Количество())]

воз_обороты_до = обороты_сс(воз.Ссылка)
print(f"ВООЗ обороты до: {воз_обороты_до:.2f}")

# === Параметры и прогон ===
def построить_параметры():
    листы1с = erp.NewObject("Массив")
    for имя, строки in листы:
        строки1с = erp.NewObject("Массив")
        for назв, факт in строки:
            стр = erp.NewObject("Структура")
            стр.Вставить("Наименование", назв)
            стр.Вставить("ТекстФакта", факт)
            строки1с.Добавить(стр)
        опис = erp.NewObject("Структура")
        опис.Вставить("ИмяЛиста", имя)
        опис.Вставить("Строки", строки1с)
        листы1с.Добавить(опис)
    парам = erp.NewObject("Структура")
    парам.Вставить("СтруктураСеб", сс.Ссылка)
    парам.Вставить("Листы", листы1с)
    парам.Вставить("Год", 2026)
    парам.Вставить("Время", 9 * 3600)
    парам.Вставить("Проводить", True)
    парам.Вставить("КоличествоМодулейПоУмолчанию", 8)  # в домиковом режиме не используется
    return парам

def прогон(заголовок):
    рез = proc.ЗагрузитьВыполнениеИзДанных(построить_параметры())
    print(f"--- {заголовок}: Ошибка={рез.Ошибка}")
    if рез.Ошибка:
        print("   ТекстОшибки:", рез.ТекстОшибки)
    for i in range(рез.Сообщения.Количество()):
        print("   |", рез.Сообщения.Получить(i))
    доки = []
    for i in range(рез.Документы.Количество()):
        о = рез.Документы.Получить(i)
        доки.append((str(о.Лист), float(о.ЕВ), int(о.Строк), str(о.Действие), str(о.Подразделение)))
    assert not рез.Ошибка, рез.ТекстОшибки
    return доки

доки1 = прогон("Прогон 1")
assert len(доки1) == ДОМОВ, f"документов {len(доки1)} != {ДОМОВ}"
for л, ев, стр, действие, подр in доки1:
    print(f"   {подр[:44]}: {действие}, строк {стр}, EV {ев:.4f}")
    assert стр == 26, "строк ТЧ на домик должно быть 26 (по работе на строку)"
    assert abs(ев - эталон_ev / ДОМОВ) < 0.02, f"EV домика {ев} != {эталон_ev/ДОМОВ:.4f}"

# === Документы в базе ===
дб = доки_ирс()
assert len(дб) == ДОМОВ
номера = set()
for г, м, дн, ч, подр, пр, км in дб:
    assert (г, м, дн, ч, пр, км) == (2026, 7, 10, 9, 1, ДОМОВ), f"шапка неверна: {(г,м,дн,ч,пр,км)} {подр}"
    mn = re.search(r"№(\d+)", подр)
    номера.add(int(mn.group(1)) if mn else 0)
assert номера == set(range(1, ДОМОВ + 1)), f"подразделения-домики: {номера}"
print(f"В базе {ДОМОВ} проведённых доков 10.07.2026 9:00, домики №1..№{ДОМОВ} — OK")

# === Обороты: сумма и по домикам ===
q = erp.NewObject("Запрос"); q.УстановитьПараметр("СС", сс.Ссылка)
q.Текст = """
ВЫБРАТЬ Т.Подразделение.Наименование КАК Подр, СУММА(Т.ЧасыВыполнение) КАК Ч
ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т
ГДЕ Т.СтруктураСебестоимости = &СС
СГРУППИРОВАТЬ ПО Т.Подразделение.Наименование
"""
т = q.Execute().Выгрузить()
всего = 0.0
for i in range(т.Количество()):
    ч = float(т.Получить(i).Ч or 0)
    всего += ч
    assert abs(ч - эталон_ev / ДОМОВ) < 0.02, f"оборот домика {т.Получить(i).Подр}: {ч}"
print(f"Обороты РН IRS: всего {всего:.2f} (эталон {эталон_ev:.2f}), по домикам по {эталон_ev/ДОМОВ:.4f} — OK")
assert abs(всего - эталон_ev) < 0.05

# === Идемпотентность ===
доки2 = прогон("Прогон 2 (идемпотентность)")
assert all(д[3] == "обновлён" for д in доки2), "повтор должен обновлять"
assert доки_ирс() == дб, "повтор изменил состав документов"
q = erp.NewObject("Запрос"); q.УстановитьПараметр("СС", сс.Ссылка)
q.Текст = "ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т ГДЕ Т.СтруктураСебестоимости = &СС"
всего2 = float(q.Execute().Выгрузить().Получить(0).Ч or 0)
assert abs(всего2 - всего) < 0.01, f"повтор изменил обороты {всего} -> {всего2}"
print("Идемпотентность — OK")

# === ВООЗ не тронут ===
воз_обороты_после = обороты_сс(воз.Ссылка)
assert abs(воз_обороты_после - воз_обороты_до) < 0.01, "обороты ВООЗ изменились!"
print(f"ВООЗ обороты после: {воз_обороты_после:.2f} — не изменились")

# === СС не изменена ===
сс2 = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(СС_ИМЯ)
assert int(сс2.КоличествоДомов) == ДОМОВ and int(сс2.А_КоличествоМодулей) == 0, "СС изменилась!"
print("СС IRS не изменена (КоличествоДомов=6, А_КоличествоМодулей=0) — OK")

print("\nSMOKE IRS PASS")
