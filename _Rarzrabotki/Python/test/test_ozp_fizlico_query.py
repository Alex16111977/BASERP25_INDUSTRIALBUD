# -*- coding: utf-8 -*-
"""Pretest: проверить, что добавление ФизическоеЛицо в GROUP BY
ВтИсходныеПрочиеРасходы НЕ меняет Σ Сумма по (Подразделение, СтатьяРасходов, АналитикаРасходов).

Шаги:
  1) Берём документ ОЗП 000Ц-000003 от 31.12.2025 (ТОВ ІНДАСТРІАЛБУД)
  2) Из ТЧ НачисленнаяЗарплатаИВзносы (свёрнутые СтатьиРасходов) проверяем 2 свёртки:
     - БезФЛ: GROUP BY (Подр, Статья, Аналитика)
     - СФЛ:   GROUP BY (Подр, Статья, Аналитика, ФизЛицо)
  3) Σ обеих свёрток должна совпасть. Кол-во строк в "СФЛ" >= "БезФЛ".
  4) % строк с ФизЛицо <> ПустаяСсылка в варианте СФЛ — должно быть > 50%.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Найдём документ
qDok = conn.NewObject("Запрос")
qDok.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете
ГДЕ Проведен И Номер = "000Ц-000003" И Дата = ДАТАВРЕМЯ(2025,12,31,12,0,0)
"""
r = qDok.Выполнить().Выбрать(); r.Следующий()
doc = r.Ссылка
print(f"Документ: {doc}")

# Запрос с детализацией: SELECT Подразделение, СтатьяРасходов, АналитикаРасходов,
# ФизическоеЛицо, Сумма. Из реальных ТЧ документа (Зарплата=Сводно: из НачисленнаяЗарплатаИВзносы;
# ProvodkiПоРаботникам Тогда из НачисленнаяЗарплатаИВзносыПоФизлицам).
# Здесь упростим: возьмём ВСЕ ТЧ через UNION ALL и проверим Σ.
qFL = conn.NewObject("Запрос")
qFL.УстановитьПараметр("Док", doc)
qFL.Текст = """
ВЫБРАТЬ
    Н.ПодразделениеПредприятия КАК Подразделение,
    Н.СтатьяРасходов КАК СтатьяРасходов,
    Н.АналитикаРасходов КАК АналитикаРасходов,
    Н.ФизическоеЛицо КАК ФизическоеЛицо,
    Н.Сумма КАК Сумма
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете.НачисленнаяЗарплатаИВзносыПоФизлицам КАК Н
ГДЕ Н.Ссылка = &Док
    И Н.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
    И Н.ВидОперации НЕ В (
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.ЕжегодныйОтпускОценочныеОбязательстваИРезервы),
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.КомпенсацияЕжегодногоОтпускаОценочныеОбязательства),
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.ЕжегодныйОтпускОценочныеОбязательства),
        ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоЗарплате.ЕжегодныйОтпускРезервы))
"""
tz = qFL.Выполнить().Выгрузить()
print(f"Строк НачЗПвзПФЛ (с фильтром): {tz.Количество()}")

# Свёртка БезФЛ
tz_no = tz.Скопировать()
tz_no.Свернуть("Подразделение,СтатьяРасходов,АналитикаРасходов", "Сумма")
sum_no = sum(r.Сумма for r in tz_no)
print(f"  БезФЛ свёртка: {tz_no.Количество()} строк, Σ Сумма = {sum_no:.2f}")

# Свёртка СФЛ
tz_yes = tz.Скопировать()
tz_yes.Свернуть("Подразделение,СтатьяРасходов,АналитикаРасходов,ФизическоеЛицо", "Сумма")
sum_yes = sum(r.Сумма for r in tz_yes)
fl_filled = sum(1 for r in tz_yes if r.ФизическоеЛицо and conn.ЗначениеЗаполнено(r.ФизическоеЛицо))
pct = 100.0 * fl_filled / max(tz_yes.Количество(), 1)
print(f"  СФЛ   свёртка: {tz_yes.Количество()} строк, Σ Сумма = {sum_yes:.2f}, ФЛ заполнен={fl_filled} ({pct:.1f}%)")

delta = sum_no - sum_yes
status = "OK" if abs(delta) < 0.01 else f"FAIL Δ={delta:.4f}"
print(f"  Σ-инвариант: {status}")

# Проверяем структуру таблицы — есть ли свёртка где ФизЛицо ПУСТО (т.е. при детализации она просто дает доп. строки)
empty = sum(1 for r in tz_yes if not (r.ФизическоеЛицо and conn.ЗначениеЗаполнено(r.ФизическоеЛицо)))
print(f"  Строк с пустым ФЛ в детализированной свёртке: {empty}")

# Все проверки
print()
print(f"ИТОГ: Δ={delta:.4f} ₽, ФЛ заполнен={pct:.1f}%")
assert abs(delta) < 0.01, f"Σ-инвариант нарушен"
assert pct >= 50.0, f"Слишком мало ФЛ заполнено: {pct:.1f}%"
print("Σ-инвариант OK, % ФЛ OK")
