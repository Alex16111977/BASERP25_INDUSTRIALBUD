import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Проверим заполненность Подразделения в проводках по налоговым счетам ERP
# движения - таблица записей с КорСчет
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Дв.Подразделение КАК Подр,
    Дв.Сумма КАК Сумма
ИЗ
    РегистрБухгалтерии.Хозрасчетный КАК Дв
ГДЕ
    Дв.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
    И (Дв.СчетДт В ИЕРАРХИИ (&Счета) ИЛИ Дв.СчетКт В ИЕРАРХИИ (&Счета))
"""
сч = erp.NewObject("Массив")
for code in ["6411","651","642"]:
    a = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду(code)
    if not a.Пустая():
        сч.Добавить(a)
q.УстановитьПараметр("Счета", сч)
r = q.Execute().Выгрузить()
total = r.Количество()
пусто = 0
sум_пусто = 0.0
sум_заполн = 0.0
подр_set = {}
for i in range(total):
    s = r.Получить(i)
    if s.Подр.Пустая():
        пусто += 1
        sум_пусто += float(s.Сумма)
    else:
        sум_заполн += float(s.Сумма)
        nm = str(s.Подр.Наименование)
        подр_set[nm] = подр_set.get(nm, 0.0) + float(s.Сумма)
print(f"Проводок по 6411/651/642: {total}; с ПУСТЫМ Подразделением: {пусто} (Σ={sум_пусто:,.2f}); заполнено Σ={sум_заполн:,.2f}")
print(f"Уникальных подразделений: {len(подр_set)}")
print("ТОП-15 подразделений по сумме проводок:")
for nm, su in sorted(подр_set.items(), key=lambda x:-abs(x[1]))[:15]:
    print(f"  {nm[:40]:<40} Σ={su:>16,.2f}")
