"""Етап 4 верифікація: провести січень, Σ по Статья == ПАП-еталон
(«Оплата труда» — допуск округлення розкладу), ФизическоеЛицо заповнено
для «Оплата труда», субконто Етапів 2-3 збережені, Актив=Пасив Σ≈0."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0); DDATE = datetime(2026, 1, 31, 14, 0, 0)
TOL=0.01; TOL_ОТ=1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
q0 = conn.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
s = q0.Выполнить().Выбрать(); s.Следующий(); org = s.С
qb = conn.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД"
qb.УстановитьПараметр("М", M); rb=qb.Выполнить().Выбрать(); rb.Следующий(); НМ=rb.НМ; КД=rb.КД
qi = conn.NewObject("Запрос")
qi.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование В (&Сп)"
arr = conn.NewObject("Массив")
for n in ["Собственные средства","Доходы текущего периода","Расходы текущего периода"]: arr.Добавить(n)
qi.УстановитьПараметр("Сп", arr)
ИсклСт = qi.Выполнить().Выгрузить().ВыгрузитьКолонку("С")
qo = conn.NewObject("Запрос")
qo.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Оплата труда"'
so = qo.Выполнить().Выбрать(); so.Следующий(); ОТ_key=str(conn.XMLСтрока(so.С))
qe = conn.NewObject("Запрос")
qe.Текст = """ВЫБРАТЬ Б.Статья КАК Статья, СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
    Организация=&Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
СГРУППИРОВАТЬ ПО Б.Статья ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток)<>0"""
qe.УстановитьПараметр("Д1",НМ); qe.УстановитьПараметр("Д2",КД)
qe.УстановитьПараметр("Орг",org); qe.УстановитьПараметр("Искл",ИсклСт)
te = qe.Выполнить().Выгрузить()
eталон = {str(conn.XMLСтрока(te.Получить(i).Статья)): float(te.Получить(i).sK or 0) for i in range(te.Количество())}

q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ Документ.А_ФинРез_Баланс"
tz = q.Выполнить().Выгрузить()
for i in range(tz.Количество()): tz.Получить(i).С.ПолучитьОбъект().Удалить()
doc = conn.Документы.А_ФинРез_Баланс.СоздатьДокумент()
doc.Дата=DDATE; doc.Организация=org; doc.Месяц=M; doc.ВключатьДочерние=False
mode = conn.PredefinedValue("РежимЗаписиДокумента.Проведение")
doc.Записать(mode)
assert doc.Проведен, "FAIL: не проведено"
ref = doc.Ссылка
print(f"[OK] проведено №{doc.Номер}")

qr = conn.NewObject("Запрос")
qr.Текст = """ВЫБРАТЬ Статья КАК Статья, СУММА(СуммаКонечныйОстаток) КАК sK
ИЗ РегистрСведений.А_ОтчетБаланс_Свод ГДЕ Регистратор=&Д
СГРУППИРОВАТЬ ПО Статья"""
qr.УстановитьПараметр("Д", ref)
trr = qr.Выполнить().Выгрузить()
после = {str(conn.XMLСтрока(trr.Получить(i).Статья)): float(trr.Получить(i).sK or 0) for i in range(trr.Количество())}
bad=[]
for k in set(eталон)|set(после):
    d=abs(eталон.get(k,0)-после.get(k,0)); lim=TOL_ОТ if k==ОТ_key else TOL
    if d>lim: bad.append((k,eталон.get(k,0),после.get(k,0),d))
if bad:
    print(f"FAIL: {len(bad)} статей розбіжні з ПАП-еталоном:")
    for k,a,b,d in bad[:10]: print(f"  {k[:40]} ПАП={a:,.2f} рег={b:,.2f} Δ={d:,.4f}")
    sys.exit(1)
print(f"[OK] пост-інваріант: Σ по статтях == ПАП (Оплата труда Δ={abs(eталон.get(ОТ_key,0)-после.get(ОТ_key,0)):,.4f})")
assert abs(sum(после.values())) < 1.0, f"FAIL: Актив≠Пасив Σ={sum(после.values()):,.2f}"

q3 = conn.NewObject("Запрос")
q3.Текст = """ВЫБРАТЬ
 СУММА(ВЫБОР КОГДА ОбъектРасчетов<>ЗНАЧЕНИЕ(Справочник.ОбъектыРасчетов.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ОР,
 СУММА(ВЫБОР КОГДА Номенклатура<>ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Ном,
 СУММА(ВЫБОР КОГДА ДенежныеСредства<>НЕОПРЕДЕЛЕНО И ДенежныеСредства<>"" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ДС,
 СУММА(ВЫБОР КОГДА Статья=&ОТ И ФизическоеЛицо<>ЗНАЧЕНИЕ(Справочник.ФизическиеЛица.ПустаяСсылка) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ФЛ
ИЗ РегистрСведений.А_ОтчетБаланс_Свод ГДЕ Регистратор=&Д"""
q3.УстановитьПараметр("Д", ref); q3.УстановитьПараметр("ОТ", so.С)
r3 = q3.Выполнить().Выбрать(); r3.Следующий()
print(f"ОбъектРасчетов={int(r3.ОР)} Номенклатура={int(r3.Ном)} ДенежныеСредства={int(r3.ДС)} | ФизическоеЛицо(Оплата труда)={int(r3.ФЛ)}")
assert int(r3.ФЛ)>0, "FAIL: ФизическоеЛицо для Оплата труда не заповнено"
assert int(r3.ОР)>0 and int(r3.Ном)>0 and int(r3.ДС)>0, "FAIL: субконто Етапів 2-3 втрачені"
print("PASS Етап 4")
