"""Діагностика 2: шукаємо документи 00DL-6990 та 00DL-6991 напряму.
Де зберігається договір — в шапці чи в РП? В якому полі?
"""
import win32com.client
import datetime

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

print("Connecting to BaseERP...")
conn = v8.Connect(CONN_ERP)
print("Connected OK\n")

for doc_num in ["00DL-6990", "00DL-6991"]:
    print("=" * 70)
    print(f"ДОКУМЕНТ: ПоступлениеБезналичныхДС #{doc_num}")
    print("=" * 70)

    q = conn.NewObject("Запрос")
    q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1
        Док.Ссылка КАК Ссылка,
        Док.Номер КАК Номер,
        Док.Дата КАК ДатаДок,
        Док.Договор КАК Договор,
        Док.А_Подразделение КАК А_Подразделение,
        Док.А_НаправлениеДеятельности КАК А_НаправлениеДеятельности,
        Док.Подразделение КАК Подразделение,
        Док.НаправлениеДеятельности КАК НаправлениеДеятельности
    ИЗ
        Документ.ПоступлениеБезналичныхДенежныхСредств КАК Док
    ГДЕ
        Док.Номер ПОДОБНО &Номер"""
    q.SetParameter("Номер", f"%{doc_num}%")
    res = q.Execute()
    sel = res.Select()
    if sel.Next():
        print(f"  Номер: {sel.Номер}")
        print(f"  Дата: {sel.ДатаДок}")
        print(f"  ШАПКА Договор: '{conn.String(sel.Договор)}' filled={conn.ValueIsFilled(sel.Договор)}")
        print(f"  ШАПКА А_Подразделение: '{conn.String(sel.А_Подразделение)}'")
        print(f"  ШАПКА А_НаправлениеДеятельности: '{conn.String(sel.А_НаправлениеДеятельности)}'")
        print(f"  ШАПКА Подразделение(стд): '{conn.String(sel.Подразделение)}'")
        print(f"  ШАПКА НаправлениеДеятельности(стд): '{conn.String(sel.НаправлениеДеятельности)}'")

        # РасшифровкаПлатежа
        doc_ref = sel.Ссылка
        q2 = conn.NewObject("Запрос")
        q2.Text = """ВЫБРАТЬ
            РП.НомерСтроки КАК НомерСтроки,
            РП.А_Договор КАК А_Договор,
            РП.Подразделение КАК РП_Подразделение,
            РП.НаправлениеДеятельности КАК РП_Направление,
            РП.Сумма КАК Сумма
        ИЗ
            Документ.ПоступлениеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК РП
        ГДЕ
            РП.Ссылка = &Ссылка"""
        q2.SetParameter("Ссылка", doc_ref)
        res2 = q2.Execute()
        sel2 = res2.Select()
        print(f"\n  РасшифровкаПлатежа:")
        while sel2.Next():
            print(f"    Стр.{sel2.НомерСтроки}: А_Договор='{conn.String(sel2.А_Договор)}' filled={conn.ValueIsFilled(sel2.А_Договор)}")
            print(f"      Подразделение='{conn.String(sel2.РП_Подразделение)}' filled={conn.ValueIsFilled(sel2.РП_Подразделение)}")
            print(f"      Направление='{conn.String(sel2.РП_Направление)}' filled={conn.ValueIsFilled(sel2.РП_Направление)}")
            print(f"      Сумма={sel2.Сумма}")
    else:
        print("  НЕ ЗНАЙДЕНО!")
    print()

