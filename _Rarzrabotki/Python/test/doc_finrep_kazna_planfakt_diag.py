# -*- coding: utf-8 -*-
"""Диагностика: какие статьи дают лишние затраты-факт в МД IRC 2026 / МД ООН Админ / МД ПРООН."""
import sys
sys.stdout.reconfigure(encoding="utf-8")
from collections import defaultdict
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"')
S = conn.String

гр_расход = conn.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("1В")
направление = conn.Справочники.Направления.НайтиПоНаименованию("Производство", True)

q = conn.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	БДДСОбороты.Подразделение.Наименование КАК ПодрИмя,
	БДДСОбороты.СтатьяДвиженияДенежныхСредств.Наименование КАК СтатьяИмя,
	БДДСОбороты.СтатьяДвиженияДенежныхСредств.Код КАК СтатьяКод,
	ВЫБОР
		КОГДА БДДСОбороты.СтатьяДвиженияДенежныхСредств В ИЕРАРХИИ (&ГруппаРасход)
			ТОГДА (БДДСОбороты.СуммаПриходОборот + БДДСОбороты.СуммаРасходОборот) * ВЫБОР
					КОГДА БДДСОбороты.НаправлениеДДС = ЗНАЧЕНИЕ(Перечисление.НаправленияДвиженийДенежныхСредств.Расход)
						ТОГДА -1
					ИНАЧЕ 1
				КОНЕЦ
		ИНАЧЕ 0
	КОНЕЦ КАК Расход
ИЗ
	РегистрНакопления.БДДС.Обороты(ДАТАВРЕМЯ(2026,8,1,0,0,0), ДАТАВРЕМЯ(2026,8,14,23,59,59), , Направление = &Направление) КАК БДДСОбороты
"""
q.УстановитьПараметр("ГруппаРасход", гр_расход)
q.УстановитьПараметр("Направление", направление)
r = q.Execute().Выгрузить()

цели = ("МД IRC", "МД ООН Админ", "МД ПРООН")
по_статьям = defaultdict(float)
for i in range(r.Количество()):
    row = r.Получить(i)
    подр = S(row.ПодрИмя)
    if not any(подр.startswith(ц) or ц in подр for ц in цели):
        continue
    расход = float(row.Расход)
    if расход == 0:
        continue
    ключ = (подр, S(row.СтатьяИмя), S(row.СтатьяКод))
    по_статьям[ключ] += расход

for (подр, имя, код), сумма in sorted(по_статьям.items()):
    print(f"{подр:30} | {имя!r:55} | {код:10} | {сумма:>14,.2f}")

# также: все статьи, похожие на исключения (поиск по подстроке)
print("\n=== Статьи справочника, похожие на исключения ===")
q2 = conn.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ Ст.Наименование КАК Имя, Ст.Код КАК Код, Ст.ЭтоГруппа КАК Гр, Ст.ПометкаУдаления КАК Удал
ИЗ Справочник.СтатьиДвиженияДенежныхСредств КАК Ст
ГДЕ Ст.Наименование ПОДОБНО "%Фин агент%"
	ИЛИ Ст.Наименование ПОДОБНО "%Транзит%"
	ИЛИ Ст.Наименование ПОДОБНО "%Внутригрупп%"
"""
r2 = q2.Execute().Выгрузить()
for i in range(r2.Количество()):
    row = r2.Получить(i)
    print(f"{S(row.Имя)!r:55} код={S(row.Код):12} группа={row.Гр} удал={row.Удал}")
