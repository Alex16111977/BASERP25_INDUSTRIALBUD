def try_post(описание, обj):
    try:
        обj.Записать(erp.РежимЗаписиДокумента.Проведение)
        print(f"  [OK] {описание} — ПРОВЕДЕНО")
        return True
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"  [FAIL] {описание}: {e.excepinfo[2][:150]}")
        else:
            print(f"  [FAIL] {описание}: {e}")
        return False


