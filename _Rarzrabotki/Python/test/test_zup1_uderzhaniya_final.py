# -*- coding: utf-8 -*-
# Фінальний запит — перевірка що можемо витягти все для побудови рядків таблиці
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="localhost";Ref="zup";Usr="cfo";Pwd="2442"')
S = zup.String

def com_date(y, m, d):
    return pywintypes.Time(datetime.datetime(y, m, d))

print("=" * 80)
print("Фінальний запит: Удержания за груд 2025 з Получатель (Контрагент)")
print("=" * 80)
try:
    q = zup.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        У.Сотрудник.Наименование КАК СотрудникФИО,
        У.Сотрудник.Физлицо.КодПоДРФО КАК СотрудникИНН,
        У.ВидРасчета.Наименование КАК ВидУдержания,
        У.ВидРасчета.Код КАК КодВидаУдержания,
        СУММА(У.Результат) КАК Сумма,
        У.ДокументОснование.Номер КАК НомерИЛ,
        У.ДокументОснование.Дата КАК ДатаИЛ,
        У.ДокументОснование.ВидИсполнительногоДокумента КАК ВидИЛ,
        У.ДокументОснование.Получатель.Наименование КАК ИмяПолучателя,
        У.ДокументОснование.Получатель.КодПоЕДРПОУ КАК ЕДРПОУПолучателя,
        У.ДокументОснование.Получатель.ИНН КАК ИННПолучателя,
        КодыОрг.КодПоЕДРПОУ КАК ЕДРПОУОрг
    ИЗ РегистрРасчета.УдержанияРаботниковОрганизаций КАК У
        ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.КодыОрганизации.СрезПоследних КАК КодыОрг
            ПО У.Организация = КодыОрг.Организация
    ГДЕ У.ПериодРегистрации МЕЖДУ &Н И &К
        И У.Результат <> 0
        И У.ДокументОснование <> ЗНАЧЕНИЕ(Документ.ИсполнительныйЛист.ПустаяСсылка)
    СГРУППИРОВАТЬ ПО
        У.Сотрудник.Наименование,
        У.Сотрудник.Физлицо.КодПоДРФО,
        У.ВидРасчета.Наименование,
        У.ВидРасчета.Код,
        У.ДокументОснование.Номер,
        У.ДокументОснование.Дата,
        У.ДокументОснование.ВидИсполнительногоДокумента,
        У.ДокументОснование.Получатель.Наименование,
        У.ДокументОснование.Получатель.КодПоЕДРПОУ,
        У.ДокументОснование.Получатель.ИНН,
        КодыОрг.КодПоЕДРПОУ
    """
    q.SetParameter("Н", com_date(2025, 12, 1))
    q.SetParameter("К", com_date(2025, 12, 31))
    r = q.Execute().Выгрузить()
    print(f"\nЗнайдено: {r.Количество()} рядків\n")
    for i in range(r.Количество()):
        row = r.Получить(i)
        print(f"[{i+1}] {S(row.СотрудникФИО).strip()} (ІНН={S(row.СотрудникИНН)})")
        print(f"    Вид: {S(row.ВидУдержания)} [код {S(row.КодВидаУдержания)}]")
        print(f"    Сума: {S(row.Сумма)} грн")
        print(f"    ИЛ №{S(row.НомерИЛ)} від {S(row.ДатаИЛ)} [{S(row.ВидИЛ)}]")
        print(f"    Получатель: {S(row.ИмяПолучателя)}")
        print(f"      ЄДРПОУ={S(row.ЕДРПОУПолучателя)}, ІНН={S(row.ИННПолучателя)}")
        print(f"    Орг ЄДРПОУ: {S(row.ЕДРПОУОрг)}")
        print()
except Exception as e:
    print(f"ПОМИЛКА: {str(e)[:800]}")
