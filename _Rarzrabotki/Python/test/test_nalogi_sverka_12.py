import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

d = datetime.date(2025,12,31)
moment = datetime.datetime(d.year, d.month, d.day, 23, 59, 59)

# Развёрнутое сальдо: по одной паре (Орг,Счёт) одновременно Дт и Кт по разным субконто?
q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    Ост.Счет.Код КАК Счет,
    СУММА(ВЫБОР КОГДА Ост.СуммаОстаток > 0 ТОГДА Ост.СуммаОстаток ИНАЧЕ 0 КОНЕЦ) КАК ДтЧасть,
    СУММА(ВЫБОР КОГДА Ост.СуммаОстаток < 0 ТОГДА Ост.СуммаОстаток ИНАЧЕ 0 КОНЕЦ) КАК КтЧасть,
    СУММА(Ост.СуммаОстаток) КАК Свернуто
ИЗ
    РегистрБухгалтерии.Хозрасчетный.Остатки(&Момент, , Субконто1, ) КАК Ост
ГДЕ (Ост.Счет.Код ПОДОБНО "641%" ИЛИ Ост.Счет.Код ПОДОБНО "642%" ИЛИ Ост.Счет.Код ПОДОБНО "651%")
СГРУППИРОВАТЬ ПО Ост.Организация.КодПоЕДРПОУ, Ост.Счет.Код
ИМЕЮЩИЕ СУММА(ВЫБОР КОГДА Ост.СуммаОстаток > 0 ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) > 0
    И СУММА(ВЫБОР КОГДА Ост.СуммаОстаток < 0 ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) > 0
УПОРЯДОЧИТЬ ПО ЕДРПОУ, Счет
"""
q.SetParameter("Момент", moment)
try:
    r = q.Execute().Выгрузить()
    print(f"=== BuhBud: пары (Орг,Счёт) с РАЗВЁРНУТЫМ сальдо (есть и Дт-субконто и Кт-субконто) на 31.12 — {r.Количество()} ===")
    for s in r:
        print(f"  ЕДРПОУ={str(s.ЕДРПОУ):11} сч{s.Счет:6} | Дт-часть={s.ДтЧасть:>14,.2f} | Кт-часть={s.КтЧасть:>14,.2f} | Свёрнуто={s.Свернуто:>14,.2f}")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"  FAIL razvern: {e.excepinfo[2]}")
    else:
        print(f"  FAIL razvern: {e}")

