# -*- coding: utf-8 -*-
"""
Определяем, какие ресурсы регистров ПрочиеРасходы / ПрочиеДоходы / ФинансовыеРезультаты
возвращают сумму С НДС, а какие БЕЗ НДС.

На скриншоте пользователя: ПТУ 000111, 000202, 000320 в текущей логике дают 147.25/441.75/255.75
(сумма 844.75 — без НДС). В PL-документе та же статья 1013.70 — с НДС (20%).
Хотим тянуть "с НДС" чтобы суммы совпадали.
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONNECTION_STRING = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
PERIOD_START = datetime(2026, 1, 1)
PERIOD_END = datetime(2026, 1, 31, 23, 59, 59)


def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected")

    # Сравнение ресурсов ПрочиеРасходы.Обороты для документов ПТУ января 2026
    q = conn.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ ПЕРВЫЕ 10
        Р.Регистратор КАК Документ,
        Р.СуммаПриход КАК Сумма,
        Р.СуммаБезНДСПриход КАК СуммаБезНДС,
        Р.СуммаРеглПриход КАК СуммаРегл,
        Р.СуммаРеглБезНДСПриход КАК СуммаРеглБезНДС,
        Р.НДСРеглПриход КАК НДСРегл
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(&НачалоПериода, &КонецПериода, Регистратор, ) КАК Р
    ГДЕ ТИПЗНАЧЕНИЯ(Р.Регистратор) = ТИП(Документ.ПриобретениеТоваровУслуг)
        И Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
    УПОРЯДОЧИТЬ ПО Р.Регистратор.Номер
    """
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(PERIOD_START))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(PERIOD_END))
    try:
        res = q.Выполнить().Выгрузить()
        print(f"\n=== ПрочиеРасходы: {res.Количество()} строк ===")
        print(f"{'Документ':50} {'Сумма':>12} {'БезНДС':>12} {'Регл':>12} {'РеглБезНДС':>12} {'НДСРегл':>10}")
        for row in res:
            doc_str = str(row.Документ)[:50]
            print(f"{doc_str:50} {float(row.Сумма):>12.2f} {float(row.СуммаБезНДС):>12.2f} "
                  f"{float(row.СуммаРегл):>12.2f} {float(row.СуммаРеглБезНДС):>12.2f} {float(row.НДСРегл):>10.2f}")
    except Exception as e:
        print(f"[FAIL] ПрочиеРасходы: {e}")

    # ПрочиеДоходы
    q2 = conn.NewObject("Запрос")
    q2.Текст = """
    ВЫБРАТЬ ПЕРВЫЕ 10
        Д.Регистратор КАК Документ,
        Д.СуммаПриход КАК Сумма,
        Д.СуммаРеглПриход КАК СуммаРегл,
        Д.СуммаРеглБезНДСПриход КАК СуммаРеглБезНДС
    ИЗ РегистрНакопления.ПрочиеДоходы.Обороты(&НачалоПериода, &КонецПериода, Регистратор, ) КАК Д
    """
    q2.УстановитьПараметр("НачалоПериода", pywintypes.Time(PERIOD_START))
    q2.УстановитьПараметр("КонецПериода", pywintypes.Time(PERIOD_END))
    try:
        res2 = q2.Выполнить().Выгрузить()
        print(f"\n=== ПрочиеДоходы: {res2.Количество()} строк ===")
        print(f"{'Документ':50} {'Сумма':>12} {'Регл':>12} {'РеглБезНДС':>12}")
        for row in res2:
            doc_str = str(row.Документ)[:50]
            print(f"{doc_str:50} {float(row.Сумма):>12.2f} {float(row.СуммаРегл):>12.2f} {float(row.СуммаРеглБезНДС):>12.2f}")
    except Exception as e:
        print(f"[FAIL] ПрочиеДоходы: {e}")

    # ФинансовыеРезультаты
    q3 = conn.NewObject("Запрос")
    q3.Текст = """
    ВЫБРАТЬ ПЕРВЫЕ 10
        Ф.Регистратор КАК Документ,
        Ф.ДоходыОборот КАК Доходы,
        Ф.ДоходыРеглБезНДСОборот КАК ДоходыРеглБезНДС
    ИЗ РегистрНакопления.ФинансовыеРезультаты.Обороты(&НачалоПериода, &КонецПериода, Регистратор, ) КАК Ф
    ГДЕ Ф.ДоходыОборот <> 0
    """
    q3.УстановитьПараметр("НачалоПериода", pywintypes.Time(PERIOD_START))
    q3.УстановитьПараметр("КонецПериода", pywintypes.Time(PERIOD_END))
    try:
        res3 = q3.Выполнить().Выгрузить()
        print(f"\n=== ФинансовыеРезультаты: {res3.Количество()} строк ===")
        print(f"{'Документ':50} {'Доходы':>12} {'ДоходыРеглБезНДС':>18}")
        for row in res3:
            doc_str = str(row.Документ)[:50]
            print(f"{doc_str:50} {float(row.Доходы):>12.2f} {float(row.ДоходыРеглБезНДС):>18.2f}")
    except Exception as e:
        print(f"[FAIL] ФинансовыеРезультаты: {e}")

    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
