import sys
sys.stdout.reconfigure(encoding="utf-8")
import win32com.client

# ============================================================
# V5: Проверка маппинга кассы Казна -> ЕРП (§2/§4.2 спеки)
# ============================================================
v8 = win32com.client.Dispatch("V83.COMConnector")

# ДВА соединения
kazna = v8.Connect('Srvr="SQLSERVER";Ref="BuhKazn";Usr="cfo";Pwd="2442"')
erp   = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

print("Соединения открыты: BuhKazn + BaseERP")

# ------------------------------------------------------------
# 1) Список наличных касс из Казны (различные БанковскийСчетКасса
#    с ВидДенежныхСредств = Наличные) — как в V4.
#    Берём из РН.ДенежныеСредства за весь период, фильтр Наличные.
# ------------------------------------------------------------
q = kazna.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    ДС.БанковскийСчетКасса КАК Касса,
    ДС.БанковскийСчетКасса.Код КАК Код,
    ДС.БанковскийСчетКасса.Наименование КАК Наименование
ИЗ
    РегистрНакопления.ДенежныеСредства КАК ДС
ГДЕ
    ДС.ВидДенежныхСредств = ЗНАЧЕНИЕ(Перечисление.ВидыДенежныхСредств.Наличные)
    И ДС.БанковскийСчетКасса <> НЕОПРЕДЕЛЕНО
УПОРЯДОЧИТЬ ПО
    Наименование
"""
r = q.Execute().Выгрузить()
total = r.Количество()
print(f"Наличных касс в Казне: {total}")

# ------------------------------------------------------------
# 2) Для каждой кассы Казны — маппинг в ЕРП
#    uuid = kazna.String(касса.УникальныйИдентификатор())
#    ref  = erp.А_Привилегированный.ПолучитьСправочникUID("Кассы", uuid)
#    fallback: erp.Справочники.Кассы.НайтиПоКоду(код) -> НайтиПоНаименованию(наим)
# ------------------------------------------------------------
mapped = []      # (код_казна, наим_казна, способ, наим_ерп)
unmapped = []    # (код_казна, наим_казна)

for i in range(total):
    стр = r.Получить(i)
    касса_ksn = стр.Касса
    код_ksn = kazna.String(стр.Код) if kazna.ЗначениеЗаполнено(стр.Код) else ""
    наим_ksn = kazna.String(стр.Наименование) if kazna.ЗначениеЗаполнено(стр.Наименование) else ""

    # UUID читаем В КОНТЕКСТЕ Казны (canon CLAUDE.md): kazna.String(...)
    uuid = kazna.String(касса_ksn.УникальныйИдентификатор())

    ref = None
    способ = ""

    # Спроба 1 — по UUID через привилегированный модуль ЕРП
    try:
        ref_uid = erp.А_Привилегированный.ПолучитьСправочникUID("Кассы", uuid)
        if erp.ЗначениеЗаполнено(ref_uid) and ref_uid.ПолучитьОбъект() is not None:
            ref = ref_uid
            способ = "UID"
    except Exception:
        ref = None

    # Спроба 2 — НайтиПоКоду
    if ref is None and код_ksn != "":
        try:
            ref_cod = erp.Справочники.Кассы.НайтиПоКоду(код_ksn.strip())
            if erp.ЗначениеЗаполнено(ref_cod):
                ref = ref_cod
                способ = "Код"
        except Exception:
            pass

    # Спроба 3 — НайтиПоНаименованию
    if ref is None and наим_ksn != "":
        try:
            ref_nam = erp.Справочники.Кассы.НайтиПоНаименованию(наим_ksn.strip())
            if erp.ЗначениеЗаполнено(ref_nam):
                ref = ref_nam
                способ = "Наим"
        except Exception:
            pass

    if ref is not None:
        наим_ерп = erp.String(ref.Наименование)
        mapped.append((код_ksn, наим_ksn, способ, наим_ерп))
    else:
        unmapped.append((код_ksn, наим_ksn))

# ------------------------------------------------------------
# 3) Итоги
# ------------------------------------------------------------
print("=" * 60)
print(f"Смаппилось {len(mapped)} из {total}")
print("-" * 60)
print("СМАППЛЕННЫЕ (Казна -> ЕРП):")
for код, наим, способ, наим_ерп in mapped:
    print(f"  [{способ}] Код={код} '{наим}'  ->  '{наим_ерп}'")
print("-" * 60)
print(f"НЕ СМАППЛЕНО: {len(unmapped)}")
for код, наим in unmapped:
    print(f"  Код={код} '{наим}'")
print("=" * 60)
