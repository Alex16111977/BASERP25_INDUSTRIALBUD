# -*- coding: utf-8 -*-
"""Prototype запроса для контроля К13 (BuhBud, READ-ONLY).

Оборот Кт счёта 361 за 01.08.2026 - КонецДня(14.08.2026) в разрезе
ПОДРАЗДЕЛЕНИЯ ДОГОВОРА (Субконто2 -> ДоговорыКонтрагентов.Подразделение),
фильтр: Направление договора = "Производство".

Паттерн запроса переиспользован 1:1 из живого модуля
_Rarzrabotki/BASEBuh/Documents/А_ФинансовыйОтчетПроизводства/Ext/ObjectModule.bsl
(функции ЗапросОборотов / ЗапросНеотнесенныхОборотов):
  - виртуальная таблица РегистрБухгалтерии.Хозрасчетный.Обороты
  - ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение
  - фильтр направления через реквизит договора .Направление

Даты - ЛИТЕРАЛАМИ в тексте запроса (COM теряет сутки при SetParameter).
Скрипт НИЧЕГО не пишет в базу.
"""
import sys
sys.stdout.reconfigure(encoding="utf-8")

import json
import re
import win32com.client

CONN_BUH = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
CONN_KAZNA = 'Srvr="SQLSERVER";Ref="kazna";Usr="cfo";Pwd="2442"'

# Эталон - факт поступлений казны (совпадение НЕ гарантировано, К13 ловит расхождения)
ЭТАЛОН = {
    "МК Кривий ріг": 1637071.10,
    "МД ПРООН Черкаси  ДСНС": 1317348.70,
    "МД МХП ОРІЛЬ": 391440.55,
}


def норм(имя):
    """Нормализация имени подразделения для сопоставления (двойные пробелы, регистр)."""
    return re.sub(r"\s+", " ", str(имя or "")).strip().lower()


def ошибка_ком(e):
    return e.excepinfo[2] if getattr(e, "excepinfo", None) else str(e)


v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect(CONN_BUH)

НАПРАВЛЕНИЕ = buh.Справочники.Направления.НайтиПоНаименованию("Производство", True)
if not buh.ЗначениеЗаполнено(НАПРАВЛЕНИЕ):
    print("FAIL: направление «Производство» не найдено в BuhBud")
    sys.exit(1)

СЧЕТ361 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("361")
if not buh.ЗначениеЗаполнено(СЧЕТ361):
    print("FAIL: счёт 361 не найден в Хозрасчетном")
    sys.exit(1)

СЧЕТА = buh.NewObject("Массив")
СЧЕТА.Добавить(СЧЕТ361)

# ---------------------------------------------------------------------------
# Основной запрос К13: оборот Кт 361 по подразделению договора, направление
# "Производство". Даты - литералами (грабли COM #1).
# ---------------------------------------------------------------------------
ЗАПРОС_К13 = """
ВЫБРАТЬ
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение КАК Подразделение,
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение.Наименование КАК ПодразделениеИмя,
	СУММА(Об.СуммаОборотКт) КАК ОборотКт
ИЗ
	РегистрБухгалтерии.Хозрасчетный.Обороты(ДАТАВРЕМЯ(2026, 8, 1, 0, 0, 0), ДАТАВРЕМЯ(2026, 8, 14, 23, 59, 59), ,
		Счет В (&Счета), , , , ) КАК Об
ГДЕ
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Направление = &Направление

СГРУППИРОВАТЬ ПО
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение,
	ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение.Наименование

УПОРЯДОЧИТЬ ПО
	ОборотКт УБЫВ
"""

q = buh.NewObject("Запрос")
q.Текст = ЗАПРОС_К13
q.УстановитьПараметр("Счета", СЧЕТА)
q.УстановитьПараметр("Направление", НАПРАВЛЕНИЕ)
try:
    таблица = q.Execute().Выгрузить()
except Exception as e:
    print("FAIL основной запрос:", ошибка_ком(e))
    sys.exit(1)

обороты = {}   # имя подразделения -> оборот Кт
итог = 0.0
print("=== Оборот Кт 361, 01.08.2026 - 14.08.2026 23:59:59, направление «Производство» ===")
for i in range(таблица.Количество()):
    стр = таблица.Получить(i)
    имя = str(стр.ПодразделениеИмя or "").strip() or "<без подразделения>"
    кт = float(стр.ОборотКт or 0)
    обороты[имя] = обороты.get(имя, 0.0) + кт
    итог += кт
for имя, кт in sorted(обороты.items(), key=lambda x: -x[1]):
    print(f"  {имя:45} {кт:>16,.2f}")
print(f"  {'ИТОГО':45} {итог:>16,.2f}")

# ---------------------------------------------------------------------------
# Сверка с эталоном казны (равенство НЕ обязательно - К13 ловит расхождения)
# ---------------------------------------------------------------------------
обороты_норм = {норм(k): (k, v) for k, v in обороты.items()}
сравнение = []
print("\n=== Сверка с фактом поступлений казны ===")
for имя_эт, сумма_эт in ЭТАЛОН.items():
    найдено = обороты_норм.get(норм(имя_эт))
    факт361 = найдено[1] if найдено else 0.0
    имя_361 = найдено[0] if найдено else None
    разница = round(факт361 - сумма_эт, 2)
    метка = "СОВПАЛО" if abs(разница) < 0.01 else "РАСХОЖДЕНИЕ"
    сравнение.append({
        "подразделение": имя_эт,
        "эталон_казна": сумма_эт,
        "кт361_бухбуд": round(факт361, 2),
        "разница": разница,
        "статус": метка,
        "имя_в_361": имя_361,
    })
    print(f"  {метка:12} {имя_эт:30} казна {сумма_эт:>14,.2f}  Кт361 {факт361:>14,.2f}  разница {разница:>+14,.2f}")

# ---------------------------------------------------------------------------
# МК Подгорцы: в казне есть, по 361 движения нет - ОЖИДАЕМОЕ расхождение
# ---------------------------------------------------------------------------
print("\n=== Проверка «МК Подгорцы» ===")
q_подр = buh.NewObject("Запрос")
q_подр.Текст = """
ВЫБРАТЬ
	П.Наименование КАК Имя
ИЗ
	Справочник.Подразделения КАК П
ГДЕ
	(П.Наименование ПОДОБНО "%Подгор%"
		ИЛИ П.Наименование ПОДОБНО "%Підгір%"
		ИЛИ П.Наименование ПОДОБНО "%Підгор%")
	И НЕ П.ПометкаУдаления
"""
имена_подгорцы_бух = []
try:
    т = q_подр.Execute().Выгрузить()
    имена_подгорцы_бух = [str(т.Получить(i).Имя) for i in range(т.Количество())]
except Exception as e:
    print("  WARN поиск подразделения в BuhBud:", ошибка_ком(e))
print(f"  Справочник Подразделения (BuhBud): {имена_подгорцы_бух or 'не найдено'}")

в_361 = [имя for имя in обороты if "подгор" in норм(имя) or "підгір" in норм(имя) or "підгор" in норм(имя)]
подгорцы_нет_в_361 = len(в_361) == 0
print(f"  Движение Кт 361 за период: {'НЕТ (ожидаемое расхождение подтверждено)' if подгорцы_нет_в_361 else 'ЕСТЬ: ' + str(в_361)}")

# Дополнительно: подтвердить наличие подразделения в казне (только чтение справочника)
имена_подгорцы_казна = []
try:
    kazna = v8.Connect(CONN_KAZNA)
    q_к = kazna.NewObject("Запрос")
    q_к.Текст = """
ВЫБРАТЬ
	П.Наименование КАК Имя
ИЗ
	Справочник.Подразделения КАК П
ГДЕ
	(П.Наименование ПОДОБНО "%Подгор%"
		ИЛИ П.Наименование ПОДОБНО "%Підгір%"
		ИЛИ П.Наименование ПОДОБНО "%Підгор%")
	И НЕ П.ПометкаУдаления
"""
    т = q_к.Execute().Выгрузить()
    имена_подгорцы_казна = [str(т.Получить(i).Имя) for i in range(т.Количество())]
    print(f"  Справочник Подразделения (kazna): {имена_подгорцы_казна or 'не найдено'}")
except Exception as e:
    print("  WARN kazna недоступна:", ошибка_ком(e))

# ---------------------------------------------------------------------------
# Итог для оркестратора
# ---------------------------------------------------------------------------
результат = {
    "период": "2026-08-01 .. 2026-08-14 23:59:59",
    "счет": "361 Кт",
    "направление": "Производство",
    "обороты_по_подразделениям": {k: round(v, 2) for k, v in sorted(обороты.items(), key=lambda x: -x[1])},
    "итого_кт361": round(итог, 2),
    "сравнение_с_казной": сравнение,
    "мк_подгорцы": {
        "в_справочнике_бухбуд": имена_подгорцы_бух,
        "в_справочнике_казна": имена_подгорцы_казна,
        "движение_кт361_отсутствует": подгорцы_нет_в_361,
    },
}
print("\nJSON_RESULT:")
print(json.dumps(результат, ensure_ascii=False, indent=2))
