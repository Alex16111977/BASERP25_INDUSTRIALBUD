"""Пре-тест СверкаСПАП. Часть 1 (Task 4): эталон ПАП.ОстаткиИОбороты по
(Орг,Подр,Статья), 4 ресурса, фильтр исключения 3 групп (OD-3); Σ КонОст ≈ 0
(Актив=Пассив, закрытый январь). Часть 2 (Task 11): провести документ и
сверить Σ Свод по (Орг,Подр,Статья) == эталон до копейки + контроль Расхождение."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime
pythoncom.CoInitialize()
ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q0 = ERP.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qm = ERP.NewObject("Запрос")
qm.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qm.УстановитьПараметр("М", datetime(2026, 1, 1, 12, 0, 0))
rm = qm.Выполнить().Выбрать(); rm.Следующий()

qi = ERP.NewObject("Запрос")
qi.Текст = ('ВЫБРАТЬ Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Сп)')
a = ERP.NewObject("Массив")
for n in ["Собственные средства", "Доходы текущего периода",
          "Расходы текущего периода"]:
    a.Добавить(n)
qi.УстановитьПараметр("Сп", a)
ИСКЛ = qi.Выполнить().Выгрузить().ВыгрузитьКолонку("С")

qe = ERP.NewObject("Запрос")
qe.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Б.Статья) КАК Ст,
 СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
 Организация = &Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Б.Статья)
ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток) <> 0"""
qe.УстановитьПараметр("Д1", rm.НМ); qe.УстановитьПараметр("Д2", rm.КД)
qe.УстановитьПараметр("Орг", ORG); qe.УстановитьПараметр("Искл", ИСКЛ)
te = qe.Выполнить().Выгрузить()
et = {str(te.Получить(i).Ст): float(te.Получить(i).sK or 0)
      for i in range(te.Количество())}
ΣК = sum(et.values())
print(f"Эталон ПАП (январь/ТОВ, OD-3 фильтр): статей={len(et)}; "
      f"Σ КонОст = {ΣК:,.2f}")
assert abs(ΣК) < 1.0, f"FAIL: Σ КонОст эталона != 0 ({ΣК:,.2f}) — период открыт?"
print("PASS test_balans_m_sverka (часть1: эталон ПАП, Актив=Пассив)")
