"""
Прототип детектора задвоения ПДВ «за першою подією» (рахунок 6442) — BAS Бухгалтерія (bas_industrialbud).

Ідея (перевірено 28.09.2026):
  Рішення «перша/друга подія» приймає НалоговыйУчет.ДвиженияПоРегистрамНалоговогоУчетаУпрощенныйНалоговыйУчет
  за залишками РН ПриобретенияНалоговыйУчет на МоментВремени документа:
      ПС = max(Надходження, Оплата)_після − max(Надходження, Оплата)_до
  РН ПриобретенияНалоговыйУчет пишеться ОДНАКОВО за будь-якого порядку проведення (повні суми подій),
  «Закриття місяця» згортає обидві сторони на однакову суму (max зсувається рівно на неї → не впливає на ПС).
  Тому «правильну» ПС кожного документа можна обчислити хронологічним проходом і порівняти з фактом —
  рухами РН ОжидаемыйИПодтвержденныйНДСПриобретений (КодОперации = ОжидаемыйНДС) цього документа.

Факт: подія «Возврат» у ОиП пишеться ПРИХОДОМ з додатним НДС → у факт іде зі знаком «−».
ОиП пишеться лише для гривневих договорів → валютні договори виключено.

Запуск:  python pdv6442_detector_prototype.py [YYYY-MM-DD]      (за замовчуванням 2026-01-01)
Запити написані 1:1 як для BSL (Rule #-1). Тривалість ~3–4 хв через COM (24 тис. рухів).
"""
