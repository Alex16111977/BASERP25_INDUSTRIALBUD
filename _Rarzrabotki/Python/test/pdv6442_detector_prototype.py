def connect():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    last = None
    for s in CONNS:
        try:
            return v8.Connect(s)
        except Exception as e:  # noqa
            last = e
    raise SystemExit(f"FAIL connect: {last}")


def run(c, text, **params):
    z = c.NewObject("Запрос")
    z.Text = text
    for k, v in params.items():
        z.SetParameter(k, v)
    try:
        return z.Execute().Выбрать()
    except Exception as e:
        info = e.excepinfo[2] if getattr(e, 'excepinfo', None) else e
        raise SystemExit(f"FAIL query: {info}")


def main():
    date_from = sys.argv[1] if len(sys.argv) > 1 else '2026-01-01'
    y, m, d = map(int, date_from.split('-'))
    c = connect()
    t0 = time.time()
    X = c.XMLString
    names = {}

    def nm(ref):
        k = X(ref)
        if k not in names:
            names[k] = c.String(ref)
        return k

    params = dict(ДатаНачала=datetime.datetime(y, m, d),
                  Гривня=c.Константы.ВалютаРегламентированногоУчета.Получить())
    ev = c.Перечисления.СобытияПриобретенияНалоговыйУчет
    ev_o = {X(ev.ПоступлениеОтПоставщика): 1, X(ev.ВозвратПоставщику): -1}
    ev_p = {X(ev.ОплатаПоставщику): 1, X(ev.ВозвратОплатыПоставщиком): -1}

    fact = collections.defaultdict(float)
    sel = run(c, QUERY_FACT, **params)
    while sel.Следующий():
        key = tuple(nm(getattr(sel, f)) for f in KEY_DIMS)
        fact[(key, nm(sel.Регистратор))] += float(sel.СуммаНДС)
    print(f"факт ОиП: {len(fact)} пар (ключ, документ), {time.time()-t0:.0f} c", flush=True)

    # Хронологічний прохід. У BSL — той самий цикл по Выборке, впорядкованій за ключем, Периодом, Регистратором.
    # У BSL порядок усередині однакового Периода брати за МоментВремени документа (Дата+Ссылка), як бачить
    # сама конфігурація; тут — за Регистратором (для документів з однаковим часом можливі «перестановки» пар).
    bad = []                       # (ключ, документ, очікувано, факт)
    first_bad = {}                 # ключ -> перший документ розбіжності
    state = {}                     # ключ -> [O, P]
    counters = {'checked': 0}
    acc = []                       # [ключ, документ, dO, dP] — поточний документ

    def close_doc():
        if not acc:
            return
        key, reg, dO, dP = acc
        acc.clear()
        st = state.setdefault(key, [0.0, 0.0])
        before = max(st)
        st[0] += dO
        st[1] += dP
        exp = max(st) - before
        act = fact.get((key, reg), 0.0)
        counters['checked'] += 1
        if abs(act - exp) > TOL:
            bad.append((key, reg, round(exp, 2), round(act, 2)))
            first_bad.setdefault(key, reg)

    sel = run(c, QUERY_MOVES, **params)
    while sel.Следующий():
        key = tuple(nm(getattr(sel, f)) for f in KEY_DIMS)
        e = X(sel.Событие)
        vat = float(sel.СуммаНДС)
        dO = ev_o.get(e, 0) * vat
        dP = ev_p.get(e, 0) * vat
        if int(sel.Порядок) == 0 or sel.ЭтоЗакрытие:
            close_doc()            # вхідний залишок / «Закриття місяця» — без очікуваної ПС
            st = state.setdefault(key, [0.0, 0.0])
            st[0] += dO
            st[1] += dP
            continue
        reg = nm(sel.Регистратор)
        if not acc or acc[0] != key or acc[1] != reg:
            close_doc()
            acc.extend([key, reg, 0.0, 0.0])
        acc[2] += dO
        acc[3] += dP
    close_doc()

    surplus = collections.defaultdict(float)
    for key, reg, exp, act in bad:
        surplus[key] += act - exp
    print(f"перевірено документів: {counters['checked']}; розбіжних: {len(bad)}; ключів: {len(first_bad)}; "
          f"надлишок ПС (факт−очік.): {sum(surplus.values()):.2f}; {time.time()-t0:.0f} c")
    for key, s in sorted(surplus.items(), key=lambda kv: -abs(kv[1]))[:30]:
        print(f"{s:14.2f} | {names[key[0]][:16]} | {names[key[1]][:34]} | {names[key[2]][:60]} | "
              f"{names[key[4]]} | перший: {names[first_bad[key]][:70]}")
    hit = [b for b in bad if '000013825' in names[b[1]]]
    print("приклад 000013825:", [(names[b[1]], b[2], b[3]) for b in hit] or "НЕ знайдено (вже виправлено?)")


if __name__ == '__main__':
    main()
