# -*- coding: utf-8 -*-
"""
SMOKE: создаёт Документ.А_ПередачаНачисленийМеждуПодразделениями через метод объекта
А_ОтражениеЗПпоКазне №000000005 и проверяет движения:
  - документ создан и проведён;
  - Σ signed ПАП(Регистратор=новый) = 0 (всего и по каждой статье — net-zero реверс/копия);
  - Σ signed А_ВзСС(Регистратор=новый) = 0;
  - ТЧ Начисления Σ == ПАП(Оплата труда).Приход (реверс на исходных = сумма ТЧ).
Запуск: C:\\Python313\\python.exe <этот файл>
"""
import win32com.client as w
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

erp = w.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def run(text, **p):
    z = erp.NewObject("Запрос"); z.Текст = text
    for k, v in p.items():
        z.УстановитьПараметр(k, v)
    return z.Выполнить().Выгрузить()


def one(tz, col, i=0):
    return getattr(tz.Получить(i), col) if tz.Количество() > i else None


fails = []

# --- создать передачу через метод объекта родителя ---
parent = run('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.А_ОтражениеЗПпоКазне ГДЕ Номер = "000000005" И Проведен').Получить(0).С
parent.ПолучитьОбъект().СоздатьПередачуНачисленийМеждуПодразделениями()

ndt = run('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С, Проведен КАК П ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями '
          'ГДЕ А_ДокументОснование = &Р', Р=parent)
if ndt.Количество() != 1:
    print("FAIL: документ передачи не создан"); sys.exit(1)
nd = ndt.Получить(0).С
provd = ndt.Получить(0).П
print("Документ передачи:", nd, "| Проведён:", provd)
if not provd:
    fails.append("документ не проведён")

# --- ПАП движения нового документа ---
pap = run("""
ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(П.Статья) КАК Статья,
  СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Signed,
  СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА П.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Приход,
  СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) ТОГДА П.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Расход,
  КОЛИЧЕСТВО(*) КАК Строк
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
ГДЕ П.Регистратор = &Д
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(П.Статья)""", Д=nd)
print("\nПАП движения (Регистратор=новый документ):")
tot = 0.0
ot_prihod = 0.0
for i in range(pap.Количество()):
    r = pap.Получить(i)
    s = round(float(r.Signed), 2)
    tot += s
    if r.Статья == "Оплата труда":
        ot_prihod = round(float(r.Приход), 2)
    print(f"  {r.Статья:<22} Signed={s:>14.2f}  Приход={float(r.Приход):>14.2f}  Расход={float(r.Расход):>14.2f}  строк={r.Строк}")
    if abs(s) > 0.01:
        fails.append(f"ПАП статья '{r.Статья}' Signed={s} != 0 (нет пары реверс/копия)")
tot = round(tot, 2)
print(f"  ИТОГО Signed ПАП = {tot:.2f}")
if abs(tot) > 0.01:
    fails.append(f"Σ ПАП Signed={tot} != 0")
if pap.Количество() == 0:
    fails.append("ПАП движений нет")

# --- А_ВзСС движения нового документа ---
vzs = run("""
ВЫБРАТЬ
  СУММА(ВЫБОР КОГДА ВзСС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ВзСС.СуммаВзаиморасчетов ИНАЧЕ -ВзСС.СуммаВзаиморасчетов КОНЕЦ) КАК Signed,
  СУММА(ВзСС.СуммаВзаиморасчетов) КАК Оборот,
  КОЛИЧЕСТВО(*) КАК Строк
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзСС
ГДЕ ВзСС.Регистратор = &Д""", Д=nd)
vsigned = round(float(one(vzs, "Signed") or 0), 2)
vstrok = one(vzs, "Строк") or 0
print(f"\nА_ВзСС: Signed={vsigned:.2f}  оборот={float(one(vzs,'Оборот') or 0):.2f}  строк={vstrok}")
if abs(vsigned) > 0.01:
    fails.append(f"Σ А_ВзСС Signed={vsigned} != 0")
if vstrok == 0:
    fails.append("А_ВзСС движений нет")

# --- ТЧ Начисления Σ == ПАП(Оплата труда).Приход ---
tch_nach = round(float(one(run(
    'ВЫБРАТЬ СУММА(Сумма) КАК С ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.Начисления ГДЕ Ссылка = &Д', Д=nd),
    "С") or 0), 2)
print(f"\nТЧ Начисления Σ = {tch_nach:.2f}  | ПАП(Оплата труда).Приход = {ot_prihod:.2f}")
if abs(tch_nach - ot_prihod) > 0.01:
    fails.append(f"ТЧ Начисления Σ ({tch_nach}) != ПАП(ОТ).Приход ({ot_prihod})")

# счётчики ТЧ
for тч in ("Начисления", "Налоги", "Удержания"):
    c = one(run(f'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ Документ.А_ПередачаНачисленийМеждуПодразделениями.{тч} ГДЕ Ссылка = &Д', Д=nd), "К")
    print(f"  ТЧ {тч}: {c} строк")

print("\n" + ("SMOKE PASS" if not fails else "SMOKE FAIL:\n  - " + "\n  - ".join(fails)))
sys.exit(0 if not fails else 1)
