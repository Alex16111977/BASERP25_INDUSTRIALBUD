# -*- coding: utf-8 -*-
# СКД-smoke собранного .erf А_РасшифровкаПартийСписаннойНоменклатуры:
# 1) Создать .erf через COM (ObjectModule компилируется против реальной BuhBud);
# 2) ПолучитьДанные(реал) -> эталон Біта РН -> Надходження ІБ00-007655 в ТЗ;
# 3) программная компоновка СКД с внешним набором "Данные" -> ВысотаТаблицы > 0.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
def S(v):
    try: return buh.String(v) if v is not None else "None"
    except: return "<?>"
def full(v):
    try: return v.Метаданные().ПолноеИмя()
    except: return ""

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_РасшифровкаПартийСписаннойНоменклатуры.erf"
отчет = buh.ВнешниеОтчеты.Создать(ERF)
мета = отчет.Метаданные()
print("Отчёт:", мета.ПолноеИмя(), "| Имя:", мета.Имя)
try:
    print("ОсновнаяФорма:", мета.ОсновнаяФорма.ПолноеИмя())
except Exception as e:
    print("ОсновнаяФорма (raw):", S(мета.ОсновнаяФорма))

q = buh.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.РеализацияТоваровУслуг "
          "ГДЕ Номер=&Н И Дата>=ДАТАВРЕМЯ(2026,1,1) УПОРЯДОЧИТЬ ПО Дата УБЫВ")
q.SetParameter("Н", "ІБ00-000113")
s = q.Execute().Выбрать(); s.Следующий(); реал = s.Ссылка
print("Реализация:", S(реал))

# --- (2) ПолучитьДанные + эталон ---
тз = отчет.ПолучитьДанные(реал)
print("ПолучитьДанные строк:", тз.Количество())
эталон = False; кол = 0.0; сум = 0.0; докОК = True
for r in тз:
    кол += r.Количество; сум += r.Сумма
    if full(r.Документ) != "Документ.РеализацияТоваровУслуг":
        докОК = False
    if "Біта РН 2*50" in S(r.Номенклатура) and "ІБ00-007655" in S(r.ПартияПрихода) \
       and full(r.ПартияПрихода) == "Документ.ПоступлениеТоваровУслуг":
        эталон = True
        print("  ЭТАЛОН:", S(r.Номенклатура), "| списання:", S(r.ПартияСписания)[:40],
              "| прихід:", S(r.ПартияПрихода), "| Кол=", r.Количество, "Сум=", r.Сумма)
print(f"Σ Кол={round(кол,3)}  Σ Сум={round(сум,2)}  (ожидалось Кол=3800.016 Сум=59663.36)")
print("Документ=Реализация во всех строках:", "OK" if докОК else "FAIL")
print("ЭТАЛОН в ТЗ:", "OK" if эталон else "FAIL")

# --- multi-batch: Кол/Сум не должны висеть на тупике-Перемещении, если есть реальный приход ---
плохих = 0
for r in тз:
    if r.Сумма != 0 and full(r.ПартияПрихода) == "Документ.ПеремещениеТоваров":
        плохих += 1
        print("  ВНИМАНИЕ: Сум на тупике-Перемещении:", S(r.Номенклатура), "->", S(r.ПартияПрихода))
print("Кол/Сум на реальном приходе (не тупик), multi-batch детерминизм:", "OK" if плохих == 0 else f"FAIL ({плохих})")

# --- (3) СКД-композиция с внешним набором "Данные" (как ПриКомпоновкеРезультата) ---
настройки = отчет.КомпоновщикНастроек.ПолучитьНастройки()
настройки.ПараметрыДанных.УстановитьЗначениеПараметра("ДокументРеализации", реал)
дР = buh.NewObject("ДанныеРасшифровкиКомпоновкиДанных")
try:
    схема = отчет.СхемаКомпоновкиДанных
except Exception:
    схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
км = buh.NewObject("КомпоновщикМакетаКомпоновкиДанных")
макет = км.Выполнить(схема, настройки, дР)
внеш = buh.NewObject("Структура"); внеш.Вставить("Данные", тз)
проц = buh.NewObject("ПроцессорКомпоновкиДанных")
проц.Инициализировать(макет, внеш, дР)
пв = buh.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
таб = buh.NewObject("ТабличныйДокумент")
пв.УстановитьДокумент(таб)
пв.Вывести(проц)
print("ВысотаТаблицы=", таб.ВысотаТаблицы, " ШиринаТаблицы=", таб.ШиринаТаблицы)
print("СКД-SMOKE:", "OK" if таб.ВысотаТаблицы > 0 else "FAIL")

# --- (4) ДЕФИНИТИВНО: СкомпоноватьРезультат (как кнопка «Сформувати» -> ПриКомпоновкеРезультата) ---
# Именно этот путь падал в приложении «Метод объекта не обнаружен (ПолучитьПараметр)».
отчет2 = buh.ВнешниеОтчеты.Создать(ERF)
отчет2.КомпоновщикНастроек.Настройки.ПараметрыДанных.УстановитьЗначениеПараметра("ДокументРеализации", реал)
таб2 = buh.NewObject("ТабличныйДокумент")
скд_ок = False
try:
    отчет2.СкомпоноватьРезультат(таб2)
    скд_ок = таб2.ВысотаТаблицы > 0
    print("СкомпоноватьРезультат: OK  ВысотаТаблицы=", таб2.ВысотаТаблицы)
except Exception as e:
    print("СкомпоноватьРезультат FAIL:", e.excepinfo[2] if getattr(e,'excepinfo',None) else e)
print("СФОРМУВАТИ (end-to-end ПриКомпоновкеРезультата):", "OK" if скд_ок else "FAIL")

итог = эталон and докОК and таб.ВысотаТаблицы > 0 and скд_ок and плохих == 0
print("\n=== РЕЗУЛЬТАТ SMOKE:", "✅ GREEN" if итог else "❌ RED", "===")
