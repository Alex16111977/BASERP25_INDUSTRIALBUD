def агрегат_тч_по_типу(o):
    """Σ СуммаСальдо (signed Кт-Дт) по ТипНалога; ключ = XMLСтрока(ТипНалога)."""
    res = {}
    n = o.Налоги.Количество()
    for i in range(n):
        стр = o.Налоги.Получить(i)
        тип = XML(стр.ТипНалога)
        res[тип] = round(res.get(тип, 0.0) + float(стр.СуммаСальдо), 2)
    return res, n


def агрегат_тч_по_счету_signed(o):
    """Σ signed СуммаСальдо (Кт-Дт) по коду счёта.
    Хозрасчетный пишет знак: сальдо>0 -> Кт<счёт>(+), сальдо<0 -> Дт<счёт>(-),
    поэтому корректная сверка — signed Σ ТЧ == нетто (Кт-Дт) регистра по счёту."""
    signed = {}
    n = o.Налоги.Количество()
    for i in range(n):
        стр = o.Налоги.Получить(i)
        if not ЗАП(стр.Счет):
            continue
        код = str(стр.КодСчета).strip()
        signed[код] = round(signed.get(код, 0.0) + float(стр.СуммаСальдо), 2)
    return signed


def пап_по_типу(reg_kr):
    """Records-level ПАП этого регистратора, статья=Налоги: signed по Аналитика(ТипНалога)."""
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("КР", reg_kr)
    q.Текст = """ВЫБРАТЬ
    П.Аналитика КАК Аналитика,
    СУММА(ВЫБОР КОГДА П.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА П.Сумма ИНАЧЕ -П.Сумма КОНЕЦ) КАК Сумма
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
    ГДЕ П.Регистратор = &КР
        И П.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.Налоги)
    СГРУППИРОВАТЬ ПО П.Аналитика"""
    res = {}
    в = q.Выполнить().Выбрать()
    while в.Следующий():
        res[XML(в.Аналитика)] = round(float(в.Сумма), 2)
    return res


