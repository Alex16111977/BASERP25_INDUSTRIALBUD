def удалить_документ(ref, имя):
    """Throwaway cleanup: снять проведение (очистить движения) -> Удалить().

    Просто Удалить() у проведённого документа оставляет наборы движений сиротами,
    поэтому сначала отменяем проведение (это активные наборы запишет пустыми),
    затем удаляем сам документ с ОбменДанными.Загрузка=Истина.
    """
    if ref is None or not ЗАП(ref):
        print(f"  CLEANUP: {имя} — ссылка пуста, удалять нечего")
        return
    об = ref.ПолучитьОбъект()
    if об is None:
        print(f"  CLEANUP: {имя} — объект уже отсутствует")
        return
    # 1) снять проведение -> очистить движения (КР записан без проведения, поэтому Попытка).
    #    ОтменаПроведения НЕ в режиме загрузки (иначе «Действие не может в режиме загрузки»).
    try:
        if об.Проведен:
            об.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
            об = ref.ПолучитьОбъект()  # перечитать после записи
    except Exception as e:
        print(f"  CLEANUP: {имя} — отмена проведения не потребовалась/не удалась: {e}")
    # 2) очистить наборы движений напрямую (для КР, который записан БЕЗ проведения)
    for имя_рег in ("ПрочиеАктивыПассивы", "Хозрасчетный"):
        try:
            набор = getattr(об.Движения, имя_рег)
            набор.Записывать = True
            набор.Очистить()
            набор.Записать()
        except Exception:
            pass  # у этого документа такого набора нет — норм
    # 3) удалить документ
    об = ref.ПолучитьОбъект()
    об.ОбменДанными.Загрузка = True
    об.Удалить()
    print(f"  CLEANUP: удалён {имя}: {XML(ref)}")


