def хозрасчетный_нетто_по_счету(reg_ob):
    """Нетто Кт-Дт по налоговым счетам (исключая 00) + Σ Дт, Σ Кт по документу."""
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("ОБ", reg_ob)
    # СчётДт/СчётКт у Хозрасчетного — измерения; код достаём через .Код
    q.Текст = """ВЫБРАТЬ
    Х.СчетДт.Код КАК КодДт,
    Х.СчетКт.Код КАК КодКт,
    Х.Сумма КАК Сумма
    ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
    ГДЕ Х.Регистратор = &ОБ"""
    нетто, сумДт, сумКт = {}, 0.0, 0.0
    в = q.Выполнить().Выбрать()
    while в.Следующий():
        с = float(в.Сумма)
        кд = str(в.КодДт).strip() if в.КодДт is not None else ""
        кк = str(в.КодКт).strip() if в.КодКт is not None else ""
        сумДт += с; сумКт += с
        if кк and кк != "00":
            нетто[кк] = round(нетто.get(кк, 0.0) + с, 2)   # Кт: +
        if кд and кд != "00":
            нетто[кд] = round(нетто.get(кд, 0.0) - с, 2)   # Дт: -
    return нетто, round(сумДт, 2), round(сумКт, 2)


