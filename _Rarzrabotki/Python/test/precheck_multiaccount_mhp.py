"""Подтверждение многосчётности на РЕАЛЬНОМ складе задачи (МХП ОРІЛЬ виробничий, скрин)."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
НаДату = pywintypes.Time(datetime.datetime(2026, 6, 22, 23, 59, 59))

Счета = buh.NewObject("Массив")
for код in ("20", "22", "28"):
    Счета.Добавить(buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код))

qСк = buh.NewObject("Запрос")
qСк.Текст = ('ВЫБРАТЬ Склады.Ссылка КАК С, Склады.Наименование КАК Н ИЗ Справочник.Склады КАК Склады '
             'ГДЕ Склады.Наименование ПОДОБНО "%МХП%ОР%виробнич%"')
tСк = qСк.Выполнить().Выгрузить()
Склады = buh.NewObject("Массив")
for i in range(tСк.Количество()):
    Склады.Добавить(tСк.Получить(i).С)
    print("склад:", tСк.Получить(i).Н)

q = buh.NewObject("Запрос")
q.УстановитьПараметр("НаДату", НаДату)
q.УстановитьПараметр("Счета", Счета)
q.УстановитьПараметр("Склады", Склады)
q.Текст = """
ВЫБРАТЬ Ост.Счет КАК Счет, Ост.Организация КАК Орг, СУММА(Ост.КоличествоОстаток) КАК К
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ(&Счета), , ) КАК Ост
ГДЕ Ост.КоличествоОстаток > 0 И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) В (&Склады)
СГРУППИРОВАТЬ ПО Ост.Счет, Ост.Организация
"""
t = q.Выполнить().Выгрузить()
print(f"строк-групп (Счет×Орг): {t.Количество()}")
rows = sorted([(str(t.Получить(i).Счет.Код), buh.String(t.Получить(i).Орг), round(float(t.Получить(i).К),2)) for i in range(t.Количество())])
for код, орг, к in rows:
    print(f"   счёт {код}  {орг}  Σ={к}")
