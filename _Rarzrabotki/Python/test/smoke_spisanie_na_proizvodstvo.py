# -*- coding: utf-8 -*-
"""Приёмка внешнего отчёта А_ОтчетПоСписаниюНаПроизводство на живой BaseERP.

Сверяет результат ПолучитьДанные() с НЕЗАВИСИМЫМИ запросами в тот же момент времени
(база живая, расчёт себестоимости прогоняют — константы приёмки быстро протухают).

Запуск:  python _Rarzrabotki/Python/test/smoke_spisanie_na_proizvodstvo.py
"""
import win32com.client, pythoncom, sys, datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетПоСписаниюНаПроизводство.erf"
CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
ДАТА_НАЧАЛА = datetime.datetime(2026, 1, 1, 0, 0, 0)
ДАТА_ОКОНЧАНИЯ = datetime.datetime(2026, 8, 31, 0, 0, 0)

ЭПС = 0.05  # копеечный допуск на округления

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
S = erp.String

провалов = 0
проверок = 0


def проверка(имя, условие, деталь=""):
    global провалов, проверок
    проверок += 1
    метка = "OK  " if условие else "FAIL"
    if not условие:
        провалов += 1
    print(f"  [{метка}] {имя}" + (f" — {деталь}" if деталь else ""))


def дата_для_1с(цель):
    """Подбирает Python-datetime так, чтобы 1С увидела РОВНО заданный момент.

    COM-прослойка сдвигает datetime на смещение часового пояса, и величина сдвига зависит
    от даты (январь UTC+2, август UTC+3) — мерить один раз и применять ко всему году нельзя,
    иначе начало периода уезжает на час и отсекает документы от 00:00:00 первого дня.
    """
    кандидат = цель
    for _ in range(5):
        q = erp.NewObject("Запрос")
        q.Text = ("ВЫБРАТЬ ГОД(&Д) КАК Г, МЕСЯЦ(&Д) КАК М, ДЕНЬ(&Д) КАК Д,"
                  " ЧАС(&Д) КАК Ч, МИНУТА(&Д) КАК Мин, СЕКУНДА(&Д) КАК С")
        q.SetParameter("Д", кандидат)
        r = q.Execute().Выгрузить().Получить(0)
        видит = datetime.datetime(int(r.Г), int(r.М), int(r.Д), int(r.Ч), int(r.Мин), int(r.С))
        if видит == цель:
            return кандидат
        кандидат = кандидат + (цель - видит)
    raise RuntimeError(f"не удалось подобрать дату под {цель}")


# ---------------------------------------------------------------- 1. открыть отчёт
print("=== 1. Открытие внешнего отчёта ===")
отчет = erp.ВнешниеОтчеты.Создать(ERF)
проверка("ВнешниеОтчеты.Создать отработал", отчет is not None)

НАЧ = дата_для_1с(ДАТА_НАЧАЛА)
КОН = дата_для_1с(ДАТА_ОКОНЧАНИЯ)
период = erp.NewObject("СтандартныйПериод")
период.ДатаНачала = НАЧ
период.ДатаОкончания = КОН

qd = erp.NewObject("Запрос")
qd.Text = ("ВЫБРАТЬ ГОД(&Д1) КАК Г1, МЕСЯЦ(&Д1) КАК М1, ДЕНЬ(&Д1) КАК Д1, ЧАС(&Д1) КАК Ч1,"
           " ДЕНЬ(&Д2) КАК Д2, МЕСЯЦ(&Д2) КАК М2")
qd.SetParameter("Д1", НАЧ)
qd.SetParameter("Д2", КОН)
д = qd.Execute().Выгрузить().Получить(0)
проверка("границы периода скомпенсированы под сдвиг COM",
         д.Г1 == 2026 and д.М1 == 1 and д.Д1 == 1 and д.Ч1 == 0 and д.Д2 == 31 and д.М2 == 8,
         f"1С видит {д.Д1:.0f}.{д.М1:.0f}.{д.Г1:.0f} {д.Ч1:.0f}ч — {д.Д2:.0f}.{д.М2:.0f}")

ТЗ = отчет.ПолучитьДанные(период)
проверка("ПолучитьДанные вернул строки", ТЗ.Количество() > 0, f"строк={ТЗ.Количество()}")

# ---------------------------------------------------------------- 2. свод по отчёту
кол = ТЗ.Количество()
СВОД = {}
итог = dict(ПланКол=0.0, ПланГрн=0.0, ФактКол=0.0, ФактГрнСоб=0.0, ФактГрнПлан=0.0)
факт_без_этапа = 0
факт_всего = 0
по_статусу = {}
статус_с_ценой_но_нулём = 0
парные = dict(соб=0.0, план=0.0, строк=0)
без_себестоимости = 0

for i in range(кол):
    с = ТЗ.Получить(i)
    др = S(с.Подразделение)
    г = СВОД.setdefault(др, dict(ПланКол=0.0, ПланГрн=0.0, ФактКол=0.0, ФактГрнСоб=0.0,
                                 ФактГрнПлан=0.0, викон=set(), викон_план=set()))
    for k in ("ПланКол", "ПланГрн", "ФактКол", "ФактГрнСоб", "ФактГрнПлан"):
        v = float(getattr(с, k))
        г[k] += v
        итог[k] += v
    план = (с.ВидДокумента == "0. План")
    if план:
        г["викон_план"].add(S(с.ПодразделениеИсполнитель))
    else:
        факт_всего += 1
        г["викон"].add(S(с.ПодразделениеИсполнитель))
        if not S(с.Этап):
            факт_без_этапа += 1
        ст = S(с.СтатусПлана)
        а = по_статусу.setdefault(ст, dict(строк=0, соб=0.0, план=0.0))
        а["строк"] += 1
        а["соб"] += float(с.ФактГрнСоб)
        а["план"] += float(с.ФактГрнПлан)
        if ст != "1. В плані" and float(с.ФактГрнПлан) != 0:
            статус_с_ценой_но_нулём += 1
        # для санитарной проверки методики берём ТОЛЬКО парные строки: где есть и себестоимость,
        # и оценка в плановых ценах. Строки без себестоимости — это незакрытый месяц, а не дефект.
        if float(с.ФактГрнСоб) != 0 and float(с.ФактГрнПлан) != 0:
            парные["соб"] += float(с.ФактГрнСоб)
            парные["план"] += float(с.ФактГрнПлан)
            парные["строк"] += 1
        elif float(с.ФактГрнПлан) != 0:
            без_себестоимости += 1

print(f"\n=== 2. Свод отчёта (драйверов={len(СВОД)}) ===")
for др, г in sorted(СВОД.items()):
    print(f"  {др[:44]:46} план {г['ПланКол']:>12,.3f} / {г['ПланГрн']:>14,.2f}"
          f" | факт {г['ФактКол']:>12,.3f} / {г['ФактГрнСоб']:>14,.2f}"
          f" | вик.план={len(г['викон_план'])} вик.факт={len(г['викон'])}")
print(f"  {'ИТОГО':46} план {итог['ПланКол']:>12,.3f} / {итог['ПланГрн']:>14,.2f}"
      f" | факт {итог['ФактКол']:>12,.3f} / {итог['ФактГрнСоб']:>14,.2f}")

# ---------------------------------------------------------------- 3. эталон плана
print("\n=== 3. План: норма ТЧ × КоличествоДомов (независимый запрос) ===")
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	ВЫБОР
		КОГДА СС.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА СС.ПодразделениеОбъекта
		ИНАЧЕ СС.Подразделение
	КОНЕЦ КАК Драйвер,
	СУММА(К.Количество * ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ) КАК ПланКол,
	СУММА(К.Сумма * ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ) КАК ПланГрн
ИЗ
	Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
		ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.А_СтруктураСебестоимости КАК СС
		ПО К.Ссылка = СС.Ссылка
ГДЕ
	НЕ СС.ЭтоГруппа И СС.Активная
СГРУППИРОВАТЬ ПО
	ВЫБОР
		КОГДА СС.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА СС.ПодразделениеОбъекта
		ИНАЧЕ СС.Подразделение
	КОНЕЦ
"""
r = q.Execute().Выгрузить()
ok_план = True
for i in range(r.Количество()):
    э = r.Получить(i)
    др = S(э.Драйвер)
    г = СВОД.get(др)
    if г is None:
        ok_план = False
        print(f"     нет в отчёте: {др}")
        continue
    dk = abs(г["ПланКол"] - float(э.ПланКол))
    dg = abs(г["ПланГрн"] - float(э.ПланГрн))
    if dk > ЭПС or dg > ЭПС:
        ok_план = False
        print(f"     {др[:44]:46} Δкол={dk:.4f} Δгрн={dg:.4f}")
проверка("Σ план по исполнителям == норма × КоличествоДомов (инвариант тиража)", ok_план)

# ---------------------------------------------------------------- 4. эталон факта
print("\n=== 4. Факт: независимый запрос по РН.СебестоимостьТоваров ===")
ЭТ_ФАКТ = """
ВЫБРАТЬ
	СУММА(СТ.Количество) КАК ФактКол,
	СУММА(СТ.Стоимость) КАК ФактГрн
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
	И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
	И СТ.Период МЕЖДУ &НачП И &КонП
	И ТИПЗНАЧЕНИЯ(СТ.Регистратор) В (ТИП(Документ.СборкаТоваров), ТИП(Документ.ВнутреннееПотреблениеТоваров))
	И СТ.Подразделение В ИЕРАРХИИ (&Драйвер)
"""
qd2 = erp.NewObject("Запрос")
qd2.Text = "ВЫБРАТЬ КОНЕЦПЕРИОДА(&Д, ДЕНЬ) КАК КД"
qd2.SetParameter("Д", КОН)
конец_дня = qd2.Execute().Выгрузить().Получить(0).КД

ok_факт = True
for др, г in sorted(СВОД.items()):
    qq = erp.NewObject("Запрос")
    qq.Text = ЭТ_ФАКТ
    # ссылку на драйвер берём из самой ТЗ отчёта
    ссылка = None
    for i in range(кол):
        if S(ТЗ.Получить(i).Подразделение) == др:
            ссылка = ТЗ.Получить(i).Подразделение
            break
    qq.SetParameter("Драйвер", ссылка)
    qq.SetParameter("НачП", НАЧ)
    qq.SetParameter("КонП", конец_дня)
    э = qq.Execute().Выгрузить().Получить(0)
    эк = float(э.ФактКол or 0)
    эг = float(э.ФактГрн or 0)
    dk, dg = abs(г["ФактКол"] - эк), abs(г["ФактГрнСоб"] - эг)
    if dk > ЭПС or dg > ЭПС:
        ok_факт = False
        print(f"     {др[:44]:46} отчёт {г['ФактКол']:.3f}/{г['ФактГрнСоб']:.2f}"
              f" эталон {эк:.3f}/{эг:.2f}")
проверка("Σ факт == РН.СебестоимостьТоваров (Расход, Сборка+ВнутрПотребление)", ok_факт)

# ---------------------------------------------------------------- 5. смысловые инварианты
print("\n=== 5. Смысловые инварианты ===")
IRS15 = [d for d in СВОД if "15 м" in d]
if IRS15:
    г = СВОД[IRS15[0]]
    проверка("IRS 15 м: план роздано на 6 виконавців", len(г["викон_план"]) == 6,
             f"виконавців плану={len(г['викон_план'])}")

проверка("факт не двоится: жодного драйвера без плану", all(г["ПланГрн"] > 0 for г in СВОД.values()))
проверка("ФактГрнПлан заповнена (гібрид працює)", итог["ФактГрнПлан"] > 0,
         f"{итог['ФактГрнПлан']:,.2f} грн")
доля_этапа = 100.0 * (факт_всего - факт_без_этапа) / факт_всего if факт_всего else 0
проверка("факт розкладено по Етапах > 50% рядків", доля_этапа > 50,
         f"{доля_этапа:.1f}% ({факт_всего - факт_без_этапа}/{факт_всего})")

print("  --- розподіл факту за статусом плану ---")
соб_всего = sum(а["соб"] for а in по_статусу.values())
for ст in sorted(по_статусу):
    а = по_статусу[ст]
    дол = 100.0 * а["соб"] / соб_всего if соб_всего else 0
    print(f"      {ст:22} {а['строк']:5} рядків | собів. {а['соб']:>14,.2f} ({дол:5.1f}%)"
          f" | у пл.цінах {а['план']:>14,.2f}")

проверка("ФактГрнПлан = 0 у всіх рядків поза статусом «1. В плані»", статус_с_ценой_но_нулём == 0,
         f"порушень={статус_с_ценой_но_нулём}")
проверка("статус проставлено всім фактовим рядкам", "" not in по_статусу,
         f"без статусу={по_статусу.get('', {}).get('строк', 0)}")
покрытие = 100.0 * по_статусу.get("1. В плані", {}).get("соб", 0) / соб_всего if соб_всего else 0
проверка("планова ціна покриває > 70% фактичної собівартості", покрытие > 70,
         f"{покрытие:.1f}%")
# Санитарная граница методики: оценка в плановых ценах не должна отрываться от себестоимости
# в разы (так ловился «мшп» — мусорная общая назва, дававшая 34 млн вместо 11 млн).
# ⚠️ Считаем ТОЛЬКО по парным строкам, где есть и себестоимость, и плановая оценка.
# Иначе проверка падает не на дефекте методики, а на состоянии закрытия месяца: строки
# с количеством, но без ещё не разнесённой себестоимости, задирают отношение.
if парные["строк"]:
    отн = парные["план"] / парные["соб"] if парные["соб"] else 0
    проверка("ФактГрнПлан / ФактГрнСоб на ПАРНИХ рядках у межах (0,5…2,5)", 0.5 < отн < 2.5,
             f"відношення={отн:.2f} на {парные['строк']} рядках")
else:
    проверка("є парні рядки для перевірки методики", False, "жодного рядка з собівартістю")
print(f"      довідково: рядків з плановою оцінкою, але БЕЗ собівартості = {без_себестоимости}"
      f" (місяць ще не закритий — це стан бази, не дефект звіту)")

# ---------------------------------------------------------------- 6. E2E: ПриКомпоновкеРезультата
# Гоняем РОВНО тот путь, по которому отчёт открывает пользователь.
# ⚠️ Без этой проверки у отчёта-близнеца в бою вылезла ошибка «Метод объекта не обнаружен
# (ПолучитьПараметр)»: приёмка дёргала ПолучитьДанные напрямую и не заходила в обработчик.
print("\n=== 6. E2E: СформироватьОтчет — тело ПриКомпоновкеРезультата (путь пользователя) ===")


def прогон_как_в_форме(нач, кон):
    отч = erp.ВнешниеОтчеты.Создать(ERF)
    схема = отч.СхемаКомпоновкиДанных
    отч.КомпоновщикНастроек.Инициализировать(
        erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    отч.КомпоновщикНастроек.ЗагрузитьНастройки(схема.НастройкиПоУмолчанию)

    п = erp.NewObject("СтандартныйПериод")
    п.ДатаНачала = нач
    п.ДатаОкончания = кон
    отч.КомпоновщикНастроек.Настройки.ПараметрыДанных.УстановитьЗначениеПараметра("Период", п)

    док = erp.NewObject("ТабличныйДокумент")
    расшифровка = erp.NewObject("ДанныеРасшифровкиКомпоновкиДанных")
    отч.СформироватьОтчет(док, расшифровка)
    return док


try:
    док = прогон_как_в_форме(НАЧ, КОН)
    проверка("СформироватьОтчет (тело ПриКомпоновкеРезультата) отработал, документ непустой", док.ВысотаТаблицы > 0,
             f"строк={док.ВысотаТаблицы}, колонок={док.ШиринаТаблицы}")
except Exception as e:
    проверка("СформироватьОтчет (тело ПриКомпоновкеРезультата) отработал", False,
             e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e))

try:
    пусто = erp.NewObject("СтандартныйПериод")
    док2 = прогон_как_в_форме(пусто.ДатаНачала, пусто.ДатаОкончания)
    проверка("СформироватьОтчет с ПУСТЫМ периодом (дефолт формы)", док2.ВысотаТаблицы > 0,
             f"строк={док2.ВысотаТаблицы}")
except Exception as e:
    проверка("СформироватьОтчет с пустым периодом", False,
             e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e))

# ---------------------------------------------------------------- итог
print(f"\n{'=' * 60}")
print(f"ПРОВЕРОК: {проверок}   ПРОВАЛОВ: {провалов}")
print("=" * 60)
sys.exit(1 if провалов else 0)
