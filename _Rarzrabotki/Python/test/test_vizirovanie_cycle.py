# -*- coding: utf-8 -*-
"""
Сквозная приёмка визирования заказов поставщикам (BaseERP).

Проверяет ГЛАВНОЕ утверждение конструкции:
    заказ вступает в силу (КОформлению + ТоварыКПоступлению) ТОЛЬКО на статусе "Подтвержден",
    и виза открывает именно этот переход.

Всё идемпотентно (get-or-create). Тестовый заказ помечается на удаление в конце,
Удалить() не вызывается.

Гейт запрета обхода на этом этапе ещё НЕ включён — он проверяется отдельно (этап 5).
"""
import win32com.client, sys, datetime

sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
MARKER = "ТЕСТ ВИЗИРОВАНИЯ (автоприёмка)"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)

ok = fail = 0


def check(name, got, expected):
    global ok, fail
    good = (got == expected)
    if good:
        ok += 1
        print(f"  [OK]   {name:<52} {got}")
    else:
        fail += 1
        print(f"  [FAIL] {name:<52} получено={got!r}  ожидалось={expected!r}")
    return good


def s(x):
    return erp.String(x)


def движения(доксылка):
    """Замер движений заказа: (Заказано, КОформлению, строкТКП)."""
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        СУММА(ЕСТЬNULL(З.Заказано, 0))    КАК Заказано,
        СУММА(ЕСТЬNULL(З.КОформлению, 0)) КАК КОформлению
    ИЗ РегистрНакопления.ЗаказыПоставщикам КАК З
    ГДЕ З.Регистратор = &Ссылка
    """
    q.SetParameter("Ссылка", доксылка)
    r = q.Execute().Выгрузить()
    зак = r.Получить(0).Заказано if r.Количество() else 0
    коф = r.Получить(0).КОформлению if r.Количество() else 0

    q2 = erp.NewObject("Запрос")
    q2.Text = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрНакопления.ТоварыКПоступлению КАК Т ГДЕ Т.Регистратор = &Ссылка"
    q2.SetParameter("Ссылка", доксылка)
    r2 = q2.Execute().Выгрузить()
    ткп = r2.Получить(0).Кол if r2.Количество() else 0

    return (зак or 0), (коф or 0), (ткп or 0)


print("=" * 100)
print("СКВОЗНАЯ ПРИЁМКА ВИЗИРОВАНИЯ ЗАКАЗОВ ПОСТАВЩИКАМ — BaseERP")
print("=" * 100)

# ─── 1. Тестовые данные (идемпотентно) ────────────────────────────────────────
print("\n[1] Настройка тестовых данных")

админ = erp.Пользователи.ТекущийПользователь()


def get_or_create_роль(имя, вид_адресации):
    ссыл = erp.Справочники.А_РолиВизирования.НайтиПоНаименованию(имя, True)
    if not erp.ЗначениеЗаполнено(ссыл):
        об = erp.Справочники.А_РолиВизирования.СоздатьЭлемент()
        об.Наименование = имя
        об.ВидАдресации = вид_адресации
        об.Записать()
        ссыл = об.Ссылка
    return ссыл


роль1 = get_or_create_роль("Тест Снабженец", erp.Перечисления.А_ВидыАдресацииРолейВизирования.ПоПодразделению)
роль2 = get_or_create_роль("Тест Финдиректор", erp.Перечисления.А_ВидыАдресацииРолейВизирования.ПоОрганизации)
print(f"  роли: {s(роль1)} (по подразделению), {s(роль2)} (по организации)")

# схема из двух ролей
схема = erp.Справочники.А_СхемыВизирования.НайтиПоНаименованию("Тестовая схема", True)
if not erp.ЗначениеЗаполнено(схема):
    об = erp.Справочники.А_СхемыВизирования.СоздатьЭлемент()
    об.Наименование = "Тестовая схема"
    об.Роли.Добавить().Роль = роль1
    об.Роли.Добавить().Роль = роль2
    об.Записать()
    схема = об.Ссылка
print(f"  схема: {s(схема)} (маршрут из 2 ролей)")

# ─── 2. Тестовый заказ: копия существующего (заодно проверяем ПриКопировании) ──
print("\n[2] Тестовый заказ")

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 З.Ссылка КАК Ссылка
ИЗ Документ.ЗаказПоставщику КАК З
ГДЕ ВЫРАЗИТЬ(З.Комментарий КАК СТРОКА(200)) = &Маркер И НЕ З.ПометкаУдаления
"""
q.SetParameter("Маркер", MARKER)
r = q.Execute().Выгрузить()

if r.Количество():
    заказ = r.Получить(0).Ссылка
    об = заказ.ПолучитьОбъект()
    # сброс визы в исходное состояние через САМ движок — прогон должен быть повторяемым
    об.Записать(erp.РежимЗаписиДокумента.Проведение)   # заказ мог остаться распроведённым
    об = заказ.ПолучитьОбъект()
    об.А_Виза_Причина = ""
    об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Черновик)
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    об = заказ.ПолучитьОбъект()
    print(f"  переиспользуем (виза сброшена движком): {s(заказ)}")
else:
    # берём донора: проведённый заказ с товарами
    qd = erp.NewObject("Запрос")
    qd.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 1 З.Ссылка КАК Ссылка
    ИЗ Документ.ЗаказПоставщику КАК З
    ГДЕ З.Проведен И НЕ З.ПометкаУдаления
        И З.Ссылка В (ВЫБРАТЬ Т.Ссылка ИЗ Документ.ЗаказПоставщику.Товары КАК Т)
    УПОРЯДОЧИТЬ ПО З.Дата УБЫВ
    """
    донор = qd.Execute().Выгрузить().Получить(0).Ссылка
    об = донор.ПолучитьОбъект().Скопировать()
    об.Дата = datetime.datetime.now()
    об.Комментарий = MARKER
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    заказ = об.Ссылка
    print(f"  создан копированием донора {s(донор)} → {s(заказ)}")

об = заказ.ПолучитьОбъект()

# ПриКопировании + ИнициализироватьДокумент: заказ должен войти в контур как Черновик
check("А_Виза_Состояние нового/скопированного", s(об.А_Виза_Состояние), "Черновик")
check("Статус нового заказа (типовая инициализация)", s(об.Статус), "Согласован")

# правило выбора схемы — по подразделению заказа
рс = erp.РегистрыСведений.А_ОпределениеСхемыВизирования.СоздатьМенеджерЗаписи()
рс.Подразделение = об.Подразделение
рс.Организация = об.Организация
рс.Сумма = 0
рс.СхемаВизирования = схема
рс.Приоритет = 1
рс.Записать(True)
print(f"  правило схемы: Подразделение={s(об.Подразделение)} → {s(схема)}")

# адресация: обе роли на администратора
for роль, объект in ((роль1, об.Подразделение), (роль2, об.Организация)):
    мз = erp.РегистрыСведений.А_ИдентификацияВизирующихПоРолям.СоздатьМенеджерЗаписи()
    мз.Роль = роль
    мз.Объект = объект
    мз.Пользователь = админ
    мз.Записать(True)
print(f"  адресация: обе роли → {s(админ)}")

зак0, коф0, ткп0 = движения(заказ)
print(f"\n  движения ДО визирования: Заказано={зак0}  КОформлению={коф0}  ТоварыКПоступлению={ткп0} строк")

# ─── 3. Инициатор отправляет на визирование ───────────────────────────────────
print("\n[3] Инициатор отправляет на визирование")

об = заказ.ПолучитьОбъект()
рез = об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Утвержден)
if not рез.Успех:
    print(f"  [FAIL] движок вернул ошибку: {рез.ТекстОшибки}")
    fail += 1
else:
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    об = заказ.ПолучитьОбъект()
    check("состояние визы", s(об.А_Виза_Состояние), "На визировании")
    check("текущая роль", s(об.А_Виза_ТекущаяРоль), "Тест Снабженец")
    check("строк маршрута (Инициатор + 2 роли)", об.А_Визы.Количество(), 3)
    check("текущих визирующих", об.А_ТекущиеВизирующие.Количество(), 1)
    check("СТАТУС остался Согласован", s(об.Статус), "Согласован")
    з, к, т = движения(заказ)
    check("КОформлению = 0 (заказ НЕ в силе)", к, 0)
    print(f"         (справочно) ТоварыКПоступлению={т} — заказами в этой базе не пишется")

# ─── 4. Виза роли 1 из 2 ──────────────────────────────────────────────────────
print("\n[4] Виза роли 1 из 2 (Снабженец)")

об = заказ.ПолучитьОбъект()
рез = об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Утвержден)
if not рез.Успех:
    print(f"  [FAIL] {рез.ТекстОшибки}")
    fail += 1
else:
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    об = заказ.ПолучитьОбъект()
    check("состояние визы (маршрут не пройден)", s(об.А_Виза_Состояние), "На визировании")
    check("текущая роль сдвинулась", s(об.А_Виза_ТекущаяРоль), "Тест Финдиректор")
    check("СТАТУС всё ещё Согласован", s(об.Статус), "Согласован")
    з, к, т = движения(заказ)
    check("КОформлению всё ещё 0", к, 0)

# ─── 5. Виза роли 2 — финальная ───────────────────────────────────────────────
print("\n[5] Виза роли 2 (Финдиректор) — ФИНАЛЬНАЯ")

об = заказ.ПолучитьОбъект()
кол_товаров = sum(об.Товары.Получить(i).Количество for i in range(об.Товары.Количество()))
рез = об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Утвержден)
if not рез.Успех:
    print(f"  [FAIL] {рез.ТекстОшибки}")
    fail += 1
else:
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    об = заказ.ПолучитьОбъект()
    check("состояние визы", s(об.А_Виза_Состояние), "Утвержден")
    check("🔑 СТАТУС → Подтвержден", s(об.Статус), "Подтвержден")
    з, к, т = движения(заказ)
    check("🔑 КОформлению = количеству товаров", к, кол_товаров)
    print(f"         (справочно) ТоварыКПоступлению={т} — заказами в этой базе не пишется, рубеж = КОформлению")

# ─── 6. Отклонение — заказ теряет силу ────────────────────────────────────────
print("\n[6] Отклонение — заказ должен потерять силу")

об = заказ.ПолучитьОбъект()
допы = erp.NewObject("Структура")
допы.Вставить("Виза_Причина", "Тест отклонения")
рез = об.А_Виза_УстановитьСостояние(erp.Перечисления.А_Визы_Состояния.Отклонено, допы)
if not рез.Успех:
    print(f"  [FAIL] {рез.ТекстОшибки}")
    fail += 1
else:
    об.Записать(erp.РежимЗаписиДокумента.Проведение)
    об = заказ.ПолучитьОбъект()
    check("состояние визы", s(об.А_Виза_Состояние), "Отклонено")
    check("🔑 СТАТУС вернулся в Согласован", s(об.Статус), "Согласован")
    check("причина отклонения сохранена", об.А_Виза_Причина, "Тест отклонения")
    з, к, т = движения(заказ)
    check("🔑 КОформлению снова 0", к, 0)
    print(f"         (справочно) ТоварыКПоступлению={т}")

# ─── 7. Обменный заказ вне контура ────────────────────────────────────────────
print("\n[7] Обменный заказ — вне контура визирования")

qx = erp.NewObject("Запрос")
qx.Text = """
ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА З.А_Виза_Состояние = ЗНАЧЕНИЕ(Перечисление.А_Визы_Состояния.ПустаяСсылка)
               ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ВнеКонтура,
    КОЛИЧЕСТВО(*) КАК Всего
ИЗ Документ.ЗаказПоставщику КАК З
"""
rx = qx.Execute().Выгрузить().Получить(0)
print(f"  заказов всего={rx.Всего}, вне контура (пустая виза)={rx.ВнеКонтура}")
check("исторические/обменные заказы вне контура", rx.ВнеКонтура >= rx.Всего - 1, True)

# ─── Уборка ───────────────────────────────────────────────────────────────────
# Распроведение снимает ВСЕ движения (в т.ч. Заказано), поэтому тестовый заказ не засоряет
# регистры. Удалить() не вызываем — заказ переиспользуется следующим прогоном (get-or-create).
об = заказ.ПолучитьОбъект()
об.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
зк, кк, тк = движения(заказ)
check("уборка: движений не осталось", (зк, кк, тк), (0, 0, 0))
print(f"  тестовый заказ {s(заказ)} распроведён (Удалить() не вызывался)")

print("\n" + "=" * 100)
print(f"ИТОГО:  OK = {ok}   FAIL = {fail}")
print("=" * 100)
sys.exit(1 if fail else 0)
