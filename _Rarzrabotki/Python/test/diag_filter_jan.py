# -*- coding: utf-8 -*-
"""ДІАГНОСТИКА: чи ламає фільтр виключення 3 груп баланс НА СІЧЕНЬ 2026
(закритий період). Період серверний. Read-only."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)
EXCL = ["Собственные средства", "Доходы текущего периода", "Расходы текущего периода"]

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

def arr(items):
    a = conn.NewObject("Массив")
    for it in items: a.Добавить(it)
    return a

q0 = conn.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
s = q0.Выполнить().Выбрать(); s.Следующий(); org = s.С

qb = conn.NewObject("Запрос")
qb.Текст = "ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД"
qb.УстановитьПараметр("М", M)
rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ = rb.НМ; КД = rb.КД
print(f"період СІЧЕНЬ: {НМ} .. {КД}")

qe = conn.NewObject("Запрос")
qe.Текст = "ВЫБРАТЬ Ссылка КАК С, Наименование КАК Н ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование В (&Сп)"
qe.УстановитьПараметр("Сп", arr(EXCL))
tze = qe.Выполнить().Выгрузить()
excl_refs = [tze.Получить(i).С for i in range(tze.Количество())]
print(f"виключаємо статей: {tze.Количество()}")

# 1) БЕЗ фільтра
q1 = conn.NewObject("Запрос")
q1.Текст = """ВЫБРАТЬ СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,Организация=&Орг) КАК Б"""
q1.УстановитьПараметр("Д1",НМ); q1.УстановитьПараметр("Д2",КД); q1.УстановитьПараметр("Орг",org)
r1 = q1.Выполнить().Выбрать(); r1.Следующий()
без = float(r1.sK or 0)
print(f"\n[БЕЗ фільтра]  Σ КонОст = {без:,.2f}")

# 2) КОЖНА виключена стаття: КонОст за СІЧЕНЬ
print("\n[Виключені статті — їх КонОст за СІЧЕНЬ]:")
sum_excl = 0.0
for i in range(tze.Количество()):
    ref = tze.Получить(i).С; nm = str(tze.Получить(i).Н)
    qg = conn.NewObject("Запрос")
    qg.Текст = """ВЫБРАТЬ СУММА(Б.СуммаКонечныйОстаток) КАК sK
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
        Организация=&Орг И Статья В ИЕРАРХИИ(&Г)) КАК Б"""
    qg.УстановитьПараметр("Д1",НМ); qg.УстановитьПараметр("Д2",КД)
    qg.УстановитьПараметр("Орг",org); qg.УстановитьПараметр("Г",ref)
    rg = qg.Выполнить().Выбрать(); rg.Следующий()
    v = float(rg.sK or 0); sum_excl += v
    print(f"  {nm:<35} КонОст = {v:>16,.2f}")
print(f"  {'Σ виключеного':<35}        = {sum_excl:>16,.2f}")

# 3) З фільтром (НЕ В ИЕРАРХИИ)
q3 = conn.NewObject("Запрос")
q3.Текст = """ВЫБРАТЬ СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&Д1,&Д2,Авто,,
    Организация=&Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б"""
q3.УстановитьПараметр("Д1",НМ); q3.УстановитьПараметр("Д2",КД)
q3.УстановитьПараметр("Орг",org); q3.УстановитьПараметр("Искл",arr(excl_refs))
r3 = q3.Выполнить().Выбрать(); r3.Следующий()
сфильтром = float(r3.sK or 0)
print(f"\n[З фільтром]   Σ КонОст = {сфильтром:,.2f}")
print(f"\n>>> ВИСНОВОК: фільтр на СІЧЕНЬ {'НЕ ламає' if abs(сфильтром) < 1.0 else 'ЛАМАЄ'} "
      f"баланс (Σ з фільтром = {сфильтром:,.2f}; має бути ≈0 щоб не ламав)")
