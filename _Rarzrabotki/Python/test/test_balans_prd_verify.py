def пап_оо_подр(нм, кд):
    """ПАП.ОстаткиИОбороты(OD-3) по (Орг,Подр,Статья) — == штатный
    «Управленческий баланс по направлениям и подразделениям»."""
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("НМ", нм)
    q.УстановитьПараметр("КД", кд); q.УстановитьПараметр("Искл", Искл)
    q.Текст = """ВЫБРАТЬ
        Б.Организация КАК Орг,
        ЕСТЬNULL(Б.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        Б.Статья КАК Ст,
        СУММА(Б.СуммаНачальныйОстаток) КАК НО,
        СУММА(Б.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&НМ, &КД, Авто, ,
        Организация = &Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
    СГРУППИРОВАТЬ ПО Б.Организация,
        ЕСТЬNULL(Б.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)),
        Б.Статья"""
    t = q.Выполнить().Выгрузить()
    res = {}
