# -*- coding: utf-8 -*-
# Знаходимо людей які є в РаспределениеКазна (А_ОтражениеЗПпоКазне 000000001)
# але НЕМА в НачисленияУпр. Все обробляється ОДНИМ запитом у ERP.
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


# Знайти документ
q_find = erp.NewObject("Запрос")
q_find.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д ГДЕ Д.Номер = &Н И Д.Дата МЕЖДУ &Д1 И &Д2"
q_find.SetParameter("Н", "000000001")
q_find.SetParameter("Д1", com_date(2025, 12, 31, 0, 0, 0))
q_find.SetParameter("Д2", com_date(2025, 12, 31, 23, 59, 59))
sel = q_find.Execute().Выбрать()
if not sel.Следующий():
    print("Документ не знайдено")
    sys.exit(1)
doc_ref = sel.Ссылка
print(f"Документ: {S(doc_ref)}")

# ОДИН ЗАПИТ: ФізОсоби з РаспределениеКазна (через Сотрудник.ФизическоеЛицо) + ФізОсоби з НачисленияУпр
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    РК.Сотрудник.ФизическоеЛицо КАК ФизЛицо,
    РК.Сотрудник.ФизическоеЛицо.Наименование КАК ФизЛицоНаим,
    СУММА(РК.Сумма) КАК СуммаКазна,
    ИСТИНА КАК ВКазне,
    ЛОЖЬ КАК ВНачислУпр
ПОМЕСТИТЬ Казна
ИЗ Документ.А_ОтражениеЗПпоКазне.РаспределениеКазна КАК РК
ГДЕ РК.Ссылка = &Ссылка
СГРУППИРОВАТЬ ПО РК.Сотрудник.ФизическоеЛицо, РК.Сотрудник.ФизическоеЛицо.Наименование
;
ВЫБРАТЬ РАЗЛИЧНЫЕ
    НУ.ФизЛицо КАК ФизЛицо,
    НУ.ФизЛицо.Наименование КАК ФизЛицоНаим,
    СУММА(НУ.Сумма) КАК СуммаНачУпр
ПОМЕСТИТЬ НачУпр
ИЗ Документ.А_ОтражениеЗПпоКазне.НачисленияУпр КАК НУ
ГДЕ НУ.Ссылка = &Ссылка
СГРУППИРОВАТЬ ПО НУ.ФизЛицо, НУ.ФизЛицо.Наименование
;
ВЫБРАТЬ
    ЕСТЬNULL(К.ФизЛицоНаим, Н.ФизЛицоНаим) КАК Имя,
    ЕСТЬNULL(К.СуммаКазна, 0) КАК СуммаКазна,
    ЕСТЬNULL(Н.СуммаНачУпр, 0) КАК СуммаНачУпр,
    ВЫБОР КОГДА К.ФизЛицо ЕСТЬ NULL ТОГДА "тільки_НачУпр"
          КОГДА Н.ФизЛицо ЕСТЬ NULL ТОГДА "тільки_Казна"
          ИНАЧЕ "в_обох" КОНЕЦ КАК Категория
ИЗ Казна КАК К
    ПОЛНОЕ ВНЕШНЕЕ СОЕДИНЕНИЕ НачУпр КАК Н ПО К.ФизЛицо = Н.ФизЛицо
УПОРЯДОЧИТЬ ПО Категория, Имя
"""
q.SetParameter("Ссылка", doc_ref)
r = q.Execute().Выгрузить()

print(f"\nРядків: {r.Количество()}")

тільки_казна = []
тільки_нач_упр = []
в_обох = []

for i in range(r.Количество()):
    row = r.Получить(i)
    имя = S(row.Имя) or "(пусто)"
    сум_каз = float(S(row.СуммаКазна).replace('\xa0', '').replace(' ', '').replace(',', '.') or "0")
    сум_нач = float(S(row.СуммаНачУпр).replace('\xa0', '').replace(' ', '').replace(',', '.') or "0")
    кат = S(row.Категория)
    запис = (имя, сум_каз, сум_нач)
    if кат == "тільки_Казна":
        тільки_казна.append(запис)
    elif кат == "тільки_НачУпр":
        тільки_нач_упр.append(запис)
    else:
        в_обох.append(запис)

print(f"\n=== Підсумки ===")
print(f"В обох:           {len(в_обох)}")
print(f"Тільки в Казні:   {len(тільки_казна)}")
print(f"Тільки в НачУпр:  {len(тільки_нач_упр)}")

print(f"\n=== ТІЛЬКИ в РаспределениеКазна (немає у НачисленияУпр) ===")
for имя, sk, sn in тільки_казна[:30]:
    print(f"  {имя:50s}  Казна={sk:>12,.2f}")
if len(тільки_казна) > 30:
    print(f"  ... і ще {len(тільки_казна) - 30}")

print(f"\n=== ТІЛЬКИ в НачисленияУпр (немає у РаспределениеКазна) ===")
for имя, sk, sn in тільки_нач_упр[:20]:
    print(f"  {имя:50s}  НачУпр={sn:>12,.2f}")
if len(тільки_нач_упр) > 20:
    print(f"  ... і ще {len(тільки_нач_упр) - 20}")

print(f"\n=== Сума тільки-в-Казні ===")
print(f"  Кількість людей: {len(тільки_казна)}")
print(f"  Сума Казна:      {sum(x[1] for x in тільки_казна):,.2f}")
