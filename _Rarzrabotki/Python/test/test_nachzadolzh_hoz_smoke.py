# -*- coding: utf-8 -*-
"""Smoke Фаза 2 (Хозрасчетный): перепровести НачальнаяЗадолженность (запишет Дт00/Кт661),
проверить 661 += входящий долг, проводка балансируется, 00 = контр."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0
РЗ = erp.РежимЗаписиДокумента.Проведение
РП = erp.РежимПроведенияДокумента.Неоперативный

# ТЧ opening total (эталон)
qt = erp.NewObject("Запрос")
qt.Текст = "ВЫБРАТЬ СУММА(Сумма) КАК С ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате"
opening = f(qt.Выполнить().Выгрузить()[0].С)
print(f"opening (ТЧ) = {opening:,.2f}")

# перепровести 3 документа
q = erp.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ Документ.НачальнаяЗадолженностьПоЗарплате ГДЕ Проведен"
nz = [r.С for r in q.Выполнить().Выгрузить()]
for s in nz:
    s.ПолучитьОбъект().Записать(РЗ, РП)
print(f"перепроведено: {len(nz)}")

# Хозрасчетный движения регистраторов НачальнаяЗадолженность
qh = erp.NewObject("Запрос")
qh.Текст = """
ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА Х.СчетКт.Код = "661" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Кт661,
    СУММА(ВЫБОР КОГДА Х.СчетДт.Код = "661" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Дт661,
    СУММА(ВЫБОР КОГДА Х.СчетДт.Код = "00" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Дт00,
    СУММА(ВЫБОР КОГДА Х.СчетКт.Код = "00" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Кт00,
    КОЛИЧЕСТВО(*) КАК Стр
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
ГДЕ Х.Регистратор ССЫЛКА Документ.НачальнаяЗадолженностьПоЗарплате
"""
r = qh.Выполнить().Выгрузить()[0]
кт661, дт661, дт00, кт00, стр = f(r.Кт661), f(r.Дт661), f(r.Дт00), f(r.Кт00), int(f(r.Стр))
net661 = кт661 - дт661   # прирост долга (Кт-Дт)
net00 = дт00 - кт00      # дебет 00
print(f"\nХозрасчетный от НачальнаяЗадолженность: строк={стр}")
print(f"  Кт661={кт661:,.2f}  Дт661={дт661:,.2f}  → нетто 661 (Кт-Дт)={net661:,.2f}  (эталон {opening:,.2f})")
print(f"  Дт00={дт00:,.2f}  Кт00={кт00:,.2f}  → нетто 00 (Дт-Кт)={net00:,.2f}")

TOL = 0.05
checks = [
    ("661 нетто (Кт-Дт) == opening", abs(net661 - opening) <= TOL),
    ("00 нетто (Дт-Кт) == opening (контр сбалансирован)", abs(net00 - opening) <= TOL),
    ("проводка балансируется (661 += 00)", abs(net661 - net00) <= TOL),
]
ok_all = True
for name, ok in checks:
    ok_all = ok_all and ok
    print(f"  [{'OK' if ok else 'FAIL'}] {name}")
print("\nSMOKE PASS (Хозрасчетный)" if ok_all else "SMOKE FAIL")
sys.exit(0 if ok_all else 1)
