# -*- coding: utf-8 -*-
"""Расследование плуга «Оплата труда» 3,17М без ФизЛица:
связь с документом НачальнаяЗадолженностьПоЗарплате (пишет А_ВзСС, НЕ пишет ПАП)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# 1) Документы НачальнаяЗадолженностьПоЗарплате
print("=== 1. Документы НачальнаяЗадолженностьПоЗарплате ===")
q = erp.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Ссылка КАК С, Номер, Дата, Месяц, ПРЕДСТАВЛЕНИЕ(Организация) КАК Орг, Проведен
ИЗ Документ.НачальнаяЗадолженностьПоЗарплате
УПОРЯДОЧИТЬ ПО Дата
"""
docs = q.Выполнить().Выгрузить()
for r in docs:
    print(f"   №{str(r.Номер).strip()} Дата={r.Дата} Месяц={r.Месяц} Орг={r.Орг} Проведен={r.Проведен}")

# 2) ТЧ ЗадолженностьПоЗарплате — Σ по подразделению (А_Подразделение)
print("\n=== 2. ТЧ ЗадолженностьПоЗарплате: Σ Сумма по подразделению ===")
q2 = erp.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(З.Подразделение.А_Подразделение) КАК Подр,
    СУММА(З.Сумма) КАК Σ, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ З.Сотрудник) КАК ФЛ
ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате КАК З
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(З.Подразделение.А_Подразделение)
УПОРЯДОЧИТЬ ПО Σ УБЫВ
"""
tch_total = 0.0
for r in q2.Выполнить().Выгрузить():
    tch_total += f(r.Σ)
    print(f"   {str(r.Подр):<42} Σ={f(r.Σ):>14,.2f}  ФЛ={int(f(r.ФЛ))}")
print(f"   ИТОГО ТЧ = {tch_total:>14,.2f}")

# 3) А_ВзСС движения по этому регистратору (per ФизЛицо/Подр/Период)
print("\n=== 3. А_ВзаиморасчетыССотрудниками: движения НачальнойЗадолженности ===")
q3 = erp.NewObject("Запрос")
q3.Текст = """
ВЫБРАТЬ
    ВзСС.Период КАК Период,
    ПРЕДСТАВЛЕНИЕ(ВзСС.ВидДвижения) КАК ВД,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВзСС.ФизическоеЛицо) КАК ФЛ,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ВзСС.Подразделение) КАК Подр,
    СУММА(ВзСС.СуммаВзаиморасчетов) КАК Σ
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзСС
ГДЕ ВзСС.Регистратор ССЫЛКА Документ.НачальнаяЗадолженностьПоЗарплате
СГРУППИРОВАТЬ ПО ВзСС.Период, ПРЕДСТАВЛЕНИЕ(ВзСС.ВидДвижения)
"""
for r in q3.Выполнить().Выгрузить():
    print(f"   Период={r.Период} ВД={r.ВД} ФЛ={int(f(r.ФЛ))} Подр={int(f(r.Подр))} Σ={f(r.Σ):>14,.2f}")

# 4) ПАП(ОТ): есть ли вообще движения с регистратором НачальнаяЗадолженность?
print("\n=== 4. ПАП(Оплата труда): движения регистратора НачальнаяЗадолженность? (ожидаем 0) ===")
q4 = erp.NewObject("Запрос")
q4.Текст = """
ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол, СУММА(Т.Сумма) КАК Σ
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор ССЫЛКА Документ.НачальнаяЗадолженностьПоЗарплате
    И Т.Статья.Наименование = "Оплата труда"
"""
r4 = q4.Выполнить().Выгрузить()[0]
print(f"   движений ПАП от НачальнойЗадолженности = {int(f(r4.Кол))}, Σ={f(r4.Σ):,.2f}")

# 5) Плуг в регистре свёртки (Статья=ОТ, Расхождение=Истина) дек 2025, per подразделение
print("\n=== 5. Плуг свёртки (Статья=ОТ, Расхождение=Истина) дек 2025 ===")
q5 = erp.NewObject("Запрос")
q5.Текст = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Рег.Подразделение) КАК Подр,
    СУММА(Рег.СуммаКонечныйОстаток) КАК КО, КОЛИЧЕСТВО(*) КАК Стр
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Статья.Наименование = "Оплата труда" И Рег.Расхождение
    И Рег.Регистратор.Месяц = ДАТАВРЕМЯ(2025,12,1)
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Рег.Подразделение)
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
plug_total = 0.0
for r in q5.Выполнить().Выгрузить():
    plug_total += f(r.КО)
    print(f"   {str(r.Подр):<42} КО={f(r.КО):>14,.2f}  стр={int(f(r.Стр))}")
print(f"   ИТОГО ПЛУГ = {plug_total:>14,.2f}")

print(f"\n=== СВЯЗЬ: ТЧ начальной задолженности {tch_total:,.2f} ~ плуг {plug_total:,.2f} ? Δ={tch_total-plug_total:,.2f} ===")
