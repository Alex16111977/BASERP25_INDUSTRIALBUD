# -*- coding: utf-8 -*-
"""ЦВБ: аудит ложных расхождений контура Взаиморасчёты за декабрь 2025 (read-only).

Повторяет сеанс «Тільки звіт» (РежимАвто=Ложь -> Фазы 1-2 + классификация, данные баз
не меняются), обогащает каждую строку класса B движениями ERP (РСК/РСП) и проводками
пары в Бух (Хозрасчетный), классифицирует FP-1/FP-2/FP-3/REAL и печатает свод.

Классы (см. notebook/knowledge_ЦентрВыравниванияБаз/08_lozhnye_raskhozhdeniya_vzaimoraschety.md):
  FP-1  методология АвансовыйОтчет: ERP движет РасчетыСПоставщиками (закупка через
        подотчётника), Бух проводит Дт затрат Кт 3721 БЕЗ контрагента -> счетов сверки
        в проводках пары нет -> «Проведений, різниця в рухах». Перепроведение бесполезно.
  FP-2  внутренние операции владельца/учредителя: документы ERP по контрагенту с
        зеркальными парами (нетто 0) и его же непарные выплаты; в Бух осознанно
        не передаются. «Розпровести в ЕРП» -- ложная рекомендация.
  FP-3  прочая методология (описывается вручную).
  REAL  реальное расхождение (документ должен быть в Бух / суммы должны сходиться).
"""
import win32com.client, sys, json, datetime, os

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
CONN_BUH = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'

# счета сверки взаиморасчётов (СписокСчетовРасчетов_V83 плагина А_СинхронизироватьВзаиморасчеты)
SVERKA_PREFIXES = ("361", "362", "631", "632", "6851", "6852", "6855",
                   "3771", "3772", "601", "602", "684", "655")

QA_DVIZH = """
ВЫБРАТЬ
	"РСК" КАК Регистр,
	Дв.АналитикаУчетаПоПартнерам.Контрагент.Наименование КАК Контрагент,
	Дв.Сумма КАК Сумма
ИЗ РегистрНакопления.РасчетыСКлиентами КАК Дв
ГДЕ Дв.Регистратор = &Рег И Дв.Активность

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
	"РСП",
	Дв2.АналитикаУчетаПоПартнерам.Контрагент.Наименование,
	Дв2.Сумма
ИЗ РегистрНакопления.РасчетыСПоставщиками КАК Дв2
ГДЕ Дв2.Регистратор = &Рег И Дв2.Активность
"""

QB_SOOTV = """
ВЫБРАТЬ
	Соотв.УникальныйИдентификаторПриемника КАК УИД,
	Соотв.ТипПриемника КАК Тип
ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
ГДЕ Соотв.УникальныйИдентификаторИсточника = &Рег
	И Соотв.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20
"""

QC_PROV = """
ВЫБРАТЬ Дв.СчетДт.Код КАК СчетДт, Дв.СчетКт.Код КАК СчетКт, Дв.Сумма КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Дв
ГДЕ Дв.Регистратор = &Рег И Дв.Активность
"""


def run(conn, text, params):
    q = conn.NewObject("Запрос")
    q.Text = text
    for k, val in params.items():
        q.SetParameter(k, val)
    return q.Execute().Выгрузить()


def sverka_schet(kod):
    return any(str(kod).startswith(p) for p in SVERKA_PREFIXES)


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect(CONN_ERP)
    buh = v8.Connect(CONN_BUH)

    kontur = erp.Справочники.А_КонтурыСверкиБаз.Взаиморасчеты
    nach = datetime.datetime(2025, 12, 1)
    kon = datetime.datetime(2025, 12, 31, 23, 59, 59)
    res = erp.А_ВыравниваниеБазСервер.ОбработатьКонтурПоЗначениям(
        kontur, nach, kon, False, True, 500, 200, datetime.datetime.now(), 1)

    rows = []
    arr = res.СтрокиПодтверждения
    for i in range(arr.Количество()):
        el = arr.Получить(i)
        rows.append({"ТипДокумента": str(el.ТипДокумента),
                     "Предст": str(el.ДокументПредставление),
                     "UID": str(el.UIDДокумента), "Действие": str(el.Действие),
                     "Дельта": float(el.Дельта), "Статус": str(el.Статус)})
    assert res.СтрокиРазбора.Количество() == 0 or True  # класс C печатается отдельно
    print(f"Класс B: {len(rows)} строк")

    # --- обогащение ---
    for r in rows:
        uid = erp.NewObject("УникальныйИдентификатор", r["UID"])
        ref = getattr(erp.Документы, r["ТипДокумента"]).ПолучитьСсылку(uid)
        tz = run(erp, QA_DVIZH, {"Рег": ref})
        r["Контрагенты"] = sorted({str(tz.Получить(i).Контрагент) for i in range(tz.Количество())})
        tz = run(erp, QB_SOOTV, {"Рег": ref})
        r["ПараЕсть"] = tz.Количество() > 0
        r["ПараПроводки"] = []
        if r["ПараЕсть"]:
            s = tz.Получить(0)
            tip_b = str(s.Тип).replace("ДокументСсылка.", "")
            try:
                ref_b = getattr(buh.Документы, tip_b).ПолучитьСсылку(
                    buh.NewObject("УникальныйИдентификатор", str(s.УИД)))
                if ref_b.ПолучитьОбъект() is not None:
                    tzc = run(buh, QC_PROV, {"Рег": ref_b})
                    r["ПараПроводки"] = [
                        {"Дт": str(tzc.Получить(j).СчетДт), "Кт": str(tzc.Получить(j).СчетКт),
                         "Сумма": float(tzc.Получить(j).Сумма)} for j in range(tzc.Количество())]
            except Exception:
                pass

    # --- классификация ---
    # контрагенты с зеркальными парами: |нетто дельт «Немає в BuhBud»-пар| близко к 0
    mirror_owners = set()
    net_by_kontr = {}
    for r in rows:
        if r["Статус"].startswith("Немає в BuhBud") and len(r["Контрагенты"]) == 1:
            k = r["Контрагенты"][0]
            net_by_kontr.setdefault(k, []).append(r["Дельта"])
    for k, deltas in net_by_kontr.items():
        plus = [d for d in deltas if d > 0]
        minus = [d for d in deltas if d < 0]
        if plus and minus:  # есть зеркало
            mirror_owners.add(k)

    for r in rows:
        klass = "REAL"
        if (r["ТипДокумента"] == "АвансовыйОтчет"
                and r["Статус"].startswith("Проведений, різниця в рухах")
                and r["ПараЕсть"] and r["ПараПроводки"]
                and not any(sverka_schet(p["Дт"]) or sverka_schet(p["Кт"])
                            for p in r["ПараПроводки"])):
            klass = "FP-1"
        elif (r["Статус"].startswith("Немає в BuhBud")
              and len(r["Контрагенты"]) == 1 and r["Контрагенты"][0] in mirror_owners):
            klass = "FP-2"
        r["Класс"] = klass

    # --- свод ---
    svod = {}
    for r in rows:
        s = svod.setdefault(r["Класс"], {"строк": 0, "сумма": 0.0})
        s["строк"] += 1
        s["сумма"] += abs(r["Дельта"])
    print("\nСВОД ПО КЛАССАМ:")
    for k in ("FP-1", "FP-2", "FP-3", "REAL"):
        if k in svod:
            print(f"  {k}: {svod[k]['строк']} строк, Σ|дельт| = {svod[k]['сумма']:,.2f}")
    print("\nСТРОКИ:")
    for r in rows:
        print(f"  [{r['Класс']}] {r['ТипДокумента']:<38} {r['Предст'][:55]:<55} "
              f"{r['Дельта']:>14,.2f}  {r['Статус']}")

    unclassified = [r for r in rows if r["Класс"] == "REAL"]
    if unclassified:
        print(f"\nВНИМАНИЕ: {len(unclassified)} строк REAL/не классифицировано — разобрать вручную")
    assert all("Класс" in r for r in rows), "все строки классифицированы"
    print("\nOK")


if __name__ == "__main__":
    main()
