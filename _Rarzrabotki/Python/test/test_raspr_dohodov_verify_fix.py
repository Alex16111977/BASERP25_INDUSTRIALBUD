"""
Верифікація виправлення: запустити виправлений запит напряму
щоб побачити що Подразделение заповнюється правильно.
Імітує запит з виправленого ManagerModule.
"""
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
conn = v8.Connect(CONN_ERP)

DOC_UUID = "a6f0a6dd-fd21-11f0-a2e2-c54425f51b91"

doc_ref = conn.Documents.РаспределениеДоходовПоНаправлениямДеятельности.ПолучитьСсылку(
    conn.NewObject("УникальныйИдентификатор", DOC_UUID))

# Спочатку перевіримо чи ВТФинансовыеРезультаты має Подразделение
# Для цього виконаємо основний запит що формує цю таблицю
query = conn.NewObject("Query")
query.Text = """
ВЫБРАТЬ
    ФР.Организация.Наименование КАК Организация,
    ФР.Подразделение.Наименование КАК Подразделение,
    ФР.НаправлениеДеятельности.Наименование КАК НаправлениеДеятельности,
    ФР.СтатьяДоходов.Наименование КАК СтатьяДоходов,
    ФР.Сумма КАК Сумма
ИЗ
    Документ.РаспределениеДоходовПоНаправлениямДеятельности.Доходы КАК ФР
ГДЕ
    ФР.Ссылка = &Док
"""
query.SetParameter("Док", doc_ref)
result = query.Execute()
sel = result.Choose()

print("=" * 100)
print("Табличная часть Доходы документа (джерело для ВТФинансовыеРезультаты)")
print("=" * 100)

while sel.Next():
    org = str(sel.Организация)
    podrazd = str(sel.Подразделение) if conn.ValueIsFilled(sel.Подразделение) else "(ПОРОЖНІЙ)"
    napr = str(sel.НаправлениеДеятельности) if conn.ValueIsFilled(sel.НаправлениеДеятельности) else "(порожній)"
    statya = str(sel.СтатьяДоходов)
    summa = float(sel.Сумма) if sel.Сумма else 0
    print(f"  {podrazd:40s} | {napr:30s} | {statya:30s} | {summa:>12,.2f}")

# Перевіримо метадані ТЧ Доходы
print()
print("=" * 100)
print("Перевірка: ВТФинансовыеРезультаты (проміжна таблиця) має поле Подразделение")
print("Якщо воно заповнене — виправлений запит поверне його правильно")
print("=" * 100)

# Імітуємо виправлений запит: GROUP BY з Подразделение
query2 = conn.NewObject("Query")
query2.Text = """
ВЫБРАТЬ
    "Расход" КАК ВидДвиж,
    ФР.Организация.Наименование КАК Организация,
    ВЫБОР КОГДА ФР.Подразделение = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
        ТОГДА "(порожній)"
        ИНАЧЕ ФР.Подразделение.Наименование
    КОНЕЦ КАК Подразделение,
    "ПрибылиИУбытки" КАК Статья,
    СУММА(ФР.Сумма) КАК Сумма
ИЗ
    Документ.РаспределениеДоходовПоНаправлениямДеятельности.Доходы КАК ФР
ГДЕ
    ФР.Ссылка = &Док
    И НЕ ФР.Сумма = 0
СГРУППИРОВАТЬ ПО
    ФР.Организация,
    ФР.Подразделение,
    ФР.НаправлениеДеятельности
"""
query2.SetParameter("Док", doc_ref)
result2 = query2.Execute()
sel2 = result2.Choose()

print("\nВИПРАВЛЕНИЙ РАСХОД (ПрибылиИУбытки) — з Подразделение:")
total = 0
rows_with_podrazd = 0
rows_empty = 0
while sel2.Next():
    podrazd = str(sel2.Подразделение)
    summa = float(sel2.Сумма)
    total += summa
    if podrazd == "(порожній)":
        rows_empty += 1
    else:
        rows_with_podrazd += 1
    print(f"  Расход | {podrazd:40s} | ПрибылиИУбытки | {summa:>15,.2f}")

print(f"\nВсього: {total:>15,.2f}")
print(f"Рядків з підрозділом: {rows_with_podrazd}")
print(f"Рядків без підрозділу: {rows_empty}")

if rows_with_podrazd > 0 and rows_empty <= 1:
    print("\n>>> ВИПРАВЛЕННЯ КОРЕКТНЕ: РАСХОД тепер розбито по підрозділах!")
else:
    print("\n>>> ПЕРЕВІРИТИ: дані з ТЧ Доходы не мають Подразделение")
