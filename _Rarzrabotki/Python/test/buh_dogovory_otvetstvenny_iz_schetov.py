# -*- coding: utf-8 -*-
"""BuhBud: ДоговорыКонтрагентов.Ответственный (лише ПОРОЖНІЙ) — з СчетНаОплатуПоставщика.ОтветственныйКазна рахунків
цього договору. Правило головного бухгалтера: рахунки найсвіжішого року, де вони є (2026, інакше 2025); найчастіший
відповідальний, при рівності — у кого рахунок пізніший.
    python buh_dogovory_otvetstvenny_iz_schetov.py          — dry-run
    python buh_dogovory_otvetstvenny_iz_schetov.py --apply  — запис (бекап у json)"""
import datetime, io, json, os, sys
from collections import defaultdict
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ЗАПИС = "--apply" in sys.argv
ПАПКА = os.path.dirname(os.path.abspath(__file__))
bh = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = bh.String
q = bh.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ
	С.ДоговорКонтрагента КАК Дог,
	С.ОтветственныйКазна КАК Відп,
	ГОД(С.Дата) КАК Рік,
	КОЛИЧЕСТВО(*) КАК Кількість,
	МАКСИМУМ(С.Дата) КАК Останній
ИЗ
	Документ.СчетНаОплатуПоставщика КАК С
ГДЕ
	НЕ С.ПометкаУдаления
	И С.Дата >= ДАТАВРЕМЯ(2025, 1, 1)
	И С.ОтветственныйКазна <> ЗНАЧЕНИЕ(Справочник.Пользователи.ПустаяСсылка)
	И С.ДоговорКонтрагента <> ЗНАЧЕНИЕ(Справочник.ДоговорыКонтрагентов.ПустаяСсылка)
	И С.ДоговорКонтрагента.Ответственный = ЗНАЧЕНИЕ(Справочник.Пользователи.ПустаяСсылка)
СГРУППИРОВАТЬ ПО
	С.ДоговорКонтрагента,
	С.ОтветственныйКазна,
	ГОД(С.Дата)"""
т = q.Execute().Выгрузить()
за_договором = defaultdict(list)
for i in range(т.Количество()):
    р = т.Получить(i)
    за_договором[S(р.Дог.УникальныйИдентификатор())].append(
        (int(р.Рік), int(р.Кількість), str(р.Останній), р.Відп, S(р.Відп), р.Дог))
вибір = []
for уід, рядки in за_договором.items():
    рік = max(р[0] for р in рядки)
    свіжі = [р for р in рядки if р[0] == рік]
    найкращий = max(свіжі, key=lambda р: (р[1], р[2]))
    вибір.append((найкращий[5], найкращий[3], найкращий[4], рік, найкращий[1],
                  "; ".join(f"{р[4]}×{р[1]}" for р in sorted(свіжі, key=lambda р: -р[1])[:4])))
print(f"договорів з порожнім відповідальним і рахунками 2025–2026: {len(вибір)}")
for д, _, ім, рік, n, усі in вибір[:5]:
    print(f"   {S(д)[:50]:50} → {ім} ({рік}: {усі})")
if not ЗАПИС:
    print("DRY-RUN. Для запису: --apply")
    sys.exit(0)
бекап = os.path.join(ПАПКА, f"buh_dogovory_otvetstvenny_iz_schetov_backup_{datetime.datetime.now():%Y%m%d_%H%M}.json")
with io.open(бекап, "w", encoding="utf-8") as f:
    json.dump([{"uuid": S(д.УникальныйИдентификатор()), "договір": S(д), "стане": ім} for д, _, ім, *_ in вибір],
              f, ensure_ascii=False, indent=1)
записано, помилки = 0, []
for д, відп, ім, *_ in вибір:
    try:
        о = д.ПолучитьОбъект()
        if S(о.Ответственный):
            continue
        о.Ответственный = відп
        о.Записать()
        записано += 1
    except Exception as e:
        помилки.append((S(д), str(e.excepinfo[2] if getattr(e, "excepinfo", None) else e)[:150]))
print(f"записано: {записано}; помилок: {len(помилки)} {помилки[:5]}; бекап (список змін): {бекап}")
