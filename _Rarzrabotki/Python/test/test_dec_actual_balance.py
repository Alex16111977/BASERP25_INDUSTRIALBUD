# -*- coding: utf-8 -*-
# ФАКТИЧЕСКАЯ проверка баланса по подразделениям за декабрь 2025 ПОСЛЕ ручного прогона обработки.
# Для КАЖДОГО документа-основания и КАЖДОГО подразделения:
#   ПАП-нетто основания + ПАП-нетто всех его взаимозачётов == 0.
# (взаимозачёт двигает ПАП "Задолженность ..." на том же подразделении, что и дисбаланс)
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
ИСКЛ = ('И НЕ ПАП.Статья В (ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),'
        ' ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))')

# 1) ПАП-нетто взаимозачётов декабря, сгруппировано по (основание, подразделение)
q = erp.NewObject("Запрос")
q.Text = f"""
ВЫБРАТЬ Вз.А_ДокументОснованиеДляБаланса КАК Осн, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК Подр,
	СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Нетто
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
	ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВзаимозачетЗадолженности КАК Вз ПО ПАП.Регистратор = Вз.Ссылка
ГДЕ Вз.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО И НЕ Вз.ПометкаУдаления
	И Вз.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
	{ИСКЛ}
СГРУППИРОВАТЬ ПО Вз.А_ДокументОснованиеДляБаланса, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение)
"""
vz = {}            # осн_key -> {подр: нетто}
осн_refs = {}      # осн_key -> ref
s = q.Execute().Выбрать()
while s.Следующий():
    k = erp.XMLСтрока(s.Осн)
    осн_refs[k] = s.Осн
    vz.setdefault(k, {})[s.Подр] = round(s.Нетто, 2)
print(f"Оснований с взаимозачётами в декабре: {len(vz)}")

# 2) ПАП-нетто самих оснований по (основание, подразделение)
массив = erp.NewObject("Массив")
for r in осн_refs.values():
    массив.Добавить(r)
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("Список", массив)
q2.Text = f"""
ВЫБРАТЬ ПАП.Регистратор КАК Осн, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК Подр,
	СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Нетто
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Регистратор В (&Список) {ИСКЛ}
СГРУППИРОВАТЬ ПО ПАП.Регистратор, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение)
"""
src = {}
s = q2.Execute().Выбрать()
while s.Следующий():
    src.setdefault(erp.XMLСтрока(s.Осн), {})[s.Подр] = round(s.Нетто, 2)

# 3) Сверка: source_net[подр] + vz_net[подр] == 0
плохие = []
for k in set(src) | set(vz):
    sd = src.get(k, {})
    vd = vz.get(k, {})
    for п in set(sd) | set(vd):
        итог = round(sd.get(п, 0) + vd.get(п, 0), 2)
        if abs(итог) > 0.01:
            имя = erp.String(осн_refs.get(k)) if k in осн_refs else k
            плохие.append((имя, п, sd.get(п, 0), vd.get(п, 0), итог))

if плохие:
    print(f"\n!!! НЕ СБАЛАНСИРОВАНО: {len(плохие)} (основание | подр | ПАП_осн | ПАП_взаимозач | остаток)")
    for имя, п, s_, v_, it in плохие[:50]:
        print(f"   {имя[:50]:50} | {п[:28]:28} | {s_:>13.2f} | {v_:>13.2f} | {it:>11.2f}")
    if len(плохие) > 50:
        print(f"   ... ещё {len(плохие)-50}")
else:
    print("Все основания: ПАП_основания + ПАП_взаимозачётов = 0 по каждому подразделению.")

# 4) Дубли четвёркой
q3 = erp.NewObject("Запрос")
q3.Text = """
ВЫБРАТЬ Док.А_ДокументОснованиеДляБаланса КАК О, Док.КонтрагентДебитор КАК Д, Док.КонтрагентКредитор КАК К,
	Док.А_СтатьяДисбалансаПоПодразделению КАК С, КОЛИЧЕСТВО(*) КАК Кол
ИЗ Документ.ВзаимозачетЗадолженности КАК Док
ГДЕ Док.А_ДокументОснованиеДляБаланса <> НЕОПРЕДЕЛЕНО И НЕ Док.ПометкаУдаления
	И Док.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2025,12,31,23,59,59)
СГРУППИРОВАТЬ ПО Док.А_ДокументОснованиеДляБаланса, Док.КонтрагентДебитор, Док.КонтрагентКредитор, Док.А_СтатьяДисбалансаПоПодразделению
ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1
"""
дубли = 0
s = q3.Execute().Выбрать()
while s.Следующий(): дубли += 1
print(f"\nДубли четвёркой (Осн,КДт,ККт,Статья): {дубли} {'OK' if дубли==0 else 'FAIL'}")

ok = (len(плохие) == 0 and дубли == 0)
print("\n=== ДЕКАБРЬ 2025: БАЛАНС ПО ПОДРАЗДЕЛЕНИЯМ В ПОРЯДКЕ (PASS) ===" if ok
      else "\n=== ЕСТЬ ПРОБЛЕМЫ (FAIL) ===")
