# -*- coding: utf-8 -*-
"""Диагностика: Создание РКО с ОбменДанными.Загрузка = Истина."""
import win32com.client
import pythoncom
import sys
import io

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

CONN_STRING = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONN_STRING)
    print("[OK] Подключение установлено")

    # 1. Найти документ-источник и данные
    q = conn.NewObject("Запрос")
    q.Текст = (
        'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка, Д.Дата, Д.Организация, Д.Касса, '
        'Д.СтатьяДвиженияДенежныхСредств КАК СтатьяДДС, '
        'Д.Подразделение, Д.А_НаправлениеДеятельности КАК НапрДеят, '
        'Д.Касса.ВалютаДенежныхСредств КАК Валюта '
        'ИЗ Документ.А_ПриходДенегОтФинАгента КАК Д '
        'ГДЕ Д.Номер = &Н'
    )
    q.УстановитьПараметр("Н", "N00023533")
    r = q.Выполнить().Выбрать()
    r.Следующий()
    doc_ref = r.Ссылка
    print(f"[OK] Источник найден")

    # Первая строка
    q2 = conn.NewObject("Запрос")
    q2.Текст = (
        'ВЫБРАТЬ ПЕРВЫЕ 1 НомерСтроки, Контрагент, ОбъектРасчетов, СуммаКомиссии '
        'ИЗ Документ.А_ПриходДенегОтФинАгента.РасшифровкаПлатежа '
        'ГДЕ Ссылка = &С И СуммаКомиссии > 0 '
        'УПОРЯДОЧИТЬ ПО НомерСтроки'
    )
    q2.УстановитьПараметр("С", doc_ref)
    r2 = q2.Выполнить().Выбрать()
    r2.Следующий()

    # Партнёр
    q3 = conn.NewObject("Запрос")
    q3.Текст = "ВЫБРАТЬ Партнер ИЗ Справочник.Контрагенты ГДЕ Ссылка = &К"
    q3.УстановитьПараметр("К", r2.Контрагент)
    r3 = q3.Выполнить().Выбрать()
    r3.Следующий()

    # === Тест А: ОбменДанными.Загрузка = True + Записать(0) потом Записать(1) ===
    print("\n=== Тест А: ОбменДанными.Загрузка + Записать(0), потом снимаем флаг и Записать(1) ===")
    try:
        rko = conn.Документы.РасходныйКассовыйОрдер.СоздатьДокумент()
        rko.Дата = r.Дата
        rko.Организация = r.Организация
        rko.ХозяйственнаяОперация = conn.Перечисления.ХозяйственныеОперации.ОплатаПоставщику
        rko.Касса = r.Касса
        rko.Контрагент = r2.Контрагент
        rko.Партнер = r3.Партнер
        rko.Валюта = r.Валюта
        rko.СуммаДокумента = r2.СуммаКомиссии
        rko.СтатьяДвиженияДенежныхСредств = r.СтатьяДДС
        rko.Подразделение = r.Подразделение
        rko.НаправлениеДеятельности = r.НапрДеят
        rko.А_ПриходДенегОтФинАгента = doc_ref
        # ТЧ РасшифровкаПлатежа
        strRP = rko.РасшифровкаПлатежа.Добавить()
        strRP.Сумма = r2.СуммаКомиссии
        strRP.СуммаВзаиморасчетов = r2.СуммаКомиссии
        strRP.ВалютаВзаиморасчетов = r.Валюта
        strRP.СтатьяДвиженияДенежныхСредств = r.СтатьяДДС
        strRP.Подразделение = r.Подразделение
        strRP.НаправлениеДеятельности = r.НапрДеят
        strRP.Партнер = r3.Партнер

        # Записать с флагом Загрузка
        rko.ОбменДанными.Загрузка = True
        print("  ОбменДанными.Загрузка = True")
        rko.Записать(0)  # Запись
        print(f"  [OK] РКО записан (без проведения): {rko.Номер}")

        # Снять флаг и провести
        rko.ОбменДанными.Загрузка = False
        print("  ОбменДанными.Загрузка = False, пробуем Записать(1)...")
        rko.Записать(1)
        print(f"  [OK] РКО проведён: {rko.Номер}, Проведен={rko.Проведен}")
    except Exception as e:
        print(f"  [ERR А] {e}")
        # Попробуем удалить если создан
        try:
            if rko.Номер:
                print(f"  Пробуем удалить {rko.Номер}...")
                rko.ОбменДанными.Загрузка = True
                rko.Записать(2)  # отмена проведения
                rko.УстановитьПометкуУдаления(True)
                print("  [OK] Помечен на удаление")
        except:
            pass

    # === Тест Б: ОбменДанными.Загрузка = True для всего (запись + проведение) ===
    print("\n=== Тест Б: ОбменДанными.Загрузка = True + Записать(1) ===")
    try:
        rko2 = conn.Документы.РасходныйКассовыйОрдер.СоздатьДокумент()
        rko2.Дата = r.Дата
        rko2.Организация = r.Организация
        rko2.ХозяйственнаяОперация = conn.Перечисления.ХозяйственныеОперации.ОплатаПоставщику
        rko2.Касса = r.Касса
        rko2.Контрагент = r2.Контрагент
        rko2.Партнер = r3.Партнер
        rko2.Валюта = r.Валюта
        rko2.СуммаДокумента = r2.СуммаКомиссии
        rko2.СтатьяДвиженияДенежныхСредств = r.СтатьяДДС
        rko2.Подразделение = r.Подразделение
        rko2.НаправлениеДеятельности = r.НапрДеят
        rko2.А_ПриходДенегОтФинАгента = doc_ref
        # ТЧ
        strRP2 = rko2.РасшифровкаПлатежа.Добавить()
        strRP2.Сумма = r2.СуммаКомиссии
        strRP2.СуммаВзаиморасчетов = r2.СуммаКомиссии
        strRP2.ВалютаВзаиморасчетов = r.Валюта
        strRP2.СтатьяДвиженияДенежныхСредств = r.СтатьяДДС
        strRP2.Подразделение = r.Подразделение
        strRP2.НаправлениеДеятельности = r.НапрДеят
        strRP2.Партнер = r3.Партнер

        rko2.ОбменДанными.Загрузка = True
        print("  ОбменДанными.Загрузка = True, пробуем Записать(1)...")
        rko2.Записать(1)  # Проведение
        print(f"  [OK] РКО2 проведён: {rko2.Номер}, Проведен={rko2.Проведен}")

        # Проверить движения
        qm = conn.NewObject("Запрос")
        qm.Текст = (
            'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол '
            'ИЗ РегистрНакопления.ДенежныеСредстваНаличные '
            'ГДЕ Регистратор = &Р'
        )
        qm.УстановитьПараметр("Р", rko2.Ссылка)
        rm = qm.Выполнить().Выбрать()
        rm.Следующий()
        print(f"  Движений в ДенежныеСредстваНаличные: {rm.Кол}")

        # Очистка
        rko2.ОбменДанными.Загрузка = True
        rko2.Записать(2)
        rko2.УстановитьПометкуУдаления(True)
        print("  [OK] РКО2 помечен на удаление")
    except Exception as e:
        print(f"  [ERR Б] {e}")

    print("\n[DONE]")


if __name__ == "__main__":
    main()
