def _непроведенные(док, подразделения, договоры):
    """Непроведённые документы реализации — вторая ветка колонки «Акти подані»."""
    buh = док.buh
    результат = []
    for вид in ВИДЫ_РЕАЛИЗАЦИИ:
        q = buh.NewObject("Запрос")
        q.Текст = f"""
        ВЫБРАТЬ
          Р.Ссылка                            КАК Документ,
          ПРЕДСТАВЛЕНИЕ(Р.Ссылка)             КАК ДокументПред,
          Р.Дата                              КАК Дата,
          Р.Контрагент                        КАК Контрагент,
          Р.ДоговорКонтрагента                КАК Договор,
          Р.ДоговорКонтрагента.Подразделение  КАК Подразделение,
          Р.СуммаДокумента                    КАК Сумма
        ИЗ Документ.{вид} КАК Р
        ГДЕ НЕ Р.Проведен И НЕ Р.ПометкаУдаления И Р.Дата <= &К
          И (Р.ДоговорКонтрагента.Подразделение В (&Подразделения)
              ИЛИ Р.ДоговорКонтрагента В (&Договоры))
        """
        q.УстановитьПараметр("К", док.ДатаРасчета)
        q.УстановитьПараметр("Подразделения", массив(buh, подразделения))
        q.УстановитьПараметр("Договоры", массив(buh, договоры))
        try:
            т = q.Execute().Выгрузить()
        except Exception as e:
            инфо = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "К90",
                      f"Не вдалося опитати непроведені «{вид}»: {инфо}")
            continue
        for i in range(т.Количество()):
            s = т.Получить(i)
            результат.append({"Вид": вид, "Документ": s.Документ, "ДокументПред": str(s.ДокументПред),
                              "Дата": s.Дата, "Контрагент": s.Контрагент, "Договор": s.Договор,
                              "Подразделение": s.Подразделение, "Сумма": float(s.Сумма or 0)})
    return результат


