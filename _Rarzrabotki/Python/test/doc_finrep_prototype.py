def _обороты361(док, подразделения, договоры):
    """Обороты по счетам расчётов в разрезе документ × контрагент × договор × отметка «Оригінал»."""
    buh = док.buh
    q = buh.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ
      Об.Регистратор                                                          КАК Регистратор,
      ПРЕДСТАВЛЕНИЕ(Об.Регистратор)                                           КАК РегистраторПред,
      Об.Субконто1                                                            КАК Контрагент,
      Об.Субконто2                                                            КАК Договор,
      ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение КАК Подразделение,
      ЕСТЬNULL(ОПД.ДокументыПолучены, ЛОЖЬ)                                   КАК Оригинал,
      ЕСТЬNULL(ОПД.ДатаОтправки, ДАТАВРЕМЯ(1,1,1))                            КАК ДатаОтправки,
      СУММА(Об.СуммаОборотДт)                                                 КАК ОборотДт,
      СУММА(Об.СуммаОборотКт)                                                 КАК ОборотКт
    ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(&Н, &К, Регистратор, Счет В (&Счета), , , , ) КАК Об
      ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.ОтправкаПолучениеДокументов КАК ОПД
        ПО ОПД.Документ = Об.Регистратор
    ГДЕ ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение В (&Подразделения)
        ИЛИ Об.Субконто2 В (&Договоры)
    СГРУППИРОВАТЬ ПО
      Об.Регистратор, ПРЕДСТАВЛЕНИЕ(Об.Регистратор), Об.Субконто1, Об.Субконто2,
      ВЫРАЗИТЬ(Об.Субконто2 КАК Справочник.ДоговорыКонтрагентов).Подразделение,
      ЕСТЬNULL(ОПД.ДокументыПолучены, ЛОЖЬ),
      ЕСТЬNULL(ОПД.ДатаОтправки, ДАТАВРЕМЯ(1,1,1))
    """
    q.УстановитьПараметр("Н", док.НачалоПериода if док.НачалоПериода else нд(док.buh, 1, 1, 1))
    q.УстановитьПараметр("К", док.ДатаРасчета)
    q.УстановитьПараметр("Счета", массив(buh, док.СчетаРасчетов))
    q.УстановитьПараметр("Подразделения", массив(buh, подразделения))
    q.УстановитьПараметр("Договоры", массив(buh, договоры))
    return q.Execute().Выгрузить()


