def Рассчитать(док):
    if not ПроверитьПараметры(док):
        return False

    buh = док.buh
    док.Расчет = []
    док.РасшифровкаДокументов = []

    включенные = [с for с in док.Подразделения if с.get("Включать", True)]
    подр_ссылки = [с["Подразделение"] for с in включенные]
    подр_ключи = {имя(с["Подразделение"]): с for с in включенные}

    # карта «договор -> целевое подразделение» из ТЧ ДоговорыДополнительно
    доп = {}
    for с in док.ДоговорыДополнительно:
        доп[str(buh.String(с["Договор"].УникальныйИдентификатор()))] = имя(с["Подразделение"])
    доп_ссылки = [с["Договор"] for с in док.ДоговорыДополнительно]

    # исключённые документы: uuid -> причина
    исключены = {str(buh.String(с["Документ"].УникальныйИдентификатор())): (с.get("Причина") or "")
                 for с in док.ИсключенныеДокументы
                 if с.get("Документ") is not None and not с["Документ"].Пустая()}
    исключено_сумма = [0.0]
    исключено_строк = [0]

    def исключен(ссылка):
        if not исключены or ссылка is None:
            return False
        try:
            return str(buh.String(ссылка.УникальныйИдентификатор())) in исключены
        except Exception:
            return False

    def целевое(договор, подразделение_договора):
        """К какой строке отчёта отнести договор."""
        if договор is not None and not договор.Пустая():
            к = str(buh.String(договор.УникальныйИдентификатор()))
            if к in доп:
                return доп[к]
        н = имя(подразделение_договора)
        return н if н in подр_ключи else None

    # аккумулятор по подразделениям
    # H делится на две ветки: Hп — проведённые без «Оригіналу» (сидят в сальдо),
    # Hн — непроведённые (в сальдо их НЕТ). Контроль К01 сверяет сальдо только с Hп.
    итог = {к: {"E": 0.0, "F": 0.0, "Hп": 0.0, "Hн": 0.0, "Сальдо": 0.0,
                "Контрагенты": {}, "ДокументовБезОригинала": 0, "НепроведенныхДок": 0}
            for к in подр_ключи}

    # ---- 1. Обороты
    т = _обороты361(док, подр_ссылки, доп_ссылки)
    неотнесенные = {}
    for i in range(т.Количество()):
        s = т.Получить(i)
        цель = целевое(s.Договор, s.Подразделение)
        дт, кт = float(s.ОборотДт or 0), float(s.ОборотКт or 0)
        if цель is None:
            if дт or кт:
                неотнесенные[имя(s.Контрагент) + " / " + имя(s.Договор)] = \
                    неотнесенные.get(имя(s.Контрагент) + " / " + имя(s.Договор), 0) + дт
            continue
        if исключен(s.Регистратор):
            исключено_сумма[0] += дт
            исключено_строк[0] += 1
            continue
        а = итог[цель]
        оригинал = bool(s.Оригинал)
        if оригинал:
            а["E"] += дт
        else:
            а["Hп"] += дт
            if дт:
                а["ДокументовБезОригинала"] += 1
        а["F"] += кт
        ключ_к = имя(s.Контрагент)
        а["Контрагенты"][ключ_к] = а["Контрагенты"].get(ключ_к, 0) + дт

        вид = "Оплата" if кт > 0 and дт == 0 else ("Виконані роботи" if оригинал else "Акт поданий")
        док.РасшифровкаДокументов.append({
            "Подразделение": цель, "Контрагент": имя(s.Контрагент), "Договор": имя(s.Договор),
            "Документ": s.Регистратор, "ДокументПред": str(s.РегистраторПред),
            "Вид": вид, "Проведен": True, "Оригинал": оригинал,
            "СуммаДт": дт, "СуммаКт": кт, "Сумма": дт if дт else кт})

    # ---- 2. Непроведённые
    if док.ВключатьНепроведенные:
        for н in _непроведенные(док, подр_ссылки, доп_ссылки):
            цель = целевое(н["Договор"], н["Подразделение"])
            if цель is None or н["Сумма"] == 0:
                continue
            if исключен(н["Документ"]):
                исключено_сумма[0] += н["Сумма"]
                исключено_строк[0] += 1
                continue
            итог[цель]["Hн"] += н["Сумма"]
            итог[цель]["НепроведенныхДок"] += 1
            док.РасшифровкаДокументов.append({
                "Подразделение": цель, "Контрагент": имя(н["Контрагент"]), "Договор": имя(н["Договор"]),
                "Документ": н["Документ"], "ДокументПред": н["ДокументПред"],
                "Вид": "Акт поданий (непроведений)", "Проведен": False, "Оригинал": False,
                "СуммаДт": н["Сумма"], "СуммаКт": 0.0, "Сумма": н["Сумма"]})

    # ---- 3. Сальдо (для контроля К01)
    тс = _сальдо361(док, подр_ссылки, доп_ссылки)
    for i in range(тс.Количество()):
        s = тс.Получить(i)
        цель = целевое(s.Договор, s.Подразделение)
        if цель is not None:
            итог[цель]["Сальдо"] += float(s.Сальдо or 0)

    # ---- 4. Строки результата + формулы
    корр = {}
    for с in док.Корректировки:
        к = имя(с["Подразделение"])
        корр.setdefault(к, {}).setdefault(с["Колонка"], 0)
        корр[к][с["Колонка"]] += float(с.get("Сумма", 0) or 0)

    for ключ, пар in подр_ключи.items():
        а = итог[ключ]
        E_р, F_р = round(а["E"], 2), round(а["F"], 2)
        Hп, Hн = round(а["Hп"], 2), round(а["Hн"], 2)
        H_р = round(Hп + Hн, 2)
        к = корр.get(ключ, {})
        E = E_р + к.get("ВыполненныеРаботы", 0)
        F = F_р + к.get("Оплачено", 0)
        H = H_р + к.get("АктыПоданные", 0)
        G = round(E - F, 2)
        I = float(пар.get("ГарантийныеПлатежи", 0) or 0) + к.get("ГарантийныеПлатежи", 0)
        J = round(-H / (1 + 100.0 / float(док.СтавкаНДС)) if док.СтавкаНДС else 0, 2)
        J += к.get("НДСНезарегистрированный", 0)

        вариант = пар["ВариантФормулы"]
        if вариант == ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ:
            K = G + I + J + H * float(пар.get("КоефАктів", 1) or 1)
        elif вариант == ФОРМУЛА_ВИКОНАННЯ_МІНУС_ОПЛАТА:
            K = (E + H) * (1 - float(пар.get("ПроцентУтримання", 0) or 0) / 100.0) + J - F
        else:
            K = 0.0
        K = round(K + к.get("ИтогоКПолучению", 0), 2)

        док.Расчет.append({
            "Подразделение": ключ, "Примечание": пар.get("Примечание", ""),
            "СуммаСоглашения": float(пар.get("СуммаСоглашения", 0) or 0),
            "СуммаДЦ": float(пар.get("СуммаДЦ", 0) or 0),
            "ВыполненныеРаботыРасч": E_р, "ОплаченоРасч": F_р, "АктыПоданныеРасч": H_р,
            "ВыполненныеРаботы": round(E, 2), "Оплачено": round(F, 2), "Задолженность": G,
            "АктыПоданные": round(H, 2), "АктыПоданныеПроведенные": Hп,
            "АктыПоданныеНепроведенные": Hн, "ГарантийныеПлатежи": round(I, 2),
            "НДСНезарегистрированный": J, "ИтогоКПолучению": K,
            "Сальдо361": round(а["Сальдо"], 2), "ВариантФормулы": вариант})

    # ---- 5. Контроли ПОСЛЕ расчёта
    _контролиПослеРасчета(док, итог, неотнесенные, исключено_строк[0], исключено_сумма[0])
    return True


def _контролиПослеРасчета(док, итог, неотнесенные, искл_строк, искл_сумма):
    for стр in док.Расчет:
        к = стр["Подразделение"]
        путь = f"Объект.Расчет / {к}"
        # К01 — сверка: сальдо счёта включает ТОЛЬКО проведённые акты,
        # поэтому вычитаем проведённую часть H. Непроведённые в сальдо не попадают.
        расч = round(стр["Сальдо361"] - стр["АктыПоданныеПроведенные"], 2)
        if abs(расч - стр["Задолженность"]) > 0.01:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "К01",
                      f"{к}: звірка не зійшлася. Сальдо {стр['Сальдо361']:,.2f} − проведені акти "
                      f"{стр['АктыПоданныеПроведенные']:,.2f} = {расч:,.2f}, а Заборгованість (E−F) = "
                      f"{стр['Задолженность']:,.2f}. Різниця {расч - стр['Задолженность']:,.2f}.", путь)
        # К02 — нет данных вообще
        if стр["ВыполненныеРаботыРасч"] == 0 and стр["ОплаченоРасч"] == 0 and стр["АктыПоданныеРасч"] == 0:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "К02",
                      f"{к}: за період немає жодного руху за рахунками розрахунків. "
                      "Перевірте підрозділ у договорах або період.", путь)
        # К06 — отрицательный итог
        if стр["ИтогоКПолучению"] < 0:
            замечание(док, УРОВЕНЬ_ИНФО, "К06",
                      f"{к}: «Разом до отримання» від'ємне ({стр['ИтогоКПолучению']:,.2f}) — "
                      "переплата замовника або невірний варіант формули.", путь)
        # К08 — оплата без актов
        if стр["ВыполненныеРаботы"] + стр["АктыПоданные"] == 0 and стр["Оплачено"] > 0:
            замечание(док, УРОВЕНЬ_ИНФО, "К08",
                      f"{к}: є оплата {стр['Оплачено']:,.2f} без жодного акта — аванс замовника.", путь)

    # К03 — договоры с оборотом, не отнесённые ни к одной строке
    if неотнесенные:
        сумма = sum(неотнесенные.values())
        топ = sorted(неотнесенные.items(), key=lambda x: -x[1])[:5]
        замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "К03",
                  f"Договорів поза розрахунком: {len(неотнесенные)} на {сумма:,.2f} грн "
                  f"(підрозділ договору не заповнено або не входить у ТЧ). "
                  f"Найбільші: {'; '.join(f'{k} — {v:,.2f}' for k, v in топ)}. "
                  "Додайте потрібні у «Договори додатково».")

    # К04/К10 — непроведённые вошли в расчёт: перечислить поимённо, чтобы пользователь увидел
    старые = [р for р in док.РасшифровкаДокументов if not р["Проведен"]]
    if старые:
        замечание(док, УРОВЕНЬ_ИНФО, "К04",
                  f"Непроведених документів у розрахунку: {len(старые)} на "
                  f"{sum(р['СуммаДт'] for р in старые):,.2f} грн. Вони формують «Акти подані».")
        for р in старые:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "К10",
                      f"{р['Подразделение']}: непроведений «{р['ДокументПред']}» на "
                      f"{р['СуммаДт']:,.2f} грн увійшов до «Акти подані». "
                      "Якщо це не очікувано — додайте його у «Виключені документи» з причиною.",
                      "Объект.РасшифровкаДокументов")

    # К11 — что исключено вручную
    if искл_строк:
        замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "К11",
                  f"Вручну виключено з розрахунку: {искл_строк} записів на {искл_сумма:,.2f} грн. "
                  "Причини — у табл. частині «Виключені документи».", "Объект.ИсключенныеДокументы")

    # К05 — не отправлены заказчику
    без_отметки = [р for р in док.РасшифровкаДокументов if р["Проведен"] and not р["Оригинал"]]
    if без_отметки:
        замечание(док, УРОВЕНЬ_ИНФО, "К05",
                  f"Проведених документів без відмітки «Оригінал»: {len(без_отметки)} на "
                  f"{sum(р['СуммаДт'] for р in без_отметки):,.2f} грн.")


