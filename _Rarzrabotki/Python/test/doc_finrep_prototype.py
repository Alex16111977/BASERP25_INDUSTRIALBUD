def _найти_непроведенный(buh, вид, номер, подразделение):
    """ВНИМАНИЕ: номер документа в BuhBud НЕ уникален (одинаковые номера в разных годах),
    поэтому ищем по номеру + признаку «непроведён» + подразделению договора."""
    q = buh.NewObject("Запрос")
    q.Текст = (f"ВЫБРАТЬ Р.Ссылка КАК С, ПРЕДСТАВЛЕНИЕ(Р.Ссылка) КАК П "
               f"ИЗ Документ.{вид} КАК Р "
               f"ГДЕ Р.Номер ПОДОБНО &Н И НЕ Р.ПометкаУдаления И НЕ Р.Проведен "
               f"  И Р.ДоговорКонтрагента.Подразделение.Наименование = &Подр")
    q.УстановитьПараметр("Н", "%" + номер + "%")
    q.УстановитьПараметр("Подр", подразделение)
    т = q.Execute().Выгрузить()
    if т.Количество() == 0:
        print(f"  ⚠ документ {вид} №{номер} НЕ ЗНАЙДЕНО — виключення не застосовано")
        return None
    if т.Количество() > 1:
        print(f"  ⚠ під №{номер} знайдено {т.Количество()} документів — беремо перший")
    return т.Получить(0).С


