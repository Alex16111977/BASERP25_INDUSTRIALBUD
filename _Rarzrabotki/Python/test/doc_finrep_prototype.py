УРОВЕНЬ_ОШИБКА = "Помилка"
УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ = "Попередження"
УРОВЕНЬ_ИНФО = "Інформація"


# ──────────────────────────────────────────────────────────────────────────
#  Модель документа (в BSL это реквизиты шапки и табличные части)
# ──────────────────────────────────────────────────────────────────────────
class Документ:
    def __init__(self, buh):
        self.buh = buh
        # шапка
        self.ДатаРасчета = None            # конец дня
        self.НачалоПериода = None          # None = с начала времён
        self.СтавкаНДС = 20
        self.ПроцентУтриманняПоУмолчанию = 0
        self.ВключатьНепроведенные = True
        self.ПорогДнейНепроведенных = 30
        # табличные части-параметры
        self.Подразделения = []            # [{Подразделение, Включать, ПроцентУтримання, КоефАктів,
                                           #   ГарантийныеПлатежи, ВариантФормулы, СуммаСоглашения, СуммаДЦ, Примечание}]
        self.ДоговорыДополнительно = []    # [{Подразделение, Договор}]
        self.СчетаРасчетов = []            # [Счет]
        self.Корректировки = []            # [{Подразделение, Колонка, Сумма, Причина}]
        self.ИсключенныеДокументы = []     # [{Документ, Причина}] — точечный вывод документа из расчёта
        # результат
        self.Расчет = []
        self.РасшифровкаДокументов = []
        self.Контроль = []


# ──────────────────────────────────────────────────────────────────────────
#  Служебное
