# Варианты формулы «Разом до отримання» (2 варианта покрывают все 4 случая Excel)
ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ = "ЗаборгованістьПлюсАкти"      # G + I + J + H*КоефАктів
ФОРМУЛА_ВИКОНАННЯ_МІНУС_ОПЛАТА = "ВиконанняМінусОплата"  # (E+H)*(1-%Утримання) + J - F
