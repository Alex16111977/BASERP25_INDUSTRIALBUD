def замечание(док, уровень, код, текст, путь=""):
    док.Контроль.append({"Уровень": уровень, "Код": код, "Текст": текст, "Путь": путь})


def имя(ссылка):
    if ссылка is None:
        return ""
    try:
        return str(ссылка.Наименование).strip()
    except Exception:
        return str(ссылка)


def кд(buh, год, мес, день):
    """Конец дня без COM-сдвига дат: получаем дату запросом на стороне 1С."""
    q = buh.NewObject("Запрос")
    q.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({год},{мес},{день},23,59,59) КАК Д"
    return q.Execute().Выгрузить().Получить(0).Д


def нд(buh, год, мес, день):
    q = buh.NewObject("Запрос")
    q.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({год},{мес},{день},0,0,0) КАК Д"
    return q.Execute().Выгрузить().Получить(0).Д


def массив(buh, значения):
    м = buh.NewObject("Массив")
    for з in значения:
        м.Добавить(з)
    return м


# ──────────────────────────────────────────────────────────────────────────
#  ПроверитьПараметры — блокирующие ошибки и предупреждения ДО расчёта
# ──────────────────────────────────────────────────────────────────────────
def ПроверитьПараметры(док):
    док.Контроль = []
    buh = док.buh

    # --- П04/П05: даты
    if док.ДатаРасчета is None:
        замечание(док, УРОВЕНЬ_ОШИБКА, "П04", "Не заповнено «Дата розрахунку».", "Объект.ДатаРасчета")
    if док.НачалоПериода is not None and док.ДатаРасчета is not None and док.НачалоПериода > док.ДатаРасчета:
        замечание(док, УРОВЕНЬ_ОШИБКА, "П05",
                  "«Початок періоду» пізніше за «Дата розрахунку».", "Объект.НачалоПериода")

    # --- П06: счета
    if not док.СчетаРасчетов:
        сч = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("361")
        док.СчетаРасчетов = [сч]
        замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П06",
                  "Рахунки розрахунків не задані — підставлено 361.", "Объект.СчетаРасчетов")
    # --- П07: у счёта должно быть субконто «Договори» вторым
    for сч in док.СчетаРасчетов:
        вс = сч.ВидыСубконто
        имена = [имя(вс.Получить(i).ВидСубконто) for i in range(вс.Количество())]
        if len(имена) < 2 or "огов" not in имена[1]:
            замечание(док, УРОВЕНЬ_ОШИБКА, "П07",
                      f"Рахунок {сч.Код}: друге субконто не «Договори» ({имена}). "
                      "Розріз за підрозділом договору неможливий.", "Объект.СчетаРасчетов")

    # --- П01..П03, П10..П14: строки подразделений
    включенные = [с for с in док.Подразделения if с.get("Включать", True)]
    if not включенные:
        замечание(док, УРОВЕНЬ_ОШИБКА, "П01",
                  "Не вибрано жодного підрозділу (табл. частина порожня або всі рядки вимкнені).",
                  "Объект.Подразделения")

    видел = {}
    for i, с in enumerate(док.Подразделения, 1):
        подр = с.get("Подразделение")
        если_путь = f"Объект.Подразделения[{i-1}]"
        if подр is None or подр.Пустая():
            замечание(док, УРОВЕНЬ_ОШИБКА, "П03", f"Рядок {i}: підрозділ не заповнено.", если_путь)
            continue
        ключ = имя(подр)
        if ключ in видел:
            замечание(док, УРОВЕНЬ_ОШИБКА, "П02",
                      f"Підрозділ «{ключ}» вказано двічі (рядки {видел[ключ]} та {i}).", если_путь)
        else:
            видел[ключ] = i
        if подр.ПометкаУдаления:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П12",
                      f"Рядок {i}: підрозділ «{ключ}» позначено на видалення.", если_путь)

        п = float(с.get("ПроцентУтримання", 0) or 0)
        if п < 0 or п > 100:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П10",
                      f"Рядок {i}: відсоток утримання {п} поза межами 0..100 — обрізано.", если_путь)
            с["ПроцентУтримання"] = min(max(п, 0), 100)

        к = с.get("КоефАктів", None)
        if к is None:
            с["КоефАктів"] = 1
        elif float(к) < 0 or float(к) > 1:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П19",
                      f"Рядок {i}: коефіцієнт актів {к} поза межами 0..1 — обрізано.", если_путь)
            с["КоефАктів"] = min(max(float(к), 0), 1)

        в = с.get("ВариантФормулы")
        if not в:
            с["ВариантФормулы"] = ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П14",
                      f"Рядок {i} ({ключ}): не задано варіант формули — узято «{ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ}».",
                      если_путь)
        elif в not in (ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ, ФОРМУЛА_ВИКОНАННЯ_МІНУС_ОПЛАТА, ФОРМУЛА_ЛИШЕ_РУЧНИЙ):
            замечание(док, УРОВЕНЬ_ОШИБКА, "П20", f"Рядок {i}: невідомий варіант формули «{в}».", если_путь)

        # П11: параметр задан, но формула его не использует
        if с["ВариантФормулы"] == ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ and float(с.get("ПроцентУтримання", 0) or 0) > 0:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П11",
                      f"Рядок {i} ({ключ}): відсоток утримання заданий, але формула "
                      f"«{ФОРМУЛА_ЗАБОРГ_ПЛЮС_АКТИ}» його не використовує.", если_путь)
        if с["ВариантФормулы"] == ФОРМУЛА_ВИКОНАННЯ_МІНУС_ОПЛАТА and float(с.get("ГарантийныеПлатежи", 0) or 0) != 0:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П11",
                      f"Рядок {i} ({ключ}): гарантійні платежі задані, але формула "
                      f"«{ФОРМУЛА_ВИКОНАННЯ_МІНУС_ОПЛАТА}» їх не використовує.", если_путь)

    # --- П15..П17: договоры дополнительно
    подр_вкл = {имя(с["Подразделение"]) for с in включенные
                if с.get("Подразделение") is not None and not с["Подразделение"].Пустая()}
    видел_дог = {}
    к_удалению = []
    for i, с in enumerate(док.ДоговорыДополнительно, 1):
        дог = с.get("Договор")
        путь = f"Объект.ДоговорыДополнительно[{i-1}]"
        if дог is None or дог.Пустая():
            замечание(док, УРОВЕНЬ_ОШИБКА, "П21", f"Дод. договори, рядок {i}: договір не заповнено.", путь)
            continue
        ключ = str(buh.String(дог.УникальныйИдентификатор()))
        if ключ in видел_дог:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П17",
                      f"Дод. договори, рядок {i}: договір «{имя(дог)}» вказано двічі — рядок проігноровано.", путь)
            к_удалению.append(i - 1)
            continue
        видел_дог[ключ] = i
        # П15 — двойной счёт: договор уже попадёт по своему подразделению
        собств = имя(дог.Подразделение) if дог.Подразделение is not None else ""
        if собств and собств in подр_вкл:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П15",
                      f"Дод. договори, рядок {i}: договір «{имя(дог)}» уже входить у розрахунок "
                      f"за власним підрозділом «{собств}» — рядок проігноровано (подвійний рахунок).", путь)
            к_удалению.append(i - 1)
            continue
        # П16 — целевое подразделение не входит в расчёт
        цель = с.get("Подразделение")
        if цель is None or цель.Пустая() or имя(цель) not in подр_вкл:
            замечание(док, УРОВЕНЬ_ОШИБКА, "П16",
                      f"Дод. договори, рядок {i}: підрозділ «{имя(цель)}» відсутній серед увімкнених "
                      "рядків табл. частини «Підрозділи».", путь)

    for idx in reversed(к_удалению):
        док.ДоговорыДополнительно.pop(idx)

    # --- П18: НДС
    if float(док.СтавкаНДС or 0) == 0:
        замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П18",
                  "Ставка ПДВ = 0 — колонка «незареєстрований ПДВ» буде нульова.", "Объект.СтавкаНДС")

    # --- П22: корректировки
    for i, с in enumerate(док.Корректировки, 1):
        путь = f"Объект.Корректировки[{i-1}]"
        if not (с.get("Причина") or "").strip():
            замечание(док, УРОВЕНЬ_ОШИБКА, "П22",
                      f"Коригування, рядок {i}: не заповнено «Причина». "
                      "Ручні суми без пояснення заборонені.", путь)
        подр = с.get("Подразделение")
        if подр is None or подр.Пустая() or имя(подр) not in подр_вкл:
            замечание(док, УРОВЕНЬ_ОШИБКА, "П23",
                      f"Коригування, рядок {i}: підрозділ «{имя(подр)}» відсутній серед увімкнених.", путь)
        if float(с.get("Сумма", 0) or 0) == 0:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П24",
                      f"Коригування, рядок {i}: сума = 0, рядок нічого не змінює.", путь)

    # --- П25/П26: исключённые документы
    видел_искл = set()
    for i, с in enumerate(док.ИсключенныеДокументы, 1):
        путь = f"Объект.ИсключенныеДокументы[{i-1}]"
        д = с.get("Документ")
        if д is None or д.Пустая():
            замечание(док, УРОВЕНЬ_ОШИБКА, "П25",
                      f"Виключені документи, рядок {i}: документ не заповнено.", путь)
            continue
        if not (с.get("Причина") or "").strip():
            замечание(док, УРОВЕНЬ_ОШИБКА, "П26",
                      f"Виключені документи, рядок {i}: не заповнено «Причина». "
                      "Виключення без пояснення заборонено.", путь)
        к = str(buh.String(д.УникальныйИдентификатор()))
        if к in видел_искл:
            замечание(док, УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "П27",
                      f"Виключені документи, рядок {i}: документ вказано двічі.", путь)
        видел_искл.add(к)

    ошибки = [з for з in док.Контроль if з["Уровень"] == УРОВЕНЬ_ОШИБКА]
    return len(ошибки) == 0


