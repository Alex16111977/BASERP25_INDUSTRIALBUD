import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# Свод по Счёт + Организация + Субконто1(вид налога). Имена субконто резолвим в запросе через ПРЕДСТАВЛЕНИЕ.
q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Ост.Счет КАК Счет,
    Ост.Организация КАК Организация,
    Ост.Субконто1 КАК Налог,
    СУММА(Ост.СуммаНачальныйОстаток) КАК НО,
    СУММА(Ост.СуммаОборотДт) КАК Дт,
    СУММА(Ост.СуммаОборотКт) КАК Кт,
    СУММА(Ост.СуммаКонечныйОстаток) КАК КО
ИЗ
    РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(
        ДАТАВРЕМЯ(2025,12,1,0,0,0),
        ДАТАВРЕМЯ(2026,6,30,23,59,59),
        ,
        ,
        Счет В ИЕРАРХИИ (&Счета)) КАК Ост
СГРУППИРОВАТЬ ПО
    Ост.Счет, Ост.Организация, Ост.Субконто1
УПОРЯДОЧИТЬ ПО
    Счет
"""
сч = buh.NewObject("Массив")
for code in ["641","642","651","65","645"]:
    a = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(code)
    if not a.Пустая():
        сч.Добавить(a)
q.УстановитьПараметр("Счета", сч)
r = q.Execute().Выгрузить()
print("rows:", r.Количество())
print(f"{'Счёт':<6}|{'Организация':<30}|{'Вид налога/субконто':<34}|{'НачОст':>15}|{'Дт':>15}|{'Кт':>15}|{'КонОст':>15}")
for i in range(r.Количество()):
    s = r.Получить(i)
    код = str(s.Счет.Код)
    орг = str(s.Организация.Наименование) if not s.Организация.Пустая() else "-"
    налог = str(s.Налог.Наименование) if (s.Налог and hasattr(s.Налог,'Наименование') and not s.Налог.Пустая()) else "(пусто)"
    print(f"{код:<6}|{орг[:30]:<30}|{налог[:34]:<34}|{s.НО:>15,.2f}|{s.Дт:>15,.2f}|{s.Кт:>15,.2f}|{s.КО:>15,.2f}")
