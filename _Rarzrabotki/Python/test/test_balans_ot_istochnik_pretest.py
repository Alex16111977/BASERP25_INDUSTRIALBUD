# -*- coding: utf-8 -*-
"""Rule #-1 pre-тест фикса захвата источника ПрочиеАктивыПассивы в свёртке.
Read-only. Проверяет ДО правки BSL, что новая логика даст эталоны штатного баланса."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

def ref_statya(name):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Н", name)
    q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов "
               "ГДЕ Наименование = &Н")
    r = q.Выполнить().Выгрузить()
    return r[0].С if r.Количество() else None

ОТ  = ref_statya("Оплата труда")
КАС = ref_statya("Денежные средства (наличные)")

MONTHS = [
    ("дек2025", "ДАТАВРЕМЯ(2025,12,31,23,59,59)"),
    ("янв2026", "ДАТАВРЕМЯ(2026, 1,31,23,59,59)"),
    ("фев2026", "ДАТАВРЕМЯ(2026, 2,28,23,59,59)"),
    ("мар2026", "ДАТАВРЕМЯ(2026, 3,31,23,59,59)"),
]
ETALON_OT  = {"дек2025": 1913101.80, "янв2026": 246187.13, "фев2026": 248195.93, "мар2026": -125654.87}
ETALON_KAS = {"дек2025":21783747.00, "янв2026":23489702.23, "фев2026":18441213.58, "мар2026":10304321.88}
TOL = 0.05
fails = []

def pap_signed(statya, lit, src_filter):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("Ст", statya)
    q.Текст = f"""
    ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Период <= {lit} И Т.Статья = &Ст {src_filter}
    """
    return f(q.Выполнить().Выгрузить()[0].КО)

EMPTY = "И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)"
BOTH  = ("И Т.Источник В (ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка), "
         "ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПрочиеАктивыПассивы))")
ALL   = ""

print("=== A. ПАП(ОТ, {empty,named}) == эталон ОТ (цель Свод_ОплатаТруда) ===")
for m, lit in MONTHS:
    got = pap_signed(ОТ, lit, BOTH)
    ok = abs(got - ETALON_OT[m]) <= TOL
    print(f"  {m}: ПАП(ОТ,both)={got:>16,.2f}  эталон={ETALON_OT[m]:>16,.2f}  {'OK' if ok else 'FAIL'}")
    if not ok: fails.append(f"OT {m}: {got} != {ETALON_OT[m]}")
    if abs(pap_signed(ОТ, lit, BOTH) - pap_signed(ОТ, lit, ALL)) > TOL:
        fails.append(f"OT {m}: both != all (есть прочие источники у ОТ!)")

print("\n=== B. касса наличная: текущий регистр + ПАП(касса,{empty,named}) == эталон ===")
for m, lit in MONTHS:
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("КАС", КАС)
    nm = {"дек2025":"ДАТАВРЕМЯ(2025,12,1)","янв2026":"ДАТАВРЕМЯ(2026,1,1)",
          "фев2026":"ДАТАВРЕМЯ(2026,2,1)","мар2026":"ДАТАВРЕМЯ(2026,3,1)"}[m]
    q.Текст = f"""
    ВЫБРАТЬ СУММА(Рег.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Статья = &КАС И Рег.Регистратор.Месяц = {nm}
    """
    cur_reg = f(q.Выполнить().Выгрузить()[0].КО)
    add_pryamoy = pap_signed(КАС, lit, BOTH)
    new_total = cur_reg + add_pryamoy
    ok = abs(new_total - ETALON_KAS[m]) <= TOL
    print(f"  {m}: тек.регистр={cur_reg:>14,.2f} + Прямой(both)={add_pryamoy:>14,.2f} = {new_total:>14,.2f}  эталон={ETALON_KAS[m]:>14,.2f}  {'OK' if ok else 'FAIL'}")
    if not ok: fails.append(f"KAS {m}: {new_total} != {ETALON_KAS[m]}")

print("\n=== C. Регрессия: источник 'ПрочиеАктивыПассивы' трогает ТОЛЬКО {ОТ, касса наличная} ===")
for m, lit in MONTHS:
    q = erp.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Период <= {lit}
        И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПрочиеАктивыПассивы)
    СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)
    ИМЕЮЩИЕ СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) <> 0
    """
    arts = {str(r.Ст).strip() for r in q.Выполнить().Выгрузить()}
    extra = arts - {"Оплата труда", "Денежные средства (наличные)"}
    print(f"  {m}: статьи named-источника = {sorted(arts)}  {'OK' if not extra else 'FAIL extra='+str(extra)}")
    if extra: fails.append(f"named {m}: лишние статьи {extra}")

print("\n=== D. Sanity: сейчас (до фикса) ОТ в регистре НЕ равен эталону (баг существует) ===")
q = erp.NewObject("Запрос")
q.УстановитьПараметр("ОТ", ОТ)
q.Текст = """
ВЫБРАТЬ СУММА(Рег.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Статья = &ОТ И Рег.Регистратор.Месяц = ДАТАВРЕМЯ(2026,1,1)
"""
cur_ot = f(q.Выполнить().Выгрузить()[0].КО)
print(f"  янв ОТ в регистре сейчас = {cur_ot:,.2f} (ожидаем ~-9 430 814, т.е. != эталона +246 187)")

print("\n" + ("="*60))
if fails:
    print(f"PRE-TEST FAIL ({len(fails)}):")
    for x in fails: print("  -", x)
    sys.exit(1)
else:
    print("PRE-TEST PASS — новая логика даёт эталоны, регрессии нет.")
