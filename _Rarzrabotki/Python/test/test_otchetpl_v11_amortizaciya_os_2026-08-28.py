def разбор(таб):
    """Суммы АГРЕГИРУЮТСЯ по ключу без аналитики: v11 дробит строку амортизации
    на карточки (47 вместо 1), поэтому сравнение построчно неприменимо — сверяем
    агрегаты (это и есть инвариант «суммы не поехали»)."""
    ключи, строки = {}, []
    for i in range(таб.Количество()):
        с = таб.Получить(i)
        к = (int(с.КолонкаСорт), S(с.Подразделение), S(с.СтатьяPL) if с.СтатьяPL else "",
             S(с.ДДС) if с.ДДС else "", S(с.Документ) if с.Документ else "")
        а = ключи.setdefault(к, [0.0, 0.0, 0.0])
        а[0] += float(с.СуммаФ1 or 0)
        а[1] += float(с.СуммаФ2 or 0)
        а[2] += float(с.СуммаИтого or 0)
        строки.append((int(с.КолонкаСорт), S(с.Документ) if с.Документ else "", с.Аналитика,
                       round(float(с.СуммаИтого or 0), 2)))
    return ключи, строки


