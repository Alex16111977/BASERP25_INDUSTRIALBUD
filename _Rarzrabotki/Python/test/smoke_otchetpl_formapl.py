# -*- coding: utf-8 -*-
"""
Smoke (bas-verify): отчёт А_ОтчетPL после загрузки нового кода в BaseERP.
  1) Вызвать ДЕПЛОЕННЫЙ метод Отчеты.А_ОтчетPL.ПолучитьОбъединенныеДанные() (свежее COM видит правку)
     → проверить наличие 4 колонок + построчные инварианты Ф1+Ф2=ЕРП, РазницаФ1+Ф2=Разница.
  2) Скомпоновать отчёт целиком (СКД + ПриКомпоновкеРезультата) за декабрь 2025 → без ошибки, есть строки.
"""
import sys, io, datetime
import win32com.client, pythoncom

if sys.stdout.encoding != "utf-8":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

pythoncom.CoInitialize()
ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

nach = datetime.datetime(2025, 12, 1)
konec = datetime.datetime(2025, 12, 31, 23, 59, 59)

Отчет = ERP.Отчеты.А_ОтчетPL.Создать()

# --- 1) деплоенный метод ---
ТЗ = Отчет.ПолучитьОбъединенныеДанные(nach, konec, False, True, True, True)
cols = [c.Имя for c in ТЗ.Колонки]
print(f"ПолучитьОбъединенныеДанные: строк={ТЗ.Количество()}, колонок={len(cols)}")
for need in ("СуммаЕРПФ1", "СуммаЕРПФ2", "РазницаФ1", "РазницаФ2"):
    assert need in cols, f"в деплоенном методе нет колонки {need}"
print("  4 новые колонки присутствуют:", [c for c in cols if "ЕРПФ" in c or "РазницаФ" in c])

bad1 = bad2 = 0
sЕРП = sФ1 = sФ2 = sРазн = sРФ1 = sРФ2 = 0.0
for i in range(ТЗ.Количество()):
    r = ТЗ[i]
    ерп, ф1, ф2 = float(r.СуммаЕРП), float(r.СуммаЕРПФ1), float(r.СуммаЕРПФ2)
    разн, рф1, рф2 = float(r.Разница), float(r.РазницаФ1), float(r.РазницаФ2)
    sЕРП += ерп; sФ1 += ф1; sФ2 += ф2; sРазн += разн; sРФ1 += рф1; sРФ2 += рф2
    if abs(ф1 + ф2 - ерп) > 0.01: bad1 += 1
    if abs(рф1 + рф2 - разн) > 0.01: bad2 += 1
print(f"  Σ СуммаЕРП={sЕРП:,.2f}  Σ ЕРПФ1={sФ1:,.2f}  Σ ЕРПФ2={sФ2:,.2f}  (Ф1+Ф2={sФ1+sФ2:,.2f})")
print(f"  Σ Разница={sРазн:,.2f}  Σ РазницаФ1={sРФ1:,.2f}  Σ РазницаФ2={sРФ2:,.2f}")
print(f"  строк ломают Ф1+Ф2=ЕРП: {bad1}; РазницаФ1+Ф2=Разница: {bad2}")
assert bad1 == 0 and bad2 == 0, "построчные инварианты нарушены"
assert abs(sФ1 + sФ2 - sЕРП) < 0.5, "Σ(Ф1+Ф2) != Σ ЕРП"

# --- 2) полная компоновка отчёта (СКД + обработчик) ---
try:
    КН = Отчет.КомпоновщикНастроек
    Период = ERP.NewObject("СтандартныйПериод")
    Период.ДатаНачала = nach
    Период.ДатаОкончания = konec
    КН.Настройки.ПараметрыДанных.УстановитьЗначениеПараметра("Период", Период)
    ТабДок = ERP.NewObject("ТабличныйДокумент")
    Отчет.СкомпоноватьРезультат(ТабДок, None)
    print(f"\nСкомпоноватьРезультат: OK — строк={ТабДок.ВысотаТаблицы}, колонок={ТабДок.ШиринаТаблицы}")
    assert ТабДок.ВысотаТаблицы > 0, "пустой результат компоновки"
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    print(f"\n!! Полная компоновка не выполнилась через COM: {msg}")
    print("   (метод данных + СКД-валидация прошли; компоновку можно проверить в UI)")

print("\n########## SMOKE OK ##########")
