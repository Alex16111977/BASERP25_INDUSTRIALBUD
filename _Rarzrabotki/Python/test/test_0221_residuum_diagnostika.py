def run(withorg, надату):
    q = buh.NewObject("Запрос")
    орг = "Ост.Организация КАК Организация, ПРЕДСТАВЛЕНИЕ(Ост.Организация) КАК ОргС," if withorg else ""
    q.Текст = f"""
    ВЫБРАТЬ
        {орг}
        Ост.Субконто1 КАК С1, ПРЕДСТАВЛЕНИЕ(Ост.Субконто1) КАК С1С,
        Ост.Субконто2 КАК С2, ПРЕДСТАВЛЕНИЕ(Ост.Субконто2) КАК С2С,
        Ост.Субконто3 КАК С3, ПРЕДСТАВЛЕНИЕ(Ост.Субконто3) КАК С3С,
        Ост.СуммаОстатокДт КАК Сумма,
        Ост.КоличествоОстатокДт КАК Количество
    ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет = &Счет) КАК Ост
    ГДЕ Ост.КоличествоОстатокДт = 0 И Ост.СуммаОстатокДт <> 0
    УПОРЯДОЧИТЬ ПО Сумма УБЫВ
    """
    q.УстановитьПараметр("Счет", счет.Ссылка)
    q.УстановитьПараметр("НаДату", надату)
    return q.Выполнить().Выгрузить()

