def test6_subquery_document(conn):
    """Тест 6: Суб-запрос к конкретному документу (КоличествоДт - КоличествоКт)"""
    print("\n" + "=" * 80)
    print("ТЕСТ 6: Суб-запрос — КоличествоДт - КоличествоКт для doc 007653")
    print("=" * 80)

    # Найти UUID документа через ПРЕДСТАВЛЕНИЕ
    query = conn.NewObject("Запрос")
    query.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 1\n"
        "  Док.Ссылка КАК Ссылка,\n"
        "  ПРЕДСТАВЛЕНИЕ(Док.Ссылка) КАК Предст\n"
        "ИЗ Документ.ПриобретениеТоваровУслуг КАК Док\n"
        "ГДЕ Док.Номер ПОДОБНО \"%007653%\"\n"
        "  И Док.Дата МЕЖДУ &Н И &К"
    )
    query.УстановитьПараметр("Н", make_time(DATE_FROM))
    query.УстановитьПараметр("К", make_time(DATE_TO))

    try:
        result = query.Выполнить().Выбрать()
        if not result.Следующий():
            print("[!] Документ 007653 не найден в справочнике")
            return
        doc_ref = result.Ссылка
        doc_name = str(result.Предст)
        print(f"  Найден: {doc_name}")

        # Теперь суб-запрос как в ПроверитьДокументВBuhBud
        q2 = conn.NewObject("Запрос")
        q2.Текст = (
            "ВЫБРАТЬ\n"
            "  СУММА(ЕСТЬNULL(Движения.КоличествоДт, 0)) - СУММА(ЕСТЬNULL(Движения.КоличествоКт, 0)) КАК Количество\n"
            "ИЗ\n"
            "  РегистрБухгалтерии.Хозрасчетный КАК Движения\n"
            "ГДЕ\n"
            "  Движения.Регистратор = &Регистратор"
        )
        q2.УстановитьПараметр("Регистратор", doc_ref)
        r2 = q2.Выполнить().Выбрать()
        if r2.Следующий():
            print(f"  Количество (КолДт - КолКт): {r2.Количество}")
            print("[OK] Тест 6 пройден")
        else:
            print("[!] Нет записей")
    except Exception as e:
        print(f"[ОШИБКА] Тест 6: {e}")


