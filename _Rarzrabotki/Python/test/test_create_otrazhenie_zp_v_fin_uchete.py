# -*- coding: utf-8 -*-
# Тест Find-Or-Create: СоздатьДокументОтражениеЗарплатыВФинансовомУчете()
# для А_ОтражениеЗПпоКазне.
#
# ПЕРЕДУМОВА: оновлений ObjectModule.bsl завантажений у конфігурацію (F7).
# Документ А_ОтражениеЗПпоКазне 000000001 від 31.12.2025 ПРОВЕДЕНИЙ з заповненими ТЧ.
#
# Сценарії:
#   1. Create: перший виклик створює ОтражениеЗарплатыВФинансовомУчете
#   2. Update: повторний виклик → той самий UUID, без дублів
#   3. Інваріант: SUM(…ПоФизлицам) == SUM(…Начисления) по Сумма + ВзносыВсего
#   4. Проводки: у РегистрБухгалтерии.Хозрасчетный з Регистратор=<новий ОЗ> є Кт 661
#   5. ФизическиеЛица: унікальні з усіх ТЧ
#   6. Guard: на непроведеному батькові процедура не створює документ
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


def parse_num(val):
    s = S(val).replace('\xa0', '').replace(' ', '').replace(',', '.')
    return float(s or "0")


# === Знайти батьківський документ ===
q = erp.NewObject("Запрос")
q.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка, Д.Проведен "
    "ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д "
    "ГДЕ Д.Номер = &Н И Д.Дата МЕЖДУ &Д1 И &Д2"
)
q.SetParameter("Н", "000000001")
q.SetParameter("Д1", com_date(2025, 12, 31, 0, 0, 0))
q.SetParameter("Д2", com_date(2025, 12, 31, 23, 59, 59))
sel = q.Execute().Выбрать()
if not sel.Следующий():
    print("ПОМИЛКА: батьківський документ А_ОтражениеЗПпоКазне не знайдено")
    sys.exit(1)

doc_ref = sel.Ссылка
proveden = S(sel.Проведен)
print(f"Батько: {S(doc_ref)}, Проведен={proveden}")
if proveden != "Да":
    print("ПОМИЛКА: батько не проведений — спершу провести його")
    sys.exit(1)

obj = doc_ref.ПолучитьОбъект()

# === Суми у джерелі (для інваріанту) ===
src_sum_na = 0.0
src_sum_vz = 0.0
for i in range(obj.НачисленнаяЗарплатаИВзносыПоФизлицам.Количество()):
    r = obj.НачисленнаяЗарплатаИВзносыПоФизлицам.Получить(i)
    src_sum_na += parse_num(r.Сумма)
    src_sum_vz += parse_num(r.ВзносыВсего)
print(f"\nДжерело НачисленнаяЗарплатаИВзносыПоФизлицам: рядків={obj.НачисленнаяЗарплатаИВзносыПоФизлицам.Количество()}, "
      f"Сума={src_sum_na:.2f}, Внески={src_sum_vz:.2f}")

# === Виклик 1: створити ===
print("\n>>> Виклик 1: СоздатьДокументОтражениеЗарплатыВФинансовомУчете() ...")
try:
    obj.СоздатьДокументОтражениеЗарплатыВФинансовомУчете()
    print(">>> OK")
except Exception as e:
    print(f">>> ПОМИЛКА: {e}")
    sys.exit(1)

# === Знайти створений підлеглий ===
q2 = erp.NewObject("Запрос")
q2.Text = (
    "ВЫБРАТЬ ОЗ.Ссылка, ОЗ.Проведен, ОЗ.Дата, ОЗ.ПериодРегистрации, "
    "       ОЗ.Сводно, ОЗ.ПроводкиПоРаботникам "
    "ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете КАК ОЗ "
    "ГДЕ ОЗ.А_ДокОтражениеЗПпоКазне = &Осн И НЕ ОЗ.ПометкаУдаления"
)
q2.SetParameter("Осн", doc_ref)
r2 = q2.Execute().Выгрузить()
print(f"\nЗнайдено ОтражениеЗарплатыВФинансовомУчете: {r2.Количество()}")
if r2.Количество() == 0:
    print("FAIL: жодного ОтражениеЗарплатыВФинансовомУчете не створено")
    sys.exit(1)

оз_row = r2.Получить(0)
оз_ref = оз_row.Ссылка
print(f"  {S(оз_ref)}")
print(f"  Проведен={S(оз_row.Проведен)}  ПериодРегистрации={S(оз_row.ПериодРегистрации)}")
print(f"  Сводно={S(оз_row.Сводно)}  ПроводкиПоРаботникам={S(оз_row.ПроводкиПоРаботникам)}")

оз_uuid_1 = S(оз_ref.УникальныйИдентификатор())

# Лічильники ТЧ + суми
оз_obj = оз_ref.ПолучитьОбъект()
na_cnt = оз_obj.НачисленнаяЗарплатаИВзносы.Количество()
napofl_cnt = оз_obj.НачисленнаяЗарплатаИВзносыПоФизлицам.Количество()
ndfl_cnt = оз_obj.НачисленныйНДФЛ.Количество()
ud_cnt = оз_obj.УдержаннаяЗарплата.Количество()
fl_cnt = оз_obj.ФизическиеЛица.Количество()

dst_sum_na = 0.0
dst_sum_vz = 0.0
for i in range(na_cnt):
    r = оз_obj.НачисленнаяЗарплатаИВзносы.Получить(i)
    dst_sum_na += parse_num(r.Сумма)
    dst_sum_vz += parse_num(r.ВзносыВсего)

dst_pofl_na = 0.0
dst_pofl_vz = 0.0
for i in range(napofl_cnt):
    r = оз_obj.НачисленнаяЗарплатаИВзносыПоФизлицам.Получить(i)
    dst_pofl_na += parse_num(r.Сумма)
    dst_pofl_vz += parse_num(r.ВзносыВсего)

print(f"\n=== ТЧ ОтражениеЗарплатыВФинансовомУчете (виклик 1) ===")
print(f"  НачисленнаяЗарплатаИВзносы:            {na_cnt} рядків, Сума={dst_sum_na:.2f}, Внески={dst_sum_vz:.2f}")
print(f"  НачисленнаяЗарплатаИВзносыПоФизлицам:  {napofl_cnt} рядків, Сума={dst_pofl_na:.2f}, Внески={dst_pofl_vz:.2f}")
print(f"  НачисленныйНДФЛ:                       {ndfl_cnt}")
print(f"  УдержаннаяЗарплата:                    {ud_cnt}")
print(f"  ФизическиеЛица:                        {fl_cnt}")

# Перевірка, що СпособОтраженияЗарплатыВБухучете у НДФЛ пустий
ndfl_sposob_empty = True
for i in range(ndfl_cnt):
    r = оз_obj.НачисленныйНДФЛ.Получить(i)
    if erp.ЗначениеЗаполнено(r.СпособОтраженияЗарплатыВБухучете):
        ndfl_sposob_empty = False
        break

# Унікальні ФЛ з трьох ТЧ джерела (для перевірки)
unique_fl_src = set()
for tc in (оз_obj.НачисленнаяЗарплатаИВзносыПоФизлицам,
           оз_obj.НачисленныйНДФЛ,
           оз_obj.УдержаннаяЗарплата):
    for i in range(tc.Количество()):
        r = tc.Получить(i)
        fl = r.ФизическоеЛицо
        if erp.ЗначениеЗаполнено(fl):
            unique_fl_src.add(S(fl.УникальныйИдентификатор()))

# === Виклик 2: повторний (має оновити той самий документ) ===
print("\n>>> Виклик 2 (повторний): СоздатьДокументОтражениеЗарплатыВФинансовомУчете() ...")
try:
    obj.СоздатьДокументОтражениеЗарплатыВФинансовомУчете()
    print(">>> OK")
except Exception as e:
    print(f">>> ПОМИЛКА: {e}")

r3 = q2.Execute().Выгрузить()
print(f"\nЗнайдено ОтражениеЗарплатыВФинансовомУчете після виклику 2: {r3.Количество()}")
if r3.Количество() != 1:
    print(f"FAIL: очікувався 1, отримано {r3.Количество()} (дубль!)")
    sys.exit(1)

оз_ref_2 = r3.Получить(0).Ссылка
оз_uuid_2 = S(оз_ref_2.УникальныйИдентификатор())
print(f"  UUID виклику 1: {оз_uuid_1}")
print(f"  UUID виклику 2: {оз_uuid_2}")

# === Проводки у Хозрасчетный ===
# ВАЖЛИВО: у BAS ERP 2.5 проводки по ОтражениеЗарплатыВФинансовомУчете формуються НЕ через
# ОбработкаПроведения документа, а через ВІДКЛАДЕНИЙ механізм "Отражение документов в
# регламентированном учете" (РегламентированныйУчетПроведениеСервер + регламентне завдання).
# Тому одразу після Записать(Проведение) рухів у Хозрасчетный буде 0 — це НЕ помилка.
# Просто інформуємо.
оз_obj_2 = оз_ref_2.ПолучитьОбъект()
dvizh = оз_obj_2.Движения.Хозрасчетный
dvizh.Прочитать()
tz_dvizh = dvizh.Выгрузить()
movs_cnt = tz_dvizh.Количество()

print(f"\n=== Проводки у РегистрБухгалтерии.Хозрасчетный (інформаційно) ===")
print(f"  Всього рухів: {movs_cnt}")
print(f"  (У BAS ERP 2.5 проводки формуються окремо через 'Отражение документов в регл. учёте')")

# === ПЕРЕВІРКИ ===
print("\n=== ПЕРЕВІРКИ ===")
checks = [
    (r2.Количество() == 1, "Створено рівно 1 ОтражениеЗарплатыВФинансовомУчете"),
    (r3.Количество() == 1, "Повторний виклик НЕ створює дубль"),
    (оз_uuid_1 == оз_uuid_2, "UUID збігається між викликами (Find-Or-Create)"),
    (S(оз_row.Проведен) == "Да", "Документ ПРОВЕДЕНО"),
    (S(оз_row.Сводно) == "Нет", "Сводно = Ложь"),
    (S(оз_row.ПроводкиПоРаботникам) == "Да", "ПроводкиПоРаботникам = Істина"),
    (napofl_cnt > 0, "ТЧ НачисленнаяЗарплатаИВзносыПоФизлицам не пуста"),
    (na_cnt > 0, "ТЧ НачисленнаяЗарплатаИВзносы (свертка) не пуста"),
    (na_cnt <= napofl_cnt, "Свертка ≤ деталізація"),
    (abs(dst_sum_na - dst_pofl_na) < 0.01,
     f"Інваріант Суми: свертка({dst_sum_na:.2f}) == деталізація({dst_pofl_na:.2f})"),
    (abs(dst_sum_vz - dst_pofl_vz) < 0.01,
     f"Інваріант Внесків: свертка({dst_sum_vz:.2f}) == деталізація({dst_pofl_vz:.2f})"),
    (abs(dst_pofl_na - src_sum_na) < 0.01,
     f"Джерело({src_sum_na:.2f}) == дочка({dst_pofl_na:.2f}) по Сума"),
    (abs(dst_pofl_vz - src_sum_vz) < 0.01,
     f"Джерело({src_sum_vz:.2f}) == дочка({dst_pofl_vz:.2f}) по Внески"),
    (fl_cnt == len(unique_fl_src), f"ФизическиеЛица ({fl_cnt}) == унікальні з ТЧ ({len(unique_fl_src)})"),
    (ndfl_sposob_empty, "НДФЛ.СпособОтраженияЗарплатыВБухучете — пусто в усіх рядках"),
]
all_ok = True
for ok, desc in checks:
    mark = "OK" if ok else "FAIL"
    print(f"  [{mark}] {desc}")
    if not ok:
        all_ok = False

print()
if all_ok:
    print("==> ТЕСТ СоздатьДокументОтражениеЗарплатыВФинансовомУчете ПРОЙДЕНО")
    sys.exit(0)
else:
    print("==> ПОМИЛКИ")
    sys.exit(1)
