# -*- coding: utf-8 -*-
"""Діагностика: договір 'Договір купівлі-продажу' для Бадлюк Марія Іванівна.
Обробка поставила Підгірці, а в звіті документи мають '6 БУДИНОК (КГ "Подгорцы")'.
Перевіряємо ВСІ поля підрозділу в шапці та РасшифровкаПлатежа.
"""
import win32com.client
import datetime

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

print("Connecting to BaseERP...")
conn = v8.Connect(CONN_ERP)
print("Connected OK\n")

# 1. Знайти договір
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 5
    Спр.Ссылка КАК Ссылка,
    Спр.Наименование КАК Наименование,
    Спр.Подразделение КАК Подразделение,
    Спр.А_ПодразделениеБанк КАК ПодразделениеБанк,
    Спр.А_НаправлениеДеятельностиБанк КАК НаправлениеБанк
ИЗ
    Справочник.ДоговорыКонтрагентов КАК Спр
ГДЕ
    Спр.Наименование ПОДОБНО &Наим"""
q.SetParameter("Наим", "%купівлі-продажу%")

res = q.Execute()
sel = res.Select()
contract_ref = None
while sel.Next():
    print(f"Договір: {conn.String(sel.Наименование)}")
    print(f"  Подразделение: {conn.String(sel.Подразделение)}")
    print(f"  А_ПодразделениеБанк: {conn.String(sel.ПодразделениеБанк)}")
    print(f"  А_НаправлениеДеятельностиБанк: {conn.String(sel.НаправлениеБанк)}")
    contract_ref = sel.Ссылка

if not contract_ref:
    print("Договір не знайдено!")
    exit()

# 2. Банковські документи — показуємо ВСІ поля підрозділу
print("\n" + "=" * 70)
print("БАНКОВСЬКІ ДОКУМЕНТИ (Поступление + Списание)")
print("=" * 70)

for doc_type in ["ПоступлениеБезналичныхДенежныхСредств", "СписаниеБезналичныхДенежныхСредств"]:
    q2 = conn.NewObject("Запрос")
    q2.Text = """ВЫБРАТЬ
        Док.Номер КАК Номер,
        Док.Дата КАК ДатаДок,
        Док.А_Подразделение КАК А_Подразделение,
        Док.А_НаправлениеДеятельности КАК А_НаправлениеДеятельности,
        Док.Подразделение КАК Подразделение,
        Док.НаправлениеДеятельности КАК НаправлениеДеятельности,
        РП.Подразделение КАК РП_Подразделение,
        РП.НаправлениеДеятельности КАК РП_НаправлениеДеятельности
    ИЗ
        Документ.""" + doc_type + """.РасшифровкаПлатежа КАК РП
        ЛЕВОЕ СОЕДИНЕНИЕ Документ.""" + doc_type + """ КАК Док
        ПО РП.Ссылка = Док.Ссылка
    ГДЕ
        Док.Проведен
        И РП.А_Договор = &Договор
        И Док.Дата >= &Дата1"""
    q2.SetParameter("Договор", contract_ref)
    q2.SetParameter("Дата1", datetime.datetime(2025, 12, 1))

    res2 = q2.Execute()
    sel2 = res2.Select()
    print(f"\n  --- {doc_type} ---")
    count = 0
    while sel2.Next():
        count += 1
        print(f"\n  #{count} Док #{sel2.Номер} от {sel2.ДатаДок}")
        print(f"    ШАПКА: А_Подразделение = '{conn.String(sel2.А_Подразделение)}'")
        print(f"    ШАПКА: А_НаправлениеДеятельности = '{conn.String(sel2.А_НаправлениеДеятельности)}'")
        print(f"    ШАПКА: Подразделение (стд) = '{conn.String(sel2.Подразделение)}'")
        print(f"    ШАПКА: НаправлениеДеятельности (стд) = '{conn.String(sel2.НаправлениеДеятельности)}'")
        print(f"    РП: Подразделение = '{conn.String(sel2.РП_Подразделение)}' filled={conn.ValueIsFilled(sel2.РП_Подразделение)}")
        print(f"    РП: НаправлениеДеятельности = '{conn.String(sel2.РП_НаправлениеДеятельности)}' filled={conn.ValueIsFilled(sel2.РП_НаправлениеДеятельности)}")
    print(f"  Всього: {count}")

print("\n=== DONE ===")
