# --- 5. Уникальность (Номенклатура, СпособОтраженияРасходов) в НазначенияИспользования ---
print("\n=== НазначенияИспользования: сколько и уникальны ли по (Номенклатура, Способ) ===")
try:
    q = buh.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ Ссылка, Наименование, Номенклатура, СпособОтраженияРасходов КАК Способ
    ИЗ Справочник.НазначенияИспользования ГДЕ НЕ ПометкаУдаления"""
    s = q.Выполнить().Выбрать()
    rows = []
    while s.Следующий():
        rows.append((buh.String(s.Номенклатура), buh.String(s.Способ)))
    print(f"  всего элементов: {len(rows)}")
    from collections import Counter
    c = Counter(rows)
    dups = {k: v for k, v in c.items() if v > 1}
    print(f"  дублей по (Номенклатура,Способ): {len(dups)}")
    # только по Способу — сколько на способ
    cs = Counter(sp for _, sp in rows)
    print(f"  различных способов: {len(cs)}; макс элементов на 1 способ: {max(cs.values()) if cs else 0}")
except Exception as e:
    ei = getattr(e, 'excepinfo', None); print("  FAIL:", ei[2] if ei else e)

