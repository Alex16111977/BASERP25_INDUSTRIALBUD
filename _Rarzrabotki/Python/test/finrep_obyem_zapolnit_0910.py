# -*- coding: utf-8 -*-
"""Заповнення «Вид продукції» / «Обсяг за договором» у РС.А_ПараметрыДоговоровФинотчета (09.10.2026,
специфікація 2026-10-09-finzvit-obyem-metal-domiki-design). Обсяг — з додатка «Договірна ціна» договору.

Запуск: python finrep_obyem_zapolnit_0910.py            пробний прогін («було → стане»)
        python finrep_obyem_zapolnit_0910.py --apply    бекап JSON поруч + запис (без реєстрації обміну)
        python finrep_obyem_zapolnit_0910.py --rollback=<бекап.json>
"""
import datetime
import json
import os
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
APPLY = "--apply" in sys.argv
ROLLBACK = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--rollback=")), None)
ТУТ = os.path.dirname(os.path.abspath(__file__))
c = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = c.String
рег = c.РегистрыСведений.А_ПараметрыДоговоровФинотчета
М, Д = "Металлоконструкции", "Дома"
# назва договору (точно) -> (вид, обсяг або None = не відомий, не чіпати)
ДОГОВОРИ = {
    "Договір підряду 06/04/26-МК Кривий РІГ": (М, 242.0),           # Дод. «Договірна ціна»: 242 т × 32 900
    "Договір підряду 07/07/26-МК Каменец Цемент": (М, 88.14),       # Дод. 1: 88,14 т × 34 400
    "Договір підряду 01/07/26-МК Кривий РІГ(елеват)": (М, None),    # договору в файлах немає — обсяг вносить користувач
    "Договір купівлі-продажу поставки товарів від 16.06": (Д, 13.0),  # IRC: 6 × 15 м + 7 × 30 м
    "РО139674 РАМКОВИЙ ДОГОВІР НА НАДАННЯ БУДІВЕЛЬНИХ": (Д, None),  # ООН Админ — обсяг вносить користувач
}


def знайти_договір(назва):
    q = c.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д "
              "ГДЕ Д.Наименование = &Н И НЕ Д.ПометкаУдаления И Д.Подразделение.Наименование ПОДОБНО \"М_ %\"")
    q.SetParameter("Н", назва)
    в = q.Execute().Выгрузить()
    if в.Количество() != 1:
        raise SystemExit(f"ПОМИЛКА: договір «{назва}» знайдено {в.Количество()} разів")
    return в.Получить(0).Ссылка


def набір(дог):
    нз = рег.СоздатьНаборЗаписей()
    нз.Отбор.Договор.Установить(дог)
    нз.Прочитать()
    if нз.Количество() != 1:
        raise SystemExit(f"ПОМИЛКА: у регістрі немає запису «{S(дог)}»")
    return нз


def записати(нз):
    нз.ДополнительныеСвойства.Вставить("ОтключитьМеханизмРегистрацииОбъектов", True)
    нз.Записать()


if ROLLBACK:
    for р in json.load(open(ROLLBACK, encoding="utf-8")):
        дог = c.Справочники.ДоговорыКонтрагентов.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", р["уид"]))
        нз = набір(дог)
        з = нз.Получить(0)
        з.ВидПродукции, з.ОбъемПоДоговору = р["вид"], р["обсяг"]
        записати(нз)
    print("ВІДКАТ ВИКОНАНО")
    sys.exit(0)

бекап, дії = [], []
for назва, (вид, обсяг) in ДОГОВОРИ.items():
    дог = знайти_договір(назва)
    нз = набір(дог)
    з = нз.Получить(0)
    було = (S(з.ВидПродукции), float(з.ОбъемПоДоговору))
    стане = (вид, було[1] if обсяг is None else обсяг)
    if було == стане:
        print(f"  {назва}: без змін {було}")
        continue
    print(f"  {назва}: {було} -> {стане}")
    бекап.append({"уид": S(дог.УникальныйИдентификатор()), "назва": назва, "вид": було[0], "обсяг": було[1]})
    з.ВидПродукции, з.ОбъемПоДоговору = стане
    дії.append(lambda н=нз: записати(н))

if APPLY and дії:
    шлях = os.path.join(ТУТ, f"finrep_obyem_backup_{datetime.datetime.now():%Y%m%d_%H%M}.json")
    json.dump(бекап, open(шлях, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("БЕКАП:", шлях)
    for дія in дії:
        дія()
print(("ЗАПИСАНО" if APPLY else "ПРОБНИЙ ПРОГІН") + f", змін: {len(дії)}")
