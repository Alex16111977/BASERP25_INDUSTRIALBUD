"""
Тесты запросов для v3 (переводы между своими счетами):
Q7: ERP обороты Фазы 2 + ХозОперация + А_Списание пары (через ВЫРАЗИТЬ)
Q8: BuhBud пер-счётный поток документа через ДвиженияССубконто (Дт(X)-Кт(X))
Проверка на живом примере 1432 / счёт-приёмник ТАС_Виробн.
"""
import sys
from datetime import datetime

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

NACH = datetime(2026, 1, 30, 0, 0, 0)
KON = datetime(2026, 1, 30, 23, 59, 59)

FAILS = 0


def run(label, fn):
    global FAILS
    try:
        msg = fn()
        print(f"{label} OK{(', ' + msg) if msg else ''}")
    except Exception as e:
        FAILS += 1
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"{label} FAIL: {e.excepinfo[2]}")
        else:
            print(f"{label} FAIL: {e}")


# Счёт-приёмник ТАС_Виробн (IBAN из скриншота)
IBAN_PRIEMNIK = "UA663395002600601537072000002"


def naiti_schet_erp(iban):
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 1 БСО.Ссылка КАК Ссылка
    ИЗ Справочник.БанковскиеСчетаОрганизаций КАК БСО
    ГДЕ БСО.НомерСчета = &НомерСчета
    """
    q.SetParameter("НомерСчета", iban)
    r = q.Execute().Выгрузить()
    assert r.Количество() == 1
    return r.Получить(0).Ссылка


# --- Q7: обороты ERP по счёту-приёмнику + ХозОперация + А_Списание пары ---
PARA_UUID = None
POSTUP_PRIHOD = None


def q7():
    global PARA_UUID, POSTUP_PRIHOD
    schet = naiti_schet_erp(IBAN_PRIEMNIK)
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
    	Об.Регистратор КАК Регистратор,
    	ПРЕДСТАВЛЕНИЕ(Об.Регистратор) КАК РегистраторПредст,
    	Об.СуммаПриход КАК Приход,
    	Об.СуммаРасход КАК Расход,
    	ВЫРАЗИТЬ(Об.Регистратор КАК Документ.ПоступлениеБезналичныхДенежныхСредств).ХозяйственнаяОперация КАК ХозОперацияПоступления,
    	ВЫРАЗИТЬ(Об.Регистратор КАК Документ.ПоступлениеБезналичныхДенежныхСредств).А_СписаниеБезналичныхДенежныхСредств КАК ПарноеСписание,
    	ВЫРАЗИТЬ(Об.Регистратор КАК Документ.СписаниеБезналичныхДенежныхСредств).ХозяйственнаяОперация КАК ХозОперацияСписания,
    	Соотв.УникальныйИдентификаторПриемника КАК UIDвBuhBud,
    	Соотв.ТипПриемника КАК ТипПриемника,
    	Соотв.ТипИсточника КАК ТипИсточника
    ИЗ
    	РегистрНакопления.ДенежныеСредстваБезналичные.Обороты(
    		&НачалоПериода, &КонецПериода, Авто,
    		БанковскийСчет = &БанковскийСчет) КАК Об
    	ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
    	ПО Об.Регистратор = Соотв.УникальныйИдентификаторИсточника
    		И (Соотв.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20)
    """
    q.SetParameter("НачалоПериода", NACH)
    q.SetParameter("КонецПериода", KON)
    q.SetParameter("БанковскийСчет", schet)
    r = q.Execute().Выгрузить()
    n_pair = 0
    for i in range(r.Количество()):
        s = r.Получить(i)
        if erp.ЗначениеЗаполнено(s.ПарноеСписание):
            n_pair += 1
            if "008305" in str(erp.String(s.Регистратор)):
                PARA_UUID = str(erp.String(s.ПарноеСписание.УникальныйИдентификатор())).strip().upper()
                POSTUP_PRIHOD = float(s.Приход)
    assert PARA_UUID is not None, "пара для 00DL-008305 не найдена в выборке"
    return f"рядків={r.Количество()}, з парою={n_pair}, пара UUID={PARA_UUID}, приход={POSTUP_PRIHOD}"


# --- Q8: BuhBud пер-счётный поток документа через ДвиженияССубконто ---
def q8():
    assert PARA_UUID is not None
    # BuhBud-счёт по IBAN
    qb0 = buh.NewObject("Запрос")
    qb0.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка
    ИЗ Справочник.БанковскиеСчета
    ГДЕ НомерСчета = &НомерСчета
    	И Наименование <> ""
    	И Наименование НЕ ПОДОБНО "%$$$%"
    УПОРЯДОЧИТЬ ПО Наименование
    """
    qb0.SetParameter("НомерСчета", IBAN_PRIEMNIK)
    rb0 = qb0.Execute().Выгрузить()
    assert rb0.Количество() == 1, "BuhBud счёт не найден по IBAN"
    bank_x = rb0.Получить(0).Ссылка

    reg = buh.Документы.СписаниеСРасчетногоСчета.ПолучитьСсылку(
        buh.NewObject("УникальныйИдентификатор", PARA_UUID))

    qb = buh.NewObject("Запрос")
    qb.Text = """
    ВЫБРАТЬ
    	СУММА(Т.Приход) - СУММА(Т.Расход) КАК Сумма
    ИЗ
    	(ВЫБРАТЬ Д.Сумма КАК Приход, 0 КАК Расход
    	ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(, , Регистратор = &Регистратор, , ) КАК Д
    	ГДЕ Д.СчетДт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))
    		И Д.СубконтоДт1 = &БанкРахунок

    	ОБЪЕДИНИТЬ ВСЕ

    	ВЫБРАТЬ 0, Д.Сумма
    	ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(, , Регистратор = &Регистратор, , ) КАК Д
    	ГДЕ Д.СчетКт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))
    		И Д.СубконтоКт1 = &БанкРахунок) КАК Т
    """
    qb.SetParameter("Регистратор", reg)
    qb.SetParameter("БанкРахунок", bank_x)
    rb = qb.Execute().Выгрузить()
    summa = float(rb.Получить(0).Сумма or 0)
    assert abs(summa - 2426200.50) < 0.01, f"поток по приёмнику = {summa}, ожидалось 2426200.50"
    assert abs(summa - POSTUP_PRIHOD) < 0.01, f"BuhBud {summa} != ERP приход {POSTUP_PRIHOD}"
    return f"поток Дт(X)-Кт(X) = {summa} == приход ERP-Поступления"


run("Q7", q7)
run("Q8", q8)
