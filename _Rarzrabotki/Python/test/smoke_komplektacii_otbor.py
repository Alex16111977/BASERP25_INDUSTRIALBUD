# -*- coding: utf-8 -*-
"""COM-smoke доработки СозданиеКомплектацийБух (Фаза 2 — відбір+підсумки).
Перевіряє: (1) перебудована .epf вантажиться і РассчитатьАнализ працює (регресія);
(2) логіка ПрименитьОтборИИтоги (Σ по відбору) на еталоні «шайба» = контроль 756/254/502."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

обр = buh.ВнешниеОбработки.Создать(EPF, False)
print("OK  обробка завантажена:", обр.Метаданные().Имя)

обр.Период = pywintypes.Time(datetime.datetime(2026, 4, 7, 12, 0, 0))
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000003")

qS = buh.NewObject("Запрос")
qS.Текст = ('ВЫБРАТЬ Склады.Ссылка КАК С ИЗ Справочник.Склады КАК Склады '
            'ГДЕ Склады.Наименование ПОДОБНО "%ПРО%ООН%виробнич%" '
            'ИЛИ Склады.Наименование ПОДОБНО "%ПРО%ООН%відвантаж%"')
tS = qS.Выполнить().Выгрузить()
for i in range(tS.Количество()):
    обр.СкладыОстатков.Добавить().Склад = tS.Получить(i).С

обр.РассчитатьАнализ()
тч = обр.ТабличнаяЧастьОстатков
print(f"OK  рядків аналізу: {тч.Количество()}")

# --- глобальні підсумки (регресія) ---
g_ост = g_вн = g_пн = 0.0
for i in range(тч.Количество()):
    s = тч.Получить(i)
    g_ост += s.Остаток; g_вн += s.ВНорме; g_пн += s.ПонадНорму
print(f"    GLOBAL  Залишок={round(g_ост,2)}  В нормі={round(g_вн,2)}  Понад={round(g_пн,2)}  баланс={round(g_вн+g_пн-g_ост,4)}")
assert g_ост > 0, f"немає залишків (Остаток={g_ост})"  # абс. число дрейфує з живими даними (FINDINGS); інваріант = баланс нижче
assert abs((g_вн+g_пн) - g_ост) < 0.01, "глобальний баланс не сходиться"

# --- ПрименитьОтборИИтоги: Σ по відбору (1:1 логіка BSL: відбір + текстовий пошук) ---
def итоги_по_отбору(отбор_эталон=None, отбор_склад=None, только_понад=False, пошук=""):
    о = вн = пн = 0.0
    n = 0
    текст = (пошук or "").strip().upper()
    for i in range(тч.Количество()):
        s = тч.Получить(i)
        if отбор_склад is not None and not s.Склад == отбор_склад:
            continue
        if отбор_эталон is not None and not s.ОбщееНазвание == отбор_эталон:
            continue
        if только_понад and not (s.ПонадНорму > 0):
            continue
        if текст:
            # buh.String(ref) == BSL Строка(ref) == представлення (Наименование); англ. String надійний через COM-проксі
            цель = (buh.String(s.Номенклатура) + " " + buh.String(s.ОбщееНазвание) + " " + buh.String(s.Склад)).upper()
            if текст not in цель:
                continue
        о += s.Остаток; вн += s.ВНорме; пн += s.ПонадНорму; n += 1
    return round(о, 2), round(вн, 2), round(пн, 2), n

# знайти еталон(и) з «шайб» у назві серед рядків аналізу
эталоны = {}
for i in range(тч.Количество()):
    s = тч.Получить(i)
    эт = s.ОбщееНазвание
    if buh.ЗначениеЗаполнено(эт):
        эталоны[str(эт.Наименование)] = эт
шайбы = {n: r for n, r in эталоны.items() if "шайб" in n.lower()}
print(f"OK  еталонів «шайба» знайдено: {len(шайбы)} -> {list(шайбы.keys())}")

for имя, реф in шайбы.items():
    о, вн, пн, n = итоги_по_отбору(отбор_эталон=реф)
    print(f"    ВІДБІР еталон «{имя}»: рядків={n} Залишок={о}  В нормі={вн}  Понад={пн}  баланс={round(вн+пн-о,4)}")
    assert abs((вн + пн) - о) < 0.01, "баланс відбору не сходиться"

# --- НОВЕ: текстовий ПОШУК (як у формі поле «Пошук») ---
for q in ("гофр", "шайб"):
    о, вн, пн, n = итоги_по_отбору(пошук=q)
    print(f"    ПОШУК «{q}»: рядків={n} Залишок={о}  В нормі={вн}  Понад={пн}  баланс={round(вн+пн-о,4)}")
    assert abs((вн + пн) - о) < 0.01, f"баланс пошуку «{q}» не сходиться"
о, вн, пн, n = итоги_по_отбору(пошук="гофр", только_понад=True)
print(f"    ПОШУК «гофр» + Тільки понад: рядків={n} Залишок={о}  В нормі={вн}  Понад={пн}")

print("\nSMOKE Фаза2: PASS")
