e = tВ.Получить(0)
for n in col_names:
    val = getattr(e, n)
    sval = conn.String(val)
    # Печатать только значимые поля или со 'списан', 'платеж', 'банк'
    if (val is not None and sval and len(sval) > 0 and sval != "0" and sval != "False"
        and ('писан' in n.lower() or 'латеж' in n.lower() or 'анк' in n.lower()
             or 'твет' in n.lower() or 'снован' in n.lower() or 'тат' in n.lower())):
        print(f"  {n} = {sval}")

