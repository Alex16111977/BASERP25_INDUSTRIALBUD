def run(name, text):
    q = erp.NewObject("Запрос")
    q.Text = text
    try:
        t = q.Execute().Выгрузить()
        print(f"[OK] {name}: строк={t.Количество()}")
        return t
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print(f"[FAIL] {name}: {msg}")
        return None

