# -*- coding: utf-8 -*-
"""Приёмка правил A/B на ЖИВЫХ встроенных обработках BaseERP (декабрь 2025).

Проверяет Definition of Done промта PROMPT_pravila_isklyucheniya_A_B.md:
  DoD#1  Взаиморасчёты: РКО/банковские Воронцова (000Ц-000102/282, 000Ц-000007/008,
         N0000053085/86/87) БОЛЬШЕ не «Немає в BuhBud» — «ОК: …», без действия.
  DoD#2  Безнал: банковский с А_ВведенВЕРП=Истина без пары → «ОК: …», ЕстьРасхождение=Ложь
         (:436 хармонизирована — точное «= ОК» заменено на префикс).
  DoD#3  Документы С ПАРОЙ («різниця в рухах») — статус НЕ изменился (правила A/B туда не лезут).
  DoD#4  Ни одно движение в базах не изменено — прогон только читает (СравнитьОстатки /
         АнализироватьДокументы); мутирующий ВыполнитьСинхронизацию НЕ вызывается.

Полностью read-only. Ничего не проводит/распроводит.
"""
import datetime
import sys
import win32com.client as w

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

v8 = w.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

НАЧ = datetime.datetime(2025, 12, 1)
КОН = datetime.datetime(2025, 12, 31)
ЦЕЛЕВЫЕ = ["000Ц-000102", "000Ц-000282", "000Ц-000007", "000Ц-000008",
           "N0000053085", "N0000053086", "N0000053087"]
ОК_A = "ОК: тільки в ЕРП (А_ВведенВЕРП)"
ОК_B = "ОК: РКО/ПКО з Казни"
провалы = []


def строки(обр):
    """Снимок ТаблицаДокументов -> список dict."""
    рез = []
    т = обр.ТаблицаДокументов
    for j in range(т.Количество()):
        с = т.Получить(j)
        номер = ""
        try:
            номер = str(с.ДокументЕРП.Номер)
        except Exception:
            pass
        рез.append({
            "номер": номер,
            "докЕРП": erp.String(с.ДокументЕРП),
            "статус": str(с.Статус),
            "действие": str(с.Действие),
            "синхр": bool(с.Синхронизировать),
            "естьрасх": bool(с.ЕстьРасхождение),
            "естьсоотв": bool(с.ЕстьСоответствие),
        })
    return рез


def prove(cond, msg):
    print(("   [PASS] " if cond else "   [FAIL] ") + msg)
    if not cond:
        провалы.append(msg)


# ============================ КОНТУР ВЗАИМОРАСЧЁТЫ ============================
print("=" * 70)
print("КОНТУР ВЗАИМОРАСЧЁТЫ — декабрь 2025")
print("=" * 70)
взр = erp.Обработки.А_СинхронизироватьВзаиморасчеты.Создать()
взр.НачалоПериода = НАЧ
взр.ОкончаниеПериода = КОН
print("Фаза 1:", взр.СравнитьОстатки())
взр.АнализироватьДокументы()   # все расходящиеся контрагенты
rows_взр = строки(взр)
print(f"Строк документов (все контрагенты): {len(rows_взр)}")

нет_в_buh = [r for r in rows_взр if r["статус"].startswith("Немає в BuhBud")]
ок_прав = [r for r in rows_взр if r["статус"].startswith("ОК:")]
пары = [r for r in rows_взр if r["естьсоотв"]]
разн_в_рухах = [r for r in rows_взр if r["статус"] == "Проведений, різниця в рухах"]
print(f"   «Немає в BuhBud»={len(нет_в_buh)}  «ОК:»={len(ок_прав)}  "
      f"с парой={len(пары)}  «різниця в рухах»={len(разн_в_рухах)}")

# DoD#1 — целевые документы Воронцова стали «ОК:», без действия
целевые_строки = [r for r in rows_взр if any(ц in r["номер"] for ц in ЦЕЛЕВЫЕ)]
prove(len(целевые_строки) >= 7, f"DoD#1: целевые документы найдены в прогоне ({len(целевые_строки)} шт)")
for r in целевые_строки:
    ок = (r["статус"].startswith("ОК:") and r["действие"] == "" and not r["синхр"]
          and not r["естьрасх"])
    prove(ок, f"DoD#1: {r['докЕРП']} -> Статус='{r['статус']}' Дія='{r['действие']}' "
              f"Синхр={r['синхр']} ЕстьРасх={r['естьрасх']}")

# DoD#1 — среди целевых есть и правило A, и правило B
prove(any(r["статус"] == ОК_A for r in целевые_строки), "DoD#1: сработало правило A (флаг А_ВведенВЕРП)")
prove(any(r["статус"] == ОК_B for r in целевые_строки), "DoD#1: сработало правило B (РКО/ПКО з Казни)")

# DoD#3 — правила A/B НИКОГДА не срабатывают на документах С ПАРОЙ
пары_с_окправил = [r for r in пары if r["статус"] in (ОК_A, ОК_B)]
prove(len(пары_с_окправил) == 0,
      f"DoD#3: документы С ПАРОЙ не получили статусы правил A/B ({len(пары_с_окправил)} нарушений)")
# DoD#3 — «різниця в рухах» сохраняют действие «Перепровести в ЕРП» и синхр
if разн_в_рухах:
    все_ок = all(r["действие"] == "Перепровести в ЕРП" and r["синхр"] for r in разн_в_рухах)
    prove(все_ок, f"DoD#3: «різниця в рухах» без изменений (Дія='Перепровести в ЕРП', {len(разн_в_рухах)} шт)")
else:
    print("   [INFO] DoD#3: строк «Проведений, різниця в рухах» в этом прогоне нет "
          "(инвариант структурный — правила A/B только в ветке «нет соответствия»)")


# ============================ КОНТУР ДЕНЬГИ-БЕЗНАЛ ============================
print("\n" + "=" * 70)
print("КОНТУР ДЕНЬГИ-БЕЗНАЛ — декабрь 2025")
print("=" * 70)
дг = erp.Обработки.А_СинхронизироватьДеньги.Создать()
дг.НачалоПериода = НАЧ
дг.ОкончаниеПериода = КОН
print("Фаза 1:", дг.СравнитьОстатки())
дг.АнализироватьДокументы()
rows_дг = строки(дг)
print(f"Строк документов (все счета): {len(rows_дг)}")

дг_A = [r for r in rows_дг if r["статус"] == ОК_A]
дг_пары = [r for r in rows_дг if r["естьсоотв"]]
дг_разн = [r for r in rows_дг if r["статус"] == "Проведений, різниця в рухах"]
print(f"   «ОК: тільки в ЕРП»={len(дг_A)}  с парой={len(дг_пары)}  «різниця в рухах»={len(дг_разн)}")

# DoD#2 — есть банковский с флагом без пары -> «ОК:», ЕстьРасхождение=Ложь
prove(len(дг_A) >= 1, f"DoD#2: банковские с А_ВведенВЕРП=Истина без пары получили «ОК: …» ({len(дг_A)} шт)")
for r in дг_A[:8]:
    ок = (not r["естьрасх"] and r["действие"] == "" and not r["синхр"] and not r["естьсоотв"])
    prove(ок, f"DoD#2: {r['докЕРП']} -> ЕстьРасх={r['естьрасх']} Дія='{r['действие']}' "
              f"Синхр={r['синхр']} ЕстьСоотв={r['естьсоотв']}")

# DoD#3 (безнал) — правило A не трогает документы с парой
дг_пары_окA = [r for r in дг_пары if r["статус"] == ОК_A]
prove(len(дг_пары_окA) == 0,
      f"DoD#3(безнал): документы С ПАРОЙ не получили статус правила A ({len(дг_пары_окA)} нарушений)")
if дг_разн:
    все_ок = all(r["синхр"] for r in дг_разн)
    prove(все_ок, f"DoD#3(безнал): «різниця в рухах» без изменений ({len(дг_разн)} шт)")


# ============================ ИТОГ ============================
print("\n" + "=" * 70)
if провалы:
    print(f"РЕЗУЛЬТАТ: FAIL — {len(провалы)} нарушений")
    for m in провалы:
        print("   - " + m)
    sys.exit(1)
else:
    print("РЕЗУЛЬТАТ: PASS — все DoD (#1 Взаиморасчёты, #2 Безнал, #3 пары) подтверждены.")
    print("DoD#4: движения не изменялись — прогон только читал (ВыполнитьСинхронизацию не вызывался).")
