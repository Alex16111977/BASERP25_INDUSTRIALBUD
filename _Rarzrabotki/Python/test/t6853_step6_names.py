import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

qs = buh.NewObject("Запрос")
qs.Text = """ВЫБРАТЬ Сч.Ссылка КАК Ссылка ИЗ ПланСчетов.Хозрасчетный КАК Сч ГДЕ Сч.Код = "6853" """
счет = qs.Execute().Выгрузить().Получить(0).Ссылка

# Остатки на 30.06.2025 с именами получателей
q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Ост.Организация.Наименование КАК Орг,
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    ПРЕДСТАВЛЕНИЕ(Ост.Субконто1) КАК ПолучательПредст,
    Ост.Субконто1 КАК Получатель,
    Ост.СуммаОстатокКт КАК Кт
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Дата, Счет = &Счет) КАК Ост
"""
q.SetParameter("Дата", datetime.datetime(2025,6,30,23,59,59))
q.SetParameter("Счет", счет)
r = q.Execute().Выгрузить()
print("Остатки 6853 на 30.06.2025 (примеры взыскателей):")
for i in range(r.Количество()):
    s=r.Получить(i)
    tname = s.Получатель.Метаданные().Имя if buh.ЗначениеЗаполнено(s.Получатель) else "Пусто"
    print(f"  Орг={s.Орг} ЕДРПОУ={s.ЕДРПОУ} | Получатель[{tname}]={s.ПолучательПредст} | Кт={s.Кт}")

# Проверим, бывает ли субконто типа Физлица или Организации в движениях 6853 за всё время
print("\nТипы субконто1 во ВСЕХ движениях 6853:")
q2 = buh.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    ВЫБОР КОГДА Дв.СчетКт = &Счет ТОГДА Дв.СубконтоКт1 ИНАЧЕ Дв.СубконтоДт1 КОНЕЦ КАК Суб
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Дв
ГДЕ (Дв.СчетДт = &Счет ИЛИ Дв.СчетКт = &Счет)
"""
q2.SetParameter("Счет", счет)
r2 = q2.Execute().Выгрузить()
types = {}
samples = {}
for i in range(r2.Количество()):
    s = r2.Получить(i)
    if buh.ЗначениеЗаполнено(s.Суб):
        tn = s.Суб.Метаданные().Имя
        types[tn] = types.get(tn,0)+1
        if tn not in samples:
            samples[tn] = str(s.Суб)
    else:
        types["Пусто"] = types.get("Пусто",0)+1
print("  типы:", types)
print("  примеры:", samples)
