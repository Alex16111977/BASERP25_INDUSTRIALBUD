# -*- coding: utf-8 -*-
"""Pre-test для нової Свод_ОплатаТруда — розшифровка ОТ через А_ВзСС по ФизическоеЛицо.

Стратегія (узгоджена з поточним кодом Свод_ОплатаТруда):
  - А_ВзСС читаємо ПРЯМОЮ ТАБЛИЦЕЮ (НЕ ВТ.ОстаткиИОбороты!) щоб мати симетричний
    фільтр Период з ПАП. Платформа пише ПАП(ОТ).Период з зсувом ОЗФУ на +1 місяць,
    а А_ВзСС.Период = НачалоМесяца(Дата); ВТ.ОстаткиИОбороты використовує А_ВзСС.Период
    і повертає невідповідні цифри.
  - Інверсія знаку: А_ВзСС.signed = -ПАП.signed. Множимо на -1 у втВзСС.

Asserts per Орг,Подр:
  1) |Σ_наш_інверс_КО + Σ_ПАП_КО| ≤ 1 ₽
  2) 100% рядків з ФЛ ≠ Пустая
  3) 0 дублів ключа (Орг,Подр,ФЛ)
"""
import sys, io
from datetime import datetime
from collections import defaultdict
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

# УВАГА: Python COM datetime має tz-зсув (UTC→локальний). Тому замість
# передачі datetime параметром використовуємо ДАТАВРЕМЯ() прямо в 1С-запиті.
НМ_str = "ДАТАВРЕМЯ(2026, 1, 1, 0, 0, 0)"
КМ_str = "ДАТАВРЕМЯ(2026, 1, 31, 23, 59, 59)"

# 1) Запит — кандидат для BSL (симетричний з поточним Свод_ОплатаТруда)
print("[TEST] Запит-кандидат для BSL Свод_ОплатаТруда")
qVzSS = conn.NewObject("Запрос")
qVzSS.Текст = f"""
ВЫБРАТЬ
    ВзСС.Организация КАК Организация,
    ЕСТЬNULL(ВзСС.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подразделение,
    ВзСС.ФизическоеЛицо КАК ФизическоеЛицо,
    СУММА(ВЫБОР КОГДА ВзСС.Период < {НМ_str}
            ТОГДА ВЫБОР КОГДА ВзСС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                    ТОГДА -ВзСС.СуммаВзаиморасчетов ИНАЧЕ ВзСС.СуммаВзаиморасчетов КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК НО,
    СУММА(ВЫБОР КОГДА ВзСС.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА -ВзСС.СуммаВзаиморасчетов ИНАЧЕ ВзСС.СуммаВзаиморасчетов КОНЕЦ) КАК КО
ИЗ
    РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзСС
ГДЕ
    ВзСС.Организация = &Орг
    И ВзСС.Период <= {КМ_str}
СГРУППИРОВАТЬ ПО
    ВзСС.Организация,
    ЕСТЬNULL(ВзСС.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)),
    ВзСС.ФизическоеЛицо
"""
qVzSS.УстановитьПараметр("Орг", ORG)
res_vzss = qVzSS.Выполнить().Выгрузить()
print(f"  Рядків деталей (Орг,Подр,ФЛ): {res_vzss.Количество()}")

# Σ-агрегати
Σ_наш_НО = 0; Σ_наш_КО = 0
fl_total = 0; fl_empty = 0
keys = defaultdict(int)
for i in range(res_vzss.Количество()):
    rec = res_vzss.Получить(i)
    Σ_наш_НО += float(rec.НО or 0); Σ_наш_КО += float(rec.КО or 0)
    fl_total += 1
    if not conn.ЗначениеЗаполнено(rec.ФизическоеЛицо):
        fl_empty += 1
    keys[(S(rec.Организация), S(rec.Подразделение), S(rec.ФизическоеЛицо))] += 1
дублі = sum(1 for v in keys.values() if v > 1)
fl_pct = 100.0 * (fl_total - fl_empty) / max(1, fl_total)
print(f"  Σ_наш_НО (інверс): {Σ_наш_НО:>+14,.2f}")
print(f"  Σ_наш_КО (інверс): {Σ_наш_КО:>+14,.2f}")
print(f"  ФЛ заповнено: {fl_total - fl_empty}/{fl_total} ({fl_pct:.1f}%)")
print(f"  Дублі ключа (Орг,Подр,ФЛ): {дублі}")

# 2) ПАП(ОТ) за той самий період (як у поточному Свод_ОплатаТруда)
print("\n[PAP] Σ ПАП(ОТ, Источник=Пуст) за той самий період (signed)")
qPap = conn.NewObject("Запрос")
qPap.Текст = f"""
ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА Т.Период < {НМ_str}
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                    ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК НО,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Период <= {КМ_str}
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Статья = &ОТ
"""
qPap.УстановитьПараметр("Орг", ORG); qPap.УстановитьПараметр("ОТ", ОТ)
rP = qPap.Выполнить().Выбрать(); rP.Следующий()
ПАП_НО = float(rP.НО or 0); ПАП_КО = float(rP.КО or 0)
print(f"  ПАП_НО signed: {ПАП_НО:>+14,.2f}")
print(f"  ПАП_КО signed: {ПАП_КО:>+14,.2f}")

# 3) Інваріант
Δ_НО = abs(Σ_наш_НО - ПАП_НО)
Δ_КО = abs(Σ_наш_КО - ПАП_КО)
print(f"\n[ІНВАРИАНТ]")
print(f"  Σ_наш_НО ({Σ_наш_НО:>+14,.2f}) vs ПАП_НО ({ПАП_НО:>+14,.2f}) → |Δ|={Δ_НО:.2f}")
print(f"  Σ_наш_КО ({Σ_наш_КО:>+14,.2f}) vs ПАП_КО ({ПАП_КО:>+14,.2f}) → |Δ|={Δ_КО:.2f}")

# 4) Per (Орг,Подр) Δ — для діагностики
print("\n[Per Орг,Подр] Δ розкладка (зрізи з |Δ КО| > 1 ₽):")
qP2 = conn.NewObject("Запрос")
qP2.Текст = f"""
ВЫБРАТЬ
    Т.Организация КАК Орг,
    ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Период <= {КМ_str}
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Статья = &ОТ
СГРУППИРОВАТЬ ПО Т.Организация, ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))
"""
qP2.УстановитьПараметр("Орг", ORG); qP2.УстановитьПараметр("ОТ", ОТ)
res_pap = qP2.Выполнить().Выгрузить()
pap_по_подр = {}
for i in range(res_pap.Количество()):
    r = res_pap.Получить(i)
    pap_по_подр[(S(r.Орг), S(r.Подр))] = float(r.КО or 0)

# Згрупувати наш per (Орг,Подр)
наш_по_подр = defaultdict(float)
for i in range(res_vzss.Количество()):
    rec = res_vzss.Получить(i)
    наш_по_подр[(S(rec.Организация), S(rec.Подразделение))] += float(rec.КО or 0)

розб = 0
for k, наш_КО in наш_по_подр.items():
    пап_КО = pap_по_подр.get(k, 0)
    Δ = abs(наш_КО - пап_КО)
    if Δ > TOL_RUB:
        розб += 1
        print(f"  Подр={k[1]:30} наш={наш_КО:>+12,.2f} ПАП={пап_КО:>+12,.2f} |Δ|={Δ:>10,.2f}")
print(f"  Усього (Орг,Подр): {len(наш_по_подр)}; розбіжностей: {розб}")

# 5) Verdict
print(f"\n[VERDICT]")
ok = Δ_НО <= TOL_RUB and Δ_КО <= TOL_RUB and розб == 0 and fl_pct >= 99.0 and дублі == 0
print(f"  {'[OK] PASS' if ok else '[FAIL]'} — інваріант {'сходиться' if Δ_КО <= TOL_RUB else 'НЕ сходиться'}")
sys.exit(0 if ok else 1)
