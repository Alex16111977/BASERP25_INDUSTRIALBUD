# -*- coding: utf-8 -*-
"""Разведка: договоры класса А сверки (BuhBud) — заполнено ли Направление.

ТОЛЬКО ЧТЕНИЕ. Ищет договоры по числовой сигнатуре в номере/наименовании,
показывает всех кандидатов с владельцем/подразделением/направлением + UUID.
Отдельно находит элемент справочника Направления «Производство».
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# --- элемент «Производство» справочника Направления ---
print("=== Справочник Направления ===")
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Н.Ссылка КАК С, Н.Наименование КАК Имя, Н.ПометкаУдаления КАК ПУ
ИЗ Справочник.Направления КАК Н
УПОРЯДОЧИТЬ ПО Имя"""
т = q.Execute().Выгрузить()
for i in range(т.Количество()):
    s = т.Получить(i)
    uид = str(buh.String(s.С.УникальныйИдентификатор()))
    метка = " [ПОМЕЧЕН НА УДАЛЕНИЕ]" if s.ПУ else ""
    print(f"  {uид}  «{s.Имя}»{метка}")

# --- договоры по сигнатурам ---
ИСКОМЫЕ = [
    ("1203/2026",         "МХП|ОРІЛЬ|ОРИЛЬ"),
    ("28/10/24",          "Кернел|Кухня"),
    ("20/01/25",          "Чорноморськ|Черноморск|Ойл"),
    ("20/01/26",          "Чорноморськ|Черноморск"),
    ("24/09/25",          "Глобино|Форшахта"),
    ("Contract 10499944", "ПРООН|ДСНС|Черкаси"),
]

print("\n=== Кандидаты-договоры ===")
q2 = buh.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    Д.Ссылка КАК С,
    Д.Наименование КАК Имя,
    Д.Номер КАК Ном,
    Д.Дата КАК Дат,
    ЕСТЬNULL(Д.Владелец.Наименование, "") КАК Влад,
    ЕСТЬNULL(Д.Подразделение.Наименование, "") КАК Подр,
    ЕСТЬNULL(Д.Направление.Наименование, "") КАК Напр,
    Д.ПометкаУдаления КАК ПУ
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ НЕ Д.ЭтоГруппа
  И (Д.Номер ПОДОБНО &Ш
      ИЛИ Д.Наименование ПОДОБНО &Ш)
УПОРЯДОЧИТЬ ПО Дат"""

for сигнатура, подсказка in ИСКОМЫЕ:
    print(f"\n--- поиск: «{сигнатура}» (подсказка: {подсказка}) ---")
    q2.УстановитьПараметр("Ш", "%" + сигнатура + "%")
    т2 = q2.Execute().Выгрузить()
    if т2.Количество() == 0:
        print("  НИЧЕГО НЕ НАЙДЕНО")
        continue
    for i in range(т2.Количество()):
        s = т2.Получить(i)
        uид = str(buh.String(s.С.УникальныйИдентификатор()))
        имя = " ".join(str(s.Имя).split())
        напр = str(s.Напр) if str(s.Напр).strip() else "<ПУСТО>"
        метка = " [ПОМЕЧЕН]" if s.ПУ else ""
        # дату печатаем строкой средствами 1С, чтобы не терять сутки в COM
        дата = str(buh.String(s.Дат))
        print(f"  UUID={uид}{метка}")
        print(f"    Наименование: {имя}")
        print(f"    Номер: {s.Ном} | Дата: {дата}")
        print(f"    Владелец: {s.Влад}")
        print(f"    Подразделение: [{s.Подр}]")
        print(f"    Направление: {напр}")
