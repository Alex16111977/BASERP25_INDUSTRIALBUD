# -*- coding: utf-8 -*-
"""Discovery для классификатора видов контрагентов (внутригрупповая задолженность):
1) Все статьи ПВХ.СтатьиАктивовПассивов (имя + АктивПассив + группа)
2) Состав папки _КОРПОРАТИВНІ в Справочник.Партнеры (иерархия)
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

print("=" * 70)
print("1. СТАТЬИ ПВХ.СтатьиАктивовПассивов")
print("=" * 70)
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    СА.Наименование КАК Наименование,
    ПРЕДСТАВЛЕНИЕ(СА.АктивПассив) КАК АктПас,
    ЕСТЬNULL(СА.Родитель.Наименование, "") КАК Группа
ИЗ
    ПланВидовХарактеристик.СтатьиАктивовПассивов КАК СА
ГДЕ
    НЕ СА.ПометкаУдаления
УПОРЯДОЧИТЬ ПО
    Группа, Наименование
"""
try:
    r = q.Execute().Выгрузить()
    print(f"OK, рядків={r.Количество()}")
    for i in range(r.Количество()):
        row = r.Получить(i)
        grp = S(row.Группа)
        print(f"  [{grp}] {S(row.Наименование)} | {S(row.АктПас)}")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")

print()
print("=" * 70)
print("2. ПАРТНЕРЫ в иерархии _КОРПОРАТИВНІ")
print("=" * 70)
try:
    спр = erp.Справочники.Партнеры.НайтиПоНаименованию("_КОРПОРАТИВНІ")
    if not erp.ЗначениеЗаполнено(спр):
        print("Папка _КОРПОРАТИВНІ в Партнерах НЕ найдена")
    else:
        print(f"Корень найден: {S(спр)}")
        q3 = erp.NewObject("Запрос")
        q3.Text = """
        ВЫБРАТЬ
            П.Наименование КАК Наименование,
            ЕСТЬNULL(П.Родитель.Наименование, "") КАК Папка,
            КОЛИЧЕСТВО(РАЗЛИЧНЫЕ К.Ссылка) КАК ЧислоКонтрагентов
        ИЗ
            Справочник.Партнеры КАК П
            ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Контрагенты КАК К
            ПО К.Владелец = П.Ссылка И НЕ К.ПометкаУдаления
        ГДЕ
            П.Ссылка В ИЕРАРХИИ (&Корень)
            И НЕ П.ПометкаУдаления
        СГРУППИРОВАТЬ ПО
            П.Наименование, ЕСТЬNULL(П.Родитель.Наименование, "")
        УПОРЯДОЧИТЬ ПО
            Папка, Наименование
        """
        q3.SetParameter("Корень", спр)
        r3 = q3.Execute().Выгрузить()
        print(f"OK, рядків={r3.Количество()}")
        for i in range(r3.Количество()):
            row = r3.Получить(i)
            print(f"  [{S(row.Папка)}] {S(row.Наименование)} (контрагентов: {row.ЧислоКонтрагентов})")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")

print()
print("=" * 70)
print("3. Сколько ДОГОВОРОВ у контрагентов корпоративной папки")
print("=" * 70)
q4 = erp.NewObject("Запрос")
q4.Text = """
ВЫБРАТЬ
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Ссылка) КАК ЧислоДоговоров,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Владелец) КАК ЧислоКонтрагентов
ИЗ
    Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
    Д.Владелец.Владелец В ИЕРАРХИИ (&Корень)
    И НЕ Д.ПометкаУдаления
"""
try:
    спр = erp.Справочники.Партнеры.НайтиПоНаименованию("_КОРПОРАТИВНІ")
    q4.SetParameter("Корень", спр)
    r4 = q4.Execute().Выгрузить()
    row = r4.Получить(0)
    print(f"Договоров: {row.ЧислоДоговоров}, контрагентов с договорами: {row.ЧислоКонтрагентов}")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")
