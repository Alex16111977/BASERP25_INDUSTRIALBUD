# Пре-флайт: резолв всех членов глобальных объектов, используемых в модуле формы обработки.
# Ловит рантайм «Поле объекта не обнаружено» (напр. WebЦвета.СинийСтальной) ДО открытия в UI.
import sys
sys.path.insert(0, r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test')
import _common_neizv as c

erp = c.connect()


def check(name, fn):
    # сам доступ к члену = тест: несуществующий член кинет «Поле объекта не обнаружено»
    try:
        fn()
        print(f"  OK   {name}")
        return True
    except Exception as e:
        info = getattr(e, 'excepinfo', None)
        print(f"  FAIL {name}: {info[2] if info else e}")
        return False


# Само-проверка метода: несуществующий член ДОЛЖЕН падать
print("=== Само-проверка метода (СинийСтальной должен FAIL) ===")
neg = check("WebЦвета.СинийСтальной (ожидаем FAIL)", lambda: erp.WebЦвета.СинийСтальной)
print("  метод ловит несуществующие члены:", "ДА" if not neg else "НЕТ — метод не работает!")

print("\n=== Резолв членов глобальных объектов (модуль формы) ===")
ok = True
ok &= check("WebЦвета.Серый", lambda: erp.WebЦвета.Серый)
ok &= check("WebЦвета.Красный", lambda: erp.WebЦвета.Красный)
ok &= check("WebЦвета.Синий", lambda: erp.WebЦвета.Синий)
ok &= check("ЦветаСтиля.ПоясняющийТекст", lambda: erp.ЦветаСтиля.ПоясняющийТекст)
ok &= check("ВидСравненияКомпоновкиДанных.НачинаетсяС", lambda: erp.ВидСравненияКомпоновкиДанных.НачинаетсяС)
ok &= check("ВидСравненияКомпоновкиДанных.Равно", lambda: erp.ВидСравненияКомпоновкиДанных.Равно)
ok &= check("Перечисления.ЮрФизЛицо.ФизЛицо", lambda: erp.Перечисления.ЮрФизЛицо.ФизЛицо)
ok &= check("Перечисления.ЮрФизЛицо.ИндивидуальныйПредприниматель", lambda: erp.Перечисления.ЮрФизЛицо.ИндивидуальныйПредприниматель)
ok &= check("Перечисления.КомпанияЧастноеЛицо.ЧастноеЛицо", lambda: erp.Перечисления.КомпанияЧастноеЛицо.ЧастноеЛицо)
ok &= check("Перечисления.КомпанияЧастноеЛицо.Компания", lambda: erp.Перечисления.КомпанияЧастноеЛицо.Компания)

print("\nИТОГ:", "ВСЁ OK" if ok else "ЕСТЬ НЕВАЛИДНЫЕ ССЫЛКИ")
sys.exit(0 if ok else 1)
