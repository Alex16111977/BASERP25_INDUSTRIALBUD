# Патерн: "Зарплата%" → Начисления, "Начисления%" → ФОТ, "Удержание%" → Налоги/удержания.
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
kazna = v8.Connect('Srvr="SQLSERVER";Ref="BuhKazn";Usr="cfo";Pwd="2442"')
S = kazna.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


def parse_num(s):
    return float(S(s).replace('\xa0', '').replace(' ', '').replace(',', '.') or "0")


НачПер = com_date(2025, 12, 1)
КонПер = com_date(2025, 12, 31, 23, 59, 59)

q = kazna.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    БДДС.Подразделение.Код КАК ПодразделениеКод,
    БДДС.Направление.Код КАК НаправлениеКод,
    БДДС.Сотрудник.ИНН КАК СотрудникИНН,
    БДДС.Сотрудник.Наименование КАК СотрудникФИО,
    БДДС.Сотрудник.Код КАК СотрудникКод,
    БДДС.Регистратор.Организация.ЕГРПОУ КАК ОрганизацияЕГРПОУ,
    БДДС.Регистратор КАК Регистратор,
    ВЫБОР
        КОГДА БДДС.Регистратор ССЫЛКА Документ.РаспределениеЗаработнойПлаты
            ТОГДА "А_РаспределениеЗаработнойПлаты"
        ИНАЧЕ "РаспределениеФ2"
    КОНЕЦ КАК ВидДокумента,
    СУММА(БДДС.Сумма) КАК Сумма,
    СУММА(ВЫБОР
        КОГДА БДДС.СтатьяДвиженияДенежныхСредств.Наименование ПОДОБНО "Зарплата%"
        ТОГДА БДДС.Сумма ИНАЧЕ 0
    КОНЕЦ) КАК СуммаНачисления,
    СУММА(ВЫБОР
        КОГДА БДДС.СтатьяДвиженияДенежныхСредств.Наименование ПОДОБНО "Начисления%"
        ТОГДА БДДС.Сумма ИНАЧЕ 0
    КОНЕЦ) КАК СуммаФОТ,
    СУММА(ВЫБОР
        КОГДА БДДС.СтатьяДвиженияДенежныхСредств.Наименование ПОДОБНО "Удержание%"
        ТОГДА БДДС.Сумма ИНАЧЕ 0
    КОНЕЦ) КАК СуммаНалогов,
    МАКСИМУМ(БДДС.СтатьяДвиженияДенежныхСредств.Код) КАК СтатьяКодMax
ИЗ РегистрНакопления.БДДС КАК БДДС
ГДЕ (
    (БДДС.Регистратор ССЫЛКА Документ.РаспределениеЗаработнойПлаты
        И БДДС.Регистратор.КассаДатаС >= &Н
        И БДДС.Регистратор.КассаДатаПо <= &К
        И БДДС.Регистратор.Организация.А_ПереносЕРП)
    ИЛИ
    (БДДС.Регистратор ССЫЛКА Документ.РаспределениеФ2
        И БДДС.Регистратор.КассаДатаС >= &Н
        И БДДС.Регистратор.КассаДатаПо <= &К)
)
СГРУППИРОВАТЬ ПО
    БДДС.Подразделение.Код,
    БДДС.Направление.Код,
    БДДС.Сотрудник.ИНН,
    БДДС.Сотрудник.Наименование,
    БДДС.Сотрудник.Код,
    БДДС.Регистратор.Организация.ЕГРПОУ,
    БДДС.Регистратор,
    ВЫБОР
        КОГДА БДДС.Регистратор ССЫЛКА Документ.РаспределениеЗаработнойПлаты
            ТОГДА "А_РаспределениеЗаработнойПлаты"
        ИНАЧЕ "РаспределениеФ2"
    КОНЕЦ
"""
q.SetParameter("Н", НачПер)
q.SetParameter("К", КонПер)

try:
    r = q.Execute().Выгрузить()
    print(f"Рядків: {r.Количество()}")

    total_s = 0.0
    total_n = 0.0
    total_f = 0.0
    total_u = 0.0
    rows_with_nach = 0
    rows_with_fot = 0
    rows_with_ud = 0
    rows_mismatch = 0

    for i in range(r.Количество()):
        row = r.Получить(i)
        s = parse_num(row.Сумма)
        n = parse_num(row.СуммаНачисления)
        f = parse_num(row.СуммаФОТ)
        u = parse_num(row.СуммаНалогов)
        total_s += s
        total_n += n
        total_f += f
        total_u += u
        if n != 0: rows_with_nach += 1
        if f != 0: rows_with_fot += 1
        if u != 0: rows_with_ud += 1
        if abs((n + f + u) - s) > 0.01:
            rows_mismatch += 1

    print(f"\n=== Тотали ===")
    print(f"  Сумма (тотал):     {total_s:>15,.2f}")
    print(f"  СуммаНачисления:   {total_n:>15,.2f}")
    print(f"  СуммаФОТ:          {total_f:>15,.2f}")
    print(f"  СуммаНалогов/Уд:   {total_u:>15,.2f}")
    print(f"  Σ(нач+фот+нал):    {(total_n + total_f + total_u):>15,.2f}")
    print(f"  Різниця тотал−Σ:   {(total_s - (total_n + total_f + total_u)):>15,.2f}")
    print(f"\n  Рядків з Начисления: {rows_with_nach}")
    print(f"  Рядків з ФОТ:         {rows_with_fot}")
    print(f"  Рядків з Удерж:       {rows_with_ud}")
    print(f"  Рядків де Σ≠тотал:    {rows_mismatch}")

    print(f"\n=== Перші 5 рядків ===")
    for i in range(min(5, r.Количество())):
        row = r.Получить(i)
        print(f"  {S(row.СотрудникФИО)[:30]:30s}  Тот={parse_num(row.Сумма):>10.2f} Нач={parse_num(row.СуммаНачисления):>10.2f} ФОТ={parse_num(row.СуммаФОТ):>10.2f} Уд={parse_num(row.СуммаНалогов):>10.2f}")
except Exception as e:
    print(f"ERR: {str(e)[:500]}")
