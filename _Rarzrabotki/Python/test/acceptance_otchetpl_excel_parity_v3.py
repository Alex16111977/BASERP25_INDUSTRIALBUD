def норм(текст):
    return re.sub(r"\s+", " ", (текст or "")).strip().lower()


def в_число(текст):
    """«-42 478,89» / «81,71%» -> float; пусто -> None."""
    т = (текст or "").strip().replace("\xa0", "").replace(" ", "").replace("%", "")
    if not т:
        return None
    т = т.replace(",", ".")
    try:
        return float(т)
    except ValueError:
        return None


def период(гy, гm, гd, кy, кm, кd):
    """ГРАБЛИ: даты нельзя собирать в Python — COM сдвигает их на −3 ч и теряет сутки.
    Границы получаем выражением ДАТАВРЕМЯ на стороне 1С."""
    q = erp.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ ДАТАВРЕМЯ(%d,%d,%d,0,0,0) КАК Н, ДАТАВРЕМЯ(%d,%d,%d,23,59,59) КАК К"
              % (гy, гm, гd, кy, кm, кd))
    г = q.Execute().Выгрузить().Получить(0)
    п = erp.NewObject("СтандартныйПериод")
    п.ДатаНачала = г.Н
    п.ДатаОкончания = г.К
    return п


def построить(пер, метка):
    """Полный путь пользователя: .erf + сохранённая настройка + период."""
    отчет = erp.ВнешниеОтчеты.Создать(ERF)
