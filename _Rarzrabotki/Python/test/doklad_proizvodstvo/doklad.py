"""Доклад по направлению «Производство» для зачитывания на совещании (русский) — из книги «План Факт Производство».

Источник — книга, которую формирует документ А_ФинансовыйОтчетПроизводства (листы «План-факт», «Сценарии —
основания»). Структура текста — по докладу строительства (стенограмма «Новая запись 10»): по каждому объекту
поступления (план, факт, %, недополучено) → затраты (план, факт, %, остаток к оплате) → маржа (план, факт, недобор) →
оптимистичный и пессимистичный сценарии с актами, сроками оплаты и лимитом.

Правила сценариев (пользователь 09.10 и 15.10.2026): пессимистичный — ТОЛЬКО подписанные акты (оригинал получен,
стадия S1) с оплатой до конца месяца, просроченные входят; акты на согласовании (S2) и не проведённые (S2н) — только
оптимистичный; без срока оплаты — только оптимистичный. Лимит = MAX(0; Δ + П), доп. маржа = Δ + П − Лимит,
Δ = маржа факт − план. Потребность не вводилась — покрытие = лимит.
    python -B doklad.py <книга План Факт Производство.xlsx> <выход без расширения>
"""
import sys, os, re, datetime as dt, html as H
import openpyxl

sys.stdout.reconfigure(encoding="utf-8")


def ч(v):
    return float(v) if isinstance(v, (int, float)) else 0.0


def г(x, знак=False):
    s = f"{abs(x):,.2f}".replace(",", " ").replace(".", ",")
    if знак and x < -0.004:
        return "−" + s
    return s


def п(x):
    return f"{x:.1f}".replace(".", ",") + " %"


def д(x):
    return x.strftime("%d.%m") if isinstance(x, (dt.date, dt.datetime)) else ""


def читать(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    pf = wb["План-факт"]
    шапка = str(pf["A1"].value or "")
    объекты = {}
    for r in range(6, pf.max_row + 1):
        a = pf.cell(r, 1).value
        if a and pf.cell(r, 25).value and str(pf.cell(r, 25).value).startswith("Казна"):
            имя = str(a).strip()
            объекты[имя] = {k: ч(pf.cell(r, c).value) for k, c in
                            (("D", 4), ("E", 5), ("F", 6), ("G", 7), ("I", 9), ("J", 10), ("K", 11), ("L", 12),
                             ("M", 13), ("N", 14), ("O", 15))}
            объекты[имя]["имя"] = имя
            объекты[имя]["позиции"] = []
    итого = None
    for r in range(6, pf.max_row + 1):
        if str(pf.cell(r, 1).value or "").strip() == "Итого":
            итого = {k: ч(pf.cell(r, c).value) for k, c in (("D", 4), ("E", 5), ("F", 6), ("G", 7), ("I", 9), ("J", 10),
                                                            ("K", 11), ("L", 12), ("M", 13), ("N", 14), ("O", 15))}
    sc = wb["Сценарии — основания"]
    тек = None
    for r in range(4, sc.max_row + 1):
        a, d = sc.cell(r, 1).value, sc.cell(r, 4).value
        if a and str(a).strip() in объекты:
            тек = str(a).strip()
            continue
        if тек and d:
            объекты[тек]["позиции"].append({"док": str(d).strip(), "стадия": str(sc.cell(r, 5).value or ""),
                                           "условие": str(sc.cell(r, 7).value or ""), "оплата": sc.cell(r, 8).value,
                                           "корзина": str(sc.cell(r, 9).value or ""), "сумма": ч(sc.cell(r, 10).value),
                                           "подписать_до": sc.cell(r, 13).value})
        if a and str(a).strip() == "Проверка":
            break
    m = re.search(r"на (\d\d\.\d\d\.\d{4})", шапка)
    дата = dt.datetime.strptime(m.group(1), "%d.%m.%Y").date() if m else None
    return объекты, итого, шапка, дата


def сценарии(о):
    Δ = о["O"]
    опт = sum(x["сумма"] for x in о["позиции"])
    песс = sum(x["сумма"] for x in о["позиции"] if x["стадия"].startswith("S1") and x["оплата"])
    def лд(P):
        L = max(0.0, Δ + P)
        return L, Δ + P - L
    о["опт"], о["песс"] = опт, песс
    о["лим_опт"], о["доп_опт"] = лд(опт)
    о["лим_песс"], о["доп_песс"] = лд(песс)


def абзац(о, дата):
    имя = о["имя"]
    ч_ = []
    D, E, F, G, I, J, K, L, M, N, O = (о[k] for k in "DEFGIJKLMNO")
    if D > 0:
        if E >= D - 0.005:
            ч_.append("Плановая сумма поступлений за месяц — <b>%s</b> грн, фактически от заказчика поступило <b>%s</b> грн — "
                      "план по поступлениям выполнен." % (г(D), г(E)))
        elif E < 0.005:
            ч_.append("Плановая сумма поступлений за месяц — <b>%s</b> грн, поступлений от заказчика пока не было." % г(D))
        else:
            ч_.append("Плановая сумма поступлений за месяц — <b>%s</b> грн, фактически от заказчика поступило <b>%s</b> грн, "
                      "это %s плана, недополучено <b>%s</b> грн." % (г(D), г(E), п(F), г(-G)))
    elif E:
        ч_.append("Поступлений по плану на месяц нет, фактически поступило %s грн — вне бюджета." % г(E))
    else:
        ч_.append("Поступлений по плану на месяц нет.")
    if I and abs(J) < 0.005:
        ч_.append("Плановые затраты — <b>%s</b> грн, затраты ещё не оплачивались." % г(-I))
    elif I:
        ч_.append("Плановые затраты — <b>%s</b> грн, фактически оплачено <b>%s</b> грн — %s плана, остаток затрат к оплате — "
                  "<b>%s</b> грн." % (г(-I), г(-J), п(K), г(L)))
    elif J:
        ч_.append("Затрат по плану нет, по факту %s грн — вне бюджета." % г(J))
    else:
        ч_.append("Затрат по плану и по факту нет.")
    if O < -0.004:
        ч_.append("Маржа по бюджету — <b>%s</b> грн, фактическая на сегодня — <b>%s</b> грн, недобор до плановой маржи — "
                  "<b>%s</b> грн." % (г(M, True), г(N, True), г(-O)))
    elif O > 0.004:
        хвост = " — затраты месяца оплачены ещё не полностью" if I and abs(J) < abs(I) else ""
        ч_.append("Маржа по бюджету — <b>%s</b> грн, фактическая на сегодня — <b>%s</b> грн, выше плановой на <b>%s</b> грн%s."
                  % (г(M, True), г(N, True), г(O), хвост))
    опт_акты = о["позиции"]
    песс_акты = [x for x in опт_акты if x["стадия"].startswith("S1") and x["оплата"]]
    if not опт_акты:
        if о["лим_опт"] > 0:
            ч_.append("Актов к получению нет, поступлений до конца месяца не ожидаем; лимит на затраты — <b>%s</b> грн "
                      "в пределах бюджета." % г(о["лим_опт"]))
        else:
            ч_.append("Актов к получению нет, поступлений до конца месяца не ожидаем; лимит — 0, маржа останется ниже плана "
                      "на <b>%s</b> грн." % г(-о["доп_опт"]))
        return ч_
    условия = sorted({x["условие"] for x in опт_акты if x["оплата"] and "не задан" not in x["условие"]})
    if len(условия) == 1:
        ч_.append("Оплата по договору — %s." % усл_текст(условия[0]))
    перечень = "; ".join(акт_кратко(x, дата, len(условия) != 1) for x in опт_акты)
    if abs(о["опт"] - о["песс"]) < 0.005:
        т = ("Все акты к получению подписаны, поэтому оба сценария совпадают: до конца месяца ожидаем <b>%s</b> грн — %s. "
             % (г(о["опт"]), перечень))
        т += лимит_текст(о["лим_опт"], о["доп_опт"])
        ч_.append(т)
        return ч_
    т = "<span class=opt>Оптимистичный сценарий</span> — до конца месяца ожидаем <b>%s</b> грн: %s. " % (г(о["опт"]), перечень)
    т += лимит_текст(о["лим_опт"], о["доп_опт"])
    ч_.append(т)
    if len(песс_акты) == 1:
        т = ("<span class=pes>Пессимистичный сценарий</span> — только подписанный акт %s на <b>%s</b> грн. "
             % (re.sub(r" от (\d\d\.\d\d)\.\d{4}", r" от \1", песс_акты[0]["док"]), г(о["песс"])))
    elif песс_акты:
        т = ("<span class=pes>Пессимистичный сценарий</span> — только подписанные акты: <b>%s</b> грн (%s). "
             % (г(о["песс"]), "; ".join(re.sub(r" от (\d\d\.\d\d)\.\d{4}", r" от \1", x["док"]) + " — " + г(x["сумма"]) for x in песс_акты)))
    else:
        т = "<span class=pes>Пессимистичный сценарий</span> — подписанных актов к оплате нет, поступлений не ожидаем: "
    т += лимит_текст(о["лим_песс"], о["доп_песс"], о["песс"])
    ч_.append(т)
    return ч_


def усл_текст(у):
    m = re.match(r"(\d+) (банк|кал|раб)\. дн\. после (.+)", у)
    if not m:
        return у
    return "%s %s дней после %s" % (m.group(1), {"банк": "банковских", "кал": "календарных", "раб": "рабочих"}[m.group(2)],
                                    m.group(3))


def акт_кратко(x, дата, с_условием):
    номер = re.sub(r" от (\d\d\.\d\d)\.\d{4}", r" от \1", x["док"])
    ст = "подписан" if x["стадия"].startswith("S1") else "на согласовании"
    if not x["оплата"] or "не задан" in x["условие"]:
        срок = "срок оплаты в договоре не задан"
    elif дата and x["оплата"].date() < дата:
        срок = "срок оплаты %s прошёл, просрочено %d дн." % (д(x["оплата"]), (дата - x["оплата"].date()).days)
    else:
        срок = "оплата до %s" % д(x["оплата"])
    if с_условием and x["оплата"] and "не задан" not in x["условие"]:
        срок = усл_текст(x["условие"]) + ", " + срок
    return "%s на <b>%s</b> грн — %s, %s" % (номер, г(x["сумма"]), ст, срок)


def лимит_текст(L, доп, П=None):
    if доп < -0.004:
        if L > 0.004:
            return "Лимит с учётом поступлений — <b>%s</b> грн." % г(L)
        if П is not None and П < 0.005:
            return "лимит — 0, маржа останется ниже плана на <b>%s</b> грн." % г(-доп)
        return "Поступления не закрывают недобор маржи: лимит — 0, маржа останется ниже плана на <b>%s</b> грн." % г(-доп)
    return "Лимит с учётом поступлений — <b>%s</b> грн." % г(L)


def задачи(объекты, дата):
    з = []  # (порядок, -сумма, текст): просрочки, подписание, без срока, план без актов
    for о in объекты:
        for x in о["позиции"]:
            номер = re.sub(r" от (\d\d\.\d\d)\.\d{4}", r" от \1", x["док"])
            if x["стадия"].startswith("S1") and x["оплата"] and дата and x["оплата"].date() < дата:
                з.append((0, -x["сумма"], "<b>%s</b>: %s на %s грн подписан, срок оплаты %s прошёл (просрочено %d дн.) — "
                          "требовать оплату." % (о["имя"], номер, г(x["сумма"]), д(x["оплата"]), (дата - x["оплата"].date()).days)))
            elif not x["стадия"].startswith("S1") and x["подписать_до"]:
                пд = x["подписать_до"].date() if isinstance(x["подписать_до"], dt.datetime) else x["подписать_до"]
                if дата and пд < дата:
                    когда = "срок подписания для оплаты в октябре (%s) уже прошёл — оплата сдвигается на ноябрь" % д(пд)
                elif дата and пд == дата:
                    когда = "чтобы оплата пришла в октябре, акт нужно подписать сегодня, %s" % д(пд)
                else:
                    когда = "чтобы оплата пришла в октябре, акт нужно подписать до %s" % д(пд)
                з.append((1, -x["сумма"], "<b>%s</b>: %s на %s грн — на согласовании; %s."
                          % (о["имя"], номер, г(x["сумма"]), когда)))
            elif not x["оплата"]:
                з.append((2, -x["сумма"], "<b>%s</b>: %s на %s грн — срок оплаты в договоре не задан, уточнить условия оплаты."
                          % (о["имя"], номер, г(x["сумма"]))))
        if о["D"] > о["E"] + 0.005 and not о["позиции"]:
            з.append((3, -(о["D"] - о["E"]), "<b>%s</b>: по бюджету ожидается %s грн поступлений, но актов к получению нет — "
                      "поступление под вопросом." % (о["имя"], г(о["D"] - о["E"]))))
    return [t for _, _, t in sorted(з)]


