"""Доклад по направлению «Производство» для зачитывания на совещании (русский) — из книги «План Факт Производство».

Источник — книга документа А_ФинансовыйОтчетПроизводства: лист «План-факт» (цифры по объектам — как в книге, правило
нуля: итоги = xlsx), «Сценарии — основания» (акты, стадии, сроки оплаты, «подписать до»), «Недели» (поступления
недели отчёта), «Изменения за неделю» (рост факта с прошлого отчёта). Необязательно — фінзвіт «с расшифровкой»:
ДЦ на рассмотрении, незарегистрированный НДС, частичные оплаты актов, оплаченные, но не подписанные акты.
Структура текста — по докладу строительства (стенограмма «Новая запись 10»): по каждому объекту поступления
(план, факт, %, недополучено) → затраты (план, факт, %, остаток к оплате) → маржа (план, факт, недобор) →
оптимистичный и пессимистичный сценарии: поступления, акты, лимит, потребность и хватает ли на неё лимита.

Колонки «План-факт» ищутся по заголовкам (группа + подзаголовок), поэтому подходят обе раскладки книги:
16.10 (Потребность «на месяц», Пессимистичный, Оптимистичный, Источник) и 19.10 (Оптимистичный и Пессимистичный
сценарии со своими «Потребность» и «Доп. маржа»). Суммы сценариев, лимиты и потребность берутся из книги — их
уточняют в базе. Лимит = MAX(0; Δ + П), доп. маржа = Δ + П − Лимит, Δ = маржа факт − план; покрытие = лимит − потребность.
    python -B doklad.py <книга План Факт Производство.xlsx> <выход без расширения> [<фінзвіт с расшифровкой.xlsx>]
"""
import sys, re, datetime as dt, html as H
import openpyxl

sys.stdout.reconfigure(encoding="utf-8")
ε = 0.995  # до гривны — ручной ввод в базе округляет; для «совпадают» нужна точность до копейки
МЕСЯЦ_П = {1: "январе", 2: "феврале", 3: "марте", 4: "апреле", 5: "мае", 6: "июне", 7: "июле", 8: "августе",
           9: "сентябре", 10: "октябре", 11: "ноябре", 12: "декабре"}
ЧИСЛО_АКТОВ = {1: "одному акту", 2: "двум актам", 3: "трём актам", 4: "четырём актам"}
ЧИСЛО_Д = {2: "двум", 3: "трём", 4: "четырём", 5: "пяти", 6: "шести", 7: "семи", 8: "восьми"}


def ч(v):
    return float(v) if isinstance(v, (int, float)) else 0.0


def г(x, знак=False):
    s = f"{abs(x):,.2f}".replace(",", " ").replace(".", ",")
    if знак and x < -0.004:
        return "−" + s
    return s


def м(x):
    """Сумма для чтения вслух: отрицательная — словом «минус»."""
    return ("минус " if x < -0.004 else "") + г(x)


def п(x):
    return f"{x:.1f}".replace(".", ",") + " %"


def д(x):
    return x.strftime("%d.%m") if isinstance(x, (dt.date, dt.datetime)) else ""


def дата_(x):
    return x.date() if isinstance(x, dt.datetime) else x


def дней(n):
    if n % 10 == 1 and n % 100 != 11:
        return "%d день" % n
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "%d дня" % n
    return "%d дней" % n


def номер(x):
    return re.sub(r" от (\d\d\.\d\d)\.\d{4}", r" от \1", x["док"])


def код(x):
    return x["док"].split(" ")[0]


def подписан(x):
    return x["стадия"].startswith("S1")


def со_сроком(x):
    return bool(x["оплата"]) and "не задан" not in x["условие"]


ГРУППЫ = (("поступ", "пост"), ("затрат", "затр"), ("марж", "марж"), ("оптим", "опт"), ("пессим", "песс"),
          ("потреб", "потр"), ("источ", "ист"))
ПОДЗАГ = (("план", "план"), ("факт", "факт"), ("%", "%"), ("разниц", "разн"), ("поступ", "пост"), ("лимит", "лимит"),
          ("потреб", "потр"), ("доп", "доп"), ("покрыт", "покр"), ("на месяц", "месяц"))


def норм(v, словарь):
    s = str(v or "").strip().lower()
    for k, n in словарь:
        if s.startswith(k):
            return n
    return None


def колонки(ws):
    """(группа, подзаголовок) → номер колонки; строка заголовка групп — первая, где A = «Подразделение» дважды подряд."""
    for r0 in range(1, 15):
        if ws.cell(r0, 1).value == "Подразделение" and ws.cell(r0 + 1, 1).value == "Подразделение":
            break
    else:
        raise ValueError("не найдена шапка листа «План-факт»")
    к, группа = {}, None
    for c in range(2, ws.max_column + 1):
        группа = норм(ws.cell(r0, c).value, ГРУППЫ) or (группа if ws.cell(r0, c).value is None else None)
        под = норм(ws.cell(r0 + 1, c).value, ПОДЗАГ)
        if группа and (под or группа in ("потр", "ист")):
            к[(группа, под)] = c
    return к, r0 + 2


ПОЛЯ = {"D": ("пост", "план"), "E": ("пост", "факт"), "F": ("пост", "%"), "G": ("пост", "разн"),
        "I": ("затр", "план"), "J": ("затр", "факт"), "K": ("затр", "%"), "L": ("затр", "разн"),
        "M": ("марж", "план"), "N": ("марж", "факт"), "O": ("марж", "разн")}


def читать(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    pf = wb["План-факт"]
    шапка = str(pf["A1"].value or "")
    к, r1 = колонки(pf)
    ист = к.get(("ист", None))

    def значения(r):
        о = {k: ч(pf.cell(r, к[кл]).value) if кл in к else 0.0 for k, кл in ПОЛЯ.items()}
        for сц in ("опт", "песс"):
            for поле in ("пост", "лимит", "потр", "доп"):
                кл = (сц, поле)
                о[сц + "_" + поле] = ч(pf.cell(r, к[кл]).value) if кл in к else None
            if о[сц + "_потр"] is None:  # раскладка 16.10: одна потребность на месяц
                о[сц + "_потр"] = ч(pf.cell(r, к[("потр", "месяц")]).value) if ("потр", "месяц") in к else 0.0
        return о

    объекты, итого = {}, None
    for r in range(r1, pf.max_row + 1):
        a = str(pf.cell(r, 1).value or "").strip()
        if not a:
            continue
        if a == "Итого":
            итого = значения(r)
            break
        if (ист and str(pf.cell(r, ист).value or "").startswith("Казна")) or \
                (not ист and pf.row_dimensions[r].outline_level == 0):
            объекты[a] = dict(значения(r), имя=a, позиции=[], дц=0.0, ндс=0.0)
    sc = wb["Сценарии — основания"]
    тек = None
    for r in range(4, sc.max_row + 1):
        a, d = sc.cell(r, 1).value, sc.cell(r, 4).value
        if a and str(a).strip() == "Проверка":
            break
        if a and str(a).strip() in объекты:
            тек = str(a).strip()
            continue
        if тек and d:
            объекты[тек]["позиции"].append({
                "док": str(d).strip(), "стадия": str(sc.cell(r, 5).value or ""), "условие": str(sc.cell(r, 7).value or ""),
                "оплата": дата_(sc.cell(r, 8).value), "сумма": ч(sc.cell(r, 10).value), "песс": ч(sc.cell(r, 11).value),
                "подписать_до": дата_(sc.cell(r, 13).value), "частично": None})
    m = re.search(r"на (\d\d\.\d\d\.\d{4})", шапка)
    дата = dt.datetime.strptime(m.group(1), "%d.%m.%Y").date() if m else None
    неделя = {}
    if "Недели" in wb.sheetnames and дата:
        ws = wb["Недели"]
        for r in range(1, ws.max_row + 1):
            mm = re.match(r"(\d\d)–(\d\d)$", str(ws.cell(r, 1).value or "").strip())
            if mm and int(mm.group(1)) <= дата.day <= int(mm.group(2)):
                неделя.update(с=int(mm.group(1)), поступило=ч(ws.cell(r, 3).value))
    if "Изменения за неделю" in wb.sheetnames:
        ws = wb["Изменения за неделю"]
        mm = re.search(r"от (\d\d\.\d\d)\.\d{4}", str(ws["A1"].value or ""))
        в_итого = False
        for r in range(1, ws.max_row + 1):
            a = str(ws.cell(r, 1).value or "").strip()
            if a == "Итого":
                в_итого = True
            elif в_итого and a == "Факт затрат":
                неделя.update(прошлый=mm.group(1) if mm else "", затраты=ч(ws.cell(r, 4).value))
    return объекты, итого, дата, неделя


def фінзвіт(path, объекты):
    """ДЦ на рассмотрении и незарегистрированный НДС по объекту; акты: статус, сумма, частичная оплата, оплачен ли."""
    ws = openpyxl.load_workbook(path, data_only=True).worksheets[0]
    акты, тек = {}, None
    for r in range(1, ws.max_row + 1):
        a = str(ws.cell(r, 1).value or "").strip()
        lvl = ws.row_dimensions[r].outline_level
        if lvl == 0 and " (" in a:
            тек = a.split(" (")[0].strip()
            if тек in объекты:
                объекты[тек].update(дц=ч(ws.cell(r, 4).value), ндс=ч(ws.cell(r, 10).value))
        elif lvl == 0 and a == "Итого":
            тек = None
        elif тек and lvl == 2 and not a.startswith("Поступление"):
            mm = re.search(r"([^\W\d_]{2}\d\d-\d{6}) от \d\d\.\d\d\.\d{4}", a)
            if not mm:
                continue
            b, n = str(ws.cell(r, 2).value or ""), str(ws.cell(r, 14).value or "")
            mp = re.search(r"оплачено [\d\s ,]+ \(последняя (\d\d\.\d\d\.\d{4})\); не оплачено", n)
            акты[mm.group(1)] = {
                "объект": тек, "док": mm.group(0), "статус": "подписан" if b.startswith("оригинал получен") else b,
                "сумма": ч(ws.cell(r, 5).value) or ч(ws.cell(r, 8).value),
                "частично": dt.datetime.strptime(mp.group(1), "%d.%m.%Y").date() if mp else None,
                "оплачен": bool(re.search(r"(?:^|; )оплачен\b", n)) and "не оплачено" not in n}
    for о in объекты.values():
        for x in о["позиции"]:
            if код(x) in акты:
                x["частично"] = акты[код(x)]["частично"]
    return акты


def усл_текст(у):
    m = re.match(r"(\d+) (банк|кал|раб)\. дн\. после (.+)", у)
    if not m:
        return у
    return "%s %s дней после %s" % (m.group(1), {"банк": "банковских", "кал": "календарных", "раб": "рабочих"}[m.group(2)],
                                    m.group(3))


def дата_акта(x):
    m = re.search(r" от (\d\d\.\d\d)", x["док"])
    return m.group(1) if m else ""


def срок_ключ(x, дата):
    """Признаки, по которым акты одного объекта объединяются в одну фразу."""
    if подписан(x):
        частично = x["частично"] if (x["частично"] and дата and x["частично"].month == дата.month) else None
        if not со_сроком(x):
            return ("S1", частично, "без", None)
        return ("S1", частично, "просрочен" if дата and x["оплата"] < дата else "до", x["оплата"])
    if not со_сроком(x):
        return ("S2", None, "без", None)
    пд = x["подписать_до"]
    if not пд:
        return ("S2", None, "после", None)
    return ("S2", None, "прошёл" if дата and пд < дата else "сегодня" if дата and пд == дата else "подписать", пд)


def фраза_срока(к, дата, мн, со_статусом):
    """Хвост фразы об акте(ах): статус (если статусы на объекте разные) и срок оплаты/подписания."""
    мес = МЕСЯЦ_П.get(дата.month, "этом месяце") if дата else "этом месяце"
    if к[0] == "S1":
        if к[2] == "без":
            срок = "срок оплаты в договоре не задан"
        elif к[2] == "просрочен":
            срок = "срок оплаты %s прошёл, просрочка на дату отчёта — %s" % (д(к[3]), дней((дата - к[3]).days))
        else:
            срок = "оплата до %s" % д(к[3])
        if к[1]:
            return " %s%s оплачен%s частично; %s" % ("подписан%s и " % ("ы" if мн else "") if со_статусом else "", д(к[1]),
                                                   "ы" if мн else "", срок)
        return (" подписан%s, " % ("ы" if мн else "") if со_статусом else " — ") + срок
    хв = {"без": "срок оплаты в договоре не задан",
          "после": "оплата после подписания",
          "подписать": "для оплаты в %s нужно подписать до %s" % (мес, д(к[3])),
          "сегодня": "для оплаты в %s нужно было подписать до %s, но на дату отчёта %s"
                     % (мес, д(к[3]), "акты не подписаны" if мн else "акт не подписан"),
          "прошёл": "срок подписания для оплаты в %s (%s) прошёл" % (мес, д(к[3]))}[к[2]]
    if со_статусом:
        return " на согласовании" + (": " if к[2] in ("подписать", "сегодня") else ", ") + хв
    return (" " if к[2] in ("подписать", "сегодня") else " — ") + хв


def акты_фраза(набор, дата, многоусл):
    """Продолжение фразы «ожидаем S грн…»: акты сгруппированы по статусу и сроку, чтобы не повторять одно и то же."""
    if len(набор) == 1:
        x = набор[0]
        к = срок_ключ(x, дата)
        хв = фраза_срока(к, дата, False, True)
        if многоусл and со_сроком(x):
            хв += ", по договору " + усл_текст(x["условие"])
        return " по акту %s; акт%s." % (номер(x), хв)
    одна_дата = len({дата_акта(x) for x in набор}) == 1
    подп = {подписан(x) for x in набор}
    смешано = len(подп) > 1
    вступление = " по %s%s актам%s" % (ЧИСЛО_Д.get(len(набор), str(len(набор))), " подписанным" if подп == {True} else "",
                                        " от " + дата_акта(набор[0]) if одна_дата else "")
    if подп == {False}:
        вступление += ", оба на согласовании" if len(набор) == 2 else ", все на согласовании"
    группы = {}
    for x in набор:
        группы.setdefault(срок_ключ(x, дата), []).append(x)
    фразы, первая = [], True
    for к, аа in группы.items():
        ссылки = []
        for x in аа:
            ссылки.append("%s%s (%s<b>%s</b> грн)" % (код(x), "" if одна_дата else " от " + дата_акта(x),
                                                     "к получению " if первая else "", г(x["показ"])))
            первая = False
        мн = len(аа) > 1
        с = " и ".join(ссылки) if len(ссылки) <= 2 else ", ".join(ссылки[:-1]) + " и " + ссылки[-1]
        хв = фраза_срока(к, дата, мн, смешано)
        if многоусл and со_сроком(аа[0]):
            хв += ", по договору " + усл_текст(аа[0]["условие"])
        фразы.append("Акт%s %s%s." % ("ы" if мн else "", с, хв))
    return вступление + ". " + " ".join(фразы)


def потребность_текст(L, П, нулевая=False):
    """Хватает ли лимита на потребность (покрытие = лимит − потребность)."""
    if not П or П < 0.005:
        return "потребность нулевая" if нулевая else "потребность не заявлена"
    if L > 0.005 and L >= П - 0.005:
        ост = L - П
        return "потребность <b>%s</b> грн — %s" % (г(П), ("лимита хватает, остаётся <b>%s</b> грн" % г(ост)) if ост > 0.005
                                                 else "лимита хватает, остатка нет")
    if L > 0.005:
        return "потребность <b>%s</b> грн — лимита не хватает <b>%s</b> грн" % (г(П), г(П - L))
    return "потребность <b>%s</b> грн не покрыта" % г(П)


def лимит_текст(о, сц, без_поступлений=False):
    """Лимит, доп. маржа и потребность сценария — фрагмент с маленькой буквы, с точкой в конце."""
    L, доп, П = о[сц + "_лимит"], о[сц + "_доп"], о[сц + "_потр"]
    if доп < -0.004 and L < 0.005:
        т = ("лимита нет, маржа останется ниже плана на <b>%s</b> грн" % г(-доп) if без_поступлений else
             "поступления не закрывают недобор маржи, поэтому лимита нет и маржа останется ниже плана на <b>%s</b> грн" % г(-доп))
    elif L < 0.005:
        т = "лимита нет" if без_поступлений else "эти поступления только закрывают недобор маржи, поэтому лимита нет"
    else:
        т = ("лимит — <b>%s</b> грн" if без_поступлений else "лимит с учётом поступлений — <b>%s</b> грн") % г(L)
    return т + "; " + потребность_текст(L, П) + "."


def с_большой(т):
    return т[0].upper() + т[1:]


def подмножество(акты, сумма):
    """Какие акты дают сумму сценария: все, только подписанные со сроком, отмеченные книгой; иначе — None."""
    for набор in (акты, [x for x in акты if подписан(x) and со_сроком(x)], [x for x in акты if x["песс"]]):
        if набор and abs(sum(x["сумма"] for x in набор) - сумма) < ε:
            return набор
    return None


