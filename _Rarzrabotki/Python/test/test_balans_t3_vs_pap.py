"""Test 3 (OD-5, v1.2): Σ регістра по Статья == ПАП.ОстаткиИОбороты по Статья
БЕЗ фільтра, до копійки; Σ повного набору КонОст ≈ 0 (Актив=Пасив).
Період січень 2026 (закритий, Актив=Пасив). Межі періоду рахуються СЕРВЕРНО
(1С НачалоПериода/КонецПериода від Месяц-опівдні) — щоб уникнути TZ-зсуву
Python-наївних дат через границю року (CLAUDE.md: дати з опівднем)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
M = datetime(2026, 1, 1, 12, 0, 0)   # січень 2026, опівдні (TZ-safe anchor)
TOL = 0.01

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

q0 = conn.NewObject("Запрос")
q0.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"'
s = q0.Выполнить().Выбрать(); s.Следующий(); org = s.С

# межі періоду 1:1 як BSL (серверний розрахунок, без Python-TZ)
qb = conn.NewObject("Запрос")
qb.Текст = """ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М, МЕСЯЦ) КАК НМ,
КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М, МЕСЯЦ), ДЕНЬ) КАК КД"""
qb.УстановитьПараметр("М", M)
rb = qb.Выполнить().Выбрать(); rb.Следующий()
НМ = rb.НМ; КД = rb.КД
print(f"період: {НМ} .. {КД}")

def key(ref):
    try: return str(conn.XMLСтрока(ref))
    except Exception: return repr(ref)

# 1) регістр по Статья (документи за цей Месяц, проведені)
qr = conn.NewObject("Запрос")
qr.Текст = """
ВЫБРАТЬ Статья КАК Статья, ПРЕДСТАВЛЕНИЕ(Статья) КАК Н,
    СУММА(СуммаКонечныйОстаток) КАК sK
ИЗ РегистрСведений.А_ОтчетБаланс_Свод
ГДЕ Регистратор В (ВЫБРАТЬ Ссылка ИЗ Документ.А_ФинРез_Баланс
                   ГДЕ Организация = &Орг И Месяц = &НМ
                     И НЕ ПометкаУдаления И Проведен)
СГРУППИРОВАТЬ ПО Статья, ПРЕДСТАВЛЕНИЕ(Статья)
"""
qr.УстановитьПараметр("Орг", org); qr.УстановитьПараметр("НМ", НМ)
tz1 = qr.Выполнить().Выгрузить()
reg = {}; reg_nm = {}; reg_total = 0.0
for i in range(tz1.Количество()):
    rr = tz1.Получить(i); k = key(rr.Статья); v = float(rr.sK or 0)
    reg[k] = v; reg_nm[k] = str(rr.Н); reg_total += v
print(f"регістр: {len(reg)} статей, Σ КонОст = {reg_total:,.2f}")

# 2) ПАП.ОстаткиИОбороты — БЕЗ фільтра, ті самі (серверні) межі періоду
qp = conn.NewObject("Запрос")
qp.Текст = """
ВЫБРАТЬ Б.Статья КАК Статья, СУММА(Б.СуммаКонечныйОстаток) КАК sK
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(
        &Д1, &Д2, Авто, , Организация = &Орг) КАК Б
СГРУППИРОВАТЬ ПО Б.Статья
ИМЕЮЩИЕ СУММА(Б.СуммаКонечныйОстаток) <> 0
"""
qp.УстановитьПараметр("Орг", org)
qp.УстановитьПараметр("Д1", НМ); qp.УстановитьПараметр("Д2", КД)
tz2 = qp.Выполнить().Выгрузить()
pap = {}; pap_total = 0.0
for i in range(tz2.Количество()):
    rr = tz2.Получить(i); k = key(rr.Статья); v = float(rr.sK or 0)
    pap[k] = v; pap_total += v
print(f"ПАП:     {len(pap)} статей, Σ КонОст = {pap_total:,.2f}")

# 3) звірка по статтях до копійки
diffs = []
for k in set(reg) | set(pap):
    d = abs(reg.get(k, 0.0) - pap.get(k, 0.0))
    if d > TOL:
        diffs.append((reg_nm.get(k, k[:40]), reg.get(k,0.0), pap.get(k,0.0), d))
if diffs:
    print(f"FAIL: {len(diffs)} статей розбіжні")
    for nm,a,b,d in sorted(diffs, key=lambda x:-x[3])[:15]:
        print(f"  {nm[:44]:<46} рег={a:>16,.2f} ПАП={b:>16,.2f} Δ={d:>13,.2f}")
    sys.exit(1)

# 4) Актив=Пасив: Σ повного набору КонОст ≈ 0
assert abs(reg_total) < 1.0, f"FAIL: Актив≠Пасив у регістрі (Σ={reg_total:,.2f}; має ≈0)"
print(f"PASS Test 3 — {len(set(reg)|set(pap))} статей зійшлись до {TOL}; "
      f"Актив=Пасив (Σ регістра={reg_total:,.2f}, Σ ПАП={pap_total:,.2f})")
