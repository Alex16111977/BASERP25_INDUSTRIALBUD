def run(text):
    q = erp.NewObject("Запрос"); q.Текст = text
    t = q.Выполнить().Выгрузить()
    names = [t.Колонки.Получить(j).Имя for j in range(t.Колонки.Количество())]
    return names, [[t.Получить(i).Получить(j) for j in range(len(names))] for i in range(t.Количество())]

def show(title, names, rows):
    print("\n" + "=" * 72 + f"\n{title}\n" + "=" * 72)
    print("  " + " | ".join(names))
    for r in rows:
        print("  " + " | ".join(str(x) for x in r))

