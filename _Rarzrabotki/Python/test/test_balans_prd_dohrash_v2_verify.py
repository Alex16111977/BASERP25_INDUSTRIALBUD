# -*- coding: utf-8 -*-
"""Verify v2 — перепровести Финансовый результат Баланс 00000000004 от 30.04.2026
после внедрения расшифровки через РегНакопл.ПрочиеРасходы / ПрочиеДоходы.

Asserts:
- В РС А_ОтчетБаланс_Свод по этому регистратору / Глобино-2 / Расх.тек.пер.:
  * РОВНО 1 строка-деталь (Расхождение=Ложь)
  * СтатьяДоходыРасходы = "Затраты на служебные командировки..."
  * НО = 0, КО = 2400
  * Аналитика1 = ПРЕДСТАВЛЕНИЕ(СтатьяДохРасх)
- По Глобино-2 / Дох.тек.пер. — 0 строк
- Σ свод per (Орг,Подр,Статья) == ПАП.ОстаткиИОбороты до 0.01
- Идемпотентность 2-го прогона
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client
from datetime import datetime

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
S = erp.String
TOL = 0.01

q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Ссылка ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273" """
own_org = q.Execute().Выгрузить().Получить(0).Ссылка

# Документ апрель 2026
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", own_org)
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.А_ФинРез_Баланс
ГДЕ Организация = &Орг И НЕ ПометкаУдаления
    И Месяц >= ДАТАВРЕМЯ(2026,4,1,0,0,0) И Месяц <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
"""
doc_ref = q.Execute().Выгрузить().Получить(0).Ссылка
print(f"Документ: {S(doc_ref)}")

# Перепровести
try:
    doc_obj = doc_ref.ПолучитьОбъект()
    doc_obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("[OK] Перепроведение PASS")
except Exception as e:
    print(f"[FAIL] {e}"); sys.exit(1)

# Глобино-2 / Расх.тек.пер.
СтРасх = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода")
СтДох = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Доходы текущего периода")
glob2 = erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Глобино-2")

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Рег", doc_ref)
q.УстановитьПараметр("Орг", own_org)
q.УстановитьПараметр("Глобино2", glob2)
q.УстановитьПараметр("СтРасх", СтРасх)
q.Text = """
ВЫБРАТЬ
    РС.СтатьяДоходыРасходы, ПРЕДСТАВЛЕНИЕ(РС.СтатьяДоходыРасходы) КАК СДРПред,
    РС.Аналитика1,
    РС.Расхождение,
    РС.СуммаНачальныйОстаток КАК НО,
    РС.СуммаКонечныйОстаток КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК РС
ГДЕ РС.ДокументДвижения = &Рег И РС.Организация = &Орг
    И РС.Подразделение = &Глобино2 И РС.Статья = &СтРасх
"""
r = q.Execute().Выгрузить()
print(f"\n=== Глобино-2 / Расходы текущего периода (после перепроведения) ===")
print(f"Строк: {r.Количество()}")
total_no = 0.0
total_ko = 0.0
detail_count = 0
plug_count = 0
detail_st = None
detail_an1 = None
detail_no = 0.0
detail_ko = 0.0
for i in range(r.Количество()):
    row = r.Получить(i)
    no = float(row.НО)
    ko = float(row.КО)
    total_no += no
    total_ko += ko
    tag = "ПЛУГ" if row.Расхождение else "Деталь"
    print(f"  [{tag}] {S(row.СДРПред):<60} | НО={no:>10.2f} | КО={ko:>10.2f} | Аналитика1='{S(row.Аналитика1)}'")
    if row.Расхождение:
        plug_count += 1
    else:
        detail_count += 1
        detail_st = S(row.СДРПред)
        detail_an1 = S(row.Аналитика1)
        detail_no = no
        detail_ko = ko

print(f"\nTOTAL: НО={total_no:.2f} КО={total_ko:.2f}")
print(f"Детали: {detail_count}, Плуги: {plug_count}")

assert detail_count == 1, f"Глобино-2/Расх.тек.пер.: ожидаем 1 деталь, получили {detail_count}"
assert "командировки" in detail_st.lower(), f"Ожидаем 'Затраты на служебные командировки', получили '{detail_st}'"
assert abs(detail_no) < TOL, f"Деталь НО=0 ожидаем, получили {detail_no}"
assert abs(detail_ko - 2400) < TOL, f"Деталь КО=2400 ожидаем, получили {detail_ko}"
assert detail_an1.strip() != "", f"Аналитика1 не должна быть пустой"
assert abs(total_ko - 2400) < TOL, f"Σ КО Глобино-2 должна быть 2400, получили {total_ko}"

print(f"\n[OK] Глобино-2/Расх.тек.пер.: 1 деталь, СтатьяДоходыРасходы='{detail_st}', НО=0, КО=2400")
print(f"[OK] Аналитика1='{detail_an1}' (непустая)")

# Глобино-2 / Дох.тек.пер. — должно быть 0 строк
q.УстановитьПараметр("СтРасх", СтДох)
r2 = q.Execute().Выгрузить()
assert r2.Количество() == 0, f"Глобино-2/Дох.тек.пер.: ожидаем 0 строк, получили {r2.Количество()}"
print(f"[OK] Глобино-2/Дох.тек.пер.: 0 строк")

# Σ свод per (Орг,Подр,Статья) == ПАП per same для статей Расх/Дох тек.пер.
СтСС = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Собственные средства")
iskl_arr = erp.NewObject("Массив")
iskl_arr.Добавить(СтСС)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Рег", doc_ref)
q.Text = """
ВЫБРАТЬ
    РС.Организация, ПРЕДСТАВЛЕНИЕ(РС.Организация) КАК ОргПред,
    РС.Подразделение, ПРЕДСТАВЛЕНИЕ(РС.Подразделение) КАК ПодрПред,
    РС.Статья, ПРЕДСТАВЛЕНИЕ(РС.Статья) КАК СтатьяПред,
    СУММА(РС.СуммаНачальныйОстаток) КАК НО,
    СУММА(РС.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК РС
ГДЕ РС.ДокументДвижения = &Рег
СГРУППИРОВАТЬ ПО РС.Организация, РС.Подразделение, РС.Статья
"""
svod = q.Execute().Выгрузить()
svod_map = {}
for i in range(svod.Количество()):
    row = svod.Получить(i)
    svod_map[(S(row.ОргПред), S(row.ПодрПред), S(row.СтатьяПред))] = (float(row.НО), float(row.КО))

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", own_org)
q.УстановитьПараметр("Искл", iskl_arr)
q.Text = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Б.Организация) КАК ОргПред,
    ЕСТЬNULL(ПРЕДСТАВЛЕНИЕ(Б.Подразделение), "") КАК ПодрПред,
    ПРЕДСТАВЛЕНИЕ(Б.Статья) КАК СтатьяПред,
    СУММА(Б.СуммаНачальныйОстаток) КАК НО,
    СУММА(Б.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(
        ДАТАВРЕМЯ(2026,4,1,0,0,0),
        ДАТАВРЕМЯ(2026,4,30,23,59,59),
        Авто, ,
        Организация = &Орг И НЕ Статья В ИЕРАРХИИ(&Искл)) КАК Б
СГРУППИРОВАТЬ ПО Б.Организация, Б.Подразделение, Б.Статья
"""
pap = q.Execute().Выгрузить()
pap_map = {}
for i in range(pap.Количество()):
    row = pap.Получить(i)
    pap_map[(S(row.ОргПред), S(row.ПодрПред), S(row.СтатьяПред))] = (float(row.НО), float(row.КО))

# Сверка
all_keys = set(pap_map.keys()) | set(svod_map.keys())
mismatches = []
for k in all_keys:
    sno, sko = svod_map.get(k, (0.0, 0.0))
    pno, pko = pap_map.get(k, (0.0, 0.0))
    if abs(sno - pno) > TOL or abs(sko - pko) > TOL:
        mismatches.append((k, sno, sko, pno, pko))

if mismatches:
    print(f"\n[FAIL] {len(mismatches)} расхождений свод vs ПАП:")
    for k, sno, sko, pno, pko in mismatches[:10]:
        print(f"  {k} | свод НО={sno:.2f} КО={sko:.2f} | ПАП НО={pno:.2f} КО={pko:.2f}")
    sys.exit(1)
print(f"\n[OK] Σ свод per (Орг,Подр,Статья) == ПАП.ОстаткиИОбороты до 0.01 ({len(all_keys)} ключей)")

# Идемпотентность
doc_obj2 = doc_ref.ПолучитьОбъект()
doc_obj2.Записать(erp.РежимЗаписиДокумента.Проведение)
print("[OK] Идемпотентность — 2-й прогон без ошибок")

print("\n[OK] Verify v2 PASS")
