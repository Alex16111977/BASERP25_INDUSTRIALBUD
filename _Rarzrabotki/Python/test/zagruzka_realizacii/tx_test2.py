"""Транзакційний тест (відкат): два завантаження поспіль -> вкладень не більшає (вихідний файл не дублюється, журнал
один і оновлюється), журнал: «Завантажень» = 2, автопідбір із першого завантаження, виправлення бухгалтера видно."""
import sys
import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
EPF = sys.argv[1]
c = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = c.String
q = c.NewObject("Запрос")
q.Текст = 'ВЫБРАТЬ Д.Ссылка КАК С ИЗ Документ.РеализацияТоваровУслуг КАК Д ГДЕ Д.Номер = "ІБ00-000189"'
док = q.Execute().Выгрузить().Получить(0).С
ФАЙЛ = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\temp\Специфікація з АСУБЗ.xls"


def вкладення():
    q3 = c.NewObject("Запрос")
    q3.Текст = """ВЫБРАТЬ Ф.Ссылка КАК С, Ф.Наименование КАК Н, Ф.Расширение КАК Р, Ф.Описание КАК О
    ИЗ Справочник.РеализацияТоваровУслугПрисоединенныеФайлы КАК Ф ГДЕ Ф.ВладелецФайла = &Д И НЕ Ф.ПометкаУдаления"""
    q3.SetParameter("Д", док)
    ф = q3.Execute().Выгрузить()
    return [(ф.Получить(i).С, S(ф.Получить(i).Н), S(ф.Получить(i).Р), S(ф.Получить(i).О)) for i in range(ф.Количество())]


def товари():
    q2 = c.NewObject("Запрос")
    q2.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(Т.НомерСтроки) КАК Р, ЕСТЬNULL(СУММА(Т.Сумма), 0) КАК Сум ИЗ Документ.РеализацияТоваровУслуг.Товары КАК Т ГДЕ Т.Ссылка = &Д"
    q2.SetParameter("Д", док)
    r = q2.Execute().Выгрузить().Получить(0)
    return int(r.Р), S(r.Сум)


def журнал(ссылка):
    дані = c.РаботаСФайлами.ДвоичныеДанныеФайла(ссылка)
    імя = c.ПолучитьИмяВременногоФайла("xlsx")
    дані.Записать(імя)
    таб = c.NewObject("ТабличныйДокумент")
    таб.Прочитать(імя)
    т = lambda r, k: S(таб.Область(r, k, r, k).Текст)
    return таб.ВысотаТаблицы, [т(1, k) for k in range(1, 22)], {т(r, 1): [т(r, k) for k in range(1, 22)] for r in range(2, таб.ВысотаТаблицы + 1)}


до = вкладення()
print("ДО: товари", товари(), "вкладень", len(до))
обр = c.ВнешниеОбработки.Создать(EPF, False)
обр.ЗаполнитьНастройки(док)
print("ОчиститьТовары за замовчуванням:", S(обр.ОчиститьТовары))
адреса = c.PutToTempStorage(c.NewObject("ДвоичныеДанные", ФАЙЛ))
р = обр.ПрочитатьИСопоставить(адреса, "Специфікація з АСУБЗ.xls")
print("ИтогФайла:", S(р.ИтогФайла))
т = р.Таблица
for i in range(т.Количество()):
    x = т.Получить(i)
    if S(x.Номенклатура) and (x.Подтверждено or int(x.Сходство) >= 85):
        x.Подтверждено = True
помилки = []
c.BeginTransaction()
try:
    р1 = обр.ЗагрузитьВДокумент(т, адреса, "Специфікація з АСУБЗ.xls")
    п1 = вкладення()
    print("1-ше: помилка", S(р1.Ошибка) or "-", "| рядків", S(р1.Строк), "| товари", товари(), "| вкладень", len(п1),
          "| попередження:", S(р1.Предупреждения)[:150] or "-")
    # бухгалтер міняє рядок 3 на інший варіант і завантажує вдруге
    x = т.Получить(1)
    варіанти = [р.Варианты.Получить(i) for i in range(р.Варианты.Количество()) if int(р.Варианты.Получить(i).НомерСтроки) == int(x.НомерСтроки)]
    x.Номенклатура = варіанти[1].Номенклатура
    x.Подтверждено = True
    x.Способ = "Вибрано вручну"
    р2 = обр.ЗагрузитьВДокумент(т, адреса, "Специфікація з АСУБЗ.xls")
    п2 = вкладення()
    print("2-ге: помилка", S(р2.Ошибка) or "-", "| рядків", S(р2.Строк), "| товари", товари(), "| вкладень", len(п2))
    нові = [в for в in п2 if в[1] not in {д[1] for д in до}]
    for в in нові:
        print("   нове вкладення:", в[1], в[2], "|", в[3][:140])
    if len(п2) != len(п1):
        помилки.append("друге завантаження додало вкладення")
    if len(п1) - len(до) > 1:
        помилки.append("перше завантаження додало більше 1 вкладення (вихідний файл уже був)")
    жур = [в for в in п2 if в[1] == "Журнал зіставлення Специфікація з АСУБЗ"]
    if len(жур) != 1:
        помилки.append(f"журналів нового формату {len(жур)}")
    else:
        висота, заголовки, рядки = журнал(жур[0][0])
        print("   журнал: рядків", висота - 1, "| колонок", sum(1 for z in заголовки if z))
        р3 = рядки.get("3")
        print("   рядок 3: авто", р3[6][:40], р3[7], "| обрано", р3[10][:40], р3[11], "| виправлено", р3[14], "| завантажень", р3[19], "| перше", р3[20])
        if р3[19] != "2":
            помилки.append("Завантажень ≠ 2")
        if р3[14] != "так" or р3[7] == р3[11]:
            помилки.append("виправлення бухгалтера не видно")
        if not р3[20]:
            помилки.append("немає дати першого завантаження")
finally:
    c.RollbackTransaction()
print("ПІСЛЯ ВІДКАТУ: товари", товари(), "вкладень", len(вкладення()))
print("ПОМИЛКИ:", помилки or "немає")
