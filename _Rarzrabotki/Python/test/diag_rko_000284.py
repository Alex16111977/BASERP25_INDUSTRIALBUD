# -*- coding: utf-8 -*-
"""Детальна діагностика тестового РКО №000Ц-000284 від 31.12.2025 на 22 575 UAH.

Завдання:
1. Знайти документ за номером
2. Показати всі поля шапки і ТЧ (особливо РасшифровкаПлатежа + ВыплатаЗП)
3. Подивитись усі рухи ПАП → який саме блок дав ОТ
4. Знайти ФизЛице (можливо в РасшифровкеПлатежа)
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Шукаємо за номером
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Д
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
ГДЕ Д.Номер = &Н
"""
q.УстановитьПараметр("Н", "000Ц-000284")
r = q.Выполнить().Выбрать()
if not r.Следующий():
    print("FAIL: Не знайдено")
    sys.exit(1)
ref = r.Д
obj = ref.ПолучитьОбъект()
S = conn.String  # shortcut
print(f"[DOC] №{obj.Номер.strip()} від {obj.Дата} на {obj.СуммаДокумента} {S(obj.Валюта)}")
print(f"      ХозОп                 = {S(obj.ХозяйственнаяОперация)}")
print(f"      Подразделение         = {S(obj.Подразделение)}")
print(f"      А_Подразделение       = {S(obj.А_Подразделение)}")
print(f"      Ведомость             = {S(obj.Ведомость)}")
print(f"      Контрагент            = {S(obj.Контрагент)}")
print(f"      ПодотчетноеЛицо       = {S(obj.ПодотчетноеЛицо)}")
print(f"      Партнер               = {S(obj.Партнер)}")
print(f"      ВыплатаЗП рядків      = {obj.ВыплатаЗаработнойПлаты.Количество()}")
print(f"      РасшифПлатежа рядків  = {obj.РасшифровкаПлатежа.Количество()}")

# ТЧ ВыплатаЗП
if obj.ВыплатаЗаработнойПлаты.Количество() > 0:
    print(f"\n[ТЧ ВыплатаЗаработнойПлаты]")
    for i in range(obj.ВыплатаЗаработнойПлаты.Количество()):
        s = obj.ВыплатаЗаработнойПлаты.Получить(i)
        print(f"  ФЛ={S(s.ФизическоеЛицо)}, Сумма={s.Сумма}, ГрУчета={S(s.ГруппаУчетаНачислений)}")

# ТЧ РасшифровкаПлатежа — повний вивід
print(f"\n[ТЧ РасшифровкаПлатежа]")
for i in range(obj.РасшифровкаПлатежа.Количество()):
    s = obj.РасшифровкаПлатежа.Получить(i)
    print(f"  --- Рядок {i+1} ---")
    print(f"    Сумма                = {s.Сумма}")
    print(f"    Подразделение        = {s.Подразделение}")
    print(f"    СтатьяДвиженияДС     = {s.СтатьяДвиженияДенежныхСредств}")
    print(f"    СтатьяРасходов       = {s.СтатьяРасходов}")
    print(f"    АналитикаАктПас      = {s.АналитикаАктивовПассивов}")
    print(f"    АналитикаРасходов    = {s.АналитикаРасходов}")
    print(f"    НаправлениеДеят      = {s.НаправлениеДеятельности}")
    print(f"    Партнер              = {s.Партнер}")
    print(f"    Заявка               = {s.ЗаявкаНаРасходованиеДенежныхСредств}")
    print(f"    ОбъектРасчетов       = {s.ОбъектРасчетов}")
    print(f"    Организация          = {s.Организация}")
    print(f"    ДоговорКредитаДепоз  = {s.ДоговорКредитаДепозита}")
    print(f"    ДоговорЛизинга       = {s.ДоговорЛизинга}")
    print(f"    ДоговорЗаймаСотр     = {s.ДоговорЗаймаСотруднику}")
    print(f"    СчетУчета            = {s.СчетУчета}")
    print(f"    Субконто1            = {s.Субконто1}")
    print(f"    Субконто2            = {s.Субконто2}")
    print(f"    Субконто3            = {s.Субконто3}")
    print(f"    Комментарий          = {s.Комментарий}")

# Рухи ПАП — детально
print(f"\n[Рухи ПАП(ОТ) для цього РКО]")
qP = conn.NewObject("Запрос")
qP.Текст = """
ВЫБРАТЬ
    П.Период, П.ВидДвижения, П.Сумма,
    П.Организация, П.Подразделение,
    П.НаправлениеДеятельности, П.Статья, П.Аналитика, П.Источник
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК П
ГДЕ П.Регистратор = &Док
УПОРЯДОЧИТЬ ПО П.Период
"""
qP.УстановитьПараметр("Док", ref)
res_p = qP.Выполнить().Выгрузить()
print(f"  Усього рухів: {res_p.Количество()}")
for i in range(res_p.Количество()):
    rec = res_p.Получить(i)
    print(f"    {S(rec.ВидДвижения)} {rec.Сумма:>12,.2f} | Ист={S(rec.Источник)} | Стаття={S(rec.Статья)} | Подразд={S(rec.Подразделение)} | НапрДеят={S(rec.НаправлениеДеятельности)} | Аналит={S(rec.Аналитика)}")
