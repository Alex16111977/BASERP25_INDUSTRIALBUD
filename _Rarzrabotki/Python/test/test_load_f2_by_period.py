# -*- coding: utf-8 -*-
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="kazna";Usr="cfo";Pwd="2442"')
S = conn.String

# Тестуємо запит з плану: фільтр по КассаДатаС/КассаДатаПо
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ
    БДДС.Подразделение.Код КАК ПодразделениеКод,
    БДДС.СтатьяДвиженияДенежныхСредств.Код КАК СтатьяКод,
    БДДС.СтатьяДвиженияДенежныхСредств.Наименование КАК СтатьяНаим,
    БДДС.Направление.Код КАК НаправлениеКод,
    БДДС.Сотрудник.ИНН КАК СотрудникИНН,
    БДДС.Сотрудник.Наименование КАК СотрудникФИО,
    БДДС.Сотрудник.Код КАК СотрудникКод,
    СУММА(БДДС.Сумма) КАК Сумма,
    БДДС.Регистратор КАК Регистратор,
    БДДС.Регистратор.Организация.ЕГРПОУ КАК ОрганизацияЕГРПОУ,
    БДДС.Регистратор.Номер КАК НомерДокумента,
    ВЫБОР
        КОГДА БДДС.Регистратор ССЫЛКА Документ.РаспределениеЗаработнойПлаты
            ТОГДА "А_РаспределениеЗаработнойПлаты"
        ИНАЧЕ "РаспределениеФ2"
    КОНЕЦ КАК ВидДокумента
ИЗ
    РегистрНакопления.БДДС КАК БДДС
ГДЕ
    (
        (БДДС.Регистратор ССЫЛКА Документ.РаспределениеЗаработнойПлаты
            И БДДС.Регистратор.КассаДатаС >= &НачПериода
            И БДДС.Регистратор.КассаДатаПо <= &КонПериода
            И БДДС.Регистратор.Организация.А_ПереносЕРП)
        ИЛИ
        (БДДС.Регистратор ССЫЛКА Документ.РаспределениеФ2
            И БДДС.Регистратор.КассаДатаС >= &НачПериода
            И БДДС.Регистратор.КассаДатаПо <= &КонПериода)
    )
СГРУППИРОВАТЬ ПО
    БДДС.Подразделение.Код,
    БДДС.СтатьяДвиженияДенежныхСредств.Код,
    БДДС.СтатьяДвиженияДенежныхСредств.Наименование,
    БДДС.Направление.Код,
    БДДС.Сотрудник.ИНН,
    БДДС.Сотрудник.Наименование,
    БДДС.Сотрудник.Код,
    БДДС.Регистратор,
    БДДС.Регистратор.Организация.ЕГРПОУ,
    БДДС.Регистратор.Номер,
    ВЫБОР
        КОГДА БДДС.Регистратор ССЫЛКА Документ.РаспределениеЗаработнойПлаты
            ТОГДА "А_РаспределениеЗаработнойПлаты"
        ИНАЧЕ "РаспределениеФ2"
    КОНЕЦ"""

q.SetParameter("НачПериода", datetime.datetime(2025, 12, 1))
q.SetParameter("КонПериода", datetime.datetime(2025, 12, 31, 23, 59, 59))

res = q.Execute()
sel = res.Choose()

# Статистика по документам
docs = {}  # (Вид, Номер) -> total sum
stetsuk_rows = []
cnt = 0
while sel.Next():
    cnt += 1
    key = (S(sel.ВидДокумента), S(sel.НомерДокумента))
    if key not in docs:
        docs[key] = 0
    docs[key] += float(S(sel.Сумма).replace('\xa0', '').replace(' ', '').replace(',', '.'))

    fio = S(sel.СотрудникФИО).strip()
    if "Стецюк" in fio:
        stetsuk_rows.append({
            "стаття": S(sel.СтатьяНаим)[:40],
            "подр": S(sel.ПодразделениеКод),
            "сум": float(S(sel.Сумма).replace('\xa0', '').replace(' ', '').replace(',', '.')),
            "рег": S(sel.Регистратор),
        })

print(f"Всього записів: {cnt}")
print(f"\n=== Документи-реєстратори ===")
for (вид, ном), сум in sorted(docs.items()):
    print(f"  {вид:35s} №{ном:15s} = {сум:.2f}")

print(f"\n=== Стецюк за грудень 2025 ===")
for r in stetsuk_rows:
    print(f"  {r['рег'][:60]:60s} Стаття={r['стаття'][:35]:35s} Підр={r['подр']:10s} Сум={r['сум']:.2f}")

total_stetsuk = sum(r['сум'] for r in stetsuk_rows)
print(f"\n  РАЗОМ Стецюк: {total_stetsuk:.2f}")
print(f"  Очікувалось: ~36,046 (без ф2 028 = листопад)")

# Перевірка що ф2 №28 НЕ потрапив
has_028 = any("000000028" in k[1] and "Ф2" in k[0] for k in docs.keys())
has_033 = any("000000033" in k[1] and "Ф2" in k[0] for k in docs.keys())
has_268 = any("000000268" in k[1] and "Заработной" in k[0] for k in docs.keys())

print(f"\n=== Перевірка фільтру ===")
print(f"  ф2 №28 (листопад, НЕ має бути): {'ЗНАЙДЕНО ❌' if has_028 else 'OK ✅'}")
print(f"  ф2 №33 (грудень, має бути):     {'OK ✅' if has_033 else 'НЕ ЗНАЙДЕНО ❌'}")
print(f"  ЗП №268 (грудень, має бути):    {'OK ✅' if has_268 else 'НЕ ЗНАЙДЕНО ❌'}")
