import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# 1) Свод ПАП по типу налога: Приход/Расход + по типу регистратора
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    ПАП.Статья КАК Статья,
    ПАП.Аналитика КАК Аналитика,
    ПАП.Источник КАК Источник,
    ПАП.ВидИсточника КАК ВидИсточника,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Приход,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) ТОГДА ПАП.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Расход,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ПАП.Подразделение) КАК ЧислоПодр
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ
    ПАП.Период МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
    И ТИПЗНАЧЕНИЯ(ПАП.Аналитика) = ТИП(Перечисление.ТипыНалогов)
СГРУППИРОВАТЬ ПО
    ПАП.Статья, ПАП.Аналитика, ПАП.Источник, ПАП.ВидИсточника
УПОРЯДОЧИТЬ ПО Аналитика
"""
r = q.Execute().Выгрузить()
print("=== ERP ПАП налоги: свод по тип налога / регистратор / источник ===")
for i in range(r.Количество()):
    s = r.Получить(i)
    ст = str(s.Статья.Наименование) if not s.Статья.Пустая() else "-"
    ан = erp.XMLСтрока(s.Аналитика) if s.Аналитика else "-"
    ист = erp.XMLСтрока(s.Источник) if s.Источник else "(пусто)"
    ви = erp.XMLСтрока(s.ВидИсточника) if s.ВидИсточника else "(пусто)"
    print(f"СТ={ст[:14]:<14}|АН={ан[:16]:<16}|ИСТ={ист[:20]:<20}|ВИ={ви[:16]:<16}|подр={int(s.ЧислоПодр):>4}|Прих={s.Приход:>16,.2f}|Расх={s.Расход:>16,.2f}")

# 2) Статья "Налоги" - точное имя ПВХ + предопределённость
print("\n=== Статья ПВХ.СтатьиАктивовПассивов 'Налоги' ===")
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ Ст.Ссылка КАК С, Ст.Наименование КАК Наим, Ст.Код КАК Код, Ст.ХозяйственнаяОперация КАК ХО
ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК Ст
ГДЕ Ст.Наименование ПОДОБНО "%алог%"
"""
r2 = q2.Execute().Выгрузить()
for i in range(r2.Количество()):
    s = r2.Получить(i)
    хо = erp.XMLСтрока(s.ХО) if s.ХО else "-"
    print(f"  Код={str(s.Код):<8} | Наим={str(s.Наим):<28} | ХозОп={хо}")
