# -*- coding: utf-8 -*-
"""
Тест запросов обработки АнализРегистраторРасчетов.
Проверяет что запрос находит задвоенные РегистраторыРасчетов.
"""
import win32com.client
import sys

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

print("Connecting to BaseERP...")
conn = v8.Connect(CONN_ERP)
print("OK\n")

query = conn.NewObject("Запрос")

# === Тест 1: Запрос по Поставщикам ===
print("=" * 60)
print("Тест 1: Дубли РегистраторРасчетов по ПОСТАВЩИКАМ")
print("=" * 60)

query.Text = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ДокументРегистратор) КАК Источник,
    Р.ДокументРегистратор.Дата КАК ДатаИсточника,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.Регистратор) КАК КолРегистраторов,
    СУММА(Р.ДолгРегл) КАК СуммаДолг,
    СУММА(Р.ПредоплатаРегл) КАК СуммаПредоплата
ИЗ
    РегистрНакопления.РасчетыСПоставщикамиПоСрокам КАК Р
ГДЕ
    Р.Период >= ДАТАВРЕМЯ(2025,12,1)
    И Р.Период <= ДАТАВРЕМЯ(2026,4,1)
    И Р.Регистратор ССЫЛКА Документ.РегистраторРасчетов
СГРУППИРОВАТЬ ПО
    Р.ДокументРегистратор,
    Р.ДокументРегистратор.Дата
ИМЕЮЩИЕ
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.Регистратор) > 1
УПОРЯДОЧИТЬ ПО
    ДатаИсточника
"""

result = query.Execute().Выбрать()
count = 0
while result.Следующий():
    count += 1
    print(f"  {count}. {result.Источник}")
    print(f"     Дата: {result.ДатаИсточника}, Регистраторов: {result.КолРегистраторов}")
    print(f"     Долг: {result.СуммаДолг}, Предоплата: {result.СуммаПредоплата}")

print(f"\nИтого поставщики: {count} документов с дублями")

# === Тест 2: Запрос по Клиентам ===
print("\n" + "=" * 60)
print("Тест 2: Дубли РегистраторРасчетов по КЛИЕНТАМ")
print("=" * 60)

query.Text = """
ВЫБРАТЬ
    ПРЕДСТАВЛЕНИЕ(Р.ДокументРегистратор) КАК Источник,
    Р.ДокументРегистратор.Дата КАК ДатаИсточника,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.Регистратор) КАК КолРегистраторов,
    СУММА(Р.ДолгРегл) КАК СуммаДолг,
    СУММА(Р.ПредоплатаРегл) КАК СуммаПредоплата
ИЗ
    РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
ГДЕ
    Р.Период >= ДАТАВРЕМЯ(2025,12,1)
    И Р.Период <= ДАТАВРЕМЯ(2026,4,1)
    И Р.Регистратор ССЫЛКА Документ.РегистраторРасчетов
СГРУППИРОВАТЬ ПО
    Р.ДокументРегистратор,
    Р.ДокументРегистратор.Дата
ИМЕЮЩИЕ
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.Регистратор) > 1
УПОРЯДОЧИТЬ ПО
    ДатаИсточника
"""

result = query.Execute().Выбрать()
count2 = 0
while result.Следующий():
    count2 += 1
    print(f"  {count2}. {result.Источник}")
    print(f"     Дата: {result.ДатаИсточника}, Регистраторов: {result.КолРегистраторов}")
    print(f"     Долг: {result.СуммаДолг}, Предоплата: {result.СуммаПредоплата}")

print(f"\nИтого клиенты: {count2} документов с дублями")

# === Тест 3: Проверка битых ссылок (осиротевших) ===
print("\n" + "=" * 60)
print("Тест 3: Осиротевшие записи (битые ссылки на РегистраторРасчетов)")
print("=" * 60)

registers = [
    "РасчетыСПоставщикамиПоСрокам",
    "РасчетыСКлиентамиПоСрокам",
    "РасчетыСПоставщикамиПланОплат",
    "РасчетыСКлиентамиПланОплат",
    "РасчетыСКлиентамиПланОтгрузок",
    "РасчетыСПоставщикамиПланПоставок",
]

for reg in registers:
    query.Text = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрНакопления.{reg} ГДЕ Регистратор.Ссылка ЕСТЬ NULL"
    try:
        result = query.Execute().Выбрать()
        result.Следующий()
        kol = result.Кол
        status = "БИТЫХ" if kol > 0 else "OK"
        print(f"  {reg}: {kol} {status}")
    except Exception as e:
        print(f"  {reg}: ОШИБКА - {str(e)[:80]}")

print(f"\n{'=' * 60}")
print(f"ИТОГО: поставщики={count}, клиенты={count2} документов с дублями")
print(f"{'=' * 60}")
