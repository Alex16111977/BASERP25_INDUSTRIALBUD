# -*- coding: utf-8 -*-
# E2E throwaway: эмулирует логику СоздатьДокументы (ПАП агрегат + бухучёт построчно с субконто Вставить),
# пишет оба документа на дате 2099, проверяет движения, удаляет.
import win32com.client, sys, datetime
sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

ДатаДок = datetime.datetime(2099, 12, 26, 23, 59, 59)

def тип_налога_по_счету(kod):
    kod = str(kod).strip()
    m = {'6411':'НДФЛ','642':'ВоенныйСбор','651':'НачисленныйЕСВ','6412':'НДС',
         '6413':'НалогНаПрибыль','6414':'ЕдиныйНалог'}
    name = m.get(kod, 'ДругиеНалоги')
    return getattr(erp.Перечисления.ТипыНалогов, name)

def заполнить_субконто(коллекция, счет, наим):
    if not erp.ЗначениеЗаполнено(счет): return
    o = счет.ПолучитьОбъект()
    for vs in o.ВидыСубконто:
        вид = vs.ВидСубконто
        tz = вид.ТипЗначения
        is_nalogi = any(erp.String(t) == 'Налоги' for t in tz.Типы())
        if is_nalogi and наим and str(наим).strip() and str(наим) != 'None':
            el = erp.Справочники.Налоги.НайтиПоНаименованию(str(наим).strip())
            if erp.ЗначениеЗаполнено(el):
                коллекция.Вставить(вид, el)

# Тестовый набор строк (как ТЧ Налоги): несколько счетов и знаков
selO = erp.NewObject('Запрос')
selO.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Орг.Ссылка КАК С ИЗ Справочник.Организации КАК Орг ГДЕ Орг.А_ВБалансе'
Орг = selO.Выполнить().Выгрузить().Получить(0).С
Подр = Орг.А_ПодразделениеЗарплатаБух
pscht = erp.ПланыСчетов.Хозрасчетный

строки = [
    # (КодСчета, ВидНалогаНаим, Сальдо)
    ('6411', 'ПДФО',                    -12141.65),  # НДФЛ, переплата (Дт), без субконто
    ('651',  'ЕСВ ФОТ (работники)',     -21528.07),  # ЕСВ переплата, субконто Налоги
    ('651',  'ЕСВ ФОТ (по договорам ГПХ)', 5331.86), # ЕСВ долг (Кт), субконто Налоги
    ('642',  'Военный сбор',            -383.77),     # ВС переплата, субконто Налоги
    ('6413', 'None',                    1643480.14),  # НалПриб долг, субконто Статьи деклараций (пусто)
]
налоги = []
for kod, naim, summ in строки:
    налоги.append({
        'Орг': Орг, 'КодСчета': kod, 'Счет': pscht.НайтиПоКоду(kod),
        'ТипНалога': тип_налога_по_счету(kod), 'Подр': Подр,
        'ВидНалогаНаим': naim, 'Сальдо': summ
    })

# ===== 1) ПАП агрегат =====
докКР = erp.Документы.КорректировкаРегистров.СоздатьДокумент()
докКР.Дата = ДатаДок
докКР.Операция = erp.Перечисления.ОперацииКорректировкиРегистров.РучнаяКорректировка
докКР.Комментарий = 'E2E TW NALOGI'
докКР.ТаблицаРегистров.Добавить().Имя = 'ПрочиеАктивыПассивы'
нпап = докКР.Движения.ПрочиеАктивыПассивы; нпап.Записывать = True

# агрегация по (Орг, Подр, ТипНалога)
агр = {}
for r in налоги:
    key = (erp.String(r['Орг']), erp.String(r['Подр']), erp.String(r['ТипНалога']))
    агр.setdefault(key, {'Орг':r['Орг'],'Подр':r['Подр'],'Тип':r['ТипНалога'],'Σ':0.0})
    агр[key]['Σ'] += r['Сальдо']

for v in агр.values():
    if v['Σ'] == 0: continue
    абс = abs(v['Σ'])
    дв = нпап.Добавить()
    дв.Период = ДатаДок; дв.Активность = True
    дв.ВидДвижения = erp.ВидДвиженияНакопления.Приход if v['Σ']>0 else erp.ВидДвиженияНакопления.Расход
    дв.Организация = v['Орг']; дв.Подразделение = v['Подр']
    дв.Статья = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.Налоги
    дв.Аналитика = v['Тип']
    дв.Источник = erp.Перечисления.ИсточникиУправленческогоБаланса.ПустаяСсылка()
    дв.ВидИсточника = erp.Перечисления.ВидыИсточниковДвижений.ПустаяСсылка()
    дв.Сумма = абс

докКР.Записать(erp.РежимЗаписиДокумента.Запись)
print('ПАП документ записан:', erp.String(докКР.Ссылка))

# проверка ПАП
qp = erp.NewObject('Запрос')
qp.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(ПАП.Аналитика) КАК Ан, ПАП.ВидДвижения КАК ВД, ПАП.Сумма КАК С,
ПРЕДСТАВЛЕНИЕ(ПАП.Статья) КАК Ст, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК Подр
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП ГДЕ ПАП.Регистратор=&Р"""
qp.УстановитьПараметр('Р', докКР.Ссылка)
rp = qp.Выполнить().Выгрузить()
print('Движений ПАП:', rp.Количество())
for i in range(rp.Количество()):
    r = rp.Получить(i)
    print('   Статья=', r.Ст, '| Аналитика=', r.Ан, '| ВидДв=', erp.String(r.ВД), '| Подр=', r.Подр, '| Σ=', r.С)

# ===== 2) Хозрасчетный построчно =====
докОБ = erp.Документы.ОперацияБух.СоздатьДокумент()
докОБ.Дата = ДатаДок; докОБ.Организация = Орг; докОБ.Комментарий = 'E2E TW NALOGI'
нхр = докОБ.Движения.Хозрасчетный; нхр.Записывать = True
Счет00 = pscht.НайтиПоКоду('00')
for r in налоги:
    if r['Сальдо'] == 0 or not erp.ЗначениеЗаполнено(r['Счет']): continue
    абс = abs(r['Сальдо'])
    д = нхр.Добавить()
    д.Период = ДатаДок; д.Активность = True; д.Организация = r['Орг']
    д.Содержание = 'Ввод начального остатка по налогам'
    if r['Сальдо'] > 0:
        д.СчетДт = Счет00; д.СчетКт = r['Счет']
        заполнить_субконто(д.СубконтоКт, r['Счет'], r['ВидНалогаНаим'])
    else:
        д.СчетДт = r['Счет']; д.СчетКт = Счет00
        заполнить_субконто(д.СубконтоДт, r['Счет'], r['ВидНалогаНаим'])
    д.Сумма = абс

докОБ.Записать(erp.РежимЗаписиДокумента.Проведение)
print('\nОперацияБух проведён:', erp.String(докОБ.Ссылка), '| Проведен=', докОБ.Проведен)

# проверка проводок + субконто (через набор записей)
рс = erp.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
рс.Отбор.Регистратор.Установить(докОБ.Ссылка)
рс.Прочитать()
print('Проводок Хозрасчетного:', рс.Количество())
for i in range(рс.Количество()):
    зап = рс.Получить(i)
    субД = '; '.join(erp.String(p.Ключ)+'='+(erp.String(p.Значение) if erp.ЗначениеЗаполнено(p.Значение) else 'пусто') for p in зап.СубконтоДт)
    субК = '; '.join(erp.String(p.Ключ)+'='+(erp.String(p.Значение) if erp.ЗначениеЗаполнено(p.Значение) else 'пусто') for p in зап.СубконтоКт)
    print(f'   Дт{erp.String(зап.СчетДт.Код)} [{субД}] / Кт{erp.String(зап.СчетКт.Код)} [{субК}] | Σ={зап.Сумма}')

# ===== чистка =====
for d in (докОБ, докКР):
    o = d.Ссылка.ПолучитьОбъект(); o.ОбменДанными.Загрузка = True; o.Удалить()
print('\nОба throwaway-документа удалены.')
