def run_query(erp, text, params=None, label=""):
    q = erp.NewObject("Запрос")
    q.Text = text
    if params:
        for k, v in params.items():
            q.SetParameter(k, v)
    try:
        return q.Execute().Выгрузить()
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        # Encode in cp1251 for Cyrillic readability in cmd
        try:
            msg_str = str(msg)
        except Exception:
            msg_str = "<unprintable>"
        raise RuntimeError(f"FAIL [{label}]: {msg_str}")


