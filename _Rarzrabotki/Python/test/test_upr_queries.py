# -*- coding: utf-8 -*-
"""Rule #-1: проверка запросов отчёта А_ОтчетПоСписаниюНаПроизводствоУправленческий
на живой BaseERP ДО переноса в BSL. Запросы 1:1 с будущим модулем."""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

ОШИБОК = 0

def провал(текст):
    global ОШИБОК
    ОШИБОК += 1
    print("FAIL:", текст)

def выполнить(текст_запроса, параметры=None):
    q = erp.NewObject("Запрос")
    q.Текст = текст_запроса
    for имя, знач in (параметры or {}).items():
        q.УстановитьПараметр(имя, знач)
    return q.Выполнить().Выгрузить()

# --- границы периода получаем ИЗ 1С (сдвиги COM-дат не мешают) ---
q = erp.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,1,1,0,0,0) КАК Н, ДАТАВРЕМЯ(2026,8,31,23,59,59) КАК К"
границы = q.Выполнить().Выгрузить().Получить(0)
НачП, КонП = границы.Н, границы.К

# === Запрос 1: драйверы (копия донора, регресс) ===
Q_DRIVERS = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	ВЫБОР
		КОГДА СС.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА СС.ПодразделениеОбъекта
		ИНАЧЕ СС.Подразделение
	КОНЕЦ КАК Драйвер
ИЗ
	Справочник.А_СтруктураСебестоимости КАК СС
ГДЕ
	НЕ СС.ЭтоГруппа
	И СС.Активная
	И ВЫБОР
		КОГДА СС.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА СС.ПодразделениеОбъекта
		ИНАЧЕ СС.Подразделение
	КОНЕЦ <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
"""
драйверы = выполнить(Q_DRIVERS)
print("Драйверов:", драйверы.Количество())
if драйверы.Количество() == 0:
    провал("нет драйверов")

# === Запрос 2: факт списания по драйверу (НОВЫЙ: без плановой ветки, с ВТ) ===
Q_FAKT = """
ВЫБРАТЬ
	СТ.Подразделение КАК ПодразделениеИсполнитель,
	СТ.АналитикаУчетаНоменклатуры.Номенклатура.А_ОбщееНазваниеНоменклатуры КАК ОбщееНазвание,
	СТ.АналитикаУчетаНоменклатуры.Номенклатура КАК Аналитика,
	СТ.АналитикаУчетаНоменклатуры.Номенклатура.Наименование КАК НоменклатураНаименование,
	СТ.АналитикаУчетаНоменклатуры.Номенклатура.ЕдиницаИзмерения КАК Единица,
	СТ.Регистратор КАК Документ,
	ВЫРАЗИТЬ(ВЫБОР
		КОГДА ТИПЗНАЧЕНИЯ(СТ.Регистратор) = ТИП(Документ.СборкаТоваров)
			ТОГДА "1. Комплектація"
		ИНАЧЕ "2. Внутрішнє споживання"
	КОНЕЦ КАК СТРОКА(50)) КАК ВидДокумента,
	СТ.Количество КАК Количество,
	СТ.Стоимость КАК СуммаСоб
ПОМЕСТИТЬ ВТ_Факт
ИЗ
	РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ
	СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
	И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
	И СТ.Период МЕЖДУ &НачП И &КонП
	И ТИПЗНАЧЕНИЯ(СТ.Регистратор) В (ТИП(Документ.СборкаТоваров), ТИП(Документ.ВнутреннееПотреблениеТоваров))
	И СТ.Подразделение В ИЕРАРХИИ (&Драйвер)
;
ВЫБРАТЬ
	&Драйвер КАК Подразделение,
	Ф.ПодразделениеИсполнитель КАК ПодразделениеИсполнитель,
	Ф.ОбщееНазвание КАК ОбщееНазвание,
	Ф.Аналитика КАК Аналитика,
	Ф.НоменклатураНаименование КАК НоменклатураНаименование,
	Ф.Единица КАК Единица,
	Ф.Документ КАК Документ,
	Ф.ВидДокумента КАК ВидДокумента,
	СУММА(Ф.Количество) КАК Количество,
	СУММА(Ф.СуммаСоб) КАК СуммаСоб
ИЗ
	ВТ_Факт КАК Ф
СГРУППИРОВАТЬ ПО
	Ф.ПодразделениеИсполнитель,
	Ф.ОбщееНазвание,
	Ф.Аналитика,
	Ф.НоменклатураНаименование,
	Ф.Единица,
	Ф.Документ,
	Ф.ВидДокумента
"""

# === Запрос 3: карты СС по драйверу (НОВЫЙ: этапы первым вхождением + цены) ===
Q_KARTY = """
ВЫБРАТЬ
	К.Ссылка.Наименование КАК ИмяСС,
	К.НомерСтроки КАК НомерСтроки,
	ЕСТЬNULL(ВЫБОР
		КОГДА К.Номенклатура = ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
			ТОГДА К.ОбщееНазвание.Наименование
		ИНАЧЕ К.Номенклатура.А_ОбщееНазваниеНоменклатуры.Наименование
	КОНЕЦ, "") КАК ИмяНазвы,
	К.Этап КАК Этап,
	ЕСТЬNULL(К.Единица.Наименование, "") КАК ИмяЕдиницы,
	К.Количество КАК Количество,
	К.Сумма КАК Сумма
ИЗ
	Справочник.А_СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Активная
	И НЕ К.Ссылка.ЭтоГруппа
	И ВЫБОР
		КОГДА К.Ссылка.ПодразделениеОбъекта <> ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)
			ТОГДА К.Ссылка.ПодразделениеОбъекта
		ИНАЧЕ К.Ссылка.Подразделение
	КОНЕЦ = &Драйвер
УПОРЯДОЧИТЬ ПО
	ИмяСС,
	НомерСтроки
"""

итого_кол = 0.0
итого_сумма = 0.0
for i in range(драйверы.Количество()):
    драйвер = драйверы.Получить(i).Драйвер
    имя_драйвера = erp.String(драйвер)

    факт = выполнить(Q_FAKT, {"Драйвер": драйвер, "НачП": НачП, "КонП": КонП})
    кол = sum(факт.Получить(r).Количество for r in range(факт.Количество()))
    сум = sum(факт.Получить(r).СуммаСоб for r in range(факт.Количество()))
    итого_кол += кол
    итого_сумма += сум

    карты = выполнить(Q_KARTY, {"Драйвер": драйвер})

    # эмуляция построения карты этапов: ключ -> этап первого вхождения
    этапы = {}
    номера_этапов = {}
    счетчик = 0
    for r in range(карты.Количество()):
        стр = карты.Получить(r)
        ключ = str(стр.ИмяНазвы).strip().upper()
        имя_этапа = erp.String(стр.Этап)
        if not ключ or not имя_этапа:
            continue
        if имя_этапа not in номера_этапов:
            счетчик += 1
            номера_этапов[имя_этапа] = счетчик
        if ключ not in этапы:
            этапы[ключ] = имя_этапа
    print(f"  {имя_драйвера}: факт строк={факт.Количество()} кол={кол:.3f} сумма={сум:.2f}; "
          f"ТЧ строк={карты.Количество()} назв в карте={len(этапы)} этапов={счетчик}")
    if карты.Количество() > 0 and счетчик == 0:
        print(f"  WARN: у драйвера {имя_драйвера} ни одного этапа в СС (весь факт уйдёт в Позапланово)")

print(f"ИТОГО факт: кол={итого_кол:.3f} сумма={итого_сумма:.2f}")
print("РЕЗУЛЬТАТ:", "OK" if ОШИБОК == 0 else f"ОШИБОК={ОШИБОК}")
sys.exit(0 if ОШИБОК == 0 else 1)
