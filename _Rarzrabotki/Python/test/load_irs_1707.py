def норм(s):
    return re.sub(r"\s+", " ", str(s or "").strip().lower().replace("'", "").replace("’", ""))

def факт_текст(value, nf):
    """Текст факта как отображает Excel: строки — как есть; числовые %-ячейки -> 'P%' (0,5 -> '50%')."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return ""
    if isinstance(value, (int, float)):
        if "%" in (nf or ""):
            return f"{value*100:g}%"
        return f"{value:g}"
    return str(value).strip()

def читать_файл(path):
    """Один лист-снимок «ЗВіт …» -> (имя, [(наименование, текст_факта)])."""
    wb = openpyxl.load_workbook(path, data_only=True)
    for имя in wb.sheetnames:
        h = имя.strip().lower()
        if not h.startswith("звіт") or h == "звіт":
            continue
        ws = wb[имя]
        колф = 7
        for c in range(1, min(ws.max_column, 15) + 1):
            if "факт виконання робіт" in str(ws.cell(1, c).value or "").lower():
                колф = c; break
        строки = []
        for r in range(2, ws.max_row + 1):
            назв = str(ws.cell(r, 1).value or "").strip()
            if not назв or "Загальна" in назв or назв.lower() == "табель":
                continue
            cell = ws.cell(r, колф)
            строки.append((назв, факт_текст(cell.value, cell.number_format)))
        return имя, строки
    return None, []

