def эталон_ev(строки, тег):
    ev = [0.0]*N
    print(f"\n--- Разбор «{тег}» (ненулевые) ---")
    for назв, факт in строки:
        r = proc.РазобратьПроцентыФакта(факт, N)
        p = None if r is None else [0.0 if r.Получить(i) is None else float(r.Получить(i)) for i in range(N)]
        план = план_сс.get(норм(назв))
        if p and any(x for x in p):
            метка = "" if план is not None else "  <НЕТ В СС — пропуск>"
            print(f"   {назв[:36]:36} H={факт[:24]!r:26} -> {[int(x) for x in p]}{метка}")
        if план is not None and p:
            for k in range(N):
                ev[k] += план / N * p[k] / 100.0
    print(f"   EV по домикам: " + ", ".join(f"№{k+1}={ev[k]:.3f}" for k in range(N)) + f"  всего={sum(ev):.3f}")
    return ev

