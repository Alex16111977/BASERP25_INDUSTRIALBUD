ev17 = эталон_ev(стр17, имя17)

def построить_параметры(имя, строки):
    л1с = erp.NewObject("Массив")
    с1с = erp.NewObject("Массив")
    for назв, факт in строки:
        s = erp.NewObject("Структура"); s.Вставить("Наименование", назв); s.Вставить("ТекстФакта", факт)
        с1с.Добавить(s)
    o = erp.NewObject("Структура"); o.Вставить("ИмяЛиста", имя); o.Вставить("Строки", с1с)
    л1с.Добавить(o)
    p = erp.NewObject("Структура")
    p.Вставить("СтруктураСеб", сс.Ссылка); p.Вставить("Листы", л1с)
    p.Вставить("Год", 2026); p.Вставить("Время", 9*3600)
    p.Вставить("Проводить", True); p.Вставить("КоличествоМодулейПоУмолчанию", 8)
    return p

def обороты_по_домикам(ссылка):
    q = erp.NewObject("Запрос"); q.УстановитьПараметр("СС", ссылка)
    q.Текст = ("ВЫБРАТЬ Т.Подразделение.Наименование КАК П, СУММА(Т.ЧасыВыполнение) КАК Ч "
               "ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т ГДЕ Т.СтруктураСебестоимости = &СС "
               "СГРУППИРОВАТЬ ПО Т.Подразделение.Наименование УПОРЯДОЧИТЬ ПО П")
    т = q.Execute().Выгрузить()
    return [(str(т.Получить(i).П), float(т.Получить(i).Ч or 0)) for i in range(т.Количество())]

def обороты_всего(ссылка):
    q = erp.NewObject("Запрос"); q.УстановитьПараметр("СС", ссылка)
    q.Текст = ("ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т "
               "ГДЕ Т.СтруктураСебестоимости = &СС")
    return float(q.Execute().Выгрузить().Получить(0).Ч or 0)

