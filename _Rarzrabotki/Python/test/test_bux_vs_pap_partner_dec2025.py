# -*- coding: utf-8 -*-
"""
Уровень 2: накопленное сальдо Бух vs ПАП по ПАРТНЁРУ на 31.12.2025.
ТОВ ІНДАСТРІАЛБУД.

ЦЕЛЬ:
    Сравнить «по партнёру», у кого реально разошлись бух и ПАП к концу декабря.
    Парные документы-зеркала (внутренние перебросы) схлопываются.
    Остаются только партнёры с НЕнулевой разницей — там и сидит проблема.

ЛОГИКА:
    БухКлиент(партнёр)  = Σ(Дт36X−Кт36X со ссылкой на Партнёра) − Σ(Дт681−Кт681) на 31.12
    ПАПКлиент(партнёр)  = Σ(ЗадКл − ПолучАв) по Партнёру по Источник=РасчКлПоСр на 31.12
    Δ_Кл(партнёр) = ПАПКлиент − БухКлиент

    Аналогично для поставщиков с 631 и 3711.

Сводное правило:
    Если |Δ_партнёр| > порога → партнёр с проблемой → ищем документы декабря по этому партнёру.

Партнёр в бухгалтерии — это Субконто1 счетов 36X/631/371/681 (тип Партнёры).
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)
import win32com.client, pythoncom
pythoncom.CoInitialize()

ПОРОГ = 1.00   # 1 гривна

v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = erp.NewObject('Запрос')
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
орг = q.Выполнить().Выгрузить().Получить(0).Ссылка
print(f'Организация: {орг}', flush=True)

КМ = datetime.datetime(2025, 12, 31, 23, 59, 59)

# === ПАП на 31.12 — сальдо по партнёру ===
qq = erp.NewObject('Запрос')
qq.УстановитьПараметр('Орг', орг)
qq.УстановитьПараметр('КМ', КМ)
qq.Текст = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Т.Аналитика КАК Справочник.ОбъектыРасчетов).Партнер КАК Партнер,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьКлиентов)
              И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ЗадКл,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ПолученныеАвансы)
              И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ПолучАв,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ЗадолженностьПередПоставщиками)
              И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ЗадПост,
    СУММА(ВЫБОР КОГДА Т.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыданныеАвансы)
              И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам)
            ТОГДА ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ
            ИНАЧЕ 0 КОНЕЦ) КАК ПАП_ВыдАв
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Период <= &КМ
    И Т.Источник В (
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
СГРУППИРОВАТЬ ПО ВЫРАЗИТЬ(Т.Аналитика КАК Справочник.ОбъектыРасчетов).Партнер
"""
rp = qq.Выполнить().Выгрузить()
пап = {}  # партнёр-ссылка → dict
for i in range(rp.Количество()):
    row = rp.Получить(i)
    п = row.Партнер
    ключ = str(п) if п else 'NULL'
    пап[ключ] = dict(ссылка=п,
        ПАП_ЗадКл=float(row.ПАП_ЗадКл or 0), ПАП_ПолучАв=float(row.ПАП_ПолучАв or 0),
        ПАП_ЗадПост=float(row.ПАП_ЗадПост or 0), ПАП_ВыдАв=float(row.ПАП_ВыдАв or 0))
print(f'ПАП-партнёров: {len(пап)}', flush=True)

# === Бухгалтерия на 31.12 — сальдо по субконто-Партнёру (Субконто1 счетов 36X/631) ===
# Для счетов 36X/631 первое субконто = Партнёр.
# Для 681/371 первое субконто = Объект расчётов, но через .Партнер можно тоже достать.
# Используем виртуальную таблицу .Остатки по партнёру.
qq.Текст = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Б.Субконто1 КАК Справочник.Партнеры) КАК Партнер,
    Б.Счет.Код КАК Счет,
    Б.СуммаОстатокДт КАК ОстДт,
    Б.СуммаОстатокКт КАК ОстКт
ПОМЕСТИТЬ втРаскл
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&КМ, ) КАК Б
ГДЕ Б.Организация = &Орг
    И (Б.Счет.Код ПОДОБНО "36%" ИЛИ Б.Счет.Код ПОДОБНО "681%"
       ИЛИ Б.Счет.Код ПОДОБНО "631%" ИЛИ Б.Счет.Код ПОДОБНО "371%")
;
ВЫБРАТЬ
    Партнер,
    СУММА(ВЫБОР КОГДА Счет ПОДОБНО "36%" ТОГДА ОстДт - ОстКт ИНАЧЕ 0 КОНЕЦ) КАК Бух_Кл_361,
    СУММА(ВЫБОР КОГДА Счет ПОДОБНО "681%" ТОГДА ОстКт - ОстДт ИНАЧЕ 0 КОНЕЦ) КАК Бух_Кл_681,
    СУММА(ВЫБОР КОГДА Счет ПОДОБНО "631%" ТОГДА ОстКт - ОстДт ИНАЧЕ 0 КОНЕЦ) КАК Бух_Пост_631,
    СУММА(ВЫБОР КОГДА Счет ПОДОБНО "371%" ТОГДА ОстДт - ОстКт ИНАЧЕ 0 КОНЕЦ) КАК Бух_Пост_371
ИЗ втРаскл
ГДЕ Партнер <> NULL
СГРУППИРОВАТЬ ПО Партнер
"""
rb = qq.Выполнить().Выгрузить()
бух = {}
for i in range(rb.Количество()):
    row = rb.Получить(i)
    п = row.Партнер
    ключ = str(п) if п else 'NULL'
    бух[ключ] = dict(ссылка=п,
        Бух_Кл_361=float(row.Бух_Кл_361 or 0), Бух_Кл_681=float(row.Бух_Кл_681 or 0),
        Бух_Пост_631=float(row.Бух_Пост_631 or 0), Бух_Пост_371=float(row.Бух_Пост_371 or 0))
print(f'Бух-партнёров: {len(бух)}', flush=True)

# === Соединение по партнёру ===
все_партнёры = set(пап) | set(бух)
итог = []
for ключ in все_партнёры:
    p = пап.get(ключ, {})
    b = бух.get(ключ, {})
    п_ссылка = p.get('ссылка') or b.get('ссылка')
    ПАП_кл  = p.get('ПАП_ЗадКл',0) - p.get('ПАП_ПолучАв',0)
    БУХ_кл  = b.get('Бух_Кл_361',0) - b.get('Бух_Кл_681',0)
    ПАП_пост= p.get('ПАП_ЗадПост',0) - p.get('ПАП_ВыдАв',0)
    БУХ_пост= b.get('Бух_Пост_631',0) - b.get('Бух_Пост_371',0)
    Δ_кл = ПАП_кл - БУХ_кл
    Δ_пост= ПАП_пост - БУХ_пост
    итог.append(dict(ссылка=п_ссылка, ключ=ключ,
        ПАП_кл=ПАП_кл, БУХ_кл=БУХ_кл, Δ_кл=Δ_кл,
        ПАП_пост=ПАП_пост, БУХ_пост=БУХ_пост, Δ_пост=Δ_пост))

ok_partner = [x for x in итог if abs(x['Δ_кл']) < ПОРОГ and abs(x['Δ_пост']) < ПОРОГ]
аномалии = [x for x in итог if abs(x['Δ_кл']) >= ПОРОГ or abs(x['Δ_пост']) >= ПОРОГ]
аномалии.sort(key=lambda x: max(abs(x['Δ_кл']), abs(x['Δ_пост'])), reverse=True)

print()
print('=' * 130)
print('СВОДКА — сальдо Бух vs ПАП по ПАРТНЁРУ на 31.12.2025')
print('=' * 130)
print(f'  всего партнёров с движением   : {len(итог)}')
print(f'  чисто OK (Δ < 1 грн)          : {len(ok_partner)}')
print(f'  РАЗЛЁТ                        : {len(аномалии)}')
total_kl = sum(x['Δ_кл'] for x in аномалии)
total_post = sum(x['Δ_пост'] for x in аномалии)
print(f'  Σ Δ_кл по аномалиям           : {total_kl:>+15,.2f}')
print(f'  Σ Δ_пост по аномалиям         : {total_post:>+15,.2f}')

print()
print('=' * 130)
показать = min(len(аномалии), 30)
print(f'ТОП-{показать} ПАРТНЁРОВ — где сальдо ПАП ≠ Бух на 31.12.2025')
print('=' * 130)
print(f'{"Партнёр":<60} {"ΔКл":>14} {"ΔПост":>14} {"ПАП_кл":>14} {"БУХ_кл":>14}')
print('-' * 130)
for x in аномалии[:30]:
    п = x['ссылка']
    if п is None or not erp.ЗначениеЗаполнено(п):
        ст = '<NULL>'
    else:
        try: ст = str(п)
        except: ст = '<?>'
    print(f'{ст[:60]:<60} {x["Δ_кл"]:>+14,.2f} {x["Δ_пост"]:>+14,.2f} {x["ПАП_кл"]:>+14,.2f} {x["БУХ_кл"]:>+14,.2f}', flush=True)
