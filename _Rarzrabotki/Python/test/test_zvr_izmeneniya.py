# -*- coding: utf-8 -*-
"""Приёмка данных матрицы «Зміни»: что обработка покажет прорабу ДО загрузки.

Берёт правленый прорабом файл (Шаблоны — копия) и грузит его датой 12.08.2026,
когда документов этого дня ещё нет: «Було» = снимок 05.08, «Зміни» = ровно 6 клеток.
В базу ничего не пишет.

Запуск: python test_zvr_izmeneniya.py
"""
import os
import shutil
import sys
import tempfile

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Загрузка выполнения работ.epf"
ПРАВЛЕНЫЙ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\notebook"
             r"\knowledge_Загрузка файлов в выполнение работ\Шаблоны — копия"
             r"\МД IRS 2026 15 м (МД IRS 2026).xlsx")

ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

провалов = 0


def проверить(условие, сообщение):
    global провалов
    if not условие:
        провалов += 1
        print("    ПРОВАЛ:", сообщение)


def адрес():
    dst = os.path.join(tempfile.gettempdir(), "zvr_izm.xlsx")
    shutil.copyfile(ПРАВЛЕНЫЙ, dst)
    return ERP.ПоместитьВоВременноеХранилище(ERP.NewObject("ДвоичныеДанные", dst))


def разобрать(дата_текст):
    обр = ERP.ВнешниеОбработки.Создать(EPF, False)
    обр.ИмяФайла = "МД IRS 2026 15 м (МД IRS 2026).xlsx"
    паспорт = обр.ПрочитатьПаспортФайла(адрес(), обр.ИмяФайла)
    обр.СтруктураСебестоимости = паспорт.СтруктураСебестоимости
    if дата_текст:
        д, м, г = (int(x) for x in дата_текст.split("."))
        обр.ДатаЗагрузки = ERP.NewObject("Запрос",
                                         f"ВЫБРАТЬ ДАТАВРЕМЯ({г},{м},{д}) КАК Д").Выполнить().Выгрузить()[0].Д
    else:
        обр.ДатаЗагрузки = паспорт.Дата
    сводка = обр.РазобратьФайл(адрес(), обр.ИмяФайла)
    return обр, сводка


def клетки_с_изменением(обр):
    результат = []
    for i in range(обр.Строки.Количество()):
        с = обр.Строки[i]
        дельта = float(с.Процент) - float(с.ПроцентПред)
        if abs(дельта) > 0.001 and с.Уровень != "Помилка":
            результат.append((с.РаботаТекст, с.ЗаголовокДома, int(с.НомерМодуля),
                              float(с.ПроцентПред), float(с.Процент), дельта))
    return результат


# --- сценарий прораба: файл правлений, вантажимо датою 12.08.2026 (документів цього дня немає)
print("=== Правлений файл, дата завантаження 12.08.2026")
обр, сводка = разобрать("12.08.2026")
изменения = клетки_с_изменением(обр)
print(f"  розбір: помилок {сводка.Ошибок} · попереджень {сводка.Предупреждений} · "
      f"клітинок {сводка.Строк}")
print(f"  клітинок зі змінами: {len(изменения)}")
for р, д, м, было, стало, дельта in изменения:
    print(f"    {р[:34]:36} {д:8} М{м}  було {было:5.0f} -> стане {стало:5.0f}  ({дельта:+.0f})")

проверить(сводка.Ошибок == 0, f"ошибок быть не должно: {сводка.Ошибок}")
проверить(len(изменения) == 6, f"ожидали 6 изменённых клеток, получили {len(изменения)}")

ожидаем = {
    ("Обробка матеріалу (дерево)", "Дім №1"): (80, 100),
    ("Обробка матеріалу (дерево)", "Дім №2"): (80, 100),
    ("Обробка матеріалу (дерево)", "Дім №3"): (80, 100),
    ("монтаж мдф дверей", "Дім №1"): (0, 100),
    ("монтаж мдф дверей", "Дім №2"): (0, 100),
    ("монтаж мдф дверей", "Дім №3"): (0, 100),
}
фактически = {(р, д): (было, стало) for р, д, м, было, стало, _ in изменения}
проверить(фактически == ожидаем, f"состав изменений не совпал: {фактически}")
проверить(сводка.Предупреждений == 0, "откатов быть не должно — все изменения вверх")

# --- контроль: той самий файл датою 05.08 (документи цього дня Є) -> порівняння з ними
print("\n=== Той самий файл, дата 05.08.2026 (документи цього дня вже є)")
обр05, сводка05 = разобрать("05.08.2026")
изм05 = клетки_с_изменением(обр05)
print(f"  клітинок зі змінами: {len(изм05)} (порівняння йде з документами 05.08, а не з 31.07)")
for р, д, м, было, стало, дельта in изм05[:8]:
    print(f"    {р[:34]:36} {д:8} М{м}  було {было:5.0f} -> стане {стало:5.0f}  ({дельта:+.0f})")
проверить(len(изм05) == 6, f"и здесь должно быть ровно 6 изменений, получили {len(изм05)}")

print(f"\nПРОВАЛОВ: {провалов}")
print("ПРИЁМКА ЗМІН ПРОЙДЕНА" if провалов == 0 else "ПРИЁМКА ЗМІН НЕ ПРОЙДЕНА")
sys.exit(1 if провалов else 0)
