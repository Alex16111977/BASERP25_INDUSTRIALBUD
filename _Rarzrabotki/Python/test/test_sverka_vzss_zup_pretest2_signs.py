def fetch(conn, text, cols):
    q = conn.NewObject("Запрос")
    q.Text = text
    t = q.Execute().Выгрузить()
    out = {}
    for i in range(t.Количество()):
        r = t.Получить(i)
        drfo = (r.ДРФО or "").strip()
        if drfo:
            out[drfo] = tuple(float(getattr(r, c) or 0) for c in cols)
    return out

