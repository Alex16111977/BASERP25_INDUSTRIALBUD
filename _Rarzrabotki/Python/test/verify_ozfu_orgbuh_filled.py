# -*- coding: utf-8 -*-
"""Приёмка: после перепроведения родителя А_ОтражениеЗПпоКазне через UI проверить, что в
дочернем ОтражениеЗарплатыВФинансовомУчете ОрганизацияБухгалтерия заполнена в 4 ТЧ для Ф1.

Запуск: C:\\Python313\\python.exe verify_ozfu_orgbuh_filled.py
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
ТЧ_СПИСОК = ["НачисленнаяЗарплатаИВзносы", "НачисленнаяЗарплатаИВзносыПоФизлицам",
            "НачисленныйНДФЛ", "УдержаннаяЗарплата"]

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
XML = erp.XMLСтрока

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете "
          "ГДЕ Номер = &Н И Дата >= &Д1 И Дата < &Д2")
q.SetParameter("Н", "000Ц-000003")
q.SetParameter("Д1", datetime.datetime(2025, 12, 1))
q.SetParameter("Д2", datetime.datetime(2026, 1, 1))
в = q.Execute().Выбрать()
assert в.Следующий(), "Дочерний ОЗФУ 000Ц-000003 (дек.2025) не найден"
obj = в.Ссылка.ПолучитьОбъект()

print(f"Документ: {obj.Ссылка}\n")
все_ок = True
for имя in ТЧ_СПИСОК:
    тч = getattr(obj, имя)
    ф1_зап, ф1_пуст = 0, 0
    for i in range(тч.Количество()):
        с = тч.Получить(i)
        # у НачисленнаяЗарплатаИВзносы есть ВзносыВсего; ЕСВ-строки (взносы) — пропускаем как не-Ф1-нач
        if XML(с.ФормаPL) != "Форма1":
            continue
        if hasattr(с, "ВзносыВсего") and float(с.ВзносыВсего) != 0:
            continue  # ЕСВ-строки ОргБух могут не иметь (взносы) — не считаем
        if erp.ЗначениеЗаполнено(с.ОрганизацияБухгалтерия):
            ф1_зап += 1
        else:
            ф1_пуст += 1
    статус = "OK" if ф1_пуст == 0 and ф1_зап > 0 else ("— нет Ф1" if ф1_зап == 0 else "FAIL")
    if статус == "FAIL":
        все_ок = False
    print(f"  {имя:34} Ф1 с ОргБух={ф1_зап:4}  Ф1 пусто={ф1_пуст:4}  [{статус}]")

# спот-чек Шишкіна (ожидаем ІНДЕПТ СТІЛ)
print("\n--- Шишкіна (НачисленнаяЗарплатаИВзносыПоФизлицам, Ф1) ---")
тч = obj.НачисленнаяЗарплатаИВзносыПоФизлицам
for i in range(тч.Количество()):
    с = тч.Получить(i)
    if XML(с.ФормаPL) == "Форма1" and "шишк" in с.ФизическоеЛицо.Наименование.lower():
        об = с.ОрганизацияБухгалтерия.Наименование if erp.ЗначениеЗаполнено(с.ОрганизацияБухгалтерия) else "<пусто>"
        подр = с.ПодразделениеПредприятия.Наименование if erp.ЗначениеЗаполнено(с.ПодразделениеПредприятия) else "<пусто>"
        print(f"  {подр} / {с.СпособОтраженияЗарплатыВБухучете}: ОргБух={об} Сумма={float(с.Сумма)}")

print("\n" + ("OK: ОргБух заполнен во всех 4 ТЧ для Ф1" if все_ок else "FAIL: есть Ф1-строки без ОргБух (см. выше)"))
sys.exit(0 if все_ок else 1)
