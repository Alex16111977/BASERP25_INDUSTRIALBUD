# -*- coding: utf-8 -*-
"""
Тест COM-подключения к базам ЗУП (zup_1 и zup_2) и проверка данных за текущий месяц.
"""
import win32com.client
import datetime

v8 = win32com.client.Dispatch("V83.COMConnector")

# Период - апрель 2026
period_start = datetime.datetime(2026, 4, 1)
period_end = datetime.datetime(2026, 4, 30, 23, 59, 59)

print("=" * 60)
print("ТЕСТ 1: Подключение к zup_2 (управленческая ЗП)")
print("=" * 60)

count_zup2 = 0
count_zup2_ded = 0

try:
    conn_zup2 = v8.Connect('Srvr="localhost";Ref="zup2";Usr="cfo";Pwd="2442"')
    print("[OK] Подключение к zup_2 успешно")

    q = conn_zup2.NewObject("Запрос")
    q.Text = (
        "ВЫБРАТЬ "
        "  Начисления.Физлицо.КодПоДРФО КАК КодПоДРФО, "
        "  Начисления.ВидРасчета.Наименование КАК ВидРасчета, "
        "  Начисления.ВидРасчета.Код КАК КодВидРасчета, "
        "  Начисления.Результат КАК Сумма "
        "ИЗ "
        "  Документ.НачислениеЗарплатыРаботникам.Начисления КАК Начисления "
        "ГДЕ "
        "  Начисления.Ссылка.Дата МЕЖДУ &НачалоПериода И &КонецПериода "
        "  И Начисления.Ссылка.Проведен = ИСТИНА "
        "  И Начисления.Результат <> 0"
    )
    q.SetParameter("НачалоПериода", period_start)
    q.SetParameter("КонецПериода", period_end)

    res = q.Execute()
    sel = res.Choose()
    total_sum = 0
    while sel.Next():
        count_zup2 += 1
        total_sum += float(sel.Сумма)
        if count_zup2 <= 3:
            print(f"  Пример: ИНН={sel.КодПоДРФО}, {sel.ВидРасчета}, Сумма={sel.Сумма}")

    print(f"[OK] Начислений: {count_zup2} строк, сумма: {total_sum:,.2f}")

    # Удержания
    q2 = conn_zup2.NewObject("Запрос")
    q2.Text = (
        "ВЫБРАТЬ "
        "  Удержания.Физлицо.КодПоДРФО КАК КодПоДРФО, "
        "  Удержания.ВидРасчета.Наименование КАК ВидРасчета, "
        "  Удержания.ВидРасчета.Код КАК КодВидРасчета, "
        "  Удержания.Результат КАК Сумма "
        "ИЗ "
        "  Документ.НачислениеЗарплатыРаботникам.Удержания КАК Удержания "
        "ГДЕ "
        "  Удержания.Ссылка.Дата МЕЖДУ &НачалоПериода И &КонецПериода "
        "  И Удержания.Ссылка.Проведен = ИСТИНА "
        "  И Удержания.Результат <> 0"
    )
    q2.SetParameter("НачалоПериода", period_start)
    q2.SetParameter("КонецПериода", period_end)

    res2 = q2.Execute()
    sel2 = res2.Choose()
    while sel2.Next():
        count_zup2_ded += 1
    print(f"[OK] Удержаний: {count_zup2_ded} строк")

    conn_zup2 = None

except Exception as e:
    print(f"[ОШИБКА] zup_2: {e}")

print()
print("=" * 60)
print("ТЕСТ 2: Подключение к zup_1 (регламентная ЗП)")
print("=" * 60)

count_zup1 = 0

try:
    conn_zup1 = v8.Connect('Srvr="localhost";Ref="zup";Usr="cfo";Pwd="2442"')
    print("[OK] Подключение к zup_1 успешно")

    q3 = conn_zup1.NewObject("Запрос")
    q3.Text = (
        "ВЫБРАТЬ "
        "  Начисления.Сотрудник.Физлицо.КодПоДРФО КАК СотрудникИНН, "
        "  СУММА(Начисления.Результат) КАК СуммаНачислено, "
        "  Начисления.Сотрудник.Физлицо.Наименование КАК СотрудникНаименование "
        "ИЗ "
        "  РегистрРасчета.ОсновныеНачисленияРаботниковОрганизаций КАК Начисления "
        "ГДЕ "
        '  НАЧАЛОПЕРИОДА(Начисления.ПериодРегистрации, МЕСЯЦ) = &ПериодРегистрации '
        '  И Начисления.ВидРасчета.Код <> "00021" '
        "  И Начисления.Результат <> 0 "
        "СГРУППИРОВАТЬ ПО "
        "  Начисления.Сотрудник.Физлицо.КодПоДРФО, "
        "  Начисления.Сотрудник.Физлицо.Наименование"
    )
    q3.SetParameter("ПериодРегистрации", period_start)

    res3 = q3.Execute()
    sel3 = res3.Choose()
    total_sum3 = 0
    while sel3.Next():
        count_zup1 += 1
        total_sum3 += float(sel3.СуммаНачислено)
        if count_zup1 <= 3:
            print(f"  Пример: ИНН={sel3.СотрудникИНН}, {sel3.СотрудникНаименование}, Сумма={sel3.СуммаНачислено}")

    print(f"[OK] Начислений (бух): {count_zup1} сотрудников, сумма: {total_sum3:,.2f}")

    conn_zup1 = None

except Exception as e:
    print(f"[ОШИБКА] zup_1: {e}")

print()
print("=" * 60)
print("ИТОГО:")
print(f"  zup_2 (управленческая): начислений={count_zup2}, удержаний={count_zup2_ded}")
print(f"  zup_1 (регламентная):   сотрудников={count_zup1}")
print("=" * 60)
