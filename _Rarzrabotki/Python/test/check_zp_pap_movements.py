def xs(v):
    try:
        return erp.XMLСтрока(v) if erp.ЗначениеЗаполнено(v) else "(пусто)"
    except Exception:
        return "<err>"

def show_method(sp_obj, names):
    o = sp_obj.ПолучитьОбъект()
    for nm in names:
        try:
            val = getattr(o, nm)
            if erp.ЗначениеЗаполнено(val):
                try:
                    name = val.Наименование
                except Exception:
                    name = xs(val)
                print(f"  {nm} = {name}")
            else:
                print(f"  {nm} = (пусто)")
        except Exception as e:
            print(f"  {nm} <err {e}>")

