# -*- coding: utf-8 -*-
"""БОЕВОЙ прогон через .epf: перевод статуса «Согласован» -> «Подтвержден»
за период 01.12.2025 - 31.12.2026.

Сначала сухой анализ (ничего не пишет), затем запись.
"""
import win32com.client, sys, io, time
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ПУТЬ = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Обновить заказы поставщика.epf"
ЛОГ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\logs"
       r"\status_dec25_dec26.log")

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
лог_файл = io.open(ЛОГ, "w", encoding="utf-8")


def лог(*a):
    s = " ".join(str(x) for x in a)
    print(s); лог_файл.write(s + "\n"); лог_файл.flush()


def чис(з):
    try:
        return int(float(S(з).replace("\u00a0", "").replace(" ", "").replace(",", ".")))
    except Exception:
        return 0


def статусы(подпись):
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ РАЗЛИЧНЫЕ Д.ЗаказПоставщику КАК Заказ
    ПОМЕСТИТЬ ВТ
    ИЗ Документ.ПриобретениеТоваровУслуг КАК Д
    ГДЕ Д.ЗаказПоставщику <> ЗНАЧЕНИЕ(Документ.ЗаказПоставщику.ПустаяСсылка)
        И НЕ Д.ПометкаУдаления
        И Д.Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1,0,0,0) И ДАТАВРЕМЯ(2026,12,31,23,59,59)
    ;
    ////////////////////////////////////////////////
    ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(З.Статус) КАК Статус, КОЛИЧЕСТВО(*) КАК Заказов
    ИЗ ВТ ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ЗаказПоставщику КАК З ПО ВТ.Заказ = З.Ссылка
    СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(З.Статус)
    УПОРЯДОЧИТЬ ПО Заказов УБЫВ
    """
    r = q.Execute().Выгрузить()
    лог("  СТАТУСЫ %s:" % подпись)
    for i in range(r.Количество()):
        row = r.Получить(i)
        лог("     %-16s %s" % (S(row.Получить(0)), S(row.Получить(1))))


старт = time.time()
лог("=" * 74)
лог("ПЕРЕВОД СТАТУСА «Согласован» -> «Подтвержден»")
лог("Период отбора по дате приходов: 01.12.2025 - 31.12.2026")
лог("=" * 74)

статусы("ДО")

обр = erp.ВнешниеОбработки.Создать(ПУТЬ, False)

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ДАТАВРЕМЯ(2025,12,1,0,0,0) КАК Н, "
          "ДАТАВРЕМЯ(2026,12,31,23,59,59) КАК К")
гр = q.Execute().Выгрузить().Получить(0)
НачП, КонП = гр.Получить(0), гр.Получить(1)

# ---------- ФАЗА 1: сухой анализ ----------
лог("=" * 74)
лог("ФАЗА 1 — АНАЛИЗ (без записи)")
реестр = обр.ПолучитьРеестрЗаказов(НачП, КонП)
лог("  заказов в реестре:", S(реестр.Количество()))

пар = erp.NewObject("Структура")
пар.Вставить("ТолькоАнализ", True)
пар.Вставить("ПереводитьСогласованВПодтвержден", True)
рез = обр.ВыполнитьОбработку(реестр, пар)
лог("  " + S(обр.ПредставлениеСтатистики(рез.Статистика)).replace("\n", "\n  "))
лог("  время анализа: %d c" % int(time.time() - старт))

# ---------- ФАЗА 2: боевая запись ----------
лог("=" * 74)
лог("ФАЗА 2 — ЗАПИСЬ")
реестр2 = обр.ПолучитьРеестрЗаказов(НачП, КонП)
for i in range(реестр2.Количество()):
    реестр2.Получить(i).Обновлять = True

пар2 = erp.NewObject("Структура")
пар2.Вставить("ТолькоАнализ", False)
пар2.Вставить("ПереводитьСогласованВПодтвержден", True)
рез2 = обр.ВыполнитьОбработку(реестр2, пар2)
ст = рез2.Статистика
лог("  " + S(обр.ПредставлениеСтатистики(ст)).replace("\n", "\n  "))

обработано = (чис(ст.ЗаказОбновлён) + чис(ст.ЗаказБезИзменений) + чис(ст.ЗаказОчищен)
              + чис(ст.ЗаказПропущен) + чис(ст.ЗаказОшибка))
лог("  перебор: %d из %s" % (обработано, S(реестр2.Количество())))

# проблемные строки
лог("=" * 74)
лог("СТРОКИ С ПРОБЛЕМАМИ:")
проблем = 0
for i in range(реестр2.Количество()):
    стр = реестр2.Получить(i)
    рт = S(стр.Результат)
    пр = S(стр.Предупреждение).replace("\n", " ")
    if рт.startswith("ОШИБКА") or "Пропущен" in рт or пр.strip() != "":
        проблем += 1
        if проблем <= 60:
            лог("   %-14s %s %s" % (S(стр.Номер), рт[:70], ("| " + пр[:70]) if пр.strip() else ""))
лог("  всего проблемных строк:", проблем)

статусы("ПОСЛЕ")
лог("=" * 74)
лог("ИТОГО за %d c" % int(time.time() - старт))
лог_файл.close()
