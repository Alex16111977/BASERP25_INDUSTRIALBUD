# -*- coding: utf-8 -*-
"""ЦВБ v3.1: претест чтения булева реквизита-флага по ссылке (Rule #-1)."""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
fails = 0

# 1. Чтение флага по ссылке галочного документа
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Док
ИЗ Документ.ОприходованиеИзлишковТоваров КАК Д
ГДЕ Д.Номер = "000Ц-000007" И ГОД(Д.Дата) = 2026 И МЕСЯЦ(Д.Дата) = 5
"""
r = q.Execute().Выгрузить()
if r.Количество() == 1:
    ref = r.Получить(0).Док
    val = ref.А_ДляЗакрытиеОтрицательныхОстатков
    ok = bool(val) is True
    print(f"1. флаг по ссылке 000Ц-000007: {val} -> {'OK' if ok else 'FAIL'}")
    fails += 0 if ok else 1
else:
    print("1. FAIL: документ 000Ц-000007 не найден")
    fails += 1

# 2. Гард: у чужого типа реквизита нет (через ссылку живого документа, как в BSL).
# ⚠️ Тип «СписаниеТоваров» в ERP НЕ существует (это Бух-имя) — реальный тип
# СписаниеНедостачТоваров. Плагин пишет в ТаблицаДокументов Бух-имя (ТипБух :823) —
# см. претест 4: резолв класса B по UID через соответствия.
q2 = erp.NewObject("Запрос")
q2.Text = 'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Док ИЗ Документ.СписаниеНедостачТоваров КАК Д'
r2 = q2.Execute().Выгрузить()
ref2 = r2.Получить(0).Док
attr = ref2.Метаданные().Реквизиты.Найти("А_ДляЗакрытиеОтрицательныхОстатков")
print(f"2. гард СписаниеНедостачТоваров без реквизита: {'OK' if attr is None else 'FAIL'}")
fails += 0 if attr is None else 1

# 3. Метаданные().Реквизиты.Найти по ссылке (как будет в BSL-кэше)
found = ref.Метаданные().Реквизиты.Найти("А_ДляЗакрытиеОтрицательныхОстатков")
print(f"3. Метаданные().Реквизиты.Найти по ссылке: {'OK' if found is not None else 'FAIL'}")
fails += 0 if found is not None else 1

# 4. Резолв ERP-документа по UID-строке через соответствия (фикс ПрименитьДействиеB
# для типов с разными именами в базах: СписаниеТоваров(Бух)=СписаниеНедостачТоваров(ERP))
q4 = erp.NewObject("Запрос")
q4.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Соотв.УникальныйИдентификаторИсточника КАК Источник
ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
ГДЕ Соотв.УникальныйИдентификаторИсточникаСтрокой = &УИД
"""
q_uid = erp.NewObject("Запрос")
q_uid.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Соотв.УникальныйИдентификаторИсточникаСтрокой КАК УИДСтрока
ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
ГДЕ НЕ Соотв.УникальныйИдентификаторИсточникаСтрокой = ""
"""
r_uid = q_uid.Execute().Выгрузить()
if r_uid.Количество() == 1:
    uid_probe = str(S(r_uid.Получить(0).УИДСтрока))
    q4.SetParameter("УИД", uid_probe)
    r4 = q4.Execute().Выгрузить()
    ok4 = r4.Количество() == 1
    print(f"4. резолв по УникальныйИдентификаторИсточникаСтрокой: {'OK' if ok4 else 'FAIL'} "
          f"({S(r4.Получить(0).Источник) if ok4 else '---'})")
    fails += 0 if ok4 else 1
else:
    print("4. FAIL: нет записей соответствий для пробы")
    fails += 1

erp = None
print("PRETEST " + ("PASS" if fails == 0 else f"FAIL ({fails})"))
sys.exit(0 if fails == 0 else 1)
