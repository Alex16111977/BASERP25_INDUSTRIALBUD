# -*- coding: utf-8 -*-
"""Уборка тестовых данных визирования из BaseERP (после приёмки).
Помечает на удаление тестовый заказ, тестовые роли и схему; удаляет тестовые записи РС.
Удалить() не вызывается для заказа (get-or-create) — только ПометкаУдаления.
"""
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
def S(x): return erp.String(x)

# 1) тестовый заказ → распровести + пометить на удаление
q=erp.NewObject("Запрос")
q.Text="ВЫБРАТЬ Т.Ссылка КАК Ссыл ИЗ Документ.ЗаказПоставщику КАК Т ГДЕ ВЫРАЗИТЬ(Т.Комментарий КАК СТРОКА(200))=&М И НЕ Т.ПометкаУдаления"
q.SetParameter("М","ТЕСТ ВИЗИРОВАНИЯ (автоприёмка)")
r=q.Execute().Выгрузить()
for i in range(r.Количество()):
    об=r.Получить(i).Ссыл.ПолучитьОбъект()
    if об.Проведен:
        об.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения); об=r.Получить(i).Ссыл.ПолучитьОбъект()
    об.ОбменДанными.Загрузка=True
    об.ПометкаУдаления=True
    об.Записать()
    print(f"  заказ помечен на удаление: {S(r.Получить(i).Ссыл)}")
if r.Количество()==0: print("  тестовых заказов нет")

# 2) записи РС адресации/схемы, ссылающиеся на тестовые роли/схему — удалить
роли=[]
for имя in ("Тест Снабженец","Тест Финдиректор"):
    рл=erp.Справочники.А_РолиВизирования.НайтиПоНаименованию(имя, True)
    if erp.ЗначениеЗаполнено(рл): роли.append(рл)
схема=erp.Справочники.А_СхемыВизирования.НайтиПоНаименованию("Тестовая схема", True)

# РС.А_ИдентификацияВизирующихПоРолям — удалить записи с тестовыми ролями
уд=0
for рл in роли:
    нз=erp.РегистрыСведений.А_ИдентификацияВизирующихПоРолям.СоздатьНаборЗаписей()
    нз.Отбор.Роль.Установить(рл)
    нз.Прочитать()
    if нз.Количество()>0:
        нз.Очистить(); нз.Записать(); уд+=1
print(f"  очищено наборов адресации: {уд}")

# РС.А_ОпределениеСхемыВизирования — удалить записи с тестовой схемой
if erp.ЗначениеЗаполнено(схема):
    q2=erp.NewObject("Запрос")
    q2.Text=("ВЫБРАТЬ Т.Подразделение КАК Подр, Т.Организация КАК Орг, Т.СтатьяДвиженияДенежныхСредств КАК ДДС, "
             "Т.ФормаОплаты КАК ФО, Т.Сумма КАК Сум, Т.НаправлениеДеятельности КАК Напр "
             "ИЗ РегистрСведений.А_ОпределениеСхемыВизирования КАК Т ГДЕ Т.СхемаВизирования=&Сх")
    q2.SetParameter("Сх",схема)
    r2=q2.Execute().Выгрузить()
    for i in range(r2.Количество()):
        x=r2.Получить(i)
        мз=erp.РегистрыСведений.А_ОпределениеСхемыВизирования.СоздатьМенеджерЗаписи()
        мз.Подразделение=x.Подр; мз.Организация=x.Орг; мз.СтатьяДвиженияДенежныхСредств=x.ДДС
        мз.ФормаОплаты=x.ФО; мз.Сумма=x.Сум; мз.НаправлениеДеятельности=x.Напр
        мз.Удалить()
    print(f"  удалено правил схемы: {r2.Количество()}")

# 3) тестовые роли и схему — пометить на удаление
for рл in роли:
    о=рл.ПолучитьОбъект(); о.ПометкаУдаления=True; о.Записать()
    print(f"  роль помечена на удаление: {S(рл)}")
if erp.ЗначениеЗаполнено(схема):
    о=схема.ПолучитьОбъект(); о.ПометкаУдаления=True; о.Записать()
    print(f"  схема помечена на удаление: {S(схема)}")

# 4) контроль: заказов в контуре (должно стать 0 после пометки/распроведения)
qc=erp.NewObject("Запрос")
qc.Text="ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ Документ.ЗаказПоставщику КАК Т ГДЕ Т.А_Виза_Состояние <> ЗНАЧЕНИЕ(Перечисление.А_Визы_Состояния.ПустаяСсылка) И НЕ Т.ПометкаУдаления"
print(f"\n  заказов в контуре (не помеченных): {qc.Execute().Выгрузить().Получить(0).К}")
print("  предопределённая роль Инициатор сохранена:", S(erp.Справочники.А_РолиВизирования.Инициатор))
print("\nУборка завершена.")
