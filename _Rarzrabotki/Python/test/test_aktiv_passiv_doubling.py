# -*- coding: utf-8 -*-
"""
Тест: воспроизведение задвоения суммы в регистре ПрочиеАктивыПассивы
для документа ПриобретениеТоваровУслуг ІБ00-007404

Причина: LEFT JOIN к ДвиженияКонтрагентДоходыРасходы создаёт декартово произведение
когда в обоих таблицах > 1 строки с одинаковым Регистратор+Период+Организация.

Шаг 1: Воспроизвести ошибку оригинальным запросом
Шаг 2: Проверить исправленный запрос
"""
import win32com.client
import sys

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
conn = v8.Connect(CONN_ERP)

DOC_NUMBER = "007404"

print("=" * 70)
print("ТЕСТ: Задвоение суммы в ПрочиеАктивыПассивы")
print("=" * 70)

# -----------------------------------------------------------
# 0. Проверка исходных данных
# -----------------------------------------------------------
print("\n--- 0. Исходные данные документа ---")

q0 = conn.NewObject("Запрос")
q0.Text = """
ВЫБРАТЬ СуммаДокумента ИЗ Документ.ПриобретениеТоваровУслуг
ГДЕ Номер ПОДОБНО "%""" + DOC_NUMBER + """%"
"""
r0 = q0.Выполнить().Выбрать()
if r0.Следующий():
    doc_sum = r0.СуммаДокумента
    print(f"  СуммаДокумента = {doc_sum}")
else:
    print("  ОШИБКА: Документ не найден!")
    sys.exit(1)

# Проверить ПрочиеРасходы
print("\n--- Записи в ПрочиеРасходы ---")
q1 = conn.NewObject("Запрос")
q1.Text = """
ВЫБРАТЬ Сумма КАК Сум ИЗ РегистрНакопления.ПрочиеРасходы
ГДЕ Регистратор.Номер ПОДОБНО "%""" + DOC_NUMBER + """%"
  И ТИПЗНАЧЕНИЯ(Регистратор) = ТИП(Документ.ПриобретениеТоваровУслуг)
"""
r1 = q1.Выполнить().Выбрать()
total_pr = 0
cnt_pr = 0
while r1.Следующий():
    s = r1.Сум
    total_pr += s
    cnt_pr += 1
    print(f"  Строка {cnt_pr}: Сумма = {s}")
print(f"  Итого ПрочиеРасходы: {cnt_pr} строк, сумма = {total_pr}")

# Проверить ДвиженияКонтрагентДоходыРасходы
print("\n--- Записи в ДвиженияКонтрагентДоходыРасходы ---")
q2 = conn.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ Сумма КАК Сум, Договор ИЗ РегистрНакопления.ДвиженияКонтрагентДоходыРасходы
ГДЕ Регистратор.Номер ПОДОБНО "%""" + DOC_NUMBER + """%"
  И ТИПЗНАЧЕНИЯ(Регистратор) = ТИП(Документ.ПриобретениеТоваровУслуг)
"""
r2 = q2.Выполнить().Выбрать()
cnt_dk = 0
while r2.Следующий():
    cnt_dk += 1
    print(f"  Строка {cnt_dk}: Сумма = {r2.Сум}")
print(f"  Итого ДвиженияКонтрагент: {cnt_dk} строк")

if cnt_pr > 1 and cnt_dk > 1:
    print(f"\n  >>> ДЕКАРТОВО ПРОИЗВЕДЕНИЕ: {cnt_pr} x {cnt_dk} = {cnt_pr * cnt_dk} строк после JOIN!")
    print(f"  >>> Ожидаемое задвоение: {total_pr} x {cnt_dk} = {total_pr * cnt_dk}")

# -----------------------------------------------------------
# 1. ОРИГИНАЛЬНЫЙ запрос (с декартовым произведением)
# -----------------------------------------------------------
print("\n" + "=" * 70)
print("ШАГ 1: ОРИГИНАЛЬНЫЙ запрос (LEFT JOIN без группировки)")
print("=" * 70)

q_orig = conn.NewObject("Запрос")
q_orig.Text = """
ВЫБРАТЬ
    СУММА(Т.Сумма) КАК Сумма
ИЗ
    РегистрНакопления.ПрочиеРасходы КАК Т
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрНакопления.ДвиженияКонтрагентДоходыРасходы КАК ДвиженияКонтрагент
    ПО Т.Регистратор = ДвиженияКонтрагент.Регистратор
        И Т.Период = ДвиженияКонтрагент.Период
        И Т.Организация = ДвиженияКонтрагент.Организация
    ЛЕВОЕ СОЕДИНЕНИЕ Справочник.ДоговорыКонтрагентов КАК ДоговорКонтрагента
    ПО ДвиженияКонтрагент.Договор = ДоговорКонтрагента.Ссылка
ГДЕ
    Т.Регистратор.Номер ПОДОБНО "%""" + DOC_NUMBER + """%"
    И ТИПЗНАЧЕНИЯ(Т.Регистратор) = ТИП(Документ.ПриобретениеТоваровУслуг)
    И Т.Сумма <> 0
"""
r_orig = q_orig.Выполнить().Выбрать()
if r_orig.Следующий():
    sum_orig = r_orig.Сумма
    print(f"  Результат ОРИГИНАЛЬНОГО запроса: СУММА = {sum_orig}")
    if sum_orig == doc_sum:
        print("  >>> РЕЗУЛЬТАТ: СОВПАДАЕТ с СуммаДокумента (нет задвоения)")
    else:
        print(f"  >>> РЕЗУЛЬТАТ: ЗАДВОЕНИЕ! {sum_orig} != {doc_sum}")
        print(f"  >>> Множитель: {sum_orig / doc_sum:.1f}x")

# -----------------------------------------------------------
# 2. ИСПРАВЛЕННЫЙ запрос (с подзапросом и группировкой)
# -----------------------------------------------------------
print("\n" + "=" * 70)
print("ШАГ 2: ИСПРАВЛЕННЫЙ запрос (подзапрос с группировкой)")
print("=" * 70)

q_fix = conn.NewObject("Запрос")
q_fix.Text = """
ВЫБРАТЬ
    СУММА(Т.Сумма) КАК Сумма
ИЗ
    РегистрНакопления.ПрочиеРасходы КАК Т
    ЛЕВОЕ СОЕДИНЕНИЕ (
        ВЫБРАТЬ
            ДК.Регистратор КАК Регистратор,
            ДК.Период КАК Период,
            ДК.Организация КАК Организация,
            МАКСИМУМ(ДК.Договор) КАК Договор
        ИЗ
            РегистрНакопления.ДвиженияКонтрагентДоходыРасходы КАК ДК
        СГРУППИРОВАТЬ ПО
            ДК.Регистратор,
            ДК.Период,
            ДК.Организация
    ) КАК ДвиженияКонтрагент
    ПО Т.Регистратор = ДвиженияКонтрагент.Регистратор
        И Т.Период = ДвиженияКонтрагент.Период
        И Т.Организация = ДвиженияКонтрагент.Организация
    ЛЕВОЕ СОЕДИНЕНИЕ Справочник.ДоговорыКонтрагентов КАК ДоговорКонтрагента
    ПО ДвиженияКонтрагент.Договор = ДоговорКонтрагента.Ссылка
ГДЕ
    Т.Регистратор.Номер ПОДОБНО "%""" + DOC_NUMBER + """%"
    И ТИПЗНАЧЕНИЯ(Т.Регистратор) = ТИП(Документ.ПриобретениеТоваровУслуг)
    И Т.Сумма <> 0
"""
r_fix = q_fix.Выполнить().Выбрать()
if r_fix.Следующий():
    sum_fix = r_fix.Сумма
    print(f"  Результат ИСПРАВЛЕННОГО запроса: СУММА = {sum_fix}")
    if sum_fix == doc_sum:
        print(f"  >>> УСПЕХ: Сумма совпадает с СуммаДокумента ({doc_sum})")
    else:
        print(f"  >>> ОШИБКА: {sum_fix} != {doc_sum}")

# -----------------------------------------------------------
# 3. Итоговый вердикт
# -----------------------------------------------------------
print("\n" + "=" * 70)
print("ИТОГ")
print("=" * 70)
if sum_orig != doc_sum and sum_fix == doc_sum:
    print("  ТЕСТ ПРОЙДЕН!")
    print(f"  Оригинальный запрос: {sum_orig} (задвоение)")
    print(f"  Исправленный запрос: {sum_fix} (правильно)")
    print(f"  СуммаДокумента:      {doc_sum}")
elif sum_orig == doc_sum:
    print("  Оригинальный запрос НЕ задваивает для этого документа.")
    print("  Возможно, задвоение происходит в другом месте.")
else:
    print(f"  ОШИБКА: Исправленный запрос всё ещё неверный ({sum_fix} != {doc_sum})")
