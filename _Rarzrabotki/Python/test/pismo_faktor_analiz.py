# -*- coding: utf-8 -*-
"""Факторный разбор материалов для письма директору: экономия по ЦЕНЕ или по КОЛИЧЕСТВУ.

Источник — отчёт «План на факт за матеріалами детально» (Отчеты.А_ПланФактныйПроизводствоПолный,
разрез с ценами). Методика выведена из правил ЗаполнитьПланНаФакт отчёта и проверена
на данных 19.08.2026 до копейки:

    План на факт (ПНФ) = Факт грн + залишок кошторису × Ціна план
    Відхилення прогнозу = ПНФ − План = ціновий фактор + кількісний фактор
        ціновий    = Факт к-сть × (Ціна факт − Ціна план)          — закупили дешевше/дорожче
        кількісний = max(0, Факт к-сть − План к-сть) × Ціна план   — узяли більше кошторису
        позиція поза кошторисом (План к-сть = 0) → весь Факт у кількісний фактор

Грабли, стоившие расхождений:
  * плановую цену брать как План грн / План к-сть, НЕ из колонки «Ціна план» — та округлена
    до 2 знаков и даёт расхождение (на 19.08 — 6 462 грн);
  * позиция с ПУСТЫМ именем («без загальної назви») — реальные закупки без общего названия,
    терять её нельзя (на 19.08 это 6 632,01 грн);
  * уровни в этом отчёте: indent 2.0 — «Загальна назва», 4.0 — «Аналітика»
    (в файле «План факт» они на два шага глубже: 4.0 и 6.0).

Запуск:
    python pismo_faktor_analiz.py "<папка недели>"
"""
import os
import shutil
import sys
import tempfile
import zipfile

import openpyxl

sys.stdout.reconfigure(encoding="utf-8")

ЛИСТ = "TDSheet"


def книга(путь):
    """openpyxl падает на выгрузках 1С: строковая таблица зовётся xl/SharedStrings.xml
    с ЗАГЛАВНОЙ S, а стандарт требует строчную. Чиним копию во временном файле."""
    try:
        return openpyxl.load_workbook(путь, data_only=True)
    except KeyError:
        чинёный = os.path.join(tempfile.gettempdir(), "_" + os.path.basename(путь))
        with zipfile.ZipFile(путь) as вход,                 zipfile.ZipFile(чинёный, "w", zipfile.ZIP_DEFLATED) as выход:
            for элемент in вход.infolist():
                имя = элемент.filename
                if имя.lower() == "xl/sharedstrings.xml":
                    имя = "xl/sharedStrings.xml"
                выход.writestr(имя, вход.read(элемент.filename))
        return openpyxl.load_workbook(чинёный, data_only=True)


def найти_файл(папка, начало):
    for имя in sorted(os.listdir(папка)):
        if имя.startswith(начало) and имя.endswith(".xlsx") and not имя.startswith("~$"):
            return os.path.join(папка, имя)
    return None


def колонки(ws, строка=7):
    """Заголовок → номер колонки: между выгрузками колонки съезжают, ищем по тексту."""
    карта = {}
    for c in range(1, ws.max_column + 1):
        значение = ws.cell(строка, c).value
        if значение:
            карта[" ".join(str(значение).split()).lower()] = c
    return карта


def кол(карта, *варианты):
    for вариант in варианты:
        for имя, c in карта.items():
            if имя.startswith(вариант.lower()):
                return c
    return None


def читать_детальный(путь):
    """Итог по объекту + позиции уровня «Загальна назва» (включая безымянную)."""
    ws = книга(путь)[ЛИСТ]
    к = колонки(ws)
    поля = dict(ПланКол=кол(к, "план, к-сть"), План=кол(к, "план, грн"),
                ФактКол=кол(к, "факт, к-сть"), Факт=кол(к, "факт, грн"),
                ЦенаФакт=кол(к, "ціна факт"), ПНФ=кол(к, "план на факт"))

    def ч(r, c):
        значение = ws.cell(r, c).value if c else None
        return float(значение) if isinstance(значение, (int, float)) else 0.0

    итог, позиции = None, []
    for r in range(8, ws.max_row + 1):
        ячейка = ws.cell(r, 1)
        отступ = ячейка.alignment.indent or 0
        числа = {имя: ч(r, c) for имя, c in поля.items()}
        # строки r8/r9 — подписи группировок («Загальна назва», «Аналітика») без чисел,
        # итог объекта — первая строка нулевого уровня, где числа есть
        if (ячейка.value and отступ == 0 and итог is None
                and (числа["План"] or числа["Факт"] or числа["ПНФ"])):
            итог = dict(числа, имя=" ".join(str(ячейка.value).split()))
        elif отступ == 2.0:
            имя = " ".join(str(ячейка.value).split()) if ячейка.value else "«без загальної назви»"
            позиции.append(dict(числа, имя=имя))
        elif отступ == 0 and ячейка.value is None and числа["Факт"] > 0:
            позиции.append(dict(числа, имя="«без загальної назви»"))
    return итог, позиции


def факторы(позиции):
    """Ценовой и количественный фактор каждой позиции + её тип."""
    результат = []
    for п in позиции:
        цена_план = (п["План"] / п["ПланКол"]) if п["ПланКол"] else 0.0
        if п["ФактКол"] > 0 and п["ПланКол"] > 0:
            ценовой = п["Факт"] - п["ФактКол"] * цена_план
            количественный = max(0.0, п["ФактКол"] - п["ПланКол"]) * цена_план
            тип = "ціна" if abs(ценовой) >= abs(количественный) else "кількість"
        elif п["Факт"] > 0 and п["ПланКол"] == 0:
            ценовой, количественный, тип = 0.0, п["Факт"], "поза кошторисом"
        else:
            ценовой = количественный = 0.0
            тип = "не закуповували"
        результат.append(dict(п, ЦенаПлан=цена_план, Ценовой=ценовой,
                              Количественный=количественный, Тип=тип,
                              Отклонение=п["ПНФ"] - п["План"]))
    return результат


def читать_шапку(путь, вид):
    """Верхняя строка отчёта: деньги и часы объекта."""
    ws = книга(путь)[ЛИСТ]
    к = колонки(ws)
    for r in range(8, 20):
        ячейка = ws.cell(r, 1)
        if ячейка.value and (ячейка.alignment.indent or 0) == 0:
            def ч(c):
                значение = ws.cell(r, c).value if c else None
                return float(значение) if isinstance(значение, (int, float)) else 0.0
            # r8..r13 — подписи группировок («Блок», «Етап», «Загальна назва»…) без чисел:
            # шапка объекта — первая строка нулевого уровня, где числа есть
            if not any(ч(c) for c in к.values()):
                continue
            if вид == "планфакт":
                return dict(имя=" ".join(str(ячейка.value).split()),
                            ПланГод=ч(кол(к, "план, год")), ФактГод=ч(кол(к, "факт, год")),
                            ПланГрн=ч(кол(к, "план, грн")), ПНФ=ч(кол(к, "план на факт")))
            return dict(имя=" ".join(str(ячейка.value).split()),
                        Факт=ч(кол(к, "факт, год")), Виконання=ч(кол(к, "виконання, год")),
                        Процент=ч(кол(к, "% виконання до факту")))
    return None


def позиции_планфакт(путь):
    """Позиции блока «2. Матеріали» файла план-факта: имя → План и ПНФ (для дельт недели)."""
    ws = книга(путь)[ЛИСТ]
    к = колонки(ws)
    c_план, c_пнф = кол(к, "план, грн"), кол(к, "план на факт")

    def ч(r, c):
        значение = ws.cell(r, c).value if c else None
        return float(значение) if isinstance(значение, (int, float)) else 0.0

    карта, в_материалах = {}, False
    for r in range(8, ws.max_row + 1):
        ячейка = ws.cell(r, 1)
        имя = " ".join(str(ячейка.value).split()) if ячейка.value else ""
        отступ = ячейка.alignment.indent or 0
        if отступ == 2.0 and имя:
            в_материалах = имя.lower().startswith("2.")
        elif в_материалах and отступ == 4.0 and имя:
            карта[имя] = dict(План=ч(r, c_план), ПНФ=ч(r, c_пнф))
    return карта


def этапы(путь):
    """Этапы работ (indent 2.0) файла «Звіт з виконання СС»: имя → виконання, год."""
    ws = книга(путь)[ЛИСТ]
    c = кол(колонки(ws), "виконання, год")
    карта = {}
    for r in range(8, ws.max_row + 1):
        ячейка = ws.cell(r, 1)
        if ячейка.value and (ячейка.alignment.indent or 0) == 2.0:
            значение = ws.cell(r, c).value if c else None
            карта[" ".join(str(ячейка.value).split())] = (
                float(значение) if isinstance(значение, (int, float)) else 0.0)
    return карта


def деньги(x):
    return f"{x:,.2f}".replace(",", "\u00a0").replace(".", ",")


def main():
    по_умолчанию = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki"
                    r"\Письмо Директору по отчетам на производство\19082026")
    папка = (sys.argv[1] if len(sys.argv) > 1 else по_умолчанию).rstrip("\\/")
    детальный = найти_файл(папка, "План на факт за матеріалами детально")
    if детальный is None:
        print("ОШИБКА: в папке нет файла «План на факт за матеріалами детально…»")
        return 1

    итог, позиции = читать_детальный(детальный)
    строки = факторы(позиции)

    ценовой = sum(с["Ценовой"] for с in строки)
    количественный = sum(с["Количественный"] for с in строки)
    отклонение = итог["ПНФ"] - итог["План"]
    вне_сметы = sum(с["Количественный"] for с in строки if с["Тип"] == "поза кошторисом")

    print(f"Файл  : {os.path.basename(детальный)}")
    print(f"Обʼєкт: {итог['имя']}, позицій {len(строки)}")
    print(f"\nПлан {деньги(итог['План'])} | Факт {деньги(итог['Факт'])} | "
          f"План на факт {деньги(итог['ПНФ'])}")
    print(f"Економія {деньги(-отклонение)} ({-отклонение / итог['План'] * 100:.1f} %)")
    print(f"\n  ціновий фактор    {деньги(ценовой):>18}")
    print(f"  кількісний фактор {деньги(количественный):>18}  "
          f"(поза кошторисом {деньги(вне_сметы)}, понад план {деньги(количественный - вне_сметы)})")
    print(f"  сума факторів     {деньги(ценовой + количественный):>18}")
    print(f"  невʼязка          {деньги(ценовой + количественный - отклонение):>18}")

    def показать(заголовок, отобранные, поле):
        print(f"\n=== {заголовок} ===")
        for с in отобранные:
            доля = (с["ЦенаФакт"] / с["ЦенаПлан"] * 100) if с["ЦенаПлан"] else 0
            print(f"  {с['имя'][:34]:34} {деньги(с[поле]):>16}  "
                  f"ціна {деньги(с['ЦенаПлан']):>12} → {деньги(с['ЦенаФакт']):>12} ({доля:.0f} %) "
                  f" к-сть {с['ПланКол']:,.2f} → {с['ФактКол']:,.2f}")

    показать("ТОП цінової економії",
             sorted([с for с in строки if с["Ценовой"] < 0], key=lambda с: с["Ценовой"])[:10],
             "Ценовой")
    показать("ТОП цінової перевитрати",
             sorted([с for с in строки if с["Ценовой"] > 0], key=lambda с: -с["Ценовой"])[:10],
             "Ценовой")
    показать("ТОП кількісної перевитрати",
             sorted([с for с in строки if с["Количественный"] > 0],
                    key=lambda с: -с["Количественный"])[:10],
             "Количественный")

    print("\n=== ТОП економії наростаючим підсумком (План − ПНФ) ===")
    for с in sorted(строки, key=lambda с: с["Отклонение"])[:8]:
        if с["Отклонение"] < 0:
            print(f"  {с['имя'][:34]:34} план {деньги(с['План']):>16} → ПНФ {деньги(с['ПНФ']):>16}"
                  f"  економія {деньги(-с['Отклонение']):>15} [{с['Тип']}]")

    print("\n=== ТОП перевитрат наростаючим підсумком ===")
    for с in sorted(строки, key=lambda с: -с["Отклонение"])[:8]:
        if с["Отклонение"] > 0:
            print(f"  {с['имя'][:34]:34} план {деньги(с['План']):>16} → ПНФ {деньги(с['ПНФ']):>16}"
                  f"  перевитрата {деньги(с['Отклонение']):>13} [{с['Тип']}]")

    print(f"\n=== Поза кошторисом, разом {деньги(вне_сметы)} ===")
    for с in sorted([с for с in строки if с["Тип"] == "поза кошторисом"],
                    key=lambda с: -с["Факт"])[:8]:
        print(f"  {с['имя'][:34]:34} {деньги(с['Факт']):>16}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
