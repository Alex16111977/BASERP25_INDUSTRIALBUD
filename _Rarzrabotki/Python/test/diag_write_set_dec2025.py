# -*- coding: utf-8 -*-
"""Изоляция: ПровестиБалансСвод → записать ТОЛЬКО набор А_ОтчетБаланс_Свод
этого регистратора (.Записать()) и поймать ошибку дубля. Если падает —
причина в свёрнутом наборе и платформенный ключ ≠ моему анализу
(тогда печатаем дубль по реальному набору после повторной выгрузки)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client
from collections import defaultdict
from datetime import datetime

conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
qO = conn.NewObject("Запрос")
qO.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
sO = qO.Выполнить().Выбрать(); sO.Следующий(); ORG = sO.С
qD = conn.NewObject("Запрос")
qD.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С, Номер КАК Н
ИЗ Документ.А_ФинРез_Баланс ГДЕ Организация=&Орг И НЕ ПометкаУдаления
    И Месяц >= &Н1 И Месяц <= &Н2 И ВключатьДочерние = ЛОЖЬ УПОРЯДОЧИТЬ ПО Дата"""
qD.УстановитьПараметр("Орг", ORG)
qD.УстановитьПараметр("Н1", datetime(2025,12,1)); qD.УстановитьПараметр("Н2", datetime(2025,12,31,23,59,59))
rD = qD.Выполнить().Выбрать(); rD.Следующий(); ref = rD.С
об = ref.ПолучитьОбъект()
qb = conn.NewObject("Запрос")
qb.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КМ")
qb.УстановитьПараметр("М", об.Месяц); rb = qb.Выполнить().Выбрать(); rb.Следующий()
ш = conn.NewObject("Структура")
for kk, vv in (("Ссылка",ref),("Дата",об.Дата),("НачМес",rb.НМ),("КонМес",rb.КМ),
               ("Организация",об.Организация),("ВключатьДочерние",об.ВключатьДочерние)):
    ш.Вставить(kk, vv)
об.ПровестиБалансСвод(ш, False)
наб = об.Движения.А_ОтчетБаланс_Свод
print(f"После ПровестиБалансСвод: набор строк={наб.Количество()}")

try:
    наб.Записать()  # запись набора регистра этого регистратора
    print("[OK] набор А_ОтчетБаланс_Свод записан без дубля")
    # откатим: очистим набор регистратора, чтобы не оставлять данные у непроведённого
    наб.Очистить(); наб.Записать()
    print("(набор очищен — документ остаётся непроведённым)")
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    print(f"[FAIL набор] {msg}")
    # повторная выгрузка и поиск дубля по ПЛАТФОРМЕННОМУ ключу
    ТЗ = наб.Выгрузить()
    DIMS = ["Организация","Подразделение","Статья","Номенклатура","Контрагент",
            "Партнер","Склад","ОбъектыЭксплуатации","Договор","ФизическоеЛицо",
            "ДенежныеСредства","Source","Расхождение","Аналитика1","Аналитика2",
            "Аналитика3","ОбъектРасчетов","НематериальныйАктив","ДокументДвижения"]
    def k(v):
        if isinstance(v, bool): return f"B{int(v)}"
        if v is None: return "·∅·"
        try:
            if not conn.ЗначениеЗаполнено(v): return "·∅·"
        except Exception: pass
        try: return conn.XMLСтрока(v)
        except Exception: return str(v)
    g = defaultdict(list)
    for i in range(ТЗ.Количество()):
        r = ТЗ.Получить(i)
        g[tuple(k(getattr(r, d)) for d in DIMS)].append(i)
    d = {kk: v for kk, v in g.items() if len(v) > 1}
    print(f"набор строк={ТЗ.Количество()}; дублей платформ.ключа={len(d)}")
    for kk, idxs in list(d.items())[:10]:
        показ = {DIMS[j]: kk[j] for j in range(len(DIMS)) if kk[j] not in ("·∅·","B0")}
        print(f"  ДУБЛЬ {len(idxs)}: {показ}")
        for i in idxs[:3]:
            r = ТЗ.Получить(i)
            рес = {x: float(getattr(r,x) or 0) for x in
                   ("СуммаНачальныйОстаток","СуммаПриход","СуммаРасход","СуммаКонечныйОстаток")}
            print(f"    стр[{i}] рес={рес}")
print("=" * 64)
