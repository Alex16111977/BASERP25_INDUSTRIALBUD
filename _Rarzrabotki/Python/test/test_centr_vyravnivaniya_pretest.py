def err_text(e):
    if hasattr(e, 'excepinfo') and e.excepinfo and e.excepinfo[2]:
        return e.excepinfo[2]
    return str(e)


def run_query(title, text, params=None, show_rows=20, mask_cols=None):
    """Выполняет запрос, печатает текст, колонки и строки. Возвращает ТЗ или None."""
    print()
    print("=" * 78)
    print(title)
    print("-" * 78)
    print(text.strip())
    print("-" * 78)
    q = erp.NewObject("Запрос")
    q.Text = text
    if params:
        for k, v in params.items():
            q.SetParameter(k, v)
    try:
        tbl = q.Execute().Выгрузить()
    except Exception as e:
        print(f"[FAIL] {err_text(e)}")
        return None
    n = tbl.Количество()
    ncols = tbl.Колонки.Количество()
    cols = [tbl.Колонки.Получить(i).Имя for i in range(ncols)]
    print(f"[OK] строк={n}, колонки: {', '.join(cols)}")
    mask_cols = mask_cols or set()
    for i in range(min(n, show_rows)):
        row = tbl.Получить(i)
        vals = []
        for c in cols:
            try:
                raw = row.__getattr__(c)
                sval = S(raw)
            except Exception:
                sval = "<?>"
            if c in mask_cols and sval:
                sval = "***"
            vals.append(f"{c}={sval}")
        print("  " + " | ".join(vals))
    if n > show_rows:
        print(f"  ... ещё {n - show_rows} строк")
    return tbl


