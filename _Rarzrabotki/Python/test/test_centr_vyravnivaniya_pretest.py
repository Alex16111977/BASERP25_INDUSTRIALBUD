def test_broken_refs(cat_name, has_groups):
    print()
    print(f"### П.4 Санация битых ссылок: Справочник.{cat_name} ###")
    q = erp.NewObject("Запрос")
    filtr = " ГДЕ НЕ Т.ЭтоГруппа" if has_groups else ""
    q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 5 Т.Ссылка ИЗ Справочник.%s КАК Т%s"
              % (cat_name, filtr))
    t = q.Execute().Выгрузить()
    arr = erp.NewObject("Массив")
    real_uuids = []
    for i in range(t.Количество()):
        ref = t.Получить(i).Ссылка
        arr.Добавить(ref)
        real_uuids.append(S(ref.УникальныйИдентификатор()))
    # сфабрикованная битая ссылка — НЕ записываем!
    fake_uid = erp.NewObject("УникальныйИдентификатор")
    cat_mgr = getattr(erp.Справочники, cat_name)
    fake_ref = cat_mgr.ПолучитьСсылку(fake_uid)
    fake_uuid = S(fake_ref.УникальныйИдентификатор())
    arr.Добавить(fake_ref)
    print(f"Передано ссылок: {arr.Количество()} (5 реальных + 1 битая {fake_uuid})")
    tbl = run_query(f"П.4 Проверка существования ({cat_name})",
                    Q4_TEMPLATE % cat_name, {"Массив": arr}, show_rows=0)
    if tbl is None:
        return
    found = set()
    for i in range(tbl.Количество()):
        found.add(S(tbl.Получить(i).Ссылка.УникальныйИдентификатор()))
    print(f"Вернулось: {len(found)} ссылок")
    if fake_uuid in found:
        print(f"[FAIL] битая ссылка {fake_uuid} ПОПАЛА в результат!")
    else:
        print(f"[OK] битая ссылка {fake_uuid} в результат НЕ попала")
    missing_real = [u for u in real_uuids if u not in found]
    if missing_real:
        print(f"[WARN] не вернулись реальные: {missing_real}")
    else:
        print("[OK] все 5 реальных вернулись")


