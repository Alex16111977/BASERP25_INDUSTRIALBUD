def get_exchange_node(plan_name):
    plan_mgr = getattr(erp.ПланыОбмена, plan_name)
    this_node = plan_mgr.ЭтотУзел()
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ ПЕРВЫЕ 1
        Узлы.Ссылка КАК Ссылка,
        Узлы.Код КАК Код,
        Узлы.Наименование КАК Наименование
    ИЗ
        ПланОбмена.%s КАК Узлы
    ГДЕ
        НЕ Узлы.ПометкаУдаления
        И Узлы.Ссылка <> &ЭтотУзел
    """ % plan_name
    q.SetParameter("ЭтотУзел", this_node)
    tbl = q.Execute().Выгрузить()
    if tbl.Количество() == 0:
        return None
    row = tbl.Получить(0)
    print(f"Узел плана {plan_name}: Код={S(row.Код)} Наименование={S(row.Наименование)}")
    return row.Ссылка


