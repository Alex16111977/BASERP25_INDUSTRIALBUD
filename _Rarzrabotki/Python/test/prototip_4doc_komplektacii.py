# 4 бакета: (склад, категория) -> сумма ; категория = 'Н' (по нормам) / 'Д' (доп)
buckets = {}
def add(склад, кат, кол):
    buckets[(склад, кат)] = buckets.get((склад, кат), 0.0) + кол

for k, g in группы.items():
    cap = норма.get(k, 0.0) if g["есть"] else 0.0
    for ном, склад, кол in sorted(g["rows"], key=lambda x: -x[2]):  # порядок А
        вн = min(кол, cap) if cap > 0 else 0.0
        cap -= вн
        if вн > 0: add(склад, "Н", вн)
        if кол - вн > 0: add(склад, "Д", кол - вн)

Σост = sum(r[2] for g in группы.values() for r in g["rows"])
