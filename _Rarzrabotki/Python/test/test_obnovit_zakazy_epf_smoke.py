# -*- coding: utf-8 -*-
"""Smoke собранной обработки «Обновить заказы поставщика» (режим анализа, без записи)."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ПУТЬ = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Обновить заказы поставщика.epf"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

провал = 0


def проверка(имя, условие, деталь=""):
    global провал
    print(("  OK   " if условие else "  FAIL ") + имя + (" | " + деталь if деталь else ""))
    if not условие:
        провал += 1


print("=" * 74)
print("SMOKE: Обновить заказы поставщика")
print("=" * 74)

обр = erp.ВнешниеОбработки.Создать(ПУТЬ, False)
проверка("1. Обработка создана", обр is not None)

# границы периода считаем на стороне 1С (COM-дата теряет день)
q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ДАТАВРЕМЯ(2025,12,1,0,0,0) КАК Н, "
          "КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2025,12,1,0,0,0), МЕСЯЦ) КАК К")
гр = q.Execute().Выгрузить().Получить(0)
НачПериода, КонПериода = гр.Получить(0), гр.Получить(1)

реестр = обр.ПолучитьРеестрЗаказов(НачПериода, КонПериода)
проверка("2. Реестр получен", реестр.Количество() > 0,
         "заказов = %s" % S(реестр.Количество()))

колонки = [реестр.Колонки.Получить(i).Имя for i in range(реестр.Колонки.Количество())]
нужные = ["Обновлять", "Заказ", "Номер", "Дата", "Контрагент", "Статус", "Приходов",
          "СтрокЗаказаДо", "СтрокКОбновлению", "СуммаСводаСНДС", "ЗаказИзменится",
          "ПриходовКПерепроведению", "Предупреждение", "Результат"]
проверка("3. Колонки реестра на месте",
         all(к in колонки for к in нужные),
         "нет: " + ", ".join(к for к in нужные if к not in колонки))

# анализ по первым 30 заказам, чтобы smoke был быстрым
for i in range(реестр.Количество()):
    реестр.Получить(i).Обновлять = (i < 30)

параметры = erp.NewObject("Структура")
параметры.Вставить("ТолькоАнализ", True)
параметры.Вставить("ПереводитьСогласованВПодтвержден", False)

результат = обр.ВыполнитьОбработку(реестр, параметры)
проверка("4. ВыполнитьОбработку отработала", результат is not None)

ст = результат.Статистика
проверка("5. Ошибок нет", int(S(ст.ЗаказОшибка)) == 0,
         "ошибок = %s" % S(ст.ЗаказОшибка))
проверка("6. Анализ ничего не записал (счётчик обновлённых = 0)",
         int(S(ст.ЗаказОбновлён)) == 0 and int(S(ст.ПриходОбновлён)) == 0,
         "заказов %s / приходов %s" % (S(ст.ЗаказОбновлён), S(ст.ПриходОбновлён)))
проверка("7. Гейт работает — есть «без изменений»",
         int(S(ст.ЗаказБезИзменений)) > 0,
         "без изменений = %s" % S(ст.ЗаказБезИзменений))
проверка("8. Строк без пары нет", int(S(ст.СтрокБезПары)) == 0,
         "без пары = %s" % S(ст.СтрокБезПары))

print()
print("  Сводка движка:")
for строка in S(обр.ПредставлениеСтатистики(ст)).split("\n"):
    print("    " + строка)

print()
print("=" * 74)
print("ПРОВАЛОВ: %d" % провал)
sys.exit(1 if провал else 0)
