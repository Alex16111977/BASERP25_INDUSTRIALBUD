"""Headless-рендер СКД отчёта в TXT — увидеть реальную раскладку без UI.
Композирует СхемаКомпоновкиДанных + НастройкиПоУмолчанию + внешний набор Расшифровка,
выводит в ТабличныйДокумент, сохраняет TXT для инспекции (где Сальдо/Сумма).
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import os, pythoncom, win32com.client

ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
ERF = (r"C:\Configuration_downloads\BASERP25\.claude\worktrees"
       r"\charming-allen-2fc47b\_Rarzrabotki\Отчеты"
       r"\А_РасшифровкаЗадолженностиПодразделений.erf")
OUT = r"C:\Users\support1c\AppData\Local\Temp\rasshifrovka_render.txt"

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(ERP)
отчёт = conn.ВнешниеОтчеты.Создать(ERF, False)

# узкое окно вокруг 000Ц-000548 (31.12) + немного, чтобы объём был мал
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2025,12,30) КАК Н, ДАТАВРЕМЯ(2025,12,31,23,59,59) КАК К"
rr = q.Выполнить().Выбрать(); rr.Следующий()
П = conn.NewObject("Структура")
П.Вставить("НачалоПериода", rr.Н)
П.Вставить("ОкончаниеПериода", rr.К)
П.Вставить("Организация", None)
П.Вставить("ТолькоРасхождения", False)
П.Вставить("ВключатьНепроведенные", True)
ТЗ = отчёт.ПолучитьТаблицуРасшифровки(П)
print("строк ТЗ:", ТЗ.Количество())

схема = отчёт.СхемаКомпоновкиДанных
print("ВариантовНастроек:", схема.ВариантыНастроек.Количество())
for vi in range(схема.ВариантыНастроек.Количество()):
    print("  вариант[%d]: имя=%r" % (vi, схема.ВариантыНастроек.Получить(vi).Имя))
# Рендерим ИМЕННО сохранённый вариант (его использует форма отчёта), а не НастройкиПоУмолчанию.
if схема.ВариантыНастроек.Количество() > 0:
    настройки = схема.ВариантыНастроек.Получить(0).Настройки
    print(">>> рендер сохранённого варианта 'Основной'")
else:
    настройки = схема.НастройкиПоУмолчанию
    print(">>> рендер НастройкиПоУмолчанию")
вн = conn.NewObject("Структура"); вн.Вставить("Расшифровка", ТЗ)

др = conn.NewObject("ДанныеРасшифровкиКомпоновкиДанных")
кмакета = conn.NewObject("КомпоновщикМакетаКомпоновкиДанных")
макет = кмакета.Выполнить(схема, настройки, др)
проц = conn.NewObject("ПроцессорКомпоновкиДанных")
проц.Инициализировать(макет, вн, др)
табдок = conn.NewObject("ТабличныйДокумент")
вывод = conn.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
вывод.УстановитьДокумент(табдок)
вывод.Вывести(проц)

print("ТабДок: строк=%d колонок=%d" % (табдок.ВысотаТаблицы, табдок.ШиринаТаблицы))
табдок.Записать(OUT, conn.ТипФайлаТабличногоДокумента.TXT)
print("СОХРАНЕНО:", OUT)

# дополнительно — печатаем непустые ячейки первых ~60 строк с номером колонки
H = min(табдок.ВысотаТаблицы, 70)
W = табдок.ШиринаТаблицы
for r in range(1, H + 1):
    cells = []
    for c in range(1, W + 1):
        t = табдок.Область(r, c, r, c).Текст
        if t:
            cells.append(f"[{c}]{t}")
    if cells:
        print(f"r{r:>3}: " + " | ".join(cells))
