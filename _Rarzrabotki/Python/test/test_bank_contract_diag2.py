# -*- coding: utf-8 -*-
"""Діагностика 2: перевіряємо де саме зберігається підрозділ в документах списання
для договору 'Договір 18/СК від 13.01.2025'
"""
import win32com.client
import datetime

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

print("Connecting to BaseERP...")
conn = v8.Connect(CONN_ERP)
print("Connected OK\n")

# 1. Знайти договір
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Спр.Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Спр
    ГДЕ Спр.Наименование ПОДОБНО &Наим"""
q.SetParameter("Наим", "%18/СК%13.01.2025%")
res = q.Execute()
sel = res.Select()
sel.Next()
contract_ref = sel.Ссылка
print(f"Договір: {contract_ref}\n")

# 2. Знайти ВСІ документи списання для цього договору (без фільтру по А_Подразделение)
print("=" * 70)
print("ВСІ ДОКУМЕНТИ СПИСАННЯ (без фільтру по А_Подразделение)")
print("=" * 70)

q2 = conn.NewObject("Запрос")
q2.Text = """ВЫБРАТЬ ПЕРВЫЕ 10
    Док.Ссылка,
    Док.Номер КАК Номер,
    Док.Дата КАК ДатаДок,
    Док.А_Подразделение КАК А_Подразделение,
    Док.А_НаправлениеДеятельности КАК А_НаправлениеДеятельности,
    Док.Подразделение КАК Подразделение,
    Док.НаправлениеДеятельности КАК НаправлениеДеятельности
ИЗ
    Документ.СписаниеБезналичныхДенежныхСредств КАК Док
ГДЕ
    Док.Проведен
    И Док.Договор = &Договор
    И Док.Дата >= &Дата1
УПОРЯДОЧИТЬ ПО
    Док.Дата"""
q2.SetParameter("Договор", contract_ref)
q2.SetParameter("Дата1", datetime.datetime(2025, 12, 1))

res2 = q2.Execute()
sel2 = res2.Select()
count = 0
while sel2.Next():
    count += 1
    print(f"\n  #{count} Док #{sel2.Номер} от {sel2.ДатаДок}")
    print(f"    А_Подразделение: '{sel2.А_Подразделение}' filled={conn.ValueIsFilled(sel2.А_Подразделение)}")
    print(f"    А_НаправлениеДеятельности: '{sel2.А_НаправлениеДеятельности}' filled={conn.ValueIsFilled(sel2.А_НаправлениеДеятельности)}")
    print(f"    Подразделение (стандарт): '{sel2.Подразделение}' filled={conn.ValueIsFilled(sel2.Подразделение)}")
    print(f"    НаправлениеДеятельности (стандарт): '{sel2.НаправлениеДеятельности}' filled={conn.ValueIsFilled(sel2.НаправлениеДеятельности)}")

print(f"\nВсього знайдено: {count}")

if count == 0:
    # Може договір в РасшифровкаПлатежа?
    print("\n" + "=" * 70)
    print("ПЕРЕВІРКА: може договір не в шапці, а в РасшифровкаПлатежа?")
    print("=" * 70)

    q3 = conn.NewObject("Запрос")
    q3.Text = """ВЫБРАТЬ ПЕРВЫЕ 10
        Док.Ссылка КАК ДокСсылка,
        Док.Номер КАК Номер,
        Док.Дата КАК ДатаДок,
        Док.А_Подразделение КАК А_Подразделение,
        Док.А_НаправлениеДеятельности КАК А_НаправлениеДеятельности,
        Док.Подразделение КАК Подразделение,
        Док.НаправлениеДеятельности КАК НаправлениеДеятельности,
        РП.А_Договор КАК РП_Договор,
        РП.Подразделение КАК РП_Подразделение,
        РП.НаправлениеДеятельности КАК РП_НаправлениеДеятельности
    ИЗ
        Документ.СписаниеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК РП
        ЛЕВОЕ СОЕДИНЕНИЕ Документ.СписаниеБезналичныхДенежныхСредств КАК Док
        ПО РП.Ссылка = Док.Ссылка
    ГДЕ
        Док.Проведен
        И РП.А_Договор = &Договор
        И Док.Дата >= &Дата1
    УПОРЯДОЧИТЬ ПО
        Док.Дата"""
    q3.SetParameter("Договор", contract_ref)
    q3.SetParameter("Дата1", datetime.datetime(2025, 12, 1))

    res3 = q3.Execute()
    sel3 = res3.Select()
    count3 = 0
    while sel3.Next():
        count3 += 1
        print(f"\n  #{count3} Док #{sel3.Номер} от {sel3.ДатаДок}")
        print(f"    ШАПКА: А_Подразделение='{sel3.А_Подразделение}' filled={conn.ValueIsFilled(sel3.А_Подразделение)}")
        print(f"    ШАПКА: А_НаправлениеДеятельности='{sel3.А_НаправлениеДеятельности}' filled={conn.ValueIsFilled(sel3.А_НаправлениеДеятельности)}")
        print(f"    ШАПКА: Подразделение='{sel3.Подразделение}' filled={conn.ValueIsFilled(sel3.Подразделение)}")
        print(f"    ШАПКА: НаправлениеДеятельности='{sel3.НаправлениеДеятельности}' filled={conn.ValueIsFilled(sel3.НаправлениеДеятельности)}")
        print(f"    РП: А_Договор='{sel3.РП_Договор}'")
        print(f"    РП: Подразделение='{sel3.РП_Подразделение}' filled={conn.ValueIsFilled(sel3.РП_Подразделение)}")
        print(f"    РП: НаправлениеДеятельности='{sel3.РП_НаправлениеДеятельности}' filled={conn.ValueIsFilled(sel3.РП_НаправлениеДеятельности)}")

    print(f"\nВсього знайдено в РасшифровкаПлатежа: {count3}")

# 3. Перевірка - може договір в шапці тільки для деяких?
