# -*- coding: utf-8 -*-
"""Тест: створення РАСХОД в ПрочиеАктивыПассивы напряму з НачисленнаяАмортизация.
Використовуємо COM для доступу до ДополнительныеСвойства документа."""
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# 1. Знайти документ
q = conn.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Д.Ссылка ИЗ Документ.АмортизацияОС КАК Д
ГДЕ Д.Номер = "000Ц-000001" И Д.Дата >= &Д1 И Д.Дата <= &Д2"""
q.SetParameter("Д1", conn.NewObject("Дата", 2025, 12, 31))
q.SetParameter("Д2", conn.NewObject("Дата", 2026, 1, 1))
res = q.Execute().Select()
if not res.Next():
    print("Документ не знайдено!")
    exit()
doc_ref = res.Ссылка
print(f"Документ: {S(doc_ref)}")

# 2. Перевірити поточні рухи ПрочиеРасходы — чи є аналітика
q2 = conn.NewObject("Запрос")
q2.Text = """ВЫБРАТЬ ПЕРВЫЕ 5
    ПР.СтатьяРасходов, ПР.АналитикаРасходов, ПР.СуммаРегл, ПР.ВидДвижения
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &Рег И ПР.СуммаРегл > 0"""
q2.SetParameter("Рег", doc_ref)
tbl = q2.Execute().Unload()
print(f"\nПрочиеРасходы (перші 5 з СуммаРегл > 0): {tbl.Count()} записів")
for i in range(min(5, tbl.Count())):
    r = tbl.Get(i)
    print(f"  {S(r.ВидДвижения)}: {S(r.СтатьяРасходов)} | Аналітика={S(r.АналитикаРасходов)} | Регл={r.СуммаРегл}")

# 3. Перевірити поточні рухи ПрочиеАктивыПассивы
q3 = conn.NewObject("Запрос")
q3.Text = """ВЫБРАТЬ АП.ВидДвижения, АП.Статья, АП.Аналитика, АП.Сумма, АП.Подразделение
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК АП
ГДЕ АП.Регистратор = &Рег"""
q3.SetParameter("Рег", doc_ref)
tbl3 = q3.Execute().Unload()
print(f"\nПрочиеАктивыПассивы: {tbl3.Count()} записів")
for i in range(tbl3.Count()):
    r = tbl3.Get(i)
    print(f"  {S(r.ВидДвижения)}: Стаття={S(r.Статья)} | Аналітика={S(r.Аналитика)} | Сума={r.Сумма} | Підрозділ={S(r.Подразделение)}")

# 4. Якщо аналітика порожня — створити рухи з НачисленнаяАмортизация
print("\n" + "="*60)
print("Створення рухів ПрочиеАктивыПассивы з НачисленнаяАмортизация...")

# Отримати дані амортизації безпосередньо
q4 = conn.NewObject("Запрос")
q4.Text = """ВЫБРАТЬ
    ПР.Период, ПР.Организация, ПР.Подразделение,
    ПР.НаправлениеДеятельности, ПР.АналитикаРасходов,
    СУММА(ПР.СуммаРегл) КАК Сумма
ИЗ РегистрНакопления.ПрочиеРасходы КАК ПР
ГДЕ ПР.Регистратор = &Рег
    И ПР.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
    И ПР.СуммаРегл > 0
СГРУППИРОВАТЬ ПО
    ПР.Период, ПР.Организация, ПР.Подразделение,
    ПР.НаправлениеДеятельности, ПР.АналитикаРасходов"""
q4.SetParameter("Рег", doc_ref)
tbl4 = q4.Execute().Unload()
print(f"Записів для ПрочиеАктивыПассивы: {tbl4.Count()}")

if tbl4.Count() == 0:
    print("Немає даних!")
    exit()

# Отримати значення
VD_RASHOD = conn.Enums.ВидыДвиженийНакопления.Расход
STATYA_OS = conn.ChartsOfCharacteristicTypes.СтатьиАктивовПассивов.ОсновныеСредства

# Очистити старі і створити нові
nabor = conn.AccumulationRegisters.ПрочиеАктивыПассивы.CreateRecordSet()
nabor.Filter.Регистратор.Set(doc_ref)
nabor.Read()
old_count = nabor.Count()

# Видалити старі записи цього регістратора
nabor.Clear()

total = 0
for i in range(tbl4.Count()):
    row = tbl4.Get(i)
    rec = nabor.Add()
    rec.RecordType = VD_RASHOD
    rec.Period = row.Период
    rec.Организация = row.Организация
    rec.Подразделение = row.Подразделение
    rec.НаправлениеДеятельности = row.НаправлениеДеятельности
    rec.Статья = STATYA_OS
    rec.Аналитика = row.АналитикаРасходов  # ОбъектЭксплуатации з ПрочиеРасходы
    rec.Сумма = row.Сумма
    total += row.Сумма
    anal_str = S(row.АналитикаРасходов) if row.АналитикаРасходов else "<порожня>"
    print(f"  РАСХОД: {S(row.Подразделение)} | {anal_str} | {row.Сумма}")

print(f"\nВсього: {total}")
print(f"Старих записів: {old_count}, нових: {nabor.Count()}")

try:
    nabor.Write()
    print("ЗАПИСАНО!")
except Exception as e:
    print(f"ПОМИЛКА: {e}")

# 5. Перевірити результат
tbl5 = q3.Execute().Unload()
print(f"\nПрочиеАктивыПассивы ПІСЛЯ: {tbl5.Count()} записів")
for i in range(tbl5.Count()):
    r = tbl5.Get(i)
    anal = S(r.Аналитика) if r.Аналитика else "<порожня>"
    print(f"  {S(r.ВидДвижения)}: Стаття={S(r.Статья)} | Аналітика={anal} | Сума={r.Сумма}")
