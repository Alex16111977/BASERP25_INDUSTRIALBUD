# Регистраторы, которые штатно пишут только в ПАП или только в ПоСрокам —
# не считать их аномалиями
СЛУЖЕБНЫЕ = {
    'РегистраторРасчётов', 'РегистраторРасчетов',
    'КорректировкаРегистров',
    'А_ФинРез_Баланс', 'А_БюджетМесяц',
    'ЗакрытиеМесяца', 'РаспределениеДоходов', 'РаспределениеРасходов',
}

v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Орг
q = erp.NewObject('Запрос')
q.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации ГДЕ Наименование ПОДОБНО "%НДАСТРІАЛБУД%"'
