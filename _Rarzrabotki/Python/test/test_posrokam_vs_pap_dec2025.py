if not аномалии:
    print('Аномалий не найдено. Все документы пишут в ПАП и ПоСрокам согласованно.')
else:
    print('=' * 130)
    показать = min(len(аномалии), 50)
    print(f'ТОП-{показать} АНОМАЛИЙ — документы где ΔПАП ≠ ΔПоСрокам по клиентам/поставщикам')
    print('=' * 130)
    print(f'{"Документ":<70} {"ΔКл":>14} {"ΔПост":>14}')
    print('-' * 130)
    for зап in аномалии[:50]:
        рег = зап['рег']
        if рег is None:
            подпись = f'{зап["тип"]} <NULL>'
        else:
            try:
                ном = str(рег.Номер).strip()
                дата = рег.Дата.strftime('%Y-%m-%d')
                подпись = f'{зап["тип"]} № {ном} от {дата}'
            except Exception:
                подпись = f'{зап["тип"]} <?>'
        print(f'{подпись:<70} {зап["Дельта_Кл"]:>+14,.2f} {зап["Дельта_Пост"]:>+14,.2f}', flush=True)
