print(f'Всего регистраторов с движениями в ПАП/ПоСрокам за декабрь: {всего}', flush=True)

аномалии = []
ok_count = 0
служебных = 0

for i in range(всего):
    row = r.Получить(i)
    рег = row.Рег
    если_заполнен = bool(рег) and erp.ЗначениеЗаполнено(рег)
    тип = ''
    if если_заполнен:
        try:
            тип = рег.Метаданные().Имя
        except Exception:
            тип = '<неизв>'

    ПАП_ЗадКл = float(row.ПАП_ЗадКл or 0)
    ПАП_ПолучАв = float(row.ПАП_ПолучАв or 0)
    ПАП_ЗадПост = float(row.ПАП_ЗадПост or 0)
    ПАП_ВыдАв = float(row.ПАП_ВыдАв or 0)
    Кл_ДолгРегл = float(row.Кл_ДолгРегл or 0)
    Кл_ПредопРегл = float(row.Кл_ПредопРегл or 0)
    Пост_ДолгРегл = float(row.Пост_ДолгРегл or 0)
    Пост_ПредопРегл = float(row.Пост_ПредопРегл or 0)

    # Сальдо-сдвиги по двум источникам:
    # Клиенты:
    #   ПАП-net = ΔЗадКл - ΔПолучАв  (актив минус пассив, рост = клиент нам должен больше)
    #   ПоСрокам-net = ΔДолгРегл - ΔПредоплатаРегл (тоже)
    ΔКл_ПАП = ПАП_ЗадКл - ПАП_ПолучАв
    ΔКл_ПоСр = Кл_ДолгРегл - Кл_ПредопРегл
    Дельта_Кл = ΔКл_ПАП - ΔКл_ПоСр

    # Поставщики:
    #   ПАП-net = ΔЗадПост - ΔВыдАв  (мы должны минус нам должны, рост = мы должны больше)
    #   ПоСрокам-net = ΔДолгРегл - ΔПредоплатаРегл (для поставщиков ДолгРегл = наш долг, ПредоплатаРегл = аванс)
    ΔПост_ПАП = ПАП_ЗадПост - ПАП_ВыдАв
    ΔПост_ПоСр = Пост_ДолгРегл - Пост_ПредопРегл
    Дельта_Пост = ΔПост_ПАП - ΔПост_ПоСр

    запись = dict(
        тип=тип, рег=рег if если_заполнен else None,
        ΔКл_ПАП=ΔКл_ПАП, ΔКл_ПоСр=ΔКл_ПоСр, Дельта_Кл=Дельта_Кл,
        ΔПост_ПАП=ΔПост_ПАП, ΔПост_ПоСр=ΔПост_ПоСр, Дельта_Пост=Дельта_Пост,
    )

    if abs(Дельта_Кл) < ПОРОГ and abs(Дельта_Пост) < ПОРОГ:
        ok_count += 1
    elif тип in СЛУЖЕБНЫЕ:
        служебных += 1
    else:
        аномалии.append(запись)

аномалии.sort(key=lambda x: max(abs(x['Дельта_Кл']), abs(x['Дельта_Пост'])), reverse=True)

print()
print('=' * 130)
