# -*- coding: utf-8 -*-
"""Анализ: остатки на складах ПРООН vs нормы спецификации 000000003."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String  # английский регистр — надёжен через прокси

# --- 1. Склады остатков ---
qS = buh.NewObject("Запрос")
qS.Текст = '''
ВЫБРАТЬ Склады.Ссылка КАК Ссылка, Склады.Наименование КАК Наим
ИЗ Справочник.Склады КАК Склады
ГДЕ Склады.Наименование ПОДОБНО "%ПРО%ООН%виробнич%"
   ИЛИ Склады.Наименование ПОДОБНО "%ПРО%ООН%відвантаж%"
'''
tS = qS.Выполнить().Выгрузить()
склады = buh.NewObject("Массив")
print("Найдены склады остатков:")
for i in range(tS.Количество()):
    r = tS.Получить(i); склады.Добавить(r.Ссылка)
    print("  -", r.Наим)
if склады.Количество() == 0:
    print("СКЛАДЫ НЕ НАЙДЕНЫ — стоп"); sys.exit()

# --- 2. Спецификация 000000003 (нормы) ---
qN = buh.NewObject("Запрос")
qN.Текст = '''
ВЫБРАТЬ
    К.Номенклатура КАК Номенклатура,
    К.Номенклатура.Наименование КАК Наим,
    СУММА(К.Количество) КАК Норма
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Код = "000000003"
СГРУППИРОВАТЬ ПО К.Номенклатура, К.Номенклатура.Наименование
'''
tN = qN.Выполнить().Выгрузить()
нормы = {}
for i in range(tN.Количество()):
    r = tN.Получить(i); нормы[S(r.Номенклатура)] = (r.Наим, r.Норма)
print(f"\nНорм в спецификации 000000003: {len(нормы)} позиций")

# --- 3. Остатки на складах (Хозрасчетный, счета запасов, суб1=Номенклатура, суб3=Склад) ---
qO = buh.NewObject("Запрос")
qO.УстановитьПараметр("Склады", склады)
qO.Текст = '''
ВЫБРАТЬ
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) КАК Номенклатура,
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).Наименование КАК Наим,
    ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады).Наименование КАК Склад,
    Ост.Счет.Код КАК Счет,
    СУММА(Ост.КоличествоОстаток) КАК Остаток
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(
        , Счет.Код В ("201","202","203","204","205","2051","207","208","209","20","22","221","25","26","28","281","284","289"),
        , ) КАК Ост
ГДЕ Ост.КоличествоОстаток <> 0
    И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) В (&Склады)
СГРУППИРОВАТЬ ПО
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура),
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).Наименование,
    ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады).Наименование,
    Ост.Счет.Код
'''
try:
    tO = qO.Выполнить().Выгрузить()
except Exception as e:
    info = getattr(e, 'excepinfo', None)
    print("FAIL остатки:", info[2] if info else e); sys.exit()

# свернуть остатки по номенклатуре (суммарно по обоим складам и счетам)
остатки = {}
счета_исп = set()
for i in range(tO.Количество()):
    r = tO.Получить(i)
    k = S(r.Номенклатура)
    остатки[k] = остатки.get(k, [r.Наим, 0.0])
    остатки[k][1] += r.Остаток
    счета_исп.add(r.Счет)
print(f"Остатки: {len(остатки)} номенклатур на складах, счета: {sorted(счета_исп)}")

# --- 4. Сопоставление остаток vs норма ---
все = set(остатки) | set(нормы)
поНормам = доп = 0.0
строк = []
for k in все:
    наим = (остатки.get(k) or нормы.get(k))[0]
    ост = остатки.get(k, [None, 0.0])[1]
    норма = нормы.get(k, [None, 0.0])[1]
    вНорме = min(ост, норма) if норма > 0 else 0.0
    излишек = max(0.0, ост - норма)
    поНормам += вНорме; доп += излишек
    строк.append((наим, ост, норма, вНорме, излишек))

строк.sort(key=lambda x: -(x[1] or 0))
print(f"\n{'Номенклатура':42} {'Остаток':>10} {'Норма':>10} {'ПоНормам':>10} {'Доп':>10}")
for наим, ост, норма, вн, изл in строк[:30]:
    print(f"{(наим or '')[:42]:42} {ост:10.3f} {норма:10.3f} {вн:10.3f} {изл:10.3f}")

в_ост_не_в_норме = [s for s in строк if s[2] == 0 and s[1] > 0]
print(f"\nИТОГО: позиций={len(строк)}; Σ ПоНормам(мин)={поНормам:.3f}; Σ Дополнительно(излишек)={доп:.3f}")
print(f"Номенклатур в остатках, которых НЕТ в норме (целиком в Доп?): {len(в_ост_не_в_норме)}")
print(f"Номенклатур в норме, которых НЕТ в остатках: {len([s for s in строк if s[1]==0 and s[2]>0])}")
