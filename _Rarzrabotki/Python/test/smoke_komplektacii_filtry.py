# -*- coding: utf-8 -*-
"""COM-smoke доработки фильтров: многосчётный анализ (МХП ОРІЛЬ, ІНДЕПТ) + Счет на строку + этап-фильтр.
Форму COM не рендерит, преднаполнение счетов делает форма -> здесь заполняем СчетаОстатков вручную."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client, pywintypes, datetime
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

обр = buh.ВнешниеОбработки.Создать(EPF, False)
print("OK загружена:", обр.Метаданные().Имя)
print("новые ТЧ доступны: СчетаОстатков", обр.СчетаОстатков.Количество(), "/ Этапы", обр.Этапы.Количество())

# счета 20/22/28 (в форме преднаполняется автоматически; в COM — вручную)
for код in ("20", "22", "28"):
    обр.СчетаОстатков.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(код)
обр.Период = pywintypes.Time(datetime.datetime(2026, 6, 22, 12, 0, 0))
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005")
qO = buh.NewObject("Запрос"); qO.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК С ИЗ Справочник.Организации КАК О ГДЕ О.Наименование ПОДОБНО "%ІНДЕПТ%"'
tO = qO.Выполнить().Выгрузить()
обр.Организация = tO.Получить(0).С if tO.Количество() > 0 else buh.Справочники.Организации.ПустаяСсылка()
print("организация:", buh.String(обр.Организация))
qС = buh.NewObject("Запрос"); qС.Текст = 'ВЫБРАТЬ Склады.Ссылка КАК С ИЗ Справочник.Склады КАК Склады ГДЕ Склады.Наименование ПОДОБНО "%МХП%ОР%виробнич%"'
tС = qС.Выполнить().Выгрузить()
for i in range(tС.Количество()):
    обр.СкладыОстатков.Добавить().Склад = tС.Получить(i).С

# === многосчётный анализ + счёт на строку ===
обр.РассчитатьАнализ()
тч = обр.ТабличнаяЧастьОстатков
счета = {}
без_счета = 0
for i in range(тч.Количество()):
    с = тч.Получить(i).Счет
    без_счета += 1 if с.Пустая() else 0
    k = str(с.Код); счета[k] = счета.get(k, 0) + 1
print(f"АНАЛИЗ строк={тч.Количество()} счета={dict(sorted(счета.items()))} строк_без_счёта={без_счета}")
assert тч.Количество() > 0, "нет строк анализа"
assert без_счета == 0, "есть строки без счёта"
assert len(счета) >= 2, "ожидался многосчётный результат (201/221/2051)"

# === этап-фильтр: include Каркас vs exclude Каркас (норма должна отличаться) ===
def норма_сумма():
    обр.РассчитатьАнализ()
    s = 0.0
    for i in range(обр.ТабличнаяЧастьОстатков.Количество()):
        s += float(обр.ТабличнаяЧастьОстатков.Получить(i).Норма)
    return round(s, 2)

эт = buh.Справочники.ЭтапыРабот.НайтиПоНаименованию("Каркас", True)
обр.Этапы.Очистить(); обр.Этапы.Добавить().Этап = эт.Ссылка
обр.ИсключатьЭтапы = False
н_вкл = норма_сумма()
обр.ИсключатьЭтапы = True
н_искл = норма_сумма()
обр.Этапы.Очистить()
н_все = норма_сумма()
print(f"НОРМА Σ: включ.Каркас={н_вкл}  искл.Каркас={н_искл}  все_этапы={н_все}")
assert abs((н_вкл + н_искл) - н_все) < 0.01, "include + exclude должно = всем этапам"
print("SMOKE filtry: PASS")
