# -*- coding: utf-8 -*-
"""Acceptance: вызов Отчеты.А_ОтчетPL.ПолучитьОбъединенныеДанные() и проверка
колонки Аналитика для декабря 2025.

Шаги:
  1) Вызов функции отчёта за декабрь 2025.
  2) Σ СуммаЕРП по результату = Σ из регистра ПрочиеРасходы + ВыручкаИСебестоимостьПродаж + ПрочиеДоходы.
  3) Σ строк, где Документ ССЫЛКА ОтражениеЗарплатыВФинансовомУчете → Аналитика = ФизическоеЛицо.
  4) Σ строк, где Документ ССЫЛКА АвансовыйОтчет → Аналитика = ПодотчетноеЛицо.
  5) Σ строк, где Документ ССЫЛКА ПриобретениеТоваровУслуг → Аналитика = Контрагент.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom, datetime

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

НМ = datetime.datetime(2025,12,1)
КМ = datetime.datetime(2025,12,31,23,59,59)

# Вызов метода отчёта
отчёт = conn.Отчеты.А_ОтчетPL.Создать()
тз = отчёт.ПолучитьОбъединенныеДанные(НМ, КМ, False, True, True, True)

print(f"=== Отчёт А_ОтчетPL за декабрь 2025: {тз.Количество()} строк ===\n")

колонки = [c.Имя for c in тз.Колонки]
print(f"Колонки: {', '.join(колонки)}\n")

is_analitika = "Аналитика" in колонки
assert is_analitika, "Колонка Аналитика не найдена в результате!"

# Группировка по типу регистратора
типы = {}
for r in тз:
    док = r.Документ
    if not (док and conn.ЗначениеЗаполнено(док)):
        тип_ключ = "(пусто)"
    else:
        # Извлечём имя типа документа через метаданные
        мета = док.Метаданные()
        тип_ключ = мета.Имя
    if тип_ключ not in типы:
        типы[тип_ключ] = {"строк": 0, "сумма": 0.0, "Σ_аналитика_заполнен": 0, "Σ_контрагент_заполнен": 0}
    типы[тип_ключ]["строк"] += 1
    типы[тип_ключ]["сумма"] += float(r.СуммаЕРП)
    if r.Аналитика and conn.ЗначениеЗаполнено(r.Аналитика):
        типы[тип_ключ]["Σ_аналитика_заполнен"] += 1
    if r.Контрагент and conn.ЗначениеЗаполнено(r.Контрагент):
        типы[тип_ключ]["Σ_контрагент_заполнен"] += 1

print(f"{'Тип регистратора':<40} {'Строк':>6} {'СуммаЕРП':>15} {'Аналит':>8} {'Контраг':>8}")
print("-" * 80)
top_types = sorted(типы.items(), key=lambda x: -abs(x[1]['сумма']))
for тип, st in top_types[:15]:
    print(f"{тип:<40} {st['строк']:>6} {st['сумма']:>15.2f} {st['Σ_аналитика_заполнен']:>8} {st['Σ_контрагент_заполнен']:>8}")

# Проверка типов
ozp = типы.get("ОтражениеЗарплатыВФинансовомУчете", {})
ао = типы.get("АвансовыйОтчет", {})

print("\n=== Acceptance ===")
if ozp:
    pct = 100.0 * ozp.get("Σ_аналитика_заполнен", 0) / max(ozp.get("строк", 1), 1)
    print(f"  ОЗП: Аналитика заполнена в {ozp['Σ_аналитика_заполнен']}/{ozp['строк']} = {pct:.1f}%")
    assert pct > 50, f"Слишком мало ОЗП-строк с Аналитикой: {pct:.1f}%"
if ао:
    pct_ао = 100.0 * ао.get("Σ_аналитика_заполнен", 0) / max(ао.get("строк", 1), 1)
    print(f"  АО:  Аналитика заполнена в {ао['Σ_аналитика_заполнен']}/{ао['строк']} = {pct_ао:.1f}%")

# Σ суммы ЕРП за период по регистру
q = conn.NewObject("Запрос")
q.УстановитьПараметр("НМ", НМ)
q.УстановитьПараметр("КМ", КМ)
q.Текст = """
ВЫБРАТЬ СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ) КАК Σ
ИЗ РегистрНакопления.ПрочиеРасходы КАК Р
ГДЕ Р.Период МЕЖДУ &НМ И &КМ
    И Р.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
    И Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
"""
res = q.Выполнить().Выгрузить()
σ_регистр = float(res[0].Σ)

# Σ СуммаЕРП в отчёте (только Расход — фильтр по Документу типа расходов = только через проверку)
# Проще: Σ всех СуммаЕРП в отчёте для строк где Документ ССЫЛКА на расходные регистраторы.
σ_отчёт_расх = 0.0
расх_регистраторы = {"ОтражениеЗарплатыВФинансовомУчете", "ПриобретениеТоваровУслуг",
                      "РасходныйКассовыйОрдер", "СписаниеБезналичныхДенежныхСредств",
                      "АктВыполненныхРабот", "ВозвратТоваровПоставщику",
                      "ПриходныйКассовыйОрдер", "ПоступлениеБезналичныхДенежныхСредств",
                      "ВозвратТоваровОтКлиента", "АвансовыйОтчет"}
# Σ из отчёта суммарно (СуммаЕРП всех строк)
σ_отчёт_total = sum(float(r.СуммаЕРП) for r in тз)

print(f"\n  Σ из регистра ПрочиеРасходы (РасходныеРазрезы):  {σ_регистр:>15.2f}")
print(f"  Σ СуммаЕРП в отчёте (общая):                    {σ_отчёт_total:>15.2f}")
print(f"  (Σ отчёта включает также доходы — отличается)")

# Σ только Расходы из отчёта (по типам расходных регистраторов)
σ_отчёт_расх = 0.0
for r in тз:
    if r.Документ and conn.ЗначениеЗаполнено(r.Документ):
        тип = r.Документ.Метаданные().Имя
        if тип in расх_регистраторы:
            σ_отчёт_расх += float(r.СуммаЕРП)
print(f"\n  Σ СуммаЕРП в отчёте (только расходы):            {σ_отчёт_расх:>15.2f}")
print(f"  Δ vs регистр:                                    {σ_отчёт_расх - σ_регистр:>15.4f}")

# Σ-инвариант: разница должна быть <1 руб
diff = abs(σ_отчёт_расх - σ_регистр)
if diff < 1.0:
    print("\n[OK] Σ-инвариант отчёта совпадает с регистром")
else:
    print(f"\n[WARN] Δ={diff:.2f} — возможно есть расходы вне 10 типов или CoGS")
