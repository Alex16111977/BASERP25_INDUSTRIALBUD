"""Регрессия: РКО «ЧерезКассу» (вся ведомость) НЕ задет фиксом.

Динамически находит проведённый ЧерезКассу+ВКассу РКО (>1 ФЛ), перепроводит его
через COM (прогон ИЗМЕНЁННЫХ файлов 1-4 для общего случая) и проверяет, что
движения по-прежнему = ПОЛНАЯ ведомость (все ФЛ из А_Расшифровки), а не сужены.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
TOL = 0.01

# Найти ЧерезКассу+ВКассу РКО с >1 ФЛ
qf = erp.NewObject("Запрос")
qf.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка, Д.Номер КАК Номер
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Проведен
    И Д.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу)
СГРУППИРОВАТЬ ПО Д.Ссылка, Д.Номер
ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Рш.ФизическоеЛицо) > 1
"""
found = qf.Execute().Выгрузить()
if found.Количество() == 0:
    print("⚠ нет ЧерезКассу+ВКассу РКО (>1 ФЛ) — регрессию пропускаем")
    sys.exit(0)
ref = found[0].Ссылка
num = S(found[0].Номер)

# Эталон = полная ведомость (А_Расшифровка) per ФЛ
qe = erp.NewObject("Запрос")
qe.Text = """
ВЫБРАТЬ Рш.ФизическоеЛицо КАК ФЛ, СУММА(Рш.КВыплате) КАК Сумма
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = Д.Ведомость
ГДЕ Д.Ссылка = &Док
СГРУППИРОВАТЬ ПО Рш.ФизическоеЛицо
"""
qe.SetParameter("Док", ref)
ev = qe.Execute().Выгрузить()
ETALON = {S(r.ФЛ): float(r.Сумма) for r in ev}
print(f"РКО {num} (ЧерезКассу): эталон ведомости {len(ETALON)} ФЛ, Σ={sum(ETALON.values()):,.2f}")

# Перепровести
obj = ref.ПолучитьОбъект()
obj.Записать(erp.РежимЗаписиДокумента.Проведение)
print(f"  перепроведён, Проведен={obj.Проведен}")

# А_ВзСС после перепроводки
qv = erp.NewObject("Запрос")
qv.Text = """
ВЫБРАТЬ Р.ФизическоеЛицо КАК ФЛ, СУММА(Р.СуммаВзаиморасчетов) КАК Сумма
ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК Р
ГДЕ Р.Регистратор = &Док
СГРУППИРОВАТЬ ПО Р.ФизическоеЛицо
"""
qv.SetParameter("Док", ref)
vz = qv.Execute().Выгрузить()
GOT = {S(r.ФЛ): float(r.Сумма) for r in vz}
print(f"  А_ВзСС после: {len(GOT)} ФЛ, Σ={sum(GOT.values()):,.2f}")

assert set(GOT) == set(ETALON), f"FAIL: набор ФЛ изменился! эталон={set(ETALON)} got={set(GOT)}"
for fl, s in ETALON.items():
    assert abs(GOT.get(fl, 0) - s) < TOL, f"FAIL: {fl} {GOT.get(fl)} != {s}"

print("\n" + "=" * 80)
print(f"✅ REGRESSION PASS — ЧерезКассу {num}: вся ведомость ({len(GOT)} ФЛ) сохранена, фикс не задел")
print("=" * 80)
