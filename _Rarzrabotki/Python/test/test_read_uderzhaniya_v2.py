        print(f"  ФизЛицо : {S(row.ФизическоеЛицо)}")
        print(f"  Подразделение : {S(row.ПодразделениеПредприятия)}")
        print(f"  ВидОперации : {S(row.ВидОперации)}")
        print(f"  Контрагент : {S(row.Контрагент)}")
        print(f"  СтатьяАктивовПассивов : {S(row.СтатьяАктивовПассивов)}")
        print(f"  АналитикаАктивовПассивов : {S(row.АналитикаАктивовПассивов)}")
        print(f"  Сумма : {S(row.Сумма)}")
