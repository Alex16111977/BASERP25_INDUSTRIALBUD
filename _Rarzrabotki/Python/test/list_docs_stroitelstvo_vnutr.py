    sum_signed += float(rec.signed)
    print(f"   {rec.Период.strftime('%d.%m.%Y %H:%M:%S'):<19} | {rec.ДатаДок.strftime('%d.%m.%Y %H:%M:%S'):<19} | {str(rec.РегИмя)[:55]:<55} | {float(rec.signed):>15,.2f}", flush=True)
