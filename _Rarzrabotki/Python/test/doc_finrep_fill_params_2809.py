"""Параметри K за специфікацією 2026-09-28 (таблиця «Заповнення регістру»). Договір шукається
за підрозділом + підрядком найменування (пошук має дати РІВНО 1 договір, інакше — помилка).
Пише лише перелічені ресурси, решту зберігає (Прочитать перед записом).
    python doc_finrep_fill_params_2809.py           — dry-run
    python doc_finrep_fill_params_2809.py --apply   — запис"""
import sys, datetime
sys.stdout.reconfigure(encoding="utf-8")
import win32com.client, pywintypes

ПРИМЕНЯТЬ = "--apply" in sys.argv
buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String
РЕГ = buh.РегистрыСведений.А_ПараметрыДоговоровФинотчета
Д = lambda y, m, d: pywintypes.Time(datetime.datetime(y, m, d, 12))   # полдень: COM −3 год не зсуне день

Z20 = dict(ВариантФормулыИтога="ЗадолженностьПлюсАкты", ПроцентГарантийногоУдержания=20, ПравилоНДС="НеУчитывать")
Z0 = dict(ВариантФормулыИтога="ЗадолженностьПлюсАкты", ПроцентГарантийногоУдержания=0, ПравилоНДС="НеУчитывать")


def аванс(p, A, **дод):
    return dict(ВариантФормулыИтога="ЗачетПредоплаты", ПроцентГарантийногоУдержания=p, СуммаПредоплаты=A,
                ПравилоНДС="НеУчитывать", **дод)


ТАБЛИЦЯ = [  # (підрозділ, підрядок договору, {ресурс: значення})
    ("МК Кривий ріг", "06/04/26", аванс(15, 1194270.00, ДатаЗачетаПредоплаты=Д(2026, 9, 22), ОстатокПредоплатыНаДату=0)),
    ("МК Кривий ріг", "01/07/26", Z20),
    ("МК Каменец Цемент", "07/07/26", аванс(50, 1516008.00)),
    ("МД МХП ОРІЛЬ", "1203/2026", Z20),
    ("МД МХП ОРІЛЬ", "1103/2026", Z0),
] + [("МК Глобино", підрядок, Z20) for підрядок in (
    "09/04-25", "Каналіз", "Пост охорони", "16/09/25-1", "16/09/25-2", "16/09/25-3",
    "08/08/25", "Естакада 6.2", "Рез парк розч", "24/09/25", "Естакада 3.1.5", "Естакада 6.4",
    "Ав рез")] + [
    ("МК Глобино", "15/10/25", Z0),
    ("МД ООН 2025", "РАМКОВИЙ ДОГОВІР НА НАДАННЯ", dict(Z0, СуммаГарантийногоУдержания=1154400.18)),
    ("МД ООН 2025", "2022-DEC-178", Z0),
    ("МД Кернел Кухня", "28/10/24", аванс(100, 12178525.57)),
    ("МД ООН Админ", "РО139674", аванс(100, 3787670.30)),
    ("МД ООН Админ", "РО141392", аванс(100, 4770134.46)),
    ("МД ООН 2026", "PO144605", аванс(100, 856450.66)),
    ("МД ООН 2026", "PO145522", аванс(100, 1728305.40)),
    ("МД ПРООН Черкаси  ДСНС", "CMS ID", Z0),
    ("МД ПРООН Черкаси  ДСНС", "Дог про викон", Z0),
    ("МД IRC 2026", "від 16.06", Z0),
]

помилки = 0
for підр, підрядок, поля in ТАБЛИЦЯ:
    q = buh.NewObject("Запрос")
    q.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С, Д.Наименование КАК Н ИЗ Справочник.ДоговорыКонтрагентов КАК Д "
               "ГДЕ НЕ Д.ПометкаУдаления И Д.Подразделение.Наименование = &П И Д.Наименование ПОДОБНО &Ш")
    q.SetParameter("П", підр)
    q.SetParameter("Ш", "%" + підрядок + "%")
    т = q.Execute().Выгрузить()
    if т.Количество() != 1:
        помилки += 1
        знайдено = [S(т.Получить(i).Н)[:60] for i in range(т.Количество())]
        print(f"  ✗ {підр} / «{підрядок}»: знайдено {т.Количество()} {знайдено}")
        continue
    дог = т.Получить(0).С
    мз = РЕГ.СоздатьМенеджерЗаписи()
    мз.Договор = дог
    мз.Прочитать()
    було = "є запис" if мз.Выбран() else "НОВИЙ запис"
    опис = ", ".join(f"{к}={з if not isinstance(з, pywintypes.TimeType) else '22.09.2026'}" for к, з in поля.items())
    print(f"  {'ЗАПИС' if ПРИМЕНЯТЬ else 'dry'} [{було}] {підр} / {S(т.Получить(0).Н)[:48]}: {опис}")
    if ПРИМЕНЯТЬ:
        мз.Договор = дог
        for к, з in поля.items():
            setattr(мз, к, з)
        мз.Записать(True)
print("помилок:", помилки)
sys.exit(1 if помилки else 0)
