# -*- coding: utf-8 -*-
"""Регресс/корректность после фикса: за ЯНВАРЬ 2026 сверить ПО КАЖДОЙ статье
регистр свёртки (А_ОтчетБаланс_Свод) == ПАП(ВСЕ источники, signed cumul).
Если все статьи совпадают — свёртка точно зеркалит штатный Управленческий баланс,
и ни одна статья не дрейфанула. Плюс Σ КО=0 и кросс-сверка со скриншотом."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# 1) Регистр свёртки за январь: КО по каждой статье (имя)
qreg = erp.NewObject("Запрос")
qreg.Текст = """
ВЫБРАТЬ Рег.Статья.Наименование КАК Ст, СУММА(Рег.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Регистратор.Месяц = ДАТАВРЕМЯ(2026,1,1)
СГРУППИРОВАТЬ ПО Рег.Статья.Наименование
"""
reg = {str(r.Ст): f(r.КО) for r in qreg.Выполнить().Выгрузить()}

# 2) ПАП все источники signed cumul на конец января по каждой статье.
#    Исключаем иерархию "Собственные средства" — ТОЧНО как свёртка (ИсключенныеСтатьи + В ИЕРАРХИИ):
#    это балансирующий капитал (Вложения/Вывод собств. средств), свёртка его не несёт by-design.
qss = erp.NewObject("Запрос")
qss.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов "
             "ГДЕ Наименование = \"Собственные средства\"")
СобСр = qss.Выполнить().Выгрузить()[0].С
qpap = erp.NewObject("Запрос")
qpap.УстановитьПараметр("СС", СобСр)
qpap.Текст = """
ВЫБРАТЬ Т.Статья.Наименование КАК Ст,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59)
    И НЕ Т.Статья В ИЕРАРХИИ(&СС)
СГРУППИРОВАТЬ ПО Т.Статья.Наименование
"""
pap = {str(r.Ст): f(r.КО) for r in qpap.Выполнить().Выгрузить()}

TOL = 0.05
all_arts = sorted(set(reg) | set(pap))
print(f"{'Статья':<42} | {'Регистр КО':>16} | {'ПАП(все ист) КО':>16} | {'Δ':>12} | OK?")
mism = []
for a in all_arts:
    rg = reg.get(a, 0.0); pp = pap.get(a, 0.0); d = rg - pp
    ok = abs(d) <= TOL
    if not ok: mism.append((a, rg, pp, d))
    print(f"  {a:<40} | {rg:>16,.2f} | {pp:>16,.2f} | {d:>12,.2f} | {'OK' if ok else 'FAIL'}")

# 3) Σ КО баланс
sum_reg = sum(reg.values())
print(f"\n  Σ КО регистра (все статьи) = {sum_reg:,.2f}  (баланс, эталон ~0)")

# 4) Кросс-сверка ключевых статей со штатным отчётом (скриншот, янв 2026)
etalon_screenshot = {
    "Денежные средства (безналичные)": 50462657.15,
    "Денежные средства (наличные)":    23489702.23,
    "Товары на оптовых складах":       83627719.44,
    "Задолженность клиентов":          94569586.65,
    "Выданные авансы":                 81865120.49,
    "Оплата труда":                    246187.13,
    "Налоги":                          9331275.92,
}
print("\n  Кросс-сверка со штатным Управленческим балансом (скриншот):")
scr_ok = True
for a, exp in etalon_screenshot.items():
    got = abs(reg.get(a, 0.0))
    ok = abs(got - exp) <= 1.0
    scr_ok = scr_ok and ok
    print(f"    {a:<36} регистр|КО|={got:>16,.2f}  штатн={exp:>16,.2f}  {'OK' if ok else 'FAIL'}")

print("\n" + "="*60)
if mism:
    print(f"РЕГРЕСС: {len(mism)} статей регистр != ПАП(все ист) — РАЗОБРАТЬСЯ:")
    for a, rg, pp, d in mism:
        print(f"   {a}: рег={rg:,.2f} пап={pp:,.2f} Δ={d:,.2f}")
ok_total = (not mism) and abs(sum_reg) <= 0.5 and scr_ok
print("REGRESS PASS — свёртка зеркалит ПАП по ВСЕМ статьям, баланс=0, штатн совпал." if ok_total
      else "REGRESS: см. расхождения выше.")
sys.exit(0 if ok_total else 1)
