def get_dds_cogs(erp):
    """Аналог ПолучитьДДСПриёмникCoGS()."""
    q = erp.NewObject("Запрос")
    q.Text = (
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтатьиДвиженияДенежныхСредств "
        "ГДЕ А_ПриёмникСебестоимостиПродажPL И НЕ ПометкаУдаления"
    )
    r = q.Execute().Выгрузить()
    if r.Количество() == 0:
        return erp.Справочники.СтатьиДвиженияДенежныхСредств.ПустаяСсылка()
    return r[0].Ссылка


