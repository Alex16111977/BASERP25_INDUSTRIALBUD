# -*- coding: utf-8 -*-
"""Smoke друкованої форми М-29 документа РасчетКомплектаций (BuhBud).

Критерії приймання зі специфікації
docs/superpowers/specs/2026-08-03-m29-print-form-design.md (§4.3, §6.4),
розрахунок №00000000003 від 03.08.2026:
    Матеріали  73 позиції  322 278,22
    МШП        15 позицій    3 569,35
    ВСЬОГО                 325 847,57

Керовану форму COM не рендерить — перевіряємо рушій (СформироватьПечатьМ29)
через ТабличныйДокумент, який COM-інспектується.
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
НОМЕР_РАСЧЕТА = "00000000003"

# ⚠ 2026-08-06: магічні еталони (322 278,22 / 73 рядки / 3 569,35) ЗНОВУ протухли —
# у документи будинку №1 долили проводок після 04.08. За каноном §28 (LESSONS) абсолюти
# замінено на ЖИВИЙ інваріант: підсумки М-29 = сума проводок Хозрасчетного по
# регістраторах документа з заповненим СчетКт (точне дзеркало фільтра ДанныеМ29ПоБлоку).
ЦЕНТ = 0.01


def сумма_проводок_блока(buh, об, имя_тч):
    """Живой эталон блока: Σ Сумма движений Хозрасчетного по ПРОВЕДЁННЫМ регистраторам
    ТЧ документов (оба слота), фильтр СчетКт заполнен — зеркало ДанныеМ29ПоБлоку."""
    тч = getattr(об, имя_тч)
    регистраторы = buh.NewObject("Массив")
    видели = set()
    for i in range(тч.Количество()):
        стр = тч.Получить(i)
        for слот in (стр.ДокументПоНормам, стр.ДокументДодаткова):
            ключ = buh.String(слот)
            if not ключ or ключ in видели:
                continue
            видели.add(ключ)
            объ = слот.ПолучитьОбъект()
            if объ is not None and объ.Проведен:
                регистраторы.Добавить(слот)
    if регистраторы.Количество() == 0:
        return 0.0
    з = buh.NewObject("Запрос")
    з.Text = (
        "ВЫБРАТЬ ЕСТЬNULL(СУММА(Х.Сумма), 0) КАК Сум "
        "ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х "
        "ГДЕ Х.Регистратор В (&Регистраторы) "
        "И Х.СчетКт <> ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.ПустаяСсылка)")
    з.SetParameter("Регистраторы", регистраторы)
    т = з.Execute().Выгрузить()
    return float(т.Получить(0).Сум or 0)

провалов = []


def проверить(имя, факт, ожид, допуск=0):
    ок = abs(факт - ожид) <= допуск if isinstance(ожид, (int, float)) else факт == ожид
    print(f"  [{'OK  ' if ок else 'FAIL'}] {имя}: {факт!r}" + ("" if ок else f"  (очікували {ожид!r})"))
    if not ок:
        провалов.append(имя)


def текст(табдок, стр, кол):
    return (табдок.Область(стр, кол, стр, кол).Текст or "").strip()


def число(значение):
    s = (значение or "").strip().replace("\xa0", "").replace(" ", "").replace(",", ".")
    try:
        return float(s)
    except ValueError:
        return None


buh = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)
S = buh.String

q = buh.NewObject("Запрос")
q.Text = 'ВЫБРАТЬ Ссылка КАК С ИЗ Документ.РасчетКомплектаций ГДЕ Номер = "%s"' % НОМЕР_РАСЧЕТА
таб = q.Execute().Выгрузить()
assert таб.Количество() > 0, f"Розрахунок №{НОМЕР_РАСЧЕТА} не знайдено"
расчет = таб.Получить(0).С
об = расчет.ПолучитьОбъект()
print(f"Розрахунок: {S(расчет)}")

табдок = об.СформироватьПечатьМ29()
assert табдок is not None, "СформироватьПечатьМ29 повернула Неопределено"

высота = табдок.ВысотаТаблицы
ширина = табдок.ШиринаТаблицы
print(f"ТабДок: {высота} рядків x {ширина} колонок\n")

print("=== Структура ===")
проверить("ширина = 13 колонок", ширина, 13)
проверить("висота > 80 рядків", высота > 80, True)

# --- шапка ---
шапка = {}
for r in range(1, min(высота, 30) + 1):
    for c in range(1, 14):
        t = текст(табдок, r, c)
        if t:
            шапка.setdefault(t, (r, c))

for подпись in ("З В І Т", "про витрати основних матеріалів у будівництві",
                "в співставленні з виробничими нормами", "Форма № М-29/1",
                "Інформація з АВР", "Інформація з 1С", "Матеріали", "Примітка", "До Акту №"):
    проверить(f"шапка містить «{подпись}»", подпись in шапка, True)

# --- рядок нумерації 1..13 ---
строка_нумерации = None
for r in range(1, min(высота, 30) + 1):
    if текст(табдок, r, 1) == "1" and текст(табдок, r, 13) == "13" and текст(табдок, r, 7) == "7":
        строка_нумерации = r
        break
проверить("є рядок нумерації 1..13", строка_нумерации is not None, True)

# --- підсумкові рядки ---
итоги = {}
for r in range(1, высота + 1):
    t = текст(табдок, r, 1)
    if t in ("Разом вартість матеріалів", "Разом вартість МШП", "ВСЬОГО списано"):
        итоги[t] = (r, число(текст(табдок, r, 12)))

print("\n=== Підсумки ===")
for имя in ("Разом вартість матеріалів", "Разом вартість МШП", "ВСЬОГО списано"):
    проверить(f"є рядок «{имя}»", имя in итоги, True)

if len(итоги) == 3:
    р_мат, с_мат = итоги["Разом вартість матеріалів"]
    р_мшп, с_мшп = итоги["Разом вартість МШП"]
    р_всего, с_всего = итоги["ВСЬОГО списано"]

    эталон_мат = сумма_проводок_блока(buh, об, "ДокументиКомплектації")
    эталон_мшп = сумма_проводок_блока(buh, об, "ДокументиМалоценки")
    проверить("Разом вартість матеріалів = проводки", с_мат, эталон_мат, ЦЕНТ)
    проверить("Разом вартість МШП = проводки", с_мшп, эталон_мшп, ЦЕНТ)
    проверить("ВСЬОГО списано = проводки", с_всего, эталон_мат + эталон_мшп, ЦЕНТ)
    проверить("ВСЬОГО = Матеріали + МШП", abs(с_всего - (с_мат + с_мшп)) <= ЦЕНТ, True)

    # --- кількість рядків блоків (рядок = заповнена колонка 7 «Код») ---
    def рядків_блоку(с, по):
        return sum(1 for r in range(с, по) if текст(табдок, r, 7))

    начало_мат = строка_нумерации + 1 if строка_нумерации else 1
    проверить("рядків блоку Матеріали > 0", рядків_блоку(начало_мат, р_мат) > 0, True)
    проверить("рядків блоку МШП > 0", рядків_блоку(р_мат + 1, р_мшп) > 0, True)

    print("\n=== Блок «Інформація з АВР» (перший рядок даних) ===")
    проверить("кол. 1 = № п/п = 1", текст(табдок, начало_мат, 1), "1")
    проверить("кол. 3 = «шт»", текст(табдок, начало_мат, 3), "шт")
    проверить("кол. 4 = 1", число(текст(табдок, начало_мат, 4)), 1.0, 0)
    проверить("кол. 5 порожня (вартість з АВР)", текст(табдок, начало_мат, 5), "")
    проверить("кол. 6 порожня (вартість з АВР)", текст(табдок, начало_мат, 6), "")
    проверить("АВР лише в 1-му рядку (кол. 3 наступного порожня)",
              текст(табдок, начало_мат + 1, 3), "")

    print("\n=== Арифметика рядків: Ціна x Кількість = Сума ===")
    расхождений = 0
    сумма_строк = 0.0
    for r in range(начало_мат, р_мат):
        if not текст(табдок, r, 7):
            continue
        кол = число(текст(табдок, r, 10))
        цена = число(текст(табдок, r, 11))
        сум = число(текст(табдок, r, 12))
        if None in (кол, цена, сум):
            continue
        сумма_строк += сум
        if abs(цена * кол - сум) > 0.5:
            расхождений += 1
    проверить("сума рядків = підсумок блоку", abs(сумма_строк - с_мат) <= ЦЕНТ, True)
    проверить("рядків із розбіжністю Ціна x Кіл > 0.5 грн", расхождений, 0)

    print("\n=== Захист від подвійних проводок малоцінки ===")
    # Забалансова Дт МЦ дублює суму 1:1 -> без фільтра МШП був би рівно вдвічі більший
    # за живий еталон з проводок (який фільтр уже враховує)
    проверить("МШП не подвоєно", эталон_мшп == 0 or abs(с_мшп - эталон_мшп * 2) > ЦЕНТ, True)

    print("\n=== Підписи ===")
    подписи_текст = " | ".join(текст(табдок, r, 1) for r in range(р_всего + 1, высота + 1))
    for посада in ("Опрацював  Бухгалтер", "Витрати матеріалів перевірив", "Начальник ВТВ",
                   "Інженер ВТВ", "Начальник будівельного-монтажного комплекса",
                   "Матеріально-відповідальна особа"):
        проверить(f"підпис «{посада}»", посада in подписи_текст, True)
    проверить("є пояснення «(дата, П.І.Б., підпис)»", "(дата, П.І.Б., підпис)" in подписи_текст, True)

print("\n" + "=" * 60)
if провалов:
    print(f"FAIL — провалено перевірок: {len(провалов)}")
    for имя in провалов:
        print(f"   - {имя}")
    sys.exit(1)
print("PASS — усі перевірки пройдено")
