# -*- coding: utf-8 -*-
"""
Где «Біта» лежит по 71,00/ед на момент возврата R1: остатки по ВСЕМ счетам
Хозрасчетного (не только 0221) на 01.06.2026 перед 20:01. Показать, откуда движок
берёт себестоимость списания Кт 0221. Rule #-1.
"""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
def S(x):
    try: return buh.String(x)
    except Exception: return str(x)

# ном «Біта» из резидуума
счет0221 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("0221").Ссылка
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Ост.Субконто2 КАК Н, Ост.СуммаОстатокДт КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет=&Счет) КАК Ост
ГДЕ Ост.КоличествоОстатокДт=0 И Ост.СуммаОстатокДт<>0
"""
q.УстановитьПараметр("Счет",счет0221)
q.УстановитьПараметр("НаДату",datetime.datetime(2026,7,13,23,59,59))
r=q.Выполнить().Выгрузить()
ном=None
for i in range(r.Количество()):
    s=r.Получить(i)
    if 548.0<float(s.Сумма)<549.0: ном=s.Н; break
print("Біта:", S(ном))

# найти реальный МоментВремени R1
докR1 = buh.Документы.ВозвратТоваровПоставщику.НайтиПоНомеру("СТ00-000038", datetime.datetime(2026,6,30,23,59,59))
мв = докR1.МоментВремени()

# остатки «Біти» по ВСЕМ счетам на момент перед R1
вс = buh.NewObject("Массив")
вс.Добавить(buh.ПланыВидовХарактеристик.ВидыСубконтоХозрасчетные.Номенклатура)
q2 = buh.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    Ост.Счет.Код КАК Код, ПРЕДСТАВЛЕНИЕ(Ост.Счет) КАК Счет,
    СУММА(Ост.КоличествоОстатокДт) КАК Кол, СУММА(Ост.СуммаОстатокДт) КАК Сум
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Т, , &ВС, Субконто1 = &Ном) КАК Ост
СГРУППИРОВАТЬ ПО Ост.Счет.Код, ПРЕДСТАВЛЕНИЕ(Ост.Счет)
ИМЕЮЩИЕ СУММА(Ост.КоличествоОстатокДт) <> 0 ИЛИ СУММА(Ост.СуммаОстатокДт) <> 0
"""
q2.УстановитьПараметр("Т", мв)
q2.УстановитьПараметр("ВС", вс)
q2.УстановитьПараметр("Ном", ном)
try:
    d = q2.Выполнить().Выгрузить()
    print(f"\nОстатки «Біти» по счетам на момент перед R1 (01.06.2026 ~20:01):")
    print(f"{'Код':<8} {'Счёт':<34} {'Кол':>9} {'Сумма':>12} {'ср/ед':>9}")
    print("-"*76)
    for i in range(d.Количество()):
        s=d.Получить(i)
        к=float(s.Кол or 0); сум=float(s.Сум or 0)
        print(f"{S(s.Код):<8} {S(s.Счет)[:34]:<34} {к:>9.1f} {сум:>12.2f} {(сум/к if к else 0):>9.2f}")
except Exception as e:
    print("FAIL:", e.excepinfo[2] if hasattr(e,'excepinfo') and e.excepinfo else e)
