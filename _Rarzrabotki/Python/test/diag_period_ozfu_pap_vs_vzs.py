"""Точні значення Период для ОЗФУ № 000Ц-000001 (31.01.2026): ПАП vs А_ВзСС."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

q = conn.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Д
ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете КАК Д
ГДЕ Д.Номер = &Н И Д.Дата >= ДАТАВРЕМЯ(2026,1,1)"""
q.УстановитьПараметр("Н", "000Ц-000001")
r = q.Выполнить().Выбрать(); r.Следующий()
doc = r.Д
print(f"[DOC] № {S(doc).strip()} (дата 31.01.2026)")
print(f"      ДокОбъект.Дата = {doc.Дата}")

# Період руху в ПАП
qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

qP = conn.NewObject("Запрос")
qP.Текст = """
ВЫБРАТЬ
    Т.Период КАК П, Т.Источник КАК Ист,
    Т.ВидДвижения КАК ВД, Т.Сумма КАК Сум,
    Т.Статья КАК Стаття
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор = &Док И Т.Статья = &ОТ
"""
qP.УстановитьПараметр("Док", doc); qP.УстановитьПараметр("ОТ", ОТ)
rP = qP.Выполнить().Выгрузить()
print(f"\n[ПАП(ОТ) рухи документа] {rP.Количество()} рядків")
періоди_пап = set()
for i in range(min(5, rP.Количество())):
    rec = rP.Получить(i)
    print(f"  Період={rec.П} | {S(rec.ВД):>8} {rec.Сум:>12,.2f}")
    періоди_пап.add(rec.П)
print(f"  Унікальних Період в ПАП: {len(періоди_пап)}, перший = {sorted(періоди_пап)[0] if періоди_пап else None}")

# Період руху в А_ВзСС
