періоди_взсс = set()
for i in range(min(5, rV.Количество())):
    rec = rV.Получить(i)
    print(f"  Період={rec.П} | {S(rec.ВД):>8} {rec.Сум:>12,.2f} ФЛ={S(rec.ФЛ)[:30]}")
    періоди_взсс.add(rec.П)
print(f"  Унікальних Період в А_ВзСС: {len(періоди_взсс)}, перший = {sorted(періоди_взсс)[0] if періоди_взсс else None}")
