# -*- coding: utf-8 -*-
"""ЦВБ: эталонные проверки ложных расхождений взаиморасчётов декабря 2025 (read-only).

Фиксирует факты аудита 2026-07-20 (см. 08_lozhnye_raskhozhdeniya_vzaimoraschety.md):
1. FP-1 малый:  АО ІБ00-000368 — ERP РСП нетто 70,00 (Укрпошта АТ); пара в Бух —
   единственная проводка Дт 92 Кт 3721 70,00 (счетов сверки нет).
2. FP-1 крупный: АО ІБ00-000422 — ERP РСП нетто 91 991,86 (FACEBK); пара в Бух —
   Дт 93 Кт 3721 91 991,86.
3. REAL Бадлюк: в Бух «Передача ОЗ ІБ00-000001» (Дт361 Кт712 3 646 396,20) БЕЗ пары
   в ERP; остаток РСК Бадлюк М.І. в ERP = -3 646 396,20 (переплата не закрыта реализацией).
4. FP-2 Воронцов: декабрьские документы по контрагенту-владельцу без пар в Бух,
   зеркальные группы нетто 0 + непарные выплаты 290 772,00.
"""
import win32com.client, sys, datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
CONN_BUH = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'

UID_AO_368 = "86cdfd0b-d1da-11f0-8103-00155dce3d04"
UID_AO_422 = "e2930b2c-f69d-11f0-8105-00155dce3d04"
IDKOD_BADLUK_MI = "38f96bf4-fed9-42d0-9b39-fd0193bee902"
IDKOD_VORONCOV = "9a8a8482-64d0-11ed-80c1-00155d235309"


def run(conn, text, params):
    q = conn.NewObject("Запрос")
    q.Text = text
    for k, val in params.items():
        q.SetParameter(k, val)
    return q.Execute().Выгрузить()


def rsp_netto(erp, ref):
    tz = run(erp, """
ВЫБРАТЬ ЕСТЬNULL(СУММА(ВЫБОР КОГДА Дв.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	ТОГДА Дв.Сумма ИНАЧЕ -Дв.Сумма КОНЕЦ), 0) КАК Нетто
ИЗ РегистрНакопления.РасчетыСПоставщиками КАК Дв
ГДЕ Дв.Регистратор = &Рег И Дв.Активность
""", {"Рег": ref})
    return float(tz.Получить(0).Нетто or 0)


def para_buh(erp, buh, ref):
    tz = run(erp, """
ВЫБРАТЬ Соотв.УникальныйИдентификаторПриемника КАК УИД, Соотв.ТипПриемника КАК Тип
ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК Соотв
ГДЕ Соотв.УникальныйИдентификаторИсточника = &Рег
	И Соотв.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20
""", {"Рег": ref})
    if tz.Количество() == 0:
        return None
    s = tz.Получить(0)
    tip = str(s.Тип).replace("ДокументСсылка.", "")
    return getattr(buh.Документы, tip).ПолучитьСсылку(
        buh.NewObject("УникальныйИдентификатор", str(s.УИД)))


def provodki(buh, ref_b):
    tz = run(buh, """
ВЫБРАТЬ Дв.СчетДт.Код КАК Дт, Дв.СчетКт.Код КАК Кт, Дв.Сумма КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Дв
ГДЕ Дв.Регистратор = &Рег И Дв.Активность
""", {"Рег": ref_b})
    return [(str(tz.Получить(i).Дт), str(tz.Получить(i).Кт), float(tz.Получить(i).Сумма))
            for i in range(tz.Количество())]


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect(CONN_ERP)
    buh = v8.Connect(CONN_BUH)
    nach = datetime.datetime(2025, 12, 1)
    kon = datetime.datetime(2025, 12, 31, 23, 59, 59)

    # 1. FP-1 малый: АО ІБ00-000368
    ref = erp.Документы.АвансовыйОтчет.ПолучитьСсылку(
        erp.NewObject("УникальныйИдентификатор", UID_AO_368))
    assert ref.ПолучитьОбъект() is not None, "АО ІБ00-000368 существует"
    assert abs(rsp_netto(erp, ref) - 70.0) < 0.01, "АО-368: ERP РСП нетто 70,00"
    pb = para_buh(erp, buh, ref)
    assert pb is not None and pb.ПолучитьОбъект() is not None, "АО-368: пара в Бух есть"
    pr = provodki(buh, pb)
    assert pr == [("92", "3721", 70.0)], f"АО-368: Бух Дт92 Кт3721 70,00, факт {pr}"
    print("1. FP-1 АО ІБ00-000368: OK (ERP РСП 70,00 <-> Бух Дт92 Кт3721 70,00)")

    # 2. FP-1 крупный: АО ІБ00-000422 (FACEBK)
    ref = erp.Документы.АвансовыйОтчет.ПолучитьСсылку(
        erp.NewObject("УникальныйИдентификатор", UID_AO_422))
    assert ref.ПолучитьОбъект() is not None, "АО ІБ00-000422 существует"
    assert abs(rsp_netto(erp, ref) - 91991.86) < 0.01, "АО-422: ERP РСП нетто 91 991,86"
    pb = para_buh(erp, buh, ref)
    assert pb is not None and pb.ПолучитьОбъект() is not None, "АО-422: пара в Бух есть"
    pr = provodki(buh, pb)
    assert pr == [("93", "3721", 91991.86)], f"АО-422: Бух Дт93 Кт3721 91 991,86, факт {pr}"
    print("2. FP-1 АО ІБ00-000422 (FACEBK): OK (ERP РСП 91 991,86 <-> Бух Дт93 Кт3721)")

    # 3. REAL Бадлюк: Передача ОЗ только в Бух
    tz = run(buh, """
ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Документ.ПередачаОС КАК Д
ГДЕ Д.Номер ПОДОБНО &Ном И Д.Дата МЕЖДУ &Н И &К И Д.Проведен
""", {"Ном": "%000001", "Н": nach, "К": kon})
    assert tz.Количество() >= 1, "Передача ОЗ ІБ00-000001 в Бух есть и проведена"
    ref_oz = tz.Получить(0).Ссылка
    pr = provodki(buh, ref_oz)
    assert ("361", "712", 3646396.2) in pr, f"Передача ОЗ: Дт361 Кт712 3 646 396,20, факт {pr}"
    uid_oz = buh.String(ref_oz.УникальныйИдентификатор())
    tz = run(erp, """
ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.СоответствияОбъектовИнформационныхБаз КАК С
ГДЕ С.УникальныйИдентификаторПриемника = &УИД
	И С.УзелИнформационнойБазы ССЫЛКА ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20
""", {"УИД": uid_oz})
    assert int(tz.Получить(0).К) == 0, "Передача ОЗ не имеет пары в ERP (REAL-расхождение)"
    tz = run(erp, """
ВЫБРАТЬ ЕСТЬNULL(СУММА(О.СуммаКонечныйОстаток), 0) КАК Ост
ИЗ РегистрНакопления.РасчетыСКлиентами.ОстаткиИОбороты(&Н, &К, , ,
	АналитикаУчетаПоПартнерам.Контрагент.А_ИдКод = &ИдКод) КАК О
""", {"Н": nach, "К": kon, "ИдКод": IDKOD_BADLUK_MI})
    ost = float(tz.Получить(0).Ост or 0)
    assert abs(ost + 3646396.2) < 0.01, f"ERP РСК Бадлюк М.І. на 31.12: -3 646 396,20, факт {ost}"
    print("3. REAL Бадлюк: OK (Передача ОЗ только в Бух, ERP держит переплату -3 646 396,20)")

    # 4. FP-2 Воронцов: декабрьские доки без пар, зеркала + выплаты 290 772
    tz = run(erp, """
ВЫБРАТЬ Дв.Регистратор КАК Рег, СУММА(ВЫБОР КОГДА Дв.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	ТОГДА Дв.Сумма ИНАЧЕ -Дв.Сумма КОНЕЦ) КАК Нетто
ИЗ РегистрНакопления.РасчетыСКлиентами КАК Дв
ГДЕ Дв.Период МЕЖДУ &Н И &К И Дв.Активность
	И Дв.АналитикаУчетаПоПартнерам.Контрагент.А_ИдКод = &ИдКод
СГРУППИРОВАТЬ ПО Дв.Регистратор

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ Дв2.Регистратор, СУММА(ВЫБОР КОГДА Дв2.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	ТОГДА Дв2.Сумма ИНАЧЕ -Дв2.Сумма КОНЕЦ)
ИЗ РегистрНакопления.РасчетыСПоставщиками КАК Дв2
ГДЕ Дв2.Период МЕЖДУ &Н И &К И Дв2.Активность
	И Дв2.АналитикаУчетаПоПартнерам.Контрагент.А_ИдКод = &ИдКод
СГРУППИРОВАТЬ ПО Дв2.Регистратор
""", {"Н": nach, "К": kon, "ИдКод": IDKOD_VORONCOV})
    netto_sum = sum(float(tz.Получить(i).Нетто) for i in range(tz.Количество()))
    assert tz.Количество() >= 10, f"Воронцов: ожидалось >=10 документов декабря, факт {tz.Количество()}"
    assert abs(netto_sum - 290772.0) < 0.01, f"Воронцов: нетто декабря 290 772, факт {netto_sum:,.2f}"
    print(f"4. FP-2 Воронцов: OK ({tz.Количество()} доков, зеркала нетуются, нетто = 290 772,00)")

    print("\nВСЕ ЭТАЛОНЫ OK")


if __name__ == "__main__":
    main()
