# -*- coding: utf-8 -*-
"""У свод-вариантов отчёта А_ОтчетPL_ПолныйЕРП_Остатки сохранить параметр СводыНаправлений = Истина
(решение 02.09.2026): интерактивный отчёт должен совпадать с книгой (обработка выгрузки ставит Истина сама)."""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ВАРИАНТЫ = ["PL: Месяц, PL с начала года (для свода)",
            "PL: (без направления ЦО): Месяц, PL с начала года"]
ПРОВАЛОВ = 0
for имя in ВАРИАНТЫ:
    q = erp.NewObject("Запрос")
    q.Text = ('ВЫБРАТЬ Вар.Ссылка КАК Ссылка ИЗ Справочник.ВариантыОтчетов КАК Вар '
              'ГДЕ Вар.Наименование = &Имя И НЕ Вар.ПометкаУдаления '
              'И ВЫРАЗИТЬ(Вар.Отчет КАК Справочник.ИдентификаторыОбъектовМетаданных).ПолноеИмя = "Отчет.А_ОтчетPL_ПолныйЕРП_Остатки"')
    q.SetParameter("Имя", имя)
    r = q.Execute().Выгрузить()
    if r.Количество() != 1:
        print("FAIL: вариант «%s» — найдено %d" % (имя, r.Количество())); ПРОВАЛОВ += 1; continue
    об = r.Получить(0).Ссылка.ПолучитьОбъект()
    н = об.Настройки.Получить()
    э = н.ПараметрыДанных.Элементы.Найти("СводыНаправлений")
    if э is None:
        print("FAIL: «%s» — нет параметра СводыНаправлений" % имя); ПРОВАЛОВ += 1; continue
    было = bool(э.Значение)
    э.Значение = True
    э.Использование = True
    об.Настройки = erp.NewObject("ХранилищеЗначения", н)
    об.Записать()
    # перечитать
    н2 = r.Получить(0).Ссылка.Настройки.Получить()
    э2 = н2.ПараметрыДанных.Элементы.Найти("СводыНаправлений")
    ок = bool(э2.Значение) and bool(э2.Использование)
    print("[%s] «%s»: было %s -> стало %s" % ("OK  " if ок else "FAIL", имя, было, bool(э2.Значение)))
    ПРОВАЛОВ += 0 if ок else 1
print("ПРОВАЛОВ:", ПРОВАЛОВ)
sys.exit(1 if ПРОВАЛОВ else 0)
