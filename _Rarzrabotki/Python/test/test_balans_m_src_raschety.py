# -*- coding: utf-8 -*-
"""Пре-тест Свод_РасчетыСПартнерами (Task 5, Rule #-1).
DR-1: клиенты+поставщики (по срокам) — одна процедура. DR-2: суммы из ОСНОВНОЙ
таблицы ПрочиеАктивыПассивы по Источник (резолв по Представлению, не гадаем Имя).
4 ресурса = signed Сумма (НачОст до НачМес, Приход/Расход в периоде, КонОст всего).
Субконто ОбъектРасчетов: проверяем уникальность на Регистратор (fill-when-unique).
Контроль: Σ КонОст по Статья для этих Источников == ПАП.ОстаткиИОбороты (срез
по тем же Регистраторам через .Обороты не нужен — DR-7: все слои уже == ПАП)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom
from datetime import datetime
pythoncom.CoInitialize()
ERP = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q0 = ERP.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
s = q0.Выполнить().Выбрать(); s.Следующий(); ORG = s.С
qm = ERP.NewObject("Запрос")
qm.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
            "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
qm.УстановитьПараметр("М", datetime(2026, 1, 1, 12, 0, 0))
rm = qm.Выполнить().Выбрать(); rm.Следующий()

# Резолв Источник по Представлению (надёжно — Имена enum не гадаем)
qИ = ERP.NewObject("Запрос")
qИ.Текст = ("ВЫБРАТЬ Ссылка КАК С, ПРЕДСТАВЛЕНИЕ(Ссылка) КАК П "
            "ИЗ Перечисление.ИсточникиУправленческогоБаланса")
tИ_all = qИ.Выполнить().Выгрузить()
ЦЕЛЬ = {"Расчеты с клиентами по срокам", "Расчеты с поставщиками по срокам"}
spИст = ERP.NewObject("Массив")
найдено = []
for i in range(tИ_all.Количество()):
    r = tИ_all.Получить(i)
    if str(r.П) in ЦЕЛЬ:
        spИст.Добавить(r.С); найдено.append(str(r.П))
print(f"Источники РасчетыСПартнерами: {найдено}")
assert spИст.Количество() >= 1, "FAIL: не найдены Источники 'по срокам'"

qd = ERP.NewObject("Запрос")
qd.Текст = """ВЫБРАТЬ
 ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст,
 КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Регистратор) КАК КолРег,
 СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
   ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КонОст,
 СУММА(ВЫБОР КОГДА Т.Период<&НМ
   ТОГДА ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
     ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ ИНАЧЕ 0 КОНЕЦ) КАК НачОст
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация=&Орг И Т.Период<=&КД И Т.Источник В (&Ист)
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)"""
qd.УстановитьПараметр("Орг", ORG); qd.УстановитьПараметр("КД", rm.КД)
qd.УстановитьПараметр("НМ", rm.НМ); qd.УстановитьПараметр("Ист", spИст)
try:
    td = qd.Выполнить().Выгрузить()
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    print(f"FAIL: {msg}"); sys.exit(1)
print(f"РасчетыСПартнерами: статей={td.Количество()}")
for i in range(td.Количество()):
    r = td.Получить(i)
    print(f"  {str(r.Ст)[:42]:42} НачОст={float(r.НачОст or 0):,.2f} "
          f"КонОст={float(r.КонОст or 0):,.2f} рег={int(r.КолРег)}")

# Уникальность ОбъектРасчетов на Регистратор в источнике-регистре (для субконто)
qo = ERP.NewObject("Запрос")
qo.Текст = """ВЫБРАТЬ Р.Регистратор КАК Рег,
 КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.ОбъектРасчетов) КАК К
ИЗ РегистрНакопления.РасчетыСКлиентамиПоСрокам КАК Р
ГДЕ Р.Период МЕЖДУ &Д1 И &Д2
СГРУППИРОВАТЬ ПО Р.Регистратор
ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.ОбъектРасчетов) > 1"""
qo.УстановитьПараметр("Д1", rm.НМ); qo.УстановитьПараметр("Д2", rm.КД)
try:
    to = qo.Выполнить().Выгрузить()
    мульти = to.Количество()
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    print(f"WARN РасчетыСКлиентамиПоСрокам.ОбъектРасчетов: {msg}"); мульти = -1
print(f"\nРегистраторов с >1 ОбъектРасчетов (РасчетыСКлиентамиПоСрокам): {мульти} "
      f"(0 → ОбъектРасчетов однозначен на регистратор; >0 → fill-when-unique)")
print("PASS test_balans_m_src_raschety (вход для BSL Свод_РасчетыСПартнерами)")
