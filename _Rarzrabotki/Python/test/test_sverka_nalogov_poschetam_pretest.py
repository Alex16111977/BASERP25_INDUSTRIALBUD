# -*- coding: utf-8 -*-
# Rule #-1 pre-тест отчёта А_СравнитьОстаткиНалоговПосчетамЕРПсBASБухгалтерия.
# Сверка регл. бухучёта ОБЕИХ баз: ЕРП РегистрБухгалтерии.Хозрасчетный (ЛОКАЛЬНО) ↔ BuhBud Хозрасчетный (COM).
# Разрез по Счёт.Код, БЕЗ организации (фильтр 3 орг А_ВБалансе), знак Кт−Дт (пассив-плюс). Без НДФЛ-схлопывания.
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

НП = datetime.datetime(2025, 12, 1, 0, 0, 0)
КП = datetime.datetime(2025, 12, 31, 23, 59, 59)
print(f"Период: {НП} .. {КП}\n")

def fail(p, e):
    info = getattr(e, 'excepinfo', None)
    print(f"FAIL {p}:", info[2] if info else e); sys.exit(1)

МАП = {"6411": "НДФЛ", "642": "ВоенныйСбор", "651": "НачисленныйЕСВ", "6412": "НДС",
       "6413": "НалогНаПрибыль", "6414": "ЕдиныйНалог", "6415": "ДругиеНалоги", "6417": "ДругиеНалоги"}
def вид_налога(код):
    к = str(код).strip()
    if к in МАП: return МАП[к]
    for prefix, vn in (("6411","НДФЛ"),("6412","НДС"),("6413","НалогНаПрибыль"),
                       ("6414","ЕдиныйНалог"),("642","ВоенныйСбор"),("651","НачисленныйЕСВ")):
        if к.startswith(prefix): return vn
    return "ДругиеНалоги"

# ===== 1. ЕДРПОУ организаций «в балансе» (ERP-side) =====
qo = erp.NewObject("Запрос")
qo.Text = ('ВЫБРАТЬ Орг.КодПоЕДРПОУ КАК ЕДРПОУ, Орг.Наименование КАК Наим '
           'ИЗ Справочник.Организации КАК Орг ГДЕ Орг.А_ВБалансе И Орг.КодПоЕДРПОУ <> ""')
edrpou, orgname = [], {}
for s in qo.Execute().Выгрузить():
    edrpou.append(s.ЕДРПОУ); orgname[s.ЕДРПОУ] = s.Наим
print("ЕДРПОУ в балансе:", [(e, orgname[e][:22]) for e in edrpou], "\n")

# ===== 1a. ДИАГНОСТИКА: какие орг реально в ЕРП Хозрасчетном по налог.счетам =====
qd = erp.NewObject("Запрос")
qd.SetParameter("НП", НП); qd.SetParameter("КП", КП)
qd.Text = """
ВЫБРАТЬ Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ, Ост.Организация.Наименование КАК Наим,
    СУММА(Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) КАК Сальдо
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&НП, &КП, , , , , ) КАК Ост
ГДЕ Ост.Счет.Код ПОДОБНО "641%" ИЛИ Ост.Счет.Код ПОДОБНО "642%" ИЛИ Ост.Счет.Код ПОДОБНО "651%"
СГРУППИРОВАТЬ ПО Ост.Организация.КодПоЕДРПОУ, Ост.Организация.Наименование
"""
print("=== ДИАГНОСТИКА: орг в ЕРП Хозрасчетном (налог.счета, БЕЗ фильтра) ===")
try:
    for s in qd.Execute().Выгрузить():
        flag = "✓А_ВБалансе" if s.ЕДРПОУ in edrpou else "✗вне баланса"
        print(f"  {str(s.ЕДРПОУ):12} {str(s.Наим)[:30]:30} сальдо={float(s.Сальдо):>16,.2f}  {flag}")
except Exception as e:
    fail("ЕРП диагностика орг", e)
print()

# ===== 2. Запрос Хозрасчетный по Счёт.Код (для любой базы) =====
def хозрасчетный_по_счету(conn, нужен_едрпоу_массив=True):
    масЕ = conn.NewObject("Массив")
    for e in edrpou: масЕ.Добавить(e)
    q = conn.NewObject("Запрос")
    q.SetParameter("НП", НП); q.SetParameter("КП", КП); q.SetParameter("Список", масЕ)
    q.Text = """
    ВЫБРАТЬ Ост.Счет.Код КАК КодСчета,
        СУММА(Ост.СуммаНачальныйОстатокКт - Ост.СуммаНачальныйОстатокДт) КАК НачОст,
        СУММА(Ост.СуммаОборотКт) КАК Приход,
        СУММА(Ост.СуммаОборотДт) КАК Расход,
        СУММА(Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) КАК КонОст
    ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&НП, &КП, , , , , ) КАК Ост
    ГДЕ (Ост.Счет.Код ПОДОБНО "641%" ИЛИ Ост.Счет.Код ПОДОБНО "642%" ИЛИ Ост.Счет.Код ПОДОБНО "651%")
        И Ост.Организация.КодПоЕДРПОУ В (&Список)
    СГРУППИРОВАТЬ ПО Ост.Счет.Код
    """
    res = {}
    for s in q.Execute().Выгрузить():
        res[str(s.КодСчета).strip()] = {"НачОст": float(s.НачОст), "Приход": float(s.Приход),
                                         "Расход": float(s.Расход), "КонОст": float(s.КонОст)}
    return res

try:
    erp_acc = хозрасчетный_по_счету(erp)
except Exception as e:
    fail("ЕРП Хозрасчетный", e)
try:
    buh_acc = хозрасчетный_по_счету(buh)
except Exception as e:
    fail("BuhBud Хозрасчетный", e)
print(f"ЕРП счетов: {len(erp_acc)} | BuhBud счетов: {len(buh_acc)}\n")

# ===== 3. Merge по Счёт.Код =====
коды = sorted(set(list(erp_acc) + list(buh_acc)))
print("=== СВЕРКА ПО СЧЁТУ, КонечныйОстаток на 31.12.2025 (Кт−Дт), Разница=ЕРП−Бух ===")
print(f"{'Счёт':7} {'ВидНалога':16} {'КонОст_ЕРП':>16} {'КонОст_Бух':>16} {'Разница':>15}")
tE = tB = 0.0
for к in коды:
    e = erp_acc.get(к, {}).get("КонОст", 0.0)
    b = buh_acc.get(к, {}).get("КонОст", 0.0)
    tE += e; tB += b
    fl = "" if abs(e - b) < 0.01 else "  <-"
    print(f"{к:7} {вид_налога(к):16} {e:>16,.2f} {b:>16,.2f} {e-b:>15,.2f}{fl}")
print(f"{'ИТОГО':7} {'':16} {tE:>16,.2f} {tB:>16,.2f} {tE-tB:>15,.2f}\n")

# ===== 4. Сверка BuhBud-стороны (роллап по ВидНалога) с эталоном из текущего отчёта =====
buh_vn = {}
for к, d in buh_acc.items():
    buh_vn[вид_налога(к)] = buh_vn.get(вид_налога(к), 0.0) + d["КонОст"]
# Эталон = валидированный первый отчёт (3-орг роллап BuhBud Хозрасчетный, проверен smoke PASS)
эталон_buh = {"НДС": 5044423.44, "НалогНаПрибыль": 1643480.14, "НДФЛ": -16779.64,
              "НачисленныйЕСВ": -29284.26, "ВоенныйСбор": -1672.11, "ЕдиныйНалог": -1.57,
              "ДругиеНалоги": -228358.95}
print("=== BuhBud-сторона (роллап по ВидНалога) vs эталон первого (валидированного) отчёта ===")
ok = True
for vn, exp in эталон_buh.items():
    got = buh_vn.get(vn, 0.0); m = abs(got - exp) < 0.01; ok = ok and m
    print(f"  {vn:16} эталон={exp:>15,.2f} факт={got:>15,.2f} {'OK' if m else 'DIFF'}")
print(f"  Итого Бух: эталон=   6,411,807.05 факт={sum(buh_vn.values()):>15,.2f} "
      f"{'OK' if abs(sum(buh_vn.values())-6411807.05)<0.01 else 'DIFF'}")
print("\n=== ИТОГ pre-тест:", "PASS (BuhBud=эталон, синтаксис OK)" if ok else "BuhBud DIFF — разобрать", "===")
