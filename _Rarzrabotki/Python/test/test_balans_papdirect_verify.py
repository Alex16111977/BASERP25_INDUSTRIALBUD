def прочитать_прямой(ref):
    """Source=ПустаяСсылка строки регистратора ref."""
    qr = conn.NewObject("Запрос")
    qr.Текст = """ВЫБРАТЬ
        Организация КАК Орг,
        ЕСТЬNULL(Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
        Статья КАК Ст, ПРЕДСТАВЛЕНИЕ(Статья) КАК СтП,
        Расхождение КАК Рх, ОбъектыЭксплуатации КАК ОЭ,
        НематериальныйАктив КАК НМА, ТипНалога КАК ТН,
        ДокументДвижения КАК ДД, Регистратор КАК Рег,
        СуммаНачальныйОстаток КАК НО, СуммаПриход КАК Пр,
        СуммаРасход КАК Рс, СуммаКонечныйОстаток КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод
    ГДЕ Регистратор=&Д
        И Source = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)"""
    qr.УстановитьПараметр("Д", ref)
    t = qr.Выполнить().Выгрузить()
    свод = {}; детСубк = плугов = докНеСвой = докПуст = всего = 0
    дет_ключи = Counter(); плуг_ключи = Counter()
    плуг_ошибок = дет_ошибок = 0
    налог_тн = {}
    refX = conn.XMLСтрока(ref)
    for i in range(t.Количество()):
        r = t.Получить(i); всего += 1
        орг = conn.XMLСтрока(r.Орг)
        подр = conn.XMLСтрока(r.Подр) if conn.ЗначениеЗаполнено(r.Подр) else "∅"
        ст = conn.XMLСтрока(r.Ст); стН = str(r.СтП)
        но = float(r.НО or 0); ко = float(r.КО or 0)
        d = свод.setdefault((орг, подр, ст), [0.0, 0.0, 0.0, 0.0, стН])
        d[0] += но; d[1] += float(r.Пр or 0)
        d[2] += float(r.Рс or 0); d[3] += ко
        if not conn.ЗначениеЗаполнено(r.ДД):
            докПуст += 1
        elif conn.XMLСтрока(r.ДД) != refX:
            докНеСвой += 1
        оэ = conn.ЗначениеЗаполнено(r.ОЭ)
        нма = conn.ЗначениеЗаполнено(r.НМА)
        тн = conn.ЗначениеЗаполнено(r.ТН)
        if bool(r.Рх):
            плугов += 1
            плуг_ключи[(орг, подр, ст)] += 1
            if оэ or нма or тн:
                плуг_ошибок += 1
        else:
            if оэ or нма or тн:
                детСубк += 1
            кОЭ = conn.XMLСтрока(r.ОЭ) if оэ else "∅"
            кНМА = conn.XMLСтрока(r.НМА) if нма else "∅"
            кТН = conn.XMLСтрока(r.ТН) if тн else "∅"
            дет_ключи[(орг, подр, ст, кОЭ, кНМА, кТН)] += 1
            if стН == "Налоги" and тн:
                тнП = картаТН.get(conn.XMLСтрока(r.ТН), "?")
                налог_тн[тнП] = налог_тн.get(тнП, 0.0) + ко
    дубл_дет = sum(1 for c in дет_ключи.values() if c > 1)
    дубл_плуг = sum(1 for c in плуг_ключи.values() if c > 1)
    return dict(свод=свод, детСубк=детСубк, плугов=плугов, докНеСвой=докНеСвой,
                докПуст=докПуст, всего=всего, дубл_дет=дубл_дет,
                дубл_плуг=дубл_плуг, плуг_ошибок=плуг_ошибок,
                дет_ошибок=дет_ошибок, налог_тн=налог_тн)


