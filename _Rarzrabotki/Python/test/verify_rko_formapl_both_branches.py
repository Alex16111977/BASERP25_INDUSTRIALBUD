# извлечь изменённый запрос реквизитов из файла и прогнать для найденного РКО
content = io.open(r"C:\Configuration_downloads\BASERP25\Documents\РасходныйКассовыйОрдер\Ext\ManagerModule.bsl", encoding="utf-8-sig").read()
def depipe(lit):
    return "\n".join(ln if i==0 else (ln[ln.find("|")+1:] if "|" in ln else ln) for i,ln in enumerate(lit.split("\n"))).replace('""','"')
i = content.index("Процедура ЗаполнитьПараметрыИнициализации"); j = content.index("Запрос.Текст =", i)
op = content.index('"', j); cl = content.index('";', op+1)
rekviz = depipe(content[op+1:cl])

