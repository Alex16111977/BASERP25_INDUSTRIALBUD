# -*- coding: utf-8 -*-
# ШАГ 4 smoke: запуск собранной .epf против РЕАЛЬНОЙ BuhBud (Enterprise, без блокировки).
# ВнешниеОбработки.Создать(epf).ЗаполнитьПоСписаниюРеализацию(spis, realiz) в транзакции,
# проверка результат-Структуры и ТЧ Товары, ОТКАТ. Компилирует ObjectModule против реальных типов.
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

EPF = r'C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Заполнить в бухучете приобритение по списанию.epf'
НомерПриёмника = "ІБ00-000110"

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# Списание с максимумом Кт-проводок (по Ref)
qm = buh.NewObject("Запрос")
qm.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Х.Регистратор КАК Рег, КОЛИЧЕСТВО(*) КАК Кво
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
ГДЕ Х.КоличествоКт > 0 И ТИПЗНАЧЕНИЯ(Х.Регистратор) = ТИП(Документ.СписаниеТоваров)
СГРУППИРОВАТЬ ПО Х.Регистратор УПОРЯДОЧИТЬ ПО Кво УБЫВ
"""
sm = qm.Execute().Выбрать(); sm.Следующий()
СписаниеСсылка = sm.Рег

qp = buh.NewObject("Запрос")
qp.Text = "ВЫБРАТЬ Ссылка ИЗ Документ.РеализацияТоваровУслуг ГДЕ Номер = &Н"
qp.SetParameter("Н", НомерПриёмника)
sp = qp.Execute().Выбрать(); sp.Следующий()
ПриёмникСсылка = sp.Ссылка

print(f"Списание : {buh.String(СписаниеСсылка)}")
print(f"Приёмник : {buh.String(ПриёмникСсылка)}")

Обр = buh.ВнешниеОбработки.Создать(EPF)   # компиляция ObjectModule против реальной BuhBud
print("ВнешниеОбработки.Создать — OK (ObjectModule скомпилирован)")

buh.НачатьТранзакцию()
try:
    Рез = Обр.ЗаполнитьПоСписаниюРеализацию(СписаниеСсылка, ПриёмникСсылка)
    print("--- Результат-Структура движка ---")
    print(f"  Успех       : {Рез.Успех}")
    print(f"  Сообщение   : {Рез.Сообщение}")
    print(f"  Строк       : {Рез.Строк}")
    print(f"  ИтогоСумма  : {Рез.ИтогоСумма:.2f}")
    print(f"  ИтогоНДС    : {Рез.ИтогоНДС:.2f}")
    print(f"  Распроведён : {Рез.Распроведён}")

    Док = ПриёмникСсылка.ПолучитьОбъект()
    rСум = sum(s.Сумма for s in Док.Товары)
    rНДС = sum(s.СуммаНДС for s in Док.Товары)
    rСеб = sum(s.Себестоимость for s in Док.Товары)
    print("--- Приёмник после движка (перечитан) ---")
    print(f"  Строк ТЧ Товары : {Док.Товары.Количество()}")
    print(f"  Σ Сумма          : {rСум:.2f}")
    print(f"  Σ СуммаНДС        : {rНДС:.2f}")
    print(f"  Σ Себестоимость   : {rСеб:.2f}")
    print(f"  Проведен          : {Док.Проведен}")

    ok = (Рез.Успех and Рез.Строк == Док.Товары.Количество()
          and abs(rСум - Рез.ИтогоСумма) < 0.01
          and abs(rНДС - Рез.ИтогоНДС) < 0.01
          and abs(rСеб - Рез.ИтогоСумма) < 0.01
          and not Док.Проведен)
    print("SMOKE:", "GREEN — .epf компилируется и заполняет корректно" if ok else "RED — разобрать")
finally:
    buh.ОтменитьТранзакцию()
    print("Транзакция откачена — продакшн не изменён.")
