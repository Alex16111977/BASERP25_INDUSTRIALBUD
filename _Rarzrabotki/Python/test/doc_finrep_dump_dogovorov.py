def дата(г, м, д, ч=0, мин=0, с=0):
    q = buh.NewObject("Запрос")
    q.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({г},{м},{д},{ч},{мин},{с}) КАК Д"
    return q.Execute().Выгрузить().Получить(0).Д


def дата_текст(значение):
    """Дата ресурсу як dd.mm.yyyy; порожня дата 1С (0001 рік) — порожній рядок."""
    т = str(buh.String(значение)) if значение is not None else ""
    return "" if not т or т.startswith("01.01.0001") else т[:10]


def чисто(значение):
    """Наименования договоров содержат переносы строк и табы — они рвут TSV на части."""
    return " ".join(str(значение if значение is not None else "").split())


НАПР = buh.Справочники.Направления.НайтиПоНаименованию("Производство", True)
СЧЕТ = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("361")
