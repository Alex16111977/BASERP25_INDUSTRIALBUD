# -*- coding: utf-8 -*-
# Повний тест оновленого запиту до ZUP_1 з полем СуммаБазы (для ЄСВ).
# Симулює саме той запит що тепер у BSL, щоб переконатись що він працює
# і повертає коректну базу для Постернака.
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="SQLSERVER";Ref="zup_1";Usr="cfo";Pwd="2442"')
S = zup.String


def com_date(y, m, d, hh=0, mm=0, ss=0):
    return pywintypes.Time(datetime.datetime(y, m, d, hh, mm, ss))


# Знаходжу правильні ЄДРПОУ з ZUP_1
print("=== Організації у ZUP_1 ===")
qо = zup.NewObject("Запрос")
qо.Text = (
    "ВЫБРАТЬ Организация, Организация.Наименование КАК ОргИм, КодПоЕДРПОУ "
    "ИЗ РегистрСведений.КодыОрганизации.СрезПоследних "
)
rо = qо.Execute().Выгрузить()
print(f"Організацій: {rо.Количество()}")
mass_edrpou = zup.NewObject("Массив")
for i in range(rо.Количество()):
    row = rо.Получить(i)
    ім = S(row.ОргИм)
    кєд = S(row.КодПоЕДРПОУ)
    print(f"  {ім} — ЄДРПОУ={кєд}")
    if кєд:
        mass_edrpou.Добавить(кєд)

# Точний запит — як у BSL
q = zup.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	ВзаиморасчетыПоНДФЛ.Сотрудник.Физлицо.КодПоДРФО КАК СотрудникИНН,
	ВзаиморасчетыПоНДФЛ.Сотрудник.Физлицо.Наименование КАК СотрудникНаименование,
	СУММА(ВзаиморасчетыПоНДФЛ.НалогПриход) КАК СуммаНалога,
	СУММА(ВзаиморасчетыПоНДФЛ.ДоходПриход) КАК СуммаДохода,
	ВложенныйЗапрос.КодПоЕДРПОУ КАК КодПоЕДРПОУ,
	ВзаиморасчетыПоНДФЛ.ДоходНДФЛ.Код КАК КодДохода,
	0 КАК СуммаФОТ,
	0 КАК СуммаБазы,
	"ВоенныйСбор" КАК КодНалогаСтатьяДенег,
	"ВоенныйСбор" КАК КодНалога
ИЗ
	РегистрНакопления.ВзаиморасчетыПоНДФЛ.Обороты(&НачалоПериода, &КонецПериода, , ) КАК ВзаиморасчетыПоНДФЛ
		ВНУТРЕННЕЕ СОЕДИНЕНИЕ (ВЫБРАТЬ
			КодыОрганизацииСрезПоследних.Организация КАК Организация,
			КодыОрганизацииСрезПоследних.КодПоЕДРПОУ КАК КодПоЕДРПОУ
		ИЗ
			РегистрСведений.КодыОрганизации.СрезПоследних КАК КодыОрганизацииСрезПоследних) КАК ВложенныйЗапрос
		ПО ВзаиморасчетыПоНДФЛ.Организация = ВложенныйЗапрос.Организация
ГДЕ
	ВзаиморасчетыПоНДФЛ.НалогПриход <> 0
	И ВложенныйЗапрос.КодПоЕДРПОУ В(&масКодПоЕДРПОУ)

СГРУППИРОВАТЬ ПО
	ВзаиморасчетыПоНДФЛ.Сотрудник.Физлицо.КодПоДРФО,
	ВзаиморасчетыПоНДФЛ.Сотрудник.Физлицо.Наименование,
	ВложенныйЗапрос.КодПоЕДРПОУ,
	ВзаиморасчетыПоНДФЛ.ДоходНДФЛ.Код

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
	ВзносыВФонды.Сотрудник.Физлицо.КодПоДРФО,
	ВзносыВФонды.Сотрудник.Физлицо.Наименование,
	0,
	0,
	ВложенныйЗапрос.КодПоЕДРПОУ,
	NULL,
	СУММА(ВзносыВФонды.Результат),
	СУММА(ВзносыВФонды.База),
	"ЕСВФОТРаботники",
	ВзносыВФонды.Налог.Код
ИЗ
	РегистрРасчета.ВзносыВФонды КАК ВзносыВФонды
		ВНУТРЕННЕЕ СОЕДИНЕНИЕ (ВЫБРАТЬ
			КодыОрганизацииСрезПоследних.Организация КАК Организация,
			КодыОрганизацииСрезПоследних.КодПоЕДРПОУ КАК КодПоЕДРПОУ
		ИЗ
			РегистрСведений.КодыОрганизации.СрезПоследних КАК КодыОрганизацииСрезПоследних) КАК ВложенныйЗапрос
		ПО ВзносыВФонды.Организация = ВложенныйЗапрос.Организация
ГДЕ
	ВложенныйЗапрос.КодПоЕДРПОУ В(&масКодПоЕДРПОУ)
	И ВзносыВФонды.Результат <> 0
	И ВзносыВФонды.ПериодРегистрации МЕЖДУ &НачалоПериода И &КонецПериода

СГРУППИРОВАТЬ ПО
	ВложенныйЗапрос.КодПоЕДРПОУ,
	ВзносыВФонды.Сотрудник.Физлицо.КодПоДРФО,
	ВзносыВФонды.Сотрудник.Физлицо.Наименование,
	ВзносыВФонды.Налог.Код
"""
q.SetParameter("НачалоПериода", com_date(2025, 12, 1))
q.SetParameter("КонецПериода", com_date(2025, 12, 31, 23, 59, 59))
q.SetParameter("масКодПоЕДРПОУ", mass_edrpou)

try:
    r = q.Execute().Выгрузить()
    print(f"Всього рядків: {r.Количество()}")

    # Виводимо тільки Постернака
    print("\n=== Постернак А.В. ===")
    for i in range(r.Количество()):
        row = r.Получить(i)
        ном = S(row.СотрудникНаименование)
        if "Постернак" not in ном:
            continue
        print(f"\n  ІНН={S(row.СотрудникИНН)} ЄДРПОУ={S(row.КодПоЕДРПОУ)}")
        print(f"    Налог={S(row.КодНалога)}  КодДохода={S(row.КодДохода)}")
        print(f"    СуммаНалога={S(row.СуммаНалога)}  СуммаДохода={S(row.СуммаДохода)}")
        print(f"    СуммаФОТ={S(row.СуммаФОТ)}  СуммаБазы={S(row.СуммаБазы)}")

    # Підсумки
    print("\n=== Загальні підсумки ===")
    total_налог = 0
    total_фот = 0
    total_дохід = 0
    total_база = 0
    for i in range(r.Количество()):
        row = r.Получить(i)
        try:
            total_налог += float(S(row.СуммаНалога).replace('\xa0', '').replace(' ', '').replace(',', '.') or 0)
            total_фот += float(S(row.СуммаФОТ).replace('\xa0', '').replace(' ', '').replace(',', '.') or 0)
            total_дохід += float(S(row.СуммаДохода).replace('\xa0', '').replace(' ', '').replace(',', '.') or 0)
            total_база += float(S(row.СуммаБазы).replace('\xa0', '').replace(' ', '').replace(',', '.') or 0)
        except:
            pass
    print(f"  СуммаНалога (НДФЛ+ВС):    {total_налог:>15,.2f}")
    print(f"  СуммаДохода (по НДФЛ):    {total_дохід:>15,.2f}")
    print(f"  СуммаФОТ (ЄСВ результат): {total_фот:>15,.2f}")
    print(f"  СуммаБазы (ЄСВ база):     {total_база:>15,.2f}")
    print()
    print(f"  Перевірка: Ставка ЄСВ = {total_фот/total_база*100 if total_база > 0 else 0:.2f}% (має бути ~22%)")

except Exception as e:
    print(f"ERR: {e}")
