# ---------------------------------------------------------------- парсер
ОСНОВЫ = "мод|буд|дом|шт"
# «3 МОДУЛІ - 100%», «1 МОД.- 60%», «2 МОД. - 0%», «4 буд.:100 %»
СЕГМЕНТ = re.compile(
    r"(\d+)\s*(?:" + ОСНОВЫ + r")[a-zA-Zа-яА-ЯіїєґІЇЄҐ'’.]*\s*[-–—:]*\s*(\d+(?:[.,]\d+)?)\s*%",
    re.IGNORECASE)
# «сегментоподобный» фрагмент для контроля полноты разбора
ФРАГМЕНТ = re.compile(r"\d+\s*(?:" + ОСНОВЫ + r")", re.IGNORECASE)
ОДИНОЧНЫЙ = re.compile(r"^(\d+(?:[.,]\d+)?)\s*%$")

def парс(текст, n):
    """-> (проценты[n], флаги[list[str]]).  Никогда не молчит: всё сомнительное -> флаг."""
    t = str(текст or "").strip()
    флаги = []
    if not t:
        return [0.0]*n, флаги
    сегм = СЕГМЕНТ.findall(t)
    if сегм:
        проц, домов = [], 0
        for кол, п in сегм:
            к = int(кол); p = float(п.replace(",", "."))
            домов += к
            if p < 0 or p > 100:
                флаги.append(f"процент {p} вне 0..100")
            проц += [p]*к
        # контроль 1: все ли фрагменты разобраны
        фрагм = len(ФРАГМЕНТ.findall(t))
        if фрагм > len(сегм):
            флаги.append(f"РАСПОЗНАНО {len(сегм)} сегм. из {фрагм} — часть текста ПОТЕРЯНА")
        # контроль 2: сумма домов
        if домов != n:
            флаги.append(f"Σ домов в сегментах = {домов}, а домов {n}")
        if len(проц) > n:
            флаги.append(f"сегменты дают {len(проц)} домов > {n} — хвост отброшен")
        return (проц + [0.0]*n)[:n], флаги
    m = ОДИНОЧНЫЙ.match(t)
    if m:
        return [float(m.group(1).replace(",", "."))]*n, флаги
    # контроль 3: есть цифры и %, но не распознано
    if "%" in t and re.search(r"\d", t):
        флаги.append("есть цифры и «%», но сегменты НЕ распознаны")
    return [0.0]*n, флаги

def факт_текст(v, nf):
    if v is None or isinstance(v, bool): return ""
    if isinstance(v, (int, float)): return (f"{v*100:g}%" if "%" in (nf or "") else f"{v:g}")
    return str(v).strip()

def норм(s):
    return re.sub(r"\s+", " ", str(s or "").strip().lower().replace("'", "").replace("’", ""))

