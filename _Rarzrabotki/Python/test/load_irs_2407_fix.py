def найти(подр):
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("СС", сс.Ссылка); q.УстановитьПараметр("П", подр); q.УстановитьПараметр("Д", дата)
    q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК С ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д "
               "ГДЕ Д.СтруктураСебестоимости = &СС И Д.Подразделение = &П "
               "И Д.Дата МЕЖДУ НАЧАЛОПЕРИОДА(&Д, ДЕНЬ) И КОНЕЦПЕРИОДА(&Д, ДЕНЬ)")
    r = q.Execute().Выгрузить()
    return r.Получить(0).С if r.Количество() else None

