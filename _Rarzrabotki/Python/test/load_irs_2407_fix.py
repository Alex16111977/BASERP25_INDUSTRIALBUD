# ---------------------------------------------------------------- загрузка
def обороты(ссылка):
    q = erp.NewObject("Запрос"); q.УстановитьПараметр("СС", ссылка)
    q.Текст = ("ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т "
               "ГДЕ Т.СтруктураСебестоимости = &СС")
    return float(q.Execute().Выгрузить().Получить(0).Ч or 0)

