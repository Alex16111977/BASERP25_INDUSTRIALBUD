# Видалити існуючий ОтражениеЗарплатыВФинансовомУчете, створений процедурою,
# щоб тест створив його з нуля без старої А_РаспределениеКазна.
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Батько
q = erp.NewObject('Запрос')
q.Text = 'ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д ГДЕ Д.Номер = "000000001"'
sel = q.Execute().Выбрать()
sel.Следующий()
parent = sel.Ссылка

# Дочка
q2 = erp.NewObject('Запрос')
q2.Text = 'ВЫБРАТЬ ОЗ.Ссылка ИЗ Документ.ОтражениеЗарплатыВФинансовомУчете КАК ОЗ ГДЕ ОЗ.А_ДокОтражениеЗПпоКазне = &Осн'
q2.SetParameter('Осн', parent)
r = q2.Execute().Выгрузить()
print(f'Знайдено дочірніх: {r.Количество()}')

for i in range(r.Количество()):
    ref = r.Получить(i).Ссылка
    obj = ref.ПолучитьОбъект()
    print(f'Видаляю: {S(ref)} (А_РаспределениеКазна={obj.А_РаспределениеКазна.Количество()} рядків)')
    obj.Удалить()
print('OK')
