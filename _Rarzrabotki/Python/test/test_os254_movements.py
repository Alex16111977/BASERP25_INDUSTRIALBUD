"""Перевірка рухів документа ПринятиеКУчетуОС ІБ00-000254"""
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# 1. Знайти документ
q = conn.NewObject("Запрос")
q.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка, Д.Номер, Д.Дата, Д.Организация, Д.Подразделение ИЗ Документ.ПринятиеКУчетуОС КАК Д ГДЕ Д.Номер ПОДОБНО &Н"
q.SetParameter("Н", "%000254%")
r = q.Execute().Select()
r.Next()
ref = r.Ссылка
print(f"Док: #{r.Номер} от {r.Дата}")
print(f"Орг: {S(r.Организация)}")
print(f"Подр: {S(r.Подразделение)}")

# 2. ТЧ ОС
print("\n--- ТЧ ОС ---")
q2 = conn.NewObject("Запрос")
q2.Text = "ВЫБРАТЬ Т.ОсновноеСредство КАК ОС, Т.СтоимостьБУ ИЗ Документ.ПринятиеКУчетуОС.ОС КАК Т ГДЕ Т.Ссылка = &С"
q2.SetParameter("С", ref)
r2 = q2.Execute().Select()
while r2.Next():
    print(f"  ОС: {S(r2.ОС)} Вартість: {r2.СтоимостьБУ}")

# 3. Проводки
print("\n--- Хозрасчетный ---")
q3 = conn.NewObject("Запрос")
q3.Text = "ВЫБРАТЬ Д.СчетДт, Д.СчетКт, Д.Сумма ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д ГДЕ Д.Регистратор = &С"
q3.SetParameter("С", ref)
r3 = q3.Execute().Select()
cnt = 0
while r3.Next():
    cnt += 1
    print(f"  Дт {S(r3.СчетДт)} Кт {S(r3.СчетКт)} = {r3.Сумма}")
if cnt == 0:
    print("  ПУСТО!")

# 4. ПрочиеАктивыПассивы
print("\n--- ПрочиеАктивыПассивы ---")
