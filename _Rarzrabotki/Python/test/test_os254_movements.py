q4.SetParameter("С", ref)
r4 = q4.Execute().Select()
cnt = 0
while r4.Next():
    cnt += 1
    print(f"  {S(r4.Вид)} Статья={S(r4.Статья)} Аналит={S(r4.Аналитика)} Сума={r4.Сумма}")
