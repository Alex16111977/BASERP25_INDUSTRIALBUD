# 5. ПрочиеРасходы
print("\n--- ПрочиеРасходы ---")
q5 = conn.NewObject("Запрос")
q5.Text = "ВЫБРАТЬ Д.ВидДвижения КАК Вид, Д.СтатьяРасходов, Д.АналитикаРасходов, Д.СтоимостьРегл ИЗ РегистрНакопления.ПрочиеРасходы КАК Д ГДЕ Д.Регистратор = &С"
q5.SetParameter("С", ref)
