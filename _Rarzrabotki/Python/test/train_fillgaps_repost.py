# -*- coding: utf-8 -*-
"""
Тренировка дозаполнения: дозаполнить Подразделение + Договор в шапке
Списания 000Ц-000228 (897.45), потом перепровести. Посмотреть появятся ли
движения в РасчетыСПоставщикамиПоСрокам.

Гипотеза: типовой ВзаиморасчетыСервер.ПередЗаписью требует Подразделение
и Договор в шапке чтобы написать в ПоСрокам.

Тренировка на одном документе!
"""
import sys, io, datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', write_through=True)

import win32com.client, pythoncom
pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Д1", datetime.datetime(2025, 12, 16, 0, 0, 0))
q.УстановитьПараметр("Д2", datetime.datetime(2025, 12, 16, 23, 59, 59))
q.УстановитьПараметр("Σ", 897.45)
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Д
ГДЕ Д.Дата МЕЖДУ &Д1 И &Д2 И Д.СуммаДокумента = &Σ
"""
r = q.Выполнить().Выгрузить()
если_нет = r.Количество() == 0
print(f"Документ найден: {not если_нет}", flush=True)
if если_нет:
    sys.exit(0)
док = r.Получить(0).Ссылка
obj = док.ПолучитьОбъект()

# Берём Договор и Подразделение из строки РП
рп = obj.РасшифровкаПлатежа.Получить(0)
договор_из_рп = рп.А_Договор
подразделение_получатель = obj.Партнер  # тут партнёр-получатель Глобино-2; ищем его подразделение

# Партнёр-получатель «Глобино-2» — найти подразделение с тем же именем
qp = erp.NewObject("Запрос")
qp.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтруктураПредприятия ГДЕ Наименование = "Глобино-2"'
подразделение = qp.Выполнить().Выгрузить().Получить(0).Ссылка


def дамп_движений(метка):
    print(f"\n--- {метка} ---", flush=True)
    for имя in ["РасчетыСКлиентами", "РасчетыСПоставщиками",
                "РасчетыСКлиентамиПоСрокам", "РасчетыСПоставщикамиПоСрокам"]:
        qq = erp.NewObject("Запрос")
        qq.УстановитьПараметр("Рег", док)
        qq.Текст = f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.{имя} ГДЕ Регистратор = &Рег"
        print(f"  {имя:<40}: {int(qq.Выполнить().Выгрузить().Получить(0).К)}", flush=True)


print(f"\nДокумент: {S(док)}", flush=True)
print(f"Шапка ДО:", flush=True)
print(f"  Подразделение: {('(пусто)' if obj.Подразделение is None or obj.Подразделение.Пустая() else S(obj.Подразделение))}", flush=True)
print(f"  Договор:       {('(None)' if obj.Договор is None else ('(пусто)' if obj.Договор.Пустая() else S(obj.Договор)))}", flush=True)
print(f"  ОР:            {('(пусто)' if obj.ОбъектРасчетов is None or obj.ОбъектРасчетов.Пустая() else S(obj.ОбъектРасчетов))}", flush=True)
print(f"\nИз РП:", flush=True)
print(f"  А_Договор:     {S(договор_из_рп) if договор_из_рп and not договор_из_рп.Пустая() else '(пусто)'}", flush=True)
print(f"  ОР в РП:       {S(рп.ОбъектРасчетов) if not рп.ОбъектРасчетов.Пустая() else '(пусто)'}", flush=True)

дамп_движений("ДО — движения")

# === Дозаполняем шапку ===
print(f"\nДозаполняю в шапке: Подразделение={S(подразделение)}, Договор={S(договор_из_рп)}", flush=True)
obj.Подразделение = подразделение
obj.Договор = договор_из_рп
# Не трогаем флаги — финансист сказал они не влияют

print("Перепровожу (отмена + проведение)...", flush=True)
try:
    if obj.Проведен:
        obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
        obj = док.ПолучитьОбъект()
        # И снова дозаполнить (могло сброситься)
        obj.Подразделение = подразделение
        obj.Договор = договор_из_рп
    obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("✓ Готово.", flush=True)
except Exception as e:
    емсг = e.excepinfo[2] if (hasattr(e,'excepinfo') and e.excepinfo) else str(e)
    print(f"✗ FAIL: {емсг[:200]}", flush=True)
    sys.exit(1)

# Проверить шапку после
obj2 = док.ПолучитьОбъект()
print(f"\nШапка ПОСЛЕ:", flush=True)
print(f"  Подразделение: {('(пусто)' if obj2.Подразделение is None or obj2.Подразделение.Пустая() else S(obj2.Подразделение))}", flush=True)
print(f"  Договор:       {('(None)' if obj2.Договор is None else ('(пусто)' if obj2.Договор.Пустая() else S(obj2.Договор)))}", flush=True)
print(f"  ОР:            {('(пусто)' if obj2.ОбъектРасчетов is None or obj2.ОбъектРасчетов.Пустая() else S(obj2.ОбъектРасчетов))}", flush=True)
print(f"  А_ВведенВЕРП:  {obj2.А_ВведенВЕРП}", flush=True)

дамп_движений("ПОСЛЕ — движения")
