# -*- coding: utf-8 -*-
"""Pre-test (Rule #-1): из ТЧ НачальнаяЗадолженность строим ожидаемые движения А_ВзСС.
Подтверждает конверсии (Сотрудник.ФизическоеЛицо, Подразделение.А_Подразделение, ФормаPL пусто->Форма1)
ДО правки BSL. Запускать перед Шагом 2.

ВАЖНО (найдено discovery 2026-06-01): период движения = ДокОбъект.Месяц, НЕ ДокОбъект.Дата.
У документа ввода остатков Дата (тех.дата ввода) и Месяц (период остатка) расходятся
(эталон: Дата=2026-11-30, Месяц=2025-11-01 — разные месяцы!). Типовое проведение пишет
ВзаиморасчетыССотрудниками с периодом=Месяц; наш А_ВзСС обязан совпадать по периоду."""
import sys, win32com.client
if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
XML = erp.XMLСтрока

# --- конверсии ТЧ ---
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    З.Ссылка КАК Док,
    З.Сотрудник.ФизическоеЛицо КАК ФЛ,
    З.Подразделение.А_Подразделение КАК Подр,
    ВЫБОР КОГДА З.ФормаPL = ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.ПустаяСсылка)
        ТОГДА ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.Форма1) ИНАЧЕ З.ФормаPL КОНЕЦ КАК ФормаPL,
    З.ОрганизацияБухгалтерия КАК ОргБух,
    З.Сумма КАК Сумма
ИЗ Документ.НачальнаяЗадолженностьПоЗарплате.ЗадолженностьПоЗарплате КАК З
ГДЕ З.Ссылка.Проведен"""
вб = q.Execute().Выбрать()
n = 0
while вб.Следующий():
    n += 1
    assert erp.ЗначениеЗаполнено(вб.ФЛ), "ФизическоеЛицо пусто (Сотрудник.ФизическоеЛицо)"
    assert erp.ЗначениеЗаполнено(вб.Подр), "Подразделение.А_Подразделение пусто (конверсия не сработала)"
    assert XML(вб.ФормаPL) in ("Форма1", "Форма2"), f"ФормаPL не резолвится: {XML(вб.ФормаPL)}"
    вд = "Приход" if float(вб.Сумма) > 0 else "Расход"
    print(f"  {вб.ФЛ.Наименование} / {вб.Подр.Наименование} / {XML(вб.ФормаPL)} / "
          f"ОргБух={вб.ОргБух.Наименование if erp.ЗначениеЗаполнено(вб.ОргБух) else '<пусто>'} / "
          f"{вд} {abs(float(вб.Сумма))}")
assert n > 0, "Нет проведённых строк НачальнаяЗадолженность — нечего проверять"

# --- период: документ имеет Месяц (период остатка); пишем его, не Дата ---
q2 = erp.NewObject("Запрос")
q2.Text = ("ВЫБРАТЬ Номер, Дата, Месяц ИЗ Документ.НачальнаяЗадолженностьПоЗарплате ГДЕ Проведен")
в2 = q2.Execute().Выбрать()
while в2.Следующий():
    нм_дата, нм_мес = XML(в2.Дата)[:7], XML(в2.Месяц)[:7]
    метка = "совпадают" if нм_дата == нм_мес else f"РАСХОДЯТСЯ -> берём Месяц ({нм_мес})"
    print(f"  период №{в2.Номер}: НМ(Дата)={нм_дата} / НМ(Месяц)={нм_мес} -> {метка}")

print(f"\nOK pretest: {n} строк ТЧ -> корректные конверсии (ФЛ, Подр, ФормаPL, знак, период=Месяц)")
