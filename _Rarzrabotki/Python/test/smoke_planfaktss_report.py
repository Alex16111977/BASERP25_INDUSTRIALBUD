# -*- coding: utf-8 -*-
"""Приёмка отчёта ПланФактСС: ПОЛНЫЙ путь пользователя через COM.

Гоняем именно СформироватьОтчет, а не только ПолучитьДанные: обработчик события
ПриКомпоновкеРезультата COM-прокси не отдаёт, и ошибки уровня компоновки
(отсутствующий метод БСП, рассинхрон схемы и ТЗ) видны только здесь.
"""
import os
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\ПланФактССБухгалтерія.erf"
CONN = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'


def main():
    assert os.path.exists(ERF), f"Не собран .erf: {ERF}"

    v8 = win32com.client.Dispatch("V83.COMConnector")
    b = v8.Connect(CONN)

    отчёт = b.ВнешниеОтчеты.Создать(ERF)
    print("OK: .erf открыт")

    настройки = отчёт.КомпоновщикНастроек.ПолучитьНастройки()
    параметр = настройки.ПараметрыДанных.Элементы.Найти("Период")
    assert параметр is not None, "В схеме нет параметра Период"

    период = b.NewObject("СтандартныйПериод")
    гр = b.NewObject("Запрос")
    гр.Текст = "ВЫБРАТЬ КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2026, 7, 31), ДЕНЬ) КАК К"
    период.ДатаОкончания = гр.Выполнить().Выгрузить()[0].К
    параметр.Значение = период
    параметр.Использование = True
    отчёт.КомпоновщикНастроек.ЗагрузитьНастройки(настройки)

    документ = b.NewObject("ТабличныйДокумент")
    отчёт.СформироватьОтчет(документ)

    assert документ.ВысотаТаблицы > 0, "СформироватьОтчет вернул пустой документ"
    print(f"OK: отчёт скомпонован, строк в табличном документе = {документ.ВысотаТаблицы}")
    print("SMOKE PASSED")


if __name__ == "__main__":
    main()
