# -*- coding: utf-8 -*-
# Smoke per-статья: Анализ (read-only) обработки дисбаланса с фильтром Спецтехника.
# Проверяет: компиляцию модуля объекта (.erf), и что Спецтехника попадает в ТЧ
# И как дебитор по статье "Налоги", И как кредитор по статье "Оплата труда".
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\А_ОбработкаДисбалансаПоПодразделениям.erf"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Ссылка на подразделение Спецтехника
q = erp.NewObject("Запрос")
q.Text = ('ВЫБРАТЬ ПЕРВЫЕ 1 Сп.Ссылка КАК Ссылка ИЗ Справочник.СтруктураПредприятия КАК Сп '
          'ГДЕ Сп.Наименование = "Спецтехника" И НЕ Сп.ПометкаУдаления')
s = q.Execute().Выбрать()
if not s.Следующий():
    print("FAIL: не найдено подразделение Спецтехника"); sys.exit(1)
specteh = s.Ссылка
print("Спецтехника ref OK:", erp.String(specteh))

# Загрузка .erf = проверка компиляции модуля объекта
try:
    obr = erp.ВнешниеОтчеты.Создать(ERF, False)
except Exception:
    obr = erp.ВнешниеОтчеты.Создать(ERF)
print("ERF загружен (модуль объекта скомпилирован) OK")

obr.НачалоПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.ОкончаниеПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.Подразделение = specteh
obr.ПоказыватьВсе = True
obr.АнализДокументов()

тч = obr.ДокументыДисбаланса
print("Строк ТЧ (с фильтром Спецтехника):", тч.Количество())

спец_деб = {}   # статья -> сумма (Спецтехника = ПодразделениеПриход/дебитор)
спец_кред = {}  # статья -> сумма (Спецтехника = ПодразделениеРасход/кредитор)
n = тч.Количество()
for i in range(n):
    стр = тч.Получить(i)
    приход = erp.String(стр.ПодразделениеПриход) if erp.ЗначениеЗаполнено(стр.ПодразделениеПриход) else ""
    расход = erp.String(стр.ПодразделениеРасход) if erp.ЗначениеЗаполнено(стр.ПодразделениеРасход) else ""
    статья = erp.String(стр.СтатьяДисбаланса) if erp.ЗначениеЗаполнено(стр.СтатьяДисбаланса) else "(пусто)"
    сумма = стр.СуммаДокумента
    if приход == "Спецтехника":
        спец_деб[статья] = спец_деб.get(статья, 0) + сумма
    if расход == "Спецтехника":
        спец_кред[статья] = спец_кред.get(статья, 0) + сумма

print("Спецтехника как ДЕБИТОР (Приход):")
for k, v in спец_деб.items():
    print(f"   {k}: {v:.2f}")
print("Спецтехника как КРЕДИТОР (Расход):")
for k, v in спец_кред.items():
    print(f"   {k}: {v:.2f}")

деб_налоги = any("Налоги" in k for k in спец_деб)
кред_оплата = any("Оплата труда" in k for k in спец_кред)

ok = True
if деб_налоги:
    print("OK: Спецтехника — дебитор по 'Налоги' (раньше пряталось в NET)")
else:
    print("FAIL: нет строки Спецтехника-дебитор по 'Налоги'"); ok = False
if кред_оплата:
    print("OK: Спецтехника — кредитор по 'Оплата труда'")
else:
    print("FAIL: нет строки Спецтехника-кредитор по 'Оплата труда'"); ok = False

print("=== SMOKE PASS ===" if ok else "=== SMOKE FAIL ===")
