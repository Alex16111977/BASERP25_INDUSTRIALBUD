# -*- coding: utf-8 -*-
"""ПАП «Оплата труда» — чистое измерение (литералы ДАТАВРЕМЯ, без tz-бага).
По каждому концу месяца: empty-source, named-sources, all-sources net.
empty-source == свёртка/PowerBI; all-sources == штатный Управленческий баланс (кандидат)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

q = erp.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов "
           "ГДЕ Наименование = \"Оплата труда\"")
ОТ = q.Выполнить().Выгрузить()[0].С

# даты-литералы в тексте запроса -> нет tz-сдвига
month_literals = [
    ("2025-12", "ДАТАВРЕМЯ(2025,12,31,23,59,59)"),
    ("2026-01", "ДАТАВРЕМЯ(2026, 1,31,23,59,59)"),
    ("2026-02", "ДАТАВРЕМЯ(2026, 2,28,23,59,59)"),
    ("2026-03", "ДАТАВРЕМЯ(2026, 3,31,23,59,59)"),
]

print(f"{'Месяц':<8} | {'empty(=свёртка)':>16} | {'named-источники':>16} | {'ВСЕ источники':>16}")
for label, lit in month_literals:
    # 1) только пустой источник (точно как втПАП Свода)
    q1 = erp.NewObject("Запрос")
    q1.УстановитьПараметр("ОТ", ОТ)
    q1.Текст = f"""
    ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Период <= {lit} И Т.Статья = &ОТ
        И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    """
    empty = f(q1.Выполнить().Выгрузить()[0].КО)
    # 2) все источники
    q2 = erp.NewObject("Запрос")
    q2.УстановитьПараметр("ОТ", ОТ)
    q2.Текст = f"""
    ВЫБРАТЬ СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
                ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Период <= {lit} И Т.Статья = &ОТ
    """
    allsrc = f(q2.Выполнить().Выгрузить()[0].КО)
    print(f"{label:<8} | {empty:>16,.2f} | {allsrc-empty:>16,.2f} | {allsrc:>16,.2f}")

# Разбивка по источникам (named) на 31.01.2026 — детально
print("\n=== Разбивка ПАП(ОТ) по источникам на 31.01.2026 (литерал) ===")
qd = erp.NewObject("Запрос")
qd.УстановитьПараметр("ОТ", ОТ)
qd.Текст = """
ВЫБРАТЬ
    Т.Источник КАК ИстРеф,
    ПРЕДСТАВЛЕНИЕ(Т.Источник) КАК ИстИмя,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО,
    КОЛИЧЕСТВО(*) КАК Движ
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59) И Т.Статья = &ОТ
СГРУППИРОВАТЬ ПО Т.Источник, ПРЕДСТАВЛЕНИЕ(Т.Источник)
"""
for r in qd.Выполнить().Выгрузить():
    nm = r.ИстИмя if r.ИстИмя else "(пустой ref)"
    pusto = "ПУСТОЙ" if not erp.ЗначениеЗаполнено(r.ИстРеф) else ""
    print(f"   {nm:<36} {pusto:<7} | движений={int(f(r.Движ)):>5} | КО={f(r.КО):>16,.2f}")
