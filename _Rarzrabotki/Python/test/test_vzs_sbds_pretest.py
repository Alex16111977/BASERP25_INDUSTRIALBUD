# -*- coding: utf-8 -*-
"""Pre-test (Rule #-1) для процедуры
РегистрыНакопления.А_ВзаиморасчетыССотрудниками.ЗаполнитьИзСписанияБезнал().

Источник ФизЛица: РасшифровкаПлатежа.Ведомость → ВедомостьНаВыплатуЗарплатыВБанк
                  → РегистрНакопления.ЗарплатаКВыплате (Регистратор=Ведомость, ВидДв=Расход).
Подразделение: из шапки СписаниеБезналичных (как в типовом запросе ПАП).
Сумма: СуммаКВыплате per ФизЛицо.
Знак: Расход (финансистская семантика — выплата уменьшает долг работодателя).

Фильтр: ХозОперация В (ВыплатаЗарплатыПоЗарплатномуПроекту, ВыплатаЗарплатыНаЛицевыеСчета)
        И ПроведеноБанком.

Тестовый документ: № 00000019099 от 03.12.2025 15:55:44, СуммаДокумента=4468.23 UAH,
ХозОп=ВыплатаЗарплатыПоЗарплатномуПроекту, Подр=Строительство.
Ожидаемое: 1 строка ФЛ=Соколовська Тетяна Сергіївна Σ=4468.23.

Asserts:
  1) rows > 0
  2) Σ Сумма А_ВзСС per (Орг, Подр) per Регистратор = Σ ПАП(Статья=ОТ) per (Орг, Подр) per Регистратор
  3) 0 дублей (Орг, Подр, ФизЛицо)
  4) 100% строк имеют ФизЛицо ≠ ПустаяСсылка
"""
import sys, io
from collections import Counter
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С
ПустоеФЛ_str = conn.XMLСтрока(conn.PredefinedValue(
    "Справочник.ФизическиеЛица.ПустаяСсылка"))

# Тестовый документ
q = conn.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Док ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Д
ГДЕ Д.Номер = &Н И Д.Дата = ДАТАВРЕМЯ(2025,12,3,15,55,44)"""
q.УстановитьПараметр("Н", "00000019099")
r = q.Выполнить().Выбрать(); r.Следующий()
ДОК = r.Док
print(f"Тестовый документ: {conn.String(ДОК)}")
print(f"UUID: {conn.XMLСтрока(ДОК)}\n")

# Главный запрос (1:1 как пойдёт в BSL)
ЗАПРОС = """
ВЫБРАТЬ
    Д.Организация КАК Организация,
    Д.Подразделение КАК Подразделение,
    Зар.ФизическоеЛицо КАК ФизическоеЛицо,
    СУММА(Зар.СуммаКВыплате) КАК Сумма
ИЗ
    Документ.СписаниеБезналичныхДенежныхСредств КАК Д
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.СписаниеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК РП
        ПО РП.Ссылка = Д.Ссылка
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ РегистрНакопления.ЗарплатаКВыплате КАК Зар
        ПО Зар.Регистратор = РП.Ведомость
ГДЕ
    Д.Ссылка = &Док
    И Д.ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыПоЗарплатномуПроекту),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыНаЛицевыеСчета))
    И Д.ПроведеноБанком
    И Зар.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)
СГРУППИРОВАТЬ ПО Д.Организация, Д.Подразделение, Зар.ФизическоеЛицо
ИМЕЮЩИЕ СУММА(Зар.СуммаКВыплате) <> 0
"""

print("=== Запрос распределения по ФизЛицу ===")
qT = conn.NewObject("Запрос")
qT.Текст = ЗАПРОС
qT.УстановитьПараметр("Док", ДОК)
tT = qT.Выполнить().Выгрузить()
rows = tT.Количество()
print(f"Строк: {rows}")

# Анализ
sum_total = 0.0
by_подр = {}
by_подр_total = {}
by_подр_fl = {}
keys = Counter()
for i in range(rows):
    e = tT.Получить(i)
    подр_key = (conn.XMLСтрока(e.Организация), conn.XMLСтрока(e.Подразделение))
    by_подр.setdefault(подр_key, 0)
    by_подр[подр_key] += float(e.Сумма or 0)
    by_подр_total.setdefault(подр_key, 0)
    by_подр_total[подр_key] += 1
    fl_str = conn.XMLСтрока(e.ФизическоеЛицо)
    if fl_str != ПустоеФЛ_str:
        by_подр_fl.setdefault(подр_key, 0)
        by_подр_fl[подр_key] += 1
    keys[(conn.XMLСтрока(e.Организация), conn.XMLСтрока(e.Подразделение),
          fl_str)] += 1
    sum_total += float(e.Сумма or 0)
    print(f"  {conn.String(e.ФизическоеЛицо):<40} Σ={e.Сумма:>10.2f} "
          f"Подр={conn.String(e.Подразделение)}")
print(f"\nΣ всех строк = {sum_total:,.2f}")

дубли = {k: c for k, c in keys.items() if c > 1}
print(f"Дубли ключа (Орг,Подр,ФизЛицо): {len(дубли)}")

# Σ ПАП(ОТ) per (Орг,Подр) per Регистратор
print("\n=== Σ ПАП(ОТ) per (Орг,Подр) per Регистратор=&Док ===")
qP = conn.NewObject("Запрос")
qP.Текст = """ВЫБРАТЬ Т.Организация КАК Орг,
    ЕСТЬNULL(Т.Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
              ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК С
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Регистратор=&Д И Т.Источник=
    ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Статья=&ОТ
СГРУППИРОВАТЬ ПО Т.Организация, ЕСТЬNULL(Т.Подразделение,
    ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка))"""
qP.УстановитьПараметр("Д", ДОК); qP.УстановитьПараметр("ОТ", ОТ)
tP = qP.Выполнить().Выгрузить()
pap_map = {}
for i in range(tP.Количество()):
    e = tP.Получить(i)
    pap_map[(conn.XMLСтрока(e.Орг), conn.XMLСтрока(e.Подр))] = float(e.С or 0)
    print(f"  Подр {conn.String(e.Подр)}: ПАП signed = {float(e.С or 0):,.2f}")

# Σ-инвариант: А_ВзСС знак РАСХОД, ПАП(ОТ) знак ПРИХОД (signed +) для выплаты
# В фин-семантике А_ВзСС: Σ Сумма (положительная) = |ПАП(ОТ) signed|
# Так как для ОТ выплата = ВидДв Приход в ПАП = +signed = снижение долга
# А_ВзСС: выплата = Расход = sum положительный (как в БСЛ Σ Сумма)
# Сверка: Σ А_ВзСС per (Орг,Подр) = abs(ПАП signed per Орг,Подр)
print("\n=== Сверка: Σ А_ВзСС per (Орг,Подр) vs |ПАП signed| per (Орг,Подр) ===")
all_pass = True
все_ключи = set(by_подр.keys()) | set(pap_map.keys())
for ключ in все_ключи:
    взс = by_подр.get(ключ, 0)
    пап_signed = pap_map.get(ключ, 0)
    # Для статьи ОТ "выплата зарплаты" в ПАП = ВидДв=Приход = positive signed.
    # В А_ВзСС "выплата" = Расход = positive Σ. Совпадают по модулю и по значению.
    delta = abs(взс - abs(пап_signed))
    status = "✅" if delta <= TOL_RUB else "❌"
    print(f"  {status} {ключ}: А_ВзСС={взс:,.2f}, |ПАП|={abs(пап_signed):,.2f}, |Δ|={delta:.2f}")
    if delta > TOL_RUB:
        all_pass = False

# Доля ФизЛица
print(f"\n=== Доля строк с ФизЛицом ===")
total_rows = sum(by_подр_total.values())
fl_rows = sum(by_подр_fl.values())
доля = (fl_rows / total_rows * 100) if total_rows > 0 else 0
status_fl = "✅" if доля >= 99 else "❌"
print(f"  {status_fl} {fl_rows}/{total_rows} = {доля:.1f}%")
if доля < 99:
    all_pass = False

if дубли:
    all_pass = False
    print(f"\n❌ Дубли: {дубли}")

print("\n" + "=" * 60)
print("[OK] PASS" if all_pass else "[FAIL] есть падения")
sys.exit(0 if all_pass else 1)
