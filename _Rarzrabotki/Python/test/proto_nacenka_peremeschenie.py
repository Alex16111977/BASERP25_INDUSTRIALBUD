def num(v):
    try: return float(str(v).replace('\xa0','').replace(' ','').replace(',','.'))
    except: return None

# --- источник: списание с max Кт-проводок, группы (Номенклатура, СчётКт, НалНазнКт) ---
qm=buh.NewObject("Запрос")
