def test_real(наценка):
    buh.НачатьТранзакцию()
    try:
        d=prmReal.ПолучитьОбъект(); d.Товары.Очистить(); d.СуммаВключаетНДС=False
        for g in groups[:5]:
            ц,с = цена_сумма(g["Сум"], g["Кол"], наценка)
            r=d.Товары.Добавить()
            r.Номенклатура=g["Ном"]; r.СчетУчетаБУ=g["Счет"]; r.Количество=g["Кол"]
            r.Цена=ц; r.Сумма=с; r.ЕдиницаИзмерения=g["Ном"].БазоваяЕдиницаИзмерения; r.Коэффициент=1
            r.СтавкаНДС=Ст20; r.СуммаНДС=round(с*20/100,2); r.НалоговоеНазначение=g["Нал"]
            r.СуммаБезСкидки=с; r.СуммаСкидки=0; r.СхемаРеализации=buh.Справочники.СхемыРеализации.Товары
        d.Записать(режим(d))
        d2=prmReal.ПолучитьОбъект()
        print(f"\n  Реализация наценка={наценка}%:")
        for i,g in enumerate(groups[:5]):
            r=d2.Товары[i]; ц,с=цена_сумма(g["Сум"],g["Кол"],наценка)
            ok = abs(num(r.Сумма)-с)<0.01 and abs(num(r.СуммаБезСкидки)-с)<0.01 and abs(num(r.СуммаНДС)-round(с*20/100,2))<0.01
            print(f"    себест={g['Сум']:.2f} кол={g['Кол']:.3f} → Цена={S(r.Цена)} Сумма={S(r.Сумма)} (ожид {с:.2f}) БезСкид={S(r.СуммаБезСкидки)} НДС={S(r.СуммаНДС)} Схема={S(r.СхемаРеализации)} {'OK' if ok else 'FAIL'}")
    finally:
        buh.ОтменитьТранзакцию()

