Ст20=buh.Перечисления.СтавкиНДС.НДС20
def режим(d): return buh.РежимЗаписиДокумента.ОтменаПроведения if d.Проведен else buh.РежимЗаписиДокумента.Запись

def цена_сумма(себест, кол, наценка):
    if наценка == 0:
        сумма = себест; цена = (себест/кол) if кол else 0
    else:
        цена = round((себест/кол)*(1+наценка/100.0), 2) if кол else 0
        сумма = round(цена*кол, 2)
    return цена, сумма

