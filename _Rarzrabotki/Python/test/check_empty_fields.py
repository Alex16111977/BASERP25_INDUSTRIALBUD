# -*- coding: utf-8 -*-
"""
Діагностика: скільки рядків мають пусті ДоговорКонтрагента / ОбъектРасчетов
та як їх заповнити з РасшифровкаПлатежа документа ДокументПередачи
"""
import win32com.client, pythoncom, pywintypes
from datetime import datetime

pythoncom.CoInitialize()
v8 = win32com.client.Dispatch("V83.COMConnector")
CONN_ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
erp = v8.Connect(CONN_ERP)
print("Connected to ERP\n")

# === 1. Підрахунок пустих полів ===
print("=== 1. Статистика пустих полів в рухах ===")
q = erp.NewObject("Запрос")
q.Текст = (
    "ВЫБРАТЬ "
    "  Д.ФинАгент КАК ФА, "
    "  Д.ДокументПередачи КАК Док, "
    "  Д.НаправлениеДеятельности КАК Напр, "
    "  Д.Подразделение КАК Подр, "
    "  Д.Контрагент КАК Контр, "
    "  Д.ДоговорКонтрагента КАК Договор, "
    "  Д.ОбъектРасчетов КАК ОР, "
    "  Д.Сумма КАК Сумма, "
    "  Д.СуммаКомиссии КАК Комиссия, "
    "  Д.СуммаСКомиссией КАК СКомиссией "
    "ИЗ "
    "  РегистрНакопления.А_ДенежныеСредстваФинАгенты КАК Д "
    "ГДЕ "
    "  Д.Период МЕЖДУ &Начало И &Конец "
    "  И Д.Активность "
    "УПОРЯДОЧИТЬ ПО Д.Сумма УБЫВ"
)
q.УстановитьПараметр("Начало", pywintypes.Time(datetime(2025, 11, 30, 23, 59, 58)))
q.УстановитьПараметр("Конец", pywintypes.Time(datetime(2025, 11, 30, 23, 59, 59)))
res = q.Выполнить()
sel = res.Выбрать()

total = 0
empty_dogovor = 0
empty_or = 0
filled_both = 0
has_doc = 0
no_doc = 0

rows_info = []

while sel.Следующий():
    total += 1
    dok_filled = erp.ЗначениеЗаполнено(sel.Док)
    dog_filled = erp.ЗначениеЗаполнено(sel.Договор)
    or_filled = erp.ЗначениеЗаполнено(sel.ОР)

    if dok_filled:
        has_doc += 1
    else:
        no_doc += 1

    if not dog_filled:
        empty_dogovor += 1
    if not or_filled:
        empty_or += 1
    if dog_filled and or_filled:
        filled_both += 1

    rows_info.append({
        'fa': erp.String(sel.ФА),
        'dok': erp.String(sel.Док) if dok_filled else "<пусто>",
        'dok_filled': dok_filled,
        'dog_filled': dog_filled,
        'or_filled': or_filled,
        'summa': sel.Сумма
    })

print(f"Всього рядків: {total}")
print(f"Заповнений ДокументПередачи: {has_doc}, пустий: {no_doc}")
print(f"Пустий ДоговорКонтрагента: {empty_dogovor}")
print(f"Пустий ОбъектРасчетов: {empty_or}")
print(f"Заповнені обидва: {filled_both}")

# === 2. Перевірка: чи є РасшифровкаПлатежа у документів ДокументПередачи ===
print("\n=== 2. РасшифровкаПлатежа у ДокументПередачи ===")

# Зберемо унікальні ДокументПередачи
unique_docs = set()
for r in rows_info:
    if r['dok_filled'] and not r['dog_filled']:
        unique_docs.add(r['dok'])

print(f"Унікальних ДокПередачи з пустим Договором: {len(unique_docs)}")

# Перевіримо перші 5 документів — чи є у них РасшифровкаПлатежа
q2 = erp.NewObject("Запрос")
q2.Текст = (
    "ВЫБРАТЬ ПЕРВЫЕ 20 "
    "  Д.ФинАгент КАК ФА, "
    "  Д.ДокументПередачи КАК Док "
    "ИЗ "
    "  РегистрНакопления.А_ДенежныеСредстваФинАгенты КАК Д "
    "ГДЕ "
    "  Д.Период МЕЖДУ &Начало И &Конец "
    "  И Д.Активность "
    "  И Д.ДоговорКонтрагента = ЗНАЧЕНИЕ(Справочник.ДоговорыКонтрагентов.ПустаяСсылка) "
    "  И Д.ДокументПередачи <> ЗНАЧЕНИЕ(Документ.СписаниеБезналичныхДенежныхСредств.ПустаяСсылка)"
)
q2.УстановитьПараметр("Начало", pywintypes.Time(datetime(2025, 11, 30, 23, 59, 58)))
q2.УстановитьПараметр("Конец", pywintypes.Time(datetime(2025, 11, 30, 23, 59, 59)))

res2 = q2.Выполнить()
sel2 = res2.Выбрать()
cnt = 0
while sel2.Следующий():
    cnt += 1
    dok_ref = sel2.Док
    fa_str = erp.String(sel2.ФА)
    dok_str = erp.String(dok_ref)

    # Перевіримо РасшифровкаПлатежа
    try:
        rp = dok_ref.РасшифровкаПлатежа
        rp_count = rp.Количество()
        print(f"\n  {cnt}. ФА={fa_str}, Док={dok_str}")
        print(f"     РасшифровкаПлатежа рядків: {rp_count}")

        for j in range(min(rp_count, 3)):
            row = rp.Получить(j)
            or_val = row.ОбъектРасчетов
            or_filled = erp.ЗначениеЗаполнено(or_val)
            if or_filled:
                dog = or_val.Договор
                dog_filled = erp.ЗначениеЗаполнено(dog)
                print(f"     РП[{j}]: Сумма={row.Сумма}, ОбъектРасчетов={erp.String(or_val)}, "
                      f"Договор={'заполнен: '+erp.String(dog) if dog_filled else '<пусто>'}")
            else:
                print(f"     РП[{j}]: Сумма={row.Сумма}, ОбъектРасчетов=<пусто>")
    except Exception as e:
        print(f"  {cnt}. ФА={fa_str}, Док={dok_str}, ОШИБКА: {e}")

    if cnt >= 10:
        print(f"\n  ... показано перші 10")
        break

# === 3. Перевіримо також рядки з заповненими ДоговорКонтрагента ===
