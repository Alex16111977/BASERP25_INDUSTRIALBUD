# Реальний запит з JOIN ИсполнительныйЛист.Получатель
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="localhost";Ref="zup";Usr="cfo";Pwd="2442"')
S = zup.String

def com_date(y, m, d):
    return pywintypes.Time(datetime.datetime(y, m, d))

print("=" * 80)
print("КРОК A: Удержания де ДокументОснование заповнено (виконавчі листи)")
print("=" * 80)
try:
    q = zup.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ
        У.Сотрудник.Наименование КАК СотрудникФИО,
        У.Сотрудник.Физлицо.КодПоДРФО КАК СотрудникИНН,
        У.ВидРасчета.Наименование КАК ВидРасчета,
        У.Результат КАК Сумма,
        У.ДокументОснование КАК ДокОснование,
        У.ДокументОснование.Номер КАК НомерИЛ,
        У.ДокументОснование.Дата КАК ДатаИЛ,
        У.ДокументОснование.ВидИсполнительногоДокумента КАК ВидИД,
        У.ДокументОснование.Получатель КАК Получатель,
        У.ДокументОснование.Получатель.Наименование КАК ИмяПолуч,
        У.ДокументОснование.Получатель.КодПоЕДРПОУ КАК ЕДРПОУПолуч,
        У.ДокументОснование.Получатель.ИНН КАК ИННПолуч,
        У.Организация.КодПоЕДРПОУ КАК ЕДРПОУОрг
    ИЗ РегистрРасчета.УдержанияРаботниковОрганизаций КАК У
    ГДЕ У.ПериодРегистрации МЕЖДУ &Н И &К
        И У.Результат <> 0
        И У.ДокументОснование <> ЗНАЧЕНИЕ(Документ.ИсполнительныйЛист.ПустаяСсылка)
    """
    q.SetParameter("Н", com_date(2025, 12, 1))
    q.SetParameter("К", com_date(2025, 12, 31))
    r = q.Execute().Выгрузить()
    print(f"  Знайдено рядків: {r.Количество()}")
    for i in range(min(r.Количество(), 10)):
        row = r.Получить(i)
        print(f"\n  [{i+1}] {S(row.СотрудникФИО)} (ІНН={S(row.СотрудникИНН)})")
        print(f"      {S(row.ВидРасчета)}: сума {S(row.Сумма)} грн")
        print(f"      ИЛ: №{S(row.НомерИЛ)} від {S(row.ДатаИЛ)} [{S(row.ВидИД)}]")
        print(f"      Получатель: {S(row.ИмяПолуч)}")
        print(f"          ЄДРПОУ={S(row.ЕДРПОУПолуч)}, ІНН={S(row.ИННПолуч)}")
        print(f"      Орг ЄДРПОУ: {S(row.ЕДРПОУОрг)}")
except Exception as e:
    print(f"  ПОМИЛКА: {str(e)[:500]}")

