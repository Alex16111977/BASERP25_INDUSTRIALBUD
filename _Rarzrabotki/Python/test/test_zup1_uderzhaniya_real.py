    if r.Количество() > 0:
        print(f"\n  Колонки: {[S(r.Колонки.Получить(i).Имя) for i in range(r.Колонки.Количество())]}")
        print(f"\n  Перший рядок:")
        row = r.Получить(0)
        for i in range(r.Колонки.Количество()):
            col_name = S(r.Колонки.Получить(i).Имя)
            val = getattr(row, col_name)
            print(f"    {col_name}: {S(val)[:100]}")
