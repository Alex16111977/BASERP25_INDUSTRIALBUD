# -*- coding: utf-8 -*-
"""Runtime-верификация А_ОтчетPL (вид как в Excel) на BaseERPRazr:
1) ПолучитьОбъединенныеДанные(..., ПоказИтогиПрибыли=Истина): колонки, водопад, база %
2) СкомпоноватьРезультат с вариантом А_ОтчетPL_ВидКакВExcel по Глобино-2
"""
import win32com.client, sys, datetime
from collections import defaultdict
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERPRazr";Usr="Администратор";Pwd="24043"')
S = erp.String

# 0. Есть ли данные июня в Razr
q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ Документ.А_ОтчетPL
ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2026,6,1) И ДАТАВРЕМЯ(2026,6,30,23,59,59) И НЕ ПометкаУдаления"""
docs = q.Execute().Выгрузить().Получить(0).К
print(f"Документов А_ОтчетPL июня в Razr: {docs}")

# 1. Прямой вызов функции модуля отчёта
otchet = erp.Отчеты.А_ОтчетPL.Создать()
t = otchet.ПолучитьОбъединенныеДанные(
    datetime.datetime(2026, 6, 1), datetime.datetime(2026, 6, 30, 23, 59, 59),
    False,   # ВключатьДочерние
    False,   # ПоказPL
    True,    # ПоказЕРП
    False,   # ПоказКазна
    True)    # ПоказИтогиПрибыли
cols = [t.Колонки.Получить(i).Имя for i in range(t.Колонки.Количество())]
need = ["ВидСтроки", "СортСтроки", "ПоказательПрибыли", "БазаПроцента"]
print("Новые колонки:", {c: c in cols for c in need})

# Найти Глобино-2
qг = erp.NewObject("Запрос")
qг.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтруктураПредприятия ГДЕ Наименование = "Глобино-2" И НЕ ПометкаУдаления"""
tг = qг.Execute().Выгрузить()
глобино = tг.Получить(0).Ссылка if tг.Количество() else None
print("Глобино-2:", S(глобино) if глобино else "НЕ НАЙДЕНО")

# Независимый пересчёт водопада по строкам "Статья" этой же выгрузки
qk = erp.NewObject("Запрос")
qk.Text = """ВЫБРАТЬ Ссылка, Код ИЗ Справочник.А_ГруппаСтатей_PL
;
ВЫБРАТЬ Ссылка, Код ИЗ Справочник.А_Статьи_PL ГДЕ Код В ("000000055","000000056","000000057","000000058")"""
pak = qk.ВыполнитьПакет()
гр_код, ст_код = {}, {}
tt = pak.Получить(0).Выгрузить()
for i in range(tt.Количество()):
    r = tt.Получить(i)
    гр_код[S(r.Ссылка)] = S(r.Код)
tt = pak.Получить(1).Выгрузить()
for i in range(tt.Количество()):
    r = tt.Получить(i)
    ст_код[S(r.Ссылка)] = S(r.Код)

acc = defaultdict(float)
itog_rows = []
base_seen = set()
for i in range(t.Количество()):
    r = t.Получить(i)
    if S(r.Подразделение) != "Глобино-2":
        continue
    if S(r.ВидСтроки) == "ИтогПрибыли":
        itog_rows.append((int(r.СортСтроки), S(r.ПоказательПрибыли), float(r.СуммаЕРП)))
        continue
    base_seen.add(round(float(r.БазаПроцента), 2))
    s = float(r.СуммаЕРП)
    if s == 0:
        continue
    кс = ст_код.get(S(r.СтатьяPL))
    кг = гр_код.get(S(r.Группа))
    if кс:
        acc["ст" + кс] += s
    elif кг:
        acc["гр" + кг] += s

ОД = acc["гр000000006"]; СС = acc["гр000000001"]; ДР = acc["гр000000007"]
ОПЗ = acc["гр000000003"]; МЗ = acc["гр000000005"]; АЗ = acc["гр000000002"]; НС = acc["гр000000008"]
ФД_дох = acc["ст000000055"]; ФД_расх = acc["ст000000056"]
налог = acc["ст000000057"]; див = acc["ст000000058"]

марж = ОД - СС
опер = марж - ОПЗ - МЗ - АЗ
после = опер + ФД_дох - ФД_расх
до_нал = после - ДР
чист = до_нал - НС - налог
расп = чист - див
ожид = {
    10: марж, 20: (марж / ОД if ОД else 0), 30: опер, 40: (опер / ОД if ОД else 0),
    50: после, 60: до_нал, 70: чист, 80: расп, 90: (расп / ОД if ОД else 0),
}
ожид_база = СС + ДР + ОПЗ + МЗ + АЗ + НС + ФД_расх + налог + див
print(f"\nГлобино-2 факт: ОД={ОД:,.2f} СС={СС:,.2f} ОПЗ={ОПЗ:,.2f} АЗ={АЗ:,.2f} "
      f"ФДдох={ФД_дох:,.2f} ФДрасх={ФД_расх:,.2f} НС={НС:,.2f} ДР={ДР:,.2f}")
print(f"База %: в строках={sorted(base_seen)} ожидание={ожид_база:,.2f}")

print(f"\nБлок прибыли ({len(itog_rows)} строк):")
for порядок, имя, знач in sorted(itog_rows):
    exp = ожид[порядок]
    ok = "OK " if abs(знач - exp) <= 0.011 else "FAIL"
    print(f"  [{ok}] {порядок:2d} {имя}: {знач:,.4f} (ожид {exp:,.4f})")

# 2. Компоновка варианта А_ОтчетPL_ВидКакВExcel
print("\n=== Компоновка варианта ===")
схема = otchet.СхемаКомпоновкиДанных
вариант = None
for i in range(схема.ВариантыНастроек.Количество()):
    v = схема.ВариантыНастроек.Получить(i)
    if v.Имя == "А_ОтчетPL_ВидКакВExcel":
        вариант = v
print("Вариант найден:", вариант is not None)
otchet.КомпоновщикНастроек.ЗагрузитьНастройки(вариант.Настройки)

настройки = otchet.КомпоновщикНастроек.Настройки
# период июнь-2026
период = erp.NewObject("СтандартныйПериод")
период.ДатаНачала = datetime.datetime(2026, 6, 1)
период.ДатаОкончания = datetime.datetime(2026, 6, 30, 23, 59, 59)
настройки.ПараметрыДанных.УстановитьЗначениеПараметра("Период", период)
# отбор Подразделение = Глобино-2
отбор = настройки.Отбор.Элементы.Получить(0)
отбор.ПравоеЗначение = глобино
отбор.Использование = True

табдок = erp.NewObject("ТабличныйДокумент")
otchet.СкомпоноватьРезультат(табдок, None)
h, w = табдок.ВысотаТаблицы, табдок.ШиринаТаблицы
print(f"ТабДок: {h} x {w}")
for r in range(1, min(h, 120) + 1):
    row = []
    for c in range(1, min(w, 10) + 1):
        txt = табдок.Область(r, c, r, c).Текст
        if txt:
            row.append(txt)
    if row:
        print(f"r{r:3d}: " + " | ".join(row))
