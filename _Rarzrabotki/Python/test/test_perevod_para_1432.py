# -*- coding: utf-8 -*-
"""
Исследование схемы перевода между своими счетами на живом примере 1432:
1) каким реквизитом ERP-Поступление ссылается на ERP-Списание;
2) UUID ERP-Списания == UUID BuhBud-документа «Списання з банківського рахунку»;
3) движения BuhBud-документа по счетам 311 (Дт-приёмник / Кт-источник).
"""
import sys

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')

# --- 1. ERP: Поступление 00DL-008305 и его ссылки на Списание ---
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	П.Ссылка КАК Ссылка,
	П.ХозяйственнаяОперация КАК ХозОперация,
	П.ДокументВыдачи КАК ДокументВыдачи,
	П.ДокументОснование КАК ДокументОснование,
	П.А_СписаниеБезналичныхДенежныхСредств КАК А_Списание,
	П.СуммаДокумента КАК Сумма
ИЗ
	Документ.ПоступлениеБезналичныхДенежныхСредств КАК П
ГДЕ
	П.Номер = &Номер
	И П.Дата МЕЖДУ &Д1 И &Д2
"""
q.SetParameter("Номер", "00DL-008305")
from datetime import datetime
q.SetParameter("Д1", datetime(2026, 1, 30, 0, 0, 0))
q.SetParameter("Д2", datetime(2026, 1, 30, 23, 59, 59))
r = q.Execute().Выгрузить()
assert r.Количество() == 1, f"Поступлений найдено {r.Количество()}"
row = r.Получить(0)
print(f"Поступление: {erp.String(row.Ссылка)}")
print(f"  ХозОперация       = {erp.XMLСтрока(row.ХозОперация)}")
print(f"  ДокументВыдачи    = {erp.String(row.ДокументВыдачи)} (заполнен: {erp.ЗначениеЗаполнено(row.ДокументВыдачи)})")
print(f"  ДокументОснование = {erp.String(row.ДокументОснование)} (заполнен: {erp.ЗначениеЗаполнено(row.ДокументОснование)})")
print(f"  А_Списание        = {erp.String(row.А_Списание)} (заполнен: {erp.ЗначениеЗаполнено(row.А_Списание)})")
print(f"  Сумма             = {row.Сумма}")

# UUID Списания (через заполненный из реквизитов)
spis = None
for cand in (row.ДокументВыдачи, row.ДокументОснование, row.А_Списание):
    if erp.ЗначениеЗаполнено(cand):
        spis = cand
        break
assert spis is not None, "ни один реквизит-ссылка не заполнен!"
uid_spis = str(erp.String(spis.УникальныйИдентификатор())).strip().upper()
print(f"UUID Списания ERP = {uid_spis}")

# --- 2. BuhBud: документ по этому UUID ---
ref_buh = buh.Документы.СписаниеСРасчетногоСчета.ПолучитьСсылку(
    buh.NewObject("УникальныйИдентификатор", uid_spis))
obj_buh = ref_buh.ПолучитьОбъект()
print(f"BuhBud СписаниеСРасчетногоСчета по UUID: {'НАЙДЕН: ' + str(buh.String(ref_buh)) if obj_buh is not None else 'НЕ НАЙДЕН'}")

# --- 3. BuhBud: движения документа по Хозрасчетный (счета/субконто) ---
if obj_buh is not None:
    qb = buh.NewObject("Запрос")
    qb.Text = """
    ВЫБРАТЬ
    	Д.СчетДт.Код КАК СчетДт,
    	ПРЕДСТАВЛЕНИЕ(Д.СубконтоДт1) КАК СубконтоДт1,
    	Д.СчетКт.Код КАК СчетКт,
    	ПРЕДСТАВЛЕНИЕ(Д.СубконтоКт1) КАК СубконтоКт1,
    	Д.Сумма КАК Сумма
    ИЗ
    	РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(, , Регистратор = &Рег, , ) КАК Д
    """
    qb.SetParameter("Рег", ref_buh)
    rb = qb.Execute().Выгрузить()
    for i in range(rb.Количество()):
        s = rb.Получить(i)
        print(f"  Дт {buh.String(s.СчетДт)} [{buh.String(s.СубконтоДт1)}] / "
              f"Кт {buh.String(s.СчетКт)} [{buh.String(s.СубконтоКт1)}] = {s.Сумма}")

print("OK")
