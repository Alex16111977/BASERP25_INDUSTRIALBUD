# -*- coding: utf-8 -*-
"""
На каких счетах проводится doc ІБ00-007653
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONNECTION_STRING = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
DATE_FROM = datetime(2025, 12, 1)
DATE_TO = datetime(2025, 12, 31, 23, 59, 59)

def make_time(dt):
    return pywintypes.Time(dt)

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected")

    # 1. Raw таблица: какие счета у doc 007653
    print("\n=== Счета документа 007653 (raw table) ===")
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ\n"
        "  Д.СчетДт.Код КАК СчетДтКод,\n"
        "  Д.СчетДт.Наименование КАК СчетДтНаим,\n"
        "  Д.СчетДт.ИмяПредопределенныхДанных КАК СчетДтПредопр,\n"
        "  Д.СчетКт.Код КАК СчетКтКод,\n"
        "  Д.Сумма,\n"
        "  Д.КоличествоДт,\n"
        "  Д.КоличествоКт\n"
        "ИЗ\n"
        "  РегистрБухгалтерии.Хозрасчетный КАК Д\n"
        "ГДЕ\n"
        "  ПРЕДСТАВЛЕНИЕ(Д.Регистратор) ПОДОБНО \"%007653%\"\n"
        "  И Д.Период МЕЖДУ &Н И &К"
    )
    q.УстановитьПараметр("Н", make_time(DATE_FROM))
    q.УстановитьПараметр("К", make_time(DATE_TO))
    r = q.Выполнить().Выбрать()
    accounts = set()
    while r.Следующий():
        code = str(r.СчетДтКод).strip()
        name = str(r.СчетДтНаим)[:30]
        predopred = str(r.СчетДтПредопр)
        accounts.add(code)
        print(f"  Дт:{code} ({name}) [Предопр={predopred}]  Кт:{r.СчетКтКод}  Сумма={r.Сумма}  КолДт={r.КоличествоДт}")

    print(f"\n  Уникальные счета Дт: {accounts}")

    # 2. Проверить: есть ли эти счета в ИЕРАРХИИ "Товары"
    print("\n=== Счёт 281 в ИЕРАРХИИ Товары? ===")
    q2 = conn.NewObject("Запрос")
    q2.Текст = (
        "ВЫБРАТЬ\n"
        "  Х.Код, Х.Наименование, Х.ИмяПредопределенныхДанных\n"
        "ИЗ\n"
        "  ПланСчетов.Хозрасчетный КАК Х\n"
        "ГДЕ\n"
        "  Х.Ссылка В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.Товары))\n"
        "  И Х.Код ПОДОБНО \"28%\""
    )
    r2 = q2.Выполнить().Выбрать()
    while r2.Следующий():
        print(f"  {r2.Код} {r2.Наименование} [Предопр={r2.ИмяПредопределенныхДанных}]")

    # 3. Проверить ДвиженияССубконто для doc 007653
    print("\n=== ДвиженияССубконто для 007653 ===")
    q3 = conn.NewObject("Запрос")
    q3.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 5\n"
        "  Д.СчетДт.Код КАК СчетДтКод,\n"
        "  Д.СчетКт.Код КАК СчетКтКод,\n"
        "  Д.Сумма, Д.КоличествоДт, Д.КоличествоКт,\n"
        "  Д.СубконтоДт1, Д.СубконтоДт2, Д.СубконтоДт3\n"
        "ИЗ\n"
        "  РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(&Н, &К, , , ) КАК Д\n"
        "ГДЕ\n"
        "  ПРЕДСТАВЛЕНИЕ(Д.Регистратор) ПОДОБНО \"%007653%\""
    )
    q3.УстановитьПараметр("Н", make_time(DATE_FROM))
    q3.УстановитьПараметр("К", make_time(DATE_TO))
    try:
        r3 = q3.Выполнить().Выбрать()
        count = 0
        while r3.Следующий():
            count += 1
            print(f"  [{count}] Дт:{r3.СчетДтКод} Кт:{r3.СчетКтКод}  Сумма={r3.Сумма} КолДт={r3.КоличествоДт}")
            print(f"         СубДт1={r3.СубконтоДт1} СубДт2={r3.СубконтоДт2}")
        print(f"  Всего: {count}")
    except Exception as e:
        print(f"  ОШИБКА: {str(e)[:200]}")

    conn = None
    pythoncom.CoUninitialize()
    print("\n[OK] Done")

if __name__ == "__main__":
    main()
