# -*- coding: utf-8 -*-
"""Обратная загрузка параметров договоров из TSV в базу.

Читает «Данные по Производсту для заливки в базу Бухгалтерия.txt» и пишет параметры
в РегистрСведений.А_ПараметрыДоговоровФинотчета (с 14.08.2026 параметры живут в регистре,
реквизиты А_* из справочника удалены). Ключ — UUID договора (колонка 1), наименования
игнорируются.

Пустые значения НЕ затирают заполненное в базе: сумма 0 и пустой вариант означают
«не задано», а не «обнулить». Чтобы обнулить осознанно — впишите слово ОЧИСТИТЬ.

Запуск:
    python doc_finrep_load_dogovorov.py          — показать, что изменится (dry-run)
    python doc_finrep_load_dogovorov.py --apply  — записать
"""
import io
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
ПРИМЕНЯТЬ = "--apply" in sys.argv

ФАЙЛ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\notebook"
        r"\knowledge_А_ФинансовыйОтчетПроизводства"
        r"\Данные по Производсту для заливки в базу Бухгалтерия.txt")

ВАРИАНТЫ = ("ЗадолженностьПлюсАкты", "ВыполнениеМинусОплата", "ТолькоРучной", "ЗачетПредоплаты")
ПРАВИЛА_НДС = ("ОтАктов", "НеУчитывать", "ОтЗадолженности")
ОЧИСТИТЬ = "ОЧИСТИТЬ"

buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
РЕГИСТР = buh.РегистрыСведений.А_ПараметрыДоговоровФинотчета


def число(текст):
    т = (текст or "").strip().replace(" ", "").replace("\xa0", "").replace(",", ".")
    if not т or т.upper() == ОЧИСТИТЬ:
        return None
    try:
        return float(т)
    except ValueError:
        return None


def дата_1с(текст):
    """dd.mm.yyyy → дата 1С (полдень, щоб COM −3 год не зсунув день); порожньо — None."""
    т = (текст or "").strip()
    if not т or т.upper() == ОЧИСТИТЬ:
        return None
    д, м, г = т.split(".")
    q = buh.NewObject("Запрос")
    q.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({int(г)},{int(м)},{int(д)},12,0,0) КАК Д"
    return q.Execute().Выгрузить().Получить(0).Д


def текущие_параметры(ссылка):
    """Читает запись регистра по договору; None если записи нет."""
    мз = РЕГИСТР.СоздатьМенеджерЗаписи()
    мз.Договор = ссылка
    мз.Прочитать()
    if not мз.Выбран():
        return None
    return {"Сумма": float(мз.СуммаСоглашения or 0), "СуммаДЦ": float(мз.СуммаДЦ or 0),
            "Процент": float(мз.ПроцентГарантийногоУдержания or 0),
            "Вариант": мз.ВариантФормулыИтога,
            "ВариантИмя": str(buh.string(мз.ВариантФормулыИтога)),
            "Примечание": str(buh.string(мз.ОбъектПримечание)),
            "Предоплата": float(мз.СуммаПредоплаты or 0),
            "ДатаЗачета": str(buh.string(мз.ДатаЗачетаПредоплаты))[:10],
            "Остаток": float(мз.ОстатокПредоплатыНаДату or 0),
            "ПравилоНДС": str(buh.string(мз.ПравилоНДС)),
            "Удержание": float(мз.СуммаГарантийногоУдержания or 0)}


строки = []
for номер, сырая in enumerate(io.open(ФАЙЛ, encoding='utf-8'), 1):
    сырая = сырая.rstrip("\n")
    if not сырая.strip() or сырая.startswith("#"):
        continue
    части = сырая.split("\t")
    if части[0].strip() == "UUID":
        continue
    if len(части) not in (9, 14):
        print(f"  ⚠ рядок {номер}: колонок {len(части)}, очікували 9 або 14 — пропущено")
        continue
    части += [""] * (14 - len(части))
    строки.append({"номер": номер, "УИД": части[0].strip(), "Подр": части[1], "Договор": части[3],
                   "Сумма": число(части[4]), "СуммаДЦ": число(части[5]),
                   "Процент": число(части[6]), "Вариант": части[7].strip(),
                   "Примечание": части[8].strip(),
                   "ОчиститьСумму": части[4].strip().upper() == ОЧИСТИТЬ,
                   "ОчиститьВариант": части[7].strip().upper() == ОЧИСТИТЬ,
                   "Предоплата": число(части[9]), "ДатаЗачета": части[10].strip(),
                   "Остаток": число(части[11]), "ПравилоНДС": части[12].strip(),
                   "Удержание": число(части[13])})

print(f"Прочитано рядків даних: {len(строки)}")

изменения, ошибки = [], []
for с in строки:
    if с["Вариант"] and с["Вариант"].upper() != ОЧИСТИТЬ and с["Вариант"] not in ВАРИАНТЫ:
        ошибки.append(f"рядок {с['номер']}: невідомий варіант «{с['Вариант']}» "
                      f"(дозволено: {', '.join(ВАРИАНТЫ)})")
        continue
    if с["ПравилоНДС"] and с["ПравилоНДС"] not in ПРАВИЛА_НДС:
        ошибки.append(f"рядок {с['номер']}: невідоме правило ПДВ «{с['ПравилоНДС']}» "
                      f"(дозволено: {', '.join(ПРАВИЛА_НДС)} або порожньо)")
        continue
    if с["Процент"] is not None and not (0 <= с["Процент"] <= 100):
        ошибки.append(f"рядок {с['номер']}: відсоток {с['Процент']} поза межами 0..100")
        continue
    try:
        уид = buh.NewObject("УникальныйИдентификатор", с["УИД"])
        ссылка = buh.Справочники.ДоговорыКонтрагентов.ПолучитьСсылку(уид)
        объект = ссылка.ПолучитьОбъект()
    except Exception as e:
        ошибки.append(f"рядок {с['номер']}: UUID не розібрано — {e}")
        continue
    if объект is None:
        ошибки.append(f"рядок {с['номер']}: договір за UUID не знайдено ({с['Договор'][:40]})")
        continue

    тек = текущие_параметры(ссылка) or {"Сумма": 0.0, "СуммаДЦ": 0.0, "Процент": 0.0,
                                        "Вариант": "", "ВариантИмя": "",
                                        "Примечание": "", "Предоплата": 0.0, "ДатаЗачета": "",
                                        "Остаток": 0.0, "ПравилоНДС": "", "Удержание": 0.0}
    что = []
    if с["ОчиститьСумму"]:
        что.append(("Сумма", 0))
    elif с["Сумма"] is not None and с["Сумма"] != 0 and тек["Сумма"] != с["Сумма"]:
        что.append(("Сумма", с["Сумма"]))
    if с["СуммаДЦ"] is not None and с["СуммаДЦ"] != 0 and тек["СуммаДЦ"] != с["СуммаДЦ"]:
        что.append(("СуммаДЦ", с["СуммаДЦ"]))
    if с["Процент"] is not None and тек["Процент"] != с["Процент"]:
        что.append(("Процент", с["Процент"]))
    if с["ОчиститьВариант"]:
        что.append(("Вариант", ""))
    elif с["Вариант"] and тек["ВариантИмя"] != с["Вариант"]:
        что.append(("Вариант", с["Вариант"]))
    if с["Примечание"] and тек["Примечание"] != с["Примечание"][:200]:
        что.append(("Примечание", с["Примечание"][:200]))

    if с["Предоплата"] is not None and тек["Предоплата"] != с["Предоплата"]:
        что.append(("Предоплата", с["Предоплата"]))
    if с["ДатаЗачета"] and тек["ДатаЗачета"] != с["ДатаЗачета"]:
        что.append(("ДатаЗачета", с["ДатаЗачета"]))
    if с["Остаток"] is not None and тек["Остаток"] != с["Остаток"]:
        что.append(("Остаток", с["Остаток"]))
    if с["ПравилоНДС"] and тек["ПравилоНДС"] != с["ПравилоНДС"]:
        что.append(("ПравилоНДС", с["ПравилоНДС"]))
    if с["Удержание"] is not None and тек["Удержание"] != с["Удержание"]:
        что.append(("Удержание", с["Удержание"]))

    if что:
        изменения.append((с, ссылка, тек, dict(что)))

print(f"Договорів до зміни: {len(изменения)}")
if ошибки:
    print(f"\n--- ПОМИЛКИ ({len(ошибки)}), рядки пропущено ---")
    for о in ошибки:
        print("  " + о)

if изменения:
    print("\n--- ЩО ЗМІНИТЬСЯ ---")
    for с, _, _, что in изменения:
        поля = ", ".join(f"{имя}={знач}" for имя, знач in что.items())
        print(f"  {с['Подр'][:16]:16} | {с['Договор'][:38]:38} | {поля[:70]}")

if not ПРИМЕНЯТЬ:
    print("\n>>> DRY-RUN. Нічого не записано. Для запису: --apply")
    sys.exit(1 if ошибки else 0)

записано = 0
for с, ссылка, тек, что in изменения:
    итог = dict(тек)
    итог.update(что)
    мз = РЕГИСТР.СоздатьМенеджерЗаписи()
    мз.Договор = ссылка
    мз.Прочитать()  # 28.09.2026: писати лише змінене, решту ресурсів зберегти
    мз.Договор = ссылка
    мз.СуммаСоглашения = итог["Сумма"]
    мз.СуммаДЦ = итог["СуммаДЦ"]
    мз.ПроцентГарантийногоУдержания = итог["Процент"]
    мз.ВариантФормулыИтога = итог["Вариант"]
    мз.ОбъектПримечание = итог["Примечание"]
    if "Предоплата" in что:
        мз.СуммаПредоплаты = что["Предоплата"]
    if "ДатаЗачета" in что:
        мз.ДатаЗачетаПредоплаты = дата_1с(что["ДатаЗачета"])
    if "Остаток" in что:
        мз.ОстатокПредоплатыНаДату = что["Остаток"]
    if "ПравилоНДС" in что:
        мз.ПравилоНДС = что["ПравилоНДС"]
    if "Удержание" in что:
        мз.СуммаГарантийногоУдержания = что["Удержание"]
    мз.Записать(True)
    записано += 1
print(f"\nЗаписано договорів: {записано}")
sys.exit(1 if ошибки else 0)
