# -*- coding: utf-8 -*-
"""Приёмка внешнего отчёта А_ОтчетПоСтатьямPL_ДДС_СтатьямРасходам (.erf) на BaseERP.

Смысл отчёта (финансист): статья денег (ДДС) и статья затрат должны соответствовать 1:1.
Область — только статьи денег/затрат, выбранные в справочник А_Статьи_PL. Связи берутся из
справочников в обе стороны (ДДС.А_СтатьяРасходов и СтатьяЗатрат.А_СтатьяДвиженияДенежныхСредств).
Красным — связь 1:N, оранжевым — факт затрат уйдёт в другую PL, чем деньги, жёлтым — нет связи.

Полный путь пользователя через COM: ВнешниеОтчеты.Создать → каждый вариант → СформироватьОтчет →
разбор ТабличногоДокумента (текст и цвет фона ячеек по имени web-цвета).
Число проверок — константа 13, ни одна не стоит под if.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\А_ОтчетПоСтатьямPL_ДДС_СтатьямРасходам.erf"
RED, ORANGE, KHAKI, PINK = "LightCoral", "Orange", "Khaki", "MistyRose"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ПРОВЕРОК = 0
ПРОВАЛОВ = 0


def проверка(name, cond, extra=""):
    global ПРОВЕРОК, ПРОВАЛОВ
    ПРОВЕРОК += 1
    if cond:
        print(f"  [OK]   {name}")
    else:
        ПРОВАЛОВ += 1
        print(f"  [FAIL] {name} {extra}")


def query(text):
    q = erp.NewObject("Запрос")
    q.Text = text
    return q.Execute().Выгрузить()


def color(area):
    try:
        return S(area.ЦветФона)
    except Exception:
        return ""


def scan(doc):
    cells = []
    h, w = int(doc.ВысотаТаблицы), int(doc.ШиринаТаблицы)
    for r in range(1, h + 1):
        for c in range(1, w + 1):
            обл = doc.Область(r, c, r, c)
            t = str(обл.Текст).strip()
            if t:
                cells.append((r, c, t, color(обл)))
    return cells, h, w


def compose(отч, схема, вариант):
    отч.КомпоновщикНастроек.Инициализировать(
        erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    отч.КомпоновщикНастроек.ЗагрузитьНастройки(вариант.Настройки)
    док = erp.NewObject("ТабличныйДокумент")
    отч.СформироватьОтчет(док, erp.NewObject("ДанныеРасшифровкиКомпоновкиДанных"))
    return док


# ------------------------------------------------------------ эталон из базы (независимый расчёт)
r = query("""
ВЫБРАТЬ РАЗЛИЧНЫЕ ТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС, ТЧ.Ссылка КАК PL,
    ТЧ.СтатьяДвиженияДенежныхСредств.А_СтатьяРасходов КАК СР,
    ТЧ.СтатьяДвиженияДенежныхСредств.А_СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств КАК ДДСФакта
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления И НЕ ТЧ.Ссылка.ЭтоГруппа
""")
def nm(v):
    """Имя ссылки или "" для NULL/пустой ссылки (NULL из запроса приходит как None)."""
    if v is None:
        return ""
    try:
        if v.Пустая():
            return ""
    except Exception:
        pass
    return S(v)


rows = []
for i in range(r.Количество()):
    x = r.Получить(i)
    rows.append((S(x.ДДС), S(x.PL), nm(x.СР), nm(x.ДДСФакта)))
dds_pl = {d: pl for d, pl, _, _ in rows}
sr_dds = {}
for d, pl, sr, ddsf in rows:
    if sr:
        sr_dds.setdefault(sr, set()).add(d)
        if ddsf and ddsf in dds_pl:
            sr_dds[sr].add(ddsf)
топ = max(sr_dds.items(), key=lambda kv: len(kv[1]))
топ_имя, топ_ддс = топ[0], len(топ[1])
# число строк отчёта у топ-статьи затрат = число её ДДС в PL (каждая пара — строка)
кандидат_орандж = next(((d, pl, sr, ddsf) for d, pl, sr, ddsf in rows
                        if sr and ddsf and ddsf in dds_pl and dds_pl[ddsf] != pl), None)
многоЗатрат = {}
for d, pl, sr, ddsf in rows:
    if sr:
        многоЗатрат.setdefault(d, set()).add(sr)
for d, pl, sr, ddsf in rows:
    if sr and ddsf and ddsf in dds_pl:
        многоЗатрат.setdefault(ddsf, set()).add(sr)
ддс_1N = next((d for d, s in многоЗатрат.items() if len(s) >= 2), None)
чистая = next((sr for sr, s in sr_dds.items() if len(s) == 1 and all(dds_pl.get(x) for x in s)), None)
print(f"Эталон: топ статья затрат «{топ_имя}» ↔ {топ_ддс} статей денег; статья денег с 2+ затрат: «{ддс_1N}»; "
      f"пример «факт в другой PL»: {кандидат_орандж}; чистая статья затрат: «{чистая}»")

# ------------------------------------------------------------ отчёт
print("\n=== ОТЧЁТ ===")
отч = None
try:
    отч = erp.ВнешниеОтчеты.Создать(ERF, False)
except Exception as e:
    print("   ошибка загрузки:", e)
проверка("1. .erf загружается (модуль компилируется)", отч is not None, ERF)
схема = отч.СхемаКомпоновкиДанных if отч else None
варианты = схема.ВариантыНастроек if схема else None
n_var = int(варианты.Количество()) if варианты else 0
проверка("2. В схеме 3 варианта настроек", n_var == 3, f"вариантов={n_var}")
проверка("3. Основная форма — типовая ОбщаяФорма.ФормаОтчета",
         отч is not None and S(отч.Метаданные().ОсновнаяФорма.ПолноеИмя()) == "ОбщаяФорма.ФормаОтчета")

результаты = {}
for i in range(n_var):
    вар = варианты.Получить(i)
    имя = S(вар.Имя)
    try:
        док = compose(отч, схема, вар)
        cells, h, w = scan(док)
        результаты[имя] = (cells, h, w, "")
        print(f"   вариант «{имя}»: {h} строк × {w} колонок, непустых ячеек {len(cells)}")
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        результаты[имя] = ([], 0, 0, msg)
        print(f"   вариант «{имя}»: ОШИБКА {msg[:400]}")


def res(имя):
    return результаты.get(имя, ([], 0, 0, "нет варианта"))


v1, v2, v3 = res("ПоСтатьямPL"), res("ПоСтатьямЗатрат"), res("ПоСтатьямДенег")
проверка("4. Вариант «По статьям PL» компонуется", v1[1] > 0, v1[3][:300])
проверка("5. Вариант «По статьям затрат» компонуется", v2[1] > 0, v2[3][:300])
проверка("6. Вариант «По статьям денег» компонуется", v3[1] > 0, v3[3][:300])

# 7. топ статья затрат: столько красных ячеек, сколько у неё статей денег (по строке на пару)
топ_cells = [c for c in v1[0] if c[2] == топ_имя]
проверка(f"7. В дереве PL «{топ_имя}» встречается {топ_ддс} раз и все ячейки красные",
         топ_ддс >= 2 and len(топ_cells) == топ_ддс and all(RED in c[3] for c in топ_cells),
         f"найдено {len(топ_cells)}, цвета {[c[3] for c in топ_cells][:3]}")

# 8. Канцтовари: 4 статьи денег внутри одной PL — тоже проблема (1:N), все красные
канц = [c for c in v1[0] if c[2] == "Канцтовари"]
проверка("8. «Канцтовари» (4 статьи денег в одной PL) — 4 красные ячейки",
         len(канц) == len(sr_dds.get("Канцтовари", [])) and len(канц) >= 2 and all(RED in c[3] for c in канц),
         f"найдено {len(канц)}, ожидалось {len(sr_dds.get('Канцтовари', []))}, цвета {[c[3] for c in канц][:2]}")

# 9. чистая статья затрат не красная
чист = [c for c in v1[0] if c[2] == чистая]
проверка(f"9. Чистая статья затрат «{чистая}» не красная",
         bool(чистая) and len(чист) >= 1 and all(RED not in c[3] for c in чист),
         f"{[c[3] for c in чист][:2]}")

# 10. статья денег с 2+ статьями затрат — красная ячейка ДДС
д1n = [c for c in v1[0] if c[2] == ддс_1N]
проверка(f"10. Статья денег «{ддс_1N}» (2+ статьи затрат) — красная",
         bool(ддс_1N) and len(д1n) >= 1 and any(RED in c[3] for c in д1n),
         f"{[c[3] for c in д1n][:3]}")

# 11. факт в другой PL: в строке ДДС-кандидата ячейка PL факта оранжевая
if кандидат_орандж:
    d, pl, sr, ddsf = кандидат_орандж
    строки_д = {c[0] for c in v1[0] if c[2] == d}
    оранж = [c for c in v1[0] if c[0] in строки_д and c[2] == dds_pl[ddsf] and ORANGE in c[3]]
else:
    d, оранж = "", []
проверка(f"11. У статьи денег «{d}» ячейка «PL, куда уйдёт факт» оранжевая (деньги и факт в разных PL)",
         bool(кандидат_орандж) and len(оранж) >= 1, f"строк ДДС={len(строки_д) if кандидат_орандж else 0}")

# 12. группа PL с проблемой залита розовым (Прочие производственные затраты содержит Інші послуги)
группа = [c for c in v1[0] if c[2].startswith("Прочие производственные затраты")]
проверка("12. Группа PL с проблемой («Прочие производственные затраты») залита MistyRose",
         len(группа) >= 1 and any(PINK in c[3] for c in группа), f"{[c[3] for c in группа][:3]}")

# 13. заголовки колонок не красятся (пост-патч useInFieldsHeader)
шапка = [c for c in v1[0] if c[2] in ("Статья затрат", "Статья денег (ДДС)")]
проверка("13. Подписи колонок в шапке не красные",
         len(шапка) >= 1 and all(RED not in c[3] and ORANGE not in c[3] for c in шапка),
         f"{[(c[2], c[3]) for c in шапка][:2]}")

print(f"\nПРОВЕРОК: {ПРОВЕРОК}, ПРОВАЛОВ: {ПРОВАЛОВ}")
sys.exit(1 if ПРОВАЛОВ else 0)
