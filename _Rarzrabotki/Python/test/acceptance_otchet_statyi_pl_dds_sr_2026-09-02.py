"""Приёмка внешнего отчёта А_ОтчетПоСтатьямPL_ДДС_СтатьямРасходам (.erf) на BaseERP.

Полный путь пользователя через COM: ВнешниеОтчеты.Создать → загрузка каждого варианта
настроек → СформироватьОтчет (то же, что ПриКомпоновкеРезультата) → разбор ТабличногоДокумента.
Проблема = вхождение ДДС / статьи расходов в две и более PL-статьи.
Число проверок — константа 12, ни одна не стоит под if.
"""
