erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

ПРОВЕРОК = 0
ПРОВАЛОВ = 0


def проверка(name, cond, extra=""):
    global ПРОВЕРОК, ПРОВАЛОВ
    ПРОВЕРОК += 1
    if cond:
        print(f"  [OK]   {name}")
    else:
        ПРОВАЛОВ += 1
        print(f"  [FAIL] {name} {extra}")


def query(text):
    q = erp.NewObject("Запрос")
    q.Text = text
    return q.Execute().Выгрузить()


def rgb(color):
    """Строковое представление цвета: «Светло-коралловый (LightCoral)», «Авто» и т.п."""
    try:
        return S(color)
    except Exception:
        return ""


def scan(doc):
    """Считывает ТабличныйДокумент в список ячеек (строка, колонка, текст, фон RGB)."""
    cells = []
    h, w = int(doc.ВысотаТаблицы), int(doc.ШиринаТаблицы)
    for r in range(1, h + 1):
        for c in range(1, w + 1):
            обл = doc.Область(r, c, r, c)
            t = str(обл.Текст).strip()
            if t:
                cells.append((r, c, t, rgb(обл.ЦветФона) or ""))
    return cells, h, w


def compose(отч, схема, вариант):
    отч.КомпоновщикНастроек.Инициализировать(
        erp.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    отч.КомпоновщикНастроек.ЗагрузитьНастройки(вариант.Настройки)
    док = erp.NewObject("ТабличныйДокумент")
    отч.СформироватьОтчет(док, erp.NewObject("ДанныеРасшифровкиКомпоновкиДанных"))
    return док


# --------------------------------------------------------------- эталон из базы
r = query("""
ВЫБРАТЬ Т.СтатьяРасходов КАК СР, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Ссылка) КАК ЧислоPL, КОЛИЧЕСТВО(*) КАК Строк
ИЗ Справочник.А_Статьи_PL.Статьи КАК Т
ГДЕ НЕ Т.Ссылка.ПометкаУдаления
  И Т.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
СГРУППИРОВАТЬ ПО Т.СтатьяРасходов
ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Ссылка) > 1
УПОРЯДОЧИТЬ ПО ЧислоPL УБЫВ
""")
дубли = [(S(r.Получить(i).СР), int(r.Получить(i).ЧислоPL), int(r.Получить(i).Строк)) for i in range(r.Количество())]
r1 = query("""
ВЫБРАТЬ ПЕРВЫЕ 1 Т.СтатьяРасходов КАК СР
ИЗ Справочник.А_Статьи_PL.Статьи КАК Т
ГДЕ НЕ Т.Ссылка.ПометкаУдаления
  И Т.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
  И НЕ Т.СтатьяРасходов В (ВЫБРАТЬ Т2.СтатьяРасходов ИЗ Справочник.А_Статьи_PL.Статьи КАК Т2
        ГДЕ НЕ Т2.Ссылка.ПометкаУдаления СГРУППИРОВАТЬ ПО Т2.СтатьяРасходов
        ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т2.Ссылка) > 1)
""")
чистая_ср = S(r1.Получить(0).СР) if r1.Количество() else ""
строк_тч = int(query("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ Справочник.А_Статьи_PL.Статьи КАК Т ГДЕ НЕ Т.Ссылка.ПометкаУдаления").Получить(0).К)
топ = дубли[0] if дубли else ("", 0, 0)
print(f"Эталон: дублей статей расходов={len(дубли)} (топ: {топ[0]} в {топ[1]} PL, строк {топ[2]}); "
      f"чистая статья для контраста: «{чистая_ср}»; строк ТЧ={строк_тч}")

