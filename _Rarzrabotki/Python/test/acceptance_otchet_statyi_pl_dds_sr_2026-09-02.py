проверка("3. Основная форма отчёта — типовая ОбщаяФорма.ФормаОтчета",
         отч is not None and S(отч.Метаданные().ОсновнаяФорма.ПолноеИмя()) == "ОбщаяФорма.ФормаОтчета")

результаты = {}
for i in range(n_var):
    вар = варианты.Получить(i)
