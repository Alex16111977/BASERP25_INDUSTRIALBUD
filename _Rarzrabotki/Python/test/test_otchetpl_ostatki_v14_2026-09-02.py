"""RED-тест запроса v14 (Rule #-1): гоняем v14_full.sql через COM ДО переноса в BSL.

Правило (02.09.2026): месяцы <= 202606 — документы (месячные) / остатки (накопительные);
месяцы > 202606 — только регистры ЕРП, в месячных и накопительных.
Эталоны считаются независимыми запросами к регистрам/остаткам; строка «Операционный доход»
(группа статей PL код 000000006). Август живой — сравниваем с запросом того же момента.

    python test_otchetpl_ostatki_v14_2026-09-02.py               # v14_full.sql
    python test_otchetpl_ostatki_v14_2026-09-02.py v12_full.sql  # контроль: старый запрос должен быть красным
"""
import io
import os
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
ТЕСТ_ДИР = os.path.dirname(os.path.abspath(__file__))
SQL = io.open(os.path.join(ТЕСТ_ДИР, sys.argv[1] if len(sys.argv) > 1 else "v14_full.sql"), encoding='utf-8-sig').read()

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
ПРОВАЛОВ = [0]
ГРУППА_ОД = "000000006"


def чек(имя, ок, подробно=""):
    if not ок:
        ПРОВАЛОВ[0] += 1
    print("  [%s] %s%s" % ("OK  " if ок else "FAIL", имя, ("  — " + подробно) if подробно else ""))


def запрос(текст, **парам):
    q = erp.NewObject("Запрос")
    q.Text = текст
    for k, v in парам.items():
        q.SetParameter(k, v)
    return q.Execute().Выгрузить()


def скаляр(текст, **парам):
    r = запрос(текст, **парам)
    return r.Получить(0).Ссылка if r.Количество() else None


def число(текст, **парам):
    r = запрос(текст, **парам)
    return round(float(r.Получить(0).Сумма or 0), 2)


def описание(имя, квал=None):
    м = erp.NewObject("Массив")
    м.Добавить(erp.NewObject("ОписаниеТипов", имя).Типы().Получить(0))
    return erp.NewObject("ОписаниеТипов", м) if квал is None else erp.NewObject("ОписаниеТипов", м, квал)


def дата(г, м, д, ч=0, мин=0, с=0):
    return запрос("ВЫБРАТЬ ДАТАВРЕМЯ(%d,%d,%d,%d,%d,%d) КАК Д" % (г, м, д, ч, мин, с)).Получить(0).Д


def конец_месяца(г, м):
    return запрос("ВЫБРАТЬ КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(%d,%d,1), МЕСЯЦ) КАК Д" % (г, м)).Получить(0).Д


ПОДР = lambda имя: скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтруктураПредприятия ГДЕ Наименование = &Имя', Имя=имя)
ДДС_COGS = скаляр('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.СтатьиДвиженияДенежныхСредств ГДЕ А_ПриёмникСебестоимостиПродажPL')
СТ_ТОВАР = скаляр(
    'ВЫБРАТЬ ПЕРВЫЕ 1 СД.Ссылка КАК Ссылка, ВЫБОР КОГДА СД.Наименование = "Прочие доходи" ТОГДА 0 ИНАЧЕ 1 КОНЕЦ КАК Приоритет '
    'ИЗ ПланВидовХарактеристик.СтатьиДоходов КАК СД ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.А_Статьи_PL.Статьи КАК СтатьиТЧ '
    'ПО СтатьиТЧ.СтатьяДвиженияДенежныхСредств = СД.А_СтатьяДвиженияДенежныхСредств '
    'И СтатьиТЧ.Ссылка.Код = "000000002" И НЕ СтатьиТЧ.Ссылка.ПометкаУдаления '
    'ГДЕ НЕ СД.ПометкаУдаления УПОРЯДОЧИТЬ ПО Приоритет, СД.Наименование')
ПУСТО = дата(1, 1, 1)
ГРАНИЦА = дата(2026, 6, 30, 23, 59, 59)
НАЧАЛО_ЕРП = дата(2026, 7, 1)


def колонки(месяцы):
    кол = erp.NewObject("ТаблицаЗначений")
    кол.Колонки.Добавить("КолонкаСорт", описание("Число", erp.NewObject("КвалификаторыЧисла", 10, 0)))
    кол.Колонки.Добавить("КолонкаПредставление", описание("Строка", erp.NewObject("КвалификаторыСтроки", 30)))
    кол.Колонки.Добавить("МесяцДата", описание("Дата"))
    for м in месяцы:
        с = кол.Добавить(); с.КолонкаСорт = м; с.КолонкаПредставление = str(м); с.МесяцДата = ПУСТО
    с = кол.Добавить(); с.КолонкаСорт = 890000; с.КолонкаПредставление = "PL с начала года"; с.МесяцДата = ПУСТО
    с = кол.Добавить(); с.КолонкаСорт = 900000; с.КолонкаПредставление = "Накопительный PL"; с.МесяцДата = ПУСТО
    return кол


def прогон(свод, м1, м2):
    месяцы = [2026 * 100 + м for м in range(м1, м2 + 1)]
    z = erp.NewObject("Запрос")
    z.Text = SQL
    z.SetParameter("НачалоПериода", дата(2026, м1, 1))
    z.SetParameter("КонецПериода", конец_месяца(2026, м2))
    z.SetParameter("СводыНаправлений", свод)
    z.SetParameter("КолонкиPL", колонки(месяцы))
    z.SetParameter("ДДСCoGS", ДДС_COGS)
    z.SetParameter("СтатьяДоходовТовар", СТ_ТОВАР)
    z.SetParameter("ВыводитьФиксы", False)
    z.SetParameter("КлючНачалаГода", 202601)
    z.SetParameter("ГраницаОстатков", ГРАНИЦА)
    z.SetParameter("НачалоЕРП", НАЧАЛО_ЕРП)
    z.SetParameter("ОстаткиВГодуПериода", True)
    return z.Execute().Выгрузить()


def суммы_од(таб, корень):
    """{КолонкаСорт: сумма} по строкам группы ОД внутри поддерева корня (включая сам корень)."""
    r = запрос("""
    ВЫБРАТЬ Т.Подразделение КАК Подразделение, Т.Группа КАК Группа, Т.КолонкаСорт КАК КолонкаСорт,
        Т.СуммаИтого КАК СуммаИтого
    ПОМЕСТИТЬ втТ ИЗ &Т КАК Т
    ;
    ВЫБРАТЬ Т.КолонкаСорт КАК Кол, СУММА(Т.СуммаИтого) КАК Сумма
    ИЗ втТ КАК Т
    ГДЕ Т.Подразделение В ИЕРАРХИИ (&Корень) И Т.Группа.Код = &Код
    СГРУППИРОВАТЬ ПО Т.КолонкаСорт""", Т=таб, Корень=корень, Код=ГРУППА_ОД)
    return {int(r.Получить(i).Кол): round(float(r.Получить(i).Сумма or 0), 2) for i in range(r.Количество())}


def инварианты(таб, имя):
    r = запрос("""
    ВЫБРАТЬ Т.КолонкаСорт КАК КолонкаСорт, Т.Документ КАК Документ
    ПОМЕСТИТЬ втТ ИЗ &Т КАК Т
    ;
    ВЫБРАТЬ
        СУММА(ВЫБОР КОГДА Т.КолонкаСорт > 202606 И Т.КолонкаСорт < 890000 И Т.Документ ССЫЛКА Документ.А_ОтчетPL ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ДокПослеГраницы,
        СУММА(ВЫБОР КОГДА Т.КолонкаСорт > 0 И Т.КолонкаСорт <= 202606 И НЕ Т.Документ ССЫЛКА Документ.А_ОтчетPL ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ЕРПДоГраницы,
        СУММА(ВЫБОР КОГДА Т.КолонкаСорт В (890000, 900000) И Т.Документ ССЫЛКА Документ.А_ОтчетPL ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ДокВНакопительных,
        СУММА(ВЫБОР КОГДА Т.КолонкаСорт В (890000, 900000) И Т.Документ ССЫЛКА Документ.А_ВводОстатковОтчетаPL ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК ОстаткиВНакопительных
    ИЗ втТ КАК Т""", Т=таб).Получить(0)
    чек(имя + ": после границы нет строк А_ОтчетPL", int(r.ДокПослеГраницы or 0) == 0, str(r.ДокПослеГраницы))
    чек(имя + ": до границы нет строк ЕРП", int(r.ЕРПДоГраницы or 0) == 0, str(r.ЕРПДоГраницы))
    чек(имя + ": в накопительных нет А_ОтчетPL", int(r.ДокВНакопительных or 0) == 0, str(r.ДокВНакопительных))
    чек(имя + ": в накопительных есть регистратор остатков", int(r.ОстаткиВНакопительных or 0) > 0, str(r.ОстаткиВНакопительных))


def остатки_од(корень, свод, ресурс):
    return число("""
    ВЫБРАТЬ СУММА(Ост.СуммаФ1%s + Ост.СуммаФ2%s) КАК Сумма
    ИЗ РегистрНакопления.А_ОстаткиОтчетаPL КАК Ост
    ГДЕ Ост.Подразделение = &П И Ост.СводНаправления = &Свод И Ост.СтатьяPL.Группа.Код = &Код""" % (ресурс, ресурс),
        П=корень, Свод=свод, Код=ГРУППА_ОД)


def ерп_од(корень, м):
    н, к = дата(2026, м, 1), конец_месяца(2026, м)
    выручка = число("""
    ВЫБРАТЬ СУММА(Выр.СуммаВыручки) КАК Сумма ИЗ РегистрНакопления.ВыручкаИСебестоимостьПродаж КАК Выр
    ГДЕ Выр.Активность И Выр.Подразделение В ИЕРАРХИИ (&К) И Выр.Период МЕЖДУ &Н И &КП""", К=корень, Н=н, КП=к)
    прочие = число("""
    ВЫБРАТЬ СУММА(ПрД.Сумма) КАК Сумма ИЗ РегистрНакопления.ПрочиеДоходы КАК ПрД
    ГДЕ ПрД.Активность И ПрД.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
      И ПрД.Подразделение В ИЕРАРХИИ (&К) И ПрД.Период МЕЖДУ &Н И &КП
      И ПрД.СтатьяДоходов.А_СтатьяДвиженияДенежныхСредств В
        (ВЫБРАТЬ Ст.СтатьяДвиженияДенежныхСредств ИЗ Справочник.А_Статьи_PL.Статьи КАК Ст ГДЕ Ст.Ссылка.Группа.Код = &Код)""",
        К=корень, Н=н, КП=к, Код=ГРУППА_ОД)
    return round(выручка + прочие, 2)


def документ_од(подр, свод, м):
    return число("""
    ВЫБРАТЬ СУММА(Стр.Сумма) КАК Сумма
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК Стр ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ОтчетPL КАК Док ПО Стр.Ссылка = Док.Ссылка
    ГДЕ Док.Проведен И Док.Подразделение = &П И Док.ВключатьДочерние = &Свод
      И ГОД(Док.Дата) * 100 + МЕСЯЦ(Док.Дата) = &М И Стр.Статья.Группа.Код = &Код""", П=подр, Свод=свод, М=2026 * 100 + м, Код=ГРУППА_ОД)


def равно(a, b):
    return abs(a - b) < 0.01


def сценарий(имя, корень_имя, свод, м1, м2, месяцы_док=()):
    print("=" * 96)
    print("%s — %s, свод=%s, %02d..%02d.2026" % (имя, корень_имя, свод, м1, м2))
    корень = ПОДР(корень_имя)
    таб = прогон(свод, м1, м2)
    чек("запрос выполнился", таб.Количество() > 0, "строк %d" % таб.Количество())
    инварианты(таб, имя)
    факт = суммы_од(таб, корень)
    ерп = {м: ерп_од(корень, м) for м in range(7, м2 + 1)}
    for м in range(max(м1, 7), м2 + 1):
        чек("месяц %d = ЕРП" % (202600 + м), равно(факт.get(202600 + м, 0), ерп[м]), "%.2f / %.2f" % (факт.get(202600 + м, 0), ерп[м]))
    for м in месяцы_док:
        ож = документ_од(корень, свод, м)
        чек("месяц %d = документ" % (202600 + м), равно(факт.get(202600 + м, 0), ож), "%.2f / %.2f" % (факт.get(202600 + м, 0), ож))
    снг = остатки_од(корень, свод, "СНачалаГода") + sum(ерп.values())
    нак = остатки_од(корень, свод, "Накопительно") + sum(ерп.values())
    чек("890000 = остатки СНГ + ЕРП 07..%02d" % м2, равно(факт.get(890000, 0), снг), "%.2f / %.2f" % (факт.get(890000, 0), снг))
    чек("900000 = остатки Нак + ЕРП 07..%02d" % м2, равно(факт.get(900000, 0), нак), "%.2f / %.2f" % (факт.get(900000, 0), нак))
    return факт


