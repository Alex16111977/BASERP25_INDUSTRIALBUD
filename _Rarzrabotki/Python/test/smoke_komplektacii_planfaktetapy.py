cells = [str(т.Область(r, c, r, c).Текст) for r in range(1, min(9, h) + 1) for c in range(1, w + 1)]
head = " | ".join(x.strip() for x in cells if x.strip())
print("ШАПКА:", head[:400])
низ = head.lower()

# заголовок звіту
assert "аналіз залишків для списання за сс з етапами" in низ, "немає нового заголовка звіту"
# групування Этап
assert "етап" in низ, "немає заголовка групи «Етап»"
# одна колонка одиниці, без подвійних
assert "одиниця виміру" in низ, "немає колонки «Одиниця виміру»"
assert "одиниця виміру залишків" not in низ and "одиниця виміру сс" not in низ, "є подвійні одиниці — має бути одна"
# ключові колонки набору «Аналіз СС»
need = ["залишок", "згідно з сс", "в нормі", "понад норму", "економія", "в нормі, грн",
        "понад норму, грн", "економія, грн", "сума сс", "факт. списання", "різниця", "вик. сс"]
missing = [x for x in need if x not in низ]
assert not missing, f"немає колонок: {missing}"
# старих план-факт %-колонок не має бути
assert "% вик. (кільк.)" not in низ and "норма номенкл" not in низ, "лишились старі план-факт колонки"

# порядок: Залишок < Одиниця виміру < Згідно з СС (у шапці колонок)
pos = {}
for r in range(1, min(9, h) + 1):
    for c in range(1, w + 1):
        t2 = str(т.Область(r, c, r, c).Текст).strip()
        for hd in ("Залишок", "Одиниця виміру", "Згідно з СС"):
            if t2 == hd and hd not in pos:
                pos[hd] = c
if all(k in pos for k in ("Залишок", "Одиниця виміру", "Згідно з СС")):
    assert pos["Залишок"] < pos["Одиниця виміру"] < pos["Згідно з СС"], f"порядок колонок: {pos}"
    print(f"Порядок OK: {pos}")

# шапка звіту не янтарна
