import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

НАЧ = "ДАТАВРЕМЯ(2024,1,1)"
КОН = "ДАТАВРЕМЯ(2026,12,31,23,59,59)"

def run(text):
    q = erp.NewObject("Запрос")
    q.Текст = text
    return q.Выполнить().Выгрузить()

def show(title, text, cols=None, limit=40):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)
    try:
        t = run(text)
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        print("FAIL:", info[2] if info and len(info) > 2 else e)
        return None
    n = t.Количество()
    names = [t.Колонки.Получить(j).Имя for j in range(t.Колонки.Количество())]
    print(f"строк: {n}  колонки: {names}")
    for i in range(min(n, limit)):
        r = t.Получить(i)
        vals = []
        for j in range(len(names)):
            v = r.Получить(j)
            try:
                v = str(v)
            except Exception:
                v = "<?>"
            vals.append(f"{names[j]}={v}")
        print("  " + " | ".join(vals))
    return t

