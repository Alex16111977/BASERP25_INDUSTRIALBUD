# -*- coding: utf-8 -*-
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Статья 'Прочие пассивы' в ПВХ.СтатьиАктивовПассивов
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Ст.Ссылка КАК Ссылка,
    Ст.Наименование КАК Наим,
    Ст.Предопределенный КАК Предоп
ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК Ст
ГДЕ Ст.Наименование ПОДОБНО "%рочие пассив%"
"""
r = q.Execute().Выгрузить()
print(f"Статьи 'Прочие пассивы': рядкiв={r.Количество()}")
for i in range(r.Количество()):
    s=r.Получить(i)
    print(f"  Наим='{s.Наим}' | Предопр={s.Предоп}")
    # тип значения статьи (какая аналитика разрешена)
    try:
        print(f"     ТипЗначения(аналитика)={s.Ссылка.ТипЗначения}")
    except Exception as e:
        pass

# Документы ВводОстатковПрочихАктивовПассивов с этой статьёй - эталон знака/источника
print("\n--- Эталон: движения ПАП от ВводОстатковПрочихАктивовПассивов по статье 'Прочие пассивы' ---")
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ ПЕРВЫЕ 10
    ПРЕДСТАВЛЕНИЕ(ПАП.Регистратор) КАК Рег,
    ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА "Приход" ИНАЧЕ "Расход" КОНЕЦ КАК Вид,
    ПАП.Аналитика КАК Аналитика,
    ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК Подр,
    ПАП.ВидИсточника КАК ВидИст,
    ПАП.Источник КАК Ист,
    ПАП.Сумма КАК Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Статья.Наименование = "Прочие пассивы"
    И ТИПЗНАЧЕНИЯ(ПАП.Регистратор) = ТИП(Документ.ВводОстатковПрочихАктивовПассивов)
"""
try:
    r2 = q2.Execute().Выгрузить()
    print(f"  рядкiв={r2.Количество()}")
    for i in range(r2.Количество()):
        s=r2.Получить(i)
        anlt = f"{s.Аналитика.Метаданные().Имя}:{s.Аналитика}" if erp.ЗначениеЗаполнено(s.Аналитика) else "ПУСТО"
        vi = str(s.ВидИст) if erp.ЗначениеЗаполнено(s.ВидИст) else "ПУСТО"
        ist = f"{s.Ист.Метаданные().Имя}" if erp.ЗначениеЗаполнено(s.Ист) else "ПУСТО"
        print(f"  [{s.Вид}] Σ={s.Сумма} Подр={s.Подр} | Аналитика={anlt} ВидИст={vi} Ист={ist} | {s.Рег}")
except Exception as e:
    if hasattr(e,'excepinfo') and e.excepinfo:
        print("FAIL:", e.excepinfo[2])
    else:
        print("FAIL:", e)
