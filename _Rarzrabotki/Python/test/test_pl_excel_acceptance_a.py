# -*- coding: utf-8 -*-
"""Acceptance A: расщепление факт-выручки по ТипЗапасов, сверка план↔факт (Строительство, июнь-2026).

Услуга-корзина: Услуга, АгентскаяУслуга -> PL 000000001 (Выручка от продаж).
Товар-корзина: всё остальное -> PL 000000002 (Доход от прочей опер. деятельности).
Стыковка план<->факт по ССЫЛКЕ Подразделения (Подразделение В (&Список)).
"""
import win32com.client, sys, datetime
from collections import defaultdict
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

def run(text, params=None):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    try:
        return q.Execute().Выгрузить()
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else str(e)
        print("FAIL:", msg)
        raise

# 1. План: подразделения Строительства (ВД=Ложь) июнь-2026, суммы статей 1 и 2
plan_tz = run("""ВЫБРАТЬ
    ТЧ.Ссылка.Подразделение КАК Подразделение,
    ТЧ.Ссылка.ПодразделениеСтрока КАК Подр,
    ТЧ.Статья.Код КАК КодСтатьи,
    СУММА(ТЧ.Сумма) КАК Сумма
ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
ГДЕ ТЧ.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ(2026,6,1) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
    И НЕ ТЧ.Ссылка.ПометкаУдаления
    И НЕ ТЧ.Ссылка.ВключатьДочерние
    И ТЧ.Ссылка.НаправлениеДеятельности.Наименование = "Строительство"
    И ТЧ.Статья.Код В ("000000001", "000000002")
СГРУППИРОВАТЬ ПО ТЧ.Ссылка.Подразделение, ТЧ.Ссылка.ПодразделениеСтрока, ТЧ.Статья.Код""")

plan = defaultdict(lambda: {'000000001': 0.0, '000000002': 0.0})
refs = {}
for i in range(plan_tz.Количество()):
    r = plan_tz.Получить(i)
    plan[S(r.Подр)][S(r.КодСтатьи)] = float(r.Сумма)
    refs[S(r.Подр)] = r.Подразделение

СписокПодр = erp.NewObject("Массив")
for ref in refs.values():
    СписокПодр.Добавить(ref)

# 2. Факт: расщепление выручки по ТипЗапасов — фрагмент 1:1 как пойдёт в BSL
fact_t = run("""ВЫБРАТЬ
    Выр.Подразделение КАК Подразделение,
    ВЫБОР
        КОГДА Выр.ТипЗапасов В (ЗНАЧЕНИЕ(Перечисление.ТипыЗапасов.Услуга),
            ЗНАЧЕНИЕ(Перечисление.ТипыЗапасов.АгентскаяУслуга))
            ТОГДА "УСЛУГИ"
        ИНАЧЕ "ТОВАР"
    КОНЕЦ КАК Корзина,
    СУММА(Выр.СуммаВыручки) КАК Сумма
ИЗ РегистрНакопления.ВыручкаИСебестоимостьПродаж КАК Выр
ГДЕ Выр.Период МЕЖДУ &НачалоПериода И &КонецПериода
    И Выр.Активность
    И Выр.СуммаВыручки <> 0
    И Выр.Подразделение В (&СписокПодр)
СГРУППИРОВАТЬ ПО
    Выр.Подразделение,
    ВЫБОР
        КОГДА Выр.ТипЗапасов В (ЗНАЧЕНИЕ(Перечисление.ТипыЗапасов.Услуга),
            ЗНАЧЕНИЕ(Перечисление.ТипыЗапасов.АгентскаяУслуга))
            ТОГДА "УСЛУГИ"
        ИНАЧЕ "ТОВАР"
    КОНЕЦ""",
    {"НачалоПериода": datetime.datetime(2026,6,1), "КонецПериода": datetime.datetime(2026,6,30,23,59,59),
     "СписокПодр": СписокПодр})

# даты через строку могли не пройти — проверим количество; если 0, зададим датами 1С
if fact_t.Количество() == 0:
    print("!! Пустой результат с ISO-строками дат, пробуем ДАТАВРЕМЯ")

fact = defaultdict(lambda: {'УСЛУГИ': 0.0, 'ТОВАР': 0.0})
for i in range(fact_t.Количество()):
    r = fact_t.Получить(i)
    fact[S(r.Подразделение)][S(r.Корзина)] = float(r.Сумма)

# 3. Факт ПрочиеДоходы по этим подразделениям (для контроля «прочей»)
pd_t = run("""ВЫБРАТЬ
    П.Подразделение КАК Подразделение,
    СУММА(П.СуммаОборот) КАК Сумма
ИЗ РегистрНакопления.ПрочиеДоходы.Обороты(&НачалоПериода, &КонецПериода, , ) КАК П
ГДЕ П.СтатьяДоходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиДоходов.ПустаяСсылка)
    И П.Подразделение В (&СписокПодр)
    И П.СтатьяДоходов.А_СтатьяДвиженияДенежныхСредств.Код = "УТ-001174"
СГРУППИРОВАТЬ ПО П.Подразделение""",
    {"НачалоПериода": datetime.datetime(2026,6,1), "КонецПериода": datetime.datetime(2026,6,30,23,59,59),
     "СписокПодр": СписокПодр})
prochie = defaultdict(float)
for i in range(pd_t.Количество()):
    r = pd_t.Получить(i)
    prochie[S(r.Подразделение)] = float(r.Сумма)

# 4. Сверка
print(f"{'Подразделение':32s} {'ПЛАН Выручка':>16s} {'ФАКТ услуги':>16s} {'ПЛАН Прочая':>16s} {'ФАКТ товар':>16s} {'+ПрочДох':>14s}")
for p in sorted(plan):
    pl1, pl2 = plan[p]['000000001'], plan[p]['000000002']
    # имя подразделения-ссылки может отличаться от ПодразделениеСтрока
    ref_name = S(refs[p])
    f = fact.get(ref_name, fact.get(p, {'УСЛУГИ': 0.0, 'ТОВАР': 0.0}))
    pr = prochie.get(ref_name, prochie.get(p, 0.0))
    ok1 = "OK" if abs(pl1 - f['УСЛУГИ']) <= 0.01 else "  "
    ok2 = "OK" if abs(pl2 - f['ТОВАР']) <= 0.01 else ("OK+" if abs(pl2 - (f['ТОВАР'] + pr)) <= 0.01 else "  ")
    print(f"{p:32s} {pl1:>16,.2f} {f['УСЛУГИ']:>14,.2f}{ok1} {pl2:>16,.2f} {f['ТОВАР']:>14,.2f}{ok2:3s} {pr:>12,.2f}")

# 5. Кандидат СтатьяДоходов для товарной ветки
cand = run("""ВЫБРАТЬ Ссылка, Наименование, А_СтатьяДвиженияДенежныхСредств.Код КАК КодДДС
ИЗ ПланВидовХарактеристик.СтатьиДоходов
ГДЕ Наименование = "Прочие доходи" И НЕ ПометкаУдаления""")
for i in range(cand.Количество()):
    r = cand.Получить(i)
    print(f"Кандидат товарной СтатьиДоходов: {S(r.Наименование)!r} ДДС={S(r.КодДДС)!r} uuid={S(erp.String(r.Ссылка.УникальныйИдентификатор()))}")
