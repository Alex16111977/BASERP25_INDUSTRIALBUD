"""Заполняет НаименованиеДляОтчетаНаРусском в А_Статьи_PL и А_ГруппаСтатей_PL.

Таблицы переименований — из PROMPT_А_ОтчетPL_ПолныйЕРП_РусскиеНазвания.md (дословно).
Идемпотентно: если значение уже равно целевому — пропуск. Помеченные на удаление
пропускаются.

🔴 Грабля: ПередЗаписью() А_Статьи_PL при А_РучнаяКорректировка=Истина ставит Отказ —
пишем ТОЛЬКО через Объект.ОбменДанными.Загрузка = Истина. Меняем ЕДИНСТВЕННЫЙ реквизит.

Запуск:
    python _Rarzrabotki\\Python\\test\\fill_russkie_naimenovaniya_pl_2026-08-21.py
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Особые русские названия статей (остальным — СокрЛП(Наименование))
ОСОБЫЕ_СТАТЬИ = {
    "000000002": "Выручка от прочей операционной деятельности",
    "000000015": "Аренда техники",
    "000000028": "Расход от инвест. деятельности (ОС)",
    "000000039": "Начисления на управленческую зарплату",
    "000000043": "Начисления на зарплату РМ",  # РМ кириллицей
    "000000045": "Телекоммуникационные услуги",
    "000000048": "Затраты на командировки управленческого персонала",
    "000000056": "ФА, комиссии",
    "000000070": "Объекты, которые не закрыты, но расходы были понесены",
}

ГРУППЫ = {
    "000000006": "Операционный доход",
    "000000001": "Себестоимость проданной продукции (переменные производственные затраты)",
    "000000007": "Дополнительные расходы",
    "000000003": "Общепроизводственные затраты",
    "000000005": "Маркетинговые затраты",
    "000000002": "Административные затраты",
    "000000008": "Налоги и сборы",
    "000000004": "Финансовая деятельность",
}

итог = {"записано": 0, "пропущено": 0, "уже": 0}


def обработать(имя_спр, целевые, дефолт_из_наименования):
    print("=" * 96)
    print("Справочник", имя_спр)
    print("=" * 96)
    q = erp.NewObject("Запрос")
    q.Text = ("ВЫБРАТЬ Спр.Ссылка КАК Ссылка, Спр.Код КАК Код, Спр.Наименование КАК Имя, "
              "Спр.НаименованиеДляОтчетаНаРусском КАК Рус, Спр.ПометкаУдаления КАК Удал "
              "ИЗ Справочник.%s КАК Спр УПОРЯДОЧИТЬ ПО Код" % имя_спр)
    т = q.Execute().Выгрузить()
    for i in range(т.Количество()):
        с = т.Получить(i)
        код = S(с.Код)
        if с.Удал:
            print("  %s | %-55s | ПРОПУЩЕН (пометка удаления)" % (код, S(с.Имя)[:55]))
            итог["пропущено"] += 1
            continue
        if код in целевые:
            новое = целевые[код]
        elif дефолт_из_наименования:
            новое = S(с.Имя).strip()
        else:
            print("  %s | %-55s | ПРОПУЩЕН (нет в таблице групп!)" % (код, S(с.Имя)[:55]))
            итог["пропущено"] += 1
            continue
        старое = S(с.Рус)
        if старое == новое:
            print("  %s | %-55s | уже заполнено" % (код, новое[:55]))
            итог["уже"] += 1
            continue
        об = с.Ссылка.ПолучитьОбъект()
        об.НаименованиеДляОтчетаНаРусском = новое
        # ПередЗаписью при А_РучнаяКорректировка=Истина отказывает любой записи —
        # режим загрузки выходит из обработчика первой строкой.
        об.ОбменДанными.Загрузка = True
        об.Записать()
        print("  %s | %-45s -> %-45s | ЗАПИСАНО" % (код, S(с.Имя).strip()[:45], новое[:45]))
        итог["записано"] += 1


обработать("А_ГруппаСтатей_PL", ГРУППЫ, False)
print("")
обработать("А_Статьи_PL", ОСОБЫЕ_СТАТЬИ, True)

print("")
print("ИТОГ: записано %(записано)d, уже было %(уже)d, пропущено %(пропущено)d" % итог)

# Постпроверка: пустых русских наименований среди активных быть не должно
q = erp.NewObject("Запрос")
q.Text = ('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Справочник.А_Статьи_PL КАК Спр '
          'ГДЕ НЕ Спр.ПометкаУдаления И Спр.НаименованиеДляОтчетаНаРусском = ""')
н1 = q.Execute().Выгрузить().Получить(0).Н
q.Text = ('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Справочник.А_ГруппаСтатей_PL КАК Спр '
          'ГДЕ НЕ Спр.ПометкаУдаления И Спр.НаименованиеДляОтчетаНаРусском = ""')
н2 = q.Execute().Выгрузить().Получить(0).Н
print("пустых у активных: статьи=%s, группы=%s %s"
      % (н1, н2, "— OK" if int(н1) == 0 and int(н2) == 0 else "— ЕСТЬ ПУСТЫЕ!"))
sys.exit(0 if int(н1) == 0 and int(н2) == 0 else 1)
