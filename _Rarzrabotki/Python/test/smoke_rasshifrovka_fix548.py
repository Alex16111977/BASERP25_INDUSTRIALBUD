# -*- coding: utf-8 -*-
"""COM-смоук фикса: стороны под взаимозачётом ограничены ДВУМЯ подразделениями пары.

Грузит пересобранный .erf, вызывает ПолучитьТаблицуРасшифровки за декабрь 2025,
проверяет что под 000Ц-000548 (осн. ІБ00-007892, пара MAN №3 ↔ Логистика) НЕТ
сторон чужих подразделений (MAN №4 / MAN №5). Заодно сверяет эталоны 511/510.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import os, pythoncom, win32com.client

ERP = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
ERF = (r"C:\Configuration_downloads\BASERP25\.claude\worktrees"
       r"\charming-allen-2fc47b\_Rarzrabotki\Отчеты"
       r"\А_РасшифровкаЗадолженностиПодразделений.erf")
assert os.path.exists(ERF), "ERF не найден"

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(ERP)
отчёт = conn.ВнешниеОтчеты.Создать(ERF, False)
print("Внешний отчёт загружен, модуль скомпилирован OK")

q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2025,12,1) КАК Н, ДАТАВРЕМЯ(2025,12,31,23,59,59) КАК К"
rr = q.Выполнить().Выбрать(); rr.Следующий()

П = conn.NewObject("Структура")
П.Вставить("НачалоПериода", rr.Н)
П.Вставить("ОкончаниеПериода", rr.К)
П.Вставить("Организация", None)
П.Вставить("ТолькоРасхождения", False)
П.Вставить("ВключатьНепроведенные", True)

ТЗ = отчёт.ПолучитьТаблицуРасшифровки(П)
print(f"ПолучитьТаблицуРасшифровки вернул строк: {ТЗ.Количество()}")


def ПР(z):
    if z is None:
        return ""
    z2 = conn.NewObject("Запрос")
    z2.Текст = "ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(&З) КАК П"
    z2.УстановитьПараметр("З", z)
    s = z2.Выполнить().Выбрать(); s.Следующий()
    return str(s.П or "")


sides548 = {}   # (СторонаЗнак, Источник) -> {Подр, Сальдо, А1}
src511 = set()
src510 = set()
for i in range(ТЗ.Количество()):
    r = ТЗ.Получить(i)
    ном = str(r.Взаимозачет.Номер) if r.Взаимозачет else ""
    d = r.Дата
    if d is not None and d.year != 2025:
        continue
    if ном == "000Ц-000548":
        sides548[(str(r.СторонаЗнак), ПР(r.СторонаИсточник))] = {
            "Подр": ПР(r.СторонаПодразделение), "Сальдо": float(r.Сальдо or 0), "А1": r.Аналитика1}
    elif ном == "000Ц-000511":
        src511.add(ПР(r.СторонаИсточник))
    elif ном == "000Ц-000510":
        src510.add(ПР(r.СторонаИсточник))

print("\n--- 000Ц-000548 стороны ---")
for k in sorted(sides548):
    v = sides548[k]
    print(f"  {k[0]} | {k[1]} | Подр={v['Подр']!r} Сальдо={v['Сальдо']:,.2f} А1={v['А1']!r}")

подр548 = {v["Подр"] for v in sides548.values()}
print("\nуникальные подразделения сторон 548:", sorted(подр548))

ok = True
чужие = [p for p in подр548 if ("MAN №4" in p or "MAN №5" in p)]
if чужие:
    ok = False; print("FAIL: под 548 чужие подразделения:", чужие)
if not any("MAN №3" in p for p in подр548):
    ok = False; print("FAIL: нет стороны MAN №3")
if "Логистика" not in подр548:
    ok = False; print("FAIL: нет стороны Логистика")
# сальдо стороны = ±СуммаРегл (пер-пара): дебитор +190, кредитор -190
for k, v in sides548.items():
    if k[0] == "Кредитор" and abs(abs(v["Сальдо"]) - 190.0) > 0.01:
        ok = False; print("FAIL: кредиторская сторона 548 не равна ±СуммаРегл:", v)

# эталоны 511/510 — обе стороны на месте
if not ({"Себестоимость товаров", "Расчеты с поставщиками по срокам"} <= src511):
    ok = False; print("FAIL: 511 источники сторон:", src511)
if not ({"Прочие расходы", "Себестоимость товаров"} <= src510):
    ok = False; print("FAIL: 510 источники сторон:", src510)

print("\n" + "=" * 64)
assert ok, "FAIL"
print("PASS: фикс работает — под 000Ц-000548 только MAN №3 + Логистика (без MAN №4/№5),")
print("      сальдо стороны = ±СуммаРегл, эталоны 511/510 не сломаны.")
