"""Проверка: у СтрПредпр (через Рш.Подразделение.А_Подразделение) заполнен А_НаправлениеДеятельности?
Это критично для Подхода C — чтобы балансировка не писала плуги Вывод/Вложения СобСрс."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
    Рш.Подразделение.А_Подразделение КАК СтрПредпр,
    Рш.Подразделение.А_Подразделение.А_НаправлениеДеятельности КАК Направ
ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
ГДЕ Рш.Ссылка.Номер = &Ном
УПОРЯДОЧИТЬ ПО СтрПредпр
"""
q.SetParameter("Ном", "000Ц-000009")
r = q.Execute().Выгрузить()

print(f"Найдено уникальных СтрПредпр: {r.Количество()}\n")
print(f"{'СтрПредпр':<40} {'НаправлениеДеятельности':<40} {'Заполнено':>10}")
print("-" * 95)
empty_count = 0
for row in r:
    napr = S(row.Направ)
    filled = erp.ЗначениеЗаполнено(row.Направ)
    mark = "✅" if filled else "⚠️  ПУСТО"
    if not filled:
        empty_count += 1
    print(f"{S(row.СтрПредпр):<40} {napr:<40} {mark:>10}")

print("-" * 95)
print(f"Пустых: {empty_count} из {r.Количество()}")

# Дополнительно — что в Расходе ДенСр того же РКО (для сверки балансировки)
print("\n--- Сейчас в ПАП Расхода ДенежныеСредстваНаличные для РКО N0000052986 ---")
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    Р.Подразделение, Р.НаправлениеДеятельности, Р.Сумма
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Р
ГДЕ Р.Регистратор.Номер = &Ном
    И Р.Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ДенежныеСредстваНаличные)
"""
q2.SetParameter("Ном", "N0000052986")
r2 = q2.Execute().Выгрузить()
for row in r2:
    print(f"  Подр={S(row.Подразделение)}, Направ={S(row.НаправлениеДеятельности)}, Сумма={row.Сумма}")
