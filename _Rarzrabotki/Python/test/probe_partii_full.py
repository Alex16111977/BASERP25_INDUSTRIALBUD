# -*- coding: utf-8 -*-
# ПОЛНЫЙ прототип движка отчёта А_РасшифровкаПартийСписаннойНоменклатуры (Rule #-1).
# По выбранной Реализации: для каждой Кт-строки товарного счёта (Партія+Номенклатура)
# рекурсивно разворачивает партию через Перемещения до первичного прихода.
# Это 1:1 blueprint для BSL-движка (ObjectModule.ПолучитьДанные).
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

def S(v):
    try: return buh.String(v) if v is not None else "None"
    except: return "<?>"
def full(v):
    try: return v.Метаданные().ПолноеИмя()
    except: return ""
def uid(ref):
    if ref is None: return "None"
    try: return buh.String(ref.УникальныйИдентификатор())
    except:
        try: return buh.XMLСтрока(ref.УникальныйИдентификатор())
        except: return S(ref)
def key(ref):
    return "None" if ref is None else full(ref) + "|" + uid(ref)

def найти(typ, nomer, cond=" И Дата>=ДАТАВРЕМЯ(2026,1,1)"):
    q = buh.NewObject("Запрос")
    q.Text = f"ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.{typ} ГДЕ Номер=&Н{cond} УПОРЯДОЧИТЬ ПО Дата УБЫВ"
    q.SetParameter("Н", nomer)
    s = q.Execute().Выбрать()
    return s.Ссылка if s.Следующий() else None

ТипНом = "Справочник.Номенклатура"
ТипПеремещение = "Документ.ПеремещениеТоваров"

реал = найти("РеализацияТоваровУслуг", "ІБ00-000113")
print("Реализация:", S(реал))

# --- ВидСубконто «Партії» и его составной тип (для valueType поля СКД) ---
вид_партии = None
нз0 = buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
нз0.Отбор.Регистратор.Установить(реал); нз0.Прочитать()
for z in нз0:
    if z.КоличествоКт == 0: continue
    for kv in z.СубконтоКт:
        if "Парт" in S(kv.Ключ):
            вид_партии = kv.Ключ; break
    if вид_партии: break
print("ВидСубконто Партії:", S(вид_партии), "| мета:", full(вид_партии))
ПартТипы = []
if вид_партии is not None:
    for t in вид_партии.ТипЗначения.Типы():
        md = buh.Метаданные.НайтиПоТипу(t)
        if md is not None:
            ПартТипы.append(md.ПолноеИмя())
print(f"Партія допускает {len(ПартТипы)} типов метаданных:")
for n in ПартТипы: print("   ", n)

# --- кэш Кт-строк документа: list of dict(ном, парт, кол, сум, счет) ---
КЭШ = {}
def кт_строки(док):
    k = key(док)
    if k in КЭШ: return КЭШ[k]
    res = []
    нз = buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
    нз.Отбор.Регистратор.Установить(док); нз.Прочитать()
    for z in нз:
        if z.КоличествоКт == 0: continue
        ном = None; парт = None
        for kv in z.СубконтоКт:
            t = full(kv.Значение)
            if t == ТипНом: ном = kv.Значение
            elif "Парт" in S(kv.Ключ): парт = kv.Значение
        res.append({"ном": ном, "парт": парт, "кол": z.КоличествоКт, "сум": z.Сумма,
                    "счет": S(z.СчетКт)})
    КЭШ[k] = res
    return res

# --- ДИАГНОСТИКА: все Кт-строки реализации (разрешаем загадку None) ---
print("\n=== ДИАГНОСТИКА: все Кт-строки реализации ===")
for i, r in enumerate(кт_строки(реал)):
    нп = "пусто" if r["парт"] is None else f'{S(r["парт"])[:45]} [{full(r["парт"])}]'
    нн = "пусто" if r["ном"] is None else S(r["ном"])
    print(f"  [{i}] Счёт={r['счет']:>6}  Ном={нн:<28}  Кол={S(r['кол']):>6}  Сум={S(r['сум']):>12}  Партія={нп}")

# --- рекурсивный трейс до прихода (терминал = первый не-Перемещение) ---
def трейс(ном, парт, посещ, depth=0):
    if парт is None:
        return []
    kp = key(парт)
    if depth > 50 or kp in посещ:
        return [парт]
    посещ.add(kp)
    if full(парт) != ТипПеремещение:
        return [парт]                       # терминал
    uid_ном = uid(ном)
    источники = []; ключи = set()
    for r in кт_строки(парт):
        if r["ном"] is not None and uid(r["ном"]) == uid_ном and r["парт"] is not None:
            kk = key(r["парт"])
            if kk not in ключи:
                ключи.add(kk); источники.append(r["парт"])
    if not источники:
        return [парт]                       # тупик — показываем само перемещение
    итог = []; кл = set()
    for ист in источники:
        for прих in трейс(ном, ист, посещ, depth + 1):
            k = key(прих)
            if k not in кл:
                кл.add(k); итог.append(прих)
    return итог

# --- ПОЛНЫЙ ПРОХОД: агрегируем по (ном, партіяСписання), затем трейс ---
агр = {}    # key -> dict(ном, парт, кол, сум)
пропущено = 0
for r in кт_строки(реал):
    if r["ном"] is None or r["парт"] is None:
        пропущено += 1
        continue
    k = key(r["ном"]) + "##" + key(r["парт"])
    if k not in агр:
        агр[k] = {"ном": r["ном"], "парт": r["парт"], "кол": 0, "сум": 0}
    агр[k]["кол"] += r["кол"]; агр[k]["сум"] += r["сум"]

результат = []   # dict(ном, парт_спис, парт_прих, кол, сум)
for z in агр.values():
    приходы = трейс(z["ном"], z["парт"], set())
    if not приходы:
        приходы = [z["парт"]]
    for i, прих in enumerate(приходы):
        результат.append({"ном": z["ном"], "спис": z["парт"], "прих": прих,
                          "кол": z["кол"] if i == 0 else 0,
                          "сум": z["сум"] if i == 0 else 0})

print(f"\n=== РЕЗУЛЬТАТ ({len(результат)} строк; пропущено не-товарных Кт-строк: {пропущено}) ===")
сум_кол = 0; сум_сум = 0
for r in sorted(результат, key=lambda x: S(x["ном"])):
    сум_кол += r["кол"]; сум_сум += r["сум"]
    print(f"  Ном={S(r['ном'])[:26]:<26} | Спис={S(r['спис'])[:34]:<34} | "
          f"Прих={S(r['прих'])[:42]:<42} [{full(r['прих']).replace('Документ.','')}] "
          f"| Кол={S(r['кол']):>6} Сум={S(r['сум']):>12}")
print(f"  ИТОГО: Кол={сум_кол}  Сум={сум_сум}")

# --- ПРОВЕРКА терминалов: ни один приход не должен быть Перемещением ---
плохие = [r for r in результат if full(r["прих"]) == ТипПеремещение]
print(f"\nТерминалов-Перемещений (должно быть 0, либо тупики): {len(плохие)}")
for r in плохие:
    print("   ТУПИК:", S(r["ном"]), "->", S(r["спис"]))

# --- ЭТАЛОН: Біта РН 2*50 мм -> Надходження ІБ00-007655 (ПоступлениеТоваровУслуг) ---
print("\n=== ЭТАЛОН ===")
эталон_ок = False
for r in результат:
    if r["ном"] is not None and "Біта РН 2*50" in S(r["ном"]):
        ок = ("ІБ00-007655" in S(r["прих"])) and (full(r["прих"]) == "Документ.ПоступлениеТоваровУслуг")
        print(f"  Біта РН 2*50 -> {S(r['прих'])}  [{full(r['прих'])}]  {'✅' if ок else '❌'}")
        if ок: эталон_ок = True
print("ЭТАЛОН:", "✅ PASS — Біта РН → Надходження ІБ00-007655" if эталон_ок else "❌ FAIL")

# --- доп.проверка ≥2 другие номенклатуры -> терминал не-Перемещение ---
print("\n=== Терминалы по всем номенклатурам (выборка) ===")
видано = {}
for r in результат:
    n = S(r["ном"])
    видано.setdefault(n, set()).add(full(r["прих"]).replace("Документ.", ""))
for n in sorted(видано):
    print(f"   {n[:30]:<30} -> {', '.join(sorted(видано[n]))}")
