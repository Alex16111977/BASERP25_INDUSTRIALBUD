"""Pre-test SQL: проверить наш будущий BSL-запрос для ВТ ПАП_РКО_ВКассу_Замена.

Симулируем: на вход — Регистратор (РКО N0000052986).
Запрос должен дать 24 строки (12 Приход ОТ + 12 Расход ДенСр) per СтрПредпр.
Σ signed per (Орг, Подр) = 0.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Найти РКО
q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ Д.Ссылка КАК Сс ИЗ Документ.РасходныйКассовыйОрдер КАК Д ГДЕ Д.Номер = &Ном"
q.SetParameter("Ном", "N0000052986")
ref = q.Execute().Выгрузить()[0].Сс
print(f"РКО: {ref}")

# Прогнать наш SQL для ВТ ПАП_РКО_ВКассу_Замена напрямую (без ВТ КонтрольБаланса)
# Используем массив &Регистраторы вместо ВТ ПАП_РКО_ВКассу_Регистраторы
МассивРег = erp.NewObject("Массив")
МассивРег.Добавить(ref)

q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    РКО.Ссылка КАК Регистратор,
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) КАК ВидДвижения,
    РКО.Дата КАК Период,
    РКО.Организация КАК Организация,
    Рш.Подразделение.А_Подразделение КАК Подразделение,
    Рш.НаправлениеДеятельности КАК НаправлениеДеятельности,
    ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОплатаТруда) КАК Статья,
    НЕОПРЕДЕЛЕНО КАК Аналитика,
    ВЫРАЗИТЬ(СУММА(Рш.КВыплате) КАК ЧИСЛО(31, 2)) КАК Сумма,
    ЗНАЧЕНИЕ(Перечисление.ВидыИсточниковДвижений.ДвиженияБаланса) КАК ВидИсточника,
    ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПрочиеАктивыПассивы) КАК Источник,
    ЛОЖЬ КАК РасчетСебестоимости,
    РКО.Ссылка КАК ДокументДвижения
ИЗ
    Документ.РасходныйКассовыйОрдер КАК РКО
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = РКО.Ведомость
ГДЕ
    РКО.Ссылка В (&Регистраторы)
СГРУППИРОВАТЬ ПО
    РКО.Ссылка,
    РКО.Дата,
    РКО.Организация,
    Рш.Подразделение.А_Подразделение,
    Рш.НаправлениеДеятельности

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
    РКО.Ссылка,
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход),
    РКО.Дата,
    РКО.Организация,
    Рш.Подразделение.А_Подразделение,
    Рш.НаправлениеДеятельности,
    ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ДенежныеСредстваНаличные),
    РКО.Касса,
    ВЫРАЗИТЬ(СУММА(Рш.КВыплате) КАК ЧИСЛО(31, 2)),
    ЗНАЧЕНИЕ(Перечисление.ВидыИсточниковДвижений.ДвиженияБаланса),
    ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПрочиеАктивыПассивы),
    ЛОЖЬ,
    РКО.Ссылка
ИЗ
    Документ.РасходныйКассовыйОрдер КАК РКО
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = РКО.Ведомость
ГДЕ
    РКО.Ссылка В (&Регистраторы)
СГРУППИРОВАТЬ ПО
    РКО.Ссылка,
    РКО.Дата,
    РКО.Организация,
    Рш.Подразделение.А_Подразделение,
    Рш.НаправлениеДеятельности,
    РКО.Касса

УПОРЯДОЧИТЬ ПО
    Подразделение, ВидДвижения
"""
q2.SetParameter("Регистраторы", МассивРег)
try:
    rows = q2.Execute().Выгрузить()
    print(f"\nПолучено строк: {rows.Количество()}")
    for r in rows:
        print(f"  {erp.XMLСтрока(r.ВидДвижения):<7} {S(r.Подразделение):<30} {S(r.Статья):<35} {float(r.Сумма):>12,.2f}")
    assert rows.Количество() == 24, f"Ожидаем 24 строки, получили {rows.Количество()}"
    # Σ signed per (Подр) = 0
    by_podr = {}
    for r in rows:
        p = S(r.Подразделение)
        delta = float(r.Сумма) if erp.XMLСтрока(r.ВидДвижения) == "Receipt" else -float(r.Сумма)
        by_podr[p] = by_podr.get(p, 0) + delta
    bad = {k: v for k, v in by_podr.items() if abs(v) > 0.01}
    assert not bad, f"FAIL: per Подр баланс != 0: {bad}"
    print(f"\n✅ 24 строки, Σ signed per Подр = 0 для всех {len(by_podr)} СтрПредпр")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")
    raise
