# -*- coding: utf-8 -*-
"""Аудит задвоений в Справочник.А_Статьи_PL (ТЧ Статьи), только чтение.

Секции:
  A. СтатьяРасходов, стоящая в ТЧ двух и более PL-статей (+ обороты ПрочиеРасходы за 12 мес).
  B. ДДС, стоящая в ТЧ двух и более PL-статей (shared-ДДС по правилу 4).
  C. Строки ТЧ с пустой СтатьяРасходов (у ДДС не заполнен А_СтатьяРасходов).
  D. Повтор одной СтатьяРасходов внутри одной PL-статьи (информационно: несколько ДДС → одна статья).
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String


def query(text, params=None):
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, v in (params or {}).items():
        q.SetParameter(k, v)
    return q.Execute().Выгрузить()


now = datetime.datetime.now()
НП = datetime.datetime(now.year - 1, now.month, 1, 3, 0, 0)
КП = query("ВЫБРАТЬ КОНЕЦПЕРИОДА(&Д, МЕСЯЦ) КАК Д",
           {"Д": datetime.datetime(now.year, now.month, 1, 3, 0, 0)}).Получить(0).Д
print(f"Окно оборотов ПрочиеРасходы: {НП:%d.%m.%Y} — {КП}")

# ---------------- A. СтатьяРасходов в ≥2 PL ----------------
print("\n=== A. СтатьяРасходов в двух и более PL-статьях ===")
rA = query("""
ВЫБРАТЬ
    Дуб.СтатьяРасходов КАК СтатьяРасходов,
    Дуб.ЧислоPL КАК ЧислоPL,
    ЕСТЬNULL(Об.Сумма, 0) КАК Сумма12м
ИЗ
    (ВЫБРАТЬ Т.СтатьяРасходов КАК СтатьяРасходов, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Ссылка) КАК ЧислоPL
     ИЗ Справочник.А_Статьи_PL.Статьи КАК Т
     ГДЕ НЕ Т.Ссылка.ПометкаУдаления
       И Т.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
     СГРУППИРОВАТЬ ПО Т.СтатьяРасходов
     ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Ссылка) > 1) КАК Дуб
    ЛЕВОЕ СОЕДИНЕНИЕ
    (ВЫБРАТЬ О.СтатьяРасходов КАК СтатьяРасходов, СУММА(О.СуммаРеглПриход) КАК Сумма
     ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(&НП, &КП, , ) КАК О
     СГРУППИРОВАТЬ ПО О.СтатьяРасходов) КАК Об
    ПО Дуб.СтатьяРасходов = Об.СтатьяРасходов
УПОРЯДОЧИТЬ ПО Сумма12м УБЫВ
""", {"НП": НП, "КП": КП})
detail = query("""
ВЫБРАТЬ
    ТЧ.СтатьяРасходов КАК СтатьяРасходов,
    ТЧ.Ссылка.Код КАК КодPL,
    ТЧ.Ссылка КАК PL,
    ТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
    И ТЧ.СтатьяРасходов В
        (ВЫБРАТЬ Т.СтатьяРасходов ИЗ Справочник.А_Статьи_PL.Статьи КАК Т
         ГДЕ НЕ Т.Ссылка.ПометкаУдаления
           И Т.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
         СГРУППИРОВАТЬ ПО Т.СтатьяРасходов
         ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Ссылка) > 1)
УПОРЯДОЧИТЬ ПО СтатьяРасходов, КодPL
""")
blocked_pl = set()
for i in range(rA.Количество()):
    row = rA.Получить(i)
    sr = S(row.СтатьяРасходов)
    print(f"\n[{sr}] PL={row.ЧислоPL}  обороты 12м={float(row.Сумма12м):,.2f} ₴  "
          f"→ {'БЛОКИРУЕТ запись (правило 5)' if float(row.Сумма12м) > 0 else 'shared без оборотов, разрешено'}")
    for j in range(detail.Количество()):
        d = detail.Получить(j)
        if S(d.СтатьяРасходов) == sr:
            print(f"    {S(d.КодPL)} {S(d.PL)}  ← ДДС: {S(d.ДДС)}")
            if float(row.Сумма12м) > 0:
                blocked_pl.add((S(d.КодPL), S(d.PL)))
print(f"\nИтого статей расходов с задвоением: {rA.Количество()}; "
      f"PL-статей, которые не запишутся по правилу 5: {len(blocked_pl)}")
for code, name in sorted(blocked_pl):
    print(f"    {code} {name}")

# ---------------- B. ДДС в ≥2 PL ----------------
print("\n=== B. ДДС в двух и более PL-статьях (shared по правилу 4) ===")
rB = query("""
ВЫБРАТЬ
    ТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС,
    ТЧ.Ссылка.Код КАК КодPL,
    ТЧ.Ссылка КАК PL
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
    И ТЧ.СтатьяДвиженияДенежныхСредств В
        (ВЫБРАТЬ Т.СтатьяДвиженияДенежныхСредств ИЗ Справочник.А_Статьи_PL.Статьи КАК Т
         ГДЕ НЕ Т.Ссылка.ПометкаУдаления
         СГРУППИРОВАТЬ ПО Т.СтатьяДвиженияДенежныхСредств
         ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Ссылка) > 1)
УПОРЯДОЧИТЬ ПО ДДС, КодPL
""")
if rB.Количество() == 0:
    print("Нет: каждая ДДС стоит ровно в одной PL-статье.")
for i in range(rB.Количество()):
    row = rB.Получить(i)
    print(f"    {S(row.ДДС)}  → {S(row.КодPL)} {S(row.PL)}")

# ---------------- C. Пустая СтатьяРасходов ----------------
print("\n=== C. Строки ТЧ с пустой СтатьяРасходов ===")
rC = query("""
ВЫБРАТЬ
    ТЧ.Ссылка.Код КАК КодPL,
    ТЧ.Ссылка КАК PL,
    ТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС,
    ТЧ.СтатьяДвиженияДенежныхСредств.А_СтатьяРасходов КАК СРуДДС
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
    И ТЧ.СтатьяРасходов = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
УПОРЯДОЧИТЬ ПО КодPL
""")
if rC.Количество() == 0:
    print("Нет.")
for i in range(rC.Количество()):
    row = rC.Получить(i)
    print(f"    {S(row.КодPL)} {S(row.PL)}  ← ДДС: {S(row.ДДС)}  (А_СтатьяРасходов у ДДС: '{S(row.СРуДДС)}')")

# ---------------- D. Повтор СтатьяРасходов внутри одной PL ----------------
print("\n=== D. Одна СтатьяРасходов несколько раз внутри одной PL (информационно) ===")
rD = query("""
ВЫБРАТЬ
    ТЧ.Ссылка.Код КАК КодPL,
    ТЧ.Ссылка КАК PL,
    ТЧ.СтатьяРасходов КАК СтатьяРасходов,
    КОЛИЧЕСТВО(*) КАК Строк
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
    И ТЧ.СтатьяРасходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
СГРУППИРОВАТЬ ПО ТЧ.Ссылка.Код, ТЧ.Ссылка, ТЧ.СтатьяРасходов
ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1
УПОРЯДОЧИТЬ ПО КодPL
""")
if rD.Количество() == 0:
    print("Нет.")
for i in range(rD.Количество()):
    row = rD.Получить(i)
    print(f"    {S(row.КодPL)} {S(row.PL)}: {S(row.СтатьяРасходов)} × {row.Строк}")

# ---------------- Сводка ----------------
tot = query("""
ВЫБРАТЬ
    КОЛИЧЕСТВО(*) КАК Строк,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ТЧ.Ссылка) КАК PL,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ТЧ.СтатьяДвиженияДенежныхСредств) КАК ДДС,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ТЧ.СтатьяРасходов) КАК СР
ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
""").Получить(0)
print(f"\nСводка ТЧ: строк={tot.Строк}, PL-статей с ТЧ={tot.PL}, различных ДДС={tot.ДДС}, различных СтатьяРасходов={tot.СР}")
