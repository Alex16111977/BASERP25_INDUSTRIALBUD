# -*- coding: utf-8 -*-
"""Провести декабрьский А_ФинРез_Баланс/ТОВ свежей COM-сессией (текущий конфиг
сервера). Без Удалить — get существующий непомеченный декабрьский, перепровести.
Печать: успех + статистика РС по Регистратору, либо точная ошибка платформы."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client
from datetime import datetime

conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

qO = conn.NewObject("Запрос")
qO.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации '
            'ГДЕ КодПоЕДРПОУ = "40645273"')
sO = qO.Выполнить().Выбрать(); sO.Следующий(); ORG = sO.С

qD = conn.NewObject("Запрос")
qD.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С, Номер КАК Н
ИЗ Документ.А_ФинРез_Баланс
ГДЕ Организация=&Орг И НЕ ПометкаУдаления
    И Месяц >= &Н1 И Месяц <= &Н2 И ВключатьДочерние = ЛОЖЬ
УПОРЯДОЧИТЬ ПО Дата"""
qD.УстановитьПараметр("Орг", ORG)
qD.УстановитьПараметр("Н1", datetime(2025,12,1,0,0,0))
qD.УстановитьПараметр("Н2", datetime(2025,12,31,23,59,59))
rD = qD.Выполнить().Выбрать()
if not rD.Следующий():
    print("FAIL: декабрьский документ не найден"); sys.exit(1)
ref = rD.С
print(f"Документ: №{rD.Н} ref={conn.XMLСтрока(ref)}")

об = ref.ПолучитьОбъект()
об.Дата = datetime(2025,12,31,14,0,0)
РежПров = conn.PredefinedValue("РежимЗаписиДокумента.Проведение")
try:
    об.Записать(РежПров)
    print(f"[OK] Проведено. Проведен={об.Проведен}")
except Exception as e:
    msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
    print(f"[FAIL] {msg}")
    sys.exit(2)

# статистика РС по этому регистратору
q = conn.NewObject("Запрос")
q.Текст = """ВЫБРАТЬ
    КОЛИЧЕСТВО(*) КАК Всего,
    СУММА(ВЫБОР КОГДА Расхождение ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Плугов,
    СУММА(СуммаКонечныйОстаток) КАК СуммаКО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод ГДЕ Регистратор=&Д"""
q.УстановитьПараметр("Д", ref)
r = q.Выполнить().Выбрать(); r.Следующий()
print(f"РС движений: всего={r.Всего} плугов={r.Плугов} ΣКО={float(r.СуммаКО or 0):,.2f}")

# по Source
q2 = conn.NewObject("Запрос")
q2.Текст = """ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Source) КАК С, КОЛИЧЕСТВО(*) КАК К,
    СУММА(СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод ГДЕ Регистратор=&Д
СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Source)"""
q2.УстановитьПараметр("Д", ref)
t2 = q2.Выполнить().Выгрузить()
print("по Source:")
for i in range(t2.Количество()):
    rr = t2.Получить(i)
    print(f"  {str(rr.С)[:40]:40} строк={rr.К:6} КО={float(rr.КО or 0):,.2f}")
print("=" * 60)
