# -*- coding: utf-8 -*-
"""
Диагностика: какие предопределённые счета есть и какие субконто у них
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONNECTION_STRING = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected")

    # 1. Найти предопределённые счета с субконто "Номенклатура"
    print("\n=== Счета с субконто Номенклатура ===")
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ\n"
        "  ВС.Ссылка.Код КАК КодСчета,\n"
        "  ВС.Ссылка.Наименование КАК НаименованиеСчета,\n"
        "  ВС.Ссылка.ИмяПредопределенныхДанных КАК ИмяПредопр,\n"
        "  ВС.НомерСтроки КАК НомерСтроки,\n"
        "  ВС.ВидСубконто КАК ВидСубконто\n"
        "ИЗ\n"
        "  ПланСчетов.Хозрасчетный.ВидыСубконто КАК ВС\n"
        "ГДЕ\n"
        "  ВС.ВидСубконто = ЗНАЧЕНИЕ(ПланВидовХарактеристик.ВидыСубконтоХозрасчетные.Номенклатура)\n"
        "  И (ВС.Ссылка.Код ПОДОБНО \"20%\"\n"
        "    ИЛИ ВС.Ссылка.Код ПОДОБНО \"22%\"\n"
        "    ИЛИ ВС.Ссылка.Код ПОДОБНО \"26%\"\n"
        "    ИЛИ ВС.Ссылка.Код ПОДОБНО \"28%\"\n"
        "    ИЛИ ВС.Ссылка.Код ПОДОБНО \"15%\"\n"
        "    ИЛИ ВС.Ссылка.Код ПОДОБНО \"23%\")"
    )
    r = q.Выполнить().Выбрать()
    while r.Следующий():
        print(f"  Рах.{r.КодСчета} ({r.НаименованиеСчета}) Предопр={r.ИмяПредопр} Поз={r.НомерСтроки}")

    # 2. Проверить конкретные предопределённые имена
    print("\n=== Проверка предопределённых имён ===")
    for name in ["Товары", "Товари", "ПроизводственныеЗапасы", "Сировина",
                  "ГотоваяПродукция", "МалоценныеИБыстроизнашивающиесяПредметы",
                  "МШП", "НЗВ", "Виробництво",
                  "ПриобретениеДругихНеоборотныхМатериальныхАктивов"]:
        q2 = conn.NewObject("Запрос")
        q2.Текст = (
            f"ВЫБРАТЬ Код, Наименование ИЗ ПланСчетов.Хозрасчетный\n"
            f"ГДЕ ИмяПредопределенныхДанных = \"{name}\""
        )
        try:
            r2 = q2.Выполнить().Выбрать()
            if r2.Следующий():
                print(f"  {name} -> {r2.Код} {r2.Наименование}")
            else:
                print(f"  {name} -> НЕ НАЙДЕН!")
        except Exception as e:
            print(f"  {name} -> ОШИБКА: {str(e)[:100]}")

    conn = None
    pythoncom.CoUninitialize()
    print("\n[OK] Done")

if __name__ == "__main__":
    main()
