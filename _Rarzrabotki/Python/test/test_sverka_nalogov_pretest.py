# -*- coding: utf-8 -*-
# Rule #-1 pre-тест отчёта А_СравнитьОстаткиНалоговЕРПсBASБухгалтерия.
# Повторяет ДВА запроса отчёта 1:1:
#   ЕРП  : РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты, Статья=Налоги, Орг(ЕДРПОУ)×Аналитика(ТипыНалогов), НДФЛ-схлопывание
#   BuhBud: РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты, счета 64x/65x, Орг(ЕДРПОУ)×Счёт.Код → ТипНалога
# Знак: пассив=плюс. ЕРП ПАП Приход−Расход (КонечныйОстаток уже пассив-плюс). BuhBud Кт−Дт.
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

НП = datetime.datetime(2025, 12, 1, 0, 0, 0)
КП = datetime.datetime(2025, 12, 31, 23, 59, 59)
print(f"Период: {НП} .. {КП}\n")

def fail(prefix, e):
    info = getattr(e, 'excepinfo', None)
    print(f"FAIL {prefix}:", info[2] if info else e)
    sys.exit(1)

# ============ 0. Перечисление ТипыНалогов: значения + НДФЛ-подвиды ============
qen = erp.NewObject("Запрос")
qen.Text = "ВЫБРАТЬ Перечисление.Ссылка КАК Ссылка ИЗ Перечисление.ТипыНалогов КАК Перечисление"
vals = [s.Ссылка for s in qen.Execute().Выгрузить()]
names = [erp.XMLСтрока(v) for v in vals]
ndfl_names = [n for n in names if n.upper().startswith("НДФЛ") or n.upper().startswith("НФДЛ")]
ndfl_refs = [v for v, n in zip(vals, names) if n in ndfl_names]
print("ТипыНалогов (все):", names)
print("НДФЛ-подвиды (схлопнутся в НДФЛ):", ndfl_names)
print("ДругиеНалоги есть:", "ДругиеНалоги" in names)
print("НДФЛ (базовое) есть:", "НДФЛ" in names)
print()

масНДФЛ = erp.NewObject("Массив")
for r in ndfl_refs:
    масНДФЛ.Добавить(r)

# ============ 1. ЕДРПОУ организаций «в балансе» (ERP-side, А_ВБалансе) ============
qo = erp.NewObject("Запрос")
qo.Text = ('ВЫБРАТЬ Орг.КодПоЕДРПОУ КАК ЕДРПОУ, Орг.Наименование КАК Наим '
           'ИЗ Справочник.Организации КАК Орг ГДЕ Орг.А_ВБалансе И Орг.КодПоЕДРПОУ <> ""')
edrpou, orgname = [], {}
for s in qo.Execute().Выгрузить():
    edrpou.append(s.ЕДРПОУ); orgname[s.ЕДРПОУ] = s.Наим
print("ЕДРПОУ в балансе:", [(e, orgname[e][:24]) for e in edrpou], "\n")

масЕДРПОУ_erp = erp.NewObject("Массив")
for e in edrpou: масЕДРПОУ_erp.Добавить(e)
масЕДРПОУ_buh = buh.NewObject("Массив")
for e in edrpou: масЕДРПОУ_buh.Добавить(e)

# ============ 2. ЕРП: ПАП «Налоги» ОстаткиИОбороты (Орг × ТипыНалогов, НДФЛ collapse) ============
qp = erp.NewObject("Запрос")
qp.SetParameter("НП", НП); qp.SetParameter("КП", КП)
qp.SetParameter("Список", масЕДРПОУ_erp); qp.SetParameter("СписокНДФЛ", масНДФЛ)
qp.Text = """
ВЫБРАТЬ
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    ВЫБОР КОГДА ВЫРАЗИТЬ(Ост.Аналитика КАК Перечисление.ТипыНалогов) В (&СписокНДФЛ)
         ТОГДА ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.НДФЛ)
         ИНАЧЕ ВЫРАЗИТЬ(Ост.Аналитика КАК Перечисление.ТипыНалогов) КОНЕЦ КАК ВидНалога,
    СУММА(Ост.СуммаНачальныйОстаток) КАК НачОст,
    СУММА(Ост.СуммаПриход)           КАК Приход,
    СУММА(Ост.СуммаРасход)           КАК Расход,
    СУММА(Ост.СуммаКонечныйОстаток)  КАК КонОст
ИЗ
    РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&НП, &КП, , ,
        Статья = ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.Налоги)) КАК Ост
ГДЕ
    Ост.Организация.КодПоЕДРПОУ В (&Список)
СГРУППИРОВАТЬ ПО
    Ост.Организация.КодПоЕДРПОУ,
    ВЫБОР КОГДА ВЫРАЗИТЬ(Ост.Аналитика КАК Перечисление.ТипыНалогов) В (&СписокНДФЛ)
         ТОГДА ЗНАЧЕНИЕ(Перечисление.ТипыНалогов.НДФЛ)
         ИНАЧЕ ВЫРАЗИТЬ(Ост.Аналитика КАК Перечисление.ТипыНалогов) КОНЕЦ
"""
erp_data = {}
try:
    for s in qp.Execute().Выгрузить():
        vn = erp.XMLСтрока(s.ВидНалога) if s.ВидНалога else "(пусто)"
        erp_data[(s.ЕДРПОУ, vn)] = {"НачОст": float(s.НачОст), "Приход": float(s.Приход),
                                     "Расход": float(s.Расход), "КонОст": float(s.КонОст)}
except Exception as e:
    fail("ЕРП ПАП", e)
print("ЕРП ПАП строк (Орг×ВидНалога):", len(erp_data))

# ============ 3. BuhBud: Хозрасчетный ОстаткиИОбороты (Орг × Счёт.Код → ТипНалога) ============
МАП = {"6411": "НДФЛ", "642": "ВоенныйСбор", "651": "НачисленныйЕСВ", "6412": "НДС",
       "6413": "НалогНаПрибыль", "6414": "ЕдиныйНалог", "6415": "ДругиеНалоги", "6417": "ДругиеНалоги"}
масСчета = buh.NewObject("Массив")
for c in ["6411", "6412", "6413", "6414", "6415", "6417", "642", "651"]:
    масСчета.Добавить(c)
qb = buh.NewObject("Запрос")
qb.SetParameter("НП", НП); qb.SetParameter("КП", КП)
qb.SetParameter("Список", масЕДРПОУ_buh); qb.SetParameter("Счета", масСчета)
qb.Text = """
ВЫБРАТЬ
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    Ост.Счет.Код КАК КодСчета,
    СУММА(Ост.СуммаНачальныйОстатокКт - Ост.СуммаНачальныйОстатокДт) КАК НачОст,
    СУММА(Ост.СуммаОборотКт) КАК Приход,
    СУММА(Ост.СуммаОборотДт) КАК Расход,
    СУММА(Ост.СуммаКонечныйОстатокКт - Ост.СуммаКонечныйОстатокДт) КАК КонОст
ИЗ
    РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&НП, &КП, , , Счет.Код В (&Счета), , ) КАК Ост
ГДЕ
    Ост.Организация.КодПоЕДРПОУ В (&Список)
СГРУППИРОВАТЬ ПО
    Ост.Организация.КодПоЕДРПОУ, Ост.Счет.Код
"""
buh_data, buh_by_acc = {}, {}
try:
    for s in qb.Execute().Выгрузить():
        код = str(s.КодСчета).strip()
        vn = МАП.get(код, "ДругиеНалоги")
        d = buh_data.setdefault((s.ЕДРПОУ, vn), {"НачОст": 0.0, "Приход": 0.0, "Расход": 0.0, "КонОст": 0.0})
        d["НачОст"] += float(s.НачОст); d["Приход"] += float(s.Приход)
        d["Расход"] += float(s.Расход); d["КонОст"] += float(s.КонОст)
        buh_by_acc[(s.ЕДРПОУ, код)] = buh_by_acc.get((s.ЕДРПОУ, код), 0.0) + float(s.КонОст)
except Exception as e:
    fail("BuhBud Хозрасчетный", e)
print("BuhBud строк (Орг×ВидНалога, после маппинга):", len(buh_data), "\n")

# ============ 4. Merge (ЕДРПОУ × ВидНалога), КонечныйОстаток ============
keys = sorted(set(list(erp_data) + list(buh_data)))
print("=== СВЕРКА КонечныйОстаток на 31.12.2025 (пассив=плюс), Разница=ЕРП−Бух ===")
print(f"{'ЕДРПОУ':11} {'ВидНалога':16} {'КонОст_ЕРП':>16} {'КонОст_Бух':>16} {'Разница':>15}")
tE = tB = 0.0
for k in keys:
    e = erp_data.get(k, {}).get("КонОст", 0.0)
    b = buh_data.get(k, {}).get("КонОст", 0.0)
    tE += e; tB += b
    fl = "" if abs(e - b) < 0.01 else "  <-"
    print(f"{k[0]:11} {k[1]:16} {e:>16,.2f} {b:>16,.2f} {e-b:>15,.2f}{fl}")
print(f"{'ИТОГО':11} {'':16} {tE:>16,.2f} {tB:>16,.2f} {tE-tB:>15,.2f}\n")

# ============ 5. Сверка с эталонными числами промта (ЕРП ПАП 40645273) ============
эталон_erp = {"НДС": 6668531.29, "НалогНаПрибыль": 1641963.16, "НачисленныйЕСВ": 643405.44,
              "НДФЛ": 540199.99, "ВоенныйСбор": 152888.54, "ДругиеНалоги": -232453.95}
print("=== Проверка ЕРП ПАП 40645273 vs эталон промта ===")
ok = True
for vn, exp in эталон_erp.items():
    got = erp_data.get(("40645273", vn), {}).get("КонОст", 0.0)
    match = abs(got - exp) < 0.01
    ok = ok and match
    print(f"  {vn:16} эталон={exp:>15,.2f}  факт={got:>15,.2f}  {'OK' if match else 'DIFF'}")
got_nds_buh = buh_by_acc.get(("40645273", "6412"), 0.0)
print(f"  BuhBud 40645273 6412(НДС) эталон=   5,244,774.70  факт={got_nds_buh:>15,.2f}  "
      f"{'OK' if abs(got_nds_buh-5244774.70)<0.01 else 'DIFF'}")
print(f"\nВсе 3 орг присутствуют: {sorted(set(k[0] for k in keys)) }")
print("ИТОГ ЕРП-эталон:", "PASS" if ok else "ЕСТЬ РАСХОЖДЕНИЯ (см. выше)")
