def прочитать(ref):
    qr = conn.NewObject("Запрос")
    qr.Текст = """ВЫБРАТЬ
		Организация КАК Орг,
		ЕСТЬNULL(Подразделение, ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка)) КАК Подр,
		Статья КАК Ст, ПРЕДСТАВЛЕНИЕ(Статья) КАК СтП, Source КАК Src,
		Расхождение КАК Рх, ДенежныеСредства КАК ДС, ФизическоеЛицо КАК ФЛ,
		Номенклатура КАК Ном, Склад КАК Скл, ДокументДвижения КАК ДД,
		СуммаНачальныйОстаток КАК НО, СуммаПриход КАК Пр,
		СуммаРасход КАК Рс, СуммаКонечныйОстаток КАК КО
	ИЗ РегистрСведений.А_ОтчетБаланс_Свод
	ГДЕ Регистратор=&Д И Source В (&Ист)"""
    qr.УстановитьПараметр("Д", ref); qr.УстановитьПараметр("Ист", МассивИст)
    t = qr.Выполнить().Выгрузить()
    свод = {}; дс = фл = подотч_дет = плугов = докзап = всего = 0
    плуг_кпс = set(); дет_ключи = Counter()
    плуг_ошибок = подотч_ошибок = безналнал_ошибок = 0
    for i in range(t.Количество()):
        r = t.Получить(i); всего += 1
        орг = conn.XMLСтрока(r.Орг)
        подр = conn.XMLСтрока(r.Подр) if conn.ЗначениеЗаполнено(r.Подр) else "∅"
        ст = conn.XMLСтрока(r.Ст)
        d = свод.setdefault((орг, подр, ст), [0.0, 0.0, 0.0, 0.0, str(r.СтП)])
        d[0] += float(r.НО or 0); d[1] += float(r.Пр or 0)
        d[2] += float(r.Рс or 0); d[3] += float(r.КО or 0)
        if conn.ЗначениеЗаполнено(r.ДД):
            докзап += 1
        дс_зап = conn.ЗначениеЗаполнено(r.ДС)
        фл_зап = conn.ЗначениеЗаполнено(r.ФЛ)
        подотч = conn.XMLСтрока(r.Src) == conn.XMLСтрока(ИстПодотч)
        if bool(r.Рх):
            плугов += 1; плуг_кпс.add((орг, подр, ст))
            if (дс_зап or фл_зап or conn.ЗначениеЗаполнено(r.Ном)
                    or conn.ЗначениеЗаполнено(r.Скл)):
                плуг_ошибок += 1
        else:
            if подотч:
                подотч_дет += 1
                if фл_зап:
                    фл += 1
                if (not фл_зап) or дс_зап:
                    подотч_ошибок += 1
                субк = conn.XMLСтрока(r.ФЛ) if фл_зап else "∅"
            else:
                if дс_зап:
                    дс += 1
                if (not дс_зап) or фл_зап:
                    безналнал_ошибок += 1
                субк = conn.XMLСтрока(r.ДС) if дс_зап else "∅"
            дет_ключи[(орг, подр, ст, conn.XMLСтрока(r.Src), субк)] += 1
    дубл_дет = sum(1 for c in дет_ключи.values() if c > 1)
    return (свод, дс, фл, подотч_дет, плугов, докзап, всего, плуг_кпс,
            дубл_дет, плуг_ошибок, подотч_ошибок, безналнал_ошибок)


