def проверить(имя, факт, ожид, допуск=0):
    числа = isinstance(ожид, (int, float)) and isinstance(факт, (int, float))
    ок = abs(факт - ожид) <= допуск if числа else факт == ожид
    print(f"  [{'OK  ' if ок else 'FAIL'}] {имя}: {факт!r}" + ("" if ок else f"  (очікували {ожид!r})"))
    if not ок:
        провалов.append(имя)


def текст(тд, r, c):
    return (тд.Область(r, c, r, c).Текст or "").strip()


def число(з):
    s = (з or "").strip().replace("\xa0", "").replace(" ", "").replace(",", ".")
    try:
        return float(s)
    except ValueError:
        return None


