def шапка_и_подписи(тд, имя_акта, колонок):
    """Спільні перевірки обох Актів."""
    H = тд.ВысотаТаблицы
    весь = " | ".join(текст(тд, r, 1) for r in range(1, H + 1))
    проверить(f"{имя_акта}: ширина", тд.ШиринаТаблицы, колонок)
    проверить(f"{имя_акта}: шапка «Склади:»", "Склади:" in весь, True)
    проверить(f"{имя_акта}: шапка «Документ:»", "Документ: Розрахунок комплектацій" in весь, True)
    проверить(f"{имя_акта}: підпис Відповідальний", "Відповідальний:" in весь, True)
    проверить(f"{имя_акта}: ПІБ відповідального", S(об.Ответственный) in весь, True)
    for прибрано in ("Голова комісії", "Член комісії", "МВО:"):
        проверить(f"{имя_акта}: прибрано «{прибрано}»", прибрано in весь, False)
    return H, весь


def строка_заголовков(тд, ожидаемые):
    """Знаходить рядок шапки таблиці й звіряє назви колонок."""
    for r in range(1, min(тд.ВысотаТаблицы, 30) + 1):
        if текст(тд, r, 1) == "№":
            факт = [текст(тд, r, c) for c in range(1, len(ожидаемые) + 1)]
            return r, факт
    return None, []


def эталонный_порядок(пары):
    """Еталонний порядок будує САМА 1С — у неї українська collation.

    Python sorted() сортує за кодами Unicode і кидає «і» (U+0456) в кінець,
    бо вона більша за «я» (U+044F). У 1С правильно: ...З, И, І, Ї, Й, К...
    Тому порівнюємо з тим, що дає ТаблицаЗначений.Сортировать, а не з Python.
    """
    тз = buh.NewObject("ТаблицаЗначений")
    тз.Колонки.Добавить("Эталон")
    тз.Колонки.Добавить("Номенклатура")
    for э, н in пары:
        нс = тз.Добавить()
        нс.Эталон = э
        нс.Номенклатура = н
    тз.Сортировать("Эталон, Номенклатура")
    return [(S(тз.Получить(i).Эталон), S(тз.Получить(i).Номенклатура))
            for i in range(тз.Количество())]


def проверить_сортировку(тд, р_шапки, р_итог, имя_акта):
    """Рядки мають іти за «Загальна назва, потім Номенклатура» (колонки 2 і 3)."""
    пары = []
    for r in range(р_шапки + 1, р_итог):
        if текст(тд, r, 3):
            пары.append((текст(тд, r, 2), текст(тд, r, 3)))
    ожид = эталонный_порядок(пары)
    ок = (пары == ожид)
    проверить(f"{имя_акта}: сортування «Загальна назва + Номенклатура»", ок, True)
    if пары and not ок:
        for i, (ф, о) in enumerate(zip(пары, ожид), 1):
            if ф != о:
                print(f"    рядок {i}: факт {ф}  очікували {о}")
                break
    return пары


