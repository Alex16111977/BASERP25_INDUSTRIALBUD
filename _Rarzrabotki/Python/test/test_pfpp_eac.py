if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
def f(x): return float(x) if x is not None else 0.0
ERF = os.environ.get("PFPP_ERF") or os.path.join(os.environ["TEMP"], "pfpp_eac.erf")
