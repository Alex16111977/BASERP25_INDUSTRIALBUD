def период(кон=None):
    п = erp.NewObject("СтандартныйПериод")
    if кон is not None: п.ДатаОкончания = кон
    return п

тз = отчет.ПолучитьДанные(период(), сс.Ссылка)
cols=[c.Имя for c in тз.Колонки]
need=["ПланНаФактГрн","ПрогнозГрн","ОтклонениеПрогнозГрн","ПроцентПрогнозГрн"]
пл=фг=пнф=0.0
for i in range(тз.Количество()):
    r=тз.Получить(i)
    if r.Блок=="2. Материалы":
        пл+=f(r.ПланГрн); фг+=f(r.ФактГрн); пнф+=f(r.ПланНаФактГрн)
прог=фг+пнф
print(f"EAC-колонки: {all(n in cols for n in need)}")
print(f"Матеріали: План={пл:.2f} Факт={фг:.2f} ПланНаФакт(ETC)={пнф:.2f} Прогноз(EAC)={прог:.2f} Вик={100*прог/пл:.1f}%")

def фактчас(п):
    t=отчет.ПолучитьДанные(п, сс.Ссылка); s=0.0
    for i in range(t.Количество()):
        r=t.Получить(i)
        if r.Блок=="1. Труд": s+=f(r.ФактЧасы)
    return s
