def инвариант_план_на_факт(erp_, тз, метка):
    """Независимый пересчёт ПНФ по правилам методологии из строк ТЗ и сверка 1:1 с отчётом."""
    S = erp_.String
    группы = defaultdict(lambda: {"ПланКол": 0.0, "ФактКол": 0.0, "ПланГрн": 0.0, "ФактГрн": 0.0, "ПНФ": 0.0})
    for i in range(тз.Количество()):
        r = тз.Получить(i)
        if r.Блок != "2. Матеріали":
            continue
        он_имя = str(S(r.ОбщееНазвание)).strip()
        ключ = ("ОН|" + он_имя) if он_имя else ("НОМ|" + str(S(r.Аналитика.УникальныйИдентификатор())))
        g = группы[ключ]
        g["ПланКол"] += f(r.ПланКол); g["ФактКол"] += f(r.ФактКол)
        g["ПланГрн"] += f(r.ПланГрн); g["ФактГрн"] += f(r.ФактГрн); g["ПНФ"] += f(r.ПланНаФактГрн)
    плохие = []
    for k, g in группы.items():
        if g["ПланГрн"] <= 0:
            эталон = 0.0
        elif g["ПланКол"] <= 0:
            эталон = max(0.0, g["ПланГрн"] - g["ФактГрн"])            # правило 4
        elif g["ФактКол"] <= 0:
            эталон = g["ПланГрн"]                                     # правило 1: ровно план
        else:
            эталон = max(0.0, g["ПланКол"] - g["ФактКол"]) * (g["ПланГрн"] / g["ПланКол"])  # правило 2
        if abs(g["ПНФ"] - эталон) > 0.01:
            плохие.append((k, эталон, g["ПНФ"]))
    print(f"{метка}: групп={len(группы)}, расхождений ПНФ с методологией: {len(плохие)}")
    for k, э, п in плохие[:10]:
        print(f"  BAD {k}: эталон={э:.2f} отчёт={п:.2f}")
    assert not плохие, f"{метка}: ПНФ отчёта разошёлся с методологией"

