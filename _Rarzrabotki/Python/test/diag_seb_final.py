print(f"дублей детали по (Орг,Подр,Ст,Ном,Скл,Src) = "
      f"{sum(1 for c in key_det.values() if c>1)}")
print(f"дублей плуги по (Орг,Подр,Ст) = "
      f"{sum(1 for c in key_plug.values() if c>1)}")
