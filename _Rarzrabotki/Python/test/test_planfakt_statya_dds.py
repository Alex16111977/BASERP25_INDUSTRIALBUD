    def agg(таб):
        рез = {}
        for i in range(таб.Количество()):
            стр = таб.Получить(i)
            ключ = S(стр.Подразделение)
            строки = рез.setdefault(ключ, [0.0, 0.0, 0.0, 0.0])
            строки[0] += float(стр.ПланДоход or 0)
            строки[1] += float(стр.Доход or 0)
            строки[2] += float(стр.ПланРасход or 0)
            строки[3] += float(стр.Расход or 0)
        return рез

    a_old, a_new = agg(старая), agg(новая)
    ok = True
    for ключ in sorted(set(a_old) | set(a_new)):
        o = a_old.get(ключ, [0.0] * 4)
        n = a_new.get(ключ, [0.0] * 4)
        расх = [abs(o[k] - n[k]) for k in range(4)]
        if max(расх) > 0.005:
            ok = False
            print(f"РАСХОЖДЕНИЕ {ключ}: old={o} new={n}")
    print("СВЕРКА:", "OK — агрегаты по подразделениям совпали" if ok else "FAIL")

    # Примеры строк нового запроса со статьями
    print("\nПримеры строк нового запроса (первые 12 с ненулевыми суммами):")
    n = 0
    for i in range(новая.Количество()):
        стр = новая.Получить(i)
        суммы = (float(стр.ПланДоход or 0), float(стр.Доход or 0),
                 float(стр.ПланРасход or 0), float(стр.Расход or 0))
        if not any(суммы):
            continue
        print(f"  {S(стр.Подразделение)[:30]:32} | {S(стр.СтатьяДвиженияДенежныхСредств)[:35]:37} "
              f"| ПД={суммы[0]:>12.2f} Д={суммы[1]:>12.2f} ПР={суммы[2]:>12.2f} Р={суммы[3]:>12.2f}")
        n += 1
        if n >= 12:
            break
    if n == 0:
        print("  (нет строк с ненулевыми суммами за период — расширь период)")


