def тело_re(src, имя):
    m = re.search(r"Функция " + имя + r"\(.*?\nКонецФункции", src, re.S)
    assert m, f"FAIL: не найдена функция {имя}"
    return m.start(), m.end(), m.group(0)


def плоский(тело):
    i = тело.index("Запрос.Текст =")
    j = тело.index('"', i) + 1
    буф = []
    while j < len(тело):
        c = тело[j]
        if c == '"':
            if j + 1 < len(тело) and тело[j + 1] == '"':
                буф.append('"'); j += 2; continue
            break
        буф.append(c); j += 1
    лит = "".join(буф)
    return "\n".join(ln if k == 0 else re.sub(r"^\s*\|", "", ln)
                     for k, ln in enumerate(лит.split("\n")))


def в_bsl(s):
    """плоская форма → BSL-литерал: каждая строка → '\\t|'+строка;
    query-кавычка → '""' (⇒ '""' пустая строка → '""""')."""
    return "\n".join("\t|" + L for L in s.split("\n")).replace('"', '""')


