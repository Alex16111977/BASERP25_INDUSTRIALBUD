# Фаза 7 smoke: звіт «План-факт» через СКД — композиція дає ТабличныйДокумент,
# групування ОбщееНазвание->Номенклатура, план по номенклатурі, % виконання.
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Создания комплектаций для бух учета.epf"
обр = buh.ВнешниеОбработки.Создать(EPF, False)
обр.Период = datetime.datetime(2026, 6, 25)
обр.Спецификация = buh.Справочники.СтруктураСебестоимости.НайтиПоКоду("000000005").Ссылка
выб = buh.Справочники.Склады.Выбрать()
while выб.Следующий():
    н = выб.Наименование
    if "МХП" in н and "ОР" in н and "виробнич" in н:
        обр.СкладыОстатков.Добавить().Склад = выб.Ссылка
выбО = buh.Справочники.Организации.Выбрать()
while выбО.Следующий():
    if "ІНДЕПТ" in выбО.Наименование:
        обр.Организация = выбО.Ссылка
обр.РассчитатьАнализ()
табдок = обр.СформироватьПечатьПланФакт(обр.ТабличнаяЧастьОстатков)
h = табдок.ВысотаТаблицы
w = табдок.ШиринаТаблицы
print(f"ВысотаТаблицы={h} ШиринаТаблицы={w}")
assert h > 0, "СКД дала порожній документ"
# зібрати всі тексти клітинок
тексти = []
for r in range(1, h + 1):
    for c in range(1, w + 1):
        t = табдок.Область(r, c, r, c).Текст
        if t:
            тексти.append(str(t))
весь = " | ".join(тексти).lower()
# заголовки колонок — у верхньому рядку; зберемо текстові (нечислові) клітинки
заголовки = [t for t in тексти[:20] if not t.replace(" ", "").replace(",", "").replace("-", "").isdigit()]
print("ЗАГОЛОВКИ/перші:", " | ".join(заголовки[:12]))
# СКД-звіт: групування Эталон->Номенклатура (h великий, ≥9 колонок), ресурси план+факт
assert h > 10, f"звіт майже порожній (h={h})"
assert w >= 9, f"замало колонок (w={w}) — % або ресурси не вивелись"
need_norma = "норма" in весь            # план (Норма номенкл / Норма сумма номенкл)
need_ost = "остаток" in весь            # факт (Остаток / Сумма остатка)
need_etalon = "профнастил" in весь or "гайка" in весь or "шайба" in весь or "дошка" in весь
need_proc = ("%" in весь) or ("вик" in весь) or ("проц" in весь)  # колонки процентів (число або заголовок)
print(f"є_норма={need_norma} є_факт={need_ost} є_еталон={need_etalon} є_проц(колонка)={need_proc} ширина={w}")
assert need_norma and need_ost and need_etalon, "немає очікуваних колонок/еталонів"
assert need_proc, "колонки процентів (% вик./перевищ.) не вивелись"
print("PASS: СКД групування Эталон->Номенклатура, план+факт+проценти")
