"""Полная картина «Оплата труда» по месяцам: плуг свёртки (без ФизЛица),
ПАП(ОТ) (упр.баланс), штатный РН.ВзаиморасчетыССотрудниками (реальный долг), А_ВзСС (кастом)."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

MONTHS = [("дек2025","ДАТАВРЕМЯ(2025,12,1)","ДАТАВРЕМЯ(2025,12,31,23,59,59)"),
          ("янв2026","ДАТАВРЕМЯ(2026,1,1)","ДАТАВРЕМЯ(2026,1,31,23,59,59)"),
          ("фев2026","ДАТАВРЕМЯ(2026,2,1)","ДАТАВРЕМЯ(2026,2,28,23,59,59)"),
          ("мар2026","ДАТАВРЕМЯ(2026,3,1)","ДАТАВРЕМЯ(2026,3,31,23,59,59)")]

print(f"{'мес':<8} | {'плуг(без ФЛ)':>14} | {'детали(ФЛ)':>14} | {'регистр=ПАП':>14} | {'штатн.ВзСС':>14} | {'А_ВзСС dir':>14}")
for label, nm, end in MONTHS:
    # плуг и детали в регистре свёртки
    q = erp.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ Рег.Расхождение КАК Плуг, СУММА(Рег.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Статья.Наименование = "Оплата труда" И Рег.Регистратор.Месяц = {nm}
    СГРУППИРОВАТЬ ПО Рег.Расхождение"""
    plug = det = 0.0
    for r in q.Выполнить().Выгрузить():
        if r.Плуг: plug = f(r.КО)
        else: det = f(r.КО)
    # штатный ВзаиморасчетыССотрудниками остаток
    q2 = erp.NewObject("Запрос")
    q2.Текст = f"""ВЫБРАТЬ СУММА(Ост.СуммаВзаиморасчетовОстаток) КАК С
    ИЗ РегистрНакопления.ВзаиморасчетыССотрудниками.Остатки({end}) КАК Ост"""
    try: vzs = f(q2.Выполнить().Выгрузить()[0].С)
    except: vzs = 0.0
    # А_ВзСС direct signed cumul
    q3 = erp.NewObject("Запрос")
    q3.Текст = f"""ВЫБРАТЬ СУММА(ВЫБОР КОГДА ВзСС.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА ВзСС.СуммаВзаиморасчетов ИНАЧЕ -ВзСС.СуммаВзаиморасчетов КОНЕЦ) КАК С
    ИЗ РегистрНакопления.А_ВзаиморасчетыССотрудниками КАК ВзСС ГДЕ ВзСС.Период <= {end}"""
    avzs = f(q3.Выполнить().Выгрузить()[0].С)
    print(f"{label:<8} | {plug:>14,.2f} | {det:>14,.2f} | {plug+det:>14,.2f} | {vzs:>14,.2f} | {avzs:>14,.2f}")

print("\nплуг(без ФЛ) — должна быть ~3 165 970,77 константа (начальная задолженность 000Ц-1/2/3, ноябрь 2025)")
print("регистр=ПАП — управленческий баланс (БЕЗ начального долга)")
print("штатн.ВзСС — реальный долг по штатному регистру (с начальным долгом, погашается)")
