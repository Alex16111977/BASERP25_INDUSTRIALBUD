# -*- coding: utf-8 -*-
"""Приёмка «Казна и динамика» на боевых документах (промт ПРОМТ_Казна_и_динамика.md).

Пересчитывает № 1 (07.08) и № 2 (14.08), проверяет чек-лист приёмки:
  - класс А сверки с Excel 14.08: C/D всех 11 позиций совпадают (включая бездвижные
    договоры через «Договоры дополнительно» — модуль создаёт им пустые строки);
  - ТЧ «Казна» № 2: итоги факта, состав строк верхнего уровня, IRC свернут;
  - К12/К13 (смысловая проверка: на № 2 расхождений быть не должно — Кт361 = казна 1:1);
  - «Динаміка» № 2 против № 1 строится, есть новые документы, HTML — как письмо.
С флагом --apply документы ЗАПИСЫВАЮТСЯ; без него — расчёт в памяти.

HTML динамики № 2 сохраняется в Отчеты/Динаміка_14-08-2026.html (в обоих режимах).
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")
ПРИМЕНЯТЬ = "--apply" in sys.argv

ПАПКА_ОТЧЕТОВ = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\notebook"
                 r"\knowledge_А_ФинансовыйОтчетПроизводства\Отчеты")

ЦЕЛЕВЫЕ_C = {
    "МД IRC 2026":            19681200.00,
    "МД ООН 2025":            33485281.78,
    "МД Кернел Кухня":        12178525.57,
    "МД ПРООН Черкаси  ДСНС":  8913680.73,
    "МД Вооз ЕМS Мала 2026":   5192818.40,
    "МК Каменец Цемент":       3032016.00,
    "МК Чорноморськ":           612720.00,
    "МД МХП ОРІЛЬ":            3355204.73,
    "МК Глобино":             10237646.70,
    "МК Кривий ріг":           7961800.00,
}
ЦЕЛЕВЫЕ_D = {"МД Кернел Кухня": 716773.00}

# Казна на 14.08 (текущее состояние базы: затраты-факт включают 6 ПП, проведённых
# 14.08 в 17:20 ПОСЛЕ снятия эталонного xlsx; разница с xlsx = -1 048 446,11 объяснена)
КАЗНА_ПОСТУПЛЕНИЯ_ФАКТ = 3345860.35
КАЗНА_ЗАТРАТЫ_ФАКТ_БАЗА = -5187516.38
КАЗНА_КОНТРОЛЬ_СТРОК = {
    "МК Кривий ріг": 1637071.10,
    "МД ПРООН Черкаси  ДСНС": 1317348.70,
    "МД МХП ОРІЛЬ": 391440.55,
}

провалов = 0


def проверка(условие, текст):
    global провалов
    if условие:
        print(f"  ✓ {текст}")
    else:
        провалов += 1
        print(f"  ✗ {текст}")


buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

q = buh.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ Д.Ссылка КАК С, Д.Номер КАК Номер, ДЕНЬ(Д.ДатаРасчета) КАК День "
           "ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д "
           "ГДЕ НЕ Д.ПометкаУдаления И ГОД(Д.ДатаРасчета) = 2026 И МЕСЯЦ(Д.ДатаРасчета) = 8 "
           "УПОРЯДОЧИТЬ ПО Д.ДатаРасчета")
т = q.Execute().Выгрузить()
докссылки = {int(т.Получить(i).День): т.Получить(i).С for i in range(т.Количество())}
print(f"Боевых документов августа: {т.Количество()} (дни: {sorted(докссылки)})")
print(f"Режим: {'ЗАПИСЬ (--apply)' if ПРИМЕНЯТЬ else 'DRY-RUN (в памяти)'}")

# --- 1. Пересчёт № 1 (07.08)
print("\n[1] Пересчёт № 1 (07.08)")
объект1 = докссылки[7].ПолучитьОбъект()
рез1 = объект1.Рассчитать()
проверка(bool(рез1.Выполнено) and int(рез1.Ошибок) == 0,
         f"Рассчитать(): Выполнено, ошибок {int(рез1.Ошибок)}")
проверка(объект1.Казна.Количество() >= 10,
         f"ТЧ «Казна» № 1 заполнена ({объект1.Казна.Количество()} строк)")
if ПРИМЕНЯТЬ:
    объект1.Записать()
    print("  → № 1 записан")

# --- 2. Пересчёт № 2 (14.08)
print("\n[2] Пересчёт № 2 (14.08)")
объект2 = докссылки[14].ПолучитьОбъект()
рез2 = объект2.Рассчитать()
проверка(bool(рез2.Выполнено) and int(рез2.Ошибок) == 0,
         f"Рассчитать(): Выполнено, ошибок {int(рез2.Ошибок)}")
имя_сравнения = str(buh.string(объект2.ДокументСравнения))
проверка("00000000001" in имя_сравнения,
         f"ДокументСравнения № 2 = № 1 (фактически: {имя_сравнения})")
if ПРИМЕНЯТЬ:
    объект2.Записать()
    print("  → № 2 записан")

# --- 3. Класс А: C/D по подразделениям против Excel 14.08
print("\n[3] Класс А сверки с Excel 14.08 (C/D)")
свод = {}
for i in range(объект2.Расчет.Количество()):
    с = объект2.Расчет.Получить(i)
    имя = str(с.Подразделение.Наименование) if str(buh.string(с.Подразделение)) else "<пусто>"
    а = свод.setdefault(имя, {"C": 0.0, "D": 0.0})
    а["C"] += float(с.СуммаСоглашения)
    а["D"] += float(с.СуммаДЦ)
for имя, цель in ЦЕЛЕВЫЕ_C.items():
    факт = свод.get(имя, {}).get("C", 0.0)
    проверка(abs(факт - цель) < 0.01, f"C {имя}: {факт:,.2f} = {цель:,.2f}")
for имя, цель in ЦЕЛЕВЫЕ_D.items():
    факт = свод.get(имя, {}).get("D", 0.0)
    проверка(abs(факт - цель) < 0.01, f"D {имя}: {факт:,.2f} = {цель:,.2f}")

# --- 4. ТЧ «Казна» № 2
print("\n[4] ТЧ «Казна» документа № 2")
пост_факт = затр_факт = 0.0
имена_казны = []
строки_казны = {}
for i in range(объект2.Казна.Количество()):
    с = объект2.Казна.Получить(i)
    имя = str(с.ИмяВКазне)
    имена_казны.append(имя)
    строки_казны[имя] = float(с.ПоступленияФакт)
    пост_факт += float(с.ПоступленияФакт)
    затр_факт += float(с.ЗатратыФакт)
print(f"  Строк: {len(имена_казны)}: {', '.join(sorted(имена_казны))}")
проверка(abs(пост_факт - КАЗНА_ПОСТУПЛЕНИЯ_ФАКТ) < 0.01,
         f"Итого поступления-факт {пост_факт:,.2f} = {КАЗНА_ПОСТУПЛЕНИЯ_ФАКТ:,.2f}")
проверка(abs(затр_факт - КАЗНА_ЗАТРАТЫ_ФАКТ_БАЗА) < 0.01,
         f"Итого затраты-факт {затр_факт:,.2f} = {КАЗНА_ЗАТРАТЫ_ФАКТ_БАЗА:,.2f} "
         f"(текущее состояние базы; xlsx-эталон −4 139 070,27 снят ДО проведения 6 ПП 14.08 17:20)")
for имя, цель in КАЗНА_КОНТРОЛЬ_СТРОК.items():
    факт = строки_казны.get(имя, 0.0)
    проверка(abs(факт - цель) < 0.01, f"Казна {имя}: поступления-факт {факт:,.2f} = {цель:,.2f}")
проверка(not any(" 15 м" in имя or " 30 м" in имя for имя in имена_казны),
         "IRC свернут из вложенных (нет строк «15 м»/«30 м»)")
проверка("МК Подгорцы" in имена_казны, "МК Подгорцы присутствует в казне")

# --- 5. К12/К13
print("\n[5] Контроли К12/К13")
коды2 = [str(объект2.Контроль.Получить(i).КодЗамечания)
         for i in range(объект2.Контроль.Количество())]
к12 = коды2.count("К12")
к13 = коды2.count("К13")
print(f"  К12: {к12} шт., К13: {к13} шт. (все коды: {sorted(set(коды2))})")
# На № 2 расхождений казна↔361 быть не должно (Кт361 = казна 1:1, Подгорцы 0=0):
# отсутствие К13 здесь — корректный результат; работоспособность К12 доказана smoke.
проверка(к13 == 0, "К13 на № 2 молчит — поступления-факт казны сходятся с Кт 361 по всем строкам")

# --- 6. Динамика № 2 против № 1
print("\n[6] «Динаміка» № 2 против № 1")
try:
    таб = объект2.СформироватьПечатьДинамика()
    проверка(int(таб.ВысотаТаблицы) > 10,
             f"Печать построена: строк {таб.ВысотаТаблицы}, колонок {таб.ШиринаТаблицы}")
except Exception as e:
    проверка(False, f"Печать упала: {e.excepinfo[2] if getattr(e, 'excepinfo', None) else e}")
try:
    html = str(объект2.ТекстДинамикиHTML())
    проверка(len(html) > 1000, f"HTML-динамика: {len(html)} символов")
    проверка("Доброго дня" in html and "тис. грн" in html,
             "HTML: обращение письма + суммы в тыс. грн")
    путь_html = ПАПКА_ОТЧЕТОВ + r"\Динаміка_14-08-2026.html"
    with open(путь_html, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"  → HTML сохранён: {путь_html}")
except Exception as e:
    проверка(False, f"HTML упал: {e.excepinfo[2] if getattr(e, 'excepinfo', None) else e}")

print("\n" + "=" * 100)
print(f"ПРИЁМКА: {'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' if провалов == 0 else f'ПРОВАЛОВ: {провалов}'}")
print("=" * 100)
sys.exit(1 if провалов else 0)
