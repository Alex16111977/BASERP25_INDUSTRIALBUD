# -*- coding: utf-8 -*-
# СКД-smoke собранного .erf (количество + разрезы): Создать (компиляция),
# ПолучитьДанные (новые колонки + постобработка), композиция, регрессия.
import win32com.client, sys, os
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
ERF = os.path.join(os.environ["TEMP"], "pfpp_kr.erf")
assert os.path.exists(ERF)
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
отчет = erp.ВнешниеОтчеты.Создать(ERF)
print("ВнешниеОтчеты.Создать: OK (модуль скомпилирован)")
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
период = erp.NewObject("СтандартныйПериод")
тз = отчет.ПолучитьДанные(период, сс.Ссылка)
print(f"ПолучитьДанные: строк={тз.Количество()}")
# колонки
cols = [c.Имя for c in тз.Колонки]
need = ["ОбщееНазвание","Документ","ПланКол","ФактКол","ОтклонениеКол","ПроцентКол"]
print("Новые колонки присутствуют:", all(n in cols for n in need), "->", [n for n in need if n not in cols] or "все есть")
# агрегаты Блок x Категория
агр = {}; докум = set()
for i in range(тз.Количество()):
    r = тз.Получить(i)
    a = агр.setdefault((r.Блок, r.Категория), [0.0,0.0,0.0])
    a[0]+=float(r.ФактГрн); a[1]+=float(r.ПланКол); a[2]+=float(r.ФактКол)
    if r.Блок=="2. Матеріали" and r.Документ is not None:
        try: докум.add(r.Документ.Метаданные().Имя)
        except: pass
print(f"\n{'Блок':14}{'Категория':12}{'ФактГрн':>14}{'ПланКол':>10}{'ФактКол':>10}")
мфг=мфк=0.0
for k in sorted(агр):
    a=агр[k]; print(f"{k[0]:14}{k[1]:12}{a[0]:14.2f}{a[1]:10.2f}{a[2]:10.2f}")
    if k[0]=="2. Матеріали": мфг+=a[0]; мфк+=a[2]
print(f"\nДокумент-типы(материалы): {sorted(докум)}")
print(f"Материалы Σ ФактГрн={мфг:.2f} (эталон 1620137.97)  Σ ФактКол={мфк:.2f} (эталон 15843.68)")
assert abs(мфг-1620137.97)<0.01, "регрессия ФактГрн"
assert abs(мфк-15843.68)<0.01, "регрессия ФактКол"
# композиция
схема = отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
настройки = отчет.КомпоновщикНастроек.ПолучитьНастройки()
внеш = erp.NewObject("Структура"); внеш.Вставить("Детали", тз)
км = erp.NewObject("КомпоновщикМакетаКомпоновкиДанных")
макет = км.Выполнить(схема, настройки)
проц = erp.NewObject("ПроцессорКомпоновкиДанных"); проц.Инициализировать(макет, внеш)
док = erp.NewObject("ТабличныйДокумент")
выв = erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
выв.УстановитьДокумент(док); выв.Вывести(проц)
print(f"\nКомпозиция: ВысотаТаблицы={док.ВысотаТаблицы} ШиринаТаблицы={док.ШиринаТаблицы}")
assert док.ВысотаТаблицы>0
print("\nSMOKE PASS")
