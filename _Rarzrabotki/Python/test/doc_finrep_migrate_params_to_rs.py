# -*- coding: utf-8 -*-
"""Миграция параметров финотчёта: реквизиты А_* справочника ДоговорыКонтрагентов
→ РегистрСведений.А_ПараметрыДоговоровФинотчета (измерение Договор, 5 ресурсов).

Запускать ДО удаления реквизитов из справочника. Идемпотентно: запись перезаписывается
целиком (МенеджерЗаписи), повторный прогон даёт тот же результат.

Контроль: записей = договоров с хотя бы одним заполненным параметром (на 14.08 — 10);
«Договір підряду 06/04/26-МК Кривий РІГ»: СуммаСоглашения 7 961 800, %=15,
вариант «Виконання − оплата».
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
S = buh.String

q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
	Д.Ссылка КАК Договор,
	Д.Наименование КАК Имя,
	Д.А_СуммаСоглашения КАК СуммаСоглашения,
	Д.А_СуммаДЦ КАК СуммаДЦ,
	Д.А_ОбъектПримечание КАК ОбъектПримечание,
	Д.А_ПроцентГарантийногоУдержания КАК ПроцентУдержания,
	Д.А_ВариантФормулыИтога КАК ВариантФормулы
ИЗ
	Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ
	(Д.А_СуммаСоглашения <> 0
	ИЛИ Д.А_СуммаДЦ <> 0
	ИЛИ Д.А_ОбъектПримечание <> ""
	ИЛИ Д.А_ПроцентГарантийногоУдержания <> 0
	ИЛИ Д.А_ВариантФормулыИтога <> ЗНАЧЕНИЕ(Перечисление.А_ВариантыФормулыИтогаФинотчета.ПустаяСсылка))
"""
r = q.Execute().Выгрузить()
print(f"Договоров с параметрами: {r.Количество()}")

перенесено = 0
for i in range(r.Количество()):
    row = r.Получить(i)
    мз = buh.РегистрыСведений.А_ПараметрыДоговоровФинотчета.СоздатьМенеджерЗаписи()
    мз.Договор = row.Договор
    мз.СуммаСоглашения = row.СуммаСоглашения
    мз.СуммаДЦ = row.СуммаДЦ
    мз.ОбъектПримечание = S(row.ОбъектПримечание)
    мз.ПроцентГарантийногоУдержания = row.ПроцентУдержания
    мз.ВариантФормулыИтога = row.ВариантФормулы
    мз.Записать(True)
    перенесено += 1
    print(f"  + {S(row.Имя)[:55]:55} | СумСогл={row.СуммаСоглашения} | %={row.ПроцентУдержания}")

# --- контрольная сверка из регистра
q2 = buh.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
	П.Договор.Наименование КАК Имя,
	П.СуммаСоглашения КАК СуммаСоглашения,
	П.ПроцентГарантийногоУдержания КАК Процент,
	ПРЕДСТАВЛЕНИЕ(П.ВариантФормулыИтога) КАК Вариант
ИЗ
	РегистрСведений.А_ПараметрыДоговоровФинотчета КАК П
"""
r2 = q2.Execute().Выгрузить()
print(f"\nЗаписей в регистре: {r2.Количество()}")

кр_ок = False
for i in range(r2.Количество()):
    row = r2.Получить(i)
    if "06/04/26" in S(row.Имя):
        кр_ок = (float(row.СуммаСоглашения) == 7961800.0 and float(row.Процент) == 15.0
                 and "плата" in S(row.Вариант))
        print(f"Контроль Кривий Ріг: СумСогл={row.СуммаСоглашения} %={row.Процент} "
              f"Вариант='{S(row.Вариант)}' -> {'OK' if кр_ок else 'FAIL'}")

assert r2.Количество() == r.Количество(), "число записей регистра != числу договоров с параметрами"
assert кр_ок, "контрольные значения Кривого Рога не сошлись"
print(f"\nМИГРАЦИЯ OK: {перенесено} записей")
