"""Тест новой архитектуры (2026-05-28): создание ВКассу из А_ОтражениеЗПпоКазне напрямую.

После реверта Подхода C и переноса всей логики в А_ОтражениеЗПпоКазне:
- РаспределениеФ2 больше не создаёт ВКассу
- А_ОтражениеЗПпоКазне.СоздатьВедомостиВКассуПоОтражениюЗП() — единственная точка
- Источник: ТЧ.РаспределениеКазна (Подр уже исправлено при COM-загрузке, СтатьяДДС из БДДС)

Проверяем: для физлица Пономаренко Подразделение в А_Расшифровке = Производство (а не Главный офис).
"""
import sys, win32com.client
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# 1. Найти А_ОтражениеЗПпоКазне 000000001
qDoc = erp.NewObject("Запрос")
qDoc.Text = """ВЫБРАТЬ Д.Ссылка КАК Сс, Д.Проведен КАК Пр
ИЗ Документ.А_ОтражениеЗПпоКазне КАК Д ГДЕ Д.Номер = &Н"""
qDoc.SetParameter("Н", "000000001")
r = qDoc.Execute().Выгрузить()
assert r.Количество() == 1, f"А_ОтражениеЗПпоКазне 000000001 не найден"
ссылка = r[0].Сс
проведен = r[0].Пр
print(f"А_ОтражениеЗПпоКазне 000000001: {S(ссылка)}, Проведен={проведен}")

assert проведен, "Должен быть проведён"

# 2. Вызвать новую процедуру
obj = ссылка.ПолучитьОбъект()
print("\n--- Вызов СоздатьВедомостиВКассуПоОтражениюЗП() ---")
obj.СоздатьВедомостиВКассуПоОтражениюЗП()
print("--- Возврат из процедуры ---\n")

# 3. Проверить — есть ли ВКассу с А_ОтражениеЗПпоКазне = этому документу
qV = erp.NewObject("Запрос")
qV.Text = """ВЫБРАТЬ
    Вед.Ссылка КАК Сс, Вед.Номер, Вед.Дата, Вед.А_РаспределениеФ2 КАК Ф2,
    Вед.СуммаПоДокументу, Вед.Проведен
ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу КАК Вед
ГДЕ Вед.А_ОтражениеЗПпоКазне = &ОЗП И НЕ Вед.ПометкаУдаления"""
qV.SetParameter("ОЗП", ссылка)
ved = qV.Execute().Выгрузить()
print(f"Создано ВКассу: {ved.Количество()}")
for row in ved:
    # Через COM-ссылку получим счётчики ТЧ
    obj_v = row.Сс.ПолучитьОбъект()
    кол_зп = obj_v.Зарплата.Количество() if obj_v else 0
    кол_р = obj_v.А_РасшифровкаВыплатыЗарплатаПоФизлицам.Количество() if obj_v else 0
    print(f"  {S(row.Номер):20} от {row.Дата} | Ф2={S(row.Ф2):30} | Σ={row.СуммаПоДокументу:>15} | ЗП={кол_зп:>3} | Расш={кол_р:>3} | Пров={row.Проведен}")

# 4. Проверить Пономаренко — теперь должно быть "Производство" а не "Главный офис"
qP = erp.NewObject("Запрос")
qP.Text = """ВЫБРАТЬ
    Рш.Ссылка.Номер КАК ВедНомер,
    Рш.Подразделение КАК ПодрОрг,
    Рш.КВыплате,
    Рш.СтатьяДвиженияДенежныхСредств КАК СтатьяДДС,
    Рш.НаправлениеДеятельности КАК Направ
ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
ГДЕ Рш.Ссылка.А_ОтражениеЗПпоКазне = &ОЗП
    И Рш.ФизическоеЛицо.Наименование ПОДОБНО "Пономаренко%"
"""
qP.SetParameter("ОЗП", ссылка)
ponomarenko = qP.Execute().Выгрузить()
print(f"\nПономаренко в А_Расшифровке: {ponomarenko.Количество()} строк")
for row in ponomarenko:
    статья_заполнена = "✅" if erp.ЗначениеЗаполнено(row.СтатьяДДС) else "⚠️ ПУСТО"
    print(f"  Подр={S(row.ПодрОрг):20} | КВыпл={row.КВыплате:>10} | СтатьяДДС={S(row.СтатьяДДС):40} {статья_заполнена} | Направ={S(row.Направ)}")

# 5. Acceptance: проверить что НЕТ строк с подразделением "Главный офис"
qGO = erp.NewObject("Запрос")
qGO.Text = """ВЫБРАТЬ Рш.ФизическоеЛицо КАК ФЛ, Рш.Подразделение КАК Подр
ИЗ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
ГДЕ Рш.Ссылка.А_ОтражениеЗПпоКазне = &ОЗП
    И Рш.Подразделение.Наименование = "Главный офис"
"""
qGO.SetParameter("ОЗП", ссылка)
go_rows = qGO.Execute().Выгрузить()
print(f"\n=== ACCEPTANCE ===")
print(f"Строк с Подр='Главный офис': {go_rows.Количество()} (должно быть 0)")
if go_rows.Количество() > 0:
    for row in go_rows:
        print(f"  ⚠️  ФЛ={S(row.ФЛ)}, Подр={S(row.Подр)}")
    print("❌ FAIL — функция не применена")
    sys.exit(1)
else:
    print("✅ PASS — все Подразделения исправлены (нет 'Главный офис')")
