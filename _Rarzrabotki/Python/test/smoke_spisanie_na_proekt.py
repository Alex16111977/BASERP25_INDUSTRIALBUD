def контроль(гп):
    q = buh.NewObject("Запрос")
    q.Text = КОНТРОЛЬ
    q.SetParameter("ДатаНачала", Д1)
    q.SetParameter("ДатаОкончания", Д2)
    q.SetParameter("ВключатьГотовуюПродукцию", гп)
    строка = q.Execute().Выгрузить().Получить(0)
    return float(строка.Сумма), float(строка.СуммаБезПодразделения)


def новый_отчёт():
    отчет = buh.ВнешниеОтчеты.Создать(ERF)
    return отчет, отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")


def скомпоновать(гп, генератор="ГенераторМакетаКомпоновкиДанныхДляКоллекцииЗначений"):
    _, схема = новый_отчёт()
    настройки = схема.НастройкиПоУмолчанию
    период = buh.NewObject("СтандартныйПериод")
    период.ДатаНачала = Д1
    период.ДатаОкончания = Д2
    настройки.ПараметрыДанных.УстановитьЗначениеПараметра("Период", период)
    настройки.ПараметрыДанных.УстановитьЗначениеПараметра("ВключатьГотовуюПродукцию", гп)

    компоновщик = buh.NewObject("КомпоновщикМакетаКомпоновкиДанных")
    # Python None маршалится как VT_NULL, 1С ждёт Неопределено (VT_EMPTY) -> pythoncom.Empty
    макет = компоновщик.Выполнить(схема, настройки, pythoncom.Empty, pythoncom.Empty, тип1с(генератор))
    процессор = buh.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    return процессор


def выгрузка(гп):
    процессор = скомпоновать(гп)
    вывод = buh.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВКоллекциюЗначений")
    тз = buh.NewObject("ТаблицаЗначений")
    вывод.УстановитьОбъект(тз)
    вывод.Вывести(процессор)
    return тз


def детальные(тз):
    """В плоской выгрузке лежат строки ВСЕХ уровней группировки: итоги по подразделению,
    складу, документу И детальные записи. Суммировать можно только детальные —
    их признак: заполнена Номенклатура."""
    for i in range(тз.Количество()):
        стр = тз.Получить(i)
        if стр.Сумма is not None and buh.ЗначениеЗаполнено(стр.Номенклатура):
            yield стр


