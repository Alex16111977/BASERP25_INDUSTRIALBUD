def что_видит_1с(значение):
    _ЧТО_ВИДИТ.SetParameter("Д", значение)
    r = _ЧТО_ВИДИТ.Execute().Выгрузить().Получить(0)
    return datetime.datetime(int(r.Г), int(r.М), int(r.Д), int(r.Ч), int(r.Мин), int(r.С))


def дата1с(y, m, d, h=0, mi=0, s=0):
    """python-datetime, который на стороне 1С равен ровно указанному моменту.
    Сдвиг подбирается ДЛЯ ЭТОЙ ДАТЫ и проверяется — из-за перехода на летнее время
    единый сдвиг на весь год даёт промах на час."""
    цель = datetime.datetime(y, m, d, h, mi, s)
    кандидат = цель
    for _ in range(3):
        видит = что_видит_1с(кандидат)
        if видит == цель:
            return кандидат
        кандидат += цель - видит
    raise RuntimeError(f"не удалось подобрать дату для {цель}")


def тип1с(имя):
    """Глобальная Тип() через COM-прокси не резолвится; ОписаниеТипов — конструируется."""
    описание = buh.NewObject("ОписаниеТипов", имя)
    типы = описание.Типы()
    assert типы.Количество() == 1, f"неоднозначный тип {имя}"
    return типы.Получить(0)


