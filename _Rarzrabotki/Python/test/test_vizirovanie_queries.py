sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)

ok = fail = 0


def run(name, text, params=None):
    """Выполняет запрос. Печатает OK/FAIL. Возвращает ТЗ или None."""
    global ok, fail
    q = erp.NewObject("Запрос")
    q.Text = text
    for k, val in (params or {}).items():
        q.SetParameter(k, val)
    try:
        r = q.Execute().Выгрузить()
        print(f"  [OK]   {name:<42} строк={r.Количество()}")
        ok += 1
        return r
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e
        print(f"  [FAIL] {name:<42} {str(msg)[:110]}")
        fail += 1
        return None


print("=" * 90)
print("ПРОВЕРКА ЗАПРОСОВ ДВИЖКА ВИЗИРОВАНИЯ (Rule #-1) — база BaseERP")
