"""Дослідити: який Свод_* пише статтю "Прибыли и убытки" в А_ОтчетБаланс_Свод
   і які Source/субконто у цих рядків janv 2026."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

# Знайти статтю "Прибыли и убытки"
qS = conn.NewObject("Запрос")
qS.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
            'ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование = "Прибыли и убытки"')
rS = qS.Выполнить().Выбрать()
if not rS.Следующий():
    print("Стаття 'Прибыли и убытки' НЕ знайдена")
    sys.exit(1)
ПУ = rS.С
print(f"[INFO] Стаття: {S(ПУ)}")

# Розкладка рядків per Source + субконто для janv 2026
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    С.Source КАК Source,
    С.Подразделение КАК Подр,
    С.Аналитика1 КАК Ан1,
    С.Аналитика2 КАК Ан2,
    С.Аналитика3 КАК Ан3,
    С.ОбъектыЭксплуатации КАК ОЭ,
    С.НематериальныйАктив КАК НМА,
    С.ТипНалога КАК ТН,
    С.ФизическоеЛицо КАК ФЛ,
    С.Контрагент КАК Контр,
    С.СуммаКонечныйОстаток КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК С
ГДЕ С.Статья = &ПУ
    И С.Организация = &Орг
    И С.ДокументДвижения В (
        ВЫБРАТЬ Ссылка ИЗ Документ.А_ФинРез_Баланс
        ГДЕ Организация = &Орг И Проведен
            И НАЧАЛОПЕРИОДА(Месяц, МЕСЯЦ) = ДАТАВРЕМЯ(2026,1,1))
УПОРЯДОЧИТЬ ПО Подр
"""
q.УстановитьПараметр("ПУ", ПУ); q.УстановитьПараметр("Орг", ORG)
r = q.Выполнить().Выгрузить()
print(f"\nРядків 'Прибыли и убытки' за janv 2026: {r.Количество()}")
sources = {}
for i in range(r.Количество()):
    rec = r.Получить(i)
    src = S(rec.Source)
    sources[src] = sources.get(src, 0) + 1
    if i < 10:
        print(f"  Source={src[:25]:25} Подр={S(rec.Подр):28} Ан1='{S(rec.Ан1)}' ОЭ={S(rec.ОЭ)[:15]:15} КО={float(rec.КО or 0):>+14,.2f}")
print(f"\nРозкладка по Source: {sources}")

# Розкладка Аналитика1 на пусті/непусті
empty_an1 = sum(1 for i in range(r.Количество()) if S(r.Получить(i).Ан1) == "")
print(f"Рядків з пустою Аналитика1: {empty_an1}/{r.Количество()}")
