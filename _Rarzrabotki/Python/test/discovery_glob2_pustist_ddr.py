v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
S = erp.String

q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Ссылка ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273" """
own_org = q.Execute().Выгрузить().Получить(0).Ссылка

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", own_org)
q.УстановитьПараметр("Глобино2", erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Глобино-2"))
q.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
q.Text = """
ВЫБРАТЬ
    ТИПЗНАЧЕНИЯ(Т.Регистратор) КАК ТипРег,
    КОЛИЧЕСТВО(*) КАК Кол,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК signedΣ
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Подразделение = &Глобино2 И Т.Статья = &СтРасх
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Период <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(Т.Регистратор)
"""
r = q.Execute().Выгрузить()
print("ПАП(Источник=ПустаяСсылка, Глобино-2, Расх.тек.пер.) — по типам Регистраторов:")
for i in range(r.Количество()):
    row = r.Получить(i)
    print(f"  {S(row.ТипРег):<70} | Кол={row.Кол:>5} | signedΣ={row.signedΣ:>12.2f}")

# Теперь — есть ли по этим же регистраторам записи в ДвДохРасх?
q2 = erp.NewObject("Запрос")
q2.УстановитьПараметр("Орг", own_org)
q2.УстановитьПараметр("Глобино2", erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Глобино-2"))
q2.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
q2.Text = """
ВЫБРАТЬ ПЕРВЫЕ 30
    Т.Период,
    Т.Регистратор,
    Т.Сумма КАК ПАПСумма,
    Т.ВидДвижения
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Подразделение = &Глобино2 И Т.Статья = &СтРасх
    И Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И Т.Период <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
УПОРЯДОЧИТЬ ПО Т.Период УБЫВ
"""
r = q2.Execute().Выгрузить()
print(f"\nПримеры регистраторов ПАП(Источник=ПустаяСсылка) — последние {r.Количество()}:")
ddr_match = 0
ddr_no_match = 0
for i in range(r.Количество()):
    row = r.Получить(i)
    reg = row.Регистратор
    # Запрос к ДДР по этому регистратору
    q3 = erp.NewObject("Запрос")
    q3.УстановитьПараметр("Рег", reg)
    q3.Text = """
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол, СУММА(Сумма) КАК Σ,
        ТИПЗНАЧЕНИЯ(МАКСИМУМ(Статья)) КАК ТипСт
    ИЗ РегистрНакопления.ДвиженияДоходыРасходыПрочиеАктивыПассивы
    ГДЕ Регистратор = &Рег
    """
    rd = q3.Execute().Выгрузить().Получить(0)
    has = (rd.Кол or 0) > 0
    if has:
        ddr_match += 1
    else:
        ddr_no_match += 1
    print(f"  {row.Период} | {S(reg)[:70]:<70} | ПАП={row.ВидДвижения}{row.ПАПСумма:>10.2f} | ДДР: {rd.Кол}, Σ={float(rd.Σ or 0):.2f}")

print(f"\nИТОГО ПАП-регистраторов с ДДР: {ddr_match}, без ДДР: {ddr_no_match}")
