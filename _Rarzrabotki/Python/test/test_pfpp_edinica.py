# -*- coding: utf-8 -*-
# Smoke + render-check: единица измерения по материалам (грейн Аналітика->Единица->Документ).
# Проверяет: компиляция, наличие колонки Единица, ВИДИМОСТЬ единиц в скомпонованной таблице,
# отсутствие регрессии (Σ ФактГрн/ФактКол). Собрать .erf заранее в %TEMP%\pfpp_ed5.erf или укажи путь.
import win32com.client, sys, os
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
ERF = os.environ.get("PFPP_ERF") or os.path.join(os.environ["TEMP"], "pfpp_ed5.erf")
assert os.path.exists(ERF), f"нет .erf: {ERF}"
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
отчет = erp.ВнешниеОтчеты.Создать(ERF)
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
тз = отчет.ПолучитьДанные(erp.NewObject("СтандартныйПериод"), сс.Ссылка)
assert "Единица" in [c.Имя for c in тз.Колонки], "нет колонки Единица"
ед_имена=set(); мфг=мфк=0.0
for i in range(тз.Количество()):
    r=тз.Получить(i)
    if r.Блок=="2. Матеріали": мфг+=float(r.ФактГрн); мфк+=float(r.ФактКол)
    ед=r.Единица
    if ед is not None and not (hasattr(ед,'Пустая') and ед.Пустая()):
        try: ед_имена.add(str(ед.Наименование).strip())
        except: pass
схема=отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
наст=отчет.КомпоновщикНастроек.ПолучитьНастройки()
вн=erp.NewObject("Структура"); вн.Вставить("Детали", тз)
м=erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст)
п=erp.NewObject("ПроцессорКомпоновкиДанных"); п.Инициализировать(м, вн)
д=erp.NewObject("ТабличныйДокумент")
в=erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент"); в.УстановитьДокумент(д); в.Вывести(п)
H,W=д.ВысотаТаблицы,д.ШиринаТаблицы
тексты=set()
for rr in range(1,H+1):
    for cc in range(1,W+1):
        try:
            t=str(д.Область(rr,cc,rr,cc).Текст).strip()
            if t: тексты.add(t)
        except: pass
видно=sorted(e for e in ед_имена if e and e in тексты)
print(f"H={H} W={W}; единиц видно={len(видно)}/{len(ед_имена)}: {видно}")
print(f"Регрессия Σ ФактГрн={мфг:.2f}(1620137.97) ФактКол={мфк:.2f}(15843.68)")
assert len(видно)>=10, "единицы не отображаются"
assert abs(мфг-1620137.97)<0.01 and abs(мфк-15843.68)<0.01, "регрессия сумм/кол-ва"
print("SMOKE PASS — единица измерения отображается")
