# -*- coding: utf-8 -*-
# Smoke + render-check: единица измерения по материалам (грейн Аналітика->Единица->Документ).
# Проверяет: компиляция, наличие колонки Единица, ВИДИМОСТЬ единиц в скомпонованной таблице,
# отсутствие регрессии (Σ ФактГрн/ФактКол). Собрать .erf заранее в %TEMP%\pfpp_ed5.erf или укажи путь.
import win32com.client, sys, os
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
ERF = os.environ.get("PFPP_ERF") or os.path.join(os.environ["TEMP"], "pfpp_ed5.erf")
assert os.path.exists(ERF), f"нет .erf: {ERF}"
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
отчет = erp.ВнешниеОтчеты.Создать(ERF)
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
тз = отчет.ПолучитьДанные(erp.NewObject("СтандартныйПериод"))  # с 24.07.2026 — все подразделения сразу
ПОДР = сс.Подразделение.Наименование.strip()
assert "Единица" in [c.Имя for c in тз.Колонки], "нет колонки Единица"
ч = lambda v: float(v or 0)   # синтетические строки ETC отдают числа как None
пусто_ли = lambda ref: ref is None or (hasattr(ref, 'Пустая') and ref.Пустая())
ед_имена=set(); мфг=мфк=0.0; план_без_единицы=[]
for i in range(тз.Количество()):
    r=тз.Получить(i)
    if r.Подразделение.Наименование.strip() != ПОДР:
        continue
    if r.Блок=="2. Матеріали":
        мфг+=ч(r.ФактГрн); мфк+=ч(r.ФактКол)
        # с 04.09.2026 единица плана берётся из ТЧ СС (ЕдиницаОбщееНазвание) и заполнена всегда
        if (ч(r.ПланКол) != 0 or ч(r.ПланГрн) != 0) and r.Единица.Пустая():
            план_без_единицы.append(str(r.Аналитика))
    ед=r.Единица
    if ед is not None and not (hasattr(ед,'Пустая') and ед.Пустая()):
        try: ед_имена.add(str(ед.Наименование).strip())
        except: pass
схема=отчет.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
наст=отчет.КомпоновщикНастроек.ПолучитьНастройки()
вн=erp.NewObject("Структура"); вн.Вставить("Детали", тз)
м=erp.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, наст)
п=erp.NewObject("ПроцессорКомпоновкиДанных"); п.Инициализировать(м, вн)
д=erp.NewObject("ТабличныйДокумент")
в=erp.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент"); в.УстановитьДокумент(д); в.Вывести(п)
H,W=д.ВысотаТаблицы,д.ШиринаТаблицы
тексты=set()
for rr in range(1,H+1):
    for cc in range(1,W+1):
        try:
            t=str(д.Область(rr,cc,rr,cc).Текст).strip()
            if t: тексты.add(t)
        except: pass
видно=sorted(e for e in ед_имена if e and e in тексты)
assert not план_без_единицы, f"плановые строки материалов без единицы: {план_без_единицы[:5]}"
print(f"H={H} W={W}; единиц видно={len(видно)}/{len(ед_имена)}: {видно}")
print("EDINICA PASSED")
# Жёсткий эталон факта снят 04.09.2026: закупки приходят ежедневно (LESSONS §16),
# вместо него кросс-контроль с прямым запросом к регистру за тот же охват.
z = erp.NewObject("Запрос")
z.Текст = """
ВЫБРАТЬ
	СУММА(СТ.Стоимость) КАК Грн,
	СУММА(СТ.Количество) КАК Кол
ИЗ РегистрНакопления.СебестоимостьТоваров КАК СТ
ГДЕ СТ.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
	И СТ.РазделУчета = ЗНАЧЕНИЕ(Перечисление.РазделыУчетаСебестоимостиТоваров.ТоварыНаСкладах)
	И СТ.Регистратор ССЫЛКА Документ.ПриобретениеТоваровУслуг
	И ВЫРАЗИТЬ(СТ.Регистратор КАК Документ.ПриобретениеТоваровУслуг).Подразделение В ИЕРАРХИИ (&Подр)
"""
подр = сс.ПодразделениеЗакупки
if пусто_ли(подр):
    подр = сс.Подразделение
z.УстановитьПараметр("Подр", подр)
эт = z.Выполнить().Выгрузить()[0]
эг, эк = ч(эт.Грн), ч(эт.Кол)
print(f"Кросс-контроль факта: отчёт Σ ФактГрн={мфг:.2f} / регистр {эг:.2f}; кол-во {мфк:.2f} / {эк:.2f}")
assert len(видно)>=10, "единицы не отображаются"
# Сумма — копейка в копейку; количество в ТЗ округлено до 2 знаков (регистр хранит 3),
# поэтому по количеству допуск 0,1.
assert abs(мфг-эг)<0.01, f"факт отчёта {мфг:.2f} разошёлся с регистром {эг:.2f}"
assert abs(мфк-эк)<0.1, f"количество отчёта {мфк:.2f} разошлось с регистром {эк:.2f}"
print("SMOKE PASS — единица измерения отображается")
