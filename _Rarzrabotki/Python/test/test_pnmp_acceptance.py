# -*- coding: utf-8 -*-
"""
Приёмка Части C: логика ПередачаНачисленийМеждуПодразделениями на едином источнике.
Заполняет документ в памяти (новый BSL), затем МОДЕЛИРУЕТ заполнение ПНМП.Начисления
из НачисленнаяЗарплата Ф1 «Зарплата управл» (без записи реального документа ПНМП).

Проверяет:
  - Постернак: перенос ЦО → Строительство (ОргБух ІНДАСТРІАЛБУД), Сумма 27 913,53;
  - Шишкина: перенос только Спецтехника → Производство (6 685,71); Производство→Производство пропущено;
  - целевое подразделение = ОргБух.А_ПодразделениеЗарплатаБух; строки с исх=цел не переносятся.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

def uid(ref):
    try:
        return S(ref.УникальныйИдентификатор()) if erp.ЗначениеЗаполнено(ref) else ""
    except Exception:
        return ""

q = erp.NewObject("Запрос")
q.Текст = ('ВЫБРАТЬ А.Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне КАК А '
           'ГДЕ А.Дата >= ДАТАВРЕМЯ(2025,12,1,0,0,0) И А.Дата <= ДАТАВРЕМЯ(2025,12,31,23,59,59) '
           'УПОРЯДОЧИТЬ ПО А.Дата')
sel = q.Выполнить().Выбрать(); sel.Следующий()
obj = sel.Ссылка.ПолучитьОбъект()
print(f"Заповнюємо №{S(obj.Номер)} в пам'яті...")
obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()

ф1 = erp.XMLСтрока(erp.Перечисления.А_ФормыPL.Форма1)

# Модель ПНМП.Начисления
переносы = []
for r in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
    if erp.XMLСтрока(r.ФормаPL) != ф1 or float(r.Сумма) == 0 or float(r.ВзносыВсего) != 0:
        continue
    sp = r.СпособОтраженияЗарплатыВБухучете
    if erp.ЗначениеЗаполнено(sp) and bool(sp.А_ЭтоУдержание):
        continue
    оргбух = r.ОрганизацияБухгалтерия
    if not erp.ЗначениеЗаполнено(оргбух):
        continue
    целподр = оргбух.А_ПодразделениеЗарплатаБух
    исхподр = r.ПодразделениеПредприятия
    if not erp.ЗначениеЗаполнено(целподр) or uid(целподр) == uid(исхподр):
        continue
    переносы.append({
        "фл": S(r.ФизическоеЛицо), "оргбух": S(оргбух),
        "исх": S(исхподр), "цел": S(целподр), "сумма": float(r.Сумма),
    })

def показать(fio):
    rows = [p for p in переносы if fio in p["фл"]]
    print(f"\n=== {fio} === ПНМП.Начисления (перенос): {len(rows)} строк")
    for p in rows:
        print(f"  {p['исх'][:14]:14} -> {p['цел'][:14]:14} | ОргБух={p['оргбух'][:18]:18} | Σ={p['сумма']:>12,.2f}")
    return rows

ok = True
p_rows = показать("Постернак")
if not (len(p_rows) == 1 and abs(p_rows[0]["сумма"] - 27913.53) < 0.01
        and "Строительство" in p_rows[0]["цел"] and "ІНДАСТРІАЛБУД" in p_rows[0]["оргбух"]):
    print("  FAIL: ожидался перенос ЦО->Строительство 27 913,53"); ok = False

sh_rows = показать("Шишкіна")
sh_sum = sum(p["сумма"] for p in sh_rows)
if not (len(sh_rows) == 1 and abs(sh_rows[0]["сумма"] - 6685.71) < 0.01
        and "Производство" in sh_rows[0]["цел"] and "Спецтехника" in sh_rows[0]["исх"]):
    print(f"  FAIL: ожидался 1 перенос Спецтехника->Производство 6 685,71 (получено {len(sh_rows)}, Σ={sh_sum})"); ok = False

print(f"\nВсего переносов-начислений по документу: {len(переносы)}, Σ={sum(p['сумма'] for p in переносы):,.2f}")
print("\n" + ("OK: приёмка Части C (модель ПНМП) пройдена" if ok else "FAIL"))
sys.exit(0 if ok else 1)
