def парс(текст, n):
    """-> (проценты[n], флаги[list[str]]).  Никогда не молчит: всё сомнительное -> флаг."""
    t = str(текст or "").strip()
    флаги = []
    if not t:
        return [0.0]*n, флаги
    сегм = СЕГМЕНТ.findall(t)
    if сегм:
        проц, домов = [], 0
        for кол, п in сегм:
            к = int(кол); p = float(п.replace(",", "."))
            домов += к
            if p < 0 or p > 100:
                флаги.append(f"процент {p} вне 0..100")
            проц += [p]*к
        # контроль 1: все ли фрагменты разобраны
        фрагм = len(ФРАГМЕНТ.findall(t))
        if фрагм > len(сегм):
            флаги.append(f"РАСПОЗНАНО {len(сегм)} сегм. из {фрагм} — часть текста ПОТЕРЯНА")
        # контроль 2: сумма домов
        if домов != n:
            флаги.append(f"Σ домов в сегментах = {домов}, а домов {n}")
        if len(проц) > n:
            флаги.append(f"сегменты дают {len(проц)} домов > {n} — хвост отброшен")
        return (проц + [0.0]*n)[:n], флаги
    m = ОДИНОЧНЫЙ.match(t)
    if m:
        return [float(m.group(1).replace(",", "."))]*n, флаги
    # контроль 3: есть цифры и %, но не распознано
    if "%" in t and re.search(r"\d", t):
        флаги.append("есть цифры и «%», но сегменты НЕ распознаны")
    return [0.0]*n, флаги

def сегм_числа(текст):
    """[(номер/количество, процент), ...] из ячейки."""
    сегм = СЕГМЕНТ.findall(str(текст or "").strip())
    return [(int(k), float(p.replace(",", "."))) for k, p in сегм]

def восходящий(сегм, n):
    """Форма «4 МОД - P; 5 МОД - P; 6 МОД - P»: числа подряд, конец = n, Σ > n."""
    if len(сегм) < 2:
        return False
    k = [x[0] for x in сегм]
    return sum(k) > n and k[-1] == n and all(k[i+1] == k[i] + 1 for i in range(len(k)-1))

def вариант_B(сегм, n):
    """Первый сегмент количественный (дома №1..k0), остальные — порядковые (номер дома)."""
    r = [0.0]*n
    k0, p0 = сегм[0]
    for i in range(min(k0, n)):
        r[i] = p0
    for k, p in сегм[1:]:
        if 1 <= k <= n:
            r[k-1] = p
    return r

def вариант_C(сегм, n, пред_раб):
    """Все сегменты порядковые; неупомянутые дома — перенос % прошлого снимка."""
    r = [float(пред_раб.get(i+1, 0.0)) for i in range(n)]
    for k, p in сегм:
        if 1 <= k <= n:
            r[k-1] = p
    return r

