# -*- coding: utf-8 -*-
"""Smoke рефайнмента: перепровести 3 НачальнаяЗадолженность + А_ФинРез_Баланс дек-мар.
Проверки:
  ПАП:  «Оплата труда» = А_ВзСС (плуг=0); «Прибыли и убытки» вернулась к до-фиксовому;
        управленческий Σ КО = -3 165 970,77 (by-design, одноногая);
  Хозрасчетный: ОСВ 661 сгруппирован ПО ФизЛицу (нет субконто-типа СотрудникиОрганизаций),
        нетто 661 = +3 165 970,77, проводка балансируется."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0
РЗ = erp.РежимЗаписиДокумента.Проведение
РП = erp.РежимПроведенияДокумента.Неоперативный
OPENING = 3165970.77
SIGMA_ETALON = -OPENING
TOL = 0.05
fails = []

# 1) перепровести 3 НачальнаяЗадолженность
q = erp.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ Ссылка КАК С ИЗ Документ.НачальнаяЗадолженностьПоЗарплате ГДЕ Проведен"
nz = [r.С for r in q.Выполнить().Выгрузить()]
for s in nz: s.ПолучитьОбъект().Записать(РЗ, РП)
print(f"перепроведено НачальнаяЗадолженность: {len(nz)}")

# 2) перепровести А_ФинРез_Баланс дек-мар
q2 = erp.NewObject("Запрос")
q2.Текст = """ВЫБРАТЬ Ссылка КАК С ИЗ Документ.А_ФинРез_Баланс
ГДЕ Проведен И Месяц >= ДАТАВРЕМЯ(2025,12,1) И Месяц <= ДАТАВРЕМЯ(2026,3,1) УПОРЯДОЧИТЬ ПО Месяц"""
fb = [r.С for r in q2.Выполнить().Выгрузить()]
for s in fb: s.ПолучитьОбъект().Записать(РЗ, РП)
print(f"перепроведено А_ФинРез_Баланс дек-мар: {len(fb)}")

# 3) свёртка: ОТ=А_ВзСС, плуг=0, Σ КО = -OPENING
print("\n=== ПАП свёртка ===")
ETALON = {"дек2025":-1252868.97,"янв2026":-2919783.64,"фев2026":-2917774.84,"мар2026":-3291625.64}
MONTHS = [("дек2025","ДАТАВРЕМЯ(2025,12,1)"),("янв2026","ДАТАВРЕМЯ(2026,1,1)"),
          ("фев2026","ДАТАВРЕМЯ(2026,2,1)"),("мар2026","ДАТАВРЕМЯ(2026,3,1)")]
for label, nm in MONTHS:
    qo=erp.NewObject("Запрос")
    qo.Текст=f"""ВЫБРАТЬ Рег.Расхождение КАК Плуг, СУММА(Рег.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Статья.Наименование="Оплата труда" И Рег.Регистратор.Месяц={nm}
    СГРУППИРОВАТЬ ПО Рег.Расхождение"""
    plug=det=0.0
    for r in qo.Выполнить().Выгрузить():
        if r.Плуг: plug=f(r.КО)
        else: det=f(r.КО)
    qs=erp.NewObject("Запрос")
    qs.Текст=f"""ВЫБРАТЬ СУММА(Рег.СуммаКонечныйОстаток) КАК КО ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
    ГДЕ Рег.Регистратор.Месяц={nm}"""
    sigma=f(qs.Выполнить().Выгрузить()[0].КО)
    ot=plug+det
    ok = abs(plug)<=TOL and abs(ot-ETALON[label])<=TOL and abs(sigma-SIGMA_ETALON)<=0.5
    if not ok: fails.append(f"ПАП {label}")
    print(f"  {label}: ОТ={ot:>14,.2f} (эт.{ETALON[label]:>14,.2f}) плуг={plug:>10,.2f} Σ={sigma:>14,.2f} (эт.{SIGMA_ETALON:,.2f}) {'OK' if ok else 'FAIL'}")

# 4) «Прибыли и убытки» вернулась к до-фиксовому (янв = -116 622 011,19)
qpu=erp.NewObject("Запрос")
qpu.Текст="""ВЫБРАТЬ СУММА(Рег.СуммаКонечныйОстаток) КАК КО ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег
ГДЕ Рег.Статья.Наименование="Прибыли и убытки" И Рег.Регистратор.Месяц=ДАТАВРЕМЯ(2026,1,1)"""
пу=f(qpu.Выполнить().Выгрузить()[0].КО)
ПУ_ЭТ=-116622011.19
okpu=abs(пу-ПУ_ЭТ)<=0.5
if not okpu: fails.append("ПУ янв")
print(f"\n«Прибыли и убытки» янв = {пу:,.2f} (до-фиксовое эт. {ПУ_ЭТ:,.2f}) {'OK' if okpu else 'FAIL'}")

# 5) Хозрасчетный 661: субконто ОБЕИХ сторон (Кт661→СубконтоКт1, Дт661-переплата→СубконтоДт1)
#    ВСЕ по ФизическиеЛица (нет СотрудникиОрганизаций / NULL). Net проверяется в блоке #6.
print("\n=== Хозрасчетный 661 ===")
bad=0; типы=set(); grossKt=0.0; grossDt=0.0
def проверить_субконто(условие, поле, накопитель):
    global bad
    qq=erp.NewObject("Запрос")
    qq.Текст=f"""ВЫБРАТЬ {поле} КАК С, СУММА(Х.Сумма) КАК Сум
    ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто КАК Х
    ГДЕ Х.Регистратор ССЫЛКА Документ.НачальнаяЗадолженностьПоЗарплате И {условие}
    СГРУППИРОВАТЬ ПО {поле}"""
    s=0.0
    for r in qq.Выполнить().Выгрузить():
        s+=f(r.Сум)
        if r.С is None: bad+=1; continue
        имя=str(r.С.Метаданные().Имя); типы.add(имя)
        if имя!="ФизическиеЛица": bad+=1
    return s
grossKt=проверить_субконто('Х.СчетКт.Код="661"', "Х.СубконтоКт1", grossKt)
grossDt=проверить_субконто('Х.СчетДт.Код="661"', "Х.СубконтоДт1", grossDt)
print(f"  типы субконто 661 от НЗ = {типы}; строк не-ФизЛицо/NULL = {bad}; gross Кт661={grossKt:,.2f} Дт661(переплата)={grossDt:,.2f}")
ok661=(bad==0) and ("ФизическиеЛица" in типы)
if not ok661: fails.append("661 субконто-тип")

# баланс проводки (нетто 661 Кт-Дт == нетто 00 Дт-Кт == OPENING)
qb=erp.NewObject("Запрос")
qb.Текст="""ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА Х.СчетКт.Код="661" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ)
      - СУММА(ВЫБОР КОГДА Х.СчетДт.Код="661" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Net661,
    СУММА(ВЫБОР КОГДА Х.СчетДт.Код="00" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ)
      - СУММА(ВЫБОР КОГДА Х.СчетКт.Код="00" ТОГДА Х.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Net00
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Х
ГДЕ Х.Регистратор ССЫЛКА Документ.НачальнаяЗадолженностьПоЗарплате"""
rb=qb.Выполнить().Выгрузить()[0]
net661,net00=f(rb.Net661),f(rb.Net00)
okbal=abs(net661-net00)<=0.5 and abs(net661-OPENING)<=0.5
if not okbal: fails.append("661 баланс проводки")
print(f"  нетто 661(Кт-Дт)={net661:,.2f}  нетто 00(Дт-Кт)={net00:,.2f}  балансируется={'OK' if okbal else 'FAIL'}")

print("\nSMOKE PASS" if not fails else f"SMOKE FAIL: {fails}")
sys.exit(1 if fails else 0)
