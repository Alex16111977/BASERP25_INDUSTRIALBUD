# Производство / Расх.тек.пер. — нет в свод?
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Рег", doc_ref)
q.УстановитьПараметр("СтРасх", erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода"))
q.УстановитьПараметр("Производство", erp.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Производство"))
q.Text = """
ВЫБРАТЬ
    РС.Source, ПРЕДСТАВЛЕНИЕ(РС.Source) КАК SourcePред,
    РС.СтатьяДоходыРасходы, ПРЕДСТАВЛЕНИЕ(РС.СтатьяДоходыРасходы) КАК СДРПред,
    РС.Расхождение,
    РС.СуммаКонечныйОстаток КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК РС
ГДЕ РС.ДокументДвижения = &Рег
    И РС.Статья = &СтРасх
    И РС.Подразделение = &Производство
УПОРЯДОЧИТЬ ПО КО УБЫВ
"""
r = q.Execute().Выгрузить()
print(f"\n=== Производство / Расх.тек.пер. (декабрь doc) ===")
print(f"Строк: {r.Количество()}")
total_ko = 0.0
for i in range(min(20, r.Количество())):
    row = r.Получить(i)
    total_ko += float(row.КО)
    print(f"  Src={S(row.SourcePред):<30} | СДР={S(row.СДРПред):<35} | Расх={row.Расхождение} | КО={row.КО:>15.2f}")
if r.Количество() > 20:
    print(f"  ... ещё {r.Количество()-20}")
    for i in range(20, r.Количество()):
        row = r.Получить(i)
        total_ko += float(row.КО)
print(f"  TOTAL КО: {total_ko:.2f}")

