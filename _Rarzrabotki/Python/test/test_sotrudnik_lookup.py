# -*- coding: utf-8 -*-
# Діагностика чому регістр "Взаиморасчеты с сотрудниками" фейлить на 66 рядку:
# - Скільки ФізОсіб з НДФЛ/ВзносыФОТ мають Сотрудника з Організації ТОВ "ІНДАСТРІАЛБУД"
# - Скільки — з іншої організації
# - Скільки взагалі без активного Сотрудника
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

# Метадані Справочник.Сотрудники
print("=" * 70)
print("Справочник.Сотрудники — реквізити для фільтру по організації")
print("=" * 70)
mo = erp.Метаданные.Справочники.Найти("Сотрудники")
for i in range(mo.Реквизиты.Количество()):
    a = mo.Реквизиты.Получить(i)
    im = S(a.Имя)
    if "Орган" in im or "ФизическоеЛицо" in im:
        print(f"  {im}: {S(a.Тип)[:80]}")

# Знайти наш НЗ 000Ц-000003
q = erp.NewObject("Запрос")
q.Text = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 НЗ.Ссылка, НЗ.Организация, НЗ.Дата, НЗ.Номер "
    "ИЗ Документ.НачислениеЗарплаты КАК НЗ "
    "ГДЕ НЗ.А_ДокОтражениеЗПпоКазне.Номер = \"000000001\" И НЕ НЗ.ПометкаУдаления "
    "УПОРЯДОЧИТЬ ПО НЗ.Дата УБЫВ"
)
sel = q.Execute().Выбрать()
if not sel.Следующий():
    print("НЗ не знайдено")
    sys.exit(0)
нз = sel.Ссылка
орг = sel.Организация
print(f"\nНЗ: {S(нз)} від {S(sel.Дата)}, Організація: {S(орг)}")

обj = нз.ПолучитьОбъект()
print(f"  Начисления={обj.Начисления.Количество()}, Удержания={обj.Удержания.Количество()}, НДФЛ={обj.НДФЛ.Количество()}, ВзносыФОТ={обj.ВзносыФОТ.Количество()}")

# Зібрати ФізОсіб з УСІХ ТЧ + показати чіткий рядок 3 Удержания
фл_set = {}  # UUID str → FL ref
for ТЧ_имя in ["Удержания", "НДФЛ", "ВзносыФОТ"]:
    ТЧ = getattr(обj, ТЧ_имя)
    for i in range(ТЧ.Количество()):
        r = ТЧ.Получить(i)
        uid = S(r.ФизическоеЛицо.УникальныйИдентификатор())
        фл_set[uid] = r.ФизическоеЛицо

# Також з Начисления через Сотрудник.ФизическоеЛицо
for i in range(обj.Начисления.Количество()):
    r = обj.Начисления.Получить(i)
    fl = r.Сотрудник.ФизическоеЛицо
    uid = S(fl.УникальныйИдентификатор())
    фл_set[uid] = fl

print(f"\nВсього унікальних ФізОсіб у всіх ТЧ: {len(фл_set)}")

# 3-й рядок Удержания — підозрюваний #66 у регістрі
print("\n=== Удержания (усі 4 рядки) ===")
for i in range(обj.Удержания.Количество()):
    r = обj.Удержания.Получить(i)
    print(f"  [{i+1}] ФізЛицо='{S(r.ФизическоеЛицо)}' Удержание='{S(r.Удержание)}' Результат='{S(r.Результат)}'")

# Масив для запиту
маc = erp.NewObject("Массив")
for uid, fl in фл_set.items():
    маc.Добавить(fl)

# Запит з фільтром по ГоловнаяОрганизация
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    С.ФизическоеЛицо КАК ФизЛицо,
    С.Ссылка КАК Сотрудник,
    С.ГоловнаяОрганизация КАК ГолОрг,
    С.ПометкаУдаления КАК Удален
ИЗ Справочник.Сотрудники КАК С
ГДЕ С.ФизическоеЛицо В (&МасФЛ)
"""
q2.SetParameter("МасФЛ", маc)
r2 = q2.Execute().Выгрузить()
print(f"Рядків Сотрудники по цих ФізОсобах: {r2.Количество()}")

# Аналіз
есть_по_орг = {}
есть_вообще = {}
другая_орг = {}

for i in range(r2.Количество()):
    row = r2.Получить(i)
    fl = row.ФизЛицо
    if bool(row.Удален):
        continue
    uid = S(fl.УникальныйИдентификатор())
    есть_вообще[uid] = S(fl)
    if S(row.ГолОрг) == S(орг):
        есть_по_орг[uid] = S(fl)
    else:
        другая_орг[uid] = S(fl) + " → " + S(row.ГолОрг)

нет_вообще = {uid: S(fl) for uid, fl in фл_set.items() if uid not in есть_вообще}
только_друг = {uid: v for uid, v in другая_орг.items() if uid not in есть_по_орг}

print(f"\n=== Розподіл {len(фл_set)} ФізОсіб ===")
print(f"  Мають Сотрудника в цій Організації: {len(есть_по_орг)}")
print(f"  Мають Сотрудника в ІНШІЙ організації (і нема в цій): {len(только_друг)}")
print(f"  ВЗАГАЛІ нема активного Сотрудника: {len(нет_вообще)}")

# Приклади
print("\n=== Приклади 'інша орг' (5) ===")
лічильник = 0
for uid, v in только_друг.items():
    if лічильник >= 5: break
    print(f"  {v}")
    лічильник += 1

print("\n=== Приклади 'нема взагалі' (5) ===")
лічильник = 0
for uid, v in нет_вообще.items():
    if лічильник >= 5: break
    print(f"  {v}")
    лічильник += 1
