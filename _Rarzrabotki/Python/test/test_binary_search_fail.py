def try_post(описание, обj):
    try:
        обj.Записать(erp.РежимЗаписиДокумента.Проведение)
        print(f"  [OK] {описание} — ПРОВЕДЕНО")
        return True
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print(f"  [FAIL] {описание}: {e.excepinfo[2]}")
        else:
            print(f"  [FAIL] {описание}: {e}")
        return False


def get_obj():
    """Перезавантажуємо свіжу копію НЗ від А_ОтражениеЗПпоКазне 000000001"""
    q = erp.NewObject("Запрос")
    q.Text = (
        'ВЫБРАТЬ ПЕРВЫЕ 1 НЗ.Ссылка '
        'ИЗ Документ.НачислениеЗарплаты КАК НЗ '
        'ГДЕ НЗ.А_ДокОтражениеЗПпоКазне.Номер = "000000001" И НЕ НЗ.ПометкаУдаления '
        'УПОРЯДОЧИТЬ ПО НЗ.Дата УБЫВ'
    )
    sel = q.Execute().Выбрать()
    if not sel.Следующий():
        return None
    obj = sel.Ссылка.ПолучитьОбъект()
    # Зняти проведення якщо є
    if bool(sel.Ссылка.Проведен):
        try:
            obj.Записать(erp.РежимЗаписиДокумента.ОтменаПроведения)
        except:
            pass
    return obj


