"""Rule #-1: проверка запроса-предзагрузки НазначенияИспользования по (Владелец В (), Способ В ())
+ доступ к предопределённому НДС_Облагаемая. BuhBud."""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8': sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
НаДату = datetime.datetime(2026, 7, 13, 23, 59, 59)
сч22 = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("22")
способ = buh.Справочники.СпособыОтраженияРасходовПоАмортизации.НайтиПоКоду("00-000055")
скл = None
vs = buh.Справочники.Склады.Выбрать()
while vs.Следующий():
    if "ІС МД МХП ОРІЛЬ" in vs.Наименование and "виробнич" in vs.Наименование:
        скл = vs.Ссылка; break

# собрать номенклатуры остатков сч.221 на складе
q = buh.NewObject("Запрос")
q.УстановитьПараметр("НаДату", НаДату); q.УстановитьПараметр("Сч22", сч22); q.УстановитьПараметр("Скл", скл)
q.Текст = """
ВЫБРАТЬ РАЗЛИЧНЫЕ ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) КАК Ном
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ(&Сч22), , ) КАК Ост
ГДЕ Ост.КоличествоОстаток > 0 И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) = &Скл"""
номенклатуры = buh.NewObject("Массив")
s = q.Выполнить().Выбрать()
while s.Следующий(): номенклатуры.Добавить(s.Ном)
print("номенклатур сч.221:", номенклатуры.Количество())

# предзагрузка НазначенияИспользования
способы = buh.NewObject("Массив"); способы.Добавить(способ)
qp = buh.NewObject("Запрос")
qp.УстановитьПараметр("Ном", номенклатуры); qp.УстановитьПараметр("Способы", способы)
qp.Текст = """
ВЫБРАТЬ НИ.Владелец КАК Номенклатура, НИ.СпособОтраженияРасходов КАК Способ, НИ.Ссылка КАК Назн
ИЗ Справочник.НазначенияИспользования КАК НИ
ГДЕ НЕ НИ.ПометкаУдаления И НИ.Владелец В (&Ном) И НИ.СпособОтраженияРасходов В (&Способы)"""
кэш = {}   # эмуляция вложенного соответствия
sp = qp.Выполнить().Выбрать()
дублей = 0
while sp.Следующий():
    k = buh.String(sp.Номенклатура)
    if k in кэш: дублей += 1
    else: кэш[k] = sp.Назн
print("строк предзагрузки:", len(кэш) + дублей, "| уникальных номенклатур в кэше:", len(кэш), "| дублей(взят первый):", дублей)
# покрытие
покрыто = sum(1 for i in range(номенклатуры.Количество()) if buh.String(номенклатуры.Получить(i)) in кэш)
print(f"покрытие: {покрыто}/{номенклатуры.Количество()}")

# предопределённое
нн = buh.Справочники.НалоговыеНазначенияАктивовИЗатрат.НДС_Облагаемая
print("НДС_Облагаемая:", нн.Наименование, "| заполнено:", buh.ЗначениеЗаполнено(нн))
print("RESULT: PASS" if покрыто > 0 and buh.ЗначениеЗаполнено(нн) else "RESULT: FAIL")
