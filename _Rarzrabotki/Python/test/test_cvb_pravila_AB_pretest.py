# -*- coding: utf-8 -*-
"""Rule #-1 претест правил A/B для контуров сверки (Взаиморасчёты, Деньги-безнал).

Проверяем ТОЧНО те выражения, что пойдут в BSL:
  - гард наличия реквизита:  Регистратор.Метаданные().Реквизиты.Найти("А_ВведенВЕРП") <> Неопределено
  - правило A:               Регистратор.А_ВведенВЕРП = Истина
  - правило B (взаиморасч.):  ТипЗнч(Регистратор) = Тип("ДокументСсылка.РКО/ПКО")
                              И НЕ ЗначениеЗаполнено(Регистратор.А_ОрганизацияБухгалтерия)
на живых документах Воронцова из базы знаний 08 (декабрь 2025).
"""
import sys
import win32com.client as w

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

v8 = w.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Кандидаты типов документов, которые двигают РасчетыСКлиентами/РасчетыСПоставщиками
ТИПЫ = [
    "РасходныйКассовыйОрдер",
    "ПриходныйКассовыйОрдер",
    "СписаниеБезналичныхДенежныхСредств",
    "ПоступлениеБезналичныхДенежныхСредств",
]

# Номера из 08_pravila_isklyucheniya (декабрь 2025)
НОМЕРА = ["000Ц-000102", "000Ц-000282", "000Ц-000007", "000Ц-000008",
          "N0000053085", "N0000053086", "N0000053087",
          # варианты без префикса/с пробелами на случай иной сериализации
          "0000053085", "0000053086", "0000053087"]


def найти_документы():
    """Ищем каждый номер среди кандидатов типов, возвращаем список ссылок."""
    найдено = []
    for тип in ТИПЫ:
        q = erp.NewObject("Запрос")
        q.Текст = (
            "ВЫБРАТЬ Ссылка КАК Ссылка, Номер КАК Номер, Дата КАК Дата "
            "ИЗ Документ." + тип + " "
            "ГДЕ Номер В (&Номера) И Дата МЕЖДУ ДАТАВРЕМЯ(2025,12,1) И ДАТАВРЕМЯ(2025,12,31,23,59,59)")
        mas = erp.NewObject("Массив")
        for н in НОМЕРА:
            mas.Добавить(н)
        q.УстановитьПараметр("Номера", mas)
        выб = q.Выполнить().Выбрать()
        while выб.Следующий():
            найдено.append((тип, выб.Номер, выб.Дата, выб.Ссылка))
    return найдено


def имеет_реквизит(ссылка, имя):
    """Гард наличия реквизита через метаданные (как в BSL)."""
    try:
        return ссылка.Метаданные().Реквизиты.Найти(имя) is not None
    except Exception:
        return None  # метод недоступен через COM — используем try/except на чтении


def тип_рко_пко(ссылка):
    имя = ссылка.Метаданные().Имя
    return имя in ("РасходныйКассовыйОрдер", "ПриходныйКассовыйОрдер"), имя


print("=== Поиск целевых документов Воронцова (декабрь 2025) ===")
docs = найти_документы()
if not docs:
    print("[!] Ни один номер не найден среди кандидатов типов — проверить период/номера/типы.")

for тип, номер, дата, ссылка in docs:
    # --- Правило A: гард + значение флага ---
    есть_флаг = имеет_реквизит(ссылка, "А_ВведенВЕРП")
    ввведен_erp = None
    try:
        ввведен_erp = bool(ссылка.А_ВведенВЕРП)
    except Exception:
        ввведен_erp = "НЕТ РЕКВИЗИТА"

    # --- Правило B: тип РКО/ПКО + пустота ОргБух ---
    это_кассовый, имя_типа = тип_рко_пко(ссылка)
    оргбух_заполнена = None
    try:
        оргбух_заполнена = bool(erp.ЗначениеЗаполнено(ссылка.А_ОрганизацияБухгалтерия))
    except Exception:
        оргбух_заполнена = "НЕТ РЕКВИЗИТА"

    правило_A = (ввведен_erp is True)
    правило_B = это_кассовый and (оргбух_заполнена is False)

    if правило_A:
        ожид = 'ОК: тільки в ЕРП (А_ВведенВЕРП)  [правило A]'
    elif правило_B:
        ожид = 'ОК: РКО/ПКО з Казни  [правило B]'
    else:
        ожид = 'Немає в BuhBud (немає відповідності)  [без изменений]'

    print(f"\n{имя_типа}  №{номер}  {дата}")
    print(f"   гард 'А_ВведенВЕРП' есть?   {есть_флаг}")
    print(f"   А_ВведенВЕРП               = {ввведен_erp}")
    print(f"   кассовый (РКО/ПКО)?        {это_кассовый}")
    print(f"   А_ОрганизацияБухгалтерия заполнена? {оргбух_заполнена}")
    print(f"   -> правило A={правило_A}  правило B={правило_B}")
    print(f"   ОЖИДАЕМЫЙ статус: {ожид}")

print("\nDONE pretest")
