# -*- coding: utf-8 -*-
"""Устойчивость обработки: цикл обязан пережить заказ с битым договором.

Запуск в РЕЖИМЕ ЗАПИСИ внутри транзакции с откатом — база не меняется.
Проверяется, что после сбойного заказа обрабатываются следующие.
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ПУТЬ = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\Обновить заказы поставщика.epf"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

провал = 0


def проверка(имя, условие, деталь=""):
    global провал
    print(("  OK   " if условие else "  FAIL ") + имя + (" | " + деталь if деталь else ""))
    if not условие:
        провал += 1


def чис(з):
    try:
        return int(float(S(з).replace("\u00a0", "").replace(" ", "").replace(",", ".")))
    except Exception:
        return 0


print("=" * 74)
print("УСТОЙЧИВОСТЬ: битый заказ не должен обрывать перебор")
print("=" * 74)

обр = erp.ВнешниеОбработки.Создать(ПУТЬ, False)

# период, в который попадает заказ с битым договором (ІБ00-002860 от 21.07.2026)
q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ДАТАВРЕМЯ(2026,7,1,0,0,0) КАК Н, "
          "КОНЕЦПЕРИОДА(ДАТАВРЕМЯ(2026,7,1,0,0,0), МЕСЯЦ) КАК К")
гр = q.Execute().Выгрузить().Получить(0)
реестр = обр.ПолучитьРеестрЗаказов(гр.Получить(0), гр.Получить(1))
проверка("1. Реестр июля 2026 получен", реестр.Количество() > 0,
         "заказов = %s" % S(реестр.Количество()))

кол = реестр.Колонки
имена = [кол.Получить(i).Имя for i in range(кол.Количество())]
проверка("2. Признак битого договора в реестре", "БитаяСсылка" in имена)

битых = 0
индекс_битого = -1
for i in range(реестр.Количество()):
    стр = реестр.Получить(i)
    if S(стр.БитаяСсылка).strip() != "":
        битых += 1
        if индекс_битого < 0:
            индекс_битого = i
проверка("3. Битый заказ найден в периоде", битых > 0,
         "битых = %d, первый индекс = %d из %s" % (битых, индекс_битого, S(реестр.Количество())))

# отмечаем все строки — важно, чтобы после битого шли другие
for i in range(реестр.Количество()):
    реестр.Получить(i).Обновлять = True

параметры = erp.NewObject("Структура")
параметры.Вставить("ТолькоАнализ", False)          # РЕЖИМ ЗАПИСИ
параметры.Вставить("ПереводитьСогласованВПодтвержден", False)

erp.НачатьТранзакцию()
try:
    результат = обр.ВыполнитьОбработку(реестр, параметры)
    ст = результат.Статистика

    обработано = (чис(ст.ЗаказОбновлён) + чис(ст.ЗаказБезИзменений)
                  + чис(ст.ЗаказОчищен) + чис(ст.ЗаказПропущен) + чис(ст.ЗаказОшибка))

    print()
    print("  Статистика:", S(обр.ПредставлениеСтатистики(ст)).replace("\n", " | "))
    print()

    проверка("4. Перебор дошёл до КОНЦА реестра",
             обработано == чис(реестр.Количество()),
             "обработано %d из %s" % (обработано, S(реестр.Количество())))

    # «обновлено 0» — нормально, если данные уже совпадают. Важно, что нет НЕОБРАБОТАННЫХ
    # ошибок: битый заказ обязан идти в «пропущено», а не в «ошибок».
    проверка("5. Сбой не превратился в необработанную ошибку",
             чис(ст.ЗаказОшибка) == 0 and чис(ст.ЗаказПропущен) > 0,
             "ошибок %s, пропущено %s" % (S(ст.ЗаказОшибка), S(ст.ЗаказПропущен)))

    # битый заказ должен быть помечен как пропущенный, а не как ошибка
    if индекс_битого >= 0:
        стр = реестр.Получить(индекс_битого)
        проверка("6. Битый заказ пропущен с пояснением",
                 "битая ссылка" in S(стр.Результат).lower(),
                 "Результат: %s" % S(стр.Результат)[:60])

    # после битого заказа должны быть строки с непустым результатом
    после = 0
    for i in range(индекс_битого + 1, реестр.Количество()):
        if S(реестр.Получить(i).Результат).strip() != "":
            после += 1
    проверка("7. После битого заказа обработка продолжилась",
             после > 0, "строк с результатом после него: %d" % после)

finally:
    erp.ОтменитьТранзакцию()
    print()
    print("  ТРАНЗАКЦИЯ ОТКАЧЕНА — база не изменена.")

print("=" * 74)
print("ПРОВАЛОВ: %d" % провал)
sys.exit(1 if провал else 0)
