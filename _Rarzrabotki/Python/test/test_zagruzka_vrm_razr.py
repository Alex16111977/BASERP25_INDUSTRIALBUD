# -*- coding: utf-8 -*-
# Smoke режима «Загрузка выполнения» обработки «Загрузка А_ВыполнениеРаботМодулей» на BaseERPRazr.
#  1. Сверка BSL-парсера РазобратьПроцентыФакта с эталоном парс_проценты по ВСЕМ значениям G файла.
#  2. Сверка РазобратьДатуЛиста (время передаётся ЧИСЛОМ секунд — маршалинг дат win32com сдвигает).
#  3. Прогон ЗагрузитьВыполнениеИзДанных: 3 проведённых документа 19.06/26.06/03.07 2026 9:00.
#  4. Обороты РН накопительно = 501.78 / 1616.59 / 2401.53 (проверка литералами ДАТАВРЕМЯ в запросе).
#  5. СС.А_КоличествоМодулей = 8.
#  6. Идемпотентность: повторный прогон — те же 3 документа, обороты не меняются.
# Данные BaseERP не трогаем; документы не удаляем (get-or-create).
import win32com.client, sys, re
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import openpyxl

XLSX = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\А_ПланФактныйПроизводствоПолный\По часам\Копия ЗВіт_виконання_ВООЗ_ЕМС_Зачепилівка.xlsx"
EPF  = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\А_ПланФактныйПроизводствоПолный\По часам\Загрузка А_ВыполнениеРаботМодулей.epf"
СС_ИМЯ = "МД Вооз ЕМS Мала 2026 / Цех_МД Вооз ЕМS Мала 2026"
МОДУЛЕЙ = 8
ЭТАЛОН_EV = [501.78, 1616.59, 2401.53]

def парс_проценты(текст):
    t = str(текст or "").strip()
    if not t:
        return None
    сегменты = re.findall(r"(\d+)\s*модул\w*\s*-*\s*(\d+(?:[.,]\d+)?)\s*%", t, re.I)
    if сегменты:
        из = []
        for кол, проц in сегменты:
            из += [float(проц.replace(",", "."))] * int(кол)
        return (из + [0.0] * МОДУЛЕЙ)[:МОДУЛЕЙ]
    m = re.fullmatch(r"(\d+(?:[.,]\d+)?)\s*%", t)
    if m:
        return [float(m.group(1).replace(",", "."))] * МОДУЛЕЙ
    return None

# === Excel -> сырые листы (ровно как клиент формы: A=наименование, G=текст факта) ===
wb = openpyxl.load_workbook(XLSX, data_only=True)
листы = []  # [(имя, [(наименование, текст_факта)])]
for имя in wb.sheetnames:
    if not имя.lower().startswith("звіт ("):
        continue
    ws = wb[имя]
    строки = []
    for r in range(2, ws.max_row + 1):
        назв = str(ws.cell(r, 1).value or "").strip()
        if not назв or "Загальна" in назв or назв.lower() == "табель":
            continue
        строки.append((назв, str(ws.cell(r, 7).value or "").strip()))
    листы.append((имя, строки))
print(f"Листов снимков: {len(листы)}: {[и for и, _ in листы]}")
assert len(листы) == 3

# === 1С: подключение, загрузка .epf ===
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERPRazr";Usr="Администратор";Pwd="24043"')
proc = erp.ВнешниеОбработки.Создать(EPF, False)
print("Обработка загружена:", EPF)

сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(СС_ИМЯ)
assert сс is not None and not сс.Пустая(), "СС не найдена"

# === 1. Сверка парсера BSL <-> Python по всем уникальным G ===
уникальные = sorted({т for _, стр in листы for _, т in стр})
ошибок = 0
for текст in уникальные:
    py = парс_проценты(текст)
    bsl = proc.РазобратьПроцентыФакта(текст, МОДУЛЕЙ)
    if py is None:
        ok = bsl is None
        bsl_вид = None if bsl is None else "массив"
    else:
        ok = bsl is not None and bsl.Количество() == МОДУЛЕЙ and \
             all(abs(float(bsl.Получить(i)) - py[i]) < 1e-9 for i in range(МОДУЛЕЙ))
        bsl_вид = None if bsl is None else [float(bsl.Получить(i)) for i in range(МОДУЛЕЙ)]
    if not ok:
        ошибок += 1
        print(f"  РАСХОЖДЕНИЕ: {текст!r}: py={py} bsl={bsl_вид}")
print(f"Парсер: {len(уникальные)} уникальных значений G, расхождений {ошибок}")
assert ошибок == 0, "BSL-парсер разошёлся с эталоном"

# === 2. Сверка РазобратьДатуЛиста (время = 9:00 числом секунд) ===
д = proc.РазобратьДатуЛиста("ЗВіт (19.06)", 2026, 9 * 3600)
assert д is not None, "дата листа не разобрана"
assert erp.String(д) in ("19.06.2026 9:00:00", "19.06.2026 09:00:00"), f"дата листа: {erp.String(д)}"
assert proc.РазобратьДатуЛиста("Зразок", 2026, 0) is None
assert proc.РазобратьДатуЛиста("ЗВіт", 2026, 0) is None
print(f"Дата листа: {erp.String(д)} — OK; «Зразок»/«ЗВіт» -> Неопределено — OK")

# === Параметры загрузки (структуры создаём на стороне 1С) ===
def построить_параметры():
    листы1с = erp.NewObject("Массив")
    for имя, строки in листы:
        строки1с = erp.NewObject("Массив")
        for назв, факт in строки:
            стр = erp.NewObject("Структура")
            стр.Вставить("Наименование", назв)
            стр.Вставить("ТекстФакта", факт)
            строки1с.Добавить(стр)
        опис = erp.NewObject("Структура")
        опис.Вставить("ИмяЛиста", имя)
        опис.Вставить("Строки", строки1с)
        листы1с.Добавить(опис)
    парам = erp.NewObject("Структура")
    парам.Вставить("СтруктураСеб", сс.Ссылка)
    парам.Вставить("Листы", листы1с)
    парам.Вставить("Год", 2026)
    парам.Вставить("Время", 9 * 3600)  # числом: COM-даты сдвигаются при маршалинге
    парам.Вставить("Проводить", True)
    парам.Вставить("КоличествоМодулейПоУмолчанию", МОДУЛЕЙ)
    return парам

def протокол_в_печать(рез, заголовок):
    print(f"--- {заголовок}: Ошибка={рез.Ошибка}")
    if рез.Ошибка:
        print("   ТекстОшибки:", рез.ТекстОшибки)
    for i in range(рез.Сообщения.Количество()):
        print("   |", рез.Сообщения.Получить(i))
    доки = []
    for i in range(рез.Документы.Количество()):
        о = рез.Документы.Получить(i)
        доки.append((str(о.Лист), float(о.ЕВ), int(о.Строк), str(о.Действие)))
        print(f"   {о.Лист}: {о.Действие}, строк {о.Строк}, EV {float(о.ЕВ):.2f}")
    return доки

# === Проверочные запросы (все даты — ЛИТЕРАЛАМИ в тексте, без маршалинга) ===
def документы_в_базе():
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("СС", сс.Ссылка)
    q.Текст = """
    ВЫБРАТЬ ГОД(Д.Дата) КАК Г, МЕСЯЦ(Д.Дата) КАК М, ДЕНЬ(Д.Дата) КАК Дн,
        ЧАС(Д.Дата) КАК Ч, МИНУТА(Д.Дата) КАК Мин,
        ВЫБОР КОГДА Д.Проведен ТОГДА 1 ИНАЧЕ 0 КОНЕЦ КАК Пр
    ИЗ Документ.А_ВыполнениеРаботМодулей КАК Д
    ГДЕ Д.СтруктураСебестоимости = &СС И НЕ Д.ПометкаУдаления
    УПОРЯДОЧИТЬ ПО Д.Дата
    """
    т = q.Execute().Выгрузить()
    return [(int(т.Получить(i).Г), int(т.Получить(i).М), int(т.Получить(i).Дн),
             int(т.Получить(i).Ч), int(т.Получить(i).Мин), int(т.Получить(i).Пр))
            for i in range(т.Количество())]

def обороты_накопительно():
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("СС", сс.Ссылка)
    q.Текст = """
    ВЫБРАТЬ
        СУММА(ВЫБОР КОГДА Т.Период <= ДАТАВРЕМЯ(2026, 6, 19, 23, 59, 59) ТОГДА Т.ЧасыВыполнение ИНАЧЕ 0 КОНЕЦ) КАК О1,
        СУММА(ВЫБОР КОГДА Т.Период <= ДАТАВРЕМЯ(2026, 6, 26, 23, 59, 59) ТОГДА Т.ЧасыВыполнение ИНАЧЕ 0 КОНЕЦ) КАК О2,
        СУММА(ВЫБОР КОГДА Т.Период <= ДАТАВРЕМЯ(2026, 7, 3, 23, 59, 59) ТОГДА Т.ЧасыВыполнение ИНАЧЕ 0 КОНЕЦ) КАК О3
    ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т
    ГДЕ Т.СтруктураСебестоимости = &СС
    """
    т = q.Execute().Выгрузить()
    с = т.Получить(0)
    return [float(с.О1 or 0), float(с.О2 or 0), float(с.О3 or 0)]

# === 3-5. Первый прогон ===
рез = proc.ЗагрузитьВыполнениеИзДанных(построить_параметры())
доки1 = протокол_в_печать(рез, "Прогон 1")
assert not рез.Ошибка, рез.ТекстОшибки
assert len(доки1) == 3

доки_бд = документы_в_базе()
print("Документы в базе:", доки_бд)
assert доки_бд == [(2026, 6, 19, 9, 0, 1), (2026, 6, 26, 9, 0, 1), (2026, 7, 3, 9, 0, 1)], \
    "документы/даты/время/проведение не совпали"

об1 = обороты_накопительно()
print(f"Обороты РН накопительно: {[f'{о:.2f}' for о in об1]} (эталон {ЭТАЛОН_EV})")
for ф, э in zip(об1, ЭТАЛОН_EV):
    assert abs(ф - э) < 0.2, f"оборот {ф:.2f} != эталон {э}"

сс_проверка = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(СС_ИМЯ)
assert int(сс_проверка.А_КоличествоМодулей) == МОДУЛЕЙ, "А_КоличествоМодулей не установлен"
print(f"СС.А_КоличествоМодулей = {int(сс_проверка.А_КоличествоМодулей)} — OK")

# === 6. Идемпотентность ===
рез2 = proc.ЗагрузитьВыполнениеИзДанных(построить_параметры())
доки2 = протокол_в_печать(рез2, "Прогон 2 (идемпотентность)")
assert not рез2.Ошибка, рез2.ТекстОшибки
assert all(д[3] == "обновлён" for д in доки2), "повторный прогон должен обновлять, не создавать"
assert документы_в_базе() == доки_бд, "повторный прогон изменил состав документов"
об2 = обороты_накопительно()
assert all(abs(а - б) < 0.01 for а, б in zip(об1, об2)), f"повторный прогон изменил обороты: {об1} -> {об2}"
print("Идемпотентность: состав документов и обороты не изменились — OK")

# === Бонус: ПроанализироватьЛисты (предпросмотр) ===
анализ = proc.ПроанализироватьЛисты(построить_параметры())
assert not анализ.Ошибка
for i in range(анализ.Листы.Количество()):
    л = анализ.Листы.Получить(i)
    print(f"Предпросмотр: {л.ИмяЛиста}: строк {int(л.СтрокВсего)}, сопоставлено {int(л.Сопоставлено)}")
    assert int(л.Сопоставлено) > 0

print("\nSMOKE PASS")
