"""DIAG-2: состояние 1С-регистра А_ОтчётБаланс_Свод по Контрагенту.

Section A (Fact_Balance OlapBASERP) уже показал: Dec2025 расчётные Source
cp_filled=0, Jan2026 cp_filled>0. Нужно различить:
  (a) ETL fact_balance Dec2025 прогонялся ДО доработки 1С — в 1С регистре
      Контрагент по Dec ЕСТЬ, надо лишь --run-once fact_balance --period 2025-12
  (b) декабрьский свод в 1С не перепроведён после доработки — в самом
      регистре Контрагент по Dec пуст → сперва перепровести А_ФинРез_Баланс.

Группируем по месяцам БЕЗ date-параметров (надёжно, без +2000 SQL-офсета,
без неоднозначности MCP-параметров). Только чтение.
"""
import sys, io, win32com.client
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

print("=" * 74)
print("1) Регистр А_ОтчётБаланс_Свод — по месяцам/Source, Контрагент заполнен?")
print("   (только расчётные Source; весь регистр, без date-фильтра)")
print("=" * 74)
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    НАЧАЛОПЕРИОДА(Свод.Регистратор.Дата, МЕСЯЦ) КАК Мес,
    Свод.Source КАК Source,
    КОЛИЧЕСТВО(*) КАК Всего,
    СУММА(ВЫБОР КОГДА Свод.Контрагент = ЗНАЧЕНИЕ(Справочник.Контрагенты.ПустаяСсылка)
                 ТОГДА 0 ИНАЧЕ 1 КОНЕЦ) КАК СКонтр,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Свод.Регистратор) КАК Регистраторов
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Свод
ГДЕ Свод.Source В (
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
СГРУППИРОВАТЬ ПО
    НАЧАЛОПЕРИОДА(Свод.Регистратор.Дата, МЕСЯЦ), Свод.Source
УПОРЯДОЧИТЬ ПО Мес, Source
"""
try:
    t = q.Execute().Выгрузить()
    print(f"строк итога: {t.Количество()}")
    for i in range(t.Количество()):
        r = t.Получить(i)
        print(f"  {r.Мес:%Y-%m}  {erp.String(r.Source):<30} "
              f"всего={r.Всего:>6} сКонтрагентом={r.СКонтр:>6} рег={r.Регистраторов}")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL:", info[2] if info else e)

print()
print("=" * 74)
print("2) Документы А_ФинРез_Баланс (регистраторы) Dec2025..Jan2026")
print("   Дата / Проведён / ВерсияДанных — был ли Dec перепроведён")
print("=" * 74)
q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ
    Док.Ссылка КАК Ссылка, Док.Номер КАК Номер, Док.Дата КАК Дата,
    Док.Проведен КАК Проведен, Док.ПометкаУдаления КАК Помечен,
    Док.Организация КАК Орг
ИЗ Документ.А_ФинРез_Баланс КАК Док
ГДЕ Док.Дата >= &Нач И Док.Дата < &Кон
УПОРЯДОЧИТЬ ПО Док.Дата
"""
q2.SetParameter("Нач", erp.Дата(2025, 11, 1))
q2.SetParameter("Кон", erp.Дата(2026, 3, 1))
try:
    t2 = q2.Execute().Выгрузить()
    print(f"документов: {t2.Количество()}")
    for i in range(t2.Количество()):
        r = t2.Получить(i)
        print(f"  N={erp.String(r.Номер):<12} Дата={r.Дата:%Y-%m-%d %H:%M} "
              f"Проведен={r.Проведен} Помечен={r.Помечен} Орг={erp.String(r.Орг)}")
except Exception as e:
    info = getattr(e, "excepinfo", None)
    print("FAIL:", info[2] if info else e)

print()
print("=" * 74)
print("3) Детально Dec2025 own-org: разрез по Контрагент-заполнен / Source")
print("=" * 74)
q3 = erp.NewObject("Запрос")
q3.Text = """
ВЫБРАТЬ
    Свод.Source КАК Source,
    ВЫБОР КОГДА Свод.Контрагент = ЗНАЧЕНИЕ(Справочник.Контрагенты.ПустаяСсылка)
          ТОГДА "пусто" ИНАЧЕ "заполнен" КОНЕЦ КАК КонтрСост,
    КОЛИЧЕСТВО(*) КАК Всего
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Свод
ГДЕ Свод.Регистратор.Дата >= &Нач И Свод.Регистратор.Дата < &Кон
    И Свод.Source В (
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСКлиентамиПоСрокам),
        ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.РасчетыСПоставщикамиПоСрокам))
СГРУППИРОВАТЬ ПО Свод.Source,
    ВЫБОР КОГДА Свод.Контрагент = ЗНАЧЕНИЕ(Справочник.Контрагенты.ПустаяСсылка)
          ТОГДА "пусто" ИНАЧЕ "заполнен" КОНЕЦ
УПОРЯДОЧИТЬ ПО Source, КонтрСост
"""
