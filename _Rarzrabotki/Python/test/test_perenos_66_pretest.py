"""Pre-test (Rule #-1) для доработки «Перенос остатков сотрудников».

Проверяет, что НОВЫЙ запрос обработки (.Остатки, В ИЕРАРХИИ 66, Кт−Дт, ключ А_ИдКод)
даёт те же суммы per (А_ИдКод, ЕДРПОУ), что BuhBud-запрос отчёта-эталона
(.ОстаткиИОбороты, КонечныйОстаток Кт−Дт) на ту же дату. И сколько А_ИдКод резолвятся в ЕРП ФЛ.
"""
import sys
from datetime import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ДАТА = datetime(2025, 12, 31, 23, 59, 59)   # дата остатков (конец дня)
TOL = 0.01

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
S = erp.String

# масЕДРПОУ из ЕРП (А_ВБалансе)
qe = erp.NewObject("Запрос")
qe.УстановитьПараметр("Пусто", "")
qe.Text = ("ВЫБРАТЬ Орг.КодПоЕДРПОУ КАК ЕДРПОУ ИЗ Справочник.Организации КАК Орг\n"
           "ГДЕ Орг.А_ВБалансе = ИСТИНА И Орг.КодПоЕДРПОУ <> &Пусто")
edrpou = [S(r.ЕДРПОУ) for r in qe.Выполнить().Выгрузить()]
print(f"масЕДРПОУ (А_ВБалансе): {len(edrpou)} -> {edrpou}")
masV83 = buh.NewObject("Массив")
for e in edrpou:
    masV83.Добавить(e)

# НОВЫЙ запрос обработки (.Остатки на дату, В ИЕРАРХИИ 66, Кт−Дт)
q_new = buh.NewObject("Запрос")
q_new.УстановитьПараметр("Дата", ДАТА)
q_new.УстановитьПараметр("масЕДРПОУ", masV83)
q_new.Text = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Остатки.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод КАК А_ИдКод,
    Остатки.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    СУММА(Остатки.СуммаОстатокКт) - СУММА(Остатки.СуммаОстатокДт) КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Дата,
       Счет В ИЕРАРХИИ(ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.РасчетыПоОплатеТруда)), , ) КАК Остатки
ГДЕ Остатки.Субконто1 ССЫЛКА Справочник.ФизическиеЛица
    И Остатки.Организация.КодПоЕДРПОУ В (&масЕДРПОУ)
СГРУППИРОВАТЬ ПО
    ВЫРАЗИТЬ(Остатки.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод,
    Остатки.Организация.КодПоЕДРПОУ
ИМЕЮЩИЕ СУММА(Остатки.СуммаОстатокКт) - СУММА(Остатки.СуммаОстатокДт) <> 0
"""
NEW = {}
for r in q_new.Выполнить().Выгрузить():
    NEW[(S(r.А_ИдКод).strip(), S(r.ЕДРПОУ).strip())] = round(float(r.Сумма), 2)
print(f"\n[НОВЫЙ запрос обработки] строк={len(NEW)}, Σ={sum(NEW.values()):,.2f}")

# Запрос отчёта-эталона (.ОстаткиИОбороты, КонОст Кт−Дт на ту же дату)
q_rep = buh.NewObject("Запрос")
q_rep.УстановитьПараметр("НачалоПериода", datetime(2020, 1, 1, 0, 0, 0))
q_rep.УстановитьПараметр("КонецПериода", ДАТА)
q_rep.УстановитьПараметр("масЕДРПОУ", masV83)
q_rep.Text = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод КАК А_ИдКод,
    Ост.Организация.КодПоЕДРПОУ КАК ЕДРПОУ,
    СУММА(Ост.СуммаКонечныйОстатокКт) - СУММА(Ост.СуммаКонечныйОстатокДт) КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&НачалоПериода, &КонецПериода, , , , , ) КАК Ост
ГДЕ Ост.Субконто1 ССЫЛКА Справочник.ФизическиеЛица
    И Ост.Организация.КодПоЕДРПОУ В (&масЕДРПОУ)
    И Ост.Счет В ИЕРАРХИИ(ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.РасчетыПоОплатеТруда))
СГРУППИРОВАТЬ ПО
    ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.ФизическиеЛица).А_ИдКод,
    Ост.Организация.КодПоЕДРПОУ
"""
REP = {}
for r in q_rep.Выполнить().Выгрузить():
    v = round(float(r.Сумма), 2)
    if abs(v) > TOL:
        REP[(S(r.А_ИдКод).strip(), S(r.ЕДРПОУ).strip())] = v
print(f"[Запрос отчёта-эталона]      строк={len(REP)}, Σ={sum(REP.values()):,.2f}")

# Сравнение per (А_ИдКод, ЕДРПОУ)
mism = []
for k in set(NEW) | set(REP):
    if abs(NEW.get(k, 0) - REP.get(k, 0)) > TOL:
        mism.append((k, NEW.get(k, 0), REP.get(k, 0)))
print(f"\nСовпадение per (ФЛ,ЕДРПОУ): расхождений={len(mism)}")
for k, a, b in mism[:10]:
    print(f"   {k}: обработка={a:,.2f} отчёт={b:,.2f}")
assert not mism, "FAIL: суммы обработки != суммы отчёта"

# Резолв А_ИдКод -> ЕРП ФЛ
idkods = list({k[0] for k in NEW if k[0]})
resolved = 0
for ik in idkods:
    fl = erp.Справочники.ФизическиеЛица.НайтиПоРеквизиту("А_ИдКод", ik)
    if erp.ЗначениеЗаполнено(fl):
        resolved += 1
print(f"\nРезолв А_ИдКод -> ЕРП ФЛ: {resolved}/{len(idkods)} ({100*resolved//max(1,len(idkods))}%)")

print("\n" + "=" * 80)
print(f"✅ PRETEST PASS — запрос обработки 1:1 с отчётом ({len(NEW)} строк, Σ={sum(NEW.values()):,.2f})")
print("=" * 80)
