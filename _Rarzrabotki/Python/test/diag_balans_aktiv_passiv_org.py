def тип_имя(р):
    """Резолв enum-ссылки Тип в 'Актив'/'Пассив'/'' (None/незаполнено)."""
    if not conn.ЗначениеЗаполнено(р):
        return ""
    return картаВС.get(conn.XMLСтрока(р), "?")


def границы(мид):
    qg = conn.NewObject("Запрос")
    qg.Текст = ("ВЫБРАТЬ НАЧАЛОПЕРИОДА(&М,МЕСЯЦ) КАК НМ, "
                "КОНЕЦПЕРИОДА(КОНЕЦПЕРИОДА(&М,МЕСЯЦ),ДЕНЬ) КАК КД")
    qg.УстановитьПараметр("М", мид)
    rg = qg.Выполнить().Выбрать(); rg.Следующий()
    return rg.НМ, rg.КД


def отчет_пап_full(нм, кд):
    """Алгоритм Отчет.УправленческийБаланс: ПОЛНЫЙ ПАП.ОстаткиИОбороты
    (БЕЗ OD-3) + классификация АктивПассив (АктивПассив→Пассив).
    Возврат: {ОргX:{'А':КО,'П':КО,'статьи':{(стX,типБукв):КО}}}."""
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("НМ", нм); q.УстановитьПараметр("КД", кд)
    q.Текст = """ВЫБРАТЬ
        АП.Организация КАК Орг,
        ПРЕДСТАВЛЕНИЕ(АП.Организация) КАК ОргП,
        АП.Статья КАК Ст, ПРЕДСТАВЛЕНИЕ(АП.Статья) КАК СтП,
        ВЫБОР КОГДА ДС.АктивПассив = ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.АктивПассив)
                ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Пассив)
                ИНАЧЕ ДС.АктивПассив КОНЕЦ КАК Тип,
        СУММА(АП.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.ОстаткиИОбороты(&НМ, &КД, Авто, , ) КАК АП
        ЛЕВОЕ СОЕДИНЕНИЕ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК ДС
        ПО АП.Статья = ДС.Ссылка
    СГРУППИРОВАТЬ ПО АП.Организация, ПРЕДСТАВЛЕНИЕ(АП.Организация),
        АП.Статья, ПРЕДСТАВЛЕНИЕ(АП.Статья),
        ВЫБОР КОГДА ДС.АктивПассив = ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.АктивПассив)
                ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Пассив)
                ИНАЧЕ ДС.АктивПассив КОНЕЦ"""
    t = q.Выполнить().Выгрузить()
    res = {}
    for i in range(t.Количество()):
        r = t.Получить(i)
        оргX = conn.XMLСтрока(r.Орг)
        тип = тип_имя(r.Тип)  # "Актив"/"Пассив"/""
        ко = float(r.КО or 0)
        d = res.setdefault(оргX, {"ОргП": str(r.ОргП), "А": 0.0, "П": 0.0,
                                  "Н": 0.0, "статьи": {}})
        if тип == "Актив":
            d["А"] += ко
        elif тип == "Пассив":
            d["П"] += ко
        else:
            d["Н"] += ко  # статья без классификации АктивПассив
        d["статьи"][conn.XMLСтрока(r.Ст)] = (str(r.СтП), тип, ко)
    return res


def регистр_свод(нм, кд):
    """Σ СуммаКонечныйОстаток по регистру А_ОтчетБаланс_Свод за месяц
    (Регистратор = проведённый Документ.А_ФинРез_Баланс с Месяц в [НМ..КД]),
    та же классификация АктивПассив. {ОргX:{...}} аналогично."""
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("НМ", нм); q.УстановитьПараметр("КД", кд)
    q.Текст = """ВЫБРАТЬ
        Р.Организация КАК Орг, ПРЕДСТАВЛЕНИЕ(Р.Организация) КАК ОргП,
        Р.Статья КАК Ст, ПРЕДСТАВЛЕНИЕ(Р.Статья) КАК СтП,
        ВЫБОР КОГДА ДС.АктивПассив = ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.АктивПассив)
                ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Пассив)
                ИНАЧЕ ДС.АктивПассив КОНЕЦ КАК Тип,
        СУММА(Р.СуммаКонечныйОстаток) КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Р
        ЛЕВОЕ СОЕДИНЕНИЕ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК ДС
        ПО Р.Статья = ДС.Ссылка
    ГДЕ Р.Регистратор В (
            ВЫБРАТЬ ФР.Ссылка ИЗ Документ.А_ФинРез_Баланс КАК ФР
            ГДЕ ФР.Проведен И НЕ ФР.ПометкаУдаления
                И ФР.Месяц >= &НМ И ФР.Месяц <= &КД)
    СГРУППИРОВАТЬ ПО Р.Организация, ПРЕДСТАВЛЕНИЕ(Р.Организация),
        Р.Статья, ПРЕДСТАВЛЕНИЕ(Р.Статья),
        ВЫБОР КОГДА ДС.АктивПассив = ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.АктивПассив)
                ТОГДА ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Пассив)
                ИНАЧЕ ДС.АктивПассив КОНЕЦ"""
    t = q.Выполнить().Выгрузить()
    res = {}
    for i in range(t.Количество()):
        r = t.Получить(i)
        оргX = conn.XMLСтрока(r.Орг)
        тип = str(r.Тип)
        ко = float(r.КО or 0)
        d = res.setdefault(оргX, {"ОргП": str(r.ОргП), "А": 0.0, "П": 0.0,
                                  "Н": 0.0, "статьи": {}})
        if тип == "Актив":
            d["А"] += ко
        elif тип == "Пассив":
            d["П"] += ко
        else:
            d["Н"] += ко
        d["статьи"][conn.XMLСтрока(r.Ст)] = (str(r.СтП), тип, ко)
    return res


for имя, мид in ПЕРИОДЫ:
    НМ, КД = границы(мид)
    print(f"\n{'='*78}\n=== {имя}: период {НМ} .. {КД} (серверно) ===\n{'='*78}")
    отч = отчет_пап_full(НМ, КД)
    рег = регистр_свод(НМ, КД)

    орги = sorted(set(отч) | set(рег),
                  key=lambda o: -(abs(отч.get(o, {}).get("А", 0))
                                  + abs(отч.get(o, {}).get("П", 0))))
    for оргX in орги:
        o = отч.get(оргX, {"ОргП": "?", "А": 0, "П": 0, "Н": 0, "статьи": {}})
        g = рег.get(оргX)
        оргИмя = o["ОргП"] if o["ОргП"] != "?" else (g["ОргП"] if g else оргX)
        о_нетто = o["А"] + o["П"] + o["Н"]
        print(f"\n--- Организация: {оргИмя} ---")
        print(f"  [ОТЧЁТ ПАП-full] Актив={o['А']:,.2f}  Пассив={o['П']:,.2f}  "
              f"безТипа={o['Н']:,.2f}  НЕТТО(А+П+безтипа)={о_нетто:,.2f}")
        if g is None:
            print("  [РЕГИСТР] нет данных (нет проведённого А_ФинРез_Баланс "
                  "за этот месяц по орг)")
            continue
        г_нетто = g["А"] + g["П"] + g["Н"]
        print(f"  [РЕГИСТР  Свод ] Актив={g['А']:,.2f}  Пассив={g['П']:,.2f}  "
              f"безТипа={g['Н']:,.2f}  НЕТТО={г_нетто:,.2f}")
        print(f"  Δ(отчёт−регистр): Актив={o['А']-g['А']:,.2f}  "
              f"Пассив={o['П']-g['П']:,.2f}  НЕТТО={о_нетто-г_нетто:,.2f}")

        # декомпозиция: статьи отчёта, которых нет/мало в регистре
        gap = []
        od3_sum = 0.0
        for стX, (стН, тип, око) in o["статьи"].items():
            гко = g["статьи"].get(стX, (стН, тип, 0.0))[2]
            d = око - гко
            if abs(d) > 0.01:
                метка = "OD-3-капитал" if стX in OD3 else "не покрыта/Δ"
                if стX in OD3:
                    od3_sum += d
                gap.append((abs(d), стН, тип, око, гко, d, метка))
        gap.sort(reverse=True)
        if gap:
            print(f"  Расхождение по статьям (|Δ|>0.01), топ-12 из {len(gap)} "
                  f"(Σ OD-3-капитал Δ={od3_sum:,.2f}):")
            for _, стН, тип, око, гко, d, метка in gap[:12]:
                print(f"    {(стН or '')[:34]:34} [{str(тип)[:6]:6}] "
                      f"отчёт={око:,.2f} рег={гко:,.2f} Δ={d:,.2f} «{метка}»")

print(f"\n{'='*78}")
