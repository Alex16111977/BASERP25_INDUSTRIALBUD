# -*- coding: utf-8 -*-
"""
Критерий приёмки §8.5: перепроверка ФормаPL для Постернака после добавления Ф2-премии.

Заполняет ОЗФУ дек.2025 В ПАМЯТИ (без записи): НачисленияУпр (zup_2+Ф2),
затем НачисленнаяЗарплатаИВзносыПоФизлицам + разметку ФормаPL.

Проверяет:
  - Σ Ф1 (Форма1) по Постернаку ≈ GROSS (Σ НачисленияБух) — Ф1 НЕ изменился от премии;
  - Σ Ф2 (Форма2) > 0 — управленческий остаток (включая премию) ушёл в Форма2;
  - total = Ф1 + Ф2 сохранён.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

FIO = "Постернак"

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ А.Ссылка КАК Ссылка, А.Номер КАК Номер
ИЗ Документ.А_ОтражениеЗПпоКазне КАК А
ГДЕ А.Дата >= ДАТАВРЕМЯ(2025,12,1,0,0,0) И А.Дата <= ДАТАВРЕМЯ(2025,12,31,23,59,59)
УПОРЯДОЧИТЬ ПО А.Дата
"""
sel = q.Execute().Выбрать()
sel.Следующий()
obj = sel.Ссылка.ПолучитьОбъект()
print(f"Документ №{sel.Номер}, заповнюємо в пам'яті...")

obj.ЗаполнитьНачисленияУпризЗуп2()
obj.ЗаполнитьДляОтражения_ДокументОтражениеЗарплатыВФинансовомУчете()

ф1_имя = erp.XMLСтрока(erp.Перечисления.А_ФормыPL.Форма1)
ф2_имя = erp.XMLСтрока(erp.Перечисления.А_ФормыPL.Форма2)

print(f"  НачисленияБух рядків: {obj.НачисленияБух.Количество()}")
print(f"  НачисленнаяЗарплатаИВзносыПоФизлицам рядків: {obj.НачисленнаяЗарплатаИВзносыПоФизлицам.Количество()}")

# GROSS из НачисленияБух (фильтр по представлению ссылки через серверный Строка())
gross = 0.0
for row in obj.НачисленияБух:
    if FIO in erp.String(row.ФизЛицо):
        gross += float(row.Сумма)

# Разметка ФормаPL в НачисленнаяЗарплатаИВзносыПоФизлицам
ф1_sum = ф2_sum = total = 0.0
nf1 = nf2 = 0
for row in obj.НачисленнаяЗарплатаИВзносыПоФизлицам:
    if FIO not in erp.String(row.ФизическоеЛицо):
        continue
    s = float(row.Сумма)
    total += s
    form = erp.XMLСтрока(row.ФормаPL)
    if form == ф1_имя:
        ф1_sum += s; nf1 += 1
    elif form == ф2_имя:
        ф2_sum += s; nf2 += 1

print(f"\nПостернак:")
print(f"  GROSS (НачисленняБух)       = {gross:,.2f}")
print(f"  НачисленнаяЗП total         = {total:,.2f}  ({nf1+nf2} рядків)")
print(f"  Форма1 (офіційна, =GROSS)   = {ф1_sum:,.2f}  ({nf1} рядків)")
print(f"  Форма2 (управ/премія)       = {ф2_sum:,.2f}  ({nf2} рядків)")

ok = True
if abs(ф1_sum - gross) > 1.0:
    print(f"FAIL: Ф1={ф1_sum} != GROSS={gross} (Ф1 має дорівнювати офіційному GROSS)"); ok = False
if ф2_sum <= 0:
    print("FAIL: Ф2 <= 0 — премія Форма2 не потрапила в управлінський залишок"); ok = False
if abs((ф1_sum + ф2_sum) - total) > 0.01:
    print("FAIL: Ф1+Ф2 != total (втрата суми при розмітці)"); ok = False

print("\nOK: ФормаPL коректна — Ф1=GROSS незмінний, Ф2 містить премію" if ok else "\nFAIL")
sys.exit(0 if ok else 1)
