def parent_walk(acc, target_code):
    cur = acc
    guard = 0
    while buh.ЗначениеЗаполнено(cur) and guard < 30:
        if cur.Код == target_code:
            return True
        cur = cur.Родитель
        guard += 1
    return False

a1 = parent_walk(сч221, "22")
a2 = parent_walk(сч20, "22")
