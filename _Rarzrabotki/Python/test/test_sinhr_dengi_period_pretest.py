# -*- coding: utf-8 -*-
"""Претест (Rule #-1) для доработки А_СинхронизироватьДеньги: поток Бух-документа
по счёту с РАЗДЕЛЕНИЕМ «в периоде» / «за всё время».

Проверяем ровно тот текст запроса, который пойдёт в BSL (ПотокДокументаПоСчетуBuhBud).
Эталон: документ Бух 000007292 от 26.05.2026 (пара апрельской выписки DL-00010179),
счёт ОТП. При периоде 01.04–30.04.2026 ожидаем: в периоде 0, всего 8 000 000.
"""
import datetime
import sys

import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN_BUH = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
IBAN_OTP = "UA973005280000026004000010559"

# Текст 1:1 как пойдёт в BSL (V83-сторона выполняется в BuhBud).
Q_POTOK = """
ВЫБРАТЬ
	СУММА(Т.ПриходП) - СУММА(Т.РасходП) КАК СуммаПериод,
	СУММА(Т.ПриходВ) - СУММА(Т.РасходВ) КАК СуммаВсего
ИЗ
	(ВЫБРАТЬ
		ВЫБОР КОГДА Д.Период МЕЖДУ &НачП И &КонП ТОГДА Д.Сумма ИНАЧЕ 0 КОНЕЦ КАК ПриходП,
		0 КАК РасходП,
		Д.Сумма КАК ПриходВ,
		0 КАК РасходВ
	ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(, , Регистратор = &Регистратор, , ) КАК Д
	ГДЕ Д.СчетДт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))
		И Д.СубконтоДт1 = &БанкРахунок

	ОБЪЕДИНИТЬ ВСЕ

	ВЫБРАТЬ
		0,
		ВЫБОР КОГДА Д.Период МЕЖДУ &НачП И &КонП ТОГДА Д.Сумма ИНАЧЕ 0 КОНЕЦ,
		0,
		Д.Сумма
	ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(, , Регистратор = &Регистратор, , ) КАК Д
	ГДЕ Д.СчетКт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))
		И Д.СубконтоКт1 = &БанкРахунок) КАК Т
"""

# Fallback (когда счёт Бух не найден по IBAN) — тоже с периодом.
Q_FALLBACK = """
ВЫБРАТЬ
	СУММА(Т.ПриходП) - СУММА(Т.РасходП) КАК СуммаПериод,
	СУММА(Т.ПриходВ) - СУММА(Т.РасходВ) КАК СуммаВсего
ИЗ
	(ВЫБРАТЬ
		ВЫБОР КОГДА Д.Период МЕЖДУ &НачП И &КонП ТОГДА Д.Сумма ИНАЧЕ 0 КОНЕЦ КАК ПриходП,
		0 КАК РасходП,
		Д.Сумма КАК ПриходВ,
		0 КАК РасходВ
	ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д
	ГДЕ Д.Регистратор = &Регистратор
		И Д.СчетДт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))

	ОБЪЕДИНИТЬ ВСЕ

	ВЫБРАТЬ
		0,
		ВЫБОР КОГДА Д.Период МЕЖДУ &НачП И &КонП ТОГДА Д.Сумма ИНАЧЕ 0 КОНЕЦ,
		0,
		Д.Сумма
	ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д
	ГДЕ Д.Регистратор = &Регистратор
		И Д.СчетКт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))) КАК Т
"""

FAILS = []


def check(cond, msg):
    print(("  [OK]   " if cond else "  [FAIL] ") + msg, flush=True)
    if not cond:
        FAILS.append(msg)


v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect(CONN_BUH)
S = buh.String

nach = datetime.datetime(2026, 4, 1)
kon = datetime.datetime(2026, 4, 30, 23, 59, 59)

# ⚠️ Счёт в BuhBud искать ПО UUID (обмен хранит 1:1), а НЕ по IBAN: по этому IBAN
# в BuhBud два элемента-двойника, и поиск по номеру отдаёт пустышку с наименованием
# «UA9730…» — по ней движений нет и весь претест врёт нулями. Плагин в
# НайтиБанкСчетBuhBud тоже сначала пробует UUID.
UID_OTP_ERP = "ebcb5323-e5fc-11eb-a208-000c299fb278"
bank = buh.Справочники.БанковскиеСчета.ПолучитьСсылку(
    buh.NewObject("УникальныйИдентификатор", UID_OTP_ERP))
assert bank.ПолучитьОбъект() is not None, "счёт ОТП не найден в BuhBud по UUID"
print(f"Счёт Бух (по UUID): {S(bank)}", flush=True)

# Документы-эталоны: (UUID в BuhBud, ожидаемый поток по счёту, комментарий).
# UUID — из ERP-списаний (обмен 1:1); по номеру искать нельзя: номера повторяются
# между годами и дополнены пробелами.
ETALONY = [
    ("92efafe5-5911-11f1-8113-00155dce3d04", 8000000.0,
     "пара DL-00010179 от 16.04, проведён 26.05 — ВНЕ апреля"),
    ("4ed0888b-4fa6-11f1-8111-00155dce3d04", 5000000.0,
     "пара DL-00010511 от 30.04, проведён 14.05 — ВНЕ апреля"),
]

print("\n=== Основной запрос (по субконто банковского счёта) ===", flush=True)
for uid, ozhid, comment in ETALONY:
    qd = buh.NewObject("Запрос")
    qd.SetParameter("Ссылка", buh.Документы.СписаниеСРасчетногоСчета.ПолучитьСсылку(
        buh.NewObject("УникальныйИдентификатор", uid)))
    qd.Text = """
ВЫБРАТЬ Д.Ссылка КАК Ссылка, Д.Дата КАК Дата, Д.Номер КАК Номер
ИЗ Документ.СписаниеСРасчетногоСчета КАК Д
ГДЕ Д.Ссылка = &Ссылка
"""
    rd = qd.Execute().Выгрузить()
    if rd.Количество() == 0:
        check(False, f"документ {uid} не найден в BuhBud")
        continue
    doc = rd.Получить(0)
    nomer = str(S(doc.Номер)).strip()

    qp = buh.NewObject("Запрос")
    qp.Text = Q_POTOK
    qp.SetParameter("НачП", nach)
    qp.SetParameter("КонП", kon)
    qp.SetParameter("Регистратор", doc.Ссылка)
    qp.SetParameter("БанкРахунок", bank)
    try:
        res = qp.Execute().Выгрузить().Получить(0)
    except Exception as e:
        info = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
        check(False, f"{nomer}: запрос упал — {info}")
        continue

    per = float(res.СуммаПериод or 0)
    vse = float(res.СуммаВсего or 0)
    print(f"  {nomer} от {doc.Дата:%d.%m.%Y} ({comment})", flush=True)
    print(f"      в периоде = {per:,.2f}; всего = {vse:,.2f}", flush=True)
    check(abs(per) < 0.005, f"{nomer}: поток В ПЕРИОДЕ = 0 (сейчас плагин видит {vse:,.2f})")
    check(abs(vse - ozhid) < 0.005, f"{nomer}: поток ВСЕГО = {ozhid:,.2f}")

print("\n=== Контроль: документ, проведённый В периоде, не должен сломаться ===",
      flush=True)
qin = buh.NewObject("Запрос")
qin.SetParameter("Нач", nach)
qin.SetParameter("Кон", kon)
qin.SetParameter("Банк", bank)
qin.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
	Д.Регистратор КАК Регистратор,
	Д.Сумма КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(&Нач, &Кон, , , ) КАК Д
ГДЕ Д.СчетДт В ИЕРАРХИИ (ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.СчетаВБанках))
	И Д.СубконтоДт1 = &Банк
	И Д.Сумма > 1000
"""
rin = qin.Execute().Выгрузить()
if rin.Количество():
    reg = rin.Получить(0).Регистратор
    qp = buh.NewObject("Запрос")
    qp.Text = Q_POTOK
    qp.SetParameter("НачП", nach)
    qp.SetParameter("КонП", kon)
    qp.SetParameter("Регистратор", reg)
    qp.SetParameter("БанкРахунок", bank)
    res = qp.Execute().Выгрузить().Получить(0)
    per, vse = float(res.СуммаПериод or 0), float(res.СуммаВсего or 0)
    print(f"  {S(reg)}: в периоде {per:,.2f}, всего {vse:,.2f}", flush=True)
    check(abs(per) > 0.005, "документ периода даёт НЕнулевой поток в периоде")
    check(abs(per - vse) < 0.005,
          "у документа периода «в периоде» == «всего» (регрессии нет)")
else:
    check(False, "не нашёл документ Бух периода для контроля")

print("\n=== Fallback-запрос (без субконто) ===", flush=True)
qd = buh.NewObject("Запрос")
qd.SetParameter("Ссылка", buh.Документы.СписаниеСРасчетногоСчета.ПолучитьСсылку(
    buh.NewObject("УникальныйИдентификатор", ETALONY[0][0])))
qd.Text = """
ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Документ.СписаниеСРасчетногоСчета КАК Д
ГДЕ Д.Ссылка = &Ссылка
"""
rd = qd.Execute().Выгрузить()
if rd.Количество():
    qf = buh.NewObject("Запрос")
    qf.Text = Q_FALLBACK
    qf.SetParameter("НачП", nach)
    qf.SetParameter("КонП", kon)
    qf.SetParameter("Регистратор", rd.Получить(0).Ссылка)
    try:
        res = qf.Execute().Выгрузить().Получить(0)
        per, vse = float(res.СуммаПериод or 0), float(res.СуммаВсего or 0)
        print(f"  в периоде = {per:,.2f}; всего = {vse:,.2f}", flush=True)
        check(abs(per) < 0.005, "fallback: поток в периоде = 0")
    except Exception as e:
        info = e.excepinfo[2] if getattr(e, "excepinfo", None) else e
        check(False, f"fallback-запрос упал: {info}")

print(f"\nИТОГ: FAIL {len(FAILS)}", flush=True)
for f in FAILS:
    print(f"  FAIL: {f}", flush=True)

buh = None
print("PRETEST OK" if not FAILS else "PRETEST FAILED", flush=True)
sys.exit(1 if FAILS else 0)
