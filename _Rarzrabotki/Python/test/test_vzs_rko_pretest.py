# -*- coding: utf-8 -*-
"""Pre-test (Rule #-1) для процедури ЗаполнитьИзРКО регістра А_ВзаиморасчетыССотрудниками.

Стратегія:
  Джерело ФЛ — ТЧ ВыплатаЗаработнойПлаты документа РКО.
  Фільтр: 3 ХозОп виплати ЗП через касу (ВыплатаЗарплатыЧерезКассу/Раздатчиком/Работнику).
  Знак: Расход (виплата → борг ↓), інверсія до ПАП.Приход.
  Підрозділ: з шапки документа (Подразделение); якщо порожній — Пуст.
  Свертка per (Орг, Подр, ФЛ) — як у СБДС/ОЗФУ.

Asserts per Регістратор:
  1) |Σ_наш − (−Σ_PAP)| ≤ 1 ₽ (інваріант: А_ВзСС + ПАП = 0)
  2) 100% строк мають ФЛ ≠ Пуст
  3) 0 дублів ключа (Орг, Подр, ФЛ)
"""
import sys, io, json
from collections import defaultdict
from datetime import datetime
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

# Параметри
qOT = conn.NewObject("Запрос")
qOT.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Оплата труда"')
rOT = qOT.Выполнить().Выбрать(); rOT.Следующий(); ОТ = rOT.С

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

НМ = datetime(2025, 12, 1, 12, 0, 0)
КД = datetime(2026, 3, 1, 12, 0, 0)

# Знайти усіх кандидатів РКО з ПАП(ОТ)
qPap = conn.NewObject("Запрос")
qPap.Текст = """
ВЫБРАТЬ
    ПАП.Регистратор КАК Док,
    МАКСИМУМ(ПАП.Регистратор.Номер) КАК Номер,
    МАКСИМУМ(ПАП.Регистратор.Дата) КАК Дата,
    СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
        ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Σ_signed
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Период МЕЖДУ &НМ И &КД И ПАП.Организация = &Орг
    И ПАП.Статья = &ОТ
    И ПАП.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)
    И ТИПЗНАЧЕНИЯ(ПАП.Регистратор) = ТИП(Документ.РасходныйКассовыйОрдер)
СГРУППИРОВАТЬ ПО ПАП.Регистратор
УПОРЯДОЧИТЬ ПО Дата
"""
qPap.УстановитьПараметр("НМ", НМ); qPap.УстановитьПараметр("КД", КД)
qPap.УстановитьПараметр("Орг", ORG); qPap.УстановитьПараметр("ОТ", ОТ)
res_pap = qPap.Выполнить().Выгрузить()
print(f"[INFO] Кандидатів РКО з ПАП(ОТ) за дек'25-фев'26: {res_pap.Количество()}")

if res_pap.Количество() == 0:
    print("[OK] PASS тривіально")
    sys.exit(0)

# Запит-кандидат для BSL
qT = conn.NewObject("Запрос")
qT.Текст = """
ВЫБРАТЬ
    Д.Организация КАК Организация,
    Д.Подразделение КАК Подразделение,
    ТЧ.ФизическоеЛицо КАК ФизическоеЛицо,
    ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход) КАК ВидДвижения,
    СУММА(ТЧ.Сумма) КАК СуммаВзаиморасчетов
ИЗ
    Документ.РасходныйКассовыйОрдер КАК Д
        ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.РасходныйКассовыйОрдер.ВыплатаЗаработнойПлаты КАК ТЧ
            ПО ТЧ.Ссылка = Д.Ссылка
ГДЕ
    Д.Ссылка = &Док
    И Д.ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаздатчиком),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику))
СГРУППИРОВАТЬ ПО Д.Организация, Д.Подразделение, ТЧ.ФизическоеЛицо
ИМЕЮЩИЕ СУММА(ТЧ.Сумма) <> 0
"""

# Asserts
all_pass = True
fl_total = 0
fl_empty = 0
candidates = []
for i in range(res_pap.Количество()):
    pap_row = res_pap.Получить(i)
    док = pap_row.Док
    qT.УстановитьПараметр("Док", док)
    our = qT.Выполнить().Выгрузить()
    Σ_naash_abs = 0.0
    keys = defaultdict(int)
    for j in range(our.Количество()):
        s = our.Получить(j)
        Σ_naash_abs += float(s.СуммаВзаиморасчетов)
        ключ = (S(s.Организация), S(s.Подразделение), S(s.ФизическоеЛицо), S(s.ВидДвижения))
        keys[ключ] += 1
        fl_total += 1
        if not conn.ЗначениеЗаполнено(s.ФизическоеЛицо):
            fl_empty += 1
    Σ_signed_our = -Σ_naash_abs  # наш в інверсії
    Σ_signed_pap = float(pap_row.Σ_signed)
    delta = abs(Σ_signed_our + Σ_signed_pap)
    дублі = sum(1 for v in keys.values() if v > 1)
    status = "PASS" if delta <= TOL_RUB and дублі == 0 else "FAIL"
    if status == "FAIL":
        all_pass = False
    print(f"  №{pap_row.Номер.strip():>14} ({pap_row.Дата.strftime('%Y-%m-%d')}): "
          f"Σ_наш={Σ_signed_our:>+12,.2f} Σ_PAP={Σ_signed_pap:>+12,.2f} |Δ|={delta:>8,.2f} "
          f"рядків={our.Количество()} дублі={дублі} [{status}]")
    candidates.append({
        "uuid": S(док.УникальныйИдентификатор()),
        "number": pap_row.Номер.strip(),
        "date": pap_row.Дата.isoformat(),
        "sigma_pap": Σ_signed_pap,
        "sigma_our": Σ_signed_our,
        "rows": our.Количество(),
    })

# Доля ФЛ
fl_доля = 100.0 * (fl_total - fl_empty) / max(1, fl_total)
print(f"\n[ФЛ] Усього рядків: {fl_total}; з ФЛ={fl_total - fl_empty} ({fl_доля:.1f}%); пустих={fl_empty}")
if fl_доля < 99.0:
    print("[FAIL] Доля ФЛ < 99%")
    all_pass = False

# Зберегти кандидатів
out_path = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test\rko_candidates.json"
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(candidates, f, ensure_ascii=False, indent=2)
print(f"\n[SAVED] {out_path} ({len(candidates)} кандидатів)")
print(f"\n{'[OK] PASS' if all_pass else '[FAIL]'}")
sys.exit(0 if all_pass else 1)
