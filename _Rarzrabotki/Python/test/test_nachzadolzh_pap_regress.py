# -*- coding: utf-8 -*-
"""Регресс Фаза 1: регистр свёртки == ПАП(все источники) по КАЖДОЙ статье (янв 2026),
кроме иерархии «Собственные средства»; полный баланс=0; «Прибыли и убытки» += долг."""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

pythoncom.CoInitialize()
erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

def f(x):
    try: return float(x)
    except: return 0.0

# регистр свёртки янв по статьям
qr = erp.NewObject("Запрос")
qr.Текст = """ВЫБРАТЬ Рег.Статья.Наименование КАК Ст, СУММА(Рег.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК Рег ГДЕ Рег.Регистратор.Месяц=ДАТАВРЕМЯ(2026,1,1)
СГРУППИРОВАТЬ ПО Рег.Статья.Наименование"""
reg = {str(r.Ст): f(r.КО) for r in qr.Выполнить().Выгрузить()}

# ПАП(все ист) янв, исключая иерархию Собственные средства
qss = erp.NewObject("Запрос")
qss.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Собственные средства"')
СС = qss.Выполнить().Выгрузить()[0].С
qp = erp.NewObject("Запрос"); qp.УстановитьПараметр("СС", СС)
qp.Текст = """ВЫБРАТЬ Т.Статья.Наименование КАК Ст,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Период <= ДАТАВРЕМЯ(2026,1,31,23,59,59) И НЕ Т.Статья В ИЕРАРХИИ(&СС)
СГРУППИРОВАТЬ ПО Т.Статья.Наименование"""
pap = {str(r.Ст): f(r.КО) for r in qp.Выполнить().Выгрузить()}

TOL=0.05; fails=[]
print(f"{'Статья':<42} | {'регистр КО':>16} | {'ПАП КО':>16} | {'Δ':>10}")
for a in sorted(set(reg)|set(pap)):
    rg=reg.get(a,0.0); pp=pap.get(a,0.0); d=rg-pp
    if abs(d)>TOL: fails.append((a,rg,pp))
    mark = 'OK' if abs(d)<=TOL else 'FAIL'
    print(f"  {a:<40} | {rg:>16,.2f} | {pp:>16,.2f} | {d:>10,.2f} {mark}")
print(f"\nΣ регистр (баланс) = {sum(reg.values()):,.2f}  (эталон ~0)")
print(f"«Прибыли и убытки» = {reg.get('Прибыли и убытки',0):,.2f} (было −116 622 011,19; ожидаем +3,17М смещение)")
print(f"«Оплата труда» = {reg.get('Оплата труда',0):,.2f}; «Денежные средства (наличные)» = {reg.get('Денежные средства (наличные)',0):,.2f}")
print("\nREGRESS PASS — регистр==ПАП по всем статьям, баланс цел." if not fails and abs(sum(reg.values()))<0.5
      else f"REGRESS FAIL: {fails}")
sys.exit(0 if (not fails and abs(sum(reg.values()))<0.5) else 1)
