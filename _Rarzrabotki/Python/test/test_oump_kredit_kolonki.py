# -*- coding: utf-8 -*-
"""ОУМП, кредитные договоры: автозаполнение колонок Деньги (объекты в памяти, НЕ записываются)."""
import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
erp = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String
Т = erp.Перечисления.ТипыДоговоров
ok = True


def check(c, m):
    global ok
    print(("OK  " if c else "FAIL") + " " + m)
    ok = ok and bool(c)


def doc(num):
    q = erp.NewObject("Запрос")
    q.Text = 'ВЫБРАТЬ Д.Ссылка ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями КАК Д ГДЕ Д.Номер = &Н'
    q.SetParameter("Н", num)
    return q.Execute().Выгрузить().Получить(0).Получить(0).ПолучитьОбъект()


# 581: Строительство (Финансовая помощь) → МД IRC 2026 (Получение финансовой помощи)
О = doc("000000581")
check(О.Кредитование, "581 отмечен «Кредитование»")
С = О.Деньги.Получить(0)
for f in ("КонтрагентРасход", "ВидДоговораРасход", "КонтрагентПриход", "ВидДоговораПриход"):
    setattr(С, f, getattr(erp.Справочники.Контрагенты if f.startswith("Контр") else erp.Перечисления.А_ВидыКредитныхДоговоров, "ПустаяСсылка")())
О.А_ЗаполнитьКредитныеКолонкиДеньги()
check(S(С.ВидДоговораРасход) == "Нераспределенная прибыль", f"581 вид расхода: {S(С.ВидДоговораРасход)}")
check(S(С.КонтрагентРасход) == "Воронцов Олександр Володимирович", f"581 контрагент расхода: {S(С.КонтрагентРасход)}")
check(S(С.ВидДоговораПриход) == "Тело кредита", f"581 вид прихода: {S(С.ВидДоговораПриход)}")
check(S(С.КонтрагентПриход) == "МД IRS 2026", f"581 контрагент прихода (контрагент подразделения): {S(С.КонтрагентПриход)}")

# ручная правка не затирается
Другой = erp.Справочники.Контрагенты.НайтиПоНаименованию("ВОРОНЦОВА АННА ВАЛЕРІЇВНА", True)  # поиск по имени регистронезависим
С.КонтрагентПриход = Другой
О.А_ЗаполнитьКредитныеКолонкиДеньги()
check(S(С.КонтрагентПриход) == "ВОРОНЦОВА АННА ВАЛЕРІЇВНА", "ручной контрагент прихода сохранён")

# кредитные стороны 581 (без создания документов): расход — НП Строительство, приход — тело МД IRC 2026
С.КонтрагентПриход = erp.Справочники.Контрагенты.ПустаяСсылка()
О.А_ЗаполнитьКредитныеКолонкиДеньги()
Р = О.А_КредитнаяСторона(С, True, Т.СПоставщиком)
check(S(Р.Договор) == "Нераспределенная прибыль -- Строительство", f"581 договор списания: {S(Р.Договор)}")
П = О.А_КредитнаяСторона(С, False, Т.СПокупателем)
check(S(П.Договор) == "Кредитование от кредитора -- МД IRC 2026" and S(П.Договор.Контрагент) == "МД IRS 2026", f"581 договор поступления: {S(П.Договор)} / {S(П.Договор.Контрагент)}")
check(S(П.Договор.А_СтатьяБаланса) == "Задолженность по кредитам", "новый договор тела → статья баланса «Задолженность по кредитам»")

# регрессия: строка без кредитных статей — обе стороны идут прежним подбором
q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка.Номер КАК Номер
ИЗ Документ.А_ОказаниеУслугМеждуПодразделениями.Деньги КАК Д
ГДЕ НЕ Д.Ссылка.ПометкаУдаления
	И Д.СтатьяДвиженияДенежныхСредствРасход.А_ВидКредитногоДоговора = ЗНАЧЕНИЕ(Перечисление.А_ВидыКредитныхДоговоров.ПустаяСсылка)
	И Д.СтатьяДвиженияДенежныхСредствПриход.А_ВидКредитногоДоговора = ЗНАЧЕНИЕ(Перечисление.А_ВидыКредитныхДоговоров.ПустаяСсылка)
	И Д.Ссылка.Дата >= ДАТАВРЕМЯ(2026, 7, 1)
УПОРЯДОЧИТЬ ПО Д.Ссылка.Дата УБЫВ"""
num = S(q.Execute().Выгрузить().Получить(0).Получить(0))
О2 = doc(num)
О2.А_ЗаполнитьКредитныеКолонкиДеньги()
# флаг снят → колонки не заполняются даже у кредитного документа
О3 = doc("000000581")
О3.Кредитование = False
С3 = О3.Деньги.Получить(0)
С3.КонтрагентПриход = erp.Справочники.Контрагенты.ПустаяСсылка()
О3.А_ЗаполнитьКредитныеКолонкиДеньги()
check(not S(С3.КонтрагентПриход), "флаг снят → колонки не заполняются")
С2 = О2.Деньги.Получить(0)
check(О2.А_КредитнаяСторона(С2, True, Т.СПоставщиком) is None and О2.А_КредитнаяСторона(С2, False, Т.СПокупателем) is None,
      f"регрессия {num}: обычная строка → прежний подбор")
# возврат тела: 591 Глобино-2 → Строительство — тип «Возврат», стороны зеркальны
О4 = doc("000000591")
С4 = О4.Деньги.Получить(0)
С4.ТипыРасчетаДенежнымиСредствами = erp.Перечисления.ТипыРасчетаДенежнымиСредствами.РасходДенежныхСредств
О4.А_ЗаполнитьКредитныеКолонкиДеньги()
check(S(С4.ТипыРасчетаДенежнымиСредствами) == "Возврат денежных средств", "591: тело на стороне расхода → тип «Возврат»")
check(S(С4.КонтрагентРасход) == "Глобино-2" and S(С4.КонтрагентПриход) == "Воронцов Олександр Володимирович", "591: расход — заёмщик, приход — Воронцов")
sys.exit(0 if ok else 1)
