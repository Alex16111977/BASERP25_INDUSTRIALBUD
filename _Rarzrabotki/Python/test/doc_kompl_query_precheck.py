# -*- coding: utf-8 -*-
"""Rule #-1 pre-check двух новых запросов документа РасчетКомплектаций (bas_industrialbud)."""
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# --- 1. Паттерн запроса дублей (на КомплектацияНоменклатуры: шапка + ТЧ, диапазон дат, В (&Массив)) ---
q = buh.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	Док.Ссылка КАК Ссылка
ИЗ
	Документ.КомплектацияНоменклатуры КАК Док
		ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.КомплектацияНоменклатуры.Комплектующие КАК Строки
		ПО Строки.Ссылка = Док.Ссылка
ГДЕ
	НЕ Док.ПометкаУдаления
	И Док.Ссылка <> &Ссылка
	И Док.Дата МЕЖДУ &НачалоДня И &КонецДня
	И Строки.Номенклатура В (&СписокЗначений)
"""
q.SetParameter("Ссылка", buh.Документы.КомплектацияНоменклатуры.ПустаяСсылка())
q.SetParameter("НачалоДня", datetime.datetime(2026, 1, 1, 0, 0, 0))
q.SetParameter("КонецДня", datetime.datetime(2026, 12, 31, 23, 59, 59))
arr = buh.NewObject("Массив")
q.SetParameter("СписокЗначений", arr)
try:
    r = q.Execute().Выгрузить()
    print(f"OK дубль-паттерн, рядків={r.Количество()}")
except Exception as e:
    print(f"FAIL дубль-паттерн: {e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e}")
    sys.exit(1)

# --- 0. Живая пара Номенклатура+Склад из остатков (для теста автоподбора) ---
sch = buh.NewObject("Массив")
for kod in ("20", "22", "28"):
    s = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду(kod)
    sch.Добавить(s)
q0 = buh.NewObject("Запрос")
q0.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
	ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) КАК Ном,
	ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) КАК Скл
ИЗ
	РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ (&Счета), , ) КАК Ост
ГДЕ
	Ост.КоличествоОстаток > 0
"""
q0.SetParameter("НаДату", datetime.datetime(2026, 7, 7, 23, 59, 59))
q0.SetParameter("Счета", sch)
vb = q0.Execute().Выбрать()
assert vb.Следующий(), "нет остатков для теста"
ном, скл = vb.Ном, vb.Скл

# --- 2. Автоподбор остатка строки (боевой текст ДанныеОстаткаДляСтроки) ---
q2 = buh.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1
	Ост.Счет КАК Счет,
	ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).БазоваяЕдиницаИзмерения КАК Единица,
	ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).ОбщееНазваниеНоменклатуры КАК ОбщееНазвание,
	Ост.КоличествоОстаток КАК Остаток,
	Ост.СуммаОстаток КАК СуммаОстатка
ИЗ
	РегистрБухгалтерии.Хозрасчетный.Остатки(&НаДату, Счет В ИЕРАРХИИ (&Счета), , ) КАК Ост
ГДЕ
	Ост.КоличествоОстаток > 0
	И ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура) = &Номенклатура
	И ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Склады) = &Склад
	И (&Организация = ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка)
		ИЛИ Ост.Организация = &Организация)

УПОРЯДОЧИТЬ ПО
	Остаток УБЫВ
"""
q2.SetParameter("НаДату", datetime.datetime(2026, 7, 7, 23, 59, 59))
q2.SetParameter("Счета", sch)
q2.SetParameter("Организация", buh.Справочники.Организации.ПустаяСсылка())
q2.SetParameter("Номенклатура", ном)
q2.SetParameter("Склад", скл)
try:
    r2 = q2.Execute().Выгрузить()
    assert r2.Количество() == 1, "автоподбор вернул не 1 строку"
    st = r2.Получить(0)
    цена = round(st.СуммаОстатка / st.Остаток, 2) if st.Остаток else 0
    print(f"OK автоподбор: счёт={st.Счет.Код}, остаток={st.Остаток}, цена(безПДВ)={цена}, ном={ном.Наименование}")
except Exception as e:
    print(f"FAIL автоподбор: {e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e}")
    sys.exit(1)

print("PRECHECK PASS")
