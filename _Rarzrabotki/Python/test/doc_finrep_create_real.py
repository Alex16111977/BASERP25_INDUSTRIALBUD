# -*- coding: utf-8 -*-
"""Создание боевого документа А_ФинансовыйОтчетПроизводства в bas_industrialbud.

Отбор по направлению «Производство» (в справочнике Направления значение записано по-русски).
Дата расчёта — конец дня 07.08.2026, чтобы результат был напрямую сверяем с ручным Excel.
Get-or-create: повторный запуск переиспользует документ с тем же маркером в комментарии,
новых не плодит и ничего не удаляет.
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding='utf-8')
buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

МАРКЕР = "Фінансовий звіт виробництва на 07.08.2026 (напрямок «Производство»)"


def дата(г, м, д, ч=0, мин=0, с=0):
    q = buh.NewObject("Запрос")
    q.Текст = f"ВЫБРАТЬ ДАТАВРЕМЯ({г},{м},{д},{ч},{мин},{с}) КАК Д"
    return q.Execute().Выгрузить().Получить(0).Д


# --- get-or-create по маркеру в комментарии (Комментарий — Строка неограниченной длины)
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Д.Ссылка КАК С, Д.Номер КАК Номер
ИЗ Документ.А_ФинансовыйОтчетПроизводства КАК Д
ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК Строка(200)) = &Маркер И НЕ Д.ПометкаУдаления"""
q.УстановитьПараметр("Маркер", МАРКЕР)
найдено = q.Execute().Выгрузить()

if найдено.Количество() > 0:
    ссылка = найдено.Получить(0).С
    док = ссылка.ПолучитьОбъект()
    print(f"Знайдено наявний документ № {str(найдено.Получить(0).Номер).strip()} — перезаповнюємо")
else:
    док = buh.Документы.А_ФинансовыйОтчетПроизводства.СоздатьДокумент()
    док.Заполнить(None)
    print("Створюємо новий документ")

# --- шапка
док.Дата        = дата(2026, 8, 7, 12, 0, 0)
док.ДатаРасчета = дата(2026, 8, 7, 23, 59, 59)
док.Направление = buh.Справочники.Направления.НайтиПоНаименованию("Производство", True)
# СтавкаНДС і ЗаголовокОтчета прибрано з реквізитів 16.08.2026: ставка константна у коді,
# заголовок друку будується з дати розрахунку
док.ВключатьНепроведенные = True
док.ЗаполнятьТолькоСДвижениями = True
док.Комментарий = МАРКЕР

пользователь = buh.Справочники.Пользователи.НайтиПоНаименованию("cfo", True)
if пользователь is not None and not пользователь.Пустая():
    док.Ответственный = пользователь

if док.СчетаРасчетов.Количество() == 0:
    док.СчетаРасчетов.Добавить().Счет = buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("361")

print(f"  напрямок: {док.Направление.Наименование}")
print(f"  дата розрахунку: {док.ДатаРасчета}")

# --- подразделения по направлению (только с движениями)
док.Подразделения.Очистить()
док.ЗаполнитьПодразделенияПоУмолчанию(True)
print(f"  підрозділів заповнено: {док.Подразделения.Количество()}")

# Два варіанти формули, перевірені на Excel-еталоні. Решті — типовий варіант за замовчуванням;
# коригування та виключення НЕ проставляємо — це рішення користувача.
Ф = buh.Перечисления.А_ВариантыФормулыИтогаФинотчета
НАСТРОЙКИ = {"МК Кривий ріг": (Ф.ВыполнениеМинусОплата, 15),
             "МД МХП ОРІЛЬ":  (Ф.ВыполнениеМинусОплата, 0)}
for i in range(док.Подразделения.Количество()):
    с = док.Подразделения.Получить(i)
    имя = str(с.Подразделение.Наименование)
    if имя in НАСТРОЙКИ:
        вариант, процент = НАСТРОЙКИ[имя]
        с.ВариантФормулы = вариант
        с.ПроцентУдержания = процент
        print(f"    {имя}: варіант «Виконання − оплата», утримання {процент}%")

# --- расчёт
Результат = док.Рассчитать()
print(f"\nРозрахунок: виконано={bool(Результат.Выполнено)}, помилок={int(Результат.Ошибок)}, "
      f"попереджень={int(Результат.Предупреждений)}, рядків={int(Результат.СтрокРасчета)}")

if not bool(Результат.Выполнено):
    print("РОЗРАХУНОК ЗАБЛОКОВАНО:")
    for i in range(док.Контроль.Количество()):
        к = док.Контроль.Получить(i)
        print(f"   [{к.Уровень}] {к.КодЗамечания}: {к.Текст}")
    sys.exit(1)

# --- запись в базу
док.Записать()
print(f"\nЗАПИСАНО: № {str(док.Номер).strip()} від {док.Дата}")

# --- что получилось
print(f"\n{'ПІДРОЗДІЛ':26}|{'Виконано':>15}|{'Оплачено':>15}|{'Заборг.':>14}|{'Акти':>15}|{'Разом':>15}")
print("-" * 103)
ИтогE = ИтогF = ИтогG = ИтогH = ИтогK = 0
for i in range(док.Расчет.Количество()):
    с = док.Расчет.Получить(i)
    E, F, G = float(с.ВыполненныеРаботы), float(с.Оплачено), float(с.Задолженность)
    H, K = float(с.АктыПоданные), float(с.ИтогоКПолучению)
    print(f"{str(с.Подразделение.Наименование)[:26]:26}|{E:>15,.2f}|{F:>15,.2f}"
          f"|{G:>14,.2f}|{H:>15,.2f}|{K:>15,.2f}")
    ИтогE += E; ИтогF += F; ИтогG += G; ИтогH += H; ИтогK += K
print("-" * 103)
print(f"{'РАЗОМ':26}|{ИтогE:>15,.2f}|{ИтогF:>15,.2f}|{ИтогG:>14,.2f}|{ИтогH:>15,.2f}|{ИтогK:>15,.2f}")

print(f"\nРозшифровка: {док.РасшифровкаДокументов.Количество()} рядків")
print(f"Контроль: {док.Контроль.Количество()} записів")
уровни = {}
for i in range(док.Контроль.Количество()):
    у = str(док.Контроль.Получить(i).Уровень)
    уровни[у] = уровни.get(у, 0) + 1
for у, к in уровни.items():
    print(f"   {у}: {к}")

print("\n=== Попередження і помилки (інформаційні пропущено) ===")
for i in range(док.Контроль.Количество()):
    к = док.Контроль.Получить(i)
    if str(к.Уровень) == "Информация":
        continue
    print(f"  {к.КодЗамечания}: {к.Текст}")

# --- контрольная сверка с Excel по трём известным строкам
print("\n=== Звірка з ручним Excel (там, де еталон відомий) ===")
ЭТАЛОНЫ = {"МК Кривий ріг": {"E": 4713575.00, "F": 4823281.25, "H": 1481816.00},
           "МД МХП ОРІЛЬ":  {"E": 3355204.73, "F": 3355204.73, "H": 0.00},
           "МД IRC 2026":   {"E": 0.00,       "F": 0.00,       "H": 3758899.20}}
for i in range(док.Расчет.Количество()):
    с = док.Расчет.Получить(i)
    имя = str(с.Подразделение.Наименование)
    э = ЭТАЛОНЫ.get(имя)
    if not э:
        continue
    for поле, наш in (("E", float(с.ВыполненныеРаботы)), ("F", float(с.Оплачено)),
                      ("H", float(с.АктыПоданные))):
        знак = "=" if abs(наш - э[поле]) < 0.01 else "≠"
        примечание = "" if знак == "=" else f"   (різниця {наш - э[поле]:+,.2f})"
        print(f"  {имя:16} {поле}: {наш:>15,.2f} {знак} еталон {э[поле]:>15,.2f}{примечание}")

# --- печатные формы отрабатывают на записанном документе
таб = док.СформироватьПечатьОтчет()
print(f"\nДрукована форма «Фінансовий звіт»: {таб.ВысотаТаблицы} рядків, {таб.ШиринаТаблицы} колонок")
таб2 = док.СформироватьПечатьДоклад()
print(f"Друкована форма «Доповідь»: {таб2.ВысотаТаблицы} рядків")
html = str(док.ТекстДокладаHTML())
путь = (r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Доклады по производству"
        r"\Доповідь_фінзвіт_виробництво_07-08-2026.html")
open(путь, "w", encoding="utf-8").write(html)
print(f"Доповідь збережено: {путь}")
