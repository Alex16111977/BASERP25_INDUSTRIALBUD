# -*- coding: utf-8 -*-
"""Smoke-тест обработки «Обновить единицу в общем названии» (BuhBud).

ВНИМАНИЕ: тест РЕАЛЬНО заполняет реквизит Единица справочника
ОбщиеНазванияНоменклатуры — это целевое действие, так задумано.

Схема:
  1. Предвычисляем ожидания СВОИМИ запросами (те же Q1/Q2/Q3, что в BSL)
     + симуляция каскада П1 (мода/ничья) -> П2 (лидер закупок) -> П2б (единственная привязка).
  2. Запускаем обработку через ВнешниеОбработки.Создать(EPF, False).
  3. Сверяем счётчики протокола с ожиданиями.
  4. Повторный запуск: все счётчики заполнения = 0 (идемпотентность).
  5. Финальная проверка: пустых карточек в базе == res.ОсталосьПустых.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Загрузка СС\Обновить единицу в общем названии.epf"
CONN_BUH = 'Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"'

Q1 = """ВЫБРАТЬ
	К.ОбщееНазвание КАК ОбщееНазвание,
	К.Единица КАК Единица,
	КОЛИЧЕСТВО(*) КАК Голосов
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Активная
	И К.ОбщееНазвание <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И К.ОбщееНазвание.Единица = ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)
	И К.Единица <> ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)

СГРУППИРОВАТЬ ПО
	К.ОбщееНазвание, К.Единица

УПОРЯДОЧИТЬ ПО
	ОбщееНазвание, Голосов УБЫВ"""

Q2 = """ВЫБРАТЬ
	Т.Номенклатура.ОбщееНазваниеНоменклатуры КАК ОбщееНазвание,
	Т.Номенклатура.БазоваяЕдиницаИзмерения КАК Единица,
	СУММА(Т.Количество) КАК Куплено,
	СУММА(Т.Сумма) КАК СуммаЗакупок
ИЗ
	Документ.ПоступлениеТоваровУслуг.Товары КАК Т
ГДЕ
	Т.Ссылка.Проведен
	И Т.Номенклатура.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И Т.Номенклатура.ОбщееНазваниеНоменклатуры.Единица = ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)
	И Т.Номенклатура.БазоваяЕдиницаИзмерения <> ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)

СГРУППИРОВАТЬ ПО
	Т.Номенклатура.ОбщееНазваниеНоменклатуры, Т.Номенклатура, Т.Номенклатура.БазоваяЕдиницаИзмерения

УПОРЯДОЧИТЬ ПО
	ОбщееНазвание, Куплено УБЫВ, СуммаЗакупок УБЫВ"""

Q3 = """ВЫБРАТЬ
	Н.ОбщееНазваниеНоменклатуры КАК ОбщееНазвание,
	Н.БазоваяЕдиницаИзмерения КАК Единица,
	КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Н.Ссылка) КАК КолНоменклатур
ИЗ
	Справочник.Номенклатура КАК Н
ГДЕ
	НЕ Н.ЭтоГруппа
	И Н.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И Н.ОбщееНазваниеНоменклатуры.Единица = ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)
	И Н.БазоваяЕдиницаИзмерения <> ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)

СГРУППИРОВАТЬ ПО
	Н.ОбщееНазваниеНоменклатуры, Н.БазоваяЕдиницаИзмерения

УПОРЯДОЧИТЬ ПО
	ОбщееНазвание"""

Q_EMPTY = """ВЫБРАТЬ
	КОЛИЧЕСТВО(*) КАК Кол
ИЗ
	Справочник.ОбщиеНазванияНоменклатуры КАК ОН
ГДЕ
	НЕ ОН.ЭтоГруппа
	И ОН.Единица = ЗНАЧЕНИЕ(Справочник.КлассификаторЕдиницИзмерения.ПустаяСсылка)"""


def vt(buh, text):
    q = buh.NewObject("Запрос")
    q.Text = text
    return q.Execute().Выгрузить()


def uid(buh, ref):
    return buh.String(ref.УникальныйИдентификатор())


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    buh = v8.Connect(CONN_BUH)
    print("Подключение к BuhBud: OK")

    # --- ожидание: пустых карточек ДО запуска ---
    empty_before = int(vt(buh, Q_EMPTY).Получить(0).Кол)
    print(f"Пустых карточек до запуска: {empty_before}")

    # --- симуляция П1: мода/ничья ---
    t1 = vt(buh, Q1)
    groups = {}   # uid -> list of votes (в порядке выборки = убывание)
    order1 = []
    for i in range(t1.Количество()):
        row = t1.Получить(i)
        u = uid(buh, row.ОбщееНазвание)
        if u not in groups:
            groups[u] = []
            order1.append(u)
        groups[u].append(int(row.Голосов))
    p1_fill, p1_tie = set(), set()
    for u in order1:
        votes = groups[u]
        if len(votes) > 1 and votes[0] == votes[1]:
            p1_tie.add(u)
        else:
            p1_fill.add(u)
    exp_p1, exp_tie = len(p1_fill), len(p1_tie)

    # --- симуляция П2: карточки с закупками, не заполненные П1 ---
    t2 = vt(buh, Q2)
    q2_cards = set()
    for i in range(t2.Количество()):
        q2_cards.add(uid(buh, t2.Получить(i).ОбщееНазвание))
    p2_fill = q2_cards - p1_fill
    exp_p2 = len(p2_fill)

    # --- симуляция П2б: ровно одна привязанная номенклатура, не заполнено П1/П2 ---
    t3 = vt(buh, Q3)
    totals = {}
    for i in range(t3.Количество()):
        row = t3.Получить(i)
        u = uid(buh, row.ОбщееНазвание)
        totals[u] = totals.get(u, 0) + int(row.КолНоменклатур)
    singles = {u for u, n in totals.items() if n == 1}
    p2b_fill = singles - p1_fill - p2_fill
    exp_p2b = len(p2b_fill)

    # ничьи, которые заполнит П2/П2б -> при повторе Q1 их уже не увидит
    exp_tie_repeat = len(p1_tie - p2_fill - p2b_fill)
    exp_empty_after = empty_before - exp_p1 - exp_p2 - exp_p2b

    print(f"Ожидания: П1={exp_p1}, ничьих={exp_tie}, П2={exp_p2}, П2б={exp_p2b}, "
          f"останется пустых={exp_empty_after}, ничьих при повторе={exp_tie_repeat}")

    # --- запуск 1 ---
    obr = buh.ВнешниеОбработки.Создать(EPF, False)
    res = obr.ОбновитьВОбщемНазванииЕдиницу()
    assert not res.Ошибка, f"Ошибка обработки: {res.ТекстОшибки}"
    print("\n=== Запуск 1: протокол ===")
    print(f"  ИзСтруктур             = {int(res.ИзСтруктур)}")
    print(f"  ИзНоменклатуры         = {int(res.ИзНоменклатуры)}")
    print(f"  ИзЕдинственнойПривязки = {int(res.ИзЕдинственнойПривязки)}")
    print(f"  НичьихКонфликтов       = {int(res.НичьихКонфликтов)}")
    print(f"  ОсталосьПустых         = {int(res.ОсталосьПустых)}")

    conflicts = res.СписокКонфликтов
    n_conf = conflicts.Количество()
    print(f"\n--- Конфликты единиц ({n_conf}) ---")
    for i in range(n_conf):
        print(f"  {conflicts.Получить(i)}")

    empties = res.СписокПустых
    n_emp = empties.Количество()
    print(f"\n--- Осталось пустых ({n_emp}), первые 20 ---")
    for i in range(min(n_emp, 20)):
        print(f"  {empties.Получить(i)}")

    assert int(res.ИзСтруктур) == exp_p1, f"П1: {int(res.ИзСтруктур)} != {exp_p1}"
    assert int(res.ИзНоменклатуры) == exp_p2, f"П2: {int(res.ИзНоменклатуры)} != {exp_p2}"
    assert int(res.ИзЕдинственнойПривязки) == exp_p2b, f"П2б: {int(res.ИзЕдинственнойПривязки)} != {exp_p2b}"
    assert int(res.НичьихКонфликтов) == exp_tie, f"Ничьих: {int(res.НичьихКонфликтов)} != {exp_tie}"
    assert int(res.ОсталосьПустых) == exp_empty_after, \
        f"ОсталосьПустых: {int(res.ОсталосьПустых)} != {exp_empty_after}"
    print("\nЗапуск 1: все ассерты PASS")

    # --- запуск 2 (идемпотентность) ---
    res2 = obr.ОбновитьВОбщемНазванииЕдиницу()
    assert not res2.Ошибка, f"Ошибка повторного запуска: {res2.ТекстОшибки}"
    print("\n=== Запуск 2 (повтор): протокол ===")
    print(f"  ИзСтруктур             = {int(res2.ИзСтруктур)}")
    print(f"  ИзНоменклатуры         = {int(res2.ИзНоменклатуры)}")
    print(f"  ИзЕдинственнойПривязки = {int(res2.ИзЕдинственнойПривязки)}")
    print(f"  НичьихКонфликтов       = {int(res2.НичьихКонфликтов)}")
    print(f"  ОсталосьПустых         = {int(res2.ОсталосьПустых)}")

    assert int(res2.ИзСтруктур) == 0, f"Повтор П1: {int(res2.ИзСтруктур)} != 0"
    assert int(res2.ИзНоменклатуры) == 0, f"Повтор П2: {int(res2.ИзНоменклатуры)} != 0"
    assert int(res2.ИзЕдинственнойПривязки) == 0, f"Повтор П2б: {int(res2.ИзЕдинственнойПривязки)} != 0"
    assert int(res2.НичьихКонфликтов) == exp_tie_repeat, \
        f"Повтор ничьих: {int(res2.НичьихКонфликтов)} != {exp_tie_repeat}"
    print("\nЗапуск 2: все ассерты PASS (идемпотентность)")

    # --- финальная проверка: пустых в базе == протокол ---
    empty_db = int(vt(buh, Q_EMPTY).Получить(0).Кол)
    assert empty_db == int(res2.ОсталосьПустых), \
        f"Пустых в базе {empty_db} != протокол {int(res2.ОсталосьПустых)}"
    print(f"\nПустых карточек в базе после запуска: {empty_db} == протокол. PASS")

    print("\n=== SMOKE PASS ===")


if __name__ == "__main__":
    main()
