def отключить_аналитику(структура):
    """Вариант — ЖИВЫЕ данные пользователя: он волен добавлять свои уровни (21.08.2026
    добавил группировку «Аналитика»). Приёмка закрепляет контракт уровня статей, поэтому
    посторонние группировки отключаются перед сверкой с эталонными листами."""
    for i in range(структура.Количество()):
        эл = структура.Получить(i)
        try:
            пг = эл.ПоляГруппировки
            for j in range(пг.Элементы.Количество()):
                try:
                    if S(пг.Элементы.Получить(j).Поле) == "Аналитика":
                        эл.Использование = False
                except Exception:
                    pass
        except Exception:
            pass
        for кол in ("Структура", "Строки", "Колонки"):
            try:
                отключить_аналитику(getattr(эл, кол))
            except Exception:
                pass


