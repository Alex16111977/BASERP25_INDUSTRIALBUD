def разобрать(таб):
    """{строка: [числа июльского блока]}, порядок строк, тексты шапки, фоны строк."""
    в, ш = int(таб.ВысотаТаблицы), int(таб.ШиринаТаблицы)
    g = [[S(таб.Область(r, c, r, c).Текст).strip() for c in range(1, ш + 1)]
         for r in range(1, в + 1)]
    числа, порядок, шапка, фоны = {}, [], set(), {}
    for r in range(в):
        if r < 3:
            for x in g[r]:
                if x:
                    шапка.add(x)
        первая = ""
        for c in range(ш):
            if g[r][c]:
                первая = g[r][c]
                break
        if not первая or r < 2:
            continue
        порядок.append(норм(первая))
        числа[норм(первая)] = g[r][1:5]      # Ф1, Ф2, Сумма, % июльского блока
        try:
            фоны[норм(первая)] = S(таб.Область(r + 1, 1, r + 1, 1).ЦветФона)
        except Exception:
            pass
    return числа, порядок, шапка, фоны


def эталон(файл):
    wb = openpyxl.load_workbook(файл, data_only=True)
    ws = wb["TDSheet"]
    из = {}
    порядок = []
    for r in range(3, ws.max_row + 1):
        имя = ws.cell(r, 1).value
        if not имя:
            continue
        имя = str(имя)
        if "- убираем" in имя:
            continue
        н = норм(имя)
        порядок.append(н)
        из[н] = [ws.cell(r, c).value for c in range(2, 6)]
    return из, порядок


def чис(x):
    if x in (None, ""):
        return None
    try:
        return float(str(x).replace("\xa0", "").replace(" ", "").replace(",", ".").replace("%", ""))
    except ValueError:
        return None


