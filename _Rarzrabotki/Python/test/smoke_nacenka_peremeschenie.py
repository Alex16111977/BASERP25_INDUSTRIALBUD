def ожид(себест, кол, нац):
    if нац==0: return ((себест/кол) if кол else 0, себест)
    ц=round((себест/кол)*(1+нац/100.0),2) if кол else 0
    return ц, round(ц*кол,2)

def проверить_продажный(имя, func, prm, нац, реализация):
    buh.НачатьТранзакцию()
    try:
        Рез=func(spis, prm, нац)
        d=prm.ПолучитьОбъект()
        # пересчёт групп для сверки
        НЗ=buh.РегистрыБухгалтерии.Хозрасчетный.СоздатьНаборЗаписей()
        НЗ.Отбор.Регистратор.Установить(spis); НЗ.Прочитать()
        # просто проверим первые строки: Сумма=Цена*Кол (или себест при нац=0), НДС=20%
        bad=0
        for r in d.Товары:
            с=num(r.Сумма); ц=num(r.Цена); к=num(r.Количество); ндс=num(r.СуммаНДС)
            # инвариант: Сумма≈Цена*Кол (наценка) или Сумма точная; НДС=Окр(Сумма*0.2,2)
            if нац!=0 and abs(с-round(ц*к,2))>0.02: bad+=1
            if abs(ндс-round(с*20/100,2))>0.01: bad+=1
            if реализация and abs(num(r.СуммаБезСкидки)-с)>0.01: bad+=1
            if реализация and S(r.СхемаРеализации)!="Товары": bad+=1
        print(f"  {имя} наценка={нац}%: Успех={Рез.Успех} Строк={Рез.Строк} Σ={Рез.ИтогоСумма:.2f} НДС={Рез.ИтогоНДС:.2f} наруш.строк={bad}")
        if not Рез.Успех or bad>0: fails.append(f"{имя}/{нац}")
    finally:
        buh.ОтменитьТранзакцию()

print("\n=== Реализация ===")
