    q.SetParameter("Н", com_date(2025, 12, 1))
    q.SetParameter("К", com_date(2025, 12, 31))
    r = q.Execute().Выгрузить()
    print(f"  Знайдено рядків: {r.Количество()}")
    for i in range(min(r.Количество(), 5)):
        row = r.Получить(i)
        print(f"    Сотрудник: {S(row.СотрудникФИО)}")
        print(f"      ІНН: {S(row.СотрудникИНН)}, Вид: {S(row.ВидУдержания)}, Сума: {S(row.Сумма)}")
        print(f"      Регистратор: {S(row.Регистратор)}")
        print(f"      ИсполнительныйДокумент: {S(row.ИсполнительныйДокумент)}")
        print()
