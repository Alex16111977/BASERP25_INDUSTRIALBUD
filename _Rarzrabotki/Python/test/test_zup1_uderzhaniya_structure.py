# Діагностика структури ZUP_1: де лежать Удержания + ИсполнительныйЛист з Получатель
import win32com.client, sys, pywintypes, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
zup = v8.Connect('Srvr="SQLSERVER";Ref="zup_1";Usr="cfo";Pwd="2442"')
S = zup.String

def com_date(y, m, d):
    return pywintypes.Time(datetime.datetime(y, m, d))

print("=" * 80)
print("КРОК 1: пошук регістру розрахунку з Удержаниями в ZUP_1")
print("=" * 80)

# Перелік можливих назв регістрів розрахунку для удержаний в ЗУП 2.1 UA
# Насамперед перевіряємо УдержанияРаботниковОрганизаций
possible_registers = [
    "УдержанияРаботниковОрганизаций",
    "ОсновныеУдержанияРаботниковОрганизаций",
    "ПрочиеУдержанияРаботниковОрганизаций",
]

for reg_name in possible_registers:
    try:
        q = zup.NewObject("Запрос")
        q.Text = f"ВЫБРАТЬ ПЕРВЫЕ 1 1 КАК Х ИЗ РегистрРасчета.{reg_name}"
        r = q.Execute().Выгрузить()
        print(f"  [OK] РегистрРасчета.{reg_name} — існує")
    except Exception as e:
        err = str(e)[:100]
        print(f"  [--] РегистрРасчета.{reg_name} — {err}")

