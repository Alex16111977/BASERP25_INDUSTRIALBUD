"""Pre-test SQL: проверить наш запрос Локализация-1 для ДСДохРасх.

Имитирует ветку нового UNION ALL — детальная разбивка из А_Расшифровки.
Должен дать 21 строку (per ФЛ) с детальным Подразделением и СтатьяДДС.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q_doc = erp.NewObject("Запрос")
q_doc.Text = "ВЫБРАТЬ Д.Ссылка КАК Сс, Д.ХозяйственнаяОперация КАК ХО ИЗ Документ.РасходныйКассовыйОрдер КАК Д ГДЕ Д.Номер = &Ном"
q_doc.SetParameter("Ном", "N0000052986")
docrow = q_doc.Execute().Выгрузить()[0]
ref = docrow.Сс
hozop = docrow.ХО
print(f"РКО: {S(hozop)}")

# Запрос Локализация-1 для ДСДохРасх (1:1 как будет в BSL)
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    ДанныеДокумента.Дата КАК Период,
    &ХозяйственнаяОперация КАК ХозяйственнаяОперация,
    ДанныеДокумента.Организация КАК Организация,
    Рш.Подразделение.А_Подразделение КАК Подразделение,
    Рш.НаправлениеДеятельности КАК НаправлениеДеятельностиДС,
    Рш.Подразделение.А_Подразделение КАК ПодразделениеДоходовРасходов,
    ДанныеДокумента.Касса КАК ДенежныеСредства,
    ЗНАЧЕНИЕ(Перечисление.ТипыДенежныхСредств.Наличные) КАК ТипДенежныхСредств,
    Рш.СтатьяДвиженияДенежныхСредств КАК СтатьяДвиженияДенежныхСредств,
    ДанныеДокумента.Валюта КАК Валюта,
    Рш.НаправлениеДеятельности КАК НаправлениеДеятельностиСтатьи,
    ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ОплатаТруда) КАК СтатьяДоходовРасходов,
    НЕОПРЕДЕЛЕНО КАК АналитикаДоходов,
    НЕОПРЕДЕЛЕНО КАК АналитикаРасходов,
    Рш.ФизическоеЛицо КАК АналитикаАктивовПассивов,
    ВЫРАЗИТЬ(Рш.КВыплате * 1 КАК ЧИСЛО(31,2)) КАК Сумма,
    ВЫРАЗИТЬ(Рш.КВыплате * 1 КАК ЧИСЛО(31,2)) КАК СуммаРегл,
    Рш.КВыплате КАК СуммаВВалюте,
    Рш.КВыплате КАК СуммаКВыплатеСверхЛимита,
    0 КАК СуммаНДС,
    0 КАК СуммаНДСРегл,
    0 КАК СуммаНДСВВалютеПлатежа,
    ДанныеДокумента.Касса КАК ИсточникГФУДенежныхСредств,
    НЕОПРЕДЕЛЕНО КАК ИсточникГФУДоходовРасходов,
    НЕОПРЕДЕЛЕНО КАК СтавкаНДС
ИЗ
    Документ.РасходныйКассовыйОрдер КАК ДанныеДокумента
    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.ВедомостьНаВыплатуЗарплатыВКассу.А_РасшифровкаВыплатыЗарплатаПоФизлицам КАК Рш
        ПО Рш.Ссылка = ДанныеДокумента.Ведомость
ГДЕ
    ДанныеДокумента.Ссылка = &Ссылка
    И &ХозяйственнаяОперация В (
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыЧерезКассу),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаздатчиком),
        ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ВыплатаЗарплатыРаботнику))
    И ТИПЗНАЧЕНИЯ(ДанныеДокумента.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу)
"""
q.SetParameter("Ссылка", ref)
q.SetParameter("ХозяйственнаяОперация", hozop)
try:
    rows = q.Execute().Выгрузить()
    print(f"\nПолучено строк: {rows.Количество()}")
    unique_podr = {S(r.Подразделение) for r in rows}
    unique_dds = {S(r.СтатьяДвиженияДенежныхСредств) for r in rows}
    print(f"Уникальных Подр: {len(unique_podr)}")
    print(f"Уникальных СтатейДДС: {unique_dds}")
    total_sum = sum(float(r.Сумма) for r in rows)
    print(f"Σ Сумма: {total_sum:,.2f}")
    assert rows.Количество() == 21, f"Ожидаем 21 строку per ФЛ, получили {rows.Количество()}"
    assert len(unique_podr) == 12, f"Ожидаем 12 СтрПредпр, получили {len(unique_podr)}"
    assert "Оплата за выполненные работы" not in unique_dds, f"FAIL: общая статья: {unique_dds}"
    assert abs(total_sum - 348800.0) < 0.01, f"FAIL: Σ != 348800"
    print(f"\n✅ Локализация-1: 21 строк, {len(unique_podr)} СтрПредпр, СтатьиДДС детальные")
except Exception as e:
    if hasattr(e, 'excepinfo') and e.excepinfo:
        print(f"FAIL: {e.excepinfo[2]}")
    else:
        print(f"FAIL: {e}")
    raise
