def run_batch(text):
    q = erp.NewObject("Запрос")
    q.МенеджерВременныхТаблиц = erp.NewObject("МенеджерВременныхТаблиц")
    q.Текст = text
    return q.Выполнить().Выгрузить()

def dump(t, limit=30):
    names = [t.Колонки.Получить(j).Имя for j in range(t.Колонки.Количество())]
    print(f"строк: {t.Количество()}  колонки: {names}")
    for i in range(min(t.Количество(), limit)):
        r = t.Получить(i)
        print("  " + " | ".join(f"{names[j]}={r.Получить(j)}" for j in range(len(names))))
    return t

