# -*- coding: utf-8 -*-
"""
Финальный тест: ОстаткиИОбороты + Регистратор, универсальный запрос
Без 5-группового фильтра, INNER JOIN по Номенклатура субконто
"""
import win32com.client
import pythoncom
import pywintypes
from datetime import datetime

CONNECTION_STRING = 'Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"'
DATE_FROM = datetime(2025, 12, 1)
DATE_TO = datetime(2025, 12, 31, 23, 59, 59)
NOM_ID = "f2273409-47a4-11ec-a212-000c299fb278"

def make_time(dt):
    return pywintypes.Time(dt)

def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected")

    mas = conn.NewObject("Массив")
    q_orgs = conn.NewObject("Запрос")
    q_orgs.Текст = "ВЫБРАТЬ Орг.КодПоЕДРПОУ ИЗ Справочник.Организации КАК Орг ГДЕ Орг.КодПоЕДРПОУ <> \"\""
    r_orgs = q_orgs.Выполнить().Выбрать()
    while r_orgs.Следующий():
        mas.Добавить(r_orgs.КодПоЕДРПОУ)

    # Универсальный запрос: ОстаткиИОбороты + Регистратор
    # INNER JOIN на Номенклатура (не 5 групп!)
    # Без фильтра по складу
    print("\n=== Универсальный: ОстаткиИОбороты + Регистратор + INNER JOIN Номенклатура ===")
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ\n"
        "\tВЗ.Регистратор КАК Регистратор,\n"
        "\tПРЕДСТАВЛЕНИЕ(ВЗ.Регистратор) КАК РегистраторПредст,\n"
        "\tСУММА(ВЗ.КоличествоПриход) - СУММА(ВЗ.КоличествоРасход) КАК КоличествоИтого\n"
        "ИЗ\n"
        "\t(ВЫБРАТЬ\n"
        "\t\tВЫБОР\n"
        "\t\t\tКОГДА ПозНом.НомерСтроки = 1\n"
        "\t\t\t\tТОГДА ВЫРАЗИТЬ(Ост.Субконто1 КАК Справочник.Номенклатура).А_ИдКод\n"
        "\t\t\tКОГДА ПозНом.НомерСтроки = 2\n"
        "\t\t\t\tТОГДА ВЫРАЗИТЬ(Ост.Субконто2 КАК Справочник.Номенклатура).А_ИдКод\n"
        "\t\t\tКОГДА ПозНом.НомерСтроки = 3\n"
        "\t\t\t\tТОГДА ВЫРАЗИТЬ(Ост.Субконто3 КАК Справочник.Номенклатура).А_ИдКод\n"
        "\t\t\tИНАЧЕ \"\"\n"
        "\t\tКОНЕЦ КАК НоменклатураИдКод,\n"
        "\t\tОст.Регистратор КАК Регистратор,\n"
        "\t\tОст.КоличествоОборотДт КАК КоличествоПриход,\n"
        "\t\tОст.КоличествоОборотКт КАК КоличествоРасход,\n"
        "\t\tОст.СуммаОборотДт - Ост.СуммаОборотКт КАК СуммаНетто\n"
        "\tИЗ\n"
        "\t\tРегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(\n"
        "\t\t\t\t&НачалоПериода,\n"
        "\t\t\t\t&КонецПериода,\n"
        "\t\t\t\tРегистратор,\n"
        "\t\t\t\t,\n"
        "\t\t\t\t,\n"
        "\t\t\t\t,\n"
        "\t\t\t\t) КАК Ост\n"
        "\t\t\tВНУТРЕННЕЕ СОЕДИНЕНИЕ ПланСчетов.Хозрасчетный.ВидыСубконто КАК ПозНом\n"
        "\t\t\tПО Ост.Счет = ПозНом.Ссылка\n"
        "\t\t\t\tИ (ПозНом.ВидСубконто = ЗНАЧЕНИЕ(ПланВидовХарактеристик.ВидыСубконтоХозрасчетные.Номенклатура))\n"
        "\tГДЕ\n"
        "\t\t(Ост.КоличествоОборотДт <> 0 ИЛИ Ост.КоличествоОборотКт <> 0)\n"
        "\t\tИ Ост.Организация.КодПоЕДРПОУ В (&масКодПоЕДРПОУ)) КАК ВЗ\n"
        "ГДЕ\n"
        "\tВЗ.НоменклатураИдКод = &НоменклатураИдКод\n"
        "\n"
        "СГРУППИРОВАТЬ ПО\n"
        "\tВЗ.Регистратор\n"
        "\n"
        "ИМЕЮЩИЕ\n"
        "\tСУММА(ВЗ.СуммаНетто) <> 0"
    )
    q.УстановитьПараметр("НачалоПериода", make_time(DATE_FROM))
    q.УстановитьПараметр("КонецПериода", make_time(DATE_TO))
    q.УстановитьПараметр("НоменклатураИдКод", NOM_ID)
    q.УстановитьПараметр("масКодПоЕДРПОУ", mas)
    try:
        r = q.Выполнить().Выбрать()
        count = 0
        while r.Следующий():
            count += 1
            uid = conn.XMLСтрока(r.Регистратор.УникальныйИдентификатор()).upper()
            predst = str(r.РегистраторПредст)
            kol = r.КоличествоИтого
            print(f"  [{count}] {predst[:70]}")
            print(f"         UUID: {uid}  К-ть: {kol}")
            if "007653" in predst:
                print(f"         >>> DOC 007653 FOUND! К-ть = {kol}")
        print(f"  Записей: {count}")
    except Exception as e:
        print(f"  ОШИБКА: {str(e)[:300]}")

    conn = None
    pythoncom.CoUninitialize()
    print("\n[OK] Done")

if __name__ == "__main__":
    main()
