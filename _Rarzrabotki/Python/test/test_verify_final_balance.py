# -*- coding: utf-8 -*-
"""
Финальная верификация: после работы обработки у ІБ00-008058 дисбаланс
по подразделениям должен стать 0.

Суммируем обороты по регистру ПрочиеАктивыПассивы от:
  - самого документа ІБ00-008058
  - всех ВзаимозачетЗадолженности с А_ДокументОснованиеДляБаланса = ІБ00-008058
и проверяем, что Контроль по каждому подразделению = 0.
"""
import sys
import win32com.client

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

v8 = win32com.client.Dispatch("V83.COMConnector")
conn = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
print("Connected\n")

uid = conn.NewObject("УникальныйИдентификатор", "20b3ae2a-f767-11f0-8105-00155dce3d04")
doc_ref = conn.Документы.ПриобретениеТоваровУслуг.ПолучитьСсылку(uid)

# Найдём ВзаимозачетЗадолженности
q_vz = conn.NewObject("Запрос")
q_vz.Text = """
ВЫБРАТЬ Вз.Ссылка КАК Ссылка, Вз.Номер КАК Номер, Вз.СуммаРегл КАК Сумма, Вз.Проведен КАК Проведен,
       Вз.КонтрагентДебитор КАК КонтрагентДебитор, Вз.КонтрагентКредитор КАК КонтрагентКредитор
ИЗ Документ.ВзаимозачетЗадолженности КАК Вз
ГДЕ Вз.А_ДокументОснованиеДляБаланса = &Осн И НЕ Вз.ПометкаУдаления
"""
q_vz.УстановитьПараметр("Осн", doc_ref)
sel = q_vz.Выполнить().Выбрать()
print("Созданные ВзаимозачетЗадолженности для ІБ00-008058:")
vz_list = []
while sel.Следующий():
    vz_list.append(sel.Ссылка)
    print(f"  - №{sel.Номер} | Сумма={sel.Сумма:.2f} Проведен={sel.Проведен}"
          f" | Дт={conn.String(sel.КонтрагентДебитор)} -> Кт={conn.String(sel.КонтрагентКредитор)}")

# Считаем дисбаланс по всем регистраторам (исходный + взаимозачёты) через отдельные запросы и суммируем
by_podr = {}
all_refs = [doc_ref] + vz_list
for reg in all_refs:
    q_sum = conn.NewObject("Запрос")
    q_sum.Text = """
    ВЫБРАТЬ
        Об.Подразделение КАК Подразделение,
        СУММА(Об.СуммаПриход - Об.СуммаРасход) КАК Контроль
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы.Обороты(, , Регистратор, ) КАК Об
    ГДЕ Об.Регистратор = &Рег
        И НЕ Об.Статья В (
            ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),
            ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))
    СГРУППИРОВАТЬ ПО Об.Подразделение
    """
    q_sum.УстановитьПараметр("Рег", reg)
    tbl = q_sum.Выполнить().Выгрузить()
    for i in range(tbl.Количество()):
        row = tbl.Получить(i)
        name = conn.String(row.Подразделение)
        by_podr[name] = by_podr.get(name, 0.0) + float(row.Контроль)

print("\nИтоговый Контроль по подразделениям (документ + 3 взаимозачёта):")
all_ok = True
total = 0.0
for k in sorted(by_podr.keys()):
    v = by_podr[k]
    total += v
    marker = "OK" if abs(v) < 0.01 else "!!!"
    if abs(v) >= 0.01:
        all_ok = False
    print(f"  {marker} {k:<40s} Контроль={v:>15.2f}")

print(f"\nИтого: {total:.2f}")
print(f"\nРЕЗУЛЬТАТ: {'БАЛАНС ПО ПОДРАЗДЕЛЕНИЯМ СОШЁЛСЯ — ВСЁ OK' if all_ok else 'ЕСТЬ НЕЗАКРЫТЫЙ ДИСБАЛАНС'}")
