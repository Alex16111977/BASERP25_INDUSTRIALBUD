def run(нач, оконч, применять, контрагенты):
    q = erp.NewObject("Запрос")
    q.Text = QUERY
    q.SetParameter("НачалоПериода", нач)
    q.SetParameter("ОкончаниеПериода", оконч)
    q.SetParameter("ПрименятьОтбор", применять)
    масс = erp.NewObject("Массив")
    for k in контрагенты:
        масс.Add(k)
    q.SetParameter("масКонтрагент", масс)
    try:
        t = q.Execute().Выгрузить()
        return t.Количество(), t
    except Exception as e:
        info = getattr(e, 'excepinfo', None)
        return None, (info[2] if info else str(e))

