"""Discovery (read-only) для доработки «Перенос остатков сотрудников»:
проверяем счета 66 в BuhBud, В ИЕРАРХИИ РасчетыПоОплатеТруда, субконто ФЛ, знак Дт/Кт.
"""
import sys
from datetime import datetime
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
S = buh.String

# Q0: предопределённый счёт существует?
try:
    acc = buh.ПланыСчетов.Хозрасчетный.РасчетыПоОплатеТруда
    print(f"Q0 Predefined РасчетыПоОплатеТруда: OK | Код={acc.Код} | {S(acc.Наименование)}")
except Exception as e:
    print(f"Q0 PREDEFINED FAIL: {e}")

# Q1: счета В ИЕРАРХИИ 66 (валидирует предопределённый + В ИЕРАРХИИ на ПС)
q1 = buh.NewObject("Запрос")
q1.Text = """
ВЫБРАТЬ Счет.Код КАК Код, Счет.Наименование КАК Наим, ПРЕДСТАВЛЕНИЕ(Счет.Вид) КАК Вид
ИЗ ПланСчетов.Хозрасчетный КАК Счет
ГДЕ Счет.Ссылка В ИЕРАРХИИ(ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.РасчетыПоОплатеТруда))
УПОРЯДОЧИТЬ ПО Счет.Код
"""
try:
    r = q1.Выполнить().Выгрузить()
    print(f"\nQ1 Счета В ИЕРАРХИИ 66: {r.Количество()}")
    for row in r:
        print(f"   {S(row.Код):8} | {S(row.Вид):10} | {S(row.Наим)}")
except Exception as e:
    print(f"Q1 FAIL: {e}")

# Q2: .Остатки на дату с В ИЕРАРХИИ — какие счета имеют ФЛ-остатки + Дт/Кт
for dt in [datetime(2025, 12, 31, 12, 0, 0), datetime(2026, 4, 30, 12, 0, 0)]:
    q2 = buh.NewObject("Запрос")
    q2.УстановитьПараметр("Дата", dt)
    q2.Text = """
    ВЫБРАТЬ
        Ост.Счет.Код КАК Код,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ост.Субконто1) КАК ЧислоФЛ,
        СУММА(Ост.СуммаОстатокКт) КАК Кт,
        СУММА(Ост.СуммаОстатокДт) КАК Дт
    ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Дата, Счет В ИЕРАРХИИ(ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.РасчетыПоОплатеТруда)), , ) КАК Ост
    ГДЕ Ост.Субконто1 ССЫЛКА Справочник.ФизическиеЛица
    СГРУППИРОВАТЬ ПО Ост.Счет.Код
    УПОРЯДОЧИТЬ ПО Код
    """
    try:
        r = q2.Выполнить().Выгрузить()
        print(f"\nQ2 .Остатки на {dt:%Y-%m-%d} (Субконто1=ФЛ): счетов={r.Количество()}")
        for row in r:
            print(f"   {S(row.Код):8} | ФЛ={int(row.ЧислоФЛ):4} | Кт={float(row.Кт):>15,.2f} | Дт={float(row.Дт):>12,.2f} | Кт-Дт={float(row.Кт)-float(row.Дт):>15,.2f}")
    except Exception as e:
        print(f"Q2 ({dt:%Y-%m-%d}) FAIL: {e}")

# Q2b: что под 66 НЕ-ФЛ субконто (что отсечёт гард ССЫЛКА)
q2b = buh.NewObject("Запрос")
q2b.УстановитьПараметр("Дата", datetime(2025, 12, 31, 12, 0, 0))
q2b.Text = """
ВЫБРАТЬ Ост.Счет.Код КАК Код, ПРЕДСТАВЛЕНИЕ(ТИПЗНАЧЕНИЯ(Ост.Субконто1)) КАК ТипСубк, КОЛИЧЕСТВО(*) КАК Кол
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Дата, Счет В ИЕРАРХИИ(ЗНАЧЕНИЕ(ПланСчетов.Хозрасчетный.РасчетыПоОплатеТруда)), , ) КАК Ост
ГДЕ НЕ Ост.Субконто1 ССЫЛКА Справочник.ФизическиеЛица
СГРУППИРОВАТЬ ПО Ост.Счет.Код, ПРЕДСТАВЛЕНИЕ(ТИПЗНАЧЕНИЯ(Ост.Субконто1))
"""
try:
    r = q2b.Выполнить().Выгрузить()
    print(f"\nQ2b НЕ-ФЛ субконто под 66 (отсечёт гард): строк={r.Количество()}")
    for row in r:
        print(f"   {S(row.Код):8} | {S(row.ТипСубк)} | {int(row.Кол)}")
except Exception as e:
    print(f"Q2b FAIL: {e}")

# Q3: А_ИдКод у BuhBud ФизическиеЛица?
q3 = buh.NewObject("Запрос")
q3.Text = """
ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Всего, СУММА(ВЫБОР КОГДА ФЛ.А_ИдКод <> "" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК СИдКод
ИЗ Справочник.ФизическиеЛица КАК ФЛ
"""
try:
    r = q3.Выполнить().Выгрузить()
    print(f"\nQ3 BuhBud ФизическиеЛица: всего={int(r[0].Всего)}, с А_ИдКод={int(r[0].СИдКод)}")
except Exception as e:
    print(f"Q3 FAIL (нет реквизита А_ИдКод?): {e}")

print("\nDONE discovery")
