# -*- coding: utf-8 -*-
"""Анализ 7 готовых КомплектацияНоменклатуры vs спец 000000003 на уровне ОбщееНазвание."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
S = buh.String

НОМЕРА = ["ІБ00-000076","ІБ00-000078","ІБ00-000098","ІБ00-000077","ІБ00-000099","ІБ00-000100","ІБ00-000101"]
мас = buh.NewObject("Массив")
for n in НОМЕРА: мас.Добавить(n)

# 1) факт по документам: по ОбщееНазвание и по складу
qD = buh.NewObject("Запрос")
qD.УстановитьПараметр("Номера", мас)
qD.Текст = '''
ВЫБРАТЬ
    К.Ссылка.Склад.Наименование КАК Склад,
    К.Номенклатура.ОбщееНазваниеНоменклатуры КАК ОН,
    ПРЕДСТАВЛЕНИЕ(К.Номенклатура.ОбщееНазваниеНоменклатуры) КАК ОНН,
    СУММА(К.Количество) КАК Факт
ИЗ Документ.КомплектацияНоменклатуры.Комплектующие КАК К
ГДЕ К.Ссылка.Номер В (&Номера)
СГРУППИРОВАТЬ ПО К.Ссылка.Склад.Наименование, К.Номенклатура.ОбщееНазваниеНоменклатуры,
    ПРЕДСТАВЛЕНИЕ(К.Номенклатура.ОбщееНазваниеНоменклатуры)
'''
tD = qD.Выполнить().Выгрузить()
факт = {}        # ОН -> сумма
факт_скл = {}    # (ОН, склад) для разреза
безЭталона = 0.0
for i in range(tD.Количество()):
    s = tD.Получить(i)
    key = S(s.ОН)
    наим = s.ОНН or "<без эталона>"
    if not buh.ЗначениеЗаполнено(s.ОН):
        безЭталона += s.Факт
    факт[key] = факт.get(key, [наим, 0.0]); факт[key][1] += s.Факт
    скл = "виробн" if "виробнич" in (s.Склад or "") else "відвант"
    факт_скл[(key, скл)] = факт_скл.get((key, скл), 0.0) + s.Факт

# 2) нормы спец 000000003 по ОбщееНазвание
qN = buh.NewObject("Запрос")
qN.Текст = '''
ВЫБРАТЬ
    К.ОбщееНазвание КАК ОН,
    ПРЕДСТАВЛЕНИЕ(К.ОбщееНазвание) КАК ОНН,
    СУММА(К.Количество) КАК Норма
ИЗ Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ К.Ссылка.Код = "000000003"
СГРУППИРОВАТЬ ПО К.ОбщееНазвание, ПРЕДСТАВЛЕНИЕ(К.ОбщееНазвание)
'''
tN = qN.Выполнить().Выгрузить()
нормы = {}
for i in range(tN.Количество()):
    s = tN.Получить(i); нормы[S(s.ОН)] = [s.ОНН or "<пусто>", s.Норма]

# 3) сравнение по ОбщееНазвание
все = set(факт) | set(нормы)
строк = []
вНорме = излишек = 0.0
for k in все:
    наим = (факт.get(k) or нормы.get(k))[0]
    ф = факт.get(k, [None,0.0])[1]
    нм = нормы.get(k, [None,0.0])[1]
    вн = min(ф, нм) if нм > 0 else 0.0
    из = max(0.0, ф - нм)
    вНорме += вн; излишек += из
    вир = факт_скл.get((k,"виробн"),0.0); отг = факт_скл.get((k,"відвант"),0.0)
    строк.append((наим, ф, нм, вн, из, вир, отг))
строк.sort(key=lambda x: -(x[1] or 0))

print(f"{'ОбщееНазвание':32}{'ФактДок':>9}{'Норма':>9}{'вНорме':>9}{'Излиш':>9}{'виробн':>9}{'відвант':>9}")
for наим, ф, нм, вн, из, вир, отг in строк[:35]:
    print(f"{(наим or '')[:32]:32}{ф:9.2f}{нм:9.2f}{вн:9.2f}{из:9.2f}{вир:9.2f}{отг:9.2f}")

факт_только = [s for s in строк if s[2]==0 and s[1]>0]
норма_только = [s for s in строк if s[1]==0 and s[2]>0]
оба = [s for s in строк if s[1]>0 and s[2]>0]
print(f"\nЭталонов: всего={len(строк)}, и в факте и в норме={len(оба)}, только в факте(нет нормы)={len(факт_только)}, только в норме(нет факта)={len(норма_только)}")
print(f"Σ ФактДок={sum(s[1] for s in строк):.2f}  Σ Норма={sum(s[2] for s in строк):.2f}")
print(f"Σ вНорме(min)={вНорме:.2f}  Σ Излишек={излишек:.2f}  безЭталона(факт)={безЭталона:.2f}")
print(f"Σ виробничий={sum(s[5] for s in строк):.2f}  Σ відвантажено={sum(s[6] for s in строк):.2f}")
