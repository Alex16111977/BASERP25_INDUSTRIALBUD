# -*- coding: utf-8 -*-
"""Разведка для доработки А_ОтчетPL (вид как в Excel):
1) перечень значений Перечисление.ТипыЗапасов
2) группы статей PL с Сорт
3) статьи PL 000000001/000000002: Группа, Сорт, ТЧ Статьи (ДДС)
4) СтатьиДоходов -> А_СтатьяДвиженияДенежныхСредств (маппинг на ДДС статей PL)
5) структура ТЧ ИтогиОбщие/ИтогиПоГруппам документа А_ОтчетPL + пример Глобино-2 июнь-2026
6) где статьи «Затраты на налог на прибыль» и «Дивиденды»
"""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

def run(title, text):
    print("=" * 90)
    print(title)
    q = erp.NewObject("Запрос")
    q.Text = text
    try:
        r = q.Execute().Выгрузить()
        cols = [r.Колонки.Получить(i).Имя for i in range(r.Колонки.Количество())]
        print("  колонки:", cols)
        for i in range(r.Количество()):
            row = r.Получить(i)
            vals = []
            for c in cols:
                v = getattr(row, c)
                try:
                    vals.append(S(v))
                except Exception:
                    vals.append(repr(v))
            print("  " + " | ".join(vals))
        return r
    except Exception as e:
        if hasattr(e, 'excepinfo') and e.excepinfo:
            print("  FAIL:", e.excepinfo[2])
        else:
            print("  FAIL:", e)
        return None

# 1. Перечень ТипыЗапасов (имя значения через XMLString на стороне ERP)
print("=" * 90)
print("1. Перечисление.ТипыЗапасов")
q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ Ссылка ИЗ Перечисление.ТипыЗапасов"
r = q.Execute().Выгрузить()
for i in range(r.Количество()):
    ref = r.Получить(i).Ссылка
    try:
        xml_name = erp.XMLString(ref)
    except Exception:
        xml_name = "<XMLString FAIL>"
    print(f"  Имя={xml_name!r}  Представление={S(ref)!r}")

# 2. Группы статей PL
run("2. Справочник.А_ГруппаСтатей_PL (Код, Наименование, Сорт)",
    """ВЫБРАТЬ Код, Наименование, Сорт
    ИЗ Справочник.А_ГруппаСтатей_PL
    ГДЕ НЕ ПометкаУдаления
    УПОРЯДОЧИТЬ ПО Сорт""")

# 3. Статьи PL с группами и Сорт
run("3. Справочник.А_Статьи_PL (все, по Сорт)",
    """ВЫБРАТЬ Код, Наименование, Группа.Наименование КАК Группа, Группа.Сорт КАК ГруппаСорт, Сорт
    ИЗ Справочник.А_Статьи_PL
    ГДЕ НЕ ПометкаУдаления
    УПОРЯДОЧИТЬ ПО Группа.Сорт, Сорт""")

# 3б. ТЧ Статьи (ДДС) статей 000000001 и 000000002
run("3б. ТЧ Статьи (ДДС) статей PL 000000001/000000002",
    """ВЫБРАТЬ ТЧ.Ссылка.Код КАК КодСтатьи, ТЧ.Ссылка.Наименование КАК Статья,
        ТЧ.СтатьяДвиженияДенежныхСредств.Наименование КАК ДДС,
        ТЧ.СтатьяДвиженияДенежныхСредств.Код КАК КодДДС
    ИЗ Справочник.А_Статьи_PL.Статьи КАК ТЧ
    ГДЕ ТЧ.Ссылка.Код В ("000000001", "000000002")
    УПОРЯДОЧИТЬ ПО КодСтатьи""")

# 4. СтатьиДоходов -> ДДС, замапленные на PL статьи (какая СтатьяДоходов ведёт в 000000001/000000002)
run("4. СтатьиДоходов с А_СтатьяДвиженияДенежныхСредств -> PL статья",
    """ВЫБРАТЬ
        СД.Наименование КАК СтатьяДоходов,
        СД.ПометкаУдаления КАК ПомУд,
        СД.А_СтатьяДвиженияДенежныхСредств.Наименование КАК ДДС,
        СтатьиТЧ.Ссылка.Код КАК КодСтатьиPL,
        СтатьиТЧ.Ссылка.Наименование КАК СтатьяPL
    ИЗ ПланВидовХарактеристик.СтатьиДоходов КАК СД
        ЛЕВОЕ СОЕДИНЕНИЕ Справочник.А_Статьи_PL.Статьи КАК СтатьиТЧ
        ПО СтатьиТЧ.СтатьяДвиженияДенежныхСредств = СД.А_СтатьяДвиженияДенежныхСредств
    ГДЕ СД.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
    УПОРЯДОЧИТЬ ПО СтатьяДоходов""")

# 5. Структура ТЧ ИтогиОбщие / ИтогиПоГруппам
for tch in ("ИтогиОбщие", "ИтогиПоГруппам"):
    print("=" * 90)
    print(f"5. Колонки ТЧ {tch}")
    q = erp.NewObject("Запрос")
    q.Text = f"ВЫБРАТЬ ПЕРВЫЕ 1 * ИЗ Документ.А_ОтчетPL.{tch}"
    try:
        r = q.Execute().Выгрузить()
        cols = [r.Колонки.Получить(i).Имя for i in range(r.Колонки.Количество())]
        print("  колонки:", cols)
    except Exception as e:
        print("  FAIL:", e.excepinfo[2] if hasattr(e, 'excepinfo') and e.excepinfo else e)

# 5б. Документ Глобино-2 июнь-2026: ИтогиОбщие
run("5б. А_ОтчетPL Глобино-2 июнь-2026: шапка",
    """ВЫБРАТЬ Ссылка, Дата, Номер, Подразделение.Наименование КАК Подр, ПодразделениеСтрока,
        ВключатьДочерние, НаправлениеДеятельности.Наименование КАК Направление
    ИЗ Документ.А_ОтчетPL
    ГДЕ Дата МЕЖДУ ДАТАВРЕМЯ(2026,6,1) И ДАТАВРЕМЯ(2026,6,30,23,59,59)
        И НЕ ПометкаУдаления
        И ПодразделениеСтрока ПОДОБНО "%Глобино-2%"
    """)

# 6. Статьи налога на прибыль и дивидендов
