results = {}

# ---- 0. parent -> child ОЗФУ ----
p = run('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Документ.А_ОтражениеЗПпоКазне ГДЕ Номер = "000000005" И Проведен')
