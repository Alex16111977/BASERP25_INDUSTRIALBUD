# -*- coding: utf-8 -*-
"""Verify (Rule #5) — перепровести Финансовый результат Баланс (для OLAP) 00000000004
от 30.04.2026 12:00:00 после внедрения расшифровки СтатьяДоходыРасходы.

Asserts:
- Документ найден (get-or-create по границам апреля 2026)
- Перепроведение через Записать(Проведение) PASS
- В РС А_ОтчетБаланс_Свод по этому регистратору:
  * Есть строки Расх.тек.пер./Глобино-2 с СтатьяДоходыРасходы<>NULL
  * Аналитика1 непустая
  * Σ КО per (Орг,Подр,Статья) == ПАП.ОстаткиИОбороты(КонМес) до 0.01
  * Σ Приход = Σ Расход = 0 (остатки-only)
- Идемпотентность (2-й прогон Δ=0)
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client
from datetime import datetime

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
S = erp.String
TOL = 0.01

q = erp.NewObject("Запрос")
q.Text = """ВЫБРАТЬ Ссылка ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273" """
own_org = q.Execute().Выгрузить().Получить(0).Ссылка

# Get-or-create документ по апрелю 2026
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", own_org)
q.Text = """
ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка
ИЗ Документ.А_ФинРез_Баланс
ГДЕ Организация = &Орг И НЕ ПометкаУдаления
    И Месяц >= ДАТАВРЕМЯ(2026,4,1,0,0,0) И Месяц <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
"""
r = q.Execute().Выгрузить()
if r.Количество() == 0:
    print("[INFO] Документ не найден, создаём новый")
    doc = erp.Документы.А_ФинРез_Баланс.СоздатьДокумент()
    doc.Дата = datetime(2026, 4, 30, 12, 0, 0)
    doc.Организация = own_org
    doc.Месяц = datetime(2026, 4, 1, 0, 0, 0)
    doc.ВключатьДочерние = False
    doc.Записать()
    doc_ref = doc.Ссылка
else:
    doc_ref = r.Получить(0).Ссылка

doc_obj = doc_ref.ПолучитьОбъект()
print(f"Документ: {S(doc_ref)}, Дата: {doc_obj.Дата}, Месяц: {doc_obj.Месяц}, Проведён: {doc_obj.Проведен}")

# Перепровести
print("Перепроведение...")
try:
    doc_obj.Записать(erp.РежимЗаписиДокумента.Проведение)
    print("[OK] Перепроведение PASS")
except Exception as e:
    print(f"[FAIL] Перепроведение: {e}")
    sys.exit(1)

doc_obj = doc_ref.ПолучитьОбъект()
assert doc_obj.Проведен, "Документ не проведён после Записать"

# Проверка РС А_ОтчетБаланс_Свод по этому регистратору
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Рег", doc_ref)
q.Text = """
ВЫБРАТЬ
    РС.Организация, ПРЕДСТАВЛЕНИЕ(РС.Организация) КАК ОргПред,
    РС.Подразделение, ПРЕДСТАВЛЕНИЕ(РС.Подразделение) КАК ПодрПред,
    РС.Статья, ПРЕДСТАВЛЕНИЕ(РС.Статья) КАК СтатьяПред,
    РС.Source, ПРЕДСТАВЛЕНИЕ(РС.Source) КАК SourceПред,
    РС.СтатьяДоходыРасходы,
    ПРЕДСТАВЛЕНИЕ(РС.СтатьяДоходыРасходы) КАК СДРПред,
    РС.Аналитика1,
    РС.Расхождение,
    РС.СуммаНачальныйОстаток, РС.СуммаПриход, РС.СуммаРасход, РС.СуммаКонечныйОстаток
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК РС
ГДЕ РС.ДокументДвижения = &Рег
"""
r = q.Execute().Выгрузить()
print(f"Всего строк РС после перепроведения: {r.Количество()}")
assert r.Количество() > 0, "После перепроведения нет строк в РС"

strok_rashod_glob2 = 0
sum_kos_glob2 = 0.0
glob2_st_set = set()
glob2_analitika1_set = set()
sum_prihod = 0.0
sum_rashod = 0.0
for i in range(r.Количество()):
    row = r.Получить(i)
    sum_prihod += float(row.СуммаПриход)
    sum_rashod += float(row.СуммаРасход)
    stat = S(row.СтатьяПред)
    podr = S(row.ПодрПред)
    if stat == "Расходы текущего периода" and podr == "Глобино-2":
        strok_rashod_glob2 += 1
        sum_kos_glob2 += float(row.СуммаКонечныйОстаток)
        if row.СтатьяДоходыРасходы is not None and S(row.СДРПред):
            glob2_st_set.add(S(row.СДРПред))
        an1 = S(row.Аналитика1)
        if an1:
            glob2_analitika1_set.add(an1)

print(f"  По Глобино-2/Расх.тек.пер.: {strok_rashod_glob2} строк, Σ КО = {sum_kos_glob2:.2f}")
print(f"  Уник. СтатьяДоходыРасходы в Глобино-2/Расх.тек.пер.: {len(glob2_st_set)}, первые 5: {sorted(glob2_st_set)[:5]}")
print(f"  Уник. Аналитика1: {len(glob2_analitika1_set)}, первые 3: {sorted(glob2_analitika1_set)[:3]}")
print(f"  Σ Приход всего = {sum_prihod:.2f}, Σ Расход = {sum_rashod:.2f}")

assert strok_rashod_glob2 > 0, "Нет строк Расх.тек.пер./Глобино-2 после перепроведения"
assert len(glob2_st_set) > 0, "В Глобино-2/Расх.тек.пер. нет СтатьиДоходыРасходы"
assert len(glob2_analitika1_set) > 0, "Аналитика1 пуста для Глобино-2/Расх.тек.пер."
assert abs(sum_prihod) < TOL and abs(sum_rashod) < TOL, "Должно быть остатки-only"

# Глобино-2/Расх.тек.пер. ИТОГ всех источников (Прочие + ПустаяСсылка) = 2400.00
# (Прочие= -294 402,71 покрыто Свод_ПрочиеРасходыДоходы; ПустаяСсылка=+296 802,71 — Свод_ПрочиеАктивыПассивы_Прямой)
print(f"\nГлобино-2/Расх.тек.пер. (все Source суммарно): {sum_kos_glob2:.2f} (ожидаем 2400.00)")
assert abs(sum_kos_glob2 - 2400.00) < TOL, f"Σ КО Глобино-2/Расх.тек.пер. == 2400.00 ожидалось, получили {sum_kos_glob2}"

# Сверка с ПАП per (Орг,Подр,Статья) для статей Расх/Дох тек.пер.
СтРасх = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Расходы текущего периода")
СтДох = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Доходы текущего периода")
СтСС = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.НайтиПоНаименованию("Собственные средства")
iskl_arr = erp.NewObject("Массив")
iskl_arr.Добавить(СтСС)

q = erp.NewObject("Запрос")
q.УстановитьПараметр("Орг", own_org)
q.УстановитьПараметр("СтРасх", СтРасх)
q.УстановитьПараметр("СтДох", СтДох)
q.УстановитьПараметр("Искл", iskl_arr)
q.Text = """
ВЫБРАТЬ
    Т.Подразделение, ПРЕДСТАВЛЕНИЕ(Т.Подразделение) КАК ПодрПред,
    Т.Статья, ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК СтатьяПред,
    СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
            ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КО
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
ГДЕ Т.Организация = &Орг И Т.Период <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
    И (Т.Статья = &СтРасх ИЛИ Т.Статья = &СтДох)
    И НЕ Т.Статья В ИЕРАРХИИ(&Искл)
СГРУППИРОВАТЬ ПО Т.Подразделение, Т.Статья
"""
pap = q.Execute().Выгрузить()
pap_map = {}
for i in range(pap.Количество()):
    row = pap.Получить(i)
    pap_map[(S(row.ПодрПред), S(row.СтатьяПред))] = float(row.КО)

# Σ свод по Расх/Дох тек.пер. per (Подр,Статья) over Source
svod_kos = {}
for i in range(r.Количество()):
    row = r.Получить(i)
    stat = S(row.СтатьяПред)
    if stat not in ("Расходы текущего периода", "Доходы текущего периода"):
        continue
    key = (S(row.ПодрПред), stat)
    svod_kos[key] = svod_kos.get(key, 0.0) + float(row.СуммаКонечныйОстаток)

mismatches = []
for k, kos in svod_kos.items():
    pap_ko = pap_map.get(k, 0.0)
    if abs(kos - pap_ko) > TOL:
        mismatches.append((k, kos, pap_ko))

if mismatches:
    print(f"\n[FAIL] Σ свод != ПАП ({len(mismatches)} расхождений):")
    for k, kos, pko in mismatches[:5]:
        print(f"  {k} | свод={kos:.2f} | ПАП={pko:.2f}")
    sys.exit(1)
print(f"[OK] Σ свод по Расх/Дох тек.пер. == ПАП до {TOL} (по {len(svod_kos)} ключей)")

# Идемпотентность
print("\nПроверка идемпотентности (2-й прогон)...")
doc_obj2 = doc_ref.ПолучитьОбъект()
doc_obj2.Записать(erp.РежимЗаписиДокумента.Проведение)
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Рег", doc_ref)
q.Text = """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаКонечныйОстаток) КАК ΣКО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод ГДЕ ДокументДвижения = &Рег"""
r2 = q.Execute().Выгрузить().Получить(0)
print(f"  После 2-го прогона: строк={r2.Кол}, Σ КО={r2.ΣКО:.2f}")
assert r2.Кол == r.Количество(), f"Количество строк изменилось: {r.Количество()} -> {r2.Кол}"

print("\n[OK] Verify PASS — расшифровка работает, баланс == ПАП, идемпотентно")
