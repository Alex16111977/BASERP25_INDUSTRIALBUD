"""Как Номенклатура связана с ОбщееНазвание + структура ТЧ готового документа."""
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')
import win32com.client
v8 = win32com.client.Dispatch("V83.COMConnector")
buh = v8.Connect('Srvr="SQLSERVER";Ref="BuhBud";Usr="cfo";Pwd="2442"')
S = buh.String

# 1) Реквизиты Номенклатуры, ссылающиеся на ОбщиеНазванияНоменклатуры
print("=== Номенклатура: реквизиты-кандидаты на ОбщееНазвание ===")
mdN = buh.Метаданные.Справочники.Номенклатура
for r in mdN.Реквизиты:
    im = r.Имя
    if any(k in im for k in ("Общ","Назв","Эталон","Етал","Групп")):
        print(f"  {im}")
# полный список (вдруг другое имя)
print("  --- все реквизиты Номенклатуры ---")
print("   ", ", ".join([r.Имя for r in mdN.Реквизиты]))

# 2) Тип ОбщееНазвание в спецификации
md = buh.Метаданные.Справочники.СтруктураСебестоимости
for tc in md.ТабличныеЧасти:
    for c in tc.Реквизиты:
        if c.Имя == "ОбщееНазвание":
            print("\nСтруктураСебестоимости.Комплектующие.ОбщееНазвание тип:", S(c.Тип.Типы().Получить(0)) if hasattr(c.Тип,'Типы') else c.Тип)

# 3) ТЧ Комплектующие готового документа ІБ00-000076
