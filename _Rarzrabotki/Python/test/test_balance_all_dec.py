# -*- coding: utf-8 -*-
# ИСЧЕРПЫВАЮЩАЯ проверка баланса по подразделениям за ВЕСЬ декабрь 2025.
# Для КАЖДОГО документа-основания и КАЖДОГО его подразделения:
#   покрытие взаимозачётами (Σ где Приход - Σ где Расход)  ==  чистое ПАП-сальдо.
# Любое расхождение => документ, у которого баланс по подразделениям СЛОМАЕТСЯ.
import win32com.client, sys, datetime
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

ERF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Обработки\А_ОбработкаДисбалансаПоПодразделениям.erf"
v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

try:
    obr = erp.ВнешниеОтчеты.Создать(ERF, False)
except Exception:
    obr = erp.ВнешниеОтчеты.Создать(ERF)

# Весь декабрь (30.11 полдень .. 31.12 полдень -> КонецДня покрывает 31.12)
obr.НачалоПериода = datetime.datetime(2025, 11, 30, 12, 0, 0)
obr.ОкончаниеПериода = datetime.datetime(2025, 12, 31, 12, 0, 0)
obr.ПоказыватьВсе = True
print("Запуск Анализа за декабрь 2025 (может занять минуту)...")
obr.АнализДокументов()

# Покрытие из ТЧ: coverage[докKey][подрName] = Σ(приход) - Σ(расход)
coverage = {}
docrefs = {}   # докKey -> ref
тч = obr.ДокументыДисбаланса
for i in range(тч.Количество()):
    стр = тч.Получить(i)
    if стр.СуммаДокумента <= 0 or not erp.ЗначениеЗаполнено(стр.Документ):
        continue
    dk = erp.XMLСтрока(стр.Документ)
    docrefs[dk] = стр.Документ
    d = coverage.setdefault(dk, {})
    if erp.ЗначениеЗаполнено(стр.ПодразделениеПриход):
        п = erp.String(стр.ПодразделениеПриход)
        d[п] = round(d.get(п, 0) + стр.СуммаДокумента, 2)
    if erp.ЗначениеЗаполнено(стр.ПодразделениеРасход):
        п = erp.String(стр.ПодразделениеРасход)
        d[п] = round(d.get(п, 0) - стр.СуммаДокумента, 2)
print(f"Документов-оснований с парами: {len(coverage)}")

# ИСТИНА: ПАП-сальдо по (Регистратор, Подразделение) для этих документов (одним запросом)
массив = erp.NewObject("Массив")
for ref in docrefs.values():
    массив.Добавить(ref)
q = erp.NewObject("Запрос")
q.УстановитьПараметр("Список", массив)
q.Text = """
ВЫБРАТЬ ПАП.Регистратор КАК Рег, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение) КАК Подр,
	СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) КАК Нетто
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Регистратор В (&Список)
	И НЕ ПАП.Статья В (ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),
		ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))
СГРУППИРОВАТЬ ПО ПАП.Регистратор, ПРЕДСТАВЛЕНИЕ(ПАП.Подразделение)
ИМЕЮЩИЕ СУММА(ВЫБОР КОГДА ПАП.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА ПАП.Сумма ИНАЧЕ -ПАП.Сумма КОНЕЦ) <> 0
"""
truth = {}
s = q.Execute().Выбрать()
while s.Следующий():
    dk = erp.XMLСтрока(s.Рег)
    truth.setdefault(dk, {})[s.Подр] = round(s.Нетто, 2)

# Сверка по каждому (документ, подразделение)
плохие = []
докпров = 0
for dk in set(truth) | set(coverage):
    докпров += 1
    t = truth.get(dk, {})
    c = coverage.get(dk, {})
    for п in set(t) | set(c):
        tv = t.get(п, 0)
        cv = c.get(п, 0)
        if abs(tv - cv) > 0.01:
            имя = erp.String(docrefs.get(dk)) if dk in docrefs else dk
            плохие.append((имя, п, tv, cv, round(tv - cv, 2)))

print(f"Проверено документов: {докпров}")
if плохие:
    print(f"\n!!! РАСХОЖДЕНИЯ баланса: {len(плохие)} (документ | подразделение | ПАП | покрытие | Δ)")
    for имя, п, tv, cv, d in плохие[:40]:
        print(f"   {имя[:55]:55} | {п[:30]:30} | {tv:>13.2f} | {cv:>13.2f} | Δ={d:>11.2f}")
    if len(плохие) > 40:
        print(f"   ... ещё {len(плохие) - 40}")
    print("\n=== БАЛАНС ЛОМАЕТСЯ У НЕКОТОРЫХ ДОКУМЕНТОВ (FAIL) ===")
else:
    print("\nВсе документы: покрытие взаимозачётами == ПАП-сальдо по каждому подразделению.")
    print("=== БАЛАНС ПО ПОДРАЗДЕЛЕНИЯМ СОЙДЁТСЯ ДЛЯ ВСЕГО ДЕКАБРЯ (PASS) ===")
