# -*- coding: utf-8 -*-
"""
Rule #-1: проверка ВСЕХ запросов будущего отчёта А_ОтчетПоВыполнениюРаботвПроизводстве
на живой BaseERP до переноса в BSL.

Запросы:
  Q1 — паспорт СС (домів, модулів, площа) + дома-подразделения;
  Q2 — строки-работы кошториса (порядок, етап, норма);
  Q3 — % по (дім × модуль × работа): ТЧ ПОСЛЕДНЕГО документа каждого дома с датой <= КонП;
  Q4 — табель по домах за период.
"""
import sys, re
sys.stdout.reconfigure(encoding='utf-8')
import win32com.client

erp = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')


def выполнить(имя, текст, **п):
    z = erp.NewObject("Запрос")
    for k, v in п.items():
        z.УстановитьПараметр(k, v)
    z.Текст = текст
    try:
        r = z.Execute().Выгрузить()
        print(f"[OK]   {имя}: рядків = {r.Количество()}")
        return r
    except Exception as e:
        msg = e.excepinfo[2] if getattr(e, "excepinfo", None) else str(e)
        print(f"[FAIL] {имя}: {msg}")
        raise SystemExit(1)


для_сс = sys.argv[1] if len(sys.argv) > 1 else "МД IRS 2026 30 м (МД IRS 2026)"
print(f"=== СС: {для_сс} ===")
сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(для_сс)
гр = erp.NewObject("Запрос")
гр.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,7,1,0,0,0) КАК Н, ДАТАВРЕМЯ(2026,7,31,23,59,59) КАК К"
г = гр.Execute().Выгрузить().Получить(0)
НачП, КонП = г.Н, г.К

# ---------------------------------------------------------------- Q1 паспорт СС + дома
Q1 = """
ВЫБРАТЬ
	СС.Наименование КАК НаименованиеСС,
	ВЫБОР КОГДА СС.КоличествоДомов > 0 ТОГДА СС.КоличествоДомов ИНАЧЕ 1 КОНЕЦ КАК Домов,
	ВЫБОР КОГДА СС.А_КоличествоМодулей > 0 ТОГДА СС.А_КоличествоМодулей ИНАЧЕ 1 КОНЕЦ КАК Модулей,
	СС.Площадь КАК Площадь
ИЗ
	Справочник.А_СтруктураСебестоимости КАК СС
ГДЕ
	СС.Ссылка = &СС
"""
r = выполнить("Q1 паспорт СС", Q1, СС=сс.Ссылка)
s = r.Получить(0)
N, M = int(s.Домов), int(s.Модулей)
print(f"       домів={N} модулів={M} площа={float(s.Площадь):g}")

Q1B = """
ВЫБРАТЬ РАЗЛИЧНЫЕ
	Д.Подразделение КАК Подразделение,
	Д.Подразделение.Наименование КАК ПодрНаим
ИЗ
	Документ.А_ВыполнениеРаботМодулей КАК Д
ГДЕ
	Д.СтруктураСебестоимости = &СС
	И НЕ Д.ПометкаУдаления
	И Д.Дата <= &КонП
УПОРЯДОЧИТЬ ПО
	ПодрНаим
"""
r = выполнить("Q1B дома-подразделения", Q1B, СС=сс.Ссылка, КонП=КонП)
дома = []
for i in range(r.Количество()):
    m = re.search(r"№(\d+)", str(r.Получить(i).ПодрНаим))
    if m:
        дома.append(int(m.group(1)))
print(f"       дома: {sorted(дома)}")
assert sorted(дома) == list(range(1, N + 1)), "дома не 1..N"

# ---------------------------------------------------------------- Q2 работы кошториса
Q2 = """
ВЫБРАТЬ
	Р.НомерСтроки КАК НомерСтроки,
	Р.Работа КАК Работа,
	Р.Работа.Наименование КАК РаботаНаим,
	Р.Этап КАК Этап,
	Р.Этап.Наименование КАК ЭтапНаим,
	Р.Количество КАК Норма
ИЗ
	Справочник.А_СтруктураСебестоимости.Работы КАК Р
ГДЕ
	Р.Ссылка = &СС
УПОРЯДОЧИТЬ ПО
	НомерСтроки
"""
r = выполнить("Q2 работы кошториса", Q2, СС=сс.Ссылка)
норма = {}
for i in range(r.Количество()):
    s = r.Получить(i)
    норма[str(s.РаботаНаим)] = float(s.Норма or 0)
print(f"       Σ норм = {sum(норма.values()):.2f}")

# ---------------------------------------------------------------- Q3 % последнего снимка каждого дома
# ⚠ НЕ РегистрСведений.СрезПоследних: ключ РС (СС × Работа × НомерМодуля) НЕ содержит
# подразделения, срез схлопнул бы дома в один ключ (LESSONS §2). Берём ТЧ последнего документа дома.
Q3 = """
ВЫБРАТЬ
	Д.Подразделение КАК Подразделение,
	МАКСИМУМ(Д.Дата) КАК ДатаСнимка
ПОМЕСТИТЬ ВТ_Последние
ИЗ
	Документ.А_ВыполнениеРаботМодулей КАК Д
ГДЕ
	Д.СтруктураСебестоимости = &СС
	И НЕ Д.ПометкаУдаления
	И Д.Проведен
	И Д.Дата <= &КонП
СГРУППИРОВАТЬ ПО
	Д.Подразделение
;
ВЫБРАТЬ
	ВТ.Подразделение КАК Подразделение,
	ВТ.Подразделение.Наименование КАК ПодрНаим,
	ВТ.ДатаСнимка КАК ДатаСнимка,
	Т.Работа КАК Работа,
	Т.Работа.Наименование КАК РаботаНаим,
	Т.НомерМодуля КАК НомерМодуля,
	Т.Процент КАК Процент,
	Т.ПланЧасыМодуля КАК ПланЧасыМодуля,
	Т.Комментарий КАК Комментарий
ИЗ
	ВТ_Последние КАК ВТ
		ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей КАК Д
		ПО ВТ.Подразделение = Д.Подразделение
			И ВТ.ДатаСнимка = Д.Дата
			И Д.СтруктураСебестоимости = &СС
			И НЕ Д.ПометкаУдаления
		ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.А_ВыполнениеРаботМодулей.Работы КАК Т
		ПО Т.Ссылка = Д.Ссылка
"""
r = выполнить("Q3 % последнего снимка", Q3, СС=сс.Ссылка, КонП=КонП)
ячейки, планмод = {}, {}
даты = set()
for i in range(r.Количество()):
    s = r.Получить(i)
    k = int(re.search(r"№(\d+)", str(s.ПодрНаим)).group(1))
    ячейки[(str(s.РаботаНаим), k, int(s.НомерМодуля))] = float(s.Процент)
    планмод[str(s.РаботаНаим)] = float(s.ПланЧасыМодуля)
    даты.add(str(s.ДатаСнимка)[:10])
print(f"       дат снимков: {sorted(даты)} | работ: {len(планмод)} | ячеек: {len(ячейки)}")
assert len(ячейки) == len(планмод) * N * M, "ячеек != работ × домів × модулів"

# ---------------------------------------------------------------- Q4 табель за период
Q4 = """
ВЫБРАТЬ
	Т.Подразделение КАК Подразделение,
	Т.Подразделение.Наименование КАК ПодрНаим,
	СУММА(Т.ЧасыФакт) КАК ЧасыФакт
ИЗ
	РегистрНакопления.А_ДанныеТабелирования КАК Т
ГДЕ
	Т.Подразделение В ИЕРАРХИИ (&Подразделения)
	И Т.Период МЕЖДУ &НачП И &КонП
СГРУППИРОВАТЬ ПО
	Т.Подразделение,
	Т.Подразделение.Наименование
"""
массив = erp.NewObject("Массив")
r = выполнить("Q1B(2) список подразделений", Q1B, СС=сс.Ссылка, КонП=КонП)
for i in range(r.Количество()):
    массив.Добавить(r.Получить(i).Подразделение)
r = выполнить("Q4 табель за період", Q4, Подразделения=массив, НачП=НачП, КонП=КонП)
табель = {}
for i in range(r.Количество()):
    s = r.Получить(i)
    m = re.search(r"№(\d+)", str(s.ПодрНаим))
    if m:
        табель[int(m.group(1))] = float(s.ЧасыФакт or 0)
print(f"       табель по домах: {табель}")

# ---------------------------------------------------------------- контрольные суммы
план = sum(планмод[w] * M * N for w in планмод)
вик = sum(планмод[w] * ячейки[(w, k, m)] / 100 for w in планмод
          for k in range(1, N + 1) for m in range(1, M + 1))
print(f"\nКОНТРОЛЬ: План = {план:.2f}, Виконано = {вик:.2f} ({вик/план*100:.2f}%)")
# Виконано из ТЧ последнего снимка ОБЯЗАНО совпасть с оборотами РН по СС (±0,6 — округление
# ЧасыВыполнение до 2 знаков в ТЧ против 3 в регистре, накопленное по всем строкам).
эталон = float(выполнить("Обороты РН по СС",
                         "ВЫБРАТЬ СУММА(Т.ЧасыВыполнение) КАК Ч "
                         "ИЗ РегистрНакопления.А_ВыполнениеРаботМодулей КАК Т "
                         "ГДЕ Т.СтруктураСебестоимости = &СС", СС=сс.Ссылка).Получить(0).Ч or 0)
совп = abs(вик - эталон) < 0.6
print(f"Обороти РН по СС = {эталон:.2f} -> {'OK' if совп else 'РОЗБІЖНІСТЬ'}")
print("\nВСЕ ЗАПРОСЫ ОТЧЁТА ПРОШЛИ." if совп else "\n❌ ВИКОНАННЯ НЕ ЗБІГАЄТЬСЯ З РЕГІСТРОМ")
sys.exit(0 if совп else 1)
