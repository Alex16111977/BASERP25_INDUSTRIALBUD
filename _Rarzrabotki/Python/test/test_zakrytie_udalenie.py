# -*- coding: utf-8 -*-
"""Тест функции УдалитьДокументыЗакрытия() в скомпилированной .epf.

1. До: считаем сколько документов с флагом А_ДляЗакрытиеОтрицательныхОстатков
   в апреле 2026 у ТОВ ІНДАСТРІАЛБУД
2. Вызываем УдалитьДокументыЗакрытия() с НачалоПериода=01.04.2026, ОкончаниеПериода=30.04.2026
3. После: считаем сколько осталось — должно быть 0
4. Проверяем что СведенияОВнешнейОбработке() всё ещё работает (регрессия)
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
EPF = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\build\ЗакрытиеОтрицательныхОстатков.epf"
ORG_UUID = "6bee36b2-53f0-11e6-80d3-000c29bbac23"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)

# подготовка дат
q = erp.NewObject("Запрос")
q.Text = "ВЫБРАТЬ ДАТАВРЕМЯ(2026,4,1) КАК Н, ДАТАВРЕМЯ(2026,4,30) КАК К"
r = q.Execute().Выгрузить().Получить(0)
nach, kon = r.Н, r.К

org = erp.Справочники.Организации.ПолучитьСсылку(
    erp.NewObject("УникальныйИдентификатор", ORG_UUID))


def count_docs():
    q = erp.NewObject("Запрос")
    q.Text = """
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
    ИЗ Документ.ОприходованиеИзлишковТоваров КАК Д
    ГДЕ Д.А_ДляЗакрытиеОтрицательныхОстатков = ИСТИНА
      И Д.Дата >= ДАТАВРЕМЯ(2026,4,1)
      И Д.Дата <= ДАТАВРЕМЯ(2026,4,30,23,59,59)
      И Д.Организация = &Орг
    """
    q.SetParameter("Орг", org)
    return q.Execute().Выгрузить().Получить(0).К


print("=" * 60)
print("ТЕСТ: УдалитьДокументыЗакрытия")
print("=" * 60)

before = count_docs()
print(f"  [1] До: документов с флагом в апреле = {before}")

обработка = erp.ВнешниеОбработки.Создать(EPF)
обработка.НачалоПериода = nach
обработка.ОкончаниеПериода = kon
обработка.Организация = org

print("  [2] Запуск УдалитьДокументыЗакрытия()...")
рез = обработка.УдалитьДокументыЗакрытия()
print(f"      Удалено: {рез.Удалено}, Ошибок: {рез.Ошибок}")
if int(рез.Ошибок) > 0:
    for i in range(рез.Ошибки.Количество()):
        print(f"      ERR: {erp.String(рез.Ошибки.Получить(i))}")

after = count_docs()
print(f"  [3] После: документов осталось = {after}")
assert after == 0, f"Должно быть 0 документов, осталось {after}"

print("  [4] Проверка СведенияОВнешнейОбработке (регрессия)...")
свед = обработка.СведенияОВнешнейОбработке()
assert erp.String(свед.Вид) == "ДополнительнаяОбработка"
assert свед.Команды.Количество() >= 1
print(f"      Вид={erp.String(свед.Вид)}, команд={свед.Команды.Количество()}")

print("=" * 60)
print("OK")
