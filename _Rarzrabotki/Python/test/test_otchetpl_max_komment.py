# -*- coding: utf-8 -*-
"""
Воспроизведение и проверка исправления ошибки «Неверные параметры МАКСИМУМ»
при агрегации поля Строка неограниченной длины в отчёте А_ОтчетPL.

ТЧ Документ.А_ОтчетPL.ДанныеОтчета.Комментарий — Строка без указания длины.
1С не даёт применять МАКСИМУМ/МИНИМУМ/ГРУППИРОВАТЬ/сравнения к таким полям.

Решение: МАКСИМУМ(ВЫРАЗИТЬ(ТЧ.Комментарий КАК Строка(1000))) — ВЫРАЗИТЬ ВНУТРИ агрегата.
"""
import win32com.client
import pythoncom

CONNECTION_STRING = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'


def run_query(conn, label, query_text):
    q = conn.NewObject("Запрос")
    q.Текст = query_text
    try:
        result = q.Выполнить()
        table = result.Выгрузить()
        print(f"[OK] {label}: {table.Количество()} строк")
        return True, None
    except Exception as e:
        print(f"[FAIL] {label}: {e}")
        return False, str(e)


def main():
    pythoncom.CoInitialize()
    v8 = win32com.client.Dispatch("V83.COMConnector")
    conn = v8.Connect(CONNECTION_STRING)
    print("[OK] Connected to BaseERP")

    # === Сломанный вариант (как было до fix) ===
    broken = """
    ВЫБРАТЬ ПЕРВЫЕ 5
        ТЧ.Ссылка КАК Документ,
        ТЧ.Статья КАК СтатьяPL,
        МАКСИМУМ(ТЧ.Комментарий) КАК Комментарий
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
    ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
    СГРУППИРОВАТЬ ПО ТЧ.Ссылка, ТЧ.Статья
    """

    # === Исправленный вариант ===
    fixed = """
    ВЫБРАТЬ ПЕРВЫЕ 5
        ТЧ.Ссылка КАК Документ,
        ТЧ.Статья КАК СтатьяPL,
        МАКСИМУМ(ВЫРАЗИТЬ(ТЧ.Комментарий КАК Строка(1000))) КАК Комментарий
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
    ГДЕ НЕ ТЧ.Ссылка.ПометкаУдаления
    СГРУППИРОВАТЬ ПО ТЧ.Ссылка, ТЧ.Статья
    """

    print("\n--- Тест 1: Сломанный запрос (должен упасть) ---")
    ok_broken, _ = run_query(conn, "BROKEN МАКСИМУМ(ТЧ.Комментарий)", broken)

    print("\n--- Тест 2: Исправленный запрос (должен пройти) ---")
    ok_fixed, _ = run_query(conn, "FIXED МАКСИМУМ(ВЫРАЗИТЬ(...КАК Строка(1000)))", fixed)

    # === Полный запрос отчёта (как в ObjectModule.bsl после fix) ===
    # Эмулируем CTE втPL с новыми полями Документ + Комментарий
    full_cte_test = """
    ВЫБРАТЬ
        ТЧ.Ссылка КАК Документ,
        ТЧ.Ссылка.Подразделение КАК Подразделение,
        ТЧ.Ссылка.ПодразделениеСтрока КАК ПодразделениеСтрока,
        ТЧ.Статья КАК СтатьяPL,
        ТЧ.Статья.Группа КАК Группа,
        ТЧ.Статья.СтатьяДоходов КАК СтатьяДоходов,
        СУММА(ТЧ.СуммаФома1) КАК СуммаФ1,
        СУММА(ТЧ.СуммаФорма2) КАК СуммаФ2,
        СУММА(ТЧ.Сумма) КАК СуммаPL,
        МАКСИМУМ(ВЫРАЗИТЬ(ТЧ.Комментарий КАК Строка(1000))) КАК Комментарий
    ПОМЕСТИТЬ втPL
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
    ГДЕ ТЧ.Ссылка.Дата МЕЖДУ &НачалоПериода И &КонецПериода
        И НЕ ТЧ.Ссылка.ПометкаУдаления
    СГРУППИРОВАТЬ ПО
        ТЧ.Ссылка, ТЧ.Ссылка.Подразделение, ТЧ.Ссылка.ПодразделениеСтрока,
        ТЧ.Статья, ТЧ.Статья.Группа, ТЧ.Статья.СтатьяДоходов
    ;
    ВЫБРАТЬ ПЕРВЫЕ 5 * ИЗ втPL
    """
    print("\n--- Тест 3: Полный CTE втPL с Документ + Комментарий ---")
    import pywintypes
    from datetime import datetime
    q = conn.NewObject("Запрос")
    q.Текст = full_cte_test
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(datetime(2025, 12, 1)))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(datetime(2025, 12, 31, 23, 59, 59)))
    try:
        res = q.Выполнить().Выгрузить()
        print(f"[OK] CTE втPL вернул {res.Количество()} строк")
        if res.Количество() > 0:
            row = res.Получить(0)
            print(f"  Пример: Документ={row.Документ}, СтатьяPL={row.СтатьяPL}, Комментарий='{str(row.Комментарий)[:80]}'")
        ok_cte = True
    except Exception as e:
        print(f"[FAIL] CTE: {e}")
        ok_cte = False

    print("\n=== ИТОГ ===")
    if not ok_broken and ok_fixed and ok_cte:
        print("[PASS] Ошибка воспроизведена без ВЫРАЗИТЬ; исправление работает.")
        return 0
    elif ok_broken:
        print("[WARNING] Сломанный запрос неожиданно прошёл — возможно 1С стала терпимее?")
        return 0 if ok_fixed and ok_cte else 1
    else:
        print("[FAIL] Исправленный запрос упал.")
        return 1


if __name__ == "__main__":
    import sys
    sys.exit(main())
