def свод_по_источнику(arr, метка, пусто=False):
    q = ERP.NewObject("Запрос")
    усл = ("Т.Источник = ЗНАЧЕНИЕ(Перечисление.ИсточникиУправленческогоБаланса.ПустаяСсылка)"
           if пусто else "Т.Источник В (&Ист)")
    q.Текст = f"""ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Т.Статья) КАК Ст,
     КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Т.Регистратор) КАК КолРег,
     СУММА(ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
       ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ) КАК КонОст,
     СУММА(ВЫБОР КОГДА Т.Период<&НМ
       ТОГДА ВЫБОР КОГДА Т.ВидДвижения=ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)
         ТОГДА Т.Сумма ИНАЧЕ -Т.Сумма КОНЕЦ ИНАЧЕ 0 КОНЕЦ) КАК НачОст
    ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК Т
    ГДЕ Т.Организация=&Орг И Т.Период<=&КД И {усл}
    СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Т.Статья)"""
    q.УстановитьПараметр("Орг", ORG); q.УстановитьПараметр("КД", КД)
    q.УстановитьПараметр("НМ", НМ)
    if not пусто:
        q.УстановитьПараметр("Ист", arr)
    try:
        t = q.Выполнить().Выгрузить()
    except Exception as e:
        msg = e.excepinfo[2] if hasattr(e, "excepinfo") and e.excepinfo else str(e)
        print(f"FAIL {метка}: {msg}"); sys.exit(1)
    print(f"\n[{метка}] статей={t.Количество()}")
    итог = {}
    for i in range(t.Количество()):
        r = t.Получить(i)
        итог[str(r.Ст)] = float(r.КонОст or 0)
        print(f"  {str(r.Ст)[:40]:40} НачОст={float(r.НачОст or 0):,.2f} "
              f"КонОст={float(r.КонОст or 0):,.2f} рег={int(r.КолРег)}")
    return итог


