def користувач(u, ім):
    """Користувач казни (UUID, ім'я) → (UUID, реф) у BuhBud або None."""
    if u == НУЛЬ:
        return None
    if u not in кеш:
        ім = ПСЕВДОНІМИ.get(str(ім).strip(), str(ім).strip())
        реф = за_uuid.get(u) or за_іменем.get(ім)
        if реф is None:
            в = за_ключем.get(норм_текст(ім), [])
            реф = в[0] if len(в) == 1 else None
        кеш[u] = (уід(bh, реф), реф) if реф is not None else None
        if реф is None:
            кеш[u + "_ім"] = ім
    if кеш[u] is None:
        нема_корист[кеш[u + "_ім"]] += 1
    return кеш[u]


