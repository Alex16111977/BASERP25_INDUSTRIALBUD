def норм_текст(s):
    s = str(s).lower()
    for a, b in (("і", "и"), ("ї", "и"), ("й", "и"), ("є", "е"), ("ё", "е"), ("ґ", "г")):
        s = s.replace(a, b)
    s = re.sub(r"[ьъ'’ʼ\"«»]", "", s)
    return " ".join(sorted(re.sub(r"\s+", " ", s).strip().split()))


