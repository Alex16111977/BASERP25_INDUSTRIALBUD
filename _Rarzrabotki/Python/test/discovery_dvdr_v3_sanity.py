for i in range(r.Количество()):
    row = r.Получить(i)
    if abs(float(row.КО)) > 0.01:
        pap_map[S(row.ПодрПред)] = float(row.КО)
        print(f"    {S(row.ПодрПред):<25} | КО={row.КО:>15.2f}")
