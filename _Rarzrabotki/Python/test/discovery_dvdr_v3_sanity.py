for i in range(r.Количество()):
    row = r.Получить(i)
    if abs(float(row.Σ)) > 0.01:
        ddr_map[S(row.ПодрПред)] = float(row.Σ)
        print(f"    {S(row.ПодрПред):<25} | signedΣ={row.Σ:>15.2f}")
