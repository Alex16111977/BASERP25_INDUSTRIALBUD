# -*- coding: utf-8 -*-
"""Проверка фактических прав пользователя 'Менеджер ПТО' на А_ВыполнениеРаботМодулей."""
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

USER = "Менеджер ПТО"
ROLE = "А_ДобавлениеИзменениеВыполненияРаботМодулей"
MARKER = "А_ВыполнениеРаботПросмотрЧасов"

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ Пользователи.ИдентификаторПользователяИБ КАК УИД
ИЗ Справочник.Пользователи КАК Пользователи
ГДЕ Пользователи.Наименование = &Наим
"""
q.SetParameter("Наим", USER)
r = q.Execute().Выгрузить()
if r.Количество() == 0:
    print("FAIL: пользователь не найден")
    sys.exit(1)
uid_str = erp.String(r.Получить(0).УИД)
ib = erp.ПользователиИнформационнойБазы.НайтиПоУникальномуИдентификатору(
    erp.NewObject("УникальныйИдентификатор", uid_str))
if ib is None:
    print("FAIL: ИБ-пользователь не найден по УИД", uid_str)
    sys.exit(1)
print(f"ИБ-пользователь: {ib.Имя}")

md_role = erp.Метаданные.Роли.Найти(ROLE)
md_marker = erp.Метаданные.Роли.Найти(MARKER)
md_full = erp.Метаданные.Роли.Найти("ПолныеПрава")
print("Роль доступа на ВРМ назначена:", ib.Роли.Содержит(md_role))
print("Роль-маркер часов (должна быть False):", ib.Роли.Содержит(md_marker))
print("ПолныеПрава (должна быть False):", ib.Роли.Содержит(md_full))

md_doc = erp.Метаданные.Документы.Найти("А_ВыполнениеРаботМодулей")
md_ss = erp.Метаданные.Справочники.Найти("А_СтруктураСебестоимости")
md_et = erp.Метаданные.Справочники.Найти("А_ЭтапыРабот")
for pravo in ["Чтение", "Просмотр", "Добавление", "Изменение", "Проведение", "ИнтерактивноеПроведение", "ОтменаПроведения"]:
    print(f"  Документ.{pravo}:", erp.ПравоДоступа(pravo, md_doc, ib))
for nm, mdo in [("СтруктураСебестоимости", md_ss), ("ЭтапыРабот", md_et)]:
    for pravo in ["Чтение", "Просмотр"]:
        print(f"  {nm}.{pravo}:", erp.ПравоДоступа(pravo, mdo, ib))
md_sub = erp.Метаданные.Подсистемы.Найти("Производство")
print("  Подсистема Производство.Просмотр:", erp.ПравоДоступа("Просмотр", md_sub, ib))
print("DONE")
