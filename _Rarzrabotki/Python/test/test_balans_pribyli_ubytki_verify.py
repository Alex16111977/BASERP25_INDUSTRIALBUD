# -*- coding: utf-8 -*-
"""Verify acceptance тест для розкладу 'Прибыли и убытки' по Подразделение.

Кроки:
  1) Перепровести А_ФинРез_Баланс janv 2026 для ТОВ ІНДАСТРІАЛБУД
  2) Прочитати рядки А_ОтчетБаланс_Свод з фільтром Статья="Прибыли и убытки"
  3) Asserts:
     - 122/122 рядків мають Аналитика1 ≠ "" і == ПРЕДСТАВЛЕНИЕ(Подразделение)
     - Σ КО НЕ змінилося (−110 616 551,99)
     - 0 дублів ключа
  4) Інші статті (Налоги/ОС/НМА) НЕ змінилися (smoke)
  5) Регресія: Актив janv 2026 == 288 787 750,11 ± 1 ₽
  6) Ідемпотентність: 2-й прогон → Δ=0
"""
import sys, io
from collections import defaultdict
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

TOL_RUB = 1.0
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = conn.String

q0 = conn.NewObject("Запрос")
q0.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ Справочник.Организации ГДЕ КодПоЕДРПОУ = "40645273"')
r0 = q0.Выполнить().Выбрать(); r0.Следующий(); ORG = r0.С

qПУ = conn.NewObject("Запрос")
qПУ.Текст = ('ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК С ИЗ '
             'ПланВидовХарактеристик.СтатьиАктивовПассивов '
             'ГДЕ Наименование = "Прибыли и убытки"')
rПУ = qПУ.Выполнить().Выбрать(); rПУ.Следующий(); ПУ = rПУ.С

PROVED = conn.PredefinedValue("РежимЗаписиДокумента.Проведение")

# 1) Знайти А_ФинРез_Баланс janv 2026
qB = conn.NewObject("Запрос")
qB.Текст = """ВЫБРАТЬ ПЕРВЫЕ 1 Б.Ссылка КАК Б
ИЗ Документ.А_ФинРез_Баланс КАК Б
ГДЕ Б.Организация = &Орг
    И НАЧАЛОПЕРИОДА(Б.Месяц,МЕСЯЦ) = ДАТАВРЕМЯ(2026, 1, 1)
    И Б.Проведен"""
qB.УстановитьПараметр("Орг", ORG)
rB = qB.Выполнить().Выбрать()
if not rB.Следующий():
    print("[FAIL] А_ФинРез_Баланс janv 2026 не знайдено")
    sys.exit(1)
balans = rB.Б
print(f"[INFO] Знайдено А_ФинРез_Баланс: {S(balans)}")

# 2) Перепровести
def repost():
    balans.ПолучитьОбъект().Записать(PROVED)
    print(f"  Перепроведено")

print("\n[2] Перепроведення А_ФинРез_Баланс janv 2026")
repost()

# 3) Прочитати ПУ-рядки
def read_pu():
    q = conn.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ
        С.Подразделение КАК Подр,
        ПРЕДСТАВЛЕНИЕ(С.Подразделение) КАК Подр_представл,
        С.Аналитика1 КАК Ан1,
        С.Расхождение КАК Розб,
        С.СуммаНачальныйОстаток КАК НО,
        С.СуммаКонечныйОстаток КАК КО
    ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК С
    ГДЕ С.ДокументДвижения = &Б И С.Статья = &ПУ
    """
    q.УстановитьПараметр("Б", balans); q.УстановитьПараметр("ПУ", ПУ)
    return q.Выполнить().Выгрузить()

rows = read_pu()
print(f"\n[3] Рядків ПУ для janv 2026: {rows.Количество()}")

деталі = 0; плуг = 0
ан1_empty = 0; ан1_mismatch = 0
Σ_НО = 0; Σ_КО = 0
keys = defaultdict(int)
for i in range(rows.Количество()):
    r = rows.Получить(i)
    розб = bool(r.Розб)
    if розб:
        плуг += 1
    else:
        деталі += 1
    ан1 = S(r.Ан1)
    подр_repr = S(r.Подр_представл)
    if ан1 == "":
        ан1_empty += 1
    if not розб and ан1 != подр_repr:
        ан1_mismatch += 1
    Σ_НО += float(r.НО or 0)
    Σ_КО += float(r.КО or 0)
    keys[(S(r.Подр), ан1)] += 1
дублі = sum(1 for v in keys.values() if v > 1)

print(f"  Деталь-рядки: {деталі}")
print(f"  Плуг (Расхождение=Истина): {плуг}")
print(f"  Пуста Аналитика1: {ан1_empty}")
print(f"  Аналитика1 != Подразделение: {ан1_mismatch}")
print(f"  Дублі ключа (Подр, Ан1): {дублі}")
print(f"  Σ НО: {Σ_НО:>+14,.2f}")
print(f"  Σ КО: {Σ_КО:>+14,.2f}")

# Приклади перших 5
print(f"\nПриклади перших 5 рядків:")
for i in range(min(5, rows.Количество())):
    r = rows.Получить(i)
    print(f"  Подр='{S(r.Подр_представл):28}' Ан1='{S(r.Ан1):28}' КО={float(r.КО or 0):>+14,.2f}")

inv_ok = abs(Σ_КО - (-110_616_551.99)) <= 100  # допустимо ±100 ₽ через паралельні перепроведення
ан_ok = ан1_empty == 0 and ан1_mismatch == 0
дублі_ok = дублі == 0
деталі_ok = деталі > 0

print(f"\n[ASSERTS]")
print(f"  Деталь-рядки > 0:             {'PASS' if деталі_ok else 'FAIL'} ({деталі})")
print(f"  100% Аналитика1=Подразделение: {'PASS' if ан_ok else 'FAIL'}")
print(f"  Σ КО ≈ −110 616 551,99:       {'PASS' if inv_ok else 'FAIL'} ({Σ_КО:+,.2f})")
print(f"  Дублі = 0:                    {'PASS' if дублі_ok else 'FAIL'}")

# 4) Smoke — інші статті (Налоги) не зачеплені
print(f"\n[4] Smoke — Налоги janv 2026 КО (повинно бути ~9 331 275,92)")
qN = conn.NewObject("Запрос")
qN.Текст = """
ВЫБРАТЬ СУММА(С.СуммаКонечныйОстаток) КАК КО
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК С
ГДЕ С.ДокументДвижения = &Б
    И С.Статья В (
        ВЫБРАТЬ Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов ГДЕ Наименование = "Налоги")
"""
qN.УстановитьПараметр("Б", balans)
rN = qN.Выполнить().Выбрать(); rN.Следующий()
КО_налоги = float(rN.КО or 0)
print(f"  КО Налоги: {КО_налоги:+,.2f}")
smoke_ok = abs(КО_налоги - 9_331_275.92) <= 100
print(f"  Smoke: {'PASS' if smoke_ok else 'FAIL'}")

# 5) Регресія балансу
print(f"\n[5] Регресія Актив janv 2026")
qI = conn.NewObject("Запрос")
qI.Текст = ('ВЫБРАТЬ Ссылка ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов '
            'ГДЕ Наименование В (&Имена)')
имена = conn.NewObject("Массив")
for n in ("Собственные средства", "Доходы текущего периода", "Расходы текущего периода"):
    имена.Добавить(n)
qI.УстановитьПараметр("Имена", имена)
tI = qI.Выполнить().Выгрузить()
ИсклМ = conn.NewObject("Массив")
for i in range(tI.Количество()):
    ИсклМ.Добавить(tI.Получить(i).Ссылка)

qA = conn.NewObject("Запрос")
qA.Текст = """
ВЫБРАТЬ СУММА(ВЫБОР КОГДА Ст.АктивПассив = ЗНАЧЕНИЕ(Перечисление.ВидыСтатейУправленческогоБаланса.Актив)
                  ТОГДА С.СуммаКонечныйОстаток ИНАЧЕ 0 КОНЕЦ) КАК Актив
ИЗ РегистрСведений.А_ОтчетБаланс_Свод КАК С
    ЛЕВОЕ СОЕДИНЕНИЕ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК Ст
        ПО С.Статья = Ст.Ссылка
ГДЕ С.Организация = &Орг И НЕ С.Статья В ИЕРАРХИИ(&Искл) И С.ДокументДвижения В (
    ВЫБРАТЬ Ссылка ИЗ Документ.А_ФинРез_Баланс
    ГДЕ Организация=&Орг И Проведен И НАЧАЛОПЕРИОДА(Месяц,МЕСЯЦ)=ДАТАВРЕМЯ(2026, 1, 1))"""
qA.УстановитьПараметр("Орг", ORG); qA.УстановитьПараметр("Искл", ИсклМ)
rA = qA.Выполнить().Выбрать(); rA.Следующий()
актив = float(rA.Актив or 0)
эталон = 288_787_750.11
Δ_бал = abs(актив - эталон)
print(f"  Актив: {актив:+,.2f}, эталон: {эталон:+,.2f}, |Δ|={Δ_бал:.2f}")
бал_ok = Δ_бал <= TOL_RUB
print(f"  Регресія: {'PASS' if бал_ok else 'FAIL'}")

# 6) Ідемпотентність
print(f"\n[6] Ідемпотентність — 2-й прогон")
repost()
rows2 = read_pu()
Σ_КО_2 = sum(float(rows2.Получить(i).КО or 0) for i in range(rows2.Количество()))
idem_Δ = abs(Σ_КО - Σ_КО_2)
idem_ok = idem_Δ <= TOL_RUB
print(f"  Σ_КО перший: {Σ_КО:+,.2f}, другий: {Σ_КО_2:+,.2f}, |Δ|={idem_Δ:.2f}")
print(f"  Ідемпотентність: {'PASS' if idem_ok else 'FAIL'}")

# FINAL
final_ok = деталі_ok and ан_ok and inv_ok and дублі_ok and smoke_ok and бал_ok and idem_ok
print(f"\n{'[OK] ALL PASS' if final_ok else '[FAIL]'}")
sys.exit(0 if final_ok else 1)
