# -*- coding: utf-8 -*-
"""
Атомарное применение правок Части A (ФормаPL) в
Documents/РаспределениеПрочихЗатрат/Ext/ManagerModule.bsl — ОСНОВНОЙ ПУТЬ (Script 1).

ВАЖНО: правки ТОЛЬКО внутри процедуры РаспределитьРасходыНаФинансовыйРезультат (стр. 12-1337);
прочие функции файла (ТекстЗапросаПоступилоПрочихРасходов и др.) НЕ трогаем.

Протягивает измерение ФормаPL «спутником» по цепочке:
  ПредварительныеОстаткиРасходов -> ОстаткиРасходов (3 ветки UNION + JOIN + GROUP BY)
  -> РасходыКРаспределению -> РаспределенныеРасходы -> РезультатРаспределения (3 ветки UNION + GROUP BY).
Запись движений подхватит ФормаPL автоматически (ЗаполнитьЗначенияСвойств).

Путь погрешности округления (ПогрешностиОкругления split) — отдельный Script 2.
Каждая правка проверяется на УНИКАЛЬНОСТЬ якоря (count==1) ВНУТРИ процедуры, иначе падает.
Бэкап: _raspredelenie_ManagerModule.bak_formapl.
"""
import re
import os
import sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

SRC = r"C:\Configuration_downloads\BASERP25\Documents\РаспределениеПрочихЗатрат\Ext\ManagerModule.bsl"
BAK = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Python\test\_raspredelenie_ManagerModule.bak_formapl"

with open(SRC, "rb") as f:
    raw = f.read()
bom = b"\xef\xbb\xbf" if raw.startswith(b"\xef\xbb\xbf") else b""
if bom:
    raw = raw[3:]
text = raw.decode("utf-8")
NL = "\r\n" if "\r\n" in text else "\n"
PFX = NL + "\t\t|\t"

# --- Скоуп: процедура РаспределитьРасходыНаФинансовыйРезультат ---
i0 = text.index("Процедура РаспределитьРасходыНаФинансовыйРезультат(")
i1 = text.index("КонецПроцедуры", i0) + len("КонецПроцедуры")
head, seg, tail = text[:i0], text[i0:i1], text[i1:]
print("Скоуп процедуры: %d символов (стр. ~12-1337)" % len(seg))


def cnt(rx):
    return len(re.findall(rx, seg))


def ins_col(anchor, newcol, expect=1):
    """Вставить колонку newcol сразу ПОСЛЕ anchor (конец строки SELECT/GROUP BY перед |-продолжением)."""
    global seg
    # (?<![А-Яа-яёЁ]) — левая граница, чтобы 'Расходы.' не совпало внутри 'РаспределенныеРасходы.'
    rx = r'(?<![А-Яа-яёЁ])' + re.escape(anchor) + r'(,?)(?=[ \t]*\r?\n[ \t]*\|)'
    n = cnt(rx)
    assert n == expect, "ЯКОРЬ %r: найдено %d (ожид. %d)" % (anchor, n, expect)
    # group(1) = исходная запятая якоря: если колонка была НЕ последней (','),
    # переносим запятую ЗА новую колонку, иначе новая колонка станет последней (без запятой).
    seg = re.sub(rx, lambda m: anchor + "," + PFX + newcol + m.group(1), seg, count=1)
    print("OK  ins_col: %-52s -> %s" % (anchor[:52], newcol))


def ins_rx(name, rx_pattern, replacement, expect=1):
    global seg
    n = cnt(rx_pattern)
    assert n == expect, "ЯКОРЬ[%s]: найдено %d (ожид. %d)" % (name, n, expect)
    seg = re.sub(rx_pattern, replacement, seg, count=1)
    print("OK  rx     : %s" % name)


# ===== ОстаткиРасходов =====
ins_col("Расходы.СуммаУпрОстаток КАК СуммаУпр", "Расходы.ФормаPL КАК ФормаPL")                    # E1 ПредОстатки SELECT
ins_col("СУММА(Расходы.СуммаУпр) КАК СуммаУпр", "Расходы.ФормаPL КАК ФормаPL")                     # E2 внешний SELECT
ins_col("Расходы.СуммаУпр КАК СуммаУпр", "Расходы.ФормаPL КАК ФормаPL")                            # E3 ветка1 inner
ins_rx("E4 ветка2 КОНЕЦ КАК СуммаУпр перед ИЗ",                                                    # E4 ветка2 inner
       r'(КОНЕЦ КАК СуммаУпр)(?=[ \t]*\r?\n[ \t]*\|[ \t]*ИЗ)',
       r'\1,' + PFX + 'ТекущиеДвижения.ФормаPL КАК ФормаPL')
ins_rx("E5 ветка3 СуммаУпр перед ИЗ",                                                              # E5 ветка3 inner
       r'(ТекущиеДвижения\.СуммаУпр)(?=[ \t]*\r?\n[ \t]*\|[ \t]*ИЗ)',
       r'\1,' + PFX + 'ТекущиеДвижения.ФормаPL КАК ФормаPL')
ins_rx("E6 JOIN ПО ФормаPL",                                                                       # E6 JOIN условие
       r'(ТекущиеДвижения\.НалоговоеНазначение = Остатки\.НалоговоеНазначение\))',
       r'\1' + NL + '\t\t|\t\t\tИ (ТекущиеДвижения.ФормаPL = Остатки.ФормаPL)')
ins_col("Расходы.Организация", "Расходы.ФормаPL")                                                  # E7 GROUP BY

# ===== РасходыКРаспределению =====
ins_col("ОстаткиРасходов.НалоговоеНазначение КАК НалоговоеНазначение", "ОстаткиРасходов.ФормаPL КАК ФормаPL")  # E8

# ===== РаспределенныеРасходы =====
ins_col("РасходыКРаспределению.АналитикаРасходов КАК АналитикаРасходов", "РасходыКРаспределению.ФормаPL КАК ФормаPL")  # E9

# ===== РезультатРаспределения =====
# E10 внешний SELECT — алиас ВложенныйЗапрос есть и у ПогрешностиОкругления; берём тот, за которым СУММА(ВложенныйЗапрос.Сумма)
ins_rx("E10 РезультатРаспределения внешний SELECT ФормаPL",
       r'(ВложенныйЗапрос\.НалоговоеНазначение КАК НалоговоеНазначение,)([ \t]*\r?\n[ \t]*\|[ \t]*)(СУММА\(ВложенныйЗапрос\.Сумма\))',
       r'\1' + PFX + 'ВложенныйЗапрос.ФормаPL КАК ФормаPL,' + r'\2\3')
ins_rx("E11 GROUP BY ФормаPL",                                                                     # E11 внешний GROUP BY
       r'(ВложенныйЗапрос\.АналитикаРасходов)";',
       r'\1,' + PFX + 'ВложенныйЗапрос.ФормаPL";')
ins_col("РаспределенныеРасходы.НалоговоеНазначение КАК НалоговоеНазначение", "РаспределенныеРасходы.ФормаPL КАК ФормаPL")  # E12 ветка1
ins_rx("E13 ветка2 погрешности ФормаPL",                                                           # E13 ветка2
       r'(РасходыКРаспределению\.НалоговоеНазначение,)([ \t]*\r?\n[ \t]*\|[ \t]*)(ПогрешностиОкругления\.Сумма)',
       r'\1' + PFX + 'РасходыКРаспределению.ФормаPL КАК ФормаPL,' + r'\2\3')
ins_col("ЗНАЧЕНИЕ(Справочник.НалоговыеНазначенияАктивовИЗатрат.ПустаяСсылка) КАК НалоговоеНазначение",  # E14 ветка3 (нулевая, отбрасывается)
        "ЗНАЧЕНИЕ(Перечисление.А_ФормыPL.ПустаяСсылка) КАК ФормаPL")

# ===== Фикс нетто-логики: branch2 не должен дублировать текущий документ в предв.режиме =====
# (его обрабатывает branch3 &ДокументРаспределения). В закрытии месяца &ПредварительныйРасчет=Ложь → условие неактивно.
ins_rx("E15 branch2: исключить текущий документ в предв.режиме",
       r'(ТекущиеДвижения\.Период МЕЖДУ &НачалоПериода И &КонецПериода[ \t]*\r?\n[ \t]*\|[ \t]*И ТекущиеДвижения\.Активность)',
       r'\1' + NL + '\t\t|\t\tИ НЕ(&ПредварительныйРасчет И ТекущиеДвижения.Регистратор = &ДокументРаспределения)')

# ===== Сохранение =====
text2 = head + seg + tail
print("\nВхождений 'ФормаPL' в процедуре: %d" % seg.count("ФормаPL"))

if not os.path.exists(BAK):
    with open(BAK, "wb") as f:
        f.write(bom + text.encode("utf-8"))   # оригинал (seg ещё не вмонтирован в text)
    print("Бэкап оригинала:", BAK)
else:
    print("Бэкап уже существует:", BAK)

with open(SRC, "wb") as f:
    f.write(bom + text2.encode("utf-8"))
print("Записано:", SRC)
print("ГОТОВО (Script 1, основной путь). 14 правок применены.")
