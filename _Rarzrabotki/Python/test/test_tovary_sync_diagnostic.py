def get_erp_balances(conn_erp, start, end, with_type_filter=False):
    """Получить остатки ERP из ТоварыНаСкладах.ОстаткиИОбороты"""
    q = conn_erp.NewObject("Запрос")

    query_text = (
        "ВЫБРАТЬ "
        "  Т.Номенклатура.А_ИдКод КАК НоменклатураИдКод, "
        "  ПРЕДСТАВЛЕНИЕ(Т.Номенклатура) КАК НоменклатураНаим, "
        "  Т.Склад.А_ИдКод КАК СкладИдКод, "
        "  ПРЕДСТАВЛЕНИЕ(Т.Склад) КАК СкладНаим, "
        "  Т.ВНаличииНачальныйОстаток КАК НачОстаток, "
        "  Т.ВНаличииПриход КАК Приход, "
        "  Т.ВНаличииРасход КАК Расход, "
        "  Т.ВНаличииКонечныйОстаток КАК КонОстаток "
        "ИЗ "
        "  РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты("
        "    &НачалоПериода, &КонецПериода, , , ) КАК Т"
    )

    if with_type_filter:
        query_text += (
            " ГДЕ "
            "  Т.Номенклатура.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Товар)"
        )

    q.Текст = query_text
    q.УстановитьПараметр("НачалоПериода", pywintypes.Time(start))
    q.УстановитьПараметр("КонецПериода", pywintypes.Time(end))

    result = {}
    res = q.Выполнить()
    sel = res.Выбрать()
    while sel.Следующий():
        nom_id = str(sel.НоменклатураИдКод).strip()
        skl_id = str(sel.СкладИдКод).strip()
        key = nom_id + "|" + skl_id

        if key in result:
            r = result[key]
            r['НачОстаток'] += float(sel.НачОстаток or 0)
            r['Приход'] += float(sel.Приход or 0)
            r['Расход'] += float(sel.Расход or 0)
            r['КонОстаток'] += float(sel.КонОстаток or 0)
        else:
            result[key] = {
                'НоменклатураИдКод': nom_id,
                'СкладИдКод': skl_id,
                'НоменклатураНаим': str(sel.НоменклатураНаим),
                'СкладНаим': str(sel.СкладНаим),
                'НачОстаток': float(sel.НачОстаток or 0),
                'Приход': float(sel.Приход or 0),
                'Расход': float(sel.Расход or 0),
                'КонОстаток': float(sel.КонОстаток or 0),
            }

    return result


