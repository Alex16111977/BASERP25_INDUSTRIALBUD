def compare_and_find_discrepancies(erp_data, buh_data, label=""):
    """Сравнить ERP и BuhBud, вернуть расхождения (как обработка)"""
    all_keys = set(list(erp_data.keys()) + list(buh_data.keys()))

    discrepancies = []
    for key in sorted(all_keys):
        erp = erp_data.get(key, {'НачОстаток': 0, 'Приход': 0, 'Расход': 0, 'КонОстаток': 0})
        buh = buh_data.get(key, {'НачОстаток': 0, 'Приход': 0, 'Расход': 0, 'КонОстаток': 0})

        e_nач = erp.get('НачОстаток', 0)
        e_при = erp.get('Приход', 0)
        e_рас = erp.get('Расход', 0)
        e_кон = erp.get('КонОстаток', 0)

        b_nач = buh.get('НачОстаток', 0)
        b_при = buh.get('Приход', 0)
        b_рас = buh.get('Расход', 0)
        b_кон = buh.get('КонОстаток', 0)

        razn_kon = round(e_кон - b_кон, 3)
        razn_nach = round(e_nач - b_nач, 3)
        razn_pri = round(e_при - b_при, 3)
        razn_ras = round(e_рас - b_рас, 3)

        if razn_kon == 0 and razn_nach == 0 and razn_pri == 0 and razn_ras == 0:
            continue

        nom_name = erp.get('НоменклатураНаим', '') or buh.get('НоменклатураНаим', '') or key.split('|')[0]
        skl_name = erp.get('СкладНаим', '') or buh.get('СкладНаим', '') or key.split('|')[1]

        discrepancies.append({
            'key': key,
            'nom': nom_name,
            'skl': skl_name,
            'erp_kon': e_кон,
            'buh_kon': b_кон,
            'razn': razn_kon,
            'erp_nach': e_nач,
            'buh_nach': b_nач,
            'erp_pri': e_при,
            'buh_pri': b_при,
            'erp_ras': e_рас,
            'buh_ras': b_рас,
        })

    return discrepancies


def analyze_period(conn_erp, conn_buh, period_name, start, end):
    """Полный анализ за период"""
    print(f"\n{'='*80}")
    print(f"ПЕРИОД: {period_name}")
    print(f"{'='*80}")

    # 1. ERP без фильтра (как отчет)
    print("\n  Получаю остатки ERP (без фильтра по типу - как отчет)...")
    erp_no_filter = get_erp_balances(conn_erp, start, end, with_type_filter=False)
    print(f"    Записей: {len(erp_no_filter)}")

    # 2. ERP с фильтром (как обработка)
    print("  Получаю остатки ERP (с фильтром ТипНоменклатуры=Товар - как обработка)...")
    erp_with_filter = get_erp_balances(conn_erp, start, end, with_type_filter=True)
    print(f"    Записей: {len(erp_with_filter)}")

    # 3. BuhBud
    print("  Получаю остатки BuhBud...")
    buh_data = get_buhbud_balances(conn_buh, conn_erp, start, end)
    print(f"    Записей: {len(buh_data)}")

    # 4. Расхождения как отчет (без фильтра)
    disc_report = compare_and_find_discrepancies(erp_no_filter, buh_data, "отчет")
    print(f"\n  Расхождений по логике ОТЧЕТА: {len(disc_report)}")

    # 5. Расхождения как обработка (с фильтром)
    disc_proc = compare_and_find_discrepancies(erp_with_filter, buh_data, "обработка")
    print(f"  Расхождений по логике ОБРАБОТКИ: {len(disc_proc)}")

    # 6. Найти разницу
    report_keys = set(d['key'] for d in disc_report)
    proc_keys = set(d['key'] for d in disc_proc)

    only_in_report = report_keys - proc_keys
    only_in_proc = proc_keys - report_keys
    different_values = set()

    # Check for same key but different values
    report_dict = {d['key']: d for d in disc_report}
    proc_dict = {d['key']: d for d in disc_proc}

    for key in report_keys & proc_keys:
        r = report_dict[key]
        p = proc_dict[key]
        if (round(r['erp_kon'] - p['erp_kon'], 3) != 0 or
            round(r['buh_kon'] - p['buh_kon'], 3) != 0):
            different_values.add(key)

    if only_in_report:
        print(f"\n  >>> ОТЧЕТ видит, а ОБРАБОТКА нет ({len(only_in_report)} позиций):")
        for key in sorted(only_in_report):
            d = report_dict[key]
            print(f"    {d['nom'][:60]:60s} | {d['skl'][:25]:25s} | ЕРП={d['erp_kon']:>10.2f} Бух={d['buh_kon']:>10.2f} Разн={d['razn']:>10.2f}")

    if only_in_proc:
        print(f"\n  >>> ОБРАБОТКА видит, а ОТЧЕТ нет ({len(only_in_proc)} позиций):")
        for key in sorted(only_in_proc):
            d = proc_dict[key]
            print(f"    {d['nom'][:60]:60s} | {d['skl'][:25]:25s} | ЕРП={d['erp_kon']:>10.2f} Бух={d['buh_kon']:>10.2f} Разн={d['razn']:>10.2f}")

    if different_values:
        print(f"\n  >>> Расхождения с РАЗНЫМИ значениями ({len(different_values)} позиций):")
        for key in sorted(different_values):
            r = report_dict[key]
            p = proc_dict[key]
            print(f"    {r['nom'][:50]:50s} | Отчет: ЕРП={r['erp_kon']:.2f} Бух={r['buh_kon']:.2f} | Обработка: ЕРП={p['erp_kon']:.2f} Бух={p['buh_kon']:.2f}")

    if not only_in_report and not only_in_proc and not different_values:
        print("\n  >>> Отчет и обработка показывают ОДИНАКОВЫЕ расхождения!")

    # Показать все расхождения обработки для удобства
    print(f"\n  --- ВСЕ расхождения (обработка), всего {len(disc_proc)}: ---")
    for d in sorted(disc_proc, key=lambda x: abs(x['razn']), reverse=True)[:30]:
        print(f"    {d['nom'][:55]:55s} | {d['skl'][:25]:25s} | ЕРП={d['erp_kon']:>10.2f} Бух={d['buh_kon']:>10.2f} Разн={d['razn']:>10.2f}")
    if len(disc_proc) > 30:
        print(f"    ... и еще {len(disc_proc)-30} позиций")

    return disc_report, disc_proc


