# -*- coding: utf-8 -*-
"""Дозаливка А_ПараметрыДоговоровФинотчета — РАЗВЕДКА ч.2, ТОЛЬКО ЧТЕНИЕ.

1) глобальный поиск договоров (без фильтра направления): ООН 28/12, Навіс, 19/01, УВБК,
   ПОДІЛЬСЬКИЙ ЦЕМЕНТ, IRC (РЕСК'Ю), ВООЗ GLOBAL, подразделения IRC 15м/30м и ВООЗ Мала;
2) обороты 361 по контрагентам-заказчикам (какие договоры реально в движениях);
3) полный дамп регистра А_ПараметрыДоговоровФинотчета.
"""
import sys

import win32com.client

sys.stdout.reconfigure(encoding="utf-8")


def схлоп(т):
    return " ".join(str(т).split()) if т is not None else ""


buh = win32com.client.Dispatch("V83.COMConnector").Connect(
    'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')

# ---------- 1. Глобальный поиск договоров ----------
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
  Д.Ссылка КАК Ссыл,
  Д.Наименование КАК Имя,
  Д.Номер КАК Номер,
  Д.Дата КАК ДатаДог,
  Д.Комментарий КАК Коммент,
  ЕСТЬNULL(Д.Подразделение.Наименование, "") КАК Подр,
  ЕСТЬNULL(Д.Владелец.Наименование, "") КАК Влад,
  ЕСТЬNULL(Д.Направление.Наименование, "") КАК Напр
ИЗ Справочник.ДоговорыКонтрагентов КАК Д
ГДЕ НЕ Д.ПометкаУдаления И НЕ Д.ЭтоГруппа
  И (Д.Наименование ПОДОБНО "%28/12%"
     ИЛИ Д.Наименование ПОДОБНО "%Навіс%" ИЛИ Д.Наименование ПОДОБНО "%Навис%"
     ИЛИ Д.Наименование ПОДОБНО "%19/01%"
     ИЛИ Д.Владелец.Наименование ПОДОБНО "%УВБК%"
     ИЛИ Д.Владелец.Наименование ПОДОБНО "%ПОДІЛЬСЬК%"
     ИЛИ Д.Владелец.Наименование ПОДОБНО "%РЕСК%Ю%"
     ИЛИ Д.Владелец.Наименование ПОДОБНО "%ВООЗ GLOBAL%"
     ИЛИ Д.Подразделение.Наименование ПОДОБНО "%IRC 2026 15%"
     ИЛИ Д.Подразделение.Наименование ПОДОБНО "%IRC 2026 30%"
     ИЛИ Д.Подразделение.Наименование = "МД Вооз ЕМS Мала 2026")
"""
т = q.Execute().Выгрузить()
print(f"=== Глобальный поиск: {т.Количество()} договоров ===")
найденные = []
for i in range(т.Количество()):
    s = т.Получить(i)
    д = {"Ссылка": s.Ссыл, "Имя": схлоп(str(s.Имя)), "Номер": схлоп(str(s.Номер)),
         "Дата": str(s.ДатаДог)[:10], "Коммент": схлоп(str(s.Коммент)),
         "Подр": str(s.Подр), "Влад": схлоп(str(s.Влад)), "Напр": схлоп(str(s.Напр)),
         "УИД": str(buh.String(s.Ссыл.УникальныйИдентификатор()))}
    найденные.append(д)
    # печатаем только интересное (не «РАХУНКИ_» поставщиков), но заказчиков — всех
    интерес = (
        "28/12" in д["Имя"] or "Навіс" in д["Имя"] or "Навис" in д["Имя"] or "19/01" in д["Имя"]
        or "УВБК" in д["Влад"] or "ПОДІЛЬСЬК" in д["Влад"].upper() or "РЕСК" in д["Влад"]
        or "ВООЗ GLOBAL" in д["Влад"] or "ІНДАСТР" in д["Влад"].upper() or "ИНДАСТР" in д["Влад"].upper()
    )
    if интерес:
        print(f"[{д['Подр']!r}] {д['Имя']!r}")
        print(f"   Номер={д['Номер']!r} Дата={д['Дата']} Влад={д['Влад']!r} Напр={д['Напр']!r}")
        print(f"   Коммент={д['Коммент'][:120]!r}")
        print(f"   УИД={д['УИД']}")

# ---------- 2. Обороты 361 по контрагентам-заказчикам ----------
print("\n=== Обороты 361 по контрагентам-заказчикам (Субконто1) ===")
q = buh.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
  К.Ссылка КАК Ссыл,
  К.Наименование КАК Имя
ИЗ Справочник.Контрагенты КАК К
ГДЕ НЕ К.ПометкаУдаления
  И (К.Наименование ПОДОБНО "%УВБК%"
     ИЛИ К.Наименование ПОДОБНО "%ПОДІЛЬСЬК%"
     ИЛИ К.Наименование ПОДОБНО "%РЕСК%Ю%"
     ИЛИ К.Наименование ПОДОБНО "%ВООЗ GLOBAL%")
"""
т = q.Execute().Выгрузить()
конт = []
for i in range(т.Количество()):
    s = т.Получить(i)
    конт.append({"Ссылка": s.Ссыл, "Имя": схлоп(str(s.Имя))})
    print(f"контрагент: {схлоп(str(s.Имя))!r}")

if конт:
    список = buh.NewObject("СписокЗначений")
    for к in конт:
        список.Добавить(к["Ссылка"])
    q = buh.NewObject("Запрос")
    q.Текст = """
ВЫБРАТЬ
  Об.Субконто1 КАК Конт,
  Об.Субконто2 КАК Дог,
  Об.Период КАК Пер,
  Об.СуммаОборотДт КАК ОборотДт,
  Об.СуммаОборотКт КАК ОборотКт
ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(, , Месяц, Счет = &Сч361, , Субконто1 В (&Конты), , ) КАК Об
УПОРЯДОЧИТЬ ПО Дог, Пер"""
    q.УстановитьПараметр("Сч361", buh.ПланыСчетов.Хозрасчетный.НайтиПоКоду("361"))
    q.УстановитьПараметр("Конты", список)
    try:
        т = q.Execute().Выгрузить()
        агрег = {}
        for i in range(т.Количество()):
            s = т.Получить(i)
            имя_к = схлоп(str(s.Конт.Наименование))
            имя_д = схлоп(str(s.Дог.Наименование))
            уид_д = str(buh.String(s.Дог.УникальныйИдентификатор()))
            подр_д = ""
            try:
                подр_д = схлоп(str(s.Дог.Подразделение.Наименование))
            except Exception:
                pass
            ключ = (имя_к, имя_д, уид_д, подр_д)
            з = агрег.setdefault(ключ, {"Дт": 0.0, "Кт": 0.0, "Месяцы": []})
            дт = float(s.ОборотДт or 0)
            кт = float(s.ОборотКт or 0)
            з["Дт"] += дт
            з["Кт"] += кт
            з["Месяцы"].append(f"{str(s.Пер)[:7]}(Дт={дт:,.0f}/Кт={кт:,.0f})")
        for (имя_к, имя_д, уид_д, подр_д), з in агрег.items():
            print(f"\n  Конт={имя_к!r}")
            print(f"  Дог={имя_д!r} [{подр_д!r}] УИД={уид_д}")
            print(f"  361: Дт={з['Дт']:,.2f} Кт={з['Кт']:,.2f}")
            print(f"  мес: {'; '.join(з['Месяцы'])}")
    except Exception as e:
        if hasattr(e, "excepinfo") and e.excepinfo:
            print(f"FAIL 361: {e.excepinfo[2]}")
        else:
            print(f"FAIL 361: {e}")

