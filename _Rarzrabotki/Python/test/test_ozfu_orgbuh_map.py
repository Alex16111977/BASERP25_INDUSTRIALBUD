# -*- coding: utf-8 -*-
"""Rule #-1: проверка логики карты (ФЛ,Подр)->доминантный ОргБух на РОДИТЕЛЕ А_ОтражениеЗПпоКазне
(read-only, без пересоздания дочернего ОЗФУ — LESSONS §19).

Карта строится из Ф1-строк «Зарплата управл» НачисленнаяЗарплатаИВзносыПоФизлицам
(не удержание, ВзносыВсего=0, ОргБух заполнен). Дочерний ОЗФУ — копия 1-в-1, значит карта та же.
"""
import sys
import datetime
import win32com.client

if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect(CONN)
XML = erp.XMLСтрока

q = erp.NewObject("Запрос")
q.Text = ("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка КАК Ссылка ИЗ Документ.А_ОтражениеЗПпоКазне "
          "ГДЕ Номер = &Н И Дата >= &Д1 И Дата < &Д2")
q.SetParameter("Н", "000000001")
q.SetParameter("Д1", datetime.datetime(2025, 12, 1))
q.SetParameter("Д2", datetime.datetime(2026, 1, 1))
в = q.Execute().Выбрать()
assert в.Следующий(), "Родитель №1 (дек.2025) не найден"
obj = в.Ссылка.ПолучитьОбъект()

# Σ Сумма per (ФЛ, Подр, ОргБух) из «Зарплата управл» Ф1
agg = {}            # (флн, подрн, оргн) -> Σ Сумма
тч = obj.НачисленнаяЗарплатаИВзносыПоФизлицам
строк_ф1 = 0
строк_зпупр = 0
for i in range(тч.Количество()):
    с = тч.Получить(i)
    if XML(с.ФормаPL) != "Форма1":
        continue
    строк_ф1 += 1
    способ = с.СпособОтраженияЗарплатыВБухучете
    это_удерж = bool(способ.А_ЭтоУдержание) if erp.ЗначениеЗаполнено(способ) else False
    if это_удерж or float(с.ВзносыВсего) != 0:
        continue
    if not erp.ЗначениеЗаполнено(с.ОрганизацияБухгалтерия):
        continue
    строк_зпупр += 1
    флн = с.ФизическоеЛицо.Наименование
    подрн = с.ПодразделениеПредприятия.Наименование if erp.ЗначениеЗаполнено(с.ПодразделениеПредприятия) else "<пусто>"
    оргн = с.ОрганизацияБухгалтерия.Наименование
    agg[(флн, подрн, оргн)] = agg.get((флн, подрн, оргн), 0.0) + float(с.Сумма)

# доминантный ОргБух per (ФЛ, Подр)
по_подр = {}        # (флн,подрн) -> (оргн, Σ)
мульти = {}         # (флн,подрн) -> set(оргн)
for (флн, подрн, оргн), s in agg.items():
    k = (флн, подрн)
    мульти.setdefault(k, set()).add(оргн)
    if k not in по_подр or s > по_подр[k][1]:
        по_подр[k] = (оргн, s)

мульти_кейсы = {k: v for k, v in мульти.items() if len(v) > 1}

print(f"Ф1-строк всего: {строк_ф1}; «Зарплата управл» с ОргБух: {строк_зпупр}")
print(f"Уникальных (ФЛ,Подр) с ОргБух: {len(по_подр)}; из них мульти-орг: {len(мульти_кейсы)}")
print("\n--- Шишкіна (эталон) ---")
for (флн, подрн), (оргн, s) in sorted(по_подр.items()):
    if "Шишк" in флн.lower():
        print(f"  {флн} / {подрн}: доминантный ОргБух = {оргн} (Σ={round(s,2)})")
print("\n--- Примеры мульти-орг (доминантный выбирается по макс Σ) ---")
shown = 0
for k, orgs in мульти_кейсы.items():
    детали = sorted([(оргн, round(s, 2)) for (флн, подрн, оргн), s in agg.items() if (флн, подрн) == k], key=lambda x: -x[1])
    print(f"  {k[0]} / {k[1]}: {детали} -> доминантный {по_подр[k][0]}")
    shown += 1
    if shown >= 6:
        break

assert строк_зпупр > 0, "FAIL: нет «Зарплата управл» строк с ОргБух — карта пустая"
print("\nOK: карта (ФЛ,Подр)->доминантный ОргБух строится; «Зарплата управл» несёт ОргБух")
