# -*- coding: utf-8 -*-
"""
Запуск главной EPF через COM:
  1. Загружаем внешнюю обработку из _Rarzrabotki/build/
  2. Ставим период, захватывающий оба целевых документа
  3. Ограничиваем анализ одним документом ІБ00-008058 через реквизит Подразделение = Неопределено
     (пока прогоняем на полном периоде — чтобы захватить оба)
  4. Вызываем АнализДокументов
  5. Вызываем СоздатьДокументы
  6. Проверяем результат: дисбаланс по документу должен стать 0.

  Для ІБ00-008058 ожидаем 3 новых ВзаимозачетЗадолженности
  (Строительство ← ЦО: 13107.50, Спецтехника ← ЦО: 1123.00, Логистика ← ЦО: 375.00)
"""
import sys
import win32com.client
import datetime

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

v8 = win32com.client.Dispatch("V83.COMConnector")
CONN = 'Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
print("Connecting to BaseERP...")
conn = v8.Connect(CONN)
print("Connected\n")

EPF_PATH = r"C:\tmp\disbalance_test\disbalance.epf"

print(f"Загрузка обработки: {EPF_PATH}")
# ВнешниеОбработки.Создать(Путь) — возвращает объект без регистрации в сессии
proc = conn.ВнешниеОбработки.Создать(EPF_PATH)
print("Объект обработки создан\n")

# Период — декабрь 2025 и февраль 2026
proc.НачалоПериода = datetime.datetime(2025, 12, 1)
proc.ОкончаниеПериода = datetime.datetime(2026, 2, 28)
proc.ПоказыватьВсе = False

print("=" * 70)
print("Вызов: АнализДокументов()")
print("=" * 70)
proc.АнализДокументов()

print(f"\nРезультат анализа: {proc.ДокументыДисбаланса.Количество()} строк")
for i in range(proc.ДокументыДисбаланса.Количество()):
    row = proc.ДокументыДисбаланса.Получить(i)
    print(f"  [{i+1}] Док={conn.String(row.Документ)[:60]}")
    print(f"      Дт={conn.String(row.ПодразделениеПриход):<25s} Кт={conn.String(row.ПодразделениеРасход):<25s} Сумма={row.СуммаДокумента:>12.2f}  Обработан={row.Обработан}")

print("\n" + "=" * 70)
print("Вызов: СоздатьДокументы()")
print("=" * 70)
proc.СоздатьДокументы()

print("\nПовторный анализ для проверки 'Обработан':")
proc.АнализДокументов()
print(f"Строк: {proc.ДокументыДисбаланса.Количество()}")
for i in range(proc.ДокументыДисбаланса.Количество()):
    row = proc.ДокументыДисбаланса.Получить(i)
    print(f"  [{i+1}] Дт={conn.String(row.ПодразделениеПриход):<25s} Кт={conn.String(row.ПодразделениеРасход):<25s}"
          f" Сумма={row.СуммаДокумента:>12.2f} Вз={conn.String(row.ДокВзаимозачетЗадолженности)[:50]} Обработан={row.Обработан}")

# Верификация: проверить, что по ІБ00-008058 дисбаланс по подразделениям = 0
print("\n" + "=" * 70)
print("Верификация итогового дисбаланса по ІБ00-008058")
print("=" * 70)
uid = conn.NewObject("УникальныйИдентификатор", "20b3ae2a-f767-11f0-8105-00155dce3d04")
doc_ref = conn.Документы.ПриобретениеТоваровУслуг.ПолучитьСсылку(uid)

# Собрать все регистраторы: сам документ + все ВзаимозачетЗадолженности с А_ДокументОснованиеДляБаланса=doc_ref
q_vz = conn.NewObject("Запрос")
q_vz.Text = """
ВЫБРАТЬ Вз.Ссылка КАК Ссылка, Вз.Номер КАК Номер, Вз.СуммаРегл КАК Сумма, Вз.Проведен КАК Проведен
ИЗ Документ.ВзаимозачетЗадолженности КАК Вз
ГДЕ Вз.А_ДокументОснованиеДляБаланса = &Осн И НЕ Вз.ПометкаУдаления
"""
q_vz.УстановитьПараметр("Осн", doc_ref)
sel = q_vz.Выполнить().Выбрать()
vz_refs = [doc_ref]
print("\nСозданные ВзаимозачетЗадолженности для ІБ00-008058:")
while sel.Следующий():
    print(f"  - {sel.Номер} | Сумма={sel.Сумма:.2f} Проведен={sel.Проведен}")
    vz_refs.append(sel.Ссылка)

# Агрегат по подразделениям от ВСЕХ этих регистраторов
q_sum = conn.NewObject("Запрос")
q_sum.Text = """
ВЫБРАТЬ
    Об.Подразделение КАК Подразделение,
    СУММА(Об.СуммаПриход - Об.СуммаРасход) КАК Контроль
ИЗ РегистрНакопления.ПрочиеАктивыПассивы.Обороты(, , Регистратор, ) КАК Об
ГДЕ Об.Регистратор В (&Регистраторы)
    И НЕ Об.Статья В (
        ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВложенияСобственныхСредств),
        ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиАктивовПассивов.ВыводСобственныхСредств))
СГРУППИРОВАТЬ ПО Об.Подразделение
"""
q_sum.УстановитьПараметр("Регистраторы", vz_refs)
tbl = q_sum.Выполнить().Выгрузить()

print(f"\nИтоговый Контроль по подразделениям (документ + все взаимозачёты):")
all_ok = True
total = 0.0
for i in range(tbl.Количество()):
    row = tbl.Получить(i)
    k = float(row.Контроль)
    total += k
    marker = "OK " if abs(k) < 0.01 else "!!! "
    if abs(k) >= 0.01:
        all_ok = False
    print(f"  {marker} {conn.String(row.Подразделение):<40s} Контроль={k:>15.2f}")

print(f"\nИтого Контроль: {total:.2f}")
print(f"РЕЗУЛЬТАТ: {'СОШЁЛСЯ — ВСЁ OK' if all_ok else 'ЕСТЬ НЕЗАКРЫТЫЙ ДИСБАЛАНС'}")
