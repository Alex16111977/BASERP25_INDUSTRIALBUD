НП = datetime.datetime(2020, 1, 1); КП = datetime.datetime(2030, 12, 31, 23, 59, 59)

def прогнать(имя_сс):
    сс = erp.Справочники.А_СтруктураСебестоимости.НайтиПоНаименованию(имя_сс)
    assert not сс.Пустая(), f"СС не найдена: {имя_сс}"
    q = erp.NewObject("Запрос")
    q.УстановитьПараметр("СС", сс.Ссылка)
    q.УстановитьПараметр("НачП", НП); q.УстановитьПараметр("КонП", КП)
    q.Текст = ТЕКСТ
    try:
        тз = q.Выполнить().Выгрузить()
    except Exception as e:
        info = getattr(e, "excepinfo", None)
        open(ERR, "w", encoding="utf-8").write(str(info[2]) if info and len(info) > 2 else str(e))
        print(f"QUERY ERROR -> {ERR}"); raise
    cols = [c.Имя for c in тз.Колонки]
    assert "Работа" in cols, "нет колонки Работа"
    план_ч = факт_ч = вик_ч = мат_фг = 0.0
    с_работой = труд_план_строк = 0
    for i in range(тз.Количество()):
        r = тз.Получить(i)
        раб_пусто = пусто(r.Работа)
        if not раб_пусто:
            с_работой += 1
            assert r.Блок == "1. Праця", f"Работа заполнена вне Труда: {r.Блок}"
            assert not пусто(r.Аналитика) and уид(r.Работа) == уид(r.Аналитика), \
                "Работа != Аналитика у строки труда"
        if r.Блок == "1. Праця":
            план_ч += f(r.ПланЧасы); факт_ч += f(r.ФактЧасы); вик_ч += f(r.ВиконанняЧасы)
            if f(r.ПланЧасы) != 0 or f(r.ВиконанняЧасы) != 0:
                труд_план_строк += 1
                assert not раб_пусто, "у труд-план/EV строки Работа пустая"
        if r.Блок == "2. Матеріали":
            мат_фг += f(r.ФактГрн)
            assert раб_пусто, "у материалов Работа должна быть пустой"
    print(f"[{имя_сс[:20]}...] строк={тз.Количество()} с_работой={с_работой} "
          f"труд_план/EV={труд_план_строк}")
    print(f"  Труд: ПланЧасы={план_ч:.2f} ФактЧасы={факт_ч:.2f} ВиконанняЧасы={вик_ч:.2f}; "
          f"Материалы ФактГрн={мат_фг:.2f}")
    return план_ч, факт_ч, вик_ч, мат_фг, с_работой

пч, фч, _, мфг, сраб = прогнать("МД МХП ОРІЛЬ / СТІЛ МД МХП ОРІЛЬ")
assert abs(пч - 2795) < 0.01, f"ОРІЛЬ ПланЧасы {пч} != 2795"
