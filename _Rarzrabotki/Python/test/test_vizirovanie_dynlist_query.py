# -*- coding: utf-8 -*-
"""Rule #-1: текст запроса ДИНАМИЧЕСКОГО СПИСКА рабочего места визирования.

Запрос 1:1 переносится в ТекстЗапроса реквизита Список (ДинамическийСписок,
ОсновнаяТаблица = Документ.ЗаказПоставщику) формы А_ВизированиеЗаказовПоставщику.
Без СГРУППИРОВАТЬ ПО (запрещено в динсписке), очередь — подзапросами по ТЧ.
Параметры списка: РежимОчереди, ТекущийПользователь, Состояние_НаВизировании,
ПоказыватьПомеченные.
"""
import sys
import win32com.client

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

QUERY = """ВЫБРАТЬ
	Т.Ссылка КАК Ссылка,
	Т.Номер КАК Номер,
	Т.Дата КАК Дата,
	Т.ПометкаУдаления КАК ПометкаУдаления,
	Т.Организация КАК Организация,
	Т.Подразделение КАК Подразделение,
	Т.Партнер КАК Партнер,
	Т.Контрагент КАК Контрагент,
	Т.СуммаДокумента КАК СуммаДокумента,
	Т.Статус КАК Статус,
	Т.Автор КАК Автор,
	Т.Менеджер КАК Менеджер,
	Т.НаправлениеДеятельности КАК НаправлениеДеятельности,
	Т.А_Виза_Состояние КАК ВизаСостояние,
	Т.А_Виза_ТекущаяРоль КАК ВизаТекущаяРоль,
	Т.А_Виза_ТекущиеВизирующие КАК ВизаТекущиеВизирующие,
	Т.А_Виза_Дата КАК ВизаДата,
	ВЫРАЗИТЬ(Т.Комментарий КАК СТРОКА(200)) КАК Комментарий
ИЗ
	Документ.ЗаказПоставщику КАК Т
ГДЕ
	Т.А_Виза_Состояние <> ЗНАЧЕНИЕ(Перечисление.А_Визы_Состояния.ПустаяСсылка)
	И (&РежимОчереди = 0
			И (&ПоказыватьПомеченные ИЛИ НЕ Т.ПометкаУдаления)
		ИЛИ &РежимОчереди = 1
			И Т.Ссылка В (ВЫБРАТЬ Т2.Ссылка ИЗ Документ.ЗаказПоставщику.А_ТекущиеВизирующие КАК Т2
							ГДЕ Т2.Пользователь = &ТекущийПользователь)
			И Т.А_Виза_Состояние = &Состояние_НаВизировании
			И НЕ Т.ПометкаУдаления
		ИЛИ &РежимОчереди = 2
			И Т.Ссылка В (ВЫБРАТЬ Т3.Ссылка ИЗ Документ.ЗаказПоставщику.А_ПредварительныеВизы КАК Т3
							ГДЕ Т3.Пользователь = &ТекущийПользователь И НЕ Т3.Утверждено)
			И Т.А_Виза_Состояние = &Состояние_НаВизировании
			И НЕ Т.ПометкаУдаления)"""


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

    user = erp.Пользователи.ТекущийПользователь()
    state_na_viz = erp.Перечисления.А_Визы_Состояния.НаВизировании

    ok = 0
    for mode in (0, 1, 2):
        q = erp.NewObject("Запрос")
        q.Text = QUERY
        q.SetParameter("РежимОчереди", mode)
        q.SetParameter("ТекущийПользователь", user)
        q.SetParameter("Состояние_НаВизировании", state_na_viz)
        q.SetParameter("ПоказыватьПомеченные", False)
        try:
            r = q.Execute().Выгрузить()
            print(f"OK режим={mode}, строк={r.Количество()}")
            ok += 1
        except Exception as e:
            if hasattr(e, 'excepinfo') and e.excepinfo:
                print(f"FAIL режим={mode}: {e.excepinfo[2]}")
            else:
                print(f"FAIL режим={mode}: {e}")

    print(f"ИТОГ: {ok}/3")
    return 0 if ok == 3 else 1


if __name__ == "__main__":
    sys.exit(main())
