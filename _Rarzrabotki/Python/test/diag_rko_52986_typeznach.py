"""Прямая проверка: что возвращает ТИПЗНАЧЕНИЯ для Ведомости РКО N0000052986."""
import sys, win32com.client
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"')
S = erp.String

q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Д.Ссылка КАК Сс,
    Д.Ведомость КАК Вед,
    ТИПЗНАЧЕНИЯ(Д.Ведомость) КАК ТипВед,
    ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу) КАК ТипВКассу,
    ВЫБОР КОГДА ТИПЗНАЧЕНИЯ(Д.Ведомость) = ТИП(Документ.ВедомостьНаВыплатуЗарплатыВКассу) ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК ТипСовпадает,
    ВЫРАЗИТЬ(Д.Ведомость КАК Документ.ВедомостьНаВыплатуЗарплатыВКассу) КАК ВыразитьКВКассу,
    ВЫБОР КОГДА ВЫРАЗИТЬ(Д.Ведомость КАК Документ.ВедомостьНаВыплатуЗарплатыВКассу) ЕСТЬ NULL ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК ВыразитьЕстьNULL
ИЗ Документ.РасходныйКассовыйОрдер КАК Д
ГДЕ Д.Номер = &Н
"""
q.SetParameter("Н", "N0000052986")
r = q.Execute().Выгрузить()
for row in r:
    print(f"Сс            = {S(row.Сс)}")
    print(f"Вед           = {S(row.Вед)} (заполнена={erp.ЗначениеЗаполнено(row.Вед)})")
    print(f"ТипВед        = {row.ТипВед}")
    print(f"ТипВКассу     = {row.ТипВКассу}")
    print(f"ТипСовпадает  = {row.ТипСовпадает}")
    print(f"ВыразитьКВКассу = {S(row.ВыразитьКВКассу)} (Заполнено={erp.ЗначениеЗаполнено(row.ВыразитьКВКассу)})")
    print(f"ВыразитьЕстьNULL = {row.ВыразитьЕстьNULL}")
