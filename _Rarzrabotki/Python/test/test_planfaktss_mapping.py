# -*- coding: utf-8 -*-
"""Карта «имя загальної назви -> Етап» строится и покрывает факт."""
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

CONN = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'

ТЕКСТ = """
ВЫБРАТЬ
	ВЫБОР
		КОГДА К.Номенклатура = ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
			ТОГДА К.ОбщееНазвание.Наименование
		ИНАЧЕ К.Номенклатура.ОбщееНазваниеНоменклатуры.Наименование
	КОНЕЦ КАК ОбщееНазвание,
	К.Этап КАК Этап,
	ВЫБОР
		КОГДА К.Этап.Наименование ПОДОБНО "%Монтаж%"
			ТОГДА "Монтаж"
		ИНАЧЕ "Виробництво"
	КОНЕЦ КАК Категория
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	К.Ссылка.Подразделение = &Зонтик
	И НЕ К.Ссылка.ЭтоГруппа
	И К.Ссылка.Активная
	И НЕ К.Ссылка.ПометкаУдаления
	И К.Этап <> ЗНАЧЕНИЕ(Справочник.ЭтапыРабот.ПустаяСсылка)
	И ВЫБОР
		КОГДА К.Номенклатура = ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
			ТОГДА К.ОбщееНазвание
		ИНАЧЕ К.Номенклатура.ОбщееНазваниеНоменклатуры
	КОНЕЦ <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
"""


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    b = v8.Connect(CONN)

    z = b.NewObject("Запрос")
    z.Текст = """ВЫБРАТЬ РАЗЛИЧНЫЕ СС.Подразделение КАК Подр
    ИЗ Справочник.СтруктураСебестоимости КАК СС
    ГДЕ НЕ СС.ЭтоГруппа И СС.Активная И НЕ СС.ПометкаУдаления
    	И СС.Подразделение <> ЗНАЧЕНИЕ(Справочник.Подразделения.ПустаяСсылка)"""
    зонтики = z.Выполнить().Выгрузить()

    всего = 0
    for i in range(зонтики.Количество()):
        подр = зонтики[i].Подр
        z = b.NewObject("Запрос")
        z.Текст = ТЕКСТ
        z.УстановитьПараметр("Зонтик", подр)
        t = z.Выполнить().Выгрузить()
        карта = {}
        for j in range(t.Количество()):
            карта[t[j].ОбщееНазвание.strip().upper()] = t[j].Категория
        всего += len(карта)
        print(f"  {подр.Наименование!r:38} записей карты = {len(карта)}")
        if подр.Наименование == "МД IRS 2026":
            assert len(карта) > 0, "У IRS карта пуста — разнос факта по Етапу не сработает"

    assert всего > 0, "Карта пуста на всех зонтиках"
    print("MAPPING PASSED")


if __name__ == "__main__":
    main()
