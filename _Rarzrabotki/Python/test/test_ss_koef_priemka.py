def raw(rows):
    a = b.NewObject('Массив')
    for i, (nom, unit, qty, summ) in enumerate(rows):
        s = b.NewObject('Структура')
        for key, val in (('Ряд', i + 2), ('Тип', 'Матеріал'), ('Этап', 'Каркас'),
                         ('ОбщееНазвание', '__ТЕСТ ОН коэффициент'), ('Наименование', nom), ('Единица', unit),
                         ('Количество', qty), ('Сумма', summ)):
            s.Вставить(key, val)
        a.Добавить(s)
    return a


