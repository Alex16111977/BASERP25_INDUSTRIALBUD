def can_be_registrator(reg_full, doc_name):
    """Проверяет, входит ли документ в состав регистраторов через ВЫРАЗИТЬ (компиляция)."""
    q = erp.NewObject("Запрос")
    q.Text = (f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ {reg_full} КАК Р "
              f"ГДЕ ВЫРАЗИТЬ(Р.Регистратор КАК Документ.{doc_name}) <> НЕОПРЕДЕЛЕНО")
    try:
        r = q.Execute().Выгрузить()
        return True, r.Получить(0).К
    except Exception as e:
        msg = e.excepinfo[2] if (hasattr(e,'excepinfo') and e.excepinfo) else str(e)
        if "Несовместимые типы" in msg:
            return False, "не регистратор"
        return None, msg

