# -*- coding: utf-8 -*-
"""Шаг 0 спеки: проверка механики переноса БЕЗ следов в базе.

Проверки:
  A. УстановитьСсылкуНового создаёт архивный элемент с заданным UUID.
  B. Явно присвоенный Код не префиксуется.
  C. Запись номенклатуры БЕЗ ОбменДанными.Загрузка регистрацию на узле ЕРП
     НЕ создаёт (замерено 2026-07-26: 0 -> 0 на 5/5 образцов).
  D. Запись номенклатуры С ОбменДанными.Загрузка = Истина регистрацию СОЗДАЁТ
     (0 -> 1). В этой БСП флаг регистрацию не подавляет — см.
     ОбменДаннымиСобытия.ЗарегистрироватьИзменениеОбъекта, комментарий у входа.
     Поэтому этап 2 миграции пишет номенклатуру без этого флага.
  E. Сколько из отбираемых номенклатур имеют А_ИдКод <> UUID (объём вложенной
     перезаписи подпиской А_ДоработкаСправочникиПриЗаписи).

Все записи выполняются внутри транзакций, которые откатываются.

Запуск:
  & "C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\venv\\Scripts\\python.exe" ^
    "C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\test\\test_onn_arhiv_dry_run.py"
"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from onn_arhiv_common import (подключиться, выполнить, строки, uuid_ссылки,
                              ссылка_архива, текст_ошибки, РЕКВИЗИТЫ)

провалов = 0


def проверить(условие, описание):
    global провалов
    print(("PASS: " if условие else "FAIL: ") + описание)
    if not условие:
        провалов += 1


conn = подключиться()

# --- образцы ---------------------------------------------------------------
образец_онн = строки(выполнить(conn, """
ВЫБРАТЬ ПЕРВЫЕ 1
    Т.Ссылка КАК Ссылка, Т.Код КАК Код, Т.Наименование КАК Наименование,
    Т.ОсновнаяНоменклатура КАК ОсновнаяНоменклатура, Т.Единица КАК Единица,
    Т.ЕдиницаРекомендуемая КАК ЕдиницаРекомендуемая,
    Т.НазваниеДляОбъединения КАК НазваниеДляОбъединения,
    Т.НеПроверятьВЗакупкахпоСС КАК НеПроверятьВЗакупкахпоСС
ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК Т
ГДЕ НЕ Т.ЭтоГруппа
УПОРЯДОЧИТЬ ПО Т.Код
"""))[0]
uid_онн = uuid_ссылки(conn, образец_онн.Ссылка)
print(f"образец справочника: код={образец_онн.Код} uuid={uid_онн}")

образец_ном = строки(выполнить(conn, """
ВЫБРАТЬ ПЕРВЫЕ 1 Н.Ссылка КАК Ссылка
ИЗ Справочник.Номенклатура КАК Н
ГДЕ Н.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
УПОРЯДОЧИТЬ ПО Н.Код
"""))[0]
print(f"образец номенклатуры: {conn.String(образец_ном.Ссылка)}")

# --- A и B: создание архивного элемента с заданным UUID --------------------
conn.BeginTransaction()
try:
    менеджер = conn.Справочники.ОбщиеНазванияНоменклатурыСтарая
    объект = менеджер.СоздатьЭлемент()
    объект.УстановитьСсылкуНового(ссылка_архива(conn, uid_онн))
    объект.Код = образец_онн.Код
    объект.Наименование = образец_онн.Наименование
    for имя in РЕКВИЗИТЫ:
        setattr(объект, имя, getattr(образец_онн, имя))
    объект.ОбменДанными.Загрузка = True
    объект.Записать()

    записанный = ссылка_архива(conn, uid_онн).ПолучитьОбъект()
    проверить(записанный is not None, "A. объект создан по заданной ссылке")
    проверить(uuid_ссылки(conn, записанный.Ссылка) == uid_онн,
              "A. UUID архивного элемента совпал с оригиналом")
    проверить(str(записанный.Код) == str(образец_онн.Код),
              f"B. Код не префиксован (ожидали {образец_онн.Код}, "
              f"получили {записанный.Код})")
except Exception as ошибка:
    проверить(False, f"A/B. исключение: {текст_ошибки(ошибка)}")
finally:
    conn.RollbackTransaction()

проверить(ссылка_архива(conn, uid_онн).ПолучитьОбъект() is None,
          "A. после отката архивного элемента в базе нет")

# --- C и D: регистрация к выгрузке в ЕРП -----------------------------------
узлы = строки(выполнить(conn, """
ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Узел
ИЗ ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20 КАК П
ГДЕ НЕ П.ЭтотУзел
"""))
проверить(len(узлы) == 1, "узел обмена с ЕРП найден")
if not узлы:
    print("\nИТОГ: узла обмена нет, проверки C/D невозможны")
    sys.exit(1)
узел = узлы[0].Узел

ЗАПРОС_РЕГИСТРАЦИЙ = """
ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
ИЗ Справочник.Номенклатура.Изменения КАК Изм
ГДЕ Изм.Узел = &Узел И Изм.Ссылка = &Ном
"""


def регистраций():
    return int(строки(выполнить(conn, ЗАПРОС_РЕГИСТРАЦИЙ,
                                Узел=узел, Ном=образец_ном.Ссылка))[0].К)


было = регистраций()
print(f"регистраций до прогона: {было}")

стало_без = None
conn.BeginTransaction()
try:
    объект = образец_ном.Ссылка.ПолучитьОбъект()
    объект.Записать()                      # БЕЗ Загрузка — контроль
    стало_без = регистраций()
except Exception as ошибка:
    print(f"  C. запись без Загрузка упала: {текст_ошибки(ошибка)}")
finally:
    conn.RollbackTransaction()
проверить(стало_без is not None and стало_без == было,
          f"C. без Загрузка регистрация НЕ создаётся ({было} -> {стало_без}) "
          "— на этом строится этап 2")

стало_с = None
conn.BeginTransaction()
try:
    объект = образец_ном.Ссылка.ПолучитьОбъект()
    объект.ОбменДанными.Загрузка = True
    объект.Записать()
    стало_с = регистраций()
except Exception as ошибка:
    print(f"  D. запись с Загрузка упала: {текст_ошибки(ошибка)}")
finally:
    conn.RollbackTransaction()
проверить(стало_с is not None and стало_с > было,
          f"D. с Загрузка регистрация СОЗДАЁТСЯ ({было} -> {стало_с}) "
          "— флаг не подавляет, поэтому в этапе 2 его нет")

проверить(регистраций() == было, "C/D. после откатов регистрации на месте")

# --- E: объём вложенной перезаписи подпиской А_ИдКод ------------------------
номенклатура = строки(выполнить(conn, """
ВЫБРАТЬ Н.Ссылка КАК Ссылка, Н.А_ИдКод КАК А_ИдКод
ИЗ Справочник.Номенклатура КАК Н
ГДЕ Н.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
"""))
расходится = sum(1 for с in номенклатура
                 if str(с.А_ИдКод).strip() != uuid_ссылки(conn, с.Ссылка))
print(f"E. номенклатур в отборе: {len(номенклатура)}; "
      f"из них А_ИдКод <> UUID: {расходится} "
      f"(столько раз подписка сделает вложенную перезапись)")
проверить(len(номенклатура) == 2640,
          f"E. отбор номенклатуры = 2640 (получено {len(номенклатура)})")

print(f"\nИТОГ: провалов {провалов}")
sys.exit(1 if провалов else 0)
