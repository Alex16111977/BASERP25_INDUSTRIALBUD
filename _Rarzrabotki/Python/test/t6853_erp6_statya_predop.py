# -*- coding: utf-8 -*-
import win32com.client, sys
if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

v8 = win32com.client.Dispatch("V83.COMConnector")
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Предопределённые имена статей-тёзок через метаданные ссылки
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ Ст.Ссылка КАК Ссылка, Ст.Наименование КАК Наим
ИЗ ПланВидовХарактеристик.СтатьиАктивовПассивов КАК Ст
ГДЕ Ст.Наименование ПОДОБНО "%рочие пассив%"
"""
r = q.Execute().Выгрузить()
print("Статьи-тёзки 'Прочие пассивы':")
for i in range(r.Количество()):
    s=r.Получить(i)
    # имя предопределённого через ПолучитьИмяПредопределенного
    try:
        имяпредоп = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.ПолучитьИмяПредопределенного(s.Ссылка)
    except Exception:
        имяпредоп = "?"
    uid = erp.String(s.Ссылка.УникальныйИдентификатор())
    print(f"  Наим='{s.Наим}' | ПредопИмя={имяпредоп} | UUID={uid}")

# Точная ссылка статьи из живого движения ОЗФУ (Кт6853)
print("\n--- Статья из реального движения ОЗФУ (Прочие пассивы, привязка к Кт6853) ---")
q1 = erp.NewObject("Запрос")
q1.Text = """ВЫБРАТЬ Сч.Ссылка КАК Ссылка ИЗ ПланСчетов.Хозрасчетный КАК Сч ГДЕ Сч.Код = "6853" """
счет = q1.Execute().Выгрузить().Получить(0).Ссылка
q1b = erp.NewObject("Запрос")
q1b.Text = """ВЫБРАТЬ РАЗЛИЧНЫЕ Дв.Регистратор КАК Рег ИЗ РегистрБухгалтерии.Хозрасчетный КАК Дв ГДЕ Дв.СчетКт = &Счет"""
q1b.SetParameter("Счет", счет)
rr=q1b.Execute().Выгрузить()
regs=erp.NewObject("Массив")
for i in range(rr.Количество()):
    regs.Добавить(rr.Получить(i).Рег)

q2 = erp.NewObject("Запрос")
q2.Text = """
ВЫБРАТЬ РАЗЛИЧНЫЕ ПАП.Статья КАК Статья
ИЗ РегистрНакопления.ПрочиеАктивыПассивы КАК ПАП
ГДЕ ПАП.Регистратор В (&Регистраторы) И ПАП.Статья.Наименование = "Прочие пассивы"
"""
q2.SetParameter("Регистраторы", regs)
r2 = q2.Execute().Выгрузить()
print(f"  рядкiв={r2.Количество()}")
for i in range(r2.Количество()):
    s=r2.Получить(i)
    try:
        имяпредоп = erp.ПланыВидовХарактеристик.СтатьиАктивовПассивов.ПолучитьИмяПредопределенного(s.Статья)
    except Exception:
        имяпредоп = "?"
    uid = erp.String(s.Статья.УникальныйИдентификатор())
    print(f"  Статья ОЗФУ: ПредопИмя={имяпредоп} | UUID={uid}")
