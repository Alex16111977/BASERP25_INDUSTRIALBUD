import win32com.client, sys
sys.stdout.reconfigure(encoding='utf-8')
v8 = win32com.client.Dispatch('V83.COMConnector')
erp = v8.Connect('Srvr="localhost";Ref="BaseERP";Usr="Администратор";Pwd="24043"')

# Структура измерений Хозрасчетный ERP
rb = erp.Метаданные.РегистрыБухгалтерии.Хозрасчетный
print("=== ERP РегистрБухгалтерии.Хозрасчетный измерения ===")
for m in rb.Измерения:
    print("  ИЗМ:", m.Имя)

# Обороты по 64x/65x за период
print("\n=== ERP обороты Хозрасчетный по 64x/65x (дек25-июнь26) ===")
q = erp.NewObject("Запрос")
q.Text = """
ВЫБРАТЬ
    Об.Счет КАК Счет,
    СУММА(Об.СуммаОборотДт) КАК Дт,
    СУММА(Об.СуммаОборотКт) КАК Кт
ИЗ
    РегистрБухгалтерии.Хозрасчетный.Обороты(
        ДАТАВРЕМЯ(2025,12,1,0,0,0),
        ДАТАВРЕМЯ(2026,6,30,23,59,59),
        ,
        Счет В ИЕРАРХИИ (&Счета)) КАК Об
СГРУППИРОВАТЬ ПО Об.Счет
"""
сч = erp.NewObject("Массив")
for code in ["641","642","645","651","652","654","655","656"]:
    a = erp.ПланыСчетов.Хозрасчетный.НайтиПоКоду(code)
    if not a.Пустая():
        сч.Добавить(a)
q.УстановитьПараметр("Счета", сч)
try:
    r = q.Execute().Выгрузить()
    if r.Количество()==0:
        print("  НЕТ движений по 64x/65x в Хозрасчетный ERP за период")
    for i in range(r.Количество()):
        s = r.Получить(i)
        print(f"  {str(s.Счет.Код):<8} | {str(s.Счет.Наименование)[:30]:<30} | Дт={s.Дт:>16,.2f} | Кт={s.Кт:>16,.2f}")
except Exception as e:
    info = getattr(e,'excepinfo',None)
    print("  FAIL:", info[2] if info else e)
