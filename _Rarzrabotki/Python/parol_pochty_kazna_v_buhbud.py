# Копия пароля системной учётной записи почты: безопасное хранилище Казны -> безопасное хранилище BuhBud.
# Запускает ПОЛЬЗОВАТЕЛЬ (Claude пароли не вводит). Пароль на экран и в файлы не выводится — только ключи и сверка.
import win32com.client

v8 = win32com.client.Dispatch("V83.COMConnector")
kz = v8.Connect('Srvr="localhost";Ref="kazna";Usr="cfo";Pwd="2442"')
buh = v8.Connect('Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"')
kz.УстановитьПривилегированныйРежим(True)
buh.УстановитьПривилегированныйРежим(True)

src = kz.Справочники.УчетныеЗаписиЭлектроннойПочты.СистемнаяУчетнаяЗаписьЭлектроннойПочты
dst = buh.Справочники.УчетныеЗаписиЭлектроннойПочты.СистемнаяУчетнаяЗаписьЭлектроннойПочты

for key in ("Пароль", "ПарольSMTP"):
    value = kz.ОбщегоНазначения.ПрочитатьДанныеИзБезопасногоХранилища(src, key)
    if not value:
        print(f"{key}: в Казне пусто — пропущено")
        continue
    buh.ОбщегоНазначения.ЗаписатьДанныеВБезопасноеХранилище(dst, value, key)
    same = buh.ОбщегоНазначения.ПрочитатьДанныеИзБезопасногоХранилища(dst, key) == value
    print(f"{key}: записан в BuhBud, совпадает с Казной: {'да' if same else 'НЕТ'}")

print("Дальше: BuhBud -> Системная учетная запись -> «Проверить настройки».")
