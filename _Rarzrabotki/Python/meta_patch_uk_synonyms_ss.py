PAT = re.compile(r'(?P<ind>[ \t]*)<Synonym>(?P<eol>\r?\n)(?P<i2>[ \t]*)<v8:item>\r?\n[ \t]*<v8:lang>ru</v8:lang>\r?\n'
                 r'[ \t]*<v8:content>(?P<ru>[^<]*)</v8:content>\r?\n[ \t]*</v8:item>\r?\n(?P=ind)</Synonym>')
def fix(m):
    ru = m.group('ru')
    if ru not in UK:
        return m.group(0)
    i2, eol = m.group('i2'), m.group('eol')
    uk_item = f"{i2}<v8:item>{eol}{i2}\t<v8:lang>uk</v8:lang>{eol}{i2}\t<v8:content>{UK[ru]}</v8:content>{eol}{i2}</v8:item>{eol}"
    text = m.group(0)
    return text.replace(f"{m.group('ind')}</Synonym>", uk_item + f"{m.group('ind')}</Synonym>")
