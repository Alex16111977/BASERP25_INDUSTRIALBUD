    t2, n = PAT.subn(fix, t)
    changed = sum(1 for m in PAT.finditer(t) if m.group('ru') in UK)
    open(p, 'wb').write((b'\xef\xbb\xbf' if bom else b'') + t2.encode('utf-8'))
    print(p, 'добавлено uk:', changed)
