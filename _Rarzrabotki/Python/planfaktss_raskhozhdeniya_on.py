# -*- coding: utf-8 -*-
"""Строки активных СС (bas_industrialbud), где общая назва СТРОКИ СС не совпадает с общей назвой КАРТОЧКИ.

С 04.09.2026 отчёт ПланФактССБухгалтерія берёт общую назву плана из строки СС, а факт закупок
классифицируется карточной назвой. По строкам из этого списка план и факт разъедутся по разным
«Загальна назва» и не будут неттоваться в «План на факт». Лечится данными: выровнять назву
в строке СС или в карточке номенклатуры.

Запуск:  python planfaktss_raskhozhdeniya_on.py
Выход:   _Rarzrabotki/Отчеты/ПланФактССБухгалтерія_расхождения_ОН.md
"""
import os
import sys
import datetime

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

CONN = 'Srvr="SQLSERVER";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
OUT = r"C:\Configuration_downloads\BASERP25\_Rarzrabotki\Отчеты\ПланФактССБухгалтерія_расхождения_ОН.md"

ТЕКСТ = """
ВЫБРАТЬ
	К.Ссылка.Наименование КАК СС,
	К.НомерСтроки КАК N,
	К.Этап.Наименование КАК Этап,
	К.ОбщееНазвание.Наименование КАК ОН_Строки,
	К.НоменклатураСС КАК ТекстСС,
	К.Номенклатура.Наименование КАК Карточка,
	К.Номенклатура.ОбщееНазваниеНоменклатуры.Наименование КАК ОН_Карточки,
	К.Количество КАК Кол,
	К.Сумма КАК Сумма
ИЗ
	Справочник.СтруктураСебестоимости.Комплектующие КАК К
ГДЕ
	НЕ К.Ссылка.ЭтоГруппа
	И К.Ссылка.Активная
	И НЕ К.Ссылка.ПометкаУдаления
	И К.Номенклатура <> ЗНАЧЕНИЕ(Справочник.Номенклатура.ПустаяСсылка)
	И К.ОбщееНазвание <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И К.Номенклатура.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
	И СокрЛП(К.ОбщееНазвание.Наименование) <> СокрЛП(К.Номенклатура.ОбщееНазваниеНоменклатуры.Наименование)
УПОРЯДОЧИТЬ ПО
	СС, N
"""


def md(s):
    return str(s if s is not None else "").replace("|", "\\|").strip()


def main():
    v8 = win32com.client.Dispatch("V83.COMConnector")
    b = v8.Connect(CONN)
    z = b.NewObject("Запрос")
    z.Текст = ТЕКСТ
    t = z.Выполнить().Выгрузить()

    строки = []
    по_сс = {}
    for i in range(t.Количество()):
        r = t[i]
        строки.append(r)
        по_сс[r.СС] = по_сс.get(r.СС, 0) + 1

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# ПланФактССБухгалтерія — расхождения общей назвы: строка СС ≠ карточка номенклатуры\n\n")
        f.write(f"Снято {datetime.date.today():%d.%m.%Y}, база bas_industrialbud, активные СС. Всего строк: {len(строки)}.\n\n")
        f.write("Отчёт берёт общую назву плана из строки СС, факт — из карточки. По этим строкам план и факт\n"
                "попадут под разные «Загальна назва» и не будут неттоваться в «План на факт».\n"
                "Чтобы сошлись — выровнять назву в строке СС или в карточке (решение по каждой строке за пользователем).\n\n")
        f.write("| СС | строк |\n|---|---:|\n")
        for k, v in sorted(по_сс.items()):
            f.write(f"| {md(k)} | {v} |\n")
        f.write("\n| СС | N | Етап | ОН строки СС | НоменклатураСС | Карточка | ОН карточки | Кол | Сумма |\n")
        f.write("|---|---:|---|---|---|---|---|---:|---:|\n")
        for r in строки:
            f.write(f"| {md(r.СС)} | {r.N} | {md(r.Этап)} | {md(r.ОН_Строки)} | {md(r.ТекстСС)} | {md(r.Карточка)} | "
                    f"{md(r.ОН_Карточки)} | {r.Кол} | {r.Сумма} |\n")

    print(f"OK: {len(строки)} строк → {OUT}")
    for k, v in sorted(по_сс.items()):
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
