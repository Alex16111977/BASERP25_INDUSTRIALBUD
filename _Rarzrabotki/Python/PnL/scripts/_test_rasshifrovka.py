"""Smoke test: вариант А_ОтчетPL_РасшифровкаДокументаОтчетPL + userSettingID в Template.

Имитирует серверную функцию СформироватьПользовательскиеНастройкиОтчета из модуля формы документа А_ОтчетPL.
Проверяет:
1. Вариант А_ОтчетPL_РасшифровкаДокументаОтчетPL найден в схеме отчёта.
2. В ПользовательскиеНастройки присутствуют элементы с ИдентификаторПользовательскойНастройки "Период" и "Подразделение".
3. Установка значения параметра Период и отбора Подразделение по userSettingID проходит без ошибок.
"""
import sys
import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

conn = connect_erp()

# 1) Создать объект отчёта и получить схему
rep = conn.Отчеты.А_ОтчетPL.Создать()
схема = rep.СхемаКомпоновкиДанных
print(f"Схема: {схема}")

# 2) Найти вариант
вариант = схема.ВариантыНастроек.Найти("А_ОтчетPL_РасшифровкаДокументаОтчетPL")
if вариант is None:
    print("ОШИБКА: вариант 'А_ОтчетPL_РасшифровкаДокументаОтчетPL' не найден в схеме. Template в базе не обновлён?")
    sys.exit(1)
print("  OK — вариант найден")

# 3) Инициализировать компоновщик и загрузить вариант
компоновщик = conn.NewObject("КомпоновщикНастроекКомпоновкиДанных")
источник = conn.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема)
компоновщик.Инициализировать(источник)
компоновщик.ЗагрузитьНастройки(вариант.Настройки)

# 4) Пройти по элементам пользовательских настроек
found_period = False
found_division = False
print("\nПользовательскиеНастройки.Элементы:")
for i in range(компоновщик.ПользовательскиеНастройки.Элементы.Количество()):
    элемент = компоновщик.ПользовательскиеНастройки.Элементы.Получить(i)
    id_польз = str(элемент.ИдентификаторПользовательскойНастройки)
    тип_элемента = str(type(элемент))
    print(f"  [{i}] id={id_польз!r}")
    if id_польз == "Период":
        found_period = True
    if id_польз == "Подразделение":
        found_division = True

print(f"\nПериод найден: {found_period}")
print(f"Подразделение найден: {found_division}")

if not found_period:
    print("ОШИБКА: параметр Период не выведен в ПользовательскиеНастройки (нет userSettingID).")
if not found_division:
    print("ОШИБКА: отбор Подразделение не выведен в ПользовательскиеНастройки (нет userSettingID).")

# 5) Попробовать установить значения — как в модуле формы
import_success = True
try:
    период = conn.NewObject("СтандартныйПериод")
    период.ДатаНачала = datetime.datetime(2025, 12, 1)
    период.ДатаОкончания = datetime.datetime(2025, 12, 31, 23, 59, 59)

    подразд = conn.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Крушинка", True)

    for i in range(компоновщик.ПользовательскиеНастройки.Элементы.Количество()):
        элемент = компоновщик.ПользовательскиеНастройки.Элементы.Получить(i)
        id_ = str(элемент.ИдентификаторПользовательскойНастройки)
        if id_ == "Период":
            элемент.Значение = период
            элемент.Использование = True
            print(f"  ✓ Период установлен: {период.ДатаНачала} - {период.ДатаОкончания}")
        elif id_ == "Подразделение":
            элемент.ПравоеЗначение = подразд
            элемент.Использование = True
            print(f"  ✓ Подразделение установлено: {подразд}")
except Exception as e:
    import_success = False
    print(f"ОШИБКА при установке: {e}")

print(f"\n=== ИТОГ ===")
print(f"Вариант найден: OK")
print(f"Период в ПользовательскиеНастройки: {'OK' if found_period else 'FAIL'}")
print(f"Подразделение в ПользовательскиеНастройки: {'OK' if found_division else 'FAIL'}")
print(f"Установка значений: {'OK' if import_success else 'FAIL'}")
