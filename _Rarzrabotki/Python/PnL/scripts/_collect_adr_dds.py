def collect_vyruchka(conn, year, month):
    """РегистрНакопления.ФинансовыеРезультаты — выручка по СтатьяДоходов."""
    last = calendar.monthrange(year, month)[1]
    text = f"""
    ВЫБРАТЬ
        Об.Подразделение КАК Подразделение,
        Об.Подразделение.Наименование КАК ПодрИмя,
        Об.СтатьяДоходов КАК СтатьяДоходов,
        ЕСТЬNULL(Об.СтатьяДоходов.Наименование, "(пусто)") КАК СДИмя,
        ЕСТЬNULL(Об.СтатьяДоходов.Код, "(пусто)") КАК СДКод,
        СУММА(Об.ДоходыРеглБезНДСОборот) КАК Сумма
    ИЗ РегистрНакопления.ФинансовыеРезультаты.Обороты(
        ДАТАВРЕМЯ({year},{month},1), ДАТАВРЕМЯ({year},{month},{last},23,59,59), , ) КАК Об
    ГДЕ Об.ДоходыРеглБезНДСОборот > 0
        И Об.СтатьяДоходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиДоходов.ПустаяСсылка)
    СГРУППИРОВАТЬ ПО
        Об.Подразделение, Об.Подразделение.Наименование,
        Об.СтатьяДоходов,
        ЕСТЬNULL(Об.СтатьяДоходов.Наименование, "(пусто)"),
        ЕСТЬNULL(Об.СтатьяДоходов.Код, "(пусто)")
    """
    return query_tz(conn, text)


def main():
    conn = connect_erp()

    # aggregate: {(раздел, entity_code): {name, uuid, по_месяцам: {"2025-12": {sum: X, по_подразделениям: {...}}}}}
    universe = {
        "расходы_ДДС": {},
        "доходы_ПрочиеДоходы": {},
        "доходы_Выручка": {},
    }

    totals = {"расходы_ДДС": 0, "доходы_ПрочиеДоходы": 0, "доходы_Выручка": 0}

    for year, month, mkey in MONTHS:
        print(f"\n=== {mkey} ===")

        # ---- Расходы (ПрочиеРасходы → ДДС) ----
        tz = collect_rn_rashody(conn, year, month)
        cnt = 0
        for i in range(tz.Количество()):
            r = tz.Получить(i)
            dds_uuid = uuid_str(conn, r.ДДС) if r.ДДС and not r.ДДС.Пустая() else "__ПУСТО__"
            dds_name = str(r.ДДСИмя)
            dds_code = str(r.ДДСКод)
            подр_name = str(r.ПодрИмя) if r.ПодрИмя else "(пусто)"
            сум = float(r.Сумма or 0)
            totals["расходы_ДДС"] += сум
            cnt += 1

            key = dds_uuid
            if key not in universe["расходы_ДДС"]:
                universe["расходы_ДДС"][key] = {
                    "name": dds_name, "code": dds_code, "uuid": dds_uuid,
                    "по_месяцам": {}, "итого": 0, "подразделений": set(),
                }
            entry = universe["расходы_ДДС"][key]
            entry["по_месяцам"].setdefault(mkey, 0)
            entry["по_месяцам"][mkey] += сум
            entry["итого"] += сум
            entry["подразделений"].add(подр_name)
        print(f"  РасходыДДС: {cnt} (сумма {totals['расходы_ДДС']:.0f} суммарно)")

        # ---- Прочие доходы ----
        tz = collect_rn_dohody(conn, year, month)
        cnt = 0
        for i in range(tz.Количество()):
            r = tz.Получить(i)
            sd_uuid = uuid_str(conn, r.СтатьяДоходов) if r.СтатьяДоходов and not r.СтатьяДоходов.Пустая() else "__ПУСТО__"
            sd_name = str(r.СДИмя)
            sd_code = str(r.СДКод)
            подр_name = str(r.ПодрИмя) if r.ПодрИмя else "(пусто)"
            сум = float(r.Сумма or 0)
            totals["доходы_ПрочиеДоходы"] += сум
            cnt += 1

            key = sd_uuid
            if key not in universe["доходы_ПрочиеДоходы"]:
                universe["доходы_ПрочиеДоходы"][key] = {
                    "name": sd_name, "code": sd_code, "uuid": sd_uuid,
                    "по_месяцам": {}, "итого": 0, "подразделений": set(),
                }
            entry = universe["доходы_ПрочиеДоходы"][key]
            entry["по_месяцам"].setdefault(mkey, 0)
            entry["по_месяцам"][mkey] += сум
            entry["итого"] += сум
            entry["подразделений"].add(подр_name)
        print(f"  ПрочиеДоходы: {cnt}")

        # ---- Выручка (ФинансовыеРезультаты) ----
        tz = collect_vyruchka(conn, year, month)
        cnt = 0
        for i in range(tz.Количество()):
            r = tz.Получить(i)
            sd_uuid = uuid_str(conn, r.СтатьяДоходов) if r.СтатьяДоходов and not r.СтатьяДоходов.Пустая() else "__ПУСТО__"
            sd_name = str(r.СДИмя)
            sd_code = str(r.СДКод)
            подр_name = str(r.ПодрИмя) if r.ПодрИмя else "(пусто)"
            сум = float(r.Сумма or 0)
            totals["доходы_Выручка"] += сум
            cnt += 1

            key = sd_uuid
            if key not in universe["доходы_Выручка"]:
                universe["доходы_Выручка"][key] = {
                    "name": sd_name, "code": sd_code, "uuid": sd_uuid,
                    "по_месяцам": {}, "итого": 0, "подразделений": set(),
                }
            entry = universe["доходы_Выручка"][key]
            entry["по_месяцам"].setdefault(mkey, 0)
            entry["по_месяцам"][mkey] += сум
            entry["итого"] += сум
            entry["подразделений"].add(подр_name)
        print(f"  Выручка: {cnt}")

    # Преобразовать set в list для JSON
    for раздел in universe:
        for key, entry in universe[раздел].items():
            entry["подразделений"] = sorted(entry["подразделений"])
            entry["итого"] = round(entry["итого"], 2)
            for mk in entry["по_месяцам"]:
                entry["по_месяцам"][mk] = round(entry["по_месяцам"][mk], 2)

    # Сортируем по итого убыв.
    result = {
        "generated_at": "2026-04-17",
        "months": [m[2] for m in MONTHS],
        "итого": {k: round(v, 2) for k, v in totals.items()},
        "расходы_ДДС": sorted(universe["расходы_ДДС"].values(), key=lambda x: -x["итого"]),
        "доходы_ПрочиеДоходы": sorted(universe["доходы_ПрочиеДоходы"].values(), key=lambda x: -x["итого"]),
        "доходы_Выручка": sorted(universe["доходы_Выручка"].values(), key=lambda x: -x["итого"]),
    }

    dst = config.JSON_DIR / "adr_dds_universe.json"
    dst.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"\n=== ИТОГО ===")
    print(f"  Уникальных ДДС расходов: {len(result['расходы_ДДС'])}")
    print(f"  Уникальных СтатьяДоходов (ПрочиеДоходы): {len(result['доходы_ПрочиеДоходы'])}")
    print(f"  Уникальных СтатьяДоходов (Выручка): {len(result['доходы_Выручка'])}")
    print(f"  Сумма расходов: {totals['расходы_ДДС']:>15,.2f} ₴")
    print(f"  Сумма прочих доходов: {totals['доходы_ПрочиеДоходы']:>15,.2f} ₴")
    print(f"  Сумма выручки: {totals['доходы_Выручка']:>15,.2f} ₴")
    print(f"\nРезультат: {dst}")


if __name__ == "__main__":
    main()
