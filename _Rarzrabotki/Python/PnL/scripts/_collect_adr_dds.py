"""Этап 1.1 — собирает ВСЕ уникальные ДДС из АДР за 3 месяца по всем подразделениям.

Источники (как в стандартном АнализДоходовРасходов):
- РегистрНакопления.ПрочиеРасходы.Обороты → СуммаРеглПриход по (Подразделение, ДДС)
- РегистрНакопления.ПрочиеДоходы.Обороты → СуммаРеглПриход по (Подразделение, СтатьяДоходов)
- РегистрНакопления.ФинансовыеРезультаты.Обороты → ДоходыРеглБезНДСОборот по (Подразделение, СтатьяДоходов)

Результат: data/json/adr_dds_universe.json
"""
import calendar
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config
from utils.com_connect import connect_erp, uuid_str

MONTHS = [
    (2025, 12, "2025-12"),
    (2026, 1, "2026-01"),
    (2026, 2, "2026-02"),
]


def query_tz(conn, text):
    q = conn.NewObject("Запрос")
    q.Текст = text
    return q.Выполнить().Выгрузить()


def collect_rn_rashody(conn, year, month):
    """РегистрНакопления.ПрочиеРасходы — расходы по (Подразделение, ДДС через СтатьяРасходов)."""
    last = calendar.monthrange(year, month)[1]
    text = f"""
    ВЫБРАТЬ
        Об.Подразделение КАК Подразделение,
        Об.Подразделение.Наименование КАК ПодрИмя,
        Об.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств КАК ДДС,
        ЕСТЬNULL(Об.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств.Наименование, "(пусто)") КАК ДДСИмя,
        ЕСТЬNULL(Об.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств.Код, "(пусто)") КАК ДДСКод,
        СУММА(Об.СуммаРеглПриход) КАК Сумма
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(
        ДАТАВРЕМЯ({year},{month},1), ДАТАВРЕМЯ({year},{month},{last},23,59,59), , ) КАК Об
    ГДЕ Об.СуммаРеглПриход > 0
    СГРУППИРОВАТЬ ПО
        Об.Подразделение, Об.Подразделение.Наименование,
        Об.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств,
        ЕСТЬNULL(Об.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств.Наименование, "(пусто)"),
        ЕСТЬNULL(Об.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств.Код, "(пусто)")
    """
    return query_tz(conn, text)


