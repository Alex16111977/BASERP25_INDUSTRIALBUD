"""Объединить все три регистра для полного факта по Астарте через ДДС."""
import sys, datetime
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

c = connect_erp()
podr = c.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Астарта. Тищенки", True)

Q = """
ВЫБРАТЬ
	ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов).А_СтатьяДвиженияДенежныхСредств КАК ДДС_Расх,
	ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиДоходов).А_СтатьяДвиженияДенежныхСредств КАК ДДС_Дох,
	Р.СтоимостьРеглБезНДСОборот КАК Сумма,
	"Номенклатура" КАК Источник
ПОМЕСТИТЬ втДвижения
ИЗ РегистрНакопления.ДвиженияНоменклатураДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &П) КАК Р
;

ВЫБРАТЬ
	ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов).А_СтатьяДвиженияДенежныхСредств,
	ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиДоходов).А_СтатьяДвиженияДенежныхСредств,
	Р.СуммаРеглОборот,
	"Контрагент"
ИЗ РегистрНакопления.ДвиженияКонтрагентДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &П) КАК Р
;

ВЫБРАТЬ
	Р.СтатьяДвиженияДенежныхСредств,
	Р.СтатьяДвиженияДенежныхСредств,
	Р.СуммаРеглОборот,
	"ДС"
ИЗ РегистрНакопления.ДвиженияДенежныеСредстваДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &П) КАК Р
;

ВЫБРАТЬ
	ВЫБОР КОГДА ДДС_Расх ЕСТЬ NULL ТОГДА ДДС_Дох ИНАЧЕ ДДС_Расх КОНЕЦ КАК ДДС,
	Источник,
	Сумма
ПОМЕСТИТЬ втНорм
ИЗ втДвижения
;

ВЫБРАТЬ
	ДДС.Наименование КАК ДДСНаим,
	Источник,
	СУММА(Сумма) КАК Сумма
ИЗ втНорм
СГРУППИРОВАТЬ ПО ДДС.Наименование, Источник
УПОРЯДОЧИТЬ ПО Сумма УБЫВ
"""
q = c.NewObject("Запрос")
q.Текст = Q
q.УстановитьПараметр("С", datetime.datetime(2025, 12, 1))
q.УстановитьПараметр("ПО", datetime.datetime(2025, 12, 31, 23, 59, 59))
q.УстановитьПараметр("П", podr)

tz = q.Выполнить().Выгрузить()
print(f"Rows: {tz.Количество()}")
total = 0
print(f"{'ДДС':40} | {'Источник':12} | {'Сумма':>15}")
print("-" * 72)
for i in range(tz.Количество()):
    r = tz.Получить(i)
    s = float(r.Сумма)
    total += s
    print(f"{str(r.ДДСНаим or '—')[:40]:40} | {str(r.Источник):12} | {s:>15.2f}")
print("-" * 72)
print(f"{'ИТОГО':40} | {'':12} | {total:>15.2f}")
