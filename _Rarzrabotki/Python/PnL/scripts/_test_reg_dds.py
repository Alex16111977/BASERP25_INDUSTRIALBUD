"""Test: ДвиженияДенежныеСредстваДоходыРасходы by Астарта + ДДС, декабрь 2025."""
import sys, datetime
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

c = connect_erp()
podr = c.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Астарта. Тищенки", True)

q = c.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
	Р.СтатьяДвиженияДенежныхСредств.Наименование КАК ДДС,
	СУММА(Р.СуммаОборот) КАК Сумма,
	СУММА(Р.СуммаРеглОборот) КАК СуммаРегл
ИЗ РегистрНакопления.ДвиженияДенежныеСредстваДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &П) КАК Р
СГРУППИРОВАТЬ ПО Р.СтатьяДвиженияДенежныхСредств.Наименование
УПОРЯДОЧИТЬ ПО Сумма УБЫВ
"""
q.УстановитьПараметр("С", datetime.datetime(2025, 12, 1))
q.УстановитьПараметр("ПО", datetime.datetime(2025, 12, 31, 23, 59, 59))
q.УстановитьПараметр("П", podr)

tz = q.Выполнить().Выгрузить()
print(f"Rows: {tz.Количество()}")
print(f"{'ДДС':40} | {'Сумма':>14} | {'СуммаРегл':>14}")
for i in range(tz.Количество()):
    r = tz.Получить(i)
    print(f"{str(r.ДДС)[:40]:40} | {float(r.Сумма):>14.2f} | {float(r.СуммаРегл):>14.2f}")
