"""Compare Астарта. Тищенки Декабрь 2025: Excel (PL document) vs 1С (ФинансовыеРезультаты).

Строит таблицу по ключу ДДС и выводит расхождения.
"""
import json
import sys
import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config
from utils.com_connect import connect_erp

PERIOD_START = datetime.datetime(2025, 12, 1)
PERIOD_END = datetime.datetime(2025, 12, 31, 23, 59, 59)
PODR_NAME = "Астарта. Тищенки"

conn = connect_erp()

QUERY = """
ВЫБРАТЬ
	ТЧ.Статья.Наименование КАК СтатьяНаим,
	ТЧ.Статья.Группа.Наименование КАК ГруппаНаим,
	СтатьиТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС,
	СУММА(ТЧ.Сумма) КАК СуммаPL
ПОМЕСТИТЬ втPL
ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
	ЛЕВОЕ СОЕДИНЕНИЕ Справочник.А_Статьи_PL.Статьи КАК СтатьиТЧ
		ПО ТЧ.Статья = СтатьиТЧ.Ссылка И СтатьиТЧ.НомерСтроки = 1
ГДЕ ТЧ.Ссылка.Дата МЕЖДУ &С И &ПО
	И ТЧ.Ссылка.Подразделение = &Подр
	И НЕ ТЧ.Ссылка.ПометкаУдаления
СГРУППИРОВАТЬ ПО
	ТЧ.Статья.Наименование, ТЧ.Статья.Группа.Наименование,
	СтатьиТЧ.СтатьяДвиженияДенежныхСредств
;

ВЫБРАТЬ
	ВЫБОР
		КОГДА ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов) <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
			ТОГДА ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов).А_СтатьяДвиженияДенежныхСредств
		ИНАЧЕ ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиДоходов).А_СтатьяДвиженияДенежныхСредств
	КОНЕЦ КАК ДДС,
	Р.СтоимостьРеглБезНДСОборот КАК Сумма
ПОМЕСТИТЬ втЕРП_Сырые
ИЗ РегистрНакопления.ДвиженияНоменклатураДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &Подр) КАК Р

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
	ВЫБОР
		КОГДА ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов) <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
			ТОГДА ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов).А_СтатьяДвиженияДенежныхСредств
		ИНАЧЕ ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиДоходов).А_СтатьяДвиженияДенежныхСредств
	КОНЕЦ,
	Р.СуммаРеглОборот
ИЗ РегистрНакопления.ДвиженияКонтрагентДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &Подр) КАК Р

ОБЪЕДИНИТЬ ВСЕ

ВЫБРАТЬ
	Р.СтатьяДвиженияДенежныхСредств,
	Р.СуммаРеглОборот
ИЗ РегистрНакопления.ДвиженияДенежныеСредстваДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &Подр) КАК Р
;

ВЫБРАТЬ ДДС, ДДС.Наименование КАК ДДСНаим, СУММА(Сумма) КАК СуммаЕРП
ПОМЕСТИТЬ втЕРП
ИЗ втЕРП_Сырые
СГРУППИРОВАТЬ ПО ДДС, ДДС.Наименование
;

ВЫБРАТЬ
	ЕСТЬNULL(PL.ГруппаНаим, "") КАК ГруппаНаим,
	ЕСТЬNULL(PL.СтатьяНаим, "") КАК СтатьяНаим,
	ВЫБОР КОГДА PL.ДДС ЕСТЬ NULL ТОГДА ЕРП.ДДСНаим ИНАЧЕ PL.ДДС.Наименование КОНЕЦ КАК ДДСНаим,
	ЕСТЬNULL(PL.СуммаPL, 0) КАК СуммаPL,
	ЕСТЬNULL(ЕРП.СуммаЕРП, 0) КАК СуммаЕРП,
	ЕСТЬNULL(PL.СуммаPL, 0) - ЕСТЬNULL(ЕРП.СуммаЕРП, 0) КАК Разница
ИЗ втPL КАК PL
	ПОЛНОЕ СОЕДИНЕНИЕ втЕРП КАК ЕРП ПО PL.ДДС = ЕРП.ДДС
УПОРЯДОЧИТЬ ПО ГруппаНаим, Разница УБЫВ
"""

# find podr by name
podr_ref = conn.Справочники.СтруктураПредприятия.НайтиПоНаименованию(PODR_NAME, True)
if not podr_ref or podr_ref.Пустая():
    print(f"Подразделение не найдено: {PODR_NAME}")
    sys.exit(1)
print(f"Подразделение: {PODR_NAME}, UUID OK")

q = conn.NewObject("Запрос")
q.Текст = QUERY
q.УстановитьПараметр("С", PERIOD_START)
q.УстановитьПараметр("ПО", PERIOD_END)
q.УстановитьПараметр("Подр", podr_ref)

tz = q.Выполнить().Выгрузить()
n = tz.Количество()

print(f"\nРасхождения по (ДДС) — всего {n} строк")
print(f"{'ГРУППА':30} | {'СТАТЬЯ PL':30} | {'ДДС':35} | {'PL':>14} | {'ERP':>14} | {'Δ':>14}")
print("-" * 150)

total_pl = total_erp = 0
for i in range(n):
    r = tz.Получить(i)
    g = str(r.ГруппаНаим or "")[:30]
    s = str(r.СтатьяНаим or "")[:30]
    dds = str(r.ДДСНаим or "")[:35]
    pl = float(r.СуммаPL)
    erp = float(r.СуммаЕРП)
    diff = float(r.Разница)
    total_pl += pl
    total_erp += erp
    mark = "" if abs(diff) < 0.01 else "  ← расхождение"
    print(f"{g:30} | {s:30} | {dds:35} | {pl:>14.2f} | {erp:>14.2f} | {diff:>14.2f}{mark}")

print("-" * 150)
print(f"{'ИТОГО':30} | {'':30} | {'':35} | {total_pl:>14.2f} | {total_erp:>14.2f} | {total_pl-total_erp:>14.2f}")
