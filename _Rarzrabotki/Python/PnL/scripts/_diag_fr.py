"""Diag: ФинансовыеРезультаты за декабрь 2025 — что там вообще есть?"""
import sys, datetime
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

conn = connect_erp()
Q = """
ВЫБРАТЬ ПЕРВЫЕ 20
	Ф.Подразделение.Наименование КАК Подр,
	Ф.СтатьяДоходов.Наименование КАК СД,
	Ф.СтатьяРасходов.Наименование КАК СР,
	Ф.ДоходыРеглБезНДСОборот КАК Дох,
	Ф.РасходыРеглБезНДСОборот КАК Рас
ИЗ РегистрНакопления.ФинансовыеРезультаты.Обороты(&С, &ПО, ,) КАК Ф
ГДЕ Ф.ДоходыРеглБезНДСОборот <> 0 ИЛИ Ф.РасходыРеглБезНДСОборот <> 0
"""
q = conn.NewObject("Запрос")
q.Текст = Q
q.УстановитьПараметр("С", datetime.datetime(2025, 1, 1))
q.УстановитьПараметр("ПО", datetime.datetime(2026, 4, 17, 23, 59, 59))
tz = q.Выполнить().Выгрузить()
print(f"Rows (всего в регистре за декабрь 2025): {tz.Количество()}")
for i in range(tz.Количество()):
    r = tz.Получить(i)
    print(f"  {str(r.Подр)[:25]:25} | {str(r.СД)[:30]:30} | {str(r.СР)[:30]:30} | Дох={float(r.Дох):>12.2f} | Рас={float(r.Рас):>12.2f}")
