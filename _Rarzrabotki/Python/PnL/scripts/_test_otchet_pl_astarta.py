"""E2E-тест: воспроизводит запрос ObjectModule.ПолучитьОбъединенныеДанные
и выводит строки Астарта.Тищенки — проверка что ЗП-статьи получили СуммаЕРП.
"""
import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

conn = connect_erp()

QUERY = """
ВЫБРАТЬ
    ТЧ.Ссылка КАК ДокументPL,
    ТЧ.Ссылка.Подразделение КАК Подразделение,
    ТЧ.Ссылка.ПодразделениеСтрока КАК ПодразделениеСтрока,
    ТЧ.Статья КАК СтатьяPL,
    ТЧ.Статья.Группа КАК Группа,
    ТЧ.Статья.СтатьяДоходов КАК СтатьяДоходов,
    СтатьиТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС,
    ТЧ.СуммаФома1 КАК СуммаФ1,
    ТЧ.СуммаФорма2 КАК СуммаФ2,
    ТЧ.Сумма КАК СуммаPL
ПОМЕСТИТЬ втPL_Сырые
ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
ЛЕВОЕ СОЕДИНЕНИЕ Справочник.А_Статьи_PL.Статьи КАК СтатьиТЧ
    ПО ТЧ.Статья = СтатьиТЧ.Ссылка И СтатьиТЧ.НомерСтроки = 1
ГДЕ ТЧ.Ссылка.Дата МЕЖДУ &НП И &КП
    И НЕ ТЧ.Ссылка.ПометкаУдаления
    И ТЧ.Ссылка.Подразделение.Наименование = "Астарта. Тищенки"
;

ВЫБРАТЬ
    Подразделение,
    ПодразделениеСтрока,
    Группа,
    СтатьяPL,
    СтатьяДоходов,
    ДДС,
    СУММА(СуммаФ1) КАК СуммаФ1,
    СУММА(СуммаФ2) КАК СуммаФ2,
    СУММА(СуммаPL) КАК СуммаPL
ПОМЕСТИТЬ втPL
ИЗ втPL_Сырые
СГРУППИРОВАТЬ ПО Подразделение, ПодразделениеСтрока, Группа, СтатьяPL, СтатьяДоходов, ДДС
;

// Новая архитектура: ПрочиеРасходы (ЗП + всё остальное)
ВЫБРАТЬ
    Р.Подразделение КАК Подразделение,
    Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств КАК ДДС,
    СУММА(Р.СуммаРеглПриход) КАК СуммаЕРП_Расх
ПОМЕСТИТЬ втЕРП_Расх
ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(&НП, &КП, , ) КАК Р
ГДЕ Р.Подразделение.Наименование = "Астарта. Тищенки"
  И Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
СГРУППИРОВАТЬ ПО Р.Подразделение, Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств
;

ВЫБРАТЬ
    ВЫРАЗИТЬ(PL.СтатьяPL.Наименование КАК Строка(100)) КАК СтатьяPL,
    ВЫРАЗИТЬ(PL.Группа.Наименование КАК Строка(100)) КАК Группа,
    PL.СуммаPL,
    ЕСТЬNULL(ЕРПР.СуммаЕРП_Расх, 0) КАК СуммаЕРП,
    PL.СуммаPL - ЕСТЬNULL(ЕРПР.СуммаЕРП_Расх, 0) КАК Разница
ИЗ втPL КАК PL
ЛЕВОЕ СОЕДИНЕНИЕ втЕРП_Расх КАК ЕРПР
    ПО PL.Подразделение = ЕРПР.Подразделение И PL.ДДС = ЕРПР.ДДС
УПОРЯДОЧИТЬ ПО Группа, СтатьяPL
"""

q = conn.NewObject("Запрос")
q.Текст = QUERY
q.УстановитьПараметр("НП", datetime.datetime(2025, 12, 1))
q.УстановитьПараметр("КП", datetime.datetime(2025, 12, 31, 23, 59, 59))
tz = q.Выполнить().Выгрузить()

print(f"{'Статья PL':45} {'PL ₴':>14} {'ЕРП ₴':>14} {'Разница ₴':>14}")
print("-" * 95)
groups_seen = set()
total_pl = total_erp = 0
total_zp_pl = total_zp_erp = 0
for i in range(tz.Количество()):
    r = tz.Получить(i)
    grp = str(r.Группа or "")
    if grp not in groups_seen:
        print(f"\n  [Группа: {grp}]")
        groups_seen.add(grp)
    st = str(r.СтатьяPL or "")[:45]
    pl = float(r.СуммаPL or 0)
    erp = float(r.СуммаЕРП or 0)
    dif = float(r.Разница or 0)
    total_pl += pl
    total_erp += erp
    if any(k in st for k in ("Зарплат", "ЗП ", "Начислен", "Удержан", "Премия")):
        total_zp_pl += pl
        total_zp_erp += erp
        mark = " ★"
    else:
        mark = ""
    print(f"{st:45} {pl:>14.2f} {erp:>14.2f} {dif:>14.2f}{mark}")

print("\n" + "=" * 95)
print(f"{'ИТОГО':45} {total_pl:>14.2f} {total_erp:>14.2f} {total_pl-total_erp:>14.2f}")
print(f"{'  из них ★ЗП-блок':45} {total_zp_pl:>14.2f} {total_zp_erp:>14.2f} {total_zp_pl-total_zp_erp:>14.2f}")
