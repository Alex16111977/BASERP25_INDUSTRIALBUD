"""Проверка #2: Документ.А_ОтчетPL ↔ АнализДоходовРасходов (РН ПрочиеРасходы/ПрочиеДоходы).

Для каждой пары (период, подразделение) из документов А_ОтчетPL строит:
- ИтогиПоГруппам.Сумма_Excel — суммы PL по группам.
- Сумма расходов АДР (СуммаРеглПриход из ПрочиеРасходы) за тот же период+подразделение.
- Расхождение = PL_расходы - АДР_расходы.

Известный gap: ЗП-статьи присутствуют в PL (из Excel) и в АДР (через ПрочиеРасходы).
Обычно расхождение по ЗП = 0-1% (копеечная погрешность Ф1+Ф2 vs регл).
По другим статьям Δ может быть до 20-30% из-за разной группировки у финансиста.

Результат → data/reports/verification_pl_vs_adr.csv

Формат CSV:
    Дата;Подразделение;PL_Доходы;PL_Расходы;АДР_Доходы;АДР_Расходы;Δ_Доходы;Δ_Расходы;Δ_%_Расходы;Статус
"""
import calendar
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config
from utils.com_connect import connect_erp


QUERY_PL = """
ВЫБРАТЬ
    Док.Дата КАК Дата,
    Док.Подразделение.Наименование КАК Подразделение,
    СУММА(ВЫБОР КОГДА ИГ.Группа.Наименование = "Операционный доход"
          ИЛИ ИГ.Группа.Наименование = "Финансовая деятельность"
               И ИГ.Сумма_Excel > 0
          ТОГДА ИГ.Сумма_Excel ИНАЧЕ 0 КОНЕЦ) КАК PL_Доходы,
    СУММА(ВЫБОР КОГДА ИГ.Группа.Наименование <> "Операционный доход"
          И (ИГ.Группа.Наименование <> "Финансовая деятельность" ИЛИ ИГ.Сумма_Excel > 0)
          ТОГДА ИГ.Сумма_Excel ИНАЧЕ 0 КОНЕЦ) КАК PL_Расходы
ИЗ Документ.А_ОтчетPL КАК Док
ЛЕВОЕ СОЕДИНЕНИЕ Документ.А_ОтчетPL.ИтогиПоГруппам КАК ИГ
    ПО ИГ.Ссылка = Док.Ссылка
ГДЕ НЕ Док.ПометкаУдаления
СГРУППИРОВАТЬ ПО Док.Дата, Док.Подразделение.Наименование
УПОРЯДОЧИТЬ ПО Дата, Подразделение
"""


def query_adr(conn, year: int, month: int, подр_имя: str):
    """Получить обороты АДР за конкретный месяц по конкретному подразделению."""
    last_day = calendar.monthrange(year, month)[1]  # корректный последний день месяца
    # ПрочиеРасходы
    q1 = conn.NewObject("Запрос")
    q1.Текст = f"""
        ВЫБРАТЬ СУММА(Об.СуммаРеглПриход) КАК Сумма
        ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(
            ДАТАВРЕМЯ({year},{month},1),
            ДАТАВРЕМЯ({year},{month},{last_day},23,59,59), , ) КАК Об
        ГДЕ Об.Подразделение.Наименование = "{подр_имя}"
    """
    rr = q1.Выполнить().Выгрузить()
    расх = float(rr.Получить(0).Сумма or 0) if rr.Количество() else 0.0

    # ПрочиеДоходы
    q2 = conn.NewObject("Запрос")
    q2.Текст = f"""
        ВЫБРАТЬ СУММА(Об.СуммаРеглПриход) КАК Сумма
        ИЗ РегистрНакопления.ПрочиеДоходы.Обороты(
            ДАТАВРЕМЯ({year},{month},1),
            ДАТАВРЕМЯ({year},{month},{last_day},23,59,59), , ) КАК Об
        ГДЕ Об.Подразделение.Наименование = "{подр_имя}"
    """
    rr = q2.Выполнить().Выгрузить()
    дох = float(rr.Получить(0).Сумма or 0) if rr.Количество() else 0.0
    return дох, расх


def main():
    conn = connect_erp()
    q = conn.NewObject("Запрос")
    q.Текст = QUERY_PL
    tz = q.Выполнить().Выгрузить()
    n = tz.Количество()
    print(f"Документов А_ОтчетPL: {n}")

    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for i in range(n):
        r = tz.Получить(i)
        дата = r.Дата
        подр = str(r.Подразделение) if r.Подразделение else ""
        pl_дох = float(r.PL_Доходы or 0)
        pl_расх = float(r.PL_Расходы or 0)

        if not подр:
            continue

        адр_дох, адр_расх = query_adr(conn, дата.year, дата.month, подр)

        delta_расх = pl_расх - адр_расх
        delta_дох = pl_дох - адр_дох
        pct_расх = (delta_расх / адр_расх * 100) if адр_расх > 0 else 0
        абс_pct = abs(pct_расх)
        if абс_pct < 1:
            статус = "OK (±1%)"
        elif абс_pct < 10:
            статус = "Группировка (финансист)"
        else:
            статус = "РАЗРЫВ"

        rows.append({
            "Дата": str(дата)[:10],
            "Подразделение": подр,
            "PL_Доходы": pl_дох,
            "PL_Расходы": pl_расх,
            "АДР_Доходы": адр_дох,
            "АДР_Расходы": адр_расх,
            "Δ_Доходы": delta_дох,
            "Δ_Расходы": delta_расх,
            "Δ_%_Расходы": pct_расх,
            "Статус": статус,
        })
        мес_label = f"{дата.month:02d}.{str(дата.year)[-2:]}"
        print(f"  {подр[:30]:30} {мес_label}: PL={pl_расх:>12.0f} АДР={адр_расх:>12.0f} Δ={delta_расх:>10.0f}  {статус}")

    out_csv = config.REPORTS_DIR / "verification_pl_vs_adr.csv"
    with out_csv.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["Дата", "Подразделение", "PL_Доходы", "PL_Расходы",
                    "АДР_Доходы", "АДР_Расходы", "Δ_Доходы", "Δ_Расходы",
                    "Δ_%_Расходы", "Статус"])
        for r in rows:
            w.writerow([
                r["Дата"], r["Подразделение"],
                f"{r['PL_Доходы']:.2f}", f"{r['PL_Расходы']:.2f}",
                f"{r['АДР_Доходы']:.2f}", f"{r['АДР_Расходы']:.2f}",
                f"{r['Δ_Доходы']:.2f}", f"{r['Δ_Расходы']:.2f}",
                f"{r['Δ_%_Расходы']:.2f}", r["Статус"],
            ])

    ok = sum(1 for r in rows if "OK" in r["Статус"])
    gap = sum(1 for r in rows if "РАЗРЫВ" in r["Статус"])
    print(f"\nВсего: {len(rows)}  OK: {ok}  Разрыв: {gap}")
    print(f"Результат: {out_csv}")


if __name__ == "__main__":
    main()
