"""Почему в запросе PL=0? Проверим, сколько А_ОтчетPL за декабрь 2025 по Астарте, ПометкаУдаления."""
import sys, datetime
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

c = connect_erp()
podr = c.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Крушинка", True)

q = c.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
	Д.Ссылка, Д.Номер, Д.Дата, Д.Подразделение.Наименование КАК Подр,
	Д.ПодразделениеСтрока, Д.ПометкаУдаления, Д.Проведен,
	СУММА(Т.Сумма) КАК СуммаТЧ
ИЗ Документ.А_ОтчетPL КАК Д
	ЛЕВОЕ СОЕДИНЕНИЕ Документ.А_ОтчетPL.ДанныеОтчета КАК Т ПО Т.Ссылка = Д.Ссылка
ГДЕ Д.Дата МЕЖДУ &С И &ПО
  И (Д.Подразделение = &П ИЛИ Д.ПодразделениеСтрока ПОДОБНО "%Крушинка%")
СГРУППИРОВАТЬ ПО Д.Ссылка, Д.Номер, Д.Дата, Д.Подразделение.Наименование,
	Д.ПодразделениеСтрока, Д.ПометкаУдаления, Д.Проведен
УПОРЯДОЧИТЬ ПО Д.ПометкаУдаления, Д.Номер
"""
q.УстановитьПараметр("С", datetime.datetime(2025, 12, 1))
q.УстановитьПараметр("ПО", datetime.datetime(2025, 12, 31, 23, 59, 59))
q.УстановитьПараметр("П", podr)

tz = q.Выполнить().Выгрузить()
print(f"Документов: {tz.Количество()}")
for i in range(tz.Количество()):
    r = tz.Получить(i)
    suma = float(r.СуммаТЧ) if r.СуммаТЧ is not None else 0
    print(f"  №{r.Номер!r} {r.Дата} | Подр={str(r.Подр):22} | Помечен={r.ПометкаУдаления} | СуммаТЧ={suma:>14.2f}")
