"""Этап 1.5b — правка оставшихся проблем после _apply_dds_assignments.py:

1. Вернуть ДДС 'Персонал' (UUID bbd85493-232a-11e6-80c4-000c29bbac23) в 5 PL с пустой ТЧ:
   Премия произв., Командировочные произв., Транспортные произв., Премия упр., Транспортные упр.
   (В АДР за 3 мес сумма = 0, поэтому задвоения не будет. Эта ДДС — shared обобщение.)

2. Обновить шапку 2 PL на корректную ДДС (которая есть в ТЧ):
   - 000000039 Начисления на управленчискую → шапка = 'Начисления на админ зарплату'
   - 000000048 Затраты на коммандировки упр → шапка = 'Суточные' (первая в ТЧ)

3. Оставить 3 PL без ДДС как есть (Тип=Доход или без оборотов в АДР):
   - 000000002 Доход от прочей операционной — Тип=Доход (связь через СтатьяДоходов)
   - 000000028 Расход от ивест. деятельности (ОС) — нет аналога в АДР
   - 000000056 Финансовые расходы — нет аналога в АДР
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp, is_manually_locked, uuid_str


DDS_PERSONAL_UUID = "bbd85493-232a-11e6-80c4-000c29bbac23"

# Возвращаем «Персонал» в ТЧ
RETURN_PERSONAL_TO = [
    ("000000011", "Премия производственного персонала"),
    ("000000023", "Командировочные производственного персонала"),
    ("000000025", "Транспортные затраты производственного персонала"),
    ("000000044", "Премия управленческого персонала"),
    ("000000046", "Транспортные затраты управленческого персонала"),
]

# Обновление шапки
FIX_HEADER = [
    # (pl_code, новый_dds_uuid, имя для лога)
    ("000000039", "61c4358c-c894-11e8-a200-000c299fb278", "Начисления на админ зарплату"),
    ("000000048", None, "первая из ТЧ"),  # для коммандировок — возьмём первую из ТЧ
]


def main():
    conn = connect_erp()
    pl_mgr = conn.Справочники.А_Статьи_PL
    dds_mgr = conn.Справочники.СтатьиДвиженияДенежныхСредств

    dds_personal = dds_mgr.ПолучитьСсылку(conn.NewObject("УникальныйИдентификатор", DDS_PERSONAL_UUID))

    # 1. Возвращаем Персонал в ТЧ 5 статей
    print("=== 1. Возвращаю ДДС 'Персонал' в ТЧ ===")
    for code, name in RETURN_PERSONAL_TO:
        ref = pl_mgr.НайтиПоКоду(code)
        if not ref or ref.Пустая():
            print(f"  SKIP: {name} (код {code}) не найден")
            continue
        obj = ref.ПолучитьОбъект()
        if is_manually_locked(obj):
            print(f"  LOCK {name} (А_РучнаяКорректировка=Истина — пропущен)")
            continue
        # добавить в ТЧ, если нет
        есть = False
        for i in range(obj.Статьи.Количество()):
            row = obj.Статьи.Получить(i)
            if row.СтатьяДвиженияДенежныхСредств and uuid_str(conn, row.СтатьяДвиженияДенежныхСредств) == DDS_PERSONAL_UUID:
                есть = True
                break
        if not есть:
            stroka = obj.Статьи.Добавить()
            stroka.СтатьяДвиженияДенежныхСредств = dds_personal
        # установить в шапке (если пуста или совпадает)
        if not obj.СтатьяДвиженияДенежныхСредств or obj.СтатьяДвиженияДенежныхСредств.Пустая():
            obj.СтатьяДвиженияДенежныхСредств = dds_personal
        obj.Записать()
        print(f"  OK  {name}")

    # 2. Фикс шапок
    print("\n=== 2. Обновляю шапки (выровнять с ТЧ) ===")
    for code, new_dds_uuid, log_name in FIX_HEADER:
        ref = pl_mgr.НайтиПоКоду(code)
        if not ref or ref.Пустая():
            print(f"  SKIP: код {code} не найден")
            continue
        obj = ref.ПолучитьОбъект()
        pl_name = str(ref)
        if is_manually_locked(obj):
            print(f"  LOCK {pl_name[:50]} (А_РучнаяКорректировка=Истина — пропущен)")
            continue

        if new_dds_uuid:
            new_ref = dds_mgr.ПолучитьСсылку(conn.NewObject("УникальныйИдентификатор", new_dds_uuid))
            # проверить, что эта ДДС есть в ТЧ
            in_tch = False
            for i in range(obj.Статьи.Количество()):
                row = obj.Статьи.Получить(i)
                if row.СтатьяДвиженияДенежныхСредств and uuid_str(conn, row.СтатьяДвиженияДенежныхСредств) == new_dds_uuid:
                    in_tch = True
                    break
            if not in_tch:
                stroka = obj.Статьи.Добавить()
                stroka.СтатьяДвиженияДенежныхСредств = new_ref
            obj.СтатьяДвиженияДенежныхСредств = new_ref
        else:
            # первая из ТЧ
            if obj.Статьи.Количество() > 0:
                obj.СтатьяДвиженияДенежныхСредств = obj.Статьи.Получить(0).СтатьяДвиженияДенежныхСредств

        obj.Записать()
        print(f"  OK  {pl_name[:50]} → шапка={log_name}")

    print("\nПроверка — запустите `_detect_uncovered_dds.py` для верификации.")


if __name__ == "__main__":
    main()
