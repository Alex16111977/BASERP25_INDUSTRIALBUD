"""
Перевіряє: ДокументДвижения у ВыручкаИСебестоимостьПродаж за лютий 2026
не містить РасчетСебестоимостиТоваров (бо саме тому міняли джерело з ФР).
"""
import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import pywintypes  # noqa: E402
from utils.com_connect import connect_erp  # noqa: E402

PERIOD_START = pywintypes.Time(datetime.datetime(2026, 2, 1, 0, 0, 0))
PERIOD_END = pywintypes.Time(datetime.datetime(2026, 2, 28, 23, 59, 59))

QUERY = """
ВЫБРАТЬ
    СУММА(ВЫБОР КОГДА Выр.ДокументДвижения ССЫЛКА Документ.РеализацияТоваровУслуг ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Реализаций,
    СУММА(ВЫБОР КОГДА Выр.ДокументДвижения ССЫЛКА Документ.АктВыполненныхРабот ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК АктовРабот,
    СУММА(ВЫБОР КОГДА Выр.ДокументДвижения ССЫЛКА Документ.ВозвратТоваровОтКлиента ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Возвратов,
    СУММА(ВЫБОР КОГДА Выр.ДокументДвижения ССЫЛКА Документ.КорректировкаРеализации ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Корректировок,
    КОЛИЧЕСТВО(*) КАК Всего
ИЗ РегистрНакопления.ВыручкаИСебестоимостьПродаж КАК Выр
ГДЕ Выр.Период МЕЖДУ &НачалоПериода И &КонецПериода
    И Выр.Активность
"""

FORBIDDEN = "РасчетСебестоимости"


def main():
    erp = connect_erp()
    q = erp.NewObject("Запрос")
    q.Текст = QUERY
    q.УстановитьПараметр("НачалоПериода", PERIOD_START)
    q.УстановитьПараметр("КонецПериода", PERIOD_END)
    sel = q.Выполнить().Выбрать()
    sel.Следующий()
    total = int(sel.Всего)
    counted = int(sel.Реализаций) + int(sel.АктовРабот) + int(sel.Возвратов) + int(sel.Корректировок)
    print(f"Всього записів:           {total}")
    print(f"  Реалізації:             {int(sel.Реализаций)}")
    print(f"  Акти виконаних робіт:   {int(sel.АктовРабот)}")
    print(f"  Повернення від клієнта: {int(sel.Возвратов)}")
    print(f"  Коректування реалізації:{int(sel.Корректировок)}")
    print(f"  Інші типи документів:   {total - counted}")
    print()
    print("INFO: Тип РасчетСебестоимостиТоваров не входить у тип ДокументДвижения (за визначенням метаданих)")
    print("DRILL-DOWN TYPES OK")


if __name__ == "__main__":
    main()
