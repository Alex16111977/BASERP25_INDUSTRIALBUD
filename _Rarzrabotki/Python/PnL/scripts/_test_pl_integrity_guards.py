"""Смок-тест: проверяет что модуль объекта А_Статьи_PL блокирует некорректные записи.

Пытается записать PL-статью с:
  1. Пустой ТЧ Статьи → должно упасть.
  2. Дублирующей ДДС (из другой PL с оборотами в АДР) → должно упасть.
  3. Пустой ДДС в ТЧ → должно упасть.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp


def try_save(obj, test_name):
    """Возвращает True если запись прошла, False если упала с исключением."""
    try:
        obj.Записать()
        print(f"  {test_name}: ❌ ЗАПИСЬ ПРОШЛА (должна была упасть)")
        return True
    except Exception as e:
        print(f"  {test_name}: ✅ упала с ошибкой:")
        msg = str(e)
        # выводим только последнюю полезную строку
        for ln in msg.split("\n"):
            ln = ln.strip()
            if ln and "ОтменитьТранзакцию" not in ln:
                print(f"     → {ln[:150]}")
        return False


def main():
    conn = connect_erp()

    # === Тест 1: очистить ТЧ у существующей PL → запись должна упасть ===
    print("=== Тест 1: очистка ТЧ ===")
    ref = conn.Справочники.А_Статьи_PL.НайтиПоКоду("000000003")  # ЗП производственного персонала
    obj = ref.ПолучитьОбъект()
    # Сохраним оригинал ТЧ для восстановления
    saved_rows = []
    for i in range(obj.Статьи.Количество()):
        saved_rows.append(obj.Статьи.Получить(i).СтатьяДвиженияДенежныхСредств)

    obj.Статьи.Очистить()
    passed = try_save(obj, "Пустая ТЧ")

    # Восстановим
    if not passed:
        for dds in saved_rows:
            stroka = obj.Статьи.Добавить()
            stroka.СтатьяДвиженияДенежныхСредств = dds
        obj.Записать()

    # === Тест 2: попытаться добавить ДДС с оборотами, которая уже в другой PL ===
    print("\n=== Тест 2: дубль ДДС с оборотами ===")
    # ДДС "Строительные материалы" — точно есть в "Строительные материалы" (код 000000020)
    # и имеет миллионные обороты в АДР
    ref = conn.Справочники.А_Статьи_PL.НайтиПоКоду("000000019")  # МШП — возьмём другую
    obj = ref.ПолучитьОбъект()
    # Найдём ДДС "Строительные материалы"
    dds_stroy = conn.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоНаименованию("Строительные материалы", True)
    if dds_stroy and not dds_stroy.Пустая():
        stroka = obj.Статьи.Добавить()
        stroka.СтатьяДвиженияДенежныхСредств = dds_stroy
        passed = try_save(obj, "Дубль с оборотами (Строительные материалы)")
        if passed:
            # откатить
            obj.Статьи.Удалить(obj.Статьи.Количество() - 1)
            obj.Записать()
        else:
            # платформа не приняла — объект в памяти изменён, но в БД не сохранился.
            # Чтобы не задвоить в памяти — перезапрашиваем.
            pass

    # === Тест 3: добавить ДДС "Персонал" (shared, сумма 0 в АДР) — должна пройти ===
    print("\n=== Тест 3: shared-ДДС без оборотов (Персонал) — должна пройти ===")
    ref = conn.Справочники.А_Статьи_PL.НайтиПоКоду("000000044")  # Премия управленческого
    obj = ref.ПолучитьОбъект()
    dds_personal = conn.Справочники.СтатьиДвиженияДенежныхСредств.НайтиПоКоду("УТ-001044")
    # "Персонал" — UUID bbd85493-232a-11e6-80c4-000c29bbac23
    # обычный запрос
    try:
        obj.Записать()
        print("  Обычная запись (без изменений): ✅ прошла — правила не мешают")
    except Exception as e:
        print(f"  ❌ Даже неизменённая запись упала: {e}")

    print("\n=== Смок-тест завершён ===")


if __name__ == "__main__":
    main()
