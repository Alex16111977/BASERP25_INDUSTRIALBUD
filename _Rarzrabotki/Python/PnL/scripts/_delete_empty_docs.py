"""Удалить все непомеченные документы А_ОтчетPL с пустой ТЧ."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

c = connect_erp()
q = c.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
	Д.Ссылка,
	ЕСТЬNULL(СУММА(Т.Сумма), 0) КАК СуммаТЧ
ИЗ Документ.А_ОтчетPL КАК Д
	ЛЕВОЕ СОЕДИНЕНИЕ Документ.А_ОтчетPL.ДанныеОтчета КАК Т ПО Т.Ссылка = Д.Ссылка
ГДЕ НЕ Д.ПометкаУдаления
СГРУППИРОВАТЬ ПО Д.Ссылка
ИМЕЮЩИЕ ЕСТЬNULL(СУММА(Т.Сумма), 0) = 0
"""
tz = q.Выполнить().Выгрузить()
print(f"Пустых документов на удаление: {tz.Количество()}")
for i in range(tz.Количество()):
    ref = tz.Получить(i).Ссылка
    obj = ref.ПолучитьОбъект()
    obj.Удалить()
print("Удалены непосредственно (без пометки).")
