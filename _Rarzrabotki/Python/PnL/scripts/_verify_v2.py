"""Verify the new report query by testing PL + СтатьяДоходов match against ERP for Астарта дек 2025."""
import sys, datetime
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.com_connect import connect_erp

c = connect_erp()
podr = c.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Астарта. Тищенки", True)

Q = """
ВЫБРАТЬ
	PL.СтатьяPL.Наименование КАК СтатьяНаим,
	PL.СтатьяДоходов КАК СтатьяДоходов,
	PL.ДДС.Наименование КАК ДДСНаим,
	СУММА(PL.СуммаPL) КАК СуммаPL,
	СУММА(ЕСТЬNULL(ЕРПД.СуммаЕРП_Доход, 0)) КАК СуммаЕРПДоход,
	СУММА(ЕСТЬNULL(ЕРПР.СуммаЕРП_Расх, 0)) КАК СуммаЕРПРасход
ПОМЕСТИТЬ врем
ИЗ (
	ВЫБРАТЬ
		ТЧ.Статья КАК СтатьяPL,
		ТЧ.Статья.СтатьяДоходов КАК СтатьяДоходов,
		СтатьиТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС,
		СУММА(ТЧ.Сумма) КАК СуммаPL
	ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
		ЛЕВОЕ СОЕДИНЕНИЕ Справочник.А_Статьи_PL.Статьи КАК СтатьиТЧ
			ПО ТЧ.Статья = СтатьиТЧ.Ссылка И СтатьиТЧ.НомерСтроки = 1
	ГДЕ ТЧ.Ссылка.Дата МЕЖДУ &С И &ПО
		И ТЧ.Ссылка.Подразделение = &П
		И НЕ ТЧ.Ссылка.ПометкаУдаления
	СГРУППИРОВАТЬ ПО ТЧ.Статья, ТЧ.Статья.СтатьяДоходов, СтатьиТЧ.СтатьяДвиженияДенежныхСредств
) КАК PL
	ЛЕВОЕ СОЕДИНЕНИЕ (
		ВЫБРАТЬ Ф.СтатьяДоходов, СУММА(Ф.ДоходыРеглБезНДСОборот) КАК СуммаЕРП_Доход
		ИЗ РегистрНакопления.ФинансовыеРезультаты.Обороты(&С, &ПО, , Подразделение = &П) КАК Ф
		ГДЕ Ф.СтатьяДоходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиДоходов.ПустаяСсылка)
		СГРУППИРОВАТЬ ПО Ф.СтатьяДоходов
	) КАК ЕРПД ПО PL.СтатьяДоходов = ЕРПД.СтатьяДоходов
	ЛЕВОЕ СОЕДИНЕНИЕ (
		ВЫБРАТЬ ДДС, СУММА(Сумма) КАК СуммаЕРП_Расх ИЗ (
			ВЫБРАТЬ
				ВЫБОР КОГДА ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов) <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиРасходов.ПустаяСсылка)
					ТОГДА ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиРасходов).А_СтатьяДвиженияДенежныхСредств
					ИНАЧЕ ВЫРАЗИТЬ(Р.СтатьяДоходовРасходов КАК ПланВидовХарактеристик.СтатьиДоходов).А_СтатьяДвиженияДенежныхСредств
				КОНЕЦ КАК ДДС,
				Р.СтоимостьРеглБезНДСОборот КАК Сумма
			ИЗ РегистрНакопления.ДвиженияНоменклатураДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &П) КАК Р
			ОБЪЕДИНИТЬ ВСЕ
			ВЫБРАТЬ Р.СтатьяДвиженияДенежныхСредств, Р.СуммаРеглОборот
			ИЗ РегистрНакопления.ДвиженияДенежныеСредстваДоходыРасходы.Обороты(&С, &ПО, , Подразделение = &П) КАК Р
		) КАК О СГРУППИРОВАТЬ ПО ДДС
	) КАК ЕРПР ПО PL.ДДС = ЕРПР.ДДС
СГРУППИРОВАТЬ ПО PL.СтатьяPL.Наименование, PL.СтатьяДоходов, PL.ДДС.Наименование
;

ВЫБРАТЬ *, СуммаPL - СуммаЕРПДоход - СуммаЕРПРасход КАК Разница ИЗ врем
УПОРЯДОЧИТЬ ПО Разница УБЫВ
"""
q = c.NewObject("Запрос")
q.Текст = Q
q.УстановитьПараметр("С", datetime.datetime(2025, 12, 1))
q.УстановитьПараметр("ПО", datetime.datetime(2025, 12, 31, 23, 59, 59))
q.УстановитьПараметр("П", podr)

tz = q.Выполнить().Выгрузить()
print(f"Rows: {tz.Количество()}")
print(f"{'СТАТЬЯ PL':35} | {'СТАТЬЯ ДОХОДОВ':25} | {'ДДС':25} | {'PL':>14} | {'ЕРП Дох':>12} | {'ЕРП Рас':>12} | {'Δ':>12}")
print("-" * 150)
total_pl = total_erp = 0
for i in range(tz.Количество()):
    r = tz.Получить(i)
    pl = float(r.СуммаPL); ed = float(r.СуммаЕРПДоход); er = float(r.СуммаЕРПРасход); d = float(r.Разница)
    total_pl += pl; total_erp += ed + er
    sd = str(r.СтатьяДоходов) if r.СтатьяДоходов else ""
    print(f"{str(r.СтатьяНаим or '')[:35]:35} | {sd[:25]:25} | {str(r.ДДСНаим or '')[:25]:25} | {pl:>14.2f} | {ed:>12.2f} | {er:>12.2f} | {d:>12.2f}")
print("-" * 150)
print(f"{'ИТОГО':35} | {'':25} | {'':25} | {total_pl:>14.2f} | {total_erp:>12.2f} | {'':>12} | {total_pl-total_erp:>12.2f}")
