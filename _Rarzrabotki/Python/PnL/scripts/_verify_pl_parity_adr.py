"""Главный тест паритета: А_ОтчетPL ↔ АнализДоходовРасходов.

Для каждого (месяц, подразделение, ДДС/СтатьяДоходов) делает 2 запроса:
  1. АДР-сумма: СуммаРеглПриход по (ПрочиеРасходы+ПрочиеДоходы+ФинансовыеРезультаты)
  2. PL-сумма: из Документ.А_ОтчетPL.ДанныеОтчета через связь по ТЧ Статьи

Классифицирует расхождение:
  OK          — |Δ| < 0.01 ₴
  DATA_GAP    — ДДС привязана в PL, но суммы не совпадают (ошибка Excel финансиста)
  MAPPING_BUG — ДДС из АДР не привязана ни к одной PL (после наведения порядка должно быть 0)

Результат → data/reports/verification_pl_parity_adr.csv
          → data/reports/data_gaps_for_finance.csv (отдельный файл для финансиста)
"""
import calendar
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config
from utils.com_connect import connect_erp, uuid_str

MONTHS = [(2025, 12), (2026, 1), (2026, 2)]


def parity_query(conn, year, month):
    """Возвращает строки паритета PL ↔ АДР за месяц по всем подразделениям × всем статьям."""
    last = calendar.monthrange(year, month)[1]
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    // Агрегат PL по (Подразделение, СтатьяPL)
    ВЫБРАТЬ
        ТЧ.Ссылка.Подразделение КАК Подразделение,
        ТЧ.Статья КАК СтатьяPL,
        ТЧ.Статья.СтатьяДоходов КАК СтатьяДоходов,
        ТЧ.Статья.Группа КАК Группа,
        ТЧ.Статья.ТипСтатьи КАК ТипСтатьи,
        ТЧ.Статья.А_СозданоАвтоматически КАК Авто,
        СУММА(ТЧ.Сумма) КАК СуммаPL
    ПОМЕСТИТЬ втPL
    ИЗ Документ.А_ОтчетPL.ДанныеОтчета КАК ТЧ
    ГДЕ ТЧ.Ссылка.Дата МЕЖДУ ДАТАВРЕМЯ({year},{month},1) И ДАТАВРЕМЯ({year},{month},{last},23,59,59)
        И НЕ ТЧ.Ссылка.ПометкаУдаления
    СГРУППИРОВАТЬ ПО
        ТЧ.Ссылка.Подразделение, ТЧ.Статья, ТЧ.Статья.СтатьяДоходов,
        ТЧ.Статья.Группа, ТЧ.Статья.ТипСтатьи, ТЧ.Статья.А_СозданоАвтоматически
    ;

    // ДДС связь PL (все строки ТЧ Статьи)
    ВЫБРАТЬ РАЗЛИЧНЫЕ
        СтатьиТЧ.Ссылка КАК СтатьяPL,
        СтатьиТЧ.СтатьяДвиженияДенежныхСредств КАК ДДС
    ПОМЕСТИТЬ втPL_ДДС
    ИЗ Справочник.А_Статьи_PL.Статьи КАК СтатьиТЧ
    ГДЕ НЕ СтатьиТЧ.Ссылка.ПометкаУдаления
        И СтатьиТЧ.СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
    ;

    // АДР-расходы
    ВЫБРАТЬ
        Р.Подразделение КАК Подразделение,
        Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств КАК ДДС,
        СУММА(Р.СуммаРеглПриход) КАК СуммаАДР
    ПОМЕСТИТЬ втАДР_Расх
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(
        ДАТАВРЕМЯ({year},{month},1), ДАТАВРЕМЯ({year},{month},{last},23,59,59), , ) КАК Р
    ГДЕ Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
    СГРУППИРОВАТЬ ПО Р.Подразделение, Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств
    ;

    // АДР-доходы (выручка + прочие)
    ВЫБРАТЬ
        Д.Подразделение КАК Подразделение,
        Д.СтатьяДоходов КАК СтатьяДоходов,
        СУММА(Д.Сумма) КАК СуммаАДР
    ПОМЕСТИТЬ втАДР_Дох
    ИЗ (
        ВЫБРАТЬ Ф.Подразделение КАК Подразделение, Ф.СтатьяДоходов КАК СтатьяДоходов,
            Ф.ДоходыРеглБезНДСОборот КАК Сумма
        ИЗ РегистрНакопления.ФинансовыеРезультаты.Обороты(
            ДАТАВРЕМЯ({year},{month},1), ДАТАВРЕМЯ({year},{month},{last},23,59,59), , ) КАК Ф
        ГДЕ Ф.СтатьяДоходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиДоходов.ПустаяСсылка)
        ОБЪЕДИНИТЬ ВСЕ
        ВЫБРАТЬ П.Подразделение, П.СтатьяДоходов, П.СуммаРеглПриход
        ИЗ РегистрНакопления.ПрочиеДоходы.Обороты(
            ДАТАВРЕМЯ({year},{month},1), ДАТАВРЕМЯ({year},{month},{last},23,59,59), , ) КАК П
        ГДЕ П.СтатьяДоходов <> ЗНАЧЕНИЕ(ПланВидовХарактеристик.СтатьиДоходов.ПустаяСсылка)
    ) КАК Д
    СГРУППИРОВАТЬ ПО Д.Подразделение, Д.СтатьяДоходов
    ;

    // Агрегат АДР по PL-статье (суммирует все ДДС PL)
    ВЫБРАТЬ
        PL.Подразделение КАК Подразделение,
        PL.СтатьяPL КАК СтатьяPL,
        СУММА(ЕСТЬNULL(АДРР.СуммаАДР, 0)) КАК СуммаАДР_Расх_Агр
    ПОМЕСТИТЬ втАДР_Расх_Агр
    ИЗ втPL КАК PL
        ЛЕВОЕ СОЕДИНЕНИЕ втPL_ДДС КАК PLД ПО PLД.СтатьяPL = PL.СтатьяPL
        ЛЕВОЕ СОЕДИНЕНИЕ втАДР_Расх КАК АДРР ПО АДРР.Подразделение = PL.Подразделение И АДРР.ДДС = PLД.ДДС
    СГРУППИРОВАТЬ ПО PL.Подразделение, PL.СтатьяPL
    ;

    // Основной отчёт: PL vs АДР (через PL-статью)
    ВЫБРАТЬ
        ВЫРАЗИТЬ(PL.Подразделение.Наименование КАК Строка(60)) КАК Подразделение,
        ВЫРАЗИТЬ(PL.Группа.Наименование КАК Строка(80)) КАК Группа,
        ВЫРАЗИТЬ(PL.СтатьяPL.Наименование КАК Строка(80)) КАК СтатьяPL,
        ПРЕДСТАВЛЕНИЕ(PL.ТипСтатьи) КАК ТипСтатьи,
        PL.Авто КАК Авто,
        PL.СуммаPL КАК СуммаPL,
        ЕСТЬNULL(АДРД.СуммаАДР, 0) + ЕСТЬNULL(АГР.СуммаАДР_Расх_Агр, 0) КАК СуммаАДР
    ИЗ втPL КАК PL
        ЛЕВОЕ СОЕДИНЕНИЕ втАДР_Дох КАК АДРД ПО АДРД.Подразделение = PL.Подразделение И АДРД.СтатьяДоходов = PL.СтатьяДоходов
        ЛЕВОЕ СОЕДИНЕНИЕ втАДР_Расх_Агр КАК АГР ПО АГР.Подразделение = PL.Подразделение И АГР.СтатьяPL = PL.СтатьяPL
    """
    return q.Выполнить().Выгрузить()


def orphan_dds_query(conn, year, month):
    """ДДС из АДР, НЕ привязанные ни к одной PL-статье (MAPPING_BUG)."""
    last = calendar.monthrange(year, month)[1]
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ
        ВЫРАЗИТЬ(Р.Подразделение.Наименование КАК Строка(60)) КАК Подразделение,
        ВЫРАЗИТЬ(Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств.Наименование КАК Строка(80)) КАК ДДС,
        СУММА(Р.СуммаРеглПриход) КАК СуммаАДР
    ИЗ РегистрНакопления.ПрочиеРасходы.Обороты(
        ДАТАВРЕМЯ({year},{month},1), ДАТАВРЕМЯ({year},{month},{last},23,59,59), , ) КАК Р
    ГДЕ Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств <> ЗНАЧЕНИЕ(Справочник.СтатьиДвиженияДенежныхСредств.ПустаяСсылка)
        И НЕ Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств В (
            ВЫБРАТЬ РАЗЛИЧНЫЕ Т.СтатьяДвиженияДенежныхСредств
            ИЗ Справочник.А_Статьи_PL.Статьи КАК Т
            ГДЕ НЕ Т.Ссылка.ПометкаУдаления)
        И Р.СуммаРеглПриход > 0
    СГРУППИРОВАТЬ ПО
        Р.Подразделение.Наименование,
        Р.СтатьяРасходов.А_СтатьяДвиженияДенежныхСредств.Наименование
    """
    return q.Выполнить().Выгрузить()


def main():
    conn = connect_erp()
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    parity_rows = []
    data_gaps = []
    mapping_bugs = []

    stats = {"OK": 0, "DATA_GAP": 0, "MAPPING_BUG": 0, "AUTO": 0}
    totals = {"pl": 0, "adr": 0}

    for year, month in MONTHS:
        mkey = f"{year}-{month:02d}"
        print(f"\n=== {mkey} ===")

        # 1. Паритет по PL-статьям
        tz = parity_query(conn, year, month)
        for i in range(tz.Количество()):
            r = tz.Получить(i)
            pl_sum = float(r.СуммаPL or 0)
            adr_sum = float(r.СуммаАДР or 0)
            delta = round(pl_sum - adr_sum, 2)
            pct = round(delta / adr_sum * 100, 2) if adr_sum > 0 else (100.0 if pl_sum > 0 else 0.0)
            авто = bool(r.Авто)

            if abs(delta) < 0.01:
                статус = "OK"
                stats["OK"] += 1
            else:
                статус = "DATA_GAP"
                stats["DATA_GAP"] += 1
                data_gaps.append({
                    "Период": mkey,
                    "Подразделение": str(r.Подразделение or ""),
                    "Группа": str(r.Группа or ""),
                    "СтатьяPL": str(r.СтатьяPL or ""),
                    "Тип": str(r.ТипСтатьи or ""),
                    "Авто": "ДА" if авто else "",
                    "СуммаPL": pl_sum,
                    "СуммаАДР": adr_sum,
                    "Разница": delta,
                    "Δ_%": pct,
                })
            if авто:
                stats["AUTO"] += 1

            totals["pl"] += pl_sum
            totals["adr"] += adr_sum

            parity_rows.append({
                "Период": mkey,
                "Подразделение": str(r.Подразделение or ""),
                "Группа": str(r.Группа or ""),
                "СтатьяPL": str(r.СтатьяPL or ""),
                "Тип": str(r.ТипСтатьи or ""),
                "Авто": "ДА" if авто else "",
                "СуммаPL": pl_sum,
                "СуммаАДР": adr_sum,
                "Разница": delta,
                "Δ_%": pct,
                "Статус": статус,
            })

        # 2. ДДС из АДР без PL (MAPPING_BUG)
        tz_orph = orphan_dds_query(conn, year, month)
        for i in range(tz_orph.Количество()):
            r = tz_orph.Получить(i)
            adr_sum = float(r.СуммаАДР or 0)
            mapping_bugs.append({
                "Период": mkey,
                "Подразделение": str(r.Подразделение or ""),
                "ДДС": str(r.ДДС or ""),
                "СуммаАДР": adr_sum,
            })
            stats["MAPPING_BUG"] += 1

    # Сохранить CSV
    # Главный — все строки паритета
    main_path = config.REPORTS_DIR / "verification_pl_parity_adr.csv"
    with main_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["Период", "Подразделение", "Группа", "СтатьяPL",
                                         "Тип", "Авто", "СуммаPL", "СуммаАДР",
                                         "Разница", "Δ_%", "Статус"], delimiter=";")
        w.writeheader()
        for r in parity_rows:
            r["СуммаPL"] = f"{r['СуммаPL']:.2f}"
            r["СуммаАДР"] = f"{r['СуммаАДР']:.2f}"
            r["Разница"] = f"{r['Разница']:.2f}"
            r["Δ_%"] = f"{r['Δ_%']:.2f}"
            w.writerow(r)

    # Отдельный — DATA_GAP для финансиста
    gap_path = config.REPORTS_DIR / "data_gaps_for_finance.csv"
    with gap_path.open("w", encoding="utf-8", newline="") as f:
        if data_gaps:
            w = csv.DictWriter(f, fieldnames=list(data_gaps[0].keys()), delimiter=";")
            w.writeheader()
            for r in sorted(data_gaps, key=lambda x: -abs(float(x["Разница"]) if isinstance(x["Разница"], (int, float)) else 0)):
                r["СуммаPL"] = f"{r['СуммаPL']:.2f}"
                r["СуммаАДР"] = f"{r['СуммаАДР']:.2f}"
                r["Разница"] = f"{r['Разница']:.2f}"
                r["Δ_%"] = f"{r['Δ_%']:.2f}"
                w.writerow(r)

    # MAPPING_BUG — должно быть пусто
    bug_path = config.REPORTS_DIR / "mapping_bugs.csv"
    with bug_path.open("w", encoding="utf-8", newline="") as f:
        if mapping_bugs:
            w = csv.DictWriter(f, fieldnames=list(mapping_bugs[0].keys()), delimiter=";")
            w.writeheader()
            for r in sorted(mapping_bugs, key=lambda x: -x["СуммаАДР"]):
                r["СуммаАДР"] = f"{r['СуммаАДР']:.2f}"
                w.writerow(r)

    print(f"\n{'='*70}")
    print(f"ИТОГО за 3 месяца:")
    print(f"  PL всего:   {totals['pl']:>18,.2f} ₴")
    print(f"  АДР всего:  {totals['adr']:>18,.2f} ₴")
    print(f"  Разница:    {totals['pl']-totals['adr']:>18,.2f} ₴ ({(totals['pl']-totals['adr'])/totals['adr']*100:.2f}%)")
    print(f"\n  OK:           {stats['OK']:>5}")
    print(f"  DATA_GAP:     {stats['DATA_GAP']:>5}  (ошибки Excel-данных)")
    print(f"  MAPPING_BUG:  {stats['MAPPING_BUG']:>5}  (непривязанные ДДС — ЦЕЛЬ: 0)")
    print(f"  Авто-статьи:  {stats['AUTO']:>5}  (созданы скриптом, нет в Excel)")
    print(f"\nФайлы:")
    print(f"  {main_path}")
    print(f"  {gap_path}")
    print(f"  {bug_path}")


if __name__ == "__main__":
    main()
