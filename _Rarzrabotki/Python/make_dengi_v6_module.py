t = open(MOD, encoding="utf-8-sig").read()
rep = open(REP, encoding="utf-8-sig").read()

def sub1(text, pattern, repl, label, flags=0):
    new, n = re.subn(pattern, repl, text, count=1, flags=flags)
    assert n == 1, f"{label}: не найдено"
    return new

# --- функции отчёта 1:1 ---
m = re.search(r"// Отримання залишків з ERP.*?КонецФункции(?=\s*#КонецОбласти)", rep, re.S)
assert m, "функции отчёта не найдены"
report_funcs = m.group(0).rstrip()
assert "ПолучитьОстаткиЕРП_Бух" in report_funcs and "ПолучитьОстаткиBuhBud" in report_funcs

# --- 1. Область Фаза1 -> ДаніПорівняння ---
new_phase1 = """// ===========================================================================
// ДАНІ ПОРІВНЯННЯ ДЛЯ СКД
// Структура наборів та алгоритм — зі звіту А_СравнитьОстаткиДенегЕРПсBASБухгалтерия
// (функції отримання залишків перенесені 1:1)
// ===========================================================================

#Область ДаніПорівняння

// Будує таблиці зовнішніх наборів даних СКД
// (БезналичныеДС_ЕРП / _УПП / _ПоДнямЕРП / _ПоДнямУПП)
//
// Повертає:
//  Структура - зовнішні набори даних, або Неопределено при помилці підключення
//
Функция ПостроитьДанныеСравнения() Экспорт

	УстановитьПривилегированныйРежим(Истина);

	КонецПериодаРасч = КонецДня(ОкончаниеПериода);

	ТаблицаЕРП = ПолучитьОстаткиЕРП_Бух(НачалоПериода, КонецПериодаРасч, Ложь);
	ТаблицаПоДнямЕРП = Новый ТаблицаЗначений;
	Если ПоДням Тогда
		ТаблицаПоДнямЕРП = ПолучитьОстаткиЕРП_Бух(НачалоПериода, КонецПериодаРасч, Истина);
	КонецЕсли;

	V83 = ПодключитьсяКBuhBud();
	Если V83 = Неопределено Тогда
		Возврат Неопределено;
	КонецЕсли;

	ТаблицаУПП = ПолучитьОстаткиBuhBud(V83, НачалоПериода, КонецПериодаРасч, Ложь);
	ТаблицаПоДнямУПП = Новый ТаблицаЗначений;
	Если ПоДням Тогда
		ТаблицаПоДнямУПП = ПолучитьОстаткиBuhBud(V83, НачалоПериода, КонецПериодаРасч, Истина);
	КонецЕсли;

	V83 = Неопределено;

	Возврат Новый Структура(
		"БезналичныеДС_ЕРП, БезналичныеДС_УПП, БезналичныеДС_ПоДнямЕРП, БезналичныеДС_ПоДнямУПП",
		ТаблицаЕРП, ТаблицаУПП, ТаблицаПоДнямЕРП, ТаблицаПоДнямУПП);

КонецФункции

""" + report_funcs + """

#КонецОбласти
"""

t = sub1(t, r"// =+\r?\n// ФАЗА 1: Порівняння залишків\r?\n// =+\r?\n\r?\n#Область Фаза1_ПорівнянняЗалишків.*?#КонецОбласти\r?\n",
         new_phase1.replace("\\", "\\\\"), "область Фаза1", re.S)

# --- 2. АнализироватьДокументы -> две новые функции ---
new_analyze = """// Головна функція Фази 2 — аналіз документів по масиву банківських рахунків
//
// Параметри:
//  МассивСчетов - Массив - СправочникСсылка.БанковскиеСчетаОрганизаций
//  НачПериодаАнализ, КонПериодаАнализ - Дата - період аналізу (день або весь період)
//
Функция АнализироватьДокументыПоСчетам(МассивСчетов, НачПериодаАнализ, КонПериодаАнализ) Экспорт

	УстановитьПривилегированныйРежим(Истина);
	ТаблицаДокументов.Очистить();

	V83 = ПодключитьсяКBuhBud();
	Если V83 = Неопределено Тогда
		Возврат "Помилка підключення до BuhBud";
	КонецЕсли;

	// Отримати вузол обміну в BuhBud
	УзелОбмена = Неопределено;
	Попытка
		V83_Запрос = V83.NewObject("Запрос");
		V83_Запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20 ГДЕ НЕ ЭтотУзел";
		V83_Рез = V83_Запрос.Выполнить().Выбрать();
		Если V83_Рез.Следующий() Тогда
			УзелОбмена = V83_Рез.Ссылка;
		КонецЕсли;
	Исключение
		Сообщить("Не вдалося знайти вузол обміну в BuhBud: " + ОписаниеОшибки());
	КонецПопытки;

	Для Каждого СчетСсылка Из МассивСчетов Цикл
		Попытка
			АнализДокументов_ПоСчету(V83, СчетСсылка, НачПериодаАнализ, КонПериодаАнализ, УзелОбмена);
		Исключение
			Сообщить("ПОМИЛКА аналізу " + Строка(СчетСсылка) + ": " + ОписаниеОшибки());
		КонецПопытки;
	КонецЦикла;

	// Ознака розбіжності — для відбору на формі. Окремо від галки вибору:
	// проблемні перекази мають порожню дію (рішення за бухгалтером), але це розбіжності
	Для Каждого СтрДок Из ТаблицаДокументов Цикл
		СтрДок.ЕстьРасхождение = НЕ (СтрДок.Статус = "ОК" ИЛИ СтрДок.Статус = "Переказ: синхронно");
	КонецЦикла;

	V83 = Неопределено;
	Возврат "Документів для синхронізації: " + Строка(ТаблицаДокументов.Количество());

КонецФункции

// Аналіз документів по ВСІХ рахунках з розбіжностями за період обробки
//
Функция АнализироватьВсеРасхождения() Экспорт

	УстановитьПривилегированныйРежим(Истина);

	Данные = ПостроитьДанныеСравнения();
	Если Данные = Неопределено Тогда
		Возврат "Помилка підключення до BuhBud";
	КонецЕсли;

	// Звід 4 показників по рахунку: ЕРП мінус УПП
	Свод = Новый Соответствие;
	Для Каждого Стр Из Данные.БезналичныеДС_ЕРП Цикл
		Значения = Свод.Получить(Стр.БанковскийСчетКасса);
		Если Значения = Неопределено Тогда
			Значения = Новый Структура("Нач, Прих, Расх, Кон", 0, 0, 0, 0);
			Свод.Вставить(Стр.БанковскийСчетКасса, Значения);
		КонецЕсли;
		Значения.Нач  = Значения.Нач  + Стр.СуммаНачальныйОстаток_ЕРП;
		Значения.Прих = Значения.Прих + Стр.СуммаПриход_ЕРП;
		Значения.Расх = Значения.Расх + Стр.СуммаРасход_ЕРП;
		Значения.Кон  = Значения.Кон  + Стр.СуммаКонечныйОстаток_ЕРП;
	КонецЦикла;
	Для Каждого Стр Из Данные.БезналичныеДС_УПП Цикл
		Значения = Свод.Получить(Стр.БанковскийСчетКасса);
		Если Значения = Неопределено Тогда
			Значения = Новый Структура("Нач, Прих, Расх, Кон", 0, 0, 0, 0);
			Свод.Вставить(Стр.БанковскийСчетКасса, Значения);
		КонецЕсли;
		Значения.Нач  = Значения.Нач  - Стр.СуммаНачальныйОстаток_УПП;
		Значения.Прих = Значения.Прих - Стр.СуммаПриход_УПП;
		Значения.Расх = Значения.Расх - Стр.СуммаРасход_УПП;
		Значения.Кон  = Значения.Кон  - Стр.СуммаКонечныйОстаток_УПП;
	КонецЦикла;

	МассивСчетов = Новый Массив;
	Для Каждого КлючЗначение Из Свод Цикл
		Значения = КлючЗначение.Значение;
		Если ЗначениеЗаполнено(КлючЗначение.Ключ)
			И (Окр(Значения.Нач, 2) <> 0 ИЛИ Окр(Значения.Прих, 2) <> 0
				ИЛИ Окр(Значения.Расх, 2) <> 0 ИЛИ Окр(Значения.Кон, 2) <> 0) Тогда
			МассивСчетов.Добавить(КлючЗначение.Ключ);
		КонецЕсли;
	КонецЦикла;

	Если МассивСчетов.Количество() = 0 Тогда
		ТаблицаДокументов.Очистить();
		Возврат "Розбіжностей не знайдено";
	КонецЕсли;

	Возврат "Рахунків з розбіжностями: " + Строка(МассивСчетов.Количество()) + ". "
		+ АнализироватьДокументыПоСчетам(МассивСчетов, НачалоПериода, КонецДня(ОкончаниеПериода));

КонецФункции
"""

t = sub1(t, r"// Головна функція Фази 2 — аналіз документів для вибраних розбіжностей\r?\n//\r?\nФункция АнализироватьДокументы\(\) Экспорт.*?КонецФункции\r?\n",
         new_analyze.replace("\\", "\\\\"), "АнализироватьДокументы", re.S)

# --- 3. Параметризация АнализДокументов_ПоСчету ---
