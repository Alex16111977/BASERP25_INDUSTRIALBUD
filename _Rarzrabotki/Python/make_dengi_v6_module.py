    r"\t\tV83_Запрос\.УстановитьПараметр\(\"НачалоПериода\", НачалоПериода\);\r?\n"
    r"\t\tV83_Запрос\.УстановитьПараметр\(\"КонецПериода\", КонецДня\(ОкончаниеПериода\)\);",
