# -*- coding: utf-8 -*-
"""РАЗОВАЯ сервисная очистка сиротских записей РегистрСведений.А_ОтчетБаланс_Свод.

Контекст: в регистре накопились записи от УДАЛЁННЫХ документов А_ФинРез_Баланс
(регистраторы = «Объект не найден»). Ключ РС (RecorderSubordinate) проверяет
уникальность по измерениям → сироты конфликтуют с любой новой записью свода,
из-за чего проведение падает «Запись с такими ключевыми полями существует!».

Скрипт: по каждому РАЗЛИЧНОМУ регистратору пишет ПУСТОЙ набор записей
(штатное удаление движений регистратора). Живых данных в регистре нет —
все регистраторы битые (проверено: 3 рег., все «Объект не найден»).

Запуск (вручную):
  & "C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\venv\\Scripts\\python.exe" ^
    "C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\cleanup_otchetbalans_svod_orphans.py"
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client, pythoncom

CONN = 'Srvr="SQLSERVER";Ref="BaseERP";Usr="Администратор";Pwd="24043"'
pythoncom.CoInitialize()
conn = win32com.client.Dispatch("V83.COMConnector").Connect(CONN)

qc = conn.NewObject("Запрос")
qc.Текст = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Всего, "
            "КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Регистратор) КАК Рег "
            "ИЗ РегистрСведений.А_ОтчетБаланс_Свод")
r = qc.Выполнить().Выбрать(); r.Следующий()
print(f"ДО очистки: записей={r.Всего}, регистраторов={r.Рег}")

qreg = conn.NewObject("Запрос")
qreg.Текст = ("ВЫБРАТЬ РАЗЛИЧНЫЕ Регистратор КАК Р "
              "ИЗ РегистрСведений.А_ОтчетБаланс_Свод")
tr = qreg.Выполнить().Выгрузить()
удалено_рег = 0
for i in range(tr.Количество()):
    рег = tr.Получить(i).Р
    нз = conn.РегистрыСведений.А_ОтчетБаланс_Свод.СоздатьНаборЗаписей()
    нз.Отбор.Регистратор.Установить(рег)
    нз.Записать(True)  # пустой набор -> удаляет все записи этого регистратора
    удалено_рег += 1
    print(f"  очищен регистратор #{i + 1}: {рег}")

r2 = qc.Выполнить().Выбрать(); r2.Следующий()
print(f"ПОСЛЕ очистки: записей={r2.Всего} (регистраторов очищено "
      f"{удалено_рег})")
assert int(r2.Всего) == 0, f"FAIL: остались записи ({r2.Всего})"
print("PASS: РС А_ОтчетБаланс_Свод полностью очищен от сирот")
