# -*- coding: utf-8 -*-
"""Подбор коэффициентов пересчёта «по факту» для СС, чьи Комплектующие уже пересчитаны вручную (BuhBud), 2026-09-27.

Спека: docs/superpowers/specs/2026-09-27-ss-original-koeficienty-fajly-design.md, п. 5.2–5.3.

Логика — живой общий модуль А_СтруктураСебестоимостиСервер:
  ОтметитьДобавленныеВручную  — признак «Додано вручну» строк Комплектующие без пары в оригинале;
  ПодобратьКоэффициентыПоФакту — ТЧ КоэффициентыПересчета: позиции оригинала с несовпадающими единицами,
                                 k = Σ Комплектующие.Количество / Σ оригинала позиции.

Инварианты (проверяются на непишущейся копии объекта, при нарушении запись не выполняется):
  И3 — «Перерахувати кількість» (ПересчитатьКоличество) с подобранными коэффициентами не меняет ни одного
       Количество строк Комплектующие;
  И1 — Σ Сумма Комплектующие не меняется.
Записывается только ТЧ КоэффициентыПересчета (+ признак ДобавленоВручную). Количества Комплектующие не трогаются.

Запуск:  python ss_original_koef_podbor.py            (сухой прогон)
         python ss_original_koef_podbor.py --write    (запись)
"""
import sys

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

import win32com.client

CONN = 'Srvr="localhost";Ref="bas_industrialbud";Usr="cfo";Pwd="2442"'
CODES = ['000000008', '000000009', '000000010', '000000011']
WRITE = '--write' in sys.argv


def quantities(tab):
    return [round(float(tab.Получить(i).Количество), 3) for i in range(tab.Количество())]


def sums(tab):
    return round(sum(float(tab.Получить(i).Сумма) for i in range(tab.Количество())), 2)


def podbor(srv, obj):
    srv.ОтметитьДобавленныеВручную(obj)
    return srv.ПодобратьКоэффициентыПоФакту(obj)


def main():
    b = win32com.client.Dispatch('V83.COMConnector').Connect(CONN)
    srv = b.А_СтруктураСебестоимостиСервер
    fails = []
    for code in CODES:
        ref = b.Справочники.СтруктураСебестоимости.НайтиПоКоду(code)
        print(f'\n=== {code} {ref.Наименование}')

        # 1. Проверка инвариантов на копии: подбор + пересчёт.
        probe = ref.ПолучитьОбъект()
        q_before, s_before = quantities(probe.Комплектующие), sums(probe.Комплектующие)
        p = podbor(srv, probe)
        r = srv.ПересчитатьКоличество(probe)
        q_after, s_after = quantities(probe.Комплектующие), sums(probe.Комплектующие)
        changed = [i + 1 for i, (x, y) in enumerate(zip(q_before, q_after)) if x != y]
        print(f'  коэффициентов: {probe.КоэффициентыПересчета.Количество()} (подобрано по факту {p.Подобрано}, '
              f'не пересчитывались ранее {p.НеПересчитаныРанее}, нет в Комплектующих {p.НетВКомплектующих}, '
              f'неоднозначно {p.Неоднозначно}, не найдено {p.НеНайдено})')
        print(f'  пересчёт-проверка: строк {r.Пересчитано}, ошибка {r.Ошибка} {r.ТекстОшибки}; '
              f'изменилось количеств: {len(changed)}; Σ Сумма {s_before} -> {s_after}')
        for i in range(p.Детали.Количество()):
            print('    ', p.Детали.Получить(i))
        if r.Ошибка or changed or s_before != s_after:
            fails.append(f'{code}: инвариант нарушен, строки {changed[:10]}')
            continue

        # 2. Запись: свежий объект, только коэффициенты и признак «вручну».
        if WRITE:
            obj = ref.ПолучитьОбъект()
            q0 = quantities(obj.Комплектующие)
            podbor(srv, obj)
            obj.Записать()
            fresh = ref.ПолучитьОбъект()
            if quantities(fresh.Комплектующие) != q0:
                fails.append(f'{code}: количества изменились при записи')
            print(f'  ЗАПИСАНО: коэффициентов {fresh.КоэффициентыПересчета.Количество()}')
            for i in range(fresh.КоэффициентыПересчета.Количество()):
                c = fresh.КоэффициентыПересчета.Получить(i)
                print(f'    {c.ОбщееНазвание} | {c.НоменклатураСС} | {c.КоличествоОригинал} {c.ЕдиницаСС} x {c.Коэффициент} '
                      f'= {c.КоличествоПересчитанное} {c.ЕдиницаЗакупки} [{c.ИсточникКоэффициента}]')

    print('\nПРОВАЛЫ:\n  ' + '\n  '.join(fails) if fails else
          ('\nЗАПИСАНО, инварианты соблюдены' if WRITE else '\nСУХОЙ ПРОГОН ОК (запись: --write)'))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
