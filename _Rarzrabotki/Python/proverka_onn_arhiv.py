# -*- coding: utf-8 -*-
"""Шаг 3 спеки: верификация архива общих названий номенклатуры. Только чтение.

Шесть критериев приёмки:
  1. В архиве 322 элемента, множество UUID совпадает с оригиналом.
  2. По каждому UUID совпадают Код, Наименование, ПометкаУдаления, ЭтоГруппа,
     Родитель и пять реквизитов.
  3. Ноль номенклатур с заполненным живым и пустым архивным полем;
     заполненных архивных ровно 2640.
  4. Ноль номенклатур, где оба поля заполнены, но UUID различаются.
  5. Ноль номенклатур с заполненным архивным и пустым живым полем.
  6. В оригинальном справочнике по-прежнему 322 элемента.
  7. На узле обмена с ЕРП зарегистрировано к выгрузке 0 номенклатур — как в
     baseline до миграции.

Запуск:
  & "C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\venv\\Scripts\\python.exe" ^
    "C:\\Configuration_downloads\\BASERP25\\_Rarzrabotki\\Python\\proverka_onn_arhiv.py"
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from onn_arhiv_common import (подключиться, выполнить, строки, uuid_ссылки,
                              NULL_UUID, РЕКВИЗИТЫ)

ОЖИДАЕМО_ЭЛЕМЕНТОВ = 322
ОЖИДАЕМО_НОМЕНКЛАТУРЫ = 2640
ОЖИДАЕМО_РЕГИСТРАЦИЙ = 0   # baseline узла ЕРП до миграции

ЗАПРОС_СПРАВОЧНИКА = """
ВЫБРАТЬ
    Т.Ссылка КАК Ссылка, Т.ЭтоГруппа КАК ЭтоГруппа, Т.Родитель КАК Родитель,
    Т.Код КАК Код, Т.Наименование КАК Наименование,
    Т.ПометкаУдаления КАК ПометкаУдаления,
    Т.ОсновнаяНоменклатура КАК ОсновнаяНоменклатура,
    Т.Единица КАК Единица,
    Т.ЕдиницаРекомендуемая КАК ЕдиницаРекомендуемая,
    Т.НазваниеДляОбъединения КАК НазваниеДляОбъединения,
    Т.НеПроверятьВЗакупкахпоСС КАК НеПроверятьВЗакупкахпоСС
ИЗ Справочник.{} КАК Т
"""

ЗАПРОС_НОМЕНКЛАТУРЫ = """
ВЫБРАТЬ
    Н.Ссылка КАК Ссылка,
    Н.ОбщееНазваниеНоменклатуры КАК Живое,
    Н.ОбщееНазваниеНоменклатурыСтарая КАК Архивное
ИЗ Справочник.Номенклатура КАК Н
ГДЕ Н.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
    ИЛИ Н.ОбщееНазваниеНоменклатурыСтарая <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатурыСтарая.ПустаяСсылка)
"""

провалов = 0


def проверить(условие, описание):
    global провалов
    print(("PASS: " if условие else "FAIL: ") + описание)
    if not условие:
        провалов += 1


def сравнимое(conn, значение):
    """Ссылку сводим к UUID, строку — к обрезанной строке, остальное как есть."""
    uid = uuid_ссылки(conn, значение)
    if uid is not None:
        return uid
    if isinstance(значение, str):
        return значение.strip()
    return значение


conn = подключиться()

оригинал = {uuid_ссылки(conn, с.Ссылка): с
            for с in строки(выполнить(conn, ЗАПРОС_СПРАВОЧНИКА.format("ОбщиеНазванияНоменклатуры")))}
архив = {uuid_ссылки(conn, с.Ссылка): с
         for с in строки(выполнить(conn, ЗАПРОС_СПРАВОЧНИКА.format("ОбщиеНазванияНоменклатурыСтарая")))}

# --- 1 ---------------------------------------------------------------------
проверить(len(архив) == ОЖИДАЕМО_ЭЛЕМЕНТОВ,
          f"1. в архиве {ОЖИДАЕМО_ЭЛЕМЕНТОВ} элементов (получено {len(архив)})")
нет_в_архиве = set(оригинал) - set(архив)
лишние = set(архив) - set(оригинал)
проверить(not нет_в_архиве, f"1. не перенесено: {len(нет_в_архиве)}")
проверить(not лишние, f"1. лишних в архиве: {len(лишние)}")

# --- 2 ---------------------------------------------------------------------
ПОЛЯ = ("Код", "Наименование", "ПометкаУдаления", "ЭтоГруппа", "Родитель") + РЕКВИЗИТЫ

ЗАПРОС_ПРИВЯЗКИ = """
ВЫБРАТЬ Н.ОбщееНазваниеНоменклатуры КАК Общее
ИЗ Справочник.Номенклатура КАК Н
ГДЕ Н.Ссылка = &Ном
"""


def обнулено_штатной_проверкой(conn, uid, поле, живое_uuid, архивная_ссылка):
    """Живое значение ОсновнаяНоменклатура снято проверкой целостности конфигурации.

    Catalogs/Номенклатура/Ext/ObjectModule.bsl: ПриЗаписи -> ПроверитьОсновнуюВОбщихНазваниях
    (строка 160) обнуляет ОсновнаяНоменклатура у тех общих названий, которым эта
    номенклатура фактически не принадлежит. Массовая запись номенклатуры на шаге 2
    заставила правило отработать; архив хранит доисправленное значение — в этом и
    состоит его назначение, поэтому расхождение ожидаемо, а не дефект переноса.

    Признаётся объяснимым только при всех условиях сразу: поле именно
    ОсновнаяНоменклатура, живое значение теперь пусто, архивное непусто, а
    номенклатура из архивного значения привязана к ДРУГОМУ общему названию.
    """
    if поле != "ОсновнаяНоменклатура":
        return False
    if живое_uuid not in (None, NULL_UUID):
        return False
    if uuid_ссылки(conn, архивная_ссылка) in (None, NULL_UUID):
        return False
    найдено = строки(выполнить(conn, ЗАПРОС_ПРИВЯЗКИ, Ном=архивная_ссылка))
    if not найдено:
        return False
    return uuid_ссылки(conn, найдено[0].Общее) != uid


расхождения, объяснённые = [], []
for uid in set(оригинал) & set(архив):
    for поле in ПОЛЯ:
        слева = сравнимое(conn, getattr(оригинал[uid], поле))
        справа = сравнимое(conn, getattr(архив[uid], поле))
        if слева == справа:
            continue
        описание = f"{uid}.{поле}: живое {слева!r} != архив {справа!r}"
        if обнулено_штатной_проверкой(conn, uid, поле, слева,
                                      getattr(архив[uid], поле)):
            объяснённые.append(описание)
        else:
            расхождения.append(описание)

проверить(not расхождения,
          f"2. неожиданных расхождений по полям: {len(расхождения)}")
for строка_расх in расхождения[:10]:
    print("     " + строка_расх)
if объяснённые:
    print(f"     объяснимых расхождений: {len(объяснённые)} — живая "
          "ОсновнаяНоменклатура снята проверкой ПроверитьОсновнуюВОбщихНазваниях, "
          "доисправленное значение сохранено в архиве")
    for строка_объ in объяснённые[:10]:
        print("       " + строка_объ)

# --- 3, 4, 5 ---------------------------------------------------------------
номенклатура = строки(выполнить(conn, ЗАПРОС_НОМЕНКЛАТУРЫ))
живое_есть_архива_нет, uuid_разошлись, архив_есть_живого_нет = 0, 0, 0
архивных_заполнено = 0
for с in номенклатура:
    ж = uuid_ссылки(conn, с.Живое)
    а = uuid_ссылки(conn, с.Архивное)
    ж_есть = ж not in (None, NULL_UUID)
    а_есть = а not in (None, NULL_UUID)
    архивных_заполнено += 1 if а_есть else 0
    if ж_есть and not а_есть:
        живое_есть_архива_нет += 1
    elif а_есть and not ж_есть:
        архив_есть_живого_нет += 1
    elif ж_есть and а_есть and ж != а:
        uuid_разошлись += 1

проверить(живое_есть_архива_нет == 0,
          f"3. живое заполнено, архивное пусто: {живое_есть_архива_нет}")
проверить(архивных_заполнено == ОЖИДАЕМО_НОМЕНКЛАТУРЫ,
          f"3. архивных заполнено {ОЖИДАЕМО_НОМЕНКЛАТУРЫ} "
          f"(получено {архивных_заполнено})")
проверить(uuid_разошлись == 0, f"4. UUID живого и архивного различаются: {uuid_разошлись}")
проверить(архив_есть_живого_нет == 0,
          f"5. архивное заполнено, живое пусто: {архив_есть_живого_нет}")

# --- 6 ---------------------------------------------------------------------
проверить(len(оригинал) == ОЖИДАЕМО_ЭЛЕМЕНТОВ,
          f"6. оригинал не изменился: {len(оригинал)} из {ОЖИДАЕМО_ЭЛЕМЕНТОВ}")

# --- 7 ---------------------------------------------------------------------
узлы = строки(выполнить(conn, """
ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Узел
ИЗ ПланОбмена.ОбменУправлениеПредприятиемБухгалтерия20 КАК П
ГДЕ НЕ П.ЭтотУзел
"""))
if узлы:
    зарегистрировано = int(строки(выполнить(conn, """
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
    ИЗ Справочник.Номенклатура.Изменения КАК Изм
    ГДЕ Изм.Узел = &Узел
    """, Узел=узлы[0].Узел))[0].К)
    проверить(зарегистрировано == ОЖИДАЕМО_РЕГИСТРАЦИЙ,
              f"7. номенклатур зарегистрировано к выгрузке в ЕРП: "
              f"{зарегистрировано} (baseline {ОЖИДАЕМО_РЕГИСТРАЦИЙ})")
else:
    проверить(False, "7. узел обмена с ЕРП не найден")

print(f"\nИТОГ: провалов {провалов}")
sys.exit(1 if провалов else 0)
