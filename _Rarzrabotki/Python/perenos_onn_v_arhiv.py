from onn_arhiv_common import (подключиться, выполнить, строки, uuid_ссылки,
                              ссылка_архива, записать_батчами, порядок_по_иерархии,
                              NULL_UUID, РЕКВИЗИТЫ)

ЗАПРОС_ИСТОЧНИКА = """
ВЫБРАТЬ
    Т.Ссылка КАК Ссылка, Т.ЭтоГруппа КАК ЭтоГруппа, Т.Родитель КАК Родитель,
    Т.Код КАК Код, Т.Наименование КАК Наименование,
    Т.ПометкаУдаления КАК ПометкаУдаления,
    Т.ОсновнаяНоменклатура КАК ОсновнаяНоменклатура,
    Т.Единица КАК Единица,
    Т.ЕдиницаРекомендуемая КАК ЕдиницаРекомендуемая,
    Т.НазваниеДляОбъединения КАК НазваниеДляОбъединения,
    Т.НеПроверятьВЗакупкахпоСС КАК НеПроверятьВЗакупкахпоСС
ИЗ Справочник.ОбщиеНазванияНоменклатуры КАК Т
"""

ЗАПРОС_АРХИВА = """
ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ Справочник.ОбщиеНазванияНоменклатурыСтарая КАК Т
"""

ЗАПРОС_НОМЕНКЛАТУРЫ = """
ВЫБРАТЬ
    Н.Ссылка КАК Ссылка,
    Н.ОбщееНазваниеНоменклатуры КАК Живое,
    Н.ОбщееНазваниеНоменклатурыСтарая КАК Архивное
ИЗ Справочник.Номенклатура КАК Н
ГДЕ Н.ОбщееНазваниеНоменклатуры <> ЗНАЧЕНИЕ(Справочник.ОбщиеНазванияНоменклатуры.ПустаяСсылка)
"""


def этап1(conn):
    исходные = строки(выполнить(conn, ЗАПРОС_ИСТОЧНИКА))
    уже_в_архиве = {uuid_ссылки(conn, с.Ссылка)
                    for с in строки(выполнить(conn, ЗАПРОС_АРХИВА))}
    упорядоченные = порядок_по_иерархии(conn, исходные)
    к_переносу = [с for с in упорядоченные
                  if uuid_ссылки(conn, с.Ссылка) not in уже_в_архиве]
    print(f"ЭТАП 1: в источнике {len(исходные)}, в архиве уже {len(уже_в_архиве)}, "
          f"к переносу {len(к_переносу)}")

    менеджер = conn.Справочники.ОбщиеНазванияНоменклатурыСтарая

    def перенести(с):
        uid = uuid_ссылки(conn, с.Ссылка)
        объект = менеджер.СоздатьГруппу() if с.ЭтоГруппа else менеджер.СоздатьЭлемент()
        объект.УстановитьСсылкуНового(ссылка_архива(conn, uid))
        объект.Код = с.Код
        объект.Наименование = с.Наименование
        объект.ПометкаУдаления = с.ПометкаУдаления
        родитель = uuid_ссылки(conn, с.Родитель)
        объект.Родитель = (менеджер.ПустаяСсылка()
                           if родитель in (None, NULL_UUID)
                           else ссылка_архива(conn, родитель))
        if not с.ЭтоГруппа:          # все пять реквизитов объявлены как ForItem
            for имя in РЕКВИЗИТЫ:
                setattr(объект, имя, getattr(с, имя))
        объект.ОбменДанными.Загрузка = True
        объект.Записать()
        return True

    записано, ошибки = записать_батчами(conn, к_переносу, перенести)
    print(f"ЭТАП 1 итог: записано {записано}, элементов с ошибкой {len(ошибки)}")
    return ошибки


def этап2(conn):
    в_архиве = {uuid_ссылки(conn, с.Ссылка)
                for с in строки(выполнить(conn, ЗАПРОС_АРХИВА))}
    номенклатура = строки(выполнить(conn, ЗАПРОС_НОМЕНКЛАТУРЫ))
    к_заполнению, без_архива = [], []
    for с in номенклатура:
        живое = uuid_ссылки(conn, с.Живое)
        if живое not in в_архиве:
            без_архива.append(с)
        elif uuid_ссылки(conn, с.Архивное) != живое:
            к_заполнению.append(с)
    print(f"ЭТАП 2: номенклатур в отборе {len(номенклатура)}, "
          f"к заполнению {len(к_заполнению)}, "
          f"без архивного аналога {len(без_архива)}")
    if без_архива:
        print("  ВНИМАНИЕ: сначала должен успешно отработать этап 1")
        return [(0, f"нет архивного аналога у {len(без_архива)} номенклатур")]

    def заполнить(с):
        объект = с.Ссылка.ПолучитьОбъект()
        if объект is None:
            return False
        объект.ОбщееНазваниеНоменклатурыСтарая = ссылка_архива(conn, uuid_ссылки(conn, с.Живое))
        # БЕЗ ОбменДанными.Загрузка: прогон вхолостую показал, что в этой БСП
        # флаг наоборот ВКЛЮЧАЕТ регистрацию к выгрузке в ЕРП (0 -> 1),
        # а обычная запись регистрации не создаёт (0 -> 0).
        объект.Записать()
        return True

    записано, ошибки = записать_батчами(conn, к_заполнению, заполнить)
    print(f"ЭТАП 2 итог: записано {записано}, элементов с ошибкой {len(ошибки)}")
    return ошибки


