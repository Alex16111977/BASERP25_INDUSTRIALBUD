"""Шаги 1–2 спеки: перенос общих названий в архив и заполнение номенклатуры.

Этап 1 — клон 322 элементов Справочник.ОбщиеНазванияНоменклатуры в
          Справочник.ОбщиеНазванияНоменклатурыСтарая с сохранением UUID.
Этап 2 — Номенклатура.ОбщееНазваниеНоменклатурыСтарая := архивный аналог
          текущего значения ОбщееНазваниеНоменклатуры.

Оба этапа идемпотентны: уже перенесённые UUID и уже корректно заполненные
реквизиты пропускаются. Батчи по 200 в транзакции; упавший батч откатывается
и повторяется поштучно.

Запуск:
  ... perenos_onn_v_arhiv.py этап1
  ... perenos_onn_v_arhiv.py этап2
  ... perenos_onn_v_arhiv.py все      (по умолчанию)
"""
